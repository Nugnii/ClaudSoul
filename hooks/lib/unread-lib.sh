#!/usr/bin/env bash
# unread-lib.sh — отказ чтения СЧИТАЕТСЯ и НАЗЫВАЕТСЯ, а не гасится числом.
#
# РОД ДЕФЕКТА B (scripts/defect-class-carriers.py, секция «РОД B»). Переменная получила
# значение ИЗ ЧТЕНИЯ, чтение отказало, и `${V:-0}` перевело «я не смог посмотреть» в
# благоприятное число. У чтения канал ОТКАЗА и канал УСПЕХА выражены одним знаком —
# пустой строкой, — и после подстановки различить «в мире нуль» и «не прочитал» нечем
# ни одному потребителю. Механизм печатает «проверено», ничего не проверив.
#
# Правило рода, дословно: ноль ПРАВДИВ там, где читается СЧЁТ (пустой вход честно равен
# нулю — `grep -c`, `wc -l`), и ЛЖИВ там, где читается ЗНАЧЕНИЕ ПОЛЯ или ЗАМЕР:
# отсутствие значения не есть значение.
#
# Починка — не «не гасить»: при законно пустом входе подстановка нужна. Починка —
# гасить, НАЗВАВ ЦЕНУ. Образец взят из этого же дерева (metrics-collector.sh, где отказ
# чтения confirmed_count считался отдельно и печатался строкой «полей не прочитано: N —
# итог занижен на неизвестную величину»). Здесь образец вынут в единственное место:
# логика различения не должна стоять в каждом файле по-своему и расходиться копиями.
#
# Функции:
#   unread_or <ИМЯ> <чем> <что читали>  — ИМЯ пусто → засчитать отказ, подставить <чем>,
#                                         вернуть 1; прочитано → вернуть 0, не трогать
#   unread_note                         — «не прочитано: N (что, что)» на stdout и код 0;
#                                         код 1 и тишина, если всё прочитано.
#                                         N — по СЛУЧАЯМ, имена — по ВИДАМ (без повторов)
#
# КОД ВОЗВРАТА unread_or — ВТОРОЙ КАНАЛ, ради которого библиотека и заведена. Вызывающий,
# которому подставленное число не годится (читался ЗАМЕР, а не счёт), видит отказ и
# воздерживается от утверждения вместо того, чтобы объявить «не выполнено».
#
# ⚠️ ПОД `set -e` вызывай в условии (`if ! unread_or …`) либо с `|| true`: голый вызов,
# вернувший 1, оборвёт хук. Возврат 1 — сообщение, а не сбой.

UNREAD_N=0
UNREAD_WHAT=""
_UNREAD_SEEN="|"

# unread_or <имя переменной> <значение при отказе> <человекочитаемое «что читали»>
unread_or() {
    local _u_name="${1:-}" _u_what="${3:-неназванное чтение}" _u_val
    [ -n "$_u_name" ] || return 0
    # Косвенное чтение через eval, а не `${!name}`: `${!x}` есть в bash и отсутствует
    # в dash/POSIX sh (pattern-shell-portability). `-` вместо `:-` — переменная может
    # быть не объявлена вовсе, а хуки живут под `set -u`.
    eval "_u_val=\${$_u_name-}"
    [ -n "$_u_val" ] && return 0

    UNREAD_N=$((UNREAD_N + 1))
    case "$_UNREAD_SEEN" in
        *"|$_u_what|"*) ;;
        *)  _UNREAD_SEEN="${_UNREAD_SEEN}${_u_what}|"
            UNREAD_WHAT="${UNREAD_WHAT:+$UNREAD_WHAT, }$_u_what" ;;
    esac
    eval "$_u_name=\$2"
    return 1
}

unread_note() {
    [ "${UNREAD_N:-0}" -gt 0 ] || return 1
    printf 'не прочитано: %s (%s)' "$UNREAD_N" "$UNREAD_WHAT"
}
