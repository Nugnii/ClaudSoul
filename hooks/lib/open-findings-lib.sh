#!/usr/bin/env bash
# open-findings-lib.sh — обнаружение, оставшееся без исхода, переживает свой ход.
#
# Результат: у каждого обнаружения есть либо исход, либо напоминание на границе хода
# Проверка результата: bash hooks/tests/test_open_findings.sh даёт 0
#
# Зачем (8 сентября 2026). Владелец: «ты должен реагировать при обнаружении симптома. ЛЮБОГО.
# И искать ПРИЧИНУ. Есть и сторож и гейт и опять ничего не работает», затем уточнение —
# «событие-триггер глубже», и на выбор из трёх прочтений: НЕЗАКРЫТОСТЬ обнаруженного.
#
# Разбор показал, что распознавание и запись работают, а возврата нет. Гейт разбора пишет
# исход каждого сигнала (`rc_log_outcome`, hooks/root-cause-lib.sh:109), и среди исходов есть
# `deferred` («отказ сработал, правка отложена») и `none` («исхода не наблюдалось»). Читают
# эти записи ТОЛЬКО замеры — как статистику. Ни свод на границе хода, ни гейт закрытия про
# них не знают: `grep -c deferred` по обоим дал 0.
#
# ДРОБЬ, ИЗ КОТОРОЙ ВИДНО, ЧТО ЭТО КОРЕНЬ. Родов сигнала, требующих возврата, три. У знаний
# без исхода есть очередь, напоминание на каждой границе и истечение по семи дням. У пунктов
# долга — completion-gate и архиватор. У обнаружений — журнал есть, возврата нет ни одного.
# M = 1 из 3, разделитель назван: наличие канала напоминания. Накоплено к 8 сентября 2026:
# 115 незакрытых обнаружений в 43 журналах, из них 70 — `discovery → deferred`.
#
# ПОЧЕМУ НЕ НОВЫЙ НОСИТЕЛЬ. Журнал исходов уже есть и уже пишется; заводить рядом второй
# список значило бы развести две правды об одном (`principle-single-source-of-truth`).
# Здесь только ЧТЕНИЕ того, что записано, и счёт незакрытого.
#
# УНИВЕРСУМ ВИДОВ ВЫВОДИТСЯ, А НЕ ПЕРЕЧИСЛЯЕТСЯ. Первая редакция несла список из трёх имён,
# написанный от руки, и он был неверен дважды: имя `finding` в журналах не встречается НИ
# РАЗУ (я его выдумал), а из восьми настоящих поводов разбора учитывались два. Замер 8
# сентября 2026: незакрытых по всем видам 514, моя редакция считала 117 — теряла 77%.
# Единственный источник списка — `RC_KINDS_RE` в hooks/root-cause-lib.sh; здесь он читается,
# а не повторяется. Поймано приростом носителей рода F в тот же ход.
#
# ТРИ СОСТОЯНИЯ, А НЕ ДВА. Источник недоступен — это ПОЛОМКА, и она называется словом
# BROKEN, а не выдаёт ноль: ноль читается как «незакрытого нет», то есть отказ прибора
# становится неотличим от чистого мира (род B).
#
# НАЗВАННЫЙ ПРЕДЕЛ: `none` означает «исход не наблюдался», а не «работа брошена» — сверщик
# исхода видит четыре вида действий и мог не увидеть пятый. Поэтому счёт разделён: `deferred`
# и `none` называются отдельно, и решение по ним разное. Условие снятия: сверщик исхода
# научится различать «не наблюдалось» и «наблюдалось отсутствие».
set -uo pipefail

# of_open_counts [state_dir] — печатает «<deferred> <none> <самый старый ISO-время>».
# Считает по ВСЕМ сессиям: обнаружение, отложенное вчера, сегодня так же незакрыто.
of_open_counts() {
    _of_sd="${1:-${STATE_DIR:-$HOME/.claude/hooks/state}}"
    [ -d "$_of_sd" ] || { printf '0 0 \n'; return 0; }
    command -v python3 >/dev/null 2>&1 || { printf 'BROKEN BROKEN нет python3\n'; return 2; }
    # Виды сигнала берутся у их владельца. Своей копии не заводится: перечень, написанный
    # здесь, разойдётся с источником в тот день, когда там добавят девятый повод.
    # Проверяется ПЕРЕМЕННАЯ, а не функция: владелец перечня — `RC_KINDS_RE`, функции с
    # таким именем в дереве нет и не было. `command -v rc_kinds_re` был ложен всегда, то
    # есть ветка «источник уже загружен» не исполнялась ни разу, а библиотека источалась на
    # каждый вызов. Тот же род, что и остальные разрывы этого коммита: имя, которое читатель
    # спрашивает, писателем не объявлено.
    if [ -z "${RC_KINDS_RE:-}" ]; then
        # OF_RC_LIB — только для проверки ветки поломки: без него её нечем задать, а
        # непроверяемая ветка отказа равна её отсутствию.
        if [ -n "${OF_RC_LIB:-}" ]; then
            # Названный явно источник берётся КАК ЕСТЬ. Откат на угаданный путь превратил бы
            # переопределение в подсказку: указали несуществующий файл — и прибор молча
            # взял другой, то есть ветка поломки осталась бы непроверяемой.
            _of_rcl="$OF_RC_LIB"
        else
            _of_rcl="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.." 2>/dev/null && pwd)/root-cause-lib.sh"
            [ -f "$_of_rcl" ] || _of_rcl="$HOME/.claude/hooks/root-cause-lib.sh"
        fi
        # shellcheck source=/dev/null
        [ -f "$_of_rcl" ] && . "$_of_rcl"
    fi
    _of_kinds="${RC_KINDS_RE:-}"
    [ -n "$_of_kinds" ] || { printf 'BROKEN BROKEN источник видов сигнала недоступен\n'; return 2; }
    # Словарь исходов передаётся ЦЕЛИКОМ, а деление на слова делает python. В оболочке
    # его делать нельзя: `for x in $VAR` под zsh (а Bash-инструмент на macOS — это zsh)
    # проходит ОДИН раз всей строкой, ни один case не совпадает, и в набор закрывающих
    # попадает всё вместе с `deferred` и `none`. Тогда каждая открытая запись гасит
    # предыдущую, и счёт падает в ноль по построению — что и наблюдалось 8 сентября 2026,
    # 517 → 0. Поймал страж уровня отказа на собственной диагностике.
    OF_STATE_DIR="$_of_sd" OF_KINDS="$_of_kinds" OF_OUTCOMES="${RC_OUTCOMES:-}" \
    OF_MODE="${OF_MODE:-}" python3 - <<'PY'
import json, glob, os, datetime
sd = os.environ.get("OF_STATE_DIR", "")
# `RC_KINDS_RE` имеет вид "rework:|correction:|…|event:" — двоеточие там разделитель
# журнальной строки, в поле `signal` его нет. Снимаем и получаем имена.
SIG = {k.strip().rstrip(":") for k in os.environ.get("OF_KINDS", "").split("|") if k.strip()}
deferred = none = unread = 0
oldest = ""
oldest_cmp = None
# Закрывающим считается всё, что не оставляет повод открытым. Набор ВЫВОДИТСЯ из словаря
# владельца (`RC_OUTCOMES`), а не переписывается: появится девятый исход — заработает сам.
CLOSING = set(os.environ.get("OF_OUTCOMES", "").split()) - {"deferred", "none"}
records = []

# Нечитаемый КАТАЛОГ состояния glob отдаёт пустым списком без ошибки, и «0 0» тогда
# означает не «незакрытого нет», а «посмотреть не смогли». Различаем явно: род B требует,
# чтобы неудача чтения считалась и называлась, а не выдавалась за чистоту.
if sd:
    try:
        os.listdir(sd)
    except OSError as e:
        print(f"BROKEN BROKEN каталог состояния нечитаем: {e.__class__.__name__}")
        raise SystemExit(2)

def moment(v):
    """ISO-метка → сравнимый момент. Сравнение СТРОК врёт: `2026-09-08T00:30+03:00`
    хронологически раньше `2026-09-07T23:00:00Z`, а по алфавиту позже. Живой писатель
    ставит только `…Z`, поэтому дефект латентен — но поле объявлено временем, и
    сравнивать его надо как время."""
    if not isinstance(v, str) or not v:
        return None
    t = v.replace("Z", "+00:00")
    try:
        d = datetime.datetime.fromisoformat(t)
    except ValueError:
        return None
    if d.tzinfo is None:
        d = d.replace(tzinfo=datetime.timezone.utc)
    return d

# glob.escape: каталог состояния задаётся переменной, и метасимвол в ЕГО имени
# читался бы как часть шаблона — журнал не нашёлся бы, а ответ был бы правдоподобным нулём.
have_outcome = set()
for fp in sorted(glob.glob(os.path.join(glob.escape(sd), "outcome-*.jsonl"))):
    # Только обычные файлы: канал или сокет заставил бы чтение ждать писателя, а вместе
    # с ним ждала бы вся граница хода.
    if not os.path.isfile(fp):
        unread += 1
        continue
    try:
        with open(fp, encoding="utf-8", errors="replace") as fh:
            lines = fh.readlines()
    except OSError:
        # Неудача чтения считается и называется: молчаливый пропуск делает отказ
        # неотличимым от «нарушений нет» (род B).
        unread += 1
        continue
    for line in lines:
        try:
            o = json.loads(line)
        except ValueError:
            continue
        # Валидный JSON, не являющийся объектом (null, число, список), и нехешируемое
        # значение поля роняли разбор исключением — и вместе с ним весь счёт.
        if not isinstance(o, dict):
            continue
        sig = o.get("signal")
        if not isinstance(sig, str) or sig not in SIG:
            continue
        out = o.get("outcome")
        if out in ("deferred", "none") or out in CLOSING:
            records.append((moment(o.get("ts")), o.get("ts"), sig, out, (o.get("ref") or "")))
        # Ключ повода: сессия + ход + срод. Нужен, чтобы ниже не посчитать дважды повод,
        # у которого запись исхода уже есть.
        have_outcome.add((os.path.basename(fp)[len("outcome-"):-len(".jsonl")],
                          str(o.get("key", "")), sig))
# ПОВОДЫ БЕЗ ЕДИНОЙ ЗАПИСИ ИСХОДА (9 сентября 2026). Источник истины о том, что повод
# БЫЛ, — журнал гейта `five-whys-<SID>.seen`, а не журнал исходов: исход пишется позже и
# может не написаться вовсе. Замер по живому каталогу: поводов 1236, с исходом 991 (80%),
# без единой записи 245 (19%); из них 157 (64%) — в десяти сессиях из 61, где Stop не
# отработал совсем и журнала исходов нет. Эти поводы были невидимы дважды: и как открытые,
# и как закрытые.
# Метка времени берётся у файла журнала: строка `.seen` времени не несёт, а mtime — время
# последней записи сессии. НАЗВАННЫЙ ПРЕДЕЛ: все поводы одной сессии получают одно время,
# поэтому «самому старому N дней» для них огрубляется до конца их сессии. Условие снятия:
# гейт начнёт писать метку времени в строку журнала.
seen_no_outcome = set()
for fp in sorted(glob.glob(os.path.join(glob.escape(sd), "five-whys-*.seen"))):
    if not os.path.isfile(fp):
        unread += 1
        continue
    sid = os.path.basename(fp)[len("five-whys-"):-len(".seen")]
    try:
        with open(fp, encoding="utf-8", errors="replace") as fh:
            seen_lines = fh.readlines()
        fmt = datetime.datetime.fromtimestamp(os.path.getmtime(fp), datetime.timezone.utc)
    except OSError:
        unread += 1
        continue
    fts = fmt.strftime("%Y-%m-%dT%H:%M:%SZ")
    for line in seen_lines:
        if not line.startswith("turn:"):
            continue
        key, _, rest = line[len("turn:"):].partition("|")
        for part in rest.split("|"):
            sig = part.split(":", 1)[0]
            if not sig or sig not in SIG:
                continue
            trip = (sid, key, sig)
            # Дедуп по тройке «сессия + ход + срод». Один ход пишется в журнал несколько
            # раз — при каждом НОВОМ отпечатке сигнала, — и одна тройка встречается в
            # нескольких строках. Без дедупа счёт завышался бы: 407 строк на 245 поводов.
            if trip in have_outcome or trip in seen_no_outcome:
                continue
            seen_no_outcome.add(trip)
            records.append((moment(fts), fts, sig, "none", ""))

# Непрочитанный журнал делает счёт НЕПОЛНЫМ, и частичное число НЕ выходит в поле, откуда
# его берут как полное: потребитель, читающий первое поле, обязан увидеть поломку, а не
# число поменьше. Частичные значения сохраняются в тексте причины — они полезны для
# понимания, но не подставляются в отчёт как факт. Цена строгости названа: один нечитаемый
# журнал гасит счёт целиком; в живом каталоге таких ноль, а класс «частичное выдано за
# полное» закрывается по построению.
# ЗАЧЁТ ПО ВИДУ СИГНАЛА. Исход НЕИЗМЕНЯЕМ: `rc_log_outcome` идемпотентен по паре
# ключ+сигнал, второй записи по тому же поводу не будет. Значит закрытие приходит ДРУГОЙ
# записью, с другим ключом, и связать её с конкретным поводом нечем. Считаем зачётом:
# более позднее закрытие того же ВИДА гасит самое раннее незакрытое того же вида.
#
# НАЗВАННЫЙ ПРЕДЕЛ, и он честный: это счёт «сколько повисло», а не «какой именно повис».
# Утверждение «закрыт повод номер N» отсюда не следует и здесь не делается. Условие снятия:
# закрывающая запись начнёт нести ссылку на ключ закрываемого повода — тогда зачёт
# сменится сопоставлением, и предел уйдёт вместе с приближением.
records.sort(key=lambda r: (r[0] is None, r[0], r[1] or ""))
open_by_sig = {}
for m, ts, sig, out, ref in records:
    q = open_by_sig.setdefault(sig, [])
    if out in CLOSING:
        if q:
            q.pop(0)
    else:
        q.append((m, ts, out, ref))
for sig, q in open_by_sig.items():
    for m, ts, out, ref in q:
        if out == "deferred":
            deferred += 1
        else:
            none += 1
        if m is not None and (oldest_cmp is None or m < oldest_cmp):
            oldest_cmp, oldest = m, ts

if unread:
    print(f"BROKEN BROKEN журналов не прочитано: {unread} (частичный счёт: {deferred} отложено, {none} без исхода)")
    raise SystemExit(2)

# Режим перечня. Зачёт по виду выше — ЕДИНСТВЕННЫЙ: перечень и счёт обязаны отвечать
# об одном мире, а вторая копия правила зачёта разошлась бы с первой при первой же правке.
# Названный предел тот же, что у счёта: строка перечня говорит «повод этого вида и этого
# возраста повис», а не «повис ИМЕННО он» — связать закрытие с конкретным поводом нечем,
# пока закрывающая запись не несёт ключа закрываемого.
if os.environ.get("OF_MODE") == "list":
    rows = [(m, ts, sig, out, ref) for sig, q in open_by_sig.items() for m, ts, out, ref in q]
    rows.sort(key=lambda r: (r[0] is None, r[0], r[1] or ""))
    for m, ts, sig, out, ref in rows:
        print("\t".join([(ts or "")[:16], sig, out, (ref or "— предмет не записан").replace("\t", " ")[:200]]))
    raise SystemExit(0)
print(f"{deferred} {none} {oldest} {unread}")
PY
}

# of_open_list [state_dir] — те же незакрытые поводы, что считает of_open_counts, но
# строками «время<TAB>вид<TAB>исход<TAB>предмет». Правило зачёта не дублируется: это тот
# же прибор в другом режиме.
of_open_list() { OF_MODE=list of_open_counts "$@"; }
