#!/usr/bin/env python3
"""Detect undated relative-time expressions in assistant output.

Читает текст последней реплики агента со stdin, печатает по строке на находку
в виде «выражение :: фрагмент» (не более 5).

Правило то же, что у `test_backlog_relative_dates.sh` («даты только
абсолютные», корень 2026-08-08: «сегодня» в пункте BACKLOG прожило неделю), но
на другой поверхности — в тексте ответа. Разница в форме: в прозе относительное
слово запрещать нельзя, там оно естественно. Запрещается относительное слово
БЕЗ абсолютного якоря рядом: «вчера (20 августа)» — чисто, «вчера» — находка.
Якорь — дата или время суток; правило про время в целом, не только про
календарный день, поэтому «час назад» без «(19:40)» — тоже находка.

Почему именно так. Ошибка возникает не от незнания даты, а от того, что
относительное время берётся из близости в разговоре, а не из вычитания дат:
запись в SESSION.md рядом — значит «вчера». Требование написать дату рядом
делает вычитание обязательным шагом, а промах — видимым собеседнику сразу.

Исключения (иначе шум вместо сигнала):
  - блоки кода ``` ``` и `inline`
  - строки-цитаты «> ...» — цитата чужого текста не утверждение агента
  - предложение, где абсолютная дата уже есть
"""
import re
import sys

MONTHS = r"январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр"

# Единицы любого масштаба: правило про время, не только про календарь
# (поправка собеседника 21.08.2026 — «дата и время, а не просто дата»).
UNITS = r"(?:минут\w*|час\w*|дн\w+|день|недел\w+|месяц\w*|год\w*|лет)"

RELATIVE = re.compile(
    r"\b(?:позавчера|вчерашн\w+|вчера|сегодняшн\w+|сегодня|завтра|послезавтра"
    r"|на\s+днях|недавно|давеча"
    r"|на\s+(?:этой|прошлой)\s+неделе|в\s+прошлом\s+месяце"
    r"|только\s+что|полчаса\s+назад"
    r"|(?:\d+|пару|несколько|неделю|месяц|час)\s+" + UNITS + r"?\s*назад)\b",
    re.IGNORECASE | re.UNICODE,
)

# Якорь — дата ИЛИ время суток: «час назад (в 19:40)» так же закрывает вопрос
# «когда именно», как «вчера (20 августа)».
ABSOLUTE = re.compile(
    r"\d{1,2}:\d{2}"
    r"|\d{4}-\d{2}-\d{2}"
    r"|\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?"
    r"|\d{1,2}\s+(?:" + MONTHS + r")\w*"
    r"|(?:" + MONTHS + r")\w*\s+\d{1,2}",
    re.IGNORECASE | re.UNICODE,
)

CAP = 5


def strip_noise(text: str) -> str:
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = re.sub(r"`[^`\n]*`", " ", text)
    # Слово в кавычках — упоминание, не датировка: «правило про „вчера“» события не
    # датирует. Без этого любой разговор о самом правиле поднимает находку.
    text = re.sub(r"«[^»\n]{0,40}»", " ", text)
    return "\n".join(l for l in text.split("\n") if not l.lstrip().startswith(">"))


def sentences(text: str):
    for line in text.split("\n"):
        for part in re.split(r"(?<=[.!?;:])\s+", line):
            part = part.strip()
            if part:
                yield part


def find(text: str):
    out, seen = [], set()
    for sent in sentences(strip_noise(text)):
        hits = RELATIVE.findall(sent)
        if not hits or ABSOLUTE.search(sent):
            continue
        for expr in hits:
            key = expr.lower()
            if key in seen:
                continue
            seen.add(key)
            excerpt = re.sub(r"\s+", " ", sent)[:70]
            out.append(f"{expr} :: {excerpt}")
            if len(out) >= CAP:
                return out
    return out


def main() -> int:
    text = sys.stdin.read()
    if not text.strip():
        return 0
    for line in find(text):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
