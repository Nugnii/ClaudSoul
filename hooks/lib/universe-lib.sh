#!/usr/bin/env bash
# universe-lib.sh — множество файлов, которое обходит страж, ВЫВОДИТСЯ из индекса git.
#
# Корень рода F (D285, D294, 4 сентября 2026). Страж задавал своё множество шаблоном
# оболочки: `for f in scripts/*.sh`. Шаблон оболочки НЕ СПУСКАЕТСЯ в подкаталоги, и то,
# что в него не попало, страж не видит и молчит об этом: вердикт зелёный о непросмотренном.
# Замер того дня: `test_instrument_contract` печатал «2/2 passed», а 13 инструментов
# `scripts/ablation` не несли ни одной строки контракта — для стража их не существовало.
#
# `git ls-files` трактует `*` как спускающийся (fnmatch без FNM_PATHNAME), поэтому здесь
# множество ВЫВЕДЕНО из индекса, а исключения названы явно и по одному разу на всё дерево
# стражей. Тот же приём уже стоит в `scripts/docs-inventory.sh:49` (git ls-files) и в
# `hooks/tests/test_multibyte_var_boundary.sh:53` (find по дереву) — эта библиотека их не
# заменяет, она даёт третьей группе стражей общий источник вместо трёх перечней.
#
# ПУСТОЙ УНИВЕРСУМ — ОТКАЗ, а не пустой список. Дерево без `.git` (распакованный
# `git archive`, tarball) даёт `git ls-files` ноль строк, и страж стал бы зелёным, не
# посмотрев ни на один файл, — ровно тот дефект, который библиотека закрывает.
#
# Вызывающий задаёт UNIVERSE_ROOT — корень репозитория.

_universe() {
    # Учтённые ПЛЮС новые неигнорируемые (D1240): новый файл до `git add` иначе вне суда, и прогон перед коммитом
    # зеленел там, где CI на том же коммите красен.
    _u_out=$(git -C "$UNIVERSE_ROOT" ls-files --cached --others --exclude-standard -- "$@" 2>/dev/null)
    [ -n "$_u_out" ] || {
        echo "universe: индекс git не дал файлов по «$*» в $UNIVERSE_ROOT" >&2
        return 1
    }
    printf '%s\n' "$_u_out"
}

# Инструменты проекта — всё исполняемое в scripts/ ВМЕСТЕ С подкаталогами
# (scripts/ablation/, scripts/ablation/core/; в scripts/publish/ исполняемого нет).
universe_instruments() { _universe 'scripts/*.sh' 'scripts/*.py'; }

# Те же инструменты, только оболочечные.
universe_instruments_sh() { _universe 'scripts/*.sh'; }

# Код хуков — hooks/ вместе с под-библиотеками hooks/lib/.
# ИСКЛЮЧЕНО: hooks/tests/ — фикстуры несут ломаные формы НАРОЧНО (test_bsd_forms_paired
# пишет `stat -f %m` без GNU-пары, чтобы доказать, что страж краснеет). Проверка по
# фикстурам краснела бы на доказательствах стражей, а не на дефектах.
universe_hook_code() { _universe 'hooks/*.sh' | grep -v '^hooks/tests/'; }

# Сами тесты. В отличие от universe_hook_code, фикстуры здесь НЕ исключение, а предмет:
# речь о форме самого теста (чем берётся его код возврата), а не о коде, который он щупает.
universe_tests() { _universe 'hooks/tests/test_*.sh'; }

# Вся отслеживаемая документация — именно ВСЯ: предмет здесь свойство файла (последний
# байт), а не его роль, поэтому исключать нечего.
universe_docs() { _universe '*.md'; }

# Весь оболочечный код дерева, включая подкаталоги. Предмет — ОПРЕДЕЛЕНИЯ функций: чем
# больше файлов просмотрено, тем полнее справочник известных имён. Пропуск здесь даёт не
# молчание, а ЛОЖНУЮ тревогу: определённая в непросмотренном файле функция объявляется
# несуществующей. Замер 6 сентября 2026 на перечне globов: невидимы 9 файлов scripts/
# (scripts/ablation/) и 4 файла hooks/tests/.
universe_shell_all() { _universe 'hooks/*.sh' 'lib/*.sh' 'scripts/*.sh' 'bin/*.sh'; }

# ДЕРЕВО, НЕПОЛНОЕ ПО ПОСТРОЕНИЮ. Публичный снимок собирается из `git archive` с изъятием
# внутреннего (рабочий долг, карта корней, подсистема публикации), и у прибора, чей предмет
# изъят, «файла нет» начинает нести ДВА состояния мира: «исключён по решению» и «пропал».
# Это корень R6, и цена измерена: публичный CI красен с 30 августа 2026, пять публикаций
# подряд, а число павших тестов росло вместе с набором — 2 (v1.31.1) → 4 (v1.32.0) → 10 (v1.34.0).
#
# Признаком служит МАРКЕР, который кладёт в снимок сам публикатор (`scripts/publish-public.sh`),
# а не догадка по отсутствию файла: «не трекается» в рабочем дереве значит РОВНО ОБРАТНОЕ —
# механизм удалён, и мёртвое упоминание о нём обязано краснеть. Один канал на два состояния
# так и остался бы одним каналом, только с другим именем.
#
# НАЗВАННЫЙ ПРЕДЕЛ И ЕГО СТОРОЖ: файл с этим именем, положенный в рабочее дерево, ослепил бы
# разом все проверки ниже. Поэтому его отсутствие в рабочем дереве — отдельная нога набора
# (`hooks/tests/test_public_snapshot_marker.sh`), и маркер не трекается git никогда.
# Условие снятия: у снимка появится собственная рамка прогона (свой workflow, своя команда),
# где неприменимые проверки просто не запускаются, — тогда признак внутри теста станет не нужен.
# КОРЕНЬ ОБЯЗАТЕЛЕН. Умолчание брало его у ТЕКУЩЕГО каталога, и это ослепляло признак:
# тест, перешедший в свою песочницу, объявлял её снимком, если там случайно лежал файл с этим
# именем, — а фикстуры такие файлы кладут нарочно. Найдено раундом критика в час заведения
# (hooks/tests/test_adv_snapshot_marker_root.sh). Неназванный корень — ошибка ЗОВУЩЕГО, и
# отвечать на неё надо громко и в безопасную сторону: «дерево полное», то есть проверки
# остаются включёнными, плюс жалоба в stderr. Молчаливое «неполное» выключило бы их.
universe_partial_tree() {
    [ -n "${UNIVERSE_ROOT:-}" ] || {
        echo "universe_partial_tree: UNIVERSE_ROOT не задан — считаю дерево полным, проверки остаются" >&2
        return 1
    }
    [ -f "$UNIVERSE_ROOT/.public-snapshot" ]
}

# Причина пропуска печатается ОДНОЙ формой на всё дерево: «пропущено» без предмета неотличимо
# от «проверено и чисто» (правило трёх состояний прибора, .claude/rules/claudsoul-hooks.md § «Хук зовёт инструмент»).
universe_skip_note() { printf '    … SKIP [%s]: %s — в публичном снимке не публикуется, судить нечего\n' "${1:-нога}" "${2:-предмет}"; }
