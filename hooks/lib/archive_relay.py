#!/usr/bin/env python3
"""archive_relay.py — отказ архиватора, который держит закрытый пункт запуск за запуском, доходит до владельца, а не только до модели.

Результат: пока закрытый пункт висит под отказом архиватора столько запусков подряд, сколько задаёт срок
           (ARCHIVE_RELAY_RUNS, 12), сборщик на каждой границе хода ставит в напоминания следующей реплики строку
           «СКАЖИ владельцу» с номером пункта и причиной — до тех пор, пока итог хода этот номер не назовёт
Проверка результата: bash hooks/tests/test_archive_relay.sh даёт 0

Повод (D1271, 7 ноября 2026, ProjectA_NEW): 11 закрытых пунктов висели две недели под меткой «судит по форме». Причину
архиватор печатал (`scripts/backlog-archive.sh`), сборщик клал её в постоянное напоминание с дросселем по составу — модель
видела её ОДИН раз, а передала ли владельцу, не сверял никто; владелец спросил словами симптома. Поверхность владельца в
VSCode — только текст диалога, и пишет его модель (rules, § «Назови поверхность»), поэтому доставка держится сверкой
итога: номер не назван — напоминание повторяется на следующем ходу, без дросселя.

СРОК — В РАБОТЕ, НЕ В ЧАСАХ (D1352, решение владельца 21 ноября 2026; корень R4). Прежде срок был «сутки по часам»:
двое суток тишины давали напоминание, хотя работы не было, а сто ходов за день его не давали. Мера — число вызовов
прибора, при которых отказ пункта стоял: сборщик зовёт прибор раз на границу хода, и его собственные вызовы и есть
счётчик наработанного. У счёта ОДИН владелец — файл состояния этого прибора: первая редакция брала ещё и число
записей журнала архиватора через `max`, а архиватор пишет запись раньше, чем сборщик зовёт прибор, — счёт всегда
равнялся журналу за всё время и не сбрасывался с уходом отказа (скептик opus, H1). Порог 12 снят с журнала отказов
архиватора за 36 дней по записям режима `run` у номеров, которые видел сборщик (68 номеров): у 57 отказ уходил в
рабочем порядке не более чем за 9 запусков (медиана 2), у 11 зависших набиралось от 33 до 138.
Календарь остался только в ПОКАЗЕ («висит до N дн.») — там он законен.

Вызов: archive_relay.py <файл состояния> <сейчас, эпоха> <срок, запусков> <чей — для текста> <итог хода>; stdin — вывод
архиватора (пустой — отказа нет, файл состояния снимается, счёт запусков вместе с ним). stdout — строка напоминания либо
ничего. Состояние: «пункт ⇥ первая встреча ⇥ показан (0/1) ⇥ назван (0/1) ⇥ причина ⇥ запусков». Строка прежнего вида (без
шестого поля) читается с нулём запусков. «Назван» засчитывается только после показа: номер, упомянутый до срока по другому
поводу, доставку не гасит.
НАЗВАННЫЙ ПРЕДЕЛ: «назван» — номер пункта словом в итоге хода, а не пересказ причины.
Условие снятия: у отказа архиватора появится ключ причины, по которому пересказ в итоге хода сверяется машинно.
НАЗВАННЫЕ ПРЕДЕЛЫ СЧЁТА (скептик opus по D1352). 1. Счёт начинается с первого вызова прибора: отказ, висевший до его
установки, напомнит через срок запусков после неё. 2. Ответ архиватора без фразы об отказе при живом отказе («старше
скрипта», «нет определения пункта», вложенный прогон) снимает состояние и счёт вместе с ним; на настоящей границе хода
таких ответов не наблюдалось. 3. Срок не числом (`ARCHIVE_RELAY_RUNS=12h`) роняет прибор, и сборщик это глушит —
прибор молчит; так же было со сроком в секундах. 4. Прибор и сборщик меняют единицу срока ВМЕСТЕ: новый сборщик со
старым прибором читает 12 как секунды, старый с новым — 86400 запусков.
"""
import datetime as dt, glob, json, os, re, sys

REFUSAL = re.compile(r"^  · ([A-Z][A-Z0-9]*-?\d+): (.*)$")


def main(argv):
    """Окно «прочитать состояние — переписать» под общим замком (род H): сборщики параллельных сессий одного бэклога
    зовут модуль одновременно. Замка нет или он не взят — окно всё равно исполняется (как у `state_lock.with_lock`)."""
    out = sys.stdin.read()
    try:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from state_lock import with_lock
    except ImportError:
        return relay(argv, out)
    with with_lock(argv[1]):
        return relay(argv, out)


def relay(argv, out):
    st, now, need, who, last = argv[1], int(argv[2]), int(argv[3]), argv[4], argv[5]
    refused = {}
    for line in out.splitlines():
        m = REFUSAL.match(line)
        if m:
            refused[m.group(1)] = m.group(2).strip()
    if not refused:
        try:
            os.remove(st)
        except OSError:
            pass
        return 0
    old = {}
    try:
        for line in open(st, encoding="utf-8"):
            f = line.rstrip("\n").split("\t")
            if len(f) >= 4 and f[1].isdigit():
                old[f[0]] = (int(f[1]), f[2] == "1", f[3] == "1", int(f[5]) if len(f) >= 6 and f[5].isdigit() else 0)
    except (OSError, UnicodeDecodeError, ValueError):
        old = {}   # нечитаемое состояние — как его нет: перезапишется, доставка не выключается навсегда
    # Первая встреча ДЛЯ ПОКАЗА — у владельца факта, журнала отказов архиватора (`backlog-archive-fired-<день>.jsonl` в
    # том же каталоге состояния): «висит до N дн.» называет настоящий возраст отказа, а не возраст файла состояния.
    # Журнал не несёт пути бэклога — одинаковый номер в двух бэклогах берёт самую раннюю встречу. Срок журнал НЕ двигает.
    jfirst = {}
    for jf in glob.glob(os.path.join(os.path.dirname(st) or ".", "backlog-archive-fired-*.jsonl")):
        try:
            for jl in open(jf, encoding="utf-8", errors="replace"):
                try:
                    r = json.loads(jl)
                    iid, ts = r.get("item"), r.get("ts", "")
                    if iid in refused and ts:
                        t = int(dt.datetime.fromisoformat(ts.replace("Z", "+00:00")).timestamp())
                        jfirst[iid] = min(jfirst.get(iid, t), t)
                except Exception:
                    continue
        except OSError:
            continue
    # «Назван» — номер словом И речь об архиве в том же итоге (скептик opus по b8f9cb64, M1): очередь напоминаний общая
    # для сессий, и «правлю D1233» в соседней сессии гасило бы доставку, не сказав владельцу об отказе ни слова.
    talks_archive = re.search(r"архив", last, re.I) is not None
    said = lambda iid: talks_archive and re.search(r"(?<![\w-])" + re.escape(iid) + r"(?![\w-])", last) is not None
    rows, due = [], []
    for iid, why in refused.items():
        first, shown, relayed, runs = old.get(iid, (now, False, False, 0))
        first = min(first, jfirst.get(iid, first))
        runs += 1   # этот вызов — ещё один запуск с отказом; владелец счёта — состояние прибора, журнал его не двигает
        relayed = relayed or (shown and said(iid))
        now_due = not relayed and runs >= need
        if now_due:
            due.append((iid, why, (now - first) // 86400, runs))
        rows.append("%s\t%d\t%d\t%d\t%s\t%d" % (iid, first, 1 if (shown or now_due) else 0, 1 if relayed else 0,
                                               why.replace("\t", " "), runs))
    tmp = st + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("\n".join(rows) + "\n")
    os.replace(tmp, st)
    if due:
        # Одна причина — одна часть строки (скептик, L: 11 пунктов ProjectA давали 2170 символов с той же причиной 11 раз).
        groups = {}
        for i, w, d, n in due:
            groups.setdefault(w, []).append((i, d, n))
        def cut(w, n=200):
            return w if len(w) <= n else w[:n].rsplit(" ", 1)[0] + " …"
        parts = "; ".join("%s (отказов подряд до %d, висит до %d дн.): %s"
                          % (", ".join(i for i, _, _ in ids), max(n for _, _, n in ids), max(d for _, d, _ in ids), cut(w))
                          for w, ids in groups.items())
        print("🗄️ СКАЖИ владельцу словами, с номерами пунктов: архиватор%s не уносит закрытые пункты запуск за запуском — %s. "
              "Напоминание повторится, пока итог хода не назовёт номер. " % (who, parts))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
