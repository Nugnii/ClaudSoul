#!/usr/bin/env bash
# adversary-run-lib.sh — «был ли в этой расшифровке адверсариальный прогон». ЕДИНЫЙ ИСТОЧНИК.
# en: single source for "did an adversarial run happen in this transcript".
#
# ПРЕФИКСЫ: adversary_
#
# Зачем библиотека, а не копия. Детект нужен двум потребителям: стражу
# `code-review-reminder.sh` (решает, напоминать ли) и ретро-прогону
# `scripts/adversary-replay.sh` (меряет точность признака по корпусу). Две копии одного
# правила разойдутся на первой же правке, и тогда замер будет мерить НЕ ТО, что делает
# страж, — это род K реестра дефектов («правило вынесено в модуль, копия у потребителя
# осталась»). Вынесено 9 сентября 2026 вместе с заведением замера (D372).
#
# ВЫЗОВ, А НЕ УПОМИНАНИЕ — граница, ради которой существует точный разбор. Имя скилла
# встречается в обычном разговоре о нём: замер 9 сентября по 55 расшифровкам дал 30 с
# упоминанием против 10 с настоящим вызовом, то есть дешёвый `grep` завысил бы втрое.
#
# ИМЯ СКИЛЛА И МАРКЕР ПРОМПТА — РАЗНЫЕ ФАКТЫ, и до переименования 28.08.2026 они случайно
# совпадали. Скилл зовётся `adversary`, роль внутри его промпта осталась русской
# («Ты противник»): вызов Skill опознаётся по первому, вызов Agent/Workflow — по второму.
# Слить их обратно в одну переменную значит потерять половину детекта.
#
# ПОЛЕ `description` НАМЕРЕННО НЕ СЧИТАЕТСЯ: его пишут свободным текстом, и «обсуждаем
# противника» стало бы ложным зачётом прогона.
#
# ТО ЖЕ ПРАВИЛО — И К `prompt`, И К `script` (9 сентября 2026, атака 3 противника). Прежде
# оно было названо на ОДНОМ носителе формы: `description` исключался поимённо, а `prompt` и
# `script` — такой же свободный текст — проверялись голым `contains`. Следствие: промпт
# «найди в дереве все файлы, где встречается строка Ты противник» засчитывался ПРОГОНОМ,
# страж замолкал на крупном диффе, и в знаменатель шло `satisfied` — ошибка в ОПАСНУЮ
# сторону, занижающая ровно ту долю, по которой ADR-015 решает про уровень принуждения.
# Это `case-2026-09-08-rule-names-half-the-device`: правило назвало половину устройства.
#
# Признаки разные, потому что различают РОЛЬ, а не вид текста:
#   · `prompt` — маркер стоит В НАЧАЛЕ (там назначается роль субагента). ИЗМЕРЕНО по
#     корпусу 55 расшифровок: 30 настоящих промптов из 30 несут маркер первым, то есть
#     якорь не теряет ни одного; упоминание внутри инструкции отвергается.
#   · `script` — маркер И вызов `agent(`: настоящий воркфлоу ПЕРЕДАЁТ маркер агенту,
#     атака передаёт его `bash(` как образец для поиска.
#     НАЗВАННЫЙ ПРЕДЕЛ: измерено на 2 настоящих скриптах и 1 атаке — этого мало. Скрипт,
#     где рядом стоят и `agent(`, и поиск по маркеру, признак не различит. Условие снятия:
#     появится третий-четвёртый настоящий воркфлоу — пересчитать и, если нужно, сузить.
#
# ПРОГОН ИЗ ДРУГОЙ СЕССИИ (D373, 13 сентября 2026). До этого дня расшифровка была одна, и
# чужой прогон был невидим — ошибка в безопасную сторону (лишнее напоминание), но замеру
# точности она давала ИНТЕРВАЛ вместо точки: 58 срабатываний из 212 пришлись на дни, когда
# противник бегал в соседней сессии, и решить, ложные они или нет, было нечем.
# Теперь `adversary_run_elsewhere` читает соседние расшифровки того же проекта (тот же
# каталог, что у своей), и чужой прогон из другой сессии засчитывается, если случился В
# ОКНЕ: от времени HEAD до «сейчас» (у стража) либо до времени вызова коммита (у
# ретро-прогона). Единица окна — РАБОТА, а не календарь: сессии одного каталога делят
# рабочее дерево, дифф не бывает старше HEAD, и прогон старше HEAD его видеть не мог.
# НАЗВАННЫЙ ПРЕДЕЛ: правка, сделанная до HEAD и не вошедшая в него (частичная стадия),
# старше окна — прогон над ней засчитан не будет, напоминание выйдет лишний раз. Условие
# снятия: окно от времени последней правки файлов диффа, когда появится дешёвый способ его
# узнать.

PORTABLE_LIB_AR="${PORTABLE_LIB_AR:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.." 2>/dev/null && pwd)/portable-lib.sh}"
[ -f "$PORTABLE_LIB_AR" ] || PORTABLE_LIB_AR="$HOME/.claude/hooks/portable-lib.sh"
# shellcheck source=/dev/null
if [ -f "$PORTABLE_LIB_AR" ]; then . "$PORTABLE_LIB_AR"; fi

# _arc_select <файл расшифровки> — по строке на каждый опознанный вызов противника:
# `<время ISO>\t<вид>` (skill | agent | workflow | workflow-path). Правило опознания живёт
# ЗДЕСЬ и только здесь: adversary_run_count считает строки, adversary_run_elsewhere читает
# время. Коды: 0 — прочитал (пусто значит «вызовов нет»); 2 — НЕ СМОГ прочитать.
# ADVERSARY_SELECT_CACHE=<каталог> — память по «путь + mtime + параметры опознания»: ретро-прогон
# спрашивает одну и ту же расшифровку сотни раз, а разбор большой расшифровки стоит секунды.
# Параметры входят в ключ не для полноты: без них отрицательное плечо самопроверки
# ретро-прогона (невозможное имя скилла на том же файле) читало ответ положительного.
_arc_select() {
    _arc_tr="${1:-}"
    _arc_skill="${ADVERSARY_SKILL_NAME:-adversary}"
    # ИМЯ ПРИЗНАКА ИМЕЕТ ИСТОРИЮ, и ретро-прогон смотрит в корпус СТАРШЕ переименования.
    # Скилл звался `противник` до 28.08.2026; в живом корпусе 55 расшифровок таких вызовов
    # три против четырёх с нынешним именем — то есть сверка одним значением слепа к 3 из 7.
    # Обещание ретро-прогона «воспроизводит ровно то, что страж видел в тот момент» без
    # прежних имён неисполнимо: тогда страж искал ДРУГОЕ имя. Поймано вторым раундом
    # противника 9 сентября 2026. Список пополняется при каждом переименовании скилла.
    _arc_legacy="${ADVERSARY_SKILL_NAMES_LEGACY:-противник}"
    _arc_marker="${ADVERSARY_PROMPT_MARKER:-Ты противник}"

    if [ -z "$_arc_tr" ] || [ ! -f "$_arc_tr" ] || ! command -v jq >/dev/null 2>&1; then
        return 0
    fi
    _arc_ck=""
    if [ -n "${ADVERSARY_SELECT_CACHE:-}" ] && [ -d "$ADVERSARY_SELECT_CACHE" ] && command -v file_mtime >/dev/null 2>&1; then
        _arc_ck="$ADVERSARY_SELECT_CACHE/$(printf '%s:%s:%s:%s:%s' "$_arc_tr" "$(file_mtime "$_arc_tr" 2>/dev/null || echo 0)" "$_arc_skill" "$_arc_legacy" "$_arc_marker" | cksum | cut -d' ' -f1)"
        if [ -f "$_arc_ck" ]; then cat "$_arc_ck"; return 0; fi
    fi

    # Дешёвый фильтр пропускает и расшифровки со `scriptPath`: при запуске воркфлоу по пути
    # имени скилла в расшифровке нет вовсе, и фильтр по имени отсекал бы ровно тот случай,
    # ради которого написана ветка ниже (поймано тестом T14 до выпуска).
    _arc_seen=0
    for _arc_nm in $_arc_skill $_arc_legacy; do
        grep -qF "$_arc_nm" "$_arc_tr" 2>/dev/null && { _arc_seen=1; break; }
    done
    if [ "$_arc_seen" -eq 0 ] &&
       ! { grep -qF "$_arc_marker" "$_arc_tr" 2>/dev/null ||
           grep -qF '"scriptPath"' "$_arc_tr" 2>/dev/null; }; then
        [ -n "$_arc_ck" ] && : > "$_arc_ck" 2>/dev/null
        return 0
    fi

    # ЧИСТКА ПЕРЕД СЛУРПОМ — обязательная идиома проекта, а не осторожность.
    # `jq -rs` собирает весь файл целиком, и ОДНА оборванная строка роняет разбор
    # полностью: вызов противника, лежащий строкой 1, переставал считаться из-за мусора
    # строкой 2. Канон записан у `scripts/injection-outcome.sh` («одна битая строка роняет
    # весь разбор и прибор молчит вместо находки»); здесь он был написан заново без
    # чистки — тот же род K. Поймано противником 9 сентября 2026 (атака 2).
    _arc_clean=$(mktemp 2>/dev/null) || return 2
    jq -cRn 'inputs | fromjson? // empty' "$_arc_tr" > "$_arc_clean" 2>/dev/null
    # Сырой файл непуст, а разобрать не удалось НИ ОДНОЙ строки — это «не смог», а не «ноль».
    if [ -s "$_arc_tr" ] && [ ! -s "$_arc_clean" ]; then
        rm -f "$_arc_clean" 2>/dev/null; return 2
    fi

    _arc_sel=$(jq -r --arg s "$_arc_skill" --arg m "$_arc_marker" --arg L "$_arc_legacy" '
        ([$s] + ($L | split(" ") | map(select(length > 0)))) as $names
        | .timestamp as $t
        | (.message.content? // [])
        | if type == "array" then .[] else empty end
        | select(type == "object" and .type == "tool_use")
        # `IN($names[])`, а не `$names | index(...)`: конвейер сдвигает `.` И ДЛЯ АРГУМЕНТА,
        # поэтому `index(.input.skill)` искал поле `input` в самом массиве имён и падал
        # с «Cannot index array with string». Здесь `.` остаётся строкой имени скилла.
        | if (.name == "Skill" and ((.input.skill // "") | IN($names[]))) then "\($t)\tskill"
          elif (.name == "Agent" or .name == "Task")
               and (((.input.prompt // "") | sub("^[[:space:]]+"; "") | startswith($m))) then "\($t)\tagent"
          elif (.name == "Workflow")
               and (((.input.script // "") | contains($m)))
               and (((.input.script // "") | contains("agent("))) then "\($t)\tworkflow"
          else empty end
    ' "$_arc_clean" 2>/dev/null)
    _arc_rc=$?
    # Ненулевой код jq — это «не смог», а не «ноль». Различие держится на коде возврата, а
    # не на пустоте вывода: у здоровой расшифровки без единого вызова инструмента вывод
    # честно пуст при коде 0, и такой случай обязан остаться ответом, а не заглушкой.
    if [ "$_arc_rc" -ne 0 ]; then rm -f "$_arc_clean" 2>/dev/null; return 2; fi

    # Воркфлоу, запущенный по пути: промпт лежит в файле, а не в расшифровке. Ветка нужна,
    # только когда прямых вызовов нет, и засчитывает ОДИН — так было и до разбиения на
    # выборку и счёт (число, которое печатает adversary_run_count, не изменилось).
    if [ -z "$_arc_sel" ]; then
        _arc_paths=$(jq -r '
            .timestamp as $t
            | (.message.content? // [])
            | if type == "array" then .[] else empty end
            | select(type == "object" and .type == "tool_use" and .name == "Workflow")
            | (.input.scriptPath // empty) | "\($t)\t\(.)"
        ' "$_arc_clean" 2>/dev/null)
        while IFS="$(printf '\t')" read -r _arc_wt _arc_wf; do
            [ -n "$_arc_wf" ] && [ -f "$_arc_wf" ] || continue
            if grep -qF "$_arc_marker" "$_arc_wf" 2>/dev/null; then
                _arc_sel="$(printf '%s\tworkflow-path' "$_arc_wt")"; break
            fi
        done <<EOF
$_arc_paths
EOF
    fi

    rm -f "$_arc_clean" 2>/dev/null
    [ -n "$_arc_ck" ] && printf '%s' "$_arc_sel" > "$_arc_ck" 2>/dev/null
    [ -n "$_arc_sel" ] && printf '%s\n' "$_arc_sel"
    return 0
}

# adversary_run_count <файл расшифровки> — печатает число вызовов противника.
#
# ТРИ СОСТОЯНИЯ, А НЕ ДВА (9 сентября 2026, атака 2 противника):
#   код 0 — прочитал: напечатанное число есть ответ;
#   код 2 — НЕ СМОГ прочитать (разбор расшифровки не собрался): печатается 0, но это не
#           ответ, а заглушка, и потребитель обязан различать.
#
# Прежняя редакция обещала «всегда возвращает 0» и предлагала различать беду гейтом
# существования файла ДО вызова. Гейт этого не различает: файл СУЩЕСТВУЕТ и читается, а
# `jq -rs` не собирается из-за одной оборванной строки — и ноль уходит потребителю как
# «прогонов не было». Замер последствия: страж выдавал напоминание и писал в знаменатель
# `said`, то есть «крупный дифф ушёл в коммит без прогона» — утверждение о мире, сделанное
# там, где мир прочитать не удалось. У словаря журнала для этого есть отдельное значение
# `unread` (`root-cause-lib.sh`), заведённое ровно под такой случай.
adversary_run_count() {
    _arc_out=$(_arc_select "${1:-}") || { printf '0\n'; return 2; }
    printf '%s\n' "$(printf '%s\n' "$_arc_out" | grep -c .)"
    return 0
}

# adversary_run_elsewhere <своя расшифровка> <с (эпоха)> [по (эпоха)] — число вызовов
# противника в СОСЕДНИХ расшифровках того же каталога, случившихся в окне [с; по]
# («по» по умолчанию — сейчас). Своя расшифровка исключена: её считает adversary_run_count.
# Коды: 0 — ответ; 2 — ни одного кандидата прочитать не удалось (либо нет разбора времени).
# Дешёвый отсев по mtime честен: вызов в окне есть запись в окне, значит mtime ≥ «с».
adversary_run_elsewhere() {
    _are_tr="${1:-}"; _are_since="${2:-0}"; _are_until="${3:-}"
    case "$_are_since" in ''|*[!0-9]*) _are_since=0 ;; esac
    command -v iso_epoch >/dev/null 2>&1 || { printf '0\n'; return 2; }
    [ -n "$_are_tr" ] && [ -d "$(dirname "$_are_tr")" ] || { printf '0\n'; return 0; }
    _are_dir=$(cd "$(dirname "$_are_tr")" 2>/dev/null && pwd -P) || { printf '0\n'; return 0; }
    _are_self="$_are_dir/$(basename "$_are_tr")"
    [ -n "$_are_until" ] || _are_until=$(date +%s 2>/dev/null || echo 0)
    _are_n=0; _are_unread=0; _are_cand=0
    for _are_f in "$_are_dir"/*.jsonl; do
        [ -f "$_are_f" ] || continue
        [ "$_are_f" = "$_are_self" ] && continue
        _are_m=$(file_mtime "$_are_f" 2>/dev/null || echo "")
        case "${_are_m:-}" in ''|*[!0-9]*) _are_m="" ;; esac
        if [ -n "$_are_m" ] && [ "$_are_m" -lt "$_are_since" ]; then continue; fi
        _are_cand=$((_are_cand + 1))
        _are_sel=$(_arc_select "$_are_f") || { _are_unread=$((_are_unread + 1)); continue; }
        [ -n "$_are_sel" ] || continue
        while IFS="$(printf '\t')" read -r _are_ts _are_kind; do
            [ -n "$_are_ts" ] || continue
            _are_e=$(iso_epoch "$_are_ts" 2>/dev/null)
            case "${_are_e:-}" in ''|*[!0-9]*) continue ;; esac
            [ "$_are_e" -gt 0 ] || continue
            if [ "$_are_e" -ge "$_are_since" ] && [ "$_are_e" -le "$_are_until" ]; then
                _are_n=$((_are_n + 1))
            fi
        done <<EOF
$_are_sel
EOF
    done
    printf '%s\n' "$_are_n"
    if [ "$_are_cand" -gt 0 ] && [ "$_are_unread" -eq "$_are_cand" ]; then return 2; fi
    return 0
}
