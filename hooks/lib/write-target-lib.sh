#!/usr/bin/env bash
# write-target-lib.sh — лежит ли цель записи ЗАВЕДОМО вне проекта.
#
# Зачем. `five-whys-gate` отказывает в правке, пока не произнесена цепочка причин, и признак
# записи у него отвечает на вопрос «пишет ли», но не на вопрос «меняет ли ПРОЕКТ». Этот
# предел назван в самом гейте словами «перечислены формы записи, а не выражено правило
# „меняет мир вне себя“».
#
# ЦЕНА ИЗМЕРЕНА 5 сентября 2026 по 74 отказам гейта в корпусе расшифровок:
#   · записи в ДЕРЕВО проекта — 24, цепочка произнесена в 24 из 24: там гейт безупречен;
#   · записи в ПЕСОЧНИЦУ — 32, и все 6 «обходов» замера `stopper-effect` приходятся сюда.
# Отказ на временном зонде не защищает ничего и мешает по существу: субагент писал
# `probe.py`, чтобы НАЙТИ причину, и получал «сначала назови причину». Гейт блокировал ту
# работу, которую сам требует, — четвёртый случай этого рода в дереве (три прежних записаны
# в шапке `command-scope-lib.sh`).
#
# ПОЧЕМУ ЗДЕСЬ ТОЛЬКО ПРОВЕРКА ПУТИ, А НЕ РАЗБОР КОМАНДЫ.
# Разбор целей записи из текста команды был написан (перенаправления, `tee`, `sed -i`,
# запись из питона, подстановка переменных) и прожарен противником в тот же день:
# 5 ПОДТВЕРЖДЁННЫХ ДЫР ИЗ 6 ПРОВЕРЕННЫХ — запись из питона, `xargs cp`, `find -exec`,
# `sed -i` по нескольким файлам, `tee` с полным путём. Корень не в перечне форм, а в
# КВАНТОРЕ: предикат «все НАЙДЕННЫЕ цели вне проекта» есть глобальный вердикт из локальной
# улики (род C реестра дефектов; своего признака у него нет при точности 3%). Достаточно
# одной распознаваемой приманки в `/tmp` рядом с нераспознанной записью в дерево — и вызов
# освобождается. Заявленная безопасность «целей не найдено → отказ остаётся» верна только
# при НУЛЕ найденных целей; приманка её снимает.
#
# Добавлять формы бесполезно по построению: эффект вызова не выводим из его текста, а
# предикат утверждает именно об эффекте. Поэтому разбор УДАЛЁН целиком, а не исправлен —
# неиспользуемый небезопасный механизм хуже его отсутствия: следующий заход возьмёт его как
# готовое. Замер разбора до удаления, для честности: по 56 отбитым вызовам он освобождал 11
# и снимал 3 обхода из 6, ложных освобождений в корпусе не давал. Дыры нашлись не в корпусе,
# а у противника — корпус показывает точность и по построению молчит о полноте.
#
# ЧТО ОСТАЛОСЬ И ПОЧЕМУ ЭТО БЕЗОПАСНО. У `Edit`, `Write` и `MultiEdit` цель ОБЪЯВЛЕНА полем
# `file_path`: она одна, она не выводится разбором, приманку подложить некуда. Квантор там
# полон, и освобождение безопасно по построению.
#
# ОТКРЫТЫЙ ДОЛГ, названный числом: у Bash-записей в песочницу отказ остаётся, и все 6
# «обходов» замера приходятся именно туда. Условие снятия то же, что у самого гейта: когда
# цель записи станет наблюдаема не из текста команды, а сверкой состояния дерева до и после
# вызова.

# wt_temp_roots — временные корни, по одному в строке, в коротком написании. ПЕРЕЧЕНЬ ОДИН В ДЕРЕВЕ (D1112,
# 30 октября 2026): его спрашивают `_wt_outside` ниже, `rc_path_is_private` (hooks/root-cause-lib.sh) и замер точности
# отказов (scripts/deny-target-precision.py — через `_wt_outside`). До того перечней было три, и они расходились: здесь
# не было `/var/folders` (значение $TMPDIR на macOS), у замера — `/private/var/folders` (то же место после `pwd -P`), и
# одна запись получала разный ответ по написанию пути. Второе написание macOS (`/private/…`) снимает ФС: `_wt_outside`
# сверяет через `_wt_real` (внешний `/bin/pwd -P` — имя как на диске), `rc_path_is_private` — встроенным `pwd -P`,
# регистр у него набранный (давнее, вне D1112: одно место в другом регистре там «живое»). $TMPDIR здесь НЕТ: страж не берёт корень из окружения хука —
# `TMPDIR=$HOME` освободил бы установку (скептик D1112, L1); его добавляет только признак частного пути, как до D1112.
wt_temp_roots() {
    printf '%s\n' /tmp /var/tmp /var/folders /dev/shm
}

# _wt_real <путь> — то же место, как его знает ФС: ближайший существующий предок через `cd -P` и `pwd -P`, хвост — как
# набран (хвоста на диске нет, значит подменить собой он ничего не может). ПОЧЕМУ ФС, А НЕ СТРОКА (D1112, четвёртый
# круг): тождество места задаёт ФС — `/tmp` и `/private/tmp`, регистр и форма нормализации на APFS, символьные ссылки, — и
# три круга строкового приведения догоняли её по одной форме за круг (`/private` → регистр ASCII → регистр кириллицы и
# NFD), а ссылка из временного каталога в `~/.claude` освобождалась на всех редакциях. ФС не читается каталогом, которого
# нет. Пределы: жёсткая ссылка на файл установки (по пути её не видно) и ссылка, подложенная после проверки, — их
# правка не закрывает.
_wt_real() {
    local d="$1" t="" r n=0
    # Относительный путь — не место: у пути без `/` отрезать нечего, подъём к предку крутился вечно (мутант четвёртого
    # круга без этой проверки в `_wt_outside` висел 10 часов, а проект из `cwd` её не проходил вовсе). Проверка — здесь,
    # у единственного хозяина пути, а не у каждого вызывающего.
    case "$d" in /*) ;; *) return 1 ;; esac
    # Путь длиннее 1024 символов — не место, до подъёма: подъём квадратичен по символам звена (одно звено в 40 000 символов
    # стоило 2,4–3,3 с — скептик D1112, пятый круг, M1), а голым путём записи по нему нет: PATH_MAX macOS — 1024 байта с
    # завершающим нулём, символ не короче байта. Записать может инструмент, сокращающий путь до записи (Node `path.resolve`
    # снимает `/.` — шестой круг, L3), и любой на Linux (PATH_MAX 4096) — отказ на таком пути остаётся, сторона безопасная.
    [ "${#d}" -le 1024 ] || return 1
    # Звенья хвоста `.` и пустые (`//`) — то же место, в хвост не идут. Ссылка в любом звене хвоста (на файл или висячая) —
    # не место: она на диске ЕСТЬ, и «хвост как набран» для неё ложен — 191 ссылка `tasks/*.output → ~/.claude/projects/…`
    # освобождала запись (скептик D1112, четвёртый круг, H1). Цена (пятый круг, L5): законная запись через ссылку из
    # временного каталога во временный — тоже отказ (на стенде скептика 201 ссылка на файл и 100 188 висячих), а в корпусе
    # отказов гейта смен класса от этого правила 0 из 1035 — отказ остаётся, сторона безопасная. Больше 32 шагов подъёма —
    # не место: подъём квадратичен по длине (M1); шаг — каждое снятое звено, и `.`, и пустое (L4).
    while [ -n "$d" ] && [ ! -d "$d" ]; do
        [ -L "$d" ] && return 1
        [ $((n += 1)) -le 32 ] || return 1
        case "${d##*/}" in ''|.) ;; *) t="/${d##*/}$t" ;; esac
        d="${d%/*}"
    done
    [ -n "$d" ] || d=/
    # Внешний `/bin/pwd` — `getcwd()` ядра: регистр и форма имени как на диске. Встроенный `pwd -P` bash возвращает
    # набранный регистр (`/PRIVATE/TMP`) — с ним регистр проекта снова освобождал запись; потому без `/bin/pwd` — не
    # место, а не встроенный запасной (скептик D1112, четвёртый круг, L5).
    r=$(cd -P -- "$d" 2>/dev/null && /bin/pwd -P 2>/dev/null) || return 1
    printf '%s%s' "${r%/}" "$t"
}

# Корни, как их знает ФС, — один раз на процесс: гейт зовёт `_wt_outside` на каждой записи. Заполняется без
# подоболочки (присваивание внутри `$(…)` пропало бы вместе с ней).
_WT_ROOTS_REAL=""
_wt_roots_fill() {
    local r x IFS=$' \t\n'
    [ -z "$_WT_ROOTS_REAL" ] || return 0
    for r in $(wt_temp_roots); do x=$(_wt_real "$r") && _WT_ROOTS_REAL="$_WT_ROOTS_REAL $x"; done
}

# _wt_outside <путь> <каталог_проекта> — код 0, если путь заведомо ВНЕ проекта.
# «Заведомо» — абсолютный путь без `..`, чьё место по ФС лежит под временным корнем и не под местом проекта.
# Относительный путь считается внутри: он разрешается от рабочего каталога, а тот в проекте. ФС не ответила — внутри.
_wt_outside() {
    local p q r hit=1 IFS=$' \t\n'
    # Восхождение `..` внутри пути отменяет доказательство: `/tmp/../Users/…/ClaudSoul/x`
    # начинается с `/tmp/` и ведёт В ПРОЕКТ. Найдено собственным тестом (T15) до подключения
    # правила к стражу. По сырому пути, до обращения к ФС.
    case "$1" in */../*|*/..) return 1 ;; esac
    p=$(_wt_real "$1") || return 1
    _wt_roots_fill
    for r in $_WT_ROOTS_REAL; do
        case "$p" in "$r"/*) hit=0; break ;; esac
    done
    [ "$hit" -eq 0 ] || return 1
    q=$(_wt_real "${2:-/}") || return 1
    case "$p" in "$q"|"$q"/*) return 1 ;; esac
    return 0
}

