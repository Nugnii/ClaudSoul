#!/usr/bin/env bash
# write-target-lib.sh — лежит ли цель записи ЗАВЕДОМО вне проекта.
#
# Зачем. `five-whys-gate` отказывает в правке, пока не произнесена цепочка причин, и признак
# записи у него отвечает на вопрос «пишет ли», но не на вопрос «меняет ли ПРОЕКТ». Этот
# предел назван в самом гейте словами «перечислены формы записи, а не выражено правило
# „меняет мир вне себя“».
#
# ЦЕНА ИЗМЕРЕНА 5 сентября 2026 по 74 отказам гейта в корпусе расшифровок:
#   · записи в ДЕРЕВО проекта — 24, цепочка произнесена в 24 из 24: там гейт безупречен;
#   · записи в ПЕСОЧНИЦУ — 32, и все 6 «обходов» замера `stopper-effect` приходятся сюда.
# Отказ на временном зонде не защищает ничего и мешает по существу: субагент писал
# `probe.py`, чтобы НАЙТИ причину, и получал «сначала назови причину». Гейт блокировал ту
# работу, которую сам требует, — четвёртый случай этого рода в дереве (три прежних записаны
# в шапке `command-scope-lib.sh`).
#
# ПОЧЕМУ ЗДЕСЬ ТОЛЬКО ПРОВЕРКА ПУТИ, А НЕ РАЗБОР КОМАНДЫ.
# Разбор целей записи из текста команды был написан (перенаправления, `tee`, `sed -i`,
# запись из питона, подстановка переменных) и прожарен противником в тот же день:
# 5 ПОДТВЕРЖДЁННЫХ ДЫР ИЗ 6 ПРОВЕРЕННЫХ — запись из питона, `xargs cp`, `find -exec`,
# `sed -i` по нескольким файлам, `tee` с полным путём. Корень не в перечне форм, а в
# КВАНТОРЕ: предикат «все НАЙДЕННЫЕ цели вне проекта» есть глобальный вердикт из локальной
# улики (род C реестра дефектов; своего признака у него нет при точности 3%). Достаточно
# одной распознаваемой приманки в `/tmp` рядом с нераспознанной записью в дерево — и вызов
# освобождается. Заявленная безопасность «целей не найдено → отказ остаётся» верна только
# при НУЛЕ найденных целей; приманка её снимает.
#
# Добавлять формы бесполезно по построению: эффект вызова не выводим из его текста, а
# предикат утверждает именно об эффекте. Поэтому разбор УДАЛЁН целиком, а не исправлен —
# неиспользуемый небезопасный механизм хуже его отсутствия: следующий заход возьмёт его как
# готовое. Замер разбора до удаления, для честности: по 56 отбитым вызовам он освобождал 11
# и снимал 3 обхода из 6, ложных освобождений в корпусе не давал. Дыры нашлись не в корпусе,
# а у противника — корпус показывает точность и по построению молчит о полноте.
#
# ЧТО ОСТАЛОСЬ И ПОЧЕМУ ЭТО БЕЗОПАСНО. У `Edit`, `Write` и `MultiEdit` цель ОБЪЯВЛЕНА полем
# `file_path`: она одна, она не выводится разбором, приманку подложить некуда. Квантор там
# полон, и освобождение безопасно по построению.
#
# ОТКРЫТЫЙ ДОЛГ, названный числом: у Bash-записей в песочницу отказ остаётся, и все 6
# «обходов» замера приходятся именно туда. Условие снятия то же, что у самого гейта: когда
# цель записи станет наблюдаема не из текста команды, а сверкой состояния дерева до и после
# вызова.

# _wt_outside <путь> <каталог_проекта> — код 0, если путь заведомо ВНЕ проекта.
# «Заведомо» — временный каталог по абсолютному пути. Относительный путь считается внутри:
# он разрешается от рабочего каталога, а тот в проекте.
_wt_outside() {
    case "${1:-}" in
        /tmp/*|/private/tmp/*|/var/tmp/*|/private/var/folders/*) ;;
        *) return 1 ;;
    esac
    # Восхождение `..` внутри пути отменяет доказательство: `/tmp/../Users/…/ClaudSoul/x`
    # начинается с `/tmp/` и ведёт В ПРОЕКТ. Найдено собственным тестом (T15) до подключения
    # правила к стражу. Путь с `..` внешним не считается — нормализовать его без обращения
    # к файловой системе нельзя, а обращаться в хуке ради этого не стоит.
    case "${1:-}" in
        */../*|*/..) return 1 ;;
    esac
    case "${1:-}" in
        "${2:-///нет///}"*) return 1 ;;
    esac
    return 0
}

