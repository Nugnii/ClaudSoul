#!/usr/bin/env bash
# mktemp-shim.sh — `mktemp` для команд исполнителей: голая форма создаёт каталог внутри TMPDIR (D1198).
#
# Результат: команда, запущенная исполнителем, создаёт временный каталог или файл голой формой (`mktemp`, `mktemp -d`,
#            `mktemp -t <префикс>`) внутри своего TMPDIR, и исполнитель снимает его вместе с TMPDIR
# Проверка результата: bash hooks/tests/fixtures/probe_D1198.sh даёт 0
#
# Зачем. На macOS (замер 3 ноября 2026, 27.0.1) голая форма и `-t` берут системный каталог
# (`getconf DARWIN_USER_TEMP_DIR`) при любом TMPDIR; читает его только шаблонная форма. В тестах и пробах голых форм
# 819 из 883, и свой TMPDIR исполнителя удерживал меньшинство: в системном T копилось около 4 000 каталогов в сутки.
# GNU mktemp голой формой TMPDIR читает — подмена повторяет его поведение и на Linux ничего не меняет.
# Ставят её исполнители: `cmd_tmpdir_shim` (`hooks/timeout-lib.sh`) и `install_shim` (`hooks/lib/bounded_run.py`) —
# копия этого файла в `<каталог команды>/.bin/mktemp`, каталог первым в PATH.
# НАЗВАННЫЙ ПРЕДЕЛ: вызов по полному пути (`/usr/bin/mktemp`), команда, переписавшая PATH, склейка `-t` с другими
# ключами (`-dt x`) и `-t префикс шаблон` идут мимо подмены — к настоящему `mktemp` без изменений; команда, снёсшая
# `$TMPDIR/.bin` после первого вызова, второй получает 127 (оболочка помнит путь). В дереве на 3 ноября 2026: полный путь — 4 вызова, прочих форм — 0.
# Условие снятия: в командах, которые исполняют исполнители, появится склейка `-dt`, форма `-t префикс шаблон` или вызов
# `mktemp` по полному пути, создающий каталог без шаблона, — тогда подмена разбирает и их либо называет их отдельно.
R=/usr/bin/mktemp
[ -x "$R" ] || R=/bin/mktemp
if [ "$(uname -s 2>/dev/null)" != Darwin ] || [ -z "${TMPDIR:-}" ] || [ ! -d "$TMPDIR" ]; then
    exec "$R" "$@"
fi
all=("$@"); fl=(); pre=tmp
while [ $# -gt 0 ]; do
    case "$1" in
        -t) [ $# -ge 2 ] || exec "$R" "${all[@]}"; pre="$2"; shift 2 ;;
        -[dqu]|-[dqu][dqu]|-[dqu][dqu][dqu]) fl+=("$1"); shift ;;
        *) exec "$R" "${all[@]}" ;;   # шаблон либо иной ключ — настоящему без изменений
    esac
done
exec "$R" ${fl[@]+"${fl[@]}"} "${TMPDIR%/}/$pre.XXXXXXXXXX"
