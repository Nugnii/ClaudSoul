# transcript_user_texts <transcript_path> [n]
#   Печатает последние n строк текстовых блоков, написанных СОБЕСЕДНИКОМ.
#   Окно считается в строках — как у прежнего выражения в стражах, поведение не менялось.
#
# Зачем (8 сентября 2026). Четыре стража доставали речь собеседника одинаковым
# `jq 'select(.type == "user") | ... | .[]?'` и отличались только окном:
# trust-guard.sh:183, bulk-copy-guard.sh:144, internal-doc-leak-guard.sh:122,
# user-correction-guard.sh:56. Под `type: "user"` харнесс кладёт и СВОИ вставки — тела
# скиллов, напоминания, справку инструментов, — и они проходили как речь владельца.
#
# Замер по корпусу: 216 расшифровок основных сессий, 1739 сообщений type=user с текстом,
# из них 180 вставок харнесса. Токены авторизации trust-guard несут 74 вставки против 25
# настоящих реплик — три четверти «разрешений» написаны не человеком; в топе тело скилла
# workflow-authoring (27 раз), тела скиллов compile / retro / release (27 суммарно).
# Признак `isMeta` отбивает вставки и НЕ трогает ни одной настоящей реплики: ложных 0.
#
# ПОЧЕМУ ПРИЗНАК МАШИННЫЙ, А НЕ ТЕКСТОВЫЙ. Текстовый список `NON_USER_TURN_RE` ловит 39
# вставок из 74 — половину. Он судит по зачину, поэтому вставка, попавшая в СЕРЕДИНУ
# окна, для него невидима. `isMeta` ставит сам харнесс, он не зависит от текста и от
# положения блока. Тот же признак уже применён в дереве
# (timestamp-canary-check.sh:69, scripts/five-whys-attribution-replay.py:75) — здесь он
# просто не был подключён.
#
# ПОЛЕЙ РОЛИ ЧЕТЫРЕ, А НЕ ОДНО (D402, 12 сентября 2026). `isMeta` стоит на телах скиллов
# и справке, но уведомление фоновой задачи несёт `origin.kind == "task-notification"`
# (146 из 146 по 60 расшифровкам проекта), сводка после сжатия — `isCompactSummary`
# (19 из 19), ветка субагента — `isSidechain`, и ни одно из них не несёт `isMeta`. Один
# признак из четырёх пропускал три вида вставок как речь: окно авторизации читало «делай»
# из сводки, страж поправок — «последнюю реплику» из уведомления задачи. Те же четыре
# поля читает `shared-language-lib.sh: shlang_user_text` (D356).
# НАЗВАННЫЙ ПРЕДЕЛ: на расшифровках без этих полей (старая версия клиента, чужой клиент)
# функция вырождается в прежнее поведение и вставки снова пройдут; запись без `origin`
# считается речью — таких 5 из 635, и это настоящие реплики старого клиента. Условие
# снятия: в корпусе не останется записей речи без `origin` — тогда запись без поля можно
# будет читать как вставку, а не как речь, и умолчание "human" уйдёт.
# КОНТРПРИМЕР (признак обязан НЕ поймать): настоящая реплика собеседника, целиком
# состоящая из вставленного им документа, — `isMeta` на ней не стоит, и это верно:
# документ принёс собеседник, отсев такого — работа `user_own_speech`, а не эта.
#
# transcript_turn_window <transcript_path> [reply | around-reply | wide | no-summary]
#   Расшифровка от последней реплики владельца до конца последней полной строки — ТЕКУЩИЙ
#   ХОД (D498). Режим `reply` — только строка самой реплики; `around-reply` — от последнего
#   текста агента ДО реплики до её конца. Читателю, которому нужна реплика или текст перед
#   ней, весь ход не нужен: его цена не должна расти с длиной хода (противник окна, атаки 3-4).
#   `wide` — от последней записи `turn_user` (граница-широкая `lib/reply-readers.tsv`), `no-summary` — от последней,
#   кроме сводки сжатия и боковой ветки (граница-без-сводки): читатель своей границы не платит за молчание владельца —
#   в пакетном ходе окно от реплики доходило до 107 МБ, и хуки Stop держали ответ до 81 с (D1235, корень R6).
#   Зачем: читатели «что сказано в этом ходе» брали файл целиком на каждом вызове, и цена
#   события росла с жизнью сессии — 0,68 с на 48 МБ на КАЖДЫЙ вызов инструмента. Начало хода
#   ищет `lib/transcript_window.py` с конца файла, с меткой в $STATE_DIR следующий вызов
#   досматривает только дописанное. Реплика — то же определение, что у `transcript_user_texts`
#   ниже; читатель с более широкой границей (любая запись user) находит свою внутри окна.
#   Байты окна отдаёт сам помощник за строкой «ok» (режим --emit): прежде их резал `tail -c +N`,
#   а он на macOS копирует ~30 МБ/с — 0,2–0,3 с на 8 МБ окна, четыре окна на вызов five-whys-gate
#   давали +0,8 с на долгом ходе (D498). Конец окна — конец полной строки на момент чтения тем же
#   процессом, поэтому дописанное в зазоре не читается и SIGPIPE не возникает (атака 5).
#   Помощника нет или он не сказал «ok» — файл целиком: дорого, но верно, как было; окно дважды
#   не печатается. Код возврата всегда 0: под `pipefail` вызывающего иначе ронял бы хук.
_HIL_DIR=$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)
# transcript_stop_bound <transcript_path> <итог хода> — граница хода для ФОНОВОГО хука Stop (D1250, корень R6). Фоновый
#   хук читает расшифровку, когда уже бывает начало следующего хода (сессия 62cb88c6: через 0,3 с после Stop), и судил
#   бы чужой ход. Экспортирует TRANSCRIPT_END_BYTES — конец строки итога хода (поле Stop `last_assistant_message`);
#   читатели через transcript_window.py дальше неё не читают. Итог не найден — граница на момент вызова, поэтому зовётся
#   первым делом. Без python3 или помощника — границы нет, как прежде. Код всегда 0.
transcript_stop_bound() {
    command -v python3 >/dev/null 2>&1 && [ -f "${_HIL_DIR:-}/lib/transcript_window.py" ] && [ -f "${1:-}" ] || return 0
    _tsb_f=$(mktemp 2>/dev/null) || return 0
    printf '%s' "${2:-}" > "$_tsb_f"
    _tsb_b=$(python3 "$_HIL_DIR/lib/transcript_window.py" "$1" --stop-end "$_tsb_f" 2>/dev/null)
    rm -f "$_tsb_f"
    case "$_tsb_b" in ''|*[!0-9]*) return 0 ;; esac
    export TRANSCRIPT_END_BYTES="$_tsb_b" TRANSCRIPT_END_FILE="$1"   # граница — только своему файлу
    return 0
}
transcript_turn_window() {
    _ttw_path="${1:-}"
    [ -n "$_ttw_path" ] && [ -f "$_ttw_path" ] || return 0
    if command -v python3 >/dev/null 2>&1 && [ -f "${_HIL_DIR:-}/lib/transcript_window.py" ]; then
        { python3 "$_HIL_DIR/lib/transcript_window.py" "$_ttw_path" --emit \
              ${2:+--$2} ${STATE_DIR:+--state "$STATE_DIR"} 2>/dev/null || :; } \
            | { IFS= read -r _ttw_h; if [ "$_ttw_h" = ok ]; then cat; else _ttw_whole "$_ttw_path"; fi; } || :
        return 0
    fi
    _ttw_whole "$_ttw_path"
}
# Весь файл расшифровки без служебных копий запроса (D1346) — запасной путь окна: помощник их не отдаёт, и без него
# читатель по роли не должен принять копию за ответ модели.
_ttw_whole() { grep -vE '"type"[[:space:]]*:[[:space:]]*"api-request-blob"' "$1" 2>/dev/null || :; }

# transcript_fold <transcript_path> <имя> <turn|session> <шаг...>
#   Свёртка расшифровки по дописанным байтам (D498): шаг получает на stdin полные строки,
#   дописанные с прошлого вызова (turn — в пределах текущего хода, session — всей сессии), а
#   последним аргументом — путь файла с прежним накопленным (пустой — с нуля), и печатает новое
#   накопленное. «Докуда дочитано» хранит `lib/transcript_window.py --fold` в $STATE_DIR, само
#   определение шага остаётся у потребителя: у факта один владелец (корень R1). Шаг свёртки хода
#   ОБЯЗАН сам сбрасываться на реплике владельца: помощник начинает с неё ради цены, а запасной
#   путь отдаёт весь файл — найти реплику в оболочке значило бы третью копию её определения.
#   Зачем: сводки по всей сессии и читатели всего хода перечитывали всё накопленное на каждом
#   событии — +2,2 с у activity_flush на 40 МБ истории.
#   Помощника нет, он отказал или не сказал «ok» — шаг идёт по всему окну хода либо файлу с
#   пустым накопленным (/dev/null): дорого, но верно, как было. Успех — только строка «ok»
#   первой строкой, как у окна: помощник прежнего выпуска на незнакомый `--fold` тоже выходит
#   с 0 и печатает смещение хода — по коду возврата оно принималось за накопленное (противник
#   свёртки, атака 1). Помощник печатает только после удачного шага — дважды не печатается.
transcript_fold() {
    _tf_path="${1:-}"; _tf_name="${2:-}"; _tf_from="${3:-}"
    [ -n "$_tf_path" ] && [ -f "$_tf_path" ] && [ $# -gt 3 ] || return 1
    shift 3
    if command -v python3 >/dev/null 2>&1 && [ -f "${_HIL_DIR:-}/lib/transcript_window.py" ]; then
        { python3 "$_HIL_DIR/lib/transcript_window.py" "$_tf_path" --fold "$_tf_name" \
              ${STATE_DIR:+--state "$STATE_DIR"} $([ "$_tf_from" = turn ] && printf -- --turn) \
              -- "$@" 2>/dev/null || :; } \
            | { IFS= read -r _tf_h; if [ "$_tf_h" = ok ]; then cat; else _transcript_fold_whole "$@"; fi; } || :
        return 0
    fi
    _transcript_fold_whole "$@"
}
# Запасной путь свёртки: шаг по всему окну хода либо файлу, накопленное пустое.
_transcript_fold_whole() {
    if [ "$_tf_from" = turn ]; then transcript_turn_window "$_tf_path" | "$@" /dev/null
    else _ttw_whole "$_tf_path" | "$@" /dev/null; fi
}

# transcript_edit_then_reply <transcript_path> <путь файла> → 1 / 0; пусто — помощник не ответил
#   Была ли правка этого файла, за которой следует реплика (образец «EH» стража поправок,
#   D498). Цена — поиск подстроки пути до последней реплики, а не разбор всей сессии. Пусто —
#   вызывающий берёт свой полный разбор: «не ответил» не сливается с «образца нет».
transcript_edit_then_reply() {
    command -v python3 >/dev/null 2>&1 && [ -f "${_HIL_DIR:-}/lib/transcript_window.py" ] || return 0
    _tetr=$(python3 "$_HIL_DIR/lib/transcript_window.py" "${1:-}" --context-hit "${2:-}" 2>/dev/null)
    case "$_tetr" in 0|1) printf '%s' "$_tetr" ;; esac
}

transcript_user_texts() {
    _tut_path="${1:-}"
    _tut_n="${2:-1}"
    [ -n "$_tut_path" ] && [ -f "$_tut_path" ] || return 0
    command -v jq >/dev/null 2>&1 || return 0
    # Последняя реплика — начало окна хода (то же определение реплики), поэтому одной хватает
    # её строки; за несколькими — файл целиком, как прежде.
    # Содержимое реплики бывает и СТРОКОЙ, не только списком блоков: 552 из 2406 реплик
    # корпуса. `map` по строке — ошибка jq: на окне выходило пусто, а на всём файле jq
    # спотыкался о первую такую запись и отдавал ПРОШЛУЮ реплику (противник окна, атака 2).
    # Реплика посреди хода — вложение `queued_command`: `as_reply` из `HIL_AS_REPLY_JQ` (D1142). Реплику судит владелец
    # правила `owner_reply`, а не своя копия перечня полей рядом с ним (D1209, R3): копия не требовала роли user и падала на
    # авторе не объектом.
    # ОКНО — СТРОКИ РЕЧИ (D1328, решение владельца 19 ноября 2026 «строки, но без мусора»): пустые строки в счёт окна
    # не идут, а служебная запись с ролью user — вывод и ввод `!`-команды владельца, эхо слеш-команды — в окно не
    # входит целиком; признак один с `is_non_user_turn` (`NON_USER_TURN_RE`). Замер на 3 298 настоящих репликах:
    # 168 кончались пустой строкой (окно из одной строки отдавало пустоту), 5 служебных записей шли в окно речью.
    if [ "$_tut_n" = 1 ]; then transcript_turn_window "$_tut_path" reply; else cat "$_tut_path"; fi | jq -r --arg nu "$NON_USER_TURN_RE" "$HIL_AS_REPLY_JQ$HIL_OWNER_REPLY_JQ"'
        as_reply | select(owner_reply)
        | .message.content // []
        | (if type == "string" then . else (map(select(.type == "text") | .text) | join("\n")) end)
        | select(test($nu) | not)
    ' 2>/dev/null | awk 'NF' | tail -"$_tut_n"
}

