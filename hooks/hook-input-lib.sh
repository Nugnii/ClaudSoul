#!/usr/bin/env bash
# hook-input-lib.sh — единый источник разбора ввода UserPromptSubmit-хуков.
#
# Назначение: один авторитетный список того, какие turn'ы НЕ являются речью
# собеседника (системные/инструментальные — task-notification, эхо slash-команды,
# tool-result). Хуки детекции языковых маркеров (reformulation-tracker,
# itr-event-detector) должны скопить детекцию к словам юзера: маркер коррекции
# («не совсем» и пр.) в теле tool_result — НЕ коррекция пользователя
# (pattern-guard-scope-blindness; case-2026-06-21 «детектор скан не той области»).
#
# Единый источник, а не копия в каждом хуке: список тегов эволюционирует
# (появится новый тип системного turn — обе детекции узнают из одного места),
# дрейф двух копий = ровно тот класс бага (principle-single-source-of-truth).

# is_non_user_turn "<prompt>"
#   return 0 — turn системный/инструментальный (не речь юзера) → детекцию пропустить
#   return 1 — обычная пользовательская реплика
# Единый источник маркеров системного хода (D94). Держится ОДНОЙ строкой, потому что
# перечень нужен и этому предикату, и jq-фильтру в `activity-flush-lib.sh`. Два
# независимых перечня расходятся: 27 августа 2026 тот же класс поймали дважды за день —
# страж фазы против `phase.sh` и ветка `install.sh` против ветки `cp` в одном файле.
# `Base directory for this skill:` добавлен сюда: тело скилла — не речь собеседника.
# `[Image:` сюда НЕ добавлен намеренно — он бывает внутри настоящей реплики со
# скриншотом, и отсев целого хода потерял бы речь. Его место — поблочный фильтр.
NON_USER_TURN_RE='<task-notification|<local-command-stdout|<command-name>|<bash-stdout|<tool-use-error|^Base directory for this skill:'

is_non_user_turn() {
    # Herestring, а не труба: библиотека своего `pipefail` не ставит, но исполняется
    # под опциями вызывающего, а `itr-event-detector.sh` и `reformulation-tracker.sh`
    # ставят `set -eo pipefail`. Там `grep -q` убил бы producer'а сигналом, и статус
    # ушёл бы от убитого, а не от нашедшего (D59, замер 11 августа 2026).
    grep -qE "$NON_USER_TURN_RE" <<< "$1"
}

# -----------------------------------------------------------------------
# user_own_speech "<prompt>"
#   Печатает часть turn'а, принадлежащую собеседнику: без кодовых блоков и
#   markdown-цитат. Печатает ПУСТО, если turn целиком — вставленный документ
#   (тело скилла, continuation summary, пересланная страница, отчёт команды).
#
# Зачем: is_non_user_turn различает ОТПРАВИТЕЛЯ turn'а, а маркер коррекции
# может принадлежать чужой речи ВНУТРИ реплики собеседника — «пользователь
# прислал рецензию, где написано „не совсем“» не является коррекцией
# (BACKLOG D87, два случая 2026-08-26 подряд).
#
# Правило выведено замером по 31 срабатыванию словаря во всех транскриптах
# (2026-08-26): 17 срабатываний дали дословные системные префиксы, 2 —
# markdown-структура пересланного документа, 11 пришлись на настоящую речь
# владельца, и у неё во ВСЕХ случаях ноль заголовков, таблиц, цитат и блоков
# кода. Длина не разделяет: самая длинная настоящая реплика 3650 символов
# против ложной в 3667 — поэтому порога по длине здесь нет.
#
# Асимметрия цены намеренная: ложное срабатывание пишет событие в модель
# собеседника и двигает state (входит в 4D gate), пропуск не пишет ничего.
# При неопределённости функция молчит.
# -----------------------------------------------------------------------
user_own_speech() {
    # CR из CRLF снимается ПЕРВЫМ делом: без этого первая строка пересылки кончается на
    # «:\r», шаблон зачина не совпадает и весь чужой текст проходит (раунд 1, атака 2).
    _uos_text=$(printf '%s' "$1" | tr -d '\r')
    case "$_uos_text" in
        "Base directory for this skill:"*|"This session is being continued"*|\
        "Review target:"*|"The user just ran"*)
            return 0 ;;
    esac
    # Зачин-подпись: короткая первая строка с двоеточием перед длинным текстом —
    # «из соседней сессии:», «Вот ещё мнение рецензента:». Пересылка без markdown-разметки
    # ничем другим от собственной речи не отличается: замер по словарю состояния (43
    # срабатывания во всех транскриптах) показал, что длина здесь НЕ разделяет — выше
    # 2750 символов есть и настоящая речь владельца. Зачин-подпись ловит ровно две
    # пересылки из 32 и ни одной настоящей реплики.
    #
    # Длина считается в СИМВОЛАХ через `wc -m` с прибитой локалью, а не через ${#var}:
    # в локали C (запуск не из терминала) ${#var} даёт байты, кириллический зачин из 68
    # символов весит 125 байт, порог 100 переступается и страж молча выключается
    # (раунд 1, атака 1). Тот же приём и по той же причине стоит в intrusiveness-*-lib.
    #
    # Хвостовые пробелы у первой строки срезаются: шаблон `*:` требует, чтобы строка
    # КОНЧАЛАСЬ двоеточием, и пробел, таб или неразрывный пробел после него выключали
    # стража ровно так же, как CR до починки (раунд 2, атака 2).
    #
    # Известный предел: длинная СВОЯ реплика, начатая строкой с двоеточием, будет прочитана
    # как пересылка, и собственные слова ПОСЛЕ вставки не восстановимы — ветка не смотрит
    # дальше первой строки (раунд 1, атака 4). Поэтому сигналы distressed эту функцию не
    # используют вовсе: там цена пропуска выше цены ложного события.
    # Хвост срезается вместе с невидимыми символами: zero-width space (U+200B, байты
    # E2 80 8B) под [[:space:]] не подпадает и выключал стража так же, как обычный пробел
    # (раунд 2, атака 2, t4). Восьмеричные escape — чтобы файл оставался читаемым глазом.
    _uos_first=$(printf '%s\n' "$_uos_text" | awk 'NF { print; exit }' \
        | awk '{ gsub(/\342\200\213|\302\240/, ""); sub(/[[:space:]]+$/, ""); print }')
    # Двоеточие принимается и с невидимым хвостом: zero-width space (U+200B) многобайтовый,
    # байтовые escape в awk его не берут, а под [[:space:]] он не подпадает (раунд 2,
    # атака 2, t4). Вместо хрупкой чистки шаблон допускает хвост из НЕбуквенных символов —
    # это работает и посимвольно в UTF-8-локали, и побайтно в C.
    case "$_uos_first" in
        *:|*:[![:alnum:]]|*:[![:alnum:]][![:alnum:]]|*:[![:alnum:]][![:alnum:]][![:alnum:]])
            _uos_len=$(printf '%s' "$_uos_text" | LC_ALL=C.UTF-8 wc -m | tr -d '[:space:]')
            _uos_flen=$(printf '%s' "$_uos_first" | LC_ALL=C.UTF-8 wc -m | tr -d '[:space:]')
            case "$_uos_len$_uos_flen" in ''|*[!0-9]*) _uos_len=0; _uos_flen=999 ;; esac
            if [ "$_uos_len" -ge 500 ] && [ "$_uos_flen" -le 100 ]; then
                # Зачин печатается ЧЕРЕЗ ту же чистку, что и остальные строки: иначе
                # «он ответил "не совсем так":» уходил бы наружу сырым, в обход вырезания
                # чужой речи, — два стража стояли на путях, не перекрывающих друг друга
                # (раунд 2, атака 3).
                printf '%s\n' "$_uos_first" | awk '{
                    gsub(/"[^"]*"/, " "); gsub(/`[^`]*`/, " ")
                    gsub(/«[^»]*»/, " "); gsub(/“[^”]*”/, " "); gsub(/‘[^’]*’/, " ")
                    print
                }'
                return 0
            fi ;;
    esac
    printf '%s\n' "$_uos_text" | awk '
        BEGIN { fence = 0; doc = 0; quoted = 0; n = 0; blen = 0 }
        {
            line = $0
            if (line ~ /^[[:space:]]*```/) { fence = 1 - fence; next }
            if (fence) next
            # Цитатные строки вырезаются поштучно, а их количество — такой же признак
            # пересылки, как заголовки, и подчиняется тому же порогу объёма. Без порога
            # он обнулял уже отобранную собственную речь: «> лог\n> лог\nя имел в виду
            # другое» уходило в пустоту, а жалоба с приложенным логом переворачивалась из
            # stuck в focus (раунд 2, атаки 1 и 4). Ошибкой был не признак, а применение
            # его к реплике любого размера.
            if (line ~ /^[[:space:]]*>/) { quoted++; next }
            if (line ~ /^##/) { doc = 1 }
            if (line ~ /---/ && line ~ /\|/) { doc = 1 }
            # Чужая речь бывает и внутри строки: «он ответил "не совсем так", но по-моему
            # всё верно» — согласие, а маркер принадлежит третьему лицу (раунд 1, атака 6).
            # Типографские кавычки — «ёлочки» русской раскладки и “лапки” из веба — знали
            # только ASCII-кавычку и проносили чужую речь целиком (раунд 3, атака 1).
            # Проверено, что gsub по ним работает и в UTF-8-локали, и в C.
            #
            # Порог длины строки: gsub по /"[^"]*"/ на строке в мегабайт (свёрнутый JSON,
            # строка CSV) даёт квадратичное время — 1 МБ за 2.6 с против 0.2 с без кавычек
            # (раунд 3, атака 6). Такая строка не речь, и цена пропуска чистки здесь ниже
            # цены задержки на каждой реплике: функцию зовут три хука.
            if (length(line) < 4000) {
                gsub(/"[^"]*"/, " ", line)
                gsub(/`[^`]*`/, " ", line)
                gsub(/«[^»]*»/, " ", line)
                gsub(/“[^”]*”/, " ", line)
                gsub(/‘[^’]*’/, " ", line)
            }
            # Накопление строкой было квадратичным: buf = buf line пересобирает всё на
            # каждой входной строке, 40k строк — 3.3 с (раунд 1, атака 7).
            keep[n++] = line
            # Объём тела копится счётчиком, а не сборкой строки: конкатенация в END снова
            # сделала бы проход квадратичным — ровно то, что чинили в раунде 1, атака 7.
            probe = line
            gsub(/[[:space:]]/, "", probe)
            blen += length(probe)
        }
        END {
            # Признак документа гасит реплику, только если вне вставок осталось ОБЪЁМНОЕ
            # тело. Иначе гасла собственная короткая жалоба с приложенным размеченным
            # куском: «опять не работает» + строка `## лог` — 17 символов вне вставок, и
            # сигнал терялся целиком (раунд 1, атака 3 t6; раунд 2, атака 5 t3 — два
            # независимых критика об одном). Замер по известным входам: своя жалоба с
            # приложением даёт 17 и 42 символа, настоящие пересылки — 3512 и 7483.
            # Порог 300 лежит в этом зазоре и ни к одному краю не жмётся.
            if ((doc || quoted >= 2) && blen >= 300) exit 0
            for (i = 0; i < n; i++) printf "%s\n", keep[i]
        }
    '
}
