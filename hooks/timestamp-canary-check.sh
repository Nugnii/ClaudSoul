#!/usr/bin/env bash
# timestamp-canary-check.sh — Stop: механическая проверка таймштамп-канарейки.
# en: Stop hook — verifies the last reply starts with the injected timestamp; alerts user+agent when the canary died (context drift).
#
# Уровень 3 правила «Таймштамп-канарейка» (rules/CLAUDE.md): собеседник-детектор
# заменён машинным алертом (решение собеседника 2026-08-08, «строй стража»).
# Семантика: инжект живой (timestamp-inject задеплоен), а последняя реплика не
# начинается с «🕐 YYYY-MM-DD HH:MM» — контекст, вероятно, уплыл; шапка не
# совпадает со значением инжекта — время не эхо, а оценка. Успех молчит
# (silent correct), алерт — systemMessage собеседнику + additionalContext агенту.
#
# Сверка ЗНАЧЕНИЯ добавлена 2026-08-26 (case-2026-08-26-timestamp-on-wrong-block-
# and-invented-value): до неё страж проверял только ФОРМУ первой строки и свежесть
# ±6 часов, поэтому выдуманный, но правильно оформленный таймштамп с расхождением
# в 35 минут проходил молча — детектор был привязан к виду строки, а не к её
# источнику (pattern-detector-wired-to-failure). Значение берётся из самого
# транскрипта (записи attachment/hook_additional_context), а не из нового файла
# состояния: инжектор остаётся без состояния, и читателя без писателя не заводим.
# Инжекта в транскрипте нет (старый формат, чужой харнесс) → откат на прежнюю
# проверку свежести, а не алерт: отсутствие данных ≠ уплывание.
#
# AP2 сюда сознательно НЕ применяется: страж — заказанный собеседником детектор
# качества, не проактивное вмешательство агента; глушить его в distressed —
# прятать сигнал ровно тогда, когда он нужнее всего.
#
# Guards: нет transcript → тихо; механизм инжекта не задеплоен → тихо
# (нет инжекта ≠ уплывание — другой класс проблемы, чинится install'ом).

set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0

INPUT=$(cat)
TRANSCRIPT_PATH=$(printf '%s' "$INPUT" | jq -r '.transcript_path // empty' 2>/dev/null)
# Окно текущего хода (D498): расшифровка читается от последней реплики владельца, а не
# целиком. Библиотеки нет — окно вырождается в файл целиком.
INPUT_LIB="${INPUT_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/hook-input-lib.sh}"
[ -f "$INPUT_LIB" ] || INPUT_LIB="$HOME/.claude/hooks/hook-input-lib.sh"
# shellcheck source=/dev/null
if [ -f "$INPUT_LIB" ]; then . "$INPUT_LIB"; fi
[ -n "$TRANSCRIPT_PATH" ] && [ -f "$TRANSCRIPT_PATH" ] || exit 0

# Самозацикливание (2026-08-15): алерт уходит как additionalContext и ПРОДОЛЖАЕТ
# ход; продолжение по построению без свежего инжекта (инжектор — UserPromptSubmit,
# владелец молчит) → снова нет шапки → снова алерт → цепочка «Без изменений»
# до бесконечности. Два предохранителя, оба до любого алерта:
# 1) документированный флаг харнесса «ход уже продолжен Stop-хуком»;
STOP_ACTIVE=$(printf '%s' "$INPUT" | jq -r '.stop_hook_active // false' 2>/dev/null)
[ "$STOP_ACTIVE" = "true" ] && exit 0

# Канарейка осмысленна только при живом инжекторе. Явный TIMESTAMP_INJECT_PATH
# (тесты) — без fallback; иначе sibling-first, затем установленный.
if [ -n "${TIMESTAMP_INJECT_PATH:-}" ]; then
    INJECTOR="$TIMESTAMP_INJECT_PATH"
else
    INJECTOR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/timestamp-inject.sh"
    [ -f "$INJECTOR" ] || INJECTOR="$HOME/.claude/hooks/timestamp-inject.sh"
fi
[ -f "$INJECTOR" ] || exit 0

# Последняя реплика ассистента (образец: output-language-check.sh).
# Окно читается ОДИН раз: оба разбора ниже связаны индексом блока шапки (HDR_IDX), и
# разные байты на входе развели бы индексы.
# Ход берётся из окна хода библиотеки ввода (D1153). Помощника `transcript_turn_window` нет (файла библиотеки нет) — не
# судить: окном был бы весь файл. У старой редакции помощник есть и окно начинается с последней реплики владельца: без
# ядра `HIL_TURN_USER_JQ` его запасное `false` оставляет окно одним ходом — текущим (скептик, третий круг, M1). Ниже
# пишутся только метки этого суждения — глушить нечего лишнего.
command -v transcript_turn_window >/dev/null 2>&1 || exit 0
# Окно — от своей границы, а не от реплики владельца (D1235): в пакетном ходе окно от реплики доходило до 107 МБ, и
# канарейка держала ответ до 81 с. Инжект 🕐 в мире стоит за каждой подачей (D1172: 451 из 451), поэтому окно от
# границы его несёт. Нет в нём ни одного инжекта — подача без своего, — разбор повторяется по прежнему окну от
# реплики (`any_inject` ниже): «жив ли инжектор» судится, как прежде, по инжекту прежней подачи.
# Каталог состояния — ДО окна: помощник кладёт тёплую метку в `--state`, а без STATE_DIR каждый Stop искал границу
# холодным проходом (скептик opus по afdb1a14, Н4).
STATE_DIR="${CANARY_STATE_DIR:-${STATE_DIR:-$HOME/.claude/hooks/state}}"
_TW=$(transcript_turn_window "$TRANSCRIPT_PATH" no-summary)
# Текст итога от харнесса (D1159): поле входа Stop `last_assistant_message` — текст ПОСЛЕДНЕГО блока ассистента, без
# краевых пробелов; у блока без текста поля нет (бинарник 2.1.316: `findLast(type=="assistant")`, `.trim()||void 0`).
_LAM=$(printf '%s' "$INPUT" | jq -r '.last_assistant_message // "" | if type == "string" then . else "" end' 2>/dev/null)
_canary_parse() { printf '%s\n' "$_TW" | jq -s --arg lam "$_LAM" "${HIL_TURN_USER_JQ:-def turn_user: false;}"'
    def role(x): x.message.role // x.role // "";
    def get_text(x):
        (x.message.content // x.content // []) as $c |
        if ($c | type) == "array" then
            ($c | map(select(.type == "text") | .text) | join("\n"))
        elif ($c | type) == "string" then $c
        else "" end;
    # Реплика собеседника: role=user, не meta, не sidechain, с текстом.
    # Записи type=="last-prompt" НЕ считаются границей хода: движок пишет их
    # многократно внутри одного хода (чекпойнты), и по ним «первый ответ хода»
    # съезжал на продолжение — таймштампа там нет по построению → ложный алерт.
    # Сводка сжатия контекста — не реплика владельца (2 октября 2026): иначе граница хода
    # уезжает на неё, и шапка, выданная до сжатия, выпадает из окна — ложное «без таймштампа».
    # Тот же отсев стоит у `transcript_user_texts` (hook-input-lib.sh).
    def real_user(x): (x | turn_user)
        and ((x.isCompactSummary // false) | not)
        and ((x.isSidechain // false) | not);
    # Ход может быть запущен не репликой владельца, а самим хуком (Stop → новый
    # ход). Пока владелец молчит, $pu не двигается, и «первый ответ после
    # реплики» навсегда указывает на НАЧАЛО цепочки — ответ, который уже не
    # изменить: 6 самовоспроизводящихся алертов подряд на шапке предыдущего дня
    # (2026-08-09). Границу хода при этом из транскрипта не восстановить:
    # type=="last-prompt" пишется и внутри хода (c71af66), а «текст без
    # tool_use между блоками» ломается на многоблочных ответах.
    # Поэтому проверяется ПОСЛЕДНЯЯ выданная шапка: среди ответов в окне шапки (после
    # последнего инжекта 🕐, D1172) берётся последний блок, чья первая строка выглядит
    # шапкой. Нет ни одного такого блока — шапка пропала, это и есть уплывание (алерт
    # ниже по пустому TS). Свежесть и сегмент фазы проверяются у неё же.
    def head_line(t): (t | split("\n") | map(select(test("^[[:space:]]*$") | not)) | first // "");
    # Markdown-выделение шапки допускается: `**🕐 …**`, `*🕐 …*`, `_🕐 …_`. Предмет
    # канарейки — НАЛИЧИЕ таймштампа в начале ответа, а не способ его набрать; ложная
    # тревога здесь дороже обычной, потому что учит не читать ровно тот сигнал, ради
    # которого страж поставлен. Повод: 6 сентября 2026 страж дважды подряд объявил
    # уплывание контекста на ответах, которые начинались таймштампом в жирном. Дата
    # остаётся обязательной — выделение её не заменяет (нога T1d).
    def is_header(t): (head_line(t) | test("^\\s*[*_]{0,2}\\s*(🕐 )?[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}"));
    # Запись инжекта 🕐 — граница окна шапки (D1172, корень R1). Инжект требует шапку на КАЖДОЙ подаче: реплике
    # владельца, отчёте субагента, уведомлении задачи (замер 28 октября 2026: 35 инжектов из 35 стоят сразу за подачей,
    # за результатом инструмента — ни одного). `turn_user` отчёт и уведомление ходом не считает, и ряд «реплика → шесть
    # отчётов», шапка на каждом, давал тревогу «7 шапок»; итог без шапки после отчёта не ловился — бралась шапка из
    # начала хода владельца. Теперь окно — ответы после ПОСЛЕДНЕГО инжекта (нет его — после реплики, как прежде).
    def is_inject(x): x.type == "attachment" and ((x.attachment | type) == "object")
        and x.attachment.type == "hook_additional_context"
        and any((x.attachment.content // [])[]?; type == "string" and startswith("🕐 "));
    . as $items | (length) as $n |
    ([range(0; $n) | ($n - 1 - .) | select(real_user($items[.]))] | first) as $pu |
    ([range((if $pu == null then -1 else $pu end) + 1; $n) | select(is_inject($items[.]))] | last) as $li |
    (if $li != null then $li elif $pu != null then $pu else -1 end) as $start |
    # Позиция блока держится вместе с текстом, а не теряется в map: значение инжекта
    # выбирается ПО НЕЙ (см. INJECTED ниже). Раньше здесь оставался только текст, и
    # сравнивать шапку было не с чем, кроме «последнего инжекта вообще».
    def has_tool_use(x): role(x) == "assistant"
        and ((x.message.content // x.content // []) | if type == "array" then any(.[]; type == "object" and .type == "tool_use") else false end);
    ([range($start + 1; $n) | select(has_tool_use($items[.]))] | last) as $lt |
    ([range($start + 1; $n)
      | select(role($items[.]) == "assistant" and (($items[.].isSidechain // false) | not))
      | {i: ., t: get_text($items[.])}
      | select(.t != "")]) as $pf |
    # ИТОГ ДОСТРАИВАЕТСЯ ПОЛЕМ ВХОДА, А НЕ ПОДМЕНЯЕТСЯ ИМ (D1159). На Stop файл отстаёт от разговора: итог, начатый
    # шапкой, ещё не дописан, и судился промежуточный блок — 12 из 109 тревог «без таймштампа» (1 ноября 2026) пришли на
    # итог со шапкой. Нет в файле даже начала итога (текста после последнего вызова инструмента) — текст итога из поля
    # встаёт последним блоком окна, и дальше его судит вся логика ниже: промежуточная шапка, продолжение после Stop,
    # сверка с инжектом, число шапок. Начало итога в файле есть — судит файл: поле несёт лишь последний блок, а итог
    # бывает из нескольких. Первая редакция подменяла итог полем и снимала этим ветку промежуточной шапки и защиту
    # продолжения (финальный скептик D1159, H1, M2).
    ([$pf[] | select(.i > ($lt // $start))] | first) as $ff |
    (if $ff == null and ($lam | test("\\S")) then $pf + [{i: $n, t: $lam}] else $pf end) as $pairs |
    ([$pairs[] | select(is_header(.t))] | last) as $hdr |
    # ШАПКА В ПРОМЕЖУТОЧНОМ БЛОКЕ (D1172, L4 скептика; изъян старше окна): шапка нашлась, но итог — первый текст
    # после ПОСЛЕДНЕГО вызова инструмента в окне — идёт без неё, и между ними не было события Stop. Прежде такая шапка
    # засчитывалась за итог. Stop между ними (`system`/`stop_hook_summary`) — продолжение, запущенное хуком: там итог
    # без шапки законен, как и прежде (ноги цепочки).
    ([$pairs[] | select(.i > ($lt // $start))] | first) as $fin |
    (if ($hdr != null) and ($fin != null) and ($hdr.i < $fin.i) and (is_header($fin.t) | not)
     then ([range($hdr.i + 1; $fin.i) | select($items[.].type == "system" and $items[.].subtype == "stop_hook_summary")] | length) == 0
     else false end) as $interim |
    {pu: ($pu // -1),
     start: $start,
     interim_header: $interim,
     header_blocks: ([$pairs[] | select(is_header(.t))] | length),
     texts_after_start: ($pairs | length),
     hdr_idx: ($hdr.i // -1),
     final_written: ($fin != null),
     any_inject: ([range(0; $n) | select(is_inject($items[.]))] | length > 0),
     text: (($hdr.t) // ($pairs[0].t) // "")}
' 2>/dev/null; }
PARSED=$(_canary_parse)
if [ "$(printf '%s' "$PARSED" | jq -r '.any_inject' 2>/dev/null)" = false ]; then
    _TW=$(transcript_turn_window "$TRANSCRIPT_PATH")
    PARSED=$(_canary_parse)
fi

PU=$(printf '%s' "$PARSED" | jq -r '.pu // -1' 2>/dev/null)
# Метка хода — не голый индекс во входе (противник окна, атака 1): окно начинается с реплики,
# и индекс там почти всегда 0 — метка «уже сказали» совпала бы со всеми следующими ходами.
# Ход опознаётся первой строкой окна (сама реплика) плюс индексом; окно выродилось в файл —
# первая строка постоянна, а индекс абсолютный.
# ПЕРВАЯ СТРОКА — ЧТЕНИЕМ, А НЕ ПОДСТАНОВКОЙ (D1000, 17 октября 2026). `${_TW%%$'\n'*}` в bash 3.2
# с UTF-8 стоил «длина первой строки × размер окна»: реплика 584 КБ × окно 2,3 МБ = 271 с, и
# граница хода ждала канарейку минутами. Первую запись отдаёт awk (0,07 с на том же входе): без
# временного файла здесь-строки, чей отказ молча делал метку хода постоянной, и без SIGPIPE. Сумма
# прежняя — метка «уже сказано» не сбрасывается. Устройство и замер — у соседа
# accepted-alternative-gap.sh, где стояла та же строка; саму метку закрепляет нога T40 теста.
_TW_FIRST=$(printf '%s\n' "$_TW" | awk 'NR == 1')
# Метка — по началу окна шапки (D1172): одна тревога на подачу с инжектом, а не на ход владельца — иначе итог без
# шапки после второго отчёта молчал бы, раз первый отчёт уже дал тревогу.
START=$(printf '%s' "$PARSED" | jq -r '.start // -1' 2>/dev/null)
TURN_ID="$(printf '%s' "$_TW_FIRST" | cksum | awk '{print $1}'):${PU}:${START}"
HEADER_COUNT=$(printf '%s' "$PARSED" | jq -r '.header_blocks // 0' 2>/dev/null)
TEXTS_AFTER_START=$(printf '%s' "$PARSED" | jq -r '.texts_after_start // 0' 2>/dev/null)
INTERIM_HEADER=$(printf '%s' "$PARSED" | jq -r '.interim_header // false' 2>/dev/null)
LAST_ASSISTANT=$(printf '%s' "$PARSED" | jq -r '.text // empty' 2>/dev/null)
HDR_IDX=$(printf '%s' "$PARSED" | jq -r '.hdr_idx // -1' 2>/dev/null)
case "$HDR_IDX" in ''|*[!0-9-]*) HDR_IDX=-1 ;; esac

# Итога нет ни в файле, ни в поле (у последнего блока нет текста) — судить нечего: тревога была бы о промежуточном
# блоке (D1159). Предел: здесь не судится и число шапок окна; в мире такие ходы Stop не дают (8 из 2178 ходов, все
# прерваны — скептик D1159, L2). Второй предел: итог из нескольких блоков, не дописанный в файл целиком, судится по
# последнему блоку — поле несёт только его, и шапка первого блока не видна (в мире 0 из 3963 событий Stop). Условие
# снятия обоих: харнесс дописывает итог в файл до события Stop либо отдаёт в поле весь итог хода — документация
# хуков: файл «isn't guaranteed to include the final message at Stop time on all versions».
[ "$(printf '%s' "$PARSED" | jq -r '.final_written' 2>/dev/null)" = false ] && exit 0
[ -z "$LAST_ASSISTANT" ] && exit 0
[ "$LAST_ASSISTANT" = "null" ] && exit 0

# 2) маркер «на это окно уже алертили»: ключ — сессия + позиция реплики владельца + начало
# окна шапки (индекс последнего инжекта, D1172). Один алерт на окно: новый инжект — реплика,
# отчёт субагента, уведомление — взводит канарейку заново, продолжение после Stop — нет.
# Не полагается на семантику флага из п.1 — проверяется тестами.
SESSION_ID=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)
STATE_DIR="${CANARY_STATE_DIR:-${STATE_DIR:-$HOME/.claude/hooks/state}}"
MARK="$STATE_DIR/canary-alerted-${SESSION_ID}"
[ -f "$MARK" ] && [ "$(cat "$MARK" 2>/dev/null)" = "$TURN_ID" ] && exit 0

alert() {
    mkdir -p "$STATE_DIR" 2>/dev/null
    printf '%s' "$TURN_ID" > "$MARK" 2>/dev/null
    # Отладочного журнала здесь больше нет (13 сентября 2026, D383, корень R2): 57 строк за
    # трое суток, читателей ноль, а всё записанное — позиция реплики, число шапок, первая
    # строка, ts — выводится заново прогоном этого же стража по транскрипту: он детерминирован.
    # Алерт доходит до агента через additionalContext ниже; журнал без читателя был вторым
    # каналом в никуда, и проба R2 называла его носителем.
    # systemMessage снят 12 сентября 2026: в мобильном клиенте он рендерится построчно, и
    # алерт разворачивался у владельца в простыню. Канарейка адресована АГЕНТУ — она правит
    # его поведение, а не сообщает владельцу новость.
    jq -cn --arg m "$1" '{
      hookSpecificOutput: {hookEventName: "Stop", additionalContext: $m}
    }'
    exit 0
}

# Первая непустая строка ответа должна начинаться с «🕐 YYYY-MM-DD HH:MM».
FIRST_LINE=$(printf '%s\n' "$LAST_ASSISTANT" | grep -m1 -v '^[[:space:]]*$' || true)
# Значок 🕐 необязателен: канарейка ловит уплывание контекста, а не дисциплину
# эмодзи — эхо «2026-08-08 23:05 CEST» доказывает, что инструкция жива.
# Markdown-выделение допускается — та же оговорка, что у is_header выше. ВТОРАЯ КОПИЯ
# признака шапки: jq-версия судит, какой блок считать шапкой, эта — извлекает из неё
# значение. Копии обязаны согласовываться; 6 сентября 2026 они разошлись, и правка одной
# ничего не изменила: алерт приходил из второй (тот же класс, что D287 и D305).
TS=$(printf '%s' "$FIRST_LINE" | grep -oE '^[[:space:]]*[*_]{0,2}[[:space:]]*(🕐 )?[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}' | grep -oE '[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}' || true)

# Значение инжекта, ДЕЙСТВОВАВШЕГО НА МОМЕНТ ШАПКИ: последняя строка
# hook_additional_context с «🕐 <дата> <время>», записанная РАНЬШЕ выбранного блока.
# Контракт — сам значок 🕐, не формулировка инжектора: текст подсказки менялся и ещё
# будет, маркер времени — нет.
#
# Отбор по позиции добавлен 7 сентября 2026. До него бралось `| last` по всему
# транскрипту, то есть последний инжект ВООБЩЕ. В длинном ходе инжекты приходят не раз:
# замер того дня — ПЯТЬ инжектов и две шапки внутри одного хода. Обе шапки совпадали с
# инжектом, действовавшим в момент их написания, а страж сравнивал шапку 18:56 с инжектом
# 19:15 и объявлял уплывание. Оба входа по отдельности ВЕРНЫ — неверен был их отбор:
# сравнивались величины из разных моментов. Ложных тревог 2 из 2 на ходах с двумя и более
# инжектами; на ходах с одним инжектом поведение не меняется (шапка и так позже него).
# Это род L реестра: область механизма (весь ход) была шире предмета его утверждения
# («шапка — эхо инжекта, а не оценка»).
#
# Шапки нет ($hdr_idx = -1) — берём последний инжект как прежде: там вопрос не «совпало
# ли», а «жив ли инжектор вообще», и позиция для него не нужна.
INJECTED=$(printf '%s\n' "$_TW" | jq -rs --argjson hi "$HDR_IDX" '
    [ to_entries[]
      | select(($hi < 0) or (.key < $hi))
      | .value
      | select(.type == "attachment")
      | .attachment // empty
      | select(.type == "hook_additional_context")
      | .content // []
      | .[]?
      | select(type == "string")
      | capture("^🕐 (?<ts>[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2})").ts
    ] | last // empty' 2>/dev/null || true)

# Нет инжекта — нет и таймштампа: так велит само правило, и молчание здесь верно.
# До 28 августа 2026 страж утверждал «БЕЗ таймштампа ПРИ ЖИВОМ ИНЖЕКТЕ», ни разу не
# проверив вторую половину утверждения: признак строился по форме ОТВЕТА, а вывод делался
# об ИСТОЧНИКЕ. После сжатия контекста инжект в окне отсутствовал 470 строк подряд, а
# страж всё это время требовал перезапускать живую сессию. Сломанный инжектор — другой
# класс задачи (чинится хук, не сессия), и смешивать их нельзя.
if [ -n "$TS" ] && [ "$INTERIM_HEADER" = "true" ] && [ -n "$INJECTED" ]; then
    alert "🚨 Канарейка: шапка ($TS) стоит в промежуточном блоке, а итоговое сообщение после последнего инжекта 🕐 — без неё. Шапка — в начале ИТОГОВОГО сообщения, промежуточные блоки её не несут (rules/CLAUDE.md)."
fi
if [ -z "$TS" ]; then
    if [ -n "$INJECTED" ]; then
        alert "🚨 Канарейка контекста: итог хода БЕЗ таймштампа при живом инжекте ($INJECTED) — инструкции, вероятно, размылись. Правило: предложить собеседнику перезапустить сессию (/save → новая сессия)."
    fi
    exit 0
fi

# Фаза ablation: в VSCode-расширении диалог — единственная владелец-видимая
# поверхность (statusline/systemMessage не рендерятся; amendment phase-3,
# 2026-08-09). При активной фазе шапка ответа обязана нести сегмент 🧪.
PHM="${ABLATION_DIR:-$HOME/.claude/ablation}/active-phase.json"
if [ -f "$PHM" ]; then
    PH=$(jq -r '.phase // empty' "$PHM" 2>/dev/null)
    if [ -n "$PH" ] && ! grep -qF "🧪" <<< "$FIRST_LINE"; then
        alert "🚨 Канарейка: фаза ablation «${PH}» активна, а шапка ответа без сегмента фазы — владелец видит фазу только в диалоге (VSCode). Формат шапки: «🕐 <время> · 🧪 ${PH} · очередь N/20»."
    fi
fi

# ЛИШНИЕ ШАПКИ (8 сентября 2026). Правило: «Таймштамп несёт ОДИН блок хода» (с 2 октября 2026 —
# итоговое сообщение: промежуточный текст ложится в расшифровку пересказом без шапки)
# (rules/CLAUDE.md). Страж сверял ЗНАЧЕНИЕ одной шапки и был слеп к их ЧИСЛУ — а причина
# выдуманных значений именно в числе: инжект приходит один на ход, и для второй, третьей,
# сотой шапки времени взять неоткуда, кроме как сочинить.
#
# Замер по сессии 4e926e63 (8 сентября 2026): за ЧЕТЫРЕ хода владельца выдано 254 шапки —
# 109, 69, 27 и 49, — среди них 220 различных значений, и каждая шапка своим сообщением
# (сообщений с двумя шапками внутри — НОЛЬ). Канарейка ловила расхождение четырежды за
# сессию и каждый раз показывала симптом: она сверяет ОДНУ шапку, а привычка сочинять время
# нарабатывалась на остальных двухстах пятидесяти.
#
# ПОРОГ ОЦЕНОЧНЫЙ, И ЭТО НАЗВАНО ПРЯМО. Точного признака здесь построить нельзя: ход,
# запущенный Stop-хуком, даёт в транскрипте ровно ту же картину — несколько ответов с
# шапками после одной реплики владельца (нога T11 и комментарий к ней: «отличить продолжение
# ответа от нового хода в транскрипте нельзя»). Привязка порога к числу инжектов пробовалась
# и отвергнута замером: в цепочке Stop-хука инжекта нет вовсе, а вторая шапка там законна.
# Поэтому порог выбран разделяющим НАБЛЮДЁННЫЕ величины: законные цепочки дают единицы шапок
# (в тестах 2), наблюдённый дефект — десятки (27, 49, 69, 109). Пять лежит в этом зазоре и ни
# к одному краю не жмётся.
# УСЛОВИЕ УТОЧНЕНИЯ: появится машинный признак границы хода внутри цепочки (например, поле
# записи, отличающее продолжение от нового хода) — порог заменяется точным счётом «шапок на
# ход», и оценка становится не нужна.
# КОНТРПРИМЕР (алерт обязан НЕ сработать): цепочка из двух-трёх ходов, запущенных хуком, где
# каждый ход несёт свою шапку.
_CANARY_MAX_HEADERS="${CANARY_MAX_HEADERS:-5}"
case "$HEADER_COUNT" in ''|*[!0-9]*) HEADER_COUNT=0 ;; esac
if [ "$HEADER_COUNT" -gt "$_CANARY_MAX_HEADERS" ] 2>/dev/null; then
    alert "🚨 Канарейка: после последнего инжекта 🕐 выдано ${HEADER_COUNT} шапок с таймштампом. Законна ОДНА на подачу с инжектом — в итоговом сообщении (rules/CLAUDE.md); для остальных время взять неоткуда, кроме как выдумать, и именно так канарейка и умирает. До следующего инжекта 🕐 писать текст БЕЗ шапки; итог после нового инжекта — с ЕГО шапкой."
fi

if [ -n "$INJECTED" ]; then
    # Точное совпадение до минуты: правило требует ЭХО, а не оценку прошедшего.
    # Длинный ход — не оправдание расхождения: инжект один на ход, эхо одно.
    if [ "$TS" != "$INJECTED" ]; then
        alert "🚨 Канарейка контекста: шапка ответа ($TS) не совпадает с инжектом ($INJECTED) — время не эхо, а оценка. Правило: время не выдумывать, брать из последнего инжекта 🕐."
    fi
else
    # Инжекта в транскрипте не нашлось — прежняя проверка: эхо старше 6 часов.
    EPOCH=$(date -j -f '%Y-%m-%d %H:%M' "$TS" +%s 2>/dev/null || date -d "$TS" +%s 2>/dev/null || true)
    if [ -n "$EPOCH" ]; then
        NOW=$(date +%s)
        AGE=$(( NOW - EPOCH ))
        if [ "$AGE" -gt 21600 ] || [ "$AGE" -lt -21600 ]; then
            alert "🚨 Канарейка контекста: таймштамп ответа ($TS) отстаёт от часов больше чем на 6 часов — эхо протухло, контекст, вероятно, уплыл. Предложить собеседнику перезапуск сессии."
        fi
    fi
fi

exit 0
