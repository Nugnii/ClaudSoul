#!/usr/bin/env bash
# command-scope-lib.sh — единый источник сужения области поиска ВНУТРИ текста команды.
#
# Родственник `hook-input-lib.sh`: тот сужает область до реплик собеседника (не смотреть
# в tool_result), этот — до исполняемой части команды (не смотреть в аргументы). Оба про
# один класс — `pattern-guard-scope-blindness`: детектор сканирует не ту область и потому
# его срабатывание не значит того, что заявлено.
#
# Что случилось. `trust-guard` дал семь ложных срабатываний за одну сессию, а
# `playwright-cli-guard` дважды ЗАБЛОКИРОВАЛ реальную работу — запись собственного теста
# и запись раздела BACKLOG, где описывался этот же дефект. Причина у обоих одна: сигнатура
# искалась во всей строке команды, включая то, что никогда не исполняется:
#
#   grep -qE 'rm -rf ...' file        → `rm` внутри шаблона поиска, исполняется grep
#   python3 - <<'PY' ... PY           → тело heredoc, исполняется python, не shell
#   printf '... chromium.launch() ...' → строка-аргумент, а не запуск браузера
#
# Ключ к различению: **кавычки и heredoc содержат АРГУМЕНТЫ, а не имена команд.** Имя
# команды никогда не бывает внутри кавычек. Значит вырезать их для поиска сигнатуры
# безопасно — настоящий вызов не спрячется:
#
#   rm -rf "$T"   → после вырезания `rm -rf ` — сигнатура на месте
#   grep 'rm -rf' → после вырезания `grep ` — сигнатуры нет
#
# Важно: вырезание применяется ТОЛЬКО к поиску сигнатуры. Цель действия (что именно
# удаляют, куда пушат) извлекается из ИСХОДНОЙ строки — иначе потеряется `"$T"`.
#
# Использование:
#   source command-scope-lib.sh
#   EXEC=$(executable_part "$COMMAND")   # для матчинга сигнатур
#   TARGET=... # из "$COMMAND", не из "$EXEC"

# executable_part "<command>"
#   Печатает команду без тел heredoc и без содержимого кавычек.
#   Кавычки заменяются пробелом, чтобы `a"x"b` не склеилось в `ab` и не породило
#   ложное совпадение, которого не было ни в одном из кусков.
executable_part() {
    printf '%s' "${1:-}" | awk '
        BEGIN { in_heredoc = 0; marker = "" }
        {
            line = $0

            # Тело heredoc целиком пропускаем: оно уходит на stdin другой программе.
            if (in_heredoc) {
                stripped = line
                sub(/^[[:space:]]+/, "", stripped)
                sub(/[[:space:]]+$/, "", stripped)
                if (stripped == marker) { in_heredoc = 0; marker = "" }
                next
            }

            # Открытие heredoc: <<EOF, <<-EOF, <<"EOF", <<'"'"'EOF'"'"'
            if (match(line, /<<-?[[:space:]]*["'"'"']?[A-Za-z_][A-Za-z0-9_]*["'"'"']?/)) {
                m = substr(line, RSTART, RLENGTH)
                gsub(/^<<-?[[:space:]]*/, "", m)
                gsub(/["'"'"']/, "", m)
                marker = m
                in_heredoc = 1
                line = substr(line, 1, RSTART - 1)
            }

            # Содержимое кавычек → пробел. Имя команды в кавычках не бывает.
            gsub(/'"'"'[^'"'"']*'"'"'/, " ", line)
            gsub(/"[^"]*"/, " ", line)

            print line
        }
    ' 2>/dev/null || printf '%s' "${1:-}"
}
