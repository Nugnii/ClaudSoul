#!/usr/bin/env bash
# command-scope-lib.sh — единый источник сужения области поиска ВНУТРИ текста команды.
#
# ПРЕФИКСЫ: executable_ is_ redirect_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
#
# Родственник `hook-input-lib.sh`: тот сужает область до реплик собеседника (не смотреть
# в tool_result), этот — до исполняемой части команды (не смотреть в аргументы). Оба про
# один класс — `pattern-guard-scope-blindness`: детектор сканирует не ту область и потому
# его срабатывание не значит того, что заявлено.
#
# Что случилось. `trust-guard` дал семь ложных срабатываний за одну сессию, а
# `playwright-cli-guard` дважды ЗАБЛОКИРОВАЛ реальную работу — запись собственного теста
# и запись раздела BACKLOG, где описывался этот же дефект. Причина у обоих одна: сигнатура
# искалась во всей строке команды, включая то, что никогда не исполняется:
#
#   grep -qE 'rm -rf ...' file        → `rm` внутри шаблона поиска, исполняется grep
#   python3 - <<'PY' ... PY           → тело heredoc, исполняется python, не shell
#   printf '... chromium.launch() ...' → строка-аргумент, а не запуск браузера
#
# Ключ к различению: **кавычки и heredoc содержат АРГУМЕНТЫ, а не имена команд.** Имя
# команды почти не бывает внутри кавычек — исключение: литерал ПРОГРАММЫ после `-c`/`eval`/`trap`
# (`bash -c "git push"` → `bash -c `), он вырезается вместе с прочими (D1252; цена — ниже, пометка ponytail).
# В остальном вырезать их для поиска сигнатуры безопасно — настоящий вызов не спрячется:
#
#   rm -rf "$T"   → после вырезания `rm -rf ` — сигнатура на месте
#   grep 'rm -rf' → после вырезания `grep ` — сигнатуры нет
#
# Важно: вырезание применяется ТОЛЬКО к поиску сигнатуры. Цель действия (что именно
# удаляют, куда пушат) извлекается из ИСХОДНОЙ строки — иначе потеряется `"$T"`.
#
# Использование:
#   source command-scope-lib.sh
#   EXEC=$(executable_part "$COMMAND")   # для матчинга сигнатур
#   TARGET=... # из "$COMMAND", не из "$EXEC"

# executable_part "<command>"
#   Печатает команду без тел heredoc, без содержимого кавычек и без комментариев.
#   Вырезанное заменяется пробелом, чтобы `a"x"b` не склеилось в `ab` и не породило
#   ложное совпадение, которого не было ни в одном из кусков.
#
# Сканер посимвольный, а не набор подстановок по строке. Пять дефектов, которые
# построчные `gsub` давали и которые закрыты переходом к состоянию (все воспроизведены
# адверсариальным прогоном 2026-08-23, тест `test_adv_git_commit_scope.sh`):
#
#   `grep -q x <<< bar`      — here-string принимался за открытие heredoc, и ВСЁ, что
#                              шло дальше, до конца команды считалось телом;
#   `echo "cat << EOF" && …` — heredoc искался до вырезания кавычек, строка обрезалась;
#   `echo "текст\ngit …"`    — кавычка, закрытая на следующей строке, не вырезалась
#                              вовсе: `gsub` не пересекает границу записи awk;
#   `echo "делай \"x\""`     — экранированная кавычка рвала пару, и текст между ними
#                              выходил наружу как исполняемый;
#   `make test # см. git …`  — комментарий не вырезался и читался как команда.
#
# Состояние кавычек переносится между строками — это и есть разница с прежней версией.
executable_part() {
    # LC_ALL=C — байты, а не символы: BWK awk на macOS падает на неполной UTF-8
    # последовательности («towc: multibyte conversion failure»), и запасной путь
    # печатал СЫРУЮ команду, то есть отключал сужение области целиком. Вся значимая
    # для разбора пунктуация — ASCII, побайтовый режим её не задевает.
    printf '%s' "${1:-}" | LC_ALL=C awk '
        function eat_ws() { out = out " " }
        BEGIN { in_s = 0; in_d = 0; in_h = 0; marker = ""; dash = 0; pending = ""; qn = 0; sp = 0; ansi = 0 }
        {
            line = pending $0; pending = ""

            # Строка-продолжение: shell склеивает `\` + перевод, значит склеиваем и мы.
            if (!in_s && !in_d && !in_h && line ~ /\\$/) {
                pending = substr(line, 1, length(line) - 1) " "
                next
            }

            # Тело heredoc уходит на stdin другой программе — не наша область.
            if (in_h) {
                stripped = line
                # Терминатор простого `<<` — маркер строго с начала строки и без хвоста.
                # `<<-` срезает ведущие ТАБЫ (только их — так устроен shell).
                if (dash) sub(/^\t+/, "", stripped)
                if (stripped == marker) {
                    if (qn > 0) { marker = queue[1]; dash = qdash[1]
                                  for (k = 1; k < qn; k++) { queue[k] = queue[k+1]; qdash[k] = qdash[k+1] }
                                  qn-- }
                    else { in_h = 0; marker = ""; dash = 0 }
                }
                next
            }

            out = ""; ap = 0
            n = length(line)
            for (i = 1; i <= n; i++) {
                c = substr(line, i, 1)

                # Внутри одинарных кавычек НИЧЕГО не экранируется, включая слеш:
                # `echo '"'"'путь C:\'"'"'` закрывается этой же кавычкой, дальше идут команды.
                # Исключение — ANSI-строка $'...', где обратный слеш как раз экранирует.
                if (in_s) {
                    if (ansi && c == "\\") { i++; continue }
                    if (c == "'"'"'") { in_s = 0; ansi = 0 }
                    continue
                }

                # ВЛОЖЕННАЯ ПОДСТАНОВКА ОБРАТНОЙ КАВЫЧКОЙ (D1254, 8 ноября 2026). Внутри `…` bash снимает слеш перед
                # обратной кавычкой при разборе внешней подстановки, и `\`` становится открытием и закрытием уровнем
                # глубже: `` x=`echo "\`git commit\`"` `` запускает коммит. Уровень помечен 2 — закрывает его только `\``.
                if (c == "\\" && substr(line, i + 1, 1) == "`" && sp > 0 && stack_tick[sp]) {
                    i++
                    if (stack_tick[sp] == 2) { in_d = stack_d[sp]; sp--; continue }
                    sp++; stack_d[sp] = in_d; stack_tick[sp] = 2; in_d = 0
                    out = out "( "
                    continue
                }
                if (c == "\\") {
                    i++
                    # Вне кавычек слеш лишь снимает особый смысл со следующего символа,
                    # сам символ остаётся: `\rm` — это запуск `rm` в обход алиаса.
                    if (!in_d) out = out substr(line, i, 1)
                    continue
                }

                # Арифметика `$(( … ))` — не подстановка команды: `<<` внутри неё сдвиг, а не открытие heredoc; её текст
                # не выводится. Но подстановка команды ВНУТРИ арифметики исполняется оболочкой и разбирается обычным
                # сканером (D1326): прежде арифметика пропускалась целиком, и `"$(( now - $(stat -f %m f) ))"` терял
                # `stat` — 10 команд из 2 795 с арифметикой в корпусе 18 ноября 2026. Уровень арифметики привязан к
                # глубине стека подстановок: пока открыта вложенная подстановка, счёт скобок арифметики стоит.
                # Незакрытая арифметика кончается с концом строки, как и прежде, — остаток команды она не съедает.
                if (ap > 0 && sp == alev[ap] && !(c == "`") && !(c == "$" && substr(line, i + 1, 1) == "(" && substr(line, i + 2, 1) != "(")) {
                    if (c == "(") adepth[ap]++
                    else if (c == ")") { adepth[ap]--; if (adepth[ap] == 0) ap-- }
                    continue
                }
                if (c == "$" && substr(line, i + 1, 2) == "((") {
                    ap++; adepth[ap] = 2; alev[ap] = sp
                    i += 2
                    continue
                }

                # Подстановка команды исполняется оболочкой — внутри неё снова КОМАНДА,
                # а не текст, даже если сама подстановка стоит в двойных кавычках.
                # Прежде содержимое копировалось сырым, и `git commit -m "$(cat <<EOF …)"`
                # — штатная форма коммита в этом проекте — отдавала тело heredoc наружу
                # как исполняемое: страж требовал подтверждения на `rm -rf`, всего лишь
                # упомянутый в сообщении коммита. Вместо копирования кладём контекст
                # кавычек на стек и продолжаем обычным сканером: кавычки, heredoc и
                # комментарии внутри подстановки разбираются ровно так же, как снаружи.
                # НАЧАЛО КОМАНДЫ ОБОЗНАЧЕНО (D1212, 5 ноября 2026). Открытие прежде не выводилось
                # ничем, и `out=$(git commit -q …)` становилось `out=git commit …`: перед `git`
                # не было ни пробела, ни разделителя, и коммит не видели 16 стражей коммита (8 в
                # корпусе), переход `out=$(cd …` — счётчик переходов undefined-function-check.
                # Подстановка исполняется в подоболочке, поэтому выводится `( ` — так же, как
                # `( … )`, который сканер сохраняет; закрытие по-прежнему не выводится.
                # Обратная кавычка внутри своей же подстановки — ЗАКРЫТИЕ, а не новое открытие:
                # проверка открытия стоит раньше проверки закрытия, и прежде закрывающая кавычка
                # клала на стек второй уровень, а `"` за ней открывал строку до конца —
                # `echo "`date`" && git commit` терял коммит.
                if ((c == "$" && substr(line, i + 1, 1) == "(") || (c == "`" && !(sp > 0 && stack_tick[sp]))) {
                    sp++; stack_d[sp] = in_d; stack_tick[sp] = (c == "`")
                    in_d = 0
                    if (c != "`") i++
                    out = out "( "
                    continue
                }
                # Закрывается подстановка только вне кавычек: `"$(grep -c ")" f)"` —
                # первая скобка там аргумент grep, а не конец подстановки.
                if (sp > 0 && !in_d && ((c == ")" && !stack_tick[sp]) || (c == "`" && stack_tick[sp]))) {
                    in_d = stack_d[sp]; sp--
                    continue
                }

                if (in_d) {
                    if (c == "\"") in_d = 0
                    continue
                }

                if (c == "'"'"'") { in_s = 1; ansi = (i > 1 && substr(line, i - 1, 1) == "$"); eat_ws(); continue }
                if (c == "\"")    { in_d = 1; eat_ws(); continue }

                # Комментарий: `#` в начале слова гасит остаток строки.
                # Началом слова bash считает не только пробел: `ls ;# …`, `(ls)# …` —
                # тоже комментарии.
                # Внутри подстановки обратной кавычкой комментарий кончается на её закрывающей кавычке, и команда за ней —
                # снова команда: `` x=`echo a # c` ; git commit `` запускает коммит (D1254). Вложенный уровень `\`` —
                # граница своя, поэтому ищется первая обратная кавычка, перед которой нет слеша.
                if (c == "#" && (i == 1 || substr(line, i - 1, 1) ~ /[[:space:];&()]/)) {
                    if (sp > 0 && stack_tick[sp] == 1) {
                        for (j = i + 1; j <= n; j++)
                            if (substr(line, j, 1) == "`" && substr(line, j - 1, 1) != "\\") break
                        if (j <= n) { i = j; in_d = stack_d[sp]; sp--; continue }
                    }
                    break
                }

                if (c == "<" && substr(line, i + 1, 1) == "<") {
                    # `<<<` — here-string: обычный аргумент, не открытие heredoc.
                    if (substr(line, i + 2, 1) == "<") { out = out "<<<"; i += 2; continue }
                    rest = substr(line, i + 2)
                    if (match(rest, /^-?[[:space:]]*\\?["'"'"']?[A-Za-z_][A-Za-z0-9_]*["'"'"']?/)) {
                        m = substr(rest, RSTART, RLENGTH)
                        d = (m ~ /^-/) ? 1 : 0
                        gsub(/^-?[[:space:]]*/, "", m)
                        gsub(/[\\"'"'"']/, "", m)
                        # Тело начинается со СЛЕДУЮЩЕЙ строки, а остаток ЭТОЙ — команды:
                        # `git commit -F - <<MSG && git push` — push исполняется.
                        # Несколько heredoc в одной строке ждут своей очереди.
                        if (!in_h) { in_h = 1; marker = m; dash = d }
                        else { qn++; queue[qn] = m; qdash[qn] = d }
                        i += 1 + RLENGTH
                        continue
                    }
                }
                out = out c
            }
            print out
        }
        END { if (pending != "") print pending }
    ' 2>/dev/null || printf '%s' "${1:-}"
}

# is_git_commit "<command>"
#   Истина, когда команда РЕАЛЬНО запускает `git commit`. Упоминание в кавычках или в
#   теле heredoc — текст, а не команда.
#
# Единый матчер вместо восьми копий. До этого каждый из восьми стражей, стоящих на
# коммите, искал подстроку сам, и все восемь ошибались одинаково:
# `echo "как сделать git commit правильно"` при крупном диффе в индексе давало
# напоминание, хотя коммита нет. Три из восьми уже несли «улучшенный» матчер по
# границам слова — он ошибался ровно так же: граница на тексте в кавычках совпадает
# не хуже, чем на команде. Разница не в границах, а в том, ЧТО сканируют.
#
# Цена ошибки у большинства низкая (лишнее напоминание), но у `knowledge-capture-reminder`
# она другая: он СЧИТАЕТ коммиты за сессию, и упоминание накручивало счётчик — искажались
# данные, а не только внимание.
#
# `bash -c "git commit"` свой сканер не распознаёт — у `-c` кавычки содержат команду, а не аргумент; такой вызов
# называет владелец лексики (см. `is_git_subcommand`, D1326: живых случаев набралось 13 на 7 143 команды с коммитом).
# `ssh host "… git commit"` не распознаётся намеренно: коммит идёт на
# ДРУГОЙ машине, локальный индекс к нему отношения не имеет.
#
# `/` среди разделителей слева — это `/usr/local/bin/git commit`, полный путь к
# исполняемому файлу. Матчер «по границам слова» без него терял такой коммит, а
# наивный по подстроке — ловил: сужение области поиска не должно стоить охвата.
# Имя вроде `mygit commit` при этом остаётся отсечённым — перед `git` стоит буква.
#
# Глобальные опции git перечислены поимённо, а не как «любое -слово»: последнее ловило бы
# `git diff --name-only commit` — там `commit` аргумент, а не подкоманда.
#
# Справа граница шире пробела: `git commit; echo done`, `(git commit)`, `git commit|tee`
# — подкоманда там кончается разделителем, а не пробелом. Найдено дифференциальным
# тестом против самого bash, не критиком: 62 таких вхождения в корпусе расшифровок.
# is_git_subcommand <подкоманда> <строка> — код 0, если в исполняемой части есть `git <под>`.
#
# Обобщено из `is_git_commit` 10 сентября 2026 по находке противника: `revert-signal.sh`
# держал СВОЮ пару grep вида `git[[:space:]]+revert`, между `git` и подкомандой ничего
# вставить было нельзя, и `git -C /repo revert HEAD` откатом не считался — при том что
# ту же форму `-C` предписывает сам проект (`root-cause-lib.sh`: «git -C каталог, а не
# голый cd && git»). Копия правила у потребителя есть род K; здесь правило одно, а
# подкоманда стала доводом.
is_git_subcommand() {
    local _sub="${1:-}" _cmd="${2:-}"
    [ -n "$_sub" ] || return 1
    local _g='([[:space:]]+(-C[[:space:]]+[^[:space:]]*|-c[[:space:]]+[^[:space:]]*|--git-dir=[^[:space:]]*|--work-tree=[^[:space:]]*|--no-pager|-P))*'
    grep -qE "(^|[[:space:]]|;|&|\||\`|/|\(|\{|\\$\()git${_g}[[:space:]]+${_sub}([[:space:]]|;|&|\||\)|\$)" \
        <<< "$(executable_part "$_cmd")" && return 0
    # Свой разбор ответил «нет» — вопрос уходит владельцу лексики оболочки (`git_calls` в `hooks/lib/write_targets.py`,
    # D1326, корень R3): он раскрывает скрипт у `bash -c '…'` и `eval`, знает глобальные опции git с отдельным
    # значением и значение `-C` из подстановки или с экранированным пробелом. Замер 18 ноября 2026 на 7 143 настоящих
    # командах с коммитом: свой разбор не видел 14 коммитов (13 — внутри многострочного `bash -c '…'`, 1 — за
    # `--literal-pathspecs`), владелец — 1 (коммит на строке открытия heredoc), поэтому ответ — «да» любого из двух.
    # Владельца спрашивают, только когда в тексте есть и `git`, и подкоманда: цена вопроса — запуск python3.
    # Владельца нет (нет python3, установленная копия старее режима) — ответ своего разбора, как до D1326.
    case "$_cmd" in *git*"$_sub"*) ;; *) return 1 ;; esac
    local _wt _subs
    _wt=$(_scope_py --git-subs) || return 1
    _subs=$(printf '%s' "$_cmd" | python3 "$_wt" --git-subs 2>/dev/null) || return 1
    case $'\n'"$_subs"$'\n' in *$'\n'"$_sub"$'\n'*) return 0 ;; esac
    return 1
}

is_git_commit() {
    is_git_subcommand commit "${1:-}"
}

# ── Перенаправление В ФАЙЛ против символа «>» ────────────────────────────────────────────
#
# Третья область сужения, того же рода, что две выше: `executable_part` отвечает «где имя
# команды», `is_git_commit` — «это коммит», `redirect_bare` — «где в строке символ «>»
# действительно перенаправляет вывод».
#
# До 10 сентября 2026 этот awk-блок жил ДВУМЯ копиями — `five-whys-gate.sh:629-642` и
# `rules-write-bypass.sh:55-63`, посимвольно одинаковыми, — и обе стоят под отказом
# (уровень 4). Копия правила у потребителя есть род K реестра `defect-class-carriers.py`;
# цена копии измерена ниже.
#
# Что снимается и почему. Символ «>» перенаправляет вывод не всегда: он же входит в
# составные операторы ДРУГИХ языков, а тела heredoc, аргументы и шаблоны поиска этими
# языками и написаны.
#   'строка' "строка"   — аргумент, а не перенаправление
#   >/dev/null          — глушение вывода, мир не меняется
#   2>&1  >&2  &>       — слияние ПОТОКОВ (снято 28 августа 2026, поймано на себе)
#   >=  >>=  ->  =>     — операторы сравнения и стрелки python/awk/jq/js (снято 10 сентября
#                         2026, поймано на себе дважды за один ход: читающий вызов получил
#                         отказ с текстом «чтение, поиск и осмотр не блокируются»)
#
# ЗАМЕР перед правкой, корпус 60 крупнейших расшифровок, 16 632 вызова Bash: записью
# признаны 3374, из них 100 (3,0%) — ЕДИНСТВЕННО из-за «>=» и ещё 12 из-за «->». Прогон
# независимого критика по 14 543 командам дал 39 и 3: числа разные, класс один.
# КОНТРПРИМЕР искался числом: 135 различных контекстов вокруг «>=» во всех ложных
# срабатываниях, все до одного — операторы сравнения; перенаправления в файл с именем,
# начинающимся на «=», в корпусе нет. Потому последствие у признака ОДНО и снятие точно.
#
# НАЗВАННЫЙ ПРЕДЕЛ: снимаются лексемы, а не разбирается грамматика. Тело heredoc целиком
# не вырезается — `bash <<EOF` внутри пишет по-настоящему, и вырезание сделало бы отказ
# слепым. Оператор с «>» из языка, которого здесь нет, останется ложным срабатыванием.
# Условие снятия предела то же, что записано в `five-whys-gate.sh`: способ правки станет
# наблюдаем по факту изменения файлов, а не по тексту команды.
#
# Возвращает ОЧИЩЕННУЮ строку; признак записи остаётся за потребителем — он у каждого
# свой (гейт разбора считает записью ещё и коммит, страж правил — `cp`/`mv`/`install`).
redirect_bare() {
    printf '%s' "${1:-}" | awk '{
        s = $0
        # ДВОЙНЫЕ кавычки снимаются ПЕРВЫМИ (10 сентября 2026, находка противника): в
        # `grep -c "it$(printf \047)s" f && awk $(printf \047)$1 > 5{...}$(printf \047)`
        # апостроф внутри двойных кавычек спаривался с апострофом awk, границы разъезжались,
        # и сравнение выходило наружу как перенаправление — читающий вызов получал отказ.
        gsub(/"[^"]*"/, " ", s)
        gsub(/\047[^\047]*\047/, " ", s)
        # Арифметика оболочки — не перенаправление: `$(( n > 100 ))`, `(( x > 50 ))`.
        # `executable_part` в этом же файле их разбирает, `redirect_bare` не разбирал.
        # Простая подстановка гасится ПЕРВОЙ: внутри арифметики она встречается
        # (`(( $(ls | wc -l) > 50 ))`), и без этого шага шаблон обрывается о её скобку.
        # НАЗВАННЫЙ ПРЕДЕЛ: настоящая запись ВНУТРИ подстановки (`echo $(cat f > out)`)
        # тоже погаснет и отказа не получит. Форма редкая; условие снятия — разбор
        # вложенности вместо построчного gsub.
        gsub(/\$\([^()]*\)/, " ", s)
        gsub(/\$\(\([^)]*\)\)/, " ", s)
        gsub(/\(\([^)]*\)\)/, " ", s)
        # Комментарий до конца строки: `ls hooks  # раньше писали > в файл`.
        sub(/[[:space:]]#[^\n]*$/, " ", s)
        gsub(/[0-9]?>>?[[:space:]]*\/dev\/null/, " ", s)
        gsub(/[0-9]?>&[0-9]/, " ", s)
        gsub(/&>>?/, " ", s)
        gsub(/[-=]>|>>?=/, " ", s)
        print s
    }'
}

# ── ЦЕЛИ операций, создающих путь ────────────────────────────────────────────────────────
#
# Четвёртая область сужения, и она отвечает на вопрос, которого три первые не решают:
# `executable_part` говорит «где имя команды», `is_git_commit` — «это коммит»,
# `redirect_bare` — «где «>» перенаправляет». Здесь: «КАКОЙ ПУТЬ вызов создаёт».
#
# Повод (D420, 16 сентября 2026). `skill-name-ascii-guard` решал «вызов создаёт каталог
# скилла» НАЛИЧИЕМ слова в тексте, а имя брал подстрокой из любого токена — то есть область
# поиска не была объявлена, и ею стал весь текст вызова вместе с телом чужого heredoc и
# прозой. Замер по корпусу (35438 вызовов Bash, 487 с путём каталога скиллов): 24 отказа,
# настоящее создание ОДНО, ложных 21 — среди них отбитая починка, которой страж сам требует.
# Корень R3 карты («роль решается перечнем форм»), и остановка на его СУЖЕНИИ: дробь звена
# «признак снят с несуженного текста» — 8 из 10, у R3 как объявлен картой — 9 из 116.
#
# РАЗБОР ЛЕЖИТ В hooks/lib/write_targets.py, а не здесь: разбирать кавычки надо РАЗБОРОМ
# (`shlex`), а не вырезанием, иначе теряется цель в кавычках с пробелом. Та же пара, что у
# замка состояния (`state-lock-lib.sh` + `lib/state_lock.py`).
#
# ПОЧЕМУ ЭТО НЕ РЕЦИДИВ УДАЛЁННОГО `hooks/lib/write-target-lib.sh` — квантор обратный:
# там предикат ОСВОБОЖДАЛ от отказа (промах = защита не сработала), здесь ОТКАЗЫВАЕТ
# (промах = пропуск). Полностью довод записан в шапке `write_targets.py`.
#
# НЕТ РАЗБОРА — НЕТ ОТВЕТА, И ЭТО РАЗНЫЕ ИСХОДЫ. Код 2 значит «спросить нечем» (нет python3
# либо файла разбора); потребитель обязан отличить его от «целей не найдено» (код 0, пустой
# вывод) — иначе сломанный разбор читается как чистая команда, и отказ уровня 4 либо
# онемеет, либо начнёт бить наугад.
# Резолв разбора — ОДИН на обоих потребителей. Копия у второго была бы род K реестра:
# ровно тот дефект, ради которого заведён этот файл.
_scope_py() {                  # _scope_py [режим] → путь разбора; 1 — спросить нечем
    local _wt _mode="${1:-}"
    _wt="${WRITE_TARGETS_PY:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/lib/write_targets.py}"
    [ -f "$_wt" ] || _wt="$HOME/.claude/hooks/lib/write_targets.py"
    [ -f "$_wt" ] || return 1
    command -v python3 >/dev/null 2>&1 || return 1
    # РЕЖИМ, КОТОРОГО РАЗБОР НЕ ЗНАЕТ, — ЭТО «СПРОСИТЬ НЕЧЕМ», А НЕ ПУСТОЙ ОТВЕТ.
    # Запасной путь ведёт в УСТАНОВЛЕННУЮ копию, а она бывает старше репозиторной: старый
    # разбор неизвестный флаг игнорирует и печатает цели СОЗДАНИЯ — то есть отвечает на
    # другой вопрос, и молча. Два состояния мира шли бы по одному проводу (корень R6).
    # Поймано ногой T16g 16 сентября 2026, а не рассуждением: мутант молчал не потому,
    # что сужение работает, а потому что спрашивали прибор, не знающий вопроса.
    [ -z "$_mode" ] || grep -q -- "$_mode" "$_wt" 2>/dev/null || return 1
    printf '%s' "$_wt"
}

executable_write_targets() {   # executable_write_targets <команда> → пути по строке; 2 — спросить нечем
    local _wt
    _wt=$(_scope_py) || return 2
    printf '%s' "${1:-}" | python3 "$_wt" 2>/dev/null || return 2
}

