# Девятая область: «В КАКОМ КАТАЛОГЕ ИДЁТ КОММИТ» (D1278) — `cd` до вызова и `-C` самого вызова, сложенные разбором
# (`commit_dirs` на `git_calls`, write_targets.py). Стражи PreToolUse-суда коммита брали репозиторий от папки сессии, и
# `cd <другой> && git commit` судился там, куда коммит не шёл: учёт ложился в чужой индекс, подсказка и отказ — о другом
# репозитории. Ответ — каталог ПЕРВОГО коммита команды; код 2 («спросить нечем») и тогда, когда коммита разбор не увидел
# либо каталог задан переменной или подстановкой (`?`): потребитель судит папку вызова, как до D1278.
executable_commit_dir() {      # executable_commit_dir <папка вызова> <команда> → каталог коммита; 2 — спросить нечем
    local _wt _d
    _wt=$(_scope_py --commit-dirs) || return 2
    _d=$(printf '%s' "${2:-}" | python3 "$_wt" --commit-dirs 2>/dev/null) || return 2
    # Коммиты команды в РАЗНЫЕ каталоги — каталог не один, ответа нет: суд папки сессии, как до D1278 (скептик D1279,
    # M2: первый коммит в чужой репозиторий снимал суд второго — в папку сессии).
    [ "$(printf '%s\n' "$_d" | sort -u | wc -l | tr -d ' ')" = 1 ] || return 2
    _d=${_d%%$'\n'*}
    case "$_d" in ''|'?') return 2 ;; /*) printf '%s' "$_d" ;; *) printf '%s/%s' "${1:-.}" "$_d" ;; esac
}

# Восьмая область: «ВЫЗОВ ПИШЕТ» — вопрос стража разбора и всякого, кто отличает правку от осмотра (D1160, корень R3).
# До 1 ноября 2026 ответ держали три копии: регэксп по `redirect_bare` в `five-whys-gate.sh`, свой у
# `rules-write-bypass.sh` и `RC_OUT_WRITE_RE` в `root-cause-lib.sh` (внутри jq). Копия стража не видела 17 форм из 18
# (цель в кавычках, `&>`, `|tee`, `git -C … commit`, `sed -E -i`, `perl -pi`, `cp`/`mv`/`rm`, `install`, `node -e`,
# `awk > "f"`) и принимала «>» в теле heredoc интерпретатора за перенаправление.
# Признак собран из владельцев, а не выписан заново. Что вызов меняет — у разбора (`executable_change_targets`, режим
# `--edits`): перенаправления, создание (`cp`/`mv`/`install`/`ln`/`mkdir`/`touch`/`tee`), удаление, правка на месте
# `sed`/`perl`/`ruby -i` и `git commit` — в позиции команды, с телами `bash <<X`, `bash -c '…'` и `find -exec`. Первая
# редакция искала имена `tee`/`rm`/`-i` регэкспом по `executable_part`, и скептик opus по d33e7943 нашёл обе стороны:
# `command -v tee`, `grep -rn rm`, `perl -MTime::HiRes` — «запись»; `tee`, `sed -i` и коммит в теле `bash <<X` — «чтение»
# (`executable_part` срезает тела, которые исполнит сама оболочка). Коммит судит и `is_git_commit` — для команды, которую
# лексер разбора не берёт. Запись из интерпретатора ищется по СЫРОЙ команде: её код стоит в кавычках или в теле.
# С D1215 узнаются и формы, встреченные на корпусах расшифровок: `curl -o`/`-O`/`-c`/`-D`, `wget` (без `-O -`), `git stash`
# (кроме `list`/`show`), `git worktree add|move|remove|prune`, `git apply` (кроме `--check`/`--stat`/`--numstat`/
# `--summary`), `git checkout -- <пути>`, `git restore`, `chmod`, `find -delete` (и со скобками `\( … \)`), `tar -x`,
# удаление `os.remove`/`.unlink()` (питон `os`, `pathlib`; node `fs.unlink`)/`shutil.rmtree`; правило форм одно у основного и запасного разбора (`_edit_targets`).
# НАЗВАННЫЙ ПРЕДЕЛ: перечень, а не наблюдение изменения (тот же R3, что в `five-whys-gate.sh`): мимо идут
# `git checkout <ветка>` и `checkout .` без `--`, `reset --hard`, `am`, `truncate`, `dd of=`, `patch`, `sort -o`, `tar -c`,
# `sed -I` (BSD), `gawk -i inplace`, `awk '{print > "f"}'`, питон `open(…, 'r+')`, `os.rmdir`, `from os import remove`,
# node `unlinkSync`/`renameSync`/`copyFileSync`/`writeFile`, обёртка вне `_CMD_PREFIX` (`gtimeout`), `eval "…"` с
# командой в кавычках, свой скрипт-обёртка; частоты всех не измерены, у `os.rmdir`, `from os import remove`,
# `gtimeout … curl` и `git apply --stat --apply` на 275 807 командах — 0. Обратный
# предел — «запись» там, где её нет: слово выражения (`write_text`, `os.remove`, `shutil.rmtree`, …) в шаблоне поиска
# или в кавычках аргумента, слитное значение ключа `wget` с буквой O (`-UOpera`), `wget --version`, `chmod --help`;
# на 275 807 командах корпуса 6 ноября 2026 у слова в кавычках 2 (обе — скрипт мутаций скептика D1215), у прочих 0. Разбора нет (нет python3 либо установленная копия старее режима) — перенаправление
# судится по `redirect_bare`, как до D1160.
executable_change_targets() {  # executable_change_targets <команда> → пути, которые вызов меняет; 2 — спросить нечем
    local _wt
    _wt=$(_scope_py --edits) || return 2
    printf '%s' "${1:-}" | python3 "$_wt" --edits 2>/dev/null || return 2
}

is_write_command() {           # is_write_command <команда> → 0 пишет, 1 нет
    local _c="${1:-}" _t _rc
    is_git_commit "$_c" && return 0
    _t=$(executable_change_targets "$_c"); _rc=$?
    # Цели под /dev/ — глушение и потоки (`2>/dev/null`, `| tee /dev/stderr`): мир они не меняют, а разбор их отдаёт —
    # на 10 расшифровках 238 из 294 новых «записей» были ими.
    _t=$(printf '%s\n' "$_t" | grep -v '^/dev/')
    if [ "$_rc" -eq 2 ]; then
        grep -qE '>>?[[:space:]]*[^&[:space:]]' <<< "$(redirect_bare "$_c")" && return 0
    elif [ -n "$_t" ]; then
        return 0
    fi
    grep -qE 'write_text|write_bytes|writelines|os\.replace|os\.rename|shutil\.(copy|move)|json\.dump\(|open\([^)]*,[[:space:]]*(mode[[:space:]]*=[[:space:]]*)?["'"'"'][wa]|writeFileSync|appendFileSync|createWriteStream|\.save\(|os\.remove\(|\.unlink\(|shutil\.rmtree\(' <<< "$_c" && return 0
    return 1
}
