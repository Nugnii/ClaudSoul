#!/usr/bin/env bash
# command-scope-lib.sh — единый источник сужения области поиска ВНУТРИ текста команды.
#
# Родственник `hook-input-lib.sh`: тот сужает область до реплик собеседника (не смотреть
# в tool_result), этот — до исполняемой части команды (не смотреть в аргументы). Оба про
# один класс — `pattern-guard-scope-blindness`: детектор сканирует не ту область и потому
# его срабатывание не значит того, что заявлено.
#
# Что случилось. `trust-guard` дал семь ложных срабатываний за одну сессию, а
# `playwright-cli-guard` дважды ЗАБЛОКИРОВАЛ реальную работу — запись собственного теста
# и запись раздела BACKLOG, где описывался этот же дефект. Причина у обоих одна: сигнатура
# искалась во всей строке команды, включая то, что никогда не исполняется:
#
#   grep -qE 'rm -rf ...' file        → `rm` внутри шаблона поиска, исполняется grep
#   python3 - <<'PY' ... PY           → тело heredoc, исполняется python, не shell
#   printf '... chromium.launch() ...' → строка-аргумент, а не запуск браузера
#
# Ключ к различению: **кавычки и heredoc содержат АРГУМЕНТЫ, а не имена команд.** Имя
# команды никогда не бывает внутри кавычек. Значит вырезать их для поиска сигнатуры
# безопасно — настоящий вызов не спрячется:
#
#   rm -rf "$T"   → после вырезания `rm -rf ` — сигнатура на месте
#   grep 'rm -rf' → после вырезания `grep ` — сигнатуры нет
#
# Важно: вырезание применяется ТОЛЬКО к поиску сигнатуры. Цель действия (что именно
# удаляют, куда пушат) извлекается из ИСХОДНОЙ строки — иначе потеряется `"$T"`.
#
# Использование:
#   source command-scope-lib.sh
#   EXEC=$(executable_part "$COMMAND")   # для матчинга сигнатур
#   TARGET=... # из "$COMMAND", не из "$EXEC"

# executable_part "<command>"
#   Печатает команду без тел heredoc, без содержимого кавычек и без комментариев.
#   Вырезанное заменяется пробелом, чтобы `a"x"b` не склеилось в `ab` и не породило
#   ложное совпадение, которого не было ни в одном из кусков.
#
# Сканер посимвольный, а не набор подстановок по строке. Пять дефектов, которые
# построчные `gsub` давали и которые закрыты переходом к состоянию (все воспроизведены
# адверсариальным прогоном 2026-08-23, тест `test_adv_git_commit_scope.sh`):
#
#   `grep -q x <<< bar`      — here-string принимался за открытие heredoc, и ВСЁ, что
#                              шло дальше, до конца команды считалось телом;
#   `echo "cat << EOF" && …` — heredoc искался до вырезания кавычек, строка обрезалась;
#   `echo "текст\ngit …"`    — кавычка, закрытая на следующей строке, не вырезалась
#                              вовсе: `gsub` не пересекает границу записи awk;
#   `echo "делай \"x\""`     — экранированная кавычка рвала пару, и текст между ними
#                              выходил наружу как исполняемый;
#   `make test # см. git …`  — комментарий не вырезался и читался как команда.
#
# Состояние кавычек переносится между строками — это и есть разница с прежней версией.
executable_part() {
    # LC_ALL=C — байты, а не символы: BWK awk на macOS падает на неполной UTF-8
    # последовательности («towc: multibyte conversion failure»), и запасной путь
    # печатал СЫРУЮ команду, то есть отключал сужение области целиком. Вся значимая
    # для разбора пунктуация — ASCII, побайтовый режим её не задевает.
    printf '%s' "${1:-}" | LC_ALL=C awk '
        function eat_ws() { out = out " " }
        BEGIN { in_s = 0; in_d = 0; in_h = 0; marker = ""; dash = 0; pending = ""; qn = 0; sp = 0; ansi = 0 }
        {
            line = pending $0; pending = ""

            # Строка-продолжение: shell склеивает `\` + перевод, значит склеиваем и мы.
            if (!in_s && !in_d && !in_h && line ~ /\\$/) {
                pending = substr(line, 1, length(line) - 1) " "
                next
            }

            # Тело heredoc уходит на stdin другой программе — не наша область.
            if (in_h) {
                stripped = line
                # Терминатор простого `<<` — маркер строго с начала строки и без хвоста.
                # `<<-` срезает ведущие ТАБЫ (только их — так устроен shell).
                if (dash) sub(/^\t+/, "", stripped)
                if (stripped == marker) {
                    if (qn > 0) { marker = queue[1]; dash = qdash[1]
                                  for (k = 1; k < qn; k++) { queue[k] = queue[k+1]; qdash[k] = qdash[k+1] }
                                  qn-- }
                    else { in_h = 0; marker = ""; dash = 0 }
                }
                next
            }

            out = ""
            n = length(line)
            for (i = 1; i <= n; i++) {
                c = substr(line, i, 1)

                # Внутри одинарных кавычек НИЧЕГО не экранируется, включая слеш:
                # `echo '"'"'путь C:\'"'"'` закрывается этой же кавычкой, дальше идут команды.
                # Исключение — ANSI-строка $'...', где обратный слеш как раз экранирует.
                if (in_s) {
                    if (ansi && c == "\\") { i++; continue }
                    if (c == "'"'"'") { in_s = 0; ansi = 0 }
                    continue
                }

                if (c == "\\") {
                    i++
                    # Вне кавычек слеш лишь снимает особый смысл со следующего символа,
                    # сам символ остаётся: `\rm` — это запуск `rm` в обход алиаса.
                    if (!in_d) out = out substr(line, i, 1)
                    continue
                }

                # Арифметика `$(( … ))` — не подстановка команды: `<<` внутри неё сдвиг,
                # а не открытие heredoc. Пропускаем целиком до закрывающих скобок.
                if (c == "$" && substr(line, i + 1, 2) == "((") {
                    i += 3; adepth = 2
                    while (i <= n && adepth > 0) {
                        ch = substr(line, i, 1)
                        if (ch == "(") adepth++
                        else if (ch == ")") adepth--
                        i++
                    }
                    i--
                    continue
                }

                # Подстановка команды исполняется оболочкой — внутри неё снова КОМАНДА,
                # а не текст, даже если сама подстановка стоит в двойных кавычках.
                # Прежде содержимое копировалось сырым, и `git commit -m "$(cat <<EOF …)"`
                # — штатная форма коммита в этом проекте — отдавала тело heredoc наружу
                # как исполняемое: страж требовал подтверждения на `rm -rf`, всего лишь
                # упомянутый в сообщении коммита. Вместо копирования кладём контекст
                # кавычек на стек и продолжаем обычным сканером: кавычки, heredoc и
                # комментарии внутри подстановки разбираются ровно так же, как снаружи.
                if ((c == "$" && substr(line, i + 1, 1) == "(") || c == "`") {
                    sp++; stack_d[sp] = in_d; stack_tick[sp] = (c == "`")
                    in_d = 0
                    if (c != "`") i++
                    continue
                }
                # Закрывается подстановка только вне кавычек: `"$(grep -c ")" f)"` —
                # первая скобка там аргумент grep, а не конец подстановки.
                if (sp > 0 && !in_d && ((c == ")" && !stack_tick[sp]) || (c == "`" && stack_tick[sp]))) {
                    in_d = stack_d[sp]; sp--
                    continue
                }

                if (in_d) {
                    if (c == "\"") in_d = 0
                    continue
                }

                if (c == "'"'"'") { in_s = 1; ansi = (i > 1 && substr(line, i - 1, 1) == "$"); eat_ws(); continue }
                if (c == "\"")    { in_d = 1; eat_ws(); continue }

                # Комментарий: `#` в начале слова гасит остаток строки.
                # Началом слова bash считает не только пробел: `ls ;# …`, `(ls)# …` —
                # тоже комментарии.
                if (c == "#" && (i == 1 || substr(line, i - 1, 1) ~ /[[:space:];&()]/)) break

                if (c == "<" && substr(line, i + 1, 1) == "<") {
                    # `<<<` — here-string: обычный аргумент, не открытие heredoc.
                    if (substr(line, i + 2, 1) == "<") { out = out "<<<"; i += 2; continue }
                    rest = substr(line, i + 2)
                    if (match(rest, /^-?[[:space:]]*\\?["'"'"']?[A-Za-z_][A-Za-z0-9_]*["'"'"']?/)) {
                        m = substr(rest, RSTART, RLENGTH)
                        d = (m ~ /^-/) ? 1 : 0
                        gsub(/^-?[[:space:]]*/, "", m)
                        gsub(/[\\"'"'"']/, "", m)
                        # Тело начинается со СЛЕДУЮЩЕЙ строки, а остаток ЭТОЙ — команды:
                        # `git commit -F - <<MSG && git push` — push исполняется.
                        # Несколько heredoc в одной строке ждут своей очереди.
                        if (!in_h) { in_h = 1; marker = m; dash = d }
                        else { qn++; queue[qn] = m; qdash[qn] = d }
                        i += 1 + RLENGTH
                        continue
                    }
                }
                out = out c
            }
            print out
        }
        END { if (pending != "") print pending }
    ' 2>/dev/null || printf '%s' "${1:-}"
}

# is_git_commit "<command>"
#   Истина, когда команда РЕАЛЬНО запускает `git commit`. Упоминание в кавычках или в
#   теле heredoc — текст, а не команда.
#
# Единый матчер вместо восьми копий. До этого каждый из восьми стражей, стоящих на
# коммите, искал подстроку сам, и все восемь ошибались одинаково:
# `echo "как сделать git commit правильно"` при крупном диффе в индексе давало
# напоминание, хотя коммита нет. Три из восьми уже несли «улучшенный» матчер по
# границам слова — он ошибался ровно так же: граница на тексте в кавычках совпадает
# не хуже, чем на команде. Разница не в границах, а в том, ЧТО сканируют.
#
# Цена ошибки у большинства низкая (лишнее напоминание), но у `knowledge-capture-reminder`
# она другая: он СЧИТАЕТ коммиты за сессию, и упоминание накручивало счётчик — искажались
# данные, а не только внимание.
#
# ponytail: `bash -c "git commit"` не распознаётся — у `-c` кавычки содержат команду, а не
# аргумент, и общее правило сканера тут не работает. Замер достижимости: 0 вхождений на
# 2730 упоминаний коммита во всех расшифровках. Разбор вложенной команды — когда появится
# первый живой случай. `ssh host "… git commit"` не распознаётся намеренно: коммит идёт на
# ДРУГОЙ машине, локальный индекс к нему отношения не имеет.
#
# `/` среди разделителей слева — это `/usr/local/bin/git commit`, полный путь к
# исполняемому файлу. Матчер «по границам слова» без него терял такой коммит, а
# наивный по подстроке — ловил: сужение области поиска не должно стоить охвата.
# Имя вроде `mygit commit` при этом остаётся отсечённым — перед `git` стоит буква.
#
# Глобальные опции git перечислены поимённо, а не как «любое -слово»: последнее ловило бы
# `git diff --name-only commit` — там `commit` аргумент, а не подкоманда.
#
# Справа граница шире пробела: `git commit; echo done`, `(git commit)`, `git commit|tee`
# — подкоманда там кончается разделителем, а не пробелом. Найдено дифференциальным
# тестом против самого bash, не критиком: 62 таких вхождения в корпусе расшифровок.
is_git_commit() {
    local _g='([[:space:]]+(-C[[:space:]]+[^[:space:]]*|-c[[:space:]]+[^[:space:]]*|--git-dir=[^[:space:]]*|--work-tree=[^[:space:]]*|--no-pager|-P))*'
    grep -qE "(^|[[:space:]]|;|&|\||\`|/|\(|\{|\\$\()git${_g}[[:space:]]+commit([[:space:]]|;|&|\||\)|\$)" \
        <<< "$(executable_part "${1:-}")"
}
