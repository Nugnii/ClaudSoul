#!/usr/bin/env bash
# backlog-reading-refresh.sh — PostToolUse[Write|Edit|Read]: показания бэклога пересчитаны по правке и сверены при чтении.
# en: PostToolUse on backlog writes and reads — item readings are recomputed on write and checked against the world on read.
#
# Результат: показание открытого пункта, прочитанное агентом, совпадает с выводом своей
#            команды, а каждое чтение устаревшего показания посчитано
# Проверка результата: bash hooks/tests/test_backlog_reading_refresh.sh даёт 0
#
# Повод — поправка владельца 30 августа 2026, дословно: «накопления должны обновляться у
# пунктов бэклога каждый раз, когда туда что-то добавляется или удаляется». Замер того же
# часа: D206 утверждал «накоплено 13 записей исходов», фактически 19 — расхождение прожило
# два часа и нашлось вопросом собеседника, а не механизмом. Хуже того, условие возврата
# пункта ссылается ИМЕННО на это число («открыт, пока нет ≥20»): решение о закрытии
# принималось бы по устаревшей величине.
#
# ТРИ СОБЫТИЯ ОДНОГО ПРЕДМЕТА (D210). Пересчёт по правке файла оказался недостаточен:
# 30 августа 2026 в 01:14 показание устарело через 50 минут после его введения — журнал
# исходов рос каждым ходом, а бэклог не трогали. Предмет утверждения — мир, а не файл,
# поэтому теперь:
#   · правка BACKLOG.md (Write|Edit|MultiEdit) — пересчёт, как прежде;
#   · чтение BACKLOG.md (Read) — сверка с миром БЕЗ записи: расхождение уходит в
#     `state/backlog-stale-read-<SID>.jsonl` (это и есть величина «сколько раз показание
#     прочитано устаревшим», замер `stale-reads`) и в контекст — свежие значения, чтобы
#     решение принималось по миру, а не по файлу;
#   · граница хода (Stop) — пересчёт из `hooks/session-collector.sh` после архиватора,
#     последовательно с ним: два писателя одного файла на одном событии без порядка —
#     гонка, и пересчёт встал за архиватором, а не отдельной регистрацией.
#
# ПОЧЕМУ ПЕРЕСЧЁТ, А НЕ НАПОМИНАНИЕ. Действие однозначное — выполнить объявленную самим
# пунктом команду и подставить её вывод; спорных случаев нет. Напоминание же, по замеру
# 28 августа 2026, читается и не меняет действий.
#
# ПОТОЛОК, названный честно: чтение через Bash (`cat`, `sed -n`) хук не видит — как и
# `partial-read-guard`; чтение владельцем в редакторе тоже. Их покрывает пересчёт на Stop.
#
# КОНТРПРИМЕР: пункт без строки `**Показание.**` не трогается — у части пунктов показание
# есть суждение, а не число, и требовать от них команду значило бы врать точностью.
# Закрытые пункты не трогаются тоже: их показание — свидетельство на момент закрытия.
# Свежее показание при чтении — тишина: страж не становится фоном на здоровой работе.
#
# Input  (stdin): {session_id, tool_name, tool_input:{file_path}} (PostToolUse JSON)
# Output (stdout): {hookSpecificOutput:{additionalContext}} — что пересчитано / что устарело, либо пусто
# Exit:  always 0 (degrade gracefully).
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
case "$TOOL" in Write|Edit|MultiEdit|Read) ;; *) exit 0 ;; esac
FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)
case "$(basename "${FILE:-}")" in BACKLOG.md) ;; *) exit 0 ;; esac
[ -f "$FILE" ] || exit 0

# Скрипт ищется рядом с репозиторием ЭТОГО бэклога, а не только в ClaudSoul: пункт может
# жить в инициированном проекте, и обновлять его показания обязан его же инструмент.
ROOT=$(cd "$(dirname "$FILE")" 2>/dev/null && pwd) || exit 0
REFRESH="$ROOT/scripts/backlog-refresh-readings.sh"
[ -f "$REFRESH" ] || exit 0

# ── Чтение: сверка без записи ─────────────────────────────────────────────────
if [ "$TOOL" = "Read" ]; then
    STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
    SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "nosid"' 2>/dev/null)
    mkdir -p "$STATE" 2>/dev/null
    # Журнал устаревших чтений пишет сам пересчётчик: у него есть и файл, и мир, а разбор
    # человеческого вывода здесь был бы признаком, стоящим на форме чужого текста.
    OUT=$(STALE_JOURNAL="$STATE/backlog-stale-read-${SID}.jsonl" BACKLOG_FILE="$FILE" CLAUDSOUL_REPO="$ROOT" \
          bash "$REFRESH" --check 2>/dev/null); RC=$?
    [ "$RC" -eq 1 ] || exit 0
    MSG="📐 Показание в прочитанном BACKLOG.md устарело — решать по миру, а не по файлу:
${OUT}

Файл пересчитает граница хода (Stop); чтение устаревшего показания посчитано (замер stale-reads)."
    jq -cn --arg m "$MSG" '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$m}}' 2>/dev/null || true
    exit 0
fi

# ── Запись: пересчёт ──────────────────────────────────────────────────────────
OUT=$(BACKLOG_FILE="$FILE" CLAUDSOUL_REPO="$ROOT" bash "$REFRESH" run 2>/dev/null | head -5)
case "$OUT" in
    *"показаний обновлено"*) ;;
    *) exit 0 ;;
esac

MSG="📐 Бэклог изменился — показания пересчитаны по объявленным командам:
${OUT}

Показание пункта считается заново при каждом изменении файла, а не помнится: число,
вписанное рукой, устаревает в ту же секунду, а условие возврата ссылается именно на него."
jq -cn --arg m "$MSG" '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$m}}' 2>/dev/null || true
exit 0
