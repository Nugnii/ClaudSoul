#!/usr/bin/env bash
# backlog-reading-refresh.sh — PostToolUse: показания бэклога пересчитаны по правке и сверены при чтении.
# en: PostToolUse on backlog writes and reads — item readings are recomputed on write and checked against the world on read.
#
# Результат: показание открытого пункта, прочитанное агентом, совпадает с выводом своей
#            команды, а каждое чтение устаревшего показания посчитано
# Проверка результата: bash hooks/tests/test_backlog_reading_refresh.sh даёт 0
#
# Повод — поправка владельца 30 августа 2026, дословно: «накопления должны обновляться у
# пунктов бэклога каждый раз, когда туда что-то добавляется или удаляется». Замер того же
# часа: D206 утверждал «накоплено 13 записей исходов», фактически 19 — расхождение прожило
# два часа и нашлось вопросом собеседника, а не механизмом. Хуже того, условие возврата
# пункта ссылается ИМЕННО на это число («открыт, пока нет ≥20»): решение о закрытии
# принималось бы по устаревшей величине.
#
# ТРИ СОБЫТИЯ ОДНОГО ПРЕДМЕТА (D210). Пересчёт по правке файла оказался недостаточен:
# 30 августа 2026 в 01:14 показание устарело через 50 минут после его введения — журнал
# исходов рос каждым ходом, а бэклог не трогали. Предмет утверждения — мир, а не файл,
# поэтому теперь:
#   · правка BACKLOG.md (Write|Edit|MultiEdit) — пересчёт, как прежде;
#   · чтение BACKLOG.md (Read) — сверка с миром БЕЗ записи: расхождение уходит в
#     `state/backlog-stale-read-<SID>.jsonl` (это и есть величина «сколько раз показание
#     прочитано устаревшим», замер `stale-reads`) и в контекст — свежие значения, чтобы
#     решение принималось по миру, а не по файлу;
#   · граница хода (Stop) — пересчёт из `hooks/session-collector.sh` после архиватора,
#     последовательно с ним: два писателя одного файла на одном событии без порядка —
#     гонка, и пересчёт встал за архиватором, а не отдельной регистрацией.
#
# ПОЧЕМУ ПЕРЕСЧЁТ, А НЕ НАПОМИНАНИЕ. Действие однозначное — выполнить объявленную самим
# пунктом команду и подставить её вывод; спорных случаев нет. Напоминание же, по замеру
# 28 августа 2026, читается и не меняет действий.
#
# ПОТОЛОК, названный честно: чтение через Bash (`cat`, `sed -n`) хук не видит — как и
# `partial-read-guard`; чтение владельцем в редакторе тоже. Их покрывает пересчёт на Stop.
#
# КОНТРПРИМЕР: пункт без строки `**Показание.**` не трогается — у части пунктов показание
# есть суждение, а не число, и требовать от них команду значило бы врать точностью.
# Закрытые пункты не трогаются тоже: их показание — свидетельство на момент закрытия.
# Свежее показание при чтении — тишина: страж не становится фоном на здоровой работе.
#
# Input  (stdin): {session_id, tool_name, tool_input:{file_path}} (PostToolUse JSON)
# Output (stdout): {hookSpecificOutput:{additionalContext}} — что пересчитано / что устарело, либо пусто
# Exit:  always 0 (degrade gracefully).
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
case "$TOOL" in Write|Edit|MultiEdit|Read|Bash) ;; *) exit 0 ;; esac
FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)

PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/paths-lib.sh}"
[ -f "$PATHS_LIB" ] || PATHS_LIB="$HOME/.claude/hooks/paths-lib.sh"
# shellcheck source=/dev/null
[ -f "$PATHS_LIB" ] && . "$PATHS_LIB"
# file_mtime живёт в portable-lib, а не в paths-lib: без неё проверка «файл изменился»
# молча уходила в запасную ветку и признак рода J не держался вовсе (тест ловил это как
# «пересчётчик зван на упоминании»). GNU и BSD `stat` несовместимы — своей копии здесь нет.
PORTABLE_LIB="${PORTABLE_LIB:-$(dirname "$PATHS_LIB")/portable-lib.sh}"
# shellcheck source=/dev/null
[ -f "$PORTABLE_LIB" ] && . "$PORTABLE_LIB"

# РОД J, починен 6 сентября 2026. Предмет хука — ПРАВКА бэклога, а регистрация была снята с
# ИМЕНИ файлового инструмента. Замер по корпусу 209 расшифровок: правок BACKLOG.md — 233, из
# них через оболочку (heredoc, python3 -, sed) — 50, то есть 21,5%. На них хук не вызывался
# ни разу, и его молчание было неотличимо от «пересчитывать нечего».
#
# У Bash-вызова цели правки в payload нет и быть не может: команда произвольна. Поэтому
# предмет опознаётся не разбором команды, а МИРОМ — файл новее отметки последнего пересчёта.
# Это правило, а не перечень форм записи: `>>`, `sed -i`, `pathlib.write_text` и всякая
# будущая форма покрыты одинаково, потому что все они меняют mtime.
if [ "$TOOL" = "Bash" ]; then
    # Дешёвый предфильтр: без упоминания бэклога команда не может его править. Он экономит
    # stat на каждой Bash-команде сессии и НЕ является признаком — признак ниже, по mtime.
    CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
    case "$CMD" in *BACKLOG*) ;; *) exit 0 ;; esac
    # Бэклог, который могла тронуть команда, — бэклог ПРОЕКТА СЕССИИ, и берётся он подъёмом
    # от cwd, как у соседа (`session-collector.sh:533-540`). Прежде здесь стояла константа
    # ClaudSoul, и это проверено вызовом 11 сентября 2026: сессия в чужом проекте правила
    # СВОЙ BACKLOG.md, а хук пересчитывал показания бэклога ClaudSoul и объявлял ходу
    # «бэклог изменился» — то есть писал в файл, которого сессия не касалась, и врал о том,
    # что изменилось. Откат на ClaudSoul остаётся для сессии без своего носителя.
    _cwd=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
    _proj=""
    [ -n "$_cwd" ] && command -v find_project_root >/dev/null 2>&1 && _proj=$(find_project_root "$_cwd")
    if [ -n "$_proj" ] && [ -f "$_proj/BACKLOG.md" ]; then
        FILE="$_proj/BACKLOG.md"
    else
        FILE="${BRR_TRUSTED_ROOT:-${CLAUDSOUL_ROOT:-$HOME/My Project/ClaudSoul}}/BACKLOG.md"
    fi
fi

case "$(basename "${FILE:-}")" in BACKLOG.md) ;; *) exit 0 ;; esac
[ -f "$FILE" ] || exit 0

# Скрипт ищется рядом с репозиторием ЭТОГО бэклога: пункт может жить в инициированном
# проекте, и обновлять его показания обязан его же инструмент.
ROOT=$(cd "$(dirname "$FILE")" 2>/dev/null && pwd) || exit 0
REFRESH="$ROOT/scripts/backlog-refresh-readings.sh"
[ -f "$REFRESH" ] || exit 0

# ГРАНИЦА ДОВЕРИЯ (D244, брат корня). Путь сюда приходит из `tool_input.file_path`, то есть
# из входа сессии: достаточно прочитать BACKLOG.md в чужом склонированном репозитории.
# Дальше исполняется ДВАЖДЫ чужое: сам `$REFRESH` (`bash "$REFRESH"`) и команды «Показаний»
# внутри него (`bash -c`, scripts/backlog-refresh-readings.sh:102). Прежняя защита была
# совпадением, а не решением: чужой репозиторий обычно не содержит нашего скрипта —
# но если содержит, исполнится именно его копия.
# Замер 1 сентября 2026 перед правкой: из трёх проектов с BACKLOG.md скрипт есть только у
# ClaudSoul, то есть строгая граница не отнимает ни одного живого случая.
# НАЗВАННЫЙ ПРЕДЕЛ: инициированный проект, который однажды получит свой пересчётчик,
# перестанет обновлять показания молча. Условие снятия — явное доверие проекту
# (переменная BRR_TRUSTED_ROOT либо реестр своих проектов), а не наличие файла у него.
TRUSTED_ROOT="${BRR_TRUSTED_ROOT:-${CLAUDSOUL_ROOT:-$HOME/My Project/ClaudSoul}}"
[ "$ROOT" = "$TRUSTED_ROOT" ] || exit 0

# ── Чтение: сверка без записи ─────────────────────────────────────────────────
# Чтение из оболочки — 89,4% всех чтений бэклога (замер по корпусу: 565 чтений, инструментом
# Read лишь 60). Признак чтения НЕ перечисляет команды (`cat|grep|sed|…`) — такой перечень
# неполон по построению. Он инвертирован: команда упомянула бэклог и НЕ изменила его, значит
# читала. Форма чтения при этом безразлична, включая ещё не придуманные.
# Признак изменения — контрольная сумма содержимого, а не mtime. Секунды его не различают:
# правка и проверка в одну секунду давали «файл не менялся», и правка уходила в сверку
# вместо пересчёта (тест ловил это стабильно, 3 прогона из 3). `cksum` есть в POSIX, то есть
# и на BSD, и на GNU — своей копии и ветвлений по системе не нужно.
_bl_sum() { cksum < "$1" 2>/dev/null | awk '{print $1 "-" $2}'; }
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
mkdir -p "$STATE" 2>/dev/null
STAMP="$STATE/backlog-reading-refresh.sum"
NOW_SUM=$(_bl_sum "$FILE")
PREV_SUM=$(cat "$STAMP" 2>/dev/null || printf '')

IS_READ=0
[ "$TOOL" = "Read" ] && IS_READ=1
# Bash-команда, упомянувшая бэклог и не изменившая его, — читала его.
[ "$TOOL" = "Bash" ] && [ -n "$PREV_SUM" ] && [ "$NOW_SUM" = "$PREV_SUM" ] && IS_READ=1

if [ "$IS_READ" = "1" ]; then
    SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "nosid"' 2>/dev/null)
    # Журнал устаревших чтений пишет сам пересчётчик: у него есть и файл, и мир, а разбор
    # человеческого вывода здесь был бы признаком, стоящим на форме чужого текста.
    OUT=$(STALE_JOURNAL="$STATE/backlog-stale-read-${SID}.jsonl" BACKLOG_FILE="$FILE" CLAUDSOUL_REPO="$ROOT" \
          bash "$REFRESH" --check 2>/dev/null); RC=$?
    [ "$RC" -eq 1 ] || exit 0
    MSG="📐 Показание в прочитанном BACKLOG.md устарело — решать по миру, а не по файлу:
${OUT}

Файл пересчитает граница хода (Stop); чтение устаревшего показания посчитано (замер stale-reads)."
    jq -cn --arg m "$MSG" '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$m}}' 2>/dev/null || true
    exit 0
fi

# ── Запись: пересчёт ──────────────────────────────────────────────────────────
# У Bash упоминание бэклога в команде ещё не значит правку (`grep BACKLOG.md`, `cat`,
# сообщение коммита). Спрашиваем мир: изменился ли файл с прошлого пересчёта. У файловых
# инструментов правка уже состоялась по построению, отметка только обновляется.
# Сюда доходят только изменившие файл: неизменившие ушли в ветку чтения выше.

OUT=$(BACKLOG_FILE="$FILE" CLAUDSOUL_REPO="$ROOT" bash "$REFRESH" run 2>/dev/null | head -5)

# Отметка пишется ПОСЛЕ пересчёта, и это не порядок ради порядка. Пересчёт САМ меняет файл:
# записанная до него отметка оказывается старше нового mtime, и следующий вызов срабатывает
# вхолостую на собственном следе. Вдобавок mtime считается в секундах — при отметке «до»
# исход зависел от того, попали ли правка и проверка в одну секунду, и тест давал то 39/1,
# то 40/0 на одном и том же коде.
printf '%s' "$(_bl_sum "$FILE")" > "$STAMP" 2>/dev/null || true
case "$OUT" in
    *"показаний обновлено"*) ;;
    *) exit 0 ;;
esac

MSG="📐 Бэклог изменился — показания пересчитаны по объявленным командам:
${OUT}

Показание пункта считается заново при каждом изменении файла, а не помнится: число,
вписанное рукой, устаревает в ту же секунду, а условие возврата ссылается именно на него."
jq -cn --arg m "$MSG" '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$m}}' 2>/dev/null || true
exit 0
