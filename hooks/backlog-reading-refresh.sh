#!/usr/bin/env bash
# backlog-reading-refresh.sh — PostToolUse: показания бэклога пересчитаны по правке и сверены при чтении.
# en: PostToolUse on backlog writes and reads — item readings are recomputed on write and checked against the world on read.
#
# Результат: показание открытого пункта сверяется с выводом своей команды при чтении и
#            пересчитывается по правке, не держа ход: прогон идёт фоном, его итог приходит в том
#            же вызове (если уложился в секунду) либо на следующем касании; чтение устаревшего
#            показания посчитано
# Проверка результата: bash hooks/tests/test_backlog_reading_refresh.sh даёт 0
#
# Повод — поправка владельца 30 августа 2026, дословно: «накопления должны обновляться у
# пунктов бэклога каждый раз, когда туда что-то добавляется или удаляется». Замер того же
# часа: D206 утверждал «накоплено 13 записей исходов», фактически 19 — расхождение прожило
# два часа и нашлось вопросом собеседника, а не механизмом. Хуже того, условие возврата
# пункта ссылается ИМЕННО на это число («открыт, пока нет ≥20»): решение о закрытии
# принималось бы по устаревшей величине.
#
# ТРИ СОБЫТИЯ ОДНОГО ПРЕДМЕТА (D210). Пересчёт по правке файла оказался недостаточен:
# 30 августа 2026 в 01:14 показание устарело через 50 минут после его введения — журнал
# исходов рос каждым ходом, а бэклог не трогали. Предмет утверждения — мир, а не файл,
# поэтому теперь:
#   · правка BACKLOG.md (Write|Edit|MultiEdit) — пересчёт, как прежде;
#   · чтение BACKLOG.md (Read) — сверка с миром БЕЗ записи: расхождение уходит в
#     `state/backlog-stale-read-<SID>.jsonl` (это и есть величина «сколько раз показание
#     прочитано устаревшим», замер `stale-reads`) и в контекст — свежие значения, чтобы
#     решение принималось по миру, а не по файлу (в том же вызове, если сверка уложилась в
#     секунду, иначе на следующем касании бэклога — D1014, ниже);
#   · граница хода (Stop) — пересчёт из `hooks/session-collector.sh` после архиватора,
#     последовательно с ним: два писателя одного файла на одном событии без порядка —
#     гонка, и пересчёт встал за архиватором, а не отдельной регистрацией.
#
# ПОЧЕМУ ПЕРЕСЧЁТ, А НЕ НАПОМИНАНИЕ. Действие однозначное — выполнить объявленную самим
# пунктом команду и подставить её вывод; спорных случаев нет. Напоминание же, по замеру
# 28 августа 2026, читается и не меняет действий.
#
# ПОТОЛОК, названный честно: чтение через Bash (`cat`, `sed -n`) хук не видит — как и
# `partial-read-guard`; чтение владельцем в редакторе тоже. Их покрывает пересчёт на Stop.
#
# КОНТРПРИМЕР: пункт без строки `**Показание.**` не трогается — у части пунктов показание
# есть суждение, а не число, и требовать от них команду значило бы врать точностью.
# Закрытые пункты не трогаются тоже: их показание — свидетельство на момент закрытия.
# Свежее показание при чтении — тишина: страж не становится фоном на здоровой работе.
#
# Input  (stdin): {session_id, tool_name, tool_input:{file_path}} (PostToolUse JSON)
# Output (stdout): {hookSpecificOutput:{additionalContext}} — итог прогона (что пересчитано / что устарело):
#                  свой, если прогон уложился в секунду, иначе прошлый фоновый; либо пусто
# Exit:  always 0 (degrade gracefully).
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
case "$TOOL" in Write|Edit|MultiEdit|Read|Bash) ;; *) exit 0 ;; esac
FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)

PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/paths-lib.sh}"
[ -f "$PATHS_LIB" ] || PATHS_LIB="$HOME/.claude/hooks/paths-lib.sh"
# shellcheck source=/dev/null
[ -f "$PATHS_LIB" ] && . "$PATHS_LIB"
# file_mtime живёт в portable-lib, а не в paths-lib: без неё проверка «файл изменился»
# молча уходила в запасную ветку и признак рода J не держался вовсе (тест ловил это как
# «пересчётчик зван на упоминании»). GNU и BSD `stat` несовместимы — своей копии здесь нет.
PORTABLE_LIB="${PORTABLE_LIB:-$(dirname "$PATHS_LIB")/portable-lib.sh}"
# shellcheck source=/dev/null
[ -f "$PORTABLE_LIB" ] && . "$PORTABLE_LIB"

# РОД J, починен 6 сентября 2026. Предмет хука — ПРАВКА бэклога, а регистрация была снята с
# ИМЕНИ файлового инструмента. Замер по корпусу 209 расшифровок: правок BACKLOG.md — 233, из
# них через оболочку (heredoc, python3 -, sed) — 50, то есть 21,5%. На них хук не вызывался
# ни разу, и его молчание было неотличимо от «пересчитывать нечего».
#
# У Bash-вызова цели правки в payload нет и быть не может: команда произвольна. Поэтому
# предмет опознаётся не разбором команды, а МИРОМ — файл новее отметки последнего пересчёта.
# Это правило, а не перечень форм записи: `>>`, `sed -i`, `pathlib.write_text` и всякая
# будущая форма покрыты одинаково, потому что все они меняют mtime.
if [ "$TOOL" = "Bash" ]; then
    # Дешёвый предфильтр: без упоминания бэклога команда не может его править. Он экономит
    # stat на каждой Bash-команде сессии и НЕ является признаком — признак ниже, по mtime.
    CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
    case "$CMD" in *BACKLOG*) ;; *) exit 0 ;; esac
    # Бэклог, который могла тронуть команда, — бэклог ПРОЕКТА СЕССИИ, и берётся он подъёмом
    # от cwd, как у соседа (`session-collector.sh:539-540`). Прежде здесь стояла константа
    # ClaudSoul, и это проверено вызовом 11 сентября 2026: сессия в чужом проекте правила
    # СВОЙ BACKLOG.md, а хук пересчитывал показания бэклога ClaudSoul и объявлял ходу
    # «бэклог изменился» — то есть писал в файл, которого сессия не касалась, и врал о том,
    # что изменилось. Откат на ClaudSoul остаётся для сессии без своего носителя.
    _cwd=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
    _proj=""
    [ -n "$_cwd" ] && command -v find_project_root >/dev/null 2>&1 && _proj=$(find_project_root "$_cwd")
    if [ -n "$_proj" ] && [ -f "$_proj/BACKLOG.md" ]; then
        FILE="$_proj/BACKLOG.md"
    else
        FILE="${BRR_TRUSTED_ROOT:-${CLAUDSOUL_ROOT:-$HOME/My Project/ClaudSoul}}/BACKLOG.md"
    fi
fi

case "$(basename "${FILE:-}")" in BACKLOG.md) ;; *) exit 0 ;; esac
[ -f "$FILE" ] || exit 0

# Скрипт ищется рядом с репозиторием ЭТОГО бэклога: пункт может жить в инициированном
# проекте, и обновлять его показания обязан его же инструмент.
ROOT=$(cd "$(dirname "$FILE")" 2>/dev/null && pwd) || exit 0
REFRESH="$ROOT/scripts/backlog-refresh-readings.sh"
[ -f "$REFRESH" ] || exit 0

# ГРАНИЦА ДОВЕРИЯ (D244, брат корня). Путь сюда приходит из `tool_input.file_path`, то есть
# из входа сессии: достаточно прочитать BACKLOG.md в чужом склонированном репозитории.
# Дальше исполняется ДВАЖДЫ чужое: сам `$REFRESH` (`bash "$REFRESH"`) и команды «Показаний»
# внутри него (`bash -c`, scripts/backlog-refresh-readings.sh:125). Прежняя защита была
# совпадением, а не решением: чужой репозиторий обычно не содержит нашего скрипта —
# но если содержит, исполнится именно его копия.
# Замер 1 сентября 2026 перед правкой: из трёх проектов с BACKLOG.md скрипт есть только у
# ClaudSoul, то есть строгая граница не отнимает ни одного живого случая.
# НАЗВАННЫЙ ПРЕДЕЛ: инициированный проект, который однажды получит свой пересчётчик,
# перестанет обновлять показания молча. Условие снятия — явное доверие проекту
# (переменная BRR_TRUSTED_ROOT либо реестр своих проектов), а не наличие файла у него.
TRUSTED_ROOT="${BRR_TRUSTED_ROOT:-${CLAUDSOUL_ROOT:-$HOME/My Project/ClaudSoul}}"
[ "$ROOT" = "$TRUSTED_ROOT" ] || exit 0

# ── Чтение: сверка без записи ─────────────────────────────────────────────────
# Чтение из оболочки — 89,4% всех чтений бэклога (замер по корпусу: 565 чтений, инструментом
# Read лишь 60). Признак чтения НЕ перечисляет команды (`cat|grep|sed|…`) — такой перечень
# неполон по построению. Он инвертирован: команда упомянула бэклог и НЕ изменила его, значит
# читала. Форма чтения при этом безразлична, включая ещё не придуманные.
# Признак изменения — контрольная сумма содержимого, а не mtime. Секунды его не различают:
# правка и проверка в одну секунду давали «файл не менялся», и правка уходила в сверку
# вместо пересчёта (тест ловил это стабильно, 3 прогона из 3). `cksum` есть в POSIX, то есть
# и на BSD, и на GNU — своей копии и ветвлений по системе не нужно.
_bl_sum() { cksum < "$1" 2>/dev/null | awk '{print $1 "-" $2}'; }
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
STAMP="$STATE/backlog-reading-refresh.sum"
# БЭКЛОГ ВО ВРЕМЕННОЙ ПАПКЕ — ФИКСТУРА ТЕСТА: её отметка не идёт в ЖИВОЙ каталог по умолчанию (D1011, 20 октября
# 2026), а ложится во временную папку ключом по сумме пути — фикстуры соседних тестов одну отметку не делят.
# Сверяется сам каталог, а не пустота STATE_DIR: `paths-lib.sh:79` присваивает его по умолчанию, и «не задан»
# после подключения библиотеки неотличим — первая редакция так и не срабатывала. Временный ли путь, решает
# владелец перечня корней `rc_path_is_private` (`root-cause-lib.sh`, D1013); зовётся в подоболочке, чтобы
# библиотека не переназначила здешние STATE_LOCK_LIB и INPUT_LIB. Владельца не достать ни рядом, ни в установке —
# путь считается ЖИВЫМ, как до D1011 (вторая редакция по финальному скептику D1013): хук ставится вместе с
# библиотекой, и пробных копий хука без неё в дереве нет, поэтому недостижимый владелец здесь — частичный перенос,
# и «частный» молча увёл бы живую отметку и журнал устаревших чтений во временную папку, где их не видит замер
# `scripts/backlog-stale-reads.sh`. У трёх скриптов-носителей направление обратное: их копии без библиотеки есть.
# Цена вызова владельца — около 20 мс на касание бэклога (замер скептика: медиана 38 → 57 мс).
# Названный предел: сверка строкой, и живой путь в ненормализованной записи (`hooks//state`, `/./`) правило не
# включит — питоновые носители нормализуют; в дереве такой STATE_DIR не строит никто. Отвод — в TMPDIR, а если
# он задан и непригоден — в /tmp: пустой отвод целил бы в корень диска (финальный скептик D1011).
if [ "${STATE%/}" = "$HOME/.claude/hooks/state" ]; then
    _rc_lib="$(dirname "$PATHS_LIB")/root-cause-lib.sh"
    [ -f "$_rc_lib" ] || _rc_lib="$HOME/.claude/hooks/root-cause-lib.sh"
    if ( . "$_rc_lib" 2>/dev/null; command -v rc_path_is_private >/dev/null 2>&1 || exit 1; rc_path_is_private "$FILE" ); then
        STATE=$(cd "${TMPDIR:-/tmp}" 2>/dev/null && pwd -P) || STATE=$(cd /tmp && pwd -P)
        STAMP="$STATE/backlog-reading-refresh-$(printf '%s' "$FILE" | cksum | awk '{print $1}').sum"
    fi
fi
mkdir -p "$STATE" 2>/dev/null
NOW_SUM=$(_bl_sum "$FILE")
PREV_SUM=$(cat "$STAMP" 2>/dev/null || printf '')

IS_READ=0
[ "$TOOL" = "Read" ] && IS_READ=1
# Bash-команда, упомянувшая бэклог и не изменившая его, — читала его.
[ "$TOOL" = "Bash" ] && [ -n "$PREV_SUM" ] && [ "$NOW_SUM" = "$PREV_SUM" ] && IS_READ=1
# Пока идёт фоновый пересчёт, отметка старая: команда, прочитавшая тот самый текст, что он сейчас
# обрабатывает, — чтение, а не правка (финальный скептик D1014: иначе каждое такое чтение ставило
# повтор полного пересчёта и само не сверялось). Сумму обрабатываемого кладёт прогон в свой замок.
# Верится сумме только ЖИВОГО владельца: замок прогона, убитого посреди пересчёта (выход из системы),
# лежит с суммой дальше, и правка не пересчиталась бы ни одним Bash-касанием (скептик, третий круг).
[ "$TOOL" = "Bash" ] && [ "$IS_READ" = 0 ] && [ -n "$NOW_SUM" ] \
    && [ "$NOW_SUM" = "$(cat "${STAMP%.sum}-run.lock/sum" 2>/dev/null)" ] \
    && kill -0 "$(awk 'NR == 1 { print $1 }' "${STAMP%.sum}-run.lock/owner" 2>/dev/null)" 2>/dev/null && IS_READ=1

SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "nosid"' 2>/dev/null)
# Сверка при чтении: печатает текст сообщения либо ничего; код 2 — сверщик сломался, а не «чисто»
# (три состояния прибора: сломанная сверка не вправе отменять недоставленное «устарело»).
_brr_check() {
    local out rc
    # Журнал устаревших чтений пишет сам пересчётчик: у него есть и файл, и мир, а разбор
    # человеческого вывода здесь был бы признаком, стоящим на форме чужого текста.
    out=$(STALE_JOURNAL="$STATE/backlog-stale-read-${SID}.jsonl" BACKLOG_FILE="$FILE" CLAUDSOUL_REPO="$ROOT" \
          bash "$REFRESH" --check 2>/dev/null); rc=$?
    [ "$rc" -ge 2 ] && return 2
    [ "$rc" -eq 1 ] || return 0
    printf '%s' "📐 Показание в прочитанном BACKLOG.md устарело — решать по миру, а не по файлу:
${out}

Файл пересчитает граница хода (Stop); чтение устаревшего показания посчитано (замер stale-reads)."
}

# ── Запись: пересчёт ──────────────────────────────────────────────────────────
# У Bash упоминание бэклога в команде ещё не значит правку (`grep BACKLOG.md`, `cat`,
# сообщение коммита). Спрашиваем мир: изменился ли файл с прошлого пересчёта. У файловых
# инструментов правка уже состоялась по построению, отметка только обновляется.
# Сюда доходят только изменившие файл: неизменившие ушли в ветку чтения выше.

_brr_run() {  # пересчёт по правке: печатает текст сообщения либо ничего
    local out rc s0
    s0=$(_bl_sum "$FILE")
    out=$(BACKLOG_FILE="$FILE" CLAUDSOUL_REPO="$ROOT" bash "$REFRESH" run 2>/dev/null); rc=$?
    out=$(printf '%s\n' "$out" | head -5)
    # КОД 3 ПЕРЕСЧЁТЧИКА — «ФАЙЛ ИЗМЕНИЛСЯ ЗА ВРЕМЯ ПЕРЕСЧЁТА» (D1000, 17 октября 2026). Пересчёт идёт
    # секундами, а то и минутами (команды показаний, до 120 с каждая), и за это время бэклог правят
    # агент следующего хода, параллельная сессия или архиватор сборщика; пересчётчик тогда не пишет
    # НИЧЕГО (иначе затёр бы правку), и показания остались прежними. До этой ветки код терялся в
    # `| head`, а тишина хука читалась как «свежо»: «пересчитывать нечего» и «пересчёт отменён» шли
    # одним каналом — молчанием. Отметка при этом НЕ ставится: файл теперь отличается от последней
    # отметки, и следующая Bash-команда о бэклоге пойдёт в пересчёт, а не в сверку; правка Write/Edit
    # идёт в пересчёт всегда.
    if [ "$rc" -eq 3 ]; then
        printf '%s' "📐 Показания НЕ пересчитаны: BACKLOG.md изменился за время пересчёта, запись отменена, чтобы не затереть эту правку. Значения в «Последнее показание» могут быть устаревшими до следующей правки бэклога либо очередного пересчёта на границе хода."
        return 3
    fi
    # Отметка пишется ПОСЛЕ пересчёта, и это не порядок ради порядка. Пересчёт САМ меняет файл:
    # записанная до него отметка оказывается старше нового mtime, и следующий вызов срабатывает
    # вхолостую на собственном следе. Вдобавок mtime считается в секундах — при отметке «до»
    # исход зависел от того, попали ли правка и проверка в одну секунду, и тест давал то 39/1,
    # то 40/0 на одном и том же коде.
    # Отметка — сумма того, что прогон ОБРАБОТАЛ, а не того, что лежит после него. Пересчёт, которому
    # менять было нечего, файла не пишет и о правке, внесённой за время прогона, не знает: сумма «после»
    # накрыла бы её, и следующая команда о бэклоге ушла бы в сверку вместо пересчёта (финальный скептик
    # D1014). Записавший пересчёт сверил файл перед записью (код 3 выше), и сумма «после» — его запись;
    # названный предел: правка, легшая между его записью и этой строкой (десятки миллисекунд), отметкой
    # накрывается — так было и до фона.
    case "$out" in
        *"показаний обновлено"*) printf '%s' "$(_bl_sum "$FILE")" > "$STAMP" 2>/dev/null || true ;;
        *) printf '%s' "$s0" > "$STAMP" 2>/dev/null || true; return 1 ;;   # код 1 — менять было нечего
    esac
    printf '%s' "📐 Бэклог изменился — показания пересчитаны по объявленным командам:
${out}

Показание пункта считается заново при каждом изменении файла, а не помнится: число,
вписанное рукой, устаревает в ту же секунду, а условие возврата ссылается именно на него."
}

_brr_say() { [ -n "$1" ] || return 0; jq -cn --arg m "$1" '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$m}}' 2>/dev/null || true; }

LANE=run; [ "$IS_READ" = "1" ] && LANE=check
[ -n "${BRR_JOB:-}" ] && LANE="$BRR_JOB"
# Режим прогона — дело этого процесса, а не его потомков: команда показания, сама зовущая хук (тест,
# проба), иначе вошла бы в режим прогона с чужой полосой (скептик, третий круг).
export -n BRR_JOB 2>/dev/null
# СВЕРКА И ПЕРЕСЧЁТ ИДУТ ФОНОМ (D1014, 20 октября 2026). Ход ждал хук, пока исполнялись ВСЕ команды
# показаний: показание D408 читает корпус расшифровок (22,8 с на дереве), и в живой сессии одно касание
# бэклога держало ход 67–239 с — на каждом чтении, правке и команде со словом BACKLOG. Теперь касание
# запускает прогон ОТДЕЛЬНЫМ процессом этого же файла (`BRR_JOB=<полоса>`) в своей группе (`set -m`) и
# ждёт его не дольше секунды: быстрый итог приходит в том же вызове, долгий — на следующем касании
# бэклога; итог старше 30 минут отбрасывается как сказанный о прошлом мире.
# ВЗАИМОИСКЛЮЧЕНИЕ — У ВЛАДЕЛЬЦА, `hooks/state-lock-lib.sh` (замок `<ключ>-<полоса>.lock`): живость по PID
# владельца, а не по возрасту, атомарный срыв брошенного, снятие только своего (D500). Отдельный процесс
# нужен ровно для этого: замок судит живость по PID, а у подоболочки в bash 3.2 своего `$$` нет. Первые
# два круга финального скептика D1014 ловили в самописной занятости то, что библиотека решила раньше:
# срыв живого прогона по возрасту, неатомарный срыв, снятие чужой. Замок полосы — НЕ замок файла:
# единица «файл» договора `.claude-docs/modules/state-lock.md` касается правки файла, а здесь
# сериализуются прогоны; запись BACKLOG.md сериализует замок самого пересчётчика на этом файле.
# В полёте не больше одного прогона на полосу (сверка, пересчёт) — фон без этого прятал бы цену, а не
# снимал её. Касание при занятой полосе ставит отметку повтора: держатель публикует итог витка и идёт на
# новый виток по свежему файлу, а после снятия замка смотрит отметку ещё раз. Правка во время пересчёта
# поэтому не остаётся без пересчёта — граница хода пересчитывает лишь раз в 20 ходов
# (`session-collector.sh`, `BACKLOG_READINGS_EVERY_TURNS`).
# Названные пределы: итог видит та сессия, что коснётся бэклога первой, — каталог состояния общий;
# чтения во время идущей сверки сливаются в один её повтор, и журнал stale-reads считает сверки, нашедшие
# устаревшее, а не каждое такое чтение; прогон, один виток которого дольше потолка библиотеки (десять
# порогов `CLAUDSOUL_LOCK_STALE_S`, 300 с), либо машина, уснувшая посреди витка дольше потолка, отдают
# полосу второму прогону — запись файла сериализует замок самого пересчётчика.
# BRR_FOREGROUND=1 — прежнее исполнение в вызове хука: им ноги свидетеля судят СОДЕРЖАНИЕ прогона.
STATE_LOCK_LIB="${STATE_LOCK_LIB:-$(dirname "$PATHS_LIB")/state-lock-lib.sh}"
# Без библиотеки замка держать фон нечем — тогда прежнее исполнение в вызове, а не фон без взаимоисключения.
[ -f "$STATE_LOCK_LIB" ] || BRR_FOREGROUND=1
if [ -n "${BRR_FOREGROUND:-}" ]; then
    if [ "$LANE" = check ]; then _brr_say "$(_brr_check)"; else _brr_say "$(_brr_run)"; fi
    exit 0
fi
# Имена выводятся из отметки: у фикстуры D1011 в ней ключ пути, и соседние фикстуры полос не делят.
_key="${STAMP%.sum}"; _lk="$_key-$LANE"; _again="$_key-$LANE.again"
_publish() {  # _publish <полоса> <текст> — итог атомарно; временное имя прогона забирающий не пишет
    printf '%s\n\n(фоновый прогон закончен %s)' "$2" "$(date '+%Y-%m-%d %H:%M')" > "$_key-$1.msg.tmp.$$" 2>/dev/null \
        && mv -f "$_key-$1.msg.tmp.$$" "$_key-$1.msg" 2>/dev/null
}
if [ -n "${BRR_JOB:-}" ]; then
    # shellcheck source=/dev/null
    . "$STATE_LOCK_LIB"
    CLAUDSOUL_LOCK_TRIES=1   # проба, а не ожидание: занятую полосу ждать незачем — отметка повтора
    if ! lock_acquire "$_lk"; then
        : > "$_again" 2>/dev/null
        # Держатель мог снять замок между пробой и отметкой — тогда повтор берёт этот прогон.
        lock_acquire "$_lk" || exit 0
    fi
    while :; do
        rm -f "$_again"
        touch "$_lk.lock/owner" 2>/dev/null   # потолок живого владельца считается от записи owner
        s0=$(_bl_sum "$FILE")
        if [ "$LANE" = check ]; then
            msg=$(_brr_check); crc=$?
            # Файл менялся за время сверки — её вердикт о прошлом тексте: ни «устарело», ни отмены.
            # Сломанный сверщик (код 2) — не «чисто»: недоставленное «устарело» он не отменяет.
            if [ "$crc" -lt 2 ] && [ "$(_bl_sum "$FILE")" = "$s0" ]; then
                if [ -n "$msg" ]; then _publish check "$msg"; else rm -f "$_key-check.msg"; fi
            fi
        else
            printf '%s' "$s0" > "$_lk.lock/sum" 2>/dev/null
            msg=$(_brr_run); rrc=$?
            rm -f "$_lk.lock/sum"
            [ -n "$msg" ] && _publish run "$msg"
            # Файл переписан пересчётом (код 0) — недоставленное «устарело» говорит о другом тексте. Решает
            # код, а не слово: «НЕ пересчитаны» (код 3) содержит то же слово (скептик, третий круг).
            [ "$rrc" = 0 ] && rm -f "$_key-check.msg"
        fi
        [ -e "$_again" ] && continue   # касались во время витка: его итог опубликован, следующий — по свежему файлу
        lock_release "$_lk"
        # Отметка, поставленная между проверкой и снятием, иначе пропала бы: её видят здесь.
        [ -e "$_again" ] && lock_acquire "$_lk" && continue
        break
    done
    exit 0
fi
set -m
BRR_JOB="$LANE" bash "${BASH_SOURCE[0]:-$0}" <<< "$INPUT" >/dev/null 2>&1 &
_jp=$!
set +m
_i=0; while kill -0 "$_jp" 2>/dev/null && [ "$_i" -lt 10 ]; do sleep 0.1; _i=$((_i + 1)); done
_prev=""; _tok="$$.$RANDOM$RANDOM"
for _l in check run; do
    _m="$_key-$_l.msg"
    [ -f "$_m" ] || continue
    if [ -n "$(find "$_m" -mmin +30 2>/dev/null)" ]; then rm -f "$_m"; continue; fi
    mv "$_m" "$_m.take.$_tok" 2>/dev/null || continue   # забрал — значит показывает этот вызов, а не соседний
    _prev="${_prev:+$_prev

}$(cat "$_m.take.$_tok" 2>/dev/null)"
    rm -f "$_m.take.$_tok"
done
_brr_say "$_prev"
exit 0
