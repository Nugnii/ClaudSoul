#!/usr/bin/env bash
# СУДИТ: scripts/root-map.py
# test_root_map.sh — карта корней: дробь берётся из пробы, граф обязан быть деревом.
#
# Результат: расхождение объявленной дроби с посчитанной краснеет; цикл и сироты
#            останавливают печать порядка ремонта; отказ пробы не выдаётся за «ноль»
# Проверка результата: bash hooks/tests/test_root_map.sh даёт 0
#
# Повод, 9 сентября 2026. Второй тест остановки разбора — дробь специфичности — до этого дня
# предъявлялся ФРАЗОЙ: разбор объявил «5 из 5», настоящая была «1 из 65» (D323), и гейт ход
# пропустил, потому что формы доктрины были произнесены все. Признак карты живёт ДАННЫМИ
# (файл пробы), а не кодом прибора — в отличие от реестра родов, где 2345 строк зашитых
# признаков и 21 правка за 12 дней.
#
# ЧТО ЭТОТ ТЕСТ ЛОВИЛ БЫ У СЕБЯ. Первая редакция прибора печатала порядок ремонта и ПОСЛЕ
# этого падала на затенённой переменной — отказ, замаскированный правдоподобным выводом.
# Вторая молча выдавала порядок на графе с циклом. Обе ноги ниже краснеют на тех редакциях.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

# Предмет двух ног ниже — ЖИВАЯ карта корней, а она внутренняя и в публичный снимок не
# входит; сам прибор и шаблон карты входят, поэтому ноги на песочнице остаются предметом.
UNIVERSE_ROOT="$ROOT"; . "$ROOT/hooks/lib/universe-lib.sh" 2>/dev/null || true
partial() { command -v universe_partial_tree >/dev/null 2>&1 && universe_partial_tree; }
TOOL="$ROOT/scripts/root-map.py"
[ -f "$TOOL" ] || { echo "FAIL: нет $TOOL"; exit 1; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL: $1"; }

# Песочница: своя карта, свои пробы. Форма взята из настоящей ROOTS.md.
mk() {  # mk <дробь R1> <держит R1> <держит R2>
    mkdir -p "$TMP/scripts/probes"
    cp "$TOOL" "$TMP/scripts/"
    printf '#!/usr/bin/env bash\nprintf "a.sh:1\\nb.sh:2\\nc.sh:3\\n"\n' > "$TMP/scripts/probes/P1.sh"
    printf '#!/usr/bin/env bash\nprintf "d.sh:4\\n"\n' > "$TMP/scripts/probes/P2.sh"
    cat > "$TMP/ROOTS.md" <<MAP
# ROOTS

## R1 — первый

**Устройство.** проверочный
**Признак.** \`scripts/probes/P1.sh\`
**Дробь.** $1
**Держит.** $2

## R2 — второй

**Устройство.** проверочный
**Признак.** \`scripts/probes/P2.sh\`
**Дробь.** 1 из 1
**Держит.** $3
MAP
}
run() { CLAUDSOUL_REPO="$TMP" python3 "$TMP/scripts/root-map.py" "$@" 2>&1; }
rc()  { CLAUDSOUL_REPO="$TMP" python3 "$TMP/scripts/root-map.py" "$@" >/dev/null 2>&1; echo $?; }

# --- T1: дробь сходится с пробой → зелено ---
mk "2 из 3" "R2" ""
grep -q 'дробь сходится: 2 из 3' <<< "$(run)" && ok || bad "T1: верная дробь не признана"
[ "$(rc --check)" = "0" ] && ok || bad "T1b: --check краснеет на верной карте"
# --- T1c: --declared отдаёт знаменатель объявленной дроби без исполнения проб; чужой корень — код 2 ---
[ "$(run --declared R1)" = "3" ] && ok || bad "T1c: --declared R1 должен печатать 3 (дробь «2 из 3»), получено «$(run --declared R1)»"
[ "$(rc --declared R9)" = "2" ] && ok || bad "T1d: --declared на отсутствующем корне обязан отвечать кодом 2"

# --- T2: объявлено больше, чем нашла проба → красно. Это и есть подмена дроби ---
mk "5 из 5" "R2" ""
grep -q 'РАСХОЖДЕНИЕ' <<< "$(run)" && ok || bad "T2: подмена дроби («5 из 5» при трёх местах) не замечена"
[ "$(rc --check)" = "1" ] && ok || bad "T2b: --check не сообщил расхождение кодом"

# --- T3: цикл в графе → порядок НЕ печатается ---
mk "2 из 3" "R2" "R1"
OUT=$(run)
grep -q 'взаимная зависимость' <<< "$OUT" && ok || bad "T3: цикл R1↔R2 не замечен"
grep -q 'ПОРЯДОК РЕМОНТА' <<< "$OUT" && bad "T3b: порядок напечатан при цикле" || ok
[ "$(rc)" = "2" ] && ok || bad "T3c: цикл не сообщён кодом 2"

# --- T4: ссылка на несуществующий корень → красно ---
mk "2 из 3" "R9" ""
grep -q 'ссылка в никуда' <<< "$(run)" && ok || bad "T4: ссылка на отсутствующий корень пропущена"

# --- T5: проба на диске, но ни один корень её не объявляет → сирота ---
mk "2 из 3" "R2" ""
printf '#!/usr/bin/env bash\nprintf "x.sh:1\\n"\n' > "$TMP/scripts/probes/ORPHAN.sh"
grep -q 'проба без корня' <<< "$(run)" && ok || bad "T5: осиротевшая проба не замечена"
rm -f "$TMP/scripts/probes/ORPHAN.sh"

# --- T6: корень объявляет пробу, которой нет → красно ---
mk "2 из 3" "R2" ""
rm -f "$TMP/scripts/probes/P2.sh"
grep -qE 'пробы нет|корень без пробы' <<< "$(run)" && ok || bad "T6: отсутствующая проба выдана за ноль носителей"

# --- T7: проба падает → это НЕ «носителей нет» ---
mk "2 из 3" "R2" ""
printf '#!/usr/bin/env bash\nexit 3\n' > "$TMP/scripts/probes/P2.sh"
grep -q 'НЕ ПОСЧИТАНЫ' <<< "$(run)" && ok || bad "T7: отказ пробы выдан за пустой результат"

# --- T8: прибор доходит до конца, а не падает после печати ---
mk "2 из 3" "R2" ""
OUT=$(run 2>&1)
grep -q 'Traceback' <<< "$OUT" && bad "T8: прибор упал после вывода — отказ под правдоподобным ответом" || ok

# --- T9: прибор ПОДКЛЮЧЁН, а не лежит файлом ---
# Повод: собеседник спросил «карту то ты построил, а механизм к проверке подключил?» —
# и не был подключён: имя прибора встречалось только в комментариях его же проб, в реестре
# замеров ноль. Механизм без потребителя — ровно корень R2 этой же карты.
grep -q 'root-map-drift' "$ROOT/scripts/measurements.tsv" \
    && ok || bad "T9: замер root-map-drift выпал из реестра — прибор снова никем не зовётся"

# --- T7b: подготовка пробы упала → проба ОТКАЗЫВАЕТ, а не молчит (D398, носитель 1) ---
# Повод: `eval "$prep" >/dev/null 2>&1` не проверял код, и упавшая подготовка оставляла
# «дерево как есть» — два состояния совпадали, и проба печатала носителя, которого нет.
# Канал отказа проверяется ТРЕМЯ утверждениями сразу, потому что важен именно он: код 2
# (прибор скажет «НЕ ПОСЧИТАНЫ»), слово в stderr и ПУСТОЙ stdout — непустая строка там
# считается носителем (`scripts/root-map.py:152`), и объяснение выросло бы в крону.
# Таблица подменяется через `R6_CARRIERS_FILE`, команда дешёвая (`true`): предмет ноги —
# канал отказа, а не время прогона.
R6="$ROOT/scripts/probes/R6.sh"
if [ -f "$R6" ]; then
    printf 'падает|проверочный носитель|exit 7|exit 0|true\n' > "$TMP/carriers-bad.tsv"
    OUT7B=$(R6_CARRIERS_FILE="$TMP/carriers-bad.tsv" bash "$R6" 2>"$TMP/err7b"); RC7B=$?
    [ "$RC7B" = "2" ] && ok || bad "T7b: упавшая подготовка не дала кода 2 (rc=$RC7B)"
    grep -q 'ОТКАЗ' "$TMP/err7b" && ok || bad "T7b2: отказ подготовки не назван в stderr"
    [ -z "$OUT7B" ] && ok || bad "T7b3: отказ утёк в stdout — прибор счёл бы его носителем: '$OUT7B'"
    # T7b4: подготовка, которая ничего не меняет, — ЗАКОННА. Между 19 и 20 сентября 2026
    # здесь стоял обратный смысл: общий «сторож действия» считал такую подготовку отказом.
    # Сторож снят по поправке владельца («сверка до и после уже была, и мы от неё ушли»):
    # «что-то изменилось» отвечает не на тот вопрос, и за один вечер этот признак дал два
    # ложных ответа на двух системах. Отказ подготовки теперь громок В ИСТОЧНИКЕ — см. T7b5.
    printf 'ровный|проверочный носитель|true|true|true\n' > "$TMP/carriers-ok.tsv"
    R6_CARRIERS_FILE="$TMP/carriers-ok.tsv" bash "$R6" >/dev/null 2>&1
    [ $? -le 1 ] && ok || bad "T7b4: исправная подготовка объявлена отказом"
    # T7b5: ПРОМАХНУВШАЯСЯ ТЕКСТОВАЯ ПОДМЕНА — единственный класс, ради которого сторож и
    # заводился: шаблон перестал совпадать, `re.sub` вернул то же, код 0, и проба сравнила
    # бы два одинаковых мира (случай `docs-refresh-claims`, 12 сентября 2026). Теперь такая
    # подготовка отвечает кодом сама, а рамка называет её отказом и НЕ печатает носителя.
    printf 'промах|проверочный носитель|true|python3 -c "import sys;sys.exit(3)"|true\n' > "$TMP/carriers-miss.tsv"
    OUT7B5=$(R6_CARRIERS_FILE="$TMP/carriers-miss.tsv" bash "$R6" 2>"$TMP/err7b5"); RC7B5=$?
    [ "$RC7B5" = "2" ] && ok || bad "T7b5: промахнувшаяся подмена не дала кода 2 (rc=$RC7B5)"
    grep -q 'ненулевой код' "$TMP/err7b5" && ok || bad "T7b5: отказ подготовки не назван в stderr"
    [ -z "$OUT7B5" ] && ok || bad "T7b5: отказ утёк в stdout — прибор счёл бы его носителем: '$OUT7B5'"

    # T7b6: ПАДЕНИЕ НЕ ПОСЛЕДНЕЙ КОМАНДЫ ЦЕПОЧКИ (20 сентября 2026). `eval "a; b"` отдаёт код
    # только последней, поэтому упавшая первая была невидима, а два несобравшихся состояния
    # выходили ОДИНАКОВЫМИ — и проба печатала НОСИТЕЛЯ, которого нет. Замер того дня: из 24
    # подготовок таблицы цепочек 17 (счёт разбором; наивный поиск `;` даёт 18, лишняя —
    # строка, где все `;` внутри `python3 -c`), то есть класс покрывал две трети. Закрыто
    # `set -e` внутри eval — но ОДНОГО его мало, и это замерено 20 сентября 2026 на двух
    # оболочках: пока подоболочка стояла условием `if`, bash 5.2 errexit подавлял, и нога
    # была красной на Linux при зелени на macOS (bash 3.2 подавляет неполно). Держит пара:
    # `set -e` + подоболочка ВНЕ условия (`scripts/probes/R6.sh:209`).
    # Нога судит именно ложного носителя, а не «страж промолчал»:
    # без правки stdout несёт строку, с правкой — пуст, а код 2.
    printf 'цепочка|проверочный носитель|false; printf x > m.txt|printf y > m.txt|cat m.txt\n' > "$TMP/carriers-chain.tsv"
    OUT7B6=$(R6_CARRIERS_FILE="$TMP/carriers-chain.tsv" bash "$R6" 2>"$TMP/err7b6"); RC7B6=$?
    [ "$RC7B6" = "2" ] && ok || bad "T7b6: падение первой команды цепочки не дало кода 2 (rc=$RC7B6)"
    [ -z "$OUT7B6" ] && ok || bad "T7b6: несобравшаяся цепочка напечатала носителя: '$OUT7B6'"

    # T7b7: ОТРИЦАТЕЛЬНЫЙ КЛАСС к предыдущей ноге (20 сентября 2026, находка противника).
    # `set -e` завёл новый договор: подготовка обязана доходить до конца без ненулевых
    # кодов в середине, и законный `grep -q` без `|| true` убил бы весь прогон. Класс на
    # нынешней таблице не срабатывает, но живой для будущих строк — договор проверяется
    # здесь, а не остаётся обещанием в шапке. Признаётся именно форма `|| true`: с ней
    # цепочка обязана собраться и прогон обязан пройти.
    # Ненулевой код даёт `false`, а не `grep`: сканер SIGPIPE судит ТЕКСТ и прочитал бы
    # `|grep -q` внутри строки таблицы как утверждение через трубу. Предмет ноги от этого
    # не меняется — важен сам ненулевой код в середине цепочки, а не чем он получен.
    printf 'legit|законный ненулевой код, погашенный ||true|false || true; printf A > s.txt|false || true; printf B > s.txt|cat s.txt\n' > "$TMP/carriers-legit.tsv"
    OUT7B7=$(R6_CARRIERS_FILE="$TMP/carriers-legit.tsv" bash "$R6" 2>"$TMP/err7b7"); RC7B7=$?
    [ "$RC7B7" = "0" ] && ok || bad "T7b7: погашенный ненулевой код убил пробу (rc=$RC7B7): $(cat "$TMP/err7b7")"
    grep -q 'legit' <<< "$OUT7B7" && ok || bad "T7b7: подготовки собрались, но носитель не назван — состояния A и B дали разный выход"

else
    if partial; then universe_skip_note T7b "пробы корней scripts/probes/"
    else bad "T7b: пробы R6 нет на месте — канал отказа не проверен"; fi
fi

# --- T7c: ПОДГОТОВКА ГОТОВИТ ТУ САМУЮ КОПИЮ, КОТОРУЮ СУДЯТ (20 сентября 2026) ---
# Находка противника: `_r6_prep` исполнял подготовку без привязки к копии, и резолв
# инструментов ClaudSoul (`hooks/paths-lib.sh`) уводил её в НАСТОЯЩИЙ репозиторий, пока
# судимая команда работала с песочницей. Подготовка меряла один мир, измерение — другой,
# и проба объявляла носителем `docs-refresh-claims` на чистом клоне HEAD.
#
# ФИКСТУРА СТАВИТ ЯВЛЕНИЕ, А НЕ ПОХОЖЕЕ НА НЕГО. Первая редакция этой ноги брала дешёвую
# строку (`: > probe-touch`), чья подготовка переменной не спрашивает вовсе, — и мутант
# «привязка снята» проходил её 28 из 28. Здесь подготовка ПИШЕТ ПО АДРЕСУ, который решает
# `CLAUDSOUL_REPO`, а судит команда, исполняемая в копии: привязано — метка в копии,
# не привязано — метка ушла мимо, оба состояния дают один код, и проба печатает носителя.
# Окружение указывает на СВОЙ выбрасываемый каталог, а не на рабочее дерево: непривязанная
# подготовка пишет туда, и рабочее дерево не трогается ни в одном исходе.
if [ -f "$R6" ]; then
    # ОКРУЖАЮЩИЙ РЕПОЗИТОРИЙ — НАСТОЯЩИЙ, и это не украшение: проба на :36 сама уходит
    # `cd` в `CLAUDSOUL_REPO`, и пустой каталог там даёт ОТКАЗ сборки песочницы, а не суд.
    # Первая редакция этой ноги подставляла пустой каталог — строка молча не исполнялась,
    # и «мутант пойман» было пустым утверждением (замер 20 сентября 2026: мутант проходил
    # 29 из 29 дважды подряд именно поэтому).
    mkdir -p "$TMP/ambient"
    ( cd "$TMP/ambient" && git init -q && printf 'x\n' > seed.txt && git add -A \
      && git -c user.email=p@p -c user.name=p -c commit.gpgsign=false commit -qm i ) >/dev/null 2>&1 || { echo "подготовка мира не удалась: hooks/tests/test_root_map.sh:$LINENO" >&2; exit 1; }
    if [ -d "$TMP/ambient/.git" ]; then
        printf 'привязка|проверочный носитель|printf x > "${CLAUDSOUL_REPO:-.}/probe-mark"|printf y > "${CLAUDSOUL_REPO:-.}/other-mark"|test -f probe-mark\n' > "$TMP/carriers-bind.tsv"
        OUT7C=$(R6_CARRIERS_FILE="$TMP/carriers-bind.tsv" CLAUDSOUL_REPO="$TMP/ambient" bash "$R6" 2>"$TMP/err7c"); RC7C=$?
        [ "$RC7C" = "0" ] && ok || bad "T7c: проба не отработала (rc=$RC7C): $(head -2 "$TMP/err7c")"
        [ -z "$OUT7C" ] && ok || bad "T7c2: подготовка ушла мимо копии — проба объявила носителя: '$OUT7C'"
        [ ! -f "$TMP/ambient/probe-mark" ] && ok || bad "T7c3: подготовка писала в окружающий репозиторий, а не в копию"
    else
        bad "T7c: окружающий репозиторий не собрался — инвариант привязки НЕ ПРОВЕРЕН"
    fi
fi

