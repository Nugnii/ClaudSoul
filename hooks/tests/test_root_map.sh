# --- T11-T12 (D417): РЕСУРСЫ КАРТЫ БЕРУТСЯ РЯДОМ С НЕЙ, а не у места прибора ------------
# Ноги выше задают CLAUDSOUL_REPO="$TMP", то есть ROOT и каталог карты СОВПАДАЮТ — ровно
