#!/usr/bin/env bash
# test_suite_runtime.sh — длительность набора сверяется с документом, а отказ отличим от чистоты.
#
# Предмет: число «полный набор бежит N» было прозой без команды и разошлось вдвое (документ
# «4 мин 40 с» против измеренных 11 мин 12 с на 366 тестах, 8 сентября 2026). Ноги держат не
# сам замер (он дорогой — 11 минут), а СВЕРКУ: она и есть то, чего не было.
set -uo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/../.." && pwd)"
SCRIPT="$ROOT/scripts/suite-runtime.sh"
PASS=0; FAIL=0
ok() { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/state" "$TMP/repo/.claude-docs/modules" "$TMP/repo/scripts" "$TMP/repo/hooks/tests"
cp "$SCRIPT" "$TMP/repo/scripts/"
DOCF="$TMP/repo/.claude-docs/modules/tool-gate-check.md"
# Фикстура — НАСТОЯЩИЙ репозиторий: множество документов скрипт выводит через `git ls-files`,
# а не по фиксированному пути (род F). Каталог без git дал бы пустое множество, и ноги
# зеленели бы на «документов нет» вместо проверки сверки — форма фикстуры берётся из мира.
git -C "$TMP/repo" init -q 2>/dev/null
git -C "$TMP/repo" config user.email t@t 2>/dev/null
git -C "$TMP/repo" config user.name t 2>/dev/null
track_doc() { git -C "$TMP/repo" add -A >/dev/null 2>&1; }
ART="$TMP/state/suite-runtime.json"
run() { CLAUDSOUL_REPO="$TMP/repo" STATE_DIR="$TMP/state" bash "$TMP/repo/scripts/suite-runtime.sh" --check 2>&1; }

# T1: замера не было — «НЕ ПРОВЕРЕНО», а не «совпало». Отсутствие данных не есть чистота.
printf 'Полный набор тестов бежит 4 мин 40 с, и дальше текст.\n' > "$DOCF"; track_doc
OUT=$(run); RC=$?
if [ "$RC" = "0" ] && grep -qF "НЕ ПРОВЕРЕНО" <<< "$OUT"; then ok
else bad "T1" "без артефакта ожидались код 0 и «НЕ ПРОВЕРЕНО», получено rc=$RC: $OUT"; fi

# T2: совпадение в пределах допуска — тишина и ноль.
printf '{"date":"2026-09-08T00:00:00Z","seconds":672,"tests":366,"load":"3.9"}\n' > "$ART"
printf 'Полный набор тестов бежит 11 мин 12 с, и дальше текст.\n' > "$DOCF"; track_doc
OUT=$(run); RC=$?
if [ "$RC" = "0" ] && grep -qF "совпадает" <<< "$OUT"; then ok
else bad "T2" "совпадение не признано: rc=$RC, $OUT"; fi

# T3: КОНТРПРИМЕР — расхождение вдвое обязано краснеть. Это ровно наблюдённый случай:
# документ «4 мин 40 с» (280 с) против измеренных 672 с.
printf 'Полный набор тестов бежит 4 мин 40 с, и дальше текст.\n' > "$DOCF"; track_doc
OUT=$(run); RC=$?
if [ "$RC" = "1" ] && grep -qF "РАСХОЖДЕНИЕ" <<< "$OUT"; then ok
else bad "T3" "расхождение вдвое не поймано: rc=$RC, $OUT"; fi

# T4: сверка не просто краснеет, а называет ГОТОВУЮ строку для правки — иначе находка
# перекладывает работу обратно на человека без подсказки, что писать.
if grep -qE 'правь строку .* «бежит 11 мин 12 с»' <<< "$OUT"; then ok
else bad "T4" "не названа строка для правки: $OUT"; fi

# T5: артефакт нечитаем — СЛОМАН (код 2), а не «чисто». Разница между «не смог» и «прочитал».
printf 'мусор без чисел\n' > "$ART"
OUT=$(run); RC=$?
if [ "$RC" = "2" ]; then ok
else bad "T5" "битый артефакт не признан поломкой: rc=$RC, $OUT"; fi

# T6: утверждение исчезло из документа — тоже находка, а не тишина. Реестр без своего места
# в тексте есть мёртвая строка (тот же довод, что в шапке docs-refresh-claims).
printf '{"date":"2026-09-08T00:00:00Z","seconds":672,"tests":366,"load":"3.9"}\n' > "$ART"
printf 'Тут больше нет фразы про длительность.\n' > "$DOCF"; track_doc
OUT=$(run); RC=$?
if [ "$RC" = "1" ] && grep -qF "исчезло из дерева" <<< "$OUT"; then ok
else bad "T6" "пропажа утверждения из ВСЕГО дерева не поймана: rc=$RC, $OUT"; fi

# T7: артефакт, записанный ДРУГИМ писателем (пробел после двоеточия — обычный JSON), читается.
# Без этой ноги прибор объявлял себя сломанным на верных данных: разбор требовал `"seconds":N`
# вплотную, и переписанный python'ом артефакт стал «нечитаемым» (8 сентября 2026).
printf '{"date": "2026-09-08T00:00:00Z", "seconds": 564, "tests": 368, "load": "4.30"}\n' > "$ART"
printf 'Полный набор тестов бежит 9 мин 24 с, и дальше текст.\n' > "$DOCF"; track_doc
OUT=$(run); RC=$?
if [ "$RC" = "0" ] && grep -qF "совпадает" <<< "$OUT"; then ok
else bad "T7" "артефакт с пробелами после двоеточия не прочитан: rc=$RC, $OUT"; fi

# T8: замер на ЗАНЯТОЙ машине не записывается — на ней он измеряет соседей, а не набор.
# Замер-повод: при нагрузке 3,6 набор дал 9 мин 43 с, при 6,19 — 16 мин 13 с (+67% при
# допуске ±40%). Проверяется отказ записи, а не сам прогон: гонять набор внутри ноги дорого.
if grep -qE '_LOAD_MAX|SUITE_RUNTIME_LOAD_MAX' "$SCRIPT" && \
   grep -qF 'замер НЕ ЗАПИСАН' "$SCRIPT"; then ok
else bad "T8" "нет отказа записи при высокой нагрузке — «измерил» неотличимо от «измерил на занятой машине»"; fi

echo ""
echo "suite runtime: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
