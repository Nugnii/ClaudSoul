#!/usr/bin/env bash
# test_predicate_signal.sh — сигнал детекции обязан уметь выражать ПРАВИЛО, а не только список.
#
# Повод — разбор «пять почему» после того, как один класс дефектов проявился за сессию
# четырьмя разными формами, и блокер, поднятый в тот же день, не сработал ни разу:
#
#   1. `sed 's/[a—b-]/ /g'`            — многобайтовое тире внутри класса символов
#   2. `grep -qE "...[^а-яёa-zA-Z]..."` — кириллический диапазон, отвергаемый в C.UTF-8
#   3. `grep -nE '[^\x00-\x7F]'`        — escape, который BSD grep читает как набор букв
#   4. `echo "«$_needle»"`              — подстановка вплотную к многобайтовой кавычке
#
# Цепочка причин: чинилась форма → потому что обнаруживалась после написания → потому что
# все механизмы постфактумные → блокер стоит в момент действия, но его сигналы перечисляли
# `date -j`, `stat -f`, `tail -r`, `compgen`, `[:upper:]` → **потому что содержимое можно
# было сопоставлять ТОЛЬКО точной подстрокой**. Класс, описываемый правилом, а не перечнем,
# при списочном сигнале обречён ловиться постфактум столько раз, сколько у него форм.
#
# Отсюда `tool_input_regex` в `detection-signals-lib.sh` и предикат в самом знании.
# Этот тест проверяет обе стороны: правило ловит формы, которых в списке никогда не было,
# и молчит на законном коде.

set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
LIB="$HOOKS_DIR/detection-signals-lib.sh"
KNOW="${LESSONS_DIR:-$HOME/.claude/global-lessons}/pattern-shell-portability.md"
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }
[ -f "$LIB" ] || { echo "FAIL: нет $LIB"; exit 1; }
# shellcheck source=/dev/null
source "$LIB"

PASS=0
FAIL=0

# payload формируется в обеих кодировках: харнесс может отдать не-ASCII сырыми байтами
# либо экранировать в \uXXXX, и предикат обязан работать в обоих случаях.
_eval() { # $1=знание $2=инструмент $3=json
    ds_evaluate "$1" "$2" "$3" "" 2>/dev/null
}
_payload() { # $1=фрагмент $2=True|False (ensure_ascii)
    python3 -c "import json,sys; print(json.dumps({'file_path':'/x/hooks/p.sh','old_string':'q','new_string':sys.argv[1]}, ensure_ascii=($2)))" "$1"
}
expect() { # $1=фрагмент $2=fire|silent $3=имя
    for esc in False True; do
        _r=$(_eval "$KNOW" Edit "$(_payload "$1" "$esc")")
        _got=$([ -n "$_r" ] && echo fire || echo silent)
        if [ "$_got" = "$2" ]; then PASS=$((PASS + 1))
        else FAIL=$((FAIL + 1)); echo "FAIL [$3, кодировка $([ $esc = False ] && echo сырая || echo экранированная)]: ожидалось $2, получено $_got"; fi
    done
}

if [ ! -f "$KNOW" ]; then
    echo "SKIP: знание с предикатом недоступно ($KNOW)"
    exit 0
fi

# --- Формы, которые СЛУЧИЛИСЬ. Ни одной не было в перечислении. ---
expect "x=\$(sed 's/[a—b-]/ /g')"                  fire   "T1 тире внутри класса"
expect "grep -qE \"(^| )\$p([^а-яёa-zA-Z]|\$)\""    fire   "T2 кириллический диапазон"
expect 'grep -nE "\[[^]]*[^\x00-\x7F]" f'          fire   "T3 escape внутри класса"
expect "echo \"пропала фраза «\$_needle»\""          fire   "T4 подстановка в ёлочках"

# --- Форма, которой НЕ БЫЛО ни в одном исправлении. Ради неё правило и заводится: ---
# список её не покрывал бы никогда, предикат покрывает без единой правки.
expect 'RU=$(grep -oE "[а-яё]{3,}" "$f")'          fire   "T5 форма, которую не чинили"

# --- Законный код обязан молчать. Без этой стороны предикат превратился бы в фон. ---
expect "AGE=\$(file_mtime \"\$f\")"                 silent "T6 вызов помощника"
expect "L=\$(to_lower \"\$USER_PROMPT\")"           silent "T7 свёртка через библиотеку"
expect "# комментарий на русском про классы"        silent "T8 русский комментарий"
expect "printf '%s' \"\$x\" | grep -qF \" \$m \""    silent "T9 поиск подстрокой"

# --- Отрицательный контроль на сам механизм: без tool_input_regex правило неработоспособно.
# Проверяется не знание, а библиотека: понимает ли она предикат вообще.
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
cat > "$TMP/probe.md" <<'PROBE'
---
name: проба
blocker: true
detection_signals: |
  [
    {
      "name": "probe_predicate",
      "all_of": [
        {"tool_matches": ["Edit"]},
        {"tool_input_regex": "ЗАВЕДОМО[-_]УНИКАЛЬНАЯ[-_]СТРОКА"}
      ]
    }
  ]
---
тело
PROBE
_hit=$(_eval "$TMP/probe.md" Edit "$(_payload 'x=ЗАВЕДОМО-УНИКАЛЬНАЯ-СТРОКА' False)")
if [ -n "$_hit" ]; then PASS=$((PASS + 1))
else FAIL=$((FAIL + 1)); echo "FAIL [T10 механизм]: библиотека не понимает tool_input_regex — предикат невозможен"; fi
_miss=$(_eval "$TMP/probe.md" Edit "$(_payload 'x=обычная строка' False)")
if [ -z "$_miss" ]; then PASS=$((PASS + 1))
else FAIL=$((FAIL + 1)); echo "FAIL [T10b механизм]: предикат сработал на несовпадающем входе"; fi

# ============================================================================
# T11-T14: сигнал не срабатывает на КОММЕНТАРИИ (D56)
# ============================================================================
# Блокер переносимости дважды за сессию загорелся на тексте, где `date -j` и `stat -f`
# перечислены как ЗАПРЕЩЁННЫЕ, — то есть на пояснении к правилу, а не на его нарушении.
# `pattern-guard-scope-blindness` внутри самого блокера: для команд тот же класс закрыт
# `command-scope-lib.sh`, для содержимого правки эквивалента не было.
#
# Правило комментария оболочки: решётка В НАЧАЛЕ строки, возможно после отступа.
# Решётка внутри кода комментария не открывает — иначе страж начнёт пропускать
# настоящие нарушения, а это хуже ложных срабатываний.

expect '# GNU не знает date -j и stat -f' silent "T11: комментарий в начале строки"
expect '    # в пояснении упомянут tail -r' silent "T12: комментарий с отступом"
expect 'ts=$(date -j -f fmt x)' fire "T13: настоящий вызов"
expect 'grep -c "#" f
m=$(stat -f %m x)' fire "T14: решётка внутри кода не глушит следующую строку"


echo ""
echo "predicate signal tests: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
