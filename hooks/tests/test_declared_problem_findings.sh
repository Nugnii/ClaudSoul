#!/usr/bin/env bash
# СУДИТ: hooks/declared-problem-recorded.sh
# test_declared_problem_findings.sh — пункт раздела «Что найдено» итога без пометки исхода называется на следующей
# реплике (D1041; договор пометки — D1046).
#
# Результат: пункт без пометки `→ <исход>` попадает своим текстом в посессионный файл и не попадает в общую очередь
#            `pending-alerts.txt`; пункт с пометкой из закрытого списка (`→ D<N>`, `→ B<N>`, `→ починено <коммит>`,
#            `→ держит <механизм>`, `→ не требует: <почему>`, `→ вопрос задан`, `→ знание <имя>`), текст вне раздела и
#            после следующего заголовка — нет; словесные формы («Исправил», «B149 заведён») и стрелка с чужим словом
#            исходом не считаются; заголовок с уточнением открывает раздел, `- **Что …**` без «:» его не закрывает; тот
#            же состав второй раз не повторяется; текст — целый UTF-8 в байтовой и многобайтной локали; не больше 12
# Проверка результата: bash hooks/tests/test_declared_problem_findings.sh даёт 0
#
# Повод — поправка владельца 24 октября 2026: «ты это забудешь, потому что не записал в бэклог, а я точно забуду».
# Договор пометки — решение владельца того же дня после третьего круга скептика (корень R3).
# Хук гоняется целиком на расшифровке из двух записей; DPR_HOOK подменяет хук для положительного контроля.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HOOK="${DPR_HOOK:-$ROOT/hooks/declared-problem-recorded.sh}"
[ -f "$HOOK" ] || { echo "FAIL: нет $HOOK"; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
PASS=0; FAIL=0

# run <каталог состояния> <текст итога> — один Stop; напоминание остаётся в каталоге.
run() {
    local d="$1" t="$1/t.jsonl"
    jq -nc '{type:"user",message:{role:"user",content:"привет"},timestamp:"2026-10-24T08:00:00Z"}' > "$t"
    jq -nc --arg m "$2" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$m}]},timestamp:"2026-10-24T08:01:00Z"}' >> "$t"
    jq -nc --arg t "$t" --arg d "$d" '{session_id:"s1",transcript_path:$t,cwd:$d,hook_event_name:"Stop"}' \
        | STATE_DIR="$d" bash "$HOOK" >/dev/null 2>&1
}
# Напоминание своей сессии — в любом её файле (имя канала решает хук).
queue() { cat "$1"/*s1*.txt 2>/dev/null; }
fresh() { mktemp -d "$TMP/r.XXXX"; }
named() {   # named <нога> <текст итога> <подстрока> — подстрока обязана попасть в напоминание
    local d; d=$(fresh); run "$d" "$2"
    case "$(queue "$d")" in *"$3"*) PASS=$((PASS+1)) ;; *) FAIL=$((FAIL+1)); echo "FAIL [$1]: не названо «$3»" ;; esac
}
silent() {  # silent <нога> <текст итога> — напоминания быть не должно
    local d; d=$(fresh); run "$d" "$2"
    if [ -z "$(queue "$d")" ]; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); echo "FAIL [$1]: названо лишнее: $(queue "$d" | head -3)"; fi
}

# ── Пометка исхода ─────────────────────────────────────────────────────────────────────────────────────────────────
named F1 "$(printf 'Итог.\n\n**Что найдено**\n- черновики ждут разбора\n')" "черновики ждут разбора"
named F2 "$(printf '### Что найдено\n1. нумерованная находка без судьбы\n')" "нумерованная находка без судьбы"
silent F3 "$(printf '**Что найдено**\n- пункт заведён → D1040\n- соседний → B149\n')"
silent F4 "$(printf '**Что найдено**\n- поправка в разборе → починено 2891d6fc\n')"
silent F5 "$(printf '**Что найдено**\n- лишний файл во временной папке → не требует: она чистится сама\n')"
silent F6 "$(printf '**Что найдено**\n- длинная находка о стражах\n  с продолжением → D1042\n')"
silent F7 "$(printf 'Итог без раздела.\n- черновики ждут разбора\n')"
silent F8 "$(printf '**Что найдено**\n- шум признака → держит замер seed-drift\n\n**Что дальше**\n- сделать следующий шаг\n')"
named F9 "$(printf '**Что найдено:**\n- перенос в установку → вопрос задан\n- осталась рабочая копия\n')" "осталась рабочая копия"
silent F9б "$(printf '**Что найдено**\n- урок о локали → знание case-2026-10-24-awk-substr\n')"
silent F9в "$(printf '**Что найдено**\n- тест не видел треть отказов\n\nЗаписан пунктом → D1050\n')"
# Словесные формы и стрелка с чужим словом — не исход.
named W1 "$(printf '**Что найдено**\n- B149 заведён: уведомления без экранирования\n')" "B149 заведён"
named W2 "$(printf '**Что найдено**\n- тест не видел треть отказов. Исправил.\n')" "треть отказов. Исправил"
named W3 "$(printf '**Что найдено**\n- срабатываний 114 → 111, причина не найдена\n')" "114 → 111"
named W4 "$(printf '**Что найдено**\n- сводка считает по старым статусам. Починю в следующей волне.\n')" "Починю в следующей волне"

# F10 — тот же состав второй раз не повторяется (дроссель по составу, а не по телу).
d=$(fresh); m=$(printf '**Что найдено**\n- черновики ждут разбора\n')
run "$d" "$m"; run "$d" "$m"
n=$(queue "$d" | grep -c 'черновики ждут разбора')
if [ "${n:-0}" -eq 1 ]; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); echo "FAIL [F10]: тот же состав назван $n раз"; fi

# F11 — длинный русский пункт доходит целым UTF-8: обрезка в байтовом awk резала посреди буквы.
d=$(fresh); long=$(awk 'BEGIN { for (i = 0; i < 60; i++) printf "находка "; }')
run "$d" "$(printf '**Что найдено**\n- %s\n' "$long")"
# Целость — питоном: iconv на macOS падает «Inappropriate ioctl for device» и на целом тексте.
if [ -n "$(queue "$d")" ] && python3 -I -c 'import sys; [open(p, "rb").read().decode("utf-8") for p in sys.argv[1:]]' "$d"/*s1*.txt 2>/dev/null; then PASS=$((PASS+1))
else FAIL=$((FAIL+1)); echo "FAIL [F11]: длинный пункт не назван или текст не UTF-8"; fi

# K1 — канал: напоминание лежит у СВОЕЙ сессии, общая очередь пуста (её опустошает реплика любой сессии).
d=$(fresh); run "$d" "$(printf '**Что найдено**\n- черновики ждут разбора\n')"
if [ -n "$(queue "$d")" ] && [ ! -s "$d/pending-alerts.txt" ]; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); echo "FAIL [K1]: напоминание не у своей сессии либо попало в общую очередь"; fi

# ── Границы раздела ────────────────────────────────────────────────────────────────────────────────────────────────
silent S6 "$(printf '**Что найдено**\n- сирота → D1050\n- **Что дальше:** сделать шаг\n')"
silent S7 "$(printf '**Что найдено**\n```\n- не пункт\n```\n')"
silent S9 "$(printf 'Ниже я перечисляю то,\nчто найдено в логах прогона:\n- прогон 1 зелёный\n')"
silent S10 "$(printf '**Что найдено:** нового нет.\n')"
silent S11 "$(printf '**Что найдено**\n| находка | исход |\n|---|---|\n| сирота | — |\n')"
silent S12 "$(printf '**Что найдено и что осталось**\n- одна → D1\n')"
silent S13 "$(printf '**Что найдено**\n- одна → D1\n\nЧто дальше:\n1. Проверю, что изменили исполнители\n')"
silent S14 "$(printf '> **Что найдено**\n> - чужая находка\n')"
silent S15 "$(printf '**Что найдено**\n- основная находка\n  - деталь к ней → D1046\n')"
named N1 "$(printf '**Что найдено:** находка в строке заголовка\n')" "находка в строке заголовка"
named N7 "$(printf '**Что найдено**\nДва места:\n- страж молчит после вводной строки\n')" "страж молчит после вводной строки"
named N8 "$(printf '**Что нашлось**\n+ страж молчит под другим заголовком\n')" "страж молчит под другим заголовком"
named N9 "$(printf '**Что\302\240найдено**\r\n1) страж молчит при неразрывном пробеле\r\n')" "страж молчит при неразрывном пробеле"
named N10 "$(printf '**Что найдено**\n- первая сирота\n\n**Что дальше**\n- шаг\n\n**Что найдено ещё**\n- вторая сирота\n')" "вторая сирота"
named N11 "$(printf '## Что найдено\nЦифры по ценам API.\n\n| а | б |\n|---|---|\n| 1 | 2 |\n\n- пункт после таблицы\n')" "пункт после таблицы"
named T1 "$(printf '**Что найдено противником, первый раунд:**\n- первая сирота уточнённого заголовка\n')" "первая сирота уточнённого"
named T1б "$(printf '### Что найдено скептиком\n- скептик подтвердил без пометки\n')" "скептик подтвердил"
named T2 "$(printf '## Что найдено\n- **Что говорит сам фильтр.** вторая сирота под жирным Что\n')" "вторая сирота под жирным"
named T3 "$(printf '**Что найдено**\n- Ничего не проверяет страж — третья сирота\n')" "третья сирота"
named L7 "$(printf '## Что найдено\n**Канал**\n- сирота под подзаголовком\n')" "сирота под подзаголовком"
named L8 "$(printf -- '- **Что найдено:**\n  - первая → D1046\n  - вторая дочь без пометки\n')" "вторая дочь без пометки"
named L10 "$(printf '**Что найдено**\n```\n- x\n~~~\n- y\n```\n- сирота после блока\n')" "сирота после блока"
named L6 "$(printf 'Находка: сирота в строке заголовка-находки\n')" "сирота в строке заголовка-находки"
named L5 "$(printf '**Что найдено**\n• первая сирота точкой\n• вторая сирота точкой\n')" "вторая сирота точкой"
# D1048: маркер `•` в байтовой локали; пункт-метка `- **Что …:**`, пункт со слова «Находка» и «Ничего нового, кроме …»
# раздела не закрывают и пункт не прячут; голый пункт «1. Находки …» под «Дальше» раздела не открывает.
LC_ALL=C named L5c "$(printf '**Что найдено**\n• первая сирота точкой\n• вторая сирота точкой\n')" "вторая сирота точкой"
named L11 "$(printf '**Что найдено:**\n- **Что ломается:** хук теряет напоминание\n- сирота после метки-пункта\n')" "сирота после метки-пункта"
named L12 "$(printf '**Что найдено**\n- A → D1050\n- Находка в хуке без пометки\n')" "Находка в хуке без пометки"
named L13 "$(printf '**Что найдено**\n- Ничего нового, кроме одного: сирота после ничего\n')" "сирота после ничего"
silent L14 "$(printf '**Что найдено:**\n- A → D1050\n\n**Дальше:**\n1. Находки скептика разобрать.\n2. Перенести в установку.\n')"
# D1056: метка закрывает раздел только названием части итога целиком; «- Что найдено: …» открывает раздел; `->` с
# номером — только в конце пункта; «Ничего нового» с продолжением — находка.
named L17 "$(printf '## Что найдено\n**Что осталось сломанным:** хук X молчит.\n- сирота после метки-префикса\n')" "сирота после метки-префикса"
named L18 "$(printf -- '- Что сделано: починил хук.\n- Что найдено: сирота голого списка.\n- Что дальше: перенос в установку.\n')" "сирота голого списка"
silent L19 "$(printf -- '- Что сделано: починил хук.\n- Что найдено: A → D1050\n- Что дальше: перенос в установку.\n')"
named L20 "$(printf '**Что найдено**\n- Формула A1 -> B12 сирота стрелки\n')" "сирота стрелки"
named L21 "$(printf '**Что найдено**\n- Ничего нового. Но сирота после точки\n')" "сирота после точки"
# D1051: «→ починено коммитом <хеш>», «→ починено (<хеш>)», `->` — исход; `**Что дальше:**` закрывает и `#`-раздел.
silent L15 "$(printf '**Что найдено:**\n- A → починено коммитом 84d90c59\n- C → починено (84d90c59)\n- B -> D1050\n')"
silent L16 "$(printf '## Что найдено\n- A → D1050\n\n**Что дальше:**\n- закоммитить и перенести\n')"
# D1059: вложенная метка — продолжение находки; метка однозначной части — с любым уточнением, неоднозначной — целиком
# или с хвостом формы итога; `->` с номером — в конце строки; текст заголовка перед пунктами глубже — вводная;
# «ничего нового» с продолжением названо продолжением; «- Находки: …» внутри раздела его не переоткрывает.
named L22 "$(printf '**Что найдено**\n- Хук X молчит.\n  - Что сделано: добавил лог.\n- сирота после вложенной метки\n')" "сирота после вложенной метки"
named L23 "$(printf '## Что найдено\n- Что изменилось: формат сломал разбор, сирота под заголовком\n')" "сирота под заголовком"
silent L24 "$(printf '## Что найдено\n- Хук X молчит. → D1056\n\n**Что ждёт вас:**\n- ответить на вопрос\n')"
silent L25 "$(printf '## Что найдено\n- Хук X молчит. → D1056\n\n**Что изменилось.** Сверщик строже.\n- шаг плана\n')"
named L26 "$(printf '## Что найдено\n**Что идёт не так:** сирота неоднозначной метки\n')" "сирота неоднозначной метки"
silent L27 "$(printf '**Что найдено**\n- Хук X -> D1057 (средняя)\n- Хук Y -> D1058, D1059\n- Хук Z молчит -> D1060\n  - подробность\n')"
silent L28 "$(printf -- '- Что найдено: три дефекта\n  - хук A падает → D1\n- Что дальше: перенос\n')"
named L29 "$(printf '**Что найдено:** ничего нового.\nсирота за ответом\n')" "сирота за ответом"
named L30 "$(printf -- '- Что найдено — сирота через тире\n')" "сирота через тире"
named L31 "$(printf '## Что найдено\n- Находки: две по хукам.\n**Хук X**\n- сирота под подзаголовком\n')" "сирота под подзаголовком"
silent L32 "$(printf '## Что найдено\n- Хук X молчит. → D1056\n\n### Что дальше\n- перенос\n')"
silent L33 "$(printf -- '- Находки: нет.\n')"
# D1062: метка — только в начале строки и с хвостом формы итога из закрытого списка; абзац «Что ждёт …:» — метка, только
# если двоеточие сразу за названием; пометка `->` в первой строке снимается продолжением прозой и не берётся из
# поглощённого абзаца; вводная с точкой — находка; подзаголовок с названием части не целиком — подзаголовок находки.
named L34 "$(printf '## Что найдено\n\nРаздел **Что дальше** в README устарел.\n\nсирота после слова с меткой\n')" "сирота после слова с меткой"
named L35 "$(printf '## Что найдено\n\n- Хук X → D1\n- **Что ждёт исправления:** сирота с хвостом вне списка\n')" "сирота с хвостом вне списка"
named L36 "$(printf '## Что найдено\n\nЧто ждёт хук при пустом stdin: он падает.\n\nсирота после абзаца ждёт\n')" "сирота после абзаца ждёт"
named L37 "$(printf '## Что найдено\n\n- сирота перед поглощённым абзацем\n\nХук Y молчит -> D1041\n\nХук Z пишет мусор.\n')" "сирота перед поглощённым абзацем"
named L38 "$(printf '**Что найдено**\n- Регрессия цепочки D1041 -> D1044\n  хук X перестал писать журнал\n')" "Регрессия цепочки"
named L39 "$(printf -- '- **Что найдено:** сирота-вводная с точкой.\n  - соседний хук → не требует: вне установки\n- **Что дальше:** ничего\n')" "сирота-вводная с точкой"
named L40 "$(printf '## Что найдено\n\n### Что дальше ломается после D1040\n- сирота под подзаголовком находки\n')" "сирота под подзаголовком находки"

# P1 — потолок: из 15 пунктов названы 12 и остаток числом.
d=$(fresh); run "$d" "$(printf '**Что найдено**\n'; for i in $(seq 1 15); do printf -- '- сирота номер %s\n' "$i"; done)"
if [ "$(queue "$d" | grep -c 'сирота номер')" -eq 12 ] && grep -q 'и ещё 3' <<< "$(queue "$d")"; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); echo "FAIL [P1]: потолок 12 пунктов не держится"; fi
# L1 — многобайтная локаль: длинный пункт без ошибки awk и целым UTF-8 (substr резал букву, регулярка падала).
d=$(fresh); long=$(awk 'BEGIN { for (i = 0; i < 80; i++) printf "находка «длинная» "; }')
t="$d/t.jsonl"
jq -nc '{type:"user",message:{role:"user",content:"привет"},timestamp:"2026-10-24T08:00:00Z"}' > "$t"
jq -nc --arg m "$(printf '**Что найдено**\n- %s\n' "$long")" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$m}]},timestamp:"2026-10-24T08:01:00Z"}' >> "$t"
err=$(jq -nc --arg t "$t" --arg d "$d" '{session_id:"s1",transcript_path:$t,cwd:$d,hook_event_name:"Stop"}' \
    | LC_ALL=C.UTF-8 STATE_DIR="$d" bash "$HOOK" 2>&1 >/dev/null)
if [ -z "$err" ] && [ -n "$(queue "$d")" ] && python3 -I -c 'import sys; [open(p, "rb").read().decode("utf-8") for p in sys.argv[1:]]' "$d"/*s1*.txt 2>/dev/null; then PASS=$((PASS+1))
else FAIL=$((FAIL+1)); echo "FAIL [L1]: в UTF-8 локали ошибка «${err}» либо пункт не назван целым UTF-8"; fi

echo "test_declared_problem_findings: passed $PASS, failed $FAIL"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
