#!/usr/bin/env bash
# test_hook_header_contract.sh — первая строка описания хука обязана быть самодостаточной.
#
# Контракт, который здесь сторожится, документирован в шапке hooks/partial-read-guard.sh:
# scripts/regen-readme-skills.sh берёт для таблицы РОВНО ОДНУ строку — русскую строку 2
# после «— » или строку «# en:». Описание, разорванное переносом по ширине, попадает в
# витрину оборванным на предлоге, и продолжение теряется молча.
#
# Повод (D73, 2026-08-25). Стража не было, и к моменту переписывания README из 75 хуков
# 11 обрывали фразу («…injects a per-session signal and»), а 3 несли отсылку вместо
# описания («ADR-010 Ф2.», «UserPromptSubmit hook»). Обнаружилось не тестом, а внешним
# читателем справочника: генератор отрабатывал штатно, дефект был в данных.
# Отсюда предмет проверки — ИСТОЧНИК, а не вывод генератора.
#
# Извлечение описания скопировано из генератора ДОСЛОВНО — та же sed-подстановка для
# русской строки, то же окно для английской: весь ведущий блок комментариев. Первая версия извлекала по-своему,
# и расхождение немедленно нашлось с двух сторон: страж принимал строку 2 без имени файла
# перед тире, которую генератор выбрасывает с WARN, и проверял `# en:` на девятой строке,
# которую генератор тогда не видел и молча заменял русской. Произвольная граница в восемь
# строк убрана у обоих: окно кончается там же, где кончается шапка. Проверка, которая смотрит не на то, что уезжает в витрину,
# сторожит собственное представление о предмете.
#
# Ноль проверенных файлов — ОТКАЗ, а не успех. Скрипт, прочитанный со stdin, теряет $0,
# каталог хуков уезжает мимо, и «нарушений нет» становится дословно неотличимо от
# «файлов не нашлось» (тот же класс, что чинили в drift-check: ноль сравнений — не успех).
#
# Имена переменных перед кавычкой-ёлочкой обязаны быть в фигурных скобках: `»` в UTF-8
# начинается с байта \xc2, и bash 3.2 включает его в имя — `"$trimmed»"` читается как  # mb-ok: строка демонстрирует дефект, а не совершает его
# обращение к переменной `trimmed\xc2` и роняет тест с «unbound variable». Срез хвоста
# берётся через `tail -c`, а не `${var: -N}`: последняя форма под `set -u` в bash 3.2
# роняет тест так же. Падение с ошибкой неотличимо от отсутствия проверки.

set -uo pipefail

HOOKS_DIR="${HOOKS_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
PASS=0
FAIL=0
CHECKED_FILES=0

# Фраза законченна, если оканчивается терминатором. Порог «не короче четырёх слов»
# отсекает отсылки-заглушки, которые формально с точкой.
check_line() {
    local file="$1" lang="$2" desc="$3" next="$4"
    local trimmed words
    trimmed="$(printf '%s' "$desc" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
    words=$(printf '%s' "$trimmed" | wc -w | tr -d ' ')

    case "$trimmed" in
        *.|*!|*\?|*\)|*») ;;
        *)
            FAIL=$((FAIL + 1))
            echo "FAIL [$(basename "$file"):$lang]: описание обрывается без терминатора — «…$(printf '%s' "$trimmed" | tail -c 50)»"
            return ;;
    esac
    if [ "$words" -le 3 ]; then
        FAIL=$((FAIL + 1))
        echo "FAIL [$(basename "$file"):$lang]: описание короче четырёх слов — «${trimmed}»"
        return
    fi
    # Перенос, попавший на закрывающую кавычку или скобку, проходит проверку терминатора:
    # «…есть слово «стоп»» выглядит законченным, а на следующей строке лежит придаточное.
    # Прямой признак дефекта — не форма конца, а наличие продолжения: строка комментария,
    # начинающаяся с тире или строчной буквы, новое предложение не открывает.
    # Признак считается образцами `case`, а не `printf | grep -q`: утверждение через трубу
    # под `set -o pipefail` врёт, когда grep закрывает вход раньше времени и printf получает
    # SIGPIPE — это отдельно сторожит test_assert_no_sigpipe.sh.
    #
    # Строчная кириллица перечислена ЛИТЕРАЛАМИ, все тридцать три, а не диапазоном.
    # Диапазон `[а-я]` внутри скобок под LC_ALL=C распадается на байты и совпадает не с тем,
    # а байтовые escape-последовательности `\xd0[\xb0-\xbf]` ERE-grep не интерпретирует —
    # проверено, не нашло ни одной строки. Первая версия признака ограничивалась ASCII
    # `[a-z]`, и это было сознательным упрощением: «русский перенос всё равно оставит
    # строку без терминатора». Противник показал контрпример за один заход — описание,
    # кончающееся на закрывающую скобку, с продолжением на кириллице проходило молча,
    # то есть ровно тот дефект D73, ради которого страж написан, на языке корпуса.
    # Строка «# en:» продолжением НЕ считается — она открывает второе описание, а не
    # продолжает первое. Без этой оговорки признак ловил её сам («# e» подходит под
    # [a-z]) и красил все 44 хука с английской строкой.
    # ПРАВИЛО, А НЕ ПЕРЕЧЕНЬ. Прошлая версия перечисляла, чем продолжение НАЧИНАЕТСЯ —
    # ASCII-строчные, 33 кириллических, три тире. Перечень по определению неполон: обратная
    # кавычка вокруг идентификатора (постоянная форма этого корпуса), цифра, скобка, ёлочка
    # в список не входили и проходили молча. Инвертируем: новое предложение открывает
    # ЗАГЛАВНАЯ буква или цифра списка; всё прочее в строке комментария — продолжение.
    # Заглавные перечислены литералами: диапазон под LC_ALL=C распадается на байты.
    local is_cont=""
    case "$next" in
        "# ") ;;                                   # пустой комментарий — конец абзаца
        "# en:"*) ;;                               # открывает второе описание, не продолжает
        "# "[A-Z]*|"# "[0-9]*) ;;                   # заглавная или нумерация — новое предложение
        "# А"*|"# Б"*|"# В"*|"# Г"*|"# Д"*|"# Е"*|"# Ё"*|"# Ж"*|"# З"*|"# И"*|"# Й"*|"# К"*|"# Л"*|"# М"*|"# Н"*|"# О"*|"# П"*|"# Р"*|"# С"*|"# Т"*|"# У"*|"# Ф"*|"# Х"*|"# Ц"*|"# Ч"*|"# Ш"*|"# Щ"*|"# Ъ"*|"# Ы"*|"# Ь"*|"# Э"*|"# Ю"*|"# Я"*) ;;
        "# "?*) is_cont=yes ;;                     # всё остальное непустое — продолжение
    esac
    if [ -n "$is_cont" ]; then
        FAIL=$((FAIL + 1))
        echo "FAIL [$(basename "$file"):$lang]: описание продолжено следующей строкой, в витрину уедет только первая — «$(printf '%s' "$next" | tail -c 50)»"
        return
    fi
    PASS=$((PASS + 1))
}

for hook in "$HOOKS_DIR"/*.sh; do
    [ -f "$hook" ] || continue
    case "$(basename "$hook")" in *-lib.sh) continue ;; esac
    CHECKED_FILES=$((CHECKED_FILES + 1))

    # Русское описание — строка 2, извлечение дословно по генератору.
    line2="$(awk 'NR == 2' "$hook")"
    ru_desc=""
    case "$line2" in
        "# "*) ru_desc="$(printf '%s' "$line2" | sed -E 's/^# [^—]+—[[:space:]]*//')" ;;
    esac
    if [ -z "$ru_desc" ] || [ "$ru_desc" = "$line2" ]; then
        FAIL=$((FAIL + 1))
        echo "FAIL [$(basename "$hook"):ru]: строка 2 не даёт описания — генератор её выбросит («${line2}»)"
    else
        check_line "$hook" ru "$ru_desc" "$(awk 'NR == 3' "$hook")"
    fi

    # Английское описание — «# en:» в ведущем блоке комментариев, окно как у генератора.
    # С D219 (30 августа 2026) строка ОБЯЗАТЕЛЬНА для не-библиотечного хука: генератор
    # осознанно откатывается на русскую строку, чтобы описание не пропало молча, — но
    # откат означает русский текст в английской витрине. Три хука так и уехали и были
    # дописаны руками; отказ здесь закрывает класс для хуков ненаписанных.
    en="$(awk '/^#!/ { next } !/^#/ { exit } /^# en:[[:space:]]*/ { sub(/^# en:[[:space:]]*/, ""); print; exit }' "$hook")"
    if [ -z "$en" ]; then
        FAIL=$((FAIL + 1))
        echo "FAIL [$(basename "$hook"):en]: нет строки «# en:» — английская витрина молча получит русский текст"
    else
        en_next="$(awk '/^# en:[[:space:]]*/ { getline nxt; print nxt; exit }' "$hook")"
        check_line "$hook" en "$en" "$en_next"
    fi
done

echo ""
if [ "$CHECKED_FILES" -eq 0 ]; then
    echo "hook header contract: ОТКАЗ — не найдено ни одного хука в «${HOOKS_DIR}»"
    echo "  ноль проверенных файлов не есть успех: проверка не запустилась, а не прошла"
    exit 2
fi
echo "hook header contract: $PASS/$((PASS + FAIL)) passed ($CHECKED_FILES файлов)"
[ "$FAIL" -eq 0 ]
