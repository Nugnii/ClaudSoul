#!/usr/bin/env bash
# test_adv6_archive_second_proverka_ignored.sh — архиватор переносит ☑-пункт с ДВУМЯ
# строками «**Проверка.**», проверив только ПЕРВУЮ; красная вторая молча игнорируется.
#
# АТАКА. Гейт красной проверки берёт re.search(...) — ПЕРВОЕ совпадение
# `**Проверка.** `команда``. Если у пункта две строки проверки (осталось при правке,
# или закрытие требует двух условий), исполняется только первая. Первая зелёная,
# вторая красная — пункт уезжает в архив как доказанно закрытый, хотя одно из его же
# условий провалено. Ложно-зелёное: «закрытие утверждает, что команда даёт 0» — а
# вторая команда даёт не-0, и это не замечено.
#
# ВХОД. ☑ D250 с двумя «Проверками»: `true` → 0 (зелёная) и `false` → 0 (красная).
# ОЖИДАНИЕ. Хоть одно условие красное → пункт не переносится (как при одной красной).
# ФАКТ.     Проверена только первая (зелёная) → пункт уходит в архив.
set -u
SCRIPT="$(cd "$(dirname "$0")/../.." && pwd)/scripts/backlog-archive.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

BACKLOG="$TMP/BACKLOG.md"
ARCHIVE="$TMP/BACKLOG-archive.md"

{
  printf '# BACKLOG\n\n'
  printf '## Раздел\n\n'
  printf -- '- ☑ D250 закрытый пункт\n'
  printf -- '  **Проверка.** `true` → 0\n'
  printf -- '  примечание\n'
  printf -- '  **Проверка.** `false` → 0\n'
  printf -- '- ☐ D251 открытый, чтобы раздел уцелел\n'
} > "$BACKLOG"

BACKLOG_FILE="$BACKLOG" BACKLOG_ARCHIVE="$ARCHIVE" bash "$SCRIPT" run >/dev/null 2>&1
rc=$?

# Пункт с красной второй проверкой не должен уехать: он ещё в рабочем файле.
if grep -q 'D250' "$BACKLOG"; then
    echo "PASS: пункт с красной второй проверкой удержан в BACKLOG (rc=$rc)"
    exit 0
fi

echo "FAIL (attack succeeds): D250 перенесён в архив, хотя его вторая «Проверка»"
echo "  (\`false\`) красная — исполнена только первая. Ложно-зелёное закрытие."
echo "--- архив ---"; grep -n 'D250' "$ARCHIVE" 2>/dev/null | head
exit 1
