#!/usr/bin/env bash
# test_backlog_item_shape.sh — пункт долга опознаётся правилом, а не одной вёрсткой.
#
# Результат: все читатели BACKLOG.md видят один и тот же набор пунктов
# Проверка результата: bash hooks/tests/test_backlog_item_shape.sh даёт 0
#
# Повод. 28 августа 2026 пункты долга сменили вёрстку со списка (`- ☑ **D42**`) на
# заголовок (`### D42 ☑ …`). Три стража имели СВОЮ копию признака `^- ` и отказали в тот
# же день, молча и по-разному:
#   · `backlog-archive`      — «переносить нечего» при двух ☑ в файле;
#   · `backlog-return-check` — ноль открытых пунктов, условия возврата не проверялись;
#   · `backlog-vanish-check` — ноль идентификаторов, пропажа пункта невидима.
# Сутки это не всплывало, потому что проверка результата архиватора (`grep -c '^- ☑'`)
# искала ту же вёрстку и была зелёной ровно тогда, когда он слеп.
#
# Тест держит ПРАВИЛО: набор пунктов не зависит от вёрстки, и все читатели видят один и
# тот же набор. Проверяется поведением на обеих вёрстках, а не чтением кода.
set -uo pipefail

# Рамку задаёт тест, а не окружение (D334): унаследованный `BACKLOG_CHECKS_NESTED=1`
# уводил архиватор в дверь вложенности, и T6 краснел, не проверив ничего — 11/12 против 12/12.
unset BACKLOG_CHECKS_NESTED

REPO="$(cd "$(dirname "$0")/../.." && pwd)"

# ЖИВОЙ БЭКЛОГ ЕСТЬ НЕ В КАЖДОМ ДЕРЕВЕ. BACKLOG.md — рабочий срез и в публичный снимок не
# входит, а машинерия долга (hooks/backlog-lib.sh, архиватор, страж возврата) входит: ноги
# на фикстурах там остаются предметом, ноги на живом файле — нет. Без различения все шесть
# кричали о дефекте в снимке при нуле пунктов (корень R6, 10 красных тестов публичного CI).
UNIVERSE_ROOT="$REPO"; . "$REPO/hooks/lib/universe-lib.sh" 2>/dev/null || true
SKIP_LIVE=0
if command -v universe_partial_tree >/dev/null 2>&1 && universe_partial_tree; then SKIP_LIVE=1; fi
skip_or_bad() {  # пропуск — только там, где предмет изъят ПО ПОСТРОЕНИЮ; иначе прежний провал
    [ "$SKIP_LIVE" = 1 ] || { bad "$@"; return 0; }
    universe_skip_note "$1" "рабочий долг BACKLOG.md"
}

LIB="$REPO/hooks/backlog-lib.sh"
[ -f "$LIB" ] || { echo "FAIL: нет $LIB"; exit 1; }
# shellcheck source=hooks/backlog-lib.sh
. "$LIB"

PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# --- T1: обе вёрстки дают ОДИН набор идентификаторов ---
cat > "$TMP/list.md" <<'EOF'
## Открытое
- ☐ **D41** первый
  тело
- ☑ **D42** второй
  тело
EOF
cat > "$TMP/head.md" <<'EOF'
## Открытое
### D41 ☐ первый
тело
### D42 ☑ второй
тело
EOF
L=$(backlog_ids "$TMP/list.md" | tr '\n' ' ')
H=$(backlog_ids "$TMP/head.md" | tr '\n' ' ')
[ "$L" = "$H" ] && [ -n "$L" ] && ok || bad T1 "вёрстки дают разный набор: список [$L] против заголовков [$H]"

# --- T2: метки различаются в обеих вёрстках одинаково ---
for f in "$TMP/list.md" "$TMP/head.md"; do
    D=$(backlog_ids "$f" "$BACKLOG_DONE_MARKS" | tr '\n' ' ')
    O=$(backlog_ids "$f" "$BACKLOG_OPEN_MARKS" | tr '\n' ' ')
    { [ "$D" = "D42 " ] && [ "$O" = "D41 " ]; } && ok \
        || bad T2 "$(basename "$f"): закрытые [$D], открытые [$O] — ожидались D42 и D41"
done

# --- T3: КОНТРПРИМЕР — легенда несёт все четыре метки и пунктом НЕ является ---
backlog_is_item '**Легенда статусов:** ☐ todo · ◐ in-progress · ☑ done · ⊘ waived' \
    && bad T3 "строка легенды засчитана пунктом" || ok

# --- T4: КОНТРПРИМЕР — проза с меткой и без номера пунктом не является ---
backlog_is_item 'Пункт, чей инвариант сломан, снова открыт — верни ему ☐ в BACKLOG.md.' \
    && bad T4 "проза засчитана пунктом" || ok

# --- T5: порядок метки и номера любой (в списке метка первая, в заголовке вторая) ---
backlog_is_item '- ☑ **D12** что-то' && ok || bad T5 "списочная вёрстка не опознана"
backlog_is_item '### D109 ☑ что-то' && ok || bad T5 "заголовочная вёрстка не опознана"

# --- T5d: идентификатор пункта один, ссылка на родню им не становится ---
# Заголовок пункта законно называет родственный номер («родня D279», «вне D278»). До
# 3 сентября 2026 backlog_ids возвращал ВСЕ номера строки, и три такие ссылки дали три
# несуществующих открытых пункта — расхождение с архиватором 19 против 16. Признак был
# снят с формы, а различать надо роль.
FIX=$(mktemp -d)
printf -- '- \342\230\220 **D801** пункт со ссылкой на родню D802 и на D803.\n' > "$FIX/B.md"
GOT=$(backlog_ids "$FIX/B.md" "$BACKLOG_OPEN_MARKS" | tr '\n' ' ')
rm -rf "$FIX"
[ "$GOT" = "D801 " ] && ok \
    || bad T5d "строка с одним пунктом и двумя ссылками дала идентификаторы: $GOT"

# --- T5e: «Проверка» открытого пункта не зависит от каталога запуска ---
# Замер 3 сентября 2026: из 16 открытых пунктов 9 давали РАЗНЫЙ код возврата из корня и из
# hooks/tests, и четыре из них были оттуда ЗЕЛЁНЫМИ — то есть читатель, прогнавший команду
# не из корня, получал «проблема решена» на нерешённой. Механизмы обмануть было нельзя
# (completion-gate и backlog-archive задают cwd = каталог BACKLOG.md), обманывался человек,
# а команда пункта пишется именно для него.
#
# НАЗВАННЫЙ ПРЕДЕЛ: проверяется ФОРМА (переход в корень репозитория первым делом), а не
# поведение. Поведенческий прогон стоил бы двух прогонов всех 16 команд, среди которых есть
# идущие минутами (D292 гоняет восемь параллельных прогонов ротации). Форма выбрана потому,
# что у неё одно последствие: без перехода результат зависит от каталога.
# Условие снятия: предел уйдёт, когда у команд появится объявленная стоимость и дешёвые
# можно будет гонять поведенчески, а дорогие — по форме.
#
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ (7 сентября 2026). Предполагалось: пустой CWD_BAD значит «все
# команды переходят в корень». Ложно — он же пуст, когда осмотрено НОЛЬ команд, а нога
# читает мир и размер выборки не проверяла. Своя копия признака (`^- [☐◐] \*\*D[0-9]+\*\*`)
# делала это не гипотезой: она видела только списочную вёрстку с D-номером (28 августа
# 2026 смена вёрстки уже онемила так три стража), а класс `[☐◐]` в mawk и в локали C
# читается побайтно и путает ☐ с ☑. Замер того же дня: с занулённым `backlog_item_re`
# библиотека отдавала 0 открытых, а эта нога оставалась зелёной.
# Держат три числа: признак пункта и признак строки «Проверка» взяты у библиотеки (D305),
# осмотренных команд > 0, а число осмотренных пунктов равно счёту библиотеки.
# НАЗВАННЫЙ ПРЕДЕЛ равенства: библиотека дедуплицирует идентификаторы (`sort -u`), поток
# здесь — нет, поэтому два пункта с одним номером дадут расхождение. Такой дубликат сам по
# себе дефект, и называет его `backlog-vanish-check`.
# ПРИПИСКА ЧУЖОЙ КОМАНДЫ (13 сентября 2026). Поток нёс только заголовки ОТКРЫТЫХ пунктов, и
# «Проверка» закрытого пункта приписывалась предыдущему открытому: ⊘ D335 получил команду
# без перехода в корень (ей каталог не нужен — она читает `ps`), а нога назвала виновным D331.
# Теперь поток несёт ВСЕ заголовки, и команда судится, только пока текущий пункт открыт.
T5E_ITEM_RE=$(backlog_item_re "$BACKLOG_OPEN_MARKS")
T5E_ANY_RE=$(backlog_item_re "☐◐☑⊘")
t5e_scan() {  # t5e_scan <BACKLOG.md> → CWD_SEEN CWD_ITEMS CWD_BAD (команды открытых пунктов без перехода в корень)
    local _line _open=0
    CWD_BAD=""; CWD_SEEN=0; CWD_ITEMS=0; CWD_ID=""
    while IFS= read -r _line; do
        [ -n "$_line" ] || continue
        if grep -qE "$T5E_ITEM_RE" <<< "$_line"; then
            CWD_ITEMS=$((CWD_ITEMS + 1))
            CWD_ID=$(backlog_id_stream <<< "$_line")
            _open=1
            continue
        fi
        if grep -qE "$T5E_ANY_RE" <<< "$_line"; then _open=0; CWD_ID=""; continue; fi
        grep -qE "$BACKLOG_CHECK_RE" <<< "$_line" || continue
        [ "$_open" -eq 1 ] || continue
        CWD_SEEN=$((CWD_SEEN + 1))
        case "$_line" in
            *'CLAUDSOUL_REPO:-$(git rev-parse'*) ;;
            *) CWD_BAD="$CWD_BAD $CWD_ID" ;;
        esac
    done <<EOF
$(backlog_strip_fenced < "$1" | grep -E "$T5E_ANY_RE|$BACKLOG_CHECK_RE")
EOF
}
T5E_OPEN=$(backlog_ids "$REPO/BACKLOG.md" "$BACKLOG_OPEN_MARKS" | wc -l | tr -d ' ')
t5e_scan "$REPO/BACKLOG.md"
{ [ "$T5E_OPEN" -gt 0 ] && [ "$CWD_SEEN" -gt 0 ] && [ "$CWD_ITEMS" -eq "$T5E_OPEN" ] \
    && [ -z "${CWD_BAD// /}" ]; } && ok \
    || skip_or_bad T5e "осмотрено команд «Проверки» $CWD_SEEN у $CWD_ITEMS пунктов при $T5E_OPEN открытых по библиотеке; без перехода в корень:${CWD_BAD:- —}"

# --- T5e2: команда ЗАКРЫТОГО пункта не приписывается соседу (красная до 13 сентября 2026) ---
FIX=$(mktemp -d)
printf -- '- \342\230\220 **D900** открытый.\n  **Проверка.** `bash -c '"'"'cd "${CLAUDSOUL_REPO:-$(git rev-parse --show-toplevel 2>/dev/null)}" || exit 2; false'"'"'` → 0\n- \342\212\230 **D901** закрыт вердиктом.\n  **Вердикт.** признака нет.\n  **Проверка.** `bash -c '"'"'ps -axo ppid= | grep -c .'"'"'` → 0\n' > "$FIX/B.md"
t5e_scan "$FIX/B.md"
rm -rf "$FIX"
{ [ "$CWD_SEEN" -eq 1 ] && [ "$CWD_ITEMS" -eq 1 ] && [ -z "${CWD_BAD// /}" ]; } && ok \
    || bad T5e2 "команда закрытого пункта приписана соседу: осмотрено $CWD_SEEN, пунктов $CWD_ITEMS, без перехода:${CWD_BAD:- —}"

# --- T5f: новый пункт долга отвечает, к какому РОДУ дефекта относится ---
# Повод измерен 4 сентября 2026 владельцем проекта, а не механизмом: за 2-3 сентября закрыт
# 21 пункт и заведено 24, файл вырос со 189 строк до 539. Классификация показала, что 21 из
# 25 открытых пунктов — проявления ПЯТИ родов, а реестр родов (scripts/defect-class-carriers.py)
# не пополнялся с 1 сентября: род, найденный разбором, оставался прозой внутри пункта и не
# становился строкой инструмента. Поэтому следующий разбор находил то же самое заново и
# заводил пункт ПО МЕСТУ — приход долга обгонял расход.
#
# Требование: пункт с номером от 306 несёт строку «**Род.**». Три законных её содержания:
# буква заведённого рода, «нет — <почему это не проявление известного рода>», либо «новый —
# <правило рода>» вместе с заведением рода в реестре. Ответ обязателен, содержание — нет:
# «нет» с причиной такой же законный исход, как отнесение.
#
# ПОРОГ ПО НОМЕРУ обязателен и не формальность: 22 пункта, написанные до этого правила,
# требовать строку задним числом значило бы выдать 22 ложных отказа на правильной работе —
# та же причина, по которой BACKLOG_CONTRACT_MIN_ID=200 стоит у архиватора.
#
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ (7 сентября 2026). Предполагалось: пустой GENUS_BAD значит «у всех
# пунктов от D306 строка «Род.» есть». Ложно тем же устройством, что у T5e — пуст он и при
# нуле осмотренных пунктов. Тут это было не гипотезой вдвойне: своя копия признака
# (`"- ☐ **D"*`) видела ТОЛЬКО списочную вёрстку, только жирный номер и только букву D,
# то есть заголовочный пункт и пункт вида `X1` проезжали мимо молча. Замер: с занулённым
# `backlog_item_re` нога осталась зелёной при нуле пунктов.
# Держат два числа: осмотрено пунктов от порога > 0, а всего осмотрено ровно столько,
# сколько открытых видит библиотека (её же признаком, а не второй копией).
GENUS_MIN_ID="${BACKLOG_GENUS_MIN_ID:-306}"
GENUS_BAD=""
GENUS_CUR=""
GENUS_SEEN=0
GENUS_ITEMS=0
while IFS= read -r _line; do
    [ -n "$_line" ] || continue
    if grep -qE "$T5E_ITEM_RE" <<< "$_line"; then
        [ -n "$GENUS_CUR" ] && GENUS_BAD="$GENUS_BAD $GENUS_CUR"
        GENUS_ITEMS=$((GENUS_ITEMS + 1))
        _n=$(backlog_id_stream <<< "$_line")
        _num=${_n#D}
        if [ "${_num:-0}" -ge "$GENUS_MIN_ID" ] 2>/dev/null; then
            GENUS_CUR="$_n"; GENUS_SEEN=$((GENUS_SEEN + 1))
        else GENUS_CUR=""; fi
        continue
    fi
    case "$_line" in
        *'**Род.**'*) GENUS_CUR="" ;;
    esac
done <<EOF
$(backlog_strip_fenced < "$REPO/BACKLOG.md" | grep -E "$T5E_ITEM_RE|[*][*]Род[.][*][*]")
EOF
[ -n "$GENUS_CUR" ] && GENUS_BAD="$GENUS_BAD $GENUS_CUR"
{ [ "$GENUS_SEEN" -gt 0 ] && [ "$GENUS_ITEMS" -eq "$T5E_OPEN" ] && [ -z "${GENUS_BAD// /}" ]; } && ok \
    || skip_or_bad T5f "осмотрено пунктов $GENUS_ITEMS при $T5E_OPEN открытых, из них от D$GENUS_MIN_ID — $GENUS_SEEN; без строки «**Род.**» (буква рода, «нет — почему» либо «новый — правило»):${GENUS_BAD:- —}"

# --- T5g: пункт от D306 несёт строку «**Корень.**» ------------------------------
# Требование СИММЕТРИЧНО «Роду» и заведено 10 сентября 2026, когда владелец поручил разобрать
# бэклог от конца к началу. Отнесение к лесу проставлено у всех 43 пунктов вручную; без
# требования оно начнёт осыпаться с первого же нового пункта, и работа дня пропадёт — ровно
# то, о чём D379: связь «пункт ↔ корень» держалась рукой при 1 пункте из 38.
# Три законных содержания те же: `R<n>` заведённого корня, «нет — <почему это не проявление
# ни одного корня карты>», либо «новый — <устройство>» вместе с заведением корня в ROOTS.md.
#
# ПОРОГ ПО НОМЕРУ тот же (D306) и по той же причине: требовать строку у пунктов, написанных
# до карты, значило бы выдать ложные отказы на правильной работе.
#
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ здесь ОБЯЗАТЕЛЕН и взят у соседа дословно: пустой список «без
# строки» лжив при нуле осмотренных пунктов, поэтому ногу держат ДВА числа — осмотренных от
# порога больше нуля, и всего осмотрено ровно столько, сколько открытых видит библиотека.
# Без них нога зеленела бы на занулённом признаке пункта (замер 7 сентября 2026 на «Роде»).
#
# НАЗВАННЫЙ ПРЕДЕЛ: требование живёт в ТЕСТЕ НАБОРА, а не в страже момента записи, — значит
# пункт без корня попадёт в файл и будет назван лишь на следующем полном прогоне
# (`case-2026-09-07-check-shaped-as-test-does-not-guard`). Уровень выше — отказ на записи —
# ставится только с измеренной точностью, и её пока нет.
ROOT_MIN_ID="${BACKLOG_ROOT_MIN_ID:-306}"
ROOT_BAD=""
ROOT_CUR=""
ROOT_SEEN=0
ROOT_ITEMS=0
while IFS= read -r _line; do
    [ -n "$_line" ] || continue
    if grep -qE "$T5E_ITEM_RE" <<< "$_line"; then
        [ -n "$ROOT_CUR" ] && ROOT_BAD="$ROOT_BAD $ROOT_CUR"
        ROOT_ITEMS=$((ROOT_ITEMS + 1))
        _n=$(backlog_id_stream <<< "$_line")
        _num=${_n#D}
        if [ "${_num:-0}" -ge "$ROOT_MIN_ID" ] 2>/dev/null; then
            ROOT_CUR="$_n"; ROOT_SEEN=$((ROOT_SEEN + 1))
        else ROOT_CUR=""; fi
        continue
    fi
    case "$_line" in
        *'**Корень.**'*) ROOT_CUR="" ;;
    esac
done <<EOF
$(backlog_strip_fenced < "$REPO/BACKLOG.md" | grep -E "$T5E_ITEM_RE|[*][*]Корень[.][*][*]")
EOF
[ -n "$ROOT_CUR" ] && ROOT_BAD="$ROOT_BAD $ROOT_CUR"
{ [ "$ROOT_SEEN" -gt 0 ] && [ "$ROOT_ITEMS" -eq "$T5E_OPEN" ] && [ -z "${ROOT_BAD// /}" ]; } && ok \
    || skip_or_bad T5g "осмотрено пунктов $ROOT_ITEMS при $T5E_OPEN открытых, из них от D$ROOT_MIN_ID — $ROOT_SEEN; без строки «**Корень.**» (R-номер, «нет — почему» либо «новый — устройство»):${ROOT_BAD:- —}"

# --- T5k: ЗАКРЫТИЕ С ДРОБЬЮ несёт команду показания (14 сентября 2026) -----------------
# Повод измерен в день заведения: за один день я четырежды назвал число, которое говорило не
# о том множестве, — 9 носителей вместо 0, 3 ложно-зелёных вместо 0, 19 ответных правок из 70
# вместо 1 из 16, и пара зависимости, которой нет. Самый дорогой промах (19 из 70) прожил
# дольше всех именно потому, что число лежало ПРОЗОЙ в вердикте: механизм пересчёта показаний
# судит строку «**Показание.**», а прозы не касается. Требование: закрытие, называющее дробь
# «N из M», обязано дать команду, которой эта дробь ВЫВОДИТСЯ, — тогда пересчёт поймает
# расхождение сам, как он поймал D358 в тот же день («в файле 29, в мире 30»).
#
# ПОРОГ ПО НОМЕРУ, как у «Рода» и «Корня», и по той же причине: 83 закрытия из 115 с дробью
# написаны до правила, и требовать у них команду значило бы выдать 83 ложных отказа на
# правильной работе. Порог — номер первого пункта, закрытого после заведения ноги.
#
# НАЗВАННЫЙ ПРЕДЕЛ: дробь опознаётся формой «N из M». Число, названное процентом или словами,
# нога не видит; расширять перечень форм не стал — это корень R3. Условие снятия: появится
# признак, различающий РОЛЬ числа (показание против пересказа истории), а не его вид.
READ_MIN_ID="${BACKLOG_READING_MIN_ID:-413}"
READ_BAD=""; READ_CUR=""; READ_SEEN=0; READ_ITEMS=0; READ_FRAC=0
while IFS= read -r _line; do
    [ -n "$_line" ] || continue
    # Состояние сбрасывается на ЛЮБОМ пункте, а не только на закрытом: иначе строка
    # «**Показание.**» следующего ОТКРЫТОГО пункта гасит находку у закрытого выше
    # (поймано мутантом при заведении ноги 14 сентября 2026 — она была вакуумна).
    case "$_line" in
        "- ☐ "*|"- ◐ "*)
            [ -n "$READ_CUR" ] && READ_BAD="$READ_BAD $READ_CUR"
            READ_CUR=""; READ_ID=""
            continue ;;
    esac
    case "$_line" in
        "- ☑ "*|"- ⊘ "*)
            [ -n "$READ_CUR" ] && READ_BAD="$READ_BAD $READ_CUR"
            READ_ITEMS=$((READ_ITEMS + 1))
            _n=$(backlog_id_stream <<< "$_line")
            _num=${_n#D}
            READ_CUR=""
            if [ "${_num:-0}" -ge "$READ_MIN_ID" ] 2>/dev/null; then
                READ_SEEN=$((READ_SEEN + 1)); READ_ID="$_n"; READ_HASFRAC=0
            else READ_ID=""; fi
            continue ;;
    esac
    [ -n "${READ_ID:-}" ] || continue
    case "$_line" in
        *'**Показание.**'*) READ_CUR="" ; READ_HASFRAC=0 ; READ_ID="" ;;
        *)
            if [ "${READ_HASFRAC:-0}" -eq 0 ] && grep -qE '[0-9]+ из [0-9]+' <<< "$_line"; then
                READ_HASFRAC=1; READ_FRAC=$((READ_FRAC + 1)); READ_CUR="$READ_ID"
            fi ;;
    esac
done <<EOF
$(backlog_strip_fenced < "$REPO/BACKLOG.md")
EOF
[ -n "$READ_CUR" ] && READ_BAD="$READ_BAD $READ_CUR"
# ПУСТОЙ УНИВЕРСУМ ЗДЕСЬ ЗАКОНЕН, и это отличие от соседних ног. У них универсум — ОТКРЫТЫЕ
# пункты, они есть всегда; здесь — ЗАКРЫТЫЕ, а они регулярно уезжают в архив, и сразу после
# прогона архиватора их ноль. Контроль «осмотрено > 0», скопированный у соседа, уронил ногу
# в тот же час, когда архиватор унёс оба закрытия (14 сентября 2026). Ноль закрытий — не
# чистота и не поломка, а «судить нечего»: называется словом, в провал не превращается.
if [ "$READ_ITEMS" -eq 0 ]; then
    echo "  … T5k: закрытых пунктов в файле нет — судить нечего (архиватор унёс)"
    ok
else
    [ -z "${READ_BAD// /}" ] && ok \
        || bad T5k "закрытий осмотрено $READ_ITEMS, от D$READ_MIN_ID — $READ_SEEN, с дробью $READ_FRAC; дробь без команды «**Показание.**»:${READ_BAD:- —}"
fi

# --- T5i: пункт от D306 несёт строку «**Зелёная сторона.**» (D405, 13 сентября 2026) --------
# Красная «Проверка» открытого пункта доказывает лишь, что мир сейчас не таков, как объявлено,
# — не то, что она позеленеет от починки, а не от слепоты. Строка называет команду либо адрес
# фикстуры/мутанта/прежнего коммита в обратных кавычках, где та же команда даёт 0; исполняет
# фикстуры `test_backlog_green_side.sh`, здесь — форма. Порог и положительный контроль — как у
# «Рода» и «Корня»: осмотрено от порога > 0, осмотрено всего ровно столько, сколько открытых.
GREEN_MIN_ID="${BACKLOG_GREEN_MIN_ID:-306}"
GREEN_BAD=""
GREEN_CUR=""
GREEN_SEEN=0
GREEN_ITEMS=0
while IFS= read -r _line; do
    [ -n "$_line" ] || continue
    if grep -qE "$T5E_ITEM_RE" <<< "$_line"; then
        [ -n "$GREEN_CUR" ] && GREEN_BAD="$GREEN_BAD $GREEN_CUR"
        GREEN_ITEMS=$((GREEN_ITEMS + 1))
        _n=$(backlog_id_stream <<< "$_line")
        _num=${_n#D}
        if [ "${_num:-0}" -ge "$GREEN_MIN_ID" ] 2>/dev/null; then
            GREEN_CUR="$_n"; GREEN_SEEN=$((GREEN_SEEN + 1))
        else GREEN_CUR=""; fi
        continue
    fi
    case "$_line" in
        *'**Зелёная сторона.**'*'`'*) GREEN_CUR="" ;;   # команда либо адрес в обратных кавычках
    esac
done <<EOF
$(backlog_strip_fenced < "$REPO/BACKLOG.md" | grep -E "$T5E_ITEM_RE|[*][*]Зелёная сторона[.][*][*]")
EOF
[ -n "$GREEN_CUR" ] && GREEN_BAD="$GREEN_BAD $GREEN_CUR"
{ [ "$GREEN_SEEN" -gt 0 ] && [ "$GREEN_ITEMS" -eq "$T5E_OPEN" ] && [ -z "${GREEN_BAD// /}" ]; } && ok \
    || skip_or_bad T5i "осмотрено пунктов $GREEN_ITEMS при $T5E_OPEN открытых, из них от D$GREEN_MIN_ID — $GREEN_SEEN; без строки «**Зелёная сторона.**» с командой или адресом в обратных кавычках:${GREEN_BAD:- —}"


# --- T5h: строка «**Очередь.**», если она есть, несёт целое ≥ 1 -------------------
# Поле заведено 12 сентября 2026 (план разгребания долга): порядок взятия жил в голове,
# теперь его несёт пункт, а коллектор на Stop называет «следующий к взятию» по наименьшему
# номеру. Поле ОПЦИОНАЛЬНО — у ожиданий и взятых номера нет, — но если есть, то целое от 1:
# «0», слово или пустое значение сломали бы выбор наименьшего молча. Разбор — у владельца
# `backlog_open_items`, пустое значение он отдаёт как «?», чтобы нога это видела.
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ двумя числами, как у соседей: строк разбора ровно столько, сколько
# открытых видит библиотека, и фикстура с тремя нарушениями даёт ровно два имени.
Q_BAD=$(backlog_open_items "$REPO/BACKLOG.md" | awk -F'\t' '$4 != "" && $4 !~ /^[1-9][0-9]*$/ { printf " %s(%s)", $1, $4 }')
Q_ROWS=$(backlog_open_items "$REPO/BACKLOG.md" | wc -l | tr -d ' ')
{ [ "$Q_ROWS" -eq "$T5E_OPEN" ] && [ -z "${Q_BAD// /}" ]; } && ok \
    || bad T5h "разобрано пунктов $Q_ROWS при $T5E_OPEN открытых; «Очередь» не целое ≥ 1 у:${Q_BAD:- —}"
_qfx=$(mktemp -d)
printf -- '- ☐ **D871** ноль\n  **Очередь.** 0\n- ☐ **D872** словом\n  **Очередь.** два\n- ☐ **D873** верно\n  **Очередь.** 7\n' > "$_qfx/BACKLOG.md"
Q_CTRL=$(backlog_open_items "$_qfx/BACKLOG.md" | awk -F'\t' '$4 != "" && $4 !~ /^[1-9][0-9]*$/ { printf "%s ", $1 }')
[ "$Q_CTRL" = "D871 D872 " ] && ok || bad T5h-ctrl "положительный контроль: ожидались D871 D872, получено «${Q_CTRL}»"
rm -rf "$_qfx"

# --- T6: боевые читатели видят ТО ЖЕ, что библиотека ---
# Предмет проверки — согласие читателей, а не их внутренности: копия признака у любого из
# них снова разойдётся молча, и увидеть это можно только сравнением их ответов.
#
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ (7 сентября 2026). Предполагалось: равенство ответов значит
# «читатели согласны». Ложно — равенство выполняется ТОЖДЕСТВЕННО при обоюдном нуле, а
# ноль у обоих ровно тогда, когда общий признак ослеп: оба читателя берут его из одной
# библиотеки. Замер: с занулённым `backlog_item_re` библиотека сказала 0, архиватор
# «открытых: 0», и обе ноги T6 остались зелёными при слепом механизме.
# Держит величина: сравнение засчитывается только на НЕПУСТОЙ выборке.
REAL_OPEN=$(backlog_ids "$REPO/BACKLOG.md" "$BACKLOG_OPEN_MARKS" | wc -l | tr -d ' ')
ARCH_SAYS=$(bash "$REPO/scripts/backlog-archive.sh" check 2>/dev/null \
    | grep -oE 'открытых: [0-9]+' | grep -oE '[0-9]+')
{ [ "$REAL_OPEN" -gt 0 ] && [ "${ARCH_SAYS:-x}" = "$REAL_OPEN" ]; } && ok \
    || skip_or_bad T6 "архиватор насчитал открытых ${ARCH_SAYS:-нет ответа}, библиотека — $REAL_OPEN"

# Считаем идентификаторы ТОЛЬКО из строк-находок, а не из всего вывода: пояснение
# страж печатает прозой и упоминает там прошлые пункты (D71, D92). Первая редакция этой
# проверки считала D-номера где угодно и обвинила исправного стража — предмет счёта не
# совпал с предметом утверждения. Маркеры — все четыре, что печатает страж (✅ ⏳ 🧑 ⚠️):
# первая редакция знала одну ⚠️ и два символа, которых страж не печатает вовсе, и упала
# 30 августа 2026, когда условие возврата D206 наступило впервые и строка ✅ появилась.
#
# Тот же положительный контроль и по той же причине: «страж назвал столько же, сколько
# библиотека» при 0 = 0 выполняется у ослепшего стража ровно так же, как у исправного.
RET_SAYS=$(bash "$REPO/scripts/backlog-return-check.sh" 2>&1 \
    | grep -E '^\s+(✅|⏳|🧑|⚠️)' | grep -oE 'D[0-9]+' | sort -u | wc -l | tr -d ' ')
{ [ "$REAL_OPEN" -gt 0 ] && [ "$RET_SAYS" -eq "$REAL_OPEN" ]; } && ok \
    || skip_or_bad T6 "страж возврата назвал $RET_SAYS пунктов, открытых $REAL_OPEN"

echo "backlog item shape: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
