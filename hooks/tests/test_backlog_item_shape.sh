#!/usr/bin/env bash
# test_backlog_item_shape.sh — пункт долга опознаётся правилом, а не одной вёрсткой.
#
# Результат: все читатели BACKLOG.md видят один и тот же набор пунктов
# Проверка результата: bash hooks/tests/test_backlog_item_shape.sh даёт 0
#
# Повод. 28 августа 2026 пункты долга сменили вёрстку со списка (`- ☑ **D42**`) на
# заголовок (`### D42 ☑ …`). Три стража имели СВОЮ копию признака `^- ` и отказали в тот
# же день, молча и по-разному:
#   · `backlog-archive`      — «переносить нечего» при двух ☑ в файле;
#   · `backlog-return-check` — ноль открытых пунктов, условия возврата не проверялись;
#   · `backlog-vanish-check` — ноль идентификаторов, пропажа пункта невидима.
# Сутки это не всплывало, потому что проверка результата архиватора (`grep -c '^- ☑'`)
# искала ту же вёрстку и была зелёной ровно тогда, когда он слеп.
#
# Тест держит ПРАВИЛО: набор пунктов не зависит от вёрстки, и все читатели видят один и
# тот же набор. Проверяется поведением на обеих вёрстках, а не чтением кода.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$REPO/hooks/backlog-lib.sh"
[ -f "$LIB" ] || { echo "FAIL: нет $LIB"; exit 1; }
# shellcheck source=hooks/backlog-lib.sh
. "$LIB"

PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# --- T1: обе вёрстки дают ОДИН набор идентификаторов ---
cat > "$TMP/list.md" <<'EOF'
## Открытое
- ☐ **D41** первый
  тело
- ☑ **D42** второй
  тело
EOF
cat > "$TMP/head.md" <<'EOF'
## Открытое
### D41 ☐ первый
тело
### D42 ☑ второй
тело
EOF
L=$(backlog_ids "$TMP/list.md" | tr '\n' ' ')
H=$(backlog_ids "$TMP/head.md" | tr '\n' ' ')
[ "$L" = "$H" ] && [ -n "$L" ] && ok || bad T1 "вёрстки дают разный набор: список [$L] против заголовков [$H]"

# --- T2: метки различаются в обеих вёрстках одинаково ---
for f in "$TMP/list.md" "$TMP/head.md"; do
    D=$(backlog_ids "$f" "$BACKLOG_DONE_MARKS" | tr '\n' ' ')
    O=$(backlog_ids "$f" "$BACKLOG_OPEN_MARKS" | tr '\n' ' ')
    { [ "$D" = "D42 " ] && [ "$O" = "D41 " ]; } && ok \
        || bad T2 "$(basename "$f"): закрытые [$D], открытые [$O] — ожидались D42 и D41"
done

# --- T3: КОНТРПРИМЕР — легенда несёт все четыре метки и пунктом НЕ является ---
backlog_is_item '**Легенда статусов:** ☐ todo · ◐ in-progress · ☑ done · ⊘ waived' \
    && bad T3 "строка легенды засчитана пунктом" || ok

# --- T4: КОНТРПРИМЕР — проза с меткой и без номера пунктом не является ---
backlog_is_item 'Пункт, чей инвариант сломан, снова открыт — верни ему ☐ в BACKLOG.md.' \
    && bad T4 "проза засчитана пунктом" || ok

# --- T5: порядок метки и номера любой (в списке метка первая, в заголовке вторая) ---
backlog_is_item '- ☑ **D12** что-то' && ok || bad T5 "списочная вёрстка не опознана"
backlog_is_item '### D109 ☑ что-то' && ok || bad T5 "заголовочная вёрстка не опознана"

# --- T6: боевые читатели видят ТО ЖЕ, что библиотека ---
# Предмет проверки — согласие читателей, а не их внутренности: копия признака у любого из
# них снова разойдётся молча, и увидеть это можно только сравнением их ответов.
REAL_OPEN=$(backlog_ids "$REPO/BACKLOG.md" "$BACKLOG_OPEN_MARKS" | wc -l | tr -d ' ')
ARCH_SAYS=$(bash "$REPO/scripts/backlog-archive.sh" check 2>/dev/null \
    | grep -oE 'открытых: [0-9]+' | grep -oE '[0-9]+')
[ "${ARCH_SAYS:-x}" = "$REAL_OPEN" ] && ok \
    || bad T6 "архиватор насчитал открытых ${ARCH_SAYS:-нет ответа}, библиотека — $REAL_OPEN"

# Считаем идентификаторы ТОЛЬКО из строк-находок, а не из всего вывода: пояснение
# страж печатает прозой и упоминает там прошлые пункты (D71, D92). Первая редакция этой
# проверки считала D-номера где угодно и обвинила исправного стража — предмет счёта не
# совпал с предметом утверждения. Маркеры — все четыре, что печатает страж (✅ ⏳ 🧑 ⚠️):
# первая редакция знала одну ⚠️ и два символа, которых страж не печатает вовсе, и упала
# 30 августа 2026, когда условие возврата D206 наступило впервые и строка ✅ появилась.
RET_SAYS=$(bash "$REPO/scripts/backlog-return-check.sh" 2>&1 \
    | grep -E '^\s+(✅|⏳|🧑|⚠️)' | grep -oE 'D[0-9]+' | sort -u | wc -l | tr -d ' ')
[ "$RET_SAYS" -eq "$REAL_OPEN" ] && ok \
    || bad T6 "страж возврата назвал $RET_SAYS пунктов, открытых $REAL_OPEN"

echo "backlog item shape: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
