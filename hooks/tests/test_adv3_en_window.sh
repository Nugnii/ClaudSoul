#!/usr/bin/env bash
# test_adv3_en_window.sh — страж и генератор обязаны смотреть в ОДНО окно поиска «# en:».
#
# Найдено противником (раунд 1, 2026-08-25): окна разъехались на строку —
#   страж     awk 'NR <= 9 && /^# en:/ ...'
#   генератор awk 'NR <= 8 && /^# en:...' ...'
# Английское описание на строке 9 страж проверял и засчитывал, а генератор не видел и
# молча подставлял в английскую витрину русскую строку — фоллбек, задуманный для
# «английского нет вовсе», срабатывал на «английский есть, но я до него не дочитал».
#
# Починено сведением окон: у обоих граница — конец ведущего блока комментариев, а не
# произвольная восьмёрка. Теперь `# en:` на девятой строке ВИДЯТ ОБА, и это намеренно.
#
# Тест переписан под инвариант, а не под конкретное число строк: он утверждает, что
# описание, попавшее в витрину, проверено стражем. Прежняя формулировка закрепляла
# поведение старого генератора («страж не должен читать строку 9») и после починки
# краснела бы на верном коде — тест, сторожащий отменённое требование, хуже отсутствия
# теста. Инвариант переживёт любой следующий сдвиг границы.
#
# Достижимость: любой хук, у которого шапка длиннее восьми строк до «# en:».
# В нынешнем корпусе все «# en:» стоят на строке 3, поэтому расхождение спало.

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
GUARD="$REPO/hooks/tests/test_hook_header_contract.sh"
GEN="$REPO/scripts/regen-readme-skills.sh"
TMP="$(mktemp -d)"
FAKE="$TMP/repo"
mkdir -p "$FAKE/hooks/tests" "$FAKE/skills/demo"
# Минимальный скилл обязателен: генератор с некоторых пор отказывает на пустой таблице —
# замена стёрла бы живую витрину, а отказ после разрушения отказом не является.
# Фикстура проверяет окно поиска «# en:», а не поведение на пустом дереве.
printf -- '---\nname: demo\ndescription: "Демо-скилл для фикстуры окна."\ndescription_en: "Fixture skill for the window test."\n---\n' > "$FAKE/skills/demo/SKILL.md"
ln -s "$GUARD" "$FAKE/hooks/tests/test_hook_header_contract.sh"

RU="PreToolUse: русское описание вполне законченное."
EN="PreToolUse: an English description that is complete."
{
    printf '#!/usr/bin/env bash\n'
    printf '# en9.sh — %s\n' "$RU"
    # Наполнитель начинается с ЗАГЛАВНОЙ намеренно: страж считает переносом строку
    # комментария, начатую со строчной буквы или тире, и на «# строка-наполнитель»
    # справедливо краснел бы — фикстура тогда проверяла бы не окно, а признак переноса.
    for i in 3 4 5 6 7 8; do printf '# Наполнитель %s.\n' "$i"; done
    printf '# en: %s\n' "$EN"
} > "$FAKE/hooks/en9.sh"

printf '# fake\n<!-- SKILLS-TABLE:START -->\n<!-- SKILLS-TABLE:END -->\n<!-- HOOKS-TABLE:START -->\n<!-- HOOKS-TABLE:END -->\n' > "$FAKE/README.md"

guard_out=$(bash "$FAKE/hooks/tests/test_hook_header_contract.sh" 2>&1)
checked=$(printf '%s' "$guard_out" | sed -n 's/.*contract: \([0-9]*\)\/.*/\1/p')

README_LANG=en bash "$GEN" "$FAKE" >/dev/null 2>&1
row=$(grep -F '`en9`' "$FAKE/README.md" || true)

fails=0
# Генератор берёт с этого хука ДВА описания — русское со строки 2 и английское со
# строки 9. Значит страж обязан проверить оба: всё, что уехало в витрину, проверено.
if [ "$checked" != "2" ]; then
    echo "FAIL [test_hook_header_contract.sh]: страж проверил $checked описания(й) вместо 2 —"
    echo "     генератор берёт с этого хука и русскую строку 2, и английскую строку 9;"
    echo "     непроверенное описание уезжает в витрину без стража."
    fails=$((fails + 1))
fi
case "$row" in
    *"$EN"*) ;;
    *)  echo "FAIL [regen-readme-skills.sh]: в английскую витрину уехала русская строка."
        echo "     Строка таблицы: $row"
        echo "     Ожидалось английское: $EN"
        fails=$((fails + 1)) ;;
esac

if [ "$fails" -eq 0 ]; then
    echo "PASS: окна стража и генератора совпадают"
    echo "adv3 en window: 1/1 passed"
    exit 0
fi
echo "adv3 en window: 0/1 passed ($fails расхождения(й))"
exit 1
