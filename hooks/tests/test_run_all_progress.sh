#!/usr/bin/env bash
# test_run_all_progress.sh — оборванный прогон оставляет след, а не пустой лог.
#
# Результат: прогон, остановленный по таймауту вызывающего, оставляет в выводе счёт
#            пройденных тестов, а не ноль байт
# Проверка результата: bash hooks/tests/test_run_all_progress.sh даёт 0
#
# Повод (6 сентября 2026, поправка владельца). run_all.sh печатал в stdout только итоговую
# строку и хвосты ПАДЕНИЙ, а успехи молчали. Два синхронных прогона подряд упёрлись в
# десятиминутный предел вызывающего и были убиты — лог остался пустым (0 байт за 5 минут
# при живом процессе), хотя тесты успели отработать: их вывод лежал в $OUT_DIR, и
# `trap rm -rf "$OUT_DIR" EXIT` уносил его вместе с прогоном.
#
# Это ровно тот класс, ради которого сам run_all печатает хвосты падений — его шапка
# говорит: «Проверка, чьи доказательства недоступны в том месте, где её читают, сообщает
# факт провала и скрывает его содержание». Для упавших ТЕСТОВ класс был закрыт, для
# оборванного ПРОГОНА оставался открытым.
#
# ОБЛАСТЬ: только наличие следа. Полнота вывода при обрыве не проверяется — часть тестов
# по построению не успевает, и требовать от убитого процесса полного отчёта значило бы
# проверять не тот предмет.
set -uo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/../.." && pwd)"
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# T1: прогон, убитый на середине, оставляет счёт пройденных.
# Шаг прогресса ставим мелким, чтобы след появился заведомо раньше обрыва.
( cd "$ROOT" && PROGRESS_EVERY=2 TEST_TIMEOUT=5 bash hooks/tests/run_all.sh > "$TMP/out.log" 2>&1 ) &
RUNPID=$!
# Ждём ПРИЗНАК начала работы, а не время: лог перестал быть пустым.
for _ in $(seq 1 600); do
    [ -s "$TMP/out.log" ] && break
    kill -0 "$RUNPID" 2>/dev/null || break
    perl -e 'select(undef,undef,undef,0.1)' 2>/dev/null || sleep 1
done
# ...и даём работе ПРОДВИНУТЬСЯ (8 сентября 2026). Непустой лог — ещё не признак того, что
# прогон дошёл до отметки прогресса: первую строку даёт уже первый УПАВШИЙ тест («───── имя»),
# а строка «… прошло N» печатается только каждые PROGRESS_EVERY тестов. Обрыв сразу после
# первой строки роняет ноги T1b/T2 не потому, что счёт потерян, а потому, что его ещё не было.
#
# Ждём ВРЕМЯ, а проверяем СОДЕРЖИМОЕ — это не тавтология. Ждать появления самой строки «прошло»
# было бы ею: нога проверяет ровно её наличие, и ожидание сделало бы зелень неизбежной.
# Величина выведена из устройства прогона: PROGRESS_EVERY=2 и TEST_TIMEOUT=5 (заданы выше),
# то есть двум тестам хватает 10 с даже когда оба висят до предела; берём с запасом.
_PROGRESS_GRACE="${RUN_ALL_PROGRESS_GRACE:-12}"
for _ in $(seq 1 "$_PROGRESS_GRACE"); do
    grep -qE 'прошло [0-9]+' "$TMP/out.log" 2>/dev/null && break
    kill -0 "$RUNPID" 2>/dev/null || break
    sleep 1
done
# Убиваем ДЕРЕВО, а не родителя с одним уровнем детей (8 сентября 2026).
#
# Здесь стояло `kill -9 "$RUNPID"; pkill -9 -P "$RUNPID"`, и порядок был губителен: родитель
# умирает первым, дети в ту же секунду уходят к pid 1, и `pkill -P` по мёртвому родителю их
# уже не находит. Внуков он не искал вовсе. Воспроизведено на трёхуровневой фикстуре: после
# такой пары ребёнок ВЫЖИЛ с PPID=1 и внук выжил под ним; после `_kill_tree` мертвы оба.
#
# Цена измерена в бою: три осиротевших прогона набора жили 3 часа 49 минут, 46 процессов,
# load average 7,9. Это тот самый дефект с положительной обратной связью, что описан в шапке
# `run_all.sh:31-37` («100 осиротевших процессов, load 41,6»). Там же сказано, что починка
# «закрывает КЛАСС: ни один будущий тест не сможет пережить свою смерть детьми» — утверждение
# оказалось неверным: оно закрыло класс для тестов, которых убивает РАННЕР, и не закрыло для
# теста, который убивает процессы своим кодом. Носителя искали по симптому, а не по устройству.
#
# Помощник берётся ИЗ `run_all.sh`, а не копируется сюда: копия разошлась бы с оригиналом
# молча (род K). Тот же приём и по той же причине стоит в `test_runner_kills_tree.sh:82`.
# С 13 сентября 2026 помощник — в hooks/timeout-lib.sh (D369), раннер его зовёт оттуда же.
TIMEOUT_LIB_SRC="${TIMEOUT_LIB_SRC:-$DIR/../timeout-lib.sh}"
# shellcheck source=/dev/null
[ -f "$TIMEOUT_LIB_SRC" ] && . "$TIMEOUT_LIB_SRC"
if command -v kill_tree >/dev/null 2>&1; then
    kill_tree "$RUNPID"
else
    # Раннер потерял или переименовал помощника — бьём как умеем, но детей ПЕРВЫМИ.
    pkill -9 -P "$RUNPID" 2>/dev/null
    kill -9 "$RUNPID" 2>/dev/null
fi
wait "$RUNPID" 2>/dev/null

if [ -s "$TMP/out.log" ]; then ok
else bad "T1" "оборванный прогон оставил ПУСТОЙ лог — доказательств работы нет"; fi

if grep -qE 'прошло [0-9]+' "$TMP/out.log"; then ok
else bad "T1b" "в логе нет счёта пройденных: $(head -c 120 "$TMP/out.log")"; fi

# T2: КОНТРПРИМЕР — счёт не выдумывает работу. Число пройденных обязано быть > 0 и
# не больше числа тестовых файлов в дереве.
N=$(grep -oE 'прошло [0-9]+' "$TMP/out.log" | tail -1 | grep -oE '[0-9]+')
TOTAL=$(ls "$DIR"/test_*.sh 2>/dev/null | wc -l | tr -d ' ')
if [ -n "$N" ] && [ "$N" -gt 0 ] && [ "$N" -le "$TOTAL" ]; then ok
else bad "T2" "счёт пройденных вне диапазона: «${N}» при $TOTAL тестах в дереве"; fi

echo "run_all progress: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
