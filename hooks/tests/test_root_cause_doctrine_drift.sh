#!/usr/bin/env bash
# test_root_cause_doctrine_drift.sh — доктрина разбора одна во всех носителях.
#
# Результат: порядок разбора и признак остановки совпадают в библиотеке, правилах и
#            скиллах; редакций доктрины в дереве одна
# Проверка результата: bash hooks/tests/test_root_cause_doctrine_drift.sh даёт 0
#
# Повод, 29 августа 2026: порядок разбора существовал ТРЕМЯ редакциями. `five-whys-gate`
# нёс свежую (с шагом «вширь по проявлениям», введённым 28.08), `error-tracker:127` — ту,
# что 28.08 отменили, `rework-detector:171` — пять готовых «почему», то есть фикс-глубину,
# отменённую `/retro` 3.1 («критерий остановки — НЕ глубина 5»). Два хука в одной сессии
# говорили разное, и оба срабатывают на поводах ОДНОГО контура.
#
# Машинные носители (хуки) держатся вызовом функции — это проверяется отсутствием своих
# редакций. Человеческие (rules/CLAUDE.md, /retro, /adversary) вызвать функцию не могут,
# их держит совпадение КОРОТКИХ маркеров: выпадение целого шага ловится, перефразировка
# внутри шага — нет. Это назван предел, а не недосмотр: маркер длиной в предложение
# сделал бы тест хрупким к любой правке слога.
# Условие снятия: предел держится, пока доктрина живёт в человеческих носителях отдельным
# текстом. Станет она вставляться в них генератором из библиотеки (как таблицы скиллов в
# README) — сверять маркеры будет незачем, и предел снимется вместе с ручной копией.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$ROOT/hooks/root-cause-lib.sh"
RULES="$ROOT/rules/CLAUDE.md"
RETRO="$ROOT/skills/retro/SKILL.md"
ADV="$ROOT/skills/adversary/SKILL.md"
for f in "$LIB" "$RULES" "$RETRO" "$ADV"; do
    [ -f "$f" ] || { echo "FAIL: нет $f"; exit 1; }
done

PASS=0; FAIL=0

# Инварианты доктрины: короткие маркеры, каждый — отдельный ШАГ или условие остановки.
MARKERS=(
    'ни одним путём'      # операциональный признак корня (даёт необходимость, не корень)
    'ратья корня'         # шаг вбок (регистр первой буквы разный в носителях)
    'ПРОЯВЛЕНИЯ'          # ширина по проявлениям — с заглавных в правилах/либе
    'дробь'               # специфичность: N мест со звеном, M из них с симптомом
    'корней несколько'    # расхождение цепочек = несколько корней, а не подъём вверх
    'верный вход'         # вторая линия спуска — по данным, а не только по исполнению
)

check_marker() {   # <файл> <маркер> <метка>
    if grep -qi -- "$2" "$1"; then PASS=$((PASS+1))
    else FAIL=$((FAIL+1)); echo "FAIL [$3]: в $(basename "$1") нет маркера «$2»"; fi
}

# --- T1: библиотека несёт все инварианты ---
for m in "${MARKERS[@]}"; do check_marker "$LIB" "$m" "T1"; done

# --- T2: человеческие носители несут их же ---
for m in "${MARKERS[@]}"; do
    check_marker "$RULES" "$m" "T2-rules"
    check_marker "$RETRO" "$m" "T2-retro"
    check_marker "$ADV" "$m" "T2-adversary"
done

# --- T3: признак остановки — НЕ число звеньев ---
# Правила и /retro обязаны прямо говорить, что глубина не критерий.
if grep -q 'ориентир' "$RULES" && grep -qi 'НЕ глубина 5\|ориентир' "$RETRO"; then PASS=$((PASS+1))
else FAIL=$((FAIL+1)); echo "FAIL [T3]: остановка по числу звеньев не опровергнута в правилах/retro"; fi

# --- T4: ГЛАВНОЕ — у хуков нет СВОИХ редакций доктрины ---
# Признак своей редакции: собственный нумерованный список «почему» либо порядок разбора,
# написанный в теле хука мимо библиотеки. Проверяется на всех хуках, а не на трёх
# известных: новая редакция в четвёртом хуке — тот же дефект.
OWN=""
while IFS= read -r h; do
    case "$(basename "$h")" in root-cause-lib.sh) continue ;; esac
    # «Почему пришлось», «Почему предыдущая» … — форма готового списка вопросов.
    if grep -qE '[0-9]\. Почему |Почему пришлось править' "$h" 2>/dev/null; then
        OWN="$OWN $(basename "$h")"
        continue
    fi
    # Порядок разбора в тексте хука без вызова функции библиотеки.
    if grep -qiE 'ВШИРЬ.*ВГЛУБЬ|ВГЛУБЬ.*ВШИРЬ' "$h" 2>/dev/null \
       && ! grep -q 'rc_doctrine' "$h" 2>/dev/null; then
        OWN="$OWN $(basename "$h")"
    fi
done < <(find "$ROOT/hooks" -maxdepth 1 -name '*.sh' -type f)
if [ -z "${OWN// /}" ]; then PASS=$((PASS+1))
else FAIL=$((FAIL+1)); echo "FAIL [T4]: своя редакция доктрины в хуках:$OWN — текст берётся из rc_doctrine_*"; fi

# --- T5: КОНТРПРИМЕР — потребители действительно зовут функцию ---
for h in five-whys-gate.sh error-tracker.sh rework-detector.sh; do
    if grep -q 'rc_doctrine' "$ROOT/hooks/$h"; then PASS=$((PASS+1))
    else FAIL=$((FAIL+1)); echo "FAIL [T5]: $h не потребляет доктрину из библиотеки"; fi
done

# --- T6: КОНТРПРИМЕР — упоминание маркера в комментарии-поводе не считается вызовом ---
# (страж не должен зеленеть от того, что слово «братья корня» попало в шапку хука)
if grep -q 'rc_doctrine_full\|rc_doctrine_short' "$LIB"; then PASS=$((PASS+1))
else FAIL=$((FAIL+1)); echo "FAIL [T6]: в библиотеке нет функций доктрины"; fi

# --- T7: отменённое правило подъёма не вернулось в МАШИННЫЙ источник ---
# «Поднимайся, пока звено не накроет все проявления» отменено 30 августа 2026: оно требует
# ОДИН накрывающий узел, чем запрещает исход «корней несколько», и выталкивает вверх ровно
# в момент расхождения цепочек. В человеческих носителях фраза законно остаётся как
# названный контрпример («прежняя редакция говорила…») — потому тест смотрит только в
# библиотеку, где текст инжектится в ход как действующее указание.
if grep -qE 'поднимайся, пока|пока звено не накроет' "$LIB"; then
    FAIL=$((FAIL+1)); echo "FAIL [T7]: отменённое правило подъёма вернулось в rc_doctrine_*"
else PASS=$((PASS+1)); fi

# --- T8: КОНТРПРИМЕР к T7 — человеческому носителю фраза не запрещена ---
# Иначе тест заставил бы стереть историю правки, и следующий читатель не узнал бы, что
# именно отменено (`feedback_state_docs_not_chronicle` касается наслоения, а не отмен).
if grep -qi 'прежняя редакция' "$RULES"; then PASS=$((PASS+1))
else FAIL=$((FAIL+1)); echo "FAIL [T8]: в правилах не назван отменённый вариант — читатель не узнает, что изменилось"; fi

echo "root-cause doctrine drift: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
