#!/usr/bin/env bash
# test_backlog_relative_dates.sh — относительные даты в пунктах BACKLOG гниют.
#
# Корень (2026-08-08, вопрос владельца «сегодня — это когда?»): «сегодня» в D50
# прожило неделю, датировать пришлось раскопкой git. Правило «даты только
# абсолютные» существовало текстом и не исполнилось — теперь оно страж.
#
# Область: строки-пункты (`- ☐/◐/☑/⊘`) живого BACKLOG.md. Проза заголовков
# («насколько дефект действует сегодня») — настоящее время, не дата: вне охвата.
# Архив — хроника закрытий, тоже вне охвата.

set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

RELATIVE_RE='сегодня|вчера|завтра|на днях|недавно|на этой неделе'

scan() { # file → 0 чисто; 1 — найдены относительные даты в пунктах (печатает)
    # Альтернация литералов, не bracket-класс: многобайтовые символы внутри
    # [...] GNU grep читает байтовыми диапазонами (pattern-shell-portability).
    grep -nE '^- (☐|◐|☑|⊘)' "$1" 2>/dev/null | grep -E "$RELATIVE_RE" || return 0
    return 1
}

# --- T1: живой BACKLOG.md чист ---
if OUT=$(scan "$ROOT/BACKLOG.md"); then ok
else bad "T1: относительные даты в пунктах BACKLOG" $'\n'"$OUT"$'\n'"  (датируй абсолютно: git log -S по пункту)"; fi

# --- T2: негативный контроль — сканер видит гниющее слово ---
FIX=$(mktemp)
printf -- '- ☐ **X1** поймано сегодня, чиним на днях\n' > "$FIX"
if scan "$FIX" >/dev/null; then bad "T2" "фикстура с «сегодня» прошла как чистая"
else ok; fi
rm -f "$FIX"

# --- T3: проза с «сегодня» вне пунктов — не срабатывает (узкая область) ---
FIX=$(mktemp)
printf -- 'Порядок — по тому, насколько дефект действует сегодня.\n- ☐ **X2** датировано 2026-08-08\n' > "$FIX"
if scan "$FIX" >/dev/null; then ok
else bad "T3" "проза вне пунктов ложно сработала"; fi
rm -f "$FIX"

echo "test_backlog_relative_dates: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
