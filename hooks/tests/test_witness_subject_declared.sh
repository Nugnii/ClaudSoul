#!/usr/bin/env bash
# test_witness_subject_declared.sh — НОВЫЙ свидетель объявляет свой предмет.
# СУДИТ: scripts/behavior-condition-probe.sh
# Объявлено в тот же ход, и не из вежливости: первый же прогон этой ноги поймал ЕЁ САМУ
# как свидетеля без объявленного предмета. Механизм сработал на своём авторе.
#
# Результат: список свидетелей с неразрешённым предметом только УБЫВАЕТ; новый свидетель
#            в него не попадает, потому что несёт в шапке строку `# СУДИТ: <путь>`
# Проверка результата: bash hooks/tests/test_witness_subject_declared.sh даёт 0
#
# ЗАЧЕМ (D342, 20 сентября 2026). Прибор `behavior-condition-probe.sh` выхолащивает предмет
# свидетеля и требует, чтобы честная нога покраснела. Он нашёл 27 ложно-зелёных из 298, у
# кого предмет разрешим, — и молчит о 287, у кого предмет не разрешён вовсе: выхолащивать
# нечего, и такой свидетель не судится НИКАК. Молчание тут неотличимо от «чисто».
#
# ПОЧЕМУ НЕ «ОБЪЯВИТЬ ВСЕМ 287». Предмет выводится из дерева лишь у половины: индекс
# зависимостей даёт РОВНО ОДИН механизм у 298 из 585. Второй владелец вопроса «какой файл
# этот тест ЗАПУСКАЕТ» — `hooks/lib/write_targets.py --calls` — измерен 20 сентября 2026 на
# первых 120 неразрешённых: ровно один механизм он даёт у ТРЁХ (2,5%). Предел у него
# лексический: путь, собранный переменной (`T="$ROOT/hooks/x.sh"; bash "$T"`), ему не виден.
# Вывести предмет механически нельзя — его ОБЪЯВЛЯЕТ автор свидетеля, и только он знает.
#
# ОТСЮДА УСТРОЙСТВО СТОРОЖА: нынешние 287 заморожены реестром, а рост запрещён. Это не
# смягчение: класс закрывается по мере работы над каждым свидетелем, но перестаёт расти
# СЕГОДНЯ. Реестр только убывает — строка уходит, когда предмет объявлен, и вернуться не
# может, потому что вернуть её значит провалить эту же ногу.
#
# ВЛАДЕЛЕЦ ВОПРОСА ОДИН, И ОН НЕ ЗДЕСЬ. Список неразрешённых спрашивается у прибора
# (`--unresolved`), а не выводится здесь заново: две реализации одного признака разошлись бы
# молча — род K реестра, корень R1. Режим отдаёт список ДО дорогой части прибора, поэтому
# нога дешёвая.
#
# НАЗВАННЫЙ ПРЕДЕЛ: нога судит НАЛИЧИЕ объявления, а не его ПРАВДИВОСТЬ. Строка
# `# СУДИТ: <путь>`, указывающая не на тот файл, сделает свидетеля «разрешённым» и отдаст
# его прибору, который выхолостит чужой предмет. Ложное объявление поймает прибор — тест
# останется зелёным на выхолощенном предмете и придёт в очередь ложно-зелёных, — но уже
# следующим прогоном, а не здесь.
# Условие снятия: у объявления появится сверка с поведением — прогон свидетеля на
# выхолощенном ОБЪЯВЛЕННОМ предмете обязан краснеть, и это станет частью этой ноги.
# Проверка снятия: `grep -q "^_subject_behaves()" hooks/tests/test_witness_subject_declared.sh`
# Якорь `^` обязателен, и это поймано ПРИБОРОМ в час написания этой ноги: прежняя
# редакция искала слово-маркер и находила его в СТРОКЕ СОБСТВЕННОГО объявления — была
# зелёной с минуты написания. Тот же дефект чинили тем же днём в `frame-control-lib.sh`,
# и он повторился у автора починки через час. Якорь на определение отсекает
# комментарий: строка объявления начинается с `#`, определение функции — с имени.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO" || exit 1
BASE="hooks/tests/subject-undeclared-baseline.txt"
PROBE="scripts/behavior-condition-probe.sh"

[ -f "$PROBE" ] || { echo "SKIP: прибора нет — это другое дерево"; exit 0; }
[ -f "$BASE" ] || { echo "FAIL: реестра $BASE нет — сравнивать не с чем"; exit 1; }

NOW=$(bash "$PROBE" --unresolved 2>/dev/null) || {
    echo "BROKEN: владелец списка неразрешённых не отработал"; exit 2; }

# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ НЕ ЗАВИСИТ ОТ РЕЕСТРА (23 сентября 2026, D474). Прежний держался
# на его непустоте: «реестр непуст — значит и ответ обязан быть непуст». В тот день реестр
# разгребли до нуля, и контроль перестал действовать САМ — а с ним и различение: прибор,
# выхолощенный до заглушки, отвечает пустотой и кодом 0, то есть ровно тем же, что исправный
# на чистом дереве. Прибор ложной зелени назвал этого свидетеля поимённо.
# Признак живости взят поведенческий: на заведомо негодном дереве (git-репозиторий без
# индекса зависимостей) исправный прибор ЖАЛУЕТСЯ — код 2, слово BROKEN; заглушка отвечает
# нулём и тишиной. Замер 23 сентября: rc=2 против rc=0, вывод против пустоты.
_probe_speaks() {
    local _b _r _rc
    _b=$(mktemp -d) || return 1
    _r="$_b/repo"; mkdir -p "$_r/scripts" "$_r/hooks" || return 1
    cp "$PROBE" "$_r/scripts/" 2>/dev/null || return 1
    cp hooks/subject-probe-lib.sh hooks/timeout-lib.sh "$_r/hooks/" 2>/dev/null || return 1
    ( cd "$_r" && git init -q . ) >/dev/null 2>&1 || return 1
    ( cd "$_r" && CLAUDSOUL_REPO="$_r" bash scripts/behavior-condition-probe.sh --unresolved ) >/dev/null 2>&1
    _rc=$?
    rm -rf "$_b" 2>/dev/null
    [ "$_rc" -ne 0 ]
}
if ! _probe_speaks; then
    echo "BROKEN: прибор молчит там, где обязан жаловаться (дерево без индекса) —"
    echo "        так отвечает и заглушка, и его пустому ответу верить нельзя."
    exit 2
fi

# `grep -c` при НУЛЕ совпадений печатает «0» И выходит кодом 1 — форма `|| echo 0` дописывала
# второй ноль, и переменная становилась «0\n0» («integer expression expected», строка 87).
# Дефект лежал с постройки и ждал состояния мира: ветка требует нуля совпадений, а реестр
# стал пустым 23 сентября 2026, когда разгребли очередь D474. Тот же класс дважды чинили
# раньше — `hooks/knowledge-audit-digest.sh:341`, `hooks/backfill-compliance.sh:204`.
BASE_N=$(grep -cv '^#' "$BASE" 2>/dev/null || true)
case "$BASE_N" in ''|*[!0-9]*) BASE_N=0 ;; esac
NOW_N=$(printf '%s' "$NOW" | grep -c . || true)
if [ "$BASE_N" -gt 0 ] && [ "$NOW_N" -eq 0 ]; then
    echo "BROKEN: владелец вернул ПУСТО при непустом реестре ($BASE_N) —"
    echo "        это поломка прибора, а не разгребённый долг."
    exit 2
fi

NEW=$(printf '%s\n' "$NOW" | grep -v '^$' | grep -vxF -f <(grep -v '^#' "$BASE") || true)
if [ -n "$NEW" ]; then
    echo "FAIL: свидетель без объявленного предмета, и его нет в замороженном реестре:"
    printf '%s\n' "$NEW" | sed 's/^/  · /'
    echo ""
    echo "Предмет выводится из дерева лишь у половины свидетелей — объяви его сам строкой"
    echo "в шапке (первые 30 строк):"
    echo "    # СУДИТ: hooks/<путь к механизму, который этот тест судит>"
    echo "Тогда прибор behavior-condition-probe.sh сможет его выхолостить и проверить, что"
    echo "твой свидетель на мёртвом предмете КРАСНЕЕТ."
    exit 1
fi

GONE=$(grep -v '^#' "$BASE" | grep -vxF -f <(printf '%s\n' "$NOW" | grep -v '^$') || true)
GONE_N=$(printf '%s' "$GONE" | grep -c . || true)
echo "OK: неразрешённых $NOW_N, реестр $BASE_N, объявлено с заморозки $GONE_N"
if [ "$GONE_N" -gt 0 ]; then
    echo "Реестр пора ужать — эти уже объявлены и обязаны уйти из него:"
    printf '%s\n' "$GONE" | sed 's/^/  · /'
fi
exit 0
