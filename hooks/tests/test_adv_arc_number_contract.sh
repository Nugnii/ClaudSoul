#!/usr/bin/env bash
# test_adv_arc_number_contract.sh — атака на санитайзер числа в
# hooks/lib/adversary-run-lib.sh:72 и его четырёх братьев.
#
# ЧТО ДОКАЗЫВАЕТСЯ. Приведение к числу написано так:
#
#     case "${_arc_n:-0}" in ''|*[!0-9]*) _arc_n=0 ;; esac
#
# Подстановка `:-0` подставляет умолчание В ПРЕДМЕТ СРАВНЕНИЯ, а не в переменную. Пустая
# `_arc_n` сравнивается как строка «0», не совпадает ни с `''`, ни с `*[!0-9]*` — ветка
# `''` НЕДОСТИЖИМА ПО ПОСТРОЕНИЮ, присваивания не происходит, и переменная остаётся
# пустой. Ровно тот случай, ради которого санитайзер написан, он и пропускает.
#
# Три следствия, и все наблюдаемы:
#  1. Функция печатает ПУСТУЮ строку, хотя её шапка обещает: «Всегда печатает ЧИСЛО»
#     (adversary-run-lib.sh:29-31). Потребители читают её через `$( )` и сравнивают
#     как число.
#  2. `[ "$_arc_n" -eq 0 ]` на строке 64 падает с кодом 2 и пишет в stderr
#     «integer expression expected» — из хука PreToolUse.
#  3. Из-за упавшего сравнения ветка «воркфлоу, запущенный по пути» (строки 64-79)
#     НЕ ИСПОЛНЯЕТСЯ. Ветка, написанная как запасная, выключается ровно тогда, когда
#     основной разбор не сработал.
#
# Правильная форма лежит через два файла: `scripts/adversary-before-commit.sh:119`
# пишет `case "${_n:-}" in ''|...` — с ПУСТЫМ умолчанием, и там ветка `''` достижима.
set -uo pipefail

HOOK_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PASS=0; FAIL=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

command -v jq >/dev/null 2>&1 || { echo "SKIP: jq недоступен"; exit 0; }

ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

# shellcheck source=/dev/null
. "$HOOK_DIR/lib/adversary-run-lib.sh"

# Вход, на котором `jq -rs` падает: имя скилла в файле есть (дешёвый фильтр пропускает),
# а слурп не собирается.
TR="$TMP/tr.jsonl"
printf '{"message":{"content":[{"type":"text","text":"adversary"}]}}\n' >  "$TR"
printf '{ оборвано\n'                                                   >> "$TR"

N=$(adversary_run_count "$TR" 2>"$TMP/err.txt")
RC=$?

# --- T1: контракт — всегда ЧИСЛО ---
case "$N" in
    ''|*[!0-9]*) bad "T1" "напечатано [$N] — не число; шапка функции обещает «Всегда печатает ЧИСЛО»" ;;
    *)           ok ;;
esac

# --- T2: контракт — всегда код 0 ---
if [ "$RC" = "0" ]; then ok; else bad "T2" "код возврата $RC вместо 0"; fi

# --- T3: контракт — тихо ---
if [ ! -s "$TMP/err.txt" ]; then ok
else bad "T3" "в stderr из хука PreToolUse: $(tr '\n' ' ' < "$TMP/err.txt")"; fi

# --- T4: класс не вернулся в дерево ---
# Изначально нога воспроизводила дефектную форму прямо здесь — так она показывала, ГДЕ
# дефект, но краснела бы вечно независимо от продукта. После починки (9 сентября 2026,
# 8 носителей) она сторожит КЛАСС: подстановка непустого умолчания в предмет сравнения
# делает ветку '' недостижимой, и переменная проходит несанированной.
# Дробь на момент починки: 8 дефектных форм против 27 верных; после — 0 против 35.
_BAD=$(grep -rn ":-0}\" in ''" "$HOOK_DIR" "$HOOK_DIR/../scripts" --include='*.sh' 2>/dev/null | grep -v '/tests/' | head -5)
if [ -z "$_BAD" ]; then ok
else bad "T4" "дефектная форма санитайзера вернулась в дерево: $(printf '%s' "$_BAD" | tr '\n' ' ')"; fi

# --- T5: отрицательный контроль — на здоровом входе контракт соблюдён ---
TR_OK="$TMP/ok.jsonl"
jq -cn '{message:{content:[{type:"tool_use",name:"Skill",input:{skill:"adversary"}}]}}' > "$TR_OK"
NOK=$(adversary_run_count "$TR_OK" 2>/dev/null)
if [ "$NOK" = "1" ]; then ok; else bad "T5" "контроль провален: на здоровом входе [$NOK] вместо 1"; fi

echo ""
echo "adv-arc number-contract tests: $PASS/$((PASS+FAIL)) passed"
exit $(( FAIL != 0 ))
