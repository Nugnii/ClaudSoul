#!/usr/bin/env bash
# test_adv5_scan_false_alarm.sh — обход краснеет на законном коде: хвостовой комментарий
# и одинарные кавычки.
#
# Шапка test_multibyte_var_boundary.sh перечисляет исключения:
#   «строки комментариев (там подстановки не происходит) и намеренные тестовые данные
#    внутри кавычек с экранированным долларом (\$_needle)».
# Оба исключения описаны УЖЕ, чем предмет:
#
#   1. Комментарий отсекается образцом `^[0-9]+:[[:space:]]*#`, то есть только когда
#      строка НАЧИНАЕТСЯ с решётки. `echo ok  # «$v»` — тот же комментарий, подстановки  # mb-ok: строка демонстрирует дефект, а не совершает его
#      в нём нет, bash его вообще не разбирает, а обход его засчитывает нарушением.
#   2. Данными считается только `\$`. Одинарные кавычки подстановку выключают целиком,
#      и `'«$v»'` в bash 3.2 безопасен. Обход краснеет и на нём.  # mb-ok: строка демонстрирует дефект, а не совершает его
#
# Второе исключение не гипотетическое: САМ обход пишет свои образцы ровно так —
# строки 70 и 79, `printf '…«$name»…'` внутри одинарных кавычек. Он не горит на себе  # mb-ok: строка демонстрирует дефект, а не совершает его
# только потому, что исключил себя по имени файла (строка 52). Любой другой тест,
# описывающий тот же дефект тем же способом, покрасит прогон.
#
# Цена ложной тревоги равна цене пропуска: страж, который врёт на законном коде,
# заставляет обходить себя исключениями по имени — а исключённый файл он больше не
# проверяет вовсе.
#
# РАЗБОР (2026-08-25). Находка верна по механизму и снята по требованию. Попытка отличить
# код от не-кода эвристикой была снята этим же раундом с четырёх сторон сразу: «#» внутри
# heredoc не комментарий, экранированный доллар вырезался неверно, обход не покрывал полдерева.
# Разбирать синтаксис оболочки эвристиками — то же, что проверять парсер списком примеров.
# Поэтому правило сделано БЕЗУСЛОВНЫМ: `${var}` корректно везде, и починка от контекста
# не зависит, значит и правилу контекст знать незачем. Исключение объявляет автор строки
# пометкой `mb-ok`, а не выводит страж из текста.
#
# Отсюда предмет теста сместился: не «страж молчит на законном коде» (он намеренно
# говорит), а «тревога разрешима явной пометкой, и помеченная строка молчит». Тест на
# прежнем требовании краснел бы на верном коде — а тест, сторожащий отменённое
# требование, хуже отсутствия теста. Один случай остаётся ценой: одинарные кавычки, где
# `${v}` изменил бы вывод, — там пометка обязательна и это записано в самом стороже.

set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
GUARD="$REPO/hooks/tests/test_multibyte_var_boundary.sh"
LAQUO=$(printf '\302\253'); RAQUO=$(printf '\302\273')
rc_test=0

T="$(mktemp -d)"
mkdir -p "$T/hooks/tests" "$T/scripts"
cp "$GUARD" "$T/hooks/tests/"

# Законный код №1: хвостовой комментарий.
{
    printf '#!/bin/bash\nset -u\nv=x\n'
    printf 'echo ok  # разбор %s$v%s описан выше\n' "$LAQUO" "$RAQUO"
} > "$T/hooks/legal_trailing_comment.sh"

# Законный код №2: образец внутри одинарных кавычек — подстановки нет.
{
    printf '#!/bin/bash\nset -u\nv=x\n'
    printf "printf '%%s' '%s\$v%s'\n" "$LAQUO" "$RAQUO"
} > "$T/hooks/legal_single_quotes.sh"

# --- 1. Доказать, что оба файла законны: bash 3.2 их исполняет без «unbound variable» ---
for f in "$T/hooks/legal_trailing_comment.sh" "$T/hooks/legal_single_quotes.sh"; do
    err="$(/bin/bash "$f" 2>&1 >/dev/null)"; rc=$?
    case "$err" in
        *"unbound variable"*)
            echo "SKIP: $(basename "$f") оказался небезопасен на этом bash — [$err]"
            exit 0 ;;
    esac
    if [ "$rc" -ne 0 ]; then
        echo "SKIP: $(basename "$f") завершился с $rc — предпосылка теста не выполнена"
        exit 0
    fi
    echo "предпосылка: $(basename "$f") исполняется чисто (rc=0, stderr пуст)"
done

# --- 2. Тревога намеренна: она обязана быть РАЗРЕШИМА пометкой автора ---
guard_out="$(bash "$T/hooks/tests/$(basename "$GUARD")" 2>&1)"; guard_rc=$?
if [ "$guard_rc" -eq 0 ]; then
    echo "FAIL [A2]: обход промолчал на непомеченных строках — правило перестало быть безусловным."
    echo "     Оно намеренно говорит обо ВСЯКОЙ подстановке вплотную к не-ASCII; тишина здесь"
    echo "     означает, что вернулась эвристика «это комментарий», снятая как ненадёжная."
    rc_test=1
else
    # Помечаем обе законные строки и требуем тишины.
    for f in "$T/hooks/legal_trailing_comment.sh" "$T/hooks/legal_single_quotes.sh"; do
        sed -e '$ s/$/  # mb-ok: законно, подстановки нет/' "$f" > "$f.tmp" && cat "$f.tmp" > "$f"
    done
    marked_out="$(bash "$T/hooks/tests/$(basename "$GUARD")" 2>&1)"; marked_rc=$?
    if [ "$marked_rc" -ne 0 ]; then
        echo "FAIL [A2]: помеченные строки всё ещё красят обход — исключение не работает:"
        printf '%s\n' "$marked_out" | sed 's|^|    |'
        rc_test=1
    else
        echo "PASS [A2]: тревога намеренна и снимается пометкой mb-ok"
    fi
fi

echo ""
if [ "$rc_test" -ne 0 ]; then
    echo "adv5 scan-false-alarm: КРАСНЫЙ — правило перестало быть безусловным либо"
    echo "  пометка mb-ok не снимает тревогу."
else
    echo "adv5 scan-false-alarm: 1/1 passed"
fi
exit "$rc_test"
