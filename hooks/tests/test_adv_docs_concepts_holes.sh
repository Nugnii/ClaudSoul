#!/usr/bin/env bash
# test_adv_docs_concepts_holes.sh — АТАКИ на scripts/docs-concepts-check.sh.
#
# Прибор объявляет три состояния: нет реестра → 2, понятие пропало → 1, всё на месте → 0.
# Атаки показывают вход, при котором он говорит «всё на месте» (0), а понятие пропало.
#
# 1. Последняя строка реестра БЕЗ завершающего перевода не читается вовсе:
#    `while IFS=$'\t' read -r ...` без `|| [ -n "$name" ]` (docs-concepts-check.sh:29).
#    Это ровно тот класс (D296), который у соседа — scripts/measurement-due.sh:97-101 —
#    уже починен, и там же записано: «на самом реестре это уже случалось».
# 2. Корень карты засчитывается ПОДСТРОКОЙ: `grep -qF "$_rid"` (строка 60) находит «R1»
#    внутри «R10». Растёт карта до десяти корней — и R1..R9 закрываются упоминанием
#    любого из R10+.
# 3. Строка реестра, где вместо табуляции пробелы, молча пропускается: `pat` пуст →
#    `continue` без слова, SEEN не растёт. Опечатка в реестре гасит понятие насовсем.
set -uo pipefail

CHECK="$(cd "$(dirname "$0")/../.." && pwd)/scripts/docs-concepts-check.sh"
[ -f "$CHECK" ] || { echo "FAIL: нет $CHECK"; exit 1; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '  ok   %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  FAIL %s\n     %s\n' "$1" "$2"; }

# фикстура: корень дерева с реестром и документами состояния
_mkroot() {  # $1 — каталог
    mkdir -p "$1/scripts" "$1/docs"
    printf '# документ состояния\nкарта корней описана тут.\n' > "$1/docs/mechanism-errors-and-backlog.ru.md"
    printf '# архитектура\nкарта корней описана тут.\n' > "$1/docs/architecture.md"
    printf '# проект\nкарта корней описана тут.\n' > "$1/CLAUDE.md"
}

TMP=$(mktemp -d) || exit 1

# ── 1. последняя строка без завершающего перевода ────────────────────────────────
R1="$TMP/nonl"; _mkroot "$R1"
{
    printf 'карта корней\tкарта корней\tdocs/architecture.md\tбез неё починка идёт по листу\n'
    printf 'проба корня\tпроб[а-яё]\tdocs/architecture.md\tбез пробы дробь снова станет фразой'
} > "$R1/scripts/doc-concepts.tsv"

OUT=$(CLAUDSOUL_REPO="$R1" bash "$CHECK" 2>&1); RC=$?
if [ "$RC" -eq 1 ] && grep -q 'проба корня' <<< "$OUT"; then
    ok "последняя_строка_без_перевода: пропажа названа"
else
    bad "последняя_строка_без_перевода: пропажа названа" \
        "код=$RC, вывод: $(printf '%s' "$OUT" | tr '\n' ' ')"
fi

# положительный контроль: тот же реестр С переводом строки — понятие ловится
printf '\n' >> "$R1/scripts/doc-concepts.tsv"
OUT=$(CLAUDSOUL_REPO="$R1" bash "$CHECK" 2>&1); RC=$?
if [ "$RC" -eq 1 ] && grep -q 'проба корня' <<< "$OUT"; then
    ok "контроль: та же строка С переводом — пропажа названа"
else
    bad "контроль: та же строка С переводом — пропажа названа" \
        "код=$RC, вывод: $(printf '%s' "$OUT" | tr '\n' ' ') — фикстура не годится"
fi

# ── 2. корень засчитывается подстрокой ───────────────────────────────────────────
R2="$TMP/subroot"; _mkroot "$R2"
printf 'карта корней\tкарта корней\tdocs/architecture.md\tякорь, чтобы SEEN не был нулём\n' \
    > "$R2/scripts/doc-concepts.tsv"
cat > "$R2/ROOTS.md" <<'EOF'
# Карта корней

## R1 — имя состояния собрано литералом на каждом конце связи
тело

## R10 — область механизма шире предмета его утверждения
тело
EOF
# В документах состояния назван ТОЛЬКО R10. R1 не описан нигде.
printf '# проект\nкарта корней. Корень R10 описан.\n' > "$R2/CLAUDE.md"
printf '# архитектура\nкарта корней. Корень R10 описан.\n' > "$R2/docs/architecture.md"
printf '# пересказ\nкарта корней. Корень R10 описан.\n' > "$R2/docs/mechanism-errors-and-backlog.ru.md"

OUT=$(CLAUDSOUL_REPO="$R2" bash "$CHECK" 2>&1); RC=$?
if [ "$RC" -eq 1 ] && grep -q 'корень R1 ' <<< "$OUT"; then
    ok "корень_подстрокой: R1 без описания назван"
else
    bad "корень_подстрокой: R1 без описания назван" \
        "код=$RC, вывод: $(printf '%s' "$OUT" | tr '\n' ' ') — «R1» засчитан вхождением в «R10»"
fi

# ── 3. строка реестра с пробелами вместо табуляции ───────────────────────────────
R3="$TMP/notab"; _mkroot "$R3"
{
    printf 'карта корней\tкарта корней\tdocs/architecture.md\tякорь, чтобы SEEN не был нулём\n'
    printf 'дробь специфичности дробь docs/architecture.md единственный тест остановки\n'
} > "$R3/scripts/doc-concepts.tsv"

OUT=$(CLAUDSOUL_REPO="$R3" bash "$CHECK" 2>&1); RC=$?
if [ "$RC" -ne 0 ]; then
    ok "строка_без_табуляции: сломанная строка реестра названа"
else
    bad "строка_без_табуляции: сломанная строка реестра названа" \
        "код=0, вывод: $(printf '%s' "$OUT" | tr '\n' ' ') — «дробь» в документе отсутствует, но строка выброшена молча"
fi

echo "docs-concepts-holes: $PASS ok, $FAIL FAIL"
exit $(( FAIL != 0 ))
