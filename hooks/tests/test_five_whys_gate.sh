#!/usr/bin/env bash
# test_five_whys_gate.sh — гейт разбора причин обязан говорить на повторе и молчать,
# когда разбор уже сделан.
#
# Повод — три напоминания собеседника за три недели об одном и том же приёме. Механизма
# не было; текстовое правило («назови 2-3 версии причины» в глобальных правилах) закрывало
# ощущение разбора шириной перебора вместо глубины цепочки.
#
# Проверяется не «работает ли скрипт», а три места, где он может соврать молча:
# промолчать при повторе (ради чего заведён), загореться там, где разбор уже произнесён
# (тогда он фон), и загореться без сигнала повтора вообще (тогда он шум на каждой правке).
# Отдельно — повтор в УСПЕХАХ: именно с этой поправки собеседника всё началось, и гейт,
# слушающий только провалы, воспроизвёл бы исходную слепоту.

set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
HOOK="$REPO/hooks/five-whys-gate.sh"
[ -f "$HOOK" ] || { echo "FAIL: не найден $HOOK"; exit 1; }

PASS=0; FAIL=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
export STATE_DIR="$TMP/state"; mkdir -p "$STATE_DIR"

ok()  { PASS=$((PASS+1)); echo "  ok   — $1"; }
bad() { FAIL=$((FAIL+1)); echo "  FAIL — $1"; }
assert_silent() {
    if [ -z "$1" ]; then ok "$2"; else bad "$2 — ожидалась тишина, получено: $1"; fi
}

spoke() {  # гейт не промолчал: напоминание ИЛИ отказ с требованием цепочки
    grep -qE "Признак повторяется|Правка не пройдёт" <<< "${1:-}"
}

# Транскрипт: реплика собеседника, затем ответ агента с заданным текстом.
mk_transcript() {   # mk_transcript <файл> <текст ответа>
    : > "$1"
    printf '{"type":"user","message":{"role":"user","content":[{"type":"text","text":"чини"}]}}\n' >> "$1"
    jq -cn --arg t "$2" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$t}]}}' >> "$1"
}

call() {  # call <sid> <tool> [transcript]
    local sid="$1" tool="$2" tr="${3:-}"
    jq -cn --arg s "$sid" --arg t "$tool" --arg p "$tr" \
        '{session_id:$s, tool_name:$t, transcript_path:$p}' \
      | STATE_DIR="$STATE_DIR" bash "$HOOK" 2>/dev/null
}

TR_NO="$TMP/no.jsonl";  mk_transcript "$TR_NO"  "Правлю строку, сейчас будет зелено."
TR_YES="$TMP/yes.jsonl"; mk_transcript "$TR_YES" \
  "Почему упало — читался старый индекс. Почему старый — add шёл после. Почему не поймали — тест брал фикстуру."

# --- 1. Сигнала повтора нет — гейт молчит на любой правке.
assert_silent "$(call s1 Edit "$TR_NO")" "без сигнала повтора → тишина (не шум на каждой правке)"

# --- 2. Полоса провалов, разбора нет → горит.
touch "$STATE_DIR/error_streak_fired_s2"
OUT=$(call s2 Edit "$TR_NO")
spoke "$OUT" && ok "полоса провалов без разбора → горит" \
                                        || bad "промолчал на полосе провалов: $OUT"
grep -q "полоса упавших команд" <<<"$OUT" && ok "названо, ЧТО именно повторяется" \
                                          || bad "не назван вид повтора"

# --- 1b. ПОЧИНКА ПО ХОДУ: сигналов повтора нет, а правка уже началась.
# Поправка владельца 27 августа 2026: «обнаруживаешь проблемы... а чинил без 5 почему —
# ЭТО ПРОБЛЕМА ОСНОВНАЯ». Повтор — следствие пропущенного разбора, не его условие.
TR_FIND="$TMP/find.jsonl"
mk_transcript "$TR_FIND" "Побочно вылезла дыра в границе слова, чиню заодно."
OUT=$(call s1b Edit "$TR_FIND")
spoke "$OUT" && ok "находка по ходу без разбора → горит (повтора нет вовсе)" \
                                        || bad "промолчал на починке по ходу: $OUT"
grep -q "находка по ходу" <<<"$OUT" && ok "названо, что сработала именно находка" \
                                    || bad "не назван вид сигнала: $OUT"

TR_FIND_WHY="$TMP/find-why.jsonl"
mk_transcript "$TR_FIND_WHY" "Побочно вылезла дыра. Почему вылезла — граница не доехала. Почему не доехала — правили соседнюю ветку. Почему только соседнюю — чинили там, где заметили."
assert_silent "$(call s1c Edit "$TR_FIND_WHY")" "находка есть, но цепочка произнесена → молчит"

# Дедуп по ВИДУ, а не по числу: находка (1) погашена, но полоса провалов (тоже 1) горит.
OUT=$(call s1d Edit "$TR_FIND")
spoke "$OUT" && ok "первый заход по находке — горит" || bad "не загорелся"
assert_silent "$(call s1d Edit "$TR_FIND")" "тот же вид сигнала повторно → молчит"
touch "$STATE_DIR/error_streak_fired_s1d"
OUT=$(call s1d Edit "$TR_NO")
grep -q "полоса упавших команд" <<<"$OUT" && ok "ДРУГОЙ вид той же величины → снова горит (прежний счётчик глушил бы)" \
                                          || bad "монотонный счётчик заглушил другой сигнал: $OUT"

# --- 2b. Повтор в УТВЕРЖДЕНИЯХ: одно знание подтверждено за сессию дважды.
# Повод: 27 августа 2026 — четыре утверждения одного класса подряд, ни одной упавшей
# команды, ни одной повторной правки. Первые два сигнала слепы к такому по построению.
cat > "$STATE_DIR/disagreement-outcomes.jsonl" <<'OJ'
{"date":"2026-08-27T10:00:00Z","session":"s2b","knowledge":"pattern-x.md","outcome":"confirmed_knowledge","case":"раз"}
{"date":"2026-08-27T11:00:00Z","session":"s2b","knowledge":"pattern-x.md","outcome":"confirmed_knowledge","case":"два"}
{"date":"2026-08-27T12:00:00Z","session":"s2c","knowledge":"pattern-y.md","outcome":"confirmed_knowledge","case":"одиночка"}
{"date":"2026-08-27T12:30:00Z","session":"s2c","knowledge":"pattern-q.md","outcome":"not_applicable","case":"не тот исход"}
{"date":"2026-08-27T12:40:00Z","session":"s2c","knowledge":"pattern-q.md","outcome":"not_applicable","case":"не тот исход дважды"}
{"date":"2026-08-27T13:00:00Z","session":"s2d","knowledge":"pattern-w.md","outcome":"confirmed_knowledge","case":"раз"}
{"date":"2026-08-27T13:30:00Z","session":"s2d","knowledge":"pattern-w.md","outcome":"confirmed_knowledge","case":"два"}
OJ
OUT=$(call s2b Edit "$TR_NO")
spoke "$OUT" && ok "повтор в утверждениях без разбора → горит" \
                                        || bad "промолчал на дважды подтверждённом знании: $OUT"
grep -q "pattern-x" <<<"$OUT" && ok "названо, КАКОЕ знание повторилось" \
                              || bad "не названо повторившееся знание: $OUT"
# У s2c своя пара строк: одно подтверждение + дважды НЕ ТОТ исход. Молчание тут
# обязано быть от порога, а не от пустоты — иначе проверка проходит ни о чём.
assert_silent "$(call s2c Edit "$TR_NO")" "одно подтверждение и два not_applicable → не сигнал"
# У s2d сигнал ЕСТЬ (pattern-w дважды) — молчит именно из-за произнесённой цепочки.
assert_silent "$(call s2d Edit "$TR_YES")" "сигнал есть, но цепочка почему произнесена → молчит"
rm -f "$STATE_DIR/disagreement-outcomes.jsonl"

# --- 3. Повтор в УСПЕХАХ (третий заход на файл) — тоже сигнал.
#     Гейт, слушающий только провалы, воспроизвёл бы слепоту, с которой всё началось.
printf '{"file":"a.sh"}\n' > "$STATE_DIR/rework-fired-s3.jsonl"
OUT=$(call s3 Write "$TR_NO")
grep -q "повторные заходы на один файл" <<<"$OUT" \
    && ok "повтор в успехах засчитан наравне с провалами" \
    || bad "успехи не считаются повтором: $OUT"

# --- 4. Разбор произнесён (три «почему») → молчит.
touch "$STATE_DIR/error_streak_fired_s4"
assert_silent "$(call s4 Edit "$TR_YES")" "цепочка «почему» в ответе → тишина"

# --- 5. Одно «почему» — не цепочка.
touch "$STATE_DIR/error_streak_fired_s5"
TR_ONE="$TMP/one.jsonl"; mk_transcript "$TR_ONE" "Почему упало — не тот путь. Чиню."
OUT=$(call s5 Edit "$TR_ONE")
spoke "$OUT" && ok "одно «почему» не считается разбором" \
                                        || bad "одиночное «почему» приняло за цепочку"

# --- 6. Дедуп: тот же сигнал второй раз → молчит; новый сигнал → снова горит.
touch "$STATE_DIR/error_streak_fired_s6"
OUT=$(call s6 Edit "$TR_NO"); [ -n "$OUT" ] || bad "первое срабатывание не случилось"
assert_silent "$(call s6 Edit "$TR_NO")" "тот же сигнал повторно → тишина (не фон)"
printf '{"file":"b.sh"}\n' > "$STATE_DIR/rework-fired-s6.jsonl"
OUT=$(call s6 Edit "$TR_NO")
spoke "$OUT" && ok "новый сигнал → говорит снова" \
                                        || bad "новый сигнал проигнорирован"

# --- 7. Чужие инструменты и пустой вход.
touch "$STATE_DIR/error_streak_fired_s7"
assert_silent "$(call s7 Read "$TR_NO")" "не-правящий инструмент игнорируется"
assert_silent "$(printf '' | STATE_DIR="$STATE_DIR" bash "$HOOK" 2>/dev/null)" "пустой вход → тишина"

# --- 8. Нет транскрипта — сигнал всё равно важнее: горит.
touch "$STATE_DIR/error_streak_fired_s8"
OUT=$(call s8 Edit "")
spoke "$OUT" \
    && ok "без транскрипта гейт не глохнет (ошибка в сторону напоминания)" \
    || bad "без транскрипта промолчал: $OUT"


# --- 9. Дедуп по ЭКЗЕМПЛЯРУ, а не по виду сигнала (диагноз 2026-08-28).
# Повод измерен на расшифровке живой сессии. В одном ходе гейт сработал на индексе 1055
# с подписью «repeat + находка по ходу», а на индексе 1159 — вторая находка того же хода,
# и та, ради которой всё, — промолчал: подпись совпала, дедуп счёл «то же самое».
# Это тот же дефект, что чинили 27 августа на уровне сессии («повтор уплывает»); границу
# сдвинули сессия→ход, а ключ остался ВИДОВЫМ. Находка — то, что сказано ТОЛЬКО ЧТО,
# поэтому признак читается по последнему блоку речи, а ключ несёт его отпечаток.
mk_multi() {   # mk_multi <файл> <текст1> [текст2 ...]
    local out="$1"; shift
    : > "$out"
    printf '{"type":"user","message":{"role":"user","content":[{"type":"text","text":"чини"}]}}\n' >> "$out"
    local x
    for x in "$@"; do
        jq -cn --arg t "$x" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$t}]}}' >> "$out"
    done
}

touch "$STATE_DIR/error_streak_fired_s9"
TR_F1="$TMP/f1.jsonl"; mk_multi "$TR_F1" "Оказалось, страж читает не тот файл. Чиню."
OUT=$(call s9 Edit "$TR_F1")
spoke "$OUT" && ok "первая находка хода — гейт говорит" \
                                       || bad "первая находка пропущена: $OUT"
assert_silent "$(call s9 Edit "$TR_F1")" "тот же текст повторно → тишина (не фон)"

TR_F2="$TMP/f2.jsonl"; mk_multi "$TR_F2" "Оказалось, страж читает не тот файл. Чиню." \
                                         "Проверка не сходится с тем, что я знаю: признак мимо."
OUT=$(call s9 Edit "$TR_F2")
spoke "$OUT" \
    && ok "ВТОРАЯ находка того же хода — гейт говорит снова" \
    || bad "вторая находка съедена дедупом по виду сигнала: $OUT"

# --- 10. Пятый сигнал: один класс повторился за СУТКИ поперёк сессий.
# Третий сигнал считает в границах сессии и межсессионный повтор не видит по построению.
# Живой случай: pattern-subject-checked-by-enumeration подтверждён трижды за ~15 часов —
# 27.08 09:56 (сессия A), 27.08 19:46 (сессия B), 28.08 01:07 (сессия C). Ни одна пара не
# попала в одну сессию, и агенту пришлось написать «третий за сутки» прозой по памяти.
OUTC="$STATE_DIR/disagreement-outcomes.jsonl"
: > "$OUTC"
NOW_D=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
for s in sA sB sC; do
    jq -cn --arg s "$s" --arg d "$NOW_D" \
      '{session:$s, knowledge:"pattern-x.md", outcome:"confirmed_knowledge", date:$d}' >> "$OUTC"
done
TR_Q="$TMP/quiet.jsonl"; mk_transcript "$TR_Q" "Правлю дальше."
OUT=$(call s10 Edit "$TR_Q")
grep -q "за сутки" <<<"$OUT" && ok "межсессионный повтор класса назван" \
                             || bad "три подтверждения за сутки поперёк сессий не замечены: $OUT"
grep -q "pattern-x" <<<"$OUT" && ok "знание названо поимённо" \
                              || bad "знание не названо: $OUT"

# Два подтверждения за сутки — ещё не сигнал (иначе всякое здоровое подкрепление шумит).
: > "$OUTC"
for s in sA sB; do
    jq -cn --arg s "$s" --arg d "$NOW_D" \
      '{session:$s, knowledge:"pattern-y.md", outcome:"confirmed_knowledge", date:$d}' >> "$OUTC"
done
assert_silent "$(call s11 Edit "$TR_Q")" "двух подтверждений за сутки мало — порог три"

# Старые подтверждения за окном суток не считаются.
: > "$OUTC"
for s in sA sB sC; do
    jq -cn --arg s "$s" '{session:$s, knowledge:"pattern-z.md",
       outcome:"confirmed_knowledge", date:"2026-01-01T00:00:00Z"}' >> "$OUTC"
done
assert_silent "$(call s12 Edit "$TR_Q")" "подтверждения старше суток в окно не входят"

# --- 11. Файл дедупа — ЖУРНАЛ, а не последняя подпись.
# Диагностировать молчание гейта 28 августа было нечем: `printf > "$SEEN_FILE"` хранил
# только последнюю подпись, и вопрос «срабатывал ли он в том ходе» пришлось выяснять по
# расшифровке сессии. Журнал отвечает на него сам.
: > "$OUTC"
touch "$STATE_DIR/error_streak_fired_s13"
call s13 Edit "$TR_F1" >/dev/null
call s13 Edit "$TR_F2" >/dev/null
LOG="$STATE_DIR/five-whys-s13.seen"
if [ -f "$LOG" ] && [ "$(grep -c . "$LOG")" -ge 2 ]; then
    ok "срабатывания дописываются в журнал, а не затирают друг друга"
else
    bad "журнал срабатываний не ведётся: $( [ -f "$LOG" ] && cat "$LOG" || echo 'файла нет')"
fi


# --- 12. Отпечаток экземпляра обязателен у КАЖДОГО сигнала, не только у находки.
# Поправка собеседника 2026-08-28: «зашибись решение — дефект жив». Починка 28 августа
# дала отпечаток одному сигналу из пяти — тому, на который смотрели. У rework, streak и
# repeat ключ остался счётным или константным, то есть исходный дефект («повтор уплывает»)
# продолжал жить у трёх сигналов из пяти, включая ТОТ САМЫЙ, с которого всё началось.
# Симптом чинится там, где заметили; причина — там, где возникла.

# 12а. Полоса провалов: ДВЕ разные полосы за ход — гейт говорит дважды.
TR_P="$TMP/plain.jsonl"; mk_transcript "$TR_P" "Правлю дальше."
printf 'a\n' > "$STATE_DIR/error_streak_fired_s14"
OUT=$(call s14 Edit "$TR_P")
spoke "$OUT" || bad "первая полоса не сработала"
printf 'b\n' >> "$STATE_DIR/error_streak_fired_s14"
OUT=$(call s14 Edit "$TR_P")
spoke "$OUT" \
    && ok "ВТОРАЯ полоса провалов доходит (streak не константа)" \
    || bad "вторая полоса съедена: ключ streak константный"

# 12б. Переработка: тот же СЧЁТ, другой файл — гейт говорит снова.
printf '{"file":"a.sh"}\n' > "$STATE_DIR/rework-fired-s15.jsonl"
OUT=$(call s15 Edit "$TR_P")
spoke "$OUT" || bad "первая переработка не сработала"
printf '{"file":"b.sh"}\n' > "$STATE_DIR/rework-fired-s15.jsonl"
OUT=$(call s15 Edit "$TR_P")
spoke "$OUT" \
    && ok "переработка ДРУГОГО файла при том же счёте доходит" \
    || bad "другой файл при том же счёте съеден: ключ rework счётный"

# 12в. Повтор знания: другое знание при том же счёте — гейт говорит снова.
# Это дословно исходная поправка собеседника 27 августа: «повтор уплывает».
OUTC2="$STATE_DIR/disagreement-outcomes.jsonl"
mk_repeat() {  # mk_repeat <знание>
    : > "$OUTC2"
    jq -cn --arg k "$1" '{session:"s16", knowledge:$k, outcome:"confirmed_knowledge", date:"2026-01-01T00:00:00Z"}' >> "$OUTC2"
    jq -cn --arg k "$1" '{session:"s16", knowledge:$k, outcome:"confirmed_knowledge", date:"2026-01-01T00:00:01Z"}' >> "$OUTC2"
}
mk_repeat "pattern-alpha.md"
OUT=$(call s16 Edit "$TR_P")
grep -q "pattern-alpha" <<<"$OUT" || bad "первое знание с повтором не названо: $OUT"
mk_repeat "pattern-beta.md"
OUT=$(call s16 Edit "$TR_P")
grep -q "pattern-beta" <<<"$OUT" \
    && ok "ДРУГОЕ знание с повтором при том же счёте доходит («повтор уплывает» закрыт)" \
    || bad "другое знание съедено: ключ repeat счётный — тот самый дефект жив"

# 12г. Структурный страж: ни один сигнал не смеет класть в ключ константу или голый счёт.
# Поведенческие проверки выше держат нынешние пять сигналов; этот держит ШЕСТОЙ, которого
# ещё нет. Без него текстовое правило «не забудь отпечаток» — единственная защита, а оно
# уже один раз не сработало, будучи записанным за минуту до нарушения.
BADKEYS=$(grep -oE 'KINDS="\$\{KINDS\}[a-z]+:[^"]*"' "$HOOK" \
          | grep -vE '\$\{?_?[a-z_]*(key|name|fp|id)' || true)
if [ -z "$BADKEYS" ]; then
    ok "у всех сигналов в ключе отпечаток экземпляра, не константа и не счёт"
else
    bad "сигнал с константным/счётным ключом: $BADKEYS"
fi


# --- 13. ОТКАЗ вместо напоминания (поправка собеседника 2026-08-28).
# Повод дословно: «"Страж проекта поймал мой же новый тест… Чиню." — и сразу чинить пошёл.
# А вместо "чиню" должен был сработать страж хук 5 почему». Проверка по журналу: гейт в том
# ходе СРАБОТАЛ (repeat + daily) и сказал «разбора причин не было». Я прочитал и починил.
# То есть напоминание не остановило — двадцатый случай того же разрыва, произведённый тем
# самым механизмом, который чинили.
#
# Отказ только на СОБЫТИЙНЫХ сигналах (находка, свежая полоса, свежая переработка).
# `repeat` и `daily` — состояния: они стоят часами и сутками, отказ на них означал бы
# бессрочную блокировку. Их дело — напоминать.
#
# И только на ПИШУЩЕМ действии: чтение и осмотр обязаны проходить, иначе цепочку не
# построить — а именно её от агента и требуют. Прецедент цены записан в шапке
# command-scope-lib: страж с отказом дважды заблокировал запись собственного теста.
mk_multi2() { local out="$1"; shift; : > "$out"
    printf '{"type":"user","message":{"role":"user","content":[{"type":"text","text":"чини"}]}}\n' >> "$out"
    local x; for x in "$@"; do
        jq -cn --arg t "$x" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$t}]}}' >> "$out"
    done
}
call_bash() { # call_bash <sid> <команда> <транскрипт>
    jq -cn --arg s "$1" --arg c "$2" --arg p "$3" \
      '{session_id:$s, transcript_path:$p, hook_event_name:"PreToolUse", tool_name:"Bash", tool_input:{command:$c}}' \
    | STATE_DIR="$STATE_DIR" bash "$HOOK" 2>/dev/null
}
dec() { jq -r '.hookSpecificOutput.permissionDecision // ""' <<< "$1" 2>/dev/null; }

