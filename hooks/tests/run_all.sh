#!/usr/bin/env bash
# run_all.sh — единый раннер всех хуковых тестов.
# До него «824/824 зелёных» нельзя было воспроизвести одной командой (F16):
# тесты с разнородными форматами итога приходилось запускать вручную и суммировать.
# Прогоняет каждый test_*.sh, суммирует pass/fail по файлам, единый exit code.
#
# Таймаут на файл (v1.11). Библиотечная функция, читавшая stdin при явно
# переданном аргументе, заморозила весь прогон на 10 минут: у раннера не было
# предела, и одно блокирующее чтение выглядело как «тесты идут», а не как отказ.
# Зависание — тоже провал и должно называться провалом. `timeout(1)` на macOS без
# coreutils отсутствует (pattern-shell-portability), поэтому watchdog на bash.

set -uo pipefail
cd "$(dirname "$0")" || exit 2

TEST_TIMEOUT="${TEST_TIMEOUT:-120}"

total=0
failed=0
failed_names=""
timed_out=""

# stdin закрыт намеренно: тест не должен зависеть от терминала, а открытая труба —
# ровно то окружение, в котором всё вставало.
# Вывод упавшего теста сохраняется и печатается (v1.14.3). До этого он уходил в /dev/null,
# и прогон мог сказать только КАКОЙ тест упал, но не почему. На своей машине это неважно —
# перезапустил руками и посмотрел. В CI перезапустить нечего: там другая система, и
# одиннадцать падений выглядели одинаково пустыми. Проверка, чьи доказательства недоступны
# в том месте, где её читают, сообщает факт провала и скрывает его содержание.
OUT_DIR=$(mktemp -d)
trap 'rm -rf "$OUT_DIR"' EXIT

run_with_timeout() {
    local script="$1" pid watch_pid rc=0
    bash "$script" >"$OUT_DIR/$script.out" 2>&1 </dev/null &
    pid=$!
    ( sleep "$TEST_TIMEOUT"; kill -9 "$pid" 2>/dev/null ) &
    watch_pid=$!
    wait "$pid" 2>/dev/null || rc=$?
    kill "$watch_pid" 2>/dev/null
    wait "$watch_pid" 2>/dev/null || true
    return "$rc"
}

for t in test_*.sh; do
    [ -f "$t" ] || continue
    total=$((total + 1))
    rc=0
    run_with_timeout "$t" || rc=$?
    if [ "$rc" -ne 0 ]; then
        failed=$((failed + 1))
        failed_names="$failed_names $t"
        # 137 = SIGKILL от watchdog: тест не упал, а завис.
        [ "$rc" -eq 137 ] && timed_out="$timed_out $t"
        echo "───── $t (код $rc) ─────"
        tail -"${FAIL_OUTPUT_LINES:-25}" "$OUT_DIR/$t.out" 2>/dev/null | sed 's/^/  /'
        echo ""
    fi
done

# Дрейф между проверенной и работающей копией (v1.13.1).
#
# Здесь замыкается «закольцовка»: тесты гоняют копии из РЕПОЗИТОРИЯ
# (`$(dirname $0)/..`), а живая система — копии из `~/.claude/hooks/`. Правишь хук,
# тесты зелёные, работает по-прежнему старый код. Исправление есть, но в той рамке,
# где смотришь, оно не действует — и ты возвращаешься в состояние до бага, считая,
# что вышел из него.
#
# Существующий детектор дрейфа (Signal 6 в session-start) эту форму не ловит: он
# сравнивает НАЛИЧИЕ и РЕГИСТРАЦИЮ, а не содержимое, и работает только на старте
# сессии — то есть в другой момент времени, чем тот, когда петля замыкается.
#
# Отдельной строкой предупреждать бесполезно: её проматывают вместе с зелёным
# итогом. Поэтому оговорка вклеивается в САМУ строку успеха — чтобы «51/51 passed»
# нельзя было прочитать как «система работает».
# Семь пар, а не одна (v1.14.2, седьмая — регистрация, v1.16.2). Прежняя версия сравнивала только hooks/*.sh и вычисляла
# путь к источнику относительно $0 УЖЕ ПОСЛЕ cd выше — при вызове `bash hooks/tests/run_all.sh`
# из корня путь складывался сам с собой, шаблон не находил ничего, и печаталось
# утвердительное «репозиторий и установленное совпадают». Ноль сравнений выглядел как ноль
# расхождений. Логика вынесена в drift-check.sh, где ноль сравнений — это BROKEN.
DRIFT_LINES=$(bash "$(pwd)/drift-check.sh" 2>/dev/null)
DRIFT_RC=$?
DRIFT_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^DRIFT|' 2>/dev/null | tr -d '[:space:]')
BROKEN_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^BROKEN|' 2>/dev/null | tr -d '[:space:]')
CHECKED_FILES=$(printf '%s\n' "$DRIFT_LINES" | awk -F'|' '{s += $3} END {print s + 0}')
# Число пар считается из вывода, а не пишется руками: с добавлением седьмой проверки
# (регистрация хуков, D55) захардкоженная «6» стала бы враньём в строке итога — ровно
# тот класс «числа в N местах», что проект уже чинил трижды.
TOTAL_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^[A-Z]*|' 2>/dev/null | tr -d '[:space:]')
: "${TOTAL_PAIRS:=0}"
: "${DRIFT_PAIRS:=0}"; : "${BROKEN_PAIRS:=0}"; : "${CHECKED_FILES:=0}"

if [ "${BROKEN_PAIRS:-0}" -gt 0 ] 2>/dev/null; then
    echo "Hook test files: $((total - failed))/$total passed — НО проверка дрейфа сама не сработала: $BROKEN_PAIRS пар(ы) не с чем сравнить"
    printf '%s\n' "$DRIFT_LINES" | awk -F'|' '$1 == "BROKEN" { printf "  ⚠ %s: %s\n", $2, $5 }'
    echo "  ⚠ ноль сравнений — это не «совпадает». Что именно работает, неизвестно."
elif [ "${DRIFT_PAIRS:-0}" -gt 0 ] 2>/dev/null; then
    echo "Hook test files: $((total - failed))/$total passed — НО проверен репозиторий, а работает другое: расходятся $DRIFT_PAIRS пар(ы) из $TOTAL_PAIRS"
    printf '%s\n' "$DRIFT_LINES" | awk -F'|' '$1 == "DRIFT" { printf "  ⚠ %s (%s из %s):%s\n", $2, $4, $3, $5 }'
    echo "  ⚠ зелёные тесты здесь НЕ означают, что работает установленное. Синхронизация: bash install.sh"
elif [ "${CHECKED_FILES:-0}" -eq 0 ] 2>/dev/null; then
    # Все пары ABSENT — установки нет вовсе (чистая машина, контейнер, прогон CI).
    # Это НЕ «совпадают»: сравнивать было не с чем. Первая версия строки печатала
    # «6 пар совпадают, сверено 0 файлов» — то самое утверждение из ничего, против
    # которого и заводился статус BROKEN. Поймано прогоном CI, а не рассуждением.
    echo "Hook test files: $((total - failed))/$total passed (установки нет — пары «репозиторий ↔ установленное» не сверялись)"
else
    echo "Hook test files: $((total - failed))/$total passed ($TOTAL_PAIRS пар «репозиторий ↔ установленное» совпадают, сверено $CHECKED_FILES файлов)"
fi
[ "$DRIFT_RC" -eq 0 ] || true
[ -n "$failed_names" ] && echo "FAILED:$failed_names"
[ -n "$timed_out" ] && echo "ЗАВИСЛИ (убиты по таймауту ${TEST_TIMEOUT}с):$timed_out"
[ "$failed" -eq 0 ]
