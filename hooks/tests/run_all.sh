# Шапка объявляет ПОЛНОТУ прогона, а не только время. Выборочный прогон пишет в тот же
# журнал и затирает полный; «Проверка» пункта D392 читает последний журнал и на выборке из
# 20 тестов зеленела ложно — дорогих там нет по построению. Поймано гейтом на Stop
# 11 сентября 2026: пункт открыт, а его команда зелёная. Корень — один носитель для двух
# разных состояний мира, и читатель не мог отличить неполноту от чистоты.
printf '# прогон начат %s, тестов %s, полнота %s\n' \
    "$(date '+%Y-%m-%d %H:%M:%S')" "$(ls test_*.sh 2>/dev/null | grep -c '')" \
    "$([ "$RUN_CHANGED" -eq 1 ] && echo выборочный || echo полный)" \
    > "$SUITE_LOG" 2>/dev/null || SUITE_LOG=/dev/null

# ФАЗА 1 — параллельная. Только при TEST_JOBS>1 и только для тестов, не берущих общий ресурс.
if [ "$TEST_JOBS" -gt 1 ] 2>/dev/null; then
    SLOTS=""
    for t in $TESTS_TO_RUN; do
        [ -f "$t" ] || continue
        needs_serial "$t" && continue
        # Ждём освобождения слота ОПРОСОМ живости: `wait -n` в bash 3.2 отсутствует, а пачки
        # фиксированного размера ждут самый долгий тест в каждой (замер: ×1,6 против ×4,7).
        while : ; do
            _alive=""
            _n=0
            for _p in $SLOTS; do
                if kill -0 "$_p" 2>/dev/null; then _alive="$_alive $_p"; _n=$((_n + 1)); fi
            done
            SLOTS="$_alive"
            [ "$_n" -lt "$TEST_JOBS" ] && break
            sleep 0.05 2>/dev/null || sleep 1
        done
        ( _rc=0; run_with_timeout "$t" || _rc=$?; echo "$_rc" > "$OUT_DIR/$t.rc"; bump_progress ) &
        SLOTS="$SLOTS $!"
    done
    wait
fi

# ФАЗА 2 — последовательная: то, что взяло общий ресурс, плюс ВСЁ при TEST_JOBS=1.
for t in $TESTS_TO_RUN; do
    [ -f "$t" ] || continue
    [ -f "$OUT_DIR/$t.rc" ] && continue
    rc=0
    run_with_timeout "$t" || rc=$?
    echo "$rc" > "$OUT_DIR/$t.rc"
    # ПРОГРЕСС ПИШЕТСЯ ПО ХОДУ, а не только в конце. Прежде stdout молчал до последней
    # строки, и прогон, оборванный по таймауту вызывающего, оставлял ПУСТОЙ лог: тесты
    # успели отработать, их вывод лежал в $OUT_DIR, но `trap rm -rf` уносил и его. То есть
    # проверка, чьи доказательства недоступны там, где её читают, — ровно тот класс, ради
    # которого этот файл и печатает хвосты падений (см. шапку).
    # Шаг 25, а не 1: 352 строки залили бы вывод и спрятали хвосты падений.
    bump_progress
done

# ФАЗА 3 — подсчёт и печать. Отделена от выполнения намеренно: порядок вывода падений
# остаётся алфавитным при любом числе потоков, иначе сводный лог менялся бы от прогона к
# прогону и его нельзя было бы сравнивать.
# ── Повтор убитых сторожем В ОДИНОЧКУ (D340, корень R6) ───────────────────────────────
# Код 137 приходит одинаково у зависшего теста и у исправного, которому соседи не оставили
# времени (замер 6 сентября 2026: два из четырёх падений полного набора, оба зелёные
# поодиночке). В момент убийства сторож их не различит по построению — оба молчат. Различает
# ПОВТОР в одиночку, когда нагрузка снята, со сроком в TEST_RERUN_FACTOR раз больше: прошёл —
# тесту не хватило времени под нагрузкой, и это не провал набора; убит снова — завис
# по-настоящему; упал иным кодом — упал по делу, и в итоге он с этим кодом. Дорого только для
# убитых, а их в норме ноль. TEST_RERUN_FACTOR=1 отключает повтор.
starved_names=""; starved_lines=""
TEST_RERUN_FACTOR="${TEST_RERUN_FACTOR:-6}"
case "$TEST_RERUN_FACTOR" in ''|*[!0-9]*) TEST_RERUN_FACTOR=6 ;; esac
if [ "$TEST_RERUN_FACTOR" -gt 1 ]; then
    for t in $TESTS_TO_RUN; do
        [ -f "$t" ] || continue
        [ "$(cat "$OUT_DIR/$t.rc" 2>/dev/null)" = "137" ] || continue
        _first_s=$(awk -F'\t' -v n="$t" '$3 == n && $1 == 137 { print $2 }' "$SUITE_LOG" 2>/dev/null | tail -1)
        _rc2=0; run_with_timeout "$t" "$TEST_RERUN_FACTOR" || _rc2=$?
        _second_s=$(awk -F'\t' -v n="$t" '$3 == n { print $2 }' "$SUITE_LOG" 2>/dev/null | tail -1)
        echo "$_rc2" > "$OUT_DIR/$t.rc2"
        if [ "$_rc2" -eq 0 ]; then
            echo 0 > "$OUT_DIR/$t.rc"
            starved_names="$starved_names $t"
            starved_lines="$starved_lines
  $t: первый прогон ${_first_s:-?} с при соседях $(( TEST_JOBS > 1 ? TEST_JOBS - 1 : 0 )) (срок $(cat "$OUT_DIR/$t.deadline" 2>/dev/null || printf '?') с), в одиночку зелёный за ${_second_s:-?} с"
        elif [ "$_rc2" -ne 137 ]; then
            echo "$_rc2" > "$OUT_DIR/$t.rc"     # упал по делу при повторе — в итоге с настоящим кодом
        fi
    done
fi
for t in $TESTS_TO_RUN; do
    [ -f "$t" ] || continue
    total=$((total + 1))
    rc=$(cat "$OUT_DIR/$t.rc" 2>/dev/null || echo 1)
    case "$rc" in ''|*[!0-9]*) rc=1 ;; esac
    if [ "$rc" -ne 0 ]; then
        failed=$((failed + 1))
        failed_names="$failed_names $t"
        # 137 = SIGKILL от watchdog: тест не упал, а завис.
        [ "$rc" -eq 137 ] && timed_out="$timed_out $t($(cat "$OUT_DIR/$t.deadline" 2>/dev/null || printf '?')с)"
        echo "───── $t (код $rc) ─────"
        # utf8_trim ОБЯЗАТЕЛЕН здесь, а не украшение. Тесты режут свои сообщения по БАЙТАМ
        # (`head -c N` — 86 мест в 42 файлах), русский текст рвётся на середине символа, и один
        # такой байт делает ВЕСЬ сводный лог двоичным для grep: поиск молча отвечает «не
        # найдено» о строке, которая там есть. Замер 7 сентября 2026: `grep -c хвост` по битому
        # логу — rc=1 и пусто, по очищенному — 1. Точка выбрана ОДНА, здесь: она покрывает все
        # 86 мест разом, тогда как правка каждого была бы 86 правками с тем же исходом.
        # НАЗВАННЫЙ ПРЕДЕЛ: обрезка остаётся байтовой, символ на границе теряется — чинится
        # ПОСЛЕДСТВИЕ (лог ищется), а не причина. Условие снятия: резать по символам.
        tail -"${FAIL_OUTPUT_LINES:-25}" "$OUT_DIR/$t.out" 2>/dev/null | utf8_trim | sed 's/^/  /'
        echo ""
    fi
done

# Дрейф между проверенной и работающей копией (v1.13.1).
#
# Здесь замыкается «закольцовка»: тесты гоняют копии из РЕПОЗИТОРИЯ
# (`$(dirname $0)/..`), а живая система — копии из `~/.claude/hooks/`. Правишь хук,
# тесты зелёные, работает по-прежнему старый код. Исправление есть, но в той рамке,
# где смотришь, оно не действует — и ты возвращаешься в состояние до бага, считая,
# что вышел из него.
#
# Существующий детектор дрейфа (Signal 6 в session-start) эту форму не ловит: он
# сравнивает НАЛИЧИЕ и РЕГИСТРАЦИЮ, а не содержимое, и работает только на старте
# сессии — то есть в другой момент времени, чем тот, когда петля замыкается.
#
# Отдельной строкой предупреждать бесполезно: её проматывают вместе с зелёным
# итогом. Поэтому оговорка вклеивается в САМУ строку успеха — чтобы «51/51 passed»
# нельзя было прочитать как «система работает».
# Семь пар, а не одна (v1.14.2, седьмая — регистрация, v1.16.2). Прежняя версия сравнивала только hooks/*.sh и вычисляла
# путь к источнику относительно $0 УЖЕ ПОСЛЕ cd выше — при вызове `bash hooks/tests/run_all.sh`
# из корня путь складывался сам с собой, шаблон не находил ничего, и печаталось
# утвердительное «репозиторий и установленное совпадают». Ноль сравнений выглядел как ноль
# расхождений. Логика вынесена в drift-check.sh, где ноль сравнений — это BROKEN.
DRIFT_LINES=$(bash "$(pwd)/drift-check.sh" 2>/dev/null)
DRIFT_RC=$?
DRIFT_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^DRIFT|' 2>/dev/null | tr -d '[:space:]')
BROKEN_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^BROKEN|' 2>/dev/null | tr -d '[:space:]')
CHECKED_FILES=$(printf '%s\n' "$DRIFT_LINES" | awk -F'|' '{s += $3} END {print s + 0}')
# Число пар считается из вывода, а не пишется руками: с добавлением седьмой проверки
# (регистрация хуков, D55) захардкоженная «6» стала бы враньём в строке итога — ровно
# тот класс «числа в N местах», что проект уже чинил трижды.
TOTAL_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^[A-Z]*|' 2>/dev/null | tr -d '[:space:]')
: "${TOTAL_PAIRS:=0}"
: "${DRIFT_PAIRS:=0}"; : "${BROKEN_PAIRS:=0}"; : "${CHECKED_FILES:=0}"

if [ "${BROKEN_PAIRS:-0}" -gt 0 ] 2>/dev/null; then
    echo "Hook test files: $((total - failed))/$total passed — НО проверка дрейфа сама не сработала: $BROKEN_PAIRS пар(ы) не с чем сравнить"
    printf '%s\n' "$DRIFT_LINES" | awk -F'|' '$1 == "BROKEN" { printf "  ⚠ %s: %s\n", $2, $5 }'
    echo "  ⚠ ноль сравнений — это не «совпадает». Что именно работает, неизвестно."
elif [ "${DRIFT_PAIRS:-0}" -gt 0 ] 2>/dev/null; then
    echo "Hook test files: $((total - failed))/$total passed — НО проверен репозиторий, а работает другое: расходятся $DRIFT_PAIRS пар(ы) из $TOTAL_PAIRS"
    printf '%s\n' "$DRIFT_LINES" | awk -F'|' '$1 == "DRIFT" { printf "  ⚠ %s (%s из %s):%s\n", $2, $4, $3, $5 }'
    echo "  ⚠ зелёные тесты здесь НЕ означают, что работает установленное. Синхронизация: bash install.sh"
elif [ "${CHECKED_FILES:-0}" -eq 0 ] 2>/dev/null; then
    # Все пары ABSENT — установки нет вовсе (чистая машина, контейнер, прогон CI).
    # Это НЕ «совпадают»: сравнивать было не с чем. Первая версия строки печатала
    # «6 пар совпадают, сверено 0 файлов» — то самое утверждение из ничего, против
    # которого и заводился статус BROKEN. Поймано прогоном CI, а не рассуждением.
    echo "Hook test files: $((total - failed))/$total passed (установки нет — пары «репозиторий ↔ установленное» не сверялись)"
else
    echo "Hook test files: $((total - failed))/$total passed ($TOTAL_PAIRS пар «репозиторий ↔ установленное» совпадают, сверено $CHECKED_FILES файлов)"
fi
[ "$DRIFT_RC" -eq 0 ] || true
[ -n "$failed_names" ] && echo "FAILED:$failed_names"
if [ -n "$timed_out" ]; then
    if [ "$TEST_RERUN_FACTOR" -gt 1 ]; then
        echo "ЗАВИСЛИ (убиты по своему сроку, он в скобках, и снова при повторе в одиночку в ${TEST_RERUN_FACTOR}× срок):$timed_out"
    else
        echo "ЗАВИСЛИ (убиты по своему сроку, он в скобках; повтор в одиночку отключён):$timed_out"
    fi
fi
# Убитым под нагрузкой и зелёным в одиночку — СВОЯ строка: это не провал набора, а показание
# о нагрузке; смешать его с FAILED значило бы снова пустить два состояния по одному каналу.
if [ -n "$starved_names" ]; then
    echo "НЕ ХВАТИЛО ВРЕМЕНИ под нагрузкой (в одиночку зелёные, в итог провалов не входят):"
    printf '%s\n' "$starved_lines" | sed '/^$/d'
fi
# Дорогие тесты называются ПОИМЁННО на каждом прогоне. Порог в долях таймаута, а не в
# абсолюте: сторож и порог должны двигаться вместе, иначе при поднятом TEST_TIMEOUT
# отчёт замолкает ровно там, где тесты стали дороже.
SLOW_MIN="${TEST_SLOW_MIN:-$(( TEST_TIMEOUT / 6 ))}"
if [ -s "$SUITE_LOG" ]; then
    # Стенные секунды — первым числом (по ним сортировка и порог отчёта), процессорные — рядом:
    # под нагрузкой они расходятся в разы, и читатель обязан видеть обе (D392).
    _slow=$(awk -F'\t' -v m="$SLOW_MIN" '!/^#/ && $2+0 >= m {printf "  %4d с  %s  (CPU %s с)\n", $2, $3, ($4 == "" ? "?" : $4)}' \
            "$SUITE_LOG" | sort -rn)
    _sum=$(awk -F'\t' '!/^#/ {s+=$2} END {printf "%d", s}' "$SUITE_LOG")
    if [ -n "$_slow" ]; then
        echo "ДОРОЖЕ ${SLOW_MIN}с ($(printf '%s\n' "$_slow" | grep -c .) из $total; сумма по всем $_sum с):"
        printf '%s\n' "$_slow"
    fi
    echo "журнал прогона (пишется по ходу, переживает обрыв): $SUITE_LOG"
fi
# Базис обновляется ТОЛЬКО здесь — то есть лишь когда прогон дошёл до отчёта. Обрыв базис не
# трогает: иначе половина набора записалась бы как «обычное время», и следующий прогон
# резал бы живых по сроку, снятому с оборванного.
if [ -s "$SUITE_LOG" ] && [ "$total" -gt 0 ] && [ "$total" -ge "$(ls test_*.sh 2>/dev/null | grep -c '')" ]; then
    # Журнал ПОЛНОГО прогона сохраняется отдельной копией (D392, 13 сентября 2026): `suite-run.tsv`
    # перезаписывает каждый прогон, и выборочные прогоны коммитов стирают полный за минуты, а
    # цена тестов (кандидаты замера поодиночке, `scripts/costly-tests.sh --measure`) читается
    # только из полного. Копия — здесь же, где базис: лишь когда прогон дошёл до отчёта целиком.
    cp "$SUITE_LOG" "${SUITE_RUN_FULL_LOG:-$(dirname "$SUITE_LOG")/suite-run-full.tsv}" 2>/dev/null || true
    # Код 137 — убит сторожем, и это НЕ «время неизвестно», а «время БОЛЬШЕ срока». Прежде
    # в базис шли только успехи, и однажды убитый тест из круга не выходил: нет базиса →
    # общий срок 120 → снова убит → снова нет базиса. Поймано 11 сентября 2026 на
    # test_defect_registry_cache (в наборе 121 с и код 137, поодиночке 46 с и код 0).
    # Такому тесту базис ставится с запасом в половину — на следующем прогоне он получит
    # больше и либо уложится, либо снова вырастет. Настоящие падения (прочие коды) в базис
    # не идут: там время не о длительности, а об ошибке.
    # У теста, убитого под нагрузкой и прошедшего при повторе (D340), в журнале две строки: 137
    # и 0. В базис идёт НАСТОЯЩЕЕ время (строка 0), а не убитое ×1,5 — иначе следующий срок
    # считался бы от обрезка и тест убивали бы снова, платя повтором на каждом прогоне.
    awk -F'\t' '!/^#/ && $1 == 0 { t[$3] = $2 }
                !/^#/ && $1 == 137 && !($3 in t) { t[$3] = int($2 * 3 / 2) }
                END { for (n in t) printf "%s\t%s\n", t[n], n }' "$SUITE_LOG" \
        > "$SUITE_BASELINE.tmp" 2>/dev/null \
        && mv "$SUITE_BASELINE.tmp" "$SUITE_BASELINE" 2>/dev/null
fi
[ "$failed" -eq 0 ]
