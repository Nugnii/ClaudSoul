# Множество прогоняемого: по умолчанию всё, при --changed — выборка. Список строится ОДИН
# раз и кладётся в переменную: три обхода ниже обязаны видеть одно и то же множество,
# иначе фазы разойдутся и тест окажется то в одной, то в другой.
_changed_tests() {
    _ct_index="$REPO_SELF/.claude-docs/dep-index.tsv"
    _ct_backlog="$REPO_SELF/BACKLOG.md"
    _ct_ids=""
    _ct_always="$DIR_SELF/always-run.tsv"
