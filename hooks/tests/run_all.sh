# Предел на файл остаётся 120 с и при параллели — масштабировать его НЕ НУЖНО, и это
# установлено замером после того, как дважды было решено неверно.
# Ход был такой: под параллелью пять тестов убивались по таймауту, хотя проходят отдельно.
# Первое решение — множитель ×8 — убрало симптом. Второе — вернуть 120 с «чтобы сторож не
# слабел» — вернуло пять падений. Оба решения принимались о ПРЕДЕЛЕ, а причина была в другом:
# сторож таймаута снимался как один процесс, и его `sleep` переживал родителя. Каждый прогон
# оставлял восемь живых `sleep`, машина занималась, следующий прогон шёл медленнее и упирался
# в предел. После починки снятия (см. run_with_timeout) на ЧИСТОЙ машине: 368/368 за 4,1 мин
# при пределе 120 с и восьми потоках, ноль падений, ноль остатков.
TEST_TIMEOUT="${TEST_TIMEOUT:-120}"
TEST_TIMEOUT_MIN="${TEST_TIMEOUT_MIN:-15}"   # пол: быстрый тест всё равно получает столько
TEST_TIMEOUT_SLACK="${TEST_TIMEOUT_SLACK:-4}" # запас к обычному времени, во сколько раз
# Базис «сколько этот тест обычно идёт» — снимок последнего ПОЛНОГО прогона. Пишется в конце
# (только если прогон дошёл до отчёта), читается в начале следующего.
SUITE_BASELINE="${SUITE_BASELINE_FILE:-${STATE_DIR:-$HOME/.claude/hooks/state}/suite-baseline.tsv}"

# Срок сторожа для одного теста. Нагрузка входит множителем: на занятой машине тесты идут
# дольше, и фиксированный срок бил бы по здоровым (тот же дефект с положительной обратной
# связью, что описан в шапке `_kill_tree` — убитый тест оставляет сирот, машина занимается,
# следующий прогон медленнее).
_test_deadline() {
    local _n="$1" _base _load _mult _d
    [ -f "$SUITE_BASELINE" ] || { printf '%s' "$TEST_TIMEOUT"; return; }
    _base=$(awk -F'\t' -v n="$_n" '$2 == n {print $1; exit}' "$SUITE_BASELINE" 2>/dev/null)
    [ -n "$_base" ] || { printf '%s' "$TEST_TIMEOUT"; return; }
    # Нагрузка: 1 при свободной машине, растёт с очередью. `uptime` есть и на BSD, и на Linux
    # (pattern-shell-portability: `nproc` на macOS отсутствует, `sysctl -n hw.ncpu` — на Linux).
    # Берётся ПЕРВОЕ число после «average(s):» и только оно: на Linux дальше идут ещё два
    # через запятую («load average: 0.00, 0.01, 0.05»), и жадный шаблон склеивал их в
    # «0.00.» — awk читает такое как ноль, то есть «машина свободна» при любой нагрузке.
    _load=$(uptime 2>/dev/null | sed -n 's/.*averages*: *\([0-9][0-9]*[.,][0-9][0-9]*\).*/\1/p' \
            | head -1 | tr ',' '.')
    # НЕ ПРОЧИТАЛИ НАГРУЗКУ — отдаём общий срок, а не считаем машину свободной. Подстановка
    # `${_load:-1}` делала обратное: отказ чтения был неотличим от «нагрузки нет» (род B), и
    # последствие вредное — на занятой машине срок выходил МЕНЬШЕ нужного, и живой тест
    # убивали зря. Здесь действует то же правило, что и для отсутствия истории: нехватка
    # данных не ужесточает срок.
    case "$_load" in
        ''|*[!0-9.]*) printf '%s' "$TEST_TIMEOUT"; return ;;
    esac
    _mult=$(awk -v l="$_load" 'BEGIN { m = 1 + (l > 1 ? (l - 1) / 4 : 0); if (m > 4) m = 4; print m }')
    # ПОТОЛОК СЧИТАЕТСЯ ОТ БАЗИСА, а не берётся общим (11 сентября 2026, класс D340).
    # Прежде срок обрезался общим `TEST_TIMEOUT`, и персональный расчёт обессмысливался
    # ровно там, где нужнее: `test_defect_registry_cache` при базисе 46 с в параллели идёт
    # 121 с (делит ядра с соседями) — и убивался сторожем на 120, хотя поодиночке зелёный
    # за 46 с. Тест с базисом выше трети потолка был обречён при любой нагрузке.
    # Верхний предел остаётся, но растёт с предметом: втрое от обычного времени теста либо
    # общий срок — что больше. Зависший тест этим не спасается: его время уходит в
    # бесконечность, а не в утроенный базис.
    _cap=$(awk -v b="$_base" -v c="$TEST_TIMEOUT" 'BEGIN { t = b * 3; print (t > c ? t : c) }')
    _d=$(awk -v b="$_base" -v s="$TEST_TIMEOUT_SLACK" -v m="$_mult" -v f="$TEST_TIMEOUT_MIN" \
             -v c="$_cap" 'BEGIN { d = b * s * m; if (d < f) d = f; if (d > c) d = c; printf "%d", d }')
    printf '%s' "$_d"
}

total=0
