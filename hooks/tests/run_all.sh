# stdin закрыт намеренно: тест не должен зависеть от терминала, а открытая труба —
# ровно то окружение, в котором всё вставало.
# Вывод упавшего теста сохраняется и печатается (v1.14.3). До этого он уходил в /dev/null,
# и прогон мог сказать только КАКОЙ тест упал, но не почему. На своей машине это неважно —
# перезапустил руками и посмотрел. В CI перезапустить нечего: там другая система, и
# одиннадцать падений выглядели одинаково пустыми. Проверка, чьи доказательства недоступны
# в том месте, где её читают, сообщает факт провала и скрывает его содержание.

# Убить ДЕРЕВО процессов, а не один процесс. Сторож бил `kill -9 "$pid"` — только сам тест;
# всё, что тест запустил фоном, оставалось сиротой и продолжало крутиться. Замер 7 сентября
# 2026: 100 осиротевших процессов test_injection_log_rotate_concurrent возрастом до 8 часов,
# load average 41,6. Дефект с ПОЛОЖИТЕЛЬНОЙ ОБРАТНОЙ СВЯЗЬЮ: каждый убитый прогон оставляет
# сироту, сироты едят процессор, следующий прогон медленнее и умирает раньше — и оставляет
# ещё одну. Носитель в тестах был один, и починка здесь закрывает класс ДЛЯ ТЕСТОВ, КОТОРЫХ
# УБИВАЕТ ЭТОТ СТОРОЖ, — но не для кода, который убивает процессы сам.
#
# Здесь до 8 сентября 2026 стояло «починка здесь закрывает КЛАСС: ни один будущий тест не
# сможет пережить свою смерть детьми». Утверждение опровергнуто через сутки: три прогона
# набора висели 3 ч 49 мин (46 процессов, load 7,9), и уцелевший носитель лежал в
# `test_run_all_progress.sh:41-42` — в тесте ЭТОГО файла, который убивал вложенный прогон
# своим `kill -9` + `pkill -P` сверху вниз. Носителя тогда искали по симптому («тест, которого
# убивает раннер»), а не по устройству («код, убивающий дерево сверху вниз»); по устройству
# `grep` находит его за один вызов. Урок записан отдельно:
# case-2026-09-08-class-declared-closed-without-a-registry.
# Дети берутся ДО убийства родителя: после его смерти они уходят к pid 1, и связь теряется.
# С 13 сентября 2026 снятие дерева живёт в `hooks/timeout-lib.sh` (D369): тот же помощник нужен
# стражу возврата долга, и вторая копия разошлась бы молча (род K). Здесь он зовётся, а не
# определяется; без библиотеки сторож работать не может, и это отказ, а не тихая копия.
TIMEOUT_LIB="${TIMEOUT_LIB:-$(cd .. && pwd -P)/timeout-lib.sh}"
# shellcheck source=/dev/null
if [ -f "$TIMEOUT_LIB" ]; then . "$TIMEOUT_LIB"; else
    echo "run_all: нет $TIMEOUT_LIB — сторожу нечем снимать дерево процессов, прогон не начат" >&2
    exit 2
fi


