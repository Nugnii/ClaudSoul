#!/usr/bin/env bash
# run_all.sh — единый раннер всех хуковых тестов.
# До него «824/824 зелёных» нельзя было воспроизвести одной командой (F16):
# тесты с разнородными форматами итога приходилось запускать вручную и суммировать.
# Прогоняет каждый test_*.sh, суммирует pass/fail по файлам, единый exit code.
#
# Таймаут на файл (v1.11). Библиотечная функция, читавшая stdin при явно
# переданном аргументе, заморозила весь прогон на 10 минут: у раннера не было
# предела, и одно блокирующее чтение выглядело как «тесты идут», а не как отказ.
# Зависание — тоже провал и должно называться провалом. `timeout(1)` на macOS без
# coreutils отсутствует (pattern-shell-portability), поэтому watchdog на bash.

set -uo pipefail
cd "$(dirname "$0")" || exit 2
# Признак согласия проекта на уборку его бэклога (D512) в набор не протекает: тест, зовущий
# Stop-хук из сессии проекта с выставленным `CG_LOCAL_BACKLOG`, убирал бы НАСТОЯЩИЙ бэклог.
# Метку вложенности замера (`MEASURE_DUE_NESTED`) раннер НЕ снимает: она держит кольцо «замер → набор → тест → замер»
# (D1218, скептик opus по c1a390fc, M1), а тестам бегуна на своих реестрах не мешает — дверь судит реестр.
unset CG_LOCAL_BACKLOG

# Предел на файл остаётся 120 с и при параллели — масштабировать его НЕ НУЖНО, и это
# установлено замером после того, как дважды было решено неверно.
# Ход был такой: под параллелью пять тестов убивались по таймауту, хотя проходят отдельно.
# Первое решение — множитель ×8 — убрало симптом. Второе — вернуть 120 с «чтобы сторож не
# слабел» — вернуло пять падений. Оба решения принимались о ПРЕДЕЛЕ, а причина была в другом:
# сторож таймаута снимался как один процесс, и его `sleep` переживал родителя. Каждый прогон
# оставлял восемь живых `sleep`, машина занималась, следующий прогон шёл медленнее и упирался
# в предел. После починки снятия (см. run_with_timeout) на ЧИСТОЙ машине: 368/368 за 4,1 мин
# при пределе 120 с и восьми потоках, ноль падений, ноль остатков.
TEST_TIMEOUT="${TEST_TIMEOUT:-120}"
TEST_TIMEOUT_MIN="${TEST_TIMEOUT_MIN:-15}"   # пол: быстрый тест всё равно получает столько
TEST_TIMEOUT_SLACK="${TEST_TIMEOUT_SLACK:-4}" # запас к обычному времени, во сколько раз
# Базис «сколько этот тест обычно идёт» — снимок последнего ПОЛНОГО прогона. Пишется в конце
# (только если прогон дошёл до отчёта), читается в начале следующего.
SUITE_BASELINE="${SUITE_BASELINE_FILE:-${STATE_DIR:-$HOME/.claude/hooks/state}/suite-baseline.tsv}"

# Срок сторожа для одного теста. Нагрузка входит множителем: на занятой машине тесты идут
# дольше, и фиксированный срок бил бы по здоровым (тот же дефект с положительной обратной
# связью, что описан в шапке `_kill_tree` — убитый тест оставляет сирот, машина занимается,
# следующий прогон медленнее).
_test_deadline() {
    # РАСЧЁТ — У ВЛАДЕЛЬЦА (`deadline_for_test` в `hooks/timeout-lib.sh`), а не своей копией:
    # 23 сентября 2026 у него появился второй потребитель — прибор ложной зелени. Тело было
    # здесь и снято; при отсутствии библиотеки отдаётся общий срок, то есть прежнее поведение
    # для теста без базиса.
    if command -v deadline_for_test >/dev/null 2>&1; then
        # Путь базиса передаётся ЯВНО: в чужом дереве раннер уводит его в свой OUT_DIR
        # (:512), и владелец, читающий только STATE_DIR, взял бы чужой файл.
        SUITE_BASELINE_FILE="$SUITE_BASELINE" deadline_for_test "$1" "$TEST_TIMEOUT"
    else
        printf '%s' "$TEST_TIMEOUT"
    fi
}

total=0
failed=0
failed_names=""
timed_out=""

# stdin закрыт намеренно: тест не должен зависеть от терминала, а открытая труба —
# ровно то окружение, в котором всё вставало.
# Вывод упавшего теста сохраняется и печатается (v1.14.3). До этого он уходил в /dev/null,
# и прогон мог сказать только КАКОЙ тест упал, но не почему. На своей машине это неважно —
# перезапустил руками и посмотрел. В CI перезапустить нечего: там другая система, и
# одиннадцать падений выглядели одинаково пустыми. Проверка, чьи доказательства недоступны
# в том месте, где её читают, сообщает факт провала и скрывает его содержание.

# Убить ДЕРЕВО процессов, а не один процесс. Сторож бил `kill -9 "$pid"` — только сам тест;
# всё, что тест запустил фоном, оставалось сиротой и продолжало крутиться. Замер 7 сентября
# 2026: 100 осиротевших процессов test_injection_log_rotate_concurrent возрастом до 8 часов,
# load average 41,6. Дефект с ПОЛОЖИТЕЛЬНОЙ ОБРАТНОЙ СВЯЗЬЮ: каждый убитый прогон оставляет
# сироту, сироты едят процессор, следующий прогон медленнее и умирает раньше — и оставляет
# ещё одну. Носитель в тестах был один, и починка здесь закрывает класс ДЛЯ ТЕСТОВ, КОТОРЫХ
# УБИВАЕТ ЭТОТ СТОРОЖ, — но не для кода, который убивает процессы сам.
#
# Здесь до 8 сентября 2026 стояло «починка здесь закрывает КЛАСС: ни один будущий тест не
# сможет пережить свою смерть детьми». Утверждение опровергнуто через сутки: три прогона
# набора висели 3 ч 49 мин (46 процессов, load 7,9), и уцелевший носитель лежал в
# `test_run_all_progress.sh:41-42` — в тесте ЭТОГО файла, который убивал вложенный прогон
# своим `kill -9` + `pkill -P` сверху вниз. Носителя тогда искали по симптому («тест, которого
# убивает раннер»), а не по устройству («код, убивающий дерево сверху вниз»); по устройству
# `grep` находит его за один вызов. Урок записан отдельно:
# case-2026-09-08-class-declared-closed-without-a-registry.
# Дети берутся ДО убийства родителя: после его смерти они уходят к pid 1, и связь теряется.
# С 13 сентября 2026 снятие дерева живёт в `hooks/timeout-lib.sh` (D369): тот же помощник нужен
# стражу возврата долга, и вторая копия разошлась бы молча (род K). Здесь он зовётся, а не
# определяется; без библиотеки сторож работать не может, и это отказ, а не тихая копия.
TIMEOUT_LIB="${TIMEOUT_LIB:-$(cd .. && pwd -P)/timeout-lib.sh}"
# shellcheck source=/dev/null
if [ -f "$TIMEOUT_LIB" ]; then . "$TIMEOUT_LIB"; else
    echo "run_all: нет $TIMEOUT_LIB — сторожу нечем снимать дерево процессов, прогон не начат" >&2
    exit 2
fi


# Путь строится от ТЕКУЩЕГО каталога, а не от `BASH_SOURCE`: строка 14 уже сделала
# `cd "$(dirname "$0")"`, поэтому при вызове `bash hooks/tests/run_all.sh` из корня
# `dirname "$BASH_SOURCE"` даёт относительный «hooks/tests», и `hooks/tests/..` от уже
# сменённого каталога не существует. Дефект был виден только первой строкой вывода и
# потому жил незамеченным: библиотека переносимости молча не грузилась. Поймано
# 11 сентября 2026, когда выборочный прогон стал печатать свою строку первой.
PORTABLE_LIB="${PORTABLE_LIB:-$(cd .. && pwd -P)/portable-lib.sh}"
# shellcheck source=/dev/null
if [ -f "$PORTABLE_LIB" ]; then . "$PORTABLE_LIB"; else utf8_trim() { cat; }; fi

# ВЫВОД КАЖДОГО ТЕСТА МОЖНО ЗАБРАТЬ (23 сентября 2026). Замер «сколько свидетелей зелены,
# ничего не проверив» читается только из ВЫВОДА теста — код возврата у пропуска и у успеха
# один и тот же. Свою рамку прогона под это строить нельзя: владелец прогона здесь, и вывод
# он уже собирает. Каталог, ЗАДАННЫЙ СНАРУЖИ, прогон не удаляет — иначе замер получал бы
# пустоту; свой временный удаляет, как прежде.
# ВЛОЖЕННЫЙ ПРОГОН КАТАЛОГ НЕ НАСЛЕДУЕТ, И ЭТО ИЗМЕРЕНО В ЧАС НАПИСАНИЯ. Переменная
# окружения доходит до вложенного набора (`test_suite_runtime.sh` запускает свой), и он
# писал бы в РОДИТЕЛЬСКИЙ каталог поверх его файлов: первый же прогон уронил этот тест
# кодом 1 и стёр его собственный вывод. Тот же реестр, ради которого правка и делалась.
if [ -n "${SUITE_OUT_DIR:-}" ] && [ -z "${SUITE_RUN_NESTED:-}" ]; then
    OUT_DIR="$SUITE_OUT_DIR"
    mkdir -p "$OUT_DIR" || { echo "BROKEN: не создать $OUT_DIR" >&2; exit 2; }
else
    OUT_DIR=$(mktemp -d)
    trap 'rm -rf "$OUT_DIR"' EXIT
fi

# ПАРАЛЛЕЛЬНЫЙ ПРОГОН (8 сентября 2026). Умолчание — ОДИН поток: поведение прежнее до
# последней строки, и всё, что на нём держится (нога прогресса, порядок падений, коды),
# менять не пришлось. Ускорение включается явно: TEST_JOBS=8.
#
# Замер, из которого выведены и число, и устройство: 367 тестов, суммарно 547 с, медиана
# 0,29 с — половина тестов почти мгновенные, а топ-10 занимают 42% времени (самый долгий,
# test_mode_arg_guard, — 54 с). Последовательный прогон 9,1 мин; гибрид на 8 потоках — 1,9 мин
# (×4,7). Потолок — 0,9 мин, критический путь упирается в самый долгий тест.
#
# ПОЧЕМУ СЛОТЫ С ОПРОСОМ, А НЕ ПАЧКИ. `wait -n` в bash 3.2 нет (macOS; проверено:
# «wait: -n: invalid option»), а пачки фиксированного размера ждут самый долгий тест в
# каждой и дают всего ×1,6 — замер по тем же данным. Сортировка пачек по времени подняла бы
# до ×3,7, но требует знать длительность заранее, то есть заводить артефакт прошлого
# прогона. Опрос живости даёт истинную упаковку без всякого артефакта.
#
# ЧТО ИДЁТ ПОСЛЕДОВАТЕЛЬНО И ПОЧЕМУ. Тест, который трогает git-индекс ЭТОГО репозитория или
# пишет в боевой ~/.claude/hooks/state, параллелить нельзя: ресурс один, два писателя дают
# гонку, а не ускорение. Таких 44, и суммарно они занимают 55 с — цена их последовательности
# мала, а изоляция стоила бы правок в 44 файлах ради 50 секунд.
# Множество ВЫВОДИТСЯ из текста тестов, а не перечисляется (род F): тест, написанный завтра и
# взявший общий ресурс тем же способом, попадёт в последовательную очередь сам.
# НАЗВАННЫЙ ПРЕДЕЛ: признак видит два вида общего ресурса. Конфликт через третий (общий порт,
# фиксированное имя во временном каталоге) им не ловится. Условие снятия — нога
# test_run_all_parallel: параллельный прогон обязан давать ТОТ ЖЕ список падений, что
# последовательный; разойдутся — признак узок, и это станет видно на прогоне, а не в рассуждении.
# УМОЛЧАНИЕ ПОДНЯТО С 1 ДО ЧИСЛА ЯДЕР БЕЗ ДВУХ (11 сентября 2026). Параллельный прогон
# построен и измерен 8 сентября (коммит d1dcec6: «9,9 → 4,1 мин»), но умолчание осталось
# прежним — и все прогоны с тех пор шли в один поток: механизм есть, потребителя у него нет
# (корень R2). Цена измерена в тот день, когда владелец спросил, почему набор идёт вечность:
# 12 мин 11 с в один поток против 3 мин 54 с в восемь, 434/434 зелёные в обоих, падений и
# убитых сторожем ноль. Ядра считаются переносимо: `nproc` нет на macOS, `sysctl` на Linux
# (pattern-shell-portability); не определились — остаётся 1, то есть прежнее поведение.
# Безопасность параллели держит не это умолчание, а `needs_serial` ниже плюс нога
# `test_run_all_parallel`: параллельный прогон обязан давать ТОТ ЖЕ список падений.
_cpus=$(sysctl -n hw.ncpu 2>/dev/null || nproc 2>/dev/null || echo 1)
case "$_cpus" in ''|*[!0-9]*) _cpus=1 ;; esac
[ "$_cpus" -gt 2 ] && _jobs_default=$(( _cpus - 2 )) || _jobs_default=1
TEST_JOBS="${TEST_JOBS:-$_jobs_default}"
case "$TEST_JOBS" in ''|*[!0-9]*) TEST_JOBS=1 ;; esac
[ "$TEST_JOBS" -ge 1 ] 2>/dev/null || TEST_JOBS=1

needs_serial() {   # 0 — тест берёт общий ресурс либо меряет время, параллелить нельзя
    # ЗАМЕР ВРЕМЕНИ — третий вид общего ресурса, и он нашёлся первым же полным прогоном
    # 8 сентября 2026: test_attack_r3_quadratic_gsub упал под восемью потоками и прошёл
    # отдельно (3/3). Он сравнивает миллисекунды с порогом (1500 мс, отношение ×2.5), а
    # параллель меняет не длительность теста, а его ПРЕДМЕТ: машина занята соседями.
    # Тест это предвидел — его нога t0 говорит «замер сделан на загруженной машине,
    # вердикты ниже недостоверны», — но раннер всё равно засчитывал падение.
    # Признак: тест берёт время И сравнивает результат с числовым порогом.
    # Признак — СОБСТВЕННАЯ функция измерения (`measure()`, `now_ms()`), то есть тест меряет
    # длительность своей работы и судит по ней. Первая редакция требовала «время + сравнение
    # с числом ≥ 100» и поймала один тест из двух: `test_attack_quadratic_scaling` сравнивает
    # ОТНОШЕНИЕ (×2.5), а не миллисекунды. Расширение до «любое обращение к времени» дало бы
    # шесть, из них четыре ложных — там время это ДАННЫЕ (даты, возраст записи), и параллель
    # им безразлична. Замер: узкий признак берёт ровно два, оба падали под восемью потоками и
    # оба проходят отдельно.
    grep -qE '^[[:space:]]*(measure|now_ms)[[:space:]]*\(\)' "$1" 2>/dev/null && return 0
    grep -qE 'git +(add|commit|stash|checkout)' "$1" 2>/dev/null \
        && ! grep -qE 'git -C "\$(TMP|WORK|REPO|d|T)' "$1" 2>/dev/null && return 0
    grep -q 'STATE_DIR=' "$1" 2>/dev/null || {
        grep -q 'hooks/state' "$1" 2>/dev/null && return 0
    }
    # ВРЕМЯ МЕРИТ ВЫЗЫВАЕМЫЙ, А НЕ ТЕСТ (14 сентября 2026). Признак выше видит СОБСТВЕННУЮ
    # функцию измерения теста; тест, запускающий внутренний прогон со сторожем, времени сам
    # не берёт — его меряет раннер внутри. Под восемью потоками сторож убивает другую
    # фикстуру, и нога краснеет не по своей причине: `test_run_all_idle_timeout` упал так
    # дважды за ночь и оба раза зелен в одиночку.
    # Признак узок намеренно: зовёт `run_all.sh` И судит сторожа (ЗАВИСЛИ, НЕ ХВАТИЛО,
    # TEST_TIMEOUT, срок). Замер: берёт ТРОИХ (idle_timeout, rerun_starved, parallel) и не
    # трогает двоих, которые зовут прогон, но судят ВЫБОР тестов и долю фазы.
    grep -qE '(bash|sh) +"?\$[A-Z_]*/?run_all\.sh|bash run_all\.sh|\$RUN_ALL' "$1" 2>/dev/null \
        && grep -qE 'ЗАВИСЛИ|НЕ ХВАТИЛО|TEST_TIMEOUT|срок' "$1" 2>/dev/null && return 0
    return 1
}

# Счётчик прогресса общий для обеих фаз и переживает подоболочки: при параллели инкремент
# идёт из фоновых процессов, и переменная оболочки там не выживает (тот же класс, что
# `run_collector` в тестах контура несогласия).
PROGRESS_FILE=""
bump_progress() {
    [ -n "$PROGRESS_FILE" ] || return 0
    printf 'x' >> "$PROGRESS_FILE"
    local n f bad=0
    n=$(wc -c < "$PROGRESS_FILE" 2>/dev/null | tr -d ' ')
    case "$n" in ''|*[!0-9]*) return 0 ;; esac
    [ $((n % ${PROGRESS_EVERY:-25})) -eq 0 ] || return 0
    for f in "$OUT_DIR"/*.rc; do
        [ -f "$f" ] || continue
        [ "$(cat "$f" 2>/dev/null)" = "0" ] || bad=$((bad + 1))
    done
    echo "… прошло $n, упало $bad"
}

run_with_timeout() {  # $1 — тест, $2 — кратность срока (повтор в одиночку, D340)
    local script="$1" factor="${2:-1}" pid watch_pid rc=0
    # Свой каталог реестра сессий на каждый тест (D271). Тесты изолируются перечислением
    # известных им имён путей (LESSONS_DIR, STATE_DIR — те два, что публикует paths-lib),
    # а путь реестра лежит вне paths-lib под собственным именем; всякий путь, чьё имя в
    # перечень не попало, утекает в БОЕВОЙ ~/.claude/sessions молча. Пятнадцать тестов
    # подменяют переменную сами, но перечень — то самое устройство, которое и отказало:
    # тест, написанный завтра и забывший про неё, окажется в песочнице всё равно.
    # ВНИМАНИЕ: два теста выводят каталог ИЗ HOME намеренно и внешнюю переменную снимают
    # сами (test_knowledge_delta_reaches_registry, test_startup_signals) — их предмет
    # умолчание, и унаследованная переменная делала бы их отрицательный контроль ложным.
    # Свой TMPDIR на каждый тест (D1198) — то же устройство, что у реестра выше, и тот же
    # довод: 62 теста оставляли каталоги в системном TMPDIR с припиской «уберёт система»,
    # а система их не убирает — 31 октября 2026 там лежало 41 857 каталогов, 18,6 ГБ.
    # Каталог снимается сразу после теста, а не по выходу набора: один прогон пробы
    # оставлял 182 МБ, и на 600 тестах ждать конца набора значило копить гигабайты.
    _tmpd=$(mktemp -d "$OUT_DIR/t.XXXXXX" 2>/dev/null) || _tmpd=""
    # Подмена `mktemp` в каталоге теста (D1198): голая форма на macOS иначе уходит в системный каталог мимо TMPDIR.
    _tpath="$PATH"; [ -n "$_tmpd" ] && command -v cmd_tmpdir_shim >/dev/null 2>&1 && cmd_tmpdir_shim "$_tmpd" \
        && _tpath="$_tmpd/.bin:$PATH"
    PATH="$_tpath" TMPDIR="${_tmpd:-${TMPDIR:-/tmp}}" SR_SESSIONS_DIR="$OUT_DIR/sessions/$script" bash "$script" >"$OUT_DIR/$script.out" 2>&1 </dev/null &
    pid=$!
    _t0=$(date +%s)
    # Снимок процессорного времени детей ДО ожидания (D392, см. запись в журнал ниже): в
    # последовательном прогоне оболочка одна на все тесты, и счётчик детей накопительный.
    times > "$OUT_DIR/$script.times0" 2>/dev/null
    # СРОК У КАЖДОГО ТЕСТА СВОЙ, И ОН ВЗЯТ ИЗ ИСТОРИИ (поправка владельца 11 сентября 2026).
    # С 12 сентября это срок БЕЗ ПРОДВИЖЕНИЯ (см. сторож ниже), а не стенной.
    # Раньше сторож давал всем одни 120 с: тест, обычно идущий 2 с, висел минуту, прежде чем
    # его снимали, а прогон из 434 тестов платил за это минутами. Теперь срок = обычное время
    # этого теста × запас × поправку на нагрузку, и не меньше пола (`TEST_TIMEOUT_MIN`).
    # Теста нет в базисе (новый или первый прогон) — работает прежний общий TEST_TIMEOUT:
    # отсутствие истории НЕ ужесточает срок, иначе первый же прогон убил бы новый тест.
    _deadline=$(_test_deadline "$script")
    # Срок кладётся рядом с кодом возврата: он ПЕРСОНАЛЬНЫЙ, и отчёт обязан назвать тот,
    # по которому убили. Прежде печатался общий `TEST_TIMEOUT` — 11 сентября 2026 замер дал
    # «убиты по таймауту 3с» у теста, прожившего 75 секунд, то есть читатель шёл проверять
    # порог, которого не было.
    if [ "$factor" -gt 1 ] 2>/dev/null; then
        _deadline=$(( _deadline * factor ))
        printf '%s' "$_deadline" > "$OUT_DIR/$script.rerun_deadline" 2>/dev/null || true
    else
        printf '%s' "$_deadline" > "$OUT_DIR/$script.deadline" 2>/dev/null || true
    fi
    # СРОК — БЕЗ ПРОДВИЖЕНИЯ, а не стенной (D368, 12 сентября 2026). Утверждение сторожа —
    # «тест не продвигается», и признак продвижения у теста есть: растёт его вывод. Отсчёт
    # сбрасывается при каждом росте файла вывода и потому не зависит от числа потоков: под
    # нагрузкой тест говорит реже, но говорит. Замер 8 сентября: при TEST_JOBS=4 два теста,
    # зелёные поодиночке (28 и 54 с), были убиты стенным порогом из-за соседей; два прежних
    # захода (см. шапку) правили ПРЕДЕЛ, а предмет утверждения — не секунды. Потолок остаётся,
    # пятикратный срок: тест, который говорит, но не кончается (цикл с печатью), тоже завис.
    # Тик 1 с — пол срока 15 с, точности в секунду достаточно; размер через `wc -c`, он есть
    # везде (`stat -f`/`stat -c` расходятся между BSD и GNU).
    ( _idle=0; _wall=0; _seen=-1; _hard=$(( _deadline * 5 ))
      while kill -0 "$pid" 2>/dev/null; do
          sleep 1; _idle=$((_idle + 1)); _wall=$((_wall + 1))
          _now=$(wc -c < "$OUT_DIR/$script.out" 2>/dev/null | tr -d ' ')
          [ "${_now:-0}" != "$_seen" ] && { _seen="${_now:-0}"; _idle=0; }
          if [ "$_idle" -ge "$_deadline" ] || [ "$_wall" -ge "$_hard" ]; then kill_tree "$pid"; break; fi
      done ) &
    watch_pid=$!
    wait "$pid" 2>/dev/null || rc=$?
    # Длительность КАЖДОГО теста, а не только набора (11 сентября 2026). До этого дня
    # мерился набор целиком (`scripts/suite-runtime.sh`, период 30 дн.), и «этот тест
    # дорогой» было невыразимо: тест, разворачивающийся в прогон соседей, проходил
    # поодиночке за 2 с и валил шестерых в полном наборе. Замер — условие признака:
    # без числа порог пришлось бы назначать на глаз.
    # Журнал пополняется ЗДЕСЬ, до возврата кода наверх: обрыв прогона оставляет всё, что
    # успело отработать (проверено 11 сентября 2026 — прогон убит на 45-й секунде, в журнале
    # 137 записей). Код 137 в первом поле — убит сторожем, то есть завис, а не упал.
    # Второго артефакта о том же нет намеренно: один факт — один владелец (R1).
    # ЧЕТВЁРТАЯ КОЛОНКА — ПРОЦЕССОРНОЕ ВРЕМЯ ТЕСТА (D392, 13 сентября 2026). Стенная длительность
    # под восемью потоками раздувается соседями (тест кэша реестра: 38 с в одиночку, 282 с в
    # полном прогоне), и цена теста по ней не читается; порог «дороже 20 с» судит по CPU.
    # `times` стоит в САМОЙ оболочке до запуска и после ожидания, а не в `$(…)`: подстановка
    # форкает, и счётчик детей у форка нулевой — проба 13 сентября дала 0 при 400 мс работы
    # ребёнка. Сторож в момент снятия ещё жив и в разность не входит. Секунды, округление вниз.
    times > "$OUT_DIR/$script.times1" 2>/dev/null
    _cpu=$(awk 'FNR == 2 { s = 0; for (i = 1; i <= 2; i++) { split($i, a, /[ms]/); s += a[1] * 60 + a[2] } v[FILENAME] = s }
                END { d = v[ARGV[2]] - v[ARGV[1]]; if (d < 0) d = 0; printf "%d", d }' \
           "$OUT_DIR/$script.times0" "$OUT_DIR/$script.times1" 2>/dev/null)
    case "${_cpu:-}" in ''|*[!0-9]*) _cpu=0 ;; esac
    printf '%s\t%s\t%s\t%s\n' "$rc" "$(( $(date +%s) - _t0 ))" "$script" "$_cpu" >> "$SUITE_LOG" 2>/dev/null
    # Сторож снимается ДЕРЕВОМ, а не одним процессом (8 сентября 2026). `kill "$watch_pid"`
    # убивает подоболочку `( sleep N; _kill_tree )`, а её `sleep` переживает родителя и
    # висит весь остаток срока. При последовательном прогоне это `sleep 120` и уходило
    # незаметно; под параллелью сторожей столько же, сколько тестов, и каждый прогон
    # оставлял восемь живых `sleep 480` — машина занята, следующий прогон медленнее,
    # и он оставляет ещё восемь. Дефект с положительной обратной связью, тот же самый,
    # что описан в шапке `_kill_tree` выше и что чинили утром того же дня в
    # `test_run_all_progress.sh` — там его объявили закрытым классом, а здесь он и жил.
    kill_tree "$watch_pid"
    wait "$watch_pid" 2>/dev/null || true
    [ -n "$_tmpd" ] && rm -rf "$_tmpd"
    return "$rc"
}

