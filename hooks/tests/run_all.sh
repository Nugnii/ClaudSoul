                    grep -qF "$_cs" <<< "$(grep -vE '^[[:space:]]*#' "$_t" 2>/dev/null)" && basename "$_t"
                done
                # ВТОРОЙ ШАГ (13 сентября 2026). Прежний выбор был ОДНОШАГОВЫМ: тест,
                # зависящий от механизма ЧЕРЕЗ ПОСРЕДНИКА, имени механизма не содержит и
