# Семь пар, а не одна (v1.14.2, седьмая — регистрация, v1.16.2). Прежняя версия сравнивала только hooks/*.sh и вычисляла
# путь к источнику относительно $0 УЖЕ ПОСЛЕ cd выше — при вызове `bash hooks/tests/run_all.sh`
# из корня путь складывался сам с собой, шаблон не находил ничего, и печаталось
# утвердительное «репозиторий и установленное совпадают». Ноль сравнений выглядел как ноль
# расхождений. Логика вынесена в drift-check.sh, где ноль сравнений — это BROKEN.
DRIFT_LINES=$(bash "$(pwd)/drift-check.sh" 2>/dev/null)
DRIFT_RC=$?
DRIFT_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^DRIFT|' 2>/dev/null | tr -d '[:space:]')
BROKEN_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^BROKEN|' 2>/dev/null | tr -d '[:space:]')
CHECKED_FILES=$(printf '%s\n' "$DRIFT_LINES" | awk -F'|' '{s += $3} END {print s + 0}')
# Число пар считается из вывода, а не пишется руками: с добавлением седьмой проверки
# (регистрация хуков, D55) захардкоженная «6» стала бы враньём в строке итога — ровно
# тот класс «числа в N местах», что проект уже чинил трижды.
TOTAL_PAIRS=$(printf '%s\n' "$DRIFT_LINES" | grep -c '^[A-Z]*|' 2>/dev/null | tr -d '[:space:]')
: "${TOTAL_PAIRS:=0}"
: "${DRIFT_PAIRS:=0}"; : "${BROKEN_PAIRS:=0}"; : "${CHECKED_FILES:=0}"

if [ "${BROKEN_PAIRS:-0}" -gt 0 ] 2>/dev/null; then
    echo "Hook test files: $((total - failed))/$total passed — НО проверка дрейфа сама не сработала: $BROKEN_PAIRS пар(ы) не с чем сравнить"
    printf '%s\n' "$DRIFT_LINES" | awk -F'|' '$1 == "BROKEN" { printf "  ⚠ %s: %s\n", $2, $5 }'
    echo "  ⚠ ноль сравнений — это не «совпадает». Что именно работает, неизвестно."
elif [ "${DRIFT_PAIRS:-0}" -gt 0 ] 2>/dev/null; then
    echo "Hook test files: $((total - failed))/$total passed — НО проверен репозиторий, а работает другое: расходятся $DRIFT_PAIRS пар(ы) из $TOTAL_PAIRS"
    printf '%s\n' "$DRIFT_LINES" | awk -F'|' '$1 == "DRIFT" { printf "  ⚠ %s (%s из %s):%s\n", $2, $4, $3, $5 }'
    echo "  ⚠ зелёные тесты здесь НЕ означают, что работает установленное. Синхронизация: bash install.sh"
elif [ "${CHECKED_FILES:-0}" -eq 0 ] 2>/dev/null; then
    # Все пары ABSENT — установки нет вовсе (чистая машина, контейнер, прогон CI).
    # Это НЕ «совпадают»: сравнивать было не с чем. Первая версия строки печатала
    # «6 пар совпадают, сверено 0 файлов» — то самое утверждение из ничего, против
    # которого и заводился статус BROKEN. Поймано прогоном CI, а не рассуждением.
    echo "Hook test files: $((total - failed))/$total passed (установки нет — пары «репозиторий ↔ установленное» не сверялись)"
else
    echo "Hook test files: $((total - failed))/$total passed ($TOTAL_PAIRS пар «репозиторий ↔ установленное» совпадают, сверено $CHECKED_FILES файлов)"
fi
[ "$DRIFT_RC" -eq 0 ] || true
[ -n "$failed_names" ] && echo "FAILED:$failed_names"
if [ -n "$timed_out" ]; then
    if [ "$TEST_RERUN_FACTOR" -gt 1 ]; then
        echo "ЗАВИСЛИ (убиты по своему сроку, он в скобках, и снова при повторе в одиночку в ${TEST_RERUN_FACTOR}× срок):$timed_out"
    else
        echo "ЗАВИСЛИ (убиты по своему сроку, он в скобках; повтор в одиночку отключён):$timed_out"
    fi
fi
# Убитым под нагрузкой и зелёным в одиночку — СВОЯ строка: это не провал набора, а показание
# о нагрузке; смешать его с FAILED значило бы снова пустить два состояния по одному каналу.
if [ -n "$starved_names" ]; then
    echo "НЕ ХВАТИЛО ВРЕМЕНИ под нагрузкой (в одиночку зелёные, в итог провалов не входят):"
    printf '%s\n' "$starved_lines" | sed '/^$/d'
fi
if [ -n "$flaky_names" ]; then
    echo "УПАЛИ ТОЛЬКО ПОД НАГРУЗКОЙ (в одиночку зелёные, в итог провалов не входят; дефект теста, хвост первого падения ниже):"
    printf '%s\n' "$flaky_lines" | sed '/^$/d'
fi
[ -n "$rerun_skipped" ] && echo "ПОВТОР В ОДИНОЧКУ ПРОПУЩЕН (упавших больше TEST_RERUN_MAX=$TEST_RERUN_MAX — вероятнее общий дефект, чем нагрузка):$rerun_skipped"
# Дорогие тесты называются ПОИМЁННО на каждом прогоне. Порог в долях таймаута, а не в
# абсолюте: сторож и порог должны двигаться вместе, иначе при поднятом TEST_TIMEOUT
# отчёт замолкает ровно там, где тесты стали дороже.
SLOW_MIN="${TEST_SLOW_MIN:-$(( TEST_TIMEOUT / 6 ))}"
if [ -s "$SUITE_LOG" ]; then
    # Стенные секунды — первым числом (по ним сортировка и порог отчёта), процессорные — рядом:
    # под нагрузкой они расходятся в разы, и читатель обязан видеть обе (D392).
    _slow=$(awk -F'\t' -v m="$SLOW_MIN" '!/^#/ && $2+0 >= m {printf "  %4d с  %s  (CPU %s с)\n", $2, $3, ($4 == "" ? "?" : $4)}' \
            "$SUITE_LOG" | sort -rn)
    _sum=$(awk -F'\t' '!/^#/ {s+=$2} END {printf "%d", s}' "$SUITE_LOG")
    if [ -n "$_slow" ]; then
        echo "ДОРОЖЕ ${SLOW_MIN}с ($(printf '%s\n' "$_slow" | grep -c .) из $total; сумма по всем $_sum с):"
        printf '%s\n' "$_slow"
    fi
    echo "журнал прогона (пишется по ходу, переживает обрыв): $SUITE_LOG"
fi
# Базис обновляется ТОЛЬКО здесь — то есть лишь когда прогон дошёл до отчёта. Обрыв базис не
# трогает: иначе половина набора записалась бы как «обычное время», и следующий прогон
# резал бы живых по сроку, снятому с оборванного.
if [ -s "$SUITE_LOG" ] && [ "$total" -gt 0 ] && [ "$total" -ge "$(ls test_*.sh 2>/dev/null | grep -c '')" ]; then
    # Журнал ПОЛНОГО прогона сохраняется отдельной копией (D392, 13 сентября 2026): `suite-run.tsv`
    # перезаписывает каждый прогон, и выборочные прогоны коммитов стирают полный за минуты, а
    # цена тестов (кандидаты замера поодиночке, `scripts/costly-tests.sh --measure`) читается
    # только из полного. Копия — здесь же, где базис: лишь когда прогон дошёл до отчёта целиком.
    cp "$SUITE_LOG" "${SUITE_RUN_FULL_LOG:-$(dirname "$SUITE_LOG")/suite-run-full.tsv}" 2>/dev/null || true
    # Код 137 — убит сторожем, и это НЕ «время неизвестно», а «время БОЛЬШЕ срока». Прежде
    # в базис шли только успехи, и однажды убитый тест из круга не выходил: нет базиса →
    # общий срок 120 → снова убит → снова нет базиса. Поймано 11 сентября 2026 на
    # test_defect_registry_cache (в наборе 121 с и код 137, поодиночке 46 с и код 0).
    # Такому тесту базис ставится с запасом в половину — на следующем прогоне он получит
    # больше и либо уложится, либо снова вырастет. Настоящие падения (прочие коды) в базис
    # не идут: там время не о длительности, а об ошибке.
    # У теста, убитого под нагрузкой и прошедшего при повторе (D340), в журнале две строки: 137
    # и 0. В базис идёт НАСТОЯЩЕЕ время (строка 0), а не убитое ×1,5 — иначе следующий срок
    # считался бы от обрезка и тест убивали бы снова, платя повтором на каждом прогоне.
    awk -F'\t' '!/^#/ && $1 == 0 { t[$3] = $2 }
                !/^#/ && $1 == 137 && !($3 in t) { t[$3] = int($2 * 3 / 2) }
                END { for (n in t) printf "%s\t%s\n", t[n], n }' "$SUITE_LOG" \
        > "$SUITE_BASELINE.tmp" 2>/dev/null \
        && { mv "$SUITE_BASELINE.tmp" "$SUITE_BASELINE" 2>/dev/null \
            || echo "run_all: базис сроков не записан ($SUITE_BASELINE) — следующий прогон возьмёт прежний" >&2; }   # учёт, не вердикт (D1262)
fi
[ "$failed" -eq 0 ]
