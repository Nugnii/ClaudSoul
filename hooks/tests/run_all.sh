                #     который зовёт scripts/backlog-recheck.sh (посредник), а не библиотеку;
                #   · правка scripts/outcome-share.sh сломала test_backlog_green_side, который
                #     исполняет «Проверку» пункта D358 — а та зовёт скрипт ТЕКСТОМ КОМАНДЫ.
                # Оба ребра уже существуют в дереве и просто не подавались в выбор: индекс
                # `.claude-docs/dep-index.tsv` держит и зависимых (колонка deps), и тесты
                # механизма (колонка tests), а номер пункта связывает команду с тестом.
                # НАЗВАННЫЙ ПРЕДЕЛ: индекс может отстать от дерева (его строки пересобирает
                # `dep-index.py --changed`), и тогда второй шаг видит вчерашние рёбра;
                # молчаливого отката при этом нет — первый шаг работает как прежде.
                # Условие снятия: индекс станет пересобираться стражем на каждую правку кода,
                # и «отстал» перестанет быть возможным состоянием.
                if [ -f "$_ct_index" ]; then
                    # тесты ЗАВИСИМЫХ механизмов + собственные тесты по индексу
                    awk -F'\t' -v f="$_cf" '
                        $1 ~ /^#/ { next }
                        $1 == f || index($3, f) > 0 { print $5 }
                    ' "$_ct_index" | tr ',' '\n' | sed -n 's|^hooks/tests/||p'
                fi
                if [ -f "$_ct_backlog" ]; then
                    # номера пунктов долга, чьи команды называют этот механизм
                    _ct_ids="$_ct_ids $(awk -v n="$_cb" '
                        match($0, /\*\*D[0-9]+\*\*/) { id = substr($0, RSTART + 2, RLENGTH - 4) }
                        id != "" && index($0, n) > 0 { print id }
                    ' "$_ct_backlog" | sort -u | tr '\n' ' ')"
                fi ;;
        esac
    done
    # Тесты, называющие номер такого пункта: связь «команда пункта → тест» идёт по номеру,
    # потому что фикстуры зелёной стороны и архиватора именуются им (`green_D358`).
    # У НОМЕРА ПУНКТА комментарий считается, в отличие от имени механизма. Имя механизма
    # встречается в прозе теста сплошь и рядом, и потому берётся только из кода; номер
    # пункта, наоборот, называют ИМЕННО в шапке — «повод: D358», — и это ровно то место,
    # где тест объявляет, чему служит. Замер 13 сентября 2026: номер несут 8 тестов (D358),
    # 4 (D405), 2 (D307) — прибавка ограниченная, а без комментариев путь пустел на
    # `test_daily_signal_queued.sh`, который «Проверка» D358 буквально запускает.
    for _id in $_ct_ids; do
        [ -n "$_id" ] || continue
        grep -lF "$_id" "$DIR_SELF"/test_*.sh 2>/dev/null | while IFS= read -r _t; do
            basename "$_t"
        done
    done
}

