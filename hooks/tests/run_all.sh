    # проверить сам ВЫБОР можно только настоящей правкой рабочего дерева, а такой тест
    # мутирует репозиторий и в наборе запрещён. Боевой путь переменную не ставит.
    if [ -n "${CHANGED_FILES:-}" ]; then
        _ct_files=$(printf '%s\n' $CHANGED_FILES | sort -u)
    else
    _ct_files=$( { git -C "$REPO_SELF" diff --name-only HEAD 2>/dev/null
                   git -C "$REPO_SELF" diff --name-only --cached 2>/dev/null
                   git -C "$REPO_SELF" ls-files --others --exclude-standard 2>/dev/null; } | sort -u )
    fi
    for _cf in $_ct_files; do
        case "$_cf" in
            hooks/tests/test_*.sh) basename "$_cf" ;;          # правили сам тест — гоним его
            *.sh|*.py)
                _cb=$(basename "$_cf"); _cs="${_cb%.*}"
                printf 'test_%s.sh
' "$(printf '%s' "$_cs" | tr '-' '_')"
                # упоминание имени механизма в КОДЕ теста, а не в комментарии
                for _t in "$DIR_SELF"/test_*.sh; do
