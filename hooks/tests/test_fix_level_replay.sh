#!/usr/bin/env bash
# test_fix_level_replay.sh — «Проверка результата» fix-level-replay.py меряет объявленный результат.
#
# Результат: команда из шапки scripts/fix-level-replay.py на подложенном корпусе печатает число
#            блоков речи агента, число совпадений словаря и заглушённых по прежней и нынешней
#            логике порознь — маркер механизма в другом предложении глушил прежде и не глушит теперь.
# Проверка результата: этот тест.
#
# Повод (D282, 12 сентября 2026). Кандидатов в свидетели у инструмента не было ни одного. Корпус
# подкладывается через HOME; словарь и маркеры — настоящие, из hooks/fix-level-check.sh (их наличие
# инструмент сам проверяет отрицательным контролем). Команда БЕРЁТСЯ из шапки инструмента.
set -uo pipefail
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
TOOL="$REPO/scripts/fix-level-replay.py"
[ -f "$TOOL" ] || { echo "FAIL: $TOOL not found"; exit 1; }
CMD=$(awk '/^# Проверка результата:/ { sub(/^# Проверка результата: */, ""); print; exit }' "$TOOL" \
    | sed -E 's/ (даёт 0|—|печатает).*//')
case "$CMD" in
    *"$(basename "$0")"*) echo "FAIL: шапка инструмента зовёт сам этот тест — рекурсия"; exit 1 ;;
    *fix-level-replay.py*) ;;
    *) echo "FAIL: команда шапки не запускает инструмент: '$CMD'"; exit 1 ;;
esac

PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
has() { grep -Fq -- "$2" <<< "$OUT" && ok || bad "$1" "нет строки «$2»"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
H="$TMP/home"; P="$H/.claude/projects/proj"
blk() { printf '{"message":{"role":"assistant","content":[{"type":"text","text":"%s"}]}}\n' "$1"; }
run_tool() {
    OUT=$(cd "$REPO" && HOME="$H" bash -c "$CMD" 2>&1); RC=$?
}

# --- T1: три блока, два совпадения, одно заглушено обеими логиками ---------------------------------
rm -rf "$H"; mkdir -p "$P"
{
    blk 'Понял, надо вынести урок из этого случая.'
    blk 'Понял, надо вынести урок — заведу хук.'
    blk 'Просто ответ без фраз словаря.'
    printf '{"message":{"role":"user","content":"надо вынести урок"}}\n'
} > "$P/s1.jsonl"
run_tool
[ "$RC" -eq 0 ] && ok || bad T1 "rc=$RC — $OUT"
has T1 'блоков речи агента в корпусе: 3'
has T1 'совпадений словаря: 2'
has T1 'заглушено ПРЕЖНЕЙ логикой (маркер где угодно в ответе): 1'
has T1 'заглушено НЫНЕШНЕЙ логикой (маркер в той же фразе): 1'
has T1 'доля заглушённых: было 50%, стало 50%'

# --- T2: маркер в ДРУГОМ предложении — прежняя логика глушит, нынешняя нет -----------------------
rm -rf "$H"; mkdir -p "$P"
blk 'Надо вынести урок. Хук тут ни при чём.' > "$P/s1.jsonl"
run_tool
[ "$RC" -eq 0 ] && ok || bad T2 "rc=$RC — $OUT"
has T2 'совпадений словаря: 1'
has T2 'доля заглушённых: было 100%, стало 0%'
has T2 'признак доносит до сессии: было 0, стало 1'

# --- T3: заглушено больше половины — вердикт «сузить дальше» (порог 50%) --------------------------
rm -rf "$H"; mkdir -p "$P"
{
    blk 'Понял, надо вынести урок — заведу хук.'
    blk 'Понял, надо вынести урок — напишу тест.'
    blk 'Понял, надо вынести урок из этого случая.'
} > "$P/s1.jsonl"
run_tool
[ "$RC" -eq 0 ] && ok || bad T3 "rc=$RC — $OUT"
has T3 'совпадений словаря: 3'
has T3 'ВЕРДИКТ: глушитель всё ещё съедает больше половины'

# --- T4: две фразы в блоке, маркер только у первой — блок НЕ заглушён (условие all, не any) ----------
rm -rf "$H"; mkdir -p "$P"
blk 'Понял, надо вынести урок — заведу хук. Будем осторожнее.' > "$P/s1.jsonl"
run_tool
[ "$RC" -eq 0 ] && ok || bad T4 "rc=$RC — $OUT"
has T4 'совпадений словаря: 1'
has T4 'доля заглушённых: было 100%, стало 0%'

echo ""
echo "fix-level-replay tests: $PASS/$((PASS + FAIL)) passed"
exit $(( FAIL != 0 ))
