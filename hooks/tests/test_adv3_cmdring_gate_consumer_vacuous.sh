#!/usr/bin/env bash
# СУДИТ: hooks/completion-gate.sh hooks/tests/test_completion_gate_open_items.sh hooks/backlog-lib.sh
# test_adv3_cmdring_gate_consumer_vacuous.sh — свидетель разбора живого формата бэклога (нога T7 test_completion_gate_open_items.sh) не выносит «чисто», когда гейт не исполнил ни одной «Проверки».
#
# Атака (противник ограды кольца, раунд 3, 1 октября 2026; вход закрытого класса 3 — «пропуск
# читался как «проверено, чисто»»). Ограда завела у гейта НОВЫЙ канал «не исполнено» (#CG_RING →
# «ℹ️ … не исполнена — кольцо»). Потребитель, судящий ПОКРЫТИЕ гейта, его не знает: нога T7 гоняет
# гейт на живом BACKLOG.md и требует «нет „ОТКРЫТОГО пункта не красная“», а T7b (D460, «ПОКРЫТИЕ
# НАЗЫВАЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ») исключает лишь пропуск по БЮДЖЕТУ — «не хватило бюджета». На
# глубине 2 по живому бэклогу (законная по шапке ограды цепочка «Проверка» ☑ → свидетель → «Проверка»
# открытого — форма D499 + D263) гейт отбивает ВСЕ «Проверки» пределом глубины, в его выводе есть
# только «кольцо», и T7 зелена ни о чём: свидетель, чья нога объявлена против ложной зелени по
# непокрытию, выносит «чисто», ничего не проверив.
#
# Рамка: копия hooks/ в песочнице и её BACKLOG.md с ОТКРЫТЫМ D9901, чья «Проверка» `true` зелёная.
# С D1231 нога T7 судит РАЗБОР живого формата на копии с подменёнными командами (все `true` — гейт обязан назвать
# каждый открытый пункт), а не зелень живых пунктов. Контроль: прямой прогон копии свидетеля ЗЕЛЁН — гейт исполнил
# «Проверки» копии и назвал D9901. Предмет прежний: под оградой кольца гейт не исполняет ничего, не называет D9901,
# и T7 обязана покраснеть, а не вынести «чисто».
# Предмет: тот же прогон, когда в BACKLOG_CMD_RUNNING две записи этого бэклога (как их кладут
# архиватор и свидетель зелёной стороны выше по дереву).
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
unset BACKLOG_CHECKS_NESTED BACKLOG_CMD_RUNNING BACKLOG_CMD_DEPTH_MAX CG_BUDGET_OPEN
T=$(mktemp -d)   # временное уберёт система
export STATE_DIR="$T/state"; mkdir -p "$STATE_DIR"
S="$T/s"; mkdir -p "$S/hooks/tests"
cp "$REPO"/hooks/*.sh "$S/hooks/"
cp -R "$REPO/hooks/lib" "$S/hooks/"
cp "$REPO/hooks/tests/test_completion_gate_open_items.sh" "$REPO/hooks/tests/alerts-read.sh" "$S/hooks/tests/"   # сосед свидетеля — D1309
printf -- '# BACKLOG\n\n- ☐ **D9901** открытый пункт, чья «Проверка» уже зелёная\n  **Проверка.** `true` → 0\n' > "$S/BACKLOG.md"
SUBJ="$S/hooks/tests/test_completion_gate_open_items.sh"

# Контроль различения: прямой прогон — гейт исполнил «Проверки» копии, T7 назвала D9901, свидетель зелен.
D_OUT=$(bash "$SUBJ" 2>&1); D_RC=$?
[ "$D_RC" = 0 ] && ok \
    || bad TC "контроль: прямой прогон свидетеля красен — рамка не умеет отвечать «гейт исполнил и назвал» (rc $D_RC): «$(printf '%s' "$D_OUT" | grep FAIL | head -2 | tr '\n' ' ')»"

# Предмет: гейт не исполнил НИ ОДНОЙ «Проверки» — свидетель обязан покраснеть на T7, а не вынести «чисто». До D1231
# рамкой были две записи этого бэклога выше по дереву (ограда кольца отбивала всё); с D1231 нога T7 судит КОПИЮ
# бэклога, а ограда держится за метку файла (`backlog_cmd_fileid`), и на копии из одних `true`/`false` рекурсии нет по
# построению. «Ничего не исполнил» здесь даёт срок одной команды 0 (`CG_TIMEOUT=0`): каждая уходит в «не проверена».
V_OUT=$(env CG_TIMEOUT=0 bash "$SUBJ" 2>&1); V_RC=$?
{ [ "$V_RC" != 0 ] && grep -q 'FAIL \[T7' <<< "$V_OUT"; } && ok \
    || bad T1 "свидетель не покраснел на T7 (rc $V_RC), хотя гейт не исполнил ни одной «Проверки» (CG_TIMEOUT=0): «$(printf '%s' "$V_OUT" | grep -E 'FAIL|passed' | head -3 | tr '\n' ' ')»"

echo "adv3 cmdring gate consumer vacuous: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
