#!/usr/bin/env bash
# test_tests_exit_explicit.sh — код возврата теста берётся ЯВНЫМ exit, а не последней
# командой файла.
#
# Повод (D289). У 232 тестов из 334 последняя непустая строка была `[ "$FAIL" -eq 0 ]`, и
# код возврата скрипта есть код последней команды. Любая строка, дописанная после неё —
# echo, уборка, случайная правка, — молча делает прогон зелёным при красных утверждениях.
# Поймано не рассуждением, а случаем: жульничество критика дописало строку в тело теста, и
# тест позеленел, не изменив ни одного утверждения.
#
# Почему страж, а не разовая правка. Каждый новый тест пишется по образцу соседа, то есть
# воспроизводит его концовку. Без стража счётчик отрастает обратно за несколько дней — и
# отрастал: замер в пункте говорил «220 из 319», на 6 сентября 2026 стало 232 из 334.
#
# Универсум ВЫВОДИТСЯ из индекса git (`universe_tests`), а не перечисляется шаблоном
# оболочки: перечень не спускается в подкаталоги и даёт зелёный вердикт о непросмотренном
# (род F). Ноль просмотренных файлов — отказ, а не успех.
#
# Явные аргументы — универсум прогона (D338): так страж момента записи
# `hooks/test-exit-explicit-guard.sh` зовёт ТОТ ЖЕ предикат на итоге правки, и правило
# остаётся у одного владельца; без аргументов — весь индекс.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO" || exit 1
UNIVERSE_ROOT="$REPO"
. "$REPO/hooks/tests/universe-lib.sh"

PASS=0; FAIL=0
seen=0
bad=""

if [ "$#" -gt 0 ]; then UNIVERSE=$(printf '%s\n' "$@"); else UNIVERSE=$(universe_tests); fi
while IFS= read -r f; do
    [ -f "$f" ] || continue
    seen=$((seen + 1))
    # Последняя непустая строка файла — именно она решает код возврата.
    last=$(grep -vE '^[[:space:]]*$' "$f" | tail -1)
    case "$last" in
        exit\ *|exit) ;;                      # явный выход — норма
        *) bad="${bad}${f}: ${last}"$'\n' ;;
    esac
done <<< "$UNIVERSE"

if [ "$seen" -eq 0 ]; then
    echo "FAIL: универсум пуст — тесты не просмотрены, вердикт недействителен"
    echo "test_tests_exit_explicit: 0 passed, 1 failed"
    exit 1
fi

if [ -n "$bad" ]; then
    n=$(printf '%s' "$bad" | grep -c .)
    echo "FAIL: код возврата берётся у последней команды, а не у явного exit — тестов: $n из $seen"
    printf '%s' "$bad" | head -10
    [ "$n" -gt 10 ] && echo "  … и ещё $((n - 10))"
    FAIL=1
else
    PASS=1
fi

echo "test_tests_exit_explicit: $PASS passed, $FAIL failed (просмотрено $seen)"
exit "$FAIL"
