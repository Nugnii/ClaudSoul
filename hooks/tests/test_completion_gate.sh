#!/usr/bin/env bash
# test_completion_gate.sh — закрытие судит команда пункта, а не отчёт (эскалация
# pattern-completion-by-internal-proxy). Красное ☑ называется, зелёное молчит,
# контракт не вменяется задним числом, кэш по mtime не гоняет неизменное.
set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
HOOK="$HOOKS_DIR/completion-gate.sh"
PASS=0; FAIL=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/state"

mk_backlog() { # $1 файл
    cat > "$1" <<'EOF'
# BACKLOG

### D300 ☑ зелёное закрытие
**Результат.** мир в порядке
**Проверка.** `true` → 0

### D301 ☑ красное закрытие
**Результат.** заявлено, но неправда
**Проверка.** `false` → 0

### D150 ☑ историческое, до контракта
**Проверка.** `false` → 0

### D302 ☐ открытый пункт
**Проверка.** `false` → 0

### D303 ☑ без строки проверки — предмет архиватора
**Результат.** есть только результат
EOF
}

# Гейт с 12 сентября 2026 доставляет ТОЛЬКО в очередь pending-alerts.txt: systemMessage снят,
# потому что в мобильном клиенте он рендерится построчно и превращал перечень пунктов в
# простыню. Поэтому run() отдаёт содержимое очереди, а не stdout — ноги ниже остаются про
# ПРЕДМЕТ (какие пункты названы), а не про канал доставки.
run() { # $1 backlog, $2 cwd, $3 явный локальный бэклог (необязательно)
    # Очередь чистится ПЕРЕД вызовом, а не после: ноги ниже читают то, что добавил ИМЕННО
    # этот вызов. Дроссель гейта при этом живёт в своём файле и повторный вызов гасит сам —
    # ноги T4/T5 про кэш и повтор остаются про кэш, а не про остаток очереди.
    : > "$TMP/state/pending-alerts.txt" 2>/dev/null || true
    printf '{"session_id":"cg1","cwd":"%s"}' "${2:-/}" \
      | env CG_BACKLOG="$1" CG_LOCAL_BACKLOG="${3:-}" STATE_DIR="$TMP/state" \
        bash "$HOOK" >/dev/null 2>&1
    cat "$TMP/state/pending-alerts.txt" 2>/dev/null
}
# Дроссель гейта дедуплицирует по СОСТАВУ расхождения в пределах сессии. Тестам нужен
# каждый вызов как самостоятельное событие, поэтому дроссель сбрасывается вместе с очередью.
reset_throttle() { rm -f "$TMP/state"/completion-gate-fired-*.jsonl 2>/dev/null || true; }

# --- T1: красное ☑ названо, зелёное/открытое/историческое/без-строки молчат ---
mk_backlog "$TMP/BACKLOG.md"
OUT=$(run "$TMP/BACKLOG.md")
grep -q 'D301' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T1 красное не названо]: $OUT"; }
for id in D300 D150 D302 D303; do
    grep -q "$id" <<< "$OUT" && { FAIL=$((FAIL+1)); echo "FAIL [T1 лишний $id]"; } || PASS=$((PASS+1))
done

# --- T2: сообщение несёт исполнимую альтернативу ---
# Прежде нога требовала JSON с полем systemMessage. Канал снят 12 сентября 2026 (в мобильном
# клиенте он рендерился построчно), и предмет ноги вернулся к сути: в тексте обязана стоять
# названная альтернатива, иначе напоминание говорит «плохо» и не говорит «что делать».
grep -q 'верни метке ◐' <<< "$OUT" \
    && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T2 альтернатива не названа]: $OUT"; }

# --- T3: файл только с зелёными ☑ молчит и кэшируется по mtime ---
cat > "$TMP/GREEN.md" <<'EOF'
### D310 ☑ зелёное
**Проверка.** `true` → 0
EOF
OUT=$(run "$TMP/GREEN.md")
[ -z "$OUT" ] && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T3 зелёный молчит]: $OUT"; }
ls "$TMP/state"/completion-gate-*.ok >/dev/null 2>&1 && PASS=$((PASS+1)) \
    || { FAIL=$((FAIL+1)); echo "FAIL [T3 кэш не записан]"; }

# --- T4: кэш держит — подмена команды на красную БЕЗ смены mtime не гоняется ---
_OLD_TS=$(date -v-20M '+%Y%m%d%H%M' 2>/dev/null || date -d '20 minutes ago' '+%Y%m%d%H%M' 2>/dev/null)
touch -t "${_OLD_TS}" "$TMP/GREEN.md" 2>/dev/null
OUT=$(run "$TMP/GREEN.md"); MT_BEFORE=$OUT
sed -i.bak 's/`true`/`false`/' "$TMP/GREEN.md" && rm -f "$TMP/GREEN.md.bak"
touch -t "${_OLD_TS}" "$TMP/GREEN.md" 2>/dev/null   # тот же mtime — кэш обязан молчать
OUT=$(run "$TMP/GREEN.md")
[ -z "$OUT" ] && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T4 кэш не держит]: $OUT"; }
touch "$TMP/GREEN.md"                                # mtime сменился — красное всплывает
OUT=$(run "$TMP/GREEN.md")
grep -q 'D310' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T4 смена mtime не перечитала]: $OUT"; }

# --- T5: красный файл кэш не получает — каждый Stop напоминает, пока не починено ---
# Дроссель сбрасывается между вызовами: его предмет — не повторять ОДНО И ТО ЖЕ в одной
# сессии, а предмет ноги — отсутствие КЭША у красного файла. Без сброса нога мерила бы
# дроссель и была бы ложно-красной.
mk_backlog "$TMP/RED2.md"
run "$TMP/RED2.md" >/dev/null
reset_throttle
OUT=$(run "$TMP/RED2.md")
grep -q 'D301' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T5 красное закэшировалось]"; }

# --- T6: локальный бэклог проекта сессии — граница доверия по ИСТОЧНИКУ ПУТИ (D244) ---
# До 1 сентября 2026 этот тест закреплял обратное: бэклог, найденный по cwd, исполнялся.
# Ровно это и было дефектом — команда «Проверки» идёт через `bash -c`, и чужой
# склонированный репозиторий исполнял свою строку на первом Stop. Прежний контракт снят
# вместе с починкой; покрытие обоих случаев сохранено двумя проверками вместо одной.
mkdir -p "$TMP/proj/.git"
cat > "$TMP/proj/BACKLOG.md" <<'EOF'
### D320 ☑ локальное красное
**Проверка.** `false` → 0
EOF
# T6a: путь из cwd — не исполняется, и пропуск НАЗВАН (молчание было бы неотличимо от «чисто»).
OUT=$(run "$TMP/BACKLOG.md" "$TMP/proj")
grep -q 'D320' <<< "$OUT" && { FAIL=$((FAIL+1)); echo "FAIL [T6a исполнил недоверенный]: $OUT"; } || PASS=$((PASS+1))
grep -q 'не исполнено' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T6a пропуск не назван]: $OUT"; }
# T6b: путь назван явно — исполняется, красное локальное видно.
rm -f "$TMP/state"/completion-gate-*.ok
OUT=$(run "$TMP/BACKLOG.md" "$TMP/proj" "$TMP/proj/BACKLOG.md")
grep -q 'D320' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T6b явный локальный бэклог]: $OUT"; }

# --- T7: тихая деградация — бэклога нет, пустой stdin ---
OUT=$(run "$TMP/nope.md"); RC=$?
[ "$RC" -eq 0 ] && [ -z "$OUT" ] && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T7 деградация]"; }
OUT=$(printf '' | env CG_BACKLOG="$TMP/BACKLOG.md" STATE_DIR="$TMP/state" bash "$HOOK" 2>/dev/null); RC=$?
[ "$RC" -eq 0 ] && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T7 пустой stdin]"; }

# --- T8: закрытие слепой командой названо в ТОЙ ЖЕ сессии (13 сентября 2026) ---
# У метки «судит по форме» неотвратимость держит архиватор (☑ с меткой не переносит), но
# ходит он раз в семь дней — узнать о слепом закрытии через неделю значит узнать поздно.
# Канал ОТДЕЛЬНЫЙ от красного ☑ и от #CG_OPEN: там «команда дала не-0» и «у открытого
# прибор не о том», здесь третье — команда дала 0, а смотрела на имя файла. Ноги судят
# ПОВЕДЕНИЕ гейта на фикстуре, не текст хука.
reset_throttle
cat > "$TMP/FORM.md" <<'EOF'
### D520 ☑ закрыт слепой командой
**Результат.** объявлено сделанным
**Проверка.** `true` → 0
**Зелёная сторона.** каталог с файлом такого имени → 0. Метка: судит по форме.

### D521 ☑ закрыт прибором
**Результат.** мир изменён
**Проверка.** `true` → 0
**Зелёная сторона.** фикстура `green_D521`, прибор отдаёт 0.

### D522 ☐ открытый с меткой — предмет не этого канала
**Проверка.** `false` → 0
**Зелёная сторона.** заглушка со словом. Метка: судит по форме.
EOF
OUT=$(run "$TMP/FORM.md")
grep -q 'D520' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T8a слепое закрытие не названо]: $OUT"; }
grep -q 'судит по форме' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T8b причина не названа]: $OUT"; }
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: закрытый прибором молчит, открытый с меткой в этот канал не идёт
grep -q 'D521' <<< "$OUT" && { FAIL=$((FAIL+1)); echo "FAIL [T8c непомеченный назван]: $OUT"; } || PASS=$((PASS+1))
grep -q 'D522' <<< "$OUT" && { FAIL=$((FAIL+1)); echo "FAIL [T8d открытый попал в канал закрытий]: $OUT"; } || PASS=$((PASS+1))
# альтернатива названа — иначе напоминание говорит «плохо» и не говорит «что делать»
grep -q 'замени команду' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T8e альтернатива не названа]: $OUT"; }
# ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: сними метку — канал молчит. Признак именно в ней, а не в пункте.
reset_throttle; rm -f "$TMP/state"/completion-gate-*.ok
python3 - "$TMP/FORM.md" <<'PY2'
import sys, pathlib
p = pathlib.Path(sys.argv[1])
p.write_text(p.read_text().replace(" Метка: судит по форме.", " Прибор отдаёт 0.", 1))
PY2
OUT=$(run "$TMP/FORM.md")
grep -q 'D520' <<< "$OUT" && { FAIL=$((FAIL+1)); echo "FAIL [T8f со снятой меткой всё ещё назван]: $OUT"; } || PASS=$((PASS+1))

# --- T9: находки прожарки 13 сентября 2026 (⊘, состав дросселя, телеметрия) ---
# T9a: ⊘ с меткой называется. Отказ от работы с ослепшим критерием — то же непроверенное
# утверждение, что слепое ☑; прежняя редакция отсекала ⊘ раньше проверки метки и молчала.
reset_throttle; rm -f "$TMP/state"/completion-gate-*.ok
cat > "$TMP/WAIVED.md" <<'EOF'
### D530 ⊘ отказ от работы
**Вердикт.** цена отказа названа.
**Зелёная сторона.** заглушка с именем. Метка: судит по форме.
EOF
OUT=$(run "$TMP/WAIVED.md")
grep -q 'D530' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T9a ⊘ с меткой не назван]: $OUT"; }

# T9b: СОСТАВ дросселя несёт канал, а не только номера. Сценарий прожарки: на первом Stop
# пункт открыт и его «Проверка» зелена, на втором он закрыт слепой командой. Номер тот же,
# утверждение другое — прежний ключ («D540,») гасил вторую находку целиком.
reset_throttle; rm -f "$TMP/state"/completion-gate-*.ok
cat > "$TMP/CHAN.md" <<'EOF'
### D540 ☐ открытый, «Проверка» позеленела
**Проверка.** `true` → 0
**Зелёная сторона.** заглушка со словом. Метка: судит по форме.
EOF
OUT1=$(run "$TMP/CHAN.md")
grep -q 'ОТКРЫТОГО' <<< "$OUT1" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T9b1 открытый с зелёной не назван]: $OUT1"; }
# тот же пункт закрывают слепой командой — канал меняется, номер нет
python3 - "$TMP/CHAN.md" <<'PY2'
import sys, pathlib
p = pathlib.Path(sys.argv[1]); p.write_text(p.read_text().replace("☐ открытый, «Проверка» позеленела", "☑ закрыт слепой командой"))
PY2
rm -f "$TMP/state"/completion-gate-*.ok
OUT2=$(run "$TMP/CHAN.md")
grep -q 'судит по форме' <<< "$OUT2" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T9b2 смена канала погашена дросселем]: $OUT2"; }

# T9c: закрытие, объявленное слепым, не подтверждает точность признака #CG_OPEN.
# Прежде гейт в ОДНОМ прогоне печатал «закрыт слепой командой» и ставил тому же пункту
# outcome=confirmed — телеметрия получала подтверждение от закрытия, которое сама объявила
# несостоявшимся (дословный повтор дефекта, чиненного здесь 3 сентября 2026).
_FIRED="$TMP/state/cg-open-fired.jsonl"
grep -q '"item": *"D540"' "$_FIRED" 2>/dev/null || grep -q '"item":"D540"' "$_FIRED" 2>/dev/null
if [ -s "$_FIRED" ]; then
    python3 - "$_FIRED" <<'PY3'
import json, sys
bad = [r for r in (json.loads(l) for l in open(sys.argv[1], encoding="utf-8") if l.strip())
       if r.get("item") == "D540" and r.get("outcome") == "confirmed"]
sys.exit(1 if bad else 0)
PY3
    [ $? -eq 0 ] && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T9c слепое закрытие подтвердило точность признака]"; }
else
    PASS=$((PASS+1))   # журнала нет — подтверждать нечем, что и требовалось
fi

# --- T10: разбор, не увидевший ни одного пункта, — не «чисто» (13 сентября 2026) ---
# Незакрытый забор кода гасит остаток файла: `items` пуст, и красное ☑ под забором не судится
# ничем, а наружу не идёт ни слова. Молчание тут неотличимо от «проверено, чисто» — род B.
reset_throttle; rm -f "$TMP/state"/completion-gate-*.ok
printf '# BACKLOG\n\n```\nнезакрытый забор\n\n### D800 ☑ закрытый пункт\n**Проверка.** `false` → 0\n' > "$TMP/BROKEN.md"
OUT=$(run "$TMP/BROKEN.md")
grep -q 'НИ ОДНОГО пункта' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T10a слепой разбор промолчал]: $OUT"; }
grep -q 'забор' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T10b причина не названа]: $OUT"; }
# ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: пустой бэклог законен — пунктов нет ни в сыром, ни в очищенном.
reset_throttle; rm -f "$TMP/state"/completion-gate-*.ok
printf '# BACKLOG\n\nпунктов пока нет.\n' > "$TMP/EMPTY.md"
OUT=$(run "$TMP/EMPTY.md")
grep -q 'НИ ОДНОГО' <<< "$OUT" && { FAIL=$((FAIL+1)); echo "FAIL [T10c пустой бэклог объявлен слепым]: $OUT"; } || PASS=$((PASS+1))
# и закрытый забор тот же пункт показывает — значит нога про забор, а не про заготовку
reset_throttle; rm -f "$TMP/state"/completion-gate-*.ok
printf '# BACKLOG\n\n```\nзакрытый забор\n```\n\n### D800 ☑ закрытый пункт\n**Проверка.** `false` → 0\n' > "$TMP/FENCED.md"
OUT=$(run "$TMP/FENCED.md")
grep -q 'D800' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T10d при закрытом заборе пункт не найден]: $OUT"; }

# --- T11: возраст пункта судится ОДНИМ правилом с архиватором (13 сентября 2026) ---
# Оба потребителя объявляли правило порога единым и держали его своими шаблонами: на `D101a`
# архиватор (префикс) считал пункт историческим, гейт (строгая форма) — нет, то есть подномер
# старого пункта судился контрактом только здесь. Владелец шаблона теперь один
# (`BACKLOG_ID_NUM_RE`), и нога держит совпадение ПОВЕДЕНИЯ, а не текста выражения.
reset_throttle; rm -f "$TMP/state"/completion-gate-*.ok
cat > "$TMP/AGE.md" <<'EOF'
### D101a ☑ подномер исторического пункта, красная команда
**Проверка.** `false` → 0

### D501 ☑ новый пункт, красная команда
**Проверка.** `false` → 0
EOF
OUT=$(run "$TMP/AGE.md")
grep -q 'D101a' <<< "$OUT" && { FAIL=$((FAIL+1)); echo "FAIL [T11a подномер старого пункта не освобождён порогом]: $OUT"; } || PASS=$((PASS+1))
grep -q 'D501' <<< "$OUT" && PASS=$((PASS+1)) || { FAIL=$((FAIL+1)); echo "FAIL [T11b новый пункт освобождён порогом]: $OUT"; }

echo "completion-gate: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
