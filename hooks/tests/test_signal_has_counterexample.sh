#!/usr/bin/env bash
# test_signal_has_counterexample.sh — у лексического признака объявлен КОНТРПРИМЕР (D102).
#
# Результат: в hooks/ нет лексических признаков без объявленного случая, который они не ловят.
# Проверка результата: этот тест; красный — значит признаки без контрпримера есть.
#
# Повод — три случая за сутки 28 августа 2026, все в коде, написанном в тот же день, при
# уже известном pattern-subject-checked-by-enumeration (confidence 5):
#   (1) признак находки — перечень 17 форм, промахнулся на «поймал»;
#   (2) контракт инструмента — засчитал строку внутри docstring;
#   (3) признак записи — искал символ «>» и поймал его в «2>&1», отказав в чтении.
#
# Цепочка до корня. Перечень пишется сразу, правило требует сформулировать порождающее
# условие. В момент постройки перед глазами один-два примера, и они перечнем описываются
# полностью; признак строится ОТ НАБЛЮДЁННЫХ случаев, и множество случаев в этот момент
# равно множеству наблюдений. КОРЕНЬ: нет обязательного шага «назови случай, который этот
# признак пропустит». Контракт ниже и есть этот шаг.
#
# КОНТРПРИМЕР самого стража: он видит переменную, чьё ЗНАЧЕНИЕ содержит альтернативы, и
# НЕ видит альтернативы, вписанные прямо в вызов grep. Названо намеренно — страж,
# скрывающий свою границу, воспроизводит ровно тот дефект, который ловит.
#
# Расширен 28 августа 2026 по собственному промаху: первая редакция искала только имена
# вида `NAME_RE=` и прошла мимо `FIRE_PATTERNS=`/`SILENT_PATTERNS=` в `test_guards_provable`
# — список форм в имени переменной оказался тем же перечнем, который страж и ловит.
# ВЕРДИКТ О ГРАНИЦЕ ОБЛАСТИ (D107, закрыт 29 августа 2026 замером, а не расширением).
#
# Область этого требования — `hooks/*.sh`, и это НЕ недоделка. Дважды промерено, что
# расширять нечем:
#
# 1. Тот же признак вне `hooks/*.sh`. Прогон по всему дереву: 10 совпадений, ложных 10,
#    точность 0. Совпадали сообщения об использовании (`ARM="${1:?плечо: full|core|vanilla}"`
#    в `scripts/ablation/env-diff.sh:16` и `shadow-run.sh:19`), труба внутри подстановки
#    команды (`scripts/launchd-freshness.sh:44`) и разделители полей в тестовых фикстурах
#    (`hooks/tests/test_cross_contour_consumer.sh`, 7 совпадений). Внутри `hooks/*.sh`
#    признак работает потому, что там держится СОГЛАШЕНИЕ: заглавная константа с
#    альтернативами и есть словарь. Признак локален по построению, а не по недосмотру.
#
# 2. Широкая замена «файл решает класс по совпадению текста» (`grep -qE`,
#    `re.search|match|compile`): 86 файлов при 13 с объявленным контрпримером — 73 отказа
#    разом. Это не страж, а фон.
#
# Отдельно: повод, из которого D107 родился, ЭТИМ признаком не ловится вовсе.
# `SNAPSHOT_MARK` (`scripts/dep-index.py:84`) — простая строковая константа без
# альтернатив, и ни один `.py` в дереве под форму не подходит. То есть область узка
# дважды: по файлу и по синтаксической форме признака, — и вторая граница неустранима без
# признака «заменитель класса», которого при нынешних средствах нет.
#
# Условие снятия вердикта: появился признак «заменитель класса», чья точность вне
# `hooks/*.sh` измерена и не ниже, чем внутри. Тогда требование распространяется по нему,
# а этот блок снимается.

set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO" || exit 1

PASS=0; FAIL=0
missing=""
for f in hooks/*.sh; do
    [ -f "$f" ] || continue
    # Признак — переменная, чьё значение несёт альтернативы, независимо от её ИМЕНИ.
    grep -qE '^[A-Z_]+="[^"]*\|[^"]*\|' "$f" || continue
    base=$(basename "$f" .sh)
    # Контрпример принимается в самом хуке ЛИБО в его тесте: важно, что он назван.
    if grep -q 'КОНТРПРИМЕР' "$f" 2>/dev/null; then continue; fi
    if ls hooks/tests/test_*"${base//-/_}"*.sh >/dev/null 2>&1 \
       && grep -lq 'КОНТРПРИМЕР' hooks/tests/test_*"${base//-/_}"*.sh 2>/dev/null; then continue; fi
    missing="$missing $f"
done

if [ -z "${missing# }" ]; then
    PASS=$((PASS+1))
else
    FAIL=$((FAIL+1))
    echo "FAIL: лексические признаки без объявленного контрпримера:"
    for f in $missing; do echo "  · $f"; done
    echo "  Добавь строку рядом с признаком:"
    echo "    # КОНТРПРИМЕР: <случай, который признак НЕ ловит и это известно>"
    echo "  Не пишется — признак не правило, а перечень наблюдённых форм."
fi

# Отрицательный контроль: страж обязан ловить признак без контрпримера.
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
printf 'FOO_PATTERNS="a|b|c"\n' > "$TMP/fake.sh"
if grep -qE '^[A-Z_]+="[^"]*\|[^"]*\|' "$TMP/fake.sh" && ! grep -q 'КОНТРПРИМЕР' "$TMP/fake.sh"; then
    PASS=$((PASS+1))
else
    FAIL=$((FAIL+1)); echo "FAIL: признак без контрпримера не опознаётся"
fi

echo ""
echo "signal counterexample tests: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
