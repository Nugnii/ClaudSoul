#!/usr/bin/env bash
# test_setup_call_guard.sh — свидетель реестра `scripts/setup-call-guard.py`.
#
# ЗАЧЕМ ОН ЕСТЬ. Замер `instrument-result-measured` 19 сентября 2026 назвал этот прибор
# ЕДИНСТВЕННЫМ инструментом дерева без свидетеля: 99 измерено из 100. Прибор построен в
# тот же день (D465), а его зелёная сторона снята при закрытии пункта — вместе с ней
# исчёз и тот, кто подтверждал объявленный результат. Объявленный результат без свидетеля
# держится на слове автора: выпотрошенный прибор (`exit 0`) отвечал бы «носителей 0» так
# же, как исправный на чистом дереве.
#
# ПРЕДМЕТ СВИДЕТЕЛЯ — РАЗЛИЧЕНИЕ, а не согласие: прибор обязан НАЗВАТЬ носителя там, где
# отказ подготовки нем, и ПРОМОЛЧАТЬ там, где код читается. Обе стороны судятся на своей
# фикстуре в песочнице; рабочее дерево не читается (`--root` указывает в песочницу).
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
TOOL="$REPO/scripts/setup-call-guard.py"
[ -f "$TOOL" ] || { echo "FAIL: нет $TOOL"; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

PASS=0
FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d) || { echo "FAIL: нет временного каталога"; exit 1; }
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/hooks/tests" || exit 1

# --- T1: НЕМОЙ отказ подготовки назван -----------------------------------------------
# Форма взята из мира: `cp … 2>/dev/null` без чтения кода — ровно то, ради чего прибор
# написан. Свидетель продолжил бы работу на несобранной фикстуре и судил бы не то.
cat > "$TMP/hooks/tests/test_mute_fixture.sh" <<'FIX'
#!/usr/bin/env bash
set -uo pipefail
TMP=$(mktemp -d)
cp "$REPO/hooks/some-lib.sh" "$TMP/" 2>/dev/null
echo "проверка идёт дальше"
FIX
OUT1=$(python3 "$TOOL" --root "$TMP" 2>&1); RC1=$?
N1=$(python3 "$TOOL" --root "$TMP" --count 2>/dev/null)
if [ "${N1:-0}" -ge 1 ]; then ok; else bad "T1 немой отказ не назван" "--count дал '${N1}', вывод: $OUT1"; fi
if grep -q 'test_mute_fixture.sh' <<< "$OUT1"; then ok; else bad "T1b носитель не назван поимённо" "$OUT1"; fi

# --- T2: ЧИТАЕМЫЙ код — не носитель ---------------------------------------------------
# Отрицательный класс: та же команда, но код читается. Без этой ноги прибор, называющий
# носителем ЛЮБОЙ `cp`, прошёл бы T1 и был бы бесполезен.
rm -f "$TMP/hooks/tests/test_mute_fixture.sh"
cat > "$TMP/hooks/tests/test_loud_fixture.sh" <<'FIX'
#!/usr/bin/env bash
set -uo pipefail
TMP=$(mktemp -d)
cp "$REPO/hooks/some-lib.sh" "$TMP/" 2>/dev/null || { echo "фикстура не собралась"; exit 1; }
echo "проверка идёт дальше"
FIX
N2=$(python3 "$TOOL" --root "$TMP" --count 2>/dev/null)
if [ "${N2:-1}" = "0" ]; then ok; else bad "T2 читаемый код назван носителем" "--count дал '${N2}'"; fi

# --- T3: пустое дерево — ноль, а не отказ ---------------------------------------------
rm -f "$TMP/hooks/tests/test_loud_fixture.sh"
N3=$(python3 "$TOOL" --root "$TMP" --count 2>/dev/null); RC3=$?
if [ "${N3:-x}" = "0" ] && [ "$RC3" = "0" ]; then ok; else bad "T3 пустое дерево" "count='${N3}' rc=$RC3"; fi

# --- T4: `--fix` ставит сторож, и после него прибор молчит ----------------------------
# Предмет ноги — не текст правки, а ИСХОД: место перестаёт быть носителем, и файл остаётся
# синтаксически целым (иначе «починка» ломает свидетеля молча).
cat > "$TMP/hooks/tests/test_fixable.sh" <<'FIX'
#!/usr/bin/env bash
set -uo pipefail
TMP=$(mktemp -d)
mkdir -p "$TMP/sub" 2>/dev/null
echo "дальше"
FIX
# Отказ ГРОМКИЙ, хотя он ловился и ниже. `--fix` здесь не подготовка, а сам судимый
# прибор, и его падение обнаруживалось косвенно — следующей ногой через `--count`. Разница
# в том, ЧТО прочтёт читатель: «после --fix носитель остался» уводит искать дефект в
# признаке, тогда как прибор просто не запустился. Свой же страж это и назвал.
python3 "$TOOL" --root "$TMP" --fix >/dev/null 2>&1 \
    || { echo "FAIL T4: --fix не отработал (код $?) — судить о его результате нечем"; exit 1; }
N4=$(python3 "$TOOL" --root "$TMP" --count 2>/dev/null)
if [ "${N4:-1}" = "0" ]; then ok; else bad "T4 после --fix носитель остался" "--count дал '${N4}'"; fi
if bash -n "$TMP/hooks/tests/test_fixable.sh" 2>/dev/null; then ok; else bad "T4b --fix сломал синтаксис" "$(bash -n "$TMP/hooks/tests/test_fixable.sh" 2>&1 | head -2)"; fi

# --- T5: рабочее дерево не подменяется песочницей --------------------------------------
# Прибор обязан читать ТОТ корень, который назван: без этого ноги выше судили бы живое
# дерево, а песочница ничего не значила бы.
N5=$(python3 "$TOOL" --root "$REPO" --count 2>/dev/null)
if [ -n "$N5" ] && [ "$N5" -ge 0 ] 2>/dev/null; then ok; else bad "T5 живой корень не прочитан" "count='${N5}'"; fi

# --- T6: на живом дереве немых подготовительных вызовов нет (D1194) ---
# Закрытие D465 стояло на разовом `--fix`: за месяц новые свидетели принесли 80 носителей, и увидел их только сверщик
# архива. Нога зовёт пробу пункта в каждом прогоне набора — новый носитель краснит прогон, в котором появился.
P1194=$(CLAUDSOUL_REPO="$REPO" bash "$REPO/hooks/tests/fixtures/probe_D1194.sh" 2>&1); RC1194=$?
if [ "$RC1194" -eq 0 ]; then ok; else bad "T6 немые подготовительные вызовы в свидетелях (код $RC1194)" "$P1194"; fi

# --- T7: судится каждая команда строки, а не начало (D1219) ---
# Признак видел вызов только первым словом строки: `K=…; bash … --install … >/dev/null 2>&1` молчал, а разбор heredoc
# без кавычек прятал хвосты файлов — 74 места в 34 свидетелях; страж прошлого `--fix` вставал в конец строки и накрывал
# не ту команду. Проба судит признак и `--fix` на песочнице.
P1219=$(CLAUDSOUL_REPO="$REPO" bash "$REPO/hooks/tests/fixtures/probe_D1219.sh" 2>&1); RC1219=$?
if [ "$RC1219" -eq 0 ]; then ok; else bad "T7 команда после ';' (код $RC1219)" "$P1219"; fi

echo "---"
echo "setup call guard: PASS=$PASS FAIL=$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
