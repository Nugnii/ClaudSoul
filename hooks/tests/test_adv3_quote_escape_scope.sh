#!/usr/bin/env bash
# test_adv3_quote_escape_scope.sh — адверсариальный раунд 3: допущение шапки
# `command-scope-lib.sh` («имя команды никогда не бывает внутри кавычек») и
# обработка обратного слеша.
#
#   A5  `"$(git commit …)"` / `"`git commit …`"` — подстановка команд ВНУТРИ двойных
#       кавычек исполняется, это не аргумент. Кавычки вырезаются целиком, команда теряется.
#   A6  `'…\'` — внутри одинарных кавычек обратный слеш НЕ экранирует, закрывающая
#       кавычка закрывает строку. Сканер же обрабатывает `\` раньше проверки `in_s`,
#       съедает закрывающую кавычку — и остаток команды считается содержимым строки.
#   A7  `\rm -rf …`, `\git commit …` — приём обхода алиаса. Экранированный символ
#       заменяется пробелом вместе с самим собой: от `\rm` остаётся ` m`.
#   A8  битый байт UTF-8 роняет awk (BWK awk на macOS: «towc: multibyte conversion
#       failure», код 2), и запасной путь `|| printf '%s' "$1"` печатает СЫРУЮ команду.
#       Отказ открытый: сужение области отключается целиком, поведение откатывается
#       к дофиксовому — стражи снова видят содержимое кавычек как команды.
#
# Тесты написаны, чтобы УПАСТЬ на текущем коде. Ничего не чинят.
#
# Достижимость замерена по 18 579 реальным вызовам Bash из ~/.claude/projects:
#   A5 — форма `"$(` встречается 402 раза, обратные кавычки внутри двойных — 254;
#        с охраняемой подписью внутри — 0 (оба кандидата оказались markdown-разметкой
#        в теле python-heredoc, а не подстановкой команд);
#   A6 — 0 (все 6 совпадений оказались телом python-heredoc, не shell-строкой);
#   A7 — 0; A8 — 0 байт вне UTF-8 во всём корпусе, и JSON-транспорт их не пропустит
#        (jq отвергает неполную суррогатную пару), поэтому A8 проверяется только на
#        библиотеке — до хука такой вход не доходит.

set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
command -v jq >/dev/null 2>&1 || { echo "SKIP: jq недоступен"; exit 0; }

PASS=0
FAIL=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/state"

# shellcheck source=/dev/null
source "$HOOKS_DIR/command-scope-lib.sh"

# LC_ALL=C намеренно: в UTF-8 локали `tr` спотыкается о битый байт из A8 и печатает
# «Illegal byte sequence» вместо строки. Тот же класс, что ломает сам разбор.
_show() { printf '%s' "$1" | LC_ALL=C tr '\n' '~' | LC_ALL=C tr -c '[:print:]~' '?'; }

yes_() { # $1=команда $2=имя — is_git_commit ДОЛЖЕН распознать
    if is_git_commit "$1"; then PASS=$((PASS + 1))
    else FAIL=$((FAIL + 1))
        echo "FAIL [$2]: настоящий коммит НЕ распознан"
        echo "       вход: $(_show "$1")"
        echo "       executable_part: [$(_show "$(executable_part "$1")")]"
    fi
}
exec_has() { # $1=команда $2=подстрока $3=имя
    local e; e=$(executable_part "$1")
    if LC_ALL=C grep -qF -- "$2" <<< "$e"; then PASS=$((PASS + 1))
    else FAIL=$((FAIL + 1))
        echo "FAIL [$3]: исполняемая часть потеряла «$2»"
        echo "       вход: $(_show "$1")"
        echo "       executable_part: [$(_show "$e")]"
    fi
}
exec_lacks() { # $1=команда $2=подстрока $3=имя
    local e; e=$(executable_part "$1")
    if LC_ALL=C grep -qF -- "$2" <<< "$e"; then FAIL=$((FAIL + 1))
        echo "FAIL [$3]: текст «$2» попал в исполняемую часть"
        echo "       вход: $(_show "$1")"
        echo "       executable_part: [$(_show "$e")]"
    else PASS=$((PASS + 1)); fi
}

_run() { # $1=хук $2=команда $3=sid
    jq -cn --arg c "$2" --arg s "$3" \
        '{session_id:$s, transcript_path:"", cwd:"/tmp", tool_name:"Bash", tool_input:{command:$c}}' \
        | STATE_DIR="$TMP/state" bash "$HOOKS_DIR/$1" 2>/dev/null
}
hook_fires() { # $1=хук $2=команда $3=имя
    if [ -n "$(_run "$1" "$2" "$(printf '%s' "$3" | tr -cd '[:alnum:]-' | head -c 40)")" ]; then
        PASS=$((PASS + 1))
    else FAIL=$((FAIL + 1)); echo "FAIL [$3]: $1 промолчал на настоящем действии"
        echo "       executable_part: [$(_show "$(executable_part "$2")")]"; fi
}

# ===========================================================================
echo "=== АТАКА 5: подстановка команд внутри двойных кавычек ==="
# `"$( … )"` — не аргумент: внутренняя команда исполняется в текущей оболочке.
A5A='MSG="$(git commit -m "правка" 2>&1)"'
A5B='OUT="$(git push --force origin main)"'
A5C='echo "итог: `git commit -m x`"'
yes_ "$A5A" "A5-a  git commit внутри \"\$( … )\""
exec_has "$A5B" 'git push' "A5-b  git push внутри \"\$( … )\""
yes_ "$A5C" "A5-c  git commit в обратных кавычках внутри двойных"

# ===========================================================================
echo "=== АТАКА 6: обратный слеш перед закрывающей одинарной кавычкой ==="
# Внутри `'…'` обратный слеш — обычный символ; `'` за ним ЗАКРЫВАЕТ строку.
# Сканер съедает эту кавычку и считает остаток команды содержимым строки.
A6A='echo '"'"'путь C:\'"'"' && git commit -m "правка"'
A6B='printf %s '"'"'C:\'"'"' ; rm -rf /tmp/adv3-old'
yes_ "$A6A" "A6-a  git commit после строки, кончающейся слешем"
exec_has "$A6B" 'rm -rf' "A6-b  rm -rf после строки, кончающейся слешем"

# ===========================================================================
echo "=== АТАКА 7: обход алиаса обратным слешем ==="
# `\rm` и `\git` — законный приём: слеш отключает алиас, запускается сам файл.
# Сканер заменяет пару «слеш + следующий символ» пробелом: от `\rm` остаётся ` m`.
A7A='\git commit -m "правка"'
A7B='\rm -rf /tmp/adv3-old'
yes_ "$A7A" "A7-a  \\git commit"
exec_has "$A7B" 'rm -rf' "A7-b  \\rm -rf сохранён в исполняемой части"
hook_fires trust-guard.sh "$A7B" "A7-c  trust-guard видит \\rm -rf"

# ===========================================================================
echo "=== АТАКА 8: битый байт роняет awk, запасной путь печатает СЫРУЮ команду ==="
# Проверяется только библиотека: до хука такой вход не доходит — команда едет в
# JSON, а jq неполную последовательность не пропускает. Отказ важен формой:
# «не смог разобрать» превращается в «разбирать не будем», то есть в дофиксовое
# поведение, а не в безопасное молчание.
A8=$(printf 'echo "a\377b rm -rf /tmp/adv3-old" > /tmp/adv3-note3.txt')
exec_lacks "$A8" 'rm -rf' "A8-a  содержимое кавычек вырезано и при битом байте"
A8B=$(printf 'echo "\377 git commit -m x"')
exec_lacks "$A8B" 'git commit' "A8-b  то же для подписи коммита"

echo ""
echo "adv3 quote/escape scope: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
