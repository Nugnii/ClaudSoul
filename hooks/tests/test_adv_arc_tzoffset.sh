#!/usr/bin/env bash
# test_adv_arc_tzoffset.sh — атака на `iso_epoch` (hooks/portable-lib.sh:37).
#
# ЧТО ДОКАЗЫВАЕТСЯ. Метка ISO-8601 со СМЕЩЕНИЕМ часового пояса (`+03:00`, `-05:00`)
# разбирается так, будто смещения нет: цифры читаются как ЛОКАЛЬНОЕ время машины, а
# суффикс отбрасывается. Следствие проверяемо без знания часового пояса бегуна:
# `22:28:52+03:00` и `22:28:52-05:00` — два РАЗНЫХ мгновения (8 часов между ними) —
# получают ОДНО И ТО ЖЕ число. Ноль в таком случае был бы честнее: он говорит «не
# разобрал». Здесь функция возвращает правдоподобное число и молчит.
#
# Утверждения ниже не зависят от TZ бегуна: сравниваются разности между метками,
# описывающими одно и то же мгновение, а не абсолютные величины.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

# shellcheck source=/dev/null
. "$REPO/hooks/portable-lib.sh"

Z=$(iso_epoch "2026-09-07T22:28:52Z")
P3=$(iso_epoch "2026-09-07T22:28:52+03:00")
M5=$(iso_epoch "2026-09-07T22:28:52-05:00")
P3F=$(iso_epoch "2026-09-07T22:28:52.211+03:00")

echo "  Z=$Z  +03:00=$P3  -05:00=$M5  +03:00 с долями=$P3F"

# --- T1: два разных мгновения обязаны дать разные числа ---
if [ "$P3" != "$M5" ]; then ok
else bad "T1" "«22:28:52+03:00» и «22:28:52-05:00» разделены 8 часами, а число одно: $P3"; fi

# --- T2: +03:00 — это Z минус 3 часа ---
if [ -n "$Z" ] && [ "$P3" = "$(( Z - 10800 ))" ]; then ok
else bad "T2" "ожидалось $(( ${Z:-0} - 10800 )) (Z-3ч), получено $P3 — смещение отброшено"; fi

# --- T3: -05:00 — это Z плюс 5 часов ---
if [ -n "$Z" ] && [ "$M5" = "$(( Z + 18000 ))" ]; then ok
else bad "T3" "ожидалось $(( ${Z:-0} + 18000 )) (Z+5ч), получено $M5 — смещение отброшено"; fi

# --- T4: доли секунды при смещении срезаются так же, как при Z ---
# Владелец разбора обязан срезать доли ОДИНАКОВО: ветка `*.*Z` их снимает, ветка со
# смещением — нет (sed привязан к концу строки, а строка кончается на «+03:00»).
if [ "$P3F" = "$P3" ]; then ok
else bad "T4" "метка с долями и без дали разные числа: $P3F против $P3"; fi

# --- T5: отрицательный контроль — на метке с Z функция исправна ---
# Без него T1-T4 неотличимы от «функция сломана вообще».
if [ "$Z" != "0" ] && [ "$(iso_epoch '2026-09-07T22:28:52.211Z')" = "$Z" ]; then ok
else bad "T5" "контроль: метка с Z разбирается неверно ($Z) — тест мерит не то"; fi

echo ""
echo "adv-arc tzoffset tests: $PASS/$((PASS+FAIL)) passed"
exit $(( FAIL != 0 ))
