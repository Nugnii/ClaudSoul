#!/usr/bin/env bash
# СУДИТ: hooks/lib/archive_relay.py
# test_archive_relay.sh — отказ архиватора доходит до владельца: отказ, не простоявший срока, молчит; простоявший срок
# ЗАПУСКОВ подряд ставит «СКАЖИ владельцу» с номером и причиной и повторяет её, пока итог хода не назовёт номер; номер,
# названный ДО показа, доставку не гасит; номер — словом (D12710 не засчитывает D1271); отказа нет — состояние снято.
# Срок — в работе, а не в часах (D1352): недели тишины без запусков напоминания не дают, запуски за одну минуту — дают.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
M="$REPO/hooks/lib/archive_relay.py"
PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
[ -f "$M" ] || { echo "FAIL: нет $M"; exit 1; }
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
ST="$T/st.tsv"; NOW=2000000000; DAY=86400; NEED=3
REF=$'Закрытие без показания — в архив не переносится:\n  · D1271: ☑, а его «Зелёная сторона» помечена «судит по форме»\n'
run() { OUT=$(printf '%s' "$1" | python3 "$M" "$ST" "$2" "$NEED" "" "$3"); }
# A1: первый запуск с отказом — тишина, записаны первая встреча и один запуск.
run "$REF" "$NOW" ""
[ -z "$OUT" ] && grep -q '^D1271	2000000000	0	0	.*	1$' "$ST" && ok || bad A1 "свежий отказ — ждали тишину и запись первой встречи с одним запуском: «${OUT}», $(cat "$ST" 2>/dev/null)"
# A1b (D1352): часы срока не двигают — второй запуск через 30 суток молчит, счёт запусков 2.
run "$REF" "$((NOW + 30 * DAY))" "итог без номера"
[ -z "$OUT" ] && grep -q '	2$' "$ST" && ok || bad A1b "тридцать суток по часам при двух запусках дали напоминание либо счёт не 2: «${OUT}», $(cat "$ST")"
# A2: третий запуск подряд — срок вышел; дни в тексте остаются показом.
run "$REF" "$((NOW + 30 * DAY + 1))" "итог без номера"
grep -q 'СКАЖИ владельцу.*D1271 (отказов подряд до 3, висит до 30 дн.).*судит по форме' <<< "$OUT" && ok || bad A2 "отказ, простоявший срок запусков, не назван: «${OUT}»"
run "$REF" "$((NOW + 30 * DAY + 2))" "итог снова без номера, есть D12710"
grep -q 'D1271 (отказов' <<< "$OUT" && ok || bad A3 "напоминание не повторилось (или D12710 засчитан за D1271): «${OUT}»"
run "$REF" "$((NOW + 30 * DAY + 3))" "Архиватор держит D1271: метка «судит по форме»."
[ -z "$OUT" ] && grep -q '^D1271	[0-9]*	1	1	' "$ST" && ok || bad A4 "номер назван — ждали тишину и «назван»: «${OUT}», $(cat "$ST")"
run "" "$((NOW + 30 * DAY + 4))" ""
[ ! -e "$ST" ] && ok || bad A5 "отказа нет — состояние не снято"
# A5b (D1352): отказ ушёл и вернулся — счёт запусков начат заново, первый запуск нового отказа молчит. Журнал отказов
# архиватора при этом НА МЕСТЕ и несёт записи прежнего эпизода — так устроен настоящий ход: архиватор пишет запись
# раньше, чем сборщик зовёт прибор (скептик opus, H1: первая редакция ноги шла без журнала, а счёт через `max` с
# журналом не сбрасывался никогда).
for _h in 01 02 03 04 05; do
    printf '{"ts":"2033-05-18T%s:00:00Z","item":"D1271","why":"x","mode":"run"}\n' "$_h"
done > "$T/backlog-archive-fired-2033-05-18.jsonl"
run "$REF" "$((NOW + 31 * DAY))" ""
[ -z "$OUT" ] && grep -q '	1$' "$ST" && ok || bad A5b "вернувшийся отказ унаследовал прежний счёт (в журнале пять записей): «${OUT}», $(cat "$ST")"
rm -f "$T"/backlog-archive-fired-*.jsonl
# A2c (D1352): запуски за одну минуту срок набирают — три вызова с разницей в секунду дают напоминание.
rm -f "$ST"
run "$REF" "$NOW" ""; run "$REF" "$((NOW + 1))" ""; run "$REF" "$((NOW + 2))" ""
grep -q 'D1271 (отказов подряд до 3, висит до 0 дн.)' <<< "$OUT" && ok || bad A2c "три запуска за три секунды не дали напоминания: «${OUT}»"
# A6: номер назван ДО показа (срок не вышел) — доставка не засчитана, после срока напоминание есть.
rm -f "$ST"
run "$REF" "$NOW" ""; run "$REF" "$((NOW + 100))" "архив: работаю над D1271"
run "$REF" "$((NOW + 200))" "итог без номера"
grep -q 'D1271 (отказов' <<< "$OUT" && ok || bad A6 "номер, названный до показа, погасил доставку: «${OUT}»"
# A7: журнал отказов архиватора срок НЕ двигает — у счёта один владелец, состояние прибора: отказ, записанный в
# журнале пятью запусками две недели назад, при первом вызове модуля молчит.
rm -f "$ST"
for _h in 01 02 03 04 05; do
    printf '{"ts":"2033-05-11T%s:00:00Z","item":"D1271","why":"x","mode":"run"}\n' "$_h"
done > "$T/backlog-archive-fired-2033-05-11.jsonl"
run "$REF" "$((NOW + 7 * DAY))" ""
[ -z "$OUT" ] && grep -q '	1$' "$ST" && ok || bad A7 "записи журнала сдвинули срок: «${OUT}», $(cat "$ST")"
# A7b: первая встреча ДЛЯ ПОКАЗА — у журнала: после срока своих запусков текст называет настоящий возраст отказа
# (14 дней от записи журнала), а не возраст файла состояния.
run "$REF" "$((NOW + 7 * DAY + 1))" ""; run "$REF" "$((NOW + 7 * DAY + 2))" ""
grep -q 'D1271 (отказов подряд до 3, висит до 14 дн.)' <<< "$OUT" && ok || bad A7b "первая встреча для показа не взята у журнала архиватора: «${OUT}»"
# A8 (скептик opus по b8f9cb64, M1): номер без речи об архиве («правлю D1271» соседней сессии) доставку не засчитывает.
rm -f "$ST" "$T"/backlog-archive-fired-*.jsonl
run "$REF" "$NOW" ""; run "$REF" "$((NOW + 1))" ""; run "$REF" "$((NOW + 2))" ""
run "$REF" "$((NOW + 3))" "правлю D1271"
grep -q 'D1271 (отказов' <<< "$OUT" && ok || bad A8 "номер без речи об архиве погасил доставку: «${OUT}»"
# A9: отказы с одной причиной — одна часть строки: причина звучит один раз, номера перечислены.
rm -f "$ST"
REF2=$'Закрытие без показания:\n  · B1: метка формы\n  · B2: метка формы\n  · B3: красная проверка\n'
run "$REF2" "$NOW" ""; run "$REF2" "$((NOW + 1))" ""; run "$REF2" "$((NOW + DAY + 1))" ""
[ "$(grep -o 'метка формы' <<< "$OUT" | wc -l | tr -d ' ')" = 1 ] && grep -q 'B1, B2 (отказов подряд до 3, висит до 1 дн.): метка формы' <<< "$OUT" \
    && grep -q 'B3 (отказов подряд до 3, висит до 1 дн.): красная проверка' <<< "$OUT" && ok || bad A9 "одна причина звучит не один раз: «${OUT}»"
# A10: нечитаемое (не UTF-8) состояние — как его нет: модуль не падает и состояние перезаписано.
printf '\xff\xfe\n' > "$ST"; run "$REF" "$NOW" ""; RCN=$?
[ "$RCN" = 0 ] && grep -q '^D1271	' "$ST" && ok || bad A10 "битое состояние уронило модуль (код $RCN)"
# A11 (D1352): строка состояния прежнего вида (пять полей, без счёта) читается с нулём запусков — модуль не падает,
# первая встреча сохранена, счёт после вызова 1.
printf 'D1271\t1999000000\t0\t0\tпрежняя причина\n' > "$ST"; run "$REF" "$NOW" ""
[ -z "$OUT" ] && grep -q '^D1271	1999000000	0	0	.*	1$' "$ST" && ok || bad A11 "строка прежнего вида не принята: «${OUT}», $(cat "$ST")"
echo "archive relay: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
