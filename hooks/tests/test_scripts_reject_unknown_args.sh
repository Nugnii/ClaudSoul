#!/usr/bin/env bash
# test_scripts_reject_unknown_args.sh — инструмент отбивает неузнанный аргумент ДО записи.
#
# Результат: ни один инструмент scripts/ не принимает аргумент вне объявленного перечня;
#            неузнанный вход отбивается кодом 2 и мир не меняется
# Проверка результата: bash hooks/tests/test_scripts_reject_unknown_args.sh даёт 0
#
# Повод (D320, замер 6 сентября 2026). Режим опознавался вхождением строки в argv, и всё
# несовпавшее шло в ветку по умолчанию — то есть В РАБОТУ:
#   · `regen-seed.py --help` печатал «seed пересобран», возвращал 0 и переписывал ВСЕ 40
#     файлов knowledge/ (содержимое совпало только потому, что seed был актуален);
#   · `knowledge-independence.py --mark-untrace` (опечатка в известном флаге) отрабатывал
#     как обычный замер с кодом 0, а пометка молча не ставилась — отличить «пометил» от
#     «не понял флаг» снаружи было нечем.
#
# ОБЛАСТЬ: два инструмента с ПИШУЩИМ вызовом. Третий носитель формы
# (scripts/colon-lead-in-count.py) не проверяется намеренно: пишущих вызовов у него ноль,
# последствия нет, и требовать от него кода 2 значило бы менять поведение без причины.
# Условие снятия предела: у него появится запись в мир.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PORTABLE_LIB="${PORTABLE_LIB:-$(cd "$(dirname "$0")/.." && pwd)/portable-lib.sh}"
# shellcheck source=/dev/null
if [ -f "$PORTABLE_LIB" ]; then . "$PORTABLE_LIB"; else utf8_trim() { cat; }; fi

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

# Снимок мира: содержимое и время правки seed. Дефект D320 виден именно как ЗАПИСЬ.
snap() { ls -l "$ROOT"/knowledge/*.md 2>/dev/null | shasum | cut -d' ' -f1; }

# --- T1: неизвестный аргумент отбивается кодом 2 -------------------------------
for tool in "scripts/regen-seed.py" "scripts/knowledge-independence.py"; do
    B=$(snap)
    OUT=$(cd "$ROOT" && python3 "$tool" --заведомо-неизвестный-флаг 2>&1); RC=$?
    A=$(snap)
    [ "$RC" -eq 2 ] && ok || bad "T1:$tool" "неузнанный аргумент дал код $RC вместо 2: $(printf '%s' "$OUT" | head -c 90 | utf8_trim)"
    [ "$B" = "$A" ] && ok || bad "T1w:$tool" "мир изменился при неузнанном аргументе"
done

# --- T2: опечатка в известном флаге не проходит как «режим по умолчанию» --------
# Именно этот случай измерен: --mark-untrace вместо --mark-untraced.
B=$(snap)
OUT=$(cd "$ROOT" && python3 scripts/knowledge-independence.py --mark-untrace 2>&1); RC=$?
A=$(snap)
[ "$RC" -eq 2 ] && ok || bad "T2" "опечатка во флаге дала код $RC вместо 2"
[ "$B" = "$A" ] && ok || bad "T2w" "мир изменился при опечатке во флаге"

# --- T3: --help не работает как «режим по умолчанию» ---------------------------
B=$(snap)
OUT=$(cd "$ROOT" && python3 scripts/regen-seed.py --help 2>&1); RC=$?
A=$(snap)
[ "$B" = "$A" ] && ok || bad "T3" "--help ПЕРЕПИСАЛ knowledge/: справка не должна менять мир"
grep -qi 'usage\|использование\|--check' <<< "$OUT" && ok || bad "T3h" "--help не печатает перечня режимов: $(printf '%s' "$OUT" | head -c 80 | utf8_trim)"

# --- T4: ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ — объявленные режимы работают как прежде -------
# Без него строгий разбор мог бы отбивать всё подряд, и тест был бы зелен вхолостую.
#
# ПРЕДМЕТ — РАЗБОР АРГУМЕНТА, А НЕ СОСТОЯНИЕ SEED (12 сентября 2026, D401). Прежняя редакция
# требовала кода 0 и слов «seed актуален», то есть брала фикстурой ЖИВОЕ дерево. Но `--check`
# отвечает 1 при отставшем seed — а отставание между релизами НОРМА (D354), и 12 сентября
# оно наступило само: база знаний выросла на 46 записей, ноги покраснели и обвинили в этом
# «строгий разбор», который тут ни при чём. Красное показание о несуществующем дефекте
# отправляет чинить целое, и это третий такой случай за сутки.
# Разбор аргументов отвергает вызов кодом 2 (ноги T1/T2 выше), поэтому признак «режим
# объявлен и принят» — это «код НЕ 2». Различающая способность сохранена: подмени `--check`
# опечаткой — вернётся 2, и нога покраснеет (ровно это и проверяет T2 на соседнем скрипте).
# База — фикстура через LESSONS_DIR, а не живая `~/.claude/global-lessons`: на машине без базы
# (CI) оба скрипта отвечают кодом 2 «база не найдена» — тем же, что и на неузнанный аргумент,
# и нога не различала их (12 сентября 2026). Десять принципов seed — достаточный вход.
BASE4=$(mktemp -d); trap 'rm -rf "$BASE4"' EXIT
cp "$ROOT"/knowledge/principle-*.md "$BASE4"/
OUT=$(cd "$ROOT" && LESSONS_DIR="$BASE4" python3 scripts/regen-seed.py --check 2>&1); RC=$?
[ "$RC" -ne 2 ] && ok || bad "T4" "--check отбит строгим разбором: код $RC, $(printf '%s' "$OUT" | head -c 80 | utf8_trim)"
# Вывод обязан быть ПРО SEED — то есть режим отработал, а не проглочен. Оба законных ответа
# режима («seed актуален» и «расходится …») несут это слово; слово «неизвестный» — не несёт.
grep -qi 'seed' <<< "$OUT" && ok || bad "T4o" "--check потерял свой вывод: $(printf '%s' "$OUT" | head -c 80 | utf8_trim)"

# Разбор шапок у замера идёт через PyYAML; без него скрипт честно отвечает 2 «не измерен», и
# нога не о разборе аргументов — пропуск НАЗВАН, как у соседей (`SKIP: нет pyyaml`).
if python3 -c 'import yaml' 2>/dev/null; then
    OUT=$(cd "$ROOT" && LESSONS_DIR="$BASE4" python3 scripts/knowledge-independence.py 2>&1); RC=$?
    [ "$RC" -le 1 ] && ok || bad "T5" "замер без аргументов сломан: код $RC"
else
    echo "SKIP [T5]: нет PyYAML — замер knowledge-independence здесь не измерен"
fi

echo "scripts reject unknown args: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
