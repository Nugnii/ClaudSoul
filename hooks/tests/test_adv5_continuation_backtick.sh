#!/usr/bin/env bash
# test_adv5_continuation_backtick.sh — признак «описание продолжено следующей строкой»
# знает только буквы и тире; перенос, начатый обратной кавычкой, цифрой или ёлочкой,
# проходит молча, и в витрину уезжает обрубок.
#
# test_hook_header_contract.sh:81-84 — весь список признаков продолжения:
#     "# "[a-z]* | "# —"* | "# –"* | "# -"*        (ASCII-строчные и три тире)
#     "# а"* … "# я"*                              (тридцать три строчных кириллических)
# Раунд 4 добавил кириллицу, потому что ASCII-класса не хватало. Класс всё ещё описан
# перечислением, а не отрицанием: строка продолжения, начатая любым ДРУГИМ символом,
# невидима. В этом корпусе три таких символа встречаются постоянно:
#     `имя-файла.sh`   — обратная кавычка вокруг идентификатора
#     «цитата»         — ёлочка
#     3 попытки        — цифра
#
# Комбинация с уже закрытым adv3_wrapped_terminator даёт исходный дефект D73 целиком:
# строка 2 кончается закрывающей скобкой (терминатор засчитан), строка 3 начинается с
# обратной кавычки (продолжение не засчитано) — страж зелен, генератор печатает половину
# фразы. Тест проверяет обе стороны: вердикт стража И то, что реально уехало в витрину.

set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
GUARD="$REPO/hooks/tests/test_hook_header_contract.sh"
GEN="$REPO/scripts/regen-readme-skills.sh"
rc_test=0

T="$(mktemp -d)"
mkdir -p "$T/hooks" "$T/skills/dummy"
printf -- '---\nname: dummy\ndescription: заглушка для генератора.\n---\n' > "$T/skills/dummy/SKILL.md"
printf '<!-- SKILLS-TABLE:START -->\n<!-- SKILLS-TABLE:END -->\n<!-- HOOKS-TABLE:START -->\n<!-- HOOKS-TABLE:END -->\n' > "$T/README.ru.md"

cat > "$T/hooks/wrapped_hook.sh" <<'HOOKEOF'
#!/usr/bin/env bash
# wrapped_hook.sh — PreToolUse: сверяет команду со списком разрешённого (по образцу)
# `command-scope-lib.sh` даёт разбор, а решение принимает вызывающий хук.
echo
HOOKEOF

echo "строка 2: $(awk 'NR==2' "$T/hooks/wrapped_hook.sh")"
echo "строка 3: $(awk 'NR==3' "$T/hooks/wrapped_hook.sh")"

# --- 1. Страж обязан назвать обрыв ---
guard_out="$(HOOKS_DIR="$T/hooks" bash "$GUARD" 2>&1)"; guard_rc=$?
if [ "$guard_rc" -eq 0 ]; then
    echo "FAIL [A5a]: страж зелен на описании, разорванном переносом:"
    printf '%s\n' "$guard_out" | sed 's|^|    |'
    rc_test=1
else
    echo "PASS [A5a]: страж назвал обрыв"
fi

# --- 2. Показать, что именно уехало в витрину ---
README_FILE="$T/README.ru.md" bash "$GEN" "$T" >/dev/null 2>&1
row="$(grep -F '| `wrapped_hook` |' "$T/README.ru.md" || true)"
echo "строка витрины: $row"
case "$row" in
    *"решение принимает вызывающий"*)
        echo "FAIL [A5b]: генератор склеил строки — его контракт изменился незаявленно."
        rc_test=1 ;;
    *)
        # Обрубок в витрине — НЕ дефект генератора: он берёт одну строку по контракту,
        # и это записано в шапке partial-read-guard.sh. Разделение ролей намеренно:
        # генератор не разбирает язык, а страж не даёт таким данным дожить до витрины.
        # Требование «пусть генератор склеивает» здесь не заявлял никто; принять его
        # значило бы завести в генераторе разбор предложений — то есть ровно ту
        # эвристику над синтаксисом, которую этот же раунд снял в обходе.
        echo "PASS [A5b]: генератор берёт одну строку, как и обещал; полноту сторожит страж" ;;
esac

echo ""
if [ "$rc_test" -ne 0 ]; then
    echo "adv5 continuation-backtick: КРАСНЫЙ — роли разъехались:"
    echo "  либо страж пропустил обрыв, либо генератор начал склеивать сам."
else
    echo "adv5 continuation-backtick: 2/2 passed"
fi
exit "$rc_test"
