#!/usr/bin/env bash
# test_test_cost_notice.sh — страж цены теста говорит о ДОРОГОМ и молчит обо всём прочем.
#
# Результат: правка теста, чья измеренная цена выше порога, называет число; дешёвый тест,
#            не-тест и отсутствие журнала проходят молча.
# Проверка результата: bash hooks/tests/test_test_cost_notice.sh даёт 0
#
# Ноги держат ОБЕ стороны различения: без T2-T4 тест зеленел бы у стража, который молчит
# всегда, а без T1 — у того, который говорит на всё подряд.
#
# Отдельная нога на отсутствие журнала: «журнала нет» — это «прибора здесь нет» (молчать и
# выйти нулём), а не «цена в порядке». Свалить их в один канал значит пустить два смысла по
# одному проводу — правило «Хук зовёт инструмент» в .claude/rules/claudsoul-hooks.md.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
GUARD="$REPO/hooks/test-cost-notice.sh"
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }
# Хелперы взяты у соседа (test_budget_gate.sh), а не изобретены: прувер
# `test_guards_provable.sh` распознаёт доказательство тишины ПО СИГНАТУРЕ, и ручной
# `[ -z "$OUT" ]` доказательством не считает — страж, который горит всегда, тоже бесполезен.
assert_silent() {   # $1 вывод, $2 метка — тишина стража
    [ -z "$1" ] && ok || bad "$2" "ожидалась тишина, получено: ${1}"
}
assert_contains() { # $1 вывод, $2 искомое, $3 метка — срабатывание
    if grep -Fq "$2" <<< "$1"; then ok; else bad "$3" "нет '$2' в: ${1}"; fi
}
[ -f "$GUARD" ] || { echo "FAIL: нет $GUARD"; exit 1; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/state" "$TMP/hooks/tests"
# ЖУРНАЛ НОВОГО ДОГОВОРА (13 сентября 2026, D410): копия ПОЛНОГО прогона, четыре колонки —
# код, стенные секунды, имя, ПРОЦЕССОРНОЕ время. Мера берётся у владельца факта
# (scripts/costly-tests.sh), а не считается здесь: прежняя редакция судила по колонке 2, и
# на живом журнале это давало 16 «дорогих» против 10 настоящих — шесть ложных просьб.
# `test_wall_only` — ровно тот класс: дорог по стене, дёшев по процессору.
printf '# прогон начат 2026-01-01 00:00:00, тестов 4, полнота полный\n0\t120\ttest_heavy.sh\t99\n0\t9\ttest_light.sh\t3\n0\t80\ttest_wall_only.sh\t4\n0\t70\ttest_justified.sh\t66\n' \
    > "$TMP/state/suite-run-full.tsv"

run() { printf '{"tool_input":{"file_path":"%s"}}' "$1" | STATE_DIR="$TMP/state" bash "$GUARD" 2>&1; }

# --- T1: дорогой тест → цена названа числом ---
OUT=$(run "$TMP/hooks/tests/test_heavy.sh")
assert_contains "$OUT" "99" "T1: цена дорогого теста не названа"

# --- T2: дешёвый тест → молчание (иначе страж станет фоном) ---
OUT=$(run "$TMP/hooks/tests/test_light.sh")
assert_silent "$OUT" "T2: страж заговорил о дешёвом тесте"

# --- T3: файл не из hooks/tests → страж не его предмет ---
OUT=$(run "$TMP/hooks/some-hook.sh")
assert_silent "$OUT" "T3: страж заговорил о файле, который не тест"

# --- T4: теста нет в журнале (новый) → молчание, цена ещё не измерена ---
OUT=$(run "$TMP/hooks/tests/test_brand_new.sh")
assert_silent "$OUT" "T4: страж высказался о тесте, цены которого не знает"

# --- T6: дорог по СТЕНЕ, дёшев по процессору → молчание. Тот самый класс ложных просьб:
# на живом журнале таких шесть из шестнадцати, и каждая спорила бы с владельцем факта. ---
OUT=$(run "$TMP/hooks/tests/test_wall_only.sh")
assert_silent "$OUT" "T6: страж судит по стенным секундам вместо процессорных"

# --- T7: дороговизна ОПРАВДАНА реестром → молчание. Решение принято владельцем факта,
# и повторять его просьбой «удешеви» значит спорить с принятым решением. ---
printf '# тест\tCPU\tпричина\ntest_justified.sh\t66\tпроба реестра\n' > "$TMP/hooks/tests/costly-justified.tsv"
OUT=$(COSTLY_JUSTIFIED="$TMP/hooks/tests/costly-justified.tsv" run "$TMP/hooks/tests/test_justified.sh")
assert_silent "$OUT" "T7: страж спорит с реестром оправданий"
# Положительный контроль к T7: с ПУСТЫМ реестром тот же тест назван — иначе нога зелена
# вхолостую. Пустой, а не отсутствующий: запасной путь стража выводит реестр из
# расположения файла и нашёл бы фикстурный.
OUT=$(COSTLY_JUSTIFIED=/dev/null run "$TMP/hooks/tests/test_justified.sh")
assert_contains "$OUT" "66" "T7б: без реестра дорогой тест не назван — контроль пуст"

# --- T5: журнала нет вовсе → молчание и код 0, а не выдумка ---
rm -f "$TMP/state/suite-run-full.tsv"
OUT=$(run "$TMP/hooks/tests/test_heavy.sh"); RC=$?
assert_silent "$OUT" "T5: без журнала страж не промолчал"
[ "$RC" -eq 0 ] && ok || bad "T5b" "без журнала код не 0, а ${RC} — «нет прибора» стало отказом"

echo "test cost notice: PASS=$PASS FAIL=$FAIL"
exit $(( FAIL != 0 ))
