#!/usr/bin/env bash
# test_named_limit_has_exit.sh — у названного предела есть условие снятия.
#
# Результат: в дереве нет названного предела без условия, при котором он перестаёт держаться
# Проверка результата: bash hooks/tests/test_named_limit_has_exit.sh даёт 0
#
# Зачем (D106). Проект заводит реестры известного-и-несделанного, и у каждого должен быть
# выход. У очереди «на производство» выход — вердикт плюс срок; у исходов несогласия —
# автогашение; у BACKLOG.md — условие возврата. «Названные пределы» в шапках механизмов
# выхода не имели вовсе: предел объявлялся и жил неограниченно долго.
#
# ПРАВИЛО. Предел — это РЕШЕНИЕ, а не долг, поэтому срок ему не нужен: он не ждёт
# исполнения. Ему нужно УСЛОВИЕ СНЯТИЯ — названное обстоятельство, при котором предел
# перестаёт держаться. Без него предел неотличим от «дальше не смогли»: перечитать его
# некому и не по какому поводу, и он переживает обстоятельства, которые его породили.
#
# Замер 29 августа 2026 до этого стража: пределов 10, с условием снятия 3.
#
# КОНТРПРИМЕРЫ, каждый измерен на дереве 29 августа 2026:
#   · файл, лишь ССЫЛАЮЩИЙСЯ на чужой предел («предел назван в шапке такого-то»), своего
#     не объявляет;
#   · тест атаки (`hooks/tests/test_adv*`), внутри которого предел стоит в ФИКСТУРЕ —
#     подложном документе, а не в собственной шапке теста. Предел там принадлежит фикстуре;
#   · строка-значение YAML (`reason: "… предел назван …"`) — это пересказ в провенансе
#     знания, а не объявление.
# Без этих трёх оговорок признак дал 7 находок при 5 настоящих: ловил слово, а не
# объявление.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO" || exit 1
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

python3 - <<'PY'
import re, subprocess, sys, pathlib

files = subprocess.run(["git", "ls-files", "*.sh", "*.py", "*.md"],
                       capture_output=True, text=True).stdout.split("\n")

DECLARE = re.compile(r'НАЗВАННЫЙ ПРЕДЕЛ|Названный предел|\*\*Названный предел|назван предел|предел назван')
# Условие снятия: сказано, ЧТО должно измениться, чтобы предел перестал держаться.
EXIT = re.compile(r'словие снятия|нимается, когда|Снимается|пока не появ|как только появ|перестаёт держаться, когда')
# Ссылка на ЧУЖОЙ предел — не объявление своего.
REFERENCE = re.compile(r'предел (?:назван|объявлен) (?:в|у) ')

missing, ok_n, refs = [], 0, 0
for f in files:
    if not f:
        continue
    t = pathlib.Path(f).read_text(errors="replace")
    if not DECLARE.search(t):
        continue
    # Хроника (CHANGELOG, BACKLOG-archive, SESSION) пределов не объявляет — она их
    # пересказывает. Требовать от летописи условие снятия значило бы проверять не тот
    # предмет: она описывает прошлое, а предел живёт в механизме.
    if pathlib.Path(f).name in ("CHANGELOG.md", "внутренний архив (не публикуется)",
                                "BACKLOG-archive.md", "SESSION.md"):
        continue
    # Тест атаки: предел живёт в подложном документе, который тест сам и создаёт.
    if re.match(r'hooks/tests/test_adv', f):
        continue
    # Объявление стоит СТРОКОЙ, а не внутри значения YAML: `reason: "… предел …"` — это
    # пересказ в провенансе, и требовать от него условия снятия значило бы проверять не тот
    # предмет.
    declared_lines = [l for l in t.splitlines()
                      if DECLARE.search(l) and not re.match(r'\s+\w+:\s*"', l)]
    if not declared_lines:
        continue
    if EXIT.search(t):
        ok_n += 1
        continue
    if REFERENCE.search(t) and not re.search(r'НАЗВАННЫЙ ПРЕДЕЛ|\*\*Названный предел', t):
        refs += 1          # только ссылка на чужой предел — свой не объявлен
        continue
    missing.append(f)

print(f"названных пределов с условием снятия: {ok_n}, "
      f"ссылок на чужой предел: {refs}, БЕЗ условия снятия: {len(missing)}")
for f in missing:
    print(f"  · {f}")
if missing:
    print("  Предел — решение, а не долг: сроку он не подлежит, а условию снятия — да.")
    print("  Допиши: «Условие снятия: <что должно измениться, чтобы предел перестал держаться>».")
sys.exit(1 if missing else 0)
PY
