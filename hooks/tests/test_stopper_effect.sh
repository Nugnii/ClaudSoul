#!/usr/bin/env bash
# СУДИТ: scripts/stopper-effect.sh
# test_stopper_effect.sh — замер «изменил ли стопор действие», а не «сколько раз сработал».
#
# Повод — знание, записанное 28 августа 2026:
# `case-2026-08-28-reminder-fired-and-was-read-and-changed-nothing`. Гейт разбора сработал
# в ходе, был прочитан и не изменил ничего. При учёте «сколько раз сработал» он выглядел
# бы здоровым. Отсюда правило: у стража, который должен менять поведение, считать долю
# случаев, где после срабатывания действие ИЗМЕНИЛОСЬ.
#
# Тест держит три вещи: отказ опознаётся в расшифровке, цепочка после отказа засчитывается
# как изменение, её отсутствие — как обход. Без третьей проверки замер стал бы льстивым.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
S="$REPO/scripts/stopper-effect.sh"
[ -f "$S" ] || { echo "FAIL: нет $S"; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
D="$TMP/transcripts"; mkdir -p "$D"

usr()  { jq -cn --arg t "$1" '{type:"user",message:{role:"user",content:[{type:"text",text:$t}]}}'; }
# Настоящий отказ несёт is_error: отменённый вызов возвращается ОШИБКОЙ. Без этого поля
# та же метка приходит из исходника стража, его ручного прогона и падения теста —
# 57 таких совпадений из 156 в живом корпусе 4 сентября 2026.
deny() { jq -cn '{type:"user",message:{role:"user",content:[{type:"tool_result",is_error:true,content:"⛔ ОТКАЗ (вызов не выполнен). Правка не пройдёт, пока не произнесена цепочка причин."}]}}'; }
# Отказ стража, чей требуемый выход НЕ цепочка, а исполнение.
deny_other() { jq -cn '{type:"user",message:{role:"user",content:[{type:"tool_result",is_error:true,content:"⛔ ОТКАЗ (вызов не выполнен). Запись в установленные правила мимо библиотеки слияния."}]}}'; }
# Маркер В НАЧАЛЕ блока, но БЕЗ is_error — собственный вывод агента, начатый маркером.
# ФОРМА ВЗЯТА ИЗ МИРА, а не придумана (16 сентября 2026): прежняя фикстура изображала строку
# исходника стража с номером (`427\tDENY_MSG="⛔ …"`), то есть маркер НЕ в начале. С якорным
# выражением владельца (D421) такой блок отсекается ЯКОРЕМ, а не полем is_error, и фантомом
# уже не является — предмет счётчика сменился вместе с признаком. Замер по корпусу:
# «маркер в начале, is_error нет» — 5 случаев (образец ниже дословный), «маркер не в начале» —
# 847, и это другой отсев. Фикстура под подстрочный признак осталась бы зелёной по инерции.
phantom() { jq -cn '{type:"user",message:{role:"user",content:[{type:"tool_result",content:"⛔ ВОСПРОИЗВЕЛОСЬ: run_all.sh виснет, когда stdin — открытая труба"}]}}'; }
say()  { jq -cn --arg t "$1" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$t}]}}'; }

# Ход 1: отказ, затем цепочка — действие изменилось.
{ usr "чини"; say "Оказалось, мимо. Чиню."; deny
  # Фикстура несёт АДРЕС: с 9 сентября 2026 он обязателен во всех ветвях критерия
  # (`rc_chain_spoken`) — разбор без единого адреса есть речь, а не разбор.
  say "Почему мимо? Признак перечнем (scripts/defect-class-carriers.py:579). Почему перечнем? Считать дёшево. Почему дёшево победило? Условия остановки не было."; } > "$D/a.jsonl"

# Ход 2: отказ, цепочки нет — обход.
{ usr "чини"; say "Оказалось, мимо. Чиню."; deny; say "Ладно, зайду иначе."; } > "$D/b.jsonl"

OUT=$(STOPPER_TRANSCRIPT_DIR="$D" bash "$S" 2>&1)

grep -q "отказов: 2" <<< "$OUT" && ok || bad "счёт отказов" "не найдено «отказов: 2»: $OUT"
grep -q "цепочка произнесена: 1" <<< "$OUT" && ok || bad "счёт изменений" "не найдено «цепочка произнесена: 1»: $OUT"
grep -qE "обойд|без цепочки: 1" <<< "$OUT" && ok || bad "счёт обходов" "обход не назван: $OUT"

# Без отказов вовсе — замер честно говорит, что судить не о чем, и не выдаёт 100%.
E="$TMP/empty"; mkdir -p "$E"; { usr "привет"; say "Готово."; } > "$E/c.jsonl"
OUT2=$(STOPPER_TRANSCRIPT_DIR="$E" bash "$S" 2>&1)
grep -q "отказов: 0" <<< "$OUT2" && ok || bad "пустой корпус" "не сказано «отказов: 0»: $OUT2"
grep -qE "судить не о чем|данных нет|рано" <<< "$OUT2" && ok \
    || bad "пустой корпус" "при нуле отказов замер обязан сказать, что вывода нет: $OUT2"
grep -q "100%" <<< "$OUT2" && bad "пустой корпус" "на нуле показана доля 100% — лесть: $OUT2" || ok

# T7: метка БЕЗ is_error отказом не считается — иначе исходник стража и его ручной прогон
# растят число отказов. Замер 4 сентября 2026: 57 таких совпадений из 156.
P="$TMP/phantom"; mkdir -p "$P"
{ usr "чини"; say "Смотрю стража."; phantom; say "Ладно."; } > "$P/p.jsonl"
OUT3=$(STOPPER_TRANSCRIPT_DIR="$P" bash "$S" 2>&1)
grep -q "отказов: 0" <<< "$OUT3" && ok || bad "T7 фантом" "исходник стража засчитан отказом: $OUT3"
# Нога судит НАЛИЧИЕ ЧИСЛА у величины, а не формулировку строки: прежний шаблон был
# привязан к словам («не считаются: 1»), и уточнение имени величины 16 сентября 2026 уронило
# его при верном числе. Признак привязан к устойчивой части — «без is_error» и цифра за ней.
grep -qE "без is_error[^0-9]*1" <<< "$OUT3" && ok || bad "T7 фантом" "фантом не назван числом: $OUT3"

# T8: отказ стража, требующего исполнения, в долю разбора НЕ входит. До 4 сентября 2026
# такие отказы судились «цепочкой» — 30 из 99, и доля занижалась ими молча.
O="$TMP/other"; mkdir -p "$O"
{ usr "чини"; say "Пишу в правила."; deny_other; say "Иду через библиотеку слияния."; } > "$O/o.jsonl"
OUT4=$(STOPPER_TRANSCRIPT_DIR="$O" bash "$S" 2>&1)
grep -q "отказов: 1" <<< "$OUT4" && ok || bad "T8 прочие" "отказ не посчитан: $OUT4"
grep -qE "ПРОЧИЕ СТРАЖИ: 1" <<< "$OUT4" && ok || bad "T8 прочие" "не отнесён к прочим: $OUT4"
grep -qE "цепочка произнесена: 0 " <<< "$OUT4" && bad "T8 прочие" "свёрнут в долю разбора: $OUT4" || ok
[ "$(STOPPER_TRANSCRIPT_DIR="$O" bash "$S" >/dev/null 2>&1; echo $?)" = "0" ] && ok \
    || bad "T8 прочие" "отказ прочего стража дал находку, хотя его выход не измеряется"

# T9: цепочка по КАНОНУ без слова «почему» засчитывается. Своя копия критерия
# («почему» ≥ 3) считала такой разбор обходом: 52% против 91% на одних отказах.
C="$TMP/canon"; mkdir -p "$C"
{ usr "чини"; say "Правлю."; deny
  say "Вширь по проявлениям: a.sh:12 и b.sh:7. Вглубь: корень в разделителе, дробь 2 из 9."; } > "$C/c.jsonl"
OUT5=$(STOPPER_TRANSCRIPT_DIR="$C" bash "$S" 2>&1)
grep -q "цепочка произнесена: 1" <<< "$OUT5" && ok \
    || bad "T9 канон" "разбор без слова «почему» засчитан обходом: $OUT5"

echo ""
echo "stopper effect tests: $PASS/$((PASS + FAIL)) passed"
exit $(( FAIL != 0 ))
