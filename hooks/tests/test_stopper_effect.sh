#!/usr/bin/env bash
# test_stopper_effect.sh — замер «изменил ли стопор действие», а не «сколько раз сработал».
#
# Повод — знание, записанное 28 августа 2026:
# `case-2026-08-28-reminder-fired-and-was-read-and-changed-nothing`. Гейт разбора сработал
# в ходе, был прочитан и не изменил ничего. При учёте «сколько раз сработал» он выглядел
# бы здоровым. Отсюда правило: у стража, который должен менять поведение, считать долю
# случаев, где после срабатывания действие ИЗМЕНИЛОСЬ.
#
# Тест держит три вещи: отказ опознаётся в расшифровке, цепочка после отказа засчитывается
# как изменение, её отсутствие — как обход. Без третьей проверки замер стал бы льстивым.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
S="$REPO/scripts/stopper-effect.sh"
[ -f "$S" ] || { echo "FAIL: нет $S"; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
D="$TMP/transcripts"; mkdir -p "$D"

usr()  { jq -cn --arg t "$1" '{type:"user",message:{role:"user",content:[{type:"text",text:$t}]}}'; }
deny() { jq -cn '{type:"user",message:{role:"user",content:[{type:"tool_result",content:"⛔ ОТКАЗ (вызов не выполнен). Правка не пройдёт, пока не произнесена цепочка причин."}]}}'; }
say()  { jq -cn --arg t "$1" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$t}]}}'; }

# Ход 1: отказ, затем цепочка — действие изменилось.
{ usr "чини"; say "Оказалось, мимо. Чиню."; deny
  say "Почему мимо? Признак перечнем. Почему перечнем? Считать дёшево. Почему дёшево победило? Условия остановки не было."; } > "$D/a.jsonl"

# Ход 2: отказ, цепочки нет — обход.
{ usr "чини"; say "Оказалось, мимо. Чиню."; deny; say "Ладно, зайду иначе."; } > "$D/b.jsonl"

OUT=$(STOPPER_TRANSCRIPT_DIR="$D" bash "$S" 2>&1)

grep -q "отказов: 2" <<< "$OUT" && ok || bad "счёт отказов" "не найдено «отказов: 2»: $OUT"
grep -q "цепочка произнесена: 1" <<< "$OUT" && ok || bad "счёт изменений" "не найдено «цепочка произнесена: 1»: $OUT"
grep -qE "обойд|без цепочки: 1" <<< "$OUT" && ok || bad "счёт обходов" "обход не назван: $OUT"

# Без отказов вовсе — замер честно говорит, что судить не о чем, и не выдаёт 100%.
E="$TMP/empty"; mkdir -p "$E"; { usr "привет"; say "Готово."; } > "$E/c.jsonl"
OUT2=$(STOPPER_TRANSCRIPT_DIR="$E" bash "$S" 2>&1)
grep -q "отказов: 0" <<< "$OUT2" && ok || bad "пустой корпус" "не сказано «отказов: 0»: $OUT2"
grep -qE "судить не о чем|данных нет|рано" <<< "$OUT2" && ok \
    || bad "пустой корпус" "при нуле отказов замер обязан сказать, что вывода нет: $OUT2"
grep -q "100%" <<< "$OUT2" && bad "пустой корпус" "на нуле показана доля 100% — лесть: $OUT2" || ok

echo ""
echo "stopper effect tests: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
