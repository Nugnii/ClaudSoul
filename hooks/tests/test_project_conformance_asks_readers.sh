#!/usr/bin/env bash
# СУДИТ: scripts/project-conformance.sh
# test_project_conformance_asks_readers.sh — сверщик заведения проекта СПРАШИВАЕТ читателя
# долга, а не смотрит на наличие файла (D416).
#
# Результат: вердикт «долг проекта виден» подтверждён показанием читателя, а сломанная
#            разметка названа отдельно от «файла нет» и от «проверить нечем»
# Проверка результата: bash hooks/tests/test_project_conformance_asks_readers.sh даёт 0
#
# Повод (15 сентября 2026): на ProjectA_NEW сверщик отчитался «Расхождений нет», а архиватор
# видел там «открытых: 0» при 23 пунктах — у пунктов не было номеров. Галочка стояла на
# `bl.is_file()`: пока разметка цела, такой вердикт верен СЛУЧАЙНО.
#
# ФИКСТУРА СТРОИТСЯ ДО ПЕРВОЙ ПРОВЕРКИ, и это куплено тремя переработками 18 сентября
# 2026. Две первые редакции правки проверялись прогоном на ЖИВЫХ файлах, где разметка цела
# и красная ветка недостижима по построению; оба дефекта (чтение `os.environ` без
# `import os`; обе стороны счёта через один признак `backlog_item_re`, из-за чего
# расхождение недостижимо) вскрылись за одну команду, как только появилась фикстура со
# сломанной разметкой.
#
# ТРИ СОСТОЯНИЯ, А НЕ ДВА: число пунктов · «метки есть, пунктов нет» (разметка) ·
# «читателя не спросили» (библиотеки нет). Последнее — НЕ «чисто».
set -uo pipefail
unset BACKLOG_CHECKS_NESTED

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
REPO_ROOT="$(cd "$HOOKS_DIR/.." && pwd)"
SUT="$REPO_ROOT/scripts/project-conformance.sh"
[ -f "$SUT" ] || { echo "SKIP: нет $SUT"; exit 0; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

PASS=0; FAIL=0; SAW_RED=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

run() { # run <каталог проекта> [доп. env] → строки вывода про долг
    local proj="$1"; shift
    env "$@" bash "$SUT" "$proj" 2>&1 | grep -iE 'BACKLOG' || true
}

# --- фикстуры ------------------------------------------------------------------------
mkdir -p "$TMP/ok" "$TMP/broken" "$TMP/empty"
printf '# BACKLOG\n\n### B1 ☐ [P2] первый\n\n### B2 ☐ [P3] второй\n' > "$TMP/ok/BACKLOG.md"
# метки есть, идентификаторов нет — ровно форма, на которой ослеп архиватор 15 сентября
printf '# BACKLOG\n\n### Пункт без номера ☐ [P2] сломано\n\n### Ещё ☐ [P3] тоже\n' > "$TMP/broken/BACKLOG.md"
printf '# BACKLOG\n\nпока пусто\n' > "$TMP/empty/BACKLOG.md"

# --- T1: нормальная разметка → вердикт несёт ЧИСЛО, а не факт существования -----------
OUT=$(run "$TMP/ok")
case "$OUT" in
    *"читатель видит открытых пунктов: 2"*) ok ;;
    *"BACKLOG.md есть — долг проекта виден"*) bad T1 "вердикт по наличию файла, читателя не спросили: $OUT" ;;
    *) bad T1 "число открытых пунктов не названо: ${OUT:-<пусто>}" ;;
esac

# --- T2 (ГЛАВНАЯ): метки есть, пунктов читатель не видит → КРАСНОЕ --------------------
OUT=$(run "$TMP/broken")
case "$OUT" in
    *"пунктов читатель НЕ ВИДИТ"*) ok; SAW_RED=$((SAW_RED + 1)) ;;
    *) bad T2 "сломанная разметка прошла как здоровая — долг невидим, а сверщик молчит: ${OUT:-<пусто>}" ;;
esac

# --- T3: пустой бэклог — это НЕ поломка ----------------------------------------------
# Ноль пунктов законен, пока в файле нет и меток: иначе страж горел бы на новом проекте.
OUT=$(run "$TMP/empty")
case "$OUT" in
    *"пунктов читатель НЕ ВИДИТ"*) bad T3 "пустой бэклог назван сломанной разметкой: $OUT" ;;
    *) ok ;;
esac

# --- T4: читателя нет → «НЕ ПРОВЕРЕНО», а не «чисто» ---------------------------------
mkdir -p "$TMP/nohome"
OUT=$(run "$TMP/ok" BL_LIB=/nonexistent/backlog-lib.sh HOME="$TMP/nohome")
case "$OUT" in
    *"читателя не спросили"*) ok; SAW_RED=$((SAW_RED + 1)) ;;
    *"читатель видит открытых пунктов"*) bad T4 "без библиотеки напечатано показание — откуда? $OUT" ;;
    *) bad T4 "отсутствие читателя не названо: ${OUT:-<пусто>}" ;;
esac

# --- T5: ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ — красная ветка вообще достижима ---------------------
# Без него T1 и T3 зеленеют на сверщике, у которого весь блок вырезан: у них ожидаемый
# исход — отсутствие красной строки. Первая редакция правки как раз и была такой:
# обе стороны счёта шли одним признаком, и «метки есть, пунктов нет» не наступало никогда.
[ "$SAW_RED" -ge 2 ] && ok || bad T5 "красная ветка сработала $SAW_RED раз(а) — ноги молчания зеленеют от неработающего блока"

echo "project-conformance asks readers: $PASS passed, $FAIL failed (красных веток $SAW_RED)"
exit $(( FAIL != 0 ))
