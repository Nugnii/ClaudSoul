#!/usr/bin/env bash
# СУДИТ: hooks/knowledge-audit-digest.sh
# Предмет исправлен 21 сентября 2026: объявлен был `scripts/backlog-recheck.sh`, потому что
# трасса исполнения видела его вызов. Но тест САМ кладёт его заглушкой в песочницу (`_run`
# пишет свой скрипт) — сверщик здесь ВХОД, а судится дайджест, который строит из его вывода
# сигнал об откате. Признак «исполнен» не различает файл дерева от фикстуры теста.
# test_rollback_signal_names_item.sh — сигнал об откате называет ПУНКТ, а не только число.
#
# Результат: подсказка об откатившемся закрытии несёт имя пункта, по которому расхождение проверяется
# Проверка результата: bash hooks/tests/test_rollback_signal_names_item.sh даёт 0
#
# Повод (D343). Дважды за вечер 6-7 сентября 2026 сигнал старта говорил «1 инвариант
# закрытых пунктов перестал держаться», а прямой прогон `backlog-recheck.sh` в тот же
# момент отвечал «все держатся». Разобрать расхождение было нечем: дайджест СЧИТАЛ строки
# `✗` и выбрасывал вывод вместе с именами. Предписание «верни пункту ☐», которое нельзя
# исполнить, учатся пролистывать — а вместе с ним пролистают настоящий откат.
#
# Проверяется ПОВЕДЕНИЕМ, а не наличием слова в файле: объявленная в пункте «Проверка»
# была `grep` по строке и позеленела бы от одного комментария (тот же дефект ловили у D321).
set -uo pipefail
unset BACKLOG_CHECKS_NESTED

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
DIGEST="${DIGEST_SH:-$REPO/hooks/knowledge-audit-digest.sh}"
[ -f "$DIGEST" ] || { echo "FAIL: нет $DIGEST"; exit 1; }

PASS=0; FAIL=0
S=$(mktemp -d)
trap 'rm -rf "$S"' EXIT
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

mkdir -p "$S/scripts" "$S/state" "$S/lessons"
# База знаний уводится в песочницу (11 сентября 2026, D392). Предмет теста — СИГНАЛ ОБ
# ОТКАТЕ, который дайджест строит из вывода `backlog-recheck.sh`; сам обход знаний к нему
# отношения не имеет. Прежде `LESSONS_DIR` не подменялся, и каждый из трёх вызовов обходил
# все 507 настоящих записей — 16 с на вызов, 55 с на тест. Одной записи довольно: дайджест
# отказывается работать на пустом каталоге (`No lessons dir`), и пустота проверяла бы не то.
printf 'name: proba\nconfidence: 1\n---\nЗапись-фикстура для песочницы.\n' > "$S/lessons/pattern-proba.md"

_run() {   # <строки, которые печатает заглушка сверщика> → печатает строку подсказки про долг
    printf '#!/usr/bin/env bash\n%s\n' "$1" > "$S/scripts/backlog-recheck.sh"
    chmod +x "$S/scripts/backlog-recheck.sh"
    rm -f "$S/state/audit-hint.txt"
    STATE_DIR="$S/state" CLAUDSOUL_ROOT="$S" CLAUDSOUL_REPO="$S" LESSONS_DIR="$S/lessons" \
        bash "$DIGEST" >/dev/null 2>&1 || { echo "подготовка мира не удалась: hooks/tests/test_rollback_signal_names_item.sh:$LINENO" >&2; exit 1; }
    grep -i 'Долг:' "$S/state/audit-hint.txt" 2>/dev/null | head -1
}

# T1: сломанный инвариант — имя пункта в подсказке.
OUT=$(_run 'printf "  ✗ %s  %s\n" D999 "заглушка"')
grep -q 'D999' <<< "$OUT" && ok || bad "T1" "имя пункта не названо: «${OUT}»"
grep -q 'откатилось' <<< "$OUT" && ok || bad "T1b" "подсказка про откат не выдана вовсе: «${OUT}»"

# T2: ДВА сломанных — названы оба, иначе имя выродится в «первый попавшийся».
OUT2=$(_run 'printf "  ✗ %s  %s\n" D998 "a"; printf "  ✗ %s  %s\n" D997 "b"')
{ grep -q 'D998' <<< "$OUT2" && grep -q 'D997' <<< "$OUT2"; } && ok \
    || bad "T2" "названы не все сломавшиеся: «${OUT2}»"

# T3 ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: всё держится — подсказки про откат нет вовсе.
# Без него T1 был бы зелен и у механизма, который печатает эту строку всегда.
OUT3=$(_run 'echo "Инвариантов проверено: 7, все держатся."')
[ -z "$OUT3" ] && ok || bad "T3" "при целых инвариантах выдана подсказка об откате: «${OUT3}»"

# T4 (D1147): красное без слов пробы — «откат или гнилая проба», а не «откатилось»; говорящее рядом остаётся
# «откатилось». Обе стороны — иначе зеленел бы дайджест, зовущий всё одним словом. Одна строка «Долг» на оба
# состояния: подсказка режется до двух строк, и отдельная строка вытесняла бы «проверить нечем» (круг 3, L8).
# Метка признаётся только сразу за номером: D994 несёт её в словах пробы и остаётся откатом (круг 3, L1).
_run 'printf "  ✗ %s  %s\n" D996 "красна (код 1, объявлен 0): \`x\` — вывод: дефект"; printf "  ✗ %s  [без слов пробы] %s\n" D995 "архив: красна (код 1, объявлен 0) — откат от гнилой пробы по её выводу не отличить"; printf "  ✗ %s  %s\n" D994 "красна — вывод: ждали [без слов пробы]"; printf "  ? %s  %s\n" D993 "не измерила"' >/dev/null
ALL4=$(grep -i 'Долг:' "$S/state/audit-hint.txt" 2>/dev/null)
L_ROLL=$(grep 'откатилось' <<< "$ALL4" | sed 's/ Ещё .*//'); L_SIL=$(grep -o 'БЕЗ СЛОВ ПРОБЫ.*' <<< "$ALL4")
{ grep -q 'D996' <<< "$L_ROLL" && grep -q 'D994' <<< "$L_ROLL" && ! grep -q 'D995' <<< "$L_ROLL" \
    && grep -q 'D995' <<< "$L_SIL" && ! grep -qE 'D99[64]' <<< "$L_SIL"; } && ok \
    || bad "T4" "молчащее красное не разведено с говорящим: «${ALL4}»"
grep -q 'Долг: 2 инвариант' <<< "$L_ROLL" && ok || bad "T4b" "счёт откатов включил молчащее: «${L_ROLL}»"
grep -q 'проверить нечем' <<< "$ALL4" && ok || bad "T4c" "строка «проверить нечем» вытеснена: «${ALL4}»"

echo ""
echo "rollback signal names item: $PASS/$((PASS + FAIL)) passed"
exit $(( FAIL != 0 ))
