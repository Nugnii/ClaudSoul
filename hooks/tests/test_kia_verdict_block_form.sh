#!/usr/bin/env bash
# test_kia_verdict_block_form.sh — прибор «знание → инструмент» читает вердикт в ОБЕИХ
# формах записи, и отказ выводит из очереди, а `candidate` — оставляет.
#
# Результат: блочный `decision: не заводится` закрывает пункт; блочный `decision: candidate` нет.
# Проверка результата: bash hooks/tests/test_kia_verdict_block_form.sh даёт 0
#
# Повод (10 сентября 2026). Вердикт пишется рукой в двух формах — скалярной и блочной, — а
# читатель знал одну. `str(dict).split()[0]` после чистки давал слово `decision`, которого нет
# ни в одном словаре, и все ДЕВЯТЬ файлов базы с блочной формой стояли в очереди на
# производство при уже вынесенном отказе: пять строк очереди из четырнадцати были этим.
# Русское значение «не заводится» латинский словарь тоже не узнавал. Корень R1 из ROOTS.md:
# имя состояния собрано литералом на стороне читателя, у писателя ни схемы, ни валидатора.
#
# Ноги держат ОБЕ стороны различения: без T2 тест зеленел бы у прибора, который выпускает
# из очереди по любому непустому вердикту, — а это ровно дефект D106, закрытый 28 августа.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

command -v python3 >/dev/null 2>&1 || { echo "нет python3 — пропуск"; exit 0; }

# Фикстура: одно знание, у которого вердикт задан БЛОЧНОЙ формой.
mk() {  # $1 — каталог, $2 — значение decision
    mkdir -p "$1"
    cat > "$1/pattern-fixture-verdict.md" <<MD
---
name: fixture-verdict
description: фикстура для проверки чтения вердикта
type: pattern
outcome: error
confidence: 5
impact: 5
confirmed_count: 42
contradicted_count: 0
status: active
blocker: false
instrument_verdict:
  decision: "$2"
  why: "фикстура"
  dated: "2026-09-10"
---
тело фикстуры
MD
}

# Прибор пишет отчёт в ОБЩЕЕ состояние (`$STATE_DIR/knowledge-instrument.md`), поэтому
# прогон на фикстуре обязан увести и вывод, и состояние к себе: первый заход этого теста
# затёр рабочий отчёт фикстурой — «хранится 1, 100% базы».
run() {
    LESSONS_DIR="$1" STATE_DIR="$1/state" KIA_OUTPUT="$1/report.md" \
        bash "$REPO/scripts/knowledge-instrument-audit.sh" 2>&1
}

# Число очереди добывается ОТДЕЛЬНО от вопроса «прибор вообще ответил»: иначе молчание
# прибора и его ответ приходят одним каналом (род B), и тест судит по подставленному
# значению. Пустой вывод здесь возможен по-настоящему — прибор зовёт python3 и падает
# без PyYAML.
queue_of() {  # печатает число очереди либо BROKEN
    local out; out=$(run "$1")
    [ -n "$out" ] || { echo BROKEN; return; }
    local n; n=$(grep -o 'очередь на производство: [0-9]*' <<< "$out" | grep -o '[0-9]*$')
    [ -n "$n" ] || { echo BROKEN; return; }
    echo "$n"
}

# --- T1: блочный ОТКАЗ выводит пункт из очереди ---
D1=$(mktemp -d); mk "$D1" "не заводится"
Q1=$(queue_of "$D1")
if [ "$Q1" = "BROKEN" ]; then
    bad T1 "прибор не ответил — отличить «отказ закрыл пункт» от «прибор молчит» нечем"
elif [ "$Q1" = "0" ]; then
    ok
else
    bad T1 "блочный отказ не закрыл пункт — в очереди осталось $Q1"
fi

# --- T2: блочный `candidate` из очереди НЕ выводит (положительный контроль) ---
D2=$(mktemp -d); mk "$D2" "candidate"
Q2=$(queue_of "$D2")
if [ "$Q2" = "BROKEN" ]; then
    bad T2 "прибор не ответил — положительный контроль недоказуем"
elif [ "$Q2" -gt 0 ] 2>/dev/null; then
    ok
else
    bad T2 "candidate выпущен из очереди — прибор выпускает по любому вердикту (D106)"
fi

rm -rf "$D1" "$D2" 2>/dev/null
echo "kia verdict block form: PASS=$PASS FAIL=$FAIL"
exit $(( FAIL != 0 ))
