#!/usr/bin/env bash
# СУДИТ: hooks/lib/open-findings-lib.sh hooks/root-cause-lib.sh hooks/session-collector.sh
# test_open_findings.sh — обнаружение без исхода возвращается на границе хода (D365).
#
# Повод 8 сентября 2026 — владелец: «ты должен реагировать при обнаружении симптома. ЛЮБОГО.
# И искать ПРИЧИНУ. Есть и сторож и гейт и опять ничего не работает», затем уточнение
# «событие-триггер глубже» → НЕЗАКРЫТОСТЬ обнаруженного.
#
# Предмет проверки — не распознавание (гейт уже пишет исход каждого сигнала), а ВОЗВРАТ:
# читает ли кто-нибудь записанное. До этой правки не читал никто, кроме замеров.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$REPO/hooks/lib/open-findings-lib.sh"
COLLECTOR="$REPO/hooks/session-collector.sh"
[ -f "$LIB" ] || { echo "FAIL: нет $LIB"; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
S="$TMP/state"; mkdir -p "$S"

# shellcheck source=/dev/null
. "$LIB"

# 1. Пусто — ноль, а не ошибка и не мусор.
R=$(of_open_counts "$S")
[ "$(printf '%s' "$R" | awk '{print $1" "$2}')" = "0 0" ] \
    && ok || bad T1 "на пустом состоянии: «${R}»"

# 2. Счёт по видам. Форма записи взята из ЖИВОГО журнала, а не придумана:
#    {"ts":...,"key":...,"signal":"discovery","outcome":"deferred","ref":"","trace":{...}}
cat > "$S/outcome-aaa.jsonl" <<'J'
{"ts":"2026-09-01T10:00:00Z","key":"k1","signal":"discovery","outcome":"deferred","ref":""}
{"ts":"2026-09-02T10:00:00Z","key":"k2","signal":"rework","outcome":"none","ref":""}
{"ts":"2026-08-20T10:00:00Z","key":"k3","signal":"correction","outcome":"deferred","ref":""}
{"ts":"2026-09-03T10:00:00Z","key":"k4","signal":"discovery","outcome":"fixed","ref":"x"}
J
cat > "$S/outcome-bbb.jsonl" <<'J'
{"ts":"2026-09-04T10:00:00Z","key":"k5","signal":"небывалый","outcome":"deferred","ref":""}
{"ts":"2026-09-05T10:00:00Z","key":"k6","signal":"discovery","outcome":"none","ref":""}
не json вовсе
J
R=$(of_open_counts "$S")
set -- $R
# Счёт ведётся ЗАЧЁТОМ: более позднее закрытие того же вида гасит самое раннее открытое.
# k4 (discovery/fixed, 3 сентября) закрывает k1 (discovery/deferred, 1 сентября) — значит
# из discovery открытым остаётся только k6 (none, 5 сентября). k3 (correction/deferred) открыт,
# k2 (rework/none) открыт, k5 несёт вид, которого в источнике НЕТ.
# Итог: deferred 1 (k3), none 2 (k2, k6), самое старое — k3 от 20 августа.
[ "${1:-}" = "1" ] && ok || bad T2a "deferred: ждали 1, получили «${1:-}» (всё: «${R}»)"
[ "${2:-}" = "2" ] && ok || bad T2b "none: ждали 2, получили «${2:-}»"
[ "${3:-}" = "2026-08-20T10:00:00Z" ] && ok || bad T2c "самое старое: «${3:-}»"
# T2d (D1256): стоячий вид (`event`, `question`) отказа не держал и исхода не требует — в счёт не идёт ни отложенным, ни
#   «без исхода»; вид с правом на отказ рядом — идёт.
S2d="$TMP/s2d"; mkdir -p "$S2d"
printf '%s\n' '{"ts":"2026-09-01T10:00:00Z","key":"q1","signal":"event","outcome":"deferred","ref":""}' \
    '{"ts":"2026-09-01T11:00:00Z","key":"q2","signal":"question","outcome":"none","ref":""}' \
    '{"ts":"2026-09-01T12:00:00Z","key":"q3","signal":"rework","outcome":"deferred","ref":""}' > "$S2d/outcome-d.jsonl"
[ "$(of_open_counts "$S2d" | awk '{print $1" "$2}')" = "1 0" ] && ok \
    || bad T2d "стоячие виды посчитаны поводами без исхода: «$(of_open_counts "$S2d")»"

# 3. КОНТРОЛЬ МУТАЦИЕЙ поля времени. Библиотека читает поле `ts`; первая её редакция
#    просила несуществующее `date` и молча отдавала пустоту. Переименовав поле во ВХОДЕ,
#    обязаны потерять возраст — проверяется ИМЕННО отсутствие метки, а не её новое
#    значение: при зачёте порядок записей без времени меняет и счёт, и это законно.
BEFORE_TS=$(printf '%s' "${R}" | awk '{print $3}')
sed 's/"ts"/"date"/' "$S/outcome-aaa.jsonl" > "$TMP/mut" && mv "$TMP/mut" "$S/outcome-aaa.jsonl"
R=$(of_open_counts "$S")
AFTER_TS=$(printf '%s' "${R}" | awk '{print $3}')
[ "${AFTER_TS}" != "${BEFORE_TS}" ] \
    && ok || bad T3 "мутация поля времени не изменила ответ: «${R}» — прибор читает не поле ts"

# 4. КОНТРОЛЬ МУТАЦИЕЙ исхода: сделать все исходы закрытыми — счёт обязан упасть в ноль.
#    Без этого T2 проходил бы и у прибора, который считает ВСЕ строки подряд.
for f in "$S"/outcome-*.jsonl; do
    sed 's/"deferred"/"fixed"/; s/"none"/"fixed"/' "$f" > "$TMP/mut" && mv "$TMP/mut" "$f"
done
R=$(of_open_counts "$S")
[ "$(printf '%s' "$R" | awk '{print $1" "$2}')" = "0 0" ] \
    && ok || bad T4 "закрытые исходы всё ещё считаются незакрытыми: «${R}»"

# 5. УНИВЕРСУМ ВИДОВ ВЫВОДИТСЯ ИЗ ИСТОЧНИКА, А НЕ ПЕРЕЧИСЛЕН ЗДЕСЬ.
#    Первая редакция несла три имени от руки, и одно из них (`finding`) в журналах не
#    встречается ни разу, а из восьми настоящих поводов учитывались два: 117 вместо 514.
#    Плечо задаёт СВОЙ список видов и требует, чтобы счёт ему подчинился, — прибор с
#    зашитым перечнем этого не сможет.
S5="$TMP/s5"; mkdir -p "$S5"
cat > "$S5/outcome-ccc.jsonl" <<'J'
{"ts":"2026-09-06T10:00:00Z","key":"k7","signal":"rework","outcome":"deferred","ref":""}
{"ts":"2026-09-07T10:00:00Z","key":"k8","signal":"correction","outcome":"none","ref":""}
{"ts":"2026-09-07T11:00:00Z","key":"k9","signal":"discovery","outcome":"deferred","ref":""}
J
R=$(RC_KINDS_RE='rework:|correction:' of_open_counts "$S5")
[ "$(printf '%s' "${R}" | awk '{print $1" "$2}')" = "1 1" ] \
    && ok || bad T5u "чужой список видов не изменил счёт: «${R}» — универсум зашит, а не выведен"

# 6. ТРИ СОСТОЯНИЯ, А НЕ ДВА: источник недоступен — это ПОЛОМКА, а не «ноль незакрытых».
#    Ноль здесь читается как «всё закрыто», то есть отказ прибора становится неотличим от
#    чистого мира. Тот же род B, что уже закрыт в hooks/lib/unread-lib.sh.
# Пустая переменная поломкой НЕ является: источник заполняет её своим умолчанием, и это
# правильно. Поломка — когда источника нет вовсе.
R=$(RC_KINDS_RE= OF_RC_LIB="$TMP/нет-такого-файла.sh" of_open_counts "$S5" 2>/dev/null); C=$?
case "${R}" in
    BROKEN*) [ "$C" -eq 2 ] && ok || bad T6c "сказал BROKEN, но код $C вместо 2" ;;
    *)       bad T6 "источник недоступен, а прибор ответил «${R}» вместо BROKEN" ;;
esac


# 6б. ЗАКРЫВАЮЩИЕ ИСХОДЫ ВЫВОДЯТСЯ ИЗ СЛОВАРЯ ВЛАДЕЛЬЦА, а не перечислены здесь.
#     Плечо берёт исход `knowledge` — он закрывает повод наравне с `fixed`, но зашитый
#     перечень его не содержит. Контроль мутацией: подмена выведенного набора на {"fixed"}
#     обязана покраснеть, иначе тест зелен и при перечне (проверено 8 сентября 2026 —
#     первая редакция плеча этого не различала).
S6="$TMP/s6"; mkdir -p "$S6"
cat > "$S6/outcome-ddd.jsonl" <<'J'
{"ts":"2026-09-01T10:00:00Z","key":"m1","signal":"discovery","outcome":"deferred","ref":""}
{"ts":"2026-09-02T10:00:00Z","key":"m2","signal":"discovery","outcome":"knowledge","ref":""}
{"ts":"2026-09-01T10:00:00Z","key":"m3","signal":"event","outcome":"deferred","ref":""}
{"ts":"2026-09-02T10:00:00Z","key":"m4","signal":"event","outcome":"disproved","ref":""}
J
R=$(of_open_counts "$S6")
[ "$(printf '%s' "${R}" | awk '{print $1" "$2}')" = "0 0" ] \
    && ok || bad T6d "исходы knowledge/disproved не закрыли повод: «${R}» — набор закрывающих зашит, а не выведен"

# 7. ВОЗВРАТ. Смысл всей правки: счёт доходит до границы хода. Проверяется по самому своду,
#    а не по библиотеке — до 8 сентября 2026 библиотека дала бы верное число НИКОМУ.
if [ -f "$COLLECTOR" ]; then
    # Граница имени, а не вхождение: `grep -q of_open_counts` находит подстроку и в
    # `of_open_countsX`, поэтому контроль мутацией переименованием был ложно-зелёным
    # (пойман на себе 8 сентября 2026). Это тот же род, что «признак судит по форме,
    # а не по роли»: совпадение есть, названного смысла нет.
    grep -qE '(^|[^A-Za-z0-9_])of_open_counts([^A-Za-z0-9_]|$)' "$COLLECTOR" \
        && ok || bad T7a "свод не зовёт of_open_counts — журнал снова читают одни замеры"
    # Вид алерта обязан войти в ключ дросселя, иначе строка либо повторяется каждый ход,
    # либо (хуже) глушит собой соседние: дроссель ключуется составом видов.
    grep -q '🔎' "$COLLECTOR" && grep -q '_sc_kinds="${_sc_kinds}of"' "$COLLECTOR" \
        && ok || bad T7b "вид 🔎 не заведён в ключ дросселя — строка встанет вместо соседней"
else
    echo "SKIP: нет $COLLECTOR"
fi

# 8. ПАРА «ОТЛОЖЕНО → СНЯТО» (D1034): снятие той же пары «ход, сигнал» закрывает отложенное,
#    открытого не остаётся — иначе отказ, снятый в том же ходе, висел бы вечно. Время у записей
#    одно: порядок внутри секунды держит порядок файла.
S8="$TMP/s8"; mkdir -p "$S8"
printf '%s\n' '{"ts":"2026-10-23T10:00:00Z","key":"k1","signal":"discovery","outcome":"deferred","ref":""}' \
               '{"ts":"2026-10-23T10:00:00Z","key":"k1","signal":"discovery","outcome":"looked","ref":""}' > "$S8/outcome-a.jsonl"
R=$(of_open_counts "$S8")
[ "$(printf '%s' "${R}" | awk '{print $1" "$2}')" = "0 0" ] \
    && ok || bad T8 "снятие той же пары не закрыло отложенное: «${R}»"
# 8б. В МИРЕ, ГДЕ ТОГО ЖЕ ВИДА УЖЕ ВИСИТ ЧУЖОЙ `none` постарше (финальный скептик D1034: в живом
#     каталоге — с 3 октября), снятие гасит СВОЁ отложенное, а не самое раннее по зачёту: иначе
#     снятый отказ оставался «повисшим», а чужой повод закрывался (копия живого: 807 → 808).
printf '%s\n' '{"ts":"2026-10-03T09:00:00Z","key":"k0","signal":"discovery","outcome":"none","ref":"чужой"}' > "$S8/outcome-b.jsonl"
R=$(of_open_counts "$S8")
[ "$(printf '%s' "${R}" | awk '{print $1" "$2}')" = "0 1" ] \
    && ok || bad T8b "снятие пары гасит чужое по зачёту, своё остаётся: «${R}» (ждали «0 1»)"
R=$(of_open_list "$S8")
{ grep -q "чужой" <<< "$R" && ! grep -q "deferred" <<< "$R"; } \
    && ok || bad T8c "перечень открытых: ждали чужой none без deferred, получили: ${R}"

echo "open findings: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
