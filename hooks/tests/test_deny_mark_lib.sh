#!/usr/bin/env bash
# СУДИТ: hooks/deny-mark-lib.sh
# test_deny_mark_lib.sh — у имени состояния «вызов отказан стражем» ОДИН владелец, и оно
#                         различает решение стража от упавшей команды.
# Результат: отказ стража не входит в окно провалов `error-tracker`, а страж с НОВЫМ текстом
#            отказа не может пройти незамеченным — перечень маркеров один на дерево
# Проверка результата: bash hooks/tests/test_deny_mark_lib.sh даёт 0
#
# Повод (D421, 16 сентября 2026). Три отказа `five-whys-gate` подряд дали «Из последних 6 команд
# упало 5»; полоса добавила тому же гейту новый повод, и он отбил повтор уже произнесённой
# цепочки — страж порождал повод для самого себя. Замер по корпусу: отказов 411, засчитано
# провалами 338 (82%).
#
# ЧЕМ ЭТОТ СВИДЕТЕЛЬ ОТЛИЧАЕТСЯ ОТ ПРОВЕРКИ ФОРМЫ. Прежняя «Проверка» пункта была
# `grep -q "ОТКАЗ" hooks/error-tracker.sh` — она зеленеет от СЛОВА в комментарии и ничего не
# доказывает. Здесь судится поведение: хуку подаётся расшифровка, и проверяется, что он на ней
# сказал и чего не сказал. Т7 доказывает различающую способность мутантом: выпотрошенный
# владелец обязан уронить T3, иначе зелёный вердикт не значит ничего.

set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
LIB="$HOOKS_DIR/deny-mark-lib.sh"
HOOK="$HOOKS_DIR/error-tracker.sh"
[ -f "$LIB" ]  || { echo "FAIL: нет $LIB"; exit 1; }
[ -f "$HOOK" ] || { echo "FAIL: нет $HOOK"; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }

PASS=0; FAIL=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL $1: $2"; }

# shellcheck source=../deny-mark-lib.sh
. "$LIB"

# --- T1: все ЧЕТЫРЕ написания отказа опознаны ----------------------------------------------
# Перечень выведен из двух источников: корпус дал доли (⛔ ОТКАЗ 378, 🛑 27, 🚫 6), чтение кода —
# два написания, которых в корпусе нет вовсе (secret-guard «⛔ Секрет», publish-guard
# «⛔ Необратимая»). Ни один источник поодиночке перечня не давал.
while IFS='|' read -r name text; do
    [ -n "$name" ] || continue
    if deny_mark_is_denial "$text"; then ok; else bad "T1 $name" "отказ не опознан: $text"; fi
done <<'CASES'
отказ-вызова|⛔ ОТКАЗ (вызов не выполнен). Правка не пройдёт
секрет|⛔ Секрет в записываемом содержимом: aws_key (строка: 12)
публикация|⛔ Необратимая публикация наружу без предъявленного сухого прогона.
блокер|🛑 playwright-cli-guard: одноразовый скрипт — запрещено.
нет-инструмента|🚫 `timeout` на этой машине НЕТ (проверено `command -v`)
CASES

# --- T1p: те же отказы в форме расшифровки — с префиксом харнесса (D527) ---------------------
# С 26 сентября 2026 харнесс пишет отказ как `PreToolUse:<инструмент> hook error: <текст>`;
# на живой расшифровке 11 октября голых отказов после 25 сентября 0 из ≈ 370.
while IFS='|' read -r name text; do
    [ -n "$name" ] || continue
    if deny_mark_is_denial "PreToolUse:Bash hook error: $text"; then ok; else bad "T1p $name" "отказ с префиксом не опознан: $text"; fi
done <<'CASES'
отказ-вызова|⛔ ОТКАЗ (вызов не выполнен). Правка не пройдёт
секрет|⛔ Секрет в записываемом содержимом: aws_key (строка: 12)
блокер|🛑 playwright-cli-guard: одноразовый скрипт — запрещено.
нет-инструмента|🚫 `timeout` на этой машине НЕТ (проверено `command -v`)
CASES
deny_mark_is_denial 'PreToolUse:Edit hook error: ⛔ ОТКАЗ (вызов не выполнен).' && ok || bad "T1p Edit" "отказ на Edit с префиксом не опознан"
# Префикс посреди вывода настоящего провала — не отказ: якорь стоит на начало ВСЕГО текста.
if deny_mark_is_denial 'Exit code 1 PreToolUse:Bash hook error: 🛑 x'; then
    bad "T1p якорь" "префикс внутри вывода провала принят за отказ"; else ok; fi

# --- T2: ЯКОРЬ. Настоящий провал с маркером ВНУТРИ вывода отказом не считается --------------
# Это не придирка: `🛑 Blocker:` инжектится в контекст и попадает в вывод настоящих падений.
# Без якоря такой провал молча выпадал бы из счёта — прежняя редакция EXCL_RE держала голый `🛑`.
if deny_mark_is_denial 'Exit code 1 Traceback (most recent call last) 🛑 Blocker: x'; then
    bad "T2" "провал с маркером внутри принят за отказ — якорь не работает"; else ok; fi
if deny_mark_is_denial 'cp: no such file'; then bad "T2b" "обычный провал принят за отказ"; else ok; fi

# --- фикстура расшифровки: блоки tool_result с заданным телом -------------------------------
mk_body() { local out="$1"; shift; : > "$out"; local b
    for b in "$@"; do
        jq -cn --arg t "$b" '{type:"user",message:{content:[{type:"tool_result",is_error:true,content:$t}]}}' >> "$out"
    done; }
run() { printf '{"session_id":"%s","transcript_path":"%s","hook_event_name":"PreToolUse","tool_name":"Bash"}' "$2" "$1" \
        | STATE_DIR="$TMP/state" ERROR_TRACKER_DRAFT_DIR="$TMP/drafts" bash "$HOOK" 2>&1; }

D1='⛔ ОТКАЗ (вызов не выполнен). 🛑 Blocker: pattern-shell-portability'
D2='🚫 `timeout` на этой машине НЕТ (проверено `command -v`)'
D3='⛔ Секрет в записываемом содержимом: token (строка: 3)'

# --- T3: ПРЕДМЕТ ПУНКТА. Шесть отказов подряд — полоса провалов НЕ растёт -------------------
mk_body "$TMP/deny" "$D1" "$D2" "$D3" "$D1" "$D2" "$D3"
OUT=$(run "$TMP/deny" sdeny)
if [ -z "$OUT" ]; then ok; else bad "T3" "отказы стражей засчитаны провалами: $OUT"; fi

# --- T4: ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. Настоящие провалы считаться обязаны ------------------------
# Без этой ноги T3 зеленеет и от хука, ослепшего целиком, — то есть не значит ничего.
mk_body "$TMP/real" 'Exit code 1 Traceback (most recent call last)' 'Exit code 2 cp: no such file'
OUT=$(run "$TMP/real" sreal)
if [ -n "$OUT" ]; then ok; else bad "T4" "настоящие провалы перестали считаться — сужение съело отзыв"; fi

# --- T5: СМЕСЬ. Отказы не гасят настоящие провалы, стоящие рядом ----------------------------
mk_body "$TMP/mix" "$D1" 'Exit code 1 Traceback' "$D2" 'Exit code 1 cp: no such file'
OUT=$(run "$TMP/mix" smix)
if [ -n "$OUT" ]; then ok; else bad "T5" "два настоящих провала среди отказов не замечены"; fi

# --- T6: ПИШУЩИЙ КОНЕЦ. Страж с НОВЫМ маркером не проходит незамеченным --------------------
# Root закрывается здесь, а не у читателя: пока все писатели берут маркер из перечня владельца,
# любой читатель видит всякий отказ. Признак судит ИСХОДНИК, потому что текст отказа собирается
# динамически и статически не извлекаем.
# НАЗВАННЫЙ ПРЕДЕЛ: маркер ищется во ВСЁМ файле, а не в тексте отказа. `docs-family-check` прошёл T6
# с отказом на «📝» (до 11 октября 2026), потому что «🛑» стоял в его подсказке, а не в отказе;
# поймано чтением, нога на живой текст отказа — `test_adv2_docs_family_quotepath.sh`. Условие снятия:
# у каждого стража есть нога, вызывающая его отказ, — тогда маркер судится по выводу, а не по файлу.
scan_writers() {  # scan_writers <каталог> → имена файлов, пишущих deny БЕЗ владельческого маркера
    local d="$1" f
    for f in "$d"/*.sh; do
        [ -f "$f" ] || continue
        grep -qE 'permissionDecision["[:space:]:]+"?deny' "$f" 2>/dev/null || continue
        grep -q '⛔\|🛑\|🚫' "$f" 2>/dev/null || printf '%s\n' "${f##*/}"
    done
}
BAD=$(scan_writers "$HOOKS_DIR")
if [ -z "$BAD" ]; then ok; else bad "T6" "страж пишет отказ без владельческого маркера: $BAD"; fi

# T6b: ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ признака — страж с чужим маркером обязан быть назван.
# Без него T6 зеленеет и от сломанного grep, и «нарушителей нет» неотличимо от «не посмотрел».
mkdir -p "$TMP/fixture"
printf '#!/usr/bin/env bash\necho %s\n' \
  "'{\"hookSpecificOutput\":{\"permissionDecision\":\"deny\",\"permissionDecisionReason\":\"XX новый маркер\"}}'" \
  > "$TMP/fixture/new-guard.sh"
BAD=$(scan_writers "$TMP/fixture")
if [ "$BAD" = "new-guard.sh" ]; then ok; else bad "T6b" "признак не назвал стража с чужим маркером (дал: '$BAD')"; fi

# --- T7: МУТАНТ. Выпотрошенный владелец обязан уронить T3 -----------------------------------
# Различающая способность показывается мутацией, а не словами: если хук молчит на отказах и с
# неработающим владельцем — значит молчал не от него, и весь свидетель ложно-зелёный.
#
# МУТАНТ ВЫБРАН НЕ С ПЕРВОГО РАЗА, И ЭТО ЗАПИСАНО. Первая редакция подавала `DENY_MARK_RE=' '`
# и нога покраснела: пробел в альтернативе делает выражение совпадающим с ЛЮБЫМ текстом, где
# есть пробел, — хук молчал не от владельца, а оттого, что исключалось всё. Мутант обязан НЕ
# совпадать ни с чем, иначе он проверяет обратное тому, ради чего поставлен.
mutant() {  # mutant <значение DENY_MARK_RE> <sid> → вывод хука на расшифровке из одних отказов
    mk_body "$TMP/mut-$2" "$D1" "$D2" "$D3" "$D1" "$D2" "$D3"
    printf '{"session_id":"%s","transcript_path":"%s","hook_event_name":"PreToolUse","tool_name":"Bash"}' \
        "$2" "$TMP/mut-$2" \
        | STATE_DIR="$TMP/state-$2" ERROR_TRACKER_DRAFT_DIR="$TMP/drafts-$2" DENY_MARK_RE="$1" bash "$HOOK" 2>&1
}
OUT=$(mutant '\AZZ_NE_SOVPADAET_NIKOGDA' smut1)
if [ -n "$OUT" ]; then ok; else bad "T7" "с неработающим владельцем хук всё равно молчит — T3 ничего не доказывает"; fi

# T7b: ОТСУТСТВИЕ библиотеки — названная деградация, а не тишина. Хук обязан ЖИТЬ (не умереть
# под set -u на необъявленном имени) и вернуться к поведению до 16 сентября 2026: считать отказы
# провалами.
#
# БИБЛИОТЕКУ НАДО УБРАТЬ ПО-НАСТОЯЩЕМУ, И ЭТО ВЫЯСНИЛОСЬ ПРОГОНОМ. Первая редакция подавала
# `DENY_MARK_RE=''` и нога покраснела: `${DENY_MARK_RE:-умолчание}` подставляет умолчание и на
# ПУСТОМ значении, то есть библиотека работала как обычно. Пустая переменная отсутствия файла не
# изображает. Поэтому здесь уводится и путь библиотеки, и `HOME` — иначе хук подберёт копию,
# установленную в `~/.claude/hooks`, и ветка деградации снова не будет исполнена.
mk_body "$TMP/mut-nolib" "$D1" "$D2" "$D3" "$D1" "$D2" "$D3"
mkdir -p "$TMP/nohome"
OUT=$(printf '{"session_id":"snolib","transcript_path":"%s","hook_event_name":"PreToolUse","tool_name":"Bash"}' \
        "$TMP/mut-nolib" \
      | HOME="$TMP/nohome" DENY_LIB="$TMP/net-takogo-faila.sh" \
        STATE_DIR="$TMP/state-nolib" ERROR_TRACKER_DRAFT_DIR="$TMP/drafts-nolib" bash "$HOOK" 2>&1)
if [ -n "$OUT" ]; then ok; else bad "T7b" "без библиотеки хук молчит — деградация не к прежнему поведению, а в слепоту"; fi

echo "deny mark lib tests: $PASS/$((PASS+FAIL)) passed"
exit $(( FAIL != 0 ))
