#!/usr/bin/env bash
# test_adv3_kia_empty_base_percent.sh
#
# АТАКА: при пустой базе отчёт печатает «| хранится | 0 | 100% |».
#
# Доля у остальных уровней считается через `pct()` (строка 339), и при `stored == 0` она
# честно даёт «—». А доля строки «хранится» не считается вовсе — она вписана словом `100%`
# (строка 352). На пустом входе таблица утверждает 100% от нуля, стоя рядом с четырьмя
# прочерками: единственная строка с долей — та, где доли нет.
#
# Вход достижим не только «пустой базой»: `LESSONS_DIR`, указанный на каталог без `*.md`
# (переименовали, смонтировали не то), проходит проверку `[ -d "$LESSONS" ]` и даёт код 0 —
# «отработал, находок нет». `measurement-due.sh` ставит отметку прогона на неделю.
#
# Ожидание: доля нуля не называется числом 100%.

set -uo pipefail

REPO="$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/../.." && pwd -P)"
SCRIPT="$REPO/scripts/knowledge-instrument-audit.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
L="$TMP/lessons"; S="$TMP/state"; mkdir -p "$L" "$S"

FAIL=0
fail() { printf 'ПРОВАЛ: %s\n' "$*"; FAIL=1; }
ok()   { printf 'ok: %s\n' "$*"; }

out="$(LESSONS_DIR="$L" STATE_DIR="$S" bash "$SCRIPT" 2>&1)"; rc=$?
report="$(cat "$S/knowledge-instrument.md" 2>/dev/null)"
table="$(grep -E '^\| (хранится|доходило|\*\*действует|из них)' <<< "$report")"

printf -- '--- вывод замера (rc=%s) ---\n%s\n--- таблица уровней ---\n%s\n' "$rc" "$out" "$table"

if grep -qE '^\| хранится \| 0 \| 100% \|' <<< "$table"; then
    fail "пустая база: «хранится 0», доля 100% — при том что все остальные доли в той же таблице «—»"
else
    ok "доля нуля не названа числом"
fi

exit "$FAIL"
