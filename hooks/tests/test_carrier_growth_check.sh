#!/usr/bin/env bash
# test_carrier_growth_check.sh — прирост носителей рода называется на границе хода вместе
# с файлом, который его принёс.
#
# Повод (D322). 6 сентября 2026 пять раз за день агент писал текст, который сам становился
# ложным носителем: нога теста искала имя мёртвой функции литералом и стала единственным
# совпадением, контрпример рода F сделал носителем файл контрпримеров, цикл ожидания нашёл
# сам себя, комментарий процитировал фразу, которую ищет «Проверка» пункта. Все пять
# замечены через часы — стражем «Проверки», собеседником или случаем, но не в тот момент,
# когда правку ещё дёшево переписать.
#
# Корень: между «агент пишет текст» и «прибор читает дерево» нет обратной связи. Приборы
# работают верно, связи нет.
#
# ЦЕНА И ПРЕДЕЛ. Прогон реестра родов — 3,5 с, и один род почти не дешевле полного: общая
# часть в чтении дерева. На каждую запись файла это неприемлемо, поэтому сигнал стоит на
# границе хода. Между письмом и сигналом остаётся один ход — предел назван, условие снятия
# в пункте.
#
# Источник чисел подменяем (CARRIER_CMD): иначе тест стоил бы 3,5 с и зависел от живого
# дерева, то есть проверял бы не себя, а состояние репозитория в момент прогона.
set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
HOOK="$HOOKS_DIR/carrier-growth-check.sh"
PASS=0; FAIL=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# Прибор-фикстура: печатает то, что положили в файл ответа.
mk_probe() { printf '#!/usr/bin/env bash\ncat %s\n' "$1" > "$TMP/probe.sh"; chmod +x "$TMP/probe.sh"; }

# CLAUDSOUL_ROOT задаётся явно: корень хука больше не выводится из cwd, и без него ноги
# сверяли бы фикстуру с настоящим деревом ClaudSoul, а гейт по cwd закрыл бы хук молча.
# Контракт paths-lib (`:=`) уважает заданное окружением.
run() {  # run <каталог состояния>
    printf '{"session_id":"cg","cwd":"%s"}' "$TMP" \
      | STATE_DIR="$1" CLAUDSOUL_ROOT="$TMP" CARRIER_CMD="$TMP/probe.sh" bash "$HOOK" 2>/dev/null
}
assert_contains()  { if grep -qi -- "$2" <<< "$1"; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); echo "FAIL [$3]: нет «$2» в: ${1:0:200}"; fi; }
assert_not_contains(){ if grep -qi -- "$2" <<< "$1"; then FAIL=$((FAIL+1)); echo "FAIL [$3]: лишнее «$2» в: ${1:0:200}"; else PASS=$((PASS+1)); fi; }

S="$TMP/state"; mkdir -p "$S"

# --- T1: первый прогон только запоминает и молчит ------------------------------
# Иначе на любой чистой машине страж закричал бы о «приросте» с нуля.
printf 'РОД F · носителей: 2\n  · механизм uninstall.sh\n  · страж hooks/tests/test_a.sh\n' > "$TMP/ans"
mk_probe "$TMP/ans"
OUT=$(run "$S")
assert_not_contains "$OUT" "прирост" "T1: первый прогон молчит"

# --- T2: прирост называется вместе с родом И новым файлом ----------------------
printf 'РОД F · носителей: 3\n  · механизм uninstall.sh\n  · страж hooks/tests/test_a.sh\n  · страж hooks/tests/test_new.sh\n' > "$TMP/ans"
OUT=$(run "$S")
assert_contains "$OUT" "test_new.sh" "T2: новый носитель назван поимённо"
assert_contains "$OUT" "F" "T2b: род назван"

# --- T3: повтор без изменений молчит -------------------------------------------
# Без этой ноги страж кричал бы каждый ход после первого прироста.
OUT=$(run "$S")
assert_not_contains "$OUT" "прирост" "T3: без изменений — тишина"

# --- T4: убыль носителей не считается приростом --------------------------------
printf 'РОД F · носителей: 1\n  · механизм uninstall.sh\n' > "$TMP/ans"
OUT=$(run "$S")
assert_not_contains "$OUT" "прирост" "T4: убыль — не повод для тревоги"

# --- T6: счётчик внутри строки носителя приростом НЕ является --------------------
# Строка носителя несёт числа («невидимо 358», «подстановок=2», «hash_value:183»), и они
# меняются от правок, не меняющих носителя. Сравнение строк целиком читало это как прирост:
# 6 сентября 2026 uninstall.sh назывался новым ТРИ хода подряд, потому что его «невидимо»
# росло вместе с числом файлов дерева. Повторный сигнал о том же носителе обучает себя не
# читать — потому нога и заведена.
S6="$TMP/state6"; mkdir -p "$S6"
printf 'РОД F · носителей: 1\n  · механизм uninstall.sh  hooks/*.sh: в поле зрения 96, невидимо 357\n' > "$TMP/ans"
run "$S6" >/dev/null                       # первый прогон запоминает
printf 'РОД F · носителей: 1\n  · механизм uninstall.sh  hooks/*.sh: в поле зрения 96, невидимо 358\n' > "$TMP/ans"
OUT=$(run "$S6")
assert_not_contains "$OUT" "прирост" "T6: вырос счётчик, а не число носителей — тишина"

# --- T7: НОВЫЙ носитель в том же файле по-прежнему называется --------------------
# Отрицательный контроль к T6: вычёркивание чисел не должно глушить настоящую находку.
printf 'РОД F · носителей: 2\n  · механизм uninstall.sh  hooks/*.sh: в поле зрения 96, невидимо 358\n  · механизм install.sh  templates/*: в поле зрения 7, невидимо 3\n' > "$TMP/ans"
OUT=$(run "$S6")
assert_contains "$OUT" "install.sh" "T7: настоящий новый носитель назван"

# --- T8: цифра в ИМЕНИ файла не стирается, разные файлы не схлопываются ----------
# Первая редакция вычёркивания стёрла числа ВЕЗДЕ: test_adv5_scan стал test_adv#_scan, а
# test_adv2_bump и test_adv3_bump сделались одним ключом — второй носитель исчезал бы молча.
S8="$TMP/state8"; mkdir -p "$S8"
printf 'РОД A · носителей: 1\n  · тест hooks/tests/test_adv2_bump.sh  извлечений=3\n' > "$TMP/ans"
run "$S8" >/dev/null
printf 'РОД A · носителей: 2\n  · тест hooks/tests/test_adv2_bump.sh  извлечений=3\n  · тест hooks/tests/test_adv3_bump.sh  извлечений=4\n' > "$TMP/ans"
OUT=$(run "$S8")
assert_contains "$OUT" "test_adv3_bump" "T8: сосед с другой цифрой в имени — отдельный носитель"

# --- T9: смена формата ключа молчит, а не зовёт ко всему дереву -------------------
# Снимок прежнего формата несопоставим с новым, и comm объявляет приростом ВСЁ: первая
# редакция дала 47 «новых» разом. Это смена системы координат, а не находка.
S9="$TMP/state9"; mkdir -p "$S9"
printf 'старый-формат-ключа\nhooks/старое.sh  подстановок=1\n' > "$S9/carrier-snapshot.txt"
printf 'РОД B · носителей: 1\n  · hooks/новое.sh  подстановок=2\n' > "$TMP/ans"
OUT=$(run "$S9")
assert_not_contains "$OUT" "прирост" "T9: снимок чужого формата — молчание и перезапись"
assert_contains "$(head -n 1 "$S9/carrier-snapshot.txt")" "v2-tail-numbers" "T9b: снимок перезаписан в нынешнем формате"

# --- T10: прерванная запись не оставляет ПОЛОВИННОГО снимка (род H) --------------
# ДВЕ ПРЕДЫДУЩИЕ РЕДАКЦИИ ЭТОЙ НОГИ БЫЛИ ЗЕЛЕНЫ ПО НЕВЕРНОЙ ПРИЧИНЕ, и обе названы:
#  · первая проверяла целость снимка при восьми ОДНОВРЕМЕННЫХ прогонах. Предмет не тот:
#    `CUR` приходит от прибора, читающего одно дерево, поэтому обе сессии пишут одинаковое
#    содержимое — победитель гонки не важен, находка не теряется;
#  · вторая убивала прогон через 50 мс, а полный прогон длится 626 мс (замерено): хук не
#    доходил до записи, снимок оставался прежним, и это засчитывалось как успех при ЛЮБОЙ
#    реализации записи.
# Настоящее последствие наблюдалось вживую: половинный снимок из одной строки версии
# читается как «формат тот, носителей нет», и следующий ход объявляет приростом всё дерево —
# 47 носителей разом, 6 сентября 2026. Достижимость измерена: неатомарная запись 20 001
# строки, прерванная через 4 мс после НАЧАЛА записи, оставляет в файле 1 строку.
# Поэтому ждём не время, а ПРИЗНАК начала записи: появился tmp либо снимок начал меняться.
S10="$TMP/state10"; mkdir -p "$S10"
SNAPF="$S10/carrier-snapshot.txt"
printf 'v2-tail-numbers\nстарый-ключ  подстановок=#\n' > "$SNAPF"
SNAP_BEFORE=$(shasum < "$SNAPF" | cut -d' ' -f1)
{ echo 'РОД F · носителей: 20000'; for i in $(seq 1 20000); do echo "  · механизм файл-$i.sh  подстановок=1"; done; } > "$TMP/ans"
printf '{"session_id":"cg","cwd":"%s"}' "$TMP" \
  | STATE_DIR="$S10" CLAUDSOUL_ROOT="$TMP" CARRIER_CMD="$TMP/probe.sh" bash "$HOOK" >/dev/null 2>&1 &
CGPID=$!
for _ in $(seq 1 6000); do
    ls "$S10"/carrier-snapshot.txt.tmp.* >/dev/null 2>&1 && break
    [ "$(shasum < "$SNAPF" 2>/dev/null | cut -d' ' -f1)" != "$SNAP_BEFORE" ] && break
    kill -0 "$CGPID" 2>/dev/null || break
    perl -e 'select(undef,undef,undef,0.005)' 2>/dev/null || sleep 0.01
done
kill -9 "$CGPID" 2>/dev/null
wait "$CGPID" 2>/dev/null
LINES=$(grep -c . "$SNAPF" 2>/dev/null) || LINES=0
FIRST=$(head -n 1 "$SNAPF" 2>/dev/null)
# Допустимы ровно два исхода: прежний снимок (2 строки) либо новый целиком (20001).
# Всё между ними — половинная запись, ради которой нога и заведена.
if [ "$FIRST" = "v2-tail-numbers" ] && { [ "$LINES" -eq 2 ] || [ "$LINES" -ge 20001 ]; }; then
    PASS=$((PASS+1))
else
    FAIL=$((FAIL+1)); echo "FAIL [T10]: половинный снимок после прерванной записи — строк $LINES, первая «${FIRST}»"
fi
# Временный файл после `kill -9` остаться МОЖЕТ — процесс не успел его убрать, и это не
# дефект: читается только сам снимок. Требовать уборки от убитого процесса значило бы
# проверять не тот предмет — ровно та ошибка, что уже сделана дважды выше.
# Мир возвращаем: следующие ноги ждут маленький ответ прибора.
printf 'РОД F · носителей: 1\n  · механизм uninstall.sh  hooks/*.sh: в поле зрения 96, невидимо 357\n' > "$TMP/ans"

# --- T5: отказ прибора отличим от «прироста нет» — и НЕ печатается на Stop -------
# Молчание на сломанном приборе неотличимо от молчания на чистом дереве (род B), но канал
# «additionalContext на Stop» здесь запрещён: отказ прибора — состояние ПОСТОЯННОЕ, а Stop
# с непустым additionalContext перезапускает ход (8 пустых ходов подряд, 7 сентября 2026).
# Отказ уходит в очередь pending-alerts.txt, её поднимает pending-alerts-surface на следующем
# UserPromptSubmit — канал видимый в VSCode и ход не перезапускающий.
printf '#!/usr/bin/env bash\nexit 3\n' > "$TMP/probe.sh"; chmod +x "$TMP/probe.sh"
OUT=$(run "$S")
assert_not_contains "$OUT" "additionalContext" "T5: отказ НЕ печатается на Stop — ход не перезапускается"
assert_contains "$(cat "$S/pending-alerts.txt" 2>/dev/null)" "НЕ ПРОВЕРЕН" "T5b: отказ лёг в очередь видимого канала"
# T5c — нога, ради которой правка: ПОВТОР того же отказа очередь не растит. Без дросселя фон
# просто переехал бы из одного канала в другой.
: > "$S/pending-alerts.txt"
run "$S" >/dev/null
assert_not_contains "$(cat "$S/pending-alerts.txt" 2>/dev/null)" "НЕ ПРОВЕРЕН" "T5c: повтор постоянного отказа гасится дросселем сессии"

# --- T6: путь проекта с ПРОБЕЛОМ — своя команда зовётся без сборки строкой -------
# Рамка этой ноги отличается от прочих намеренно: здесь CARRIER_CMD НЕ задан, то есть
# исполняется ветка, которой пользуется бой. Дефект был найден живым прогоном, а не тестом:
# прочие ноги подменяют прибор фикстурой в пути без пробелов и потому слепы к нему.
SP="$TMP/with space/repo"
mkdir -p "$SP/scripts"
printf '#!/usr/bin/env python3\nprint("РОД F · носителей: 1")\nprint("  · механизм uninstall.sh")\n' \
    > "$SP/scripts/defect-class-carriers.py"
S6="$TMP/state6"; mkdir -p "$S6"
OUT=$(printf '{"session_id":"cg","cwd":"%s"}' "$SP" \
      | STATE_DIR="$S6" CLAUDSOUL_REPO="$SP" bash "$HOOK" 2>/dev/null)
assert_not_contains "$OUT" "НЕ ПРОВЕРЕН" "T6: путь с пробелом — прибор отработал, а не упал"

echo "carrier growth check: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
