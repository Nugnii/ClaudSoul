#!/usr/bin/env bash
# АТАКА: предположенная дата входа затвердевает в измеренный возраст.
#
# knowledge-instrument-audit.sh:251-259 помечает пункт, чья дата входа НЕ ЗАПИСАНА
# (вердикт `candidate`, поля `instrument_assessed` нет), пометкой «дата входа не
# записана» — ровно чтобы не выдать предположение за замер. Но в том же прогоне
# предположенная дата пишется в реестр (строка 290). На ВТОРОМ прогоне пункт уже
# «в реестре», ledger_guessed для него не заполняется, и та же ячейка показывает
# «0 дн.» — измеренный возраст, которого никто не мерил.
#
# Вход тот же, отчёт другой. Часы пункта пошли не в день разбора, а в день первого
# прогона замера — то есть D106 возвращается через реестр: пункт вечно молод, порог
# 30 дней не догоняет никогда, пока прогон повторяется чаще, чем раз в 30 дней
# (а он повторяется раз в 7 — scripts/measurements.tsv).
set -uo pipefail

REPO="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)}"
AUDIT="$REPO/scripts/knowledge-instrument-audit.sh"
FAILED=0
ok()  { printf '  ✓ %s\n' "$1"; }
bad() { printf '  ✗ %s: %s\n' "$1" "$2"; FAILED=1; }

T=$(mktemp -d); L="$T/l"; S="$T/s"; mkdir -p "$L" "$S"
trap 'rm -rf "$T"' EXIT

cat > "$L/pattern-cand.md" <<'EOF'
---
outcome: error
status: active
confidence: 4
impact: 5
confirmed_count: 28
instrument_verdict: candidate   # выразим, инструмента ещё нет
description: Кандидат, у которого дата разбора не записана
---
Тело.
EOF

run() { LESSONS_DIR="$L" STATE_DIR="$S" bash "$AUDIT" >/dev/null 2>&1; RC=$?; ROW=$(grep 'pattern-cand' "$S/knowledge-instrument.md" 2>/dev/null); }

echo "--- прогон 1 ---"
run; R1="$ROW"; echo "$R1"
echo "--- прогон 2 (вход НЕ менялся) ---"
run; R2="$ROW"; echo "$R2"

# T1: пометка «дата входа не записана» обязана пережить второй прогон — вход тот же.
if grep -q 'дата входа не записана' <<< "$R1"; then
    ok "T1a прогон 1 честно говорит: дата входа не записана"
else
    bad "T1a" "прогон 1 не поставил пометку — атака собрана неверно: $R1"
fi
if grep -q 'дата входа не записана' <<< "$R2"; then
    ok "T1b пометка пережила второй прогон"
else
    bad "T1b" "второй прогон на ТОМ ЖЕ входе выдал предположенную дату за измеренный возраст: [$R2]"
fi

# T2: отчёт не должен меняться сам по себе — вход между прогонами не трогали.
if [ "$R1" = "$R2" ]; then
    ok "T2 два прогона на одном входе дают одну строку"
else
    bad "T2" "строка отчёта изменилась без изменения входа:
       было: $R1
       стало: $R2"
fi

echo
[ "$FAILED" -eq 0 ] && { echo "PASS"; exit 0; } || { echo "FAIL"; exit 1; }
