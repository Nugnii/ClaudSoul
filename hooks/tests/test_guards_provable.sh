#!/usr/bin/env bash
# test_guards_provable.sh — мета-тест: страж, чьё срабатывание никогда не доказано,
# не считается стражем.
#
# Зачем. За четыре релиза подряд (v1.12.0-v1.12.3) проверка молчала по неверной
# причине, и каждый раз на её молчание ссылались как на факт:
#   v1.12.0 — метрика считала строки лога сессиями, «0% принятия» было артефактом;
#   v1.12.1 — страж загорался ровно при СОБЛЮДЕНИИ контракта, то есть всегда;
#   v1.12.2 — страж проверял присутствие файла в коммите вместо содержания;
#   v1.12.3 — та же проверка спрашивала только с README, план и архитектуру пропускала.
#
# Общее у всех четырёх: результат проверки был структурно независим от того, что
# она якобы проверяла. Молчание неотличимо от «проверил и чисто» ровно до тех пор,
# пока не показано, что эта проверка вообще СПОСОБНА загореться.
#
# Отсюда правило, вынесенное из текста в механизм: у каждого хука, который что-то
# инжектит или спрашивает (`additionalContext` / `permissionDecision`), обязан быть
# тест, и в нём обязано быть утверждение о СРАБАТЫВАНИИ — не только о тишине.
# Тест из одних `assert_empty` доказывает лишь, что хук молчит; он молчал бы и будучи
# пустым файлом.
#
# Чего этот тест НЕ гарантирует — важно, чтобы не переоценить его так же, как
# переоценивали предыдущие. Он не ловит случай, когда утверждение о срабатывании
# есть, но фикстура не соответствует живым данным: ровно так прошли v1.12.1
# (фикстура «complete» ставила `- [x]`, чего нет ни в одном реальном скилле) и
# v1.12.2. Против этого класса — `test_guards_live.sh`, прогон по настоящему дереву.
set -uo pipefail

TESTS_DIR="$(cd "$(dirname "$0")" && pwd)"
HOOKS_DIR="$(cd "$TESTS_DIR/.." && pwd)"

PASS=0
FAIL=0
FAILED=()

# Словарь утверждений. Собран по живым тестам, а не придуман: первая версия знала
# только `assert_contains`/`assert_empty` и дала четыре ложных срабатывания —
# `assert_nonsilent`, `ok`/`no` и прочие локальные хелперы она не видела. Мета-тест,
# судящий о смысле по имени функции, — сам проверка со слабой связью с предметом,
# поэтому словарь расширяемый и намеренно не считает неоднозначные (`assert_rc`:
# код возврата не говорит, был вывод или нет).
# `denied|fired|blocked` — имена хелперов, чьё ИМЯ и есть утверждение «страж сработал»
# (8 сентября 2026). Без них `test_publish_guard` числился недоказанным при девяти
# зелёных ногах: он проверяет отказ через свой `denied "$OUT"`, а словарь искал `ok` в
# начале строки — там оно стоит после `then`. Признак был снят с ВИДА строки, а роль у
# неё другая (pattern-marker-matches-form-not-role — тот же корень, что чинили здесь же
# 2 сентября 2026 на объявлениях хелперов).
# ПРОВЕРЕНО ЧИСЛОМ: такой хелпер в дереве один, вердикт по остальным 50 стражам не
# изменился — расширение не размывает признак, а добавляет ему известную форму.
# Третья форма — ожидаемое РЕШЕНИЕ хука в позиции сравнения (10 сентября 2026). Тест
# сторожа секретов зовёт свой хелпер `chk "имя" "$(run …)" deny`, и ни один из перечней
# выше его не узнавал: мета-страж объявлял «проверок срабатывания нет» при пяти проверках
# на отказ. Ложность доказана мутацией — поломка хука даёт 5 провалов из 11, то есть тест
# настоящий, а молчал признак.
# Перечень здесь ЗАКОННО закрыт, в отличие от перечня форм ассертов: `allow|deny|ask` —
# полный словарь `permissionDecision` из контракта Claude Code, он принадлежит платформе и
# не растёт от того, как пишут тесты (тот же довод, что у контрпримера
# `pattern-subject-checked-by-enumeration`: расширения файлов и подкоманды — закрытые
# словари системы, а не открытая речь).
# ПРОВЕРЕНО ЧИСЛОМ: расширение засчитывает один новый тест из 51, вердикт по остальным 50
# не изменился.
FIRE_PATTERNS='assert_contains|assert_fires|assert_not_empty|assert_nonsilent|assert_output|(^|[;&|][[:space:]]*)ok([[:space:]]|;|$)|ok\(|\b(denied|fired|blocked)[[:space:]]+"|[[:space:]](deny|ask)$|permissionDecision.*(deny|ask)|\[[[:space:]]+-n[[:space:]]+"?\$\('
# Тишина у стражей с хелпером-утверждением выражается РОЛЬЮ, а не словом: «сработал →
# это плохо», то есть `denied "$OUT"; then bad`. Признак взят по связке, а не по одному
# имени: голое `denied` значит обратное (проверку срабатывания) и уже засчитано выше.
# Симметрично `FIRE_PATTERNS`: ожидаемая ТИШИНА в позиции сравнения — прочерк в конце
# строки (`chk "обычный код" "$(run …)" -`). Без этой формы мета-страж, научившись видеть
# ожидание `deny`, тут же объявил у того же теста «нет проверки тишины» при шести таких
# ногах: половину признака дополнили, половину нет — и вердикт остался ложным, только с
# другой формулировкой.
SILENT_PATTERNS='assert_empty|assert_silent|assert_not_contains|assert_no_output|(^|[;&|][[:space:]]*)no([[:space:]]|;|$)|no\(|\b(denied|fired|blocked)[[:space:]]+"[^"]*";[[:space:]]*then[[:space:]]+bad|[[:space:]]-$|\[[[:space:]]+-z[[:space:]]+"?\$\('

for hook in "$HOOKS_DIR"/*.sh; do
    base=$(basename "${hook%.sh}")
    case "$base" in *-lib) continue ;; esac

    # Страж = хук, который что-то говорит наружу. Строку ищем в КОДЕ, не в
    # комментариях: первая версия ловила `pre-compact-finalizer` по его же
    # комментарию «Silent: no systemMessage, no additionalContext» — то есть по
    # фразе, утверждающей обратное. Детектор, читающий комментарии как код,
    # измеряет текст о предмете, а не предмет.
    grep -q 'additionalContext\|permissionDecision' <<< "$(grep -vE '^[[:space:]]*#' "$hook" 2>/dev/null)" || continue

    # Свой тест. Сначала по соглашению об имени (`test_<hook>.sh` с подчёркиваниями) —
    # grep-угадывание брало ПЕРВЫЙ файл, упомянувший имя хука, и для session-collector
    # подсунуло чужой `test_disagreement_loop.sh`, где он лишь упоминается.
    conv="$TESTS_DIR/test_$(printf '%s' "$base" | tr '-' '_').sh"
    if [ -f "$conv" ]; then
        test_files="$conv"
    else
        # Имя хука ищем в КОДЕ кандидата, не в комментарии: две привязки из десяти
        # держались на упоминании в чужом комментарии (test_stopping_message_names_outcome.sh:34,
        # test_module_doc_registration_claims.sh:194). Форма herestring, а не труба:
        # `grep -vE … | grep -q` под `set -uo pipefail` отдаёт 141 при найденном совпадении
        # (SIGPIPE — класс D59), и `|| continue` прочёл бы это как «не найдено».
        test_files=""
        for cand in "$TESTS_DIR"/test_*.sh; do
            case "$cand" in *test_guards_provable.sh) continue ;; esac
            grep -q -- "$base" <<< "$(grep -vE '^[[:space:]]*#' "$cand" 2>/dev/null)" || continue
            test_files="${test_files}${test_files:+
}$cand"
        done
    fi

    if [ -z "$test_files" ]; then
        FAIL=$((FAIL + 1))
        FAILED+=("$base — теста нет вообще; его молчание ничего не значит")
        continue
    fi
    ALL_TESTS="${ALL_TESTS:-}${test_files}"$'\n'

    # Считаем только строки-ВЫЗОВЫ: комментарии и строки ОБЪЯВЛЕНИЯ хелпера
    # доказательством не являются. Замер 2 сентября 2026: у девяти стражей ВСЕ совпадения
    # словаря приходились на объявление (`assert_contains() {`), то есть тест из одних
    # утверждений о тишине проходил мета-тест за то, что в нём объявлена функция с нужным
    # именем. Тот же корень чинили в test_named_limit_has_exit (D269): признак снят с вида
    # текста, а различать надо роль строки.
    # КОНТРПРИМЕРЫ признака: (а) определение и вызов на одной строке (`f() { :; }; f x`)
    # засчитается вызовом — формы в дереве нет; (б) питоновское `def assert_contains(...)`
    # в heredoc под bash-форму объявления не подходит и тоже засчитается вызовом.
    fire=0
    silent=0
    while IFS= read -r tf; do
        [ -n "$tf" ] || continue
        calls=$(grep -vE '^[[:space:]]*#' "$tf" 2>/dev/null \
            | grep -vE '^[[:space:]]*(function[[:space:]]+)?[A-Za-z_][A-Za-z0-9_]*[[:space:]]*\([[:space:]]*\)')
        n=$(grep -cE "$FIRE_PATTERNS" <<< "$calls" | head -1)
        fire=$((fire + ${n:-0}))
        n=$(grep -cE "$SILENT_PATTERNS" <<< "$calls" | head -1)
        silent=$((silent + ${n:-0}))
    done <<EOF
$test_files
EOF

    if [ "$fire" -eq 0 ]; then
        FAIL=$((FAIL + 1))
        FAILED+=("$base — тест есть, но проверок срабатывания в нём нет (только тишина): пустой файл прошёл бы так же")
        continue
    fi
    if [ "$silent" -eq 0 ]; then
        FAIL=$((FAIL + 1))
        FAILED+=("$base — есть проверка срабатывания, но нет проверки тишины: страж, который горит всегда, тоже бесполезен (v1.12.1)")
        continue
    fi
    PASS=$((PASS + 1))
done

# Неполнота словаря НАЗВАНА ЧИСЛОМ (D338), а не закрыта дописыванием имён. Утверждение
# узнаётся по РОЛИ: функция теста, чьё тело трогает счётчики PASS/FAIL либо зовёт ok/bad, —
# хелпер-утверждение, какое бы имя она ни носила. Те из них, чьего имени словарь выше не
# знает, печатаются поимённо. Это мера, а не вердикт: стражи выше доказаны словарём, но
# новый тест, написанный ТОЛЬКО такими хелперами, придёт сюда «без проверок срабатывания»,
# и верный ответ ему — не строка в перечне, а имя здесь. Форма `has`/`hasnt` (12 файлов
# дерева) в тестах стражей не встречается — потому и не ловилась: измерено 12 сентября 2026.
OUTSIDE=$(printf '%s' "${ALL_TESTS:-}" | sort -u | while IFS= read -r tf; do
    [ -n "$tf" ] && [ -f "$tf" ] || continue
    awk '/^[a-z_][a-z0-9_]*[[:space:]]*\(\)[[:space:]]*\{/ { n=$1; sub(/[[:space:]]*\(\).*/,"",n); b=$0; f=1; if ($0 ~ /\}[[:space:]]*$/) d=1; else next }
         f && !d && /^\}/ { d=1 }
         f && !d { b=b " " $0; next }
         f && d { f=0; d=0; if (b ~ /(FAIL|PASS)=\$\(\(|[^a-z_](bad|ok)([[:space:]]|$|;|\))/) print n }' "$tf"
done | sort -u | while IFS= read -r h; do
    [ -n "$h" ] || continue
    grep -qF -- "$h" <<< "$FIRE_PATTERNS|$SILENT_PATTERNS" && continue
    printf '%s ' "$h"
done)
OUTSIDE_N=$(printf '%s' "$OUTSIDE" | wc -w | tr -d ' ')

echo ""
echo "=================================="
echo "guards-provable: $PASS доказано, $FAIL без доказательства"
echo "словарь утверждений: хелперов вне словаря в тестах стражей — ${OUTSIDE_N:-0}${OUTSIDE:+ (${OUTSIDE% })} — мера неполноты перечня, не вердикт"
if [ "$FAIL" -gt 0 ]; then
    echo ""
    for f in "${FAILED[@]}"; do echo "  ✗ $f"; done
fi
echo "=================================="
exit $(( FAIL != 0 ))
