#!/usr/bin/env bash
# test_instrument_contract.sh — у инструмента объявлен результат и проверка результата.
#
# Результат: в `scripts/` нет инструментов без строк «# Результат:» и «# Проверка результата:».
# Проверка результата: этот тест; красный — значит инструменты без контракта есть.
#
# Повод — поправка владельца 28 августа 2026: «всегда должен быть результат и проверка его
# наличия при построении инструмента… Измерять ради измерения это фигня. Замечать и не
# исправлять — фигня». Замер в тот же день: инструментов в scripts/ — 28, с объявленным
# результатом — 0.
#
# Почему тест, а не напоминание. Ровно в этой сессии измерено, что напоминания читаются и
# не меняют действия (минимум 9 случаев из 20). Красный тест нельзя прочитать и пройти мимо.
#
# Почему «состояние мира», а не «работа прибора»: при формулировке «назвал нарушителей»
# перечисление засчитывается как завершённая работа, и находка остаётся жить. Именно так
# producer-filter-check нашёл пять хуков без отсева и ничего не починил.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO" || exit 1

PASS=0; FAIL=0
missing=""
for f in scripts/*.sh scripts/*.py; do
    [ -f "$f" ] || continue
    case "$f" in scripts/publish/*) continue ;; esac
    # Строки контракта должны быть НАСТОЯЩИМИ комментариями, а не текстом внутри литерала.
    # Поймано на себе 28 августа 2026: первая вставка легла ВНУТРЬ docstring семи питоновских
    # файлов, и страж засчитал её — признак совпадал с упоминанием, тот же класс, что чинили
    # утром предикатом command_uses. Для .py контракт требуется ДО открытия docstring.
    _head=$(head -40 "$f")
    case "$f" in
        *.py)
            _cut=$(printf '%s\n' "$_head" | awk '/^[[:space:]]*"""/ { exit } { print }')
            ;;
        *) _cut="$_head" ;;
    esac
    grep -qE '^#[[:space:]]*Результат:' <<< "$_cut" || { missing="$missing $f"; continue; }
    grep -qE '^#[[:space:]]*Проверка результата:' <<< "$_cut" || missing="$missing $f"
done

if [ -z "${missing# }" ]; then
    PASS=$((PASS+1))
else
    FAIL=$((FAIL+1))
    echo "FAIL: инструменты без объявленного результата и проверки:"
    for f in $missing; do echo "  · $f"; done
    echo "  Добавь в шапку две строки:"
    echo "    # Результат: <состояние мира, которое считается достигнутым>"
    echo "    # Проверка результата: <команда, дающая 0 при достижении>"
    echo "  Результат — СОСТОЯНИЕ МИРА, не работа прибора: «нарушителей ноль», а не «назвал нарушителей»."
fi

# Отрицательный контроль: страж обязан ловить подделку, иначе он декоративен.
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/scripts"
printf '#!/usr/bin/env bash\n# просто скрипт\n' > "$TMP/scripts/fake.sh"
_probe=$(head -40 "$TMP/scripts/fake.sh" | grep -cE '^#[[:space:]]*Результат:')
if [ "$_probe" = "0" ]; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); echo "FAIL: признак не отличает файл без контракта"; fi

echo ""
echo "instrument contract tests: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
