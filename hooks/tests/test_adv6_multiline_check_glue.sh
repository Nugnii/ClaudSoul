#!/usr/bin/env bash
# test_adv6_multiline_check_glue.sh — completion-gate ложно краснит закрытый пункт,
# чья «Проверка» — многострочная команда в бэктиках.
#
# АТАКА. Контракт пункта: **Проверка.** `команда` → 0. Одна пара бэктиков может
# охватывать НЕСКОЛЬКО строк — контракт этого не запрещает. Разборщик берёт
# `[^`]+` (жадно, поперёк переводов строк даже без re.S — класс символов, не точка),
# затем cmd = " ".join(cm.group(1).split()) СКЛЕИВАЕТ строки в одну команду через
# пробел. Семантика меняется: две команды скрипта становятся одной строкой с чужим
# разбором аргументов.
#
# ВХОД. Пункт ☑ D250 с проверкой, ЗЕЛЁНОЙ как двухстрочный скрипт:
#     a=ok
#     [ "$a" = ok ]        (rc 0 — присвоили и проверили)
# После " ".join(split): `a=ok [ "$a" = ok ]` — bash берёт a=ok временным env для
# команды `[`, а $a раскрывается ТЕКУЩЕЙ оболочкой (пусто) → `[ "" = ok ]` → rc 1.
#
# ОЖИДАНИЕ. Пункт закрыт корректно (его проверка зелёная) → completion-gate молчит.
# ФАКТ. Гейт склеивает команду, получает rc 1 и печатает ложный алерт «закрытие
#       расходится со своим же критерием». Тот же корень — в scripts/backlog-archive.sh
#       (та же связка `[^`]+` + " ".join(split)): пункт вечно не переносится.
set -u
HOOK="$(cd "$(dirname "$0")/.." && pwd)/completion-gate.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

STATE="$TMP/state"; mkdir -p "$STATE"
BACKLOG="$TMP/BACKLOG.md"
CWD="$TMP/proj"; mkdir -p "$CWD"   # без BACKLOG.md — локальный бэклог не подхватится

# Пункт ☑ с многострочной проверкой (перевод строки ВНУТРИ пары бэктиков).
{
  printf '# BACKLOG\n\n'
  printf '### D250 закрытый пункт ☑\n'
  printf '**Проверка.** `a=ok\n'
  printf '[ "$a" = ok ]` → 0\n'
  printf '\nОписание.\n'
} > "$BACKLOG"

# Санитарная проба: проверка ЗЕЛЁНАЯ как двухстрочный скрипт (то, что написал автор).
if ! bash -c 'a=ok
[ "$a" = ok ]'; then
    echo "SKIP: авторский скрипт сам по себе не зелёный — тест некорректен"
    exit 0
fi

INPUT=$(printf '{"session_id":"advsix","cwd":"%s"}' "$CWD")
OUT=$(printf '%s' "$INPUT" | STATE_DIR="$STATE" CG_BACKLOG="$BACKLOG" bash "$HOOK" 2>/dev/null)

if printf '%s' "$OUT" | grep -q 'completion-gate'; then
    echo "FAIL (attack succeeds): гейт ложно краснит корректно закрытый пункт с"
    echo "  многострочной проверкой — команда склеена \" \".join(split), rc искажён."
    echo "--- вывод гейта ---"
    printf '%s\n' "$OUT"
    exit 1
fi

echo "PASS: гейт не алертит на корректно закрытый пункт"
exit 0
