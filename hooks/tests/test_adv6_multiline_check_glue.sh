#!/usr/bin/env bash
# test_adv6_multiline_check_glue.sh — completion-gate ложно краснит закрытый пункт,
# чья «Проверка» — многострочная команда в бэктиках.
#
# АТАКА. Контракт пункта: **Проверка.** `команда` → 0. Одна пара бэктиков может
# охватывать НЕСКОЛЬКО строк — контракт этого не запрещает. Разборщик берёт
# `[^`]+` (жадно, поперёк переводов строк даже без re.S — класс символов, не точка),
# затем cmd = " ".join(cm.group(1).split()) СКЛЕИВАЕТ строки в одну команду через
# пробел. Семантика меняется: две команды скрипта становятся одной строкой с чужим
# разбором аргументов.
#
# ВХОД. Пункт ☑ D250 с проверкой, ЗЕЛЁНОЙ как двухстрочный скрипт:
#     a=ok
#     [ "$a" = ok ]        (rc 0 — присвоили и проверили)
# После " ".join(split): `a=ok [ "$a" = ok ]` — bash берёт a=ok временным env для
# команды `[`, а $a раскрывается ТЕКУЩЕЙ оболочкой (пусто) → `[ "" = ok ]` → rc 1.
#
# ОЖИДАНИЕ. Пункт закрыт корректно (его проверка зелёная) → completion-gate молчит.
# ФАКТ. Гейт склеивает команду, получает rc 1 и печатает ложный алерт «закрытие
#       расходится со своим же критерием». Тот же корень — в scripts/backlog-archive.sh
#       (та же связка `[^`]+` + " ".join(split)): пункт вечно не переносится.
set -u
. "$(dirname "$0")/alerts-read.sh"
# РАМКУ ЗАДАЁТ ТЕСТ (D334, D1179): дверь вложенности вызывающего снимается — ключ кольца BACKLOG_CMD_RUNNING остаётся (D503).
unset BACKLOG_CHECKS_NESTED
HOOK="$(cd "$(dirname "$0")/.." && pwd)/completion-gate.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

STATE="$TMP/state"; mkdir -p "$STATE"
BACKLOG="$TMP/BACKLOG.md"
CWD="$TMP/proj"; mkdir -p "$CWD"   # без BACKLOG.md — локальный бэклог не подхватится

# Пункт ☑ с многострочной проверкой (перевод строки ВНУТРИ пары бэктиков).
{
  printf '# BACKLOG\n\n'
  printf '### D250 закрытый пункт ☑\n'
  # «Результат.» обязателен у ☑ с 17 сентября 2026 (D431). Без неё гейт краснеет ПО СВОЕЙ
  # причине — «закрытие без Результата», — а не по предмету этой ноги, и свидетель судил бы
  # чужое. Поймано 20 сентября 2026, когда свидетелю починили канал вердикта: прежде он
  # читал stdout, всегда пустой, и не видел ни одной жалобы гейта вообще.
  printf '**Результат.** Есть.\n'
  printf '**Проверка.** `a=ok\n'
  printf '[ "$a" = ok ]` → 0\n'
  printf '\nОписание.\n'
} > "$BACKLOG"

# Санитарная проба: проверка ЗЕЛЁНАЯ как двухстрочный скрипт (то, что написал автор).
if ! bash -c 'a=ok
[ "$a" = ok ]'; then
    echo "SKIP: авторский скрипт сам по себе не зелёный — тест некорректен"
    exit 0
fi

# КАНАЛ ВЕРДИКТА — ОЧЕРЕДЬ, А НЕ STDOUT (D342, 20 сентября 2026).
#
# Здесь стояло `OUT=$(… bash "$HOOK")` и вердикт по stdout. Гейт на Stop в stdout НЕ ПИШЕТ
# НИЧЕГО и не может: непустой `additionalContext` на Stop перезапускает ход, поэтому
# постоянное состояние уходит в очередь `pending-alerts.txt` (правило «на Stop постоянное
# состояние печатать запрещено», `hooks/throttle-lib.sh`). Замер того дня: на ЗАВЕДОМО
# красном закрытии stdout пуст, а в очереди лежит «⚠️ completion-gate: закрытие расходится
# со своим же критерием».
#
# Значит вердикт свидетеля был невыполним по построению: пустой stdout не содержит строки
# «completion-gate» НИКОГДА, при любом поведении гейта. Свидетель был зелен не оттого, что
# атака отбита, а оттого, что он слушал молчащий провод — и описанную им атаку не поймал бы
# и на живом гейте. Канал взят у ВЛАДЕЛЬЦА: так же читает свой гейт `test_completion_gate.sh:54`.
INPUT=$(printf '{"session_id":"advsix","cwd":"%s"}' "$CWD")
alerts_clear "$STATE" || true
printf '%s' "$INPUT" | STATE_DIR="$STATE" CG_BACKLOG="$BACKLOG" bash "$HOOK" >/dev/null 2>&1
OUT=$(alerts_of "$STATE")

# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: гейт обязан ЗАГОВОРИТЬ на заведомо красном закрытии. Без него
# свидетель зеленел и с ВЫХОЛОЩЕННЫМ гейтом — молчание есть ровно то, что производит
# заглушка. Дроссель гейта дедуплицирует по составу расхождения в пределах сессии, поэтому
# контрольный прогон идёт со своим STATE_DIR и своей очередью.
_ctlstate="$TMP/state-ctl"; mkdir -p "$_ctlstate"
_bad="$TMP/BACKLOG-bad.md"
{
  printf '# BACKLOG\n\n'
  printf '### D999 ☑ красное закрытие\n'
  printf '**Результат.** заявлено, но неправда\n'
  printf '**Проверка.** `false` → 0\n'
} > "$_bad"
printf '%s' "$INPUT" | STATE_DIR="$_ctlstate" CG_BACKLOG="$_bad" bash "$HOOK" >/dev/null 2>&1
_ctl=$(alerts_of "$_ctlstate")
if ! grep -q 'completion-gate' <<< "$_ctl"; then
    echo "FAIL [рамка не собралась]: гейт промолчал на ЗАВЕДОМО красном закрытии D999 —"
    echo "     значит он мёртв, и его молчание о многострочной проверке ничего не значит."
    echo "--- очередь контрольного прогона ---"
    printf '%s\n' "$_ctl"
    exit 1
fi

if printf '%s' "$OUT" | grep -q 'completion-gate'; then
    echo "FAIL (attack succeeds): гейт ложно краснит корректно закрытый пункт с"
    echo "  многострочной проверкой — команда склеена \" \".join(split), rc искажён."
    echo "--- вывод гейта ---"
    printf '%s\n' "$OUT"
    exit 1
fi

echo "PASS: гейт не алертит на корректно закрытый пункт"
exit 0
