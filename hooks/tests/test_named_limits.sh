#!/usr/bin/env bash
# test_named_limits.sh — прибор называет предел, чьё условие снятия НАСТУПИЛО.
# СУДИТ: scripts/named-limits.py
#
# Результат: `named-limits.py --check` находит и НАЗЫВАЕТ предел с позеленевшей проверкой
#            снятия, молчит о пределе с красной, и отличает сломанную проверку от обеих
# Проверка результата: bash hooks/tests/test_named_limits.sh даёт 0
#
# ЗАЧЕМ. Договор результата инструмента (ADR-021): у каждого прибора есть свидетель, красный
# на выпотрошенном приборе. У `named-limits.py` его не было — шапка обещала этот файл, а
# файла не существовало, и `instrument-result-measured.sh` числил прибор как «НЕТ СНИМКА».
#
# ТРИ НОГИ, И ТРЕТЬЯ ВАЖНЕЕ ДВУХ. Зелёная проверка снятия и красная — очевидная пара. Третья
# нога судит СЛОМАННУЮ проверку: 20 сентября 2026 две проверки снятия этого дерева зеленели
# ОТТОГО, ЧТО НЕ РАБОТАЛИ (producer с кодом 2 в конвейере; поиск имени, находящий себя), и
# прибор объявлял условие наступившим. Слить «наступило» с «судить нечем» значит пустить два
# состояния мира по одному проводу — корень R6.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
TOOL="$REPO/scripts/named-limits.py"
[ -f "$TOOL" ] || { echo "SKIP: прибора нет — это другое дерево"; exit 0; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }
command -v git >/dev/null 2>&1 || { echo "SKIP: нет git"; exit 0; }

SB=$(mktemp -d) || { echo "BROKEN: нет временного каталога"; exit 2; }
trap 'rm -rf "$SB"' EXIT
mkdir -p "$SB/scripts"
git -C "$SB" init -q . 2>/dev/null || { echo "BROKEN: песочница не стала репозиторием"; exit 2; }

cat > "$SB/arrived.md" <<'EOF'
# Подставной механизм с наступившим условием.
НАЗВАННЫЙ ПРЕДЕЛ: прибор не умеет того-то.
Условие снятия: появится такой-то механизм.
Проверка снятия: `true`
EOF
cat > "$SB/holding.md" <<'EOF'
# Подставной механизм с держащимся пределом.
НАЗВАННЫЙ ПРЕДЕЛ: прибор не умеет иного.
Условие снятия: появится иной механизм.
Проверка снятия: `false`
EOF
cat > "$SB/broken.md" <<'EOF'
# Подставной механизм со СЛОМАННОЙ проверкой снятия.
НАЗВАННЫЙ ПРЕДЕЛ: прибор не умеет третьего.
Условие снятия: появится третий механизм.
Проверка снятия: `exit 2`
EOF
# Отказ подготовки ГРОМКИЙ: без индекса `git ls-files` пуст, прибор не найдёт ни одного
# объявления и честно ответит «не отработал» кодом 2 — а нога T1 ждёт кода 1 и покраснеет
# с непонятной причиной. Немая подготовка превращает поломку рамки в загадку (D465).
git -C "$SB" add -A >/dev/null 2>&1 \
    || { echo "подготовка мира не удалась: hooks/tests/test_named_limits.sh:$LINENO (git add)" >&2; exit 2; }

run() { CLAUDSOUL_REPO="$SB" python3 "$1" --check 2>&1; }

OUT=$(run "$TOOL"); RC=$?

fail=0
# T1 — наступивший назван ПОИМЁННО, а не числом: адрес и есть результат прибора.
grep -q 'arrived\.md' <<< "$OUT" || { echo "FAIL T1: наступивший предел не назван адресом"; fail=1; }
# T2 — держащийся не назван.
grep -q 'holding\.md' <<< "$OUT" && { echo "FAIL T2: держащийся предел объявлен наступившим"; fail=1; }
# T3 — сломанная проверка отделена от обеих: своё слово, а не молчание и не «наступило».
grep -q 'broken\.md' <<< "$OUT" || { echo "FAIL T3: сломанная проверка снятия не названа"; fail=1; }
grep -q 'СУДИТЬ НЕЧЕМ' <<< "$OUT" || { echo "FAIL T3b: сломанная не отделена от наступившей"; fail=1; }
# T4 — код отказа при находке.
[ "$RC" -eq 1 ] || { echo "FAIL T4: при находке код $RC, а не 1"; fail=1; }

# T5 — КОНТРОЛЬ РАМКИ: без единого объявления прибор обязан сказать «не отработал» (код 2),
# а не «находок нет». Без этой ноги свидетель зеленел бы на приборе, потерявшем признак.
rm -f "$SB"/arrived.md "$SB"/holding.md "$SB"/broken.md
# Тот же громкий отказ: если индекс не обновился, подставные пределы останутся видны
# прибору, он ответит кодом 1, и нога ниже прочтёт это как «прибор не сказал не отработал».
git -C "$SB" add -A >/dev/null 2>&1 \
    || { echo "подготовка мира не удалась: hooks/tests/test_named_limits.sh:$LINENO (git add)" >&2; exit 2; }
CLAUDSOUL_REPO="$SB" python3 "$TOOL" --check >/dev/null 2>&1
[ "$?" -eq 2 ] || { echo "FAIL T5: на пустом дереве прибор не сказал «не отработал»"; fail=1; }

# T6–T9 — РОЛЬ СТРОКИ В КОДЕ НАЗЫВАЕТ РАЗБОРЩИК ЯЗЫКА, А НЕ ЕЁ ВИД (D1341, корень R3). Прежний признак «строка на #»
# не видел предел в строке документации (37 строк в 12 файлах дерева, среди них пределы самого прибора) и принимал за
# объявление текст фикстуры в heredoc. Четыре файла — четыре роли; имена в выводе различают их поимённо.
cat > "$SB/doc.py" <<'EOF'
"""Подставной модуль.

НАЗВАННЫЙ ПРЕДЕЛ: модуль не умеет четвёртого.
Условие снятия: появится четвёртый механизм.
Проверка снятия: `true`
"""
EOF
cat > "$SB/data.py" <<'EOF'
FIXTURE = """
# НАЗВАННЫЙ ПРЕДЕЛ: текст подложного файла, а не объявление этого модуля.
# Условие снятия: никогда.
# Проверка снятия: `true`
"""
EOF
# Текст фикстуры бывает только в тестах и пробах (скептик D1341, H2): тот же heredoc вне `hooks/tests/` — программа
# автора, которую скрипт пишет в файл и исполняет, и её комментарий — настоящее объявление (T10).
mkdir -p "$SB/hooks/tests"
cat > "$SB/hooks/tests/fixture.sh" <<'OUTER'
cat > "$W/a.sh" <<'FIX'
# НАЗВАННЫЙ ПРЕДЕЛ: текст фикстуры, пишущейся в файл.
# Условие снятия: никогда.
# Проверка снятия: `true`
FIX
OUTER
cat > "$SB/tool.sh" <<'OUTER'
cat > "$P" <<'PYPROG'
# НАЗВАННЫЙ ПРЕДЕЛ: программа автора не умеет шестого.
# Условие снятия: появится шестой механизм.
# Проверка снятия: `true`
PYPROG
python3 "$P"
OUTER
# T11 — комментарий, цитирующий форму heredoc, его не открывает (скептик D1341, H1): без этого метка из комментария
# закрывалась на конце НАСТОЯЩЕГО heredoc ниже, и объявление между ними уходило в «текст фикстуры».
cat > "$SB/hooks/tests/quoted.sh" <<'OUTER'
# Раньше здесь стояло: cat > "$W/x" <<'EOF'
# НАЗВАННЫЙ ПРЕДЕЛ: тест не умеет седьмого.
# Условие снятия: появится седьмой механизм.
# Проверка снятия: `true`
cat > "$W/x" <<'EOF'
данные
EOF
OUTER
# T12 — метка, которая не закрылась (форма heredoc внутри строки), тела не имеет: хвост файла остаётся кодом.
cat > "$SB/hooks/tests/unclosed.sh" <<'OUTER'
MSG="пример: cat > a <<ZZ"
# НАЗВАННЫЙ ПРЕДЕЛ: тест не умеет восьмого.
# Условие снятия: появится восьмой механизм.
# Проверка снятия: `true`
OUTER
cat > "$SB/embedded.sh" <<'EOF'
python3 - <<'PY'
# НАЗВАННЫЙ ПРЕДЕЛ: код в heredoc не умеет пятого.
# Условие снятия: появится пятый механизм.
# Проверка снятия: `true`
PY
EOF
# Проверка снятия, зовущая сам прибор: вложенный вызов обязан отдать счёт и проверок не исполнять — иначе кольцо.
cat > "$SB/nested.md" <<EOF
НАЗВАННЫЙ ПРЕДЕЛ: проверка снятия зовёт сам прибор.
Условие снятия: вложенный вызов скажет, что проверок не исполнял.
Проверка снятия: \`grep -q "вложенный вызов" <<< "\$(CLAUDSOUL_REPO="$SB" python3 "$TOOL")"\`
EOF
git -C "$SB" add -A >/dev/null 2>&1 \
    || { echo "подготовка мира не удалась: hooks/tests/test_named_limits.sh:$LINENO (git add)" >&2; exit 2; }
OUT=$(run "$TOOL")
grep -q 'doc\.py' <<< "$OUT" || { echo "FAIL T6: предел в строке документации .py не виден"; fail=1; }
grep -q 'data\.py' <<< "$OUT" && { echo "FAIL T7: #-строка внутри литерала с данными принята за объявление"; fail=1; }
grep -q 'hooks/tests/fixture\.sh' <<< "$OUT" && { echo "FAIL T8: текст heredoc теста, пишущегося в файл, принят за объявление"; fail=1; }
grep -q '· tool\.sh' <<< "$OUT" || { echo "FAIL T10: программа автора в heredoc вне тестов принята за фикстуру"; fail=1; }
grep -q 'hooks/tests/quoted\.sh' <<< "$OUT" || { echo "FAIL T11: комментарий, цитирующий heredoc, ослепил объявление ниже"; fail=1; }
grep -q 'hooks/tests/unclosed\.sh' <<< "$OUT" || { echo "FAIL T12: незакрытая метка ослепила хвост файла"; fail=1; }
grep -q 'embedded\.sh' <<< "$OUT" || { echo "FAIL T8b: комментарий в коде heredoc интерпретатора не виден"; fail=1; }
# Судится строка НАСТУПИВШЕГО («  · файл»), а не любое упоминание: на кольце прежней редакции тот же файл назван
# сорванной проверкой («  ⚠ файл … СРОК ИСТЁК»), и нога, искавшая имя, зеленела бы на обоих.
{ grep -q '· nested\.md' <<< "$OUT" && ! grep -q '⚠ nested\.md' <<< "$OUT"; } \
    || { echo "FAIL T9: вложенный вызов прибора исполнил проверки либо не ответил"; fail=1; }

[ "$fail" -eq 0 ] && echo "OK: наступивший назван, держащийся молчит, сломанная отделена, роль строки — у разборщика"
exit "$fail"
