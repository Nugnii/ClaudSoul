#!/usr/bin/env bash
# test_completion_gate_open_coverage.sh — гейт судит ВСЕ открытые пункты, а пропуск
# называет поимённо.
#
# Повод измерен 6 сентября 2026. `CG_MAX_OPEN=16` при 26 открытых пунктах означало, что
# последние десять — D303, D304, D305, D306, D307, D308, D310, D309, D313, D314, то есть
# ровно все пункты-роды — не проверялись НИ РАЗУ. Наружу уходил только «#CG_STATUS
# partial», который читает лишь bash-сторона для решения о кэше; имён пропущенных не
# получал никто. Тот же файл в соседней ветке держит обратный принцип дословно: «Не
# исполняем и НЕ молчим: молчаливый пропуск неотличим от „проверено, чисто“»
# (completion-gate.sh:216) — до счётного лимита он не дошёл.
#
# Цена была двойной: зелёная «Проверка» у любого из десяти оставалась незамеченной, и
# журнал cg-open-fired.jsonl (знаменатель замера open-check-precision, он же условие
# закрытия D264) не получал записей от этих пунктов вовсе.
#
# Счётный предел снят: цену Stop ограничивает ВРЕМЯ, а не число пунктов. Замер 6 сентября
# 2026 на живом файле: 26 команд суммарно 22,34 с, из них четыре прогона реестра родов —
# 13,6 с. Бюджет поднят до 60 с — запас против роста числа пунктов, а не против их цены.
#
# Как и соседи, файл поднимает хук через `env -u BACKLOG_CHECKS_NESTED`: по этому маркеру
# гейт выходит первой строкой, и тест был бы зелёным из рук и красным из-под гейта.
set -uo pipefail
. "$(dirname "$0")/alerts-read.sh"

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
HOOK="$HOOKS_DIR/completion-gate.sh"
PASS=0; FAIL=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/state"

# Канал — очередь pending-alerts (systemMessage снят 12 сентября 2026: в мобильном клиенте
# рендерится построчно); предмет ног прежний. Дроссель гейта сбрасывается: T2 и T7 повторяют
# состав T1 и T4 в той же сессии, и без сброса очередь пустела бы по дросселю, а не по делу.
run() { # $1 backlog; далее — переменные окружения вида ИМЯ=знач
    local bl="$1"; shift
    alerts_clear "$TMP/state" || true
    rm -f "$TMP/state"/completion-gate-fired-*.jsonl 2>/dev/null || true
    printf '{"session_id":"cgcov","cwd":"/"}' \
      | env -u BACKLOG_CHECKS_NESTED CG_BACKLOG="$bl" CG_LOCAL_BACKLOG="" \
        STATE_DIR="$TMP/state" "$@" bash "$HOOK" >/dev/null 2>&1
    alerts_of "$TMP/state"
}

assert_contains() { # $1 haystack, $2 needle, $3 label
    if grep -q -- "$2" <<< "$1"; then PASS=$((PASS+1));
    else FAIL=$((FAIL+1)); echo "FAIL [$3]: нет «$2» в: $1"; fi
}
assert_not_contains() { # $1 haystack, $2 needle, $3 label
    if grep -q -- "$2" <<< "$1"; then FAIL=$((FAIL+1)); echo "FAIL [$3]: лишнее «$2» в: $1";
    else PASS=$((PASS+1)); fi
}

# Фикстура: N открытых пунктов с КРАСНОЙ «Проверкой» и один зелёный в самом конце.
# Красные молчат по контракту, поэтому в выводе обязан быть ровно последний.
make_backlog() { # $1 путь, $2 сколько красных перед зелёным
    local f="$1" n="$2" i
    : > "$f"
    for i in $(seq 1 "$n"); do
        printf -- '- ☐ **D9%02d** красный пункт %s.\n  **Проверка.** `false`\n\n' "$i" "$i" >> "$f"
    done
    printf -- '- ☐ **D999** зелёная у открытого — дефект, обязан быть назван.\n  **Проверка.** `true`\n' >> "$f"
}

# --- T1. Пункт ЗА прежним счётным пределом судится и называется -----------------
# 20 красных + зелёный двадцать первым: при CG_MAX_OPEN=16 до него не доходили никогда.
make_backlog "$TMP/far.md" 20
OUT=$(run "$TMP/far.md")
# Форма важна, а не факт упоминания: при счётном лимите D999 тоже попадал бы в вывод —
# но как «не проверен». Мутация «вернуть CG_MAX_OPEN=16» ловится ровно этой строкой.
assert_contains "$OUT" "D999 (зелёная у открытого)" "T1: зелёная у открытого за пределом 16 ИСПОЛНЕНА и названа"

# --- T2. Ближний пункт называется по-прежнему (положительный контроль) ----------
# Если T1 позеленеет от того, что разбор вообще перестал работать, T2 это покажет.
make_backlog "$TMP/near.md" 2
OUT=$(run "$TMP/near.md")
assert_contains "$OUT" "D999 (зелёная у открытого)" "T2: зелёная у открытого в пределах лимита названа"

# --- T3. Красные молчат: гейт не стал болтливым -------------------------------
assert_not_contains "$OUT" "D901" "T3: красная «Проверка» открытого пункта молчит"

# --- T4. Обрыв по ВРЕМЕНИ называет пропущенных поимённо ------------------------
# Бюджет 0 с обрывает на первом же пункте. Молчаливый пропуск неотличим от «чисто»,
# поэтому имена обязаны быть в выводе.
OUT=$(run "$TMP/far.md" CG_BUDGET_OPEN=0)
assert_contains "$OUT" "D901" "T4: при обрыве по времени пропущенный назван поимённо"
assert_not_contains "$OUT" "(зелёная у открытого)" "T4b: при нулевом бюджете НИЧЕГО не исполнено — и это сказано, а не показано зеленью"

# --- T5. Обрыв назван словом, а не только кодом статуса ------------------------
assert_contains "$OUT" "не хватило бюджета" "T5: обрыв назван человекочитаемо"

# --- T6. Лимит закрытых пунктов НЕ тронут (CG_MAX=3, D-номер ниже порога не в счёт) ---
# У ☑ своя цена и свой предел, закреплённый test_adv4_cg_maxruns_false_green.
: > "$TMP/closed.md"
for i in 1 2 3 4; do
    printf -- '- ☑ **D8%02d** закрытый %s.\n  **Проверка.** `false`\n\n' "$i" "$i" >> "$TMP/closed.md"
done
OUT=$(run "$TMP/closed.md")
assert_contains "$OUT" "D801" "T6: закрытые с красной «Проверкой» называются"

# --- T7. Служебная строка протокола НЕ уходит владельцу как находка -------------
# Повод (11 сентября 2026). Каналов у гейта четыре (`#CG_STATUS`, `#CG_UNTRUSTED`,
# `#CG_OPEN`, `#CG_UNCHECKED`), а фильтр вырезал ТРИ: последний заведён позже и в перечень
# имён не попал. Строка «#CG_UNCHECKED D901 D902» уходила в канал «закрытие расходится со
# своим же критерием» — то есть обвиняла ОТКРЫТЫЕ пункты в неверном ЗАКРЫТИИ, да ещё
# текстом про метку ☑, которой у них нет. Ровно тот же выход, что у D901/D902 в T4-T5:
# там это законное «не смотрели», здесь — ложная тревога поверх него.
# Нога держит ПРАВИЛО, а не имя канала: ни одна строка с префиксом `#CG_` не должна
# доходить до владельца, включая каналы, которых ещё нет.
# Вывод берётся СВОИМ прогоном, а не `$OUT` от T6: там фикстура из ЗАКРЫТЫХ пунктов, и
# «закрытие расходится» у неё законно — первая редакция ноги упала именно на этом.
OUT7=$(run "$TMP/far.md" CG_BUDGET_OPEN=0)
assert_contains "$OUT7" "не хватило бюджета" "T7-контроль: фикстура та самая — обрыв по бюджету состоялся"
assert_not_contains "$OUT7" "#CG_" "T7: служебная строка протокола просочилась в сообщение владельцу"
assert_not_contains "$OUT7" "закрытие расходится" "T7b: открытые пункты обвинены в неверном ЗАКРЫТИИ"

# --- T8, T9. Ротация открытых (D1204) -------------------------------------------
# Обход в порядке файла обрывался бюджетом на одном месте, и хвост файла не проверялся ни на одной границе. Исполнение
# судится по журналу самих команд (`$TMP/rot.log`), а не по сообщению: рухнувший гейт сообщения не даёт и сошёл бы за
# «всё проверено». Два круга, а не один — мутант «номер прогона всегда 1» проходил первый круг и голодал со второго
# (скептик opus по 5176378e, M2).
unch() { grep -o 'не хватило бюджета: [D0-9 ]*' <<< "$1" | sed 's/^не хватило бюджета: //'; }
: > "$TMP/rot.md"; : > "$TMP/rot.log"
for i in 1 2 3 4; do printf -- '- ☐ **D70%s** открытый.\n  **Проверка.** `echo D70%s >> "%s"; sleep 0.4; false`\n\n' "$i" "$i" "$TMP/rot.log" >> "$TMP/rot.md"; done
for _n in 1 2 3 4 5 6 7 8; do run "$TMP/rot.md" CG_BUDGET_OPEN=0.6 >/dev/null; done
[ "$(grep -cx D704 "$TMP/rot.log")" -ge 2 ] && PASS=$((PASS+1)) \
    || { FAIL=$((FAIL+1)); echo "FAIL [T8]: последний пункт файла исполнен меньше двух раз за восемь границ — ротации нет ($(grep -cx D704 "$TMP/rot.log"))"; }
# T12 — пункт с двумя строками «Проверки», чья первая команда съедает бюджет, получает номер и уходит назад (скептик
# opus по 5176378e, M1): без номера он стоял первым вечно, и соседний пункт исполнялся один раз.
: > "$TMP/m1.log"
printf -- '- ☐ **D610** дешёвый.\n  **Проверка.** `echo D610 >> "%s"; false`\n\n- ☐ **D611** две строки.\n  **Проверка.** `sleep 0.8; false`\n  **Проверка.** `false`\n\n- ☐ **D612** дешёвый.\n  **Проверка.** `false`\n' "$TMP/m1.log" > "$TMP/m1.md"
for _n in 1 2 3 4; do run "$TMP/m1.md" CG_BUDGET_OPEN=0.5 >/dev/null; done
[ "$(grep -cx D610 "$TMP/m1.log")" -ge 2 ] && PASS=$((PASS+1)) \
    || { FAIL=$((FAIL+1)); echo "FAIL [T12]: за пунктом с дорогой первой строкой сосед исполнен меньше двух раз за четыре границы"; }
# T9 — пункт, упёршийся в срок одной команды (CG_TIMEOUT), уходит назад, а не стоит первым вечно: его «Проверка» дороже
# бюджета, и без этого следующий за ним не проверялся бы никогда.
printf -- '- ☐ **D601** дорогой.\n  **Проверка.** `sleep 5`\n\n- ☐ **D602** дешёвый.\n  **Проверка.** `false`\n' > "$TMP/to.md"
OUT9a=$(run "$TMP/to.md" CG_BUDGET_OPEN=0.5 CG_TIMEOUT=1)
assert_contains "$(unch "$OUT9a")" "D602" "T9-контроль: первая граница съедена дорогим пунктом"
OUT9=$(run "$TMP/to.md" CG_BUDGET_OPEN=0.5 CG_TIMEOUT=1)
assert_not_contains "$(unch "$OUT9")" "D602" "T9: пункт за упёршимся в срок проверен на следующей границе"
# T10 — сломанный журнал ротации называется, а не читается пустым (D1204, род B): тихий откат к порядку файла и есть
# дефект пункта. Нечитаемый журнал перезаписывается тем же прогоном — следующая граница молчит.
for _r in "$TMP/state"/completion-gate-*.rotation; do [ -f "$_r" ] && printf 'не json' > "$_r"; done
assert_contains "$(run "$TMP/rot.md" CG_BUDGET_OPEN=0.6)" "журнал ротации не читается" "T10: сломанный журнал ротации назван"
assert_not_contains "$(run "$TMP/rot.md" CG_BUDGET_OPEN=0.6)" "журнал ротации" "T10б: журнал перезаписан тем же прогоном — следующая граница молчит"
# T10в — в ТОЙ ЖЕ сессии (дроссель не сброшен) сломанный журнал всё равно назван: без канала в составе ключа дросселя
# граница с тем же числом непроверенных гасла как повтор (скептик opus по 5176378e, L1).
run_thr() { alerts_clear "$TMP/state"
    printf '{"session_id":"cgthr","cwd":"/"}' | env -u BACKLOG_CHECKS_NESTED CG_BACKLOG="$1" CG_LOCAL_BACKLOG="" \
        STATE_DIR="$TMP/state" CG_BUDGET_OPEN=0.6 bash "$HOOK" >/dev/null 2>&1 || { echo "подготовка мира не удалась: hooks/tests/test_completion_gate_open_coverage.sh:$LINENO" >&2; exit 1; }; alerts_of "$TMP/state"; }
sed 's/rot\.log/rot2.log/' "$TMP/rot.md" > "$TMP/rot2.md"
assert_contains "$(unch "$(run_thr "$TMP/rot2.md")")" "D70" "T10в-контроль: первая граница сессии назвала непроверенных"
printf 'не json' > "$TMP/state/completion-gate-$(printf '%s' "$TMP/rot2.md" | cksum | awk '{print $1}').rotation"
assert_contains "$(run_thr "$TMP/rot2.md")" "журнал ротации не читается" "T10в: сломанный журнал назван и в той же сессии"
# T11 — команда «Проверки» не получает настроек гейта `CG_*` (D1204): проба, зовущая гейт вложенно, наследовала
# `CG_FIRED_LOG` — журнал под замком внешнего гейта — и ждала его на каждом вызове. Унаследованная настройка видна
# командой: зелёная у открытого пункта.
printf -- '- ☐ **D501** утечка настроек.\n  **Проверка.** `[ -n "${CG_FIRED_LOG:-}${CG_FILE:-}" ]`\n' > "$TMP/leak.md"
assert_not_contains "$(run "$TMP/leak.md")" "D501 (зелёная у открытого)" "T11: команда «Проверки» унаследовала настройки гейта CG_*"

echo "test_completion_gate_open_coverage: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
exit $?
