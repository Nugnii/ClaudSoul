#!/usr/bin/env bash
# test_attack_r3_own_structured_erased.sh — АТАКА: собственное длинное сообщение
# собеседника, размеченное ЕГО ЖЕ заголовками, стирается целиком.
#
# В END стоит `if ((doc || quoted >= 2) && blen >= 300) exit 0`. Порог 300 добавлен
# раундами 1 и 2, чтобы не гасла КОРОТКАЯ жалоба с приложением. Комментарий называет
# замер: «своя жалоба с приложением даёт 17 и 42 символа, настоящие пересылки — 3512
# и 7483. Порог 300 лежит в этом зазоре».
#
# В зазор не попал третий вид входа: СОБСТВЕННОЕ длинное сообщение с собственной
# разметкой. Собеседник, который в этом проекте пишет `## Что надо сделать` /
# `## Что не трогать` в постановке задачи, переваливает за 300 непробельных символов
# с первого же абзаца — и вся его речь обнуляется. Признак `doc` отличает не автора,
# а наличие решётки: собственный заголовок неотличим от чужого.
#
# Асимметрия цены, заявленная в шапке функции («ложное срабатывание пишет событие,
# пропуск не пишет ничего»), здесь работает против системы: теряется не шум, а прямая
# коррекция собеседника — «ты меня не так понял, я имел в виду первый вариант».
# Именно ту точку данных весь каскад L4 и собирает.
#
# Отличие от закрытой атаки раунда 2 (test_attack_r2_quote_erases_own.sh): там своя речь
# гибла от ДВУХ строк цитаты и порог 300 был ответом. Здесь порог пройден по существу —
# объём даёт сам собеседник, а не приложение, — и потому не спасает.

set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
LIB="$HOOKS_DIR/hook-input-lib.sh"
[ -f "$LIB" ] || { echo "FAIL: $LIB not found"; exit 1; }
# shellcheck source=/dev/null
source "$LIB"

PASS=0
FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

assert_keeps() {  # $1=текст $2=подстрока, обязанная остаться $3=имя
    local got; got=$(user_own_speech "$1")
    if grep -qF "$2" <<< "$got"; then ok
    else bad "$3" "'$2' стёрто, на выходе ${#got} символов"; fi
}

# Постановка задачи, написанная САМИМ собеседником: его заголовки, его текст,
# ни одной вставки. 379 непробельных символов — порог 300 пройден его же словами.
OWN_TASK="Смотри, распишу по разделам, чтобы не путаться

## Что надо сделать
Первый пункт про хуки, второй про тесты, третий про документацию, и всё это надо успеть сегодня.
Ещё раз повторю, потому что вчера получилось не то: правки только в тех файлах, что я перечислил.

## Что не трогать
Ничего из соседних каталогов, там чужой код и его ломать нельзя ни при каких обстоятельствах.

Ты меня не так понял в прошлый раз, я имел в виду именно первый вариант, а не второй."

# t0 — контроль: та же коррекция без заголовков слышна
assert_keeps "Ты меня не так понял в прошлый раз, я имел в виду именно первый вариант, а не второй." \
    "не так понял" "t0 bare correction kept"

# t1 — АТАКА: собственные заголовки стирают собственную коррекцию
assert_keeps "$OWN_TASK" "не так понял" "t1 own headers erase own correction"

# t2 — то же со своей таблицей: собеседник расписал задачу таблицей
OWN_TABLE="Распишу таблицей, так нагляднее

| файл | что сделать |
|------|-------------|
| hooks/a.sh | добавить проверку входа и покрыть её тестом в соседнем каталоге |
| hooks/b.sh | вынести общую часть в библиотеку, чтобы копия не разъезжалась |
| docs/c.md | описать оба изменения и сослаться на решение из журнала |

Ты меня не так понял в прошлый раз, я имел в виду именно первый вариант, а не второй."
assert_keeps "$OWN_TABLE" "не так понял" "t2 own table erases own correction"

# t3 — граница в другую сторону: пересылка ОБЯЗАНА гаситься и после починки
_pasted="## Чужая рецензия

$(printf 'Автор пишет длинно, абзац за абзацем, и так на много экранов подряд. %.0s' 1 2 3 4 5 6 7 8)
Автор считает, что это не совсем то, что нужно."
_got=$(user_own_speech "$_pasted")
if [ -z "$_got" ]; then ok
else bad "t3 pasted doc must stay silenced" "пересылка ушла как речь (${#_got} символов)"; fi

# t4 — та же дыра на оси состояния: своя жалоба в размеченном сообщении теряет stuck
ITR_LIB="$HOOKS_DIR/intrusiveness-state-lib.sh"
if [ -f "$ITR_LIB" ]; then
    TMP=$(mktemp -d)
    export ITR_STATE_DIR="$TMP"
    export STATE_DIR="$TMP"
    # shellcheck source=/dev/null
    source "$ITR_LIB" 2>/dev/null || true
    if command -v itr_compute_state >/dev/null 2>&1; then
        st=$(itr_compute_state "" "Распишу по разделам, чтобы не путаться

## Что уже пробовали
Первый пункт про хуки, второй про тесты, третий про документацию, и всё это надо успеть сегодня.
Ничего из соседних каталогов не трогали, там чужой код и его ломать нельзя ни при каких условиях.

## Что происходит сейчас
Опять не работает сборка, снова та же ошибка, третий заход подряд и ничего не меняется." 2>/dev/null)
        case "$st" in
            stuck*) ok ;;
            *) bad "t4 own stuck signal lost" "своя жалоба дала состояние: $st" ;;
        esac
    fi
fi

# t5 — сквозной: хук молчит на настоящей коррекции собеседника
HOOK="$HOOKS_DIR/reformulation-tracker.sh"
if [ -f "$HOOK" ] && command -v jq >/dev/null 2>&1; then
    TMP2=$(mktemp -d); mkdir -p "$TMP2/state"
    out=$(jq -nc --arg s r3o1 --arg p "$OWN_TASK" \
        '{session_id:$s,prompt:$p,transcript_path:""}' \
        | STATE_DIR="$TMP2/state" bash "$HOOK" 2>/dev/null)
    if grep -qF "КОРРЕКТИРУЕТ" <<< "$out"; then ok
    else bad "t5 hook loses real BACKWARD" "хук промолчал на прямой коррекции собеседника"; fi
fi

echo ""
echo "attack r3 own-structured-erased: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
