#!/usr/bin/env bash
# test_public_snapshot_marker.sh — свидетель признака «дерево неполно по построению».
#
# Предмет: маркер `.public-snapshot` ОТЛИЧАЕТ публичный снимок от рабочего дерева, и из-за
#          него тест, чей предмет изъят, печатает пропуск вместо провала — а без маркера
#          тот же тест на том же дереве краснеет.
# Результат: маркера нет в рабочем дереве (иначе один файл ослепляет весь набор), а в копии
#          с маркером живые ноги долга пропускаются с названной причиной.
# Проверка результата: bash hooks/tests/test_public_snapshot_marker.sh даёт 0.
#
# Зачем (15 сентября 2026). Публичный CI был красен с 30 августа, пять публикаций подряд:
# 10 тестов из 523 судили предметы, которые exclude.txt изымает (BACKLOG.md, ROOTS.md,
# scripts/probes/, подсистема публикации), и звали их отсутствие дефектом. Один канал нёс
# два состояния мира — «изъят по решению» и «пропал» (корень R6).
set -uo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$DIR/../.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# --- T1: в РАБОЧЕМ дереве маркера нет ни на диске, ни в индексе ------------------------
# Названный предел признака: файл с этим именем, положенный сюда, разом снимает проверки
# Условие снятия: у снимка появится своя рамка прогона, где неприменимые проверки не
# запускаются вовсе, — тогда и маркер, и эта нога станут не нужны.
# всех живых предметов. Поэтому его отсутствие — нога набора, а не устная договорённость.
# Предмет ноги — РАБОЧЕЕ дерево. В самом снимке маркер лежит по построению, и судить нечего:
# свидетель маркера едет наружу вместе со снимком и там обязан молчать, а не падать на себе.
UNIVERSE_ROOT="$REPO"; . "$REPO/hooks/lib/universe-lib.sh"
if universe_partial_tree; then
    universe_skip_note T1 "рабочее дерево (здесь сам снимок)"
else
    [ -e "$REPO/.public-snapshot" ] && bad T1 "маркер снимка лежит в рабочем дереве — живые проверки ослеплены" || ok
    if git -C "$REPO" ls-files --error-unmatch .public-snapshot >/dev/null 2>&1; then
        bad T1b "маркер снимка трекается git — он обязан появляться только в снимке"
    else ok; fi
fi

# --- T2: различение доказано ДВУМЯ входами --------------------------------------------
UNIVERSE_ROOT="$TMP/plain"; mkdir -p "$UNIVERSE_ROOT"
universe_partial_tree && bad T2 "дерево без маркера названо неполным" || ok
: > "$UNIVERSE_ROOT/.public-snapshot"
universe_partial_tree && ok || bad T2b "дерево с маркером неполным не названо"

# --- T3/T4: настоящий тест на копии дерева, где предмет изъят --------------------------
# Предмет берётся НАСТОЯЩИЙ (свидетель рабочего долга), а не выдуманная фикстура: фикстура
# беднее мира уже роняла здешние выводы трижды за сессию.
COPY="$TMP/copy"; mkdir -p "$COPY"
cp -R "$REPO/hooks" "$REPO/scripts" "$COPY"/ 2>/dev/null || { echo "подготовка мира не удалась: hooks/tests/test_public_snapshot_marker.sh:$LINENO" >&2; exit 1; }
rm -f "$COPY/BACKLOG.md"
VICTIM="$COPY/hooks/tests/test_backlog_item_shape.sh"
if [ ! -f "$VICTIM" ]; then
    bad T3 "в копии нет свидетеля рабочего долга — контроль не поставлен"
else
    # МУТАНТ ПЕРВЫМ: без маркера тот же тест на том же дереве обязан покраснеть. Без этой
    # ноги T3 зеленела бы на тесте, который и так зелен, и ничего бы не доказывала.
    OUT_NO=$(bash "$VICTIM" 2>&1); RC_NO=$?
    [ "$RC_NO" -ne 0 ] && ok || bad T4 "без маркера тест с изъятым предметом дал 0 — пропуск вызван не маркером"
    : > "$COPY/.public-snapshot"
    OUT_YES=$(bash "$VICTIM" 2>&1); RC_YES=$?
    [ "$RC_YES" -eq 0 ] && ok || bad T3 "под маркером тест не позеленел (код $RC_YES): $(printf '%s' "$OUT_YES" | grep -m2 FAIL)"
    grep -q 'SKIP' <<< "$OUT_YES" && ok || bad T3b "пропуск не назван словом SKIP — молчание неотличимо от «чисто»"
fi

echo "public snapshot marker: passed $PASS, failed $FAIL"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
