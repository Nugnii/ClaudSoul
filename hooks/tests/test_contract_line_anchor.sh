#!/usr/bin/env bash
# test_contract_line_anchor.sh — строка контракта пункта распознаётся по РОЛИ, а не по виду.
#
# Повод (1 сентября 2026). Архиватор отказался переносить закрытый D244, предъявив его
# «Проверкой» строку `. Источников два: канонический (`. Такой команды в пункте не было:
# в абзаце «Дефект» стоял литерал `**Проверка.**` в обратных кавычках — ОПИСАНИЕ механизма,
# — и разбор взял следующую пару кавычек за команду. Тот же регексп стоял в completion-gate,
# то есть строка шла в `bash -c` на каждом Stop.
#
# Признак с одним последствием: контрактная строка НАЧИНАЕТ строку файла (после отступа).
# То же сочетание в середине предложения — цитата, командой она не является никогда.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/state"
MARK="$TMP/RAN"

# Пункт, в теле которого литерал контрактной строки стоит ВНУТРИ inline-кода, а настоящая
# строка контракта — своя, отдельная и в начале строки.
cat > "$TMP/BACKLOG.md" <<BL
# BACKLOG

- ☑ **D900** Пункт, описывающий сам механизм контракта.
  **Дефект.** Команда берётся из обратных кавычек строки
  \`**Проверка.**\`. Источников два: канонический и локальный.
  **Результат.** Ничего.
  **Проверка.** \`touch $MARK\` → 0
BL

# 1-2. Архиватор: настоящая команда исполняется, ложная — нет, и перенос проходит.
cp "$TMP/BACKLOG.md" "$TMP/b1.md"; : > "$TMP/arch1.md"
OUT=$(BACKLOG_FILE="$TMP/b1.md" BACKLOG_ARCHIVE="$TMP/arch1.md" \
      bash "$REPO/scripts/backlog-archive.sh" run 2>&1)
[ -f "$MARK" ] && ok || bad T1 "настоящая «Проверка» не исполнилась: $OUT"
grep -q "Источников два" <<< "$OUT" && bad T2 "цитата принята за команду: $OUT" || ok

# 3-4. Гейт завершения: та же пара на том же пункте.
rm -f "$MARK"
OUT=$(printf '{"session_id":"anchor","cwd":"/"}' \
      | CG_BACKLOG="$TMP/BACKLOG.md" STATE_DIR="$TMP/state" \
        bash "$REPO/hooks/completion-gate.sh" 2>/dev/null)
[ -f "$MARK" ] && ok || bad T3 "гейт не исполнил настоящую «Проверку»"
grep -q "Источников два" <<< "$OUT" && bad T4 "гейт принял цитату за команду: $OUT" || ok

# 5-6. Пересчётчик показаний — третий носитель того же контракта. Правка 04c7f66 поставила
# якорь «в обоих носителях», а их четыре: scripts/backlog-refresh-readings.sh:73 и :87
# остались с жёстким `^`, и с 1 сентября 2026 (пункты стали элементами списка, поля ушли под
# отступ) он осматривал 0 показаний из 2, докладывая «все показания открытых пунктов свежие».
# Случай ловит ОБА его якоря: показание не найдено → осмотрено 0; строка «Последнее
# показание» не найдена → old=None → пункт объявлен разошедшимся.
cat > "$TMP/reading.md" <<'BL'
# BACKLOG

- ◐ **D901** Открытый пункт с показанием под отступом.
  **Показание.** `echo 42`
  **Последнее показание (2026-09-01).** 42
BL
OUT=$(BACKLOG_FILE="$TMP/reading.md" bash "$REPO/scripts/backlog-refresh-readings.sh" --check 2>&1)
RC=$?
[ "$RC" -eq 0 ] && ok || bad T5 "показание под отступом не распознано (rc=$RC): $OUT"
grep -q "осмотрено 1 из 1" <<< "$OUT" && ok || bad T6 "осмотрено не 1 из 1: $OUT"

# 10-11. Страж условий возврата — ЧЕТВЁРТЫЙ носитель того же контракта, и до 3 сентября
# 2026 якоря у него не было вовсе: `grep -m1 -F` брал литерал где угодно в строке, а `sed`
# — следующую пару кавычек. Правка 04c7f66 поставила якорь «в обоих носителях», их было
# четыре, и до этого она не дошла. Носитель вписан в реестр, чтобы следующий переписчик
# не снял якорь молча: реестр держит класс, а не память о нём.
rm -f "$MARK"
mkdir -p "$TMP/ret/scripts" "$TMP/ret/hooks"
cp "$REPO/scripts/backlog-return-check.sh" "$TMP/ret/scripts/"
cp "$REPO/hooks/backlog-lib.sh" "$TMP/ret/hooks/"
cp "$REPO/hooks/timeout-lib.sh" "$TMP/ret/hooks/"   # страж возврата исполняет команды с бюджетом (D369); без библиотеки — код 2
cat > "$TMP/ret/BACKLOG.md" <<BL
# BACKLOG

- ☐ **D903** пункт, чьё тело ОПИСЫВАЕТ контракт, а своего условия не имеет
  Дефект. Строка **Проверка возврата:** \`touch $MARK\` в середине предложения —
  описание механизма, а не контракт пункта.
BL
OUT=$(cd "$TMP" && HOME=/nonexistent-home bash "$TMP/ret/scripts/backlog-return-check.sh" 2>&1)
[ -f "$MARK" ] && bad T10 "страж возврата исполнил цитату: $OUT" || ok
grep -q "ПРОВЕРКИ НЕТ:.*D903" <<< "$OUT" && ok || bad T11 "страж возврата объявил зелёным пункт без условия: $OUT"

# 7-9. Род E в реестре дефектных родов: носителей нет, и признак различает формы.
# Реестр заведён после того, как род укусил дважды (04c7f66 и 28 августа) — здесь он
# держится проверкой, а не памятью.
python3 "$REPO/scripts/defect-class-carriers.py" --genus E >/dev/null 2>&1 \
    && ok || bad T7 "род E нашёл носителей жёсткого якоря в дереве"
# T8/T9: признак ловит жёсткую форму и НЕ ловит здоровую — иначе «0 носителей» ничего не значит
_probe() {
    python3 - "$1" <<'PYE'
import re, sys
W = "Показание|Проверка|Результат|Вердикт|Последнее|Дефект|Корень|Сигнал"
print(1 if re.search(r"\^\\\*\\\*(?:" + W + r")", sys.argv[1]) else 0)
PYE
}
[ "$(_probe 'r"^\*\*Показание\.\*\*"')" = "1" ] && ok || bad T8 "жёсткий якорь не распознан признаком рода E"
[ "$(_probe 'r"^[ \t]*\*\*Проверка\.\*\*"')" = "0" ] && ok || bad T9 "здоровая форма принята за носителя"

echo "contract line anchor: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
