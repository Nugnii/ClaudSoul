#!/usr/bin/env bash
# СУДИТ: scripts/guard-edition-exposures.sh
# test_guard_edition_exposures.sh — замер обрывов фильтра после отказа стража редакции различает три состояния: обрывов
# нет (0, пробы посчитаны по ярлыку редакции), обрыв после среза есть (1, обрыв и откат названы — под любым ярлыком),
# мерить нечем (2: прибора обрывов нет либо он упал). Рамка: копия инструмента в песочном дереве, прибор обрывов —
# заглушка, печатающая строки в формате восьми колонок « | ».
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
mkdir -p "$T/scripts" "$T/.claude-docs/safeguard-block"
cp "$REPO/scripts/guard-edition-exposures.sh" "$T/scripts/" || { echo "подготовка мира не удалась: hooks/tests/test_guard_edition_exposures.sh:$LINENO" >&2; exit 1; }
P="$T/.claude-docs/safeguard-block/exposures.py"
rows() {  # строки заглушки прибора — через аргументы; срез, поданный прибору, заглушка пишет в argv.txt
    { echo 'import sys'; printf 'open(%s, "w").write(" ".join(sys.argv[1:]))\n' "'$T/argv.txt'"; echo 'print("заголовок без колонок")'
      for r in "$@"; do printf 'print(%s)\n' "$(python3 -c 'import json,sys; print(json.dumps(sys.argv[1], ensure_ascii=False))' "$r")"; done; } > "$P"
}
run() { OUT=$(bash "$T/scripts/guard-edition-exposures.sh" 2026-10-23T13:57:32Z D1035 2>&1); RC=$?; }

# T1 — обрывов нет: 0, пробы по ярлыку редакции, чужая редакция в пробы не входит. Счёты несимметричны (отказом хука
# 2, содержимым 1), а у чужой редакции есть и содержимое: перестановка колонок и счёт «содержимым» по всем редакциям
# краснят ногу (скептик opus по 06715882, M3). Остаток до вывода — 26 минус проб ОТКАЗОМ ХУКА.
rows 'a | b | c | d | e | отказ хука | D1035 | принят' 'a | b | c | d | e | отказ хука | D1035 | принят' \
     'a | b | c | d | e | содержимое | D1035 | принят' 'a | b | c | d | e | отказ хука | D1033 | принят' \
     'a | b | c | d | e | содержимое | D1033 | принят'
run
[ "$RC" = 0 ] && grep -q 'проб 3 (отказом хука 2, содержимым 1), обрывов после среза 0' <<< "$OUT" && grep -q 'осталось 24$' <<< "$OUT" && ok \
    || bad T1 "обрывов нет — ждали 0, «проб 3 (отказом хука 2, содержимым 1), обрывов после среза 0» и «осталось 24»: код $RC, «${OUT}»"
# T1b — срез подан прибору (M2 скептика): без него прибор берёт свой срез по умолчанию и считает старые обрывы новыми.
[ "$(cat "$T/argv.txt" 2>/dev/null)" = "2026-10-23T13:57:32Z" ] && ok \
    || bad T1b "прибору не подан срез: argv «$(cat "$T/argv.txt" 2>/dev/null)»"

# T2 — обрыв под чужим ярлыком после среза: 1, обрыв и откат названы; принятая проба под заголовок обрывов не попадает.
rows 'a | b | c | d | e | отказ хука | D1035 | принят' 'x | y | z | w | v | содержимое | новая | БЛОК'
run
[ "$RC" = 1 ] && grep -q 'обрывов после среза 1' <<< "$OUT" && grep -q 'ОБРЫВ после среза' <<< "$OUT" \
    && grep -q 'x | y | z | w | v | содержимое | новая | БЛОК' <<< "$OUT" && grep -q '^Откат:' <<< "$OUT" \
    && ! grep -q '^  a | b | c' <<< "$OUT" && ok \
    || bad T2 "обрыв после среза — ждали 1, только строку обрыва и откат: код $RC, «${OUT}»"

# T3 — прибор упал: 2, а не ложный ноль.
echo 'import sys; sys.exit(3)' > "$P"
run
[ "$RC" = 2 ] && grep -q 'прибор обрывов упал' <<< "$OUT" && ok || bad T3 "прибор упал — ждали 2: код $RC, «${OUT}»"

# T4 — прибора нет: 2 и сказано, что он локален.
rm -f "$P"
run
[ "$RC" = 2 ] && grep -q 'прибора обрывов нет' <<< "$OUT" && ok || bad T4 "прибора нет — ждали 2: код $RC, «${OUT}»"

# T5 — без аргументов: 2 и применение.
OUT=$(bash "$T/scripts/guard-edition-exposures.sh" 2>&1); RC=$?
[ "$RC" = 2 ] && grep -q 'применение' <<< "$OUT" && ok || bad T5 "без аргументов — ждали 2 и применение: код $RC"

echo "guard-edition-exposures: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
