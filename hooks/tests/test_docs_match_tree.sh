#!/usr/bin/env bash
# СУДИТ: scripts/docs-inventory.sh scripts/docs-duplicates.sh
# test_docs_match_tree.sh — документация описывает то, что есть, и только то, что есть.
#
# Результат: docs-inventory и docs-duplicates дают 0.
# Проверка результата: этот тест; красный — значит документы разошлись с деревом.
#
# Повод — вопрос собеседника 28 августа 2026: внесена ли работа сессии в документацию?
# Замер: семь новых механизмов упомянуты в architecture.md, README и CLAUDE.md НОЛЬ раз, а
# два стража документации были узкими — один срабатывает лишь при бампе версии и проверяет,
# что файлы ТРОНУТЫ коммитом, другой только на появление нового модуля.
#
# Почему тест, а не запуск по расписанию. Инструмент, который надо не забыть запустить, —
# прибор; красный тест нельзя прочитать и пройти мимо. Это тот же вывод, что дал замер
# 19 случаев «знание было уместно и не применено»: напоминания не меняют действия.
set -uo pipefail
# Оба инструмента считают питоном: без него они отвечают 2 «не измерено», и этот тест пропускается,
# как их собственные свидетели, а не краснеет с ярлыком «нашёл расхождение» (прожарка 13 сентября
# 2026, раунд 3, атака 5).
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO" || exit 1

PASS=0; FAIL=0
for tool in scripts/docs-inventory.sh scripts/docs-duplicates.sh; do
    if [ ! -x "$tool" ]; then
        FAIL=$((FAIL+1)); echo "FAIL: нет исполняемого $tool"; continue
    fi
    out=$(bash "$tool" 2>&1); rc=$?
    # НОЛЬ САМ ПО СЕБЕ НЕ ПОКАЗАНИЕ (23 сентября 2026, D474). Выпотрошенный инструмент —
    # заглушка `:` — отвечает тем же нулём при пустом выводе, и тест зеленел на МЁРТВОМ
    # предмете: прибор ложной зелени назвал его поимённо. Исправный прибор говорит ЧИСЛОМ
    # («проверено адресов: 144», «дублей нет»), и это требование отличает работу от молчания.
    if [ "$rc" -eq 0 ] && ! grep -q '[^[:space:]]' <<< "$out"; then
        FAIL=$((FAIL+1))
        echo "FAIL: $tool ответил нулём, не сказав НИЧЕГО — так отвечает и заглушка;"
        echo "  исправный прибор обязан назвать показание (сколько проверено, что найдено)."
    elif [ "$rc" -eq 0 ]; then
        PASS=$((PASS+1))
    elif [ "$rc" -ge 2 ]; then
        # Код 2 — инструмент НЕ ОТРАБОТАЛ (нет исполнителя, универсум не выведен): это отказ прибора,
        # а не расхождение документов, и подпись обязана это различать.
        FAIL=$((FAIL+1))
        echo "FAIL: $tool НЕ ОТРАБОТАЛ (код $rc) — сверять нечем:"
        printf '%s\n' "$out" | sed 's/^/    /'
    else
        FAIL=$((FAIL+1))
        echo "FAIL: $tool нашёл расхождение —"
        printf '%s\n' "$out" | sed 's/^/    /'
    fi
done

echo ""
echo "docs match tree tests: $PASS/$((PASS + FAIL)) passed"
exit $(( FAIL != 0 ))
