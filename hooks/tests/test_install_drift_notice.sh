#!/usr/bin/env bash
# СУДИТ: hooks/install-drift-notice.sh
# test_install_drift_notice.sh — сторож называет правку, не дошедшую до установленной копии.
#
# Результат: расхождение репозитория с ~/.claude названо в конце хода, а не через сутки
# Проверка результата: bash hooks/tests/test_install_drift_notice.sh даёт 0
#
# Повод, 7 сентября 2026: rc_outcome_observed был построен, проверен и закоммичен — и не
# работал, потому что живая копия о нём не знала. Сверщик установки живёт в hooks/tests/
# и бежит только в полном наборе (4 мин 40 с); правок хуков за сутки 33.
#
# ПРАВКА 7 сентября 2026: адрес репозитория берётся у CLAUDSOUL_ROOT, а не у cwd сессии, и
# сказанное уходит в очередь pending-alerts.txt, а не в systemMessage. Прежний контрпример
# «сессия вне репозитория — сторож молчит» был САМИМ ДЕФЕКТОМ: сторож молчал в 14 проектах
# из 15 и даже в подкаталоге ClaudSoul, а молчание «я не там» неотличимо от «всё свежо».
# Теперь это T4 — положительный контроль.
#
# КОНТРПРИМЕРЫ, все три проверяются ниже:
#   · дрейфа нет (код 0) — сторож молчит;
#   · сверщик СЛОМАН (код 2) — отказ НАЗВАН, а не проглочен: молчание неотличимо от чистоты;
#   · сверщика нет по разрешённому адресу — «НЕ ПРОВЕРЕНО», а не тишина.
#
# СТРОГО: stdout сторожа обязан быть ПУСТ всегда. Непустой additionalContext на событии Stop
# перезапускает ход, а отставание установки — состояние ПОСТОЯННОЕ: печать на Stop дала бы
# цикл (8 пустых ходов подряд, замер 7 сентября 2026).
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HOOK="${DRIFT_NOTICE:-$ROOT/hooks/install-drift-notice.sh}"
[ -f "$HOOK" ] || { echo "SKIP: нет $HOOK"; exit 0; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# Репозиторий подаётся CLAUDSOUL_ROOT, а не cwd: адрес сторожа больше не выводится из места
# сессии, и cwd везде ставится ЗАВЕДОМО ЧУЖОЙ. Сказанное читается ИЗ ОЧЕРЕДИ — stdout пуст.
# session_id уникален на ногу: дроссель живёт в сессии, общий id глушил бы соседние ноги.
SEQ=0
SEQ=0; OUT=""; LAST_STDOUT=""
run() {  # run <корень репозитория> -> OUT = очередь, LAST_STDOUT = stdout сторожа
    # ПРИСВАИВАЕТ, а не печатает: подстановка исполнила бы функцию в подоболочке, и второе
    # наблюдение (stdout сторожа) наружу бы не вышло. А наблюдений здесь ровно два, и оба
    # нужны: что сказано (очередь) и что НЕ напечатано на Stop (пустой stdout).
    SEQ=$((SEQ + 1))
    _q="$TMP/state$SEQ"; mkdir -p "$_q"
    printf '{"session_id":"t%s","hook_event_name":"Stop","cwd":"/"}' "$SEQ" \
      | CLAUDSOUL_ROOT="$1" STATE_DIR="$_q" bash "$HOOK" >"$TMP/out$SEQ" 2>&1
    LAST_STDOUT=$(cat "$TMP/out$SEQ" 2>/dev/null)
    OUT=$(cat "$_q/pending-alerts.txt" 2>/dev/null)
}

mk_repo() {
    _r="$TMP/$1"; mkdir -p "$_r/scripts"
    { printf '#!/usr/bin/env bash\n'
      printf '%s\n' '[ -n "${CMD_MARK:-}" ] && : > "$CMD_MARK"'
      printf '%s\n' "$2"
      printf 'exit %s\n' "$3"; } > "$_r/scripts/sync-drifted.sh"
    chmod +x "$_r/scripts/sync-drifted.sh"
    printf '%s' "$_r"
}

# --- T1: дрейфа нет (код 0) — тишина ---
R1=$(mk_repo clean 'printf "дрейфа нет\n"' 0)
run "$R1"
[ -z "$OUT" ] && ok || bad "T1" "на чистом дереве сторож заговорил: $OUT"
[ -z "$LAST_STDOUT" ] && ok || bad "T1b" "stdout не пуст — ход перезапустится: $LAST_STDOUT"

# --- T2: дрейф (код 1) — назван файл и названа команда переноса ---
R2=$(mk_repo drift 'printf "[хуки] расхождений: 1 из 96\n  > hooks/trust-guard.sh\n"' 1)
run "$R2"
case "$OUT" in
    *"trust-guard.sh"*) ok ;;
    *) bad "T2" "разошедшийся файл не назван: $OUT" ;;
esac
case "$OUT" in
    *"sync-drifted.sh --apply"*) ok ;;
    *) bad "T2b" "команда переноса не названа: $OUT" ;;
esac

# --- T2c (D1211): каждая напечатанная команда выполняется из терминала как есть. Строка команды ИСПОЛНЯЕТСЯ — bash и
# zsh, если он есть, — из чужого каталога, а не разбирается: заглушка скрипта отмечает запуск (`CMD_MARK`), и запуск
# обязан случиться, а чужой каталог — остаться пустым. Имя репозитория несёт пробел, апостроф, `$(…)`, обратные кавычки и
# `$HOME`: в двойных кавычках подстановки исполнились бы (скептик D1211, M3), без `&&` скрипт не запустился бы (M2).
# Судятся все три команды напоминания: перенос (дрейф), пересборка seed, сухой прогон (сверщик сломан) — M1.
exec_ok() {  # exec_ok <метка> <текст очереди> -> 0, если каждая команда запустила свой скрипт и ничего лишнего
    local lines line sh n=0 dir="$TMP/elsewhere-$1"
    lines=$(printf '%s\n' "$2" | grep '^    cd ')
    [ -n "$lines" ] || return 1
    mkdir -p "$dir"
    while IFS= read -r line; do
        for sh in bash zsh; do
            command -v "$sh" >/dev/null 2>&1 || continue
            n=$((n + 1))
            ( cd "$dir" && CMD_MARK="$TMP/mark-$1-$n" "$sh" -c "$line" >/dev/null 2>&1 )
            [ -f "$TMP/mark-$1-$n" ] || return 1
        done
    done <<< "$lines"
    [ -z "$(ls -A "$dir")" ]
}
NASTY="sp ace it's a\$(touch INJ1)b \`touch INJ2\` c\$HOME"
R2S=$(mk_repo "drift $NASTY" 'printf "[хуки] расхождений: 1 из 96\n  > hooks/trust-guard.sh\n"' 1)
run "$R2S"
exec_ok drift "$OUT" && ok || bad "T2c" "команда переноса не выполнится как напечатана: $OUT"
R3S=$(mk_repo "broken $NASTY" 'printf "сверщик упал\n"' 2)
run "$R3S"
exec_ok broken "$OUT" && ok || bad "T2d" "команда сухого прогона не выполнится как напечатана: $OUT"
R9S=$(mk_repo "seed $NASTY" 'printf "[seed знаний] расхождений: 1 из 3\n  > knowledge/x.md\n"' 3)
printf '%s\n' 'import os' 'm = os.environ.get("CMD_MARK")' 'm and open(m, "w").close()' > "$R9S/scripts/regen-seed.py"
run "$R9S"
exec_ok seed "$OUT" && ok || bad "T2e" "команда пересборки seed не выполнится как напечатана: $OUT"

# --- T3: КОНТРПРИМЕР — сверщик СЛОМАН (код 2): отказ назван, а не проглочен ---
R3=$(mk_repo broken 'printf "корень не разрешился\n" >&2' 2)
run "$R3"
case "$OUT" in
    *"НЕ ПРОВЕРЕНО"*) ok ;;
    *) bad "T3" "отказ сверщика проглочен, вывод: '$OUT'" ;;
esac
case "$OUT" in
    *"--apply"*) bad "T3b" "при сломанном сверщике предложен перенос: $OUT" ;;
    *) ok ;;
esac

# --- T4: ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ — сессия в ЧУЖОМ каталоге, сторож всё равно говорит ---
# Прежде здесь стоял контрпример «вне репозитория — тишина». Он и был дефектом: адрес брался
# у cwd, и сторож молчал везде, кроме корня ClaudSoul. Все run выше уже идут с cwd="/", то
# есть ЛЮБАЯ их зелень доказывает это же; нога оставлена явной, чтобы смена знака была видна.
run "$R2"
case "$OUT" in
    *"trust-guard.sh"*) ok ;;
    *) bad "T4" "из чужого каталога сторож не назвал дрейф: $OUT" ;;
esac

# --- T4b: КОНТРПРИМЕР на месте снятого — сверщика нет по разрешённому адресу ---
# «Нечем сверить» это не «расхождений нет»: молчание тут неотличимо от чистоты.
mkdir -p "$TMP/norepo"
run "$TMP/norepo"
case "$OUT" in
    *"НЕ ПРОВЕРЕНО"*) ok ;;
    *) bad "T4b" "без сверщика сторож промолчал вместо «НЕ ПРОВЕРЕНО»: $OUT" ;;
esac

# --- T5: пустой вход — тишина, не падение ---
OUT=$(printf '' | bash "$HOOK" 2>&1); RC=$?
if [ "$RC" = "0" ] && [ -z "$OUT" ]; then ok
else bad "T5" "на пустом входе rc=$RC вывод='$OUT'"; fi

# --- T6: stdout ПУСТ, а сказанное лежит в очереди ---
# Смена канала и есть предмет правки: systemMessage в VSCode-расширении не рендерится
# (case-2026-06-14), а additionalContext на Stop перезапускает ход.
run "$R2"
if [ -z "$LAST_STDOUT" ] && [ -n "$OUT" ]; then ok
else bad "T6" "stdout='$LAST_STDOUT' очередь='$OUT' — ожидались пустой stdout и непустая очередь"; fi

# --- T7: ПОВТОР той же редакции состояния очередь не растит (дроссель) ---
# Отставание постоянно: без дросселя сторож, видимый во всех проектах, дописывал бы строку
# на каждый ход — фон переехал бы из одного канала в другой.
Q7="$TMP/state-thr"; mkdir -p "$Q7"
for _ in 1 2 3; do
    printf '{"session_id":"thr","hook_event_name":"Stop","cwd":"/"}' \
      | CLAUDSOUL_ROOT="$R2" STATE_DIR="$Q7" bash "$HOOK" >/dev/null 2>&1
done
N7=$(grep -c 'trust-guard.sh' "$Q7/pending-alerts.txt" 2>/dev/null) || N7=0
[ "$N7" = "1" ] && ok || bad "T7" "три хода дали $N7 сообщений вместо одного — дроссель не держит"

# --- T8: дрейф, который переносом НЕ чинится, тоже называется ---
# Живой случай: единственная разошедшаяся пара — seed знаний, её sync-drifted намеренно не
# чинит. Прежде такой прогон отдавал код 0, и сторож молчал при живом дрейфе.
R8=$(mk_repo left 'printf "[seed знаний] расхождений: 1 из 3\n  x seed знаний НЕ синхронизируется\n"' 1)
run "$R8"
case "$OUT" in
    *"переносом это не чинится"*) ok ;;
    *) bad "T8" "неустранимый переносом дрейф проглочен: $OUT" ;;
esac

# --- T9: код 3 (отстал только seed) — свой уровень разговора, не «правка не дошла» ---
# D354: сигнал верен, но срабатывает с частотой работы со знаниями (126 касаний knowledge/
# за 30 дней) и тем обесценивает соседний, редкий и настоящий — «хук не доставлен».
R9=$(mk_repo seedonly 'printf "[seed знаний] расхождений: 1 из 3\n  x seed знаний НЕ синхронизируется\n"' 3)
# Команда пересборки называется только при живом инструменте (гейт `-f`, как у
# ci-check-reminder): фикстура кладёт его, иначе нога T9b проверяла бы совет о файле,
# которого в этом дереве нет.
: > "$R9/scripts/regen-seed.py"
run "$R9"
case "$OUT" in
    *"НОРМА между релизами"*) ok ;;
    *) bad "T9" "отставание seed названо как отставание установки: $OUT" ;;
esac
case "$OUT" in
    *"regen-seed.py"*) ok ;;
    *) bad "T9b" "не названа команда, которой это чинится: $OUT" ;;
esac
# Перенос здесь предлагать НЕЛЬЗЯ: seed синхронизатор намеренно не трогает, и совет
# «--apply» отправил бы владельца исполнять команду, которая его дрейф не устранит.
case "$OUT" in
    *"sync-drifted.sh --apply"*) bad "T9c" "на seed-дрейфе предложен перенос, который его не чинит: $OUT" ;;
    *) ok ;;
esac

# --- T9d: ключ дросселя ПОСТОЯНЕН — имена разошедшихся знаний его не двигают ---
# Это и есть вторая половина D354. Прежний ключ собирался из контрольной суммы вывода, а в
# выводе стоят имена знаний: каждая новая запись в базу давала «новую редакцию состояния»,
# и сторож говорил снова. Проверяем РАЗНЫМ выводом при одном коде — прежний ключ дал бы 2.
Q9="$TMP/state-seed-thr"; mkdir -p "$Q9"
for _n in alpha beta; do
    R9v=$(mk_repo "seed-$_n" "printf '[seed знаний] расхождений: 1 из 3\n  x seed знаний НЕ синхронизируется: pattern-$_n.md\n'" 3)
    printf '{"session_id":"seedthr","hook_event_name":"Stop","cwd":"/"}' \
      | CLAUDSOUL_ROOT="$R9v" STATE_DIR="$Q9" bash "$HOOK" >/dev/null 2>&1
done
N9=$(grep -c 'НОРМА между релизами' "$Q9/pending-alerts.txt" 2>/dev/null) || N9=0
[ "$N9" = "1" ] && ok || bad "T9d" "две записи знаний дали $N9 сообщений вместо одного — ключ дросселя всё ещё зависит от имён"

echo "install drift notice: PASS=$PASS FAIL=$FAIL"
exit $(( FAIL != 0 ))
