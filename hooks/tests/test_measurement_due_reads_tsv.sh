#!/usr/bin/env bash
# test_measurement_due_reads_tsv.sh — бегун замеров читает реестр как TSV и отличает
# исполненный замер от неисполненного.
#
# Повод (D303, одиннадцать атак прожарки 3 сентября 2026). Строка реестра подаётся в `eval`
# без вопроса, есть ли там команда: закомментированная строка исполняется в пустоту, даёт
# код 0 и отчитывается «выполнен, находок нет» — после чего получает отметку прогона и
# ИСЧЕЗАЕТ ИЗ ПРОСРОЧКИ НАВСЕГДА. Замер молчит не потому, что находок нет, а потому, что
# его никто не звал.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Соседний `test_measurement_due.sh` под полным набором переменчив
# (пункт называет это отдельной ногой результата: два полных прогона подряд дали 17/18 и
# 319/319, в одиночку зелёный всегда, причина не найдена). Класть новые утверждения в
# переменчивый файл значило бы прятать их исход за чужим шумом.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# Каждый прогон — свой репозиторий и своё состояние: отметки прогонов не должны течь
# между ногами.
mk() {  # mk <строки реестра через \n> [флаг «без завершающего перевода строки»]
    local d; d=$(mktemp -d "$TMP/run-XXXXXX")
    mkdir -p "$d/repo/scripts" "$d/state"
    cp "$REPO/scripts/measurement-due.sh" "$d/repo/scripts/"
    if [ "${2:-}" = "no-eol" ]; then printf '%b' "$1" > "$d/repo/scripts/measurements.tsv"
    else printf '%b\n' "$1" > "$d/repo/scripts/measurements.tsv"; fi
    printf '%s' "$d"
}
run() { CLAUDSOUL_REPO="$1/repo" STATE_DIR="$1/state" bash "$1/repo/scripts/measurement-due.sh" run 2>&1; }

ok()  { PASS=$((PASS+1)); }
no()  { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }
has() { if grep -q -- "$2" <<< "$1"; then ok; else no "$3" "нет «$2» в: $(head -c 300 <<< "$1")"; fi; }
hasnt() { if grep -q -- "$2" <<< "$1"; then no "$3" "лишнее «$2» в: $(head -c 300 <<< "$1")"; else ok; fi; }

# --- T1: закомментированная команда — не «выполнен» -----------------------------
D=$(mk 'commented\t7\t# отключён\tкоманда закомментирована')
OUT=$(run "$D")
hasnt "$OUT" "выполнен, находок нет" "T1: закомментированный замер не объявляется выполненным"

# --- T2: и отметки он не получает — иначе исчезнет из просрочки навсегда ---------
# Второй прогон обязан снова назвать его просроченным.
OUT2=$(run "$D")
has "$OUT2" "просрочен: commented" "T2: неисполненный замер остаётся в просрочке"

# --- T3: положительный контроль — настоящая команда исполняется и отмечается -----
D3=$(mk 'real\t7\ttrue\tнастоящая команда')
OUT=$(run "$D3")
has "$OUT" "real" "T3: настоящий замер назван"
OUT=$(run "$D3")
hasnt "$OUT" "просрочен: real" "T3b: исполненный замер уходит из просрочки"

# --- T4: последняя строка без завершающего перевода — видима бегуну --------------
# Класс D296: построчное чтение теряет последнюю строку, и замер невидим бегуну, но
# видим всем счётчикам реестра.
D4=$(mk 'first\t7\ttrue\tпервая\nlast\t7\ttrue\tпоследняя без перевода' no-eol)
OUT=$(run "$D4")
has "$OUT" "last" "T4: последняя строка без перевода строки не теряется"

# --- T5: замер, читающий stdin, не съедает остаток реестра ----------------------
D5=$(mk 'greedy\t7\tcat\tчитает stdin\nafter\t7\ttrue\tидёт следом')
OUT=$(run "$D5")
has "$OUT" "after" "T5: замер после жадного до stdin не пропадает"

# --- T6: пустая колонка не схлопывается, поля не съезжают ------------------------
# `read` с IFS=$'\t' схлопывает подряд идущие табы, потому что таб — пробельный
# разделитель. Строка с пустой колонкой команды отдавала описание в поле команды, и бегун
# исполнял ПРОЗУ: «НЕ ВЫПОЛНЕН (код 127)» вместо «команда пуста».
D6=$(mk 'gap\t7\t\tописание без команды')
OUT=$(run "$D6")
has "$OUT" "команда пуста" "T6: пустая колонка не съедает поля"
hasnt "$OUT" "код 127" "T6b: проза из описания не исполняется как команда"

# --- T7: отметка прогона из будущего не глушит замер навсегда --------------------
# Возраст считался как (сегодня − отметка); отметка из будущего давала отрицательный
# возраст, замер вечно «свежий», и НИЧТО этого не называло.
D7=$(mk 'future\t7\ttrue\tотметка из будущего')
mkdir -p "$D7/state/measurement-runs"
python3 -c "import time;print(int(time.time())+86400*365)" > "$D7/state/measurement-runs/future"
OUT=$(run "$D7")
has "$OUT" "future" "T7: замер с отметкой из будущего назван, а не молча пропущен"

echo "measurement-due reads tsv: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
