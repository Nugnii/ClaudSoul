#!/usr/bin/env bash
# СУДИТ: hooks/lib/open-findings-lib.sh hooks/root-cause-lib.sh
# test_open_findings_seen_source.sh — повод виден своду, даже если исход не записался.
#
# Результат: повод из журнала гейта без единой записи исхода попадает в счёт незакрытого;
#            одна тройка «сессия+ход+срод» считается один раз, сколько бы строк её ни несло
# Проверка результата: bash hooks/tests/test_open_findings_seen_source.sh даёт 0
#
# Повод, 9 сентября 2026. Свод читал ТОЛЬКО журналы исходов, а источник истины о том, что
# повод БЫЛ, — журнал гейта: исход пишется позже и может не написаться вовсе. Замер по
# живому каталогу: поводов 1236, с исходом 991 (80%), без единой записи 245 (19%); из них
# 157 (64%) — в десяти сессиях из 61, где Stop не отработал совсем. Эти поводы были
# невидимы и как открытые, и как закрытые: свод говорил 127 висящих при настоящих 346.
#
# Второй повод — в САМОЙ этой правке: первая редакция считала СТРОКИ журнала, а одна тройка
# встречается в нескольких (гейт дописывает строку на каждый новый отпечаток сигнала).
# 407 строк против 245 поводов; прибор, построенный против завышенного счёта, завышал сам.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$ROOT/hooks/lib/open-findings-lib.sh"
RC="$ROOT/hooks/root-cause-lib.sh"
for f in "$LIB" "$RC"; do [ -f "$f" ] || { echo "FAIL: нет $f"; exit 1; }; done
# shellcheck source=/dev/null
. "$RC"
# shellcheck source=/dev/null
. "$LIB"

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
PASS=0; FAIL=0
ck() { if [ "$2" = "$3" ]; then PASS=$((PASS+1)); else FAIL=$((FAIL+1));
       echo "FAIL: $1"; echo "   ожидалось: [$2]"; echo "   получено:  [$3]"; fi; }

# Сессия, где гейт сработал, а Stop не отработал: журнала исходов нет вовсе. Второй срод —
# `repeat:` (несёт имя знания); прежний образец `daily:` снят из перечня 13 сентября 2026 (D358).
printf 'turn:111|rework:aaa|repeat:pattern-x|\n' > "$TMP/five-whys-S1.seen"
ck "повод без журнала исходов виден" "0 2" "$(of_open_counts "$TMP" | cut -d' ' -f1,2)"

# Та же тройка в нескольких строках — гейт дописывает строку на каждый новый отпечаток.
printf 'turn:111|rework:bbb|\n' >> "$TMP/five-whys-S1.seen"
printf 'turn:111|rework:ccc|\n' >> "$TMP/five-whys-S1.seen"
ck "одна тройка считается один раз" "0 2" "$(of_open_counts "$TMP" | cut -d' ' -f1,2)"

# Появился исход одному из двух — счёт убывает ровно на него.
rc_log_outcome "$TMP" "S1" "111" "rework" "recorded" "предмет"
ck "записанный исход убирает свой повод" "0 1" "$(of_open_counts "$TMP" | cut -d' ' -f1,2)"

# Незнакомый срод не считается: перечень видов у своего владельца.
printf 'turn:222|неведомый:zzz|\n' >> "$TMP/five-whys-S1.seen"
ck "чужой срод не попадает в счёт" "0 1" "$(of_open_counts "$TMP" | cut -d' ' -f1,2)"

echo "PASS=$PASS FAIL=$FAIL"
exit $(( FAIL != 0 ))
