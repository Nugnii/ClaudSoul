#!/usr/bin/env bash
# АТАКА: отчёт объявляет очередь пустой и умалчивает, что пункт выпал по НЕЧИТАЕМОМУ
# полю — то есть о причине пустоты.
#
# knowledge-instrument-audit.sh:331 открывает `if queue:`, и блок «Не прочитано полей»
# (строки 345-351) лежит ВНУТРИ него. Пусто в очереди → блок не печатается вовсе.
# А пусто в очереди бывает именно потому, что поле не прочиталось: `confirmed_count`
# не разобрался → cc = 0 (строка 140) → порог не пройден → пункта нет.
#
# Скрипт сам называет это враньём: «Подстановка значения вместо сообщения о
# нечитаемости — то же, что соврать: подставленное всегда отвечает на вопрос замера,
# и всегда благоприятно (ноль подтверждений — не в очереди)» (строки 67-69). Признание
# уходит только в stdout, а measurement-due.sh запускает замер как
# `( cd "$REPO" && eval "$cmd" >/dev/null 2>&1 )` — stdout выброшен. Единственный
# переживающий артефакт — файл отчёта, и в нём стоит «Пусто».
set -uo pipefail

REPO="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)}"
AUDIT="$REPO/scripts/knowledge-instrument-audit.sh"
FAILED=0
ok()  { printf '  ✓ %s\n' "$1"; }
bad() { printf '  ✗ %s: %s\n' "$1" "$2"; FAILED=1; }

T=$(mktemp -d); L="$T/l"; S="$T/s"; mkdir -p "$L" "$S"
trap 'rm -rf "$T"' EXIT

cat > "$L/pattern-bad-count.md" <<'EOF'
---
outcome: error
status: active
confidence: 4
impact: 5
confirmed_count: пять
description: Подтверждений много, но поле написано словом
---
EOF

STDOUT=$(LESSONS_DIR="$L" STATE_DIR="$S" bash "$AUDIT" 2>&1); RC=$?
REPORT=$(cat "$S/knowledge-instrument.md")

echo "--- stdout замера (measurement-due его выбрасывает) ---"; printf '%s\n' "$STDOUT"
echo "--- раздел отчёта ---"; grep -A2 'Очередь на производство' <<< "$REPORT"

if grep -q 'НЕ ПРОЧИТАНО полей' <<< "$STDOUT"; then
    ok "T1 stdout нечитаемое поле называет"
else
    bad "T1" "атака собрана неверно: stdout про нечитаемое поле молчит"
fi

# T2: отчёт — единственное, что переживает прогон под measurement-due.
if grep -q 'pattern-bad-count' <<< "$REPORT"; then
    ok "T2 отчёт называет знание с нечитаемым полем"
else
    bad "T2" "отчёт не упоминает pattern-bad-count вовсе: причина пустой очереди потеряна"
fi
if grep -q 'Не прочитано полей' <<< "$REPORT"; then
    ok "T3 отчёт содержит блок «Не прочитано полей»"
else
    bad "T3" "блок «Не прочитано полей» в отчёт не попал — он заперт внутри ветки if queue"
fi

# T4: «Пусто» без оговорки читается как «неоценённых знаний нет», а их не посчитали.
if grep -q 'Пусто: неоценённых знаний' <<< "$REPORT"; then
    bad "T4" "отчёт утверждает «Пусто», хотя знание выпало из счёта по нечитаемому полю, а не по существу"
else
    ok "T4 отчёт не выдаёт непрочитанное за пустую очередь"
fi

echo "код возврата замера: $RC"
if [ "$RC" -eq 0 ]; then
    bad "T5" "rc=0 — «отработал, находок нет»; measurement-due по нулю ставит отметку прогона и молчит, хотя поле знания не прочитано"
else
    ok "T5 код возврата отличает непрочитанное от чистого прогона"
fi

echo
[ "$FAILED" -eq 0 ] && { echo "PASS"; exit 0; } || { echo "FAIL"; exit 1; }
