#!/usr/bin/env bash
# test_utf8_trim.sh — обрезка по байтам не должна ослеплять поиск по логам.
#
# Результат: сводный лог прогона остаётся валидным UTF-8 и потому ИЩЕТСЯ, чем бы тест ни
#            заканчивал своё сообщение
# Проверка результата: bash hooks/tests/test_utf8_trim.sh даёт 0
#
# Повод, 7 сентября 2026. Поиск по `run_all.log` трижды за сессию ответил «не найдено» о
# строке, которая там есть. Корень: `head -c 80` в test_scripts_reject_unknown_args.sh:56
# разрубил русское слово «расходится» посередине символа, и один недописанный байт сделал
# ВЕСЬ файл двоичным для grep. Носителей байтовой обрезки в дереве 90; последствие у всех
# одно — молчаливо неверный ответ поиска.
#
# ФОРМА ФИКСТУРЫ ВЗЯТА ИЗ МИРА, а не из головы: битый байт получается ровно так, как его
# производит дерево — русский текст через `head -c N`. Сочинять «примерно такой» байт нельзя
# (pattern-fixture-form-not-taken-from-the-world).
#
# ЧТО ЭТОТ ТЕСТ НЕ УТВЕРЖДАЕТ, и это измерено. Связь «битый байт → поиск слепнет» НАБЛЮДАЕМА,
# но НЕ детерминирована в этой среде: 7 сентября 2026 один и тот же файл с одним и тем же
# шаблоном дал `grep -q` сначала rc=1 (слеп), а через минуту rc=0 (нашёл), не меняясь. `grep`
# здесь — ugrep со своей эвристикой двоичности. Поэтому ноги проверяют ВАЛИДНОСТЬ вывода,
# которая детерминирована, а не ответ поиска, который в этой среде плавает. Утверждение теста:
# «после конвейера лог валиден» — а не «поиск по нему сработает».
# Условие снятия предела: поведение эвристики двоичности станет воспроизводимым — тогда
# положительный контроль можно будет строить прямо на ответе поиска.
set -uo pipefail

TESTS_DIR="$(cd "$(dirname "$0")" && pwd)"
HOOKS_DIR="$(cd "$TESTS_DIR/.." && pwd)"
LIB="${PORTABLE_LIB:-$HOOKS_DIR/portable-lib.sh}"
[ -f "$LIB" ] || { echo "SKIP: нет $LIB"; exit 0; }
# shellcheck source=/dev/null
. "$LIB"

PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

valid_utf8() { python3 -c 'import sys;sys.exit(0 if _ok(sys.argv[1]) else 1)
' 2>/dev/null || python3 - "$1" <<'PY'
import sys
try:
    open(sys.argv[1],"rb").read().decode("utf-8"); sys.exit(0)
except UnicodeDecodeError:
    sys.exit(1)
PY
}

# Битый байт производится ТАК ЖЕ, как его производит дерево.
printf 'сообщение про расходится' | head -c 20 > "$TMP/broken.txt"
printf '\nхвост-который-ищут\n' >> "$TMP/broken.txt"

# --- T1: ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ — без очистки поиск слепнет ---
# Без этой ноги зелень остальных ничего не значит: может, битого байта и не получилось.
if valid_utf8 "$TMP/broken.txt"; then
    bad "T1" "фикстура НЕ битая — обрезка по байтам не дала недописанного символа, проверять нечего"
else
    ok
fi
# Ноги «поиск по битому файлу слеп» здесь НЕТ намеренно: она была написана и упала не по
# делу — см. предел в шапке. Её место занимает утверждение о валидности, которое устойчиво.

# --- T2: после utf8_trim файл валиден и ищется ---
utf8_trim < "$TMP/broken.txt" > "$TMP/clean.txt"
if valid_utf8 "$TMP/clean.txt"; then ok; else bad "T2" "после очистки файл всё ещё невалиден"; fi
# Хвост уцелел: очистка снимает НЕДОПИСАННЫЙ символ, а не всё после него.
if grep -aq 'хвост-который-ищут' "$TMP/clean.txt" 2>/dev/null; then ok
else bad "T2b" "очистка съела текст после битого байта"; fi

# --- T3: КОНТРПРИМЕР — чистый текст не меняется ни на байт ---
# Очистка обязана быть тождественной там, где чинить нечего.
printf 'обычная русская строка без обрезки\n' > "$TMP/fine.txt"
utf8_trim < "$TMP/fine.txt" > "$TMP/fine.out"
if cmp -s "$TMP/fine.txt" "$TMP/fine.out"; then ok
else bad "T3" "чистый текст изменён очисткой"; fi

# --- T4: раннер пропускает вывод упавшего теста через очистку ---
# Нога ПОВЕДЕНЧЕСКАЯ: гоняется тот же конвейер, что стоит в run_all.sh, а не греп по его тексту.
OUTP=$(tail -25 "$TMP/broken.txt" 2>/dev/null | utf8_trim | sed 's/^/  /')
printf '%s\n' "$OUTP" > "$TMP/summary.log"
if valid_utf8 "$TMP/summary.log"; then ok; else bad "T4" "сводный лог невалиден после конвейера раннера"; fi
if grep -aq 'хвост-который-ищут' "$TMP/summary.log" 2>/dev/null; then ok
else bad "T4b" "конвейер раннера потерял текст после битого байта"; fi

# --- T5: раннер и правда зовёт очистку (иначе T4 доказывает конвейер, а не раннер) ---
if grep -q 'utf8_trim' "$TESTS_DIR/run_all.sh"; then ok
else bad "T5" "run_all.sh не пропускает вывод через utf8_trim — T4 тогда про воздух"; fi

echo "utf8 trim: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
