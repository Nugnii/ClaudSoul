#!/usr/bin/env bash
# test_attack_foreign_raises_stuck.sh — ГРАНИЦА (бывшая атака): короткая вставка чужого
# текста поднимает состояние, и порог 500 делает вердикт скачкообразным.
#
# Атака воспроизведена и НЕ закрыта — здесь она закреплена как названный предел, а не как
# одобренное поведение. Пункт долга D92. Почему не чинится сейчас: единственный доступный
# признак — зачин-подпись, и снятие у него порога длины закрыло бы вход ценой формы
# «смотри:» + собственная жалоба, которая от «вот вывод:» + чужой лог машинно неотличима.
# В выборке всех транскриптов реплик с зачином-двоеточием в канале состояния три, и все
# три — пересылки; трёх наблюдений мало, чтобы менять поведение на частой форме.
#
# Тест держит границу на месте: если поведение изменится в любую сторону — он покраснеет
# и заставит перечитать D92, вместо того чтобы дефект тихо переехал.
#
# `user_own_speech` отбрасывает вставленное тело ТОЛЬКО когда в нём есть markdown
# (```, `>`, `##`, таблица) или когда сработал зачин-подпись (первая строка на `:`
# И весь turn ≥ 500). Обычная вставка вывода короче порога проходит целиком, и слова
# из чужого лога («не работает», «same error») дают state=stuck. stuck входит в 4D
# gate и режет вмешательства на весь ход — по тексту, которого собеседник не писал.
#
# Один и тот же текст длиной 499 и 500 символов классифицируется по-разному.

set -uo pipefail

LIB="$(cd "$(dirname "$0")/.." && pwd)/intrusiveness-state-lib.sh"
[ -f "$LIB" ] || { echo "FAIL: $LIB not found"; exit 1; }

TMP=$(mktemp -d)
export ITR_STATE_DIR="$TMP"
# shellcheck source=/dev/null
source "$LIB"

PASS=0
FAIL=0
state_of() { itr_compute_state "" "$1" | cut -d'|' -f1; }

# ASCII-текст ровно заданной длины: «вот вывод:» + повторяющееся тело чужого лога.
build() {  # $1=итоговая длина
    local out="log output:
"
    local body="Error: same error as before, restart did not help. "
    while [ "${#out}" -lt "$1" ]; do out="$out$body"; done
    printf '%s' "${out:0:$1}"
}

# t0 — контроль: собственная жалоба обязана давать stuck
got=$(state_of "опять не работает, третий раз подряд")
if [ "$got" = "stuck" ]; then PASS=$((PASS + 1))
else FAIL=$((FAIL + 1)); echo "FAIL [t0 own complaint (control)]: ожидалось stuck, получено '$got'"; fi

# t1 — ГРАНИЦА: короткая вставка чужого вывода СЕЙЧАС поднимает состояние (D92)
got=$(state_of "вот вывод:
Error: не работает опять, same error")
if [ "$got" = "stuck" ]; then
    PASS=$((PASS + 1))
else
    FAIL=$((FAIL + 1))
    echo "FAIL [t1 известная граница изменилась: короткая вставка больше не даёт stuck — перечитай D92]: получено '$got'"
fi

# t2 — то же самое ровно на символ ниже порога 500
S499=$(build 499)
got=$(state_of "$S499")
if [ "$got" = "stuck" ]; then PASS=$((PASS + 1))
else
    FAIL=$((FAIL + 1))
    echo "FAIL [t2 известная граница изменилась: вставка на 499 больше не даёт stuck — перечитай D92]: получено '$got'"
fi

# t3 — вердикт не должен переворачиваться от одного символа
S500=$(build 500)
a=$(state_of "$S499"); b=$(state_of "$S500")
if [ "$a" = "stuck" ] && [ "$b" != "stuck" ]; then PASS=$((PASS + 1))
else
    FAIL=$((FAIL + 1))
    echo "FAIL [t3 край порога 500 сместился — перечитай D92]: 499 → '$a', 500 → '$b'"
fi

rm -rf "$TMP"
echo ""
echo "attack foreign-raises-stuck: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
