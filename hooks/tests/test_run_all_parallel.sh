#!/usr/bin/env bash
# test_run_all_parallel.sh — параллельный прогон даёт ТОТ ЖЕ результат, что последовательный.
#
# Предмет. `TEST_JOBS>1` раскладывает тесты по потокам, оставляя последовательными те, что
# берут общий ресурс (git-индекс репозитория, боевой state). Признак таких тестов выведен из
# их текста и потому НЕПОЛОН по построению: конфликт через третий вид ресурса (общий порт,
# фиксированное имя во временном каталоге) он не видит. Единственная настоящая проверка —
# сравнить исход двух режимов, и она здесь.
#
# Замер 8 сентября 2026: 367 тестов, последовательно 9,9 мин, на восьми потоках 4,1 мин
# (×2,4). Теоретический потолок упаковки был ×4,7 — разницу съедает конкуренция за ресурсы,
# а не устройство очереди.
#
# ПОЧЕМУ ПОДМНОЖЕСТВО, А НЕ ВЕСЬ НАБОР. Полный прогон в двух режимах стоит 14 минут, и нога
# такой цены не бежала бы ни в одном наборе — то есть не охраняла бы ничего. Здесь берётся
# горсть быстрых тестов в отдельном каталоге с копией раннера.
set -uo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
PASS=0; FAIL=0
ok() { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/tests"
cp "$DIR/run_all.sh" "$TMP/tests/"
cp "$DIR/../timeout-lib.sh" "$TMP/"   # раннер зовёт снятие дерева из библиотеки (D369)
# drift-check раннер зовёт по своему пути; заглушка держит вывод предсказуемым и не даёт
# ноге зависеть от состояния установки.
printf '#!/usr/bin/env bash\nexit 0\n' > "$TMP/tests/drift-check.sh"
chmod +x "$TMP/tests/drift-check.sh"

# Фикстуры: три зелёных, один красный, один «берущий общий ресурс» (по признаку раннера —
# git add без своего репозитория). Красный обязателен: набор, где всё зелено, не показал бы
# разницы между «списки совпали» и «список пуст в обоих режимах».
i=1
while [ "$i" -le 6 ]; do
    printf '#!/usr/bin/env bash\nsleep 0.3\necho "ok %s"\nexit 0\n' "$i" > "$TMP/tests/test_green_$i.sh"
    chmod +x "$TMP/tests/test_green_$i.sh"
    i=$((i + 1))
done
printf '#!/usr/bin/env bash\necho "нарочно красный"\nexit 1\n' > "$TMP/tests/test_red_one.sh"
chmod +x "$TMP/tests/test_red_one.sh"
printf '#!/usr/bin/env bash\n# git add без своего -C: раннер обязан увести такой тест в последовательную фазу\ntrue git add .\nexit 0\n' > "$TMP/tests/test_shared_git.sh"
chmod +x "$TMP/tests/test_shared_git.sh"

# Журнал прогона уводится в песочницу: `run_all.sh` пишет ход в общий
# `state/suite-run.tsv`, и прогон-фикстура затирал бы журнал последнего НАСТОЯЩЕГО прогона —
# того самого, по которому считаются дорогие тесты и базис сроков. Маркер `SUITE_RUN_NESTED`
# здесь не спасает: он ставится, когда набор зовёт набор, а этот тест зовёт его напрямую.
# Поймано 11 сентября 2026 на первом же прогоне новой ноги.
export SUITE_RUN_LOG="$TMP/suite-run.tsv"
run_mode() { (cd "$TMP/tests" && TEST_JOBS="$1" PROGRESS_EVERY=99 bash run_all.sh 2>&1); }

SEQ=$(run_mode 1); SEQ_RC=$?
PAR=$(run_mode 4); PAR_RC=$?

# T1: код возврата один и тот же.
if [ "$SEQ_RC" = "$PAR_RC" ]; then ok
else bad "T1" "коды разошлись: последовательно $SEQ_RC, параллельно $PAR_RC"; fi

# T2: список падений совпадает дословно. Это главная нога: она ловит любой конфликт,
# которого не увидел текстовый признак.
S_FAILED=$(printf '%s\n' "$SEQ" | grep '^FAILED:' | tr ' ' '\n' | sort | tr '\n' ' ')
P_FAILED=$(printf '%s\n' "$PAR" | grep '^FAILED:' | tr ' ' '\n' | sort | tr '\n' ' ')
if [ "$S_FAILED" = "$P_FAILED" ]; then ok
else bad "T2" "списки падений разошлись:«${S_FAILED}» против «${P_FAILED}»"; fi

# T3: итоговый счёт совпадает.
S_TOT=$(printf '%s\n' "$SEQ" | sed -n 's/.*Hook test files: \([0-9]*\/[0-9]*\) passed.*/\1/p')
P_TOT=$(printf '%s\n' "$PAR" | sed -n 's/.*Hook test files: \([0-9]*\/[0-9]*\) passed.*/\1/p')
if [ -n "$S_TOT" ] && [ "$S_TOT" = "$P_TOT" ]; then ok
else bad "T3" "счёт разошёлся: «${S_TOT}» против «${P_TOT}»"; fi

# T4: КОНТРПРИМЕР — красный тест виден в ОБОИХ режимах. Без него T2 зеленела бы и на паре
# пустых списков, то есть проверяла бы ничто.
if grep -q 'test_red_one.sh' <<< "$S_FAILED" && grep -q 'test_red_one.sh' <<< "$P_FAILED"; then ok
else bad "T4" "красный тест не попал в списки: «${S_FAILED}» / «${P_FAILED}»"; fi

# T5: тест, берущий общий ресурс, признаётся последовательным. Проверяется сам признак, а не
# его последствие: иначе поломка признака была бы видна только на редком конфликте.
if (cd "$TMP/tests" && TEST_JOBS=4 bash -c '
    . ./run_all.sh --source-only 2>/dev/null || true
    grep -qE "git +(add|commit|stash|checkout)" test_shared_git.sh \
        && ! grep -qE "git -C \"\\\$(TMP|WORK|REPO|d|T)" test_shared_git.sh'); then ok
else bad "T5" "признак общего ресурса не узнаёт git add без своего репозитория"; fi

# T6: умолчание ВЫВОДИТСЯ из числа ядер и ОГРАНИЧЕНО, а переменная окружения его перекрывает.
#
# До 11 сентября 2026 эта нога требовала буквального `${TEST_JOBS:-1}` с доводом «ускорение
# включается явно, иначе правка меняла бы поведение всем, кто про неё не знает». Довод был
# верен в день ввода механизма (8 сентября), когда параллель ещё не была проверена на живом
# наборе. Три дня спустя условие осторожности выполнено, и это измерено: полный набор в один
# поток — 12 мин 11 с, в восемь — 3 мин 54 с, 434/434 зелёные В ОБОИХ, падений и убитых
# сторожем ноль; ноги T1-T5 этого же теста (коды сходятся, признак общего ресурса работает)
# прошли на параллельном прогоне. Цена прежнего умолчания: механизм, построенный и
# измеренный, три дня не работал ни у кого — результат без потребителя.
#
# Предмет ноги сохранён, а не снят: «поведение не меняется без спроса» значит теперь
# «умолчание предсказуемо, ограничено и перекрываемо», а не «умолчание равно единице».
_ra="$DIR/run_all.sh"
if grep -qE 'TEST_JOBS="\$\{TEST_JOBS:-\$_jobs_default\}"' "$_ra" \
   && grep -qE '_jobs_default=\$\(\( *_cpus - 2 *\)\)' "$_ra" \
   && grep -qE '_jobs_default=1' "$_ra"; then ok
else bad "T6" "умолчание TEST_JOBS не выводится из ядер с запасом 2 и падением на 1 — поведение непредсказуемо"; fi

# T6b: переменная окружения ОСТАЁТСЯ сильнее умолчания — иначе прежний способ звать набор в
# один поток (TEST_JOBS=1) перестал бы работать, а на него опираются чужие прогоны и CI.
# Вывод в переменную, а не через пайп в `grep -q`: под `set -o pipefail` ранний выход grep
# шлёт набору SIGPIPE, статус пайпа становится 141, и зелёное читается как красное.
_t6b=$(cd "$TMP/tests" && TEST_JOBS=1 PROGRESS_EVERY=99 bash run_all.sh 2>&1)
if grep -q 'Hook test files' <<<"$_t6b"; then ok
else bad "T6b" "TEST_JOBS=1 перестал приниматься — умолчание перебивает явное значение"; fi

# T7: прогон ВНЕ своего репозитория не пишет в ОБЩИЙ базис сроков (11 сентября 2026).
# Повод измерен в тот же день: проба корня R6 распаковывает дерево через `git archive`,
# оставляет там один тест и гоняет набор — защита «прогон полный, если тестов не меньше,
# чем файлов в каталоге» в такой копии истинна по построению, и базис ВСЕГО набора был
# затёрт одной записью. Второй носитель того же класса — этот самый тест: он уводил в
# песочницу журнал (`SUITE_RUN_LOG` выше), а базис писал в общий файл своими восемью
# фикстурами, то есть портил сроки на каждом полном прогоне. Обоих гасит один признак —
# отсутствие git-контекста, — и ноге он предъявляется маркером, а не чтением кода.
_bl_common="$TMP/common-baseline.tsv"
printf '42\ttest_marker_probe.sh\n' > "$_bl_common"
( cd "$TMP/tests" && STATE_DIR="$TMP" HOME="$TMP" TEST_JOBS=1 PROGRESS_EVERY=99 bash run_all.sh >/dev/null 2>&1 )
if [ -f "$TMP/suite-baseline.tsv" ]; then
    bad "T7" "прогон вне репозитория записал общий базис $TMP/suite-baseline.tsv"
else ok; fi

# T7b: ЯВНО названный путь базиса остаётся сильнее — иначе починка T7 отняла бы у тестов
# способ увести состояние в свою песочницу, то есть вылечила бы одно, сломав другое.
_bl_named="$TMP/named-baseline.tsv"
rm -f "$_bl_named"
( cd "$TMP/tests" && SUITE_BASELINE_FILE="$_bl_named" TEST_JOBS=1 PROGRESS_EVERY=99 bash run_all.sh >/dev/null 2>&1 )
if [ -s "$_bl_named" ] && grep -q 'test_green_1.sh' "$_bl_named"; then ok
else bad "T7b" "явный SUITE_BASELINE_FILE не получил записей: $(cat "$_bl_named" 2>/dev/null | head -2)"; fi

echo ""
echo "run_all parallel: $PASS passed, $FAIL failed"
exit $(( FAIL != 0 ))
