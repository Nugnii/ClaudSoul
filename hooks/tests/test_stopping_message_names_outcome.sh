#!/usr/bin/env bash
# test_stopping_message_names_outcome.sh — тормозящее сообщение называет исполнимый исход.
#
# Результат: в дереве нет хука, который тормозит действие и не говорит, что делать вместо
#            БЕЗ ожидания чужого разрешения
# Проверка результата: bash hooks/tests/test_stopping_message_names_outcome.sh даёт 0
#
# Зачем (D111). Замер 29 августа 2026: из 12 хуков, чьё сообщение тормозит действие, что
# делать вместо называли 3. Наблюдаемое следствие в тот же день: `inquiry-gap` говорил
# «строить — только после явного слова» и не говорил, что оставить, если слова нет; ход
# закончился без исхода, и находка не попала ни в починку, ни в долг — хотя запись в долг
# разрешения не требует.
#
# Отдельно: тот замер был РАЗОВЫМ прогоном, инструмента после него не осталось, и число
# 12/3/9 нечем было пересчитать. Этот страж и есть тот инструмент: он же замер, он же
# проверка при добавлении нового тормозящего хука.
#
# ПРАВИЛО. Хук, который тормозит (отказывает, спрашивает, говорит «стой»/«прежде чем»),
# обязан назвать альтернативу, исполнимую без разрешения собеседника: команду, действие
# или закрытый список исходов. «Переспроси» альтернативой НЕ является, когда именно
# отсутствие разрешения и есть повод срабатывания — предписание тогда упирается в
# недостающее условие, и ход кончается ничем.
#
# КОНТРПРИМЕРЫ, объявлены и проверяются:
#   · хук, который ничего не тормозит (только сообщает факт), под правило не подпадает;
#   · слово «стоп» в КОММЕНТАРИИ или в шапке-поводе — не тормозящее сообщение; признак
#     читает код со снятыми комментариями, как `test_guards_provable.sh`;
#   · библиотека (`*-lib.sh`) сообщений от себя не печатает — форматирует чужие.
#
# КАЛИБРОВКА 29 августа 2026. Первая редакция признака дала 5 находок при НУЛЕ настоящих:
# исход был назван во всех пяти, но способом, которого признак не знал —
#   `ablation-phase-guard`: команда без бэктиков («Закрытие: scripts/ablation/phase.sh close»);
#   `skill-name-ascii-guard`: глагол вне словаря («Переименуй каталог и поле name»);
#   `bulk-copy-guard`: то же («классифицируй по типу, копируй явно перечисленные»);
#   `five-whys-gate`: текст приходит подстановкой `rc_doctrine_short/full` из библиотеки;
#   `blocker-tier-check`: текст приходит из поля `remedy` самого сигнала.
# Отсюда три оговорки ниже: команда узнаётся и без бэктиков, словарь глаголов расширен
# измеренными формами, подстановка исхода из библиотеки и из данных засчитывается. Это тот
# же урок, что у соседнего стража пределов: признак ловил СЛОВО, а не объявление.
#
# НАЗВАННЫЙ ПРЕДЕЛ: признак читает СЛОВА (наличие команды в бэктиках либо глагола действия
# из словаря), а не смысл. Сообщение, где альтернатива названа описанием без глагола
# («дождись поручения»), признаком не ловится — тот же потолок, что был у разового замера.
# Условие снятия: предел держится, пока исход называется прозой. Появится у сообщений общая
# структура (поле «исход» в едином форматере) — сверять слова станет незачем.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO" || exit 1
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

python3 - <<'PY'
import re, pathlib, sys

HOOKS = pathlib.Path("hooks")

# Тормозящее: отказ/вопрос через permissionDecision либо текст, требующий остановиться.
STOPPING = re.compile(
    r'permissionDecision"?\s*:\s*"?(deny|ask)'
    r'|СТОП[:\s]|Остановись|остановись до|Прежде чем|прежде чем выполнять'
    r'|не пройдёт, пока|Правку — в ветку|запрещ',
)
# Исход: команда (в бэктиках или без них), подстановка исхода из библиотеки/данных,
# либо глагол действия. Все три формы измерены на дереве, см. КАЛИБРОВКУ в шапке.
OUTCOME = re.compile(
    r'`[^`\n]+`'                                   # команда/путь в бэктиках
    r'|(?:bash |python3 )?(?:scripts|hooks)/[\w./-]+\.(?:sh|py)'   # команда без бэктиков
    r'|rc_resolution_kinds|rc_doctrine'            # исход подставляется из библиотеки
    r'|remedy'                                     # исход приходит из данных сигнала
    r'|(?:з|З)апиши|(?:з|З)апис(?:ать|ь)|(?:д|Д)опиши|(?:в|В)ерни|(?:п|П)ереведи'
    r'|(?:н|Н)азови|(?:п|П)окажи|(?:с|С)делай|(?:и|И)справь|(?:ч|Ч)ини|(?:п|П)редъяви'
    r'|(?:п|П)рочитай|(?:с|С)вер(?:ить|и)|(?:д|Д)обавь|(?:п|П)редложи|(?:в|В)ынеси'
    r'|(?:п|П)ереименуй|(?:к|К)лассифицируй|(?:к|К)опируй|(?:п|П)еречисли|(?:з|З)амени',
)
# «Переспроси» само по себе исходом не является — оно требует того самого разрешения.
ONLY_ASK = re.compile(r'(?:п|П)ереспроси|(?:с|С)проси разрешени|жди подтвержд')

def strip_comments(text):
    """Код без комментариев: слово «стоп» в шапке-поводе тормозящим сообщением не является."""
    out = []
    for line in text.split("\n"):
        if re.match(r'^\s*#', line):
            continue
        out.append(line)
    return "\n".join(out)

stopping, with_outcome, missing = 0, 0, []
for f in sorted(HOOKS.glob("*.sh")):
    if f.name.endswith("-lib.sh"):
        continue
    raw = f.read_text(errors="replace")
    code = strip_comments(raw)
    if not STOPPING.search(code):
        continue
    stopping += 1
    if OUTCOME.search(code):
        with_outcome += 1
    else:
        why = "нет исхода вовсе"
        if ONLY_ASK.search(code):
            why = "единственный выход — переспросить, а разрешения нет по условию срабатывания"
        missing.append((f.name, why))

print(f"тормозящих хуков: {stopping}, с названным исходом: {with_outcome}, без: {len(missing)}")
for name, why in missing:
    print(f"  · {name} — {why}")

# --- Отрицательный контроль: признак обязан ловить подлог ---
# Без него «ноль находок» неотличимо от неработающего признака — а после калибровки
# находок на дереве ноль, и отличить эти два состояния больше нечем.
FAKE_STOP = 'jq -cn \'{hookSpecificOutput:{permissionDecision:"deny"}}\'\necho "СТОП: так нельзя"\n'
if not STOPPING.search(FAKE_STOP):
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОВАЛЕН: признак не видит явно тормозящий текст")
    sys.exit(2)
if OUTCOME.search(FAKE_STOP):
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОВАЛЕН: признак нашёл исход там, где его нет")
    sys.exit(2)
# «Переспроси» — не исход, когда разрешения нет по условию срабатывания (случай trust-guard
# до 29 августа 2026). Признак обязан отличать его от настоящей альтернативы.
FAKE_ASK = 'echo "СТОП. Переспроси прежде чем выполнять — нужна явная авторизация"\n'
if OUTCOME.search(FAKE_ASK) or not ONLY_ASK.search(FAKE_ASK):
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОВАЛЕН: «переспроси» засчитано как исполнимый исход")
    sys.exit(2)
# Положительный контроль: настоящая альтернатива обязана распознаваться всеми тремя
# формами — командой без бэктиков, глаголом, подстановкой из библиотеки.
for good in ('Закрытие: scripts/ablation/phase.sh close',
             'Переименуй каталог и поле name',
             'выход: $(rc_doctrine_short)'):
    if not OUTCOME.search(good):
        print(f"ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ПРОВАЛЕН: не узнан исход в «{good}»")
        sys.exit(2)

# Исторические строки — те, что стояли в дереве ДО 29 августа 2026 и были признаны
# нарушением. Они остаются в тесте как доказательство, что зелёный прогон означает
# починку, а не слепоту признака: после правок находок ноль, и отличить «исправлено» от
# «перестало ловиться» больше нечем.
WAS_BROKEN = (
    "Переспроси прежде чем выполнять — destructive действия требуют явной auth.",
    "состояние могло измениться, сверяй прежде чем действовать:",
)
for bad in WAS_BROKEN:
    if OUTCOME.search(bad):
        print(f"РЕГРЕСС ПРИЗНАКА: исторически нарушающая строка засчитана как исход — «{bad}»")
        sys.exit(2)

sys.exit(1 if missing else 0)
PY
RC=$?

if [ "$RC" -eq 0 ]; then
    echo "stopping message names outcome: 0 failed"
elif [ "$RC" -eq 1 ]; then
    echo "stopping message names outcome: есть тормозящие сообщения без исполнимого исхода (D111)"
    echo "  Допиши в сообщение, что делать вместо, БЕЗ ожидания разрешения: команду в бэктиках,"
    echo "  действие («запиши в долг», «покажи число»), либо \`rc_resolution_kinds\` из root-cause-lib."
fi
exit "$RC"
