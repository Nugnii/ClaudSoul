#!/usr/bin/env bash
# test_adv_measurement_row_dropped.sh — АТАКА на scripts/measurement-due.sh.
#
# Строка реестра, в которой разделитель оказался пробелом, а не табуляцией, выбрасывается
# МОЛЧА: `case "$period" in ''|*[!0-9]*) continue ;;` (measurement-due.sh:113) — и замер
# исчезает из расписания навсегда, а прибор печатает «просроченных нет».
#
# Это тот же род, который сам файл объявляет своим предметом двумя абзацами выше
# (D303: «Реестр объявлен TSV, и читать его надо как TSV»): там починили СХЛОПЫВАНИЕ
# пустых колонок, а «строка вовсе не разобралась» осталась тишиной. Реестр правится рукой
# — 88 строк, — и опечатка в разделителе неотличима от отсутствия строки.
#
# Ожидание по доктрине самого дерева («молчание неотличимо от чистоты»): нераспознанная
# строка обязана быть НАЗВАНА, а не выброшена.
set -uo pipefail

DUE="$(cd "$(dirname "$0")/../.." && pwd)/scripts/measurement-due.sh"
[ -f "$DUE" ] || { echo "FAIL: нет $DUE"; exit 1; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '  ok   %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  FAIL %s\n     %s\n' "$1" "$2"; }

TMP=$(mktemp -d) || exit 1
mkdir -p "$TMP/state"

# ── контроль: правильная строка попадает в просрочку ──────────────────────────────
printf 'нормальный\t7\techo ничего\tчто меряет\n' > "$TMP/ok.tsv"
OUT=$(MEASUREMENT_REGISTRY="$TMP/ok.tsv" STATE_DIR="$TMP/state" bash "$DUE" check 2>&1)
if grep -q 'нормальный' <<< "$OUT"; then
    ok "контроль: замер с табуляциями назван просроченным"
else
    bad "контроль: замер с табуляциями назван просроченным" \
        "вывод: $(printf '%s' "$OUT" | tr '\n' ' ') — фикстура не годится"
fi

# ── АТАКА: разделитель — пробелы. Замер исчезает без единого слова ────────────────
printf 'нормальный\t7\techo ничего\tчто меряет\nопечатка 7 echo ничего что меряет\n' > "$TMP/bad.tsv"
OUT=$(MEASUREMENT_REGISTRY="$TMP/bad.tsv" STATE_DIR="$TMP/state" bash "$DUE" check 2>&1); RC=$?
if grep -q 'опечатка' <<< "$OUT"; then
    ok "строка_без_табуляции: нераспознанная строка названа"
else
    bad "строка_без_табуляции: нераспознанная строка названа" \
        "код=$RC, вывод: $(printf '%s' "$OUT" | tr '\n' ' ') — замер выброшен молча, счётчики его не знают"
fi

# ── АТАКА-2: реестр из одних комментариев — «просроченных нет» вместо отказа ──────
printf '# только комментарии\n# и ничего больше\n' > "$TMP/empty.tsv"
OUT=$(MEASUREMENT_REGISTRY="$TMP/empty.tsv" STATE_DIR="$TMP/state" bash "$DUE" check 2>&1); RC=$?
if [ "$RC" -ne 0 ] || ! grep -q 'просроченных нет' <<< "$OUT"; then
    ok "пустой_реестр: ноль строк не выдан за чистоту"
else
    bad "пустой_реестр: ноль строк не выдан за чистоту" \
        "код=$RC, вывод: $(printf '%s' "$OUT" | tr '\n' ' ') — сравнили ноль замеров, а сказано «просроченных нет»"
fi

echo "measurement-row-dropped: $PASS ok, $FAIL FAIL"
exit $(( FAIL != 0 ))
