#!/usr/bin/env bash
# test_case_folding_portable.sh — свёртка регистра для кириллицы только через общую функцию.
#
# Повод. `tr '[:upper:]' '[:lower:]'` сворачивает кириллицу ТОЛЬКО на BSD. GNU tr читает
# ввод побайтно и многобайтовые символы не трогает ни в какой локали, включая C.UTF-8 —
# это разница реализаций, а не настройка машины. Следствие: любой детектор, который
# приводит реплику к нижнему регистру и сравнивает с русскими словами, на Linux молча
# не срабатывает. Прогон CI нашёл это в четырёх хуках; ревизия — ещё в пяти, включая
# `trust-guard`, где ломаются сразу распознавание согласия и распознавание разрушительного
# намерения, то есть в разные стороны.
#
# Почему проверкой, а не правилом в тексте. К моменту починки в репозитории жили ТРИ разных
# приёма: цепочка sed, арифметика по кодовым точкам в jq и перечисление обоих написаний
# в шаблоне («затем|Затем»). Третий покрывал только заглавную первую букву и промахивался
# на «ЗАТЕМ». Три копии появились не по небрежности, а потому что каждый чинил своё место
# отдельно — текстовое правило этого не остановит, а проверка остановит.
#
# Что именно проверяется: файл, который сравнивает с кириллическими литералами, не имеет
# права строить сравниваемую строку через `tr '[:upper:]' '[:lower:]'`. Свёртка обязана идти
# через `to_lower` из `portable-lib.sh` — там оба пути (jq и sed) дают одинаковый результат.

# ВАЖНО про локаль в самой этой проверке. Кириллический класс `[а-яёА-ЯЁ]` GNU grep
# ОТВЕРГАЕТ в локали C.UTF-8 — «Invalid collation character», и проверка молча перестаёт
# что-либо находить. Прогон CI идёт именно в C.UTF-8, и первая версия этого файла упала там
# ровно так: три ошибки grep и «отрицательный контроль не распознал нарушение». То есть тест,
# написанный против непереносимых сравнений, сам оказался непереносимым сравнением.
# Поэтому все греп-вызовы с кириллицей здесь идут под `LC_ALL=C`: там класс читается как
# набор БАЙТОВ, ошибки нет, а для вопроса «есть ли в строке кириллица» байтового уровня
# достаточно.

set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PASS=0
FAIL=0

# --- 1. Статическая проверка: ни один хук не сворачивает регистр сырым tr рядом с кириллицей
VIOLATIONS=""
for f in "$HOOKS_DIR"/*.sh; do
    b=$(basename "$f")
    # portable-lib — единственное законное место: там сырой tr стоит в запасной ветке
    # и обслуживает латиницу, а кириллицу добирает цепочка sed.
    [ "$b" = "portable-lib.sh" ] && continue

    # Строки с сырой свёрткой, из которых убрано законное:
    #   · комментарии — команда там лишь УПОМЯНУТА в пояснении, почему её не используют
    #     (первая версия ловила на этом `user-correction-guard`);
    #   · запасная ветка `else to_lower() { ... tr ... }` — она срабатывает, только когда
    #     библиотеки нет рядом, и неполная свёртка лучше выключенного хука.
    #
    # Без `grep -q` намеренно. Первая версия писала `grep -vE '^#' "$f" | grep -q '...'`,
    # и это молча пропускало файлы: `grep -q` завершается по первому совпадению, шлёт
    # SIGPIPE предыдущей команде, а под `pipefail` статус конвейера становится ненулевым —
    # то есть `|| continue` срабатывал ИМЕННО КОГДА совпадение найдено. На мелких файлах
    # производитель успевал дописать и ошибки не было, на крупных — была. Проверка
    # пропускала файлы по размеру и выглядела зелёной. Тот же SIGPIPE уже ловили
    # в `reformulation-tracker`.
    raw=$(grep -n "tr '\[:upper:\]' '\[:lower:\]'" "$f" 2>/dev/null \
          | grep -vE '^[0-9]+:[[:space:]]*#' \
          | grep -v 'to_lower() {' || true)
    [ -n "$raw" ] || continue

    # Сравнивается ли где-то с кириллическим литералом — снова СМОТРЯ В КОД, не в пояснения.
    # `knowledge-activator` попал в нарушители именно так: кириллица у него только в
    # комментариях, а сама свёртка обслуживает латиницу — сразу после неё стоит
    # `grep -oE '[a-z_]{3,}'`, который русские слова отбрасывает. Правило исключения
    # комментариев должно действовать на ОБА условия, иначе оно закрывает половину щели.
    cyr=$(grep -vE '^[[:space:]]*#' "$f" 2>/dev/null | LC_ALL=C grep -cE "(grep -[a-zA-Z]*[qcoEF][a-zA-Z]*|case |\*)[^\"']*[а-яёА-ЯЁ]" || true)
    if [ "${cyr:-0}" -gt 0 ] 2>/dev/null; then
        VIOLATIONS="$VIOLATIONS
  $b: $(printf '%s' "$raw" | head -2 | tr '\n' ' ')"
    fi
done

if [ -z "$VIOLATIONS" ]; then
    PASS=$((PASS + 1))
else
    FAIL=$((FAIL + 1))
    echo "FAIL [T1: сырая свёртка регистра рядом с кириллицей]:$VIOLATIONS"
fi

# --- 1b. Многобайтовый символ внутри скобочного выражения sed/grep ---
#
# Отдельный случай того же корня, допущенный при написании `pad_words`: в класс
# `[...—–-]` попали длинное и среднее тире. Они многобайтовые, рядом с `-` читаются как
# диапазон БАЙТОВ, и GNU sed в контейнере съедал байты кириллицы — «Да» превращалось
# в «\xNN а». На macOS то же выражение работало. Класс символов вообще не место для
# не-ASCII: замена делается литералами или `tr` по ASCII-набору.
MB_VIOLATIONS=""
for f in "$HOOKS_DIR"/*.sh; do
    b=$(basename "$f")
    # Не-ASCII определяется через `tr` с восьмеричным диапазоном, а не классом `[^\x00-\x7F]`.
    # Первая версия использовала именно такой класс — и BSD grep прочитал его как набор букв
    # `\`, `x`, `0`, `7`, `F`, отчего в нарушители попали четыре строки с чисто ASCII-скобками.
    # То есть детектор непереносимых классов сам был написан непереносимым классом.
    hits=""
    while IFS= read -r _ln; do
        [ -n "$_ln" ] || continue
        # Проверяется содержимое САМИХ скобок, а не всей строки. Промежуточная версия
        # флагала «в строке есть скобки И где-то есть не-ASCII» — и ловила законное
        # `grep -qE "(копируй[[:space:]]+всё)"`, где кириллица стоит СНАРУЖИ класса.
        printf '%s' "$_ln" | grep -o '\[[^]]*\]' 2>/dev/null | tr -d '\000-\177' | grep -q . || continue
        hits="$_ln"; break
    done <<INNER
$(grep -nE '(sed|grep)[^|]*\[' "$f" 2>/dev/null | grep -vE '^[0-9]+:[[:space:]]*#' || true)
INNER
    [ -n "$hits" ] && MB_VIOLATIONS="$MB_VIOLATIONS
  $b: $(printf '%s' "$hits" | head -1 | cut -c1-110)"
done
if [ -z "$MB_VIOLATIONS" ]; then
    PASS=$((PASS + 1))
else
    FAIL=$((FAIL + 1))
    echo "FAIL [T1b: многобайтовый символ в скобочном выражении]:$MB_VIOLATIONS"
fi

# --- 2. Поведение: обе ветки to_lower дают одинаковый результат
LIB="$HOOKS_DIR/portable-lib.sh"
if [ ! -f "$LIB" ]; then
    FAIL=$((FAIL + 1)); echo "FAIL [T2]: нет $LIB"
else
    TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
    SAMPLE='Подожди НЕ ТО. Fix IT Ёлка ЖУРНАЛ'
    EXPECT='подожди не то. fix it ёлка журнал'

    GOT_MAIN=$(bash -c "source '$LIB'; to_lower '$SAMPLE'" 2>/dev/null)
    # ветка без jq — подменяется условие, а не PATH: снос PATH убрал бы и sed с tr
    sed 's|if command -v jq >/dev/null 2>&1; then|if false; then|' "$LIB" > "$TMP/nojq.sh"
    GOT_FALLBACK=$(bash -c "source '$TMP/nojq.sh'; to_lower '$SAMPLE'" 2>/dev/null)

    for pair in "основной:$GOT_MAIN" "запасной:$GOT_FALLBACK"; do
        name="${pair%%:*}"; got="${pair#*:}"
        if [ "$got" = "$EXPECT" ]; then PASS=$((PASS + 1))
        else FAIL=$((FAIL + 1)); echo "FAIL [T2 путь $name]: ожидалось «$EXPECT», получено «$got»"; fi
    done
fi

# --- 3. Отрицательный контроль: проверка обязана уметь поймать нарушение
# Без него зелёный результат выше не означает, что T1 вообще на что-то смотрит.
NEG=$(mktemp -d)
cat > "$NEG/fake-guard.sh" <<'BAD'
#!/usr/bin/env bash
USER_LOWER=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')
case "$USER_LOWER" in *согласен*) echo "да" ;; esac
BAD
FOUND=""
if grep -q "tr '\[:upper:\]' '\[:lower:\]'" "$NEG/fake-guard.sh" &&
   LC_ALL=C grep -qE "(grep -[a-zA-Z]*[qcoEF][a-zA-Z]*|case |\*)[^\"']*[а-яёА-ЯЁ]" "$NEG/fake-guard.sh"; then
    FOUND="да"
fi
rm -rf "$NEG"
if [ -n "$FOUND" ]; then PASS=$((PASS + 1))
else FAIL=$((FAIL + 1)); echo "FAIL [T3 отрицательный контроль]: заведомо нарушающий файл не распознан — проверка ничего не измеряет"; fi

echo ""
echo "case folding portability tests: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
