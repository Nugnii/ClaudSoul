#!/usr/bin/env bash
# СУДИТ: scripts/docs-inventory.sh
# test_green_verdict_names_denominator.sh — зелёный вердикт замера называет свой знаменатель.
#
# Повод (4 сентября 2026). Просроченный замер `docs-inventory` отчитался «выполнен, находок
# нет» и напечатал три вердикта БЕЗ единого числа: «все механизмы дерева упомянуты»,
# «мёртвых упоминаний нет», «мёртвых ссылок нет». Отсутствие НАХОДОК и отсутствие ПРЕДМЕТА
# выглядели одинаково. Это уже расходилось однажды: комментарий в самом
# `scripts/docs-inventory.sh` фиксирует 13 механизмов замера аблации, не проверявшихся
# вовсе, — при отчёте «все механизмы дерева упомянуты». Тогда расширили универсум, но
# наблюдаемость зелёного не починили, и усохший универсум выглядел бы точно так же.
#
# Осмотр 49 замеров реестра из 51 (у двух команда без пути к скрипту — НЕ ПРОВЕРЕНО) дал
# 6 настоящих носителей в 4 скриптах и 3 ложных: у ложных знаменатель напечатан строкой
# выше (`${DENIES}`, `${#FILES[@]}`). Точность признака 6 из 9 — измерена, не оценена.
#
# Тест держит ОДНО свойство: у зелёной ветки есть цифра. Он НЕ судит, тот ли это
# ПОЧЕМУ У docs-inventory ПРОВЕРКА ИСХОДНИКА, А НЕ ПРОГОНА. Его прогон стоит 27 с, из них
# ~23 с — 93 запуска `python3 -c` в цикле ссылок (замерено 4 сентября 2026: один старт
# интерпретатора ≈ 0,25 с). В параллельном наборе эти 27 с перевели соседний
# `test_mode_arg_guard.sh` (86 с в одиночку) за его лимит 120 с. Свойство у него проверено
# ВРУЧНУЮ мутацией в тот же день: на прежнем скрипте три вердикта краснели. Здесь остаётся
# слабая форма — чтение исходника, — и это названо, а не выдано за поведенческую проверку.
#
# знаменатель, — это остаётся на осмотре: у `dead-sensor` цифра была и до правки, но
# Условие снятия этого предела: у замера появится объявленный предмет утверждения
# (строкой реестра `measurements.tsv` либо полем вывода), и тогда «та ли цифра»
# станет сверяемо машинно — предмет против знаменателя, — а не осмотром.
# считала окно сессий, а утверждение делалось об ОБЪЯВЛЕННЫХ признаках. Названный предел.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
EMPTY="$TMP/empty"; mkdir -p "$EMPTY"

# Пустая база знаний — ровно тот случай, ради которого правка: находок нет ПОТОМУ ЧТО
# предмета нет. Зелёное обязано это показать числом.
for pair in "escalation-age:scripts/escalation-age.sh" \
            "knowledge-staleness:scripts/knowledge-staleness.sh" \
            "dead-sensor:scripts/dead-sensor-check.sh"; do
    name="${pair%%:*}"; script="${pair#*:}"
    [ -f "$REPO/$script" ] || { bad "$name" "нет $script"; continue; }
    out=$(LESSONS_DIR="$EMPTY" bash "$REPO/$script" 2>&1)
    # Строка вердикта — та, что утверждает отсутствие. У неё обязана быть цифра.
    verdict=$(printf '%s\n' "$out" | grep -E 'нет|молчащих' | head -1)
    if [ -z "$verdict" ]; then
        # Скрипт мог честно сказать «объявленных признаков не найдено» — это тоже
        # называние отсутствия ПРЕДМЕТА, и оно засчитывается.
        grep -qE 'не найдено|не измеряли|пуст' <<< "${out}" && ok \
            || bad "$name" "на пустой базе не сказано ни о находках, ни об отсутствии предмета: $out"
        continue
    fi
    case "$verdict" in
        *[0-9]*) ok ;;
        *) bad "$name" "зелёный вердикт без числа: «${verdict}»" ;;
    esac
done

# docs-inventory: у трёх его вердиктов обязана быть подстановка знаменателя в ИСХОДНИКЕ.
# Форма слабее прогона (см. шапку) и названа слабой.
src="$REPO/scripts/docs-inventory.sh"
for var in checked_mech checked_ment checked_link; do
    if grep -q "\${${var}}" "$src"; then ok; else
        bad "docs-inventory" "зелёный вердикт не называет знаменатель ${var}"
    fi
done

echo ""
echo "green verdict denominator: $PASS/$((PASS + FAIL)) passed"
exit $(( FAIL != 0 ))
