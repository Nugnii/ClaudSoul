# --- Контрпример рода B — свойство ПРИЗНАКА, а не файла ---------------------------------
# «Возврат маркера есть различение» — правило обо всех местах сразу, и проверять его по
# именам файлов нельзя: файл бывает носителем ЗА ДРУГУЮ строку. `scripts/usage-outcome-audit.py`
# ровно таков — маркер `?` на :95 законен, а `except` вокруг `json.load` в `load()` глотает
# файлы отчёта и ужимает знаменатель покрытия. Поэтому сверяется сам регексп: ни одно его
# совпадение во всём дереве не смеет быть возвратом НЕПУСТОГО строкового литерала.
import re as _re
_MARKER = _re.compile(r'''(?:return|[a-z_]+\s*=)\s*(?:"([^"]+)"|\'([^\']+)\')\s*$''')
_seen = _bad = 0
for _f in m.tracked("*.sh", "*.py"):
    _t = _f.read_text(errors="replace")
    for _mo in m.B_PY.finditer(_t):
        _seen += 1
        _tail = _mo.group(0).strip().splitlines()[-1].strip()
        if _MARKER.search(_tail):
            _bad += 1
            # Строка считается по КОНЦУ совпадения: маркер стоит на последней строке
            # `except …:\n    return "?"`, а не на первой, и адрес от начала промахивался.
            bad("род B маркер", "%s:%d — `%s` пойман, хотя возврат маркера есть различение"
                % (_f.relative_to(ROOT), _t[:_mo.end()].rstrip("\n").count("\n") + 1, _tail))
if _seen == 0:
    skip("род B маркер", "совпадений B_PY в дереве нет — правило мерить не на чем")
elif _bad == 0:
    ok()

# Все рода «не измерены» — это не успех, а мёртвый прибор: реестр не увидел ни одного
# файла дерева (не тот корень, сломанный `git ls-files`, пустая копия). Без этой ноги тест
# выходил зелёным на реестре, положенном ВНЕ репозитория, — тот самый род B, ради которого
# он написан: «не смог посмотреть» было неотличимо от «смотреть нечего».
if PASS == 0:
    bad("прибор жив", "ни один род не дал носителей — реестр не видит дерева, "
                      "проверять контрпримеры не на чем")

print("")
print("defect registry counterexamples: %d/%d passed, %d не измерено"
      % (PASS, PASS + FAIL, SKIP))
sys.exit(1 if FAIL else 0)
