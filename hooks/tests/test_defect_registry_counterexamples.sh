# test_defect_registry_counterexamples.sh — контрпримеры реестра родов проверяются машиной,
# а не живут прозой рядом с регекспом.
#
# Повод (5 сентября 2026, разбор рода B). У каждого рода в `scripts/defect-class-carriers.py`
# написан КОНТРПРИМЕР — место, которое признак «обязан НЕ поймать», — и у каждого назван
# конкретный адрес в дереве. Проверял их только глаз автора в день написания; тестов у
# реестра не было ни одного. Первый же прогон этой проверки нашёл ТРИ нарушения в роде B:
# `B_PY` ловил `return "bad"` / `"?"` / `"unknown"`, тогда как контрпример двенадцатью
# строками выше объявляет возврат маркера РАЗЛИЧЕНИЕМ, а не его отсутствием.
#
# Цена не в трёх лишних строках списка. Носитель, попавший в очередь по нарушенному
# контрпримеру, зовёт чинить УЖЕ ПРАВИЛЬНОЕ место: очередь не убывает от работы — та же
# болезнь, что дважды описана в самом реестре (роды A и B).
#
# Устройство. У каждого рода ДВЕ ноги, и вторая обязательна:
#   · контрпример по своему адресу НЕ в списке носителей;
#   · положительный контроль — список рода не пуст.
# Без второй ноги отказавшая функция рода делает все контрпримеры зелёными вхолостую —
# ровно род B в самом приборе. Род с ПУСТЫМ списком (все носители починены) — законное
# состояние, и его контрпримеры честно объявляются НЕ ИЗМЕРЕННЫМИ: зелёными они не
# считаются, красными тоже, потому что мерить нечем.
#
# Зерно проверки — АДРЕС из комментария рода, и сверяется он в той же единице, в какой род
# отдаёт носителя: A по файлу, F по ШАБЛОНУ внутри файла, G и H по ИМЕНИ поля/переменной.
# Первая редакция теста сверяла всё по файлу и дала два ложных отказа: `test_docs_family_check.sh`
# числится носителем F за `docs/*.md` в строке-сообщении (:166), а его heredoc с
# `hooks/*.sh` (:398) — тот самый контрпример — пропускается верно.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
# Путь реестра переопределяется ради МУТАЦИИ: тест обязан краснеть на прежнем коде,
# и показать это можно только подсунув ему прежнюю редакцию файла.
REG="${DCC_REGISTRY:-$REPO/scripts/defect-class-carriers.py}"
[ -f "$REG" ] || { echo "FAIL: нет $REG"; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

cd "$REPO" || exit 1
python3 - "$REG" <<'PY'
import importlib.util, pathlib, sys

spec = importlib.util.spec_from_file_location("dcc", sys.argv[1])
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
# Корень берётся У САМОГО РЕЕСТРА, а не из cwd: носителей он перечисляет относительно
# СВОЕГО корня, и при `DCC_REGISTRY`, указывающем наружу (мутация), `relative_to(cwd)`
# упал бы исключением. Прежняя редакция этого не показала только потому, что у той копии
# список носителей был пуст и до `relative_to` дело не доходило.
ROOT = getattr(m, "ROOT", None) or pathlib.Path.cwd()

PASS = FAIL = SKIP = 0
def ok():
    globals().__setitem__("PASS", PASS + 1)
def bad(t, w):
    globals().__setitem__("FAIL", FAIL + 1)
    print("FAIL [%s]: %s" % (t, w))
def skip(t, w):
    globals().__setitem__("SKIP", SKIP + 1)
    print("НЕ ИЗМЕРЕНО [%s]: %s" % (t, w))

def rows_of(genus, fn):
    """Список носителей либо None, если род не измерим (упал или пуст)."""
    try:
        rows = fn()
    except Exception as e:                       # noqa: BLE001 — отказ обязан быть НАЗВАН
        bad("род %s" % genus, "функция носителей упала: %r" % (e,))
        return None
    if not rows:
        skip("род %s" % genus, "носителей нет — контрпримеры ниже мерить нечем")
        return None
    ok()
    return rows

# --- Сверка ПО ФАЙЛУ: род отдаёт файл целиком -------------------------------------------
