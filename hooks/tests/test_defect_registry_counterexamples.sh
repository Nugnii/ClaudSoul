        bad("род %s адрес" % genus, "контрпример %s исчез из дерева" % addr)
        continue
    hit = False
    for r in rows:
        if str(r[0].relative_to(ROOT)) != addr:
            continue
        for item in r[1]:
            got = item[0] if isinstance(item, (tuple, list)) else item
            if name in str(got):
                hit = True
    if hit:
        bad("род %s контрпример" % genus, "%s: `%s` пойман, хотя %s" % (addr, name, why))
    else:
