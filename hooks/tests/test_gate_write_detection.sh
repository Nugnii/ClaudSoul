#!/usr/bin/env bash
# test_gate_write_detection.sh — отказ гейта видит ЗАПИСЬ, а не форму команды.
#
# Результат: находка по ходу не даёт починить файл ни одним из применяемых способов правки
# Проверка результата: bash hooks/tests/test_gate_write_detection.sh даёт 0
#
# Повод, измеренный 29 августа 2026 на живой расшифровке этой же сессии. Отказ гейта
# срабатывает при EVENT=1 (находка по ходу) И IS_WRITE=1. Признак записи искал
# перенаправление в файл, tee и git commit. Замер способов правки за сессию:
#
#   запись через интерпретатор : 198   ← отказ НЕ срабатывал
#   правка на месте            :   7   ← отказ НЕ срабатывал
#   перенаправление            :  97   ← срабатывал
#   фиксация                   :  13   ← срабатывал
#
# То есть 205 правок из 315 (65%) проходили мимо отказа. В шапке гейта записан замер,
# отвергнувший признак «правка через Edit/Write»: «работа идёт через Bash». Вывод был
# верен, а признак накрыл лишь ту долю Bash-правок, у которой запись имеет ФОРМУ в строке
# команды. Запись внутри интерпретатора формы в строке не имеет.
#
# Корень: признак описывал СИНТАКСИС команды, а не её ПОСЛЕДСТВИЕ.
#
# КОНТРПРИМЕРЫ, оба проверяются ниже:
#   · читающий вызов интерпретатора (read_text, print, подсчёт) записью не является и
#     обязан проходить — иначе цепочку не из чего строить, а это прямое условие в шапке
#     гейта: «чтение, поиск и осмотр не блокируются»;
#   · поиск и потоковый разбор без правки на месте обязаны проходить.
set -uo pipefail

HOOKS="$(cd "$(dirname "$0")/.." && pwd)"
GATE="$HOOKS/five-whys-gate.sh"
[ -f "$GATE" ] || { echo "FAIL: нет $GATE"; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }

PASS=0; FAIL=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Находка по ходу в последнем блоке речи агента — это и есть событийный сигнал.
cat > "$TMP/t.jsonl" <<'TR'
{"message":{"role":"user","content":"делай"},"timestamp":"2026-08-29T12:00:00Z"}
{"message":{"role":"assistant","content":"Оказалось, разбор времени неверен — чиню."},"timestamp":"2026-08-29T12:01:00Z"}
TR

# Идентификатор сессии — ПОДПИСЬ случая, а не счётчик. Счётчик, увеличенный внутри
# подстановки команд, живёт в подоболочке и до родителя не доходит: все случаи ушли бы
# под одним идентификатором, второй и далее заглушил бы дедуп гейта, и тест показал бы
# «пропуск» там, где на деле отказ. Поймано первым же прогоном этого файла.
verdict() {   # <идентификатор> <команда> → ОТКАЗ | пропуск
    _out=$(STATE_DIR="$TMP" bash "$GATE" <<PAYLOAD
{"tool_name":"Bash","tool_input":{"command":$(printf '%s' "$2" | jq -Rs .)},"session_id":"$1","transcript_path":"$TMP/t.jsonl"}
PAYLOAD
)
    case "$_out" in *permissionDecision*) printf 'ОТКАЗ' ;; *) printf 'пропуск' ;; esac
}

expect() {   # <ожидание> <имя> <команда>
    _got=$(verdict "$2" "$3")
    if [ "$_got" = "$1" ]; then PASS=$((PASS+1))
    else FAIL=$((FAIL+1)); echo "FAIL [$2]: ждали $1, получили $_got"; fi
}

# --- записи: все формы, которыми в проекте правят файлы ---
expect ОТКАЗ   "запись-через-интерпретатор" 'python3 - <<PY
import pathlib; pathlib.Path("x").write_text("y")
PY'
expect ОТКАЗ   "открытие-на-запись"         'python3 - <<PY
open("x","w").write("y")
PY'
expect ОТКАЗ   "правка-на-месте"            'sed -i.bak "s/a/b/" hooks/x.sh'
expect ОТКАЗ   "перенаправление"            'cat > hooks/x.sh'
expect ОТКАЗ   "фиксация"                   'git commit -q -m x'

# --- КОНТРПРИМЕРЫ: чтение обязано проходить ---
expect пропуск "чтение-через-интерпретатор" 'python3 - <<PY
import pathlib; print(pathlib.Path("x").read_text())
PY'
expect пропуск "поиск"                      'grep -rn foo hooks/'
expect пропуск "потоковый-разбор"           'sed -n "1,5p" hooks/x.sh'

echo "gate write detection: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
