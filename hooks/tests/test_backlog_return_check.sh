#!/usr/bin/env bash
# СУДИТ: scripts/backlog-return-check.sh
# test_backlog_return_check.sh — характеризующий тест зеркала к backlog-recheck.
# Повод: 27 августа 2026 проход по девяти открытым пунктам показал, что два условия
# возврата невыполнимы по построению (D71 — источник данных заморожен разовым выгрузом,
# D92 — назначенный счётчик не существует), а одно (D92) при этом уже наступило с запасом.
# Текстовое условие может ссылаться на замер, которого нет, и молчать об этом сколько угодно.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
S="$REPO/scripts/backlog-return-check.sh"
[ -f "$S" ] || { echo "FAIL: $S not found"; exit 1; }

PASS=0; FAIL=0
ok()   { PASS=$((PASS+1)); }
bad()  { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }
has()  { grep -q -- "$2" <<< "$1" && ok || bad "$3" "не найдено '$2' в: $1"; }
hasnt(){ grep -q -- "$2" <<< "$1" && bad "$3" "лишнее '$2' в: $1" || ok; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
cd "$TMP" && git init -q . 2>/dev/null && git config user.email t@t && git config user.name t

write_backlog() { cat > "$TMP/BACKLOG.md"; }

run() { ( cd "$TMP" && bash "$S" 2>&1 ); }
code() { ( cd "$TMP" && bash "$S" >/dev/null 2>&1; echo $? ); }

# 1. Пункт без строки проверки — назван как дефект, ненулевой код.
write_backlog <<'EOF'
- ☐ **D10** первый, условие прозой и без команды
  **Условие возврата:** когда-нибудь станет лучше
EOF
OUT=$(run)
has "$OUT" "ПРОВЕРКИ НЕТ" "проза без команды названа"
has "$OUT" "D10" "пункт назван поимённо"
[ "$(code)" = "1" ] && ok || bad "код выхода" "ожидался 1 при пункте без проверки"

# 2. Команда проходит — условие наступило.
write_backlog <<'EOF'
- ☐ **D11** второй
  **Проверка возврата:** `true`
EOF
OUT=$(run)
has "$OUT" "НАСТУПИЛО" "выполнившееся условие названо"
has "$OUT" "D11" "поимённо"
[ "$(code)" = "0" ] && ok || bad "код выхода" "ожидался 0"

# 3. Команда падает — ещё не наступило, и это не дефект.
write_backlog <<'EOF'
- ☐ **D12** третий
  **Проверка возврата:** `false`
EOF
OUT=$(run)
has "$OUT" "ещё нет" "невыполнившееся условие в своём разделе"
hasnt "$OUT" "ПРОВЕРКИ НЕТ" "падение команды дефектом пункта не считается"

# 4. Решение владельца — не событие, проверять нечего.
write_backlog <<'EOF'
- ◐ **D13** четвёртый
  **Проверка возврата:** решение
EOF
OUT=$(run)
has "$OUT" "решения владельца" "решение отделено от событий"
hasnt "$OUT" "ПРОВЕРКИ НЕТ" "решение дефектом не считается"

# 5. Закрытый пункт не проверяется — им занят backlog-recheck.
write_backlog <<'EOF'
- ☑ **D14** закрытый, никакой строки проверки
- ☐ **D15** открытый
  **Проверка возврата:** `true`
EOF
OUT=$(run)
hasnt "$OUT" "D14" "закрытый пункт не разбирается"
has "$OUT" "D15" "открытый разбирается"

# 6. Команда берётся из своего пункта, а не из соседнего.
write_backlog <<'EOF'
- ☐ **D16** первый
  **Проверка возврата:** `false`
- ☐ **D17** второй
  **Проверка возврата:** `true`
EOF
OUT=$(run)
grep -q "НАСТУПИЛО.*D17" <<< "$OUT" && ok || bad "границы блока" "D17 не опознан как наступивший: $OUT"
grep -q "ещё нет.*D16" <<< "$OUT" && ok || bad "границы блока" "D16 не опознан как ждущий: $OUT"

# --- Прожарка 3 сентября 2026: пункт опознавался по ВИДУ строки, а не по РОЛИ в блоке ---
# Все семь ног ниже красны против редакции до правки (проверено копией `git archive HEAD`).

# 7. Блок берётся по границам пункта, а не подстрочным совпадением идентификатора.
#    `- ☐ **D280**` удовлетворяет шаблону `D28`, и страж брал условие ЧУЖОГО пункта.
write_backlog <<'EOF'
- ☐ **D28** открытый, условия возврата нет вовсе
  Условие возврата: когда-нибудь.

- ☐ **D280** сосед, чей номер начинается так же
  **Проверка возврата:** `true`
EOF
OUT=$(run)
grep -q "ПРОВЕРКИ НЕТ:.*D28\b" <<< "$OUT" && ok || bad "чужой блок" "D28 без условия не назван: $OUT"
grep -q "НАСТУПИЛО.*D280" <<< "$OUT" && ok || bad "чужой блок" "D280 не опознан наступившим: $OUT"
[ "$(code)" = "1" ] && ok || bad "чужой блок" "ожидался 1 при пункте без проверки"

# 8. Ссылка на родню в заголовке пункта — не идентификатор блока.
#    `- ☐ **D284** … — родня D279` удовлетворяла шаблону `D279`.
write_backlog <<'EOF'
- ☐ **D284** корпус подан полным текстом — родня D279
  **Проверка возврата:** `true`

- ☐ **D279** переоткрытый
  **Проверка возврата:** `false`
EOF
OUT=$(run)
grep -q "НАСТУПИЛО.*D284" <<< "$OUT" && ok || bad "родня в заголовке" "D284 не наступил: $OUT"
grep -q "ещё нет.*D279" <<< "$OUT" && ok || bad "родня в заголовке" "D279 взял чужое условие: $OUT"

# 9-10. Контрактная строка НАЧИНАЕТ строку файла. То же сочетание в прозе пункта —
#    цитата, и последствие у неё ровно одно: командой она не является (D244, тот же
#    якорь стоит в backlog-archive.sh и completion-gate.sh).
MARK="$TMP/СЛЕД-ИСПОЛНЕНИЯ"
rm -f "$MARK"
write_backlog <<EOF
- ☐ **D700** условие возврата держится ПРОЗОЙ
  Дефект. Пункт без строки **Проверка возврата:** \`touch $MARK\` попадает в раздел
  «проверки нет» — и это дефект ведения, а не скрипта.
EOF
OUT=$(run)
[ -e "$MARK" ] && bad "проза как команда" "команда из прозы исполнена: появился $MARK" || ok
grep -q "ПРОВЕРКИ НЕТ:.*D700" <<< "$OUT" && ok || bad "проза как команда" "D700 объявлен зелёным: $OUT"

# 11. Идентификатор не-D формы — пункт всё равно проверяется, а не исчезает из цикла.
write_backlog <<'EOF'
- ☐ **R7.1** открытый пункт без условия возврата
  **Результат.** что-то

- ☐ **D400** обычный
  **Проверка возврата:** `false`
EOF
OUT=$(run)
grep -q "ПРОВЕРКИ НЕТ:.*R7\.1" <<< "$OUT" && ok || bad "не-D идентификатор" "R7.1 не назван: $OUT"
[ "$(code)" = "1" ] && ok || bad "не-D идентификатор" "ожидался 1: пункт без проверки есть"

# 12. Идентификатор — токен ЦЕЛИКОМ и любой нумерации (общая функция библиотеки).
#     `D300a` отдавался как `D300` и склеивался с соседом; `R7.1` не отдавался вовсе.
. "$REPO/hooks/backlog-lib.sh"
IDS_GOT=$(printf '%s\n' '- ☐ **D300** первый' '- ☐ **D300a** подномер' '- ☐ **R7.1** не-D' '### D109 ☑ заголовок' | backlog_id_stream | tr '\n' ' ')
[ "$IDS_GOT" = "D300 D300a R7.1 D109 " ] && ok || bad "идентификатор по роли" "поток идентификаторов: '$IDS_GOT'"

# 13. `решение` читается ПОСЛЕ литерала, а не где угодно в строке: иначе команда,
#     в которой это слово встретилось, была бы принята за слово владельца.
write_backlog <<'EOF'
- ☐ **D401** команда, в которой есть слово решение
  **Проверка возврата:** `grep -q решение /dev/null`
EOF
OUT=$(run)
hasnt "$OUT" "решения владельца" "команда со словом «решение» осталась командой"
has "$OUT" "ещё нет" "и была исполнена: команда не нашла — условие не наступило"

# --- Проверка правки 3 сентября 2026: у блока границ три, статус — первой меткой ---
# Ноги 14-18 красны против первой редакции правки (проверено копией дерева).

# 14. Ограждение ``` — текст, а не структура. Контрактная строка, ПРОЦИТИРОВАННАЯ
#     образцом внутри ограждения, командой не является: шапка самого BACKLOG.md так
#     цитирует контракт (строки 18-22).
MARK="$TMP/СЛЕД-ИЗ-ПРИМЕРА"
rm -f "$MARK"
write_backlog <<EOF
- ☐ **D800** условия возврата НЕТ; тело лишь показывает, какую строку дописать
  Дописать в пункт строку такого вида:

  \`\`\`
  **Проверка возврата:** \`touch "$MARK"\`
  \`\`\`
EOF
OUT=$(run)
[ -e "$MARK" ] && bad "образец в ограждении" "команда из примера исполнена: появился $MARK" || ok
grep -q "ПРОВЕРКИ НЕТ:.*D800" <<< "$OUT" && ok || bad "образец в ограждении" "D800 объявлен зелёным: $OUT"

# 15. Пункт, НАРИСОВАННЫЙ внутри ограждения, пунктом не является — иначе образец
#     контракта в шапке заводил бы призрачные пункты.
write_backlog <<'EOF'
Так выглядит пункт:

```
- ☐ **D802** призрак из образца
  **Проверка возврата:** `true`
```

- ☐ **D803** настоящий
  **Проверка возврата:** `false`
EOF
OUT=$(run)
hasnt "$OUT" "D802" "нарисованный в ограждении пункт не разбирается"
has "$OUT" "D803" "настоящий разбирается"

# 16. Заголовок раздела ЗАКРЫВАЕТ блок пункта: контрактная строка пояснительного
#     раздела ниже принадлежит разделу, а не последнему пункту выше.
write_backlog <<'EOF'
## Раздел

- ☐ **D801** пункт БЕЗ условия возврата

## Как файл живёт

Внутри открытого пункта одна из двух строк:
**Проверка возврата:** `true`
— и это описание контракта, а не контракт какого-либо пункта.
EOF
OUT=$(run)
grep -q "ПРОВЕРКИ НЕТ:.*D801" <<< "$OUT" && ok || bad "граница раздела" "D801 взял строку из пояснения: $OUT"
[ "$(code)" = "1" ] && ok || bad "граница раздела" "ожидался 1 при пункте без проверки"

# 17. Статус — ПЕРВОЙ меткой строки, а не наличием метки где угодно: закрытый
#     заголовочный пункт, поминающий прежнее состояние, открытым не является.
#     Тот же разрыв библиотека уже закрыла ситом `backlog_status_is`.
write_backlog <<'EOF'
### D905 ☑ done — механизм построен (было ◐ с 2026-08-30)

  **Проверка.** `true` → 0

- ☐ **D906** живой открытый пункт
  **Проверка возврата:** `false`
EOF
OUT=$(run)
hasnt "$OUT" "D905" "закрытый заголовочный пункт не назван открытым"
has "$OUT" "D906" "живой открытый назван"
[ "$(code)" = "0" ] && ok || bad "статус первой меткой" "ожидался 0: у всех открытых условие есть"
#     И то же числом: перечень открытых у стража совпадает с перечнем библиотеки.
LIB_OPEN=$(backlog_ids "$TMP/BACKLOG.md" "$BACKLOG_OPEN_MARKS" | tr '\n' ' ')
GUARD_OPEN=$(sed -n 's/.*ещё нет://p;s/.*НАСТУПИЛО[^:]*://p;s/.*решения владельца[^:]*://p;s/.*ПРОВЕРКИ НЕТ://p' <<< "$OUT" | tr -s ' ' '\n' | grep -v '^$' | sort -u | tr '\n' ' ')
[ "$LIB_OPEN" = "$GUARD_OPEN" ] && ok || bad "статус первой меткой" "библиотека даёт '$LIB_OPEN', страж '$GUARD_OPEN'"

# 18. Табуляция в заголовке пункта не разрывает канал полей между awk и оболочкой:
#     хвост ЗАГОЛОВКА командой не становится, вердикт не переворачивается.
printf -- '- \342\230\220 **D902** \321\201 \321\202\320\260\320\261\321\203\320\273\321\217\321\206\320\270\320\265\011true\n  **\320\237\321\200\320\276\320\262\320\265\321\200\320\272\320\260 \320\262\320\276\320\267\320\262\321\200\320\260\321\202\320\260:** `false`\n' > "$TMP/BACKLOG.md"
grep -q "$(printf '\t')" "$TMP/BACKLOG.md" || bad "табуляция в заголовке" "фикстура без табуляции — нога зелена вхолостую"
OUT=$(run)
grep -q "ещё нет:.*D902" <<< "$OUT" && ok || bad "табуляция в заголовке" "исполнен хвост заголовка вместо условия: $OUT"
hasnt "$OUT" "НАСТУПИЛО" "вердикт не перевёрнут"

# --- Проверка правки 3 сентября 2026, второй круг: забор БИБЛИОТЕЧНЫЙ, граница по роли ---
# Ноги 19-23 красны против первой редакции правки (проверено копией дерева).

# 19. Забор `~~~` — та же разметка того же документа, что и ```. Библиотека знает обе
#     формы (`BACKLOG_FENCE_RE`), и страж обязан брать признак у неё, а не свой, более
#     узкий: контракт, ПРОЦИТИРОВАННЫЙ образцом внутри `~~~`, командой не является.
MARK="$TMP/СЛЕД-ИЗ-ТИЛЬДЫ"
rm -f "$MARK"
write_backlog <<EOF
- ☐ **D810** условия возврата НЕТ; тело лишь показывает образец, забор тильдами
  ~~~
  **Проверка возврата:** \`touch "$MARK"\`
  ~~~
EOF
grep -q '~~~' "$TMP/BACKLOG.md" || bad "забор тильдами" "фикстура без ~~~ — нога зелена вхолостую"
OUT=$(run)
[ -e "$MARK" ] && bad "забор тильдами" "команда из образца внутри ~~~ исполнена: появился $MARK" || ok
grep -q "ПРОВЕРКИ НЕТ:.*D810" <<< "$OUT" && ok || bad "забор тильдами" "D810 объявлен зелёным: $OUT"

# 20. Забор ПОМНИТ, каким маркером открыт. Показать забор кода образцом — законная форма
#     (``` внутри ~~~), и такая строка не смеет переворачивать состояние: иначе остаток
#     файла целиком выпадает из разбора вместе с настоящими открытыми пунктами.
write_backlog <<'EOF'
- ☐ **D811** показ забора образцом
  ~~~
  ```bash
  echo пример
  ~~~
  **Проверка возврата:** `false`

- ☐ **D812** второй открытый, ниже по файлу
  **Проверка возврата:** `true`
EOF
OUT=$(run)
grep -q "ещё нет:.*D811" <<< "$OUT" && ok || bad "парность забора" "настоящее условие D811 потеряно: $OUT"
grep -q "НАСТУПИЛО.*D812" <<< "$OUT" && ok || bad "парность забора" "D812 пропал: чужой маркер перевернул забор: $OUT"

# 21. Заголовок закрывает блок ПО РОЛИ, а не по виду: подзаголовок ВНУТРИ пункта
#     заголовочной вёрстки есть его собственный подраздел, а не следующий сосед.
write_backlog <<'EOF'
## Раздел

### D820 ☐ todo — пункт заголовочной вёрстки

#### Подробности

  **Проверка возврата:** `false`

### D821 ☐ todo — сосед того же уровня

## Как файл живёт

**Проверка возврата:** `true`
— описание контракта, а не контракт пункта.
EOF
OUT=$(run)
grep -q "ещё нет:.*D820" <<< "$OUT" && ok || bad "уровень заголовка" "условие D820 из его же подраздела не найдено: $OUT"
#     Встречная сторона: заголовок УРОВНЯ ВЫШЕ по-прежнему закрывает блок — иначе
#     починка V3 просто отменила бы границу N2 и вернула бы старый дефект.
grep -q "ПРОВЕРКИ НЕТ:.*D821" <<< "$OUT" && ok || bad "уровень заголовка" "D821 взял строку из пояснительного раздела: $OUT"

# 22. И то же ЧИСЛОМ: пункт, НАРИСОВАННЫЙ внутри `~~~`, — не пункт, и перечень открытых
#     у стража обязан совпасть с перечнем библиотеки. Форма «маркер не создан» такого
#     расхождения не ловит, а эта — ловит.
write_backlog <<'EOF'
Так выглядит пункт:

~~~
- ☐ **D840** призрак из образца
  **Проверка возврата:** `true`
~~~

- ☐ **D841** настоящий
  **Проверка возврата:** `false`
EOF
OUT=$(run)
hasnt "$OUT" "D840" "нарисованный внутри ~~~ пункт не разбирается"
LIB_OPEN=$(backlog_ids "$TMP/BACKLOG.md" "$BACKLOG_OPEN_MARKS" | tr '\n' ' ')
GUARD_OPEN=$(sed -n 's/.*ещё нет://p;s/.*НАСТУПИЛО[^:]*://p;s/.*решения владельца[^:]*://p;s/.*ПРОВЕРКИ НЕТ://p' <<< "$OUT" | tr -s ' ' '\n' | grep -v '^$' | sort -u | tr '\n' ' ')
[ "$LIB_OPEN" = "$GUARD_OPEN" ] && ok || bad "забор числом" "библиотека даёт '$LIB_OPEN', страж '$GUARD_OPEN'"

# 23. Библиотека старше скрипта — ОТКАЗ, а не молчаливое «открытых пунктов нет».
#     Забор снимается функцией библиотеки; при старой копии её нет, конвейер отдаёт пусто,
#     и страж без этой проверки объявил бы файл чистым кодом 0.
OLD=$(mktemp -d)
mkdir -p "$OLD/scripts" "$OLD/hooks"
cp "$REPO/scripts/backlog-return-check.sh" "$OLD/scripts/"
sed '/^backlog_strip_fenced()/,/^}/d' "$REPO/hooks/backlog-lib.sh" > "$OLD/hooks/backlog-lib.sh"
grep -q '^backlog_strip_fenced()' "$OLD/hooks/backlog-lib.sh" && bad "старая библиотека" "фикстура не обрезана — нога зелена вхолостую"
printf -- '- ☐ **D850** открытый без условия\n' > "$OLD/BACKLOG.md"
OLD_RC=$( cd "$OLD" && HOME=/nonexistent-home bash scripts/backlog-return-check.sh >/dev/null 2>&1; echo $? )
[ "$OLD_RC" = "2" ] && ok || bad "старая библиотека" "ожидался отказ кодом 2, получено $OLD_RC"
rm -rf "$OLD"

echo ""
# --- D369: команда дороже бюджета — свой исход, не «ещё нет» и не «проверки нет» ---
write_backlog <<'EOF'
- ☐ **D14** долгая команда
  **Проверка возврата:** `sleep 5`
- ☐ **D15** быстрая рядом с долгой
  **Проверка возврата:** `true`
EOF
OUT=$(cd "$TMP" && RETURN_CHECK_TIMEOUT=1 bash "$S" 2>&1); RC=$?
has "$OUT" "СРОК ИСТЁК" "срыв срока назван своим исходом"
grep -qE "СРОК ИСТЁК.*D14" <<< "$OUT" && ok || bad "срыв поимённо" "D14 не назван в строке срыва: $OUT"
grep -qE "НАСТУПИЛО.*D15" <<< "$OUT" && ok || bad "сосед проверен" "быстрая команда рядом с долгой не проверена: $OUT"
