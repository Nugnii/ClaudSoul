#!/usr/bin/env bash
# test_backlog_return_check.sh — характеризующий тест зеркала к backlog-recheck.
# Повод: 27 августа 2026 проход по девяти открытым пунктам показал, что два условия
# возврата невыполнимы по построению (D71 — источник данных заморожен разовым выгрузом,
# D92 — назначенный счётчик не существует), а одно (D92) при этом уже наступило с запасом.
# Текстовое условие может ссылаться на замер, которого нет, и молчать об этом сколько угодно.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
S="$REPO/scripts/backlog-return-check.sh"
[ -f "$S" ] || { echo "FAIL: $S not found"; exit 1; }

PASS=0; FAIL=0
ok()   { PASS=$((PASS+1)); }
bad()  { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }
has()  { grep -q -- "$2" <<< "$1" && ok || bad "$3" "не найдено '$2' в: $1"; }
hasnt(){ grep -q -- "$2" <<< "$1" && bad "$3" "лишнее '$2' в: $1" || ok; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
cd "$TMP" && git init -q . 2>/dev/null && git config user.email t@t && git config user.name t

write_backlog() { cat > "$TMP/BACKLOG.md"; }

run() { ( cd "$TMP" && bash "$S" 2>&1 ); }
code() { ( cd "$TMP" && bash "$S" >/dev/null 2>&1; echo $? ); }

# 1. Пункт без строки проверки — назван как дефект, ненулевой код.
write_backlog <<'EOF'
- ☐ **D10** первый, условие прозой и без команды
  **Условие возврата:** когда-нибудь станет лучше
EOF
OUT=$(run)
has "$OUT" "ПРОВЕРКИ НЕТ" "проза без команды названа"
has "$OUT" "D10" "пункт назван поимённо"
[ "$(code)" = "1" ] && ok || bad "код выхода" "ожидался 1 при пункте без проверки"

# 2. Команда проходит — условие наступило.
write_backlog <<'EOF'
- ☐ **D11** второй
  **Проверка возврата:** `true`
EOF
OUT=$(run)
has "$OUT" "НАСТУПИЛО" "выполнившееся условие названо"
has "$OUT" "D11" "поимённо"
[ "$(code)" = "0" ] && ok || bad "код выхода" "ожидался 0"

# 3. Команда падает — ещё не наступило, и это не дефект.
write_backlog <<'EOF'
- ☐ **D12** третий
  **Проверка возврата:** `false`
EOF
OUT=$(run)
has "$OUT" "ещё нет" "невыполнившееся условие в своём разделе"
hasnt "$OUT" "ПРОВЕРКИ НЕТ" "падение команды дефектом пункта не считается"

# 4. Решение владельца — не событие, проверять нечего.
write_backlog <<'EOF'
- ◐ **D13** четвёртый
  **Проверка возврата:** решение
EOF
OUT=$(run)
has "$OUT" "решения владельца" "решение отделено от событий"
hasnt "$OUT" "ПРОВЕРКИ НЕТ" "решение дефектом не считается"

# 5. Закрытый пункт не проверяется — им занят backlog-recheck.
write_backlog <<'EOF'
- ☑ **D14** закрытый, никакой строки проверки
- ☐ **D15** открытый
  **Проверка возврата:** `true`
EOF
OUT=$(run)
hasnt "$OUT" "D14" "закрытый пункт не разбирается"
has "$OUT" "D15" "открытый разбирается"

# 6. Команда берётся из своего пункта, а не из соседнего.
write_backlog <<'EOF'
- ☐ **D16** первый
  **Проверка возврата:** `false`
- ☐ **D17** второй
  **Проверка возврата:** `true`
EOF
OUT=$(run)
grep -q "НАСТУПИЛО.*D17" <<< "$OUT" && ok || bad "границы блока" "D17 не опознан как наступивший: $OUT"
grep -q "ещё нет.*D16" <<< "$OUT" && ok || bad "границы блока" "D16 не опознан как ждущий: $OUT"

echo ""
echo "backlog-return-check tests: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
