#!/usr/bin/env bash
# test_backlog_archive.sh — в рабочем бэклоге остаётся только несделанное.
#
# Повод дословно: «сейчас в бэклоге я наблюдаю отмеченные как выполненные пункты, и он
# из-за них распухший». Замер на момент заведения: 21 открытый против 32 выполненных,
# 65% символов файла — уже закрытое.
#
# Уборка в v1.14.7 шла РАЗДЕЛАМИ: в архив уезжал раздел без открытых пунктов, выполненный
# пункт внутри живого раздела оставался. Одной сессии хватило, чтобы файл распух заново, —
# то есть уборка была обязанностью без владельца и срока. Здесь проверяется поштучный
# перенос и то, что свидетельства закрытий не теряются.

set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPT="$REPO/scripts/backlog-archive.sh"
[ -f "$SCRIPT" ] || { echo "FAIL: нет $SCRIPT"; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

PASS=0
FAIL=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
has() { grep -qF -- "$1" <<< "$2"; }

_fixture() {
    cat > "$TMP/BACKLOG.md" <<'EOF'
# BACKLOG

Преамбула, обязана остаться.

## Раздел А — часть закрыта

- ☐ **X1** открытый
  продолжение открытого
- ☑ **X2** закрытый
  продолжение закрытого

## Раздел Б — всё закрыто

- ☑ **Y1** закрытый
- ⊘ **Y2** отказ

## Раздел В — только в работе

- ◐ **Z1** взят в работу
EOF
    printf '# BACKLOG — архив\n' > "$TMP/BACKLOG-archive.md"
}
run() { BACKLOG_FILE="$TMP/BACKLOG.md" BACKLOG_ARCHIVE="$TMP/BACKLOG-archive.md" bash "$SCRIPT" "${1:-run}" 2>&1; }

_fixture
# --- T1: режим check считает и ничего не двигает ---
BEFORE=$(cat "$TMP/BACKLOG.md")
OUT=$(run check); RC=$?
has "выполненных пунктов: 3" "$OUT" && ok || bad "T1a" "неверный счёт выполненных: $OUT"
has "открытых: 2" "$OUT" && ok || bad "T1b" "◐ не посчитан как открытый: $OUT"
[ "$RC" -ne 0 ] && ok || bad "T1c" "check с накопленным выполненным вернул 0 — просрочка невидима"
[ "$(cat "$TMP/BACKLOG.md")" = "$BEFORE" ] && ok || bad "T1d" "режим check изменил файл"

# --- T2: перенос — выполненное уходит, несделанное остаётся ---
run run >/dev/null
B=$(cat "$TMP/BACKLOG.md"); A=$(cat "$TMP/BACKLOG-archive.md")
has "X1" "$B" && ok || bad "T2a" "открытый пункт потерян"
has "Z1" "$B" && ok || bad "T2b" "пункт в работе (◐) унесён в архив — он не сделан"
has "Преамбула" "$B" && ok || bad "T2c" "преамбула потеряна"
has "X2" "$B" && bad "T2d" "выполненный пункт остался в рабочем файле" || ok
has "Y2" "$B" && bad "T2e" "отказ (⊘) остался в рабочем файле" || ok

# --- T3: продолжение пункта уезжает вместе с ним, а не отрывается ---
has "продолжение закрытого" "$A" && ok || bad "T3a" "продолжение закрытого пункта не перенесено"
has "продолжение закрытого" "$B" && bad "T3b" "продолжение осталось сиротой в рабочем файле" || ok
has "продолжение открытого" "$B" && ok || bad "T3c" "продолжение открытого пункта потеряно"

# --- T4: свидетельства закрытий сохранены целиком ---
for it in X2 Y1 Y2; do
    has "$it" "$A" && ok || bad "T4:$it" "свидетельство закрытия потеряно — архив не источник для перепроверки"
done

# --- T5: заголовок раздела уцелевает только при живых пунктах ---
has "Раздел А" "$B" && ok || bad "T5a" "заголовок с открытым пунктом выброшен"
has "Раздел Б" "$B" && bad "T5b" "заголовок без открытых пунктов остался пустым" || ok
has "Раздел Б" "$A" && ok || bad "T5c" "контекст раздела не перенесён в архив"

# --- T6: заголовок не слипается с предыдущим текстом ---
grep -qE '^\S.*\n?## ' <<< "$B" && bad "T6" "заголовок слип с текстом" || ok

# --- T7: повторный прогон ничего не меняет (идемпотентность) ---
B2_BEFORE=$(cat "$TMP/BACKLOG.md")
OUT=$(run run)
has "Переносить нечего" "$OUT" && ok || bad "T7a" "повторный прогон не распознал, что переносить нечего: $OUT"
[ "$(cat "$TMP/BACKLOG.md")" = "$B2_BEFORE" ] && ok || bad "T7b" "повторный прогон изменил файл"

# --- T8: отрицательный контроль — вернуть выполненный пункт, перенос обязан снова сработать ---
# Без него зелёный T7 не отличим от «скрипт вообще перестал что-либо делать».
printf -- '- ☑ **W9** снова закрытый\n' >> "$TMP/BACKLOG.md"
run run >/dev/null
has "W9" "$(cat "$TMP/BACKLOG.md")" && bad "T8" "подложенный выполненный пункт не перенесён — перенос ничего не делает" || ok

# --- T9: реестр знает про уборку, и она там ДЕЙСТВИЕМ, а не отчётом ---
# Первая версия строки стояла в режиме `check`: замер честно отрабатывал, сообщал
# «13 выполненных пунктов» — и файл оставался распухшим. Уборка отчитывалась вместо того,
# чтобы убирать; ровно тот класс, что чинится в этом же файле.
_line=$(grep '^backlog-archive' "$REPO/scripts/measurements.tsv" 2>/dev/null || true)
[ -n "$_line" ] && ok || bad "T9a" "уборки нет в реестре замеров: через сессию файл распухнет снова"
grep -q 'backlog-archive\.sh run' <<< "$_line" && ok \
    || bad "T9b" "в реестре стоит отчёт, а не уборка: файл не почистится сам"

echo ""
echo "backlog archive tests: $PASS/$((PASS + FAIL)) passed"
[ "$FAIL" -eq 0 ]
