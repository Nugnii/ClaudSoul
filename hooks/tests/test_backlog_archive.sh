#!/usr/bin/env bash
# test_backlog_archive.sh — в рабочем бэклоге остаётся только несделанное.
#
# Повод дословно: «сейчас в бэклоге я наблюдаю отмеченные как выполненные пункты, и он
# из-за них распухший». Замер на момент заведения: 21 открытый против 32 выполненных,
# 65% символов файла — уже закрытое.
#
# Уборка в v1.14.7 шла РАЗДЕЛАМИ: в архив уезжал раздел без открытых пунктов, выполненный
# пункт внутри живого раздела оставался. Одной сессии хватило, чтобы файл распух заново, —
# то есть уборка была обязанностью без владельца и срока. Здесь проверяется поштучный
# перенос и то, что свидетельства закрытий не теряются.

set -uo pipefail

# РАМКУ ЗАДАЁТ ТЕСТ, А НЕ ОКРУЖЕНИЕ (D334, 9 сентября 2026). `BACKLOG_CHECKS_NESTED=1`
# ставит себе `hooks/completion-gate.sh` — защита от кольца исполнителей, — и любой прогон
# ИЗ-ПОД него наследовал маркер. Архиватор тогда выходит на двери вложенности
# (`scripts/backlog-archive.sh:82-85`), и 50 проверок из 116 краснели, не проверив ничего:
# красный от рамки неотличим от красного по делу. Зеркало D291, где тот же маркер делал
# проверку красной ВСЕГДА. Саму дверь проверяет T26 — намеренно, а не наследованием.
unset BACKLOG_CHECKS_NESTED

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPT="$REPO/scripts/backlog-archive.sh"
[ -f "$SCRIPT" ] || { echo "FAIL: нет $SCRIPT"; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "SKIP: нет python3"; exit 0; }

PASS=0
FAIL=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
ok()  { PASS=$((PASS + 1)); }
bad() { FAIL=$((FAIL + 1)); echo "FAIL [$1]: $2"; }
has() { grep -qF -- "$1" <<< "$2"; }

_fixture() {
    cat > "$TMP/BACKLOG.md" <<'EOF'
# BACKLOG

Преамбула, обязана остаться.

## Раздел А — часть закрыта

- ☐ **X1** открытый
  продолжение открытого
- ☑ **X2** закрытый
  продолжение закрытого
  **Проверка.** `true`

## Раздел Б — всё закрыто

- ☑ **Y1** закрытый
  **Проверка.** `true`
- ⊘ **Y2** отказ
  **Вердикт.** цена отказа названа.

## Раздел В — только в работе

- ◐ **Z1** взят в работу
EOF
    printf '# BACKLOG — архив\n' > "$TMP/BACKLOG-archive.md"
}
run() { BACKLOG_FILE="$TMP/BACKLOG.md" BACKLOG_ARCHIVE="$TMP/BACKLOG-archive.md" bash "$SCRIPT" "${1:-run}" 2>&1; }

_fixture
# --- T1: режим check считает и ничего не двигает ---
BEFORE=$(cat "$TMP/BACKLOG.md")
OUT=$(run check); RC=$?
has "выполненных пунктов: 3" "$OUT" && ok || bad "T1a" "неверный счёт выполненных: $OUT"
has "открытых: 2" "$OUT" && ok || bad "T1b" "◐ не посчитан как открытый: $OUT"
[ "$RC" -ne 0 ] && ok || bad "T1c" "check с накопленным выполненным вернул 0 — просрочка невидима"
[ "$(cat "$TMP/BACKLOG.md")" = "$BEFORE" ] && ok || bad "T1d" "режим check изменил файл"

# --- T2: перенос — выполненное уходит, несделанное остаётся ---
run run >/dev/null
B=$(cat "$TMP/BACKLOG.md"); A=$(cat "$TMP/BACKLOG-archive.md")
has "X1" "$B" && ok || bad "T2a" "открытый пункт потерян"
has "Z1" "$B" && ok || bad "T2b" "пункт в работе (◐) унесён в архив — он не сделан"
has "Преамбула" "$B" && ok || bad "T2c" "преамбула потеряна"
has "X2" "$B" && bad "T2d" "выполненный пункт остался в рабочем файле" || ok
has "Y2" "$B" && bad "T2e" "отказ (⊘) остался в рабочем файле" || ok

# --- T3: продолжение пункта уезжает вместе с ним, а не отрывается ---
has "продолжение закрытого" "$A" && ok || bad "T3a" "продолжение закрытого пункта не перенесено"
has "продолжение закрытого" "$B" && bad "T3b" "продолжение осталось сиротой в рабочем файле" || ok
has "продолжение открытого" "$B" && ok || bad "T3c" "продолжение открытого пункта потеряно"

# --- T4: свидетельства закрытий сохранены целиком ---
for it in X2 Y1 Y2; do
    has "$it" "$A" && ok || bad "T4:$it" "свидетельство закрытия потеряно — архив не источник для перепроверки"
done

# --- T5: заголовок раздела уцелевает только при живых пунктах ---
has "Раздел А" "$B" && ok || bad "T5a" "заголовок с открытым пунктом выброшен"
has "Раздел Б" "$B" && bad "T5b" "заголовок без открытых пунктов остался пустым" || ok
has "Раздел Б" "$A" && ok || bad "T5c" "контекст раздела не перенесён в архив"

# --- T6: заголовок не слипается с предыдущим текстом ---
grep -qE '^\S.*\n?## ' <<< "$B" && bad "T6" "заголовок слип с текстом" || ok

# --- T7: повторный прогон ничего не меняет (идемпотентность) ---
B2_BEFORE=$(cat "$TMP/BACKLOG.md")
OUT=$(run run)
has "Переносить нечего" "$OUT" && ok || bad "T7a" "повторный прогон не распознал, что переносить нечего: $OUT"
[ "$(cat "$TMP/BACKLOG.md")" = "$B2_BEFORE" ] && ok || bad "T7b" "повторный прогон изменил файл"

# --- T8: отрицательный контроль — вернуть выполненный пункт, перенос обязан снова сработать ---
# Без него зелёный T7 не отличим от «скрипт вообще перестал что-либо делать».
printf -- '- ☑ **W9** снова закрытый\n  **Проверка.** `true`\n' >> "$TMP/BACKLOG.md"
run run >/dev/null
has "W9" "$(cat "$TMP/BACKLOG.md")" && bad "T8" "подложенный выполненный пункт не перенесён — перенос ничего не делает" || ok

# --- T9: реестр знает про уборку, и она там ДЕЙСТВИЕМ, а не отчётом ---
# Первая версия строки стояла в режиме `check`: замер честно отрабатывал, сообщал
# «13 выполненных пунктов» — и файл оставался распухшим. Уборка отчитывалась вместо того,
# чтобы убирать; ровно тот класс, что чинится в этом же файле.
_line=$(grep '^backlog-archive' "$REPO/scripts/measurements.tsv" 2>/dev/null || true)
[ -n "$_line" ] && ok || bad "T9a" "уборки нет в реестре замеров: через сессию файл распухнет снова"
grep -q 'backlog-archive\.sh run' <<< "$_line" && ok \
    || bad "T9b" "в реестре стоит отчёт, а не уборка: файл не почистится сам"

# --- T10: перенос СОХРАНЯЕТ mtime рабочего файла ---
# Уборка идёт на каждом Stop, а сверщик исхода хода судит «агент записал в носитель» по mtime
# BACKLOG.md: bump подделал бы `none` → `recorded` в том же ходе, где закрыли пункт (D210).
# Фикстуре ставится старое mtime — иначе запись и проверка в одной секунде, и мутация проходит.
_fixture
python3 -c "import os,sys; os.utime(sys.argv[1], (1700000000, 1700000000))" "$TMP/BACKLOG.md"
run run >/dev/null
_m=$(python3 -c "import os,sys; print(int(os.stat(sys.argv[1]).st_mtime))" "$TMP/BACKLOG.md")
[ "$_m" -eq 1700000000 ] && ok || bad "T10" "перенос сдвинул mtime ($_m) — сверщик исхода примет уборку за запись агента"
has "X2" "$(cat "$TMP/BACKLOG.md")" && bad "T10b" "при сохранении mtime перенос не состоялся" || ok

# --- Режим проверки называет то же, что покажет исполнение ---
# До 1 сентября 2026 блокеры печатались только при `run`: `check` выдавал счёт и молчал о
# том, что перенос не пройдёт. Увидеть отказ удалось лишь потому, что `--check` (чужое для
# этого скрипта написание) исполнился как `run`. Печать находки была привязана к режиму
# завершения — смешаны «что показать» и «чем завершиться».
TCK="$TMP/check-mode"; mkdir -p "$TCK"
cat > "$TCK/BACKLOG.md" <<'BLC'
# BACKLOG

- ⊘ **D900** Отказ без строки вердикта.
  **Дефект.** Ничего.

- ◐ **D901** Открытый пункт.
BLC
: > "$TCK/arch.md"
_ck_out=$(BACKLOG_FILE="$TCK/BACKLOG.md" BACKLOG_ARCHIVE="$TCK/arch.md" \
          bash "$SCRIPT" check 2>&1); _ck_rc=$?
case "$_ck_out" in
    *"D900"*) ok ;;
    *) bad "check-silent" "режим проверки не назвал блокер: $_ck_out" ;;
esac
[ "$_ck_rc" -ne 0 ] && ok || bad "check-rc" "проверка при блокере вернула 0"
# КОНТРПРИМЕР: проверка НЕ переносит и НЕ правит файл — иначе это не проверка
grep -q 'D900' "$TCK/BACKLOG.md" && ok || bad "check-writes" "режим проверки унёс пункт"
[ ! -s "$TCK/arch.md" ] && ok || bad "check-arch" "режим проверки записал в архив"
# И чистый случай: нечего переносить, блокеров нет → 0
cat > "$TCK/clean.md" <<'BLD'
# BACKLOG

- ◐ **D902** Только открытый пункт.
BLD
BACKLOG_FILE="$TCK/clean.md" BACKLOG_ARCHIVE="$TCK/arch2.md" bash "$SCRIPT" check >/dev/null 2>&1
[ $? -eq 0 ] && ok || bad "check-clean" "чистый бэклог дал ненулевой код в режиме проверки"

# ─────────────────────────────────────────────────────────────────────────────
# Пункт опознаётся по РОЛИ токенов, а не по ВИДУ строки.
#
# Прожарка 3 сентября 2026: признак «префикс + произвольный текст + метка где угодно»
# звал пунктом всё, что похоже. Обе поражённые формы взяты из живого корпуса —
# в BACKLOG-archive.md заголовок раздела с меткой один, строк ТЕЛА с меткой одиннадцать.
# Ноги ниже держат разбор по ролям, а не конкретные входы атак.

_arch() {   # _arch <каталог> <режим> [доп. окружение…]
    local d="$1" mode="$2"; shift 2
    env "$@" BACKLOG_FILE="$d/BACKLOG.md" BACKLOG_ARCHIVE="$d/ARCH.md" \
        bash "$SCRIPT" "$mode" 2>&1
}

# --- T11: заголовок РАЗДЕЛА, упомянувший метку, пунктом не является ---
# «## Прогон 2026-06-20 — пилот `hooks/` (выполнен, все ☑)» — BACKLOG-archive.md:41.
# Ложный приём тут стоит дороже всего: раздел с вводным абзацем уезжает в архив, а
# открытые пункты под ним сиротеют и встают под ЧУЖОЙ заголовок.
T11="$TMP/section"; mkdir -p "$T11"
cat > "$T11/BACKLOG.md" <<'EOF'
# BACKLOG

## Раздел A

- ☐ **D501** открытый пункт A

## Прогон 2026-06-20 — пилот `hooks/` (выполнен, все ☑)

Вводный абзац раздела.

- ☐ **D502** открытый пункт B
EOF
printf '# BACKLOG — архив\n' > "$T11/ARCH.md"
_o=$(_arch "$T11" run)
grep -qF 'Прогон 2026-06-20' "$T11/BACKLOG.md" && ok || bad "T11a" "заголовок раздела с меткой унесён в архив как пункт"
grep -qF 'Вводный абзац раздела.' "$T11/ARCH.md" && bad "T11b" "вводный абзац живого раздела уехал в архив" || ok
has "Переносить нечего" "$_o" && ok || bad "T11c" "архиватор нашёл что переносить при нуле выполненных пунктов: $_o"

# --- T12: строка ТЕЛА пункта, несущая метку, пунктом не является ---
# «- Статус:     ☑ done (2026-06-20)», «- Источник: F7 … · ☐ todo» — 11 таких строк
# в архиве. Ложный приём вырезал ХВОСТ живого открытого пункта: из тела исчезали
# «Результат» и «Проверка возврата» — те самые строки, отсутствие которых стражи
# потом вменяют пункту в вину.
T12="$TMP/body"; mkdir -p "$T12"
cat > "$T12/BACKLOG.md" <<'EOF'
# BACKLOG

## Раздел

### D601 ☐ Открытый пункт в заголовочной вёрстке

**Дефект.** Носители:

- `hooks/a.sh` — уже починен, ☑
- `hooks/b.sh` — ещё нет
- Статус:     ☑ done (2026-06-20)

**Результат.** Оба носителя починены.
**Проверка возврата:** `false`

### D602 ☐ Следующий открытый пункт
EOF
printf '# BACKLOG — архив\n' > "$T12/ARCH.md"
_o=$(_arch "$T12" run)
_b=$(cat "$T12/BACKLOG.md")
for _need in '`hooks/b.sh` — ещё нет' '**Результат.** Оба носителя починены.' '**Проверка возврата:** `false`'; do
    has "$_need" "$_b" && ok || bad "T12:$_need" "строка тела ОТКРЫТОГО пункта вырезана и унесена"
done
grep -qF 'Проверка возврата' "$T12/ARCH.md" && bad "T12arch" "тело открытого пункта уехало в архив закрытых" || ok

# --- T13: свидетельство пишется ПЕРВЫМ — при недоступном архиве пункт не пропадает ---
# BACKLOG_ARCHIVE — штатный вход скрипта; права, полный диск или чужой путь дают отказ
# записи без всякого умысла. При обратном порядке текста закрытого пункта не оставалось
# НИ в рабочем файле, НИ в архиве.
T13="$TMP/ro"; mkdir -p "$T13/lock"
cat > "$T13/BACKLOG.md" <<'EOF'
# BACKLOG

## Раздел

- ☑ **D42** закрытый пункт
  свидетельство закрытия — единственный экземпляр
- ☐ **D43** открытый
EOF
printf '# BACKLOG — архив\n' > "$T13/lock/ARCH.md"
chmod 400 "$T13/lock/ARCH.md"; chmod 500 "$T13/lock"
_o=$(BACKLOG_FILE="$T13/BACKLOG.md" BACKLOG_ARCHIVE="$T13/lock/ARCH.md" \
     BACKLOG_CONTRACT_MIN_ID=99999 bash "$SCRIPT" run 2>&1); _rc=$?
chmod 700 "$T13/lock"; chmod 600 "$T13/lock/ARCH.md"
if grep -qF 'свидетельство закрытия — единственный экземпляр' "$T13/BACKLOG.md" \
   || grep -qF 'свидетельство закрытия — единственный экземпляр' "$T13/lock/ARCH.md"; then ok
else bad "T13a" "при отказе записи архива текст закрытого пункта потерян и там, и там"; fi
[ "$_rc" -ne 0 ] && ok || bad "T13b" "несостоявшийся перенос отчитался успехом (rc=$_rc)"
case "$_o" in *Traceback*) bad "T13c" "наружу ушёл питоновский traceback: $_o" ;; *) ok ;; esac

# --- T14: труба в заголовке пункта не делает его невидимым ---
# Прежнее `[^|]*` в признаке запрещало `|` до метки, и закрытый пункт оставался в рабочем
# файле навсегда — а «Проверка результата» архиватора при этом была ЗЕЛЁНОЙ, потому что
# выражена той же слепотой. В архиве 11 строк пунктов с трубой (`sid|key|date`, `cmd | grep -q`).
T14="$TMP/pipe"; mkdir -p "$T14"
cat > "$T14/BACKLOG.md" <<'EOF'
# BACKLOG

## Раздел

### D702 · Труба `cmd | grep -q` теряет код возврата — ☑ done (2026-09-03)
**Проверка.** `true`
свидетельство закрытия D702

### D703 · Разбор строки `sid|key|date` — ☐ открытый пункт
EOF
printf '# BACKLOG — архив\n' > "$T14/ARCH.md"
_o=$(_arch "$T14" check); _rc=$?
has "выполненных пунктов: 1" "$_o" && ok || bad "T14a" "пункт с трубой в заголовке не опознан: $_o"
has "открытых: 1" "$_o" && ok || bad "T14b" "открытый пункт с трубой не опознан: $_o"
[ "$_rc" -ne 0 ] && ok || bad "T14c" "«Проверка результата» зелена при закрытом пункте в рабочем файле"
_arch "$T14" run >/dev/null
grep -qF 'свидетельство закрытия D702' "$T14/ARCH.md" && ok || bad "T14d" "пункт с трубой не перенесён"
grep -qF 'D703' "$T14/BACKLOG.md" && ok || bad "T14e" "открытый пункт с трубой унесён"

# --- T15: метка — ПОЛЕ СТАТУСА, а не любой глиф строки ---
# «- ☑ **D250** … — было ◐, работа закончена»: закрытый пункт, чей заголовок законно
# называет ПРЕЖНЕЕ состояние. Отбор по присутствию метки числил его открытым — библиотека
# расходилась с архиватором, а страж возврата требовал «Проверку возврата» у закрытого.
T15="$TMP/mark"; mkdir -p "$T15"
cat > "$T15/BACKLOG.md" <<'EOF'
# BACKLOG

**Легенда статусов:** ☐ todo · ◐ in-progress · ☑ done · ⊘ waived

## Раздел

- ☑ **D250** Страж слеп к автотаблицам — было ◐, работа закончена.
  **Проверка.** `true`

- ☐ **D251** Обычный открытый пункт — раньше стоял ☑ по ошибке.
EOF
printf '# BACKLOG — архив\n' > "$T15/ARCH.md"
_o=$(_arch "$T15" check)
has "выполненных пунктов: 1" "$_o" && ok || bad "T15a" "статус взят не первой меткой строки: $_o"
has "открытых: 1" "$_o" && ok || bad "T15b" "открытых посчитано не 1: $_o"
# и то же самое — у общей библиотеки, из которой кормятся остальные читатели
_LIB="$REPO/hooks/backlog-lib.sh"
if [ -f "$_LIB" ]; then
    # shellcheck source=/dev/null
    . "$_LIB"
    _op=$(backlog_ids "$T15/BACKLOG.md" "$BACKLOG_OPEN_MARKS" | tr '\n' ' ')
    _dn=$(backlog_ids "$T15/BACKLOG.md" "$BACKLOG_DONE_MARKS" | tr '\n' ' ')
    [ "$_op" = "D251 " ] && ok || bad "T15c" "библиотека считает открытыми [$_op], открыт один D251"
    [ "$_dn" = "D250 " ] && ok || bad "T15d" "библиотека считает закрытыми [$_dn], закрыт один D250"
    backlog_is_item '- Статус:     ☑ done (2026-06-20)' \
        && bad "T15e" "строка тела пункта засчитана пунктом" || ok
    backlog_is_item '## Прогон 2026-06-20 — пилот `hooks/` (выполнен, все ☑)' \
        && bad "T15f" "заголовок раздела засчитан пунктом" || ok
    # Легенда, написанная СПИСКОМ. Шапка библиотеки объявляет строку легенды
    # контрпримером, а признак до 3 сентября 2026 требовал идентификатор только от
    # заголовочной вёрстки — и звал пунктом «- ☑ done — сделано». Цена симметрии
    # измерена: из 187 списочных пунктов живого корпуса идентификатор несут 187.
    backlog_is_item '- ☑ done — сделано' \
        && bad "T15g" "легенда, написанная списком, засчитана пунктом" || ok
    backlog_is_item '- ☐ todo — ещё не начато' \
