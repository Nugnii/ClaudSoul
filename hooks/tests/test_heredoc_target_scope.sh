#!/usr/bin/env bash
# test_heredoc_target_scope.sh — предикат heredoc_target_regex видит СВОЮ цель и только её.
#
# Повод 8 сентября 2026. У предиката не было ни одного теста, и он молча выключился: замер
# по корпусу дал 1 найденную цель на 1357 команд, записывающих файл heredoc-ом. На нём стоят
# два признака уровня ОТКАЗА — их молчание десять дней было неотличимо от «нарушений нет».
#
# Три правила, каждое со своим плечом и контрпримером:
#   1. цель бывает ДО маркера — `cat > hooks/x.sh <<'EOF'` — это одна команда;
#   2. цель за РАЗДЕЛИТЕЛЕМ команд чужая — `cmd > /tmp/x.sh && python3 - <<PY`;
#   3. строка внутри ЧУЖОГО тела heredoc целью не является — там текст, а не команда;
#   4. цель бывает и ВНУТРИ тела — `python3 - <<PY` с записью изнутри программы (D415):
#      перенаправления нет, а файл пишется. Берётся ТОЛЬКО аргумент вызова записи, потому
#      что тело поминает пути, в которые не пишет (2372 команды корпуса из 3715).
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$REPO/hooks/detection-signals-lib.sh"
[ -f "$LIB" ] || { echo "FAIL: нет $LIB"; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }
# shellcheck source=/dev/null
. "$LIB"
# Пропуск здесь означал бы «прибора нет» — а он есть; отсутствие функции это ПОЛОМКА,
# и она обязана краснеть, а не молчать зелёным (три состояния прибора, не два).
command -v ds_evaluate_node >/dev/null 2>&1 \
    || { echo "FAIL: ds_evaluate_node недоступна — движок сломан, а не отсутствует"; exit 1; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

NODE='{"heredoc_target_regex":"(hooks|scripts)/[^ ]*\\.(sh|bash)"}'
probe() { # $1=команда → 0 если цель признана своей
    ds_evaluate_node "$NODE" "Bash" "$(jq -nc --arg c "$1" '{command:$c}')" "" 2>/dev/null
}
case_is() { # $1=метка $2=ожидание(hit|miss) $3=команда
    if probe "$3"; then got=hit; else got=miss; fi
    [ "$got" = "$2" ] && ok || bad "$1" "ждали ${2}, получили ${got}"
}

# 1. Цель ДО маркера — самая частая форма записи файла через оболочку.
case_is T1 hit "$(printf '%s\n' "cat > hooks/x.sh <<'EOF'" "R=1" "EOF")"

# 2. Цель ПОСЛЕ маркера — форма, которую предикат умел и до починки.
case_is T2 hit "$(printf '%s\n' "python3 - <<'PY' > hooks/gen.sh" "print(1)" "PY")"

# 3. КОНТРПРИМЕР: перенаправление за разделителем принадлежит ДРУГОЙ команде.
#    Ради этого правила предикат и сужали 29 августа 2026 — сужение остаётся в силе.
case_is T3 miss "$(printf '%s\n' "git show HEAD:hooks/x.sh > /tmp/x.sh && python3 - <<'PY'" "print(1)" "PY")"

# 4. КОНТРПРИМЕР: строка внутри ЧУЖОГО тела heredoc — текст, а не команда.
#    Поймано на себе в день починки: прозаический пример в записи CHANGELOG был принят
#    за настоящую запись в hooks/.
case_is T4 miss "$(printf '%s\n' "python3 - <<'PYX'" 'txt = """' "форма: cat > hooks/x.sh <<EOF" '"""' "PYX")"

# 5. КОНТРПРИМЕР: чужой каталог целью не считается.
case_is T5 miss "$(printf '%s\n' "cat > /tmp/probe.sh <<'EOF'" "R=1" "EOF")"

# 6. Упоминание пути рядом, без перенаправления, целью не является.
#    Сужение 28 августа 2026: предмет проверки — файл, который СОЗДАЁТСЯ.
case_is T6 miss "$(printf '%s\n' "bash hooks/guard.sh <<'EOF'" "вход" "EOF")"

# 7. Тот же разделитель, но перенаправление ведёт В ДЕРЕВО. Без этого плеча правило
#    «отсекать по разделителю» не проверяется ничем: в T3 цель отвергается ДРУГИМ правилом
#    (чужой каталог), и мутация, снимающая отсечение, оставляет прогон зелёным. Поймано
#    контролем мутацией в день написания теста.
case_is T7 miss "$(printf '%s\n' "git show HEAD:x.sh > hooks/old.sh && python3 - <<'PY'" "print(1)" "PY")"

# 8. ЦЕЛЬ ВНУТРИ ТЕЛА, самая частая форма записи питоном (3000 команд корпуса из 3382):
#    путь стоит в переменной, вызов записи её читает. До 15 сентября 2026 предикат молчал
#    здесь по построению, и молчание было неотличимо от чистой команды.
case_is T8 hit "$(printf '%s\n' "python3 - <<'PY'" "p = 'hooks/probe.sh'" 'open(p, "w").write("x")' "PY")"

# 9. Второй вызов записи того же устройства — write_text у пути (1817 команд корпуса).
case_is T9 hit "$(printf '%s\n' "python3 - <<'PY'" "import pathlib" 'p = pathlib.Path("hooks/y.sh")' 'p.write_text("x")' "PY")"

# 10. КОНТРПРИМЕР режима: ЧТЕНИЕ файла записью не является. Кодировка ascii несёт букву
#     `a`, и без разбора режима открытия чтение засчитывалось бы как запись — мутация,
#     снимающая проверку режима, роняет именно это плечо.
case_is T10 miss "$(printf '%s\n' "python3 - <<'PY'" "p = 'hooks/z.sh'" "s = open(p, encoding='ascii').read()" "PY")"

# 11. КОНТРПРИМЕР источника пути: в теле есть путь в дерево, но пишется ДРУГОЙ файл.
#     Это плечо и запрещает правило «любой литерал тела»: путь берётся из аргумента вызова
#     записи, а не оттуда, где на него удобно смотреть.
case_is T11 miss "$(printf '%s\n' "python3 - <<'PY'" "src = 'hooks/guard.sh'" 'open("/tmp/out.txt", "w").write(open(src).read())' "PY")"

echo "heredoc target scope: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
