#!/usr/bin/env bash
# test_signal_precision_universe.sh — универсум замера выводится, а не перечисляется.
#
# Повод (5 сентября 2026, род F). `signal-precision.sh` читал ровно одно семейство журналов
# — `blocker-fired-*`, — потому что писался под конкретный повод (D113) и универсум был взят
# С МЕСТА НАХОДКИ. Замер покрытия: журналов срабатываний в состоянии ДЕСЯТЬ семейств и 1188
# записей настоящих сессий, читались 285 — 26%. Молчал замер и о полях, ради которых род G
# держал носителя: `bulk-copy-fired` (128 записей) читателя не имел вовсе.
#
# Корень не в перечне имён: у семейства «журнал срабатываний стража» нет реестра, каждый
# страж заводит имя сам (`pattern-declaration-family-without-a-registry`). Правило вместо
# перечня: любой `*-fired-*.jsonl` НАСТОЯЩЕЙ сессии — журнал срабатываний.
#
# Тест держит четыре свойства, и три из них — про честность знаменателя:
#   универсум выводится (новое семейство видно без правки кода);
#   фикстуры тестов в него НЕ попадают (иначе знаменатель растёт от прогонов набора);
#   битые строки считаются и называются, а не гасятся (`jq -s` падал целиком);
#   имя признака не берётся голым хешем (у `trust-guard` `key` — хеш, имя в `signature`).
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPT="$REPO/scripts/signal-precision.sh"
[ -f "$SCRIPT" ] || { echo "FAIL: нет $SCRIPT"; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "SKIP: нет jq"; exit 0; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
ST="$TMP/state"; mkdir -p "$ST"
# Корпус расшифровок — СВОЙ, пустой (D392, 13 сентября 2026). Прибор считает сессии с видимым
# отказом по `CLAUDE_PROJECTS_DIR` и без рычага читал живой корпус владельца: `grep -rl` по
# 800 МБ на каждом из четырёх вызовов — 40 с CPU у теста, предмет которого — универсум
# журналов в каталоге состояния. Положительный контроль рычага — T7 ниже.
export CLAUDE_PROJECTS_DIR="$TMP/projects"; mkdir -p "$CLAUDE_PROJECTS_DIR"
U1="11111111-1111-1111-1111-111111111111"
U2="22222222-2222-2222-2222-222222222222"

# Семейство, которого в коде замера нет ни одним именем: универсум обязан вывести его сам.
printf '{"date":"2026-09-05T10:00:00Z","signal":"выдуманный_признак"}\n%.0s' 1 2 3 \
    > "$ST/совсем-новое-fired-$U1.jsonl"
# Хеш в `key` и имя в `signature` — как у trust-guard.
printf '{"date":"2026-09-05T10:00:00Z","key":"d41d8cd98f00b204e9800998ecf8427e","signature":"rm -rf"}\n%.0s' 1 2 \
    > "$ST/хеш-fired-$U2.jsonl"
# Битая строка рядом с целыми: `jq -s` падал бы целиком.
printf 'это не json\n{"date":"2026-09-05T10:00:00Z","signal":"целый"}\n' >> "$ST/хеш-fired-$U2.jsonl"
# Фикстура теста — БЕЗ идентификатора сессии: в универсум попадать не должна.
printf '{"date":"2026-09-05T10:00:00Z","signal":"фикстура_прогона"}\n%.0s' 1 2 3 4 5 \
    > "$ST/blocker-fired-replay-7-12345.jsonl"

OUT=$(STATE_DIR="$ST" bash "$SCRIPT" 2>&1)

grep -q "выдуманный_признак" <<< "$OUT" && ok \
    || bad "T1 универсум выводится" "новое семейство не прочитано: $OUT"

grep -q "фикстура_прогона" <<< "$OUT" && bad "T2 фикстуры" "фикстура теста попала в знаменатель" || ok

grep -qE "не разобралось 1|НЕ разобралось 1" <<< "$OUT" && ok \
    || bad "T3 битые строки" "битая строка не названа числом: $OUT"

grep -q "целый" <<< "$OUT" && ok \
    || bad "T3b устойчивый разбор" "целые записи потеряны вместе с битой: $OUT"

grep -q "rm -rf" <<< "$OUT" && ok \
    || bad "T4 имя, а не хеш" "имя признака не взято из signature: $OUT"

grep -q "d41d8cd98f00b204e9800998ecf8427e" <<< "$OUT" && \
    bad "T4b имя, а не хеш" "хеш дросселя выдан за имя признака" || ok

# Пустое состояние — замер обязан сказать это, а не молчать зелёным.
E="$TMP/empty"; mkdir -p "$E"
OUT2=$(STATE_DIR="$E" bash "$SCRIPT" 2>&1)
grep -qE "журналов срабатываний нет" <<< "$OUT2" && ok \
    || bad "T5 пустое состояние" "о пустоте не сказано: $OUT2"

# --- T5: доля нечитаемых строк названа ПРОЦЕНТОМ, а не только числом (D383) ---
grep -qE "НЕ разобралось 1 \(25%\)" <<< "$OUT" && ok \
    || bad "T5 доля битых" "доля нечитаемых строк не названа процентом (1 из 4 = 25%): $OUT"

# --- T6: журнал разрешённых вызовов стража доверия ЧИТАЕТСЯ: в окне и за всё время (D383, корень R2) ---
U3="33333333-3333-3333-3333-333333333333"
printf '{"date":"2026-09-05T10:00:00Z","key":"k","signature":"rm -rf x"}\n' > "$ST/trust-guard-fired-$U3.jsonl"
printf '{"date":"2026-09-05T10:00:00Z","session":"%s","signature":"rm -rf x","target":"x","reason":"said"}\n' "$U3" > "$ST/trust-guard-authorized.jsonl"
printf '{"date":"2026-08-01T10:00:00Z","session":"99999999-9999-9999-9999-999999999999","signature":"rm y","target":"y","reason":"said"}\n' >> "$ST/trust-guard-authorized.jsonl"
printf 'битая строка\n' >> "$ST/trust-guard-authorized.jsonl"
OUT=$(STATE_DIR="$ST" bash "$SCRIPT" 2>&1)
grep -q "разрешённых вызовов (authorized): в окне 1, за всё время 2" <<< "$OUT" && ok \
    || bad "T6 authorized" "журнал разрешённых вызовов не прочитан или посчитан неверно: $OUT"
rm -f "$ST/trust-guard-authorized.jsonl"
OUT=$(STATE_DIR="$ST" bash "$SCRIPT" 2>&1)
grep -q "разрешённых вызовов (authorized): журнала нет" <<< "$OUT" && ok \
    || bad "T6b authorized нет" "отсутствие журнала не названо словами: $OUT"

# --- T7: счёт сессий с видимым отказом читается из CLAUDE_PROJECTS_DIR, а не из живого корпуса ---
mkdir -p "$CLAUDE_PROJECTS_DIR/-proj-x"
printf '{"type":"text","text":"ОТКАЗ (вызов не выполнен)"}\n' > "$CLAUDE_PROJECTS_DIR/-proj-x/44444444-4444-4444-4444-444444444444.jsonl"
OUT=$(STATE_DIR="$ST" bash "$SCRIPT" 2>&1)
grep -q "сессий с видимым отказом в расшифровках: 1" <<< "$OUT" && ok \
    || bad "T7 корпус по рычагу" "отказ в фикстурном корпусе не сосчитан (ждали 1): $(grep 'видимым отказом' <<< "$OUT")"

echo ""
echo "signal precision universe: $PASS/$((PASS + FAIL)) passed"
exit $(( FAIL != 0 ))
