#!/usr/bin/env bash
# test_frame_control_lib.sh — свидетель владельца контроля рамки.
#
# Результат: пустая популяция даёт код 2 и слово в stderr, непустая — 0 и тишину;
#            «число не получено» считается тем же исходом, что ноль
# Проверка результата: bash hooks/tests/test_frame_control_lib.sh даёт 0
#
# Предмет ноги T3 — тот самый промах, ради которого библиотека заведена: пустая строка
# приходит, когда разбор не отработал, и `[ "$n" -gt 0 ]` на ней падает синтаксически,
# уводя прибор в ветку, которой автор не писал.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$REPO/hooks/frame-control-lib.sh"
[ -f "$LIB" ] || { echo "FAIL: нет $LIB"; exit 1; }
# shellcheck source=../frame-control-lib.sh
. "$LIB"

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

# T1: непустая популяция — вердикт выносится, тишина.
err=$(frame_require_nonempty 7 "свидетелей" 2>&1); rc=$?
[ "$rc" = "0" ] && ok || bad T1 "непустая популяция дала код $rc"
[ -z "$err" ] && ok || bad T1b "на непустой популяции прибор что-то сказал: $err"

# T2: ноль — СУДИТЬ НЕЧЕМ, код 2, и слово названо.
err=$(frame_require_nonempty 0 "свидетелей" 2>&1); rc=$?
[ "$rc" = "2" ] && ok || bad T2 "пустая популяция дала код $rc, а не 2"
case "$err" in *"СУДИТЬ НЕЧЕМ"*) ok ;; *) bad T2b "отказ не назван словом: $err" ;; esac
# Код 0 ЗАПРЕЩЁН именно здесь: это и есть слияние «чисто» с «не смотрел».
[ "$rc" != "0" ] && ok || bad T2c "пустая популяция прочиталась как «находок нет»"

# T3: число не получено (разбор не отработал) — тот же исход, а не падение.
err=$(frame_require_nonempty "" "свидетелей" 2>&1); rc=$?
[ "$rc" = "2" ] && ok || bad T3 "пустая строка дала код $rc"
err=$(frame_require_nonempty "BROKEN" "свидетелей" 2>&1); rc=$?
[ "$rc" = "2" ] && ok || bad T3b "нечисловой ответ дал код $rc"

# T4: способ сборки рамки называется, когда подан — читателю чинить рамку, а не гадать.
err=$(frame_require_nonempty 0 "носителей" "прогон по копии дерева" 2>&1)
case "$err" in *"прогон по копии дерева"*) ok ;; *) bad T4 "способ сборки рамки не назван" ;; esac

# T5: повторное источание не ломает и не повторяет объявления.
. "$LIB"
command -v frame_require_nonempty >/dev/null 2>&1 && ok || bad T5 "функция пропала после второго источания"

# T6: frame_require_red — известное нарушение обязано покраснеть.
# Зелёный положительный контроль значит, что судимый механизм мёртв, а не что мир чист.
frame_require_red "подставное нарушение" false 2>/dev/null; rc=$?
[ "$rc" = "0" ] && ok || bad T6 "красная команда дала код $rc, а не 0"

frame_require_red "подставное нарушение" true 2>/dev/null; rc=$?
[ "$rc" = "2" ] && ok || bad T6b "ЗЕЛЁНЫЙ контроль дал код $rc — слит с «нарушений нет»"

# T6c: позван без команды — тоже «судить нечем», а не молчаливое согласие.
frame_require_red "без команды" 2>/dev/null; rc=$?
[ "$rc" = "2" ] && ok || bad T6c "вызов без команды дал код $rc"

# T6d: команда зовётся МАССИВОМ, а не строкой. Текст непринятой команды — данные: через
# eval или bash -c подстановка внутри аргумента сработала бы, здесь она остаётся текстом.
frame_require_red "подстановка" sh -c 'exit 3' _ '$(echo x)' 2>/dev/null; rc=$?
[ "$rc" = "0" ] && ok || bad T6d "команда с подстановкой в аргументе дала код $rc"

# T6e: причина названа в stderr — читателю чинить рамку, а не гадать.
err=$(frame_require_red "известное нарушение" true 2>&1)
case "$err" in *"НЕ покраснел"*) ok ;; *) bad T6e "причина зелёного контроля не названа" ;; esac

echo "frame control lib: PASS=$PASS FAIL=$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
