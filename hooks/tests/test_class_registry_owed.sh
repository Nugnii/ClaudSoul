#!/usr/bin/env bash
# СУДИТ: scripts/signal-precision-corpus.py
# test_class_registry_owed.sh — опознание класса без реестра носителей становится ДОЛГОМ
# границы хода, а не репликой в поток.
#
# Повод (23 сентября 2026, D408). Вторая обязанность срода `self_repeat` жила только в тексте
# напоминания — уровень 2-3 лестницы встроенности. Замер сессии `9ea6931d`: напоминание
# выдано 14 раз, реестр назван дважды, доля по корпусу 50,3% → 50,5%, то есть шум.
# Уровень 4 здесь запрещён своим же правилом: точность признака `self_repeat` 15 из 20, и
# каждый четвёртый отказ был бы ложным.
#
# Предмет: владелец признака различает ТРИ состояния кодами, и различает их верно. Своей
# копии признака свидетель не держит — он судит ответ владельца, как судит его и свод.
set -uo pipefail
. "$(dirname "$0")/alerts-read.sh"
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
CORPUS="$REPO/scripts/signal-precision-corpus.py"
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

command -v python3 >/dev/null 2>&1 || { echo "SKIP: python3 недоступен"; exit 0; }
[ -f "$CORPUS" ] || { echo "SKIP: нет $CORPUS"; exit 0; }

# Код судится ВМЕСТЕ с текстом ответа (D1152): упавший разбор выходит с тем же 1, что «долг», и ноги долга
# зеленели бы на сломанном владельце (case-2026-10-29-debt-legs-green-on-crashed-parser).
_ask() {
    local out rc
    out=$(printf '%s' "$1" | python3 "$CORPUS" --registry-in-text 2>/dev/null); rc=$?
    case "$rc:$out" in
        0:*'реестр назван: да'*|1:*'реестр назван: НЕТ'*|2:*'опознания класса в тексте нет'*) echo "$rc" ;;
        *) echo "x$rc" ;;
    esac
}

# T1 — опознание И реестр числом: долга нет.
[ "$(_ask 'Тот же класс, что вчера: носителей 3 из 7.')" = 0 ] && ok \
    || bad T1 "реестр числом не засчитан"

# T2 — опознание без реестра: ДОЛГ. Это и есть предмет пункта.
[ "$(_ask 'Тот же класс, что вчера. Чиню на месте.')" = 1 ] && ok \
    || bad T2 "опознание без реестра не названо долгом"

# T3 — опознания нет: судить нечего, и это ТРЕТЬЕ состояние, а не «долга нет».
# Слить его со вторым значило бы повторить R6, ради которого пункт и ведётся.
[ "$(_ask 'Правка прошла, тест зелёный.')" = 2 ] && ok \
    || bad T3 "текст без опознания не отделён от текста с реестром"

# T4 — реестр, названный СЛОВОМ при слове о носителях, засчитан; счёт ПОВТОРОВ — нет (D1152,
# решение владельца 29 октября 2026 — «строгий счёт»). Замер 14 сентября 2026 засчитал «чинился
# трижды» реестром, и на единице хода такие слова стояли почти в каждом длинном ходе: из
# 35 засчитанных реестров настоящих было 15.
[ "$(_ask 'Тот же класс: все семь носителей починены.')" = 0 ] && ok \
    || bad T4 "счёт носителей словом не засчитан реестром"
[ "$(_ask 'Тот же класс: чинился трижды в других местах.')" = 1 ] && ok \
    || bad T4b "счёт повторов засчитан реестром"

# T4c — реестр ПРИВЯЗАН к опознанию (D1152): счёт носителей дальше 300 знаков от формы опознания
# — не реестр этого класса; «33 из 33» тестов и номер пункта — не реестр вовсе.
_far=$(printf 'Правка прошла, тесты зелёные. %.0s' $(seq 12))
[ "$(_ask "Это тот же класс, что вчера. ${_far} Где-то ещё носителей 3 из 7.")" = 1 ] && ok \
    || bad T4c "далёкий счёт носителей засчитан реестром опознания"
[ "$(_ask 'Это тот же класс, что D420. Тесты: 33 из 33.')" = 1 ] && ok \
    || bad T4d "номер пункта или счёт тестов засчитан реестром"

# T4e–T4g — механика окна (второй круг D1152, M2): место опознания ИЩЕТСЯ, а не берётся началом текста; ширина
# окна — ровно 300 знаков от начала формы опознания до начала формы реестра.
[ "$(_ask "${_far} Это тот же класс: носителей 3 из 7.")" = 0 ] && ok \
    || bad T4e "реестр рядом с опознанием в конце длинного текста не засчитан"
[ "$(_ask "Тот же класс.$(printf '%*s' 287 '')носителей 3 из 7.")" = 0 ] && ok \
    || bad T4f "реестр на 300 знаков от опознания не засчитан"
[ "$(_ask "Тот же класс.$(printf '%*s' 288 '')носителей 3 из 7.")" = 1 ] && ok \
    || bad T4g "реестр на 301 знак от опознания засчитан"
# Та же граница НАЗАД (седьмой скептик, M-1): без неё прибор, засчитавший форму на любом расстоянии ДО опознания (снятый
# `abs`), был зелёным, а строка долга по-прежнему говорила «не дальше 300 знаков».
[ "$(_ask "носителей 3 из 7.$(printf '%*s' 283 '')Тот же класс.")" = 0 ] && ok \
    || bad T4g "реестр за 300 знаков до опознания не засчитан"
[ "$(_ask "носителей 3 из 7.$(printf '%*s' 284 '')Тот же класс.")" = 1 ] && ok \
    || bad T4g "реестр за 301 знак до опознания засчитан"

# T4h — то, что строка долга называет «не реестром», им и не засчитано (второй круг D1152, M1, L3).
for _t in 'Тот же класс. Все три теста зелёные.' 'Тот же класс. Все триггеры перепроверил.' \
          'Тот же класс. Носителей не считал (D1200).' 'Тот же класс. Реестр замеров 110 строк.' \
          'Тот же класс. Прогон: 33 из 33 файлов зелёные.' 'Записано в обоих носителях: кейс от 2026-09-12.' \
          'Тот же класс. Все восемь зелёные.' 'Это тот же класс, что вчера. Это братья корня, их ищут до починки.'; do
    [ "$(_ask "$_t")" = 1 ] && ok || bad T4h "засчитано реестром: $_t"
done

# T4i — «все + числительное» без слова о носителях — НЕ реестр (решение владельца 29 октября 2026 — «только со
# словом»): «Чиню все три» бывает и реестром, и счётом тестов («все восемь зелёные»), ложное «назвал» хуже.
[ "$(_ask 'Тот же класс. Чиню все три.')" = 1 ] && ok \
    || bad T4i "«все три» без слова о носителях засчитано реестром"

# T4k — окно в обе стороны (второй круг D1152, M2); «реестр — N» снят решением владельца.
[ "$(_ask 'Носителей 3 из 7: это тот же класс, что вчера.')" = 0 ] && ok \
    || bad T4k "реестр ПЕРЕД опознанием не засчитан"
[ "$(_ask 'Тот же класс: реестр — 5.')" = 1 ] && ok || bad T4k "«реестр — N» без слова о носителях засчитан"
[ "$(_ask 'Тот же класс: 3 из 7 мест.')" = 0 ] && ok || bad T4k "«N из M мест» не засчитано"

# T4j — якорь — каждая форма опознания, а не первая (L1), и каждое ВХОЖДЕНИЕ формы, а не первое (скептик второго
# круга, M2).
[ "$(_ask "Это тот же класс. ${_far} Класс закрыт: носителей 3 из 7.")" = 0 ] && ok \
    || bad T4j "реестр рядом со второй формой опознания не засчитан"
[ "$(_ask "Это тот же класс, что вчера. ${_far} Тот же класс: носителей 3 из 7.")" = 0 ] && ok \
    || bad T4j "реестр рядом со вторым вхождением формы опознания не засчитан"

# T4l — ФОРМЫ РЕЕСТРА — ОДИН СПИСОК (третий круг D1152). Два круга скептика подряд строка долга, регулярка и ноги
# расходились: у факта было три владельца. Теперь ноги берутся из списка `REGISTRY_FORMS`: каждый пример «да» рядом
# с опознанием засчитан и ловится ТОЛЬКО своей формой (иначе снятие формы не краснит ничего), каждый пример «нет»
# не засчитан. Перечень имён закреплён здесь: снятая форма уносит и свои примеры, и обход этого не заметил бы.
_forms=$(python3 - "$CORPUS" <<'PY' 2>&1
import importlib.util, re, sys
spec = importlib.util.spec_from_file_location('spc', sys.argv[1]); m = importlib.util.module_from_spec(spec)
sys.argv = [sys.argv[0]]; spec.loader.exec_module(m)
F = m.REGISTRY_FORMS; bad = []
names = [f[0] for f in F]
if names != ['слово и число', 'число и слово', 'числительное и слово', 'реестр родов']:
    bad.append(f'перечень форм: {names}')
for i, (name, rx, desc, yes, no) in enumerate(F):
    rest = re.compile('|'.join('(?:%s)' % g[1] for j, g in enumerate(F) if j != i), re.I)
    if not yes or not no or desc not in m.REGISTRY_TOLD:
        bad.append(f'{name}: нет примеров или описания в REGISTRY_TOLD')
    for y in yes:
        if m.class_recognition_of('Тот же класс: ' + y) != ('тот же класс', True) or rest.search(y.lower()):
            bad.append(f'{name}: «да» не засчитано своей формой — {y}')
    for n in no:
        if m.class_recognition_of('Тот же класс: ' + n)[1]:
            bad.append(f'{name}: «нет» засчитано — {n}')
print('\n'.join(bad) or 'чисто')
PY
)
[ "$_forms" = 'чисто' ] && ok || bad T4l "список форм: $_forms"

# T4m — ответ «форма опознания» — ПЕРВАЯ по порядку RECOGNITION (её читают показание и свод), и места и реестр
# мерятся в одной системе координат (L2): «İ» удлиняет строку при lower(), смешанные индексы сдвигали окно.
case "$(printf '%s' 'Класс закрыт. Тот же класс: носителей 3 из 7.' | python3 "$CORPUS" --registry-in-text 2>/dev/null)" in
    'опознание: тот же класс;'*) ok ;; *) bad T4m "форма опознания — не первая по RECOGNITION" ;; esac
[ "$(_ask "Тот же класс.İİİİİİİİİİ$(printf '%*s' 277 '')носителей 3 из 7.")" = 1 ] && ok \
    || bad T4m "окно мерится по смешанным индексам (сырой текст против lower)"

# T4n — строка долга берёт описание форм У ПРИБОРА: ответ «долг» несёт REGISTRY_TOLD ЦЕЛИКОМ (обрывок описания —
# тоже дефект, третий скептик), а свод своей копии — ни форм, ни ширины окна — не держит.
_told=$(python3 - "$CORPUS" <<'PY' 2>/dev/null
import importlib.util, sys
spec = importlib.util.spec_from_file_location('spc', sys.argv[1]); m = importlib.util.module_from_spec(spec)
sys.argv = [sys.argv[0]]; spec.loader.exec_module(m); print(m.REGISTRY_TOLD)
PY
)
[ -n "$_told" ] && [ "$(printf '%s' 'Тот же класс. Чиню на месте.' | python3 "$CORPUS" --registry-in-text 2>/dev/null)" \
    = "опознание: тот же класс; реестр назван: НЕТ; засчитывается: ${_told}" ] && ok \
    || bad T4n "ответ «долг» не несёт описание форм целиком"
# Сравнение с REGISTRY_TOLD того же модуля — тавтология (четвёртый скептик, M-1): исказится описание — исказится и
# эталон. Поэтому описание судится ПОВЕДЕНИЕМ прибора, а не своей копией: ширина — та же, что у ног T4f/T4g; каждый
# пример головы прибор засчитывает реестром, каждый пример хвоста — нет.
# Описание закреплено здесь буквально и ЦЕЛИКОМ (пятый скептик, H-1; шестой, H-2 и M-1): связующий текст судить
# поведением нельзя, слова «носители»/«места» стоят до примеров, а пример с ложным обобщением («носителей 3 из 7 — и
# любое другое число») прибор засчитывает по его настоящей части. Эталон лежит в тесте, а не в модуле, — поэтому это
# не тавтология M-1 четвёртого скептика. Правка формулировки описания — правка и этой строки.
_told_pinned='форма не дальше 300 знаков от опознания — число рядом со словом «носители» или «места»: «носителей 3 из 7», «носителей: 3», «носителей три», «места: 5», «3 носителя», «в 5 местах», «3 из 7 мест», «три носителя», «в трёх местах», «все двенадцать носителей», раздел «**Братья корня.**» (жирным или с начала строки), «братья корня R6 —», вызов `defect-class-carriers.py --…`; не реестр, например: «у носителей 3 теста упали», «33 из 33 тестов», «все три теста зелёные», «ищу братьев корня.»'
[ "$_told" = "$_told_pinned" ] && ok || bad T4n "описание форм разошлось с закреплённым"
_head=${_told#*«места»: }; _head=${_head%%; не реестр, например: *}; _tail=${_told##*; не реестр, например: }
while IFS= read -r _x; do
    [ -n "$_x" ] && { [ "$(_ask "Тот же класс: $_x")" = 0 ] && ok || bad T4n "пример головы описания — не реестр: $_x"; }
done < <(grep -o '«[^»]*»' <<<"$_head" | sed 's/^«//; s/»$//')
while IFS= read -r _x; do
    [ -n "$_x" ] && { [ "$(_ask "Тот же класс: $_x")" = 1 ] && ok || bad T4n "пример хвоста описания — реестр: $_x"; }
done < <(grep -o '«[^»]*»' <<<"$_tail" | sed 's/^«//; s/»$//')
# Хвост ВЫВЕДЕН из списка — по примеру на каждую из четырёх закреплённых в T4l форм; хвост, написанный руками, правдив
# и проходит судейство поведением, но расходится со списком при следующей правке формы.
[ "$(grep -o '«[^»]*»' <<<"$_tail" | wc -l | tr -d ' ')" = 4 ] && ok || bad T4n "хвост описания не выведен из списка форм"
_cr_line=$(grep 'Класс опознан, а РЕЕСТР' "$REPO/hooks/session-collector.sh" 2>/dev/null)
if grep -qiE '«|засчитыва|знаков' <<<"${_cr_line//\$\{_cr_out\}/}"; then
    bad T4n "свод держит свою копию описания форм или окна"; else ok; fi

# T4o — ПРИМЕРЫ «НЕТ» ЗАКРЕПЛЕНЫ ВНЕ СПИСКА (третий скептик, M3): тест, читающий примеры из того же списка, что и
# прибор, пропускает ослабление формы вместе со снятием её примера. Ложное «назвал» — худший исход (решение
# владельца), поэтому закреплено именно это направление.
for _t in 'у носителей 3 теста упали' 'носители не искал, тесты 33 из 33' 'носители: 3 раза запускал поиск' \
          'носителей 5 минут искал' 'носителей 1,5 часа' 'носителей 12%' 'носителей 2026-09-12' 'носителей D1200' \
          'носителей №1200' 'носителей 14:05' 'во всех носителях 3 теста' 'для носителя 5 вызовов' 'местами 3 падают' \
          '33 из 33 тестов' '12 из 12 фикстур' 'на 1 месте в очереди' 'занял 1 место' '2 местных переменных' \
          'версия 1.3 носителя' 'D420 носителя' '3 теста носителя' 'все три теста зелёные' 'все восемь зелёные' \
          'чиню все три' 'все триггеры перепроверил' 'три раза местами' 'все три разных теста носителя' \
          'гоню набор и ищу братьев корня.' 'не искал братьев корня.' 'это братья корня, их ищут до починки' \
          'это братья корня: их ищут до починки' '[defect-class-carriers.py:145](scripts/defect-class-carriers.py)' \
          '(«братья корня — где то же устройство»)' '**Братья корня не искал**, чиню на месте' \
          'гоню набор и ищу **братьев корня**.' '**Братья корня — потом**'; do
    [ "$(_ask "Тот же класс: $_t")" = 1 ] && ok || bad T4o "засчитано реестром: $_t"
done

# T5 — свод ЗОВЁТ владельца, а не держит свою копию признака: иначе две реализации одного
# правила разойдутся молча (корень R1).
if grep -q 'registry-in-text' "$REPO/hooks/session-collector.sh" 2>/dev/null; then ok
else bad T5 "свод не спрашивает владельца признака"; fi

# T6 — ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ рамки: пустой вход не должен считаться долгом, иначе строка
# долга печаталась бы на каждом ходу и перестала значить что-либо.
[ "$(_ask '')" = 2 ] && ok || bad T6 "пустой текст засчитан как опознание"

# --- T7: ИСХОД ОБЯЗАННОСТИ ЗАПИСЫВАЕТСЯ, И ОБА СОСТОЯНИЯ (24 сентября 2026, D408) ---------
# Прежде свод ПЕЧАТАЛ долг и не записывал ничего, а «реестр назван» не записывал вовсе:
# ответить «помогло ли напоминание» было нечем. Хуже: ветка стояла под сторожем
# `command -v rc_turn_text`, а `root-cause-lib.sh` в своде не подключался НИ РАЗУ — прямая
# проба давала «НЕТ», то есть перенос обязанности на границу хода не состоялся вообще.
# Нога судит СКВОЗНОЕ поведение свода, а не вид его кода.
_COLL="$REPO/hooks/session-collector.sh"
if [ ! -f "$_COLL" ] || ! command -v jq >/dev/null 2>&1; then
    echo "SKIP: нет свода либо jq — сквозную пробу ставить нечем"
else
    _T7=$(mktemp -d)
    _t7_mk() {   # _t7_mk <текст> <файл>
        printf '{"type":"user","message":{"role":"user","content":[{"type":"text","text":"чини"}]}}\n' > "$2"
        jq -cn --arg t "$1" '{type:"assistant",message:{role:"assistant",content:[{type:"text",text:$t}]}}' >> "$2"
    }
    _t7_mk "Это тот же класс, что чинили утром. Правлю на месте." "$_T7/owed.jsonl"
    _t7_mk "Это тот же класс: носителей 7, починено 7 из 7." "$_T7/met.jsonl"
    _t7_mk "Правка прошла, тест зелёный." "$_T7/none.jsonl"
    mkdir -p "$_T7/state-owed" "$_T7/state-met" "$_T7/state-none"
    # Корень ClaudSoul задаётся рамкой теста: свод ищет владельца признака через
    # CLAUDSOUL_ROOT, а без него — по указателю установки. На машине владельца указатель
    # есть, на чистом Linux нет: нога зеленела у владельца и краснела на CI (2 октября 2026).
    # Бэклог — песочницы (D1179, M1): корень здесь живое дерево, и сборщик уносил его ☑ в архив.
    for _k in owed met none; do
        jq -cn --arg s "t7-$_k" --arg p "$_T7/$_k.jsonl" \
            '{session_id:$s, transcript_path:$p, hook_event_name:"Stop"}' \
          | STATE_DIR="$_T7/state-$_k" CLAUDSOUL_REPO="$REPO" CLAUDSOUL_ROOT="$REPO" CLAUDSOUL_BACKLOG="$_T7/none.md" bash "$_COLL" >/dev/null 2>&1 || true
    done
    _t7_state() { grep -o '"state":"[a-z]*"' "$_T7/state-$1/class-registry-fired-t7-$1.jsonl" 2>/dev/null | head -1; }
    [ "$(_t7_state owed)" = '"state":"owed"' ] && ok \
        || bad T7 "долг не записан: $(_t7_state owed)"
    # Второе состояние — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: без него нога зелена на редакции, которая
    # перестала писать вовсе. Первая правка именно им и была поймана: под `set -e`
    # присваивание из подстановки с кодом 1 убивало свод, и «долг» не писался никогда.
    [ "$(_t7_state met)" = '"state":"met"' ] && ok \
        || bad T7b "«реестр назван» не записан: $(_t7_state met)"
    # Третье — «судить нечего» записи не даёт, иначе знаменатель раздуется ходами не по теме.
    [ -z "$(_t7_state none)" ] && ok || bad T7c "ход без опознания дал запись: $(_t7_state none)"
    # T7d — текст долга, ушедший в очередь напоминаний, несёт описание форм прибора ЦЕЛИКОМ (третий скептик, M2):
    # мутант сборщика, срезающий `${_cr_out}`, проходил все прочие ноги.
    # Строка долга сверяется ЦЕЛИКОМ (пятый скептик, H-1): закреплённое начало, ответ прибора, закреплённый хвост —
    # дописанная фраза, подменённое «НЕТ», переписанное начало краснят ногу.
    _t7_line="🧬 Класс опознан, а РЕЕСТР НОСИТЕЛЕЙ не назван рядом с опознанием: опознание: тот же класс; реестр назван: НЕТ; засчитывается: ${_told}. Опознание обязывает — сколько мест того же устройства в дереве? Способ добычи: scripts/defect-class-carriers.py, поиск по УСТРОЙСТВУ, scripts/dep-index.py --impact. Без реестра класс закроется не целиком."
    # Подстрокой этого не судить (шестой скептик, H-1): сборщик склеивает напоминания в одну строку очереди, и ложь,
    # дописанная до «🧬» или после «…не целиком.», проходила. Поэтому каждый ход — в своём STATE_DIR, а очередь хода с
    # долгом, из которой вынута строка долга, обязана совпасть с очередью хода без опознания байт в байт.
    _t7_q() { alerts_of "$_T7/state-$1"; }
    _t7_qo=$(_t7_q owed); _t7_qn=$(_t7_q none)
    [ -n "$_told" ] && [ "$(grep -oF "$_t7_line" <<<"$_t7_qo" | wc -l | tr -d ' ')" = 1 ] \
        && _t7_rest="${_t7_qo/"$_t7_line "/}" && _t7_rest=$(printf '%s' "$_t7_rest") && [ "$_t7_rest" = "$_t7_qn" ] && ok \
        || bad T7d "очередь хода с долгом — не очередь хода без опознания плюс строка долга"
    # Разность не видит то, что сборщик пишет на КАЖДОМ ходу (седьмой скептик, L-1): напоминаний о реестре в очереди
    # хода без опознания нет вовсе — ни со значком «🧬», ни без него (восьмой скептик, L-1). «Реестр» в признак не
    # берётся: это слово несёт законное напоминание сборщика о `CG_LOCAL_BACKLOG`.
    if grep -qiE '🧬|носител|опознан' <<<"$_t7_qn"; then bad T7d "очередь хода без опознания несёт напоминание о реестре"; else ok; fi
    rm -rf "$_T7"
fi

echo "test_class_registry_owed: passed $PASS, failed $FAIL"
exit $(( FAIL != 0 ))
