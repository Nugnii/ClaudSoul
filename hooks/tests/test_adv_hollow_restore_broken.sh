#!/usr/bin/env bash
# СУДИТ: hooks/subject-probe-lib.sh
# АТАКА: выхолащивание предмета-СПИСКА не восстанавливает то, что уже успело испортить.
#
# Ветка списка (subject-probe-lib.sh:41-56) идёт по элементам: проверила, скопировала в
# `.keep`, подменила заглушкой — и так по кругу. Восстановление стоит ПОСЛЕ прогона, то
# есть после цикла; на выходе из цикла посреди дороги его нет.
#
# C1. Список, где второй элемент недоступен (переименован, ещё не закоммичен, либо это
#     каталог с косой — в списке такой элемент `[ -f ]` не проходит). Первый элемент уже
#     подменён заглушкой, а `rm -f $_kept` (:44) стирает ЕГО ЖЕ копию. Ожидание: дерево
#     вернулось в исходное состояние, код 9. Факт: код 9, а механизм остался заглушкой,
#     копии нет — вернуть нечем. Списков-объявлений в дереве 66 (замер 22 сентября 2026),
#     и каждое ломается переименованием любого своего звена.
# C2. Список, где элемент повторён. Вторая итерация копирует в `.keep` уже ЗАГЛУШКУ,
#     затирая настоящую копию. Ожидание: файл восстановлен. Факт: код 0 (успех!), файл
#     остался заглушкой навсегда, и зовущий об этом не узнаёт — все следующие свидетели
#     судятся по выпотрошенному дереву.
#
# Обе ветки портят снимок, а не рабочее дерево, — но библиотека объявлена общей на всех
# потребителей (её шапка), и «предмет восстановлен» — часть её договора, а не свойство
# нынешних двух зовущих.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$REPO/hooks/subject-probe-lib.sh"
[ -f "$LIB" ] || { echo "SKIP: нет $LIB"; exit 0; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "FAIL [$1]: $2"; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

ORIG='#!/usr/bin/env bash
echo MARKER
exit 0'

build() {  # build <каталог>
    mkdir -p "$1/hooks/tests"
    printf '%s\n' "$ORIG" > "$1/hooks/one.sh"
    printf '#!/usr/bin/env bash\nexit 0\n' > "$1/hooks/tests/test_adv_stub.sh"
}

# shellcheck source=/dev/null
. "$LIB"
# Выхолощенный предмет не должен зеленить эту ногу: без функции судить нечего, и молчать
# тут значило бы стать тем самым ложно-зелёным, которого ищет behavior-condition-probe.sh.
command -v sp_hollow_run >/dev/null 2>&1 \
    || { echo "FAIL: sp_hollow_run не объявлена — предмет выхолощен или переименован"; exit 1; }

# ── C1: второго элемента нет ────────────────────────────────────────────────────────────
S1="$TMP/s1"; build "$S1"
sp_hollow_run "$S1" "hooks/tests/test_adv_stub.sh" "hooks/one.sh hooks/gone.sh" "$S1/.out"
RC1=$?

if [ "$(cat "$S1/hooks/one.sh")" = "$ORIG" ]; then ok
else bad C1 "механизм не восстановлен, в нём осталось: $(cat "$S1/hooks/one.sh")"; fi

if [ -f "$S1/hooks/one.sh.keep" ] || [ "$(cat "$S1/hooks/one.sh")" = "$ORIG" ]; then ok
else bad C1b "копия стёрта (rm -f \$_kept), восстанавливать нечем; код возврата $RC1"; fi

# ── C2: элемент повторён ────────────────────────────────────────────────────────────────
S2="$TMP/s2"; build "$S2"
sp_hollow_run "$S2" "hooks/tests/test_adv_stub.sh" "hooks/one.sh hooks/one.sh" "$S2/.out"
RC2=$?

if [ "$(cat "$S2/hooks/one.sh")" = "$ORIG" ]; then ok
else bad C2 "после прогона (код $RC2) механизм остался заглушкой: $(cat "$S2/hooks/one.sh")"; fi

# Успех, объявленный поверх испорченного дерева, хуже отказа: зовущий продолжает работу.
if [ "$RC2" != 0 ] || [ "$(cat "$S2/hooks/one.sh")" = "$ORIG" ]; then ok
else bad C2b "код 0 — «прогон удался» — при невосстановленном предмете"; fi

echo "test_adv_hollow_restore_broken: passed $PASS, failed $FAIL"
exit $(( FAIL != 0 ))
