# ПОДАЮТСЯ ФАЙЛЫ, ТРОНУТЫЕ С ПРОШЛОГО СОБЫТИЯ, а не все грязные (13 сентября 2026).
# Первая редакция брала весь грязный список, и это крало слот у РАБОЧЕГО пути: у стражей
# бывает свой дроссель на сессию, журнал общий для обоих путей, — задне-числовая подача
# гасила срабатывание на пути ДО записи, где сообщение единственно и осмысленно. Замер с
# положительным контролем: подача задним числом в сессии S → настоящая правка того же
# файла в S даёт 0 байт, она же в свежей сессии T — 669. Плюс шум: по файлам последних
# 20 коммитов страж `backlog-touch-check` попадал на КАЖДЫЙ ТРЕТИЙ тронутый файл (28 из 90),
# то есть весь грязный список означал десятки инжектов за сессию.
# Метка сессии двигается на каждом событии: подаётся то, что новее её. Первое событие сессии
# меткой не располагает, и весь грязный список брать нельзя — это ровно тот шум, от которого
# уходим. Берётся тронутое за последние пять минут: окно названо числом, а не подразумевается.
#
# КАНДИДАТЫ БЕРУТСЯ У УЧЁТА ПРОЕКТА, А НЕ У ДЕРЕВА КАТАЛОГОВ (1 октября 2026, D487). Прежний
# `find .` обходил всё дерево на каждом событии: в ProjectA это 140 011 файлов и 1,46 с на
# команду (список git — 2 095 за 0,05 с), а прод-сборка клала в очередь сессии 16 тыс. файлов
# `web/.next`. Кандидаты: учтённые (в том числе закоммиченные той же командой, что их правила —
# «грязный» список git их потерял бы), неучтённые неигнорируемые и ОТДЕЛЬНЫЕ игнорируемые
# файлы. Пропускаются игнорируемые КАТАЛОГИ целиком. Разделитель измерен, а не выбран:
# каталог — сборка, зависимости, окружение; отдельный файл бывает ручным (`SESSION.md` и
# `.claude/settings.local.json` здесь, `web/CLAUDE.md` в ProjectA), а предмет `secret-guard` —
# любой файл. Предел назван: файл внутри каталога, исключённого целиком (`.claude/` в ProjectA),
# стражам не виден; на пути инструмента страж по-прежнему стоит ДО записи.
# Префикс `./` ставит `printf` по аргументам, а не цикл чтения: имя с ведущим дефисом `find`
# иначе прочёл бы как ключ, а `read -d ''` из трубы bash читает побайтно — на 30 тыс. учтённых
# файлов это 3 с процессорного времени на событие без работы (раунд критика 1 октября 2026).
# КОРЕНЬ GIT — СВОЯ ВСЕЛЕННАЯ, И ЭТО НАЗВАННЫЙ ПРЕДЕЛ. Вложенная рабочая копия (подмодуль,
# вложенный репозиторий, worktree в `.claude/worktrees/`) приходит от git одной строкой
# каталога, и её файлы подаются событием с cwd в её собственном корне, а не в объемлющем.
# Рекурсия в неё пробовалась и снята вторым раундом критика: она смешивала две вселенные —
# свежий checkout целиком вставал в очередь впереди настоящих правок, игнорируемое проектом
# (`node_modules/`) подавалось изнутри копии, ссылка на каталог уводила в чужой репозиторий,
# один файл подавался из двух корней. Держит `test_adv_dispatch_nested_checkout.sh`.
#
# СОСТОЯНИЕ — ПАРЫ «СЕССИЯ + КОРЕНЬ», А НЕ СЕССИИ (раунд критика 1 октября 2026). Под одним
# id сессии метка и очередь хранили пути относительно корня, а сессия с субагентами бывает в
# нескольких корнях (cd в соседний проект, worktree): одноимённый `BACKLOG.md` второго корня
# отсекался как пройденный, отложенный путь первого корня решался против второго, а событие в
# одном корне сдвигало общую метку, не заглянув в другой. Тот же ключ отрезает очереди прежней
# редакции (с файлами игнорируемых каталогов): их имена другие, и голодать они не дают.
_rk=$(printf '%s' "$ROOT" | cksum | awk '{print $1}')
KEY="${SID}-${_rk:-0}"
MARK="$STATE_DIR/bash-dispatch-mark-${KEY}"
QUEUE="$STATE_DIR/bash-dispatch-queue-${KEY}"

# ОДНО СОБЫТИЕ ПАРЫ ЗА РАЗ (раунд критика 1 октября 2026). Субагенты одной сессии шлют
# события одновременно, и дедуп по флагу не держал их: флаг проверялся до вызова стража, а
# ставился после — 30 одновременных событий дали 187 подач вместо 7, и находку печатали 18 из
# 30; они же рвали строки очереди, потому что дописывание больше 4 КБ не атомарно. Событие
# пробует замок ОДИН раз и, не взяв, выходит: метку оно не двигало, его правки подберёт отбор
# держателя замка либо следующего события. Под многоагентной нагрузкой лишние события почти
# бесплатны. Библиотеки замка нет — подача идёт без него, как шла прежде (третье состояние
# названо: работает, но параллельность не держит).
# ЗАМОК ДЕРЖИТСЯ ВСЁ СОБЫТИЕ, вместе с вызовами стражей. Брошенность библиотека судит по
# живости владельца, а не по возрасту (D500): живой держатель долгого события замок не теряет,
# убитый тайм-аутом снимает его ловушкой (SIGTERM её исполняет), убитый SIGKILL срывается на
# следующем событии. Порог 90 с судит замок БЕЗ владельца (библиотека прежней редакции) и задаёт
# потолок для живого — десять порогов.
SL_LIB="$HOOK_DIR/state-lock-lib.sh"
[ -f "$SL_LIB" ] && . "$SL_LIB"
if command -v lock_acquire >/dev/null 2>&1; then
    CLAUDSOUL_LOCK_TRIES=1 CLAUDSOUL_LOCK_STALE_S=90 lock_acquire "$QUEUE" || exit 0
    trap 'lock_release "$QUEUE"' EXIT
fi

# НОВАЯ МЕТКА СТАВИТСЯ ДО ОТБОРА, А НЕ ПОСЛЕ. Метка, поставленная концом отбора, хоронила
# правку соседа, легшую между отбором и `touch`: та оказывалась старше метки, и `-newer` её
# больше не отбирал. Имя постоянное — под замком событие пары одно.
# ОЧЕРЕДЬ ПИШЕТСЯ ДО СДВИГА МЕТКИ (раунд критика 1 октября 2026): событие, прерванное между
# сдвигом метки и дописыванием очереди, теряло отобранную правку навсегда — отбор жил только в
# памяти, а метка уже была новее правки. Теперь прерывание оставляет старую метку, и следующее
# событие отберёт то же самое; повтор в очереди безвреден.
# ИМЯ С ПЕРЕВОДОМ СТРОКИ ИЛИ ТАБУЛЯЦИЕЙ НЕ РАСПАДАЕТСЯ (D495). Отбор бережёт имена NUL до `find`,
# а `cksum`, очередь и журнал построчны: имя «nl⏎f1.md» давало две строки, подавался НЕТРОНУТЫЙ
# `f1.md`, а записанный файл — никогда. Каждая запись `cksum` начинается с «crc размер ./»; строка
# без такого начала — продолжение имени, и `awk` склеивает её знаком \001, табуляцию в имени
# кодирует \002 (табуляция — разделитель полей очереди). При подаче имя раскодируется. Предел:
# продолжение имени, само похожее на начало записи `cksum`, склеено не будет.
# ВЕРСИЯ ФАЙЛА — ЕГО СОДЕРЖИМОЕ, И СНИМАЕТСЯ ОНА В МОМЕНТ ОТБОРА (D489). Ключ дедупа был парой
# «файл + страж» без версии, и вторая правка того же файла командой за сессию до стражей не
# доходила никогда (песочница: 7 подач первой версии, ни одной второй). Строка очереди —
# «путь ⇥ crc-размер» от `cksum` тем же процессом `find`, что отбирает: цена — по тронутым
# файлам события, а не по истории.
# ТРОНУТ — ЭТО И НОВОЕ СОДЕРЖИМОЕ, И НОВЫЙ ПУТЬ (D493). Перенос (`mv`, `git mv`), копия с
# сохранением времени (`cp -p`, `rsync -a`) и распаковка кладут в дерево путь со СТАРЫМ mtime —
# старше метки, и такой файл не отбирался никогда. Время смены метаданных (ctime) перенос
# двигает, поэтому отбор берёт новее метки по любому из двух. Смена одних прав (`chmod`) тоже
# двигает ctime, но повторной подачи не даёт: версия файла та же (D489).
# ПЕРВОЕ СОБЫТИЕ — ТОЛЬКО ПО mtime. Окно «пять минут» по ctime взяло бы весь свежий клон или
# распакованное дерево — ctime ставит сама файловая система, и состарить его нельзя: на
# 30 тыс. учтённых файлов это 116 с процессорного времени на событие. Предел назван: файл,
# перенесённый со старым mtime ДО первого события сессии, не отбирается.
if [ -f "$MARK" ]; then _age_op=-newer; _age_cop=-cnewer; _age_arg=$MARK; else _age_op=-mmin; _age_cop=-mmin; _age_arg=-5; fi
: > "$MARK.next" 2>/dev/null
# ПЕРВОЕ СОБЫТИЕ — ИЗМЕНЁННОЕ, А НЕ ВЕСЬ УЧЁТ (D501). Без метки отбор брал всё учтённое моложе пяти
# минут, а свежий checkout (worktree агента, клон) моложе целиком: правка сессии вставала в очередь
# за всеми его файлами и ждала ~N×7/6 событий. Свежий checkout чист, поэтому на первом событии
# учтённые кандидаты — изменённые против HEAD (в индексе и в рабочей копии); без коммитов — все
# учтённые, как прежде. С меткой — снова все учтённые: «правлен и закоммичен той же командой».
# git — через `project_git` (paths-lib): папка сессии бывает чужим репозиторием, и голый git
# исполнял бы `core.fsmonitor` и фильтры из его настроек (D515).
_sel=$(cd "$ROOT" && { if [ -f "$MARK" ]; then project_git ls-files -z --cached
                       else project_git diff -z --name-only HEAD 2>/dev/null || project_git ls-files -z --cached; fi
                      project_git ls-files -z --others --exclude-standard
                      project_git ls-files -z --others --ignored --exclude-standard --directory; } 2>/dev/null \
    | xargs -0 -r sh -c 'printf "./%s\0" "$@"' sh \
