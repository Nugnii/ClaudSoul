#!/usr/bin/env bash
# bash-write-dispatch.sh — PostToolUse[Bash]: правка, сделанная КОМАНДОЙ, подаётся стражам записи, которые видят только инструмент Edit.
# en: PostToolUse[Bash] — replays file writes made via shell into the guards registered for Edit/Write only.
#
# Зачем (13 сентября 2026, D407). Предмет «запись в файл» достижим двумя путями: инструментом
# (Edit/Write/MultiEdit) и командой (`python3 - <<PY`, `sed -i`, перенаправление). Стражи
# подписаны на первый. Замер: за сессию правлено 11 файлов кода, сработал НОЛЬ стражей;
# у `backlog-open-write-guard` — отказа УРОВНЯ 4 — ноль срабатываний при четырёх коммитах,
# тронувших его предмет. Доля правок оболочкой измерена ещё 27 августа: 1357 против 1675 (45%).
#
# ПОЧЕМУ ДИСПЕТЧЕР, А НЕ ПРАВКА КАЖДОГО СТРАЖА. Устройство у промаха одно, и чинить его
# восемь раз значит завести восемь мест для расхождения (корень R1). Здесь один вход и
# объявленный список: страж добавляется строкой, а не новым механизмом.
#
# ЧЕСТНО НАЗВАННАЯ ЦЕНА: событие ПОСЛЕ записи, поэтому ОТКАЗ здесь невозможен по построению —
# файл уже изменён. Уровень 4 на этом пути вырождается в громкое уведомление с требованием
# починить или откатить, и это записано, а не умолчано. Уровень 4 остаётся живым на пути
# инструмента, где страж стоит ДО записи.
#
# Input  (stdin): {tool_name:"Bash", session_id, cwd, ...} (PostToolUse JSON)
# Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} либо пусто
# Exit:  always 0.

set -uo pipefail

PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
if [ -f "$PATHS_LIB" ]; then source "$PATHS_LIB"; else : "${STATE_DIR:=$HOME/.claude/hooks/state}"; fi
mkdir -p "$STATE_DIR" 2>/dev/null

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat); [ -z "$INPUT" ] && exit 0
TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
[ "$TOOL" = "Bash" ] || exit 0

CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
[ -n "$CWD" ] && [ -d "$CWD" ] || CWD="$PWD"
ROOT=$(git -C "$CWD" rev-parse --show-toplevel 2>/dev/null) || exit 0
SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)
HOOK_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

# СПИСОК ОБЪЯВЛЕН ЗДЕСЬ. Трое отказывающих — их пропуск дороже всего — и один замечающий,
# добавленный 13 сентября 2026 по ЗАМЕРУ, а не по общему соображению:
# `pipefail-grep-q-notice` даёт 0 срабатываний на 719 отслеживаемых *.sh дерева, то есть
# говорит только на НОВОМ нарушении, и его сообщение осмысленно после записи («в коде,
# который ты только что записал, `grep -q` под pipefail»).
# ДВОЕ ДОБАВЛЕНЫ ПОСЛЕ СНЯТИЯ ВОЗРАЖЕНИЙ (13 сентября 2026):
# · `test-cost-notice` — возражение было «мера не та» (судил стенные секунды при владельце
#   факта на процессорных). Мера, источник и реестр оправданий взяты у владельца (D410),
#   числа сошлись: 13 дорогих по CPU минус 3 оправданных = 10 у стража.
# · `backlog-touch-check` — возражение было «подача крадёт слот его же дросселя». Кража шла
#   от того, что диспетчер подавал ВЕСЬ грязный список; теперь подаётся тронутое с прошлого
#   события, то есть ровно та популяция, которую увидел бы путь инструмента.
# ОТКАЗАНО ПО ЗАМЕРУ, с исключением в самих стражах: `budget-gate` (предмет не файл —
# из входа читает только session_id и tool_name, вывод побайтово одинаков на чистом и
# нарушающем) и `module-context-inject` (в этом дереве нем по построению: нет
# `.claude-docs/module-index.md`, нет и генератора).
GUARDS="secret-guard.sh test-exit-explicit-guard.sh backlog-open-write-guard.sh pipefail-grep-q-notice.sh test-cost-notice.sh backlog-touch-check.sh"

# ПОДАЮТСЯ ФАЙЛЫ, ТРОНУТЫЕ С ПРОШЛОГО СОБЫТИЯ, а не все грязные (13 сентября 2026).
# Первая редакция брала весь грязный список, и это крало слот у РАБОЧЕГО пути: у стражей
# бывает свой дроссель на сессию, журнал общий для обоих путей, — задне-числовая подача
# гасила срабатывание на пути ДО записи, где сообщение единственно и осмысленно. Замер с
# положительным контролем: подача задним числом в сессии S → настоящая правка того же
# файла в S даёт 0 байт, она же в свежей сессии T — 669. Плюс шум: по файлам последних
# 20 коммитов страж `backlog-touch-check` попадал на КАЖДЫЙ ТРЕТИЙ тронутый файл (28 из 90),
# то есть весь грязный список означал десятки инжектов за сессию.
# Метка сессии двигается на каждом событии: подаётся то, что новее её.
MARK="$STATE_DIR/bash-dispatch-mark-${SID}"
if [ -f "$MARK" ]; then
    _sel=$(cd "$ROOT" && find . -newer "$MARK" -type f -not -path './.git/*' 2>/dev/null | sed 's|^\./||')
else
    # Первое событие сессии: без метки списка «что изменилось» нет, и весь грязный список
    # брать нельзя — это ровно тот шум, от которого уходим. Берём тронутое за последние
    # пять минут: окно названо числом, а не подразумевается.
    _sel=$(cd "$ROOT" && find . -type f -mmin -5 -not -path './.git/*' 2>/dev/null | sed 's|^\./||')
fi
touch "$MARK" 2>/dev/null

# ОЧЕРЕДЬ, А НЕ МГНОВЕННЫЙ СНИМОК. Два требования спорят: подавать только свежее (иначе
# крадём слот дросселя у рабочего пути) и ОТКЛАДЫВАТЬ пары сверх бюджета (иначе ход платит
# секунды). Мгновенный снимок исполняет первое и ломает второе: отложенная пара к следующему
# событию уже не «свежая». Поэтому свежие дописываются в очередь сессии, а обойдённые в ней
# остаются; пройденные стоят дёшево — проверка флага.
QUEUE="$STATE_DIR/bash-dispatch-queue-${SID}"
printf '%s\n' "$_sel" | grep -v '^$' >> "$QUEUE" 2>/dev/null
CHANGED=$(sort -u "$QUEUE" 2>/dev/null | grep -v '^$' || true)
[ -n "$CHANGED" ] || exit 0

# ПОТОЛОК ВЫВОДА, А НЕ ОБНАРУЖЕНИЯ (13 сентября 2026). Замер сессии: тронут 41 файл
# (23 документа, 13 скриптов, 2 python). Стражей в списке несколько, дедуп — по ПАРЕ
# «файл + страж», поэтому одна команда, тронувшая десяток файлов, способна выдать
# десятки строк разом. Потолок стоит на ПЕЧАТИ: находки считаются все, показываются
# первые, остаток называется числом — иначе повторится дефект, который в этот же день
# стоил половины словаря признаков (`awk NR<=30` на словаре вместо вывода).
MAX_SHOW="${BASH_DISPATCH_MAX_SHOW:-5}"
# БЮДЖЕТ ВЫЗОВОВ, а не только печати (13 сентября 2026). Замер: 3 файла × 3 стража = 1,1 с,
# то есть 0,12 с на вызов; при восьми стражах и десятке тронутых файлов ход платил бы
# ~9 секунд. Дедуп по паре «файл + страж» делает цену РАЗОВОЙ за сессию, но вся она падает
# на ту команду, которая случилась первой после правок. Бюджет размазывает её по ходам:
# непройденные пары флага НЕ получают и приходят на следующем событии.
MAX_RUNS="${BASH_DISPATCH_MAX_RUNS:-6}"
FOUND=""; SHOWN=0; EXTRA=0; RUNS=0
while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    case "$rel" in *.sh|*.py|*.md|*.json|*.tsv|*.txt|*.yml) ;; *) continue ;; esac
    f="$ROOT/$rel"
    [ -f "$f" ] || continue
    # Файл целиком в поле `content`: стражи читают именно его. Огромные файлы пропускаем —
    # цена подачи не должна расти без предела.
    sz=$(wc -c < "$f" 2>/dev/null | tr -d ' ')
    [ -n "$sz" ] && [ "$sz" -le 400000 ] || continue
    for g in $GUARDS; do
        [ -f "$HOOK_DIR/$g" ] || continue
        key=$(printf '%s|%s' "$rel" "$g" | (command -v md5sum >/dev/null 2>&1 && md5sum || md5) 2>/dev/null | awk '{print $1}')
        flag="$STATE_DIR/bash-dispatch-${SID}-${key}.flag"
        [ -f "$flag" ] && continue
        [ "$RUNS" -ge "$MAX_RUNS" ] && break 2
        RUNS=$((RUNS+1))
        payload=$(jq -n --arg f "$f" --arg sid "$SID" --arg cwd "$ROOT" --rawfile c "$f" \
            '{tool_name:"Write", session_id:$sid, cwd:$cwd, tool_input:{file_path:$f, content:$c}}' 2>/dev/null) || continue
        out=$(printf '%s' "$payload" | bash "$HOOK_DIR/$g" 2>/dev/null)
        [ -n "$out" ] || { : > "$flag" 2>/dev/null; continue; }
        reason=$(printf '%s' "$out" | jq -r '(.hookSpecificOutput.permissionDecisionReason // .hookSpecificOutput.additionalContext // "")' 2>/dev/null)
        [ -n "$reason" ] || { : > "$flag" 2>/dev/null; continue; }
        # ПОРЯДОК ДВУХ ОГРАНИЧИТЕЛЕЙ ОБЪЯВЛЕН ЗДЕСЬ: дедуп гасит ПОКАЗАННОЕ, потолок
        # откладывает ПОКАЗ. Первая редакция ставила флаг до потолка, и отложенная находка
        # гасла навсегда — сообщение обещало «ждут следующего хода», а ждать было нечему.
        # Дробь класса измерена в тот же час: носитель 1 из 4 мест дерева, где дедуп и
        # потолок стоят рядом (`impact-inject.sh:73-74` уже держит верный порядок, у
        # `claude-md-size-check` и `module-context-inject` `head` режет строку, а не находки).
        # ПОТОЛОК ЗНАКОВ ИЗМЕРЕН, А НЕ ВЗЯТ КРУГЛЫМ: сообщения стражей доходят до 590
        # знаков, и прежние 400 отрезали у `backlog-touch-check` ТРЕТИЙ исход — «пункт уже
        # решён, а метка осталась → закрой с показанием», ровно тот, что после записи
        # вероятнее прочих. Замер скептика 13 сентября 2026.
        if [ "$SHOWN" -ge "$MAX_SHOW" ]; then
            EXTRA=$((EXTRA+1))
            continue
        fi
        : > "$flag" 2>/dev/null
        SHOWN=$((SHOWN+1))
        FOUND="${FOUND}
  · ${rel} — ${g%.sh}: ${reason:0:700}"
    done
done <<< "$CHANGED"

[ -n "$FOUND" ] || exit 0

MSG="⛔ Правка сделана КОМАНДОЙ, и стражи записи её не видели — подаю им задним числом:${FOUND}"
[ "$EXTRA" -gt 0 ] && MSG="${MSG}
  · и ещё ${EXTRA} находк(и) в этом ходу — показаны первые ${MAX_SHOW}, остальные ждут следующего хода (дедуп по паре «файл + страж» их не потеряет)."
MSG="${MSG}
Отказать уже нельзя: файл изменён. Почини или откати ПРЕЖДЕ, чем коммитить."
jq -cn --arg m "$MSG" '{hookSpecificOutput: {hookEventName: "PostToolUse", additionalContext: $m}}'
exit 0
