# ОЧЕРЕДЬ, А НЕ МГНОВЕННЫЙ СНИМОК. Два требования спорят: подавать только свежее (иначе
# крадём слот дросселя у рабочего пути) и ОТКЛАДЫВАТЬ пары сверх бюджета (иначе ход платит
# секунды). Мгновенный снимок исполняет первое и ломает второе: отложенная пара к следующему
# событию уже не «свежая». Поэтому свежие дописываются в очередь сессии, а обойдённые в ней
# остаются.
# ПРОЙДЕННОЕ — ЖУРНАЛ ПАР «ПУТЬ ⇥ ВЕРСИЯ ⇥ СТРАЖ», А ОЖИДАЮЩЕЕ СЧИТАЕТ ОДИН `awk` (D489).
# Прежде здесь были флаг-файл на пару (имя — md5 пары, процесс на КАЖДУЮ пару) и список
# пройденных файлов с отпечатком набора стражей в имени. Смена набора начинала список с нуля, и
# одно событие считало md5 для каждой пары всей истории: при истории в 10 и 20 файлов — 62 и 122
# вызова хеш-утилит на событии без единой подачи. Флаги же были каждый своим семейством уборки
# (хеш пары стоял в имени после id сессии) и не убирались никогда — 66 тыс. в каталоге состояния
# (D496). Теперь у пары «сессия + корень» три файла — метка, очередь, журнал; ожидающая пара — та,
# что для ПОСЛЕДНЕЙ версии файла в очереди и присутствующего стража не записана в журнале.
# Цена — чтение двух файлов одним процессом, без процесса на пару. Неподаваемое (расширение,
# размер) пишется в журнал со стражем «*». Строки очереди прежней редакции (без версии)
# пропускаются: пересмотреть их было бы нечем, а тронутое после — отберётся заново.
# Очередь и журнал пишет только держатель замка, и оба только дописываются.
# «ПРОЙДЕНО» — ОТНОСИТЕЛЬНО СТРАЖЕЙ, КОТОРЫЕ ЕСТЬ (раунд критика 1 октября 2026): страж,
# доехавший установкой позже, получает ожидающие пары по всей очереди один раз.
_present=""
for g in $GUARDS; do [ -f "$HOOK_DIR/$g" ] && _present="${_present} $g"; done
PAIRS="$STATE_DIR/bash-dispatch-pairs-${KEY}"
[ -f "$PAIRS" ] || : > "$PAIRS" 2>/dev/null
# РАСШИРЕНИЕ — СВОЙСТВО СТРАЖА, А НЕ ФАЙЛА (D491). Фильтр `*.sh|*.py|*.md|*.json|*.tsv|*.txt|*.yml`
# стоял перед ВСЕМИ стражами и прятал от `secret-guard` то, ради чего D487 расширил отбор: `.env`
# (архетип отдельного игнорируемого файла с секретом), `*.ts`/`*.tsx`, `*.yaml`, `*.toml`. На пути
# инструмента тот же страж судит любой путь (замер 1 октября 2026: deny для `config.ts`, `.env`,
# `deploy.yaml`, `pyproject.toml`). Теперь `secret-guard` получает пару для любого файла, прочие
# стражи — по прежнему списку: их предмет — код и документы. Цена — одна пара на файл вне списка,
# 0,24 с вызова `secret-guard`: после команды, тронувшей сотни таких файлов (форматтер), очередь
# догоняет их по бюджету событий. Пары файлов из списка идут в очереди РАНЬШЕ — правка кода агента
# не ждёт за массовой правкой прочего.
# Строка «путь ⇥ версия ⇥ страж ⇥ !» — сбой стража на паре (D494): пара остаётся ожидающей, после
# второго сбоя снимается — вечно падающий страж иначе съедал бы бюджет вызовов каждого события.
PEND=$(LC_ALL=C awk -F'\t' -v gs="$_present" '
    FILENAME == ARGV[1] { if (NF == 3) done[$0] = 1; else if (NF == 4 && $4 == "!") crash[$1 "\t" $2 "\t" $3]++; next }
    NF == 2 && $1 != "" && $2 != "" { if (!($1 in ver)) ord[++k] = $1; ver[$1] = $2 }
    END {
        n = split(gs, G, " ")
        for (i = 1; i <= k; i++) {
            r = ord[i]; v = ver[r]
            if ((r "\t" v "\t*") in done) continue
            code = (r ~ /\.(sh|py|md|json|tsv|txt|yml)$/)
            for (j = 1; j <= n; j++) {
                if (!code && G[j] != "secret-guard.sh") continue
                p = r "\t" v "\t" G[j]
                if (!(p in done) && crash[p] < 2) print (code ? "0" : "1") "\t" p
            }
        }
    }' "$PAIRS" "$QUEUE" 2>/dev/null | LC_ALL=C sort -s -t "$(printf '\t')" -k1,1 -k2,2 | cut -f2-)
[ -n "$PEND" ] || exit 0

# ПОТОЛОК ВЫВОДА, А НЕ ОБНАРУЖЕНИЯ (13 сентября 2026). Замер сессии: тронут 41 файл
# (23 документа, 13 скриптов, 2 python). Стражей в списке несколько, дедуп — по ПАРЕ
# «файл + страж», поэтому одна команда, тронувшая десяток файлов, способна выдать
# десятки строк разом. Потолок стоит на ПЕЧАТИ: находки считаются все, показываются
# первые, остаток называется числом — иначе повторится дефект, который в этот же день
# стоил половины словаря признаков (`awk NR<=30` на словаре вместо вывода).
MAX_SHOW="${BASH_DISPATCH_MAX_SHOW:-5}"
# БЮДЖЕТ ВЫЗОВОВ, а не только печати (13 сентября 2026). Замер: 3 файла × 3 стража = 1,1 с,
# то есть 0,12 с на вызов; при восьми стражах и десятке тронутых файлов ход платил бы
# ~9 секунд. Дедуп по паре «версия файла + страж» делает цену РАЗОВОЙ на версию, но вся она
# падает на ту команду, которая случилась первой после правок. Бюджет размазывает её по ходам:
# непройденные пары в журнал НЕ пишутся и приходят на следующем событии.
MAX_RUNS="${BASH_DISPATCH_MAX_RUNS:-6}"
FOUND=""; CRASH=""; SHOWN=0; EXTRA=0; RUNS=0
_lr=""; _skip=0
while IFS="$(printf '\t')" read -r rel ver g; do
    [ -n "$rel" ] && [ -n "$g" ] || continue
    if [ "$rel" != "$_lr" ]; then
        _lr="$rel"; _skip=0
        # Неподаваемое по размеру пишется пройденным сразу (страж «*»): стражи читают файл целиком
        # в поле `content`, и цена подачи не должна расти без предела. Расширение — свойство
        # СТРАЖА, а не файла, и судит его `awk` выше (D491).
        [ "${ver##*-}" -gt 400000 ] 2>/dev/null && _skip=1
        [ "$_skip" = 1 ] && printf '%s\t%s\t*\n' "$rel" "$ver" >> "$PAIRS" 2>/dev/null
        # Имя раскодируется лениво: только у подаваемого файла и только с закодированным знаком —
        # процесс на каждый неподаваемый файл очереди вернул бы цену истории (D487).
        if [ "$_skip" = 0 ]; then
            case "$rel" in
                *$'\001'*|*$'\002'*) f="$ROOT/$(printf '%s' "$rel" | tr '\001\002' '\n\t')" ;;
                *) f="$ROOT/$rel" ;;
            esac
            # Исчезнувший файл остаётся ожидающим: проверка встроенная, вернувшийся — подаётся.
            [ -f "$f" ] || _skip=2
        fi
    fi
    [ "$_skip" = 0 ] || continue
    [ "$RUNS" -ge "$MAX_RUNS" ] && break
    RUNS=$((RUNS+1))
    # Подача называет свой момент — файл УЖЕ записан. Страж, сравнивающий запись с диском, иначе
    # сравнил бы её саму с собой и молчал на любом входе (D492).
    payload=$(jq -n --arg f "$f" --arg sid "$SID" --arg cwd "$ROOT" --rawfile c "$f" \
        '{hook_event_name:"PostToolUse", tool_name:"Write", session_id:$sid, cwd:$cwd, tool_input:{file_path:$f, content:$c}}' 2>/dev/null) || continue
    out=$(printf '%s' "$payload" | bash "$HOOK_DIR/$g" 2>/dev/null); _grc=$?
    # СБОЙ СТРАЖА — НЕ «ЧИСТО» (D494). Пустой вывод бывает и у «проверил, чисто», и у «упал»
    # (необъявленная переменная под `set -u`, отказ fork под нагрузкой); различает их код.
    # Упавший не пишет пару пройденной: она подаётся снова, а сбой называется.
    if [ -z "$out" ] && [ "$_grc" -ne 0 ]; then
        printf '%s\t%s\t%s\t!\n' "$rel" "$ver" "$g" >> "$PAIRS" 2>/dev/null
        CRASH="${CRASH}
  · ${rel} — ${g%.sh}: страж упал (код ${_grc}) и не ответил — исход неизвестен; пара будет подана снова, после второго сбоя снимается"
        continue
    fi
    [ -n "$out" ] || { printf '%s\t%s\t%s\n' "$rel" "$ver" "$g" >> "$PAIRS" 2>/dev/null; continue; }
    reason=$(printf '%s' "$out" | jq -r '(.hookSpecificOutput.permissionDecisionReason // .hookSpecificOutput.additionalContext // "")' 2>/dev/null); _jrc=$?
    # НЕЧИТАЕМЫЙ ОТВЕТ — НЕ «ЧИСТО» (D1026). Страж записи собрал JSON строкой, разрез лёг после `\`, и `jq` не разобрал
    # вывод: пустой разбор писал пару пройденной, и подсказка о дефектной строке пропала молча. Ответ той же версии файла
    # повторится, поэтому пара пишется пройденной, а нечитаемость называется один раз. Причину, которую `jq` успел
    # разобрать до ошибки (объект и хвост не-JSON), показываем её, а не обрезок сырого вывода.
    if [ "$_jrc" -ne 0 ]; then
        printf '%s\t%s\t%s\n' "$rel" "$ver" "$g" >> "$PAIRS" 2>/dev/null
        if [ -n "$reason" ]; then _unr="${reason:0:700}"; else _unr="${out:0:160}"; fi
        CRASH="${CRASH}
  · ${rel} — ${g%.sh}: страж ответил не JSON протокола — находка прочитана не целиком, исход неизвестен: «${_unr}»"
        continue
    fi
    [ -n "$reason" ] || { printf '%s\t%s\t%s\n' "$rel" "$ver" "$g" >> "$PAIRS" 2>/dev/null; continue; }
    # ПОРЯДОК ДВУХ ОГРАНИЧИТЕЛЕЙ ОБЪЯВЛЕН ЗДЕСЬ: дедуп гасит ПОКАЗАННОЕ, потолок
    # откладывает ПОКАЗ. Первая редакция ставила флаг до потолка, и отложенная находка
    # гасла навсегда — сообщение обещало «ждут следующего хода», а ждать было нечему.
    # Дробь класса измерена в тот же час: носитель 1 из 4 мест дерева, где дедуп и
    # потолок стоят рядом (`impact-inject.sh:73-74` уже держит верный порядок, у
    # `claude-md-size-check` и `module-context-inject` `head` режет строку, а не находки).
    # ПОТОЛОК ЗНАКОВ ИЗМЕРЕН, А НЕ ВЗЯТ КРУГЛЫМ: сообщения стражей доходят до 590
    # знаков, и прежние 400 отрезали у `backlog-touch-check` ТРЕТИЙ исход — «пункт уже
    # решён, а метка осталась → закрой с показанием», ровно тот, что после записи
    # вероятнее прочих. Замер скептика 13 сентября 2026.
    if [ "$SHOWN" -ge "$MAX_SHOW" ]; then
        EXTRA=$((EXTRA+1))
        continue
    fi
    printf '%s\t%s\t%s\n' "$rel" "$ver" "$g" >> "$PAIRS" 2>/dev/null
    SHOWN=$((SHOWN+1))
    FOUND="${FOUND}
  · ${rel} — ${g%.sh}: ${reason:0:700}"
done <<< "$PEND"

[ -n "$FOUND" ] || [ -n "$CRASH" ] || exit 0

MSG=""
if [ -n "$FOUND" ]; then
    MSG="⛔ Файл изменён после прошлого события, и стражи записи этого изменения не видели — подаю им задним числом:${FOUND}"
    [ "$EXTRA" -gt 0 ] && MSG="${MSG}
  · и ещё ${EXTRA} находк(и) в этом ходу — показаны первые ${MAX_SHOW}, остальные ждут следующего хода (дедуп по паре «версия файла + страж» их не потеряет)."
    MSG="${MSG}
Отказать уже нельзя: файл изменён. Кто изменил, диспетчер не знает: эта команда, твой Edit или другой процесс (соседняя сессия в той же рабочей копии, редактор). Правка твоя — почини прежде, чем коммитить; не твоя — не трогай чужую работу, назови находку владельцу."
fi
[ -n "$CRASH" ] && MSG="${MSG:+$MSG
}⚠️ Страж записи упал или ответил нечитаемо на правке, сделанной командой, — его ответа нет, и это НЕ «чисто»:${CRASH}"
jq -cn --arg m "$MSG" '{hookSpecificOutput: {hookEventName: "PostToolUse", additionalContext: $m}}'
exit 0
