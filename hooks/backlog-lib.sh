#!/usr/bin/env bash
# backlog-lib.sh — ЕДИНСТВЕННОЕ определение того, что такое пункт долга.
#
# ПРЕФИКСЫ: backlog_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
#
# Результат: все читатели BACKLOG.md опознают пункт одинаково, независимо от его вёрстки
# Проверка результата: bash hooks/tests/test_backlog_item_shape.sh даёт 0
#
# Зачем. 28 августа 2026 пункты долга сменили вёрстку со списка (`- ☑ **D42**`) на
# заголовок (`### D42 ☑ …`). Три стража перестали видеть их в тот же день и молчали сутки:
#
#   · `scripts/backlog-archive.sh`     — «переносить нечего» при двух ☑ в файле;
#   · `scripts/backlog-return-check.sh` — ноль открытых пунктов, условия возврата не проверялись;
#   · `hooks/backlog-vanish-check.sh`  — ноль идентификаторов, пропажа пункта невидима.
#
# У каждого признак был снят с ТОГДАШНЕГО состава файла (`^- ` + метка), а не выражен
# правилом о предмете. Пока состав совпадал, признак работал; сменился — отказал молча.
# Комментарий в `backlog-vanish-check.sh` (про уехавшие в архив заголовки D59, D20, D23, D50;
# в редакции до f3bc4e7 — строка 51) к тому моменту уже упоминал заголовки — знание
# о второй форме в проекте было, до признака не дошло.
#
# Отдельно про то, почему сутки. Проверка результата архиватора звучала как
# `grep -c '^- ☑' BACKLOG.md даёт 0` — то есть искала ту же форму, что и сам инструмент, и
# была зелёной ровно тогда, когда он слеп. Проверка, выраженная через реализацию,
# наследует её слепое пятно и не может обнаружить её отказ; поэтому здесь она выражена
# через СОСТОЯНИЕ: «выполненных пунктов в файле нет», а форму знает эта библиотека.
#
# ПРАВИЛО. Пункт долга опознаётся по РОЛИ токенов в строке, а не по её ВИДУ. Роль
# у каждой вёрстки своя, и признак называет именно её:
#
#   · списочная — метка стоит СРАЗУ за маркером списка, а сразу за меткой —
#     ИДЕНТИФИКАТОР (`- ☑ **D42** …`). Метка здесь и есть поле статуса пункта, поэтому
#     признак — её ПОЗИЦИЯ, а не присутствие;
#   · заголовочная — сразу за решётками стоит ИДЕНТИФИКАТОР (`### D42 ☑ …`,
#     `#### TASK-003a · … — ☑ done`), а метка стоит где угодно в строке.
#
# Идентификатора требуют ОБЕ вёрстки. До 3 сентября 2026 списочная не требовала, и
# `- ☑ done — сделано` (легенда, написанная списком) была пунктом — при том, что строка
# легенды объявлена контрпримером тут же ниже. Цена требования измерена по живому корпусу:
# из 187 списочных пунктов (16 в BACKLOG.md, 171 в архиве) идентификатор несут 187.
#
# До 3 сентября 2026 правило звучало «префикс + произвольный текст + метка где угодно»,
# то есть проверяло ВИД строки. Замер по живому корпусу (BACKLOG-archive.md):
#   · из 182 списочных строк с меткой пунктами являются 171 — метка сразу за `- `;
#     остальные 11 суть ТЕЛО заголовочных пунктов («- Статус:     ☑ done (2026-06-20)»,
#     «- Источник: F7 (P1) · … · ☐ todo»), и старый признак звал пунктом каждую;
#   · из 73 заголовков с меткой идентификатор несут 71; двое без него —
#     «## Прогон 2026-06-20 — пилот `hooks/` (выполнен, все ☑)» (BACKLOG-archive.md:41),
#     это РАЗДЕЛ, и старый признак звал его выполненным пунктом.
#
# НАЗВАННЫЙ ПРЕДЕЛ. Второй заголовок без идентификатора — «### Остаток STATE_DIR (003e)
# и compile-reminder — ⊘ оставлено намеренно» — пунктом является, и признак его не видит:
# 72 верных из 73 против 71 у прежнего.
#
# Первая редакция этого абзаца оправдывала предел словами «ложный ПРОПУСК оставляет пункт
# лежать в рабочем файле, где он и был». Прогон 3 сентября 2026 это ОПРОВЕРГ: у архиватора
# заголовок, не признанный пунктом и не имеющий под собой открытых пунктов, не попадал ни
# в рабочий файл, ни в архив — он ИСЧЕЗАЛ вместе со своим телом, при коде возврата 0.
# Последствие было названо по модели, а не по замеру, хотя замер стоил одного прогона.
# Корень был не в признаке, а в записи архиватора (заголовок выводился только через стек
# перенесённых), и починен там же: непринятый заголовок теперь остаётся в рабочем файле.
# Теперь предел действительно означает «пункт лежит там, где был», и это проверено
# (hooks/tests/test_backlog_archive.sh, T16).
#
# Чего предел стоит СЕЙЧАС: такой пункт невидим стражу пропажи (`backlog-vanish-check`
# фильтрует строки этим же признаком) и стражу возврата — то есть его исчезновение чужой
# рукой некому заметить. Направление ошибки всё равно выбрано так: ложный ПРИЁМ уносил
# раздел в архив и сиротил живые пункты под ним. Условие снятия предела: у заголовочных
# пунктов появится обязательный идентификатор — тогда предел исчезнет сам.
#
# КОНТРПРИМЕРЫ, которые признак обязан отвергать:
#   · строка легенды в любой вёрстке: «**Легенда статусов:** ☐ todo · ◐ …» — нет
#     префикса; «- ☑ done — сделано» — префикс и метка есть, идентификатора нет;
#   · проза «верни пункту ☐ в BACKLOG.md» — нет префикса;
#   · тело пункта «- Статус:     ☑ done» — префикс есть, метка не первая;
#   · заголовок раздела «## Прогон … (выполнен, все ☑)» — решётки есть, идентификатора нет;
#   · строка ВНУТРИ забора кода («```») — образец разметки, а не пункт: роль у неё задана
#     не строкой, а окружением, поэтому её снимает `backlog_strip_fenced`, а не признак.

# Метки, означающие «сделано» и «не сделано» (легенда BACKLOG.md).
# Каждая метка названа ОТДЕЛЬНОЙ переменной, а наборы собираются из них: читателю метка
# нужна и поодиночке — в сообщении собеседнику («верни метке ◐»), — и вырезать её из
# набора он не может, не заведя своей копии глифа. Своя копия глифа в читателе — та же
# вторая копия признака, что и своя регулярка (D305); резать набор `${VAR%?}` тоже
# нельзя: в локали C оболочка снимает БАЙТ, а метка трёхбайтовая.
BACKLOG_MARK_DONE='☑'
BACKLOG_MARK_WAIVED='⊘'
BACKLOG_MARK_TODO='☐'
BACKLOG_MARK_WIP='◐'
BACKLOG_DONE_MARKS="${BACKLOG_MARK_DONE}${BACKLOG_MARK_WAIVED}"
BACKLOG_OPEN_MARKS="${BACKLOG_MARK_TODO}${BACKLOG_MARK_WIP}"

# backlog_item_re [метки] — регулярное выражение строки пункта.
# Обе вёрстки в одном выражении: префикс либо `- `, либо `#{2,4} `.
# МЕТКИ — АЛЬТЕРНАТИВОЙ ЛИТЕРАЛОВ, А НЕ КЛАССОМ. Класс `[☐◐]` в mawk (он стоит в чистом
# Debian) и в grep под локалью C читается по БАЙТАМ: ☑ (E2 98 91) делит первый байт с ☐
# (E2 98 90), и закрытый пункт проходит за открытый. Поймано CI 30 августа 2026
# (test_backlog_touch_check T3), на macOS невидимо — awk и grep там знают UTF-8.
backlog_marks_alt() {   # <метки> → «☐|◐» из известных меток, по подстроке, без разбора байтов
    _alt=""
    for _mk in ☐ ◐ ☑ ⊘; do
        case "$1" in *"$_mk"*) _alt="${_alt}${_alt:+|}${_mk}" ;; esac
    done
    printf '%s' "${_alt:-☐|◐|☑|⊘}"
}

# Идентификатор пункта: латиница, дефисы и цифры, хотя бы одна цифра обязательна
# (`D42`, `X1`, `TASK-003a`). Кириллическое слово им не является — этим и отсекаются
# заголовки разделов. `[*]{0,2}` — необязательное жирное начертание, скобочным
# выражением, а не `\*`: в awk (backlog-touch-check зовёт признак динамическим регекспом)
# escape вне перечня POSIX не определён.
BACKLOG_ID_RE='[*]{0,2}[A-Za-z][A-Za-z0-9-]*[0-9][A-Za-z0-9-]*'

backlog_item_re() {
    _m="${1:-${BACKLOG_DONE_MARKS}${BACKLOG_OPEN_MARKS}}"
    _a="$(backlog_marks_alt "$_m")"
    # `.` в grep -E перевод строки и так не покрывает — отдельный `[^\n]` не нужен, а
    # `printf` истолковал бы `\n` как настоящий перевод и разрушил бы выражение. Ловушка
    # поймана тестами стража в тот же час: вывод хука стал пустым.
    #
    # Труба больше не запрещена. Прежнее `[^|]*` делало НЕВИДИМЫМ пункт, чей заголовок
    # несёт `|` до метки («### D702 · Труба `cmd | grep -q` … — ☑ done»); в архиве 11
    # строк пунктов с трубой (`sid|key|date`, `printf … | tr …`). Отсекать таблицу
    # Markdown ей было незачем: строку таблицы и так отсекает префикс `^- ` / `^#{2,6} `.
    printf '^(- (%s) %s|#{2,6} %s.*(%s))' "$_a" "$BACKLOG_ID_RE" "$BACKLOG_ID_RE" "$_a"
}

# backlog_ids <файл> [метки] — идентификаторы пунктов с указанными метками, по одному в строку.
# backlog_id_stream — читает строки пунктов со stdin, печатает ИДЕНТИФИКАТОР каждой.
# Отдельной функцией, потому что читателей два и порядок им нужен разный: архиватору и
# библиотеке — уникальные и отсортированные, стражу возврата — в порядке появления. Копия
# признака у второго читателя уже расходилась молча (T6 в test_backlog_item_shape), поэтому
# признак живёт здесь, а не в двух местах.
#
# ПЕРВЫЙ номер строки, а не все. Идентификатор у пункта один, а заголовок законно
# ссылается на родню: «- ☐ **D284** … — родня D279», «… вне D278», «закрытие D236
# воскресло». До 3 сентября 2026 `grep -oE 'D[0-9]+'` возвращал ВСЕ совпадения, и три
# такие ссылки дали три несуществующих открытых пункта: библиотека насчитала 19 при 16 у
# архиватора. Признак был снят с ФОРМЫ («в строке есть D-номер»), а различать надо РОЛЬ
# («этот номер — идентификатор пункта»), — тот же род, что D279.
#
# ТОКЕН ЦЕЛИКОМ И ЛЮБОЙ НУМЕРАЦИИ. Та правка развела форму и роль наполовину: выражение
# осталось `D[0-9]+`, то есть без правой границы и в одном пространстве имён. Два отказа
# из этого, замерены 3 сентября 2026 на живых файлах:
#   · `- ☐ **D300a**` отдавал `D300` — тот же идентификатор, что у соседнего пункта.
#     `sort -u` склеивал два РАЗНЫХ пункта в один, и `backlog-vanish-check` переставал
#     видеть бесследную пропажу подномера (BEFORE = AFTER);
#   · не-D идентификаторы не отдавали НИЧЕГО, хотя шапка этого файла объявляет их
#     законными («бывает `D42`, а бывает `X1`»). В BACKLOG-archive.md таких пунктов 30
#     из 255 (`R1.1`, `TASK-003a`, `F7`, `DEFER-1`), и для стража возврата пункт без
#     D-номера просто исчезал из цикла ещё до проверки условия.
# Правило теперь о РОЛИ: идентификатор — первый токен «буквы + номер», взятый ЦЕЛИКОМ до
# границы. Разметка `**` снимается ДО поиска, поэтому обе вёрстки читаются одним
# выражением: в списке идентификатор жирный (`- ☐ **D284**`), в заголовке голый
# (`### D109 ☑ …`). На живом BACKLOG.md результат не изменился: 16 пунктов, 16 тех же
# идентификаторов (`diff` старого и нового потока пуст).
# `match/RSTART/RLENGTH` — POSIX awk, работает и в mawk.
# Выражение вынесено в константу, потому что читателей у него два: этот поток и гейт
# закрытия в `scripts/backlog-archive.sh` (он берёт её через окружение). До 3 сентября 2026
# у гейта была СВОЯ копия — `re.search(r'D(\\d+)', …)`, то есть тот же дефект уровнем ниже:
# идентификатор брался по ВИДУ (любой D-номер строки). Замер того же дня: на пункте
# «- ☑ **X1** Закрыт по образцу D284» библиотека отдавала `X1`, а гейт винил `D284` —
# ЖИВОЙ открытый пункт настоящего BACKLOG.md, к делу не относящийся.
BACKLOG_ID_TOKEN_RE='[A-Za-z]+-?[0-9][A-Za-z0-9.-]*'

backlog_id_stream() {
    awk -v tok="$BACKLOG_ID_TOKEN_RE" '{ _s = $0; gsub(/\*/, "", _s)
           if (match(_s, tok))
               print substr(_s, RSTART, RLENGTH) }'
}

# ЗАБОР КОДА. Роль строки задаётся не только её содержимым, но и окружением: внутри
# ``` лежит ОБРАЗЕЦ разметки, а не пункт. Форма живая — BACKLOG.md:18-22 показывает
# контракт пункта именно забором кода. Признак строки такого различить не может по
# построению (`backlog_is_item` видит одну строку и контекста не имеет), поэтому забор
# снимается ДО признака, потоком. Строки внутри забора заменяются пустыми, а не
# выбрасываются: нумерация строк файла остаётся прежней для тех, кто её считает.
BACKLOG_FENCE_RE='^[ \t]*(````*|~~~~*)'

# ЗАБОР ПОМНИТ, КАКИМ МАРКЕРОМ ОТКРЫТ И КАКОЙ ДЛИНЫ. Прежняя модель была ОДНОРАЗРЯДНОЙ
# (`inf = 1 - inf`): она хранила, что забор открыт, а не КАКОЙ. Показать забор кода
# образцом — законная и живая форма («```» внутри «~~~»), и такая строка ПЕРЕВОРАЧИВАЛА
# состояние: остаток файла целиком становился «текстом внутри забора» и исчезал из разбора
# вместе с настоящими пунктами. Замер 3 сентября 2026 на фикстуре из двух открытых пунктов
# (``` внутри ~~~ в теле первого): `backlog_ids` отдавал {D810} вместо {D810 D811} —
# ОТКРЫТЫЙ пункт пропадал молча.
#
# ДЛИНА — вторая половина той же роли, и без неё маркера мало. Показать забор из ТРЁХ
# кавычек можно только забором из ЧЕТЫРЁХ — другой формы в Markdown нет. Признак же
# опознавал забор по ВИДУ первых трёх символов, поэтому внутренний ``` читался закрытием
# внешнего ````: образец внутри становился настоящим пунктом, уезжал в архив и уносил с
# собой хвост тела ОТКРЫТОГО пункта. Правило CommonMark: забор, открытый N маркерами,
# закрывается только N и более маркерами ТОГО ЖЕ вида; более короткая последовательность
# внутри — обычный текст. Хвост после маркеров (info-строка вида ```` ```bash ````) бывает
# только у ОТКРЫВАЮЩЕГО забора — строка с хвостом закрыть не может.
#
# `````*` вместо `{3,}`: три обязательных маркера и звезда на четвёртом. Интервал в awk
# читается не везде (mawk стоит в чистом Debian, где идут прогоны CI), а звезда — везде;
# знание `pattern-shell-portability` — самое нарушаемое в базе, и цена здесь нулевая.
backlog_strip_fenced() {   # со stdin файл → он же, но строки внутри заборов кода пусты
    awk -v fre="$BACKLOG_FENCE_RE" '
        $0 ~ fre {
            match($0, fre); _s = substr($0, RSTART, RLENGTH); sub(/^[ \t]+/, "", _s)
            _mk = substr(_s, 1, 1); _len = length(_s)
            _info = substr($0, RSTART + RLENGTH); gsub(/[ \t]/, "", _info)
            if (!inf) { inf = 1; _open = _mk; _olen = _len }
            else if (_mk == _open && _len >= _olen && _info == "") inf = 0
            print ""; next
        }
        inf      { print ""; next }
                 { print }'
}

# СТРОКА «ПРОВЕРКА» — часть того же контракта, и владелец у неё тот же. До 6 сентября
# 2026 её извлекали ДВЕ копии выражения — `hooks/completion-gate.sh` и
# `scripts/backlog-archive.sh`, — а здесь его не было вовсе: владельцем объявили признак
# ПУНКТА и не назначили владельца строке показания (D305). Копии уже расходились: 1
# сентября 2026 архиватор предъявил командой строку из абзаца «Дефект», потому что якорь
# на начало строки стоял не у обоих.
# Якорь `^` обязателен: то же сочетание в СЕРЕДИНЕ предложения — цитата контракта (такие
# в файле законны), и командой она не является.
BACKLOG_CHECK_RE='^[ \t]*\*\*Проверка\.\*\*[ \t]*`([^`]+)`'

# МЕТКА «судит по форме» — тот же контракт, тот же владелец. Ставит её заводящий пункт,
# когда «Проверка» зеленеет от ИМЕНИ файла или СЛОВА в тексте, а не от результата прибора:
# появился файл с таким именем — команда дала 0, хотя работы не было. Первый проход зелёных
# сторон 13 сентября 2026 дал 6 таких из 11.
# Признак судит ОБЪЯВЛЕНИЕ, а не команду: отличить слепую команду от зрячей автоматом нельзя
# (grep по слову в ЖУРНАЛЕ исходов судит результат, такой же grep по тексту скрипта — форму).
# Читателей двое — архиватор (не переносит закрытый пункт с меткой) и гейт закрытия (называет
# в той же сессии), — потому выражение здесь, а не по копии у каждого (D305).
#
# ЛИТЕРАЛ КАНОНИЧЕН, И ЭТО ВЫВЕДЕНО ПРОЖАРКОЙ ТОГО ЖЕ ДНЯ, А НЕ ВЫБРАНО. Первая редакция
# требовала маркер `**Зелёная сторона.**` и слова «судит по форме» на ОДНОЙ физической
# строке. Два подтверждённых обхода: (1) перенос строки — в самом BACKLOG.md 39 контрактных
# полей свёрнуты по ширине, и метка, уехавшая на вторую строку, снимала ОБА рубежа молча
# (воспроизведено на копии живого файла, пункт D342); (2) отрицание — фраза «больше не судит
# по форме», то есть свидетельство СНЯТИЯ метки, читалась как метка. Плюс вёрстка: под-буллет
# и NBSP-отступ не пускал якорь `^[ \t]*`.
# Поэтому ловится канонический литерал «Метка: судит по форме» ГДЕ УГОДНО в теле пункта, и
# вход у обоих читателей — текст со снятыми заборами кода: образец разметки внутри ``` меткой
# не является. Цена решения названа: цитата этого литерала в прозе пункта сработает как метка
# — но это сознательная запись, а не вёрстка, и снимается она правкой одной фразы.
BACKLOG_FORM_PROXY_RE='Метка:[ \t]*судит по форме'

# ОГРАДА КОЛЬЦА — ПО ПУНКТУ, А НЕ БУЛЕВЫМ МАРКЕРОМ (1 октября 2026, D503). Команды бэклога
# исполняют шестеро: архиватор, completion-gate, страж возврата, пересчёт показаний, страж
# записи открытого пункта и свидетель зелёной стороны. Дверь `BACKLOG_CHECKS_NESTED` стоит у
# двоих, а снимают её свидетели, задающие свою рамку (D334, D461): кольцо «архиватор →
# «Проверка» D499 → свидетель → архиватор» прошло мимо неё (D502, 298 процессов).
# Кольцо — исполнение команды ВНУТРИ ЕЁ ЖЕ исполнения, поэтому ключ — сама команда пункта
# («текст команды#ID#вид»), а не место бэклога: копия бэклога, ссылка на него и путь в другом
# регистре несут ту же команду, и кольцо через них — то же кольцо (противник D503, атаки 8, 9).
# «Проверка» D499 законно зовёт свидетеля, исполняющего ДРУГИЕ пункты, — у них другие ключи.
# Вид (check — «Проверка», return — условие возврата, reading — «Показание») в ключе потому, что
# это разные команды одного пункта: кольцо из двух видов ловится на втором входе того же вида.
# ПРЕДЕЛ ГЛУБИНЫ — ПО ФАЙЛУ (BACKLOG_CMD_DEPTH_MAX, 2). Исключение по ключу ограничивает глубину
# лишь числом команд, и дерево вызовов растёт как n!: 4 пункта, чьи «Проверки» зовут исполнителя,
# дали 64 исполнения (атака 6). Ветвится оно по командам ОДНОГО бэклога, поэтому записей того же
# файла выше по дереву не больше предела — тогда не больше n². Общий на все файлы предел ломал
# законные цепочки: «Проверка» ☑ → свидетель → «Проверка» открытого → проба → исполнитель на
# своей фикстуре — три уровня, и вложенный пропуск поднимался наверх ложным вердиктом (раунд 2,
# атака 1); свидетели на фикстурах наследовали чужую глубину (атака 2). Метка файла —
# «устройство:inode» (`stat -L`): её не меняют ни ссылка, ни регистр пути; копия — другой файл,
# и ветвление через копии предел не держит (назван, носителей нет), а кольцо — держит ключ.
# Запись BACKLOG_CMD_RUNNING — «метка файла \036 ключ», записи разделены \037; рамки свидетелей
# её не касаются. Текст команды в ключе СЫРОЙ — ровно байты между обратными кавычками: у правила было две
# реализации (оболочка и питон), и обрезка краёв расходилась у них по локали и по юникоду (раунд 3,
# атака 1); сырой текст у всех разборщиков один. Питоновские исполнители своей копии правила не держат
# (D1238): `hooks/lib/backlog_cmd.py` спрашивает `backlog_cmd_blocked`/`backlog_cmd_env` этой библиотеки.
BACKLOG_CMD_SEP=$'\037'
BACKLOG_CMD_FSEP=$'\036'
# Предел приводится ЧИСЛОМ (раунд 3, атака 2): «00» проходил сверку текстом, а `[ n -ge 00 ]`
# отбивал всё на нулевой глубине. Не число — 2; ведущие нули снимаются; больше трёх знаков — 100.
case "${BACKLOG_CMD_DEPTH_MAX:-}" in ''|*[!0-9]*) BACKLOG_CMD_DEPTH_MAX=2 ;; ????*) BACKLOG_CMD_DEPTH_MAX=100 ;; esac
BACKLOG_CMD_DEPTH_MAX=$((10#$BACKLOG_CMD_DEPTH_MAX)); [ "$BACKLOG_CMD_DEPTH_MAX" -ge 1 ] || BACKLOG_CMD_DEPTH_MAX=2
backlog_cmd_key() {  # <вид> <ID> <команда> → ключ «команда#ID#вид», текст команды сырой
    printf '%s#%s#%s' "$3" "$2" "$1"
}
backlog_open_items_us() {  # <файл> → строки `backlog_open_items` с разделителем \037 для `read`
    # Табуляция ВНУТРИ последнего поля («Проверка») — часть команды, а не разделитель: прежний
    # перевод всех табуляций резал команду, и исполнители одного пункта исполняли разное.
    backlog_open_items "$1" | awk -F'\t' 'BEGIN { OFS = "\037" }
        { o = $1; for (i = 2; i <= 6 && i <= NF; i++) o = o OFS $i
          if (NF > 6) { r = $7; for (i = 8; i <= NF; i++) r = r "\t" $i; o = o OFS r }
          print o }'
}
backlog_cmd_fileid() {  # <файл> → «устройство:inode»; файла нет — «path:<путь>»
    local id
    id=$(stat -L -c '%d:%i' "$1" 2>/dev/null) || id=$(stat -L -f '%d:%i' "$1" 2>/dev/null) || id=""
    printf '%s' "${id:-path:$1}"
}
backlog_cmd_blocked() {  # <файл> <вид> <ID> <команда> → 0 и причина в stdout, если исполнять нельзя
    local k fid e n=0
    k=$(backlog_cmd_key "$2" "$3" "$4"); fid=$(backlog_cmd_fileid "$1")
    while IFS= read -r -d "$BACKLOG_CMD_SEP" e; do
        [ -n "$e" ] || continue
        case "$e" in *"$BACKLOG_CMD_FSEP"*) ;; *) e="${BACKLOG_CMD_FSEP}$e" ;; esac
        if [ "${e#*"$BACKLOG_CMD_FSEP"}" = "$k" ]; then
            printf 'кольцо: команда уже исполняется выше по дереву процессов'; return 0
        fi
        [ "${e%%"$BACKLOG_CMD_FSEP"*}" = "$fid" ] && n=$((n + 1))
    done <<< "${BACKLOG_CMD_RUNNING:-}${BACKLOG_CMD_SEP}"
    if [ "$n" -ge "$BACKLOG_CMD_DEPTH_MAX" ]; then
        printf 'кольцо не исключено: вложенность команд этого бэклога глубже %s (BACKLOG_CMD_DEPTH_MAX)' "$BACKLOG_CMD_DEPTH_MAX"
        return 0
    fi
    return 1
}
backlog_cmd_env() {  # <файл> <вид> <ID> <команда> → значение BACKLOG_CMD_RUNNING для окружения команды
    printf '%s%s%s%s%s' "${BACKLOG_CMD_RUNNING:-}" "$BACKLOG_CMD_SEP" "$(backlog_cmd_fileid "$1")" \
        "$BACKLOG_CMD_FSEP" "$(backlog_cmd_key "$2" "$3" "$4")"
}

# ВОЗРАСТ ПУНКТА — тоже одно правило на двоих. Порог контракта (`BACKLOG_CONTRACT_MIN_ID`,
# `CG_MIN_ID`) действует там, где есть чем доказать возраст: идентификатор вне D-нумерации
# (`X1`, `TASK-003a`, `R1.1`) возраста не сообщает и порогом не отсекается. Оба потребителя
# объявляли это правило «единым», а держали своими шаблонами, и они разошлись: на `D42a`
# архиватор (`re.match(r'D(\d+)')`, префикс) считал пункт историческим, гейт (`D(\d+)$`,
# целиком) — нет. Найдено прожаркой 13 сентября 2026.
# Берётся ПРЕФИКСНАЯ форма — не по рассуждению о цене ошибки, а по закреплённому намерению:
# нога T18f в `hooks/tests/test_backlog_archive.sh` требует, чтобы подномер старого пункта
# (`D101a`) освобождался порогом наравне с `D101`, потому что возраст у него доказан тем же
# числом. Строгая форма эту ногу красит — проверено в тот же час, и это единственное, что
# отличает здесь намерение от домысла. Хвост после числа возраста не отменяет.
BACKLOG_ID_NUM_RE='^D([0-9]+)'

# ПОРЯДКОВАЯ ЧАСТЬ ИДЕНТИФИКАТОРА — предмет ИНОЙ, чем у BACKLOG_ID_NUM_RE выше, потому
# выражение второе, а не то же. Там судится возраст ПРОТИВ ПОРОГА («старше ли D413»), и для
# этого не-D идентификатор непригоден по праву: у него своя нумерация, с D-порогом
# несравнимая, — так и записано абзацем выше. Здесь судится ОТНОСИТЕЛЬНЫЙ ПОРЯДОК ВНУТРИ
# ОДНОГО ФАЙЛА («кто из этих заведён раньше»), и в этом предмете `B1` против `B30` сравнимы
# прекрасно, а `B1` против `D307` из другого файла — нет, потому что шкалы независимы.
# Потребитель обязан сравнивать ТОЛЬКО внутри файла: очередь залежавшегося долга
# (`completion-gate.sh`, блок «Залежавшийся ☐»).
# Повод (18 сентября 2026, прожарка D461). Первая редакция очереди брала BACKLOG_ID_NUM_RE и
# получила два дефекта разом: при 22 открытых пунктах `B1`..`B30` в живом проекте владельца
# она МОЛЧАЛА (не-D не подставлялся, grep выбрасывал), а два файла сравнивала одной шкалой —
# чужой `D1` оказывался «самым старым» и глушил долг ClaudSoul на всю сессию.
# НАЗВАННЫЙ ПРЕДЕЛ: идентификатор вовсе без числовой части («TODO», «FIXME») выражением не
# разбирается; потребитель падает на порядок появления в файле и обязан это назвать.
# Условие снятия: появится идентификатор без числа, у которого возраст доказуем иначе.
BACKLOG_ID_SEQ_RE='^[A-Za-z]+-?([0-9]+)'

# backlog_stable_copy <файл> — путь, по которому читать: 0 — временная копия, прочитанная ЦЕЛИКОМ (удаляет вызывающий);
# 3 — копию сделать нельзя (нет TMPDIR, копия не пишется, файл не читается): печатается сам файл, читать его как до
# D1065 и НЕ удалять — отказ копии не «файл пишут» (скептик D1065: ложный «не устоялся» за 1,3 с и молчаливый код 2
# при отсутствующем TMPDIR, D1100); 2 — файл не устоялся, его пишут прямо сейчас (D1065).
# Писатели кладут бэклог усечением и записью (`write_text`, `cat >`), и читатель посреди записи видел пустой либо
# обрезанный файл — «открытых 0» тем же значением, что и пустой бэклог (корень R6; замер на копии: 53 неверных чтения
# из 479 при записи раз в 20 мс). Замена файла переименованием откатана: ограда кольца ключует бэклог по inode
# (`backlog_cmd_fileid`). Поэтому цельность судит читатель: второе чтение совпало с первым — копия цельная, иначе
# повтор. Оба чтения внутри окна усечения — микросекунды против миллисекунд между ними — не наблюдались (0 из 397).
# Копия — файл, а не переменная: захват архива (3,4 МБ) в переменную оболочки утроил время чтения.
# Пустая копия бывает и у пустого файла, и в окне усечения: на архиве запись длится дольше пары чтений, и обе пустые
# копии совпадали (скептик D1065, F5). Пустую принимаем, только если файл пуст и после паузы.
backlog_stable_copy() {
    _sc_t=$(mktemp "${TMPDIR:-/tmp}/backlog-read.XXXXXX" 2>/dev/null) || { printf '%s' "$1"; return 3; }
    _sc_n=0
    while [ "$_sc_n" -lt 20 ]; do
        cat -- "$1" > "$_sc_t" 2>/dev/null || { rm -f "$_sc_t"; printf '%s' "$1"; return 3; }
        if cat -- "$1" 2>/dev/null | cmp -s - "$_sc_t"; then
            [ -s "$_sc_t" ] && { printf '%s' "$_sc_t"; return 0; }
            sleep 0.05
            [ -s "$1" ] || { printf '%s' "$_sc_t"; return 0; }
        fi
        _sc_n=$((_sc_n + 1)); sleep 0.05
    done
    rm -f "$_sc_t"
    printf 'backlog-lib: %s не устоялся за %s пар чтений — его пишут прямо сейчас\n' "$1" "$_sc_n" >&2
    return 2
}

# backlog_read <файл> — содержимое файла, прочитанное ЦЕЛИКОМ, в stdout (D1101); 2 — файл не устоялся; 3 — файла нет или он
# не читается (D1121). Для читателей
# вне функций библиотеки: они читали файл сами и посреди записи с усечением видели пустой или обрезанный бэклог.
# Вызывающий пишет `{ backlog_read f 2>/dev/null || cat -- f 2>/dev/null; }`: со старой библиотекой без этой функции
# (установленный хук новее установленной библиотеки) — прежнее чтение, а не пустота. Ранний выход читателя (`grep -q`,
# `awk … exit`) убивает только `cat`, копия удаляется следующей строкой.
backlog_read() {
    _br_t=$(backlog_stable_copy "$1"); _br_s=$?
    [ "$_br_s" = 2 ] && return 2
    # Файла нет или его нельзя прочитать — код 3 и пусто (D1121, род B): прежде `cat` падал молча, функция отвечала 0,
    # и у потребителей «не прочитан» и «пуст» было одним значением. Решается ДО чтения, а не кодом `cat`: ранний выход
    # читателя под pipefail тоже роняет `cat` (141), и это не «не прочитан».
    [ "$_br_s" = 3 ] && [ ! -r "$1" ] && return 3
    cat -- "$_br_t"
    if [ "$_br_s" = 0 ]; then rm -f "$_br_t"; fi
    return 0
}

backlog_ids() {
    _f="$1"; _m="${2:-${BACKLOG_DONE_MARKS}${BACKLOG_OPEN_MARKS}}"
    [ -f "$_f" ] || return 0
    _bt=$(backlog_stable_copy "$_f"); _bs=$?
    [ "$_bs" = 2 ] && return 2
    backlog_strip_fenced < "$_bt" \
        | grep -E "$(backlog_item_re "$_m")" 2>/dev/null \
        | backlog_status_is "$_m" | backlog_id_stream | sort -u
    if [ "$_bs" = 0 ]; then rm -f "$_bt"; fi
}

# backlog_revert_ids <файл> — открытые (☐/◐) пункты, чей заголовок называет откат закрытого: строки «<закрытый>\t<пункт>».
# Правило одно для всех потребителей (D1295, 15 ноября 2026, корень R1): прежде оно жило строчным литералом «откат D<N>» у
# двоих — `probe_D1196.sh` и `scripts/behavior-condition-probe.sh`, — и заголовок, НАЧИНАЮЩИЙСЯ с этого слова
# («Откат D474: …», D1295), не видел ни один: проба D1196 краснела на названном откате, прибор звал её «рамка не собралась».
# Первая буква — альтернацией литералов, а не классом: классы с кириллицей GNU grep в C.UTF-8 отвергает.
backlog_revert_ids() {
    _f="$1"
    [ -f "$_f" ] || return 0
    _bt=$(backlog_stable_copy "$_f"); _bs=$?
    [ "$_bs" = 2 ] && return 2
    backlog_strip_fenced < "$_bt" \
        | grep -E "$(backlog_item_re "$BACKLOG_OPEN_MARKS")" 2>/dev/null \
        | backlog_status_is "$BACKLOG_OPEN_MARKS" \
        | awk -v tok="$BACKLOG_ID_TOKEN_RE" '{ _s = $0; gsub(/\*/, "", _s)
              if (!match(_s, tok)) next
              _id = substr(_s, RSTART, RLENGTH); _s = substr(_s, RSTART + RLENGTH)
              while (match(_s, /(откат|Откат) D[0-9]+/)) {
                  _r = substr(_s, RSTART, RLENGTH); sub(/^.* /, "", _r)
                  print _r "\t" _id; _s = substr(_s, RSTART + RLENGTH) } }'
    if [ "$_bs" = 0 ]; then rm -f "$_bt"; fi
}

# backlog_status_is <метки> — со stdin строки пунктов, наружу те, чья СТАТУСНАЯ метка
# (первая в строке) входит в набор. Списочную вёрстку признак уже отбирает позицией, а
# заголовочную — нет: `### D42 ☑ … (было ◐)` попадает и в запрос открытых. В корпусе
# таких нет (0 из 73 заголовков несут вторую метку), но это свойство данных, а не
# признака, — потому отбор по статусу стоит отдельным ситом.
# Метка достаётся `match` по АЛЬТЕРНАЦИИ литералов, а не посимвольным обходом строки:
# `substr($0,i,1)` в awk без UTF-8 (BSD awk на macOS с пустой локалью, mawk в чистом
# Debian) отдаёт БАЙТ, и сравнение с трёхбайтовой меткой не совпадает никогда — сито
# молча выбрасывало всё. Поймано первым же прогоном атаки: `backlog_ids` вернул пусто.
backlog_status_is() {
    awk -v want="$1" '
        match($0, /☐|◐|☑|⊘/) && index(want, substr($0, RSTART, RLENGTH)) > 0'
}

# backlog_is_item <строка> — 0, если строка есть пункт долга.
backlog_is_item() {
    grep -qE "$(backlog_item_re)" <<< "$1"
}

# backlog_mark_of <строка> — метка пункта либо пусто.
backlog_mark_of() {
    backlog_is_item "$1" || return 1
    printf '%s' "$1" | grep -oE "$(backlog_marks_alt "${BACKLOG_DONE_MARKS}${BACKLOG_OPEN_MARKS}")" | head -1
}

# backlog_snapshot <state> <sid> <файл> — снимок меток пунктов на СТАРТЕ сессии; печатает
# путь снимка. Код: 0 — снимок уже был, 3 — создан этим вызовом, 1 — файла нет/ошибка.
# Строки снимка: `ID метка` по каждому пункту всех четырёх меток. Пишется ОДИН РАЗ
# (write-if-absent): второй вызов в той же сессии — от `compact`/`resume` или от ленивого
# фолбэка гейта — снимок не перетирает, иначе «заведён в этой сессии» стёрлось бы вместе с
# ним. Единственный владелец схемы имени и формата: читатель — `hooks/completion-gate.sh`
# (свежий ☐ без взятого в сессии ◐), писатель — `hooks/session-start.sh`; две копии схемы
# разошлись бы молча (D305).
# Имя без `-fired-`: файлы `*-fired-*` throttle-lib подрезает по TTL, а снимок обязан
# жить всю сессию. Ключ пути — cksum от `pwd -P` каталога: `/var` и `/private/var` на macOS
# должны давать один снимок (идиома carrier-growth-check.sh:63). Запись атомарна через
# временный файл (род H — правка общего состояния из двух хуков).
backlog_snapshot() {
    _f="${3:-}"
    [ -n "$_f" ] && [ -f "$_f" ] || return 1
    _d=$(cd "$(dirname "$_f")" 2>/dev/null && pwd -P) || return 1
    _k=$(printf '%s/%s' "$_d" "$(basename "$_f")" | cksum | awk '{print $1}')
    _s="$1/backlog-snapshot-$2-$_k.txt"
    if [ -f "$_s" ]; then printf '%s' "$_s"; return 0; fi
    mkdir -p "$1" 2>/dev/null || return 1
    # `|| true` на каждом конвейере — не косметика: под `pipefail` (гейт и тесты идут с ним)
    # метка без единого пункта (⊘ почти всегда) даёт `grep` код 1, группа считается упавшей,
    # `mv` не исполняется, и функция отвечала 1 — «снимка нет» при исправном файле. В чистой
    # оболочке без pipefail то же место работало, оттого дефект и не был виден до прогона.
    {
        for _mk in "$BACKLOG_MARK_TODO" "$BACKLOG_MARK_WIP" "$BACKLOG_MARK_DONE" "$BACKLOG_MARK_WAIVED"; do
            backlog_ids "$_f" "$_mk" | awk -v m="$_mk" 'NF { print $1, m }' || true
        done
    } > "$_s.tmp.$$" 2>/dev/null && mv "$_s.tmp.$$" "$_s" 2>/dev/null || { rm -f "$_s.tmp.$$" 2>/dev/null; return 1; }
    printf '%s' "$_s"; return 3
}

# КОРЕНЬ ПУНКТА — первое слово после `**Корень.**` в начале строки (после отступа). «не дефект» — двумя словами: это
# единственная форма, где первое «не» значит «не дефект»; «не заведён», «не разобран» — отсутствие корня (финальный
# скептик D1019: 7 таких в ProjectA). Одна функция awk на двух читателей — `backlog_open_items` (поле 5) и
# `backlog_root_of` (сверка исхода стража разбора, D1106): вторая копия правила разошлась бы молча (D305).
BACKLOG_ROOT_AWK='
function backlog_root_word(l,   rest, n, w, r) {
    if (!match(l, /^[[:space:]]*[*][*]Корень\.[*][*]/)) return ""
    rest = substr(l, RSTART + RLENGTH); sub(/^[[:space:]]+/, "", rest)
    n = split(rest, w, /[[:space:]]+/); r = (n > 0 ? w[1] : "")
    if (r == "не" && n > 1 && w[2] ~ /^дефект/) r = "не дефект"
    return r
}'

# backlog_root_of — со stdin блок пункта → его корень по правилу выше (пусто — строки корня нет).
backlog_root_of() {
    awk '{ r = backlog_root_word($0); if (r != "") { print r; exit } }'"$BACKLOG_ROOT_AWK"
}

# backlog_item_block <файл> <ID> — блок пункта с этим идентификатором, ЛЮБОЙ метки: первая строка «<начало>\t<конец>»
# (номера строк файла), дальше строки блока. 1 — пункта нет, 2 — файл не устоялся. Границы — те же, что у
# `backlog_open_items`: голова пункта открывает, следующая голова либо заголовок уровня ≤ L закрывает, забор кода снят
# потоком с сохранением нумерации; идентификатор головы — по `BACKLOG_ID_TOKEN_RE`, как у `backlog_id_stream`.
# Читатель — сверка исхода стража разбора (D1106): исход `fixed` ссылается на закрытый пункт, `backlog_open_items`
# закрытых не отдаёт.
backlog_item_block() {
    _ib_f="$1"; _ib_id="$2"
    [ -f "$_ib_f" ] && [ -n "$_ib_id" ] || return 1
    _ib_t=$(backlog_stable_copy "$_ib_f"); _ib_s=$?
    [ "$_ib_s" = 2 ] && return 2
    _ib_o=$(backlog_strip_fenced < "$_ib_t" | awk -v ire="$(backlog_item_re)" -v tok="$BACKLOG_ID_TOKEN_RE" -v want="$_ib_id" '
        function idof(s) { gsub(/\*/, "", s); return (match(s, tok) ? substr(s, RSTART, RLENGTH) : "") }
        $0 ~ ire { if (on) exit
                   if (idof($0) == want) { on = 1; st = NR; last = NR; buf = $0; lvl = (match($0, /^#+/) ? RLENGTH : 0) }
                   next }
        on && /^#+[[:space:]]/ { match($0, /^#+/); if (lvl == 0 || RLENGTH <= lvl) exit }
        on { buf = buf "\n" $0; last = NR }
        END { if (on) printf "%d\t%d\n%s\n", st, last, buf }')
    if [ "$_ib_s" = 0 ]; then rm -f "$_ib_t"; fi
    [ -n "$_ib_o" ] || return 1
    printf '%s\n' "$_ib_o"
}

# backlog_names_guard_layer <корень бэклога> — со stdin блок пункта; 0 — блок называет защитный слой ЭТОГО репозитория
# (первые два условия `backlog_needs_skeptic` ниже, доводы там). Вынесено 28 октября 2026 (D1158): второй читатель —
# `hooks/guarantee-map-guard.sh` (карта гарантий у пункта ◐ защитного слоя); копия признака разошлась бы молча (род K).
backlog_names_guard_layer() {
    _gl_b=$(cat)
    [ -n "${1:-}" ] && [ -d "$1/hooks" ] || return 1
    _gl_p=$(grep -oE '(^|[^/[:alnum:]_.~-])hooks/[[:alnum:]_.*-]+' <<< "$_gl_b")
    [ -n "$_gl_p" ] && grep -qvE 'hooks/tests$' <<< "$_gl_p" && return 0
    for _gl_n in $(grep -oE '([[:alnum:]_.~-]*/)*[[:alnum:]_.-]+\.(sh|py)' <<< "$_gl_b" | sort -u); do
        _gl_f=${_gl_n##*/}
        case "$_gl_n" in */*) case "/$_gl_n" in */hooks/"$_gl_f"|*/hooks/lib/"$_gl_f") ;; *) continue ;; esac ;; esac
        if [ -f "$1/hooks/$_gl_f" ] || [ -f "$1/hooks/lib/$_gl_f" ]; then return 0; fi
    done
    return 1
}

