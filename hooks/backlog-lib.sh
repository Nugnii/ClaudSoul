            printf '🧩 Договор инициации: BACKLOG.md проекта %s не называет исполнителя архивирования, а дописать не вышло — допиши под заголовок цитату-шапку из ~/.claude/templates/BACKLOG.md.tmpl (строки с `backlog-archive.sh`) и СКАЖИ собеседнику.\n' "$_root"
        fi
    fi
    return 0
}

# Шапка — строка с исполнителем архивирования; чтение цельной копией (`backlog_read`), как у всех читателей бэклога.
_backlog_ct_has_header() { grep -q 'backlog-archive\.sh' <<< "$(backlog_read "$1" 2>/dev/null || cat -- "$1" 2>/dev/null)"; }

_backlog_ct_insert() {   # <бэклог> <шапка> → 0 дописано; 2 — шапка уже есть; 1 — замок не взят, файл изменился или запись не удалась
    local _bl="$1" _q="$2" _s0 _tmp="$1.ct.$$" _rc=1
    lock_acquire "$_bl" || return 1
    # «Шапки нет» перепроверяется ПОД замком (D1308, корень R6): решение, принятое чтением вне замка, отвечало и на «нет
    # и сейчас», и на «нет до чужой вставки» — второй вызов, дождавшийся замка, вставлял шапку ещё раз (20 пар из 20).
    if _backlog_ct_has_header "$_bl"; then lock_release "$_bl"; return 2; fi
    _s0=$(cksum < "$_bl" 2>/dev/null)
    if { if grep -q '^# ' "$_bl"; then
             CT_Q="$_q" awk '!d && /^# / {print; print ""; print ENVIRON["CT_Q"]; d = 1; next} {print}' "$_bl"
         else printf '%s\n\n' "$_q"; cat "$_bl"; fi
       } > "$_tmp" 2>/dev/null && [ "$(cksum < "$_bl" 2>/dev/null)" = "$_s0" ] && cat "$_tmp" > "$_bl" 2>/dev/null
    then _rc=0; fi
    rm -f "$_tmp" 2>/dev/null
    lock_release "$_bl"
    return "$_rc"
}
