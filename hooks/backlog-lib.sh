        case "$_ns_l" in [Oo][Pp][Uu][Ss]|[Oo][Pp][Uu][Ss][!A-Za-z_]*) return 1 ;; esac
    done <<< "$_ns_s"
    return 0
}

# backlog_open_items <файл> — по строке на каждый ОТКРЫТЫЙ пункт, поля через табуляцию:
#   id  метка  вид  очередь  корень  команда  проверка
# Седьмое поле (13 сентября 2026, D264) — команда строки «**Проверка.**» (пусто — строки нет);
# читатель — страж записи `backlog-open-write-guard.sh`, ему нужен тот же разбор блоков, что и
# стражу возврата, и третий парсер пунктов был бы копией этого.
# вид: `cmd` — условие возврата задано командой (пункт-ОЖИДАНИЕ: его закрывает событие
# мира, команда даёт 0, когда оно наступило); `decision` — слово «решение» (пункт-РАБОТА);
# `none` — строки «Проверка возврата» нет. Очередь — сырой хвост строки `**Очередь.**`
# («?», если строка есть, а значения нет — чтобы контракт формы это ловил; пусто — строки
# нет). Корень — первое слово после `**Корень.**` (R<N>, «нет», …), а у «не дефект — …» — оба слова,
# «не дефект»: первое слово «не» само по себе корнем не является («не заведён» — корня нет).
#
# ЕДИНСТВЕННЫЙ ВЛАДЕЛЕЦ разбора пункта на поля (12 сентября 2026). До этого awk жил в
# `scripts/backlog-return-check.sh`, а коллектору на Stop понадобился тот же разбор ради
# счёта «в работе / ждут условия» и «следующий к взятию» — вторая копия разошлась бы
# молча (D305). Устройство перенесено целиком, довод к каждой границе — в комментарии
# стража возврата (там же атаки прожарки 3 сентября 2026, которыми оно доказано):
#   · пункты разбираются БЛОКАМИ, роль строки — по положению в блоке, не по виду;
#   · у блока три границы: строка пункта открывает, заголовок-сосед закрывает (по уровню:
#     у пункта-заголовка уровня L закрывают заголовки ≤ L), забор кода снят ПОТОКОМ до awk;
#   · статус — ПЕРВОЙ меткой строки (сито `backlog_status_is`, здесь то же правило на тех
#     же константах, потому что awk обходит файл целиком);
#   · контрактные строки — якорем на начало строки после отступа, иначе цитата контракта в
#     прозе пункта читалась бы как контракт; слово «решение» — ПОСЛЕ литерала;
#   · табуляция в заголовке обезвреживается до печати — она разрывала бы канал.
# Идентификатор — `backlog_id_stream` от головы блока, запасной — первые 40 знаков головы.
backlog_open_items() {
    _f="$1"
    [ -f "$_f" ] || return 0
    _ire=$(backlog_item_re)
    _mre=$(backlog_marks_alt "${BACKLOG_DONE_MARKS}${BACKLOG_OPEN_MARKS}")
    _bt=$(backlog_stable_copy "$_f"); _bs=$?
    [ "$_bs" = 2 ] && return 2
    backlog_strip_fenced < "$_bt" | awk -v ire="$_ire" -v mre="$_mre" -v om="$BACKLOG_OPEN_MARKS" '
        # ВНУТРЕННИЙ разделитель — \037 (unit separator), не табуляция: для `read` табуляция
        # есть пробельный разделитель, и подряд идущие ПУСТЫЕ поля (очередь, корень, команда
        # у большинства пунктов) схлопываются в один — заголовок уезжал в чужую переменную,
        # `_h` пустел, и функция отдавала ноль строк на 43 открытых (первый прогон T5h,
        # 12 сентября 2026). Наружу — по-прежнему TSV: awk с -F"\t" пустые поля хранит.
        function emit(   h) {
            if (open) { h = head; gsub("\t", " ", h); gsub("\037", " ", h)
                        printf "%s\037%s\037%s\037%s\037%s\037%s\037%s\n", kind, mark, q, root, cmd, chk, h }
        }
        $0 ~ ire {
            emit()
            open = (match($0, mre) && index(om, substr($0, RSTART, RLENGTH)) > 0)
            mark = (open ? substr($0, RSTART, RLENGTH) : "")
            head = $0; kind = "none"; cmd = ""; q = ""; root = ""; seen = 0; chk = ""
            lvl = (match($0, /^#+/) ? RLENGTH : 0)
            next
        }
        /^#+[[:space:]]/ {
            match($0, /^#+/)
            if (lvl == 0 || RLENGTH <= lvl) { emit(); open = 0; head = ""; kind = "none"; cmd = ""; chk = "" }
            next
        }
        open && !seen && match($0, /^[[:space:]]*[*][*]Проверка возврата:[*][*]/) {
            seen = 1
            rest = substr($0, RSTART + RLENGTH)
            if (match(rest, /^[[:space:]]*решение/)) kind = "decision"
            else if (match(rest, /`[^`]+`/)) { kind = "cmd"; cmd = substr(rest, RSTART + 1, RLENGTH - 2) }
        }
        open && chk == "" && match($0, /^[[:space:]]*[*][*]Проверка\.[*][*][[:space:]]*`[^`]+`/) {
            s = substr($0, RSTART, RLENGTH); sub(/^[^`]*`/, "", s); sub(/`$/, "", s); chk = s
        }
        open && q == "" && match($0, /^[[:space:]]*[*][*]Очередь\.[*][*]/) {
            rest = substr($0, RSTART + RLENGTH)
            sub(/^[[:space:]]+/, "", rest); sub(/[[:space:]]+$/, "", rest)
            q = (rest == "" ? "?" : rest)
        }
        open && root == "" { root = backlog_root_word($0) }
        END { emit() }'"$BACKLOG_ROOT_AWK" \
    | while IFS="$(printf '\037')" read -r _k _mk _q _r _c _chk _h; do
        [ -n "$_h" ] || continue
        _id=$(printf '%s\n' "$_h" | backlog_id_stream)
        [ -n "$_id" ] || _id=$(printf '%s' "$_h" | cut -c1-40)
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$_id" "$_mk" "$_k" "$_q" "$_r" "$_c" "$_chk"
    done
    if [ "$_bs" = 0 ]; then rm -f "$_bt"; fi
}

# backlog_contract_parts_ensure <каталог> — ДОГОВОР ИНИЦИАЦИИ ДОЕЗЖАЕТ ДО УЖЕ ИНИЦИИРОВАННЫХ ПРОЕКТОВ (D1016, D1301).
# Печатает строки сигналов (по одной на событие, с путём проекта — слово со Stop читает сессия, не обязательно та) и заводит в проекте каталога, если он инициирован (корень с SESSION.md),
