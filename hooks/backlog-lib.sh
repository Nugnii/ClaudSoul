#!/usr/bin/env bash
# backlog-lib.sh — ЕДИНСТВЕННОЕ определение того, что такое пункт долга.
#
# Результат: все читатели BACKLOG.md опознают пункт одинаково, независимо от его вёрстки
# Проверка результата: bash hooks/tests/test_backlog_item_shape.sh даёт 0
#
# Зачем. 28 августа 2026 пункты долга сменили вёрстку со списка (`- ☑ **D42**`) на
# заголовок (`### D42 ☑ …`). Три стража перестали видеть их в тот же день и молчали сутки:
#
#   · `scripts/backlog-archive.sh`     — «переносить нечего» при двух ☑ в файле;
#   · `scripts/backlog-return-check.sh` — ноль открытых пунктов, условия возврата не проверялись;
#   · `hooks/backlog-vanish-check.sh`  — ноль идентификаторов, пропажа пункта невидима.
#
# У каждого признак был снят с ТОГДАШНЕГО состава файла (`^- ` + метка), а не выражен
# правилом о предмете. Пока состав совпадал, признак работал; сменился — отказал молча.
# Комментарий в `backlog-vanish-check.sh:51` к тому моменту уже упоминал заголовки — знание
# о второй форме в проекте было, до признака не дошло.
#
# Отдельно про то, почему сутки. Проверка результата архиватора звучала как
# `grep -c '^- ☑' BACKLOG.md даёт 0` — то есть искала ту же форму, что и сам инструмент, и
# была зелёной ровно тогда, когда он слеп. Проверка, выраженная через реализацию,
# наследует её слепое пятно и не может обнаружить её отказ; поэтому здесь она выражена
# через СОСТОЯНИЕ: «выполненных пунктов в файле нет», а форму знает эта библиотека.
#
# ПРАВИЛО. Пункт долга — строка, которая НАЧИНАЕТСЯ с маркера списка либо заголовка и
# несёт метку статуса из легенды BACKLOG.md (☐ ◐ ☑ ⊘). Идентификатор не требуется: он
# бывает `D42`, а бывает `X1` — архиватор уносит выполненное независимо от нумерации.
#
# КОНТРПРИМЕР: строка легенды («**Легенда статусов:** ☐ todo · ◐ in-progress …») несёт все
# четыре метки и пунктом НЕ является — она начинается с жирного текста, а не с маркера.
# Проза «верни пункту ☐ в BACKLOG.md» — по той же причине. Отсекает их ПРЕФИКС, а не
# наличие номера: первая редакция правила требовала `D<число>` и выбросила фикстуры
# архиватора с идентификаторами `X1`/`Y1` — сузила предмет по одному потребителю.

# Метки, означающие «сделано» и «не сделано» (легенда BACKLOG.md).
BACKLOG_DONE_MARKS='☑⊘'
BACKLOG_OPEN_MARKS='☐◐'

# backlog_item_re [метки] — регулярное выражение строки пункта.
# Обе вёрстки в одном выражении: префикс либо `- `, либо `#{2,4} `.
# МЕТКИ — АЛЬТЕРНАТИВОЙ ЛИТЕРАЛОВ, А НЕ КЛАССОМ. Класс `[☐◐]` в mawk (он стоит в чистом
# Debian) и в grep под локалью C читается по БАЙТАМ: ☑ (E2 98 91) делит первый байт с ☐
# (E2 98 90), и закрытый пункт проходит за открытый. Поймано CI 30 августа 2026
# (test_backlog_touch_check T3), на macOS невидимо — awk и grep там знают UTF-8.
backlog_marks_alt() {   # <метки> → «☐|◐» из известных меток, по подстроке, без разбора байтов
    _alt=""
    for _mk in ☐ ◐ ☑ ⊘; do
        case "$1" in *"$_mk"*) _alt="${_alt}${_alt:+|}${_mk}" ;; esac
    done
    printf '%s' "${_alt:-☐|◐|☑|⊘}"
}

backlog_item_re() {
    _m="${1:-${BACKLOG_DONE_MARKS}${BACKLOG_OPEN_MARKS}}"
    # `.` в grep -E перевод строки и так не покрывает — отдельный `[^\n]` не нужен, а
    # `printf` истолковал бы `\n` как настоящий перевод и разрушил бы выражение. Ловушка
    # поймана тестами стража в тот же час: вывод хука стал пустым.
    # Порядок метки и номера РАЗНЫЙ в двух вёрстках: в списке метка первая
    # (`- ☑ **D12**`), в заголовке — вторая (`### D109 ☑ …`). Правило требует наличия
    # обоих, а не их порядка: первая редакция этого выражения задала порядок по списочной
    # форме и промахнулась по заголовкам — тот же дефект, что чинится.
    printf '^(- |#{2,6} )[^|]*(%s)' "$(backlog_marks_alt "$_m")"
}

# backlog_ids <файл> [метки] — идентификаторы пунктов с указанными метками, по одному в строку.
backlog_ids() {
    _f="$1"; _m="${2:-${BACKLOG_DONE_MARKS}${BACKLOG_OPEN_MARKS}}"
    [ -f "$_f" ] || return 0
    grep -E "$(backlog_item_re "$_m")" "$_f" 2>/dev/null \
        | grep -oE 'D[0-9]+' | sort -u
}

# backlog_is_item <строка> — 0, если строка есть пункт долга.
backlog_is_item() {
    grep -qE "$(backlog_item_re)" <<< "$1"
}

# backlog_mark_of <строка> — метка пункта либо пусто.
backlog_mark_of() {
    backlog_is_item "$1" || return 1
    printf '%s' "$1" | grep -oE "$(backlog_marks_alt "${BACKLOG_DONE_MARKS}${BACKLOG_OPEN_MARKS}")" | head -1
}
