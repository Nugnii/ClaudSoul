#    наличие — урок D1020); промежуточная строка перед финальной закрытию не мешает (круг 2, L3).
# ЕДИНСТВЕННЫЙ ВЛАДЕЛЕЦ признака: страж записи (`backlog-open-write-guard.sh`) отбивает такое ☑, completion-gate называет
