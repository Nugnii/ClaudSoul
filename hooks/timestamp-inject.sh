#!/usr/bin/env bash
# timestamp-inject.sh — UserPromptSubmit: инжект текущего времени собеседника; шапку несёт ИТОГОВОЕ сообщение хода, промежуточные блоки её не несут.
# en: injects the user's current local time each prompt; the FINAL message of the turn must start with it, interim blocks must not carry it — a cheap context-drift canary.
#
# Зачем. Правило «итоговое сообщение хода начинается с таймштампа»
# (rules/CLAUDE.md, решение собеседника 2026-08-08) требует источник времени: у модели
# нет часов, время из головы — выдумка (в день введения правила записи подписывались
# «поздняя ночь» при реальных 16:45). Инжект делает таймштамп механическим:
# агент эхоит, не сочиняет. Канарейка: инжект есть, а ход начат без
# таймштампа → инструкции размылись, сессию пора перезапускать.
#
# ЕДИНИЦА НАЗВАНА В САМОМ ИНЖЕКТЕ, И ЭТО ПОЧИНКА (12 сентября 2026). Текст говорил
# «начни ответ этим таймштампом», а правило ниже по файлу — «ПЕРВЫЙ текстовый блок хода»:
# две единицы у одного требования. Инжект — самый частый носитель (раз в ход), и
# исполнялась именно его широкая редакция: за три хода одной сессии страж насчитал 7, 13
# и 6 шапок при одном инжекте на ход. Вторая и следующие шапки нести время не могут —
# инжект был один, — то есть повторяют застывшее значение, и канарейка перестаёт ловить
# ровно то, ради чего заведена. Это род L реестра: область утверждения шире его предмета.
# Формулировку держит нога T6 теста: текст обязан называть единицу и запрет на повтор.
#
# ЕДИНИЦА — ИТОГОВОЕ СООБЩЕНИЕ (2 октября 2026, решение владельца). Шапка в первом блоке
# хода до стража не доходила: промежуточный текст этот клиент кладёт в расшифровку
# пересказом. Замер того дня после сжатия контекста — 9 записей текстом против 163
# пересказов `thinking`; блок с шапкой лёг пересказом без неё, и канарейка объявила «без
# таймштампа» на ходе, где шапка была. Итоговые сообщения — 2 из 2 дословно.
#
# Универсален: без проектных файлов, без состояния, работает в любом проекте.

set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
cat >/dev/null 2>&1 || true   # stdin хука не нужен, но пайп читаем до конца

NOW=$(date '+%Y-%m-%d %H:%M %Z' 2>/dev/null) || exit 0
[ -n "$NOW" ] || exit 0

jq -cn --arg m "🕐 ${NOW} — этой шапкой начни ИТОГОВОЕ сообщение хода; в промежуточных блоках не ставить и не повторять (канарейка контекста)" \
  '{hookSpecificOutput: {hookEventName: "UserPromptSubmit", additionalContext: $m}}'
