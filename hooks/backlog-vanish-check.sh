#!/usr/bin/env bash
# backlog-vanish-check.sh — PreToolUse[Bash] на `git commit`: пункт долга не должен исчезать бесследно.
# en: PreToolUse[Bash] on `git commit`: a debt item must not vanish without a trace.
#
# Повод измерен на себе, дважды за один час 2026-08-26. Правка одного пункта делалась
# заменой ДИАПАЗОНА — «от заголовка пункта до маркера закрытых» — и оба раза уносила
# соседние пункты, лежавшие внутри границ: сперва D83/D85/D86 (коммит 6dffe5c), затем,
# уже после восстановления и разбора, снова D83/D86 (коммит 1fc183c). В архив они не
# попадали, потому что это было не закрытие, а перезапись куска файла.
#
# Почему хук, а не внимательность. Приём вычисления границ выглядит безопасным ровно до
# момента, когда между границами оказывается чужой текст, а увидеть это в момент правки
# нечем: diff показывает результат, а не то, что пропало из середины. Второе повторение
# в пределах часа — признак, что правило в голове не держится (principle-knowledge-in-the-world).
#
# Правило простое: идентификатор, бывший в BACKLOG.md на HEAD, обязан после коммита
# найтись либо в BACKLOG.md, либо в BACKLOG-archive.md. Закрытие (☑) и переезд в архив
# законны; бесследное исчезновение — нет.
#
# Input  (stdin): {tool_name, tool_input, ...} (PreToolUse JSON)
# Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} или пусто
# Exit:  always 0 — тихое напоминание, решение за агентом.
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
[ "$TOOL" = "Bash" ] || exit 0
CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
case "$CMD" in *"git commit"*) ;; *) exit 0 ;; esac

REPO=$(git rev-parse --show-toplevel 2>/dev/null) || exit 0
[ -f "$REPO/BACKLOG.md" ] || exit 0

# Идентификаторы на HEAD и в рабочем дереве. Формат пункта: `- ☐ **D42**` либо `- ☑ **D42**`.
# Опознание пункта — из общей библиотеки, а не своей копией признака. Своя копия здесь
# уже отказала: 28 августа 2026 вёрстка сменилась со списка на заголовок, и страж сутки
# видел ноль идентификаторов. Комментарий ниже (про уехавшие заголовки) о второй форме
# знал, а признак — нет.
_BL_LIB="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)/backlog-lib.sh"
[ -f "$_BL_LIB" ] || _BL_LIB="$HOME/.claude/hooks/backlog-lib.sh"
# shellcheck source=hooks/backlog-lib.sh
[ -f "$_BL_LIB" ] && . "$_BL_LIB"
ids_of() {
    if command -v backlog_item_re >/dev/null 2>&1; then
        grep -E "$(backlog_item_re)" 2>/dev/null | grep -oE 'D[0-9]+' | sort -u
    else
        grep -oE '^(- |#{2,6} )[^\n]*(☐|◐|☑|⊘)[^\n]*D[0-9]+' 2>/dev/null | grep -oE 'D[0-9]+' | sort -u
    fi
}
BEFORE=$(git -C "$REPO" show HEAD:BACKLOG.md 2>/dev/null | ids_of)
[ -n "$BEFORE" ] || exit 0
AFTER=$(ids_of < "$REPO/BACKLOG.md")
# В архиве считаем ТОЛЬКО заголовки пунктов, а не любое упоминание `**D42**`: внутри
# текста пункты ссылаются друг на друга («пункты D59, D20, D23 остаются открытыми»), и
# по упоминаниям выходило, что открытый D20 продублирован архивным. Поймано собственным
# стражем на первом же коммите после его появления.
# Из архива берём ВСЕ идентификаторы — для проверки «пункт не исчез бесследно» годится
# любой заголовок, в том числе старая открытая копия, оставшаяся от переноса летописи.
ARCHIVE=""
[ -f "$REPO/BACKLOG-archive.md" ] && ARCHIVE=$(ids_of < "$REPO/BACKLOG-archive.md")
# А для проверки на дубликат номера — только ЗАКРЫТЫЕ. В архиве живут и открытые копии:
# при переносе летописи туда уехали заголовки D59, D20, D23, D50 со статусом ☐, при том
# что сами пункты либо закрыты отдельной записью, либо продолжают жить в рабочем файле.
# По ним выходило, что открытый D20 продублирован «архивным», хотя это его же копия, а не
# второй пункт. Коллизия номеров выглядит иначе: в архиве пункт ЗАКРЫТ, а в рабочем файле
# под тем же номером стоит другой (случай D89 — fragile против вставки чужого текста).
ARCHIVE_CLOSED=""
[ -f "$REPO/BACKLOG-archive.md" ] && ARCHIVE_CLOSED=$(grep -oE '^- (☑|⊘) \*\*D[0-9]+\*\*' "$REPO/BACKLOG-archive.md" 2>/dev/null | grep -oE 'D[0-9]+' | sort -u)

VANISHED=""
# Проверка подстрокой через herestring, а не через трубу: `printf | grep -q` под
# `set -o pipefail` возвращает статус ОБОРВАННОЙ трубы, а не результат поиска, и врёт
# под нагрузкой. Класс держит `hooks/tests/test_assert_no_sigpipe.sh` — он и поймал
# эту строку при первом же прогоне.
for id in $BEFORE; do
    grep -qx "$id" <<< "$AFTER" && continue
    grep -qx "$id" <<< "$ARCHIVE" && continue
    VANISHED="$VANISHED $id"
done

# Второе: один номер у двух разных пунктов. Повод 2026-08-26 — две сессии работали
# параллельно, обе взяли следующий свободный номер, и D89 достался сразу пункту про
# `fragile` (уехал в архив закрытым) и пункту про вставку чужого текста (остался
# открытым). Номер — единственный способ сослаться на пункт из CHANGELOG, коммита и
# другого пункта; двойник делает ссылку неоднозначной задним числом.
DUPES=$(printf '%s\n%s\n' "$AFTER" "$ARCHIVE_CLOSED" | grep -E '^D[0-9]+$' | sort | uniq -d | tr '\n' ' ')

if [ -n "${DUPES// /}" ]; then
    DUP_MSG=$(printf '📋 Один номер у двух пунктов долга (BACKLOG.md и архив):%s\n\nНомер — способ сослаться на пункт из CHANGELOG, коммита и соседнего пункта; двойник делает старые ссылки неоднозначными. Обычно так выходит, когда две сессии одновременно берут следующий свободный номер. Переномеруй тот, на который ещё нет ссылок вне BACKLOG.md, и оставь след внутри пункта.' " $DUPES")
    jq -cn --arg m "$DUP_MSG" '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$m}}'
fi

# Третье: сообщение коммита объявляет пункт закрытым, а метка в BACKLOG.md — нет.
# Повод измерен на себе 2026-08-27. Коммит 6b127b7 в сообщении: «D97 закрыт удалением
# дубля»; работа сделана В ТОМ ЖЕ КОММИТЕ (таблица мостов удалена из architecture.md,
# на её месте ссылка на bridges/_index.md); строка `- ☐ **D97**` не тронута. Пункт
# остался числиться открытым: счёт открытого показывал 9 вместо 8, а backlog-recheck.sh
# — он перепроверяет ЗАКРЫТОЕ — единственный реально закрытый пункт не проверял вовсе.
#
# Корень, общий с самим D97: объявление закрытия живёт в прозе (сообщение коммита,
# CHANGELOG, текст документа), а учёт закрытия — в метке ☐/☑, и сверки между носителями
# не было ни одной. Оба прежних стража смотрят на ПУНКТЫ (не исчез ли, не задвоен ли
# номер); на расхождение ЗАЯВЛЕНИЯ и МЕТКИ не смотрел никто.
#
# Признак узкий намеренно: только пара «D<N>» и форма слова «закрыт» рядом. Простого
# упоминания номера мало — в одном сообщении соседствуют «D97 закрыт» и «D90 переписан».
# Команда, которая САМА правит BACKLOG.md перед коммитом, из проверки исключается:
# `PreToolUse` срабатывает ДО её начала, и метка на этот момент ещё старая. Поймано на
# себе 28 августа 2026 — закрытие пункта и коммит идут одной командой, и страж кричал бы
# при каждом обычном закрытии. Читать состояние, которое команда ещё не создала, нельзя.
#
# КОНТРПРИМЕР: команда, правящая долг ЧУЖИМИ руками — через скрипт, чьё имя не содержит
# «BACKLOG», — под исключение не попадёт и даст ту же ложную тревогу. Признак смотрит на
# текст команды, а не на то, какие файлы она изменит.
case "$CMD" in
    *BACKLOG*) _SELF_EDITS_BACKLOG=1 ;;
    *) _SELF_EDITS_BACKLOG=0 ;;
esac

CLAIMED=$(grep -oiE '(D[0-9]+.{0,3}закрыт|закрыт[^.]{0,20}D[0-9]+)' <<< "$CMD" 2>/dev/null \
    | grep -oE 'D[0-9]+' | sort -u)
[ "$_SELF_EDITS_BACKLOG" -eq 1 ] && CLAIMED=""
STILL_OPEN=""
for id in $CLAIMED; do
    grep -qE "^- (☐|◐) \*\*${id}\*\*" "$REPO/BACKLOG.md" 2>/dev/null && STILL_OPEN="$STILL_OPEN $id"
done
if [ -n "${STILL_OPEN# }" ]; then
    OPEN_MSG=$(printf '📋 В сообщении коммита пункт объявлен закрытым, а метка в BACKLOG.md осталась открытой:%s\n\nСчитают метку, а не прозу: с ☐ пункт входит в счёт открытого, и мимо него проходит `backlog-recheck.sh` — тот перепроверяет ЗАКРЫТОЕ. Переведи метку в ☑ и допиши внутри пункта, чем именно закрыт, либо убери слово «закрыт» из сообщения.' "$STILL_OPEN")
    jq -cn --arg m "$OPEN_MSG" '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$m}}'
fi

[ -n "${VANISHED# }" ] || exit 0

MSG=$(printf '📋 Пункты долга исчезли из BACKLOG.md и не найдены в архиве:%s\n\nЭто не закрытие — закрытый пункт уезжает в архив и там остаётся. Так выглядит перезапись куска файла: правка одного пункта заменила диапазон, внутрь которого попали соседние.\n\nВерни их (`git show HEAD:BACKLOG.md`) прежде чем коммитить. Правь блок пункта от его заголовка до заголовка СЛЕДУЮЩЕГО пункта, а не «до маркера в конце раздела».' "$VANISHED")
jq -cn --arg m "$MSG" '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$m}}'
exit 0
