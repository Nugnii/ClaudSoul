#!/usr/bin/env bash
# backlog-vanish-check.sh — PreToolUse[Bash] на `git commit`: пункт долга не должен исчезать бесследно.
# en: PreToolUse[Bash] on `git commit`: a debt item must not vanish without a trace.
#
# Повод измерен на себе, дважды за один час 2026-08-26. Правка одного пункта делалась
# заменой ДИАПАЗОНА — «от заголовка пункта до маркера закрытых» — и оба раза уносила
# соседние пункты, лежавшие внутри границ: сперва D83/D85/D86 (коммит 6dffe5c), затем,
# уже после восстановления и разбора, снова D83/D86 (коммит 1fc183c). В архив они не
# попадали, потому что это было не закрытие, а перезапись куска файла.
#
# Почему хук, а не внимательность. Приём вычисления границ выглядит безопасным ровно до
# момента, когда между границами оказывается чужой текст, а увидеть это в момент правки
# нечем: diff показывает результат, а не то, что пропало из середины. Второе повторение
# в пределах часа — признак, что правило в голове не держится (principle-knowledge-in-the-world).
#
# Правило простое: идентификатор, бывший в BACKLOG.md на HEAD, обязан после коммита
# найтись либо в BACKLOG.md, либо в BACKLOG-archive.md. Закрытие (☑) и переезд в архив
# законны; бесследное исчезновение — нет.
#
# Input  (stdin): {tool_name, tool_input, ...} (PreToolUse JSON)
# Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} или пусто
# Exit:  always 0 — тихое напоминание, решение за агентом.
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
# ЛОВУШКА GIT (D1022): `--commit-msg <файл>` зовёт `commit-trap.sh` в корне рабочего дерева коммита с его индексом
# (GIT_INDEX_FILE). «После коммита» здесь — индекс коммита, заявление «закрыт» — готовое сообщение; разбор текста
# команды (какой снимок унесёт коммит, D435) не нужен. Подсказки — в stderr. На PreToolUse страж молчит, если в
# репозитории коммита ловушка стоит.
TRAP=0; MSGF=/dev/null; INPUT=""; CMD=""
if [ "${1:-}" = "--commit-msg" ]; then
    TRAP=1; MSGF="${2:-/dev/null}"
else
    INPUT=$(cat 2>/dev/null) || exit 0
    [ -n "$INPUT" ] || exit 0
    TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
    [ "$TOOL" = "Bash" ] || exit 0
    CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
fi
_say() {   # подсказка: additionalContext на PreToolUse, stderr в ловушке (агент видит его в выводе команды)
    if [ "$TRAP" -eq 1 ]; then printf '%s\n' "$1" >&2
    else jq -cn --arg m "$1" '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$m}}'; fi
}
# ЭТО КОММИТ? — СПРАШИВАЕТСЯ У ВЛАДЕЛЬЦА (17 сентября 2026, D435). Прежде стоял литерал
# `*"git commit"*` по сырому тексту. Он промахивался в обе стороны, и обе измерены по расшифровкам
# проекта: `git -C <путь> commit`, `git -c k=v commit`, два пробела и перенос `git \` коммитом не
# считались вовсе (63 команды — пункт пропадал молча), а 230 из 1641 «команд с git commit» были
# упоминанием в кавычках и heredoc. Нет библиотеки — прежний литерал: лучше лишний вызов, чем немота.
_CS_LIB="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/command-scope-lib.sh"
[ -f "$_CS_LIB" ] || _CS_LIB="$HOME/.claude/hooks/command-scope-lib.sh"
# shellcheck source=/dev/null
[ -f "$_CS_LIB" ] && . "$_CS_LIB" 2>/dev/null
# git в папке сессии — через project_git (D519): голый git исполняет программы из её настроек.
_PL="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/paths-lib.sh"
[ -f "$_PL" ] || _PL="$HOME/.claude/hooks/paths-lib.sh"
# shellcheck source=/dev/null
[ -f "$_PL" ] && . "$_PL" 2>/dev/null
command -v project_git >/dev/null 2>&1 || project_git() { git "$@"; }   # без paths-lib — голый git (предел D515)
if [ "$TRAP" -eq 1 ]; then
    _EXEC=""
elif command -v is_git_commit >/dev/null 2>&1 && command -v executable_part >/dev/null 2>&1; then
    is_git_commit "$CMD" || exit 0
    _EXEC=$(executable_part "$CMD" 2>/dev/null); [ -n "$_EXEC" ] || _EXEC="$CMD"
else
    case "$CMD" in *"git commit"*) ;; *) exit 0 ;; esac
    _EXEC="$CMD"
fi
# Простые команды — по одной на строку: `&&`, `||`, `;`, `|` и ПЕРЕВОД СТРОКИ равно делят команду.
# Без перевода строки флаги соседней команды (`ls -la`, `git tag -a`, `git log --all` строкой ниже)
# читались флагами коммита — в истории так было дважды (находка скептика).
_GIT_G='([[:space:]]+(-C[[:space:]]+[^[:space:]]+|-c[[:space:]]+[^[:space:]]+|--git-dir=[^[:space:]]+|--work-tree=[^[:space:]]+|--no-pager|-P))*'
_SIMPLE=$(sed -E 's/(&&|\|\||;|\|)/\
/g' <<< "$_EXEC")

# cwd из payload, не из окружения процесса: процесс хука не обязан стоять в каталоге
# сессии. Тот же дефект чинился в claude-md-size-check (v1.12.4) и в трёх стражах аудита
# переносимости (2026-08-08); этот страж родился 26 августа — после обеих починок, и
# третья волна пришла ровно потому, что носителя у класса не было (см.
# hooks/tests/test_payload_cwd_root.sh).
CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null); [ -n "$CWD" ] || CWD="$PWD"
# `cd <путь> && git commit` и `git -C <путь> commit` коммитят В ДРУГОЙ репозиторий: судится он, а не каталог сессии.
# Каталог коммита — у разбора команды (`executable_commit_dir`, D1279); своё выражение по `-C` снято — `cd` оно не видело.
command -v executable_commit_dir >/dev/null 2>&1 || executable_commit_dir() { return 2; }
_CD=$(executable_commit_dir "$CWD" "$CMD") && CWD="$_CD"
REPO=$(git -C "$CWD" rev-parse --show-toplevel 2>/dev/null) || exit 0
[ "$TRAP" -eq 0 ] && command -v project_commit_trap >/dev/null 2>&1 && project_commit_trap "$REPO" commit-msg "$CMD" && exit 0
# ДВЕРИ «файла нет — выходим» ЗДЕСЬ БОЛЬШЕ НЕТ, и это не недосмотр (17 сентября 2026, D434).
# До этого дня тут стояло `[ -f "$REPO/BACKLOG.md" ] || exit 0`: вопрос «есть ли у проекта
# долг» задавался РАБОЧЕМУ ДЕРЕВУ — той самой стороне, которую страж судит, — а владелец
# ответа есть HEAD, и его спрашивали на 27 строк ниже. Оттого «долга у проекта нет» и «долг
# был в HEAD, а файл удалён целиком» отвечали одним молчанием (корень R6): потеря ОДНОГО
# пункта называлась, потеря ВСЕХ — нет, охват был обратен ущербу. Замер того же дня: `git rm`
# и простой `rm` дают тишину, перезапись файла пустым заголовком — предупреждение.
# Теперь вопрос применимости задан ОПОРНОЙ стороне: `[ -n "$BEFORE" ] || exit 0` ниже.
# Проект без BACKLOG.md в HEAD молчит, как прежде, — просто выходит там, а не здесь.
# Цена измерена: коммит в проекте без долга стал дороже на загрузку библиотеки и один
# `git show` — 34 мс против 20 мс на вызов (10 прогонов подряд, macOS).
# НАЗВАННЫЕ ПРЕДЕЛЫ — три, у каждого своё условие снятия.
# 1. Новая дверь сама отвечает одним молчанием на ДВА состояния: «в HEAD пунктов нет» и
#    «разбор HEAD не увидел ни одного» — незакрытый забор кода гасит остаток файла
#    (`backlog_strip_fenced`). Симптом D434 этим путём по-прежнему достижим: такой HEAD плюс
#    удалённый файл дают 0 байт вывода (воспроизведено 17 сентября 2026). Здоровый образец —
#    канал `#CG_BROKEN` в `completion-gate.sh`: пункты есть в сыром тексте и исчезли в
#    очищенном. Условие снятия: та же сверка сырого с очищенным здесь — отдельный пункт
#    долга, потому что забор в СЕРЕДИНЕ файла даёт частичный BEFORE, и решение там своё.
# 2. Команда, которая САМА удаляет файл перед коммитом (`git rm BACKLOG.md && git commit`),
#    стражу не видна: PreToolUse читает дерево ДО её начала (то же свойство названо ниже у
#    третьей проверки), а после такого коммита HEAD файла уже не несёт, и дальнейшее
#    молчание законно. Названы поэтому только ДВУХШАГОВЫЕ формы: удаление одной командой,
#    коммит другой. Замер 17 сентября 2026 по 71 расшифровке проекта: команд с `git commit`
#    1632, `git rm`/`git mv` в той же команде у 5, BACKLOG.md среди них 0. Условие снятия:
#    появится такой случай — читать `git rm|mv … BACKLOG.md` из текста CMD.
# 3. Рабочее дерево, где файл скрыт НАМЕРЕННО (sparse-checkout), будет названо на каждом
#    коммите. В дереве владельца таких нет: 18 репозиториев (поиск `.git` до глубины 4 в
#    `~/My Project`, `~/Documents`, `~/.claude`), у 4 HEAD несёт BACKLOG.md, файла не хватает
#    у 0, core.sparseCheckout включён у 0; за 522 коммита по BACKLOG.md удалений и переносов
#    0. Условие снятия: появится такой проект — различать бит skip-worktree (`git ls-files -t`).
# Какой снимок судится при какой форме команды — ниже, у выбора снимка (D435).

# Идентификаторы на HEAD и в рабочем дереве. Формат пункта знает библиотека — обе вёрстки,
# списочная и заголовочная.
# Опознание пункта — из общей библиотеки, а не своей копией признака. Своя копия здесь
# уже отказала: 28 августа 2026 вёрстка сменилась со списка на заголовок, и страж сутки
# видел ноль идентификаторов. Комментарий ниже (про уехавшие заголовки) о второй форме
# знал, а признак — нет.
_BL_LIB="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)/backlog-lib.sh"
[ -f "$_BL_LIB" ] || _BL_LIB="$HOME/.claude/hooks/backlog-lib.sh"
# shellcheck source=hooks/backlog-lib.sh
# shellcheck source=/dev/null
{ [ -f "$_BL_LIB" ] && . "$_BL_LIB"; } || exit 0
command -v backlog_id_stream >/dev/null 2>&1 || exit 0
command -v backlog_strip_fenced >/dev/null 2>&1 || exit 0
ids_of() {
    # Идентификатор — ПЕРВЫЙ номер строки, а не все её номера: заголовок законно ссылается
    # на родню (открытый пункт D284 со ссылкой на D279 в заголовке). Своя копия признака дала ложный
    # «один номер у двух пунктов» 3 сентября 2026 — D278 и D279 лежали в архиве, а в
    # BACKLOG.md на них лишь ссылались. Это третья копия одного признака: две первые
    # (backlog_ids, backlog-return-check) сведены в backlog_id_stream в тот же день.
    # Запасной ветки со своей копией признака здесь больше нет (D305): без библиотеки
    # страж выходит выше молча. Копия, которой пользуются «когда владельца нет», — это
    # второй признак, и расходится он ровно тогда, когда его никто не смотрит.
    # Забор кода снимается до признака: строка внутри тройных кавычек — образец.
    backlog_strip_fenced | grep -E "$(backlog_item_re)" 2>/dev/null | backlog_id_stream | sort -u
}
_HEAD_RAW=$(git -C "$REPO" show HEAD:BACKLOG.md 2>/dev/null)
BEFORE=$(printf '%s\n' "$_HEAD_RAW" | ids_of)
# D438: разбор без пунктов — это ЛИБО «в HEAD пунктов нет», ЛИБО «незакрытый забор
# кода погасил их до конца файла» (backlog_strip_fenced). Раньше оба состояния
# отвечали одним молчанием; теперь сырой текст сверяется с очищенным, как в
# completion-gate.sh (#CG_BROKEN), и расхождение называется, а не молчит.
if [ -z "$BEFORE" ]; then
    _RAW_ITEMS=$(printf '%s\n' "$_HEAD_RAW" | grep -cE "$(backlog_item_re)" 2>/dev/null)
    if [ "${_RAW_ITEMS:-0}" -gt 0 ]; then
        _say "#CG_BROKEN разбор HEAD:BACKLOG.md не увидел ни одного пункта при ${_RAW_ITEMS} в сыром тексте — похоже на незакрытый забор кода"
    fi
    exit 0
fi
# В ловушке «после» — индекс коммита, а не рабочее дерево (D1022): файлы долга читаются копиями из индекса; файла нет
# в индексе — копии нет, как удалённого файла.
BL_DIR="$REPO"
if [ "$TRAP" -eq 1 ]; then
    BL_DIR=$(mktemp -d 2>/dev/null) || exit 0
    trap 'rm -rf "$BL_DIR"' EXIT
    for _f in BACKLOG.md BACKLOG-archive.md; do
        project_git -C "$REPO" show ":$_f" > "$BL_DIR/$_f" 2>/dev/null || rm -f "$BL_DIR/$_f"
    done
fi
# Файла нет — «после» пусто, и каждый пункт HEAD ищется только в архиве (D434).
AFTER=""
# Бэклог есть, но не читается — «после» неизвестно, а не пусто (D1121): иначе каждый пункт HEAD назывался бы исчезнувшим.
if [ -f "$BL_DIR/BACKLOG.md" ] && [ ! -r "$BL_DIR/BACKLOG.md" ]; then
    _say "📋 BACKLOG.md не читается (нет права на чтение) — исчезновение пунктов судить нечем, страж о пропаже молчит."
    exit 0
fi
if [ -f "$BL_DIR/BACKLOG.md" ]; then
    AFTER=$({ backlog_read "$BL_DIR/BACKLOG.md" 2>/dev/null || cat -- "$BL_DIR/BACKLOG.md" 2>/dev/null; } | ids_of)
fi
# В архиве считаем ТОЛЬКО заголовки пунктов, а не любое упоминание `**D42**`: внутри
# текста пункты ссылаются друг на друга («пункты D59, D20, D23 остаются открытыми»), и
# по упоминаниям выходило, что открытый D20 продублирован архивным. Поймано собственным
# стражем на первом же коммите после его появления.
# Из архива берём ВСЕ идентификаторы — для проверки «пункт не исчез бесследно» годится
# любой заголовок, в том числе старая открытая копия, оставшаяся от переноса летописи.
ARCHIVE=""
[ -f "$BL_DIR/BACKLOG-archive.md" ] && ARCHIVE=$({ backlog_read "$BL_DIR/BACKLOG-archive.md" 2>/dev/null || cat -- "$BL_DIR/BACKLOG-archive.md" 2>/dev/null; } | ids_of)
# А для проверки на дубликат номера — только ЗАКРЫТЫЕ. В архиве живут и открытые копии:
# при переносе летописи туда уехали заголовки D59, D20, D23, D50 со статусом «не сделано», при том
# что сами пункты либо закрыты отдельной записью, либо продолжают жить в рабочем файле.
# По ним выходило, что открытый D20 продублирован «архивным», хотя это его же копия, а не
# второй пункт. Коллизия номеров выглядит иначе: в архиве пункт ЗАКРЫТ, а в рабочем файле
# под тем же номером стоит другой (случай D89 — fragile против вставки чужого текста).
ARCHIVE_CLOSED=""
[ -f "$BL_DIR/BACKLOG-archive.md" ] && ARCHIVE_CLOSED=$(backlog_ids "$BL_DIR/BACKLOG-archive.md" "$BACKLOG_DONE_MARKS")

VANISHED=""
# Проверка подстрокой через herestring, а не через трубу: `printf | grep -q` под
# `set -o pipefail` возвращает статус ОБОРВАННОЙ трубы, а не результат поиска, и врёт
# под нагрузкой. Класс держит `hooks/tests/test_assert_no_sigpipe.sh` — он и поймал
# эту строку при первом же прогоне.
for id in $BEFORE; do
    grep -qx "$id" <<< "$AFTER" && continue
    grep -qx "$id" <<< "$ARCHIVE" && continue
    VANISHED="$VANISHED $id"
done

# КАКОЙ СНИМОК УНЕСЁТ КОММИТ — РЕШАЕТСЯ ДЛЯ КАЖДОГО ФАЙЛА ОТДЕЛЬНО (17 сентября 2026, D435).
# Правило выше утверждает «ПОСЛЕ КОММИТА пункт найдётся», а мерило рабочую копию при любой форме:
# вход «что идёт в коммит» не был объявлен, и брался снимок, который дешевле прочесть.
# Воспроизведено: в индексе BACKLOG.md без D901, копия восстановлена с ним, `git commit -m x` —
# тишина, а коммит уносит индекс без пункта.
# Две слепые замены хуже дефекта, и обе ИЗМЕРЕНЫ по 1411 настоящим коммитам проекта (исполняемая
# часть команд 71 расшифровки). «Без -a судить индекс»: у 1333 команд (94%) `git add` стоит в той
# же команде, PreToolUse читает индекс ДО её начала, он ещё старый. «Есть `git add` — судить копию»
# (первая редакция этой починки, снята скептиком): у 398 команд add называет ЧУЖОЙ путь, долг
# уйдёт из индекса, и страж молчал на них чаще, чем прежде на голых коммитах (75); туда же —
# половина переноса одной командой (`git add BACKLOG.md && git commit`, архив не поставлен: 162
# команды) и `-am` при ещё не отслеживаемом архиве.
# Поэтому вопрос задаётся каждому из двух файлов: что команда положит в коммит ИМЕННО ЕГО?
#   · файл назван в `git add|stage|rm|mv` до коммита либо аргументом коммита — рабочая копия;
#   · `git add -A|--all|.` — рабочая копия (берёт и неотслеживаемое);
#   · `git add -u` либо `commit -a|--all` (в том числе слитно: `-am`) — рабочая копия, ЕСЛИ файл
#     отслеживается; неотслеживаемый они не возьмут — индекс;
#   · `git commit <пути>` без файла среди них — файл останется как в HEAD, пропасть ему не с чего;
#   · иначе — индекс.
# «Всё» и «только отслеживаемое» отвечает владелец разбора — `executable_commit_adds` (command-scope-lib.sh, D1087): ключи
# git он разбирает так, как git, и сверен с исполнением форм (`test_commit_adds_oracle.sh`); здесь прежде стояли свои
# выражения по строке (`-ma` читалось как `-a`, `git add -A docs` — как «всё»). Разбора нет — ответ пуст, судится индекс.
# Суд рабочей копии выше остаётся ВДОБАВОК: потеря в копии уйдёт следующим `git add`, назвать её
# сейчас дешевле, чем искать потом (на этом стоят прежние ноги теста).
# НАЗВАННЫЙ ПРЕДЕЛ: пути читаются как слова исполняемой части — glob кроме `BACKLOG*`, каталог
# кроме `.`, `git add -p`, `-i|-o|--include|--only`, pathspec-магия и алиасы git не разбираются;
# слово после `-m|-F|-C|-c|-t` путём не считается, прочие значения флагов могут быть приняты за
# путь (тогда файл судится по HEAD — молчание). Индекс в состоянии конфликта не судится: `git show
# :путь` там отвечает отказом, и «не смог прочитать» вышло бы «все пункты исчезли». Условие снятия:
# у владельца области команд появится разбор аргументов git (`hooks/lib/write_targets.py`).
VANISHED_IDX=""
_NAMED_B=0; _NAMED_A=0; _ONLY_PATHS=0; _SWEEP=""
command -v executable_commit_adds >/dev/null 2>&1 && _SWEEP=$(executable_commit_adds "$CMD")
_names_in() {   # _names_in <слова> — отмечает названные файлы долга
    case " $1 " in *" BACKLOG*"*|*"/BACKLOG*"*) _NAMED_B=1; _NAMED_A=1 ;; esac
    case " $1 " in *" BACKLOG.md "*|*"/BACKLOG.md "*) _NAMED_B=1 ;; esac
    case " $1 " in *" BACKLOG-archive.md "*|*"/BACKLOG-archive.md "*) _NAMED_A=1 ;; esac
}
while IFS= read -r _ln; do
    [ -n "$_ln" ] || continue
    if grep -qE "(^|[[:space:]]|\(|\{)git${_GIT_G}[[:space:]]+commit([[:space:]]|\$)" <<< "$_ln"; then
        _args="${_ln#*commit}"
        # слова-пути: не флаг, не значение `-m|-F|-C|-c|-t`, существует в репозитории
        _prev=""
        for _w in $_args; do
            [ "$_w" = "(" ] && continue   # открытие подстановки (`executable_part`, D1212) — не слово команды
            case "$_prev" in -m|-F|-C|-c|-t) _prev="$_w"; continue ;; esac
            _prev="$_w"
            case "$_w" in -*) continue ;; esac
            [ -e "$REPO/$_w" ] || [ -e "$CWD/$_w" ] || continue
            _ONLY_PATHS=1
            case "$_w" in .|./) _NAMED_B=1; _NAMED_A=1 ;; esac
            _names_in "$_w"
        done
        break
    fi
    if grep -qE "(^|[[:space:]]|\(|\{)git${_GIT_G}[[:space:]]+(add|stage)([[:space:]]|\$)" <<< "$_ln"; then
        _names_in "${_ln#*git}"
    elif grep -qE "(^|[[:space:]]|\(|\{)git${_GIT_G}[[:space:]]+(rm|mv)([[:space:]]|\$)" <<< "$_ln"; then
        _names_in "${_ln#*git}"
    fi
done <<< "$_SIMPLE"
_tracked() { project_git -C "$REPO" ls-files --error-unmatch -- "$1" >/dev/null 2>&1; }
_snap_of() {   # _snap_of <файл> <назван?> → wt | index | head
    if [ "$2" -eq 1 ] || [ "$_SWEEP" = all ]; then echo wt; return; fi
    if [ "$_SWEEP" = tracked ] && _tracked "$1"; then echo wt; return; fi
    if [ "$_ONLY_PATHS" -eq 1 ]; then echo head; return; fi
    echo index
}
_ids_at() {    # _ids_at <файл> <снимок> → идентификаторы пунктов файла в снимке
    case "$2" in
        wt)    [ -f "$REPO/$1" ] && ids_of < "$REPO/$1" ;;
        index) project_git -C "$REPO" show ":$1" 2>/dev/null | ids_of ;;
        head)  git -C "$REPO" show "HEAD:$1" 2>/dev/null | ids_of ;;
    esac
}
_SNAP_B=$(_snap_of BACKLOG.md "$_NAMED_B"); _SNAP_A=$(_snap_of BACKLOG-archive.md "$_NAMED_A")
# ИНДЕКС ЧИТАЕТСЯ? Испорченный индекс отвечает отказом на любое чтение, и без этого вопроса «не
# смог прочитать» выходило «все пункты пропали» — тот же R6, только внутри самой починки (находка
# скептика, воспроизведено). Отказ чтения индекса — не находка о долге: такой коммит не состоится.
if { [ "$_SNAP_B" != wt ] || [ "$_SNAP_A" != wt ]; } \
   && project_git -C "$REPO" ls-files -s -- BACKLOG.md >/dev/null 2>&1 \
   && [ -z "$(project_git -C "$REPO" ls-files -u -- BACKLOG.md BACKLOG-archive.md 2>/dev/null)" ]; then
    C_AFTER=$(_ids_at BACKLOG.md "$_SNAP_B")
    C_ARCHIVE=$(_ids_at BACKLOG-archive.md "$_SNAP_A")
    for id in $BEFORE; do
        grep -qx "$id" <<< "$C_AFTER" && continue
        grep -qx "$id" <<< "$C_ARCHIVE" && continue
        case " $VANISHED " in *" $id "*) continue ;; esac     # уже назван по рабочей копии
        VANISHED_IDX="$VANISHED_IDX $id"
    done
fi

# Второе: один номер у двух разных пунктов. Повод 2026-08-26 — две сессии работали
# параллельно, обе взяли следующий свободный номер, и D89 достался сразу пункту про
# `fragile` (уехал в архив закрытым) и пункту про вставку чужого текста (остался
# открытым). Номер — единственный способ сослаться на пункт из CHANGELOG, коммита и
# другого пункта; двойник делает ссылку неоднозначной задним числом.
DUPES=$(printf '%s\n%s\n' "$AFTER" "$ARCHIVE_CLOSED" | grep -E "^${BACKLOG_ID_TOKEN_RE}\$" | sort | uniq -d | tr '\n' ' ')

if [[ $DUPES == *[!\ ]* ]]; then
    DUP_MSG=$(printf '📋 Один номер у двух пунктов долга (BACKLOG.md и архив):%s\n\nНомер — способ сослаться на пункт из CHANGELOG, коммита и соседнего пункта; двойник делает старые ссылки неоднозначными. Обычно так выходит, когда две сессии одновременно берут следующий свободный номер. Переномеруй тот, на который ещё нет ссылок вне BACKLOG.md, и оставь след внутри пункта.' " $DUPES")
    _say "$DUP_MSG"
fi

# Третье: сообщение коммита объявляет пункт закрытым, а метка в BACKLOG.md — нет.
# Повод измерен на себе 2026-08-27. Коммит 6b127b7 в сообщении: «D97 закрыт удалением
# дубля»; работа сделана В ТОМ ЖЕ КОММИТЕ (таблица мостов удалена из architecture.md,
# на её месте ссылка на bridges/_index.md); строка пункта D97 осталась открытой. Пункт
# остался числиться открытым: счёт открытого показывал 9 вместо 8, а backlog-recheck.sh
# — он перепроверяет ЗАКРЫТОЕ — единственный реально закрытый пункт не проверял вовсе.
#
# Корень, общий с самим D97: объявление закрытия живёт в прозе (сообщение коммита,
# CHANGELOG, текст документа), а учёт закрытия — в метке статуса, и сверки между носителями
# не было ни одной. Оба прежних стража смотрят на ПУНКТЫ (не исчез ли, не задвоен ли
# номер); на расхождение ЗАЯВЛЕНИЯ и МЕТКИ не смотрел никто.
#
# Признак узкий намеренно: только пара «D<N>» и форма слова «закрыт» рядом. Простого
# упоминания номера мало — в одном сообщении соседствуют «D97 закрыт» и «D90 переписан».
# Команда, которая САМА правит BACKLOG.md перед коммитом, из проверки исключается:
# `PreToolUse` срабатывает ДО её начала, и метка на этот момент ещё старая. Поймано на
# себе 28 августа 2026 — закрытие пункта и коммит идут одной командой, и страж кричал бы
# при каждом обычном закрытии. Читать состояние, которое команда ещё не создала, нельзя.
#
# КОНТРПРИМЕР: команда, правящая долг ЧУЖИМИ руками — через скрипт, чьё имя не содержит
# «BACKLOG», — под исключение не попадёт и даст ту же ложную тревогу. Признак смотрит на
# текст команды, а не на то, какие файлы она изменит.
case "$CMD" in
    *BACKLOG*) _SELF_EDITS_BACKLOG=1 ;;
    *) _SELF_EDITS_BACKLOG=0 ;;
esac

# В ловушке заявление читается из готового сообщения, а метка — из индекса коммита: исключение «команда сама правит
# долг» там не нужно, состояние уже то, что войдёт.
# Строки-комментарии сообщения git вырежет — заявлением они не считаются (скептик D1022).
_CLAIM_SRC="$CMD"; [ "$TRAP" -eq 1 ] && _CLAIM_SRC=$(grep -v '^#' "$MSGF" 2>/dev/null)
# Заявление — причастие «закрыт/а/о/ы» ЦЕЛЫМ словом (D1140, корень R3): форма «начинается с закрыт» брала и существительное
# — «D1137: закрытие пункта, чинящего hooks/…» назвало открытый D1137 объявленным закрытым. Граница слова — «не буква»
# слева и справа, и судится она по ЗНАКАМ, а не по байтам: класс `grep` для кириллицы зависит от локали исполнителя (скептик
# D1140, M-1: «D5 закрыт—» под `LC_ALL=C` молчал, под UTF-8 ловился), поэтому разбор — в python (`re`, юникодные классы).
# Номер — без хвостовой точки и дефиса («закрыт D5.», M-3). Во втором порядке («закрыт пункт D5») точка не пересекается —
# иначе «закрыт. D5 …» связало бы два предложения. Без python3 заявление не судится: другой проект, а не отказ.
# Пределы: из перечня «D5, D6 закрыты» берётся последний номер; отрицание «не закрыт D5» читается заявлением.
CLAIMED=""
command -v python3 >/dev/null 2>&1 && CLAIMED=$(printf '%s' "$_CLAIM_SRC" | TOK="$BACKLOG_ID_TOKEN_RE" python3 -c '
import os, re, sys
tok = os.environ["TOK"]
w = r"(?<![^\W\d_])закрыт(?:а|о|ы)?(?![^\W\d_])"
pat = re.compile(r"(%s).{0,3}?%s|%s[^\w.\n]+[^.\n]{0,19}?(%s)" % (tok, w, w, tok), re.I)
ids = set()
for line in sys.stdin.read().splitlines():
    for m in pat.finditer(line):
        ids.add(re.sub(r"[.-]+$", "", m.group(1) or m.group(2)))
print("\n".join(sorted(i for i in ids if i)))' 2>/dev/null)
[ "$_SELF_EDITS_BACKLOG" -eq 1 ] && CLAIMED=""
STILL_OPEN=""
# Открытые пункты — тем же правилом, что у остальных читателей: своя строка
# `^- (метки) **id**` видела ТОЛЬКО списочную вёрстку, и заголовочный пункт («### D42 …»)
# проезжал мимо стража молча — та же слепота, что онемила три стража 28 августа 2026.
OPEN_IDS=$(backlog_ids "$BL_DIR/BACKLOG.md" "$BACKLOG_OPEN_MARKS")
for id in $CLAIMED; do
    grep -qxF "$id" <<< "$OPEN_IDS" && STILL_OPEN="$STILL_OPEN $id"
done
if [ -n "${STILL_OPEN# }" ]; then
    OPEN_MSG=$(printf '📋 В сообщении коммита пункт объявлен закрытым, а метка в BACKLOG.md осталась открытой:%s\n\nСчитают метку, а не прозу: с %s пункт входит в счёт открытого, и мимо него проходит `backlog-recheck.sh` — тот перепроверяет ЗАКРЫТОЕ. Переведи метку в %s и допиши внутри пункта, чем именно закрыт, либо убери слово «закрыт» из сообщения.' "$STILL_OPEN" "$BACKLOG_MARK_TODO" "$BACKLOG_MARK_DONE")
    _say "$OPEN_MSG"
fi

# Пункт есть в рабочей копии, а в ИНДЕКСЕ его нет — у сообщения свой текст: агент, открыв файл,
# увидит пункт на месте и не поймёт, о чём речь, если не сказать, какой снимок судился (D435).
if [ -n "${VANISHED_IDX# }" ]; then
    IDX_MSG=$(printf '📋 Пункты долга в рабочей копии на месте (в BACKLOG.md либо в архиве), а в ИНДЕКСЕ их нет ни там, ни там — и этот коммит унесёт индекс:%s\n\nКоммит без `-a` и без `git add` в той же команде берёт индекс, а не файлы на диске: после него пункт из HEAD пропадёт, хотя на диске он виден. Чаще всего это половина переноса: BACKLOG.md поставлен в индекс, а BACKLOG-archive.md — нет. Проверь `git diff --cached -- BACKLOG.md BACKLOG-archive.md` и поставь в индекс ОБА файла.' "$VANISHED_IDX")
    _say "$IDX_MSG"
fi

[ -n "${VANISHED# }" ] || exit 0

# Файл удалён ЦЕЛИКОМ — у сообщения своя строка (17 сентября 2026, D434). Прежний текст
# объясняет пропажу «перезаписью куска файла» и советует править блок пункта от заголовка до
# заголовка; при удалённом файле это неправда, и действие нужно другое. Один текст на два
# состояния был бы тем же R6, только в канале вывода. Слова «не найдены в архиве» и имена
# пунктов общие у обеих строк — по ним сообщение опознают тест и проба пункта.
if [ ! -f "$BL_DIR/BACKLOG.md" ]; then
    MSG=$(printf '📋 BACKLOG.md удалён целиком, а пункты долга из HEAD не найдены в архиве:%s\n\nЭто не закрытие — закрытый пункт уезжает в архив и там остаётся. Удалён случайно — верни: `git checkout HEAD -- BACKLOG.md`. Удалён или переименован намеренно — перенеси эти пункты туда, где долг будет жить дальше, и назови это место в сообщении коммита.' "$VANISHED")
else
    MSG=$(printf '📋 Пункты долга исчезли из BACKLOG.md и не найдены в архиве:%s\n\nЭто не закрытие — закрытый пункт уезжает в архив и там остаётся. Так выглядит перезапись куска файла: правка одного пункта заменила диапазон, внутрь которого попали соседние.\n\nВерни их (`git show HEAD:BACKLOG.md`) прежде чем коммитить. Правь блок пункта от его заголовка до заголовка СЛЕДУЮЩЕГО пункта, а не «до маркера в конце раздела».' "$VANISHED")
fi
_say "$MSG"
exit 0
