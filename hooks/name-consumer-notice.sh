#!/usr/bin/env bash
# name-consumer-notice.sh — PreToolUse[Write|Edit|MultiEdit] и подача диспетчера правок командой: правка, после которой файл перестаёт читать переменную окружения, называет файлы, которые её ещё задают и зовут этот файл.
# en: PreToolUse on file writes (and the shell-write dispatcher): when an edit makes a file stop reading an environment variable, names the other files that still set it and call this file.
#
# Результат: правка, снимающая с файла чтение переменной окружения, у которой в дереве остался
#            потребитель (задаёт её и зовёт этот файл), получает список потребителей до коммита
# Проверка результата: bash hooks/tests/fixtures/probe_D1200.sh даёт 0
#
# Зачем (D1200, 31 октября 2026). Путь архива сверщика переименован `BACKLOG_ARCHIVE` →
# `BACKLOG_RECHECK_ARCHIVE` в `scripts/backlog-recheck.sh`, а нога F пробы D1198 задавала
# старое имя и ушла бы в живой архив — 514 «Проверок» на каждом прогоне гейтом. Поймала
# соседняя сессия (66bc9d0d). Знание `pattern-owner-of-the-fact-was-not-asked` (confidence 4)
# стояло в контексте и дважды за сессию не применилось: инжект идёт почти на каждый вызов и
# момента действия не отмечает (`case-2026-10-31-test-expectation-from-own-model-of-guard`).
# Здесь момент отмечен: правка, после которой имя снято, а потребитель жив.
#
# ЧЕМ РЕШАЛОСЬ РАНЬШЕ, И СУДЬБА КАЖДОГО:
#   · `undefined-function-check.sh` — обратное направление для функций: вызов в ЗАПИСАННОМ файле
#     имени, которого нет нигде. Остаётся; здесь предмет — другие файлы, которых правка не
#     касалась. Функции сюда не взяты по замеру: на истории дерева 17 из 17 снятых определений с
#     живыми вызовами (7 правок) — перенос в другую библиотеку, настоящих сирот 0.
#   · `impact-inject.sh` — кто стоит на ФАЙЛЕ по карте связей. Остаётся; здесь единица — ИМЯ:
#     на файле стоят десятки, на снятом имени — те, кого правка ломает.
#   · знание `pattern-owner-of-the-fact-was-not-asked` — текст, уровень 2; механизм его не снимает.
#
# ПРИЗНАК И ТОЧНОСТЬ (разбор и ядро признака — `hooks/lib/name_consumers.py`, `consumers()`). Прежняя
# редакция файла читает переменную в строке кода (не в комментарии, не в докстроке): `$NAME`, `${NAME…}`,
# `os.environ.get/[ ]`, `getenv`, awk `ENVIRON[…]`, `'NAME' in os.environ`, а в файле, трогающем окружение,
# и голый литерал (обёртка `_int("NAME", 300)`). Новая редакция не читает его ни сама, ни по префиксу
# (`startswith("GIT_")`), ни через файл, который ПОДКЛЮЧАЕТ строкой кода без прозы. Потребитель — другой
# `*.sh`/`*.py`, который задаёт переменную (`NAME=`, `'NAME':`, `["NAME"] =`, `setenv/putenv/setdefault`) и
# называет файл в строке кода. Замер 3 ноября 2026 тем же ядром по 2 591 коммиту: 3 срабатывания в 2 правках,
# настоящие обе — сам повод (b6f66dbc) и `test_root_cause_lib.sh`, задающий с 29 августа 2026 (2e7d80c9)
# `DPR_BACKLOG` и `DPR_LESSONS`, которых `declared-problem-recorded.sh` с 12 сентября 2026 (b07fb76e) не читает
# (D1241). Без уточнения про подключение — 16 в 13 правках, 13 ложных: чтение уходило в подключённую библиотеку.
# Каждое условие признака держит своя нога теста: 23 мутанта, снимающих по условию, краснят каждый свою.
# Слово в комментарии чтением не считается: при переименовании повода старое имя осталось в
# пояснении «не `BACKLOG_ARCHIVE`», и признак по слову его бы не увидел.
#
# ПОЧЕМУ ПОДСКАЗКА, А НЕ ОТКАЗ. Последствий у признака больше одного: потребитель бывает
# приманкой (`probe_D1147.sh` задаёт старое имя нарочно) либо задаёт значение для другого
# читателя той же команды. Уровень 3; отказ на смешанных последствиях запрещён правилом выбора
# уровня (`case-2026-08-28-enforcement-is-a-property-of-consequence`).
#
# СТАРАЯ РЕДАКЦИЯ — ПОСЛЕДНИЙ КОММИТ, А НЕ ДИСК. На пути команды (диспетчер, PostToolUse) диск уже
# новый; один источник «было» для обоих путей. Если и последний коммит уже равен новой редакции (`sed -i … &&
# git commit` одной командой либо коммит следующей — около 17% правок кода командой, замер скептика), «было»
# берётся у родителя свежего коммита, тронувшего файл (окно `RECENT` 600 с), и подсказка говорит «Коммит … снял».
# Повтор той же находки за сессию гасит дедуп по её составу. Потребители ищутся и среди НЕУЧТЁННЫХ файлов
# (`git grep --untracked`): сканер по `git ls-files` слеп к новому файлу соседней сессии (D1240).
#
# НАЗВАННЫЕ ПРЕДЕЛЫ:
#   · ключ состояния не судится: формы у него нет (имя файла собирается строкой), признак не заведён;
#   · имя без подчёркивания не судится (`REPO`, `HOME`) — короткие имена сплошь локальные;
#   · коммит переименования старше 600 с хук не судит: последний коммит уже не читает имя. Момент — правка;
#   · на пути команды подача идёт после записи и в очереди диспетчера (потолок вызовов на событие),
#     поэтому подсказка может прийти следующим событием Bash;
#   · транзитивный потребитель (задаёт имя и зовёт драйвер, который зовёт файл) не виден: у `CLAUDSOUL_ROOT`
#     его задают 81 файл, а `paths-lib` прямо называют 20 (скептик, L6);
#   · «было» — коммит, а рабочая копия общая: незакоммиченное снятие соседней сессии приписывается текущей
#     правке (род D1004 диспетчера; скептик, L8).
#
# Input  (stdin): {tool_name, tool_input:{file_path, content|old_string,new_string|edits}, session_id}
# Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} либо пусто
# Exit:  always 0 (degrade gracefully).
set -uo pipefail
PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
NC_PY="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/name_consumers.py"
[ -f "$PATHS_LIB" ] && [ -f "$NC_PY" ] || exit 0
command -v python3 >/dev/null 2>&1 && command -v jq >/dev/null 2>&1 || exit 0
. "$PATHS_LIB" 2>/dev/null
export STATE_DIR="${STATE_DIR:-$HOME/.claude/hooks/state}"
INPUT=$(cat); [ -n "$INPUT" ] || exit 0
# Неразборный вход — не «не код»: путь, не извлечённый `jq`, иначе читался бы как «судить нечего» (род B).
FP=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null) || {
    jq -cn '{hookSpecificOutput: {hookEventName: "PreToolUse", additionalContext: "⚠️ name-consumer-notice: вход хука не разобран — потребители снятых переменных НЕ ПРОВЕРЕНЫ"}}'
    exit 0; }
case "$FP" in *.sh|*.py) ;; *) exit 0 ;; esac
EVENT=$(printf '%s' "$INPUT" | jq -r '.hook_event_name // "PreToolUse"' 2>/dev/null)
MSG=$(printf '%s' "$INPUT" | python3 "$NC_PY" "$PATHS_LIB" 2>&1); RC=$?
# Сломанный разбор — не «чисто»: молчание здесь читалось бы как «потребителей нет».
[ "$RC" -eq 0 ] || MSG="⚠️ name-consumer-notice: разбор не ответил (код $RC) — потребители снятых переменных НЕ ПРОВЕРЕНЫ: ${MSG:0:300}"
[ -n "$MSG" ] || exit 0
jq -cn --arg e "$EVENT" --arg m "$MSG" '{hookSpecificOutput: {hookEventName: $e, additionalContext: $m}}'
exit 0
