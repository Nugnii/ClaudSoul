#!/usr/bin/env bash
# shared-language-lib.sh — мост L3↔L7: кандидаты в shared vocabulary из речи собеседника.
# en: bridge L3<->L7 — detect recurring interlocutor shorthand not yet in the vocabulary.
#
# ПРЕФИКСЫ: shlang_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
#
# Проект моста (пункт 2): на Stop выявлять shorthand — устойчивые термины собеседника,
# которых ещё нет в словаре проекта. Выявлять, НЕ записывать: словарь курируется
# осмысленно, детектор только предлагает (уровень 2, инжект-напоминание).
#
# Сигнал синтаксический, не частотно-языковой — урок v1.13.3 (придуманный словарь:
# 9 срабатываний за 214 сессий, ноль полезных). Кандидат — токен, который:
#   - состоит из латиницы/цифр/дефиса/подчёркивания/слэша (идентификаторы, команды,
#     составные вроде blocker-tier, /compile, co-cognition);
#   - длиной ≥ 4, содержит букву, не URL-обломок;
#   - употреблён СОБЕСЕДНИКОМ ≥ N раз за сессию (default 3, проект моста);
#   - отсутствует в shared-vocabulary.md проекта.
# ponytail: кириллические термины («растяжка», «гейт») этот уровень не ловит —
# граница слова в кириллице требует pad_words-подхода; расширять, когда данные
# покажут, что латинских кандидатов мало.
#
# Служебные «user»-сообщения (уведомления задач, тела скиллов, сводка сжатия, ветка
# субагента) — не речь собеседника и отбрасываются до токенизации, иначе детектор тонет в
# их латинице. Роль решается ПОЛЯМИ харнесса, а не формой текста (D356, корень R3);
# конверты харнесса внутри речи вырезаются спаном — см. `shlang_user_text`.

# shlang_vocab_path <cwd> — путь словаря проекта в памяти.
# Кодировка каталога памяти: '/' и пробел → '-' (как ~/.claude/projects/).
shlang_vocab_path() {
    local cwd="${1:-}"
    [ -n "$cwd" ] || return 0
    printf '%s/.claude/projects/%s/memory/shared-vocabulary.md\n' \
        "$HOME" "$(printf '%s' "$cwd" | tr '/ ' '--')"
}

# shlang_user_text <transcript.jsonl> — только живая речь собеседника, по строке
# на сообщение (внутренние переводы строк схлопнуты в пробел).
shlang_user_text() {
    local t="${1:-}"
    [ -f "$t" ] || return 0
    command -v jq >/dev/null 2>&1 || return 0
    jq -rR '
        fromjson? // empty
        | select((.message.role // .role // "") == "user")
        # Вставки харнесса — тела скиллов, справка инструментов, уведомления задач, сводка
        # после сжатия контекста — под ролью "user" лежат наравне с речью. РОЛЬ решается
        # полями, которые ставит сам харнесс, а не формой текста (D356, корень R3; до
        # 12 сентября 2026 половину отсева нёс текстовый список маркеров, и в кандидаты
        # попадали «workflow», «const», «when», «phase» — лексика справки, а не словарь
        # собеседника). Замер по 60 расшифровкам проекта: тела скиллов и справка несут
        # `isMeta` (52 из 52 скиллов), уведомления фоновых задач — `origin.kind ==
        # "task-notification"` (146 из 146), сводка сжатия — `isCompactSummary` (19 из 19),
        # ветка субагента — `isSidechain`. Речь собеседника: `origin.kind == "human"` либо
        # поля нет вовсе (старый клиент, 5 записей из 635) — такие остаются речью.
        | select((.isMeta // false) | not)
        | select((.isCompactSummary // false) | not)
        | select((.isSidechain // false) | not)
        | select((.origin.kind // "human") == "human")
        | (.message.content // .content // [])
        | if type == "array" then (map(select(.type == "text") | .text) | join(" "))
          elif type == "string" then .
          else "" end
        | gsub("[\\n\\t]"; " ")
        # Конверты харнесса ВНУТРИ речи — открытый файл, выделение в редакторе, эхо
        # slash-команды, напоминание — полей роли не имеют (`origin.kind` у них "human").
        # Вырезается СПАН конверта, а не вся запись: за `<ide_selection>` идёт реплика
        # собеседника, и прежний `grep -v` терял бы её целиком; `<command-args>` — слова
        # собеседника, у них снимаются только теги. Именованный предел: новый конверт
        # харнесса до внесения сюда читается как речь — показание пункта D356 считает
        # такие строки по зачину `^<[a-z_-]+>`.
        | gsub("<(?<t>ide_opened_file|ide_selection|command-message|command-name|local-command-stdout|local-command-caveat|system-reminder|task-notification)>.*?</\\k<t>>"; "")
        | gsub("</?command-args>"; "")
        | gsub("^[[:space:]]+|[[:space:]]+$"; "")
        | select(length > 0)
    ' "$t" 2>/dev/null || true
}

# shlang_candidates <transcript.jsonl> <vocab_file> [min_count] — до 5 кандидатов,
# строки вида «token ×N», по убыванию N. Пустой вывод = кандидатов нет.
shlang_candidates() {
    local t="${1:-}" vocab="${2:-}" min="${3:-3}"
    [ -f "$t" ] || return 0
    local vocab_lc=""
    if [ -n "$vocab" ] && [ -f "$vocab" ]; then
        vocab_lc=$(tr 'A-Z' 'a-z' < "$vocab")
    fi
    shlang_user_text "$t" \
    | sed 's|https\{0,1\}://[^ ]*| |g' \
    | tr -c 'A-Za-z0-9_/\-' ' ' \
    | tr ' ' '\n' \
    | tr 'A-Z' 'a-z' \
    | awk 'length($0) >= 4 && $0 ~ /[a-z]/ && $0 !~ /^[0-9\/_-]+$/' \
    | sort | uniq -c | sort -rn \
    | while read -r n tok; do
        [ "$n" -ge "$min" ] 2>/dev/null || break
        # расширения файлов — не термины (ограниченный список по правилу, не по вкусу:
        # это суффиксы путей, а не слова речи)
        case "$tok" in *.md|*.sh|*.py|*.json|*.txt|md|json|txt) continue ;; esac
        if [ -n "$vocab_lc" ] && grep -Fq -- "$tok" <<< "$vocab_lc"; then
            continue
        fi
        printf '%s ×%s\n' "$tok" "$n"
    # `|| true` держит ОБА ранних выхода конвейера: head после 5 строк и break на
    # пороге min (строка 70) шлют SIGPIPE вверх (sort/производителю), и под pipefail
    # вызывающего с set -e статус 141 убил бы его (D239)
    done | head -5 || true
}
