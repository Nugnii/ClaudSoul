#!/usr/bin/env bash
# mcp-orphan-reap.sh — SessionEnd: осиротевший сервер MCP снимается по признаку сиротства.
# Живой сервер идущей сессии не трогается никогда: на SessionEnd его родитель ещё жив.
# en: SessionEnd reaper for orphaned stdio MCP servers (parent claude gone).
#
# Результат (состояние мира): число процессов `mcp-server/server.py` не превышает числа
# живых процессов-владельцев, и разница называется одной строкой.
#
# ПРИЗНАК СИРОТСТВА — почему именно он, и почему не возраст (повод: D327).
#
# Сервер MCP разговаривает с сессией по stdio: труба принадлежит тому процессу `claude`,
# который его породил, и другого собеседника у сервера нет и быть не может. Пока родитель
# жив, труба жива и сервер нужен — сколько бы часов ни шла беседа. Когда родитель умирает,
# ядро переставляет сироту под launchd: `ppid` становится 1, труба закрыта навсегда, а
# процесс продолжает висеть. Это и есть признак: РОДИТЕЛЬ МЁРТВ, наблюдаемо одной колонкой
# `ps -o ppid=`.
#
# Чем он отличается от запрещённых:
#   · не возраст. Сирота бывает минутой от роду, а живой сервер — сутками (замер 6 сентября
#     2026: четыре сервера возрастом 11 ч … 1 сут 4 ч, и у ВСЕХ ЧЕТЫРЁХ родитель жив).
#     Убийство по возрасту сняло бы сервер идущей двенадцатичасовой беседы.
#   · не наличие файла (D298: список живых определялся каталогом `active/`, а не признаком
#     жизни). Здесь не спрашивается «лежит ли запись в реестре» — спрашивается «существует
#     ли процесс». Реестр может отстать, соврать и содержать фикстуры; ядро — нет.
#
# ЧТО ЭТОТ ПРИЗНАК НЕ ЛОВИТ, и это названо вслух. Замер 6 сентября 2026: серверов 4, сирот
# 0. Копятся не осиротевшие серверы, а сами процессы `claude`: расширение VS Code держит
# их после того, как разговор кончился (две из четырёх бесед последний раз говорили за 12 и
# 22 часа до замера). Их сервер сиротой НЕ является — родитель жив, труба цела, беседу можно
# продолжить. Отличить такой процесс от идущей долгой сессии нечем, кроме возраста, а возраст
# запрещён поводом. Поэтому: сироты снимаются, лишние живые называются числом и оставляются.
#
# ponytail: SIGTERM без добивания SIGKILL. Потолок: сервер, не умерший по TERM, доживёт до
# следующего SessionEnd и будет назван снова. Добивание — когда счётчик «сирот» перестанет
# опускаться до нуля между прогонами.

set -uo pipefail

# Признак носителя. Вынесен в переменную, чтобы прибор можно было навести на копию дерева;
# по умолчанию — путь, которым Claude Code запускает сервер.
PATTERN="${MCP_REAP_PATTERN:-mcp-server/server.py}"

DRY=0
for a in "$@"; do
    case "$a" in
        --dry-run|--report) DRY=1 ;;
        *) echo "usage: $0 [--dry-run]" >&2; exit 2 ;;
    esac
done

# stdin НЕ ЧИТАЕТСЯ вовсе, и это решение, а не упущение. SessionEnd подаёт JSON, но признак
# берётся из ядра, а не из полезной нагрузки. Осушение трубы по условию «не терминал»
# (`[ -t 0 ] || cat`) — известный класс зависания: «не tty» не значит «данные придут», и на
# открытой незакрытой трубе раннера `cat` висит вечно, маскируясь под работу
# (case-2026-07-25-stdin-tty-heuristic-hangs-runner). Непрочитанный stdin стоит вызывающему
# EPIPE на мёртвого потомка, то есть ничего.

# Отказ чтения считается и называется, а не гасится нулём (род дефекта B). Пустая таблица
# процессов законно пустой не бывает — в ней всегда есть хотя бы pid 1, — поэтому пустота
# здесь означает «прибор не посмотрел», и это обязано быть отличимо от «сирот нет».
# Запасной ветки нет намеренно: без библиотеки хук упадёт с «command not found», а не
# досчитает молча по-своему.
for _unread_lib in "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/unread-lib.sh" \
                   "$HOME/.claude/hooks/lib/unread-lib.sh"; do
    [ -f "$_unread_lib" ] && { . "$_unread_lib"; break; }
done

# `-ww` — против усечения строки запуска по ширине терминала в GNU ps: усечённый argv
# прячет признак носителя и даёт ложное «сирот нет».
PSTABLE=$(ps -ww -eo pid=,ppid=,args= 2>/dev/null)
if ! unread_or PSTABLE "" "таблица процессов (ps)"; then
    printf 'НЕ ИЗМЕРЕНО: %s\n' "$(unread_note)"
    [ "$DRY" -eq 1 ] && exit 2
    exit 0
fi

TOTAL=0
ORPHANS=0
REAPED=0
OWNERS=""

# Одна выборка на весь прогон: pid, ppid и полная строка запуска.
while read -r pid ppid rest; do
    case "$rest" in
        *"$PATTERN"*) ;;
        *) continue ;;
    esac
    case "$pid" in ''|*[!0-9]*) continue ;; esac
    TOTAL=$((TOTAL + 1))
    if [ "$ppid" = "1" ]; then
        ORPHANS=$((ORPHANS + 1))
        if [ "$DRY" -eq 0 ]; then
            kill -TERM "$pid" 2>/dev/null && REAPED=$((REAPED + 1))
        fi
    else
        OWNERS="$OWNERS $ppid"
    fi
done <<< "$PSTABLE"

LIVE=0
for o in $OWNERS; do LIVE=$((LIVE + 1)); done
# Владельцы считаются различными: один claude держит один сервер, но если появится второй,
# счёт владельцев не должен раздуваться.
if [ -n "$OWNERS" ]; then
    LIVE=$(printf '%s\n' $OWNERS | sort -u | wc -l | tr -d ' ')
fi

# Разница называется всегда в сухом прогоне (там прибор и спрашивают) и только при находке
# в режиме хука: молчаливая правильная уборка — не повод для строки в конце каждой сессии.
if [ "$DRY" -eq 1 ] || [ "$ORPHANS" -gt 0 ]; then
    printf 'серверов MCP: %s, живых владельцев: %s, сирот: %s, снято: %s\n' \
        "$TOTAL" "$LIVE" "$ORPHANS" "$REAPED"
fi

# Код возврата. В сухом прогоне прибор обязан уметь покраснеть — иначе «сирот нет»
# становится свойством прибора, а не мира (pattern-detector-wired-to-failure).
# В режиме хука — всегда 0: ненулевой код на SessionEnd показывается собеседнику как ошибка,
# а уборка не повод для тревоги.
if [ "$DRY" -eq 1 ] && [ "$ORPHANS" -gt 0 ]; then exit 1; fi
exit 0
