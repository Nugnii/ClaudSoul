        # и обрезок с открытой `"` съедал вид. Названные пределы — общие со `scan` и читателем: `${x//(/y}` и обратные
        # кавычки внутри `$(…)` сдвигают счёт скобок, склейка `\` даёт ложный отказ и на строке. Вложенный heredoc внутри
        # `$(…)` тела судится кодом целиком — ложный отказ на его данных; ветка «тело — данные» (D1064) откатана (D1066):
        # перечень форм `<<` (кавычки у метки, `((…))`, `$[…]`, комментарий, табы внешнего `<<-`) дал десять пропусков
        # против двух ложных отказов. Условие снятия: замер назовёт команду корпуса с ними.
        function semit(last, ok,    k) {
            if (ok) { for (k = 1; k <= Sk; k++) print SP[k]; print last }
            Sk = 0
        }
        function subs(line,    sc, n, i, c, st, prev) {
            n = split(line, sc, ""); st = 1; prev = ""
            for (i = 1; i <= n; i++) {
                c = sc[i]
                if (Sd == 0 && !Sbt) {
                    if (c == "\\") i++
                    else if (c == "`") { Sbt = 1; Sq = 0; Sk = 0; Ss = 0; st = i + 1 }
                    else if (c == "$" && i < n && sc[i + 1] == "(" && !(i + 1 < n && sc[i + 2] == "(")) { Sd = 1; Sq = 0; Sk = 0; Ss = 0; st = i + 2; i++ }
                    continue
                }
                if (Sbt && c == "`") { semit(substr(line, st, i - st), Sq == 0); Sbt = 0; continue }
                if (Sq == 1) { if (Sa && c == "\\") i++; else if (c == "\047") Sq = 0; prev = c; continue }
                if (c == "\\") { i++; prev = "w"; continue }
                if (Sq == 2) {
                    if (c == "\"") Sq = 0
                    else if (c == "(" && prev == "$" && !Sbt) { SS[++Ss] = Sd++; Sq = 0 }
                    prev = c; continue
                }
                if (c == "\047") { Sq = 1; Sa = (prev == "$"); prev = c; continue }
                if (c == "\"") { Sq = 2; prev = c; continue }
                prev = c
                if (Sbt) continue
                if (c == "(") Sd++
                else if (c == ")") {
                    if (Ss > 0 && --Sd == SS[Ss]) { Ss--; Sq = 2 }
                    else if (Ss == 0 && --Sd == 0) semit(substr(line, st, i - st), 1)
                }
            }
            if (Sd > 0 || Sbt) SP[++Sk] = substr(line, st)
        }
        # Чьё тело читается следующим. Метки — две очереди (четвёртый круг D1042): внутренние (`IL`, метка в
        # многострочной области обратных кавычек) — сразу, их тело лежит внутри области; внешние (`OL`) — после строки,
        # на которой область закрылась, как у bash. Одна очередь в порядке строки задерживала тело внутренней метки,
        # стоящей после внешней (``cat << 2 `cat <<EOF⏎…``, регресс фазза), и ставила тело внешней на строку области.
        # Внутренняя метка ставится только при открытой на конце строки области, поэтому при `XC == 0` внутренних нет.
        function nextq() {
            if (IH <= IT) return IL[IH++]
            if (!XC && OH <= OT) return OL[OH++]
            if (IH > IT && OH > OT) { QN = IT = OT = 0; IH = OH = 1 }
            return 0
        }
        BEGIN { IH = OH = 1 }
        cur > 0 {
            t = $0; if (QD[cur]) sub(/^\t+/, "", t)
            if (t == QM[cur]) {
                # Подстановка, не закрытая до конца тела, печатается, только если её кавычки парны.
                if (Sd > 0 || Sbt) semit("", Sq == 0 && !Sbt)
                Sd = 0; Sbt = 0; Sq = 0; Ss = 0
                cur = nextq()
            }
            else if (body) print
            else if (!QQ[cur]) subs($0)
            next
        }
        # Тело внешнего heredoc начинается после строки, на которой закрылась многострочная область обратных кавычек
        # (L1 четвёртого круга D1042: прежде — со следующей за меткой, и строка области читалась телом, а перенос `XC`
        # переживал тело); метка внутри области — её тело идёт сразу (`nextq`).
        # НАЗВАННЫЙ ПРЕДЕЛ (L3 скептика 2693e19c): многострочные `"…"`, `'…'`, `$(…)` на строке метки — bash читает тело
        # после строки, где они закрылись, а вид — со следующей (`H <<E; echo "a⏎$(x)"⏎…`: `$(x)` вид прячет телом);
        # так у всех редакций. Условие снятия — отсрочка тела по любой многострочной области, а не только по `XC`.
        { LN++; split("", PR); keep(); scan($0, 1); back(); scan($0, 2); if (!body) print; cur = nextq() }
    '
}

# ds_heredoc_writes — ЕДИНСТВЕННЫЙ владелец разбора «куда пишет heredoc» (D366, 12 сентября
# 2026). Команда оболочки на stdin; на stdout — записи протокола: `T<TAB>цель` (строка на
# каждую цель heredoc), затем строки тела с ведущим `|`, затем `E`. Heredoc без цели
# (`python3 - <<'PY'`) записью файла не является и не печатается вовсе. Потребители:
# предикат `heredoc_target_regex` в ds_evaluate_node (берёт только строки `T`) и
# `scripts/signal-precision-corpus.py` (цель и тело — синтетический Write). До этого у
# корпуса была СВОЯ регулярка, и две реализации расходились в 1356 случаях из 1357: прибор
# корпуса видел записи, живой движок — цель у одной. Правила разбора (цель до маркера — та же
# команда; за разделителем — чужая; труба не рвёт поток; тело чужого heredoc — текст) и их
# поводы записаны у предиката ниже; здесь только устройство.
#
# ЗАПИСЬ БЫВАЕТ ДВУХ УСТРОЙСТВ, и до 15 сентября 2026 печаталось одно (D415). Первое — цель
# стоит в командной строке (`> файл`, `tee файл`). Второе — телом кормится ПИТОН, цель у
# heredoc отсутствует, а файл пишется изнутри программы. Прежняя шапка объявляла второе
# «не записью», и предикат молчал на нём по построению: из 3715 таких команд корпуса,
# поминающих hooks|scripts, он видел 0. Молчание при состоявшейся записи неотличимо от
# молчания на чистой команде — корень R6, и на этом предикате стоят два признака уровня
# отказа.
# Названный предел (брат корня D1039, 24 октября 2026): метка с прилипшим разделителем
# (`cat > a <<A; cat > b <<B`) читается вместе с `;` и тела не закрывает — хвост команды
# уходит в тело. В корпусе 65 042 команд такая форма у 10, тело записи не закрыто ни у одной.
# Условие снятия: замер назовёт команду, где тело записи осталось незакрытым.
ds_heredoc_writes() {
    # LC_ALL=C — разбор ПОБАЙТОВЫЙ, как и у соседнего предиката. Тело heredoc разбирается
    # посимвольно с 15 сентября 2026, а входом бывает произвольная команда из мира: на
    # негодной многобайтной последовательности awk в UTF-8-локали умирает кодом 2
    # (`towc: multibyte conversion failure`), и предикат получает ПУСТО — «сломался»
    # становится неотличимо от «целей нет». Поймано на себе в час правки: старый разбор
    # отвечал 0, новый 2. Сравнения здесь все ASCII, побайтовый режим их не меняет.
    LC_ALL=C awk '
        # У токена две стороны, и путать их нельзя: TOK — весь текст со снятыми кавычками (годится
        # в ОПЕРАНДЫ), TU — только та часть, что стояла ВНЕ кавычек (единственное, что может быть
        # СИНТАКСИСОМ). маркер в кавычках несёт синтаксис снаружи, а имя внутри; строка-аргумент
        # не несёт синтаксиса вовсе. \047 и \042 — коды кавычек: кавычка, написанная собой,
        # зависит от способа создания файла, и на этом стенд уже соврал.
        function tokenize(line,   i, c, q, tok, unq, has, n) {
            n = 0; tok = ""; unq = ""; q = ""; has = 0
            for (i = 1; i <= length(line); i++) {
                c = substr(line, i, 1)
                if (q != "") { if (c == q) q = ""; else tok = tok c; has = 1; continue }
                if (c == "\042" || c == "\047") { q = c; has = 1; continue }
                if (c == " " || c == "\t") {
                    if (has || tok != "") { n++; TOK[n] = tok; TU[n] = unq; tok = ""; unq = ""; has = 0 }
                    continue
                }
                tok = tok c; unq = unq c
            }
            if (has || tok != "") { n++; TOK[n] = tok; TU[n] = unq }
            return n
        }
        # Труба НЕ разрывает поток: `cat <<EOF | tee hooks/a.sh` кладёт тело heredoc именно в
        # hooks/a.sh, только через посредника. Разрывают поток `;`, `;;`, `&&`, `||`, `&` — после
        # них стоит другая команда, и её перенаправление к этому телу отношения не имеет.
        function is_break(i) { return (TU[i] == TOK[i] && (TU[i] == "&&" || TU[i] == "||" || TU[i] == ";" || TU[i] == ";;" || TU[i] == "&")) }
        function target_of(a, b,   u) {
            u = TU[a]
            if (u == ">" || u == ">>" || u == ">|") { if (a < b) return TOK[a+1]; return "" }
            if (u ~ /^>\|./)     { u = TOK[a]; sub(/^>\|/, "", u); return u }
            if (u ~ /^>>?[^>|]/) { u = TOK[a]; sub(/^>>?/, "", u); return u }
            return ""
        }
        # ПУТЬ, ЛЕЖАЩИЙ В ТЕЛЕ. Берётся ТОЛЬКО из аргумента вызова записи, а не из любого
        # упоминания: замер корпуса 15 сентября 2026 — вызов записи несут 3382 команды из
        # 3715, а ПОМИНАЮТ путь, в который не пишут, 2372. Правило «любой литерал тела» дало
        # бы столько же ложных целей, а ложный отказ хуже пропуска: его начинают обходить не
        # думая. Разрешается литерал в самом вызове (98 случаев) и ОДНОШАГОВАЯ переменная
        # (3000); склейка (os.path.join, f-строка) не разрешается — названный предел, 284.
        function py_lit(s,   c, i, q, out) {
            q = substr(s, 1, 1)
            if (q != "\042" && q != "\047") return ""
            out = ""
            for (i = 2; i <= length(s); i++) {
                c = substr(s, i, 1)
                if (c == q) return out
                out = out c
            }
            return ""
        }
        function py_trim(s) { sub(/^[ \t]+/, "", s); sub(/[ \t]+$/, "", s); return s }
        # Режим ОТКРЫТИЯ, а не любая строка второго аргумента: `encoding="ascii"` несёт `a`, и
        # без этой проверки чтение файла считалось бы записью.
        function py_mode(s,   i, c) {
            if (s == "") return 0
            for (i = 1; i <= length(s); i++) {
                c = substr(s, i, 1)
                if (index("rwaxbt+U", c) == 0) return 0
            }
            return (index(s, "w") > 0 || index(s, "a") > 0 || index(s, "x") > 0)
        }
        function py_path(arg) {
            arg = py_trim(arg)
            if (substr(arg, 1, 1) == "\042" || substr(arg, 1, 1) == "\047") return py_lit(arg)
            if (arg ~ /^[A-Za-z_][A-Za-z0-9_]*$/ && (arg in ASG)) return ASG[arg]
            return ""
        }
        function py_emit(t) { if (t != "" && !(t in SEEN)) { SEEN[t] = 1; PT[++np] = t } }
        function py_asg(line,   p, nm, rest) {
            p = index(line, "=")
            if (p < 2) return
            nm = py_trim(substr(line, 1, p - 1))
            if (nm !~ /^[A-Za-z_][A-Za-z0-9_]*$/) return
            rest = py_trim(substr(line, p + 1))
            sub(/^pathlib\.Path\([ \t]*/, "", rest)
            sub(/^Path\([ \t]*/, "", rest)
            if (substr(rest, 1, 1) == "\042" || substr(rest, 1, 1) == "\047") ASG[nm] = py_lit(rest)
        }
        # Получатель вызова записи: `p.write_text(...)` либо `Path("путь").write_text(...)`.
        function py_recv(line, meth,   pos, head, i, c, nm) {
            while ((pos = index(line, meth)) > 0) {
                head = substr(line, 1, pos - 1)
                if (substr(head, length(head), 1) == ")") {
                    i = index(head, "(")
                    if (i > 0) py_emit(py_path(substr(head, i + 1, length(head) - i - 1)))
                } else {
                    nm = ""
                    for (i = length(head); i >= 1; i--) {
                        c = substr(head, i, 1)
                        if (c ~ /[A-Za-z0-9_]/) nm = c nm; else break
                    }
                    if (nm != "") py_emit(py_path(nm))
                }
                line = substr(line, pos + length(meth))
            }
        }
        # `close` — встроенное имя awk, параметром его звать нельзя: mawk и gawk падают
        # разбором функции, а не вызовом, то есть молча для всего предиката.
        function py_scan(line,   pos, rest, cl, cm, a1, a2) {
            rest = line
            while ((pos = index(rest, "open(")) > 0) {
                rest = substr(rest, pos + 5)
                cl = index(rest, ")")
                if (cl > 0) a1 = substr(rest, 1, cl - 1); else a1 = rest
                cm = index(a1, ",")
                if (cm > 0) {
                    a2 = substr(a1, cm + 1)
                    a1 = substr(a1, 1, cm - 1)
                    sub(/^[ \t]*mode[ \t]*=[ \t]*/, "", a2)
                    cm = index(a2, ",")
                    if (cm > 0) a2 = substr(a2, 1, cm - 1)
                    if (py_mode(py_lit(py_trim(a2)))) py_emit(py_path(a1))
                }
            }
            py_recv(line, ".write_text(")
            py_recv(line, ".write_bytes(")
        }
        { LINES[++NL] = $0 }
        END {
            inside = 0
            for (li = 1; li <= NL; li++) {
                line = LINES[li]
                if (inside) {
                    probe = line
                    if (dash) sub(/^\t+/, "", probe)
                    if (probe == mark) {
                        # Тело питона разбирается ЦЕЛИКОМ и только на закрытии: присваивание
                        # пути стоит выше вызова записи, и однопроходный разбор его не увидит.
                        if (buf) {
                            for (bi = 1; bi <= nb; bi++) py_asg(B[bi])
                            for (bi = 1; bi <= nb; bi++) py_scan(B[bi])
                            if (np > 0) {
                                for (bi = 1; bi <= np; bi++) print "T\t" PT[bi]
                                for (bi = 1; bi <= nb; bi++) print "|" B[bi]
                                print "E"
                            }
                        } else if (rec) print "E"
                        inside = 0; rec = 0; buf = 0; continue
                    }
                    if (rec) print "|" probe
                    else if (buf) B[++nb] = probe
                    continue
                }
                n = tokenize(line)
                seg_start = 1
                for (i = 1; i <= n; i++) {
                    if (is_break(i)) { seg_start = i + 1; continue }
                    if (TU[i] !~ /^<<[^<]/ && TU[i] !~ /^<<$/) continue
                    m = TOK[i]
                    dash = (TU[i] ~ /^<<-/) ? 1 : 0
                    sub(/^<<-?/, "", m); gsub(/\\/, "", m)
                    if (m !~ /^[A-Za-z_]/) continue
                    mark = m; inside = 1; rec = 0; buf = 0
                    seg_end = n
                    for (j = i + 1; j <= n; j++) if (is_break(j)) { seg_end = j - 1; break }
                    for (j = seg_start; j <= seg_end; j++) {
                        if (TU[j] == "tee" ) {
                            for (k = j + 1; k <= seg_end; k++) if (TU[k] !~ /^-/) { print "T\t" TOK[k]; rec = 1; break }
                            continue
                        }
                        t = target_of(j, seg_end)
                        if (t != "") { print "T\t" t; rec = 1 }
                    }
                    # Цели в командной строке нет — телом может кормиться питон, и тогда путь
                    # лежит внутри программы. Перенаправление, если оно было, имеет приоритет:
                    # `python3 - <<PY > hooks/gen.sh` пишет именно туда.
                    if (!rec) {
                        for (j = seg_start; j <= seg_end; j++) if (TU[j] ~ /^python[0-9.]*$/) buf = 1
                        if (buf) { nb = 0; np = 0; split("", ASG); split("", SEEN) }
                    }
                    break
                }
            }
        }
    '
}

# Производные виды входа — один раз на вход (D506). Листья сигнала пересчитывали свою
# цепочку видов (jq на `.command`, `ds_shell_only` → `ds_code_only` → `ds_unquoted_command`)
# на КАЖДОМ листе: у паттерна переносимости около восьмидесяти листьев и 54 запуска awk на
# вызов. Вид — функция одного лишь входа, поэтому значение живёт, пока вход тот же, и
# считается ПРЕЖНИМ выражением дословно — меняется только число вычислений. Ответ — в _DS_V.
# Память пишется в текущей оболочке: звать `_ds_view` напрямую, не через $(...), иначе запись
# уйдёт вместе с подоболочкой (читать из подоболочки законно — она наследует).
_ds_view() {
    local kind="$1" ti="$2" v
    if [ -z "${_DSV_TI+set}" ] || [ "$_DSV_TI" != "$ti" ]; then
        _DSV_TI="$ti"
        unset _DSV_cmd _DSV_shell _DSV_full _DSV_unq_code_cmd _DSV_live _DSV_code_ti_raw _DSV_code_ti \
              _DSV_targets _DSV_hbody_raw _DSV_hbody_code _DSV_fpath
    fi
    eval "v=\${_DSV_$kind+set}"
    if [ -n "$v" ]; then eval "_DS_V=\$_DSV_$kind"; return 0; fi
    case "$kind" in
        cmd)          v=$(printf '%s' "$ti" | jq -r '.command // empty' 2>/dev/null) ;;
        shell)        _ds_view cmd "$ti"; v=$(ds_shell_only "$_DS_V") ;;
        # Комментарии снимает сам ds_unquoted_command, с состоянием кавычек. Прежний шаг ds_code_only
        # перед ним резал `" #…` и `⏎#…` и внутри строки — `'echo "x" # заметка'` терял кавычку,
        # и разбор со сдвигом обнажал закавыченное (ложный отказ на корпусе, вторая редакция D1015).
        full)         _ds_view shell "$ti"; v=$(ds_unquoted_command "$_DS_V") ;;
        unq_code_cmd) _ds_view cmd "$ti"; v=$(ds_unquoted_command "$_DS_V" "" raw) ;;
        live)         _ds_view shell "$ti"; v=$(ds_unquoted_command "$_DS_V" keepdq) ;;
        # Вывод ds_code_only как есть, с завершающими переводами строки (для трубы в grep),
        # и он же без них (для подстановки) — из одного запуска.
        code_ti_raw)  v=$(ds_code_only "$ti"; printf x); v="${v%x}" ;;
        code_ti)      _ds_view code_ti_raw "$ti"; v="$_DS_V"
                      while [ "${v%$'\n'}" != "$v" ]; do v="${v%$'\n'}"; done ;;
        targets)      _ds_view cmd "$ti"; v=$(printf '%s\n' "$_DS_V" \
                          | ds_heredoc_writes | awk -F'\t' '$1 == "T" { print $2 }') ;;
        hbody_raw)    _ds_view cmd "$ti"; v=$(ds_shell_only "$_DS_V" body) ;;
        hbody_code)   _ds_view hbody_raw "$ti"; v=$(ds_code_only "$_DS_V") ;;
        fpath)        v=$(printf '%s' "$ti" | jq -r '.file_path // empty' 2>/dev/null) ;;
        *)            v="" ;;
    esac
    eval "_DSV_$kind=\$v"
    _DS_V="$v"
}

