# Дерево сигналов → плоский поток лексем, ОДНИМ jq на дерево (D509). Прежний обход звал jq на
# каждый узел — ключ, длина состава, извлечение ребёнка, значение листа: 234 запуска на обычный
# вызов Bash, около 0,7 с стража. Теперь обход (_ds_walk) идёт по массиву без процессов, а
# процесс остаётся у листа, которому нужен grep, и только если до листа дошла оценка.
# Поток в прямом порядке, лексема на строку: обратная косая и перевод строки внутри неё
# экранированы (`\\`, `\n`) и раскрываются встроенным `printf -v '%b'`. Узел — одно из:
#   C <состав> <число детей> <дети…>   all_of / any_of / none_of над массивом;
#   L <ключ> <значение>                лист;
#   T | F                              узел, решённый здесь же: tool_matches (имя инструмента
#                                      известно заранее) и вырожденные узлы.
# Сигнал — S <имя> <узел>. Вырожденные узлы решаются так же, как решал прежний обход:
# не-объект и пустой объект — F; состав не над массивом — F, кроме none_of с ненулевой длиной
# (прежний пропускал неизвлекаемых детей и отвечал «исключений нет»).
# Значение и имя — РОВНО то, что давала прежняя подстановка $(jq -r …) (раунд противника D509):
# строка как есть, массив и объект — с отступами, как печатает `jq -r` (`pp`), байт NUL вырезан,
# как вырезала подстановка, хвостовые переводы строки сняты. Вход — значения, разобранные ДО
# первой ошибки разбора (`[try inputs]`), и годен, только если такое значение одно: так читал
# прежний `jq -c .` — хвост-мусор после документа отбрасывался, а два документа подряд роняли
# обход и он молчал (раунды противника D509: первая редакция требовала «ровно один документ
# целиком» и выключала блок с лишней скобкой в конце, который прежняя исполняла и который
# `ds_extract_signals` этой же библиотеки видит).
# Подстановки процесса `< <(…)` здесь нет намеренно: bash 3.2 в режиме POSIX её не разбирает,
# и библиотека не загрузилась бы вовсе — страж онемел бы без следа (раунд 2 противника).
_DS_COMPILE_JQ='
def pp($i): if type == "object" then
      (if length == 0 then "{}" else "{\n" + ([to_entries[] | $i + "  " + (.key | tojson) + ": "
        + (.value | pp($i + "  "))] | join(",\n")) + "\n" + $i + "}" end)
    elif type == "array" then
      (if length == 0 then "[]" else "[\n" + ([.[] | $i + "  " + pp($i + "  ")] | join(",\n"))
        + "\n" + $i + "]" end)
    else tojson end;
def r: (if type == "string" then . elif type == "array" or type == "object" then pp("")
        else tostring end) | gsub("\u0000"; "") | sub("\n+\\z"; "");
def node:
  if type != "object" or length == 0 then ["F"]
  else keys_unsorted[0] as $k | .[$k] as $v
    | if $k == "all_of" or $k == "any_of" or $k == "none_of" then
        if ($v | type) == "array" then ["C", $k, ($v | length | tostring)] + ([$v[] | node] | add // [])
        elif $k == "none_of" and ((try ($v | length) catch 0) > 0) then ["T"]
        else ["F"] end
      elif $k == "tool_matches" then
        if (try ($v | index($t) != null) catch false) then ["T"] else ["F"] end
      else ["L", $k, ($v | r)] end
  end;
def sig: . as $s
  | if type != "object" then ["S", "", "F"]
    else ["S", ((.name // "") | r)]
       + ((first(("all_of", "any_of", "none_of") | select(. as $o | $s | has($o))) as $op
           | {($op): $s[$op]} | node) // ["F"])
    end;
[try inputs] | if length != 1 then empty else .[0] end
| (if $m == "signals" then (if type == "array" then [.[] | sig] | add // [] else [] end)
   elif $m == "signal" then sig else node end)
| map(gsub("\u0000"; "") | gsub("\\\\"; "\\\\") | gsub("\n"; "\\n")) | join("\n")
'

# _ds_compile <signals|signal|node> <json> <инструмент> → поток в _DS_T, позиция _DS_I = 0.
_ds_compile() {
    local out tok
    _DS_T=(); _DS_I=0
    # Вход — here-string, а не труба (раунд 3 противника D509): на длинном хвосте jq бросает
    # чтение на первой ошибке разбора, `printf` в трубе получал SIGPIPE, и под pipefail статус 141
    # выбрасывал уже готовый поток. Раскрытие — только у лексемы с обратной косой: `printf -v` в
    # bash 3.2 на ПУСТОМ выводе не присваивает, и пустая лексема получала значение предыдущей.
    out=$(jq -nr --arg m "$1" --arg t "$3" "$_DS_COMPILE_JQ" <<< "$2" 2>/dev/null) || out=""
    [ -n "$out" ] || return 0
    while IFS= read -r tok; do
        case "$tok" in *\\*) printf -v tok '%b' "$tok" ;; esac
        _DS_T+=("$tok")
    done <<< "$out"
    return 0
}

# _ds_walk <оценивать 1|0> <инструмент> <вход> <промпт> — узел потока с позиции _DS_I; 0 —
# совпал. Узел за коротким замыканием читается до конца с оценкой 0: позиция встаёт на
# следующий узел, а листья его не считаются.
_ds_walk() {
    local ev="$1" t op n i r res
    t="${_DS_T[_DS_I]-}"; _DS_I=$((_DS_I + 1))
    case "$t" in
        T)  return 0 ;;
        L)  _DS_I=$((_DS_I + 2))
            [ "$ev" = 1 ] || return 1
            _ds_leaf "${_DS_T[_DS_I-2]-}" "${_DS_T[_DS_I-1]-}" "$2" "$3" "$4"
            return ;;
        C)  op="${_DS_T[_DS_I]-}"; n="${_DS_T[_DS_I+1]-0}"; _DS_I=$((_DS_I + 2))
            [ "$n" -gt 0 ] || return 1
            case "$op" in any_of) res=1 ;; *) res=0 ;; esac
            for (( i = 0; i < n; i++ )); do
                _ds_walk "$ev" "$2" "$3" "$4"; r=$?
                [ "$ev" = 1 ] || continue
                case "$op" in
                    all_of)  [ "$r" -ne 0 ] && { res=1; ev=0; } ;;
                    any_of)  [ "$r" -eq 0 ] && { res=0; ev=0; } ;;
                    none_of) [ "$r" -eq 0 ] && { res=1; ev=0; } ;;   # совпало исключение — узел ложен
                esac
            done
            return "$res" ;;
        *)  return 1 ;;
    esac
}

# Evaluate one node (either a composition or a base matcher). 0 = match, 1 = no match,
# 2 = no match and an unknown predicate was met (D1043; keys in `_DS_UNKNOWN`).
# Arguments: <node_json> <tool_name> <tool_input_json> <prompt>
ds_evaluate_node() {
    _ds_jq_available || return 1
    _DS_UNKNOWN=""
    _ds_compile node "$1" "$2"
    _ds_walk 1 "$2" "$3" "$4" && return 0
    [ -z "$_DS_UNKNOWN" ] || return 2
    return 1
}

# Лист: <ключ> <значение> <инструмент> <вход> <промпт>. 0 — совпал.
_ds_leaf() {
    local key="$1" val="$2" tool_name="$3" tool_input="$4" prompt="$5"
    case "$key" in
        file_path_regex)
            local regex file_path
            regex="$val"
            [ -z "$regex" ] && return 1
            _ds_view fpath "$tool_input"; file_path="$_DS_V"
            [ -z "$file_path" ] && return 1
            grep -qE -- "$regex" <<< "$file_path" && return 0
            return 1
            ;;
        tool_input_regex)
            local rx
            rx="$val"
            [ -z "$rx" ] && return 1
            # LC_ALL=C — сопоставление по байтам, см. пояснение в шапке.
            # here-string, а не труба: `grep -q` выходит на первом совпадении, производитель в трубе
            # получал бы SIGPIPE, и под pipefail совпадение читалось бы как «нет» (раунд 3 D509).
            # Вид без хвостового перевода строки: here-string добавит ровно один — байты те же.
            _ds_view code_ti "$tool_input"
            LC_ALL=C grep -qE -- "$rx" <<< "$_DS_V" && return 0
            return 1
            ;;
        heredoc_target_regex)
            # КУДА пишет heredoc, а не что упомянуто в команде. Область признака обязана
            # относиться к файлу, который СОЗДАЁТСЯ, — иначе она берётся оттуда, где на неё
            # удобно смотреть. Замер 28 августа 2026: отказ прилетел на запись пробника в
            # песочницу только потому, что в той же команде стоял путь запуска стража.
            # Правило было верным по букве и ложным по сути, а ложный отказ хуже пропуска:
            # его начинают обходить не думая.
            #
            # Цель ищется на строке, открывающей тело: «> файл», «>> файл», «tee файл».
            # Путь через переменную не раскрывается — сравнивается его текст, поэтому
            # «$REPO/hooks/foo.sh» совпадает с образцом дерева, а «$SP/probe.sh» нет.
            # КОНТРПРИМЕР: цель, целиком спрятанная в переменной («> "$OUT"»), не
            # опознаётся — признак промолчит, и это известно.
            # Цель ищется ТОЛЬКО в части строки ПОСЛЕ маркера heredoc. Перенаправление,
            # стоящее до маркера, к телу heredoc не относится: в
            # `git show HEAD:hooks/x.sh > /tmp/x.sh && python3 - <<'PY'` первый вывод
            # уходит во временный файл, а телом heredoc кормится python — но признак,
            # читавший строку целиком, видел путь `hooks/x.sh` и отказывал в чтении из
            # архива git. Поймано на себе 29 августа 2026, третье проявление одного рода
            # (D113): предмет признака берётся оттуда, где на него удобно смотреть.
            local trx targets
            trx="$val"
            [ -z "$trx" ] && return 1
            #
            # Перенаправление стоит и ДО маркера: `cat > hooks/x.sh <<'EOF'` — одна команда,
            # и тело heredoc уходит именно в этот файл. Правка 29 августа отрезала всё до
            # маркера целиком, потому что разбирала форму `cmd > /tmp/x.sh && python3 - <<PY`,
            # где перенаправление принадлежит ДРУГОЙ команде. Разделяет их не положение, а
            # РАЗДЕЛИТЕЛЬ команд между ними: нет разделителя — цель эта же.
            # Цена прежней редакции измерена 8 сентября 2026 по корпусу: из 1357 команд,
            # записывающих файл heredoc-ом, живой разбор находил цель у ОДНОЙ. Предикат
            # был выключен на 99,9% своего населения, а на нём стоят два признака уровня
            # отказа (bsd_gnu_token_written_into_hook_file, bsd_only_command_written_via_shell)
            # и подсказка non_ascii_adjacent_to_shell_syntax_written_via_shell.
            _ds_view targets "$tool_input"; targets="$_DS_V"
            [ -z "$targets" ] && return 1
            LC_ALL=C grep -qE -- "$trx" <<< "$targets" && return 0
            return 1
            ;;
        heredoc_body_regex)
            # Тело heredoc в команде Bash (D79). Зачем отдельный матчер, а не
            # `tool_input_regex`: у Bash `tool_input` это командная строка ЦЕЛИКОМ, и
            # регулярка, писанная под содержимое файла, горит на любом `grep` по тому же
            # образцу — ровно тот класс ложных срабатываний, что разобран в D25. Тело
            # heredoc — это то, что реально ЗАПИСЫВАЕТСЯ в файл, а не то, что ищется.
            #
            # Повод: замер 2026-08-26 — 45% правок файлов идут командами оболочки
            # (1357 против 1675 файловыми инструментами), а blocker-tier знания слушали
            # только Edit/Write, то есть на половине правок были выключены по построению.
            #
            # Тело берётся у того же разбора, что вид оболочки (`ds_shell_only … body`, вид
            # `hbody_raw`): `<<` в кавычках, `<<<` и арифметика тела не открывают, метки одной
            # строки идут очередью (D1039).
            local hrx body
            hrx="$val"
            [ -z "$hrx" ] && return 1
            _ds_view hbody_raw "$tool_input"; body="$_DS_V"
            [ -z "$body" ] && return 1
            # Комментарии из тела снимаются: строка, где запрещённая команда ПЕРЕЧИСЛЕНА
            # как запрещённая («GNU не знает date -j»), нарушением не является. Тот же
            # класс уже закрыт для содержимого правок (`ds_code_only`, D56) — здесь он
            # доехал только 29 августа 2026, после третьего ложного отказа подряд (D113).
            # НАЗВАННЫЙ ПРЕДЕЛ: строковые литералы в теле НЕ снимаются — код, записываемый
            # в файл, исполняется, и `CMD="date -j"` там настоящее использование. Поэтому
            # токен внутри кавычек-ПОДПИСИ (фикстура теста, образец в assert) по-прежнему
            # ловится; отличить подпись от вызова по тексту нельзя.
            # Условие снятия: предел держится, пока роль строки в теле определяется только
            # её текстом. Появится разбор записываемого файла по синтаксису языка — роль
            # станет наблюдаемой, и предел уйдёт вместе с угадыванием.
            _ds_view hbody_code "$tool_input"; body="$_DS_V"
            [ -z "$body" ] && return 1
            # here-string: с трубой тело больше буфера (64 КБ на macOS) и совпадением в начале давало
            # SIGPIPE производителю и «нет совпадения» под pipefail — в обеих редакциях (раунд 3 D509).
            LC_ALL=C grep -qE -- "$hrx" <<< "$body" && return 0
            return 1
            ;;
        file_size_min_lines)
            local threshold file_path line_count
            threshold="$val"
            [ -z "$threshold" ] && return 1
            _ds_view fpath "$tool_input"; file_path="$_DS_V"
            if [ -n "$file_path" ] && [ -f "$file_path" ]; then
                line_count=$(wc -l < "$file_path" 2>/dev/null | tr -d ' ')
            else
                line_count=0
            fi
            [ "${line_count:-0}" -ge "$threshold" ] && return 0
            return 1
            ;;
        prompt_contains)
            local needle
            needle="$val"
            [ -z "$needle" ] && return 1
            grep -qF -- "$needle" <<< "$prompt" && return 0
            return 1
            ;;
        command_uses)
            local needle cmd stripped
            needle="$val"
            [ -z "$needle" ] && return 1
            _ds_view cmd "$tool_input"; cmd="$_DS_V"
            [ -z "$cmd" ] && return 1
            # Вид оболочки: лексема в теле heredoc — содержимое будущего файла, а не вызов.
            _ds_view full "$tool_input"; stripped="$_DS_V"
            grep -qF -- "$needle" <<< "$stripped" && return 0
            return 1
            ;;
        tool_input_contains)
            local needle
            needle="$val"
            [ -z "$needle" ] && return 1
            _ds_view code_ti "$tool_input"
            grep -qF -- "$needle" <<< "$_DS_V" && return 0
            return 1
            ;;
        shell_regex)
            # Образец по тому, что исполнит ОБОЛОЧКА: без тела heredoc, без кавычек.
            # Для вопроса «эта команда сломана здесь и сейчас». КОНТРПРИМЕР: тот же дефект,
            # записанный в файл, сюда не попадёт — на запись есть отдельные признаки.
            local rx cmd view
            rx="$val"
            [ -z "$rx" ] && return 1
            _ds_view cmd "$tool_input"; cmd="$_DS_V"
            [ -z "$cmd" ] && return 1
            _ds_view full "$tool_input"; view="$_DS_V"
            LC_ALL=C grep -qE -- "$rx" <<< "$view" && return 0
            return 1
            ;;
        raw_command_regex)
            # Образец по команде КАК НАПИСАНА, без тел heredoc (вид `shell`): кавычки и
            # комментарии на месте, а тело — содержимое будущего файла. Для вопроса «правильно ли
            # построен вызов», где кавычки значимы: `sed -i ''` верен на BSD, `sed -i s/a/b/`
            # падает, и различает их ровно пустая строка. КОНТРПРИМЕР: слово в кавычках
            # сюда попадёт — этот вид не отличает упоминание от исполнения, и признак,
            # которому нужно такое различение, должен брать shell_regex.
            local rrx rcmd
            rrx="$val"
            [ -z "$rrx" ] && return 1
            _ds_view cmd "$tool_input"; rcmd="$_DS_V"
            [ -z "$rcmd" ] && return 1
            _ds_view shell "$tool_input"
            LC_ALL=C grep -qE -- "$rrx" <<< "$_DS_V" && return 0
            return 1
            ;;
        live_command_regex)
            # Образец по тому, что оболочка РАСКРОЕТ: тела heredoc, комментарии и `'…'` сняты, содержимое `"…"`
            # оставлено — подстановка `"${X}"` живая, а `'${X}'` — данные. Для формы, которая ломается при
            # раскрытии и в двойных кавычках тоже (D1040: `${PIPESTATUS[` в `python3 -c '…'` давал ложный отказ
            # по сырому виду). КОНТРПРИМЕР: проза в `"…"` сюда попадёт — признак о токене в позиции команды
            # берёт shell_regex.
            local lvrx
            lvrx="$val"
            [ -z "$lvrx" ] && return 1
            _ds_view cmd "$tool_input"
            [ -z "$_DS_V" ] && return 1
            _ds_view live "$tool_input"
            LC_ALL=C grep -qE -- "$lvrx" <<< "$_DS_V" && return 0
            return 1
            ;;
        command_regex)
            # То же, что command_uses, но образцом. Нужен там, где дефект — ФОРМА, а не
            # лексема: «for X in $VAR» ловится правилом, «for X in $(cmd)» законно, и  # mb-ok: показ формы
            # фиксированной подстрокой их не развести. Сопоставление идёт по РАСКАВЫЧЕННОЙ
            # команде: слово внутри строки-аргумента — упоминание, а не исполнение.
            local rx cmd stripped
            rx="$val"
            [ -z "$rx" ] && return 1
            _ds_view cmd "$tool_input"; cmd="$_DS_V"
            [ -z "$cmd" ] && return 1
            _ds_view unq_code_cmd "$tool_input"; stripped="$_DS_V"
            LC_ALL=C grep -qE -- "$rx" <<< "$stripped" && return 0
            return 1
            ;;
        command_absent)
            # Правило о МИРЕ, а не о тексте: названного исполняемого на этой машине нет,
            # значит вызов упадёт здесь и сейчас (код 127), а не «когда-нибудь на другой
            # системе». На машине, где инструмент есть, признак молчит сам — список имён
            # не нужно ни сужать, ни отключать под Linux.
            #
            # Повод: `timeout` вызывался 6 раз за корпус в 2342 вызова и на macOS
            # отсутствует; один раз код 127 был почти прочитан как «зависания нет».
            local tool_bin cmd stripped
            tool_bin="$val"
            [ -z "$tool_bin" ] && return 1
            command -v "$tool_bin" >/dev/null 2>&1 && return 1   # инструмент есть — не признак
            _ds_view cmd "$tool_input"; cmd="$_DS_V"
            [ -z "$cmd" ] && return 1
            # Вид оболочки: имя в теле heredoc — содержимое будущего файла, а не вызов.
            _ds_view full "$tool_input"; stripped="$_DS_V"
            # Имя обязано стоять в позиции КОМАНДЫ: начало строки либо после ; & | (.
            # Одного пробела слева мало — на нём `grep -r timeout hooks/` получил отказ
            # за упоминание слова аргументом (замер 28 августа 2026, первый прогон).
            # КОНТРПРИМЕР: `xargs timeout ...` и `env timeout ...` не ловятся — имя стоит
            # аргументом обёртки, и отличить его от упоминания нечем.
            # ПРИСВАИВАНИЯ перед именем — тоже позиция команды: по POSIX они стоят ПЕРЕД
            # командным словом, и `TEST_TIMEOUT=100 timeout 100 bash …` исполняет timeout
            # ровно так же, как голый вызов. Прежний якорь этого не пускал, и 8 сентября
            # 2026 я получил код 127 на собственном замере — почти прочитав его как
            # результат. Замер по корпусу: якорь ловит 37 вызовов, присваивание перед
            # именем добавляет 3. Ложного здесь нет по построению: в `X=1 grep -r timeout`
            # командным словом остаётся grep, и после пробега присваиваний имя не совпадёт.
            # Позицию команды открывают не только разделители: ключевые слова оболочки
            # (`do`, `then`, `else`, `in`), открывающая скобка группы `{` и модификаторы
            # `!`/`time` стоят ПЕРЕД командным словом ровно так же. Перечень конечен —
            # он берётся из грамматики, а не из наблюдённых форм. Замер 8 сентября 2026:
            # `for f in a; do timeout 5 true; done` реально вызывает timeout (оболочка даёт
            # код 127), а признак уровня отказа молчал.
            LC_ALL=C grep -qE -- "${DS_CMD_POS_RE}${tool_bin}([[:space:]]|$)" <<< "$stripped" && return 0
            return 1
            ;;
        os_is)
            # bsd | gnu. Флаг, который валится на BSD, на GNU законен — и наоборот.
            # Без этого различия один признак не может нести отказ: половина того, что он
            # ловит, здесь работает правильно.
            local want kernel
            want="$val"
            [ -z "$want" ] && return 1
            kernel=$(uname -s 2>/dev/null || echo unknown)
            case "$kernel" in
                Darwin|*BSD*) [ "$want" = "bsd" ] && return 0 ;;
                Linux)        [ "$want" = "gnu" ] && return 0 ;;
            esac
            return 1
            ;;
        *)
            # Предиката движок не знает (D1043): ответ «не совпало» был неотличим от настоящего
            # несовпадения, и нога признака гасла молча — 24 октября 2026 знание перешло на
            # `live_command_regex` около 10:00, библиотека с ним доехала до установки в 11:25, и всё
            # окно нога уровня отказа молчала. Ключ копится в `_DS_UNKNOWN`, код 2; входы движка
            # отвечают 2, когда совпадения нет, а незнакомый ключ встретился.
            _DS_UNKNOWN="${_DS_UNKNOWN:+$_DS_UNKNOWN }$key"
            return 2
            ;;
    esac
}

# Evaluate one named signal. Extracts the all_of/any_of branch and delegates.
# Arguments: <signal_json> <tool_name> <tool_input_json> <prompt>
ds_evaluate_signal() {
    _ds_jq_available || return 1
    _DS_UNKNOWN=""
    _ds_compile signal "$1" "$2"
    [ "${_DS_T[0]-}" = S ] || return 1
    _DS_I=2
    _ds_walk 1 "$2" "$3" "$4" && return 0
    [ -z "$_DS_UNKNOWN" ] || return 2
    return 1
}

# Main entry. Evaluates every signal in pattern; on first match echoes name and exits 0.
# No match: 1, or 2 when an unknown predicate was met — its keys go to stderr (D1043).
# Arguments: <pattern_file> <tool_name> <tool_input_json> <prompt>
ds_evaluate() {
    local pattern_file="$1" tool_name="$2" tool_input="$3" prompt="$4" name block
    [ -f "$pattern_file" ] || return 1
    _ds_jq_available || return 1
    # Блока нет — jq не зовётся вовсе, как не звался прежде (раунд противника D509).
    block=$(_ds_signals_block "$pattern_file")
    [ -n "$block" ] || return 1
    _DS_UNKNOWN=""
    _ds_compile signals "$block" "$tool_name"
    while [ "${_DS_T[_DS_I]-}" = S ]; do
        name="${_DS_T[_DS_I+1]-}"; _DS_I=$((_DS_I + 2))
        if _ds_walk 1 "$tool_name" "$tool_input" "$prompt"; then
            printf '%s\n' "$name"
            return 0
        fi
    done
    [ -z "$_DS_UNKNOWN" ] || { printf 'неизвестный предикат: %s\n' "$_DS_UNKNOWN" >&2; return 2; }
    return 1
}
