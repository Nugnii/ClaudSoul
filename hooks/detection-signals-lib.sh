#!/usr/bin/env bash
# detection-signals-lib.sh — pure evaluator of pattern detection_signals (v0.3)
#
# ПРЕФИКСЫ: ds_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
#
# Purpose: blocker-tier knowledge needs a relational pre-action check.
# Each blocker pattern declares detection_signals — named compositions of base
# matchers. At PreToolUse time, blocker-tier-check.sh calls ds_evaluate for
# every blocker pattern; first matching signal fires a silent additionalContext
# injection.
#
# Signal format (stored as JSON inside YAML block literal `detection_signals: |`):
#   [{"name":"...","all_of":[matcher, ...]}, ...]
#
# Base matchers (single-key dicts):
#   {"tool_matches": ["Edit","Write"]}            — current tool is one of
#   {"file_path_regex": "..."}                    — tool_input.file_path matches POSIX ERE
#   {"file_size_min_lines": 300}                  — wc -l of file_path ≥ N (0 if file missing)
#   {"prompt_contains": "..."}                    — last user prompt contains substring
#   {"tool_input_contains": "..."}                — JSON-stringified tool_input contains substring
#   {"tool_input_regex": "..."}                   — tool_input matches POSIX ERE под LC_ALL=C
#   {"heredoc_body_regex": "..."}                 — ТЕЛО heredoc в .command matches ERE (D79)
#   {"command_uses": "..."}                       — команда ИСПОЛНЯЕТ подстроку, а не упоминает её
#
# Почему появился regex по содержимому (v1.14.8). До него содержимое можно было
# сопоставлять ТОЛЬКО точной подстрокой, то есть сигнал умел перечислять известные
# формы и не умел выражать правило. Цена измерена: класс «не-ASCII символ вплотную
# к синтаксису оболочки» за одну сессию проявился ЧЕТЫРЬМЯ разными формами, блокер
# знал две из них списком и не сработал ни разу. Класс, описываемый правилом,
# а не перечнем, при списочном сигнале обречён ловиться постфактум столько раз,
# сколько у него форм.
#
# `LC_ALL=C` обязателен: сопоставление идёт по БАЙТАМ. Иначе предикат «есть не-ASCII»
# сам зависел бы от локали — GNU grep отвергает кириллический диапазон в C.UTF-8,
# и проверка против класса совершила бы ошибку этого же класса (так уже было).
#
# Compositors: {"all_of": [...]}, {"any_of": [...]} — may nest one level inside a signal.
#
# Contract of ds_evaluate:
#   ds_evaluate <pattern_file> <tool_name> <tool_input_json> <prompt_text>
#   Exit 0 + signal name on stdout  → a signal matched
#   Exit 1 + no output              → no signal matched (or pattern has none)
#
# This library has NO state of its own. Throttling, logging, injection — all in
# blocker-tier-check.sh.

set -uo pipefail

# Позиция КОМАНДЫ в виде оболочки — начало строки либо после ; & | ( {, ключевые слова `do`,
# `then`, `else`, `in`, `if`, `elif`, `while`, `until`, модификаторы `!`/`time`, присваивания перед командным словом;
# `{` — только с пробелом после: группа команд без него не открывается (`echo {timeout 5}` — слово, D1053). Перечень из
# грамматики, а не из наблюдённых форм (замер 8 сентября 2026 — см. предикат command_absent ниже).
# Один владелец на дерево: им пользуются command_absent и страж `absent-tool-guard.sh` (D1012) —
# прежде у стража была своя, короче, без `{` и `then`, и `f() { timeout 5 x; }` проходил молча.
DS_CMD_POS_RE='(^|[;&|(]|\{[[:space:]])[[:space:]]*((do|then|else|in|if|elif|while|until|!|time)[[:space:]]+)*([A-Za-z_][A-Za-z0-9_]*=[^[:space:]]*[[:space:]]+)*'

# jq is a hard dep. Without it, return no-match so the system degrades gracefully.
_ds_jq_available() {
    command -v jq >/dev/null 2>&1
}

# Текст блока `detection_signals: |` из шапки, как он записан. Шапка и блок — одним awk (D506):
# прежде шапка и блок доставались двумя.
_ds_signals_block() {
    awk '
        /^---$/ { n++; if (n == 2) exit; next }
        n == 1 && /^detection_signals:[[:space:]]*\|[[:space:]]*$/ { in_block = 1; next }
        n == 1 && in_block {
            if ($0 ~ /^[^[:space:]]/) { exit }
            print
        }
    ' "$1"
}

# Extract detection_signals JSON array from pattern file YAML frontmatter.
# Echoes JSON (either a non-empty array or `[]`).
ds_extract_signals() {
    local pattern_file="$1"
    [ -f "$pattern_file" ] || { printf '[]\n'; return 0; }
    _ds_jq_available || { printf '[]\n'; return 0; }
    local block
    block=$(_ds_signals_block "$pattern_file")
    if [ -z "$block" ]; then
        printf '[]\n'
        return 0
    fi
    local json
    json=$(printf '%s\n' "$block" | jq -c '.' 2>/dev/null)
    if [ -z "$json" ] || [ "$json" = "null" ]; then
        printf '[]\n'
    else
        printf '%s\n' "$json"
    fi
}

# Правило флага `blocker: true` в шапке — одна программа awk на один файл и на многие
# (D506): страж перечитывал флаг awk на каждый из 71 файла базы на каждом вызове, а несут
# его 4. Состояние сбрасывается на первой строке каждого файла; файл, чья шапка кончилась
# или флаг найден, дальше не читается.
_DS_BLOCKER_AWK='
    FNR == 1 { n = 0; done = 0 }
    done { next }
    /^---$/ { n++; if (n == 2) done = 1; next }
    n == 1 && /^blocker:[[:space:]]*true[[:space:]]*$/ { print FILENAME; done = 1 }
'

# Quick boolean: does pattern declare `blocker: true` in frontmatter?
ds_has_blocker_flag() {
    local pattern_file="$1"
    [ -f "$pattern_file" ] || return 1
    [ -n "$(awk "$_DS_BLOCKER_AWK" "$pattern_file" 2>/dev/null)" ]
}

# ds_blocker_files <файл>... → имена файлов с флагом, по одному на строку, в порядке
# аргументов; одним awk. Несуществующие пропускаются до вызова: BSD awk на неоткрываемом
# файле останавливается целиком и не прочёл бы остальные.
ds_blocker_files() {
    local f
    local -a files=()
    for f in "$@"; do [ -f "$f" ] && files+=("$f"); done
    [ "${#files[@]}" -gt 0 ] || return 0
    awk "$_DS_BLOCKER_AWK" "${files[@]}" 2>/dev/null
}

# Evaluate one node (either a composition or a base matcher). 0 = match, 1 = no match.
# Arguments: <node_json> <tool_name> <tool_input_json> <prompt>
# ds_code_only <tool_input> → та же полезная нагрузка без содержимого комментариев.
#
# Повод (D56). Сигналы сопоставляют содержимое правки подстрокой, и блокер переносимости
# дважды за сессию загорелся на КОММЕНТАРИИ — на тексте, где `date -j` и `stat -f`
# перечислены как запрещённые. То есть страж сработал на пояснении к правилу, а не на его
# нарушении. Это `pattern-guard-scope-blindness` внутри самого блокера; для команд тот же
# класс уже закрыт `command-scope-lib.sh` (вырезает кавычки и heredoc), здесь — эквивалент
# для содержимого правки.
#
# Правило комментария оболочки: решётка в начале строки, возможно после отступа. Решётка
# ВНУТРИ кода (`grep -c "#" f`) комментария не открывает, и код после неё обязан уцелеть —
# иначе страж начнёт пропускать настоящие нарушения, что хуже ложных срабатываний.
#
# Нагрузка приходит одной строкой (`jq -c`), перевод строки в ней — два символа `\n`,
# поэтому границей служит он, а не настоящий конец строки.
ds_code_only() {
    # Границей строки служит последовательность `\n`, а НЕ «любая обратная косая».
    # Первая версия резала `#` до ближайшей косой — и под ASCII-экранированием кириллица
    # (`\u0413…`) обрывала вырезание на первом же символе комментария, оставляя запрещённую
    # команду видимой. Проверка поймала это только потому, что гоняет обе кодировки.
    printf '%s' "${1:-}" | awk '{
        n = split($0, a, /\\n/)
        out = ""
        for (i = 1; i <= n; i++) {
            s = a[i]
            # Две подстановки, а не одна с альтернацией. Прежняя `(^|")` печатала кавычку
            # В ОБОИХ случаях, в том числе когда комментарий начинался с начала строки, —
            # и впрыснутая кавычка паровалась ниже в ds_unquoted_command со сдвигом, обнажая
            # то, что стояло В КАВЫЧКАХ. Так `# памятка` + `printf "timeout не установлен"`
            # давал ОТКАЗ на команду, которая timeout не вызывает.
            sub(/^[[:space:]]*#.*$/, "", s)          # комментарий с начала строки — снять целиком
            # После закрывающей кавычки решётка начинает комментарий только через ПРОБЕЛ:
            # `grep -c "#" file` — это закавыченная решётка, а не комментарий, и прежняя
            # редакция съедала на ней остаток строки вместе с настоящим вызовом.
            sub(/"[[:space:]]+#.*$/, "\"", s)
            out = out s (i < n ? "\\n" : "")
        }
        print out
    }'
}

# Убрать закавыченные куски команды: это аргументы-строки, а не исполняемое.
# Повод измерен 2026-08-28: ветвь сигналов по Bash сработала на первом же живом вызове,
# где слово стояло ВНУТРИ кавычек пробы, а не запускалось. Подстрока не различает
# исполнение и упоминание, и на этом ломается любой стопор: отказ приходит там, где
# ничего не происходит, и его начинают обходить не думая.
#
# Тело heredoc НЕ трогаем намеренно: код, записываемый в файл, будет исполняться — это
# тоже использование. Для него отдельный предикат `heredoc_body_regex` (D79).
#
# Потолок назван: вложенные и экранированные кавычки снимаются грубо, одним проходом.
# Цена ошибки несимметрична — лишний пропуск дешевле ложного отказа, поэтому грубость
# смещена в сторону пропуска.
ds_unquoted_command() {
    # Разбор идёт по ВСЕМУ тексту сразу, а не построчно: кавычки в командах переносятся
    # через строки — сообщение коммита, тело `-m "…"`. Построчный проход оставлял такую
    # прозу видимой, и на ней 28 августа 2026 пришёл единственный ложный отказ замера по
    # 2342 вызовам: слово «timeout» в русской фразе сообщения коммита было прочитано как
    # вызов отсутствующего инструмента.
    # Смещение сохранено прежнее: непарная кавычка теперь съест хвост команды, то есть
    # даст ПРОПУСК, а не ложный отказ. Пропуск здесь дешевле.
    # КАВЫЧКИ — С СОСТОЯНИЕМ (D1015, 23 октября 2026, узкая починка по решению владельца). Здесь стояли две
    # замены `'[^']*'` и `"[^"]*"` без состояния: апостроф внутри `"…"` (`"it's"`), экранированная `\"` и апостроф
    # в хвостовом комментарии (`# don't`) сдвигали пары, и местный вызов оказывался «внутри кавычек». Замер по
    # корпусу 3000 настоящих команд: вид терял слова кода в 24, у 20 из них причина — эта. Теперь один проход
    # слева направо: вне кавычек `\` экранирует знак, `#` в начале слова открывает комментарий до конца строки;
    # в `'…'` экранирования нет, кроме `$'…'`; в `"…"` `\"` не закрывает. Знаки разбираются один раз в массив, вывод
    # идёт блоками — цена линейна (попытка 21 октября копировала знак за знаком в строку: 600 КБ за 16 с).
    # `$(` ВНУТРИ `"…"` ОТКРЫВАЕТ ОБЛАСТЬ КОМАНДЫ (вторая редакция по финальному скептику, 23 октября 2026). Первая
    # редакция внутри `"…"` областей не знала: в `"x: $(sed 's/"//g')"` кавычка из `'…'` закрывала внешнюю строку, и
    # хвост до следующего апострофа становился «кавычками» — вид терял настоящий код (`done`, `git push`) и обнажал
    # закавыченное (ложные сигналы стражей на корпусе); прежние две замены здесь были правы, потому что `'…'` снимали
    # первыми. Теперь стек: `$(` в `"…"` — область команды со своими кавычками до парной `)`. Её содержимое
    # ИСПОЛНЯЕТСЯ и потому остаётся в виде (снимается только литеральный текст строки): замер вердиктов по корпусу
    # показал, что снятие области прятало настоящий код — `"$(date -u -r "$(stat -f %m "$f")")"` терял верное
    # предупреждение о переносимости. Названный предел: непарная `)` внутри области (ветка `case … a)`) закрывает её
    # раньше. Условие снятия: замер назовёт команду, где это меняет вид.
    # Вторым аргументом `keepdq` содержимое `"…"` остаётся (вид `live`, D1040): подстановки в двойных кавычках оболочка
    # раскрывает, и `echo "${PIPESTATUS[0]}"` — живая форма, а в `'…'` та же запись — данные.
    # Конец области в `"…"` печатается `) `, как у `$(…)` (L-a, третий круг D1042): обратная кавычка на этом месте
    # делала слово за строкой позицией команды, и ``"a `b⏎c`"MARKZ`` — одно слово — читалось вызовом (фазз против bash).
    # Названный предел, общий с `$(…)`: ``x="`d`" timeout 5`` — вызов с присваиванием, и вид его не видит, как и
    # `x="$(d)" timeout 5`. Предел всех редакций: слово, приклеенное к кавычке или к концу области (`; MARKZ"a"`,
    # ``echo `a`MARKZ``, ``echo \`MARKZ``), вид отрывает от приклеенного — образец, у которого `` ` `` или `;` впереди,
    # читает его вызовом (фазз против bash: 13 таких случаев, где прежняя редакция была права лишь потому, что неверно
    # спаренная многострочная область глотала этот текст).
    # РОЛЬ ЗНАКА — ПО КОНСТРУКЦИИ, КОТОРУЮ ОН ЗАКРЫВАЕТ (D1042). Обратная кавычка в `"…"` открывает область команды, как
    # `$(`, и закрывает её обратная кавычка, а не `)` (`SB` — вид области в стеке): прежде `"\`echo "it's"\`"` закрывал
    # строку на внутренней `"`, апостроф съедал хвост, и живая подстановка за ним пропадала. `)` подстановки (`$(`, `<(`,
    # `>(` — вид `PT` у каждой `(`) слово не кончает: в `$(true)#x` решётка — продолжение слова, а не комментарий.
    # КОНЕЦ ОБРАТНОЙ КАВЫЧКИ — СЫРЫМ ПОИСКОМ (D1042, финальный скептик c4489c95). Оболочка кончает область на первой
    # неэкранированной обратной кавычке, не глядя на кавычки и комментарии внутри; разбор содержимого полной грамматикой
    # выпускал наружу непарный апостроф (``"Fix `it's` case"; timeout 5 true`` терял вызов) и комментарий
    # (``x=`echo a # b`; …``). Теперь конец ищется при открытии (`rawend`), и на нём область закрывается при любом
    # состоянии внутри (`BE` — место конца, `BS` — состояние снаружи). Конца нет — знак буквальный. Конец ищется и на
    # следующих строках, как у оболочки (D1042, третий круг, M-a): поиск в своей строке читал ЗАКРЫВАЮЩУЮ кавычку
    # ``x=`a⏎b`; …`` открывающей, и кавычки сдвигались до конца команды. Третий аргумент `raw` — текст с телами heredoc
    # (вид `unq_code_cmd`): там одиночная обратная кавычка строки тела (``const tick = "`";``) — данные, и конец ищется
    # только в своей строке. Названный предел этого вида (L2 третьего круга, описан по поведению): обратная кавычка без
    # пары в своей строке читается буквальной, а ЗАКРЫВАЮЩАЯ кавычка многострочной подстановки на следующей строке
    # спаривается с ближайшей обратной кавычкой той же строки — ``x=`a⏎b`; echo "it's `date`"; timeout 5 true`` теряет
    # вызов (так с 3a4d7ddb; до D1042 держали). Условие снятия: вид с телами получит разбор heredoc — тела данными,
    # остальное через перенос области, как у вида оболочки.
    printf '%s' "${1:-}" | awk -v keepdq="${2:+1}" -v raw="${3:+1}" '
        function rawend(i,    j) {
            if (i > BF0 && i < BF1) return 0       # из этого куска конца уже не нашли
            for (j = i + 1; j <= n && !(raw && ch[j] == "\n"); j++) { if (ch[j] == "\\") j++; else if (ch[j] == "`") return j }
            BF0 = i; BF1 = j; return 0
        }
        function bqopen(i, outer,    e) {
            e = rawend(i)
            if (!e || bq > 0 && e >= BE[bq]) return 0
            sp++; SB[sp] = 1; bq++; BE[bq] = e; BI[bq] = sp; BP[bq] = pd; BS[bq] = outer; st = 0
            return 1
        }
        BEGIN { RS = "\001" } {
        n = split($0, ch, ""); st = 0; buf = ""; bl = 0; prev = ""; sp = 0; pd = 0; bq = 0; BF0 = BF1 = 0
        for (i = 1; i <= n; i++) {
            c = ch[i]
            if (bq > 0 && i >= BE[bq]) {
                i = BE[bq]; sp = BI[bq] - 1; pd = BP[bq]; st = BS[bq]; bq--
                if (st == 2) { buf = buf ") "; bl += 2; prev = ")" } else { buf = buf "`"; bl++; prev = "w" }
                continue
            }
            if (st == 0) {
                # После `\x` прошлый знак — часть слова: `\ #` и `\;#` комментария не открывают.
                if (c == "\\") { buf = buf c (i < n ? ch[i + 1] : ""); bl += 2; i++; prev = "w" }
                else if (c == "\047") { st = 1; ansi = (prev == "$"); buf = buf " "; bl++ }
                else if (c == "\"") { st = 2; buf = buf " "; bl++ }
                else if (c == "`" && bqopen(i, 0)) { buf = buf c; bl++; prev = c }
                else if (c == "#" && (prev == "" || prev ~ /[[:space:];|&()]/)) {
                    while (i < n && ch[i + 1] != "\n" && !(bq > 0 && i + 1 >= BE[bq])) i++
                    prev = "#"
                }
                else {
                    if (c == "(") { pd++; PT[pd] = (prev == "$" || prev == "<" || prev == ">") }
                    else if (c == ")") {
                        wt = PT[pd]; pd--
                        if (sp > 0 && !SB[sp] && pd == SD[sp]) { sp--; st = 2; buf = buf ") "; bl += 2; prev = c; continue }
                        if (wt) { buf = buf c; bl++; prev = "w"; continue }
                    }
                    buf = buf c; bl++
                    prev = c
                }
            } else if (st == 1) {
                if (ansi && c == "\\") i++
                else if (c == "\047") { st = 0; prev = c }
            } else {
                if (c == "\\") i++
                else if (c == "\"") { st = 0; prev = c }
                else if (c == "(" && prev == "$") { sp++; SD[sp] = pd; SB[sp] = 0; pd++; st = 0; buf = buf " $("; bl += 3; prev = c }
                else if (c == "`" && bqopen(i, 2)) { buf = buf " `"; bl += 2; prev = c }
                else { prev = c; if (keepdq) { buf = buf c; bl++ } }
            }
