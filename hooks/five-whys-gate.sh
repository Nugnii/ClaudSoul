# Ключ дедупа — ПОДПИСЬ (какие сигналы и сколько) ПЛЮС метка хода. Две правки
# одного дня, обе по замеру:
#
#   1. Прежний монотонный счётчик глушил РАЗНЫЙ сигнал той же величины: находка по
#      ходу поднимала счёт до 1, и следующий настоящий повтор с тем же счётом 1 уже
#      молчал. С четырьмя источниками совпадение величин перестало быть редкостью.
#   2. Одной подписи мало: величина `repeat` считает РАЗНЫЕ знания с повтором, и при
#      одном таком знании она равна 1 навсегда. 27 августа 2026 гейт сказал про
#      `pattern-unobservable-narrated-as-fact` один раз, а класс повторился в той же
#      сессии ещё трижды — и все три раза было тихо. Поправка владельца дословно:
#      «ошибся ровно тем же способом, т.е. повтор уплывает».
#
# Область одного напоминания — ХОД, а не сессия: гейт и так читает текст после
# последней реплики собеседника, и естественная граница «то же самое» — та же реплика.
# Фоном это не станет: при произнесённой цепочке гейт молчит (проверка выше), то есть
# повторяется он ровно там, где разбора по-прежнему нет.
# Метка хода — rc_turn_key (root-cause-lib), посчитана выше, до первого выхода: та же
