# Третий сигнал считает подтверждения в границах сессии и межсессионный повтор не видит
# по построению. Живой случай 28 августа 2026: `pattern-subject-checked-by-enumeration`
# подтверждён трижды за ~15 часов — 27.08 09:56, 27.08 19:46, 28.08 01:07, — и ни одна
# пара не попала в одну сессию. Итог: агент написал «третий за сутки того же класса»
# ПРОЗОЙ ПО ПАМЯТИ. Число оказалось верным, но добытым не механизмом; в следующий раз
# память соврёт, и отличить будет нечем.
# Порог три, а не два: два подтверждения за сутки — обычное здоровое подкрепление.
if [ -f "$OUTCOMES" ]; then
    _cutoff=$(date -u -v-1d '+%Y-%m-%dT%H:%M:%SZ' 2>/dev/null \
              || date -u -d '1 day ago' '+%Y-%m-%dT%H:%M:%SZ' 2>/dev/null || printf '')
    if [ -n "$_cutoff" ]; then
        _day_name=$(jq -rs --arg c "$_cutoff" '
            [ .[] | select((.outcome // "") == "confirmed_knowledge"
                           or (.outcome // "") == "applicable_not_followed")
                  | select((.date // "") > $c) ]
            | group_by(.knowledge) | map(select(length >= 3))
            | .[0][0].knowledge // ""' "$OUTCOMES" 2>/dev/null || printf '')
        if [ -n "${_day_name:-}" ]; then
            # СУТОЧНЫЙ ФАКТ НЕ ГЕЙТИТ ХОД (D358, 13 сентября 2026). Предмет `daily` — сутки
            # поперёк сессий и проектов, а не этот ход: реплей атрибуции по 383 ходам дал
            # совпадение предмета с ходом в 5 случаях из 158 (3%), и 66 из 70 отказов, какие
            # дало бы сужение гейта, несли именно его. Факт называется ОДИН РАЗ в сутки на
            # знание — очередью отложенных уведомлений (её поднимает pending-alerts-surface на
            # следующем UserPromptSubmit), в SIGNALS/KINDS не входит: ни напоминания в ходе,
            # ни отказа, ни строки в журнале исходов. Без throttle-lib очередь не пишется —
            # иначе строка шла бы на каждом ходу; сломанная установка видна дрейфом, не спамом.
            if command -v throttle_file >/dev/null 2>&1; then
                _dq=$(throttle_file "$STATE" daily all)
                _dk="${_day_name%.md}:$(date -u +%Y-%m-%d)"
                if ! throttle_seen "$_dq" "$_dk"; then
                    throttle_mark "$_dq" "$_dk" knowledge "${_day_name%.md}" session "${SID:-}"
                    printf '🔁 За сутки одно знание подтвердилось трижды и больше поперёк сессий: %s — суточный факт, ход он не гейтит (D358); повод для /learn либо ребра к паттерну.\n' "${_day_name%.md}" >> "$STATE/pending-alerts.txt" 2>/dev/null || true
                fi
            fi
        fi
    fi
fi

