    # была зачтена в предыдущем ходе при неизменном составе сродов с правом. Запись —
    # токены сродов (`fwg_chain_tokens`), субагенту не пишется: у него общий SID, и его
    # цепочка покрыла бы поводы родителя — чужая цепочка.
    if [ "${_FWG_IN_SUBAGENT:-0}" -eq 0 ]; then
