#!/usr/bin/env bash
# five-whys-gate.sh — PreToolUse: повтор замечен, а разбора причин не было — требует «5 почему».
# en: PreToolUse: a repeat signal fired but no why-chain was stated — demands the 5 Whys.
#
# Повод — три напоминания собеседника за три недели, дословно:
#   28.07: «3 раза делал одно и то же потому что не использовал 5 почему, хотя должен был
#           и раньше это делал»
#   29.07: «А ты задавал 5 почему по этому поводу? Ты должен если видишь повторяющиеся
#           признаки понять, что есть же причина всему этому»
#   21.08: «ты детектил дефект, а использовал ли 5 почему? давненько не видел»
#
# Третье напоминание об одном и том же — это не забывчивость, а отсутствующий механизм
# (principle-knowledge-in-the-world). Проверено при заведении: хука не было ни в
# репозитории, ни в регистрации настроек с 16.06, ни одним инжектом в транскриптах —
# все 23 вхождения фразы в транскриптах оказались эхом SESSION.md через session-registry.
# Слово «вширь» носят три разные вещи. Перечень ВЕРСИЙ причины («какие бывают причины»)
# исполним без данных и потому съедает спуск — он стоял в правилах первым до 27 августа
# 2026 и убран оттуда. Перечень ПРОЯВЛЕНИЙ («где ещё виден тот же признак») добывается
# только поиском в мире и с 28 августа 2026 стоит ПЕРВЫМ: признак корня («убери звено —
# симптом не мог бы возникнуть ни одним путём») есть утверждение о множестве проявлений,
# и при одном наблюдении он непроверяем. Перечень ЗАВИСИМОСТЕЙ корня идёт последним.
# Повод порядка — замер 28 августа: один дефект (не-ASCII путь скилла) онемил пять
# стражей подряд, каждого чинили отдельным заходом от того места, где заметили.
#
# ПОЧЕМУ НЕ НОВЫЙ СЧЁТЧИК. Повторы уже считают трое: error-tracker (полоса провалов),
# rework-detector (третий заход на тот же файл). Второй существует потому, что на той же
# реплике 28.07 собеседник заметил главное: «ошибкой может быть успех, и он не
# детектируется как ошибка = не подлежит проверке на 5 почему». Поэтому гейт слушает ОБА
# сигнала: и провал, и повторяющийся успех. Третий добавлен 27 августа 2026 —
# `knowledge-counter-bump` (одно знание подтверждено за сессию дважды): первые два видят
# повтор только в ДЕЙСТВИЯХ, а повтор бывает и в УТВЕРЖДЕНИЯХ, без единой упавшей команды.
#
# ПОТОЛОК, названный честно. Произнесённость цепочки проверяется по тексту последних
# ответов — следом форм доктрины (rc_trace: «почему», заголовки шаблона, спуск «←», реестр
# мест с дробью и корнем; формы выбраны реплеем по корпусу, D211). Это распознаёт форму, а
# не мысль: пять слов «почему» подряд без содержания сочтёт разбором, а разбор в незнакомой
# форме — нет. Цена ложного «след есть» здесь — правка, прошедшая без цепочки, потому
# реестр без слова «корень» цепочкой не считается; цена пропуска — третий заход на симптом.
#
# Input  (stdin): {session_id, tool_name, transcript_path} (PreToolUse JSON)
# Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} либо пусто
# Exit:  always 0 (degrade gracefully).

set -uo pipefail

PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
if [ -f "$PATHS_LIB" ]; then
    # shellcheck source=/dev/null
    source "$PATHS_LIB"
else
    : "${STATE_DIR:=$HOME/.claude/hooks/state}"
fi
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"

command -v jq >/dev/null 2>&1 || exit 0

# Общие вычисления контура разбора — из root-cause-lib (единственное определение ключа
# хода, последнего блока речи и счёта «почему»; своя копия формулы ключа уже расходилась
# молча с копией сверщика declared-problem-recorded). Библиотеки нет — гейт молчит:
# страж, не умеющий посчитать ключ хода, не имеет права ни на отказ, ни на журнал.
RC_LIB="${RC_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/root-cause-lib.sh}"
[ -f "$RC_LIB" ] || RC_LIB="$HOME/.claude/hooks/root-cause-lib.sh"
# shellcheck source=/dev/null
{ [ -f "$RC_LIB" ] && source "$RC_LIB"; } || exit 0

INPUT=$(cat)
[ -z "$INPUT" ] && exit 0

TOOL_NAME=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
case "$TOOL_NAME" in
    Edit|Write|MultiEdit|Bash) ;;
    *) exit 0 ;;
esac

SID=$(printf '%s' "$INPUT" | jq -r '.session_id // ""' 2>/dev/null)
[ -n "$SID" ] || exit 0
TRANSCRIPT=$(printf '%s' "$INPUT" | jq -r '.transcript_path // ""' 2>/dev/null)

# ── Сигналы повтора: чужие детекторы, свой счётчик не заводится ───────────────
REWORK="$STATE/rework-fired-${SID}.jsonl"
STREAK="$STATE/error_streak_fired_${SID}"
CORRECTION="$STATE/correction-fired-${SID}.jsonl"
QUESTION="$STATE/question-open-${SID}.jsonl"
SIGNALS=0
KINDS=""
WHAT=""
# Отказом сопровождается ОДИН сигнал — находка по ходу. Граница проведена замером, а не
# вкусом: повод собеседника был именно про находку («поймал… чиню»), а частоту связки
# «полоса провалов + запись» и «переработка + запись» я НЕ мерил. Расширять отказ на
# неизмеренное нельзя: страж с отказом уже дважды блокировал настоящую работу — запись
# собственного теста и запись пункта долга про тот же дефект (шапка command-scope-lib).
# Стоячие сигналы (repeat, daily) держатся часами и сутками; отказ на них — бессрочный
# стоп, их дело напоминать.
EVENT=0
if [ -f "$REWORK" ]; then
    _n=$(grep -c '' "$REWORK" 2>/dev/null || printf '0')
    case "$_n" in ''|*[!0-9]*) _n=0 ;; esac
    if [ "$_n" -gt 0 ]; then
        SIGNALS=$((SIGNALS + _n))
        _rw_key=$(cksum < "$REWORK" 2>/dev/null | awk '{print $1}')
        KINDS="${KINDS}rework:${_rw_key:-0}|"
        _rw_files=$(jq -r '.file // empty' "$REWORK" 2>/dev/null | sort -u | tr '\n' ' ')
        WHAT="повторные заходы на один файл при зелёных прогонах"
        [ -n "${_rw_files// /}" ] && WHAT="$WHAT (${_rw_files% })"
    fi
fi
# Поправка собеседника — такой же повод для спуска, как переделка файла и полоса провалов.
# До 29 августа 2026 гейт слушал только их: предмет разбора был задан АРТЕФАКТОМ (файл,
# команда), а поведение агента артефактом не является и потому в предмет не попадало.
# Продюсер сигнала существовал и работал — `user-correction-guard` пишет
# `correction-fired-<SID>.jsonl`, таких файлов в состоянии было 27, — но к гейту подключён
# не был: контур поведения и контур разбора дефектов заведены порознь, моста между ними
# не существовало.
#
# Цена измерена на самом агенте в тот же день: собеседник дважды поправил поведение
# («перестал сам коммитить»), и оба раза разбор не запустился — поправка была принята к
# сведению и закрыта текстовым правилом, то есть починена симптомно. Это ровно тот класс,
# который в тот же день разобран и записан знанием
# `case-2026-08-29-fix-addressed-to-artifact-not-subject`.
#
# КОНТРПРИМЕР: поправка ФАКТА («не 61, а 112») сюда не относится — она закрывается
# перезамером, а не спуском к причине. Гейт считает поводом поправку, которую продюсер уже
# признал поправкой ПОВЕДЕНИЯ; отличать их — его дело, не гейта.
if [ -f "$CORRECTION" ]; then
    _c_n=$(grep -c '' "$CORRECTION" 2>/dev/null || printf '0')
    case "$_c_n" in ''|*[!0-9]*) _c_n=0 ;; esac
    if [ "$_c_n" -gt 0 ]; then
        SIGNALS=$((SIGNALS + _c_n))
        _c_key=$(cksum < "$CORRECTION" 2>/dev/null | awk '{print $1}')
        KINDS="${KINDS}correction:${_c_key:-0}|"
        if [ -n "$WHAT" ]; then WHAT="$WHAT и поправка собеседника о поведении"
        else WHAT="поправка собеседника о поведении"; fi
    fi
fi
# Вопрос собеседника — шестой повод, добавлен 29 августа 2026 по прямой поправке:
# «сигнал поправки наравне с переделкой и провалами а как же мои вопросы?».
# До этого дня вопрос распознавался (`inquiry-gap.sh`, срабатывание проверено прогоном на
# двух живых репликах) и НЕ ЗАПИСЫВАЛСЯ: продюсера состояния не существовало вовсе. Для
# поправки данные лежали и потребителя не было; для вопроса не было даже данных — то есть
# ни гейт, ни любая другая последующая проверка опереться было не на что.
#
# Сигнал СТОЯЧИЙ, не событийный: EVENT не поднимается, отказа по нему не бывает. Причина
# названа замером, а не вкусом — словарь `inquiry-gap` ловит вопросительное слово, а не род
# вопроса, и вопрос о ФАКТЕ («как запустить тесты?») попадёт в сигнал наравне с вопросом,
# вскрывающим дыру. Правило этого файла: расширять отказ на неизмеренный признак нельзя.
#
# КОНТРПРИМЕР: сессия без вопросов этого повода не получает; вопрос, на который в том же
# ходе произнесена цепочка из трёх «почему», гейт пропускает молча — как и все прочие поводы.
if [ -f "$QUESTION" ]; then
    _q_n=$(grep -c '' "$QUESTION" 2>/dev/null || printf '0')
    case "$_q_n" in ''|*[!0-9]*) _q_n=0 ;; esac
    if [ "$_q_n" -gt 0 ]; then
        SIGNALS=$((SIGNALS + _q_n))
        _q_key=$(cksum < "$QUESTION" 2>/dev/null | awk '{print $1}')
        KINDS="${KINDS}question:${_q_key:-0}|"
        if [ -n "$WHAT" ]; then WHAT="$WHAT и вопрос собеседника"
        else WHAT="вопрос собеседника"; fi
    fi
fi
if [ -f "$STREAK" ]; then
    SIGNALS=$((SIGNALS + 1))
    _st_key=$(cksum < "$STREAK" 2>/dev/null | awk '{print $1}')
    KINDS="${KINDS}streak:${_st_key:-0}|"
    if [ -n "$WHAT" ]; then WHAT="$WHAT и полоса упавших команд"
    else WHAT="полоса упавших команд"; fi
fi
# Третий сигнал: одно и то же знание подтвердилось за сессию дважды и больше.
# Первые два ловят повтор в ДЕЙСТВИЯХ — упавшая команда, третий заход на файл.
# 27 августа 2026 сессия дала четыре подряд утверждения одного класса (вывод о целом
# из прочитанного куска; величина, у которой нет источника) — ни одной упавшей
# команды, ни одной повторной правки. Гейт промолчал по построению: повтор был в
# УТВЕРЖДЕНИЯХ, а их не считал никто. Своего счётчика по-прежнему не заводим —
# `knowledge-counter-bump.sh` уже кладёт в `disagreement-outcomes.jsonl` строку с
# `session` и `knowledge`; два `confirmed_knowledge` по одному знанию в одной
# сессии и есть «второй раз в ту же стену».
OUTCOMES="$STATE/disagreement-outcomes.jsonl"
if [ -f "$OUTCOMES" ]; then
    _rep=$(jq -s --arg sid "$SID" '
        [ .[] | select((.session // "") == $sid and (.outcome // "") == "confirmed_knowledge") ]
        | group_by(.knowledge) | map(select(length >= 2)) | length' "$OUTCOMES" 2>/dev/null || printf '0')
    case "${_rep:-}" in ''|*[!0-9]*) _rep=0 ;; esac
    if [ "$_rep" -gt 0 ]; then
        _rep_name=$(jq -rs --arg sid "$SID" '
            [ .[] | select((.session // "") == $sid and (.outcome // "") == "confirmed_knowledge") ]
            | group_by(.knowledge) | map(select(length >= 2)) | .[0][0].knowledge // ""' "$OUTCOMES" 2>/dev/null || printf '')
        SIGNALS=$((SIGNALS + _rep))
        # В ключ идут ИМЕНА знаний, а не их число. Счёт одинаков у разных знаний, и
        # 27 августа собеседник назвал это дословно: «повтор уплывает». Тогда починили
        # ГРАНИЦУ (сессия → ход), а ключ остался счётным — и 28 августа тот же дефект
        # нашёлся внутри хода. Отпечаток экземпляра снимает вопрос независимо от границы.
        _rep_key=$(jq -rs --arg sid "$SID" '
            [ .[] | select((.session // "") == $sid and (.outcome // "") == "confirmed_knowledge") ]
            | group_by(.knowledge) | map(select(length >= 2)) | map(.[0].knowledge) | sort
            | join(",")' "$OUTCOMES" 2>/dev/null || printf '')
        KINDS="${KINDS}repeat:${_rep_key:-none}|"
        _rep_what="одно знание подтвердилось за сессию дважды и больше"
        [ -n "${_rep_name:-}" ] && _rep_what="$_rep_what, а именно ${_rep_name%.md}"
        if [ -n "$WHAT" ]; then WHAT="$WHAT и $_rep_what"; else WHAT="$_rep_what"; fi
    fi
fi

# ── Разбор уже произнесён? ────────────────────────────────────────────────────
# Считаем только ответы ПОСЛЕ последней реплики собеседника: разбор из прошлого хода
# к нынешнему повтору не относится. След разбора — rc_trace (root-cause-lib): не только
# слово «почему», но и формы доктрины — заголовки шаблона, спуск «←», реестр мест с дробью и
# корнем (D211). До 30 августа 2026 связный разбор без слова «почему» гейт не видел и
# отказывал зря: из трёх живых отказов один был ровно таким.
TRACE=$(rc_trace "$TRANSCRIPT")
# ── Четвёртый сигнал: ПОЧИНКА ПО ХОДУ ────────────────────────────────────────
# Поправка владельца 27 августа 2026, дословно: «Ты в процессе написания
# обнаруживаешь проблемы, а потом мне пишешь было найдено то-то, починено — а вот
# чинил ты без 5 почему. ЭТО ПРОБЛЕМА ОСНОВНАЯ».
#
# Первые три сигнала ловят ПОВТОР. Но повтор — это СЛЕДСТВИЕ пропущенного разбора,
# а не его условие: пока агент возвращается к месту второй раз, разбор уже не
# сделан один раз. Гейт стоял на симптоме собственной проблемы.
#
# Условие — сам факт починки. Признак наблюдаем в тексте агента ПЕРЕД правкой:
# находка по ходу называется словами «оказалось», «вылезло», «побочно», «заодно».
# Счёт за 27 августа: четыре починки по ходу подряд (таблица мостов, граница слова
# в страже фазы, коллизия номера долга, снос файла состояния) — ни одной цепочки,
# и ни один из трёх прежних сигналов не мог сработать: повтора не было ни разу.
# Перечень форм — признанный предел, а не недосмотр. 28 августа 2026 он пропустил слово
# «поймал» («страж поймал мой же тест — чиню»), и собеседник указал на это прямо.
# Кандидат на замену, записанный 27 августа («правка файла, который в этом же ходе
# читали»), ПРОВЕРЕН И ОТВЕРГНУТ замером: правок через Edit/Write за четыре сессии
# НОЛЬ — работа идёт через Bash, и признак не сработал бы ни разу.
# Почему перечень остаётся: находка — речевой акт, а речевой акт распознаётся словами.
# Полного перечня не бывает; честная тактика — дописывать ИЗМЕРЕННЫЕ промахи и не
# выдавать список за правило (pattern-subject-checked-by-enumeration, confidence 5).
# КОНТРПРИМЕР: находка, названная словом вне перечня, — «поймал» до 28 августа 2026,
# «всплыло», «а тут ещё» — не ловится. Находка есть речевой акт, и полного перечня слов
# для него не существует; список дополняется ИЗМЕРЕННЫМИ промахами, а не догадками.
# СОБСТВЕННАЯ ОШИБКА — тоже находка, и до 30 августа 2026 её тут не было. Повод: вопрос
# владельца «когда ты пишешь "моя ошибка" — ты это ловишь и исследуешь, или тупо чинишь?».
# Замер того же часа по этой сессии: три самопризнания подряд («прочитал код возврата
# конвейера, а не скрипта», «вызвал генератор без нужного параметра», «счётчик считал не
# то — вышло 244%»), и ни одно не привело ни к цепочке, ни к записи. Причина видна в самом
# перечне ниже: он собирался из находок о МИРЕ («оказалось, что файл…»), и признание
# ошибки о СЕБЕ под него не подпадало ни одной формой.
#
# Почему это важнее, чем кажется: ошибку в мире ловит механизм и требует разбора; ошибку
# агента ловит сам агент — и до сих пор ничто не требовало от него ничего. Контур, который
# строился весь день для системы, обходил стороной того, кто его строит.
#
# НАЗВАННЫЙ ПРЕДЕЛ: признание — речевой акт, и распознаётся словами; полного перечня форм
# не существует (`pattern-subject-checked-by-enumeration`). Список дополняется ИЗМЕРЕННЫМИ
# промахами, а не догадками. Условие снятия: предел уйдёт, когда собственная ошибка станет
# наблюдаема по следу — например, по расхождению между заявленным и перепроверенным числом.
# Слова ОТКЛАДЫВАНИЯ — «решение за владельцем», «оставил как есть» — тоже находка: проблема
# названа и никуда не легла. Замер 30 августа 2026: три хода подряд с «за владельцем», ноль
# с номером пункта, шесть решений ушли в CHANGELOG вместо BACKLOG, и ни один страж не
# сработал — сверщик записи судит по сигналам, а сигнала не было. КОНТРПРИМЕР: «владелец
# проекта решил выпускать по средам» — слово есть, откладывания нет, не ловится.
DISCOVERY_RE="${FIVE_WHYS_DISCOVERY_RE:-решени[ея] (за )?владельц|за владельцем|оставил как есть|не правил, решение|оказал|вылез|выяснил|побочно|заодно|мимоходом|попутно|расхожден|расходит|коллизи|дубликат|обнаружил|нашёл|нашлась|нашлось|не сходится|на самом деле|поймал|поймала|всплыл|подвох|мимо кассы|моя ошибка|я ошибся|я ошиблась|ошибся я|прочитал неверно|прочитал не то|неверно прочитал|посчитал неверно|неправильно понял|мой промах|виноват сам|сделал не то}"
# Признак читается по ПОСЛЕДНЕМУ блоку речи, а не по всему окну хода. Диагноз
# 28 августа 2026 на расшифровке живой сессии: в одном ходе гейт сработал на индексе 1055
# («repeat + находка»), а на 1159 — вторая находка того же хода, и та, ради которой всё, —
# промолчал. Подпись совпала, дедуп счёл «то же самое». По всему окну иначе и не выйдет:
# слово находки, однажды сказанное, остаётся в окне до конца хода, и все последующие
# находки сливаются с первой. Находка — то, что сказано ТОЛЬКО ЧТО.
# Формула — rc_last_block (root-cause-lib).
LAST_BLOCK=$(rc_last_block "$TRANSCRIPT")
if [ -n "${LAST_BLOCK:-}" ] && grep -qiE "$DISCOVERY_RE" <<< "$LAST_BLOCK"; then
    SIGNALS=$((SIGNALS + 1))
    # Отпечаток самой находки в ключе: две РАЗНЫЕ находки одного хода получают разные
    # ключи и обе доходят, а один и тот же текст при нескольких вызовах подряд — молчит.
    _find_key=$(printf '%s' "$LAST_BLOCK" | cksum 2>/dev/null | awk '{print $1}')
    KINDS="${KINDS}discovery:${_find_key:-1}|"
    EVENT=1
    if [ -n "$WHAT" ]; then WHAT="$WHAT и находка по ходу работы"
    else WHAT="находка по ходу работы, а правка уже началась"; fi
fi

# ── Восьмой сигнал: ВНЕШНЕЕ СОБЫТИЕ (D200-D203) ───────────────────────────────
# Мир подаёт поводы, которых в сессии не видно: красный прогон СВОЕГО коммита, откат
# коммита, воскресшее закрытие пункта долга, сбой самой проверки дрейфа. Зрелые практики
# запускают разбор не только на ущерб и повтор: у Google SRE сам факт ручного вмешательства
# (откат релиза) обязывает к разбору, а в медицине девять классов событий репортятся
# «regardless of outcome». У нас эти события НАБЛЮДАЛИСЬ и никуда не вели — оставались
# строкой в отчёте скрипта.
#
# Сигнал СТОЯЧИЙ: отказа по нему не бывает. Событие приходит извне хода, и блокировать
# правку из-за вчерашнего красного прогона значило бы держать стоп сутками.
if command -v rc_open_events >/dev/null 2>&1; then
    _ev=$(rc_open_events "$STATE" | head -3 | tr '\n' ';')
    if [ -n "${_ev%;}" ]; then
        SIGNALS=$((SIGNALS + 1))
        _ev_key=$(printf '%s' "$_ev" | cksum 2>/dev/null | awk '{print $1}')
        KINDS="${KINDS}event:${_ev_key:-0}|"
        _ev_what="внешнее событие (${_ev%;})"
        if [ -n "$WHAT" ]; then WHAT="$WHAT и $_ev_what"; else WHAT="$_ev_what"; fi
    fi
fi

# ── Пятый сигнал: ОДИН КЛАСС повторился за сутки ПОПЕРЁК СЕССИЙ ────────────────
# Третий сигнал считает подтверждения в границах сессии и межсессионный повтор не видит
# по построению. Живой случай 28 августа 2026: `pattern-subject-checked-by-enumeration`
# подтверждён трижды за ~15 часов — 27.08 09:56, 27.08 19:46, 28.08 01:07, — и ни одна
# пара не попала в одну сессию. Итог: агент написал «третий за сутки того же класса»
# ПРОЗОЙ ПО ПАМЯТИ. Число оказалось верным, но добытым не механизмом; в следующий раз
# память соврёт, и отличить будет нечем.
# Порог три, а не два: два подтверждения за сутки — обычное здоровое подкрепление.
if [ -f "$OUTCOMES" ]; then
    _cutoff=$(date -u -v-1d '+%Y-%m-%dT%H:%M:%SZ' 2>/dev/null \
              || date -u -d '1 day ago' '+%Y-%m-%dT%H:%M:%SZ' 2>/dev/null || printf '')
    if [ -n "$_cutoff" ]; then
        _day_name=$(jq -rs --arg c "$_cutoff" '
            [ .[] | select((.outcome // "") == "confirmed_knowledge"
                           or (.outcome // "") == "applicable_not_followed")
                  | select((.date // "") > $c) ]
            | group_by(.knowledge) | map(select(length >= 3))
            | .[0][0].knowledge // ""' "$OUTCOMES" 2>/dev/null || printf '')
        if [ -n "${_day_name:-}" ]; then
            SIGNALS=$((SIGNALS + 1))
            KINDS="${KINDS}daily:${_day_name%.md}|"
            _d_what="один класс повторился за сутки трижды и больше, а именно ${_day_name%.md}"
            if [ -n "$WHAT" ]; then WHAT="$WHAT и $_d_what"; else WHAT="$_d_what"; fi
        fi
    fi
fi

[ "$SIGNALS" -eq 0 ] && exit 0

# Метка хода нужна ДО первого выхода: ею подписывается и журнал срабатываний, и журнал
# исходов. До 29 августа 2026 она считалась ниже, после выхода по произнесённой цепочке, —
# и ход, где цепочка ПРОЗВУЧАЛА, не попадал никуда. То есть успех стража был невидим для
# его же замера, а доля «без исхода» тем самым завышалась систематически.
TURN_KEY=$(rc_turn_key "$TRANSCRIPT")

# Цепочка — это спуск, а не одно «почему». Три и больше считаем разбором; равно как два
# заголовка шаблона, три «←» или реестр мест с корнем — единственное определение в rc_chain_spoken.
MIN_WHYS="${FIVE_WHYS_MIN:-3}"
if rc_chain_spoken "$TRACE" "$MIN_WHYS"; then
    # Выход по произнесённой цепочке — ЕДИНСТВЕННЫЙ исход, который означает, что страж
    # сработал успешно: повод был, разбор состоялся, тормозить нечего. Он пишется в журнал
    # исходов, иначе в знаменатель попадают только неудачи, и правило эскалации («доля без
    # исхода выше половины — поднять уровень») считает по завышенному числу.
    #
    # Исход пишется ПОВОДУ, а не ходу (D227): цепочка гасит только сигнал, чей ПРЕДМЕТ
    # виден в тексте хода — файл переработки, имя знания, деталь события; поправка — по
    # совпадению ключа хода с хешем её записи (обе — cksum той же реплики: цепочка гасит
    # поправку, произнесённая в ходе самой поправки). До этого любая цепочка гасила ВСЕ
    # сигналы хода разом: за вечер 30 августа сигнал «поправка собеседника» входил в
    # инжекты ~15 раз и получил одну собственную цепочку — гашение чужими разборами
    # делало разрыв невидимым для замера outcome-share.
    # НАЗВАННЫЕ ПРЕДЕЛЫ: streak и question лексического предмета не несут и гасятся любой
    # цепочкой (у question и словарь ловит факт-вопросы — строгая атрибуция дала бы вечный
    # шум); разбор поправки, отложенный на поздний ход, механически не атрибуцируется —
    # сигнал продолжает напоминать до конца сессии, и это давление намеренное.
    mkdir -p "$STATE" 2>/dev/null
    TURN_TEXT=$(rc_turn_text "$TRANSCRIPT")
    for _k in $(printf '%s' "$KINDS" | grep -oE "$RC_KINDS_RE" 2>/dev/null | sed 's/:$//' | sort -u); do
        _att=0
        case "$_k" in
            discovery|streak|question) _att=1 ;;
            correction)
                grep -Fq "\"hash\":\"${TURN_KEY:-none}\"" "$CORRECTION" 2>/dev/null && _att=1 ;;
            rework)
                for _rf in ${_rw_files:-}; do
                    _bn="${_rf##*/}"
                    [ -n "$_bn" ] && grep -qF "$_bn" <<< "$TURN_TEXT" && { _att=1; break; }
                done ;;
            repeat|daily)
                _att_names="${_rep_key:-}"
                [ "$_k" = "daily" ] && _att_names="${_day_name:-}"
                for _nm in $(printf '%s' "$_att_names" | tr ',' ' '); do
                    _nm="${_nm%.md}"
                    [ -n "$_nm" ] && grep -qF "$_nm" <<< "$TURN_TEXT" && { _att=1; break; }
                done ;;
            event)
                for _tok in $(printf '%s' "${_ev:-}" | grep -oE '[A-Za-z0-9_.-]+\.(sh|py|md|tsv|js|ts|yml|yaml|json)|[0-9]{6,}' 2>/dev/null | sort -u); do
                    grep -qF "$_tok" <<< "$TURN_TEXT" && { _att=1; break; }
                done ;;
        esac
        [ "$_att" -eq 1 ] && rc_log_outcome "$STATE" "$SID" "${TURN_KEY:-0}" "$_k" "chain-spoken" "" "$TRACE"
    done
    exit 0
fi

# ── Дедуп: одно напоминание на каждый НОВЫЙ сигнал ────────────────────────────
