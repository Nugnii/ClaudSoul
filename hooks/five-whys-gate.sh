KINDS_RAW="$KINDS"

# Внутри СУБАГЕНТА права на отказ нет (10 сентября 2026), и это следствие того же правила,
# которым право объявлено выше: уровень 4 ставится только там, где последствие ОДНО.
#
# Повод. Субагент получает `session_id` РОДИТЕЛЯ — проверено на живых данных: четыре
# транскрипта `agent-*.jsonl` этой сессии несут один и тот же sessionId, различных ключей
# состояния за двадцать минут — один. Значит поводы родителя лежат в тех же файлах
# `*-fired-<SID>.jsonl`, что читает гейт, и субагент, не тронувший ни одного файла,
# получает отказ по чужой переработке. Пойман прожаркой дословно: отказ перечислил `rework`
# по 16 файлам, «поправку собеседника» и «вопрос собеседника» — ни одного из них субагент
# не создавал, а `correction-fired` был заведён за шесть часов до его старта.
# До расширения права (9 сентября) этого не случалось: отказ давал только `discovery`,
# который считается из текста ТЕКУЩЕГО хода, тогда как `rework` и `correction` — стоячее
# состояние родителя. Расширение права превратило наследуемое состояние в блокировку.
#
# Почему снимается право, а не фильтруются поводы. Различить «повод мой» и «повод родителя»
# нечем: ключ состояния у них общий, а у `rework-fired` нет даже поля даты. Раз последствия
# продолжения вызова два — законный отказ и ложный, — признак обязан вернуться на уровень
# 3: напоминание остаётся, отказ снимается (`case-2026-08-28-enforcement-is-a-property-of-consequence`).
#
# Признак берётся ЯВНЫЙ — префикс `agent-` в имени транскрипта, а не «имя не равно SID»:
# второе сочло бы субагентом любую фикстуру с транскриптом вроде `t.jsonl` и обнулило бы
# отказ во всём наборе тестов. Молчание признака безопасно: имя не узналось → считаем
# родителем → поведение остаётся прежним.
# НАЗВАННЫЙ ПРЕДЕЛ: имя транскрипта даёт харнесс, и смена схемы имён онемит признак молча.
# Условие снятия: у поводов появится владелец-актор рядом с владельцем-проектом
# (`rc_project_of`) — тогда поводы субагента станут отличимы и отказ вернётся полным.
