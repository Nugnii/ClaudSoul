    # инжекты ~15 раз и получил одну собственную цепочку — гашение чужими разборами
    # делало разрыв невидимым для замера outcome-share.
    # НАЗВАННЫЕ ПРЕДЕЛЫ: streak и question лексического предмета не несут и гасятся любой
    # цепочкой (у question и словарь ловит факт-вопросы — строгая атрибуция дала бы вечный
    # шум); разбор поправки, отложенный на поздний ход, механически не атрибуцируется —
    # сигнал продолжает напоминать до конца сессии, и это давление намеренное.
    mkdir -p "$STATE" 2>/dev/null
    TURN_TEXT=$(rc_turn_text "$TRANSCRIPT")
    for _k in $(printf '%s' "$KINDS" | grep -oE "$RC_KINDS_RE" 2>/dev/null | sed 's/:$//' | sort -u); do
        _att=0
        case "$_k" in
            # СТОЯЧИЙ РОД, ЧЕЙ ПРЕДМЕТ — СОБСТВЕННЫЙ БЛОК РЕЧИ, ЗАСЧИТЫВАЕТСЯ ПО ЭТОМУ ЖЕ
            # БЛОКУ (24 сентября 2026, поправка владельца, D481). Здесь стояло `_att=1`
            # безусловно, и цепочка про ЧУЖОЙ предмет записывала поводу исход
            # `chain-spoken`. Замер сессии 9ea6931d: `self_repeat` сработал 11 раз,
            # `chain-spoken` записан 7 раз, а сам повод (капкан `grep -q` под pipefail)
            # поминают 2 хода из 21 с маркером повтора. Решающий ход — 92 символа, цепочки
            # в нём нет вовсе. То есть замер «страж помог» врал в свою пользу, и врал он
            # ровно там, где работа идёт потоком и разборы на другие темы не иссякают.
            # Предмет этих двух родов — `LAST_BLOCK` (см. `rc_subject_of`, :676), по нему и
            # судим. Последствие ОДНО и оно метрическое: исход становится `deferred` вместо
            # `chain-spoken`. Ни отказов, ни напоминаний это не добавляет — `EVENT` поднимают
            # только роды с правом на отказ (:817), а стоячие его не поднимают.
            # Вход `rc_chain_spoken` — СЛЕД разбора, а не сырой текст: его делает
            # `rc_trace_text` со stdin (владелец формы — `hooks/root-cause-lib.sh:971`).
