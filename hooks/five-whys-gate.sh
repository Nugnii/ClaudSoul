# Проект СЕССИИ, а не рабочий каталог процесса хука: внешние поводы принадлежат проекту,
# и читать их надо от того же корня, от которого их завели. Определяется здесь, потому
# что события читаются ниже (`rc_open_events`), а прежний `_FWG_CWD` вычислялся ещё ниже —
# на момент чтения событий его не существовало.
_FWG_CWD0=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
[ -n "$_FWG_CWD0" ] || _FWG_CWD0="$PWD"
command -v rc_project_of >/dev/null 2>&1 && RC_EVENT_PROJECT=$(rc_project_of "$_FWG_CWD0")

# ── Сигналы повтора: чужие детекторы, свой счётчик не заводится ───────────────
# Поводы принадлежат АКТОРУ вызова (D452). `session_id` харнесс кладёт общим родителю и
# субагенту, поэтому до 18 сентября 2026 гейт перечислял субагенту чужое: наблюдено
# дословно — субагенту инжектнут `🔁 Второй заход на test_gate_deny_per_kind.sh`, файла
# которого он не касался. Обратное направление дороже: повод `rework-fired`, накрученный
# тремя субагентами, давал отказ уровня 4 РОДИТЕЛЮ.
# У родителя суффикс ПУСТ, поэтому имена его файлов не меняются и поведение остаётся
# байт-в-байт прежним; владелец суффикса один — `resolve_actor_suffix` в `paths-lib.sh`.
#
# ПОЧЕМУ У ВСЕХ ЧЕТЫРЁХ, хотя писателей чинится только два. `rework` и `error_streak`
# считают действия ВЫЗЫВАЮЩЕГО, и их писатели переводятся на актора (D453, D454).
# `correction-fired` и `question-open` пишет собеседник-ЧЕЛОВЕК, и писатели остаются
# общими намеренно: поправка и вопрос адресованы тому, с кем шёл разговор, то есть
