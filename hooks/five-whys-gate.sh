# ── Отказ вместо напоминания ──────────────────────────────────────────────────
# Поправка собеседника 28 августа 2026, дословно: «"Страж проекта поймал мой же новый
# тест… Чиню." — и сразу чинить пошёл. А вместо "чиню" должен был сработать страж хук
# 5 почему». Проверка по журналу: гейт в том ходе СРАБОТАЛ и сказал «разбора причин не
# было». Прочитано — и починено без цепочки. Напоминание не останавливает; это тот же
# разрыв, что меряется как «знание было уместно и не применено».
#
# Три условия сразу, и каждое сужает намеренно:
#   событийный сигнал — стоячие не блокируют (иначе стоп на сутки);
#   цепочки в ходе нет — сказал цепочку, работаешь дальше, это и есть выход;
#   действие ПИШЕТ — чтение и осмотр обязаны проходить, иначе цепочку не из чего строить.
# Прецедент цены записан в шапке `command-scope-lib.sh`: страж с отказом дважды
# заблокировал запись собственного теста и пункта долга про этот же дефект.
IS_WRITE=0
case "$TOOL_NAME" in
    Edit|Write|MultiEdit) IS_WRITE=1 ;;
    Bash)
        _cmd=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
        # Кавычки снимаем: «>» внутри строки-аргумента записью не является. Отводы в
        # /dev/null тоже не запись — это глушение вывода, а не изменение мира.
        _bare=$(printf '%s' "$_cmd" | awk '{
            s = $0
            gsub(/\047[^\047]*\047/, " ", s)
            gsub(/"[^"]*"/, " ", s)
            gsub(/[0-9]?>>?[[:space:]]*\/dev\/null/, " ", s)
            # Слияние и перенаправление ПОТОКОВ — не запись в мир: 2>&1, >&2, &>.
            # Поймано на себе 28 августа 2026: чисто читающая команда с «2>&1» получила
            # отказ, потому что признак искал СИМВОЛ «>», а не смысл «изменяет что-то вне
            # себя». Перечень форм записи вместо правила — тот же класс, что перечень форм
            # находки, названный пределом в этом же файле.
            gsub(/[0-9]?>&[0-9]/, " ", s)
            gsub(/&>>?/, " ", s)
            print s
        }')
        # Запись = перенаправление В ФАЙЛ (после «>» стоит путь, а не дескриптор), либо
        # команда, меняющая мир по существу. Правило, а не перечень символов.
        grep -qE '>>?[[:space:]]*[^&[:space:]]|[[:space:]]tee[[:space:]]|^tee[[:space:]]|git[[:space:]]+commit' <<< "$_bare" && IS_WRITE=1
        # Запись БЕЗ формы в строке команды. Замер 29 августа 2026 по расшифровке живой
        # сессии: правок через интерпретатор 198, правок на месте 7, перенаправлений 97,
        # фиксаций 13 — то есть 205 из 315 (65%) проходили мимо отказа. Замер при заведении
        # признака отвечал на вопрос «через Edit/Write или через Bash» и был верен; вопрос
        # «какую долю Bash-правок признак накрывает» тогда не задавался, и признак накрыл
        # ровно ту долю, у которой запись имеет ФОРМУ в строке.
        #
        # Проверка идёт по СЫРОЙ команде, а не по `_bare`: тот срезает кавычки, вместе с
        # ними исчезает и `open("f","w")`.
        #
        # КОНТРПРИМЕР: читающий вызов интерпретатора (`read_text`, `print`, подсчёт) сюда
        # не попадает и обязан проходить — «чтение, поиск и осмотр не блокируются» есть
        # условие работоспособности отказа, а не поблажка.
        # НАЗВАННЫЙ ПРЕДЕЛ: перечислены формы записи, а не выражено правило «меняет мир вне
        # себя»; запись через незнакомый способ (свой скрипт-обёртка, `awk` с
        # перенаправлением внутри, редактор) признаком не ловится.
        # Условие снятия: предел перестаёт держаться, когда способ правки станет наблюдаем
        # не по тексту команды, а по факту изменения файлов — например, сверкой состояния
        # рабочего дерева до и после вызова.
