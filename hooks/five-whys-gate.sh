# Цепочка — это спуск, а не одно «почему». Три и больше считаем разбором; равно как два
# заголовка шаблона, три «←» или реестр мест с корнем — единственное определение в rc_chain_spoken.
# Предмет повода — рядом с его отпечатком (9 сентября 2026). Отпечаток (cksum) годится для
# дедупа и не годится для ВОЗВРАТА: замер по живым журналам — 954 записи исходов, предмет
# назван в 4 (0,4%), и все четыре записаны рукой через scripts/outcome.sh. Свод при этом
# требовал «довести до исхода» 147 поводов, ни одного из которых показать не мог.
# Дробь корня: мест записи исхода 4, передают пустой предмет 3 — все автоматические;
# разделитель — автоматический писатель против ручного.
# НАЗВАННЫЙ ПРЕДЕЛ: `question` и `streak` предмета не несут ни в одном носителе (продюсер
# пишет только digest) — им подставляется общая формулировка хода. Условие снятия:
# продюсер начнёт писать текст рядом с digest.
rc_subject_of() {
    case "${1:-}" in
        discovery|self_repeat)  printf '%s' "${LAST_BLOCK:-}" | tr '\n' ' ' ;;
        correction) tail -1 "$CORRECTION" 2>/dev/null | jq -r '.snippet // ""' 2>/dev/null ;;
        rework)     printf '%s' "${_rw_files:-}" | tr '\n' ' ' ;;
        repeat)     printf '%s' "${_rep_key:-}" ;;
        event)      printf '%s' "${_ev:-}" | tr '\n' ' ' ;;
        breakage)   printf '%s' "${_brk:-}" | tr '\n' ' ' ;;
        *)          printf '%s' "${WHAT:-}" ;;
    esac
}

