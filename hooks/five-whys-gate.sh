# предыдущую, и 28 августа 2026 на вопрос «срабатывал ли гейт в том ходе» ответить было
# нечем: пришлось разбирать расшифровку сессии по индексам. Механизм, который не может
# показать собственную историю, диагностируется только снаружи.
