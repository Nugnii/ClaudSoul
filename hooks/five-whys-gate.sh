        # «Вызов пишет» — у владельца, `is_write_command` в `command-scope-lib.sh` (D1160, R3): своя копия
        # регэкспом по `redirect_bare` стояла здесь до 1 ноября 2026 и не видела 17 форм записи из 18 (цель в
