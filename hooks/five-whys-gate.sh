# Стоячие сроды (`FWG_STANDING`) отказа не дают и в
# токены не входят; служебный префикс `turn:` отбрасывается.
fwg_chain_tokens() {
    printf '%s' "${1:-}" | tr '|' '\n' | while IFS= read -r _tok; do
        [ -n "$_tok" ] || continue
        case "$_tok" in turn:*) continue ;; esac
        _kd="${_tok%%:*}"
        fwg_grants_deny "$_kd" || continue
        # `rework` больше НЕ сводится к голому роду: его ключ с 20 сентября 2026 несёт
        # предмет и ступень глубины (`rework:<файл>:<ступень>`), и токен идёт целиком,
        # как у прочих сродов. Прежняя строка `printf 'rework'` была тем местом, где
        # отпечаток терялся, даже если бы ключ его нёс.
        printf '%s\n' "$_tok"
    done | sort -u
}
