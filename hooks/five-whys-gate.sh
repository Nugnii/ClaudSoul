OUTCOMES="$STATE/disagreement-outcomes.jsonl"
# Живой журнал: отменённая отзывом строка снимается. Здесь искажения ещё нет (замер
# 1 сентября 2026: «второй раз в ту же стену» — 7 и до, и после снятия), но носитель тот
# же, и класс закрывается целиком, а не там, где симптом уже виден.
DIS_LIB_FW="${DIS_LIB_FW:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/disagreement-lib.sh}"
# shellcheck source=/dev/null
[ -f "$DIS_LIB_FW" ] && source "$DIS_LIB_FW" 2>/dev/null
if [ -f "$OUTCOMES" ]; then
    if command -v dis_live_outcomes >/dev/null 2>&1; then
        _fw_journal=$(dis_live_outcomes "$STATE" 2>/dev/null)
    else
        _fw_journal=$(cat "$OUTCOMES" 2>/dev/null)
    fi
    _rep=$(printf '%s\n' "$_fw_journal" | jq -s --arg sid "$SID" '
        [ .[] | select((.session // "") == $sid and (.outcome // "") == "confirmed_knowledge") ]
        | group_by(.knowledge) | map(select(length >= 2)) | length' 2>/dev/null || printf '0')
    case "${_rep:-}" in ''|*[!0-9]*) _rep=0 ;; esac
    if [ "$_rep" -gt 0 ]; then
        _rep_name=$(jq -rs --arg sid "$SID" '
            [ .[] | select((.session // "") == $sid and (.outcome // "") == "confirmed_knowledge") ]
            | group_by(.knowledge) | map(select(length >= 2)) | .[0][0].knowledge // ""' "$OUTCOMES" 2>/dev/null || printf '')
        SIGNALS=$((SIGNALS + _rep))
        # В ключ идут ИМЕНА знаний, а не их число. Счёт одинаков у разных знаний, и
        # 27 августа собеседник назвал это дословно: «повтор уплывает». Тогда починили
        # ГРАНИЦУ (сессия → ход), а ключ остался счётным — и 28 августа тот же дефект
        # нашёлся внутри хода. Отпечаток экземпляра снимает вопрос независимо от границы.
        _rep_key=$(jq -rs --arg sid "$SID" '
            [ .[] | select((.session // "") == $sid and (.outcome // "") == "confirmed_knowledge") ]
            | group_by(.knowledge) | map(select(length >= 2)) | map(.[0].knowledge) | sort
            | join(",")' "$OUTCOMES" 2>/dev/null || printf '')
        KINDS="${KINDS}repeat:${_rep_key:-none}|"
        _rep_what="одно знание подтвердилось за сессию дважды и больше"
        [ -n "${_rep_name:-}" ] && _rep_what="$_rep_what, а именно ${_rep_name%.md}"
        if [ -n "$WHAT" ]; then WHAT="$WHAT и $_rep_what"; else WHAT="$_rep_what"; fi
    fi

    # ТРЕТИЙ СИГНАЛ, ВТОРАЯ ПОЛОВИНА: повтор НЕПРИМЕНЕНИЯ (D341, 6 сентября 2026).
    # Выше считается `confirmed_knowledge` — «знание сработало дважды». Здесь считается
    # `applicable_not_followed` — «знание относилось к делу и дважды НЕ сработало».
    # Это разные поводы, и второй сильнее: проектный CLAUDE.md зовёт его единственной
    # метрикой разрыва «знание → действие».
    #
    # Почему отдельным счётом, а не добавлением исхода в запрос выше. Сообщение гейта
    # обязано называть, ЧТО повторилось: услышав «знание подтвердилось дважды», разбор
    # пойдёт искать успешное применение и не найдёт его. Один мешок стирает эту разницу.
    #
    # Повод измерен на сессии b9002213: единственное знание с двумя записями за сессию —
    # `pattern-shell-portability` с исходом `applicable_not_followed` (не-ASCII вплотную к
    # переменной: 15:04 и 19:12, интервал час). Третий сигнал вернул 0, четвёртый (окно
    # сутки, порог 3) молчал по порогу. Полоса «дважды за сессию не применил» не
    # обслуживалась никем, при том что гейт за ту же сессию сработал 197 раз по другим знаниям.
    #
    # КОНТРПРИМЕР: `not_applicable` сюда НЕ входит — там знание оказалось мимо, и повторять
    # нечего. Различие проверено ногой теста (s2c: два `not_applicable` → молчание).
    _nf=$(printf '%s\n' "$_fw_journal" | jq -s --arg sid "$SID" '
        [ .[] | select((.session // "") == $sid and (.outcome // "") == "applicable_not_followed") ]
        | group_by(.knowledge) | map(select(length >= 2)) | length' 2>/dev/null || printf '0')
    case "${_nf:-}" in ''|*[!0-9]*) _nf=0 ;; esac
    if [ "$_nf" -gt 0 ]; then
        _nf_name=$(printf '%s\n' "$_fw_journal" | jq -rs --arg sid "$SID" '
            [ .[] | select((.session // "") == $sid and (.outcome // "") == "applicable_not_followed") ]
            | group_by(.knowledge) | map(select(length >= 2)) | .[0][0].knowledge // ""' 2>/dev/null || printf '')
        SIGNALS=$((SIGNALS + _nf))
        _nf_key=$(printf '%s\n' "$_fw_journal" | jq -rs --arg sid "$SID" '
            [ .[] | select((.session // "") == $sid and (.outcome // "") == "applicable_not_followed") ]
            | group_by(.knowledge) | map(select(length >= 2)) | map(.[0].knowledge) | sort
            | join(",")' 2>/dev/null || printf '')
        KINDS="${KINDS}notfollowed:${_nf_key}|"
        _nf_what="знание не применено дважды за сессию, а именно ${_nf_name%.md}"
        if [ -n "$WHAT" ]; then WHAT="$WHAT и $_nf_what"; else WHAT="$_nf_what"; fi
    fi
fi

