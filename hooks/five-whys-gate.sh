                    [ -n "$_nm" ] && grep -qF "$_nm" <<< "$TURN_TEXT" && { _att=1; break; }
                done ;;
            event)
                # ИМЯ ФАЙЛА УЗНАЁТСЯ ПО УСТРОЙСТВУ (24 сентября 2026, корень R3): здесь стоял
                # тот же закрытый перечень расширений, что и в `RC_TRACE_ADDR_RE`, — стек
                # ClaudSoul. Событие приходит из ЛЮБОГО проекта, и `.tsx`/`.prisma` перечень
                # не видел. Расширение обязано начинаться С БУКВЫ: последствие расширения
                # признака здесь ОБРАТНОЕ соседнему — лишний токен делает гейт МЯГЧЕ, а не
                # строже, поэтому версии вида `1.2` в токены не пускаются.
                for _tok in $(printf '%s' "${_ev:-}" | grep -oE '[A-Za-z0-9_.-]*[A-Za-z0-9_-]\.[A-Za-z][A-Za-z0-9]{0,7}|[0-9]{6,}' 2>/dev/null | sort -u); do
                    grep -qF "$_tok" <<< "$TURN_TEXT" && { _att=1; break; }
                done ;;
        esac
        [ "$_att" -eq 1 ] && rc_log_outcome "$STATE" "$SID" "${TURN_KEY:-0}" "$_k" "chain-spoken" "$(rc_subject_of "$_k")" "$TRACE"
    done
    # ПАМЯТЬ ЗАЧТЁННОЙ ЦЕПОЧКИ (12 сентября 2026, ADR-020). Единица зачёта — СОСТАВ ПОВОДОВ,
    # а не окно текста хода: окно `rc_turn_text` обнуляется любой записью user в расшифровке
    # (реплика владельца, уведомление фоновой задачи, служебная заметка), и в этом клиенте
    # до конца хода в расшифровку попадает только первый текстовый блок. Замер по сессии
