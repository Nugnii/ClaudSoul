# Проверка результата: bash hooks/tests/test_adv_hollow_restore_broken.sh даёт 0
# ВЫХОЛАЩИВАНИЕ ПРЕДМЕТА — ОДИН ВЛАДЕЛЕЦ НА ВСЕХ ПОТРЕБИТЕЛЕЙ.
