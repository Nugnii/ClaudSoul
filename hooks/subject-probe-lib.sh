# Тело вынесено из `scripts/behavior-condition-probe.sh` 22 сентября 2026 (D474), когда у
# приёма появился ВТОРОЙ потребитель — объявлятель предмета `scripts/witness-subject-propose.sh`.
# Копия дала бы факту «как выхолостить предмет» двух владельцев, расходящихся молча (корень
# R1): у прибора три вида предмета — список, каталог, файл, — и правка любого из них в одном
# месте прошла бы мимо второго.
# Чем решалось раньше: этим же кодом внутри цикла прибора, единственным местом. Судьба
# предшественника названа: он снят, прибор ЗОВЁТ библиотеку.
#
# Функция НЕ судит и не считает — она отвечает кодом прогона на выхолощенном предмете:
# 0 — тест зелен без предмета (для прибора это обвинение), 9 — выхолостить не удалось
# (предмета нет, копия не легла), прочее — тест покраснел.
# Решение о смысле кода принимает ЗОВУЩИЙ: у прибора код 0 значит «подозреваемый», у
# объявлятеля ненулевой значит «этот кандидат и есть предмет».

# СВИДЕТЕЛЬ ЗАПУСКАЕТСЯ БЕЗ ЧУЖОГО STDIN (22 сентября 2026, D474). Зовущий идёт циклом
# `while read` по перечню, и запущенный тест НАСЛЕДУЕТ этот перечень своим стандартным
# входом: тест, читающий stdin, выпивает остаток очереди, а цикл тихо кончается раньше
# срока. Замер: объявлятель обработал 10 свидетелей из 52 и вышел кодом 0 — недосчёт
# неотличим от «работы сделано». Перенаправление стоит у ВСЕХ трёх прогонов: список,
# каталог, файл — вид предмета к этому отношения не имеет.
# СНИМОК — ТО ЖЕ ДЕРЕВО, КОТОРОЕ ПЕРЕЧИСЛЯЕМ (22 сентября 2026, противник, класс I).
#
# Прежде у факта «что сейчас в дереве» было ДВА владельца, собранных на каждом конце
# отдельно (корень R1): вселенную свидетелей прибор брал глобом по РАБОЧЕМУ дереву, а
# снимок — из `git archive HEAD`; объявлятель читал перечень в рабочем дереве, судил клон
# HEAD и вписывал строку обратно в рабочую копию. Расхождение давало два разных вреда:
#   · объявление, указывающее на незакоммиченный механизм, роняло ВЕСЬ прибор кодом 2
#     («предмет недоступен в снимке»), и ни один свидетель не получал вердикта;
#   · объявлятель предлагал предмет, вычитанный из коммита, файлу, который с тех пор судит
#     другое, — то есть САМ производил ту ложную зелень, ради поиска которой построен прибор,
#     а новый, ещё не закоммиченный свидетель попадал в класс «рамка не собралась».
#
# История нужна обоим (часть свидетелей берёт положительный контроль через `git show`),
# поэтому снимок собирается клоном И накрывается нынешним содержимым рабочего дерева:
# отслеживаемые плюс новые, минус игнорируемые — перечень у их владельца, `git ls-files`.
# Удалённые в рабочем дереве остаются в снимке намеренно: вселенная берётся из рабочего
# дерева, и такого свидетеля никто не перечислит, а его механизм может быть чужим предметом.

# sp_snapshot <куда> → 0 снимок собран, 2 не собрался
sp_snapshot() {
    local _dst="$1" _f
    [ -n "$_dst" ] || return 2
    git clone -q --local . "$_dst" 2>/dev/null || return 2
    git ls-files -co --exclude-standard -z 2>/dev/null | while IFS= read -r -d '' _f; do
        [ -f "$_f" ] || continue
        mkdir -p "$_dst/$(dirname "$_f")" 2>/dev/null
        cp -p "$_f" "$_dst/$_f" 2>/dev/null
    done
    return 0
}

# СРОК СВИДЕТЕЛЮ СТАВИТ ЕГО ВЛАДЕЛЕЦ (22 сентября 2026, противник, атака 4).
# Договор дерева уже назван набором: «зависание — тоже провал и должно называться провалом»
