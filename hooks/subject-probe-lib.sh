SP_WITNESS_TIMEOUT="${SP_WITNESS_TIMEOUT:-240}"
# Владелец срока — ЧАСТЬ ЭТОЙ БИБЛИОТЕКИ, а не чужой инструмент: без него договор
# «свидетель не повесит зовущего» не выполним, и тихая работа без сторожа обещала бы
# защиту, которой нет. Потому отсутствие — сломанная своя установка, а не другой проект.
_SP_TL="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/timeout-lib.sh"
[ -f "$_SP_TL" ] || _SP_TL="$HOME/.claude/hooks/timeout-lib.sh"
if [ -f "$_SP_TL" ]; then
    # shellcheck source=/dev/null
    . "$_SP_TL"
else
    echo "BROKEN: нет hooks/timeout-lib.sh — свидетелю не поставить срока" >&2
    exit 2
fi

# СРОК КОНКРЕТНОГО СВИДЕТЕЛЯ — ИЗ ЕГО БАЗИСА (23 сентября 2026, D474). Общий срок ловил тех,
# кто дороже ПО ПРИРОДЕ: замер 23 сентября дал 17 «не уложившихся», и у семи из них базис
# набора заведомо выше 30 с (`test_defect_registry_cache` 228 с, `test_docs_match_tree` 109 с).
# Прибор называл нагрузкой то, что является ценой теста, и лишал его вердикта. Владелец
# расчёта один — `deadline_for_test` в `timeout-lib.sh`, тот же, кого зовёт сторож набора.
# Свидетеля нет в базисе — остаётся SP_WITNESS_TIMEOUT, то есть прежнее поведение.
# ПОТОЛОК ПРИБОРА НИЖЕ ПОТОЛКА НАБОРА, и цена названа числом. Расчёт по базису даёт дорогому
# свидетелю 684 с (228 × 3), а прибор гоняет каждого ДО ДВУХ раз и проходит шестьсот штук:
# без потолка худший случай уходит в часы. 240 с покрывает базис самого дорогого свидетеля
# (`test_defect_registry_cache` 228 с) и второго за ним (`test_docs_match_tree` 109 с), то
# есть класс «не уложился» пустеет от тех, кто дорог ПО ПРИРОДЕ, а не от нагрузки.
# Цена: прогон прибора вырастает на сумму базисов этих свидетелей — порядка десяти минут.
SP_WITNESS_CAP="${SP_WITNESS_CAP:-240}"
_sp_deadline() {  # <путь свидетеля> → секунды
    local _n="${1##*/}" _d
    if command -v deadline_for_test >/dev/null 2>&1; then
        _d=$(deadline_for_test "$_n" "$SP_WITNESS_TIMEOUT")
    else
        _d="$SP_WITNESS_TIMEOUT"
    fi
    case "$_d" in ''|*[!0-9]*) _d="$SP_WITNESS_TIMEOUT" ;; esac
    [ "$_d" -gt "$SP_WITNESS_CAP" ] && _d="$SP_WITNESS_CAP"
    printf '%s' "$_d"
}

# sp_run_witness <снимок> <свидетель> <файл вывода> → код свидетеля (124 — срок истёк)
sp_run_witness() {
    CLAUDSOUL_REPO="$1" CLAUDSOUL_ROOT="$1" \
        run_with_timeout "$(_sp_deadline "$2")" bash "$2" > "$3" 2>&1 < /dev/null
}

# ПРОГОН БЕЗ ПРИВЯЗКИ — ВТОРОЙ ИНСТРУМЕНТ, А НЕ ЗАМЕНА ПЕРВОМУ (22 сентября 2026).
# Привязка корня к снимку лечит род M: без неё тест резолвит предмет в НАСТОЯЩЕМ дереве, где
# тот цел, и выхолащивание не судит ничего. Но у части свидетелей она ОТБИРАЕТ предмет:
#   · тест судит поведение системы ПРИ ОТСУТСТВИИ этих переменных (`rc_env_is_real` молчит на
#     приватном пути, а песочница прибора и есть приватный путь);
#   · тест строит СВОЮ вложенную песочницу и наследует чужие переменные, не переопределив их.
# Волна разбора 22 сентября 2026 нашла таких поимённо: test_measurement_due, test_periodic_digests,
# test_project_conformance_asks_readers, test_external_events, test_impact_inject, test_knowledge_meta,
# test_doc_impact_check, test_docs_family_a2_denies — вне прибора все зелёные.
# Один код возврата отвечал за два состояния мира: «свидетель сломан» и «привязка отобрала у
# него предмет». Различить их можно только вторым прогоном — ЧИСТЫМ.
# sp_run_witness_bare <снимок> <свидетель> <файл вывода> → код свидетеля без привязки корня
sp_run_witness_bare() {
    ( unset CLAUDSOUL_REPO CLAUDSOUL_ROOT
      run_with_timeout "$(_sp_deadline "$2")" bash "$2" > "$3" 2>&1 < /dev/null )
}

# ВЕСЬ СУД ИДЁТ В ОДНОМ ОКРУЖЕНИИ (22 сентября 2026). Если зовущий измерил, что свидетель
# судим только БЕЗ привязки корня (живой прогон с ней красен, без неё зелен), он ставит
# SP_BARE=1 — и выхолощенный прогон идёт там же, где живой. Судить предмет в одном окружении,
# а предпосылку в другом значило бы сравнивать разные миры.
# Режим выбирается ИЗМЕРЕНИЕМ у зовущего, а не догадкой здесь: библиотека не знает, почему
# свидетель красен, и не решает за прибор.
sp_witness_run() {  # <снимок> <свидетель> <файл вывода> — с привязкой либо без, по SP_BARE
    if [ "${SP_BARE:-0}" = 1 ]; then
        sp_run_witness_bare "$1" "$2" "$3"
    else
        sp_run_witness "$1" "$2" "$3"
    fi
}

# sp_hollow_run <снимок> <свидетель> <предмет> <файл вывода>
sp_hollow_run() {
    SNAP="$1"; t="$2"; subj="$3"; OUTF="$4"
    (
        cd "$SNAP" || exit 9
        # ПРЕДМЕТ БЫВАЕТ ГРУППОЙ, А НЕ ФАЙЛОМ (21 сентября 2026, решение владельца).
        # Свидетель конвейера судит НЕСКОЛЬКО механизмов сразу: `test_ablation_runner.sh`
        # краснеет от выхолащивания любого из пяти файлов `scripts/ablation/`. Назвать одно
        # звено предметом значило бы гадать — прогон показывает, что тест зависит от всех
        # поровну. Объявление `# СУДИТ: scripts/ablation/` (косая на конце) выхолащивает
        # ВЕСЬ каталог, и честный свидетель обязан покраснеть.
        # Замер, из которого это выросло: у 14 свидетелей из 41 краснело больше одного
        # кандидата, и все они — конвейеры.
        # СПИСОК ПРЕДМЕТОВ: выхолащиваются ВСЕ перечисленные, честная нога обязана покраснеть
        # от потери любого. Признак списка — пробел в объявлении; каталог и «дерево» с ним не
        # смешиваются, у них свои ветки выше и ниже.
        case "$subj" in
            *[[:space:]]*)
                # ЧТО ПОДМЕНИЛ — ТО И ВЕРНУ, НА КАЖДОМ ВЫХОДЕ (22 сентября 2026, противник).
                # Здесь стояло `rm -f $_kept` на обеих неудачных ветках: копии уже подменённых
                # файлов СТИРАЛИСЬ вместо возврата, и снимок оставался с заглушками — а прибор
                # продолжал судить по нему остальных. Восстановление же стояло ОДНОЙ строкой
                # после цикла, то есть предполагало, что цикл дошёл до конца.
                # Вторая половина той же дыры: повторённый в объявлении путь копировал в `.keep`
                # уже ЗАГЛУШКУ, затирая настоящую копию, — и прогон отвечал НУЛЁМ при навсегда
                # выхолощенном файле. Теперь `.keep` пишется только если его ещё нет.
                _sp_restore() { for _r in $_kept; do mv "$_r" "${_r%.keep}" 2>/dev/null; done; }
                _kept=""
                for _one in $subj; do
                    [ -f "$_one" ] || { _sp_restore; exit 9; }
                    if [ ! -f "$_one.keep" ]; then
                        cp "$_one" "$_one.keep" 2>/dev/null || { _sp_restore; exit 9; }
                        _kept="$_kept $_one.keep"
                    fi
                    case "$_one" in
                        *.py) printf 'pass\n' > "$_one" ;;
                        *) printf '#!/usr/bin/env bash\n:\n' > "$_one" ;;
                    esac
                done
                sp_witness_run "$SNAP" "$t" "$OUTF"
                rc=$?
                _sp_restore
                exit "$rc"
                ;;
        esac
        if [ "${subj%/}" != "$subj" ]; then
            _dir="${subj%/}"
            [ -d "$_dir" ] || exit 9
            cp -R "$_dir" "$_dir.keepdir" 2>/dev/null || exit 9
            # ВЫХОЛАЩИВАЮТСЯ ВСЕ ФАЙЛЫ КАТАЛОГА, а не только .sh и .py (22 сентября 2026).
            # Каталог объявляют предметом там, где механизм РАЗМАЗАН по нескольким файлам, и
            # часть из них бывает ДАННЫМИ: у конфига публикации это exclude.txt, forbidden.txt,
            # redact.sed - шаблоны, которыми гейт и работает. Прежде их не трогали, и свидетель
            # оставался зелёным при выхолощенном предмете: прибор называл его ложно-зелёным,
            # а виноват был приём. Для данных заглушка - ПУСТОЙ файл: "правил нет" и есть их
            # мёртвое состояние, тогда как строка с shebang была бы ещё одним правилом.
            find "$_dir" -type f -print0 2>/dev/null \
              | while IFS= read -r -d '' _gf; do
                    case "$_gf" in
                        *.py) printf 'pass\n' > "$_gf" ;;
                        *.sh) printf '#!/usr/bin/env bash\n:\n' > "$_gf" ;;
                        *) : > "$_gf" ;;
                    esac
                done
            sp_witness_run "$SNAP" "$t" "$OUTF"
            rc=$?
            rm -rf "$_dir" && mv "$_dir.keepdir" "$_dir"
            exit "$rc"
        fi
        # ЗАПИСЬ СКВОЗЬ ССЫЛКУ ПОРТИТ ЦЕЛЬ, А ВОЗВРАТ КЛАДЁТ НА ЕЁ МЕСТО ФАЙЛ (22 сентября
        # 2026, противник, раунд 2). У ссылки cp берёт содержимое ЦЕЛИ, printf пишет СКВОЗЬ
        # неё и выхолащивает цель, а mv возвращает обычный файл вместо ссылки: снимок
        # остаётся испорченным для всех следующих свидетелей, и честный сосед, судящий ту же
        # цель, попадает в "рамка не собралась". Носителей в дереве сегодня нет
        # (git ls-files -s без записей 120000), класс достижим с первой же ссылкой.
        # Ссылка выхолащивается САМА: снимается, на её место кладётся заглушка, возврат
        # восстанавливает ссылку целиком.
        if [ -L "$subj" ]; then
            _link_to=$(readlink "$subj" 2>/dev/null) || exit 9
            rm -f "$subj" 2>/dev/null || exit 9
            if [ "${subj%.py}" != "$subj" ]; then printf 'pass\n' > "$subj"
            else printf '#!/usr/bin/env bash\n:\n' > "$subj"; fi
            sp_witness_run "$SNAP" "$t" "$OUTF"
            rc=$?
            rm -f "$subj" 2>/dev/null
            ln -s "$_link_to" "$subj" 2>/dev/null
            exit "$rc"
        fi
        cp "$subj" "$subj.keep" 2>/dev/null || exit 9
        # ЗАГЛУШКА НЕ МЕНЯЕТ ПОТОК УПРАВЛЕНИЯ ЗОВУЩЕГО (20 сентября 2026, работа по D342).
        #
        # Здесь стояла развилка: «тест источает предмет» → пустой файл, иначе → заглушка с
        # `exit 0`. Источание узнавалось grep-ом по БАЗОВОМУ ИМЕНИ в строке `source`, а
        # обычная форма `LIB="$ROOT/hooks/timeout-lib.sh"` … `. "$LIB"` имени в той строке
        # не несёт. Развилка уходила в ветку заглушки, а `source` файла с `exit 0` завершает
        # САМ ТЕСТ кодом ноль — зелёный по построению, и прибор звал это «зелен на мёртвом
        # предмете». Контраст предъявлен прогоном на `test_timeout_lib.sh`: заглушка `exit 0`
        # даёт rc=0, пустой файл — rc=1.
        #
        # Развилка снята целиком, потому что её не нужно чинить: заглушка, которая ничего не
        # делает и НЕ выходит, верна в обоих мирах. Запущенная как программа — код 0,
        # механизм жив и бездеятелен. Источённая — не объявляет ни одной функции, и тест
        # падает на первом же вызове. Одно правило вместо признака с непроверенной точностью.
        if [ "${subj%.py}" != "$subj" ]; then
            printf 'pass\n' > "$subj"
        else
            printf '#!/usr/bin/env bash\n:\n' > "$subj"
        fi
