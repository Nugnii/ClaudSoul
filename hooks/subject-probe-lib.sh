# (`scripts/measurement-due.sh:267`) — повиснуть могла вся граница хода.
# Код 124 — срок истёк — от честного падения не отличается НАМЕРЕННО: для обоих потребителей
# это «свидетель не зелен», а различать их значит заводить пятый класс без замера.
