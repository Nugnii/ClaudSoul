#!/usr/bin/env bash
# running-file-edit-guard.sh — PreToolUse[Write|Edit|MultiEdit]: правится файл, который ПРЯМО СЕЙЧАС исполняется.
# en: PreToolUse on writes — warns when the target shell script is being executed by a live process.
#
# Результат: правка bash-скрипта, занятого живым прогоном, не уходит молча — вызывающий
#            узнаёт об этом ДО записи, а не по синтаксической ошибке в середине чужого прогона.
# Проверка результата: bash hooks/tests/test_running_file_edit_guard.sh даёт 0
#
# ПОВОД (23 сентября 2026, дважды за одну сессию). Оболочка дочитывает скрипт с диска ЛЕНИВО,
# по мере исполнения, а не берёт его в память целиком. Правка сдвигает байтовые смещения, и
# указатель чтения попадает в середину слова:
#   · `scripts/behavior-condition-probe.sh` — прибор шёл фоном, правка убила прогон на середине;
#   · `hooks/tests/run_all.sh` — набор шёл (400 тестов из 555), вставка блока дала
#     «мауту: command not found» и «syntax error near unexpected token `done`» на :584 и :590.
# Оба раза вход решения «править сейчас» был ПУСТ: факта «файл занят исполнением» не добывал
# никто. Узел, посчитавший верно по отсутствующему входу, не корень — корень здесь.
#
# ЧЕМ РЕШАЛОСЬ РАНЬШЕ: ничем. На Edit/Write стоят secret-guard, budget-gate, lib-prefix-guard,
# test-exit-explicit-guard — ни один не спрашивает про занятость файла. Предшественника нет,
# и это проверено перечнем матчеров настроек, а не памятью.
#
# ПРИЗНАК УЖЕ, ЧЕМ «ИМЯ ФАЙЛА В КОМАНДНОЙ СТРОКЕ». Процесс может УПОМИНАТЬ файл (grep по нему,
# редактор, git), и правка тогда безвредна — два последствия у одного признака. Здесь судится
# ИСПОЛНЕНИЕ: `bash <файл>` либо сам файл как argv[0]. Своих процессов (этот хук, его родитель)
# в счёт нет.
#
# УРОВЕНЬ — ПОДСКАЗКА, не отказ, и это названо честно: точность измерена на ДВУХ случаях одной
# сессии, ложные срабатывания на корпусе НЕ ИЗМЕРЕНЫ, следа «файл был занят в момент правки»
# система не пишет.
# Условие снятия: появится выборка правок занятых файлов с записанными исходами — тогда
# точность станет измеримой, и признак с одним последствием можно перевести в отказ.
# Python-скрипты сюда не входят: интерпретатор читает файл целиком, класс их не задевает.
#
# Input  (stdin): {tool_name, tool_input:{file_path}}
# Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} либо пусто
# Exit:  always 0.

set -uo pipefail
command -v jq >/dev/null 2>&1 || exit 0
command -v pgrep >/dev/null 2>&1 || exit 0

INPUT=$(cat)
[ -z "$INPUT" ] && exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
case "$TOOL" in Write|Edit|MultiEdit) ;; *) exit 0 ;; esac

FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)
case "$FILE" in *.sh) ;; *) exit 0 ;; esac
[ -f "$FILE" ] || exit 0

BASE=${FILE##*/}

# ТОТ ЖЕ ФАЙЛ, А НЕ ТО ЖЕ ИМЯ (D1090, 25 октября 2026). Сверка слова по шаблону `*/$BASE` звала опасной правку копии
# хука в репозитории, пока исполнялась УСТАНОВЛЕННАЯ копия (`~/.claude/hooks/<имя>.sh`, отдельный файл): за ход правки
# `hooks/impact-inject.sh` — 7 срабатываний из 7 ложных. Теперь слово судится идентичностью (`-ef`: устройство и inode,
# ссылки раскрываются); относительное — от каталога процесса (Linux — /proc, macOS — lsof). Не разворачивается в
# существующий файл (процесс сменил каталог, как `run_all.sh`; каталога не узнать; путь с пробелом разрезан на слова) —
# прежняя сверка по имени: пропуск занятого файла дороже ложной тревоги.
# Ответ: 0 — тот же файл; 1 — другой одноимённый; 2 — не узнать.
_proc_cwd() {
    if [ -L "/proc/$1/cwd" ]; then readlink "/proc/$1/cwd" 2>/dev/null; return; fi
    command -v lsof >/dev/null 2>&1 && lsof -a -p "$1" -d cwd -Fn 2>/dev/null | sed -n 's/^n//p' | head -n 1
}
_same_file() {   # <слово> <pid>
    local _sp _sc
    case "$1" in
        /*) _sp="$1" ;;
        *) _sc=$(_proc_cwd "$2"); [ -n "$_sc" ] || return 2; _sp="$_sc/$1" ;;
    esac
    [ -e "$_sp" ] || return 2
    [ "$_sp" -ef "$FILE" ] && return 0
    return 1
}

# Живые процессы, чья командная строка ИСПОЛНЯЕТ этот файл. Своё дерево исключается по PID:
# хук сам запущен из оболочки, где имя файла может стоять в строке вызова.
HITS=""
while IFS= read -r _pid; do
    [ -n "$_pid" ] || continue
    [ "$_pid" = "$$" ] && continue
    [ "$_pid" = "${PPID:-0}" ] && continue
    _cmd=$(ps -o command= -p "$_pid" 2>/dev/null) || continue
    [ -n "$_cmd" ] || continue
    _shell_seen=0
    # СТРОКА РАЗБИРАЕТСЯ ПО СЛОВАМ, А НЕ ШАБЛОНОМ ПО ПОДСТРОКЕ. Первая редакция сверяла
    # `*"bash $FILE"*` и `*"bash $BASE"*` и на живом случае ПРОМОЛЧАЛА: набор шёл как
    # `bash hooks/tests/run_all.sh` — путь относительный, между словом оболочки и базовым
    # именем стоит каталог. Поймал это положительный контроль, поставленный до объявления
    # стража рабочим (pattern-frame-without-a-positive-control).
    _exec=0
    set -- $_cmd
    _first=1
    for _w in "$@"; do
        case "$_w" in
            */$BASE|"$BASE")
                # Слово-скрипт: либо это argv[0], либо ему предшествовала оболочка; другой одноимённый файл — не он.
                if [ "$_first" -eq 1 ] || [ "$_shell_seen" = 1 ]; then
                    _same_file "$_w" "$_pid"; [ $? -ne 1 ] && _exec=1
                fi
                ;;
        esac
        case "$_w" in
            bash|sh|zsh|*/bash|*/sh|*/zsh) _shell_seen=1 ;;
        esac
        _first=0
    done
    [ "$_exec" -eq 1 ] && HITS="$HITS $_pid"
done <<PIDS
$(pgrep -f "$BASE" 2>/dev/null)
PIDS

HITS=$(printf '%s' "$HITS" | tr -s ' ' | sed 's/^ //')
[ -n "$HITS" ] || exit 0

N=$(printf '%s' "$HITS" | tr ' ' '\n' | grep -c . || true)

MSG="⚙️ Файл исполняется ПРЯМО СЕЙЧАС ($N процесс(ов): $HITS): $FILE
Оболочка дочитывает скрипт с диска по ходу работы — правка сдвинет смещения, и бегущий
прогон умрёт синтаксической ошибкой в середине (дважды 23 сентября 2026: прибор и набор).
Исходы: дождаться прогона · остановить его · править КОПИЮ и перенести после.
Если процесс лишь упоминает файл, а не исполняет его, правка безопасна — решает вызывающий."

jq -cn --arg msg "$MSG" '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$msg}}'
exit 0
