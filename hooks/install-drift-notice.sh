#!/usr/bin/env bash
# install-drift-notice.sh — Stop: правка, не дошедшая до установленной копии, не действует.
# en: Stop hook — a fix that never reached ~/.claude does not run in the world.
#
# Повод, 7 сентября 2026. Механизм `rc_outcome_observed` был построен, накрыт одиннадцатью
# ногами, закоммичен — и НЕ РАБОТАЛ: живая копия `~/.claude/hooks/root-cause-lib.sh` о нём
# не знала. Нашёл это субагент по другому делу, а не механизм. Тот же класс двумя днями
# раньше (повод D316): расхождение из шести хуков прожило СУТКИ, и всё это время починки
# существовали в репозитории и не действовали в мире.
#
# Почему сторожа не было. Сверщик установки живёт в `hooks/tests/drift-check.sh` — то есть
# он ТЕСТ и бежит только в полном наборе (4 мин 40 с). Правок хуков за сутки — 33; полный
# набор гоняется на порядок реже, и между ними мир молча отстаёт от репозитория.
#
# ПРИЗНАК НЕ СВОЙ. Сверку делает `scripts/sync-drifted.sh --dry-run`, и решение читается его
# КОДОМ ВОЗВРАТА (0 чисто, 1 дрейф, 2 сверщик сломан). Своя проверка «что считается дрейфом»
# была бы второй копией правила у потребителя — род K реестра, закрытый 6 сентября 2026.
#
# Отказ сверщика (код 2) НАЗЫВАЕТСЯ, а не глотается: молчащий сторож неотличим от чистого
# дерева, и это ровно тот дефект, что чинился в этот же день у undefined-function-check.
#
# Input  (stdin): {session_id, hook_event_name, cwd, ...}
# Output (stdout): ПУСТО всегда. Сказанное уходит в очередь ~/.claude/hooks/state/pending-alerts.txt,
#        её поднимает pending-alerts-surface.sh на следующем UserPromptSubmit каналом
#        additionalContext. Прежний systemMessage в VSCode-расширении не рендерится
#        (case-2026-06-14) — сторож был слышен только там, где и так виден весь вывод.
# Exit:  always 0 — напоминание, не запрет: перенос в ~/.claude есть решение владельца.
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0

# АДРЕС РЕПОЗИТОРИЯ — CLAUDSOUL_ROOT, А НЕ cwd СЕССИИ. Предмет сторожа — отставание
# УСТАНОВЛЕННОЙ копии от репозитория ClaudSoul, и оно не зависит от того, где открыта сессия:
# хук, правленный из другого проекта, точно так же не действует в мире. Дословный cwd молчал
# в 14 проектах из 15 и, поскольку walk-up не делался вовсе, — даже в ПОДКАТАЛОГЕ ClaudSoul.
# Цепочка резолва общая (paths-lib:18): CLAUDSOUL_ROOT → CLAUDSOUL_REPO → ~/.claude/claudsoul-repo
# → дефолт. Своей копии порядка нет; отказом резолв кончиться не может.
PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
# shellcheck source=/dev/null
if [ -f "$PATHS_LIB" ]; then . "$PATHS_LIB"; else : "${CLAUDSOUL_ROOT:=$HOME/My Project/ClaudSoul}"; : "${STATE_DIR:=$HOME/.claude/hooks/state}"; fi
REPO="$CLAUDSOUL_ROOT"
# Путь репозитория в командах владельцу — в одиночных кавычках, апостроф экранирован (D1211): команду вставляют в
# терминал как есть, а в двойных кавычках `$(…)`, обратные кавычки и `$имя` из пути раскрылись бы и исполнились
# (финальный скептик D1211, M3: в bash и zsh создан файл подстановкой из имени каталога).
_RQ="'$(printf '%s' "$REPO" | sed "s/'/'\\\\''/g")'"
STATE_DIR="${STATE_DIR:-$HOME/.claude/hooks/state}"

# Дроссель: отставание — состояние ПОСТОЯННОЕ, оно держится, пока владелец не перенёс. Сторож,
# ставший видимым во всех проектах, без дросселя дописывал бы в очередь строку на каждый ход.
# Ключ — РЕДАКЦИЯ состояния (код возврата + список имён), а не факт «сказал»: новый разошедшийся
# файл звучит сразу, тот же — раз за сессию. Образец решения — D345, blocker-tier-check.sh:128.
for _idn_thr in "$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/throttle-lib.sh" \
                "$HOME/.claude/hooks/throttle-lib.sh"; do
    # shellcheck source=/dev/null
    [ -f "$_idn_thr" ] && { . "$_idn_thr"; break; }
done

# Канал: очередь, а не systemMessage и не additionalContext на Stop. systemMessage в
# VSCode-расширении не рендерится (case-2026-06-14) — сторож был бы нем; additionalContext
# прямо на Stop ПЕРЕЗАПУСКАЕТ ход, а состояние постоянное, и вышел бы цикл (8 пустых ходов,
# 7 сентября 2026). Очередь показывает УЖЕ зарегистрированный pending-alerts-surface.sh на
# следующем UserPromptSubmit — правок install.sh и settings.json не нужно.
_idn_say() {  # $1 — ключ дросселя (редакция состояния), $2 — текст
    if command -v throttle_file >/dev/null 2>&1 && command -v resolve_session_id >/dev/null 2>&1; then
        _f=$(throttle_file "$STATE_DIR" install-drift "$(resolve_session_id "$INPUT")")
        throttle_seen "$_f" "$1" && exit 0
        throttle_mark "$_f" "$1"
    fi
    mkdir -p "$STATE_DIR" 2>/dev/null
    printf '%s\n' "$2" >> "$STATE_DIR/pending-alerts.txt" 2>/dev/null || true
    exit 0
}

# НЕЧЕМ СВЕРИТЬ — это не «расхождений нет». Резолв корня отказом кончиться не может, поэтому
# единственная форма невозможности одна: по разрешённому адресу нет самого сверщика.
[ -f "$REPO/scripts/sync-drifted.sh" ] || _idn_say "no-repo" \
    "⚠️ Сверить установку НЕЧЕМ: по адресу $REPO нет scripts/sync-drifted.sh.
Это не «расхождений нет» — состояние ~/.claude против репозитория НЕ ПРОВЕРЕНО.
Назови адрес репозитория:  CLAUDSOUL_REPO=<путь>  либо  echo <путь> > ~/.claude/claudsoul-repo"

OUT=$(cd "$REPO" 2>/dev/null && bash scripts/sync-drifted.sh --dry-run 2>&1)
RC=$?

case "$RC" in
    0) exit 0 ;;
    1)
        _files=$(printf '%s\n' "$OUT" | sed -n 's/^  > //p' | tr '\n' ' ')
        if [ -n "$_files" ]; then
            _idn_say "drift:${_files}" \
                "📦 Правка не дошла до установленной копии — в мире она не действует: ${_files% }

Пока файл в репозитории отличается от ~/.claude/hooks, хук работает по СТАРОЙ редакции:
починка есть в коммите и не срабатывает ни разу. Перенос — решение владельца, команда
того же размера, что и расхождение:
    cd $_RQ && bash scripts/sync-drifted.sh --apply"
        else
            # Дрейф есть, но переносом не чинится: сверщик назвал его и оставил человеку
            # (seed знаний — база владельца). Прежде это состояние давало код 0 и МОЛЧАНИЕ.
            _idn_say "left:$(printf '%s' "$OUT" | cksum | tr -d ' ')" \
                "📦 Установка разошлась с репозиторием, и переносом это не чинится — сверщик
оставил решение тебе:
$OUT"
        fi
        ;;
    3)
        # ТОЛЬКО seed знаний (D354, 12 сентября 2026). Другой род состояния — другой уровень
        # разговора И ДРУГАЯ ЧАСТОТА. Ключ дросселя здесь ПОСТОЯННЫЙ, а не вычисленный из
        # вывода: имена разошедшихся знаний меняются при каждой записи в базу, и прежний ключ
        # `left:<cksum>` заставлял сторожа говорить на каждой сессии, где велась работа со
        # знаниями, то есть ежедневно. Постоянный ключ = один раз за сессию, что бы ни
        # разошлось. Команда пересборки НЕ предлагается как действие «сейчас»: пересборка
        # перед каждым коммитом превратила бы seed в шум истории (довод записан в D354).
        # Команда пересборки называется только там, где инструмент есть: гейт `-f` ДО
        # упоминания (образец ci-check-reminder.sh:43), иначе совет в чужом дереве звал бы
        # несуществующий файл — признак NOGATE у tool-gate-check.
        _idn_seed_cmd=""
        [ -f "$REPO/scripts/regen-seed.py" ] && _idn_seed_cmd="
Пересобрать нужно К РЕЛИЗУ, одной командой:
    cd $_RQ && python3 scripts/regen-seed.py"
        _idn_say "seed" \
            "🌱 seed знаний отстал от рабочей базы — это НОРМА между релизами, а не отставание
установки. Хуки и скиллы в ~/.claude свежие; расходится только поставка знаний для чистой
установки.${_idn_seed_cmd}"
        ;;
    *)
        _idn_say "broken:$RC" \
            "⚠️ Сверщик дрейфа установки не отработал (код $RC) — состояние ~/.claude против
репозитория НЕ ПРОВЕРЕНО. Это не «расхождений нет»: прогони вручную
    cd $_RQ && bash scripts/sync-drifted.sh --dry-run"
        ;;
esac
exit 0
