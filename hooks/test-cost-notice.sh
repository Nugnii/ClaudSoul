#!/usr/bin/env bash
# test-cost-notice.sh — PostToolUse[Write|Edit|MultiEdit]: правка теста, чья ИЗМЕРЕННАЯ цена выше порога, называет её числом и приёмы удешевления.
# en: PostToolUse on test writes — editing a test whose MEASURED cost exceeds the threshold reports that number and the ways to cut it.
#
# Результат: правя дорогой тест, автор видит его цену числом в тот момент, когда правка ещё
#            открыта, а не через полный прогон.
# Проверка результата: bash hooks/tests/test_test_cost_notice.sh даёт 0
#
# Повод — поправка владельца 11 сентября 2026: «новые тесты должны писаться так, чтобы не
# быть слишком дорогими и включаться куда-то конкретно в пул тестов общего прогона».
#
# ВТОРАЯ ПОЛОВИНА ПОПРАВКИ УЖЕ ИСПОЛНЕНА И НЕ ДУБЛИРУЕТСЯ: место в пуле новый тест получает
# сам — `run_all.sh` берёт `test_*.sh` globом, а фазу выводит `needs_serial` ИЗ ТЕКСТА теста
# (род F: универсум выведен, не перечислен). Здесь только цена.
#
# ПОЧЕМУ ЦЕНА БЕРЁТСЯ ИЗ ЖУРНАЛА, А НЕ УГАДЫВАЕТСЯ ПО ТЕКСТУ. Статический признак «тест зовёт
# тяжёлый прибор без сужающего рычага» промерен на живом наборе 11 сентября 2026 и отвергнут:
# точность 1 из 23, и 13 дорогих из 14 он не увидел вовсе. Цена теста не выводится из того,
# что он вызывает, — она измеряется. Журнал прогона (`state/suite-run.tsv`) её знает.
# Названный предел: НОВЫЙ тест в журнале отсутствует, и цена его здесь неизвестна; она
# появится на первом полном прогоне, и тогда же отчёт `run_all.sh` назовёт его в списке
# «ДОРОЖЕ». Этот страж закрывает правку УЖЕ дорогого, а не рождение нового.
# Условие снятия: предел держится, пока цена нового теста неизмерима до прогона. Он спадёт,
# когда страж сможет ИЗМЕРИТЬ записываемый тест сам — прогнать его один раз под сторожем на
# границе хода (не на каждой правке: недописанный тест падает, и число будет о другом).
# Порог входа в такую пробу — тот же журнал: прогонять стоит лишь то, чего в нём ещё нет.
set -uo pipefail

PAYLOAD=$(cat 2>/dev/null || true)
FILE=$(printf '%s' "$PAYLOAD" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)
case "$FILE" in
    */hooks/tests/test_*.sh) ;;
    *) exit 0 ;;
esac
NAME="${FILE##*/}"

# МЕРА, ИСТОЧНИК И ПОРОГ — У ВЛАДЕЛЬЦА ФАКТА (13 сентября 2026, D410). «Дорогой тест» в
# этом проекте определяет scripts/costly-tests.sh:39,42,69 — копия журнала ПОЛНОГО прогона
# (suite-run-full.tsv), колонка 4 (ПРОЦЕССОРНОЕ время), порог COSTLY_CPU_MAX, реестр
# оправданий hooks/tests/costly-justified.tsv. Здесь стояли своя мера и свой источник:
# колонка 2 (стенные секунды) и suite-run.tsv, который стирает каждый ВЫБОРОЧНЫЙ прогон.
# Замер на живом журнале: дорогих по стене 16, по CPU 10 — шесть просьб удешевить шли
# тестам, которых реестр дорогими не считает. Стенные секунды под восемью потоками
# раздуваются соседями, и ровно поэтому проект перешёл на CPU (D392); страж остался на
# прежней мере и разошёлся молча — корень R1. Дробь: потребителей журнала три, судит этот
# же предмет ОДИН (scripts/suite-runtime.sh мерит длительность набора, там стенное время и
# есть предмет).
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
LOG="${SUITE_RUN_FULL_LOG:-$STATE/suite-run-full.tsv}"
# Журнала нет — молчим и выходим успехом: это «прибора здесь нет», а не «цена в порядке».
[ -f "$LOG" ] || exit 0

MAX="${COSTLY_CPU_MAX:-20}"
SECS=$(awk -F'\t' -v n="$NAME" '!/^#/ && NF >= 4 && $3 == n {print $4; exit}' "$LOG" 2>/dev/null)
# Теста в журнале нет (новый либо журнал от другого прогона) — сказать нечего.
case "$SECS" in ''|*[!0-9]*) exit 0 ;; esac
[ "$SECS" -ge "$MAX" ] || exit 0

# Дороговизна ОПРАВДАНА реестром — молчим: владелец факта решение уже принял, и просьба
# «удешеви» здесь спорила бы с ним.
REG="${COSTLY_JUSTIFIED:-}"
if [ -z "$REG" ]; then
    _root=$(cd "$(dirname "$FILE")/../.." 2>/dev/null && pwd -P) || _root=""
    [ -n "$_root" ] && REG="$_root/hooks/tests/costly-justified.tsv"
fi
if [ -n "$REG" ] && [ -f "$REG" ]; then
    awk -F'\t' -v n="$NAME" '!/^#/ && $1 == n {found=1} END{exit !found}' "$REG" 2>/dev/null && exit 0
fi

printf '%s\n' "{\"hookSpecificOutput\":{\"hookEventName\":\"PostToolUse\",\"additionalContext\":\"💰 Этот тест дорогой: ${SECS} с ПРОЦЕССОРНОГО времени на последнем полном прогоне (порог ${MAX}; мера, источник и реестр оправданий — у владельца факта scripts/costly-tests.sh). Приёмы, доказанные замером 11 сентября 2026: узкая фикстура вместо полного реестра (DOC_CLAIMS_FILE — test_mode_arg_guard 102 → 2 с); дешёвый режим прибора вместо полного (root-map.py --parse-only — test_root_map 84 → 1 с); песочница вместо живого дерева. Предмет проверки при этом обязан остаться прежним: там ноги целы, 15 и 14.\"}}"
exit 0
