[ -n "$REASON" ] || REASON="outcome ${ACTION} через /learn"
# Кавычки в reason сломали бы YAML-строку — убираем на границе, как в других хуках.
# Причина едет в ТРИ носителя с разными правилами: YAML-скаляр в двойных кавычках
# (знание), строка JSON (durable-журнал) и значение `awk -v` (которое разбирает escape
# ещё до того, как строка куда-либо попадёт). Правило, а не перечень: оставляем только то,
# что безопасно во ВСЕХ трёх — то есть снимаем кавычку, обратную косую и любой управляющий
# символ, а не те два, на которых успели обжечься.
#
# Цена перечня измерена. До 29 августа 2026 снимались `"` и перевод строки; причина вида
# `путь был указан как C:\` рвала YAML-скаляр (`\"` не закрывает строку — знание выпадало
# из индекса), рвала строку журнала (jq обрывает потоковый разбор на битой строке — уже
# стоило проекту 285 записей из 7665, внутренний архив (не публикуется):1702) и приезжала в знание
# искажённой, потому что `awk -v` съедал escape. Три носителя, один пропущенный символ.
#
# КОНТРПРИМЕР: `:` и `#` НЕ снимаются — внутри двойных кавычек YAML они безвредны, и
# снимать их значило бы портить осмысленный текст ради формы.
REASON=$(clean_reason "$REASON")

# --- Обратная сторона ссылки: кейс в source_cases родителя (D12, 2026-08-28) ---
# Ребро кейс → паттерн пишется в ДВУХ файлах (knowledge/META.md, «Связь пишется в двух
# файлах»). До этой правки скрипт писал только provenance_log, а source_cases заполнялся
# рукой — и симметрия держалась на памяти агента. Цена: 23 односторонние ссылки за три
# месяца (D12, v1.14.5) и ещё 2 в тот же день, когда правило дописали в спецификацию.
# Проверка (mcp-server/tests/test_knowledge_link_symmetry.py) стоит ПОСЛЕ записи и ловит
# уже случившееся; здесь — место, где требование выполняется.
#
# Только confirmed: contradicted-кейс паттерн опровергает, а не обосновывает, и в
# source_cases ему не место. Суффикс .md обязателен — проверка симметрии ищет ИМЯ ФАЙЛА
# кейса, и запись без суффикса её не удовлетворит.
# КОНТРПРИМЕР: `... contradicted "разошлось" case-X.md` — source_cases не трогается.
# Форма поля, которую построчная правка не осилит: поточный список, не закрытый в той же
# строке. Такую не трогаем и отказываем — второй ключ `source_cases` стоил бы потери
# прежних кейсов, а `yaml.safe_load` берёт последний ключ и молчит.
if [ "$ACTION" = "confirmed" ] && [ -n "$TRIGGER_CASE" ]; then
    _sc_line=$(awk '/^---[[:space:]]*$/ { d++; if (d >= 2) exit; next }
                    d == 1 && /^source_cases:[[:space:]]*\[/ { print; exit }' "$FILE")
    if [ -n "$_sc_line" ] && ! grep -q ']' <<< "$_sc_line"; then
        echo "knowledge-counter-bump: source_cases в $FILE — поточный список, не закрытый в строке;" >&2
        echo "  построчная правка потеряла бы прежние кейсы. Приведи поле к блочному списку и повтори." >&2
        exit 1
    fi
fi

ADD_SOURCE_CASE=""
if [ "$ACTION" = "confirmed" ] && [ -n "$TRIGGER_CASE" ]; then
    _tc=$(basename -- "$TRIGGER_CASE")
    if [ -z "$_tc" ]; then
        echo "knowledge-counter-bump: имя файла кейса не разобрано: '$TRIGGER_CASE'" >&2
        exit 1
    fi
    case "$_tc" in *.md) ;; *) _tc="${_tc}.md" ;; esac
    # Родитель — только pattern/principle: у кейса поля source_cases нет по построению.
    case "$(basename "$FILE")" in
        pattern-*|principle-*)
            # Дедуп смотрит В САМО ПОЛЕ, а не по всему файлу. Поиск по файлу отравляла
            # собственная запись скрипта: ветка `contradicted` кладёт `trigger_case: <кейс>`
            # в provenance_log, и последующий `confirmed` считал источник уже внесённым.
            # Упоминание кейса в ТЕЛЕ документа давало тот же ложный «уже есть».
            _cur=$(awk -v fld="source_cases" '
                /^---[[:space:]]*$/ { d++; if (d >= 2) exit; next }
                d == 1 {
                    if ($0 ~ "^" fld ":") { inf = 1; print; next }
                    if (inf && /^[[:space:]]/) { print; next }
                    inf = 0
                }' "$FILE")
            # Сравниваем с ЭЛЕМЕНТАМИ списка, а не с текстом поля. Поиск подстроки по
            # тексту засчитывал имя, упомянутое внутри прозаического элемента («тот же
            # признак разбирался в case-…-beta.md, но фикс туда не дошёл»), и обратная
            # ссылка не писалась — то есть возвращался ровно дефект D12, ради которого
            # ветка и заведена. Элемент — либо `- имя` блочного списка, либо запись между
            # запятыми поточного; в обоих случаях имя стоит отдельным словом.
            #
            # Здесь-строка, а не труба: под `set -o pipefail` `grep -q` выходит на первом
            # совпадении, `printf` получает SIGPIPE, и статус конвейера становится провалом —
            # дедуп сработал бы наоборот и внёс уже имеющийся кейс повторно.
            _items=$(printf '%s' "$_cur" \
                | sed -e 's/^source_cases:[[:space:]]*//' -e 's/^[[:space:]]*-[[:space:]]*//' \
                | tr ',[]' '\n\n\n' \
                | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^"//' -e "s/^'//" -e 's/"$//' -e "s/'$//")
            grep -Fqx "$_tc" <<< "$_items" || ADD_SOURCE_CASE="$_tc"
            ;;
    esac
fi

# Счётчик ДО прохода. Отчёт скрипта утверждает «counter++» — значит именно это и надо
# проверить после записи, а не наличие строки где-то в файле: в теле документа строка
# `confirmed_count: 5` встречается и ничего не значит. `show_counters` читает frontmatter.
COUNT_BEFORE=$(counter_value "$(show_counters | awk -F': ' -v f="$FIELD" '$1 == f { sub("^" f ": *", ""); print; exit }')")

TMP_OUT=$(mktemp)
trap 'rm -f "$TMP_OUT"' EXIT

# Одним проходом: инкремент счётчика, обновление last_confirmed, вставка записи в
# provenance_log. Поле провенанса существует в трёх состояниях — отсутствует,
# `[]`, блочный список; обрабатываем все три, иначе запись молча теряется.
# modification_history этот скрипт больше НЕ трогает — она только для перекроек правила.
awk -v field="$FIELD" -v kind="$KIND" -v today="$TODAY" -v reason="$REASON" \
    -v tcase="$TRIGGER_CASE" -v action="$ACTION" -v logfield="provenance_log" \
    -v addsrc="$ADD_SOURCE_CASE" -v srcfield="source_cases" \
    -v sid="${CLAUDE_CODE_SESSION_ID:-}" '
function hist_entry() {
    out = "  - date: " today "\n    kind: " kind "\n    reason: \"" reason "\""
    if (tcase != "") out = out "\n    trigger_case: " tcase
    # Сессия в провенансе (D81). Без неё независимость подтверждений непроверяема
    # машинно: замер 2026-08-26 показал 234 заявленных подтверждения против 118
    # записанных поводов, и даже у записанных нельзя было отличить пять наблюдений
    # от пяти проявлений одного. День различает грубо — в одной сессии их бывает
    # несколько; сессия — ближайшая доступная единица «отдельного случая».
    if (sid != "") out = out "\n    session: " sid
    return out
}
BEGIN { depth = 0; bumped = 0; lc = 0; hist_state = "absent"; in_hist = 0; src_state = "absent"; in_src = 0 }
/^---[[:space:]]*$/ {
    depth++
    if (depth == 2) {
        # Закрываем открытые блоки, если они шли последним полем.
        if (in_src) { print "  - " addsrc; in_src = 0 }
        if (in_hist) { print hist_entry(); in_hist = 0 }
        if (action == "confirmed" && !lc) { print "last_confirmed: " today }
        if (addsrc != "" && src_state == "absent") {
            print srcfield ":"
            print "  - " addsrc
        }
        if (hist_state == "absent") {
            print logfield ":"
            print hist_entry()
        }
        print; next
    }
    print; next
}
depth == 1 {
    # Выход из открытых блоков по следующему полю верхнего уровня.
    if (in_hist && /^[A-Za-z_][A-Za-z0-9_-]*:/) { print hist_entry(); in_hist = 0 }
    if (in_src && /^[A-Za-z_][A-Za-z0-9_-]*:/) { print "  - " addsrc; in_src = 0 }

    # source_cases — те же три состояния, что и у провенанса: пустой список, открытый
    # блок, отсутствие поля (последнее закрывается на выходе из frontmatter).
    if (addsrc != "" && $0 ~ "^" srcfield ":[[:space:]]*\\[\\][[:space:]]*$") {
        print srcfield ":"; print "  - " addsrc; src_state = "written"; next
    }
    # Четвёртая форма поля: НЕПУСТОЙ поточный список `source_cases: [a.md, b.md]`.
    # Её отсутствие стоило бы данных, а не удобства: без этой ветки состояние осталось бы
    # `absent`, и на выходе из frontmatter печатался бы ВТОРОЙ ключ `source_cases`. YAML при
    # этом валиден, `safe_load` берёт последний — прежние кейсы исчезли бы из графа молча.
    # В базе таких родителей семь (проверено 2026-08-29). Форму сохраняем: дописываем внутрь.
    if (addsrc != "" && $0 ~ "^" srcfield ":[[:space:]]*\\[[^]]*[^][:space:]][^]]*\\]") {
        _l = $0
        _p = index(_l, "]")
        print substr(_l, 1, _p - 1) ", " addsrc substr(_l, _p)
        src_state = "written"; next
    }
    if (addsrc != "" && $0 ~ "^" srcfield ":[[:space:]]*$") {
        print; in_src = 1; src_state = "written"; next
    }

    if ($0 ~ "^" field ":") {
        v = $0; sub("^" field ":[[:space:]]*", "", v)
        # Число берётся ПРАВИЛОМ «ведущее целое», а не перечнем допустимых форм. Прежняя
        # ветка признавала только голое целое и на всё прочее писала `1` — то есть
        # `confirmed_count: 17  # накопилось за три месяца` становился единицей, и потеря
        # была невидима: поле на месте, тип целый, а `reliability` и `priority` считаются
        # от него. Хвост строки (комментарий) сохраняется.
        tail = v
        if (match(v, /^-?[0-9]+/)) {
            n = substr(v, RSTART, RLENGTH) + 1
            tail = substr(v, RSTART + RLENGTH)
            printf "%s: %d%s\n", field, n, tail
        } else if (v ~ /^[[:space:]]*$/) {
            printf "%s: 1\n", field
        } else {
            # Значение есть, но числа в нём нет — это НЕ повод объявить его единицей.
            # Говорим наружу и оставляем строку нетронутой: подмена нечитаемого удобным
            # значением — то же, что соврать.
            print
            print "UNREADABLE_FIELD" > "/dev/stderr"
        }
        bumped = 1; next
    }
    if (action == "confirmed" && /^last_confirmed:/) { print "last_confirmed: " today; lc = 1; next }
    if ($0 ~ "^" logfield ":[[:space:]]*\\[\\][[:space:]]*$") {
        print logfield ":"; print hist_entry(); hist_state = "written"; next
    }
    if ($0 ~ "^" logfield ":[[:space:]]*$") {
        print; in_hist = 1; hist_state = "written"; next
    }
    print; next
}
{ print }
END {
    if (!bumped) {
        # Поля счётчика не было — сообщаем наружу, чтобы не молчать об этом.
        print "MISSING_FIELD" > "/dev/stderr"
    }
}
' "$FILE" > "$TMP_OUT" 2>"$TMP_OUT.err"

if [ ! -s "$TMP_OUT" ]; then
    echo "knowledge-counter-bump: пустой результат, файл не тронут" >&2
    exit 1
fi

if grep -q "MISSING_FIELD" "$TMP_OUT.err" 2>/dev/null; then
    # Поля не было — дописываем его в конец frontmatter, чтобы счёт начался.
    awk -v field="$FIELD" '
        /^---[[:space:]]*$/ { d++; if (d == 2) { print field ": 1" } }
        { print }
    ' "$TMP_OUT" > "$TMP_OUT.2" && mv "$TMP_OUT.2" "$TMP_OUT"
fi
rm -f "$TMP_OUT.err" 2>/dev/null || true

# Результат проверяется ДО того, как он станет файлом. Прежде проверка стояла ПОСЛЕ
# записи, и всякий её отказ оставлял знание уже изменённым: счётчик увеличен,
# `last_confirmed` переписан, запись провенанса добавлена — а наружу «исход НЕ записан» и
# код 1. Повторный вызов по той же инструкции засчитывал подтверждение второй раз при
# по-прежнему пустом журнале. Проверять до записи дешевле, чем откатывать после.
COUNT_AFTER=$(counter_value "$(show_counters "$TMP_OUT" | awk -F': ' -v f="$FIELD" '$1 == f { sub("^" f ": *", ""); print; exit }')")
if [ -z "$COUNT_AFTER" ]; then
    echo "knowledge-counter-bump: после правки $FIELD во frontmatter не читается числом — файл НЕ тронут" >&2
    exit 1
fi
if [ "${COUNT_BEFORE:-x}" = "${COUNT_AFTER}" ]; then
    echo "knowledge-counter-bump: $FIELD не изменился ($COUNT_AFTER) — файл НЕ тронут" >&2
    exit 1
fi

# Запись проверяется, а не предполагается: файл 0444 не записывается вовсе, и отчёт об
# успехе без этой проверки шёл бы безусловно. Любой отказ записи (права, ENOSPC, квота)
# идёт этим же путём.
if ! cat "$TMP_OUT" > "$FILE" 2>/dev/null; then
    echo "knowledge-counter-bump: не удалось записать $FILE — счётчик НЕ увеличен" >&2
    exit 1
fi


# Счётчик обновлён — теперь тот же исход закрывается как у остальных веток.
OUT_NAME=$(basename -- "$FILE" .md)
case "$ACTION" in
    confirmed)    JOURNAL_OUTCOME="confirmed_knowledge" ;;
    contradicted) JOURNAL_OUTCOME="outdated_knowledge" ;;
    *)            JOURNAL_OUTCOME="$ACTION" ;;
esac
# Колонка журнала называется `confidence` и обязана нести УВЕРЕННОСТЬ. До 29 августа 2026
# сюда уезжал `confirmed_count` — счётчик подтверждений: одна колонка одного журнала
# означала две разные величины, в зависимости от того, какая ветка её заполнила
# (`not_applicable` читала настоящее поле, строка 141). У `contradicted` в «уверенность»
# попадал счётчик ПОДТВЕРЖДЕНИЙ. Замер боевого журнала: из 101 записи, чьё знание ещё в
# базе, 55 расходятся с полем `confidence` своего знания; совпадения в остальных случайны —
# обе величины малые целые. Прошлые записи не чинятся: величину, которой там нет, не
# восстановить, `confirmed_count` с тех пор ушёл вперёд.
CONF_NOW=$(confidence_of "$FILE")
CLOSED=$(dis_close_outcome "$OUT_NAME" "$JOURNAL_OUTCOME" "$CONF_NOW" "$REASON")
echo "✅ $(basename "$FILE"): ${FIELD}++ ($(show_counters | tr '\n' ' ')), погашено записей: ${CLOSED:-0}"
