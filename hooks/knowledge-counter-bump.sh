#!/usr/bin/env bash
# knowledge-counter-bump.sh — механический инкремент счётчиков знания.
# en: mechanical increment of a knowledge item's confirmed/contradicted counters.
#
# Зачем механизм, а не инструкция в скилле. На 25 июля 2026 `contradicted_count` был
# равен нулю во всех 265 знаниях базы при 156 знаниях с подтверждениями (нынешнее число —
# `scripts/doc-figures.sh kb_contradicted_nonzero`). Причина была не в том, что нечего
# опровергать: /learn текстом запрещал трогать знание при противоречии, а /retro
# писал соседнее поле, которое тоже осталось нулевым. Текстовое правило уже один раз
# не исполнилось — второй раз надеяться не на что (principle-knowledge-in-the-world:
# уровень 1 «правило в тексте» хрупок, уровень 3 «механизм» неотвратим).
#
# Usage:
#   knowledge-counter-bump.sh <knowledge> confirmed   [reason] [trigger_case]
#   knowledge-counter-bump.sh <knowledge> contradicted [reason] [trigger_case]
#   knowledge-counter-bump.sh <knowledge> --show
#
#   <knowledge> — имя файла с .md или без (pattern-foo | pattern-foo.md), либо путь.
#
# Что делает:
#   confirmed   → confirmed_count++,   last_confirmed = сегодня, provenance_log += reinforced
#   contradicted → contradicted_count++, provenance_log += contradicted
#
# Почему provenance_log, а не modification_history (разнесено 2026-08-11). Раньше писали в
# историю модификаций — и она перестала означать то, что означает: 96 из 132 записей базы были
# подтверждениями, а не перекройками правила, из-за чего формула fragile (≥3 записей истории)
# по букве метила «хрупким» любое хорошо подтверждённое знание. Теперь два смысла в двух полях:
# modification_history — только narrowed/branched/deprecated/scope_widened/
# reinforced_after_challenge (её и считает fragile), provenance_log — «почему подтвердилось
# в этот раз». Миграция базы: scripts/split-provenance-log.py.
#
# Идемпотентности НЕТ намеренно: каждый вызов — отдельная встреча знания с решением.
# Дедуп «один раз за сессию» делает producer (knowledge-activator), а не этот скрипт.
#
# Exit: 0 — записано; 1 — знание не найдено / плохие аргументы.

set -uo pipefail

PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
if [ -f "$PATHS_LIB" ]; then source "$PATHS_LIB"; else : "${LESSONS_DIR:=$HOME/.claude/global-lessons}"; fi

usage() {
    echo "usage: $(basename "$0") <knowledge> confirmed|contradicted|not_applicable|applicable_not_followed [reason] [trigger_case]" >&2
    echo "       $(basename "$0") <knowledge> --show" >&2
    exit 1
}

[ $# -ge 2 ] || usage
KN="$1"; ACTION="$2"; REASON="${3:-}"; TRIGGER_CASE="${4:-}"

# --- Разрешение имени в путь ---
case "$KN" in
    */*) FILE="$KN" ;;
    *.md) FILE="$LESSONS_DIR/$KN" ;;
    *)   FILE="$LESSONS_DIR/$KN.md" ;;
esac
if [ ! -f "$FILE" ]; then
    echo "knowledge-counter-bump: не найдено знание '$KN' (искал $FILE)" >&2
    exit 1
fi

# --- НАЗВАННЫЙ ПРЕДЕЛ: правка шапки остаётся построчной ---
#
# Замер 29 августа 2026. Класс дефектов «построчный шаблон вместо разбора формата» дал за
# три раунда прожарки больше половины всех находок. У ЧТЕНИЯ он убит настоящим разбором
# (`scripts/knowledge-instrument-audit.sh`, `yaml.safe_load`). У ПРАВКИ НА МЕСТЕ — не убит,
# и это решение, а не недосмотр:
#
#   · `PyYAML` есть, но round-trip через него не сохраняет комментарии;
#   · `ruamel.yaml` (единственный, кто сохраняет) в среде ОТСУТСТВУЕТ — проверено;
#   · комментарии в шапке есть у 19 файлов из 394 базы. Переписывание шапки целиком
#     уничтожило бы их — то есть починка класса дефектов стоила бы порчи данных.
#
# Отсюда область правки СУЖЕНА до форм, которые построчный проход заведомо умеет, а на
# остальных скрипт ОТКАЗЫВАЕТ (поточный список, не закрытый в строке) вместо того, чтобы
# угадывать. Отказ здесь — не слабость, а единственный честный исход: угаданная правка
# структуры теряет данные молча, отказ — громко и обратимо.
#
# Условие снятия предела: появление в среде разбора с сохранением комментариев. Тогда
# правка переводится на него, и этот блок снимается вместе с ветками разбора форм.

# Единственное место, где значение счётчика превращается в число. До 29 августа 2026 их
# было два: awk писал по правилу «ведущее целое + хвост» (`17  # комментарий` → `18  #
# комментарий`), а проверка после записи читала «голое число» и на ту же форму отвечала
# «исход НЕ записан» — файл при этом уже был изменён, а журнал не создан. Два разбора
# одного поля расходятся молча; поэтому разбор один.
counter_value() {
    printf '%s' "${1:-}" | sed -n 's/^[[:space:]]*\(-\{0,1\}[0-9][0-9]*\).*/\1/p'
}

# Единственная очистка причины. Тоже была в двух экземплярах: ветка со счётчиком снимала
# кавычку, обратную косую и управляющие символы (правило трёх носителей), а ветка
# `not_applicable` — только кавычку и перевод строки, и через неё в журнал уезжала
# незакрытая строка JSON. `five-whys-gate` читает этот журнал через `jq -s` по всему файлу:
# одна битая строка — и «повторов ноль» навсегда, молча.
clean_reason() {
    printf '%s' "${1:-}" | tr -d '"\\' | tr -d '\000-\037'
}

# Единственное определение границы frontmatter. Разделитель признаётся с хвостовыми
# пробелами и с возвратом каретки: файл, правленный вне проекта (CRLF), — тот же файл.
# Пять выражений на одно понятие расходятся молча, и это уже случилось: `show_counters`
# требовал `/^---$/`, четыре других прохода — `/^---[[:space:]]*$/`.
FM_SEP='/^---[[:space:]\r]*$/'

# show_counters [файл] — поля счёта из шапки. Файл параметром, чтобы ту же функцию можно
# было применить к РЕЗУЛЬТАТУ до записи, а не только к тому, что уже легло на диск.
show_counters() {
    awk -v sep="^---[[:space:]\r]*$" '
        $0 ~ sep { d++; if (d >= 2) exit; next }
        d == 1 && /^(confirmed_count|contradicted_count|last_confirmed|status):/ { print }
    ' "${1:-$FILE}"
}

# Уверенность знания — одно чтение на все ветви, и оно ПРОВЕРЯЕТ значение. Ветка со
# счётчиком проверку имела, ветка `not_applicable` — нет, и нечисловое значение уезжало в
# JSON без кавычек (`"confidence":1-5`). `five-whys-gate` читает журнал целиком через
# `jq -s`: одна такая строка — и сигнал повторов замолкает навсегда, молча.
confidence_of() {
    _c=$(awk -v sep="^---[[:space:]\r]*$" '
            $0 ~ sep { d++; if (d >= 2) exit; next }
            d == 1 && /^confidence:/ { print $2; exit }
         ' "${1:-$FILE}")
    # Нечитаемая уверенность отдаётся как `null`, а не как ноль. Ноль — законное значение
    # шкалы и в журнале неотличим от измеренного; `null` в JSON разбирается и означает
    # ровно «не прочитано». Контракт чтения обязан различать «прочитал» и «не смог»:
    # пока не различает, незнание выражается значением, и выбирается удобное.
    case "${_c:-}" in ''|*[!0-9]*) printf 'null'; return ;; esac
    printf '%s' "$_c"
}

if [ "$ACTION" = "--show" ]; then show_counters; exit 0; fi

# Закрытие исхода: durable-журнал + гашение pending. Одна функция на все четыре
# исхода, потому что асимметрия здесь уже стоила измерения. Гашение появилось в D60
# вместе с `not_applicable` и досталось только новым веткам; `confirmed`/`contradicted`
# остались на инструкции «агент допишет строку руками» (/learn Step 4e). Кто положился
# на скрипт — тот инкрементировал счётчик знания, но в журнал не попадал и алерт не гасил,
# а через семь дней запись гасло истечением как `not_applicable`. Смещение systematic:
# полный автоматический цикл был ровно у того исхода, который в статистике и лидирует
# (81 `not_applicable` против 54 `confirmed_knowledge` на 2026-08-26). D20 читал это как
# «нечего опровергать», а часть перекоса делал сам инструмент.
# `DIS_SESSION=<sid>` сужает гашение до одной сессии (D85). Без переменной поведение
# прежнее — гасятся записи ключа во всех сессиях, и это осознанно оставлено умолчанием
# для обратной совместимости: вызовы без сессии уже есть в скиллах и в привычке.
#
# Зачем сужение. Запись очереди означает «знание инжектнулось в сессии X, исход
# неизвестен». Вердикт, вынесенный в сессии Y, об исходе в X не говорит ничего: у
# `pattern-defensive-misdiagnosis` было 8 открытых записей из восьми разных сессий, и
# одно суждение закрывало все восемь, завышая разобранность очереди. Инструкция /learn
# Step 4e при этом с v1.12.0 уже оперирует конкретным SID из первой колонки
# `dis_scan_open` — контракт требовал сессию, а инструмент её не принимал.
dis_close_outcome() {
    _key="$1"; _action="$2"; _conf="$3"; _reason="$4"
    # Каталог состояния. `STATE_DIR` — общесистемное имя (`paths-lib.sh:61`), и оно должно
    # работать здесь так же, как везде. До 28 августа 2026 функция читала ТОЛЬКО
    # `CLAUDE_STATE_DIR`, и потому изоляция через `STATE_DIR` молча не работала: любой
    # тест, зовущий этот скрипт, писал в БОЕВОЙ `disagreement-outcomes.jsonl`. Замер: один
    # прогон нового теста добавил туда 57 записей о выдуманных знаниях, и метрики контура
    # несогласия считали их наравне с настоящими. `CLAUDE_STATE_DIR` сохранён первым —
    # на него опирается test_disagreement_loop.sh.
    S="${CLAUDE_STATE_DIR:-${STATE_DIR:-$HOME/.claude/hooks/state}}"
    # Каталог создаём: без него `>>` молча ронял запись об исходе, а счётчик знания к тому
    # моменту уже был увеличен — база и журнал расходились на одном событии, и код возврата
    # оставался нулевым. Соседние хуки (`budget-gate`, `blocker-tier-check`, `auto-scanner`
    # и другие) предпосылку «каталог уже есть» не разделяют и создают его сами.
    mkdir -p "$S" 2>/dev/null || true
    # Дописывание в журнал строкой требует, чтобы файл КОНЧАЛСЯ строкой. Иначе новая
    # запись склеивается с прежней, и построчный читатель видит в одной строке два
    # объекта: `pending` из первого остаётся видимым, гашение становится ложным.
    _ensure_eol() {
        [ -s "$1" ] || return 0
        [ "$(tail -c 1 "$1" 2>/dev/null | od -An -c | tr -d ' ')" = "\\n" ] || printf '\n' >> "$1"
    }
    _ensure_eol "$S/disagreement-outcomes.jsonl"
    _ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)
    printf '{"date":"%s","session":"%s","knowledge":"%s.md","confidence":%s,"outcome":"%s","case":"%s"}\n' \
        "$_ts" "${CLAUDE_CODE_SESSION_ID:-}" "$_key" "${_conf:-null}" "$_action" "$_reason" \
        >> "$S/disagreement-outcomes.jsonl"
    _closed=0
    # Одна сессия либо все — множество файлов задаётся здесь, дальше логика общая.
    if [ -n "${DIS_SESSION:-}" ]; then
        set -- "$S/disagreement-pending-${DIS_SESSION}.jsonl"
    else
        set -- "$S"/disagreement-pending-*.jsonl
    fi
    for _f in "$@"; do
        [ -e "$_f" ] || continue
        # Состояние ключа определяет ПОСЛЕДНЯЯ его строка — так же, как в `dis_scan_open`,
        # которая и считает очередь. Прежний `grep` брал любую строку `pending` в файле,
        # включая давно перекрытую исходом: уже закрытая запись гасилась повторно, файл рос,
        # а отчёт врал. Живой случай 2026-08-26: «погашено записей: 10» при нуле таких
        # записей в активной очереди (D85).
        _last_line=$(grep "\"key\":\"$_key\"" "$_f" 2>/dev/null | tail -1)
        case "$_last_line" in
            *'"outcome":"pending"'*) ;;
            *) continue ;;
        esac
        _ensure_eol "$_f"
        printf '{"date":"%s","key":"%s","outcome":"%s"}\n' "$_ts" "$_key" "$_action" >> "$_f"
        _closed=$((_closed + 1))
    done
    printf '%s' "$_closed"
}

# Исходы без счётчика: знание всплыло не к месту (`not_applicable`, D60) либо
# знание ОТНОСИЛОСЬ к делу и НЕ БЫЛО применено (`applicable_not_followed`, D62).
# Счётчики не трогаются: ни «мимо», ни пропуск не подтверждают и не опровергают
# правило. Но запись обязана состояться, иначе ключ висит в pending и печатается
# каждой следующей сессией, превращая узкую очередь blocker-tier в фон — а
# единственная кнопка, гасившая алерт, писала confirmed, то есть механизм
# подталкивал завышать confirmed_count.
# Почему второй исход отдельным значением, а не «тоже мимо»: applicable_not_followed
# — единственная метрика разрыва «знание → действие», ради которой строится
# система. Слитый с not_applicable, он перестаёт быть наблюдаемым.
case "$ACTION" in not_applicable|applicable_not_followed)
    S="${CLAUDE_STATE_DIR:-${STATE_DIR:-$HOME/.claude/hooks/state}}"
    TS=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
    CONF=$(confidence_of "$FILE")
    KEY=$(basename -- "$FILE" .md)
    if [ "$ACTION" = "not_applicable" ]; then
        DEFAULT_REASON="знание не относилось к тому, что делали"
    else
        DEFAULT_REASON="знание относилось к делу и не было применено"
    fi
    REASON_CLEAN=$(clean_reason "${REASON:-$DEFAULT_REASON}")

    # Журнал и гашение — общей функцией, а не вторым экземпляром той же логики.
    # Второй экземпляр стоил дважды: правка D85 (гасить только по ПОСЛЕДНЕЙ строке ключа)
    # и правка D85 (сужение по `DIS_SESSION`) прошли мимо этой ветки, потому что чинили
    # `dis_close_outcome`, а здесь лежала своя копия цикла. Живой случай 2026-08-26:
    # вызов с `DIS_SESSION` отчитался «погашено записей: 37» вместо одной.
    CLOSED=$(dis_close_outcome "$KEY" "$ACTION" "${CONF:-null}" "$REASON_CLEAN")

    echo "✅ $KEY: $ACTION записан (счётчики не тронуты, погашено записей: $CLOSED)"
    exit 0
    ;;
esac

case "$ACTION" in
    confirmed)   FIELD="confirmed_count";   KIND="reinforced" ;;
    contradicted) FIELD="contradicted_count"; KIND="contradicted" ;;
    *) usage ;;
esac

