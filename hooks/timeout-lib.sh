#!/usr/bin/env bash
# timeout-lib.sh — бюджет времени на чужую команду и снятие ДЕРЕВА процессов, переносимо.
# Результат: команда с бюджетом либо заканчивается сама, либо снимается деревом по истечении срока,
#            и срыв срока отличим кодом 124 от любого исхода самой команды
# Проверка результата: bash hooks/tests/test_timeout_lib.sh даёт 0
# ПРЕФИКСЫ: kill_ run_ deadline_ cmd_
# (`cmd_` — каталог команды исполнителя: подмена `mktemp`, D1198.)
#
# Зачем (D369, 13 сентября 2026). `timeout(1)` на macOS нет (pattern-shell-portability, отказ
# уровня 4); переносимый ограничитель жил в ОДНОМ файле — сторож набора `hooks/tests/run_all.sh`, —
# а стражу возврата долга он был нужен так же: команда пункта без срока останавливала весь обход, и
# «страж повис на чужой команде» читалось как «проверять нечего» (корень R6). Копия в стража —
# носитель рода K; отсюда библиотека, которую зовут оба, и снятие дерева здесь же — одно на всех.
#
# СНИМАЕТСЯ ДЕРЕВО, А НЕ ПРОЦЕСС. История — из сторожа набора: 7 сентября 2026 `kill -9 pid` бил
# только сам тест, всё, что тест запустил фоном, оставалось сиротой; 100 осиротевших процессов
# возрастом до 8 часов, load average 41,6, положительная обратная связь — каждый убитый прогон
# оставлял сироту, сироты ели процессор, следующий прогон шёл медленнее и умирал раньше. Через сутки
# утверждение «класс закрыт» опровергнуто уцелевшим носителем в тесте самого раннера, убивавшем
# дерево сверху вниз (case-2026-09-08-class-declared-closed-without-a-registry). Дети берутся ДО
# смерти родителя: после неё они уходят к pid 1, и связь теряется.
#
# ОПРОС — ДЕСЯТЫМИ ДОЛЯМИ СЕКУНДЫ: быстрая команда не платит секунду ожидания (у стража возврата
# команд десятки). `sleep 0.1` есть у GNU и BSD; где его нет — шаг секунда.
# НАЗВАННЫЙ ПРЕДЕЛ: срок стенной, признака ПРОДВИЖЕНИЯ здесь нет — он у сторожа набора (D368), и
# это его специализация поверх этой же библиотеки. Условие снятия: второй потребитель, которому
# нужен срок без продвижения, — тогда сторож продвижения переезжает сюда.

kill_tree() {  # <pid> — снять процесс со всеми потомками, дети первыми
    local _p="$1" _c
    for _c in $(pgrep -P "$_p" 2>/dev/null); do kill_tree "$_c"; done
    kill -9 "$_p" 2>/dev/null || true
}

run_with_timeout() {  # <секунды> <команда…> → код команды; 124 — срок истёк, дерево снято
    local _s="$1" _pid _t=0 _lim _rc=0
    shift
    case "$_s" in ''|*[!0-9]*) _s=30 ;; esac
    _lim=$(( _s * 10 ))
    "$@" &
    _pid=$!
    while kill -0 "$_pid" 2>/dev/null; do
        if [ "$_t" -ge "$_lim" ]; then
            kill_tree "$_pid"
            wait "$_pid" 2>/dev/null
            return 124
        fi
        if sleep 0.1 2>/dev/null; then _t=$(( _t + 1 )); else sleep 1; _t=$(( _t + 10 )); fi
    done
    wait "$_pid" 2>/dev/null || _rc=$?
    return "$_rc"
}

# СРОК ОДНОГО ТЕСТА — ИЗ ЕГО БАЗИСА, А НЕ КОНСТАНТОЙ НА ВСЕХ (23 сентября 2026, D474).
# Тело вынесено из `hooks/tests/run_all.sh` (`_test_deadline`), когда у расчёта появился
# ВТОРОЙ потребитель: прибор ложной зелени гонял свидетелей под общим сроком 30 с и записывал
# в «не уложился» тех, кто дороже ПО ПРИРОДЕ — `test_defect_registry_cache` идёт 228 с,
# `test_docs_match_tree` 109 с по базису набора. Копия дала бы факту «сколько ждать этот тест»
# двух владельцев, расходящихся молча (корень R1). Судьба предшественника названа: он снят,
# раннер ЗОВЁТ библиотеку.
#
# deadline_for_test <имя теста> [общий срок] → секунды
#   Базис берётся у его владельца — `suite-baseline.tsv` в STATE_DIR (файл пишет раннер).
#   Нет базиса, нет файла, не прочитана нагрузка — отдаётся общий срок: нехватка данных не
#   ужесточает срок, иначе живой тест убивают зря (род B: отказ чтения неотличим от «свободно»).
# deadline_load_multiplier → множитель срока от нагрузки машины (1 при нагрузке до 1, +1 на каждые 4 сверх неё, не больше 4);
#   пусто — нагрузка не прочитана. Один владелец формулы: её зовут `deadline_for_test` и `deadline_under_load` (D1276).
deadline_load_multiplier() {
    local _load
    _load=$(uptime 2>/dev/null | sed -n 's/.*averages*: *\([0-9][0-9]*[.,][0-9][0-9]*\).*/\1/p' \
            | head -1 | tr ',' '.')
    case "$_load" in
        ''|*[!0-9.]*) return 0 ;;
    esac
    awk -v l="$_load" 'BEGIN { m = 1 + (l > 1 ? (l - 1) / 4 : 0); if (m > 4) m = 4; print m }'
}

# deadline_under_load <общий срок> → секунды: общий срок, умноженный на множитель нагрузки (D1276, корень R1). Для
#   ожидания без базиса — проба корня в ловушке коммита (`scripts/root-map.py`), команда показания бэклога
#   (`scripts/backlog-refresh-readings.sh`): постоянные 120 с под нагрузкой 15–24 отбивали починку, проба R6 шла 137 с.
#   На свободной машине — общий срок как есть; нагрузка не прочитана — тоже он.
deadline_under_load() {
    local _gen="${1:-120}" _mult
    case "$_gen" in ''|*[!0-9]*) _gen=120 ;; esac
    _mult=$(deadline_load_multiplier)
    [ -n "$_mult" ] || { printf '%s' "$_gen"; return; }
    awk -v g="$_gen" -v m="$_mult" 'BEGIN { printf "%d", g * m }'
}

deadline_for_test() {
    local _n="$1" _cap _base _mult _d
    local _gen="${2:-${TEST_TIMEOUT:-120}}"
    local _min="${TEST_TIMEOUT_MIN:-15}" _slack="${TEST_TIMEOUT_SLACK:-4}"
    local _bl="${SUITE_BASELINE_FILE:-${STATE_DIR:-$HOME/.claude/hooks/state}/suite-baseline.tsv}"
    [ -f "$_bl" ] || { printf '%s' "$_gen"; return; }
    _base=$(awk -F'\t' -v n="$_n" '$2 == n {print $1; exit}' "$_bl" 2>/dev/null)
    [ -n "$_base" ] || { printf '%s' "$_gen"; return; }
    _mult=$(deadline_load_multiplier)
    [ -n "$_mult" ] || { printf '%s' "$_gen"; return; }
    _cap=$(awk -v b="$_base" -v c="$_gen" 'BEGIN { t = b * 3; print (t > c ? t : c) }')
    _d=$(awk -v b="$_base" -v s="$_slack" -v m="$_mult" -v f="$_min" -v c="$_cap" \
             'BEGIN { d = b * s * m; if (d < f) d = f; if (d > c) d = c; printf "%d", d }')
    printf '%s' "$_d"
}

# Подмена `mktemp` в каталоге команды (D1198): на macOS голая форма `mktemp [-d]` и `mktemp -t <префикс>` берёт
# системный каталог при любом TMPDIR, и свой TMPDIR исполнителя удерживал только шаблонную форму. Кладёт
# `hooks/lib/mktemp-shim.sh` в `<каталог>/.bin/mktemp`; исполнитель ставит команде TMPDIR=<каталог> и
# PATH=<каталог>/.bin:$PATH. Питонская половина — `install_shim` в `hooks/lib/bounded_run.py`, файл подмены один.
cmd_tmpdir_shim() {  # <каталог команды> → 0, если подмена положена; без файла подмены — 1, команда идёт как прежде
    local _s="${MKTEMP_SHIM:-$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)/lib/mktemp-shim.sh}"
    [ -n "$1" ] && [ -f "$_s" ] && mkdir -p "$1/.bin" 2>/dev/null && cp "$_s" "$1/.bin/mktemp" 2>/dev/null \
        && chmod +x "$1/.bin/mktemp" 2>/dev/null
}
