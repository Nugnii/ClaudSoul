# rw_write_targets "<команда оболочки>"
#   Печатает по одному в строке абсолютные пути файлов проекта, В КОТОРЫЕ команда пишет.
#   Чьё содержимое команда пишет — отвечает владелец разбора (`rw_parse_load`, D1330); здесь остаются перечень
#   расширений, отсев хроник и черновиков и привязка относительного пути к каталогу сессии. Запись, которую разбор не
#   видит (python, чужой скрипт), берётся у клиента и у мира — см. ниже.
#
#   Берётся АДРЕСАТ записи, а не любое упоминание пути: `bash run_all.sh > log` упоминает
#   скрипт, но пишет в другое место. Замер по живой сессии 27 августа 2026: по упоминаниям
#   сигналов было бы 12, треть из них по файлам, которые только запускались; по адресатам —
#   3, и все три действительно переписывались многократно.
#
#   Файлы-хроники отбрасываются (они исключены и в ветке Edit, повторная правка там норма жанра —
#   калибровка D18); временный путь вне каталога сессии — черновик (`rw_is_draft`, D1268), в обеих ветках.
# rw_world_targets — что ФАКТИЧЕСКИ изменилось в рабочем дереве с прошлого вызова хука.
#
# Зачем, замер 9 сентября 2026. Признак целей записи ПЕРЕЧИСЛЯЛ формы: `> f`, `>> f`,
# `sed -i`, `tee`, и python — только при наличии `open(…, "w")` в тексте команды. Правка
# через `pathlib.Path(…).write_text(…)` под перечень не подпадает, и за живую сессию из
# ~20 правленых файлов в журнал попали 6, причём единственное срабатывание стража пришлось
# на файл ВНЕ репозитория (план), то есть было ложным, а три настоящих захода на один
# признак не увидены вовсе. Это род F: универсум механизма перечислен, а не выведен, и
# следующая форма записи снова окажется вне перечня.
#
# Здесь предмет наблюдения — не текст команды, а МИР: `git status` даёт изменённые файлы,
# `git hash-object` — их содержимое; разница со снимком прошлого вызова и есть «что тронули».
# Форма записи перестаёт иметь значение: python, sed, редирект, чужой скрипт — всё равно.
# Ключ строки — СОДЕРЖИМОЕ, а не время файла (D1291, 10 ноября 2026, корень R6): `git stash` и `git stash pop`
# переписывают файл тем же содержимым, и по времени это было неотличимо от правки — привычная проверка «без моей правки»
# давала ложный второй заход. Без фильтров (`--no-filters`, D517): clean-фильтр из настроек репозитория не исполняется.
#
# НАЗВАННЫЙ ПРЕДЕЛ: вне git-репозитория снимка нет, и ветка молчит — там остаётся перечень
# форм. Файл, изменённый и возвращённый к прежнему содержимому в пределах одного вызова,
# правкой не считается: мир после вызова тот же, что до него.
# Условие снятия: предел держится, пока «что изменилось» спрашивается у git. Появится общий
# снимок дерева по mtime, не зависящий от системы контроля версий (обход каталога проекта с
# отсечением игнорируемого), — и ветка заработает в любом каталоге, а перечень форм станет
# не нужен вовсе.
rw_world_targets() {
    _rw_root="${RW_CWD:-$PWD}"
    command -v project_git >/dev/null 2>&1 || return 0
    # Снимок принадлежит АКТОРУ, а не только сессии (10 сентября 2026). Субагент получает
    # `session_id` родителя — измерено прямым замером payload 17 сентября 2026: вызовы трёх
    # субагентов легли в журнал `rework-<SID родителя>.jsonl`, — поэтому общий снимок
    # приписывал субагенту правки родителя.
    # Наблюдалось в журнале: `rework-fired` нёс `README.md cycles=3` и `ROOTS.md cycles=2,3`
    # в сессии субагента, который ни того, ни другого не касался. Предмет наблюдения здесь —
    # «что изменилось в мире с прошлого вызова», и он верен; неверно было УТВЕРЖДЕНИЕ о
    # владельце правки (`pattern-subject-of-measurement-mismatch`).
    # Актор берётся у поля `agent_id`, а не у ИМЕНИ расшифровки (D449, замер 17 сентября
    # 2026): в `transcript_path` харнесс кладёт путь РОДИТЕЛЯ всегда, поэтому прежняя ветка
    # не срабатывала ни разу — снимков `rework-world-*.agent-*` в состоянии 0 при 3333
    # расшифровках субагентов на диске, и правки субагента приписывались родителю дальше.
    # Владелец признака — `resolve_actor_id` в `paths-lib.sh`; библиотеки нет — актор не
    # различается, то есть прежнее поведение.
    # Суффикс берётся у ВЛАДЕЛЬЦА (`resolve_actor_suffix`, `paths-lib.sh`) и считается ОДИН
    # раз на верхнем уровне — здесь только читается. Запасной ветки нет намеренно: первая
    # редакция несла её «для прямого вызова функции из тестов», но таких вызовов в дереве
    # ноль, а у родителя она возвращала бы то же пусто — мёртвый код с обоснованием,
    # которого не существует (находка адверсариальной проверки 18 сентября 2026). Второй
    # источник одного ответа опасен сам по себе: разойдутся молча.
    _rw_actor="${RW_ACTOR:-}"
    _rw_snapf="$STATE_DIR/rework-world-${SID:-unknown}${_rw_actor}.txt"
    # `-z`: пути отдаются NUL-разделёнными и БЕЗ кавычек. Прежний `--porcelain` без него брал
    # в кавычки с восьмеричными escape всякий путь с пробелом или не-ASCII (`"two words.sh"`,
    # `"\320\272..."`), проверка `[ -f ]` такого файла не находила, и путь исчезал МОЛЧА —
    # ни счётчика, ни слова. Проба: три изменённых файла, в журнал попадал один.
    # НАЗВАННЫЙ ПРЕДЕЛ: имя с настоящим переводом строки всё ещё потеряется — разделителем
    # здесь снова стал `\n`. В дереве таких нет; условие снятия — обработка потока без
    # построчного чтения.
    # project_git (paths-lib): папка сессии — чужие настройки git не исполняются (D515).
    # Пути porcelain — ВСЕГДА от корня репозитория, при любом каталоге вызова (D1244, 8 ноября 2026): склейка с каталогом
    # вызова из подкаталога не находила ни одного файла, снимок писался пустым, и следующий вызов из корня засчитывал
    # правкой каждый изменённый файл. Вершина — каталог вызова плюс `--show-cdup`, логическим `pwd`: вид путей прежний
    # (`rev-parse --show-toplevel` разрешил бы ссылки, `/var` → `/private/var`). Не репозиторий — снимка нет, как прежде.
    _rw_top=$(cd "$_rw_root" 2>/dev/null && _rw_up=$(project_git rev-parse --show-cdup 2>/dev/null) \
        && cd "./$_rw_up" 2>/dev/null && pwd) || return 0
    _rw_ls=$(cd "$_rw_top" 2>/dev/null && project_git status --porcelain -z --untracked-files=no 2>/dev/null \
        | tr '\0' '\n' | sed -E 's/^.{3}//' | while IFS= read -r _rw_p; do
            _rw_p="${_rw_p%% -> *}"
            [ -f "$_rw_top/$_rw_p" ] && [ -r "$_rw_top/$_rw_p" ] && printf '%s\n' "$_rw_p"
        done)
    # Хеши — одним процессом на все файлы, в порядке путей; файл, исчезнувший между статусом и хешем, обрывает поток, и
    # пути без хеша в снимок не идут (как прежде файл без `-f`). Пути — АБСОЛЮТНЫЕ и только читаемых файлов (скептик opus
    # по a3566bff, L1): строку на `"` поток разбирает как C-кавычки, а нечитаемый файл обрывает поток, и все файлы ниже
    # по сортировке выпадали из снимка.
    _rw_now=""
    [ -z "$_rw_ls" ] || _rw_now=$(cd "$_rw_top" 2>/dev/null && printf '%s\n' "$_rw_ls" | RW_T="$_rw_top" awk '{ print ENVIRON["RW_T"] "/" $0 }' \
        | project_git hash-object --no-filters --stdin-paths 2>/dev/null | paste -d '\t' <(printf '%s\n' "$_rw_ls") - \
        | RW_T="$_rw_top" awk -F'\t' '$2 ~ /^[0-9a-f]+$/ { print ENVIRON["RW_T"] "\t" $1 "\t" $2 }')
    # СНИМОК НАЗЫВАЕТ СВОЙ РЕПОЗИТОРИЙ (D1244, скептик opus по 0ef644fd, M1): вершина — первое поле строки, и вызов судит
    # и переписывает только строки своей вершины. Прежде снимок был один на сессию без имени репозитория: вызов из
    # вложенного `.git`, рабочей копии worktree или чужого проекта переписывал его, и следующий вызов из корня засчитывал
    # правкой каждый изменённый файл. Строка-метка «вершина ⇥ ⇥» отличает «снимок этого репозитория есть, изменённых нет»
    # от «снимка нет» (первый вызов молчит, как прежде; снимок прежнего вида в две колонки — тоже «нет»).
    # Чтение, сравнение и запись — под одним замком (род H): параллельные вызовы сессии из двух репозиториев иначе
    # теряли бы обновление друг друга. Нет библиотеки замка — без него, как прежде.
    if command -v with_lock >/dev/null 2>&1; then with_lock "$_rw_snapf" _rw_snap_update; else _rw_snap_update; fi
    return 0
}

_rw_snap_update() {  # читает _rw_snapf, _rw_top, _rw_now из rw_world_targets; печатает тронутые файлы
    # Снимок ЕСТЬ, когда есть метка вершины (D1291, скептик opus H1): строки памяти пишутся и до первого снимка, и «есть
    # строка вершины» значило бы «снимок есть» — первый вызов засчитал бы правкой каждый изменённый файл.
    # Снимок прежнего вида — ключ строки время файла (число), а не хеш содержимого (D1291) — считается отсутствующим:
    # иначе первый вызов после переноса засчитал бы правкой каждый изменённый файл. Первый вызов молчит, как прежде.
    if [ -f "$_rw_snapf" ] && RW_T="$_rw_top" awk -F'\t' '$1 == ENVIRON["RW_T"] && $2 == "" {f = 1} $1 == ENVIRON["RW_T"] && $3 ~ /^[0-9]+$/ {o = 1}
        END {exit !(f && !o)}' "$_rw_snapf" 2>/dev/null; then
        # Изменившиеся и новые строки снимка — это и есть тронутые файлы. Строка, равная ПАМЯТИ виденного файла (тот же
        # путь и то же содержимое, четвёртое поле `clean`), — не правка: сменился лишь статус в индексе (коммит, его отмена
        # `reset --soft`, `git add` нового файла), файл тот же, что был виден (D1288, D1291, корень R6). Дозапись меняет
        # содержимое.
        printf '%s\n' "$_rw_now" | while IFS= read -r _rw_line; do
            [ -n "$_rw_line" ] || continue
            grep -qxF "$_rw_line" "$_rw_snapf" 2>/dev/null && continue
            grep -qxF "$_rw_line	clean" "$_rw_snapf" 2>/dev/null && continue
            _rw_pp="${_rw_line#*	}"; _rw_pp="${_rw_pp%%	*}"
            [ -n "$_rw_pp" ] || continue
            # Файл менялся до начала окна команды — не эта команда (D1299); без окна — как прежде.
            if [ -n "${RW_WIN_START:-}" ] && command -v file_mtime >/dev/null 2>&1 \
               && [ "$(file_mtime "$_rw_top/$_rw_pp")" -lt "$RW_WIN_START" ] 2>/dev/null; then continue; fi
            printf '%s\n' "$_rw_top/$_rw_pp"
        done
    fi
    # Метка вершины пишется ПОСЛЕДНЕЙ (D1287, скептик opus M1): код группы — код последней записи, и запись, оборванная
    # посредине (EFBIG, ENOSPC), не подменяет целый снимок обрезанным — `mv` идёт, только если дописана и метка.
    # Память (D1288): строки этого репозитория, чьи файлы ушли из статуса, остаются с пометкой `clean`, пока файл снова
    # не появится в статусе; появился — память снимается (строка статуса вместо неё).
    { RW_T="$_rw_top" awk -F'\t' 'NF >= 3 && $1 != ENVIRON["RW_T"]' "$_rw_snapf" 2>/dev/null
      printf '%s\n' "$_rw_now" | RW_T="$_rw_top" awk -F'\t' 'NR == FNR { if ($2 != "") now[$2] = 1; next }
          $1 == ENVIRON["RW_T"] && $2 != "" && NF >= 3 && $3 !~ /^[0-9]+$/ && !($2 in now) { print $1 "\t" $2 "\t" $3 "\tclean" }' \
          - "$_rw_snapf" 2>/dev/null
      [ -z "$_rw_now" ] || printf '%s\n' "$_rw_now"; printf '%s\t\t\n' "$_rw_top"; } > "$_rw_snapf.$$" 2>/dev/null \
        && mv "$_rw_snapf.$$" "$_rw_snapf" 2>/dev/null || rm -f "$_rw_snapf.$$" 2>/dev/null
    return 0
}

# rw_remember_seen <абсолютный путь> — правка файловым инструментом кладёт в память снимка УВИДЕННОЕ содержимое (D1291).
#
# Зачем: снимок строится без неотслеживаемых файлов (`--untracked-files=no`), и новый файл, написанный инструментом Write,
# в нём не виден; его появление в статусе после `git add` неотличимо от правки — 10 ноября 2026 так засчитана третья
# «правка» пробы, и страж разбора отбил следующий вызов. Память — та же строка `clean`, что у ушедшего из статуса файла
# (D1288): статус файла с этим содержимым правкой не считается, дозапись — считается. Пишется и без снимка (скептик opus
# по a3566bff, H1: первая правка актора — Write нового файла, снимок заводится позже): «снимок есть» судится по метке
# вершины, а её пишет только перезапись снимка. Без библиотеки git — молчит, как ветка мира.
rw_remember_seen() {
    command -v project_git >/dev/null 2>&1 || return 0
    _rw_snapf="$STATE_DIR/rework-world-${SID:-unknown}${RW_ACTOR:-}.txt"
    _rw_top=$(cd "$(dirname "$1")" 2>/dev/null && _rw_up=$(project_git rev-parse --show-cdup 2>/dev/null) \
        && cd "./$_rw_up" 2>/dev/null && pwd) || return 0
    _rw_rel="${1#"$_rw_top"/}"
    [ "$_rw_rel" != "$1" ] || return 0
    _rw_h=$(cd "$_rw_top" 2>/dev/null && project_git hash-object --no-filters -- "$_rw_rel" 2>/dev/null) || return 0
    case "$_rw_h" in ''|*[!0-9a-f]*) return 0 ;; esac
    if command -v with_lock >/dev/null 2>&1; then with_lock "$_rw_snapf" _rw_snap_remember; else _rw_snap_remember; fi
    return 0
}

_rw_snap_remember() {  # читает _rw_snapf, _rw_top, _rw_rel, _rw_h из rw_remember_seen
    # Метку вершины память не пишет и не снимает: метку ставит только перезапись снимка. Последней идёт строка памяти —
    # оборванная запись не подменяет снимок (D1287).
    { [ ! -f "$_rw_snapf" ] || RW_T="$_rw_top" RW_P="$_rw_rel" awk -F'\t' '!($1 == ENVIRON["RW_T"] && $2 == ENVIRON["RW_P"] && $4 == "clean")' \
          "$_rw_snapf" 2>/dev/null
      printf '%s\t%s\t%s\tclean\n' "$_rw_top" "$_rw_rel" "$_rw_h"; } > "$_rw_snapf.$$" 2>/dev/null \
        && mv "$_rw_snapf.$$" "$_rw_snapf" 2>/dev/null || rm -f "$_rw_snapf.$$" 2>/dev/null
    return 0
}

# rw_run_subject <команда> — базовое имя ПРОВЕРОЧНОГО файла, который прогоняют, либо пусто.
#
# Зачем (D418, 18 сентября 2026). Повтор бывает и в успехах: один ассерт отлаживался ПЯТЬЮ
# полными прогонами спеки вместо `--debug`/`--ui`/`--trace`, и не видел этого никто —
# `error-tracker` считает провалы КОМАНД, а команды завершались успешно; этот детектор ловит
# «правка → прогон → правка», то есть требует правку МЕЖДУ прогонами, а здесь её нет вовсе.
# Предметы противоположны и потому живут рядом, а не вместо друг друга.
# Замер по 74 расшифровкам: серий «один файл подряд без правки между прогонами» 809, из них
# длиной >= 5 — 53. Точность на выборке 14 длинных серий: 12 настоящих, 2 со скрытой правкой,
# то есть около 86% — уровень ПОДСКАЗКИ, не отказа.
# НАЗВАННЫЙ ПРЕДЕЛ: предмет прогона распознаётся ПЕРЕЧНЕМ ФОРМ (корень R3) — иначе имя файла
# взять неоткуда, команда его не объявляет. Прогон незнакомой формы в серию не попадёт.
# Условие снятия: у прогонов появится объявленный предмет (аргумент, переменная, журнал),
# и имя можно будет прочитать, а не угадать по виду команды.
#
# ФОРМА ИЩЕТСЯ В ПРОГРАММАХ, КОТОРЫЕ КОМАНДА ЗОВЁТ, А НЕ В ЕЁ ТЕКСТЕ (D1330). Образец по всему тексту читал прогоном
# строку в кавычках (`grep -rn 'bash hooks/tests/x.sh' docs`) и рецепт в теле heredoc; пять таких команд давали «5-й
# прогон подряд» теста, который не запускался. Слова команд даёт владелец разбора (`rw_runs_load`): форма — пара или
# тройка СОСЕДНИХ слов одной простой команды, не читающей по своему роду.
RW_SUBJECT_HINT='tests/[^[:space:]]*\.sh|pytest|playwright'
rw_run_subject() {
    # Дешёвый необходимый признак по тексту: без него разбор зовётся на каждую команду сессии (python, ~50 мс).
    grep -qE "$RW_SUBJECT_HINT" <<< "${1:-}" 2>/dev/null || return 0
    rw_runs_load "${1:-}"
    if [ -z "$_RW_RUNS_OK" ]; then
        # Разбора нет — прежний образец по тексту: серия без владельца считается, как считалась.
        printf '%s' "${1:-}" \
            | grep -oE '(bash|sh)[[:space:]]+[^[:space:]]*(hooks/tests|tests)/[A-Za-z0-9._/-]+\.sh|pytest[[:space:]]+[^[:space:]]+\.py|playwright[[:space:]]+test[[:space:]]+[^[:space:]]+\.(spec|test)\.[tj]s' 2>/dev/null \
            | head -1 | awk '{ print $NF }' | sed 's#.*/##'
        return 0
    fi
    # Две формы настоящего прогона, которых пара соседних слов не видит (скептик D1330, L1): цикл `for t in
    # tests/a.sh tests/b.sh; do bash "$t"; done` — предметом берётся последний тест перечня (156 команд корпуса; прежний
    # образец ловил его случайно, по «sh» из конца имени первого файла); `docker … bash -c '<скрипт>'` — скрипт стоит
    # одним словом после `-c` (15 команд). НАЗВАННЫЙ ПРЕДЕЛ: скрипт строкой у `ssh хост '…'` и запуск через `zsh` в
    # серию не попадают — частота не мерилась. Условие снятия: встретятся в журналах серий.
    printf '%s\n' "$_RW_RUNS" | awk -F'\t' -v f="${_RW_FOR:-}" '
        function base(s) { sub(/.*\//, "", s); return s }
        {
            for (i = 1; i < NF; i++) {
                w = base($i); n = $(i + 1); s = ""
                if ((w == "bash" || w == "sh") && match(n, /tests\/[A-Za-z0-9._\/-]+\.sh/)) s = substr(n, RSTART, RLENGTH)
                else if ((w == "bash" || w == "sh") && n ~ /\$/ && f != "") s = f
                else if ((w == "bash" || w == "sh") && n == "-c" && i + 2 <= NF \
                         && match($(i + 2), /(bash|sh)[ ]+[^ ]*tests\/[A-Za-z0-9._\/-]+\.sh/)) {
                    s = substr($(i + 2), RSTART, RLENGTH); sub(/.* /, "", s) }
                else if (w ~ /pytest$/ && match(n, /[^[:space:]]+\.py/)) s = substr(n, RSTART, RLENGTH)
                else if (w ~ /playwright$/ && n == "test" && i + 2 <= NF \
                         && match($(i + 2), /[^[:space:]]+\.(spec|test)\.[tj]s/)) s = substr($(i + 2), RSTART, RLENGTH)
                if (s != "") { print base(s); exit }
            }
        }' 2>/dev/null
}

# rw_runs_load <команда> — простые команды вызова, которые МОГУТ быть проверкой результата: всё, кроме заведомо
# читающих. Ответ — в `_RW_RUNS` (строки владельца разбора: слова через табуляцию), `_RW_RUNS_OK` непуст, если разбор
# ответил. Один вызов разбора на вызов хука: спрашивают его и предмет серии, и запись «прогон».
#
# Зачем (D1330, атаки `any-bash-is-a-run`). Запись «прогон» ставилась на ВСЯКУЮ команду без цели записи: `ls hooks`,
# `git diff x.sh`, `pwd` между двумя правками давали «первую попытку проверили, и она не сошлась», хотя ничего не
# проверялось (в живых журналах 14 записей у 12 исполнителей). Читающая по роду программа результата не проверяет.
# НАЗВАННЫЙ ПРЕДЕЛ: это перечень форм (корень R3), и он двусторонний. Незнакомая программа считается прогоном, как
# прежде, — `python3 -c "print(1)"`, `curl`, свой скрипт; читающая программа, которой проверяли (`grep -c` по выводу,
# `diff` с эталоном), прогоном не считается, и цепочка на ней не растёт. Перечень выбран по частоте программ в 99 023
# командах корпуса, а не придуман; `git commit` оставлен прогоном — в нём исполняются стражи коммита.
# Условие снятия: у команды появится объявленная роль («проверка») — например, ненулевой код возврата как сигнал
# результата у клиента, — и род программы перестанет быть её единственным признаком.
RW_NOT_A_RUN=" cd pwd ls cat head tail cut tr sort uniq wc grep egrep fgrep rg awk sed echo printf true false : [ test \
 sleep wait date seq read set export basename dirname which file stat du ps pgrep lsof paste od comm shasum mktemp \
 mkdir cp mv rm ln touch chmod find jq for case esac break continue exit "
RW_GIT_NOT_A_RUN=" log status diff show blame grep rev-parse rev-list ls-files ls-tree cat-file hash-object check-ignore \
 describe branch config add "
_RW_RUNS=""; _RW_RUNS_OK=""; _RW_RUNS_DONE=""; _RW_FOR=""
rw_runs_load() {
    [ -z "$_RW_RUNS_DONE" ] || return 0
    _RW_RUNS_DONE=1
    rw_parse_load "${1:-}"
    # Пустой ответ — разбор не удался либо команд нет (у владельца это один ответ): считаем «спросить нечем».
    [ -n "$_RW_HEADS" ] || return 0
    _RW_RUNS_OK=1
    _RW_RUNS=$(printf '%s\n' "$_RW_HEADS" | awk -F'\t' -v r="$RW_NOT_A_RUN" -v g="$RW_GIT_NOT_A_RUN" '
        { h = $1; sub(/.*\//, "", h) }
        h == "git" { if (index(g, " " $2 " ") == 0) print; next }
        index(r, " " h " ") == 0 { print }' 2>/dev/null)
    # Перечень цикла `for … in <тесты>` — предмет его запусков `bash "$t"` (см. `rw_run_subject`).
    _RW_FOR=$(printf '%s\n' "$_RW_HEADS" | awk -F'\t' '
        $1 == "for" { for (i = 2; i <= NF; i++) if ($i ~ /tests\/[A-Za-z0-9._\/-]+\.sh$/) last = $i }
        END { if (last != "") print last }' 2>/dev/null)
}

# rw_parse_load <команда> — ОДИН запуск разбора на вызов хука (скептик D1330, M2): он отдаёт и цели содержимого, и
# слова команд. Первая редакция спрашивала их двумя запусками python, и команда без цели записи стоила 327 мс против
# 142 мс прежней редакции. Ответ: `_RW_PARSED` непуст, если разбор ответил; `_RW_TARGETS` — пути, `_RW_HEADS` — строки
# команд. Зовётся в ОСНОВНОЙ оболочке до подстановок `$( )`: ответ, полученный в подоболочке, до соседа не дожил бы.
_RW_PARSED=""; _RW_TARGETS=""; _RW_HEADS=""; _RW_PARSE_DONE=""
rw_parse_load() {
    [ -z "$_RW_PARSE_DONE" ] || return 0
    _RW_PARSE_DONE=1
    command -v executable_content_heads >/dev/null 2>&1 || return 0
    _rw_both=$(executable_content_heads "${1:-}") || return 0
    _RW_PARSED=1
    _RW_TARGETS=$(printf '%s\n' "$_rw_both" | sed -n 's/^T	//p')
    _RW_HEADS=$(printf '%s\n' "$_rw_both" | sed -n 's/^H	//p')
}

# rw_rerun_bump <предмет> — счётчик серии прогонов ОДНОГО предмета; состояние своё.
#
# Первая редакция считала серию по журналу правок и была НЕДОСТИЖИМА по построению: журнал
# заводится только правкой, а серия прогонов без правок его никогда не создаёт. Поймала это
# фикстура из шести прогонов подряд: хук промолчал шесть раз и журнала не создал.
# Предмет здесь другой (не цепочка правок, а серия прогонов), поэтому и состояние своё;
# суффикс актора берётся у владельца, как у соседей.
rw_rerun_bump() {
    _rb_subj="${1:-}"
    _rb_f="$STATE_DIR/rework-rerun-${SID:-unknown}${RW_ACTOR:-}.txt"
    [ -n "$_rb_subj" ] || { printf '0'; return 0; }
    _rb_prev_subj=""; _rb_prev_n=0
    if [ -f "$_rb_f" ]; then
        _rb_prev_subj=$(awk -F'\t' 'NR==1 { print $1 }' "$_rb_f" 2>/dev/null)
        _rb_prev_n=$(awk -F'\t' 'NR==1 { print $2 + 0 }' "$_rb_f" 2>/dev/null)
    fi
    if [ "$_rb_prev_subj" = "$_rb_subj" ]; then
        _rb_n=$(( ${_rb_prev_n:-0} + 1 ))
    else
        _rb_n=1
    fi
    printf '%s\t%s\n' "$_rb_subj" "$_rb_n" > "$_rb_f" 2>/dev/null || true
    printf '%s' "$_rb_n"
}

# rw_rerun_reset — правка обрывает серию: мир изменился, следующий прогон уже не холостой.
rw_rerun_reset() {
    : > "$STATE_DIR/rework-rerun-${SID:-unknown}${RW_ACTOR:-}.txt" 2>/dev/null || true
}

# rw_rerun_notice <журнал> <предмет> — серия достигла порога? скажи и отметь, что сказано.
#
# Уровень — ПОДСКАЗКА: точность признака на выборке 14 длинных серий 12 из 14 (около 86%),
# две серии несли скрытую правку. Для отказа этого мало, и правило проекта прямо требует
# измеренной точности на признаке с ОДНИМ последствием.
# Порог 5 взят у повода пункта (пять полных прогонов спеки ради одного ассерта) и проверен
# замером: серий длиной >= 5 в корпусе 53 на 74 расшифровки, то есть около 0,7 на сессию.
# ОТМЕТКА «СКАЗАНО» ЛЕЖИТ В СОСТОЯНИИ СЕРИИ, А НЕ В ЖУРНАЛЕ ПОВОДА ПЕРЕРАБОТКИ (D1330). До 21 ноября 2026 она писалась в
# `rework-fired-*`, а его строки страж разбора считает поводами с правом на отказ (`five-whys-gate.sh`), сборщик метрик —
# срабатываниями переработки: пять прогонов одного теста давали отказ на следующую правку любого файла (в живых журналах
# 2 сессии), то есть подсказка становилась отказом вопреки своему уровню.
rw_rerun_notice() {
    _rr_log="${1:-}"; _rr_subj="${2:-}"
