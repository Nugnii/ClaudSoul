}
# Суффикс актора — ОДИН раз на вызов и на верхнем уровне (D453). Прежде актор резолвился
# только внутри `rw_world_targets`, а та зовётся лишь в ветке `Bash` (:225): у
# `Edit|Write|MultiEdit` актор не резолвился вовсе, и правки субагента ложились в журнал
# родителя. Здесь он считается ДО `case`, поэтому обе ветки разделяются одним решением.
# Владелец суффикса один — `resolve_actor_suffix` в `paths-lib.sh`; библиотеки нет — суффикс
# пуст, то есть ПРЕЖНЕЕ поведение.
RW_ACTOR=""
if command -v resolve_actor_suffix >/dev/null 2>&1; then
    RW_ACTOR=$(resolve_actor_suffix "$INPUT")
fi
# Журнал цепочки принадлежит АКТОРУ: правка→прогон→правка родителя и субагента — разные
# цепочки. Измерено 17 сентября 2026: вызовы трёх субагентов легли в журнал
# `rework-<SID родителя>.jsonl` подряд с родительскими, и «второй заход» оказывался первой
# правкой субагента.
LOG="$STATE_DIR/rework-${SID}${RW_ACTOR}.jsonl"

case "$TOOL" in
    Bash)
        # Правка через оболочку — такая же правка (D91). Раньше здесь стоял только
        # «прогон», и цепочка не набирала ни шага в сессиях, где файлы правят через
        # heredoc и sed: замер 27 августа 2026 по живой сессии — 156 записей в логе,
        # из них 16 правок, и все 16 от субагентов через Write, а `hook-input-lib.sh`,
        # переписанный больше десяти раз через оболочку, отсутствовал полностью.
        # Непустой лог маскировал нулевой сигнал. Тот же корень закрывали 26 августа
        # для blocker-tier знаний (D79, 45% правок мимо), у этого потребителя он остался.
        # Журнала актора нет — цепочка ещё не начата, выходим БЕЗ побочных действий.
        #
        # Здесь 18 сентября 2026 стояла ветка, заводившая снимок мира для субагента: без неё
        # нога D449b свидетеля краснела. Ветку сняла адверсариальная проверка в тот же день,
        # и причинность доказана снятием ОДНОЙ строки на копии дерева. Устройство вреда:
        # снимок, заведённый ДО первой правки, делает следующий прогон «видящим изменение» —
        # `rw_world_targets` возвращает правленый файл целью, ветка пишет `edit` вместо
        # `{"kind":"run"}`, цикл не замыкается НИКОГДА, и субагент теряет сигнал переработки
        # целиком. У родителя ветки не было, поэтому снимка на этот момент нет, прогон
        # возвращает пусто и пишется `run` — асимметрия работала против субагента.
        # Дробь условия на живых данных (400 расшифровок субагентов новее 1 сентября 2026):
        # правивших файлы — 33, из них вызвавших Bash ДО первой правки — 33, то есть 100%.
        # Снимок субагента заводится там же, где у родителя: первым прогоном ПОСЛЕ того, как
        # его первая правка файловым инструментом завела журнал. Ногу D449b свидетеля это
        # требует привести к тому же порядку — она изображала мир, где журнал общий.
        # СЕРИЯ ХОЛОСТЫХ ПРОГОНОВ СЧИТАЕТСЯ ДО ВЫХОДА ПО ОТСУТСТВИЮ ЖУРНАЛА (D418).
        # Журнал цепочки заводится только правкой, а серия прогонов без правок его не
        # создаёт никогда — значит всё, что стоит ниже этой строки, для неё недостижимо.
        # Две редакции подряд ставили счётчик ниже и молчали шесть раз из шести на фикстуре;
        # вторая перенесла СОСТОЯНИЕ на своё и всё равно молчала, потому что причина была в
        # достижимости точки вызова, а не в состоянии. Проверяется это одной командой —
        # шесть одинаковых прогонов подряд, и счётчик обязан дойти до порога.
        _rw_cmd0=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
        # Разбор зовётся ЗДЕСЬ, а не в подстановке ниже: ответ, полученный в подоболочке, до записи «прогон» не дожил бы,
        # и разбор исполнялся бы дважды.
        # Нужен он, когда цепочка заведена (цели записи и «прогон ли это») либо в тексте есть слово теста (предмет серии).
        if [ -f "$STATE_DIR/rework-${SID}${RW_ACTOR}.jsonl" ] || grep -qE "$RW_SUBJECT_HINT" <<< "$_rw_cmd0" 2>/dev/null; then
            rw_runs_load "$_rw_cmd0"
        fi
        _rw_subj0=$(rw_run_subject "$_rw_cmd0")
        # Упавшая команда — не прогон (скептик opus по 99d31c91, M4): предмет хука — заход «при зелёных прогонах», а
        # событие провала заведено ради правок упавшей команды. Без этой оговорки красный прогон рос ступенью цепочки и
        # серией холостых прогонов (+6,8% ступеней по корпусу) — предмет сменился бы без слова. Правки она пишет, как прежде.
        [ -n "$_rw_subj0" ] && [ "$RW_EVENT" != PostToolUseFailure ] && rw_rerun_notice "" "$_rw_subj0"
        [ -f "$LOG" ] || exit 0
        _rw_cmd=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
        _rw_targets=$(rw_write_targets "$_rw_cmd")
        # Перечень форм молчит — спрашиваем клиента, затем мир. Порядок такой, потому что перечень
        # называет АДРЕСАТА команды точно, ответ клиента — всё изменённое ЭТОЙ командой, а мир — всё
        # тронутое с прошлого вызова, включая тронутое не этой командой (D1299). Снимок мира
        # обновляется при любом ответе: он поглощает чужие правки, иначе их засчитал бы запасной путь.
        # Клиент ответил — автора называет он, и окно по времени файла не нужно: мир без окна даёт «содержимое не то,
        # что было видно», пересечение с ответом — «и изменила его эта команда» (`rw_bed_meet`).
        _rw_src=form; _rw_bed_ok=""
        if [ -z "$_rw_targets" ] && _rw_bed=$(rw_bed_targets); then _rw_bed_ok=1; RW_WIN_START=""; fi
        _rw_world=$(rw_world_targets)
        if [ -z "$_rw_targets" ]; then
            if [ -n "$_rw_bed_ok" ]; then
                _rw_targets=$(rw_bed_meet "$_rw_bed" "$_rw_world"); _rw_src=bed
            else
                _rw_targets="$_rw_world"; _rw_src=world
            fi
        fi
        if [ -z "$_rw_targets" ]; then rw_log_run; exit 0; fi
        # Цели названы не командой, а МИРОМ, и все они уже учтены после последнего прогона —
        # значит эта команда ничего не правила, она ПРОГОН (D458). Без этой ветки запись
        # «прогон» появлялась лишь при совпадении секунд правки и прогона.
        if [ "$_rw_src" = world ] && rw_all_seen_since_run "$LOG" "$_rw_targets"; then rw_log_run; exit 0; fi
        printf '%s\n' "$_rw_targets" | while IFS= read -r _rw_f; do
            [ -n "$_rw_f" ] || continue
            printf '{"kind":"edit","path":"%s"}\n' "$_rw_f" >> "$LOG" 2>/dev/null || true
            # Память — там же, где записана правка (D1291, скептик opus H2): новый файл, созданный оболочкой, иначе
            # засчитался бы второй правкой при `git add` — неотслеживаемого в снимке нет. Цели мира и ответа клиента
            # (пересечение с миром) в снимке уже есть — память им не пишется (цена 45–50 мс на путь, скептик по 1a0945f0, L6).
            [ "$_rw_src" != form ] || rw_remember_seen "$_rw_f"
        done
        # Порог проверяется по первому адресату: команда, пишущая сразу в несколько
        # файлов проекта, в этой работе редкость, а остальные уже попали в цепочку.
        FILE=$(printf '%s\n' "$_rw_targets" | awk 'NF { print; exit }')
        ;;
    Edit|Write|MultiEdit) ;;
    *) exit 0 ;;
esac

# Сюда доходят ТОЛЬКО правки: ветка прогона выше завершается сама. Значит мир изменился,
# и серия холостых прогонов прерывается — следующий прогон уже не повтор одного и того же
# при одном и том же мире. Одно место вместо двух: у Bash-правок и файловых инструментов
# дальше общий поток.
rw_rerun_reset

# Для Bash адресат уже определён в ветке выше; у файловых инструментов он в tool_input.
if [ -z "${FILE:-}" ]; then
    FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)
fi
[ -n "$FILE" ] || exit 0

# Калибровка D18 (2026-08-08, выборка 40 срабатываний): 10 пришлись на
# файлы-хроники (CHANGELOG x4, BACKLOG x3, SESSION x2, архив) — там повторные
# правки норма жанра (append-лог), ни одно срабатывание не было переработкой.
# Хроники исключены до записи в цепочку; маска переопределяется env.
#
# Разметка выборки D23 (2026-08-11, 36 срабатываний после калибровки): хроник ноль —
# исключение работает, — но два срабатывания пришлись на CLAUDE.md и одно на META.md.
# Это документы СОСТОЯНИЯ: они переписываются по ходу сессии столько раз, сколько
# уточняется картина, и повторная правка в них — тот же жанр, что append в хронике.
# КОНТРПРИМЕР: журнальные файлы ВНЕ этого перечня — `docs/*.md`, `.claude-docs/*` —
# исключением не покрыты, и повторная дозапись в них засчитается переработкой.
# Перечень назван перечнем: он растёт по мере встречи новых журналов, не по правилу.
# Калибровка D358 (13 сентября 2026, носитель 2). Выборка 20 напоминаний с чтением текста хода
# (`scripts/five-whys-attribution-replay.py --sample-rework 20`, seed 13): настоящих разворотов 7 из 20
# (35%); из 13 ложных шесть — на ПРОИЗВОДНЫХ файлах учёта и документах, которые каждая задача
# правит по устройству: индекс зависимостей (пересборка после каждого пункта — 79 из 756
# срабатываний в 62 живых журналах, чаще любого другого файла), карта корней, README, документы
# `docs/` и доки модулей `.claude-docs/`. Всего на этих семьях 202 из 756 срабатываний (27%).
# По ADR-015 65% ложных — сужение признака, а не подъём и не снятие: перечень расширен этими
# семьями; код в `hooks/`, `scripts/`, `lib/` и тесты считаются как прежде (T8c/T8d свидетеля).
# Исключение из тестов одно — свидетель зелёной стороны (D520): реестр фикстур, дописываемый
# ногой `green_<ID>` на каждый пункт долга, жанр тот же, что у BACKLOG.
REWORK_EXCLUDE_RE="${REWORK_EXCLUDE_RE:-(CHANGELOG|SESSION|BACKLOG[^/]*|CLAUDE|META|README(\.ru)?|ROOTS)\.md$|dep-index\.tsv$|/docs/[^/]+\.md$|/\.claude-docs/.*\.md$|/test_backlog_green_side\.sh$}"
# Ответ берётся у grep, а не у трубы: под `set -o pipefail` producer, убитый SIGPIPE,
# отдаёт 141, и исключение молча перестаёт исключать (D50; доказано замером в D59).
grep -qE "$REWORK_EXCLUDE_RE" <<< "$FILE" && exit 0
rw_is_draft "$FILE" && exit 0

# Ветка Bash уже записала ВСЕ свои цели выше; здесь пишет только файловый инструмент.
# Прежде запись шла безусловно, и каждая правка через оболочку попадала в журнал ДВАЖДЫ:
# один раз перечнем целей, второй — здесь по первой из них. Замер 9 сентября 2026 на
# фикстуре: одна правка `printf x > f3.sh` → две записи `edit`. Следствие несимметричное —
# порог «три цикла» для правок через оболочку достигался вдвое быстрее, чем для Edit, а
# в живом журнале сессии 14 записей означали 7 правок. Дефект маскировался встречным:
# правки, форма которых вне перечня, не считались вовсе.
if [ "$TOOL" != "Bash" ]; then
    printf '{"kind":"edit","path":"%s"}\n' "$FILE" >> "$LOG" 2>/dev/null || true
    rw_remember_seen "$FILE"
fi

# Считаем правки этого файла, между которыми был прогон.
# Цепочка: edit(F) ... run ... edit(F) ... run ... edit(F) → CYCLES=3.
CYCLES=$(awk -v f="$FILE" '
    /"kind":"run"/ { ran = 1; next }
    /"kind":"edit"/ {
        # путь текущей строки
        if (split($0, a, "\"path\":\"") < 2) next
        split(a[2], b, "\"")
        if (b[1] != f) next
        if (first == 0) { first = 1; n = 1; ran = 0; next }
        if (ran == 1) { n++; ran = 0 }
    }
    END { print n + 0 }
' "$LOG" 2>/dev/null || echo 0)
CYCLES=${CYCLES:-0}

[ "$CYCLES" -ge "$THRESHOLD" ] 2>/dev/null || exit 0

# Throttle: один раз на (файл, число циклов) за сессию — а не на файл. Первый прогон замера
# detection-share (30 августа 2026) показал «сказал 16%»: после первого напоминания файл
# переделывался дальше — четвёртый, пятый цикл — и страж молчал, хотя каждый новый цикл есть
# НОВОЕ событие того же рода («повтор уплывает», поправка владельца 27 августа). Правки без
# прогона между ними число циклов не меняют и молчат как прежде.
# Имя повода даёт ВЛАДЕЛЕЦ ФОРМЫ (`throttle_file`), а суффикс актора — владелец суффикса:
# до 18 сентября 2026 этот писатель и читатель `five-whys-gate.sh:108` строили имя каждый
# своим литералом (корень R1), и повод, накрученный субагентами, давал отказ РОДИТЕЛЮ.
# Библиотеки нет — прежняя форма, собранная здесь: молчания быть не должно.
if command -v throttle_file >/dev/null 2>&1; then
    FIRED=$(throttle_file "$STATE_DIR" rework "$SID" "${RW_ACTOR:-}")
else
    FIRED="$STATE_DIR/rework-fired-${SID}${RW_ACTOR:-}.jsonl"
fi
if [ -f "$FIRED" ] && grep -Fq "\"path\":\"$FILE\",\"cycles\":$CYCLES}" "$FIRED" 2>/dev/null; then
    # Признак СОВПАЛ, страж промолчал по троттлу — это знаменатель, а не пустота (D205):
    # без него доля «сказал против промолчал» непосчитаема по построению. Подпись —
    # файл и цикл: повтор той же подписи в замере не считается подавлением.
    command -v rc_note_detection >/dev/null 2>&1 && \
        rc_note_detection "$STATE_DIR" "$SID" "rework-detector" "muted" "$FILE:$CYCLES"
    exit 0
fi
command -v rc_note_detection >/dev/null 2>&1 && \
    rc_note_detection "$STATE_DIR" "$SID" "rework-detector" "said" "$FILE:$CYCLES"
# Время записи (D1030, 23 октября 2026) — вход будущей меры действия стража разбора миром: повтор правки
# того же файла после починки и зелёного прогона. Самой меры пока нет; без времени её не построить —
# свести переработку с вмешательством стража было нечем. Поле стоит ПЕРВЫМ: гашение повтора выше
# ищет подстроку `"path":…,"cycles":N}` с закрывающей скобкой, и поле после `cycles` её бы сломало.
# Идентификатор ответа модели, чья правка подняла ступень (`msg`, D1289): страж разбора не отклоняет по ней остальные
# правки того же ответа — пакет параллельных правок судится как одна. Расшифровка — актора, как у стража
# (`resolve_actor_transcript`), иначе поле входа; последняя запись ответа в ней — ответ этого вызова (результаты
# инструментов — записи user). Нет расшифровки или идентификатора — запись прежнего вида.
_rw_tr=""
command -v resolve_actor_transcript >/dev/null 2>&1 && _rw_tr=$(resolve_actor_transcript "$INPUT" 2>/dev/null)
[ -n "$_rw_tr" ] || _rw_tr=$(printf '%s' "$INPUT" | jq -r '.transcript_path // empty' 2>/dev/null)
_rw_msg=""
[ -n "$_rw_tr" ] && [ -f "$_rw_tr" ] && _rw_msg=$(tail -c 4000000 "$_rw_tr" 2>/dev/null | grep -F '"type":"assistant"' \
    | tail -n 1 | jq -r '.message.id // empty' 2>/dev/null)
case "$_rw_msg" in *[!A-Za-z0-9_-]*) _rw_msg="" ;; esac
if [ -n "$_rw_msg" ]; then
    printf '{"ts":"%s","msg":"%s","path":"%s","cycles":%s}\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$_rw_msg" "$FILE" "$CYCLES" \
        >> "$FIRED" 2>/dev/null || true
else
    printf '{"ts":"%s","path":"%s","cycles":%s}\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$FILE" "$CYCLES" >> "$FIRED" 2>/dev/null || true
fi

BASE=$(basename "$FILE")
if [ "$CYCLES" -eq 2 ] 2>/dev/null; then
    # Второй заход — разворот, а не хроника: короткий вопрос, без доктрины. Полный текст
    # здесь стоил бы дороже находки: на этой стадии ещё неизвестно, есть ли что разбирать.
    CTX=$(printf '🔁 Второй заход на %s: между правками был прогон, значит первую попытку проверили и она не сошлась.\n\nНазови ОДНОЙ строкой, почему первая не сработала, прежде чем делать вторую. Если это не разворот, а следующий по плану шаг — так и скажи, и иди дальше.\n\nПрогоны при этом могли быть зелёными: детектор ошибок такое не видит, он считает провалы.' \
        "$BASE")
else
    CTX=$(printf '🔁 Переработка: %s правится %s-й раз, и между правками были прогоны — значит результат каждый раз проверяли и он не устраивал.\n\nВсе прогоны при этом могли быть зелёными: детектор ошибок такое не видит, он считает провалы.\n\nОстановись до следующей правки и назови причину, а не симптом:\n\n%s\n\n%s\n\nЕсли причина найдена — чини её, а не текущий симптом. Если правка действительно четвёртая по делу (разные задачи в одном файле) — игнорируй.' \
        "$BASE" "$CYCLES" "$RC_DOCTRINE" "$RC_OUTCOME_LINE")
fi

jq -n --arg ctx "$CTX" --arg ev "${RW_EVENT:-PostToolUse}" '{
    hookSpecificOutput: {
        hookEventName: $ev,
        additionalContext: $ctx
    }
}'
exit 0
