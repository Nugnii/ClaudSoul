# rw_bed_targets — файлы, изменённые ЭТОЙ командой, по ответу клиента (D1299 v3, 16 ноября 2026, корень R6).
#   Код 0 — канал ответил (печатает цели, возможно ни одной); 1 — не ответил, решает прежний путь (разница мира с окном).
#
# У факта «какие файлы изменила команда» есть владелец — клиент: результат Bash несёт `bashEditDiff`, разницу рабочего
# дерева до и после команды (описание поля в коде клиента 2.1.325: «for rendering and for PostToolUse Bash hooks»). Зонд
# 16 ноября 2026 (`claude -p` с хуком-дампом): поле приходит во входе `tool_response`, у правки через python — только её
# файл, у фонового агента — в его собственном событии; у упавшей команды `tool_response` пуст. v2 выводил автора из
# ЗАМЕСТИТЕЛЯ — времени файла — и ошибался там, где время лжёт: копия с сохранением времени (`cp -p`, `tar x`),
# округление и задержка хука, чужая запись в окне короткой команды (скептик opus по 99d31c91, M1–M3).
# Поле опускается в двух случаях, которые по входу не различить: команда ничего не изменила — или канал выключен (режим
# разрешений не auto, флаг клиента, фоновая или прерванная команда; в `claude -p` при режиме auto поля не было, пока его
# не включили переменной `CLAUDE_CODE_BASH_EDIT_DIFF`). Поэтому «нет поля» значит «не изменила», только если в этой
# сессии поле уже приходило и канал с тех пор не сдался (`RW_BED_MARK`), режим auto или bypassPermissions, событие —
# успех, команда не фоновая и не прерванная. Смысл объекта — по коду, который его выдаёт, а не по схеме (скептик opus по
# 1a0945f0, M2): `shared` без путей — «разницы нет, а рядом шла другая команда», то есть ответ «не изменила»;
# `skipped` (простая git checkout/reset) и `unavailable` без путей — не ответ.
# Перечень клиента — «что изменилось в дереве», а предмет хука — «содержимое ОТСЛЕЖИВАЕМОГО файла не то, что было
# видно» (L3, L4): откат своей правки в составной команде и новый неотслеживаемый файл прогона клиент перечисляет. Поэтому
# цели — пересечение перечня с разницей мира без окна (`rw_bed_meet`), а не сам перечень.
# НАЗВАННЫЕ ПРЕДЕЛЫ: поле внутреннее (`@internal`) и может смениться без объявления — тогда прежний путь; канал видит
# репозиторий каталога команды, и правка в ДРУГОМ репозитории формой вне перечня при «нет поля» не видна; чужая запись в
# окне этой команды входит в её разницу (снимок дерева до и после), как и в v2; у упавшей и фоновой команды канала нет
# по устройству клиента — там прежний путь с окном (6,8% и 3,2% вызовов за 8 дней). Условие снятия последнего: клиент
# начнёт отдавать `bashEditDiff` в событии провала.
rw_bed_targets() {
    _rb=$(printf '%s' "$INPUT" | jq -r '
        (.tool_response | if type == "object" then . else {} end) as $r
        | if ($r.bashEditDiff | type) == "object" then
            ([($r.bashEditDiff.changedFiles // [])[], ($r.bashEditDiff.files // [])[].filePath] | unique) as $p
            | if ($p | length) > 0 then ("diff", $p[])
              elif $r.bashEditDiff.shared == true and $r.bashEditDiff.unavailable != true
                   and $r.bashEditDiff.skipped != true then "diff"
              else "off" end
          elif (.permission_mode == "auto" or .permission_mode == "bypassPermissions")
               and (.hook_event_name // "PostToolUse") == "PostToolUse" and .tool_input.run_in_background != true
               and $r.backgroundTaskId == null and $r.interrupted != true then "absent"
          else "off" end' 2>/dev/null)
    case "$_rb" in
        diff*) printf '%s\n' "$_rb" | sed 1d | while IFS= read -r _rb_f; do
                   [ -f "$_rb_f" ] && ! rw_is_draft "$_rb_f" && printf '%s\n' "$_rb_f"
               done
               return 0 ;;
        absent) [ -f "$RW_BED_MARK" ] ;;
        *) return 1 ;;
    esac
}
# rw_bed_meet <перечень клиента> <разница мира без окна> — пути разницы мира, которые есть и в перечне клиента: файл
# изменила ЭТА команда, и его содержимое не то, что было видно. Сравнение — по физическому пути: клиент берёт пути у
# git, мир — логическим `pwd` каталога события (`/tmp` против `/private/tmp`, ссылки). Печатается вид мира — в нём же
# журнал хранит прежние записи этого файла.
_rw_real() { ( cd "${1%/*}" 2>/dev/null && printf '%s/%s\n' "$(pwd -P)" "${1##*/}" ); }
rw_bed_meet() {
    _bm_bed=""
    while IFS= read -r _bm_f; do
        [ -n "$_bm_f" ] && _bm_bed="$_bm_bed$(_rw_real "$_bm_f")
"
    done <<EOF
$1
EOF
    while IFS= read -r _bm_w; do
        [ -n "$_bm_w" ] || continue
        case "
$_bm_bed" in *"
$(_rw_real "$_bm_w")
"*) printf '%s\n' "$_bm_w" ;; esac
    done <<EOF
$2
EOF
}
# rw_log_run — запись «прогон» в журнал цепочки, только на успехе: упавшая команда — не прогон (скептик opus по
