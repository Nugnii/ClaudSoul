else
    RC_OUTCOME_LINE="Исход: починка механизма · пункт долга · запись знания · вердикт «показалось»."
fi

THRESHOLD="${REWORK_THRESHOLD:-2}"

mkdir -p "$STATE_DIR" 2>/dev/null
command -v jq >/dev/null 2>&1 || exit 0

# throttle_file — владелец имени журнала повода; своей копии не заводим.
THROTTLE_LIB="${THROTTLE_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/throttle-lib.sh}"
[ -f "$THROTTLE_LIB" ] || THROTTLE_LIB="$HOME/.claude/hooks/throttle-lib.sh"
# shellcheck source=/dev/null
[ -f "$THROTTLE_LIB" ] && . "$THROTTLE_LIB" 2>/dev/null || true
PORTABLE_LIB="${PORTABLE_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/portable-lib.sh}"
[ -f "$PORTABLE_LIB" ] || PORTABLE_LIB="$HOME/.claude/hooks/portable-lib.sh"
# shellcheck source=/dev/null
[ -f "$PORTABLE_LIB" ] && . "$PORTABLE_LIB" 2>/dev/null || true
# Разбор команд оболочки — у владельца (D1330, корень R3): какие программы команда зовёт и какие файлы пишет
# (`executable_content_heads` — оба ответа одним запуском). До 21 ноября 2026 и то и другое узнавалось здесь образцами по всему тексту
# команды, и строка в кавычках или в теле heredoc читалась запуском и записью.
COMMAND_SCOPE_LIB="${COMMAND_SCOPE_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/command-scope-lib.sh}"
[ -f "$COMMAND_SCOPE_LIB" ] || COMMAND_SCOPE_LIB="$HOME/.claude/hooks/command-scope-lib.sh"
# shellcheck source=/dev/null
[ -f "$COMMAND_SCOPE_LIB" ] && . "$COMMAND_SCOPE_LIB" 2>/dev/null || true

