#!/usr/bin/env bash
# rework-detector.sh — PostToolUse: ВТОРОЙ заход на тот же файл при зелёных прогонах (разворот); цели правки берутся у мира, а не из формы команды.
# en: PostToolUse: second pass over the same file while every run looks green (a turnaround); edit targets come from the world, not from the command's form.
#
# Слепое пятно, которое он закрывает. Все существующие детекторы повторения реагируют
# на ОШИБКИ: `error-tracker` считает подряд идущие провалы Bash и на втором просит
# остановиться. Повторение с ЗЕЛЁНЫМ результатом не видит никто.
#
# Живой случай (v1.12.4). Один тест переписывался трижды: чистое дерево → staged пусто,
# стражи не запускались; воспроизведение последнего коммита → покрытие случайное;
# и только «всё дерево в индекс» дало настоящий прогон. Каждая из трёх итераций
# завершалась «0 провалов», то есть выглядела успехом. Ни один счётчик их не связал,
# и разбор причины («5 почему») не запускался — запускать его было нечему.
#
# Собеседник назвал это точно: три раза сделано одно и то же, потому что не был
# применён приём, который агент знает и раньше применял. Знание без момента
# срабатывания не работает — уровень 1 embedded-ness.
#
# Сигнатура переработки: правка файла → прогон → правка ТОГО ЖЕ файла → прогон →
# правка. Просто три правки подряд не считаются: это нормальное дописывание.
# Между правками обязан быть прогон — значит, результат проверяли и он не устроил.
#
# Contract:
#   Input  (stdin): PostToolUse JSON {session_id, tool_name, tool_input}
#   Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} или пусто
#   Exit:  always 0
#
# Порог: REWORK_THRESHOLD (по умолчанию 2) — на ВТОРОЙ правке в цепочке.
#
# Было 3. Поправка владельца 9 сентября 2026: «триггером есть твоя остановка при
# разработке и проба иначе или снова». Момент, который надо поймать, — не хроническая
# переработка, а первый разворот: попробовал, проверил, не сошлось, пробую иначе. Он
# наступает на ВТОРОЙ правке, и до третьей о нём не знал никто.
# Замер по 1421 цели во всех журналах: порог 3 даёт 243 срабатывания, порог 2 — 464,
# то есть примерно 8 на сессию вместо 4. Это не фон, и цена названа числом.
# Громкость разведена по заходам: второй — короткий вопрос, третий и дальше — полная
# доктрина разбора, как было. Иначе снижение порога удвоило бы объём инжекта.
# Throttle: один раз на файл за сессию, иначе алерт станет фоном.

set -uo pipefail

PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
if [ -f "$PATHS_LIB" ]; then source "$PATHS_LIB"; else : "${STATE_DIR:=$HOME/.claude/hooks/state}"; fi

# Порядок разбора — из root-cause-lib. До 29 августа 2026 здесь стояли ПЯТЬ готовых
# вопросов «почему» — своя редакция с фикс-глубиной, отменённой /retro 3.1 («критерий
# остановки — НЕ глубина 5»). Переработка файла — один из поводов гейта разбора, и хуки
# печатали разное. Библиотеки нет — текст деградирует до строки, детекция не страдает.
RC_LIB="${RC_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/root-cause-lib.sh}"
[ -f "$RC_LIB" ] || RC_LIB="$HOME/.claude/hooks/root-cause-lib.sh"
# shellcheck source=/dev/null
[ -f "$RC_LIB" ] && source "$RC_LIB"
if command -v rc_doctrine_short >/dev/null 2>&1; then
    RC_DOCTRINE=$(rc_doctrine_short)
else
    RC_DOCTRINE="Разбор до корня: вширь по проявлениям с адресами, затем цепочка «почему» от самых разных, остановка по признаку корня."
fi
# Порядок разбора говорит, КАК искать причину, но не говорит, чем ход обязан кончиться —
# и без второго предписание тормозит, не называя исхода (D111). Список исходов закрытый и
# лежит в библиотеке, а не переписывается здесь своими словами.
if command -v rc_resolution_kinds >/dev/null 2>&1; then
    RC_OUTCOME_LINE="Исход из закрытого списка: $(rc_resolution_kinds). Все четыре исполнимы без разрешения."
else
    RC_OUTCOME_LINE="Исход: починка механизма · пункт долга · запись знания · вердикт «показалось»."
fi

THRESHOLD="${REWORK_THRESHOLD:-2}"

mkdir -p "$STATE_DIR" 2>/dev/null
command -v jq >/dev/null 2>&1 || exit 0

# file_mtime знает и BSD, и GNU stat; своей копии не заводим.
PORTABLE_LIB="${PORTABLE_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/portable-lib.sh}"
[ -f "$PORTABLE_LIB" ] || PORTABLE_LIB="$HOME/.claude/hooks/portable-lib.sh"
# shellcheck source=/dev/null
[ -f "$PORTABLE_LIB" ] && . "$PORTABLE_LIB" 2>/dev/null || true

INPUT=$(cat 2>/dev/null || true)
[ -n "$INPUT" ] || exit 0

# rw_write_targets "<команда оболочки>"
#   Печатает по одному в строке абсолютные пути файлов проекта, В КОТОРЫЕ команда пишет.
#   Формы: редирект `> f` / `>> f`; `sed -i … f`; `tee f`; запись из python
#   (`open(…, "w")` — тогда берутся литералы путей, встреченные в команде).
#
#   Берётся АДРЕСАТ записи, а не любое упоминание пути: `bash run_all.sh > log` упоминает
#   скрипт, но пишет в другое место. Замер по живой сессии 27 августа 2026: по упоминаниям
#   сигналов было бы 12, треть из них по файлам, которые только запускались; по адресатам —
#   3, и все три действительно переписывались многократно.
#
#   Временные каталоги и файлы-хроники отбрасываются: хроники исключены и в ветке Edit,
#   повторная правка там норма жанра (калибровка D18).
# rw_world_targets — что ФАКТИЧЕСКИ изменилось в рабочем дереве с прошлого вызова хука.
#
# Зачем, замер 9 сентября 2026. Признак целей записи ПЕРЕЧИСЛЯЛ формы: `> f`, `>> f`,
# `sed -i`, `tee`, и python — только при наличии `open(…, "w")` в тексте команды. Правка
# через `pathlib.Path(…).write_text(…)` под перечень не подпадает, и за живую сессию из
# ~20 правленых файлов в журнал попали 6, причём единственное срабатывание стража пришлось
# на файл ВНЕ репозитория (план), то есть было ложным, а три настоящих захода на один
# признак не увидены вовсе. Это род F: универсум механизма перечислен, а не выведен, и
# следующая форма записи снова окажется вне перечня.
#
# Здесь предмет наблюдения — не текст команды, а МИР: `git status` даёт изменённые файлы,
# `file_mtime` — время правки; разница со снимком прошлого вызова и есть «что тронули».
# Форма записи перестаёт иметь значение: python, sed, редирект, чужой скрипт — всё равно.
#
# НАЗВАННЫЙ ПРЕДЕЛ: вне git-репозитория снимка нет, и ветка молчит — там остаётся перечень
# форм. Файл, изменённый и возвращённый к прежнему содержимому в пределах одного вызова,
# виден по mtime, а не по содержимому: это правка, и считать её правкой верно.
# Условие снятия: предел держится, пока «что изменилось» спрашивается у git. Появится общий
# снимок дерева по mtime, не зависящий от системы контроля версий (обход каталога проекта с
# отсечением игнорируемого), — и ветка заработает в любом каталоге, а перечень форм станет
# не нужен вовсе.
rw_world_targets() {
    _rw_root="${RW_CWD:-$PWD}"
    command -v file_mtime >/dev/null 2>&1 || return 0
    # Снимок принадлежит АКТОРУ, а не только сессии (10 сентября 2026). Субагент получает
    # `session_id` родителя — проверено на живых данных: четыре транскрипта `agent-*.jsonl`
    # несут один sessionId, — поэтому общий снимок приписывал субагенту правки родителя.
    # Наблюдалось в журнале: `rework-fired` нёс `README.md cycles=3` и `ROOTS.md cycles=2,3`
    # в сессии субагента, который ни того, ни другого не касался. Предмет наблюдения здесь —
    # «что изменилось в мире с прошлого вызова», и он верен; неверно было УТВЕРЖДЕНИЕ о
    # владельце правки (`pattern-subject-of-measurement-mismatch`).
    _rw_actor=""
    case "$(basename "$(printf '%s' "$INPUT" | jq -r '.transcript_path // ""' 2>/dev/null)" 2>/dev/null)" in
        agent-*) _rw_actor=".$(basename "$(printf '%s' "$INPUT" | jq -r '.transcript_path // ""' 2>/dev/null)" .jsonl)" ;;
    esac
    _rw_snapf="$STATE_DIR/rework-world-${SID:-unknown}${_rw_actor}.txt"
    # `-z`: пути отдаются NUL-разделёнными и БЕЗ кавычек. Прежний `--porcelain` без него брал
    # в кавычки с восьмеричными escape всякий путь с пробелом или не-ASCII (`"two words.sh"`,
    # `"\320\272..."`), проверка `[ -f ]` такого файла не находила, и путь исчезал МОЛЧА —
    # ни счётчика, ни слова. Проба: три изменённых файла, в журнал попадал один.
    # НАЗВАННЫЙ ПРЕДЕЛ: имя с настоящим переводом строки всё ещё потеряется — разделителем
    # здесь снова стал `\n`. В дереве таких нет; условие снятия — обработка потока без
    # построчного чтения.
    _rw_now=$(cd "$_rw_root" 2>/dev/null && git status --porcelain -z --untracked-files=no 2>/dev/null \
        | tr '\0' '\n' | sed -E 's/^.{3}//' | while IFS= read -r _rw_p; do
            _rw_p="${_rw_p%% -> *}"
            [ -f "$_rw_root/$_rw_p" ] || continue
            printf '%s\t%s\n' "$_rw_p" "$(file_mtime "$_rw_root/$_rw_p" 2>/dev/null)"
        done)
    if [ -f "$_rw_snapf" ]; then
        # Изменившиеся и новые строки снимка — это и есть тронутые файлы.
        printf '%s\n' "$_rw_now" | while IFS= read -r _rw_line; do
            [ -n "$_rw_line" ] || continue
            grep -qxF "$_rw_line" "$_rw_snapf" 2>/dev/null || {
                _rw_pp="${_rw_line%%	*}"
                [ -n "$_rw_pp" ] && printf '%s\n' "$_rw_root/$_rw_pp"
            }
        done
    fi
    printf '%s\n' "$_rw_now" > "$_rw_snapf" 2>/dev/null || true
}

rw_write_targets() {
    _rw_c="$1"
    {
        printf '%s' "$_rw_c" | grep -oE '>>?[[:space:]]*["'"'"']?[A-Za-z0-9_./~-]+\.(sh|py|md|json|yml|yaml|tsv)' 2>/dev/null \
            | sed -E 's/^>>?[[:space:]]*["'"'"']?//'
        printf '%s' "$_rw_c" | grep -oE '(sed[[:space:]]+-i|tee)[^|;&]*[[:space:]]["'"'"']?[A-Za-z0-9_./~-]+\.(sh|py|md|json|yml|yaml|tsv)' 2>/dev/null \
            | grep -oE '[A-Za-z0-9_./~-]+\.(sh|py|md|json|yml|yaml|tsv)$'
        # herestring, а не труба: `cmd | grep -q` под pipefail врёт кодом 141 под нагрузкой
        # (D50, страж test_assert_no_sigpipe — он и поймал эту строку при первом прогоне).
        if grep -qE 'open\([^)]*["'"'"']w' <<< "$_rw_c" 2>/dev/null; then
            printf '%s' "$_rw_c" | grep -oE '["'"'"'][A-Za-z0-9_./~-]+\.(sh|py|md|json|yml|yaml|tsv)["'"'"']' 2>/dev/null \
                | tr -d '"'"'"'"'
        fi
    } 2>/dev/null | while IFS= read -r _rw_t; do
        [ -n "$_rw_t" ] || continue
        case "$_rw_t" in
            */tmp/*|*scratchpad*|*CHANGELOG*|*BACKLOG*|*SESSION*|*.claude-docs/sessions/*) continue ;;
        esac
        case "$_rw_t" in
            /*) [ -f "$_rw_t" ] && printf '%s\n' "$_rw_t" ;;
            *)
                # Каталог сессии из payload стоит ПЕРВЫМ (D277, 3 сентября 2026). Прежде
                # список начинался с $CLAUDE_PROJECT_DIR и $PWD, а `.cwd` не разбиралось
                # ни разу (`grep -c '\.cwd' hooks/rework-detector.sh` → 0): относительный
                # путь достраивался каталогом ПРОЦЕССА хука, и при запуске из чужого
                # каталога ни один файл не находился — цепочка не набирала ни шага, страж
                # молчал. Замер 3 сентября 2026 на трёх правках `printf x >> t.sh` из
                # процесса в `/` при cwd сессии в payload: было молчание, стало
                # срабатывание на третьей.
                for _rw_r in "${RW_CWD:-}" "${CLAUDE_PROJECT_DIR:-}" "$PWD" "$HOME/.claude/hooks"; do
                    [ -n "$_rw_r" ] || continue
                    for _rw_s in "" "hooks/" "hooks/tests/" "scripts/"; do
                        if [ -f "$_rw_r/$_rw_s$_rw_t" ]; then printf '%s\n' "$_rw_r/$_rw_s$_rw_t"; break 2; fi
                    done
                done
                ;;
        esac
    done | awk '!seen[$0]++'
}

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)
# Каталог сессии — вход события, а не состояние процесса (D277). Читается здесь, а
# используется в rw_write_targets при достройке относительных путей (см. там же).
RW_CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
LOG="$STATE_DIR/rework-${SID}.jsonl"

case "$TOOL" in
    Bash)
        # Правка через оболочку — такая же правка (D91). Раньше здесь стоял только
        # «прогон», и цепочка не набирала ни шага в сессиях, где файлы правят через
        # heredoc и sed: замер 27 августа 2026 по живой сессии — 156 записей в логе,
        # из них 16 правок, и все 16 от субагентов через Write, а `hook-input-lib.sh`,
        # переписанный больше десяти раз через оболочку, отсутствовал полностью.
        # Непустой лог маскировал нулевой сигнал. Тот же корень закрывали 26 августа
        # для blocker-tier знаний (D79, 45% правок мимо), у этого потребителя он остался.
        [ -f "$LOG" ] || exit 0
        _rw_cmd=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
        _rw_targets=$(rw_write_targets "$_rw_cmd")
        # Перечень форм молчит — спрашиваем мир. Порядок такой, потому что перечень
        # называет АДРЕСАТА команды точно, а мир — всё тронутое с прошлого вызова, включая
        # тронутое не этой командой; точное знание предпочтительнее приблизительного.
        _rw_world=$(rw_world_targets)
        [ -n "$_rw_targets" ] || _rw_targets="$_rw_world"
        if [ -z "$_rw_targets" ]; then
            printf '{"kind":"run"}\n' >> "$LOG" 2>/dev/null || true
            exit 0
        fi
        printf '%s\n' "$_rw_targets" | while IFS= read -r _rw_f; do
            [ -n "$_rw_f" ] || continue
            printf '{"kind":"edit","path":"%s"}\n' "$_rw_f" >> "$LOG" 2>/dev/null || true
        done
        # Порог проверяется по первому адресату: команда, пишущая сразу в несколько
        # файлов проекта, в этой работе редкость, а остальные уже попали в цепочку.
        FILE=$(printf '%s\n' "$_rw_targets" | awk 'NF { print; exit }')
        ;;
    Edit|Write|MultiEdit) ;;
    *) exit 0 ;;
esac

# Для Bash адресат уже определён в ветке выше; у файловых инструментов он в tool_input.
if [ -z "${FILE:-}" ]; then
    FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)
fi
[ -n "$FILE" ] || exit 0

# Калибровка D18 (2026-08-08, выборка 40 срабатываний): 10 пришлись на
# файлы-хроники (CHANGELOG x4, BACKLOG x3, SESSION x2, архив) — там повторные
# правки норма жанра (append-лог), ни одно срабатывание не было переработкой.
# Хроники исключены до записи в цепочку; маска переопределяется env.
#
# Разметка выборки D23 (2026-08-11, 36 срабатываний после калибровки): хроник ноль —
# исключение работает, — но два срабатывания пришлись на CLAUDE.md и одно на META.md.
# Это документы СОСТОЯНИЯ: они переписываются по ходу сессии столько раз, сколько
# уточняется картина, и повторная правка в них — тот же жанр, что append в хронике.
# КОНТРПРИМЕР: журнальные файлы ВНЕ этого перечня — `docs/*.md`, `.claude-docs/*` —
# исключением не покрыты, и повторная дозапись в них засчитается переработкой.
# Перечень назван перечнем: он растёт по мере встречи новых журналов, не по правилу.
# Калибровка D358 (13 сентября 2026, носитель 2). Выборка 20 напоминаний с чтением текста хода
# (`scripts/five-whys-attribution-replay.py --sample-rework 20`, seed 13): настоящих разворотов 7 из 20
# (35%); из 13 ложных шесть — на ПРОИЗВОДНЫХ файлах учёта и документах, которые каждая задача
# правит по устройству: индекс зависимостей (пересборка после каждого пункта — 79 из 756
# срабатываний в 62 живых журналах, чаще любого другого файла), карта корней, README, документы
# `docs/` и доки модулей `.claude-docs/`. Всего на этих семьях 202 из 756 срабатываний (27%).
# По ADR-015 65% ложных — сужение признака, а не подъём и не снятие: перечень расширен этими
# семьями; код в `hooks/`, `scripts/`, `lib/` и тесты считаются как прежде (T8c/T8d свидетеля).
REWORK_EXCLUDE_RE="${REWORK_EXCLUDE_RE:-(CHANGELOG|SESSION|BACKLOG[^/]*|CLAUDE|META|README(\.ru)?|ROOTS)\.md$|dep-index\.tsv$|/docs/[^/]+\.md$|/\.claude-docs/.*\.md$}"
# Ответ берётся у grep, а не у трубы: под `set -o pipefail` producer, убитый SIGPIPE,
# отдаёт 141, и исключение молча перестаёт исключать (D50; доказано замером в D59).
grep -qE "$REWORK_EXCLUDE_RE" <<< "$FILE" && exit 0

# Ветка Bash уже записала ВСЕ свои цели выше; здесь пишет только файловый инструмент.
# Прежде запись шла безусловно, и каждая правка через оболочку попадала в журнал ДВАЖДЫ:
# один раз перечнем целей, второй — здесь по первой из них. Замер 9 сентября 2026 на
# фикстуре: одна правка `printf x > f3.sh` → две записи `edit`. Следствие несимметричное —
# порог «три цикла» для правок через оболочку достигался вдвое быстрее, чем для Edit, а
# в живом журнале сессии 14 записей означали 7 правок. Дефект маскировался встречным:
# правки, форма которых вне перечня, не считались вовсе.
if [ "$TOOL" != "Bash" ]; then
    printf '{"kind":"edit","path":"%s"}\n' "$FILE" >> "$LOG" 2>/dev/null || true
fi

# Считаем правки этого файла, между которыми был прогон.
# Цепочка: edit(F) ... run ... edit(F) ... run ... edit(F) → CYCLES=3.
CYCLES=$(awk -v f="$FILE" '
    /"kind":"run"/ { ran = 1; next }
    /"kind":"edit"/ {
        # путь текущей строки
        if (split($0, a, "\"path\":\"") < 2) next
        split(a[2], b, "\"")
        if (b[1] != f) next
        if (first == 0) { first = 1; n = 1; ran = 0; next }
        if (ran == 1) { n++; ran = 0 }
    }
    END { print n + 0 }
' "$LOG" 2>/dev/null || echo 0)
CYCLES=${CYCLES:-0}

[ "$CYCLES" -ge "$THRESHOLD" ] 2>/dev/null || exit 0

# Throttle: один раз на (файл, число циклов) за сессию — а не на файл. Первый прогон замера
# detection-share (30 августа 2026) показал «сказал 16%»: после первого напоминания файл
# переделывался дальше — четвёртый, пятый цикл — и страж молчал, хотя каждый новый цикл есть
# НОВОЕ событие того же рода («повтор уплывает», поправка владельца 27 августа). Правки без
# прогона между ними число циклов не меняют и молчат как прежде.
FIRED="$STATE_DIR/rework-fired-${SID}.jsonl"
if [ -f "$FIRED" ] && grep -Fq "\"path\":\"$FILE\",\"cycles\":$CYCLES}" "$FIRED" 2>/dev/null; then
    # Признак СОВПАЛ, страж промолчал по троттлу — это знаменатель, а не пустота (D205):
    # без него доля «сказал против промолчал» непосчитаема по построению. Подпись —
    # файл и цикл: повтор той же подписи в замере не считается подавлением.
    command -v rc_note_detection >/dev/null 2>&1 && \
        rc_note_detection "$STATE_DIR" "$SID" "rework-detector" "muted" "$FILE:$CYCLES"
    exit 0
fi
command -v rc_note_detection >/dev/null 2>&1 && \
    rc_note_detection "$STATE_DIR" "$SID" "rework-detector" "said" "$FILE:$CYCLES"
printf '{"path":"%s","cycles":%s}\n' "$FILE" "$CYCLES" >> "$FIRED" 2>/dev/null || true

BASE=$(basename "$FILE")
if [ "$CYCLES" -eq 2 ] 2>/dev/null; then
    # Второй заход — разворот, а не хроника: короткий вопрос, без доктрины. Полный текст
    # здесь стоил бы дороже находки: на этой стадии ещё неизвестно, есть ли что разбирать.
    CTX=$(printf '🔁 Второй заход на %s: между правками был прогон, значит первую попытку проверили и она не сошлась.\n\nНазови ОДНОЙ строкой, почему первая не сработала, прежде чем делать вторую. Если это не разворот, а следующий по плану шаг — так и скажи, и иди дальше.\n\nПрогоны при этом могли быть зелёными: детектор ошибок такое не видит, он считает провалы.' \
        "$BASE")
else
    CTX=$(printf '🔁 Переработка: %s правится %s-й раз, и между правками были прогоны — значит результат каждый раз проверяли и он не устраивал.\n\nВсе прогоны при этом могли быть зелёными: детектор ошибок такое не видит, он считает провалы.\n\nОстановись до следующей правки и назови причину, а не симптом:\n\n%s\n\n%s\n\nЕсли причина найдена — чини её, а не текущий симптом. Если правка действительно четвёртая по делу (разные задачи в одном файле) — игнорируй.' \
        "$BASE" "$CYCLES" "$RC_DOCTRINE" "$RC_OUTCOME_LINE")
fi

jq -n --arg ctx "$CTX" '{
    hookSpecificOutput: {
        hookEventName: "PostToolUse",
        additionalContext: $ctx
    }
}'
exit 0
