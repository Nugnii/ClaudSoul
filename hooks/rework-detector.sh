    _rr_n=$(rw_rerun_bump "$_rr_subj")
    [ "${_rr_n:-0}" -ge "${REWORK_RERUN_THRESHOLD:-5}" ] 2>/dev/null || return 0
    _rr_fired="$STATE_DIR/rework-rerun-told-${SID:-unknown}${RW_ACTOR:-}.jsonl"
    grep -Fq "\"path\":\"$_rr_subj\",\"reruns\":$_rr_n}" "$_rr_fired" 2>/dev/null && return 0
    printf '{"path":"%s","reruns":%s}\n' "$_rr_subj" "$_rr_n" >> "$_rr_fired" 2>/dev/null || true
    command -v jq >/dev/null 2>&1 || return 0
    jq -n --arg s "$_rr_subj" --argjson n "$_rr_n" --arg ev "${RW_EVENT:-PostToolUse}" \
      '{hookSpecificOutput:{hookEventName:$ev,additionalContext:("🔁 " + ($n|tostring) + "-й прогон подряд одного файла без единой правки между ними: " + $s + ".\n\nПовтор бывает и в успехах — три зелёных прогона одного файла такой же признак, как три падения. Прогон ничего не меняет: чтобы результат изменился, надо изменить мир либо СПОСОБ наблюдения.\nДешевле полного прогона: точечный запуск одной проверки, отладочный режим (--debug/--ui/--trace у playwright, -x/-k у pytest), чтение журнала прошлого прогона вместо нового.\nЕсли прогон ждёт ВНЕШНЕГО события (CI, фоновая задача) — так и скажи, это другой случай.")}}' 2>/dev/null || true
}

# rw_all_seen_since_run <журнал> <цели через перевод строки> — код 0, если КАЖДАЯ цель уже
# записана в журнал после последнего `{"kind":"run"}`, то есть новых правок среди них нет.
#
# Зачем (D458, 18 сентября 2026). `{"kind":"run"}` писался ТОЛЬКО при пустом перечне целей,
# а `rw_world_targets` объявляет целью всякий файл, чей mtime отличается от снимка прошлого
# вызова; `file_mtime` меряет ЦЕЛЫМИ секундами. Поэтому прогон, идущий за правкой в ДРУГУЮ
# секунду, объявлял правленый файл целью записи и писал `edit` вместо `run` — цепочка
# «правка → прогон → правка» не росла. Замер: три цикла при паузе 0 дают 2 записи `run`,
# при паузе в секунду — одну. В живой работе дефект смягчался тем, что вызовов оболочки
# между правками обычно больше одного: второй поглощал изменение в снимок. То есть счёт
# циклов зависел от ЧИСЛА вызовов Bash — величины, к переработке отношения не имеющей.
#
# ПОЧЕМУ НЕ «писать `run` всегда, когда цели из мира»: тогда правка через форму ВНЕ перечня
# (`pathlib.Path(...).write_text(...)` и подобное) перестала бы считаться правкой вовсе —
# ради этого случая мир и спрашивается. Различает их журнал: цель, уже записанная после
# последнего прогона, — след учтённой правки; цель, которой там нет, — правка новая.
rw_all_seen_since_run() {
    _rw_log="${1:-}"; _rw_tg="${2:-}"
    [ -f "$_rw_log" ] && [ -n "$_rw_tg" ] || return 1
    # Цикл читает из herestring, а НЕ из трубы, и вердикт копится в переменной, а не
    # передаётся через `| grep -q`. Обе причины — одна: под `set -o pipefail` producer,
    # убитый SIGPIPE, отдаёт 141, и утверждение врёт под нагрузкой (D50; страж
    # `test_assert_no_sigpipe` поймал здесь первую редакцию этой самой функции — она
    # воспроизвела дефект, о котором предупреждает шапка этого же файла). Труба вдобавок
    # уводит тело цикла в подоболочку, где присваивание не переживает выхода.
    _rw_miss=0
    while IFS= read -r _rw_one; do
        [ -n "$_rw_one" ] || continue
        # Хвост журнала после последнего прогона — и в нём ищем эту цель.
        if ! awk -v p="$_rw_one" '
            /"kind":"run"/ { seen = ""; next }
            /"kind":"edit"/ {
                if (split($0, a, "\"path\":\"") < 2) next
                split(a[2], b, "\"")
                if (b[1] == p) seen = "1"
            }
            END { exit(seen == "1" ? 0 : 1) }
        ' "$_rw_log" 2>/dev/null; then
            _rw_miss=1
            break
        fi
    done <<EOF
$_rw_tg
EOF
    [ "$_rw_miss" -eq 0 ]
}

