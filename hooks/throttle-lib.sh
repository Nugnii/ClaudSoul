#!/bin/bash
# throttle-lib.sh — v1.0.0
#
# ПРЕФИКСЫ: throttle_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
# Единый per-session механизм подавления повторов для хуков ClaudSoul.
#
# До v1.0.0 логика throttle была скопирована в 6 хуков с расходящимися именами
# поля ключа ("key" в blocker-tier-check, "hash" в docs-family/enrich/
# quality-gate/skill-review) и флаг-файлом без ключа в decompose-detector.
# Копипаст уже посеял рассинхрон (см. docs/health-audit-2026-06-20.md, F1).
# Эта библиотека — единый источник. Каноническое имя поля — "key".
#
# Throttle-файлы эфемерны: имя содержит SESSION_ID, читаются только в своей
# сессии тем же кодом — смена имени поля ничего исторического не ломает.
#
# Эфемерность до v1.16.1 была ОБЪЯВЛЕНА и не исполнялась (D44): библиотека не удаляла
# свои файлы никогда, а поимённый список уборки в `session-collector.sh:466` разошёлся с
# реальностью на 20+ семейств. Замер: `blocker-fired-*` 122 файла, `trust-guard-fired-*`
# 72, `docs-family-fired-*` 61, `decompose-fired-*` 32, и дальше по списку. Документация
# описывала свойство, которого нет, — ровно тот класс, что разбирался в D38.
#
# Теперь уборка стоит ЗДЕСЬ, в единственном месте, где схема имён известна: любой новый
# страж получает её автоматически, а поимённый список не нужен и не может разойтись.
#
# Provides:
#   throttle_file <state_dir> <name> <sid>   → путь к jsonl по единой схеме
#                                               <state_dir>/<name>-fired-<sid>.jsonl
#   throttle_seen <file> <key>               → код 0 если <key> уже зафиксирован,
#                                               иначе код 1 (в т.ч. если файла нет)
#   throttle_mark <file> <key> [имя значение ...] → дописать запись о <key>;
#                                               доп. поля парами, БЕЗ кавычек и запятых:
#                                               throttle_mark "$F" "$k" marker v1.0
#
# ПОЧЕМУ ПАРЫ, А НЕ ГОТОВЫЙ КУСОК JSON (5 сентября 2026). Прежний контракт принимал сырой
# фрагмент, и экранирование лежало на КАЖДОМ зовущем — шесть мест строили его `printf`.
# Пятеро подставляли своё (имя знания, маркер версии, число), а `trust-guard.sh:241` —
# `"target":"%s"` из КОМАНДНОЙ СТРОКИ собеседника: кавычка в пути ломала строку, и журнал
# переставал разбираться. Замер 5 сентября 2026 по живым журналам: у `trust-guard-fired`
# 131 битая строка из 210, битые есть по сегодня включительно. Это ВТОРОЙ журнал, сломанный
# этим контрактом: первым был `bulk-copy-fired` (79 из 134), чинившийся 4 сентября правкой
# СВОЕГО писателя — то есть места, а не класса.
# Дробь: мест с устройством 6, с симптомом 1; разделитель назван — значение приходит от
# собеседника, а не из своего перечня. Починка в контракте закрывает и будущего седьмого.
# Кодирование делает jq; нет jq — поле опускается, а не пишется сырым: битая запись хуже
# отсутствующей, потому что читатель теряет вместе с ней и соседние.
# НАЗВАННЫЙ ПРЕДЕЛ: значения передаются как строки; число попадёт в JSON строкой.
# Условие снятия: появится зовущий, которому тип поля важен для арифметики читателя.
#
# Паттерн использования (проверка и запись разнесены — как в существующих хуках):
#   F=$(throttle_file "$STATE_DIR" docs-family "$SESSION_ID")
#   if throttle_seen "$F" "$key"; then exit 0; fi   # уже было в этой сессии
#   ... хук делает работу / инжектит маркер ...
#   throttle_mark "$F" "$key"                        # отметить, что сработал
#
# Fail silently — источается из хуков, где ошибка не должна ронять процесс.

# Семейства, у которых есть МЕЖСЕССИОННЫЙ читатель — файл переживает свою сессию и
# служит выборкой. Уборке они не подлежат, сколько бы ни было объявлено в шапке.
#
# Список выведен проверкой, а не предположением: `grep -l '<семья>-fired-\*'` по всем
# хукам и скриптам — то есть ищется читатель, обходящий ВСЕ файлы семейства, а не свой.
#   blocker-fired-*  ← backfill-compliance.sh:143, эталон round-trip гейта
#   rework-fired-*   ← metrics-collector.sh:503, накопительная выборка для порога D18
#   correction-fired-* ← metrics-collector.sh:521, выборка классификатора поправок (D25)
#   trust-guard-fired-* ← scripts/doc-figures.sh:85, число срабатываний для README (реестр doc-claims)
#
# Цена ошибки измерена на себе: первая версия этой уборки снесла 122 файла
# `blocker-fired-*`, и выборка гейта «round-trip по 26 сессиям» ужалась до 2. Данные
# писал живой хук и пересобрать их нечем. Заявление шапки об эфемерности было ЛОЖНЫМ
# для двух семейств из двенадцати, и уборка это заявление исполнила буквально.
# Второй раз тот же дефект, и потому список больше не держится на памяти: 31 июля
# сюда внесли blocker и rework по грепу читателей, а в v1.17.1 появился читатель
# `correction-fired-*` (проверяющий условия D25) — и список никто не тронул. Уборка
# стирала свидетельства поправок через 3 дня: на 2026-08-09 их было 65 в 16 файлах,
# к 2026-08-26 остался 1. Пострадали три пункта долга сразу — D25 (выборка не может
# дорасти до порога 30), D20 (второй продюсер опровержений собирает кандидатов,
# но к моменту разбора очереди основание уже стёрто) и D57 по своему классу.
# Сверку «у семейства есть читатель по маске → семейство в списке» делает теперь
# tests/test_throttle_lib.sh (T12), а не автор правки.
THROTTLE_KEEP_FAMILIES="${THROTTLE_KEEP_FAMILIES:-blocker rework correction trust-guard}"

throttle_file() {
    local state_dir="$1"
    # Уборка по возрасту — только для семейств без межсессионного читателя.
    # Порог с запасом: сессия живёт часы, но `throttle_seen` обязан находить свой ключ
    # всю сессию целиком, включая долгие.
    # Отбор семейства идёт через `case` по имени файла, а НЕ через построение
    # `! -name ...` для find. Причина измерена (D83): и цикл `for _fam in $VAR`, и
    # подстановка `$_keep_expr` в аргументы find опираются на разбиение переменной на
    # слова, а zsh его по умолчанию не делает — «blocker rework correction» там ОДНО
    # слово. Итог под zsh: keep-выражение уходило в find одним аргументом, защита не
    # действовала, и уборка сносила в том числе `blocker` и `rework`. Воспроизведено на
    # пяти файлах: bash оставил защищённые три, zsh удалил все пять.
    #
    # `case` с подстрокой на разбиение не опирается вовсе, поэтому ведёт себя одинаково
    # в обеих оболочках — а хуки идут через bash, но те же функции зовут скиллы и
    # Bash-инструмент, который на macOS zsh (pattern-shell-portability).
    local _f _base _fam
    while IFS= read -r _f; do
        [ -n "$_f" ] || continue
        _base="${_f##*/}"
        _fam="${_base%%-fired-*}"
        case " $THROTTLE_KEEP_FAMILIES " in
            *" $_fam "*) continue ;;
        esac
        rm -f "$_f" 2>/dev/null || true
    done <<KEEP_EOF
$(find "$state_dir" -maxdepth 1 -name '*-fired-*' -mtime "+${THROTTLE_TTL_DAYS:-3}" 2>/dev/null || true)
KEEP_EOF
    printf '%s/%s-fired-%s.jsonl' "$state_dir" "$2" "$3"
}

throttle_seen() {
    local file="$1" key="$2"
    [ -f "$file" ] && grep -Fq "\"key\":\"$key\"" "$file" 2>/dev/null
}

throttle_mark() {
    local file="$1" key="$2"
    shift 2 || true
    local now
    now=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    if [ "$#" -eq 0 ] || ! command -v jq >/dev/null 2>&1; then
        printf '{"date":"%s","key":"%s"}\n' "$now" "$key" >> "$file"
        return 0
    fi
    # Имена и аргументы jq копятся ОТДЕЛЬНО: первая редакция считала индексы по плоскому
    # массиву `--arg имя значение` и теряла каждую вторую пару — поле `target` не доехало,
    # а запись выглядела целой. Поймано первым же прогоном с кавычкой в значении.
    local names=() args=() n v filter='{date:$d,key:$k}'
    while [ "$#" -ge 2 ]; do
        n="$1"; v="$2"; shift 2
        names+=("$n")
        args+=(--arg "$n" "$v")
    done
    # Нечётный хвост оставляет массивы пустыми, а пустое раскрытие `"${a[@]}"` под `set -u`
    # роняет bash 3.2 (macOS). Отсюда проверка длины, а не голое раскрытие.
    if [ "${#names[@]}" -eq 0 ]; then
        printf '{"date":"%s","key":"%s"}\n' "$now" "$key" >> "$file"
        return 0
    fi
    for n in "${names[@]}"; do
        filter="${filter} + {\"${n}\": \$${n}}"
    done
    jq -cn --arg d "$now" --arg k "$key" "${args[@]}" "$filter" >> "$file" 2>/dev/null \
        || printf '{"date":"%s","key":"%s"}\n' "$now" "$key" >> "$file"
}

