#!/usr/bin/env bash
# frame-control-lib.sh — прибор не выносит вердикт, не показав, что РАМКА умеет ответить «да».
# en: refuses a verdict when the judged population is empty — "nothing found" must not be
#     indistinguishable from "could not look".
#
# Результат: прибор, чья популяция пуста, отвечает «СУДИТЬ НЕЧЕМ» (код 2), а не «чисто» (0)
# Проверка результата: bash hooks/tests/test_frame_control_lib.sh даёт 0
#
# ЗАЧЕМ (20 сентября 2026, слово владельца «паттерн в механизм»).
# Знание `pattern-frame-without-a-positive-control` записано тем же днём по замеру одной
# сессии: из ПЯТИ построенных рамок положительный контроль был у одной, и соврали ровно
# четыре остальных. Два `.md`-файла без дерева дали 56 мнимых отказов архиватора; снимок
# `git archive` без `.git` — 12 отказов, из них 11 «судить нечем»; урезанный бюджет времени
# — два «срок истёк»; разбор вывода в пустой список дал «ушли все двенадцать». Правда
# пришла только с рабочих копий и полного срока: отказ один, истинный.
# Текстом это правило уже стояло и не удержалось — замер проекта по правилам уровня 1
# однозначен, и знание само себя подтверждало бы, оставшись записью.
#
# ЧЕМ РЕШАЛОСЬ РАНЬШЕ, И ПОЧЕМУ ВЛАДЕЛЕЦ НУЖЕН. Ровно эта проверка написана В ЧЕТЫРЁХ
# приборах, каждым своими словами: `scripts/root-map.py:264` («⚠ носители НЕ ПОСЧИТАНЫ»),
# `scripts/behavior-condition-probe.sh:90` («BROKEN: свидетелей-атак не найдено»),
# `scripts/named-limits.py:315` («не найдено ни одного объявления — прибор не отработал»),
# `scripts/probes/R6.sh:214` («Носители в этом прогоне НЕ ПОСЧИТАНЫ»). Четыре реализации
# одного факта — род K реестра и корень R1: они разойдутся молча, и пятый прибор напишет
# пятую. Здесь у факта один владелец, и новый прибор зовёт его строкой.
#
# ПОЧЕМУ КОД 2, А НЕ 1. У прибора три состояния, а не два (сквозное правило проекта,
# .claude/rules/claudsoul-hooks.md § «Хук зовёт инструмент»): «находок нет» — 0, «находки есть» — 1,
# «посмотреть не смог» — 2. Слить третье с первым значит пустить два состояния мира по
# одному проводу — корень R6, и именно он стоит за всеми четырьмя промахами замера выше.
#
# НАЗВАННЫЙ ПРЕДЕЛ: `frame_require_nonempty` судит ЧИСЛО, которое прибор ей подал. Она не
# знает, верно ли он посчитал свою популяцию. Это нижний рубеж — «популяция не пуста».
#
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ПЕРЕСТАЛ БЫТЬ ПРЕДЕЛОМ 20 сентября 2026: рядом встала
# `frame_require_red` — предъявить известное «да» ПРОГОНОМ. Повод — D342: четыре свидетеля
# реестра утверждений документов были зелены и на живом страже, и на выхолощенном, потому
# что судили его МОЛЧАНИЕ. После контроля 0 на живом и 2 на выпотрошенном у всех четырёх.
# Два рубежа теперь разные и оба нужны: «популяция не пуста» отвечает на вопрос «было ли
# что судить», «известное нарушение краснеет» — на вопрос «умеет ли судья говорить „да"».
# Условие снятия у нижнего рубежа остаётся своё: прибор станет сам предъявлять популяцию
# прогоном, а не числом.
# Проверка снятия: `grep -q "^frame_require_population_by_run()" hooks/frame-control-lib.sh`
# Проверка судит ОПРЕДЕЛЕНИЕ функции, а не упоминание имени, и это поправка того же дня:
# прежняя редакция искала имя по всему дереву и находила его В ЭТОЙ ЖЕ СТРОКЕ — условие
# было «наступившим» с минуты своего написания. Проверка по форме, поймавшая сама себя;
# тот же класс, что метка `Метка: судит по форме.` в договоре пункта долга.
#
# ПРЕФИКСЫ: frame_ FRAME_
#
# Использование:
#   . "$(dirname "$0")/../hooks/frame-control-lib.sh"
#   frame_require_nonempty "$N" "свидетелей-атак" || exit $?
#   frame_require_nonempty "$N" "носителей рода" "прогон по копии дерева" || exit $?

# Вторая загрузка молча не повторяется: библиотеку источают и приборы, и их свидетели.
[ -n "${FRAME_CONTROL_LIB_LOADED:-}" ] && return 0 2>/dev/null
FRAME_CONTROL_LIB_LOADED=1

# frame_require_nonempty <число> <что считали> [чем собиралась рамка]
#   → 0, если популяция непуста; 2 и строка в stderr, если пуста либо число не число.
#
# Число «не число» — тот же исход, что пустота, и это НЕ придирка: пустая строка приходит
# ровно тогда, когда разбор не отработал, а `[ "$n" -gt 0 ]` на ней падает с синтаксической
# ошибкой и уводит прибор в ветку, которой автор не писал.
frame_require_nonempty() {
    local _n="${1:-}" _what="${2:-популяция}" _how="${3:-}"
    case "$_n" in
        ''|*[!0-9]*)
            printf 'СУДИТЬ НЕЧЕМ: %s — число не получено (%s)\n' "$_what" "${_n:-пусто}" >&2
            [ -n "$_how" ] && printf 'Рамка собиралась так: %s\n' "$_how" >&2
            printf 'Это НЕ «находок нет»: вердикт не выносится, код 2.\n' >&2
            return 2 ;;
    esac
    if [ "$_n" -eq 0 ]; then
        printf 'СУДИТЬ НЕЧЕМ: %s — ноль, рамка не собралась\n' "$_what" >&2
        [ -n "$_how" ] && printf 'Рамка собиралась так: %s\n' "$_how" >&2
        printf 'Ответ «чисто» на пустой популяции неотличим от «не смог посмотреть»,\n' >&2
        printf 'поэтому вердикт не выносится: код 2.\n' >&2
        return 2
    fi
    return 0
}

# frame_require_red <что за известное «да»> <команда...>
#   → 0, если команда КРАСНАЯ (код не ноль) — рамка жива и умеет отвечать «да»;
#   → 2 и строка в stderr, если команда зелена: судимый механизм молчит даже на известном
#     нарушении, то есть он мёртв, и его молчание на ЗАКОННОМ случае ничего не значит.
#
# ЗАЧЕМ. Свидетель-атака часто проверяет, что страж НЕ сработал на законном случае: вердикт
# у него — «судимый промолчал», код ноль. Молчание — ровно то, что производит выпотрошенный
# механизм, поэтому такой свидетель зелен и на живом страже, и на заглушке `:`. Замер
# 20 сентября 2026 (D342): четыре свидетеля реестра утверждений документов зелены в обоих
# мирах, все четыре этого устройства.
#
# Контроль прямой: в той же песочнице предъявляется ИЗВЕСТНОЕ нарушение, и страж обязан на
# нём покраснеть. Не покраснел — судить нечем, и это отличается от «нарушений нет».
#
# Функция НЕ исполняет строку: команда приходит массивом аргументов и зовётся напрямую
# (`"$@"`), потому что текст непринятой команды — данные, а не программа.
frame_require_red() {
    local _what="${1:-известное нарушение}"; shift
    if [ "$#" -eq 0 ]; then
        printf 'СУДИТЬ НЕЧЕМ: frame_require_red позван без команды (%s)\n' "$_what" >&2
        return 2
    fi
    "$@" >/dev/null 2>&1
    local _rc=$?
    if [ "$_rc" -eq 0 ]; then
        printf 'СУДИТЬ НЕЧЕМ: положительный контроль «%s» НЕ покраснел (код 0)\n' "$_what" >&2
        printf 'Судимый механизм молчит и на известном нарушении — значит он мёртв,\n' >&2
        printf 'и его молчание на законном случае ничего не доказывает. Код 2.\n' >&2
        return 2
    fi
    return 0
}
