#!/usr/bin/env bash
# rules-write-bypass.sh — PreToolUse[Bash]: запись в установленные правила только через библиотеку (D101).
# en: PreToolUse[Bash] — the installed rules file may only be written through the merge library (D101).
#
# Результат: маркеры управляемого блока в ~/.claude/CLAUDE.md не теряются — пара «правила»
#            в drift-check никогда не бывает BROKEN.
# Проверка результата: bash hooks/tests/drift-check.sh | grep -q '^OK|правила'
#
# Повод. 28 августа 2026 пара «правила» была BROKEN: в установленном файле не оказалось
# маркеров, и сравнивать стало нечем. Шесть пар из семи сверялись, седьмая — нет, то есть
# мастер-копия могла уехать от установленной сколь угодно далеко, и ни один прогон бы об
# этом не сказал. Дрейф означает «сравнили и разошлось»; здесь было «не сравнивали вовсе».
#
# Почему именно эта пара беззащитна. У остальных шести установка — побайтовая копия, и любой
# обход ловится сравнением. Здесь установка ПРЕОБРАЗУЕТ содержимое (оборачивает в маркеры),
# поэтому обход даёт не расхождение, а невозможность сравнить.
#
# Почему страж стал возможен только сейчас. Пункт D101 отверг его возражением «правка идёт
# инструментом Edit, а хук PreToolUse[Bash] её не видит». Замер 28 августа по пяти сессиям:
# касаний ~/.claude/CLAUDE.md через Bash — 23, через Edit/Write — 0. Возражение снято
# данными, а не мнением.
#
# КОНТРПРИМЕР: правка установленных правил ИЗ ДРУГОГО ПРОЦЕССА — редактором, файловым
# менеджером, чужим скриптом — сюда не попадает: хук видит только вызовы Bash этой сессии.
# Для такого случая остаётся drift-check, который скажет постфактум.
#
# Input  (stdin): {tool_name, tool_input, ...}
# Output (stdout): {hookSpecificOutput:{permissionDecision:"deny", ...}} либо пусто
# Exit:  always 0.
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
[ "$TOOL" = "Bash" ] || exit 0
CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
[ -n "$CMD" ] || exit 0


# Цель — установленные ГЛОБАЛЬНЫЕ правила, не проектный CLAUDE.md.
case "$CMD" in
    *'.claude/CLAUDE.md'*) ;;
    *) exit 0 ;;
esac

# Библиотека области (`command-scope-lib.sh`) — владелец трёх вопросов этого стража: исполняемая часть
# текста, цели записи, место перенаправления. Библиотеки нет — страж молчит: тот, кто не умеет отличить
# чтение от записи, не имеет права на отказ.
CS_LIB="${CS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/command-scope-lib.sh}"
[ -f "$CS_LIB" ] || CS_LIB="$HOME/.claude/hooks/command-scope-lib.sh"
# shellcheck source=/dev/null
{ [ -f "$CS_LIB" ] && source "$CS_LIB"; } || exit 0
# Законный путь — через библиотеку слияния либо через установщик: если он в команде есть,
# дальше не смотрим.
#
# СУДИТ ИСПОЛНЯЕМУЮ ЧАСТЬ, А НЕ ВЕСЬ ТЕКСТ (D425, корень R3, 17 сентября 2026). Прежде
# клауза стояла ВЫШЕ подключения библиотеки и грепала сырую команду подстрокой — то есть
# слово `install.sh` в кавычках эха, в комментарии оболочки или в теле ЧУЖОГО heredoc
# СНИМАЛО отказ уровня 4, и настоящая перезапись установленных правил проходила.
# Воспроизведено с контрастом: `cp rules/CLAUDE.md ~/.claude/CLAUDE.md && echo "мимо"` →
# отказ; та же команда с `echo "мимо install.sh"` → молчание.
#
# Цена ошибки здесь ОБРАТНАЯ обычной: промах даёт не лишний отказ, а ПРОПУСК — маркеры
# управляемого блока затираются, пара «правила» в `drift-check` печатает BROKEN, мастер-копия
# молча расходится с установленной. Ровно тот инцидент 28 августа 2026, ради которого страж
# и написан.
#
# Замер обеих сторон по корпусу 35 769 вызовов Bash (1131 команда со словом-паролём):
# новых отказов 3, потерянных 0 — точность выросла, отзыв не тронут.
#
# Клауза ПЕРЕНЕСЕНА ниже намеренно: `executable_part` живёт в библиотеке, а она подключается
# строкой выше. Прежний порядок делал сужение невозможным по построению — звать было нечего.
_EXEC_CMD=$(executable_part "$CMD")
case "$_EXEC_CMD" in
    *sync_claude_md*|*claude-md-merge*|*install.sh*) exit 0 ;;
esac

# ── Отказ: путь к правилам — ЦЕЛЬ записи, и цель называет владелец лексики оболочки ──
# `executable_change_targets` (`hooks/lib/write_targets.py`, режим `--edits`) за один проход разбирает кавычки,
# подстановки, `bash -c` и `eval`, обёртки, перенаправления и тела heredoc; своего перечня форм у стража нет
# (D1323, корень R3). Признак с ОДНИМ последствием: вызов пишет в установленные правила — маркеры будут затёрты.
# Путь-ИСТОЧНИК (`cp ~/.claude/CLAUDE.md /tmp/b.md`), упоминание в эхе, комментарии и данных heredoc целью не
# являются. До 18 ноября 2026 признаком было «оператор записи стоит РЯДОМ с путём» — регулярное выражение по
# сырому тексту: оно пропускало имя программы в кавычках и с путём, подстановки, `eval`, хвост `2>&1` и отвергало
# комментарий и данные heredoc (61 провал на 320 сгенерированных входах).
# НАЗВАННЫЙ ПРЕДЕЛ: запись через переменную (`F=~/.claude/CLAUDE.md; cat > "$F"`) и чужим интерпретатором
# (`python3 -c`) целью не названа — первая получает подсказку ниже. Условие снятия: форма встретится в замере.
# Разбора нет (нет python3, установленная копия старее режима) — сказать: тишина стража отказа читается как «чисто».
_TGT=$(executable_change_targets "$CMD"); _TRC=$?
if [ "$_TRC" -ne 0 ]; then
    jq -cn '{hookSpecificOutput:{hookEventName:"PreToolUse",additionalContext:"⚠️ rules-write-bypass: разбор команды не исполнился (прибор сломан) — запись в ~/.claude/CLAUDE.md в этом вызове не проверена."}}' 2>/dev/null || true
    exit 0
fi
# Сопоставление без here-string и без трубы: отказ записи временного файла не должен читаться как «цели нет».
case $'\n'"$_TGT"$'\n' in
    *$'/.claude/CLAUDE.md\n'*|*$'\n.claude/CLAUDE.md\n'*) ;;
    *)
        # Цели нет. Запись в команде есть и путь упомянут — не повод отказывать и не повод молчать: молчание
        # здесь неотличимо от «проверено, чисто». Где «>» перенаправляет, решает `redirect_bare`.
        BARE=$(redirect_bare "$CMD")
        IS_WRITE=0
        grep -qE '>>?[[:space:]]*[^&[:space:]]' <<< "$BARE" && IS_WRITE=1
        grep -qE '(^|[|;&[:space:]])(cp|mv|tee|install)[[:space:]]' <<< "$BARE" && IS_WRITE=1
        grep -qE 'sed[[:space:]]+-i' <<< "$BARE" && IS_WRITE=1
        [ "$IS_WRITE" -eq 1 ] || exit 0
        WMSG="ℹ️ rules-write-bypass: в команде упомянут ~/.claude/CLAUDE.md и есть операция записи,
    но путь не стоит целью операции — отказа нет. Если запись всё же в правила, законный путь:
        . lib/claude-md-merge.sh && sync_claude_md \"\$HOME/.claude/CLAUDE.md\" rules/CLAUDE.md"
        jq -cn --arg m "$WMSG" \
          '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$m}}' 2>/dev/null || true
        exit 0
        ;;
esac

MSG="⛔ ОТКАЗ (вызов не выполнен). Запись в установленные правила мимо библиотеки слияния.

Прямая запись в ~/.claude/CLAUDE.md стирает маркеры управляемого блока. Без них drift-check
по паре «правила» печатает BROKEN — «не с чем сравнить», — и мастер-копия может уехать от
установленной сколь угодно далеко молча. Так уже было 28 августа 2026.

Правильный путь один и он короткий:

    . lib/claude-md-merge.sh && sync_claude_md \"\$HOME/.claude/CLAUDE.md\" rules/CLAUDE.md

Библиотека сама делает бэкап и сохраняет маркеры. Чтение файла не блокируется."

jq -cn --arg m "$MSG" \
  '{hookSpecificOutput:{hookEventName:"PreToolUse", permissionDecision:"deny", permissionDecisionReason:$m}}' 2>/dev/null || true
exit 0
