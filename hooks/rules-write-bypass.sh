#!/usr/bin/env bash
# rules-write-bypass.sh — PreToolUse[Bash]: запись в установленные правила только через библиотеку (D101).
# en: PreToolUse[Bash] — the installed rules file may only be written through the merge library (D101).
#
# Результат: маркеры управляемого блока в ~/.claude/CLAUDE.md не теряются — пара «правила»
#            в drift-check никогда не бывает BROKEN.
# Проверка результата: bash hooks/tests/drift-check.sh | grep -q '^OK|правила'
#
# Повод. 28 августа 2026 пара «правила» была BROKEN: в установленном файле не оказалось
# маркеров, и сравнивать стало нечем. Шесть пар из семи сверялись, седьмая — нет, то есть
# мастер-копия могла уехать от установленной сколь угодно далеко, и ни один прогон бы об
# этом не сказал. Дрейф означает «сравнили и разошлось»; здесь было «не сравнивали вовсе».
#
# Почему именно эта пара беззащитна. У остальных шести установка — побайтовая копия, и любой
# обход ловится сравнением. Здесь установка ПРЕОБРАЗУЕТ содержимое (оборачивает в маркеры),
# поэтому обход даёт не расхождение, а невозможность сравнить.
#
# Почему страж стал возможен только сейчас. Пункт D101 отверг его возражением «правка идёт
# инструментом Edit, а хук PreToolUse[Bash] её не видит». Замер 28 августа по пяти сессиям:
# касаний ~/.claude/CLAUDE.md через Bash — 23, через Edit/Write — 0. Возражение снято
# данными, а не мнением.
#
# КОНТРПРИМЕР: правка установленных правил ИЗ ДРУГОГО ПРОЦЕССА — редактором, файловым
# менеджером, чужим скриптом — сюда не попадает: хук видит только вызовы Bash этой сессии.
# Для такого случая остаётся drift-check, который скажет постфактум.
#
# Input  (stdin): {tool_name, tool_input, ...}
# Output (stdout): {hookSpecificOutput:{permissionDecision:"deny", ...}} либо пусто
# Exit:  always 0.
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
[ "$TOOL" = "Bash" ] || exit 0
CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
[ -n "$CMD" ] || exit 0

# Законный путь — через библиотеку слияния либо через установщик. Проверяется ПЕРВЫМ:
# если он в команде есть, дальше не смотрим.
case "$CMD" in
    *sync_claude_md*|*claude-md-merge*|*install.sh*) exit 0 ;;
esac

# Цель — установленные ГЛОБАЛЬНЫЕ правила, не проектный CLAUDE.md.
case "$CMD" in
    *'.claude/CLAUDE.md'*) ;;
    *) exit 0 ;;
esac

# Запись, а не чтение. Правило, а не перечень символов: перенаправление В ФАЙЛ либо
# команда, кладущая файл на место. Слияния потоков (2>&1) записью не считаются, как и
# операторы сравнения чужих языков (>=, ->) — где «>» перенаправляет, решает
# `redirect_bare` из `command-scope-lib.sh`, там замер и предел. До 10 сентября 2026 этот
# блок стоял здесь своей копией, посимвольно совпадавшей с копией в `five-whys-gate.sh`, и
# дефект «оператор сравнения принят за редирект» жил в обеих сразу. Библиотеки нет — страж
# молчит: тот, кто не умеет отличить чтение от записи, не имеет права на отказ.
CS_LIB="${CS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/command-scope-lib.sh}"
[ -f "$CS_LIB" ] || CS_LIB="$HOME/.claude/hooks/command-scope-lib.sh"
# shellcheck source=/dev/null
{ [ -f "$CS_LIB" ] && source "$CS_LIB"; } || exit 0
BARE=$(redirect_bare "$CMD")
IS_WRITE=0
grep -qE '>>?[[:space:]]*[^&[:space:]]' <<< "$BARE" && IS_WRITE=1
grep -qE '(^|[|;&[:space:]])(cp|mv|tee|install)[[:space:]]' <<< "$BARE" && IS_WRITE=1
grep -qE 'sed[[:space:]]+-i' <<< "$BARE" && IS_WRITE=1
[ "$IS_WRITE" -eq 1 ] || exit 0

# ── Отказ требует, чтобы путь был ЦЕЛЬЮ операции, а не просто встретился в тексте ──
# Три ложных отказа за одну сессию 1 сентября 2026, все на одной форме: путь к правилам
# стоял ВНУТРИ исходника питона в теле heredoc («pathlib.Path.home()/".claude/CLAUDE.md"»,
# чтение), а знак `>` — в другом месте той же команды (`awk 'length($0) >= 40'`). Ни то,
# ни другое операцией записи в правила не является, а вместе давало отказ.
#
# Корень: страж судил ВЕСЬ текст команды, включая данные и чужой исходник, вместо самой
# оболочки. Признак «где-то путь И где-то знак записи» несёт РАЗНЫЕ последствия — настоящую
# запись и упоминание в данных, — то есть взят выше корня
# (`case-2026-08-28-enforcement-is-a-property-of-consequence`, тот же разбор, что у D244).
#
# Признак с ОДНИМ последствием: оператор записи и путь стоят РЯДОМ. Тогда продолжение
# вызова означает ровно одно — маркеры управляемого блока будут затёрты.
#
# НАЗВАННЫЙ ПРЕДЕЛ: запись через переменную (`F=~/.claude/CLAUDE.md; cat > "$F"`) рядом не
# стоит и отказа не получит — получит напоминание ниже. Условие снятия: подстановка
# переменных до сопоставления, если такая форма встретится в замере хоть раз.
# Признак снят с РОЛИ, а не с позиции (10 сентября 2026, находка противника). Прежняя
# редакция допускала между командой и путём РОВНО ОДНО слово, поэтому любой флаг снимал
# отказ уровня 4: `install -m 644 src ~/.claude/CLAUDE.md`, `cp -f`, `mv -f`, `tee -i`
# проходили с информационным сообщением, хотя `IS_WRITE` уже был взведён — страж ЗНАЛ, что
# команда пишет, и всё равно пропускал. Названный предел («запись через переменную») этот
# случай не покрывал: путь стоял литералом.
# Роль у `cp`/`mv`/`install` выражается иначе: цель — ПОСЛЕДНИЙ аргумент. Отсюда якорь
# конца команды. Он же снимает ложное срабатывание, которое первая редакция правки внесла:
# `cp ~/.claude/CLAUDE.md /tmp/backup.md` — там путь ИСТОЧНИК, и отказ был бы неверным, а
# отказ уровня 4 с ложными обязан снова становиться подсказкой.
# Проверено на 7 положительных формах и 4 контрпримерах (источник, diff, grep, cat | head).
ADJ_RE='(>>?[[:space:]]*|tee[[:space:]]+([^|;&]*[[:space:]])?|(cp|mv|install)[[:space:]]+([^|;&]*[[:space:]])?|sed[[:space:]]+-i[^|;&]*[[:space:]])["'"'"']?[^[:space:]"'"'"';|&]*\.claude/CLAUDE\.md["'"'"']?[[:space:]]*($|[;|&])'
if ! grep -qE "$ADJ_RE" <<< "$CMD"; then
    # Путь упомянут, запись в команде есть, но целью не является. Это не повод отказывать
    # и не повод молчать: молчание здесь неотличимо от «проверено, чисто».
    WMSG="ℹ️ rules-write-bypass: в команде упомянут ~/.claude/CLAUDE.md и есть операция записи,
но путь не стоит целью операции — отказа нет. Если запись всё же в правила, законный путь:
    . lib/claude-md-merge.sh && sync_claude_md \"\$HOME/.claude/CLAUDE.md\" rules/CLAUDE.md"
    jq -cn --arg m "$WMSG" \
      '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$m}}' 2>/dev/null || true
    exit 0
fi

MSG="⛔ ОТКАЗ (вызов не выполнен). Запись в установленные правила мимо библиотеки слияния.

Прямая запись в ~/.claude/CLAUDE.md стирает маркеры управляемого блока. Без них drift-check
по паре «правила» печатает BROKEN — «не с чем сравнить», — и мастер-копия может уехать от
установленной сколь угодно далеко молча. Так уже было 28 августа 2026.

Правильный путь один и он короткий:

    . lib/claude-md-merge.sh && sync_claude_md \"\$HOME/.claude/CLAUDE.md\" rules/CLAUDE.md

Библиотека сама делает бэкап и сохраняет маркеры. Чтение файла не блокируется."

jq -cn --arg m "$MSG" \
  '{hookSpecificOutput:{hookEventName:"PreToolUse", permissionDecision:"deny", permissionDecisionReason:$m}}' 2>/dev/null || true
exit 0
