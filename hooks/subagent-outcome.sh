#!/usr/bin/env bash
# subagent-outcome.sh — SubagentStop: субагент, кончившийся БЕЗ ответа, становится поводом разбора.
# en: SubagentStop: a subagent that ended without an answer becomes a root-cause trigger.
#
# Результат: обрыв субагента виден контуру — повод заводится и возвращается на границе хода
# Проверка результата: bash hooks/tests/test_subagent_outcome.sh даёт 0
#
# СЛЕПОЕ ПЯТНО, КОТОРОЕ ОН ЗАКРЫВАЕТ. Все десять поводов разбора читают состояние СЕССИИ:
# журнал переработки, полосу провалов, поправку собеседника. У субагента своя сессия и свой
# транскрипт, а события `SubagentStop` в settings.json не было вовсе — работа, вынесенная в
# субагента, выпадала из контура ПО ПОСТРОЕНИЮ, а не по недосмотру.
#
# Повод, 9 сентября 2026. Прогон трёх субагентов (4 мин 17 с) завершился без единого
# результата: все три оборвались на `tool_result`/`thinking`, структурированного ответа не
# вернул никто. Ни один страж этого не заметил. Собеседник назвал это прямо: «не дал
# результата = нерабочий инструмент, и сторож ошибки не сработал».
#
# ПРИЗНАК СНЯТ С ДЕЙСТВИЯ, А НЕ С РЕЧИ. Обрыв — это «последний значимый блок транскрипта не
# является текстовым ответом»: агент остановился на вызове инструмента или на размышлении.
# Речевой признак («не сработало», «пусто вышло») здесь не годится: замер того же дня
# показал, что словарь находки ловит признание ошибки в РАССУЖДЕНИИ («оказалось», «я
# ошибся») и не ловит отказ ИНСТРУМЕНТА — три фразы из трёх прошли мимо.
#
# ЧЕТЫРЕ СОСТОЯНИЯ, А НЕ ТРИ (уточнено 10 сентября 2026 прожаркой). Здесь стояло «три», и
# четвёртое было слито со вторым: расшифровка, которая НЕ ЧИТАЕТСЯ, давала пустой разбор и
# уходила в ту же ветку, что «блоков нет вовсе», — то есть молча выдавалась за успех.
# Проба: `printf 'не json вовсе' > t.jsonl` — страж молчал.
#   транскрипта нет      → сказать (неизвестность, не «чисто»);
#   транскрипт не читается → сказать (то же самое, другой причиной);
#   оборвался            → сказать и завести повод;
#   договорил            → молчать, это честный успех.
#
# ПОВОД ЗАВОДИТСЯ В КОНТУРЕ, а не только в очереди (10 сентября 2026). Прежде страж писал
# строку в `pending-alerts.txt` — она показывалась и исчезала: срода в `RC_KINDS_RE` не
# было, `rc_note_event` не звался, исход не писался, свод незакрытого повода не видел.
# Собственная строка этого файла обещала «повод заводится и возвращается на границе хода»,
# а возвращать было нечего. Срод `subagentcut` СТОЯЧИЙ: отказа не даёт, потому что приходит
# извне хода и промерен на малой выборке (обоснование — у таблицы `FWG_STANDING`).
set -uo pipefail

STATE_DIR="${STATE_DIR:-$HOME/.claude/hooks/state}"
mkdir -p "$STATE_DIR" 2>/dev/null || exit 0
command -v jq >/dev/null 2>&1 || exit 0

# Контур разбора: `rc_note_event` заводит повод, `rc_project_of` даёт его владельца.
# Библиотеки нет — страж всё равно скажет в очередь, но повода не заведёт: сказать без
# учёта лучше, чем промолчать.
RC_LIB="${RC_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/root-cause-lib.sh}"
[ -f "$RC_LIB" ] || RC_LIB="$HOME/.claude/hooks/root-cause-lib.sh"
# shellcheck source=/dev/null
[ -f "$RC_LIB" ] && . "$RC_LIB" 2>/dev/null || true

INPUT=$(cat 2>/dev/null || true)
[ -n "$INPUT" ] || exit 0

TRANSCRIPT=$(printf '%s' "$INPUT" | jq -r '.transcript_path // ""' 2>/dev/null)
SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)

# Канал — общая очередь: её показывает pending-alerts-surface на следующем UserPromptSubmit.
# `systemMessage` до хода не доходит (измерено в error-tracker.sh:44-47), а непустой
# additionalContext на границе хода перезапускает ход.
QUEUE="$STATE_DIR/pending-alerts.txt"

if [ -z "$TRANSCRIPT" ] || [ ! -f "$TRANSCRIPT" ]; then
    # Прибор не посмотрел — и это не «чисто». Говорится один раз на сессию, чтобы
    # неизвестность не стала фоном.
    _mark="$STATE_DIR/subagent-blind-${SID}"
    if [ ! -f "$_mark" ]; then
        printf '🧩 Субагент завершился, а его расшифровка недоступна — проверить исход нечем. Это НЕ «сработал успешно».\n' >> "$QUEUE" 2>/dev/null || true
        : > "$_mark" 2>/dev/null || true
    fi
    exit 0
fi

# Последний значимый блок: текстовый ответ означает, что агент договорил. Вызов инструмента
# или размышление последним — обрыв: работа сожжена, результата нет.
# Читается ли расшифровка вообще. Без этой проверки битый JSON давал пустой разбор, а
# пустой разбор уходил в ветку «блоков нет» и молчал — четвёртое состояние подменялось
# вторым. Дедуп общий с «транскрипта нет»: обе ветки про одну неизвестность.
if ! jq -se . "$TRANSCRIPT" >/dev/null 2>&1; then
    _mark="$STATE_DIR/subagent-blind-${SID}"
    if [ ! -f "$_mark" ]; then
        printf '🧩 Расшифровка субагента не читается (битый JSON) — проверить исход нечем. Это НЕ «сработал успешно».\n' >> "$QUEUE" 2>/dev/null || true
        : > "$_mark" 2>/dev/null || true
    fi
    exit 0
fi

# Роль ОБЯЗАТЕЛЬНА (10 сентября 2026, находка противника). Прежде брался `.message.content`
# у ЛЮБОЙ записи, и строковый content — форма, которая в живых расшифровках принадлежит
# репликам собеседника, — объявлялся блоком `text`, то есть «агент договорил». Обрыв, где
# последней записью оказалась реплика пользователя, выдавался за успех.
# Предмет стража — речь АССИСТЕНТА: договорил ли он. Чужие записи к вопросу не относятся.
LAST_KIND=$(jq -rs '
    [ .[] | select(type == "object")
          | select(((.message // {}) | if type == "object" then (.role // "") else "" end) == "assistant"
                   or (.role // "") == "assistant")
          | (.message // empty)
          | select(type == "object")
          | (.content // empty)
          | if type == "array" then (.[-1].type // "") elif type == "string" then "text" else "" end
          | select(. != "") ] | last // ""
' "$TRANSCRIPT" 2>/dev/null)

# Пустая расшифровка и расшифровка без единого блока АССИСТЕНТА — та же неизвестность, что
# «файла нет» и «файл не читается»: прибор не смог посмотреть, и молчание тут читается как
# «сработал успешно». Прежде обе ветки молча выходили нулём.
if [ -z "${LAST_KIND:-}" ]; then
    _mark="$STATE_DIR/subagent-blind-${SID}"
    if [ ! -f "$_mark" ]; then
        printf '🧩 В расшифровке субагента нет ни одного блока ответа — проверить исход нечем. Это НЕ «сработал успешно».\n' >> "$QUEUE" 2>/dev/null || true
        : > "$_mark" 2>/dev/null || true
    fi
    exit 0
fi

case "$LAST_KIND" in
    text) exit 0 ;;                       # договорил — молчим, это честный успех
esac

# Дедуп по расшифровке: одно сообщение на один оборвавшийся прогон.
_key=$(printf '%s' "$TRANSCRIPT" | cksum 2>/dev/null | awk '{print $1}')
_seen="$STATE_DIR/subagent-cut-${SID}.seen"
grep -qxF "${_key:-0}" "$_seen" 2>/dev/null && exit 0
printf '%s\n' "${_key:-0}" >> "$_seen" 2>/dev/null || true

_lines=$(wc -l < "$TRANSCRIPT" 2>/dev/null | tr -d ' ')

# Повод контура. Проект берётся у payload, как у прочих продюсеров событий.
if command -v rc_note_event >/dev/null 2>&1; then
    _sub_cwd=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
    [ -n "$_sub_cwd" ] && command -v rc_project_of >/dev/null 2>&1 \
        && RC_EVENT_PROJECT=$(rc_project_of "$_sub_cwd")
    rc_note_event "$STATE_DIR" "subagentcut" \
        "субагент оборвался без ответа (последний блок: ${LAST_KIND}, ходов: ${_lines:-?})" \
        2>/dev/null || true
fi

printf '🧩 Субагент ОБОРВАЛСЯ без ответа (последний блок: %s, ходов: %s). Запускали ради результата — его нет, это отказ инструмента, а не пустая находка. Исход: %s\n' \
    "$LAST_KIND" "${_lines:-?}" \
    "$(command -v rc_resolution_kinds >/dev/null 2>&1 && rc_resolution_kinds || printf 'починка механизма · пункт долга · запись знания · вердикт «показалось»')" \
    >> "$QUEUE" 2>/dev/null || true
exit 0
