#!/usr/bin/env bash
# subagent-outcome.sh — SubagentStop: субагент, кончившийся БЕЗ ответа, становится поводом разбора.
# en: SubagentStop: a subagent that ended without an answer becomes a root-cause trigger.
#
# Результат: обрыв субагента виден контуру — повод заводится и возвращается на границе хода
# Проверка результата: bash hooks/tests/test_subagent_outcome.sh даёт 0
#
# СЛЕПОЕ ПЯТНО, КОТОРОЕ ОН ЗАКРЫВАЕТ. Все десять поводов разбора читают состояние СЕССИИ:
# журнал переработки, полосу провалов, поправку собеседника. У субагента своя сессия и свой
# транскрипт, а события `SubagentStop` в settings.json не было вовсе — работа, вынесенная в
# субагента, выпадала из контура ПО ПОСТРОЕНИЮ, а не по недосмотру.
#
# Повод, 9 сентября 2026. Прогон трёх субагентов (4 мин 17 с) завершился без единого
# результата: все три оборвались на `tool_result`/`thinking`, структурированного ответа не
# вернул никто. Ни один страж этого не заметил. Собеседник назвал это прямо: «не дал
# результата = нерабочий инструмент, и сторож ошибки не сработал».
#
# ПРИЗНАК СНЯТ С ДЕЙСТВИЯ, А НЕ С РЕЧИ. Обрыв — это «последний значимый блок транскрипта не
# является текстовым ответом»: агент остановился на вызове инструмента или на размышлении.
# Речевой признак («не сработало», «пусто вышло») здесь не годится: замер того же дня
# показал, что словарь находки ловит признание ошибки в РАССУЖДЕНИИ («оказалось», «я
# ошибся») и не ловит отказ ИНСТРУМЕНТА — три фразы из трёх прошли мимо.
#
# ЧЕТЫРЕ СОСТОЯНИЯ, А НЕ ТРИ (уточнено 10 сентября 2026 прожаркой). Здесь стояло «три», и
# четвёртое было слито со вторым: расшифровка, которая НЕ ЧИТАЕТСЯ, давала пустой разбор и
# уходила в ту же ветку, что «блоков нет вовсе», — то есть молча выдавалась за успех.
# Проба: `printf 'не json вовсе' > t.jsonl` — страж молчал.
#   транскрипта нет      → сказать (неизвестность, не «чисто»);
#   транскрипт не читается → сказать (то же самое, другой причиной);
#   оборвался            → сказать и завести повод;
#   договорил            → молчать, это честный успех.
#
# ПОВОД ЗАВОДИТСЯ В КОНТУРЕ, а не только в очереди (10 сентября 2026). Прежде страж писал
# строку в `pending-alerts.txt` — она показывалась и исчезала: срода в `RC_KINDS_RE` не
# было, `rc_note_event` не звался, исход не писался, свод незакрытого повода не видел.
# Собственная строка этого файла обещала «повод заводится и возвращается на границе хода»,
# а возвращать было нечего. Срод `subagentcut` СТОЯЧИЙ: отказа не даёт, потому что приходит
# извне хода и промерен на малой выборке (обоснование — у таблицы `FWG_STANDING`).
set -uo pipefail

STATE_DIR="${STATE_DIR:-$HOME/.claude/hooks/state}"
mkdir -p "$STATE_DIR" 2>/dev/null || exit 0
command -v jq >/dev/null 2>&1 || exit 0

# Контур разбора: `rc_note_event` заводит повод, `rc_project_of` даёт его владельца.
# Библиотеки нет — страж всё равно скажет в очередь, но повода не заведёт: сказать без
# учёта лучше, чем промолчать.
RC_LIB="${RC_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/root-cause-lib.sh}"
[ -f "$RC_LIB" ] || RC_LIB="$HOME/.claude/hooks/root-cause-lib.sh"
# shellcheck source=/dev/null
[ -f "$RC_LIB" ] && . "$RC_LIB" 2>/dev/null || true

INPUT=$(cat 2>/dev/null || true)
[ -n "$INPUT" ] || exit 0

# Расшифровка СУБАГЕНТА, а не сессии (D450, прямой замер payload 17 сентября 2026).
# Харнесс кладёт её в `agent_transcript_path`, а в `transcript_path` — путь РОДИТЕЛЯ; страж
# читал второе и судил родителя. Цена измерена: на момент `SubagentStop` последний блок
# ассистента у родителя — `tool_use` самого вызова Task, то есть «оборвался» объявлялся на
# КАЖДОМ успешном субагенте, а постоянный ключ дедупа (`cksum` пути родителя) гасил все
# последующие — во всех 16 файлах `subagent-cut-*.seen` по всем проектам ровно по одной
# строке. Пустое поле читается как «прибор не посмотрел» (ветка ниже), и это честнее, чем
# судить чужую расшифровку: у родителя ответ на вопрос «договорил ли субагент» не записан.
# НАЗВАННЫЙ ПРЕДЕЛ: поле даёт харнесс, у старого клиента его нет — там страж скажет
# «расшифровка недоступна» вместо молчания. Условие снятия: в корпусе не останется
# событий `SubagentStop` без поля. Рядом в payload лежит готовое `last_assistant_message` —
# оно не используется намеренно: предмет стража объявлен ПОСЛЕДНИМ БЛОКОМ расшифровки, и
# смена предмета — отдельное решение, а не побочный эффект этой починки.
PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/paths-lib.sh}"
[ -f "$PATHS_LIB" ] || PATHS_LIB="$HOME/.claude/hooks/paths-lib.sh"
# shellcheck source=/dev/null
[ -f "$PATHS_LIB" ] && . "$PATHS_LIB" 2>/dev/null || true
if command -v resolve_actor_transcript >/dev/null 2>&1; then
    # На `SubagentStop` актор — субагент ПО ПОСТРОЕНИЮ события. Payload без `agent_id`
    # (старый клиент) значит «опознать актора нечем», и расшифровка родителя тут не
    # запасной путь, а ровно исходный дефект: судить чужое. Пусто уходит в ветку
    # «недоступна» ниже — названная неизвестность.
    if [ -n "$(resolve_actor_id "$INPUT")" ]; then
        TRANSCRIPT=$(resolve_actor_transcript "$INPUT")
    else
        TRANSCRIPT=""
    fi
else
    # Библиотеки нет — читаем поле сами, но это ЗАПАСНОЙ путь, а не второй владелец факта:
    # сверки пути здесь нет, поэтому она и вынесена к владельцу (находка скептика 18 сентября
    # 2026: у факта «где расшифровка актора» стало два владельца, и они разошлись).
    TRANSCRIPT=$(printf '%s' "$INPUT" | jq -r '.agent_transcript_path // ""' 2>/dev/null)
fi
SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)

# ОТВЕТ АГЕНТА БЕРЁТСЯ У ХАРНЕССА, А НЕ У ФАЙЛА (18 сентября 2026, сквозной прогон после
# переноса). Расшифровка на момент `SubagentStop` ОТСТАЁТ: живой зонд ответил текстом
# «сделано», а страж прочитал последним блоком `tool_use` и объявил обрыв — дописанная строка
# ответа легла в файл уже после вызова хука. Файл тут гонка, а `last_assistant_message` —
# то же самое от самого харнесса и без гонки (измерено зондом payload: у агента инструмента
# Task поле несёт текст ответа). Непустое поле значит «договорил», и это ПЕРВЫЙ признак;
# разбор расшифровки остаётся запасным — для payload без поля (старый клиент) и для случая,
# когда агент сдал результат вызовом инструмента.
LAST_MSG=$(printf '%s' "$INPUT" | jq -r '.last_assistant_message // ""' 2>/dev/null)
if [[ $LAST_MSG == *[![:space:]]* ]]; then exit 0; fi

# Канал — общая очередь: её показывает pending-alerts-surface на следующем UserPromptSubmit.
# `systemMessage` до хода не доходит (измерено в error-tracker.sh:44-47), а непустой
# additionalContext на границе хода перезапускает ход.
QUEUE="$STATE_DIR/pending-alerts.txt"

if [ -z "$TRANSCRIPT" ] || [ ! -f "$TRANSCRIPT" ]; then
    # Прибор не посмотрел — и это не «чисто». Говорится один раз на сессию, чтобы
    # неизвестность не стала фоном.
    _mark="$STATE_DIR/subagent-blind-${SID}"
    if [ ! -f "$_mark" ]; then
        printf '🧩 Субагент завершился, а его расшифровка недоступна — проверить исход нечем. Это НЕ «сработал успешно».\n' >> "$QUEUE" 2>/dev/null || true
        : > "$_mark" 2>/dev/null || true
    fi
    exit 0
fi

# СУД — ФУНКЦИЯ, А НЕ ОДИН СНИМОК (D1354, 22 ноября 2026). Файл на момент события отстаёт не
# только результатом сдачи (D510 ниже), но и САМИМ ПОСЛЕДНИМ ВЫЗОВОМ: тревога «ходов: 52» на
# расшифровке из 54 строк (19:48:04, 6 ноября 2026) — страж прочитал файл без вызова
# `SubagentHandback` и его результата, последним стоял `Edit` или `Bash` с ответом, и ожидание
# D510, заведённое только на вызов сдачи, не включилось вовсе. Так помечены 10 сданных отчётов из
# 10 тревог с 6 ноября по 21 ноября 2026 (7 первых запусков, 3 возобновлённых `SendMessage`);
# готовые расшифровки тех же десяти страж судит молча. Поэтому всякий вердикт, кроме «договорил»,
# — пока гипотеза: страж ждёт, дорастёт ли файл, и судит заново на каждом его росте. Предел тот
# же, что у D510, — 20 раз по 0,1 с; не дорос — судим по последнему снимку, то есть говорим.
# Цена: настоящий обрыв теперь стоит хуку 2 с, где прежде стоил ноль (кроме сдачи без результата).
# НАЗВАННЫЙ ПРЕДЕЛ: харнесс, дописывающий последнюю запись позже 2 с после события, вернёт ложную
# тревогу. Условие снятия: замер разрыва «событие → последняя запись» дольше 2 с в мире.
_judge() {
# Последний значимый блок: текстовый ответ означает, что агент договорил. Вызов инструмента
# или размышление последним — обрыв: работа сожжена, результата нет.
# Читается ли расшифровка вообще. Без этой проверки битый JSON давал пустой разбор, а
# пустой разбор уходил в ветку «блоков нет» и молчал — четвёртое состояние подменялось
# вторым. Дедуп общий с «транскрипта нет»: обе ветки про одну неизвестность.
if ! jq -se . "$TRANSCRIPT" >/dev/null 2>&1; then VERDICT=broken; return 1; fi

# Роль ОБЯЗАТЕЛЬНА (10 сентября 2026, находка противника). Прежде брался `.message.content`
# у ЛЮБОЙ записи, и строковый content — форма, которая в живых расшифровках принадлежит
# репликам собеседника, — объявлялся блоком `text`, то есть «агент договорил». Обрыв, где
# последней записью оказалась реплика пользователя, выдавался за успех.
# Предмет стража — речь АССИСТЕНТА: договорил ли он. Чужие записи к вопросу не относятся.
LAST_KIND=$(jq -rs '
    [ .[] | select(type == "object")
          | select(((.message // {}) | if type == "object" then (.role // "") else "" end) == "assistant"
                   or (.role // "") == "assistant")
          | (.message // empty)
          | select(type == "object")
          | (.content // empty)
          | if type == "array" then (.[-1].type // "") elif type == "string" then "text" else "" end
          | select(. != "") ] | last // ""
' "$TRANSCRIPT" 2>/dev/null)

# Пустая расшифровка и расшифровка без единого блока АССИСТЕНТА — та же неизвестность, что
# «файла нет» и «файл не читается»: прибор не смог посмотреть, и молчание тут читается как
# «сработал успешно». Прежде обе ветки молча выходили нулём.
if [ -z "${LAST_KIND:-}" ]; then VERDICT=empty; return 1; fi

# ЧЕМ КОНЧАЕТСЯ ДОГОВОРИВШИЙ АГЕНТ — ИЗМЕРЕНО, А НЕ ВЗЯТО ИЗ ОДНОЙ ФОРМЫ (18 сентября 2026).
# Замер по 400 свежайшим расшифровкам агентов: `tool_use` последним — 322, `text` — 77,
# `thinking` — 1. Из 322 вызовов 312 суть `StructuredOutput` с ответом «Structured output
# provided successfully», то есть агент результат СДАЛ: агент ВОЛНЫ текстом не кончает
# никогда, он отдаёт ответ вызовом инструмента. Признак «последний блок = text» был взят по
# форме агента инструмента Task и объявлял оборвавшимися 312 успешных из 322 — первая
# редакция этой починки, снятая скептиком. Настоящих обрывов в той же выборке 11: десять на
# `Bash` (у восьми последний ответ — «The user doesn't want to proceed», то есть вызов
# прерван) и один на `thinking`.
# НАЗВАННЫЙ ПРЕДЕЛ: имя инструмента даёт харнесс; переименует — страж вернётся к крику на
# каждом агенте волны, то есть в шумную сторону, а не в тихую. Условие снятия: замерить
# `last_assistant_message` из payload `SubagentStop` на агенте ВОЛНЫ (у агента Task он
# измерен и несёт текст ответа) — тогда признак возьмётся у харнесса прямо, без имени.
LAST_TOOL=$(jq -rs '
    [ .[] | select(type == "object")
          | select(((.message // {}) | if type == "object" then (.role // "") else "" end) == "assistant"
                   or (.role // "") == "assistant")
          | (.message // empty) | select(type == "object") | (.content // empty)
          | select(type == "array") | .[-1] | select(.type == "tool_use") | (.name // "") ] | last // ""
' "$TRANSCRIPT" 2>/dev/null)
LAST_RESULT=$(jq -rs '
    [ .[] | select(type == "object") | (.message // empty) | select(type == "object")
          | (.content // empty) | select(type == "array") | .[]
          | select(.type == "tool_result")
          | (if (.content | type) == "string" then .content else (.content | tostring) end) ] | last // ""
' "$TRANSCRIPT" 2>/dev/null)

# РЕЗУЛЬТАТ СДАЧИ ЛОЖИТСЯ ПОСЛЕ СОБЫТИЯ (D510, 3 октября 2026). Та же гонка, что у ответа
# текстом выше, но поле `last_assistant_message` её здесь не снимает: последний блок агента —
# вызов, а не текст, и поле пусто. Замер: событие записано в 17:28:08, строка «Report delivered»
# легла через 0,23 с, и страж объявил обрыв на сданном отчёте. Поэтому результат берётся у
# ИМЕННО этого вызова (по id); ждёт его общее ожидание роста файла после функции (D1354), а не
# своё. Хвост файла, а не весь: строка результата пишется в конец.
LAST_TOOL_ID=$(jq -rs '
    [ .[] | select(type == "object")
          | select(((.message // {}) | if type == "object" then (.role // "") else "" end) == "assistant"
                   or (.role // "") == "assistant")
          | (.message // empty) | select(type == "object") | (.content // empty)
          | select(type == "array") | .[-1] | select(.type == "tool_use") | (.id // "") ] | last // ""
' "$TRANSCRIPT" 2>/dev/null)
case "$LAST_KIND:${LAST_TOOL:-}" in
    tool_use:StructuredOutput|tool_use:SubagentHandback)
        if [ -n "${LAST_TOOL_ID:-}" ]; then
            _r=$(_result_of "$LAST_TOOL_ID")
            [ -n "$_r" ] && LAST_RESULT="$_r"
        fi ;;
esac

VERDICT=cut
case "$LAST_KIND" in
    text) VERDICT=ok ;;                   # договорил текстом — честный успех
    tool_use)
        # Сдал результат структурированным ответом — тоже договорил.
        # Herestring, а не труба: под `pipefail` producer, убитый `grep -q` сигналом, отдаёт
        # 141, и утверждение соврало бы под нагрузкой (D50; поймал `test_assert_no_sigpipe`
        # на первом же прогоне — это тот самый род дефекта, ради которого страж и заведён).
        if [ "${LAST_TOOL:-}" = "StructuredOutput" ] \
           && grep -q 'Structured output provided successfully' <<< "${LAST_RESULT:-}"; then
            VERDICT=ok
        fi
        # Фоновый агент Agent сдаёт отчёт вызовом `SubagentHandback` (2 октября 2026: 5 из 5
        # живых расшифровок, кончающихся этим вызовом, — отчёт дошёл до родителя). Названный
        # предел ниже сработал ровно так, как описан: харнесс ввёл второй инструмент сдачи, и
        # страж, знавший один, объявил обрыв на сданном отчёте противника D498.
        if [ "${LAST_TOOL:-}" = "SubagentHandback" ] \
           && grep -q 'Report delivered to your caller' <<< "${LAST_RESULT:-}"; then
            VERDICT=ok
        fi ;;
esac
[ "$VERDICT" = ok ]
}
_result_of() {
    tail -n 50 "$TRANSCRIPT" 2>/dev/null | jq -r --arg id "$1" '
        select(type == "object") | (.message // empty) | select(type == "object")
        | (.content // empty) | select(type == "array") | .[]
        | select(.type == "tool_result" and .tool_use_id == $id)
        | (if (.content | type) == "string" then .content else (.content | tostring) end)
    ' 2>/dev/null | tail -n 1
}
# Размер, а не время правки: перечитывается только выросший файл, и ожидание на настоящем
# обрыве стоит двадцать `wc`, а не двадцать полных разборов.
_size() { wc -c < "$TRANSCRIPT" 2>/dev/null | tr -d ' '; }
_sz=$(_size)
_judge && exit 0
_i=0
while [ "$_i" -lt 20 ]; do
    _i=$((_i + 1)); sleep 0.1
    _now=$(_size)
    [ "$_now" = "$_sz" ] && continue
    _sz=$_now
    _judge && exit 0
done

if [ "$VERDICT" = broken ] || [ "$VERDICT" = empty ]; then
    _mark="$STATE_DIR/subagent-blind-${SID}"
    if [ ! -f "$_mark" ]; then
        if [ "$VERDICT" = broken ]; then
            printf '🧩 Расшифровка субагента не читается (битый JSON) — проверить исход нечем. Это НЕ «сработал успешно».\n' >> "$QUEUE" 2>/dev/null || true
        else
            printf '🧩 В расшифровке субагента нет ни одного блока ответа — проверить исход нечем. Это НЕ «сработал успешно».\n' >> "$QUEUE" 2>/dev/null || true
        fi
        : > "$_mark" 2>/dev/null || true
    fi
    exit 0
fi

# Дедуп по расшифровке: одно сообщение на один оборвавшийся прогон.
_key=$(printf '%s' "$TRANSCRIPT" | cksum 2>/dev/null | awk '{print $1}')
_seen="$STATE_DIR/subagent-cut-${SID}.seen"
grep -qxF "${_key:-0}" "$_seen" 2>/dev/null && exit 0
printf '%s\n' "${_key:-0}" >> "$_seen" 2>/dev/null || true

_lines=$(wc -l < "$TRANSCRIPT" 2>/dev/null | tr -d ' ')

# Повод контура. Проект берётся у payload, как у прочих продюсеров событий.
if command -v rc_note_event >/dev/null 2>&1; then
    _sub_cwd=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
    [ -n "$_sub_cwd" ] && command -v rc_project_of >/dev/null 2>&1 \
        && RC_EVENT_PROJECT=$(rc_project_of "$_sub_cwd")
    rc_note_event "$STATE_DIR" "subagentcut" \
        "субагент оборвался без ответа (последний блок: ${LAST_KIND}, ходов: ${_lines:-?})" \
        2>/dev/null || true
fi

