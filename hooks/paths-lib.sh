#!/bin/bash
# paths-lib.sh — v1.0.0
#
# ПРЕФИКСЫ: find_ project_ resolve_ session_
# `session_` объявлен 16 ноября 2026 (D1304): адресат сообщения — сессия, как у `project_alert` — проект; пара
# `session_alert`/`project_alert` названа по адресату, а не по соседям.
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
# Единый источник путей ClaudSoul для хуков. Наполняется инкрементально (TASK-003):
# каждая под-часть добавляет сюда одну переменную/функцию, по мере перевода хуков.
#
# До paths-lib эти пути были захардкожены вразнобой по десяткам мест с разными
# именами override-переменных (см. docs/health-audit-2026-06-20.md, F10-F13).
#
# Provides:
#   CLAUDSOUL_ROOT            — корень репозитория проекта (default ~/My Project/ClaudSoul)  [003a]
#   find_project_root [dir]   — поднимается от dir (default $PWD) к ближайшему .git или
#                               CLAUDE.md; печатает его (fallback: сам dir)                  [003b]
#   project_git [-C dir] …    — git в папке, чьи настройки писал не владелец, без программ
#                               из настроек репозитория                                      [D515]
#   project_owner_copy <dir> [<сессия>] — 0, если dir — рабочая копия репозитория владельца
#                               (главная или его worktree), а папка сессии лежит внутри dir:
#                               только там исполняется код из папки             [D516–D518]
#
# Контракт: используем `:=`, поэтому уже заданное окружение (или тест) НЕ
# перезаписывается — lib лишь подставляет дефолт, когда переменная пуста.
# Источать можно многократно (идемпотентно).

# Порядок резолва корня: CLAUDSOUL_ROOT → CLAUDSOUL_REPO → ~/.claude/claudsoul-repo → дефолт.
# До D72 читался только дефолт, и файл-указатель, который install.sh кладёт на шаге 0,
# не использовался ни одним хуком — им пользовались лишь скиллы через
# bin/resolve-claudsoul-repo.sh. У всякого, кто склонировал репозиторий не в
# ~/My Project/ClaudSoul, тихо умирали алерт по BACKLOG (session-collector),
# просроченные замеры, обратный детектор дрейфа (session-start) и графовое
# расширение доменов (knowledge-activator) — без единой ошибки, молча.
#
# Полный резолвер отсюда НЕ источается намеренно: он живёт в ~/.claude/bin/ (bootstrap
# вне репозитория) и требует каталог mcp-server/ingest, то есть установленного MCP.
# Хукам корень нужен независимо от того, ставился ли MCP; общее у двух мест — порядок,
# и он повторён здесь по шагам. Отличий два, оба сознательные: нет требования
# mcp-server/ingest (см. выше) и нет отката на git-корень — хук работает в каталоге
# ЧУЖОГО проекта, и его git-корень к ClaudSoul отношения не имеет.
# Кандидат годен, только если он АБСОЛЮТНЫЙ и существует. Относительный путь здесь
# страшнее отсутствующего: `.` проходит проверку `-d` из любого каталога, и хуки начинают
# читать BACKLOG.md и domains/ того проекта, где сейчас стоит агент, считая их своими.
# Записать туда `.` умеет сам установщик: `install.sh:21` берёт позиционный аргумент
# дословно, без приведения к абсолютному, и `install.sh:113` пишет его в указатель как есть.
_cs_absdir() { case "$1" in /*) [ -d "$1" ] ;; *) return 1 ;; esac; }

# Значение из окружения проходит ту же проверку на абсолютность (D514): относительное читалось
# от папки сессии, и `CLAUDSOUL_ROOT=.` исполнял `scripts/` того проекта, где стоит агент.
# Существование НЕ проверяется: тесты называют несуществующий корень намеренно, и откат с него
# на настоящий репозиторий увёл бы их в живое дерево.
case "${CLAUDSOUL_ROOT:-}" in ''|/*) ;; *) CLAUDSOUL_ROOT="" ;; esac
if [ -z "${CLAUDSOUL_ROOT:-}" ]; then
    # 1. CLAUDSOUL_REPO — то же имя, которым override называют пользователю
    #    (bin/resolve-claudsoul-repo.sh:32, skills/enrich/SKILL.md). Без этого шага человек
    #    выполнял названную ему инструкцию, скиллы чинились, а хуки оставались в прежней
    #    тишине — тот же отказ по второму входу.
    if [ -n "${CLAUDSOUL_REPO:-}" ] && _cs_absdir "$CLAUDSOUL_REPO"; then
        CLAUDSOUL_ROOT="$CLAUDSOUL_REPO"
    # 2. Файл-указатель, который пишет install.sh на шаге 0.
    elif [ -f "$HOME/.claude/claudsoul-repo" ]; then
        # `|| true` обязателен: у 18 хуков (на 30 августа 2026), источающих эту библиотеку, объявлен `set -e`,
        # и на нечитаемом указателе (chmod 000, чужой владелец) статус присваивания равен
        # единице — оболочка выходит ПРЯМО ЗДЕСЬ. Вывод при этом пуст: stderr `cat` заглушён,
        # а `set -e` молчит по устройству. Хук умирает при источении библиотеки, не начав
        # работу и ничего не сказав. Резолв дефолта не может быть причиной отказа: это
        # последняя ступень отката, а не операция, которой позволено падать.
        _cs_pointer=$(cat "$HOME/.claude/claudsoul-repo" 2>/dev/null) || true
        _cs_absdir "${_cs_pointer:-}" && CLAUDSOUL_ROOT="$_cs_pointer" || true
        unset _cs_pointer
    fi
fi
: "${CLAUDSOUL_ROOT:=$HOME/My Project/ClaudSoul}"
: "${LESSONS_DIR:=$HOME/.claude/global-lessons}"   # база знаний (была под 3 именами: KNOWLEDGE_DIR/LESSONS_DIR/GLOBAL_LESSONS)
: "${STATE_DIR:=$HOME/.claude/hooks/state}"         # состояние хуков (003e); `:=` уважает env/тест — не перезаписывает заданное

# Единый walk-up для определения корня проекта. До 003b было: каноничная версия
# в session-registry-lib (_sr_detect_project, без параметра), а knowledge-activator
# и session-start использовали сырой cwd без walk-up (F13) — из подпапки проекта
# не находили SESSION.md/CLAUDE.md.
find_project_root() {
    local dir="${1:-$PWD}"
    local start="$dir"
    # Условие выхода — «подъём перестал двигать путь», а не только «дошли до /».
    # На относительном входе dirname упирается в точку и возвращает её же: `sub/deeper`
    # → `sub` → `.` → `.` → …, и цикл не кончается никогда. Хук при этом висит в
    # PreToolUse, то есть вешает сессию целиком. Вход берётся из payload
    # (knowledge-activator.sh:643 — `${CWD:-$PWD}` без проверки на абсолютность),
    # то есть приходит извне и на форму его никто не влияет.
    local prev=""
    while [ -n "$dir" ] && [ "$dir" != "/" ] && [ "$dir" != "$prev" ]; do
        # `.git` — каталог в обычном клоне и ФАЙЛ («gitdir: …») в worktree и подмодуле.
        # Проверка только на каталог перешагивала корень worktree и отдавала родительский
        # репозиторий: хуки писали SESSION.md и проектную память соседнего проекта, молча.
        # Worktree здесь штатный режим — инструмент Agent умеет isolation:"worktree".
        if [ -e "$dir/.git" ] || [ -f "$dir/CLAUDE.md" ]; then
            printf '%s' "$dir"; return 0
        fi
        prev="$dir"
        dir="$(dirname "$dir")"
    done
    printf '%s' "$start"
}

# Корень проекта ИЛИ ПУСТО — для тех, кто в этот корень ПИШЕТ.
#
# `find_project_root` по контракту возвращает входной каталог, когда маркера не нашёл, и
# потому не отличает «проект здесь» от «проекта нет вовсе». Читателю такая подмена безвредна
# (прочтёт пусто), писателю — нет: он создаёт каталог там, где проекта никогда не было.
# Замер 7 сентября 2026: файлов `.claude-docs/session-activity.md` в домашнем дереве 99, и
# легли они в том числе в `/Users/user`, `/Users/user/Downloads` и в подкаталоги чужих
# проектов (`ProjectA_NEW/web`, `Трёхсторонний договор/Final`), а в одном месте вложились сами в
# себя: `.claude-docs/exports/.claude-docs/`. Ни у `/Users/user`, ни у `Downloads` нет ни
# `.git`, ни `CLAUDE.md` — то есть подъёма к корню мало, нужен ещё признак «корень НАЙДЕН».
#
# Пусто — законный ответ и означает «писать некуда», а не ошибку. Проверять надо им, а не
# сравнением с входом: вход мог совпасть с корнем по-честному.
project_root_or_empty() {
    local _pr_d
    _pr_d=$(find_project_root "${1:-}")
    [ -n "$_pr_d" ] || return 0
    { [ -e "$_pr_d/.git" ] || [ -f "$_pr_d/CLAUDE.md" ]; } && printf '%s' "$_pr_d"
    return 0
}

# git в папке, чьи настройки писал не владелец (папка сессии, проекты реестра), — без программ,
# которые git берёт из настроек РЕПОЗИТОРИЯ (D515). Зовётся как git: `project_git -C <каталог> …`
# либо из каталога.
#
# Голый git в чужом репозитории исполняет код: замер 5 октября 2026 (git 2.54.0) — `status`,
# `diff`, `ls-files` запускают `core.fsmonitor` (6 команд из 9); `diff --name-only` запускает и
# фильтр содержимого `filter.<драйвер>.clean`; `log` при `log.showSignature` — `gpg.program`.
# D514 закрыл последнее флагом у одного вызова, а таких вызовов у хуков, срабатывающих сами,
# было девятнадцать в шести файлах: у правила не было владельца, и каждый звал голый git.
#
# Фильтры гасятся только из настроек репозитория (local, worktree и их include): фильтр из
# глобальных настроек владельца (git-lfs после `git lfs install`) — его собственный выбор и
# работает. Названный предел: гасится ЛЮБОЙ фильтр из настроек репозитория — LFS после
# `git lfs install --local`, нормализация концов строк, вычистка секретов: файл, у которого
# сменилась отметка времени, читается изменённым (для LFS измерено тем же днём); при
# `filter.<драйвер>.required` git падает, и хук видит
# пустой ответ. Вывод ПАТЧА (`diff` без `--name-only`) этим не гасится: там ещё внешний diff и
# textconv — нужны `--no-ext-diff --no-textconv`. Условие снятия: хук, срабатывающий сам,
# начнёт читать патч.
# `--show-scope` есть с git 2.26: на старшем git список фильтров пуст, и гасятся только
# fsmonitor и подпись. Условие снятия: git старше 2.26 в окружении владельца или на CI.
# КЛЮЧ С `=` (D1091, 25 октября 2026). Строку `-c ключ=значение` git делит по ПЕРВОМУ `=`: у драйвера с `=` в имени
# (`filter.a=b.clean`) погашение `-c filter.a=b.clean=` задавало ключ `filter.a`, а настоящий оставался жив — скептик
# исполнил программу фильтра сквозь `impact-inject.sh`. Такой ключ передаётся окружением `GIT_CONFIG_KEY_<n>` /
# `GIT_CONFIG_VALUE_<n>` (git 2.31+), где ключ и значение — разные поля; уже заданные вызывающим пары сохраняются, новые
# дописываются после них. Git, который этой передачи не знает, — отказ без вызова: исполнить фильтр хуже, чем промолчать.
# ПОДМОДУЛЬ (D1094, D1095). `status`/`diff` суперпроекта рекурсируют в подмодуль, и ДОЧЕРНИЙ git читает его настройки
# (`.git/modules/<имя>/config`), которых перечень фильтров выше не касается — он снят только в суперпроекте. Те же
# настройки писал тот же, кто и `.git/config` суперпроекта, — та же граница доверия. Гасит КОМАНДНАЯ
# `--ignore-submodules=dirty` у самих `status`/`diff`: она не пускает git в рабочее дерево подмодуля (фильтр грязного
# файла не исполняется), а смену УКАЗАТЕЛЯ подмодуля оставляет видимой. Форма `-c diff.ignoreSubmodules=dirty` слабее и
# ПЕРЕБИВАЕТСЯ ключом `submodule.<имя>.ignore=none` (в т.ч. из отслеживаемого `.gitmodules`) — D1095; командная стоит
# выше настроек и не перебивается. Флаг вставляется только у `status`/`diff` (прочие подкоманды в рабочее дерево
# подмодуля не входят); `log`/`show`/`add` не задеты. fsmonitor в подмодуле гасится `-c` сам — он пропагируется.
project_git() {
    local -a _pg_at=() _pg_o=(-c core.fsmonitor=false -c log.showSignature=false) _pg_env=() _pg_ca=()
    while [ "${1:-}" = "-C" ] && [ $# -ge 2 ]; do _pg_at+=(-C "$2"); shift 2; done
    # Подкоманда — первый не-опционный токен "$@" после вырезания `-C` (пропуская `-c` и его значение). Для status/diff
    # вставляем командный флаг СРАЗУ за ней — до `--` и путей, иначе git счёл бы его путём.
    _pg_ca=("$@")
    local _pg_j=0 _pg_sub=""
    while [ "$_pg_j" -lt "${#_pg_ca[@]}" ]; do
        case "${_pg_ca[$_pg_j]}" in
            -c|-C) _pg_j=$((_pg_j + 2)); continue ;;
            -*) _pg_j=$((_pg_j + 1)); continue ;;
            *) _pg_sub="${_pg_ca[$_pg_j]}"; break ;;
        esac
    done
    case "$_pg_sub" in
        status|diff) _pg_ca=("${_pg_ca[@]:0:_pg_j + 1}" --ignore-submodules=dirty "${_pg_ca[@]:_pg_j + 1}") ;;
    esac
    # Индекс для env-пар начинается с унаследованного GIT_CONFIG_COUNT. База — ДЕСЯТИЧНАЯ (`10#`): «08»/«09» иначе
    # роняют арифметику bash как восьмеричные (D1094, минор 2-го скептика). Непустое, но не чистое десятичное значение
    # (пробел, буквы, ведущий знак) оставляем как есть и env-пары не добавляем: тронуть чужой счётчик — потерять его пару.
    local _pg_scope _pg_key _pg_rest _pg_ma _pg_mi _pg_raw="${GIT_CONFIG_COUNT:-0}" _pg_n _pg_bad=0
    case "$_pg_raw" in ''|*[!0-9]*) _pg_bad=1; _pg_n=0 ;; *) _pg_n=$((10#$_pg_raw)) ;; esac
    while read -r _pg_scope _pg_key _pg_rest; do
        case "$_pg_scope" in global|system|command) continue ;; esac
        case "$_pg_key" in
            *=*) _pg_env+=("GIT_CONFIG_KEY_$_pg_n=$_pg_key" "GIT_CONFIG_VALUE_$_pg_n="); _pg_n=$((_pg_n + 1)) ;;
            *) _pg_o+=(-c "$_pg_key=") ;;
        esac
    done < <(git ${_pg_at[@]+"${_pg_at[@]}"} config --show-scope --get-regexp '^filter\..*\.(clean|smudge|process)$' 2>/dev/null)
    if [ "${#_pg_env[@]}" -eq 0 ]; then
        git ${_pg_at[@]+"${_pg_at[@]}"} "${_pg_o[@]}" ${_pg_ca[@]+"${_pg_ca[@]}"}
        return
    fi
    # Есть фильтр с «=» в имени, а переданный GIT_CONFIG_COUNT не чистое число — дописать пару к нему нельзя, не затерев
    # чужую; исполнить фильтр чужих настроек нельзя тем более. Отказ без вызова.
    if [ "$_pg_bad" = 1 ]; then
        echo "project_git: GIT_CONFIG_COUNT='${_pg_raw}' не число, а есть фильтр с «=» — git не зову" >&2
        return 1
    fi
    read -r _pg_ma _pg_mi < <(git version 2>/dev/null | sed -n 's/^git version \([0-9]*\)\.\([0-9]*\).*/\1 \2/p')
    if [ "${_pg_ma:-0}" -lt 2 ] || { [ "${_pg_ma:-0}" -eq 2 ] && [ "${_pg_mi:-0}" -lt 31 ]; }; then
        echo "project_git: фильтр с «=» в имени не погасить на git старше 2.31 — git не зову" >&2
        return 1
    fi
    env "${_pg_env[@]}" GIT_CONFIG_COUNT="$_pg_n" git ${_pg_at[@]+"${_pg_at[@]}"} "${_pg_o[@]}" ${_pg_ca[@]+"${_pg_ca[@]}"}
}

# Ловушка git стражей коммита (`hooks/commit-trap.sh`, D1022) СУДИТ коммит этой команды в репозитории каталога: файл
# `<ловушка>` в каталоге ловушек (`--git-path hooks` учитывает core.hooksPath) исполним, несёт метку с адресом
# (`claudsoul-commit-trap ... @ <путь>`), файл по адресу на месте, и команда не обходит ловушку. Там стражи коммита судят
# в ловушке, а на PreToolUse молчат: по тексту команды они судили папку сессии, а не репозиторий коммита. Скептик D1022:
# по одной метке PreToolUse молчал и при мёртвой ловушке (адрес в убранном worktree, шим выходит с 0), и при обходе
# (`--no-verify` на ветке: суд обхода у merge-root-gate стоит только на main), и коммит с разошедшимися таблицами входил.
# Обход узнаётся словом в команде (тот же перечень, что у merge-root-gate); ложное совпадение возвращает прежний суд
# PreToolUse, а не отказ. Предел: форма обхода вне перечня слов (D1023).
COMMIT_TRAP_MARK="claudsoul-commit-trap"
project_commit_trap() {   # <каталог> <commit-msg|pre-commit> [<команда>] -> 0, если ловушка судит этот коммит
    local _ct_h _ct_t
    _ct_h=$(project_git -C "$1" rev-parse --path-format=absolute --git-path hooks 2>/dev/null) || return 1
    [ -x "$_ct_h/$2" ] || return 1
    _ct_t=$(sed -n "s/.*${COMMIT_TRAP_MARK}[^@]*@ //p" "$_ct_h/$2" 2>/dev/null | head -n 1)
    [ -n "$_ct_t" ] && [ -f "$_ct_t" ] || return 1
    [ -n "${3:-}" ] || return 0
    grep -qiE -- '--no-veri|hookspath|GIT_CONFIG|alias[.]|commit([[:space:]]+[^;&|]*)?[[:space:]]-[a-zA-Z]*n[a-zA-Z]*([[:space:]]|$)' <<< "$3" && return 1
    return 0
}

# Рабочая копия репозитория владельца (`CLAUDSOUL_ROOT`): главная или его worktree. Хук,
# исполняющий скрипт из папки проекта (прибор карты, генератор таблиц, сверщик чисел), исполняет
# его только здесь: файл с тем же именем в чужой папке сессии — не прибор, а чужой код (D516,
# D517; правило «адрес инструмента ClaudSoul берётся у ClaudSoul», .claude/rules/claudsoul-hooks.md).
# Свидетельство доверия берётся у ДОВЕРЕННОЙ стороны — список `git worktree list` ведёт сам
# репозиторий владельца, и чужая папка вписать себя в него не может. Первая редакция (D516)
# сверяла общий каталог git, и скептик её обошёл: `.git/commondir` в чужой папке пишет чужой, а
# переменные GIT_DIR/GIT_COMMON_DIR/GIT_WORK_TREE бьют `-C` — поэтому они здесь сняты. Строки
# списка, кроме `worktree <путь>`, отсеиваются: пустая строка-разделитель дала бы `cd ""`, то есть
# текущий каталог. Адреса владельца нет — ответ «нет»: исполнять нечьё нельзя.
# Скептик D518 обошёл и эту редакцию, трижды. (1) Каталог worktree убран без `git worktree prune`,
# а путь занял чужой репозиторий со своим `.git` — запись в списке осталась: привязанная копия
# теперь засчитывается, только если `.git` у неё ФАЙЛ, как ставит `git worktree add`. (2) Адрес
# владельца не корень git (установка из архива) — `git -C` поднимался к объемлющему чужому
# репозиторию: потолок GIT_CEILING_DIRECTORIES на родителе адреса держит поиск в нём самом.
# (3) `core.worktree` в настройках чужой папки уводит её корень в копию владельца — вторым
# аргументом передаётся папка сессии, и она обязана лежать внутри сверяемого корня.
# Названный предел: подделка на пути устаревшей записи `.git`-ФАЙЛА, указывающего в каталог
# worktree владельца, засчитается — git сочтёт такую папку его worktree; условие снятия —
# у владельца появятся привязанные worktree, убираемые без prune.
project_owner_copy() {   # <каталог> [<папка сессии>]
    local _po_p _po_r _po_s _po_w _po_main=1
    [ -n "${CLAUDSOUL_ROOT:-}" ] || return 1
    _po_r=$(cd "$CLAUDSOUL_ROOT" 2>/dev/null && pwd -P) || return 1
    _po_p=$(cd "$1" 2>/dev/null && pwd -P) || return 1
    if [ -n "${2:-}" ]; then
        _po_s=$(cd "$2" 2>/dev/null && pwd -P) || return 1
        case "$_po_s/" in "$_po_p"/*) ;; *) return 1 ;; esac
    fi
    while IFS= read -r _po_w; do
        case "$_po_w" in "worktree "*) ;; *) continue ;; esac
        if [ "$(cd "${_po_w#worktree }" 2>/dev/null && pwd -P)" = "$_po_p" ]; then
            [ "$_po_main" = 1 ] || [ -f "$_po_p/.git" ]
            return
        fi
        _po_main=0
    done < <(env -u GIT_DIR -u GIT_COMMON_DIR -u GIT_WORK_TREE -u GIT_INDEX_FILE \
                 GIT_CEILING_DIRECTORIES="$(dirname "$_po_r")" git -C "$_po_r" worktree list --porcelain 2>/dev/null)
    return 1
}


# Единый парсинг session_id из payload-JSON хука (F3). Унифицирует ТОЛЬКО парсинг —
# fallback передаётся аргументом, поэтому контракт каждого хука сохраняется:
#   resolve_session_id "$INPUT"        → SID или "unknown" (для хуков, что продолжают)
#   resolve_session_id "$INPUT" ""     → SID или "" (для хуков, что делают exit при пустом)
# resolve_actor_id "<payload>"
#   Печатает `agent_id` — идентификатор СУБАГЕНТА, сделавшего вызов. Пусто, если вызов
#   принадлежит основной сессии (поля нет). Это и есть признак «вызов не родителя».
#
# resolve_actor_transcript "<payload>"
#   Печатает расшифровку ТОГО, чей вызов проверяется. Пусто, если актор — субагент, а его
#   расшифровку найти не удалось: «не знаю» обязано быть отличимо от «родитель».
#
# ЗАМЕР 17 сентября 2026 (D449; зонд в настройках проекта, 32 записи payload):
#   PreToolUse / PostToolUse — `transcript_path` ВСЕГДА родительский; `agent_id` и
#     `agent_type` есть ТОЛЬКО у субагента (24 записи из 32); поля с расшифровкой самого
#     агента на этих событиях нет вовсе;
#   SubagentStart — `agent_id`, `agent_type`, расшифровки агента нет;
#   SubagentStop  — `agent_id` И `agent_transcript_path` (собственная расшифровка агента),
#     плюс готовое `last_assistant_message`.
#   `session_id` у субагента РОДИТЕЛЬСКИЙ на всех событиях — состояние `*-<SID>` общее.
#
# ПОЧЕМУ НЕ ИМЯ ФАЙЛА. До этой правки роль актора решалась формой имени расшифровки
# (`agent-*` в basename) в двух местах — `five-whys-gate.sh:111` и `rework-detector.sh:126`
# (корень R3, «роль решается перечнем форм»). Замер: снимков `rework-world-*.agent-*` в
# состоянии 0 при 3333 расшифровках субагентов на диске; ключ дедупа в
# `subagent-cut-<SID>.seen` равен `cksum` пути РОДИТЕЛЯ в 16 файлах из 16 по всем проектам.
# Признак не срабатывал ни разу: решение «внутри субагента права на отказ нет» (10 сентября
# 2026) в силу не вступало, и 17 сентября субагенту отбили семь записей его же файлов.
# НАЗВАННЫЙ ПРЕДЕЛ: поле даёт харнесс. Payload без `agent_id` читается как вызов родителя —
# так ведут себя старые клиенты, и это ПРЕЖНЕЕ поведение, а не новое. Условие снятия: в
# корпусе не останется расшифровок клиента без поля.
# ПРЕДШЕСТВЕННИК И ЕГО СУДЬБА (правило «чем это решалось раньше»). Признак `isSidechain` уже
# живёт в `hook-input-lib.sh` (`owner_reply`, через него — `transcript_user_texts` и `transcript_agent_text_before_reply`),
# и он ОСТАЁТСЯ: там предмет иной — «чьи слова в расшифровке СЕССИИ», и запись ветки субагента
# в ней речью собеседника не является. Здесь предмет — «чей это ВЫЗОВ и где расшифровка того,
# кого судят»; пересечения нет, оба нужны. Свести их в один нельзя: `isSidechain` есть
# свойство ЗАПИСИ в файле, `agent_id` — свойство СОБЫТИЯ, и в payload вызова записей нет.
# КОНТРПРИМЕР (признак обязан НЕ поймать): вызов основной сессии при живой фоновой волне —
# `agent_id` в его payload нет, хотя субагенты в этот момент работают. Замер: 8 записей
# родителя из 32 пришли при идущей волне, ни одна поля не несёт.
resolve_actor_id() {
    local input="${1:-}" id
    [ -n "$input" ] || return 0
    command -v jq >/dev/null 2>&1 || return 0
    # Тип обязателен. `.agent_id // empty` печатает ЛЮБОЕ истинное значение, и объект
    # `{"agent_id":{"a":1}}` давал непустую многострочную выдачу — потребитель читал её как
    # «вызов субагента» и снимал отказ уровня 4 наличием ключа. Находка скептика 18 сентября
    # 2026. Признак сужен до непустой СТРОКИ; форма строки здесь НЕ судится намеренно: сузить
    # её значит вернуть ложный отказ настоящему субагенту, если харнесс сменит алфавит
    # идентификаторов. Форму судит только сборка пути ниже, где цена ошибки иная.
    id=$(printf '%s' "$input" | jq -r 'if (.agent_id | type) == "string" then .agent_id else "" end' 2>/dev/null)
    printf '%s' "$id"
}

# ЦЕНА. Четыре поля читаются ОДНИМ вызовом jq, а не четырьмя: замер 18 сентября 2026 —
# 24 мс на вызов при четырёх, 12 при одном, и функция зовётся у гейта на КАЖДОМ
# `Edit/Write/Bash`. НАЗВАННЫЙ ПРЕДЕЛ приёма: поля разделяются переводом строки, поэтому путь
# с настоящим переводом строки внутри развалит разбор; в дереве и в расшифровках таких нет.
# Условие снятия: понадобится путь с переводом строки — читать через NUL-разделитель.
resolve_actor_transcript() {
    local input="${1:-}" tr id own sid base f
    [ -n "$input" ] || return 0
    command -v jq >/dev/null 2>&1 || return 0
    {
        read -r id || true
        read -r own || true
        read -r sid || true
        read -r tr || true
    } <<EOF
$(printf '%s' "$input" | jq -r '(.agent_id // ""), (.agent_transcript_path // ""), (.session_id // ""), (.transcript_path // "")' 2>/dev/null)
EOF
    # Родитель: его расшифровка и есть расшифровка актора.
    if [ -z "${id:-}" ]; then printf '%s' "${tr:-}"; return 0; fi
    # На SubagentStop путь отдаёт сам харнесс — но берётся он не дословно. Находка скептика
    # 18 сентября 2026: дословный путь читался на ЛЮБОМ событии и из любого места
    # (`agent_transcript_path: "/etc/passwd"` возвращался как есть), а символическая ссылка
    # внутри каталога субагентов проходилась насквозь, потому что `[ -f ]` идёт по ссылке.
    # Прочитанное уходит в журнал исходов полем TRACE, то есть это чтение чужого файла.
    # Условие: путь обязан лежать в каталоге субагентов ЭТОЙ сессии и не быть ссылкой.
    if [ -n "${own:-}" ] && [ -f "$own" ] && [ ! -h "$own" ]; then
        case "$own" in
            */"${sid:-__нет__}"/subagents/*) printf '%s' "$own"; return 0 ;;
        esac
    fi
    # На событиях вызова инструмента такого поля нет; путь собирается по двум ИЗМЕРЕННЫМ
    # раскладкам: агент инструмента Task лежит в `<сессия>/subagents/`, агент волны — в
    # `<сессия>/subagents/workflows/<прогон>/`.
    [ -n "${tr:-}" ] && [ -n "${sid:-}" ] || return 0
    # Идентификаторы идут в ПУТЬ, поэтому сверяются с набором символов ДО сборки: `..` или
    # черта в `agent_id`/`session_id` увели бы чтение в произвольный файл, а признак
    # субагента (`resolve_actor_id`) от этой сверки не зависит — там предмет иной, «поле
    # есть или нет». Не прошло сверку — печатаем ПУСТО, то есть «актор неизвестен»: это
    # безопасная сторона, потребитель тогда не читает ничью расшифровку.
    case "$id" in (*[!A-Za-z0-9_-]*|'') return 0 ;; esac
    case "$sid" in (*[!A-Za-z0-9_-]*|'') return 0 ;; esac
    base="$(dirname "$tr")/$sid/subagents"
    # `! -h` на ОБЕИХ ветках: `[ -f ]` идёт по ссылке, и ссылка в каталоге субагентов вывела
    # бы чтение наружу так же, как дословный путь от харнесса (находка скептика 18 сентября
    # 2026 — первая редакция закрыла только ветку харнесса, а сборка осталась открытой).
    if [ -f "$base/agent-${id}.jsonl" ] && [ ! -h "$base/agent-${id}.jsonl" ]; then
        printf '%s' "$base/agent-${id}.jsonl"; return 0
    fi
    # Глоб с проверкой `[ -f ]`, а не `compgen`: встроенной команды bash под zsh нет
    # (pattern-shell-portability).
    for f in "$base"/workflows/*/"agent-${id}.jsonl"; do
        [ -f "$f" ] && [ ! -h "$f" ] || continue
        printf '%s' "$f"; return 0
    done
    # Субагент есть, расшифровки не нашли — ПУСТО. Подставить родителя значит выдать чужую
    # речь за его собственную: ровно дефект D449.
    return 0
}

# resolve_actor_suffix "<payload>" → ".agent-<id>" для вызова СУБАГЕНТА, пусто для родителя.
#
# ЗАЧЕМ ВЛАДЕЛЕЦ. Состояние, чей предмет — ДЕЙСТВИЕ вызывающего (его правки, его циклы
# переработки, его полоса провалов, его поводы), ключевалось одним `session_id`, а харнесс
# кладёт его общим и родителю, и субагенту (замер 17 сентября 2026, 32 записи payload).
# Следствие наблюдалось дословно: субагенту инжектировали повод `rework` по 16 файлам,
# которых он не касался, а родитель получал отказ уровня 4 по циклам, накрученным
# субагентами. Суффикс собирался ЛИТЕРАЛОМ на каждом конце связи (корень R1): писатель
# `rework-detector.sh:308` и читатель `five-whys-gate.sh:108` строили имя каждый сам.
# Цена такого расхождения уже измерена в этом же дереве — `intrusiveness-classify-lib.sh:156`:
# писателя у имени `error_count_` не было НИ ОДНОГО, читатель остался на прежнем имени, и
# мёртвая связь была неотличима от «провалов не было».
#
# ПРЕДШЕСТВЕННИКИ И ИХ СУДЬБА (правило «чем это решалось раньше»). Формой имени
# `<семья>-fired-<sid>.jsonl` уже владеет `throttle_file` (`throttle-lib.sh`), и он
# ОСТАЁТСЯ — суффикс приходит к нему четвёртым аргументом, а не собирается рядом.
# `auth_state_path` (`authorization-lib.sh:96`) и `_itr_state_path`
# (`intrusiveness-state-lib.sh:69`) тоже остаются: у обоих предмет законно СЕССИОННЫЙ —
# авторизацию даёт человек в сессии, бюджет вмешательства считается на сессию, — и
# суффикс актора там был бы дефектом, а не починкой.
#
# РАЗДЕЛИТЕЛЬ, по которому решается, звать ли эту функцию: предмет файла — ДЕЙСТВИЕ
# вызывающего (звать) или СОСТОЯНИЕ СЕССИИ (не звать). Из 82 мест дерева, собирающих имя
# состояния с `${SID}`, большинство здоровы по праву: `narrative-pending`,
# `startup-signals`, `injection-bytes-peak`, `last_keywords` описывают саму сессию, одну
# на всех акторов.
#
# ПУСТО У РОДИТЕЛЯ — не умолчание, а свойство: имя файла родителя не меняется, поэтому ни
# один нынешний читатель родительского состояния не ломается. Проверено формой глоба:
# `rework-fired-*.jsonl` ловит и `rework-fired-<SID>.agent-<id>.jsonl`, а отбор семейства
# уборкой (`throttle-lib.sh:109`, `${_base%%-fired-*}`) даёт то же `rework`.
#
# НАБОР СИМВОЛОВ СВЕРЯЕТСЯ: значение идёт в ИМЯ ФАЙЛА, и `..` или черта увели бы запись в
# чужой каталог — тот же класс, что закрыт в `resolve_actor_transcript` выше. Но ветка
# отказа здесь ИНАЯ: вернуть пусто значит молча вернуться к смешению состояния, то есть
# ровно к чинимому дефекту, и молчание было бы неотличимо от «вызов родителя» (так уже
# было с признаком `agent-*` в имени расшифровки — не сработал ни разу при 3333
# расшифровках). Поэтому непрошедшее значение не отбрасывается, а СВОРАЧИВАЕТСЯ в число
# (`cksum`): актор остаётся отличим, а имя остаётся безопасным.
# КОНТРПРИМЕР (функция обязана вернуть ПУСТО): вызов основной сессии при живой фоновой
# волне — поля `agent_id` в его payload нет, хотя субагенты в этот момент работают.
# ЦЕНА. Второй аргумент — УЖЕ ПРОЧИТАННЫЙ `agent_id`: потребитель, который всё равно
# разбирает payload своим `jq`, передаёт значение сюда и не платит за третий разбор. Правило
# сформулировано и измерено соседом выше (24 мс при четырёх вызовах против 12 при одном), а
# нарушил его первым же делом потребитель на `PreToolUse[Bash]` — самом частом событии
# (находка адверсариальной проверки 18 сентября 2026, +4,3 мс на вызов). Пустая строка
# вторым аргументом означает «поля нет», то есть вызов родителя; аргумент опущен — читаем
# сами, как раньше.
resolve_actor_suffix() {
    local input="${1:-}" id
    if [ "$#" -ge 2 ]; then
        id="${2:-}"
    else
        [ -n "$input" ] || return 0
        command -v resolve_actor_id >/dev/null 2>&1 || return 0
        id=$(resolve_actor_id "$input")
    fi
    [ -n "${id:-}" ] || return 0
    case "$id" in
        *[!A-Za-z0-9_-]*) id=$(printf '%s' "$id" | cksum | awk '{print $1}') ;;
    esac
    printf '.agent-%s' "$id"
}

resolve_session_id() {
    # ${2-unknown} (без `:`) — fallback по умолчанию только когда аргумент НЕ передан;
    # явный пустой `""` сохраняется (контракт exit-style хуков).
    local input="$1" fallback="${2-unknown}" sid
    sid=$(printf '%s' "$input" | jq -r '.session_id // empty' 2>/dev/null)
    printf '%s' "${sid:-$fallback}"
}

# session_alert <каталог состояния> <sid> <каталог проекта> <текст> — сообщение, адресованное СВОЕЙ сессии (D1304).
#
# Канал — `stop-signals-<sid>.txt`, рядом корень проекта `stop-signals-<sid>.project` (пишется один раз); показывает
# `pending-alerts-surface.sh` на следующей реплике той же сессии, а когда она кончилась — сессии того же проекта (D1047).
# Общая очередь `pending-alerts.txt` — только для сообщений обо всей системе: её снимает первая сессия с репликой, и
# «закрытые пункты проекта ProjectA» приходили в сессию ClaudSoul (42 из 156 показов за 14 дней — чужой сессии). Прежде
# канал своей сессии писали две копии трёх строк (`declared-problem-recorded.sh`, `session-collector.sh`); владелец
# записи теперь один. Сессии нет — сообщение уходит в общую очередь, как до D1304, а не теряется.
session_alert() {
    local st="$1" sid="$2" dir="$3" msg="$4" root=""
    [ -n "$msg" ] || return 0
    if [ -z "$sid" ] || [ "$sid" = unknown ]; then
        printf '%s\n' "$msg" >> "$st/pending-alerts.txt" 2>/dev/null || true
        return 0
    fi
    if [ ! -s "$st/stop-signals-${sid}.project" ] && [ -n "$dir" ]; then
        root=$(find_project_root "$dir" 2>/dev/null)
        printf '%s\n' "${root:-$dir}" > "$st/stop-signals-${sid}.project" 2>/dev/null || true
    fi
    printf '%s\n' "$msg" >> "$st/stop-signals-${sid}.txt" 2>/dev/null || true
}

# project_alert <каталог состояния> <каталог проекта> <текст> — сообщение о ПРОЕКТЕ (D1304): показывается на ближайшей
# реплике любой сессии этого проекта (`pending-alerts-surface.sh`), а не первой сессии системы. Повод — «закрытых пунктов
# проекта ProjectA унесено в архив — добавь в коммит» в сессии ClaudSoul: сборщик сессии уносит в архив и бэклог
# ClaudSoul, и адресат такого слова — тот, кто работает в проекте файла, а не сессия, чей сборщик это сделал. Ключ файла
# `project-signals-<cksum>.txt` — физический путь корня (`pwd -P`), его же считает читатель. Корень не найден — общая
# очередь, как до D1304.
project_alert() {
    local st="$1" dir="$2" msg="$3" root=""
    [ -n "$msg" ] || return 0
    root=$(find_project_root "$dir" 2>/dev/null); root="${root:-$dir}"
    root=$(cd "$root" 2>/dev/null && pwd -P) || root=""
    if [ -z "$root" ]; then
        printf '%s\n' "$msg" >> "$st/pending-alerts.txt" 2>/dev/null || true
        return 0
    fi
    printf '%s\n' "$msg" >> "$st/project-signals-$(printf '%s' "$root" | cksum | awk '{print $1}').txt" 2>/dev/null || true
}
