#!/bin/bash
# paths-lib.sh — v1.0.0
# Единый источник путей ClaudSoul для хуков. Наполняется инкрементально (TASK-003):
# каждая под-часть добавляет сюда одну переменную/функцию, по мере перевода хуков.
#
# До paths-lib эти пути были захардкожены вразнобой по десяткам мест с разными
# именами override-переменных (см. docs/health-audit-2026-06-20.md, F10-F13).
#
# Provides:
#   CLAUDSOUL_ROOT            — корень репозитория проекта (default ~/My Project/ClaudSoul)  [003a]
#   find_project_root [dir]   — поднимается от dir (default $PWD) к ближайшему .git или
#                               CLAUDE.md; печатает его (fallback: сам dir)                  [003b]
#
# Контракт: используем `:=`, поэтому уже заданное окружение (или тест) НЕ
# перезаписывается — lib лишь подставляет дефолт, когда переменная пуста.
# Источать можно многократно (идемпотентно).

# Порядок резолва корня: CLAUDSOUL_ROOT → CLAUDSOUL_REPO → ~/.claude/claudsoul-repo → дефолт.
# До D72 читался только дефолт, и файл-указатель, который install.sh кладёт на шаге 0,
# не использовался ни одним хуком — им пользовались лишь скиллы через
# bin/resolve-claudsoul-repo.sh. У всякого, кто склонировал репозиторий не в
# ~/My Project/ClaudSoul, тихо умирали алерт по BACKLOG (session-collector),
# просроченные замеры, обратный детектор дрейфа (session-start) и графовое
# расширение доменов (knowledge-activator) — без единой ошибки, молча.
#
# Полный резолвер отсюда НЕ источается намеренно: он живёт в ~/.claude/bin/ (bootstrap
# вне репозитория) и требует каталог mcp-server/ingest, то есть установленного MCP.
# Хукам корень нужен независимо от того, ставился ли MCP; общее у двух мест — порядок,
# и он повторён здесь по шагам. Отличий два, оба сознательные: нет требования
# mcp-server/ingest (см. выше) и нет отката на git-корень — хук работает в каталоге
# ЧУЖОГО проекта, и его git-корень к ClaudSoul отношения не имеет.
# Кандидат годен, только если он АБСОЛЮТНЫЙ и существует. Относительный путь здесь
# страшнее отсутствующего: `.` проходит проверку `-d` из любого каталога, и хуки начинают
# читать BACKLOG.md и domains/ того проекта, где сейчас стоит агент, считая их своими.
# Записать туда `.` умеет сам установщик: `install.sh:21` берёт позиционный аргумент
# дословно, без приведения к абсолютному, и `install.sh:113` пишет его в указатель как есть.
_cs_absdir() { case "$1" in /*) [ -d "$1" ] ;; *) return 1 ;; esac; }

if [ -z "${CLAUDSOUL_ROOT:-}" ]; then
    # 1. CLAUDSOUL_REPO — то же имя, которым override называют пользователю
    #    (bin/resolve-claudsoul-repo.sh:32, skills/enrich/SKILL.md). Без этого шага человек
    #    выполнял названную ему инструкцию, скиллы чинились, а хуки оставались в прежней
    #    тишине — тот же отказ по второму входу.
    if [ -n "${CLAUDSOUL_REPO:-}" ] && _cs_absdir "$CLAUDSOUL_REPO"; then
        CLAUDSOUL_ROOT="$CLAUDSOUL_REPO"
    # 2. Файл-указатель, который пишет install.sh на шаге 0.
    elif [ -f "$HOME/.claude/claudsoul-repo" ]; then
        # `|| true` обязателен: у 18 хуков (на 30 августа 2026), источающих эту библиотеку, объявлен `set -e`,
        # и на нечитаемом указателе (chmod 000, чужой владелец) статус присваивания равен
        # единице — оболочка выходит ПРЯМО ЗДЕСЬ. Вывод при этом пуст: stderr `cat` заглушён,
        # а `set -e` молчит по устройству. Хук умирает при источении библиотеки, не начав
        # работу и ничего не сказав. Резолв дефолта не может быть причиной отказа: это
        # последняя ступень отката, а не операция, которой позволено падать.
        _cs_pointer=$(cat "$HOME/.claude/claudsoul-repo" 2>/dev/null) || true
        _cs_absdir "${_cs_pointer:-}" && CLAUDSOUL_ROOT="$_cs_pointer" || true
        unset _cs_pointer
    fi
fi
: "${CLAUDSOUL_ROOT:=$HOME/My Project/ClaudSoul}"
: "${LESSONS_DIR:=$HOME/.claude/global-lessons}"   # база знаний (была под 3 именами: KNOWLEDGE_DIR/LESSONS_DIR/GLOBAL_LESSONS)
: "${STATE_DIR:=$HOME/.claude/hooks/state}"         # состояние хуков (003e); `:=` уважает env/тест — не перезаписывает заданное

# Единый walk-up для определения корня проекта. До 003b было: каноничная версия
# в session-registry-lib (_sr_detect_project, без параметра), а knowledge-activator
# и session-start использовали сырой cwd без walk-up (F13) — из подпапки проекта
# не находили SESSION.md/CLAUDE.md.
find_project_root() {
    local dir="${1:-$PWD}"
    local start="$dir"
    # Условие выхода — «подъём перестал двигать путь», а не только «дошли до /».
    # На относительном входе dirname упирается в точку и возвращает её же: `sub/deeper`
    # → `sub` → `.` → `.` → …, и цикл не кончается никогда. Хук при этом висит в
    # PreToolUse, то есть вешает сессию целиком. Вход берётся из payload
    # (knowledge-activator.sh:643 — `${CWD:-$PWD}` без проверки на абсолютность),
    # то есть приходит извне и на форму его никто не влияет.
    local prev=""
    while [ -n "$dir" ] && [ "$dir" != "/" ] && [ "$dir" != "$prev" ]; do
        # `.git` — каталог в обычном клоне и ФАЙЛ («gitdir: …») в worktree и подмодуле.
        # Проверка только на каталог перешагивала корень worktree и отдавала родительский
        # репозиторий: хуки писали SESSION.md и проектную память соседнего проекта, молча.
        # Worktree здесь штатный режим — инструмент Agent умеет isolation:"worktree".
        if [ -e "$dir/.git" ] || [ -f "$dir/CLAUDE.md" ]; then
            printf '%s' "$dir"; return 0
        fi
        prev="$dir"
        dir="$(dirname "$dir")"
    done
    printf '%s' "$start"
}

# Единый парсинг session_id из payload-JSON хука (F3). Унифицирует ТОЛЬКО парсинг —
# fallback передаётся аргументом, поэтому контракт каждого хука сохраняется:
#   resolve_session_id "$INPUT"        → SID или "unknown" (для хуков, что продолжают)
#   resolve_session_id "$INPUT" ""     → SID или "" (для хуков, что делают exit при пустом)
resolve_session_id() {
    # ${2-unknown} (без `:`) — fallback по умолчанию только когда аргумент НЕ передан;
    # явный пустой `""` сохраняется (контракт exit-style хуков).
    local input="$1" fallback="${2-unknown}" sid
    sid=$(printf '%s' "$input" | jq -r '.session_id // empty' 2>/dev/null)
    printf '%s' "${sid:-$fallback}"
}
