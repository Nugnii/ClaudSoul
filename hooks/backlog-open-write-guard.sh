# унёс D1111 без свидетельства, и строка переезжала хвостом последнего пункта. Признак с одним последствием: строка
# пункта, встречавшаяся только в нём, переехала в блок другого пункта (подробнее — у разбора ниже). Блоки — по устройству `backlog_item_block` (те же выражения библиотеки, заборы кода сняты, заголовок своего
# уровня и выше кончает блок); сравниваются непустые строки продолжения, заголовок пункта (метка) — нет.
_blocks_of() {   # <файл> → «ID␟строка» на каждую строку продолжения пункта; «ID␟\001H» — заголовок пункта
    [ -f "$1" ] || return 0
    backlog_strip_fenced < "$1" 2>/dev/null | awk -v ire="$(backlog_item_re)" -v tok="$BACKLOG_ID_TOKEN_RE" -v us="$_us" '
        function idof(s) { gsub(/\*/, "", s); return (match(s, tok) ? substr(s, RSTART, RLENGTH) : "") }
        $0 ~ ire { cur = idof($0); lvl = (match($0, /^#+/) ? RLENGTH : 0); if (cur != "") print cur us "\001H"; next }
        cur != "" && /^#+[[:space:]]/ { match($0, /^#+/); if (lvl == 0 || RLENGTH <= lvl) cur = "" }
        cur != "" { print cur us $0 }'
}
