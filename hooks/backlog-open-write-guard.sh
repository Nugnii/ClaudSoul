ROOTLESS=""; ROOTBAD=""
if [ -f "$ROOT_DIR/ROOTS.md" ]; then
    _old_ids=$(backlog_ids "$OLDF" 2>/dev/null)
    # Карточка — заголовок той формы, что знает владелец карты (`HEAD`, scripts/root-map.py): «## R<N> — …». Своя
    # копия `^## R[0-9]+` расходилась с ним в обе стороны (волна проверки D1019): «##  R7 — …» владелец видит, а
    # страж — нет; «## R7 - …» страж видел, а владелец, и с ним страж слияния, — нет.
    _cards=$(sed -nE 's/^##[[:space:]]+(R[0-9]+)[[:space:]]+—[[:space:]].*/\1/p' "$ROOT_DIR/ROOTS.md" 2>/dev/null)
    while IFS="$_us" read -r id mark kind q root cmd chk; do
