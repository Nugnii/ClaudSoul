# её заменяет показание при закрытии, и у нового пункта она та же дословно, даже когда открытый пункт в файле один.
RET = "**Проверка возврата:** решение — пункт описывает наличный дефект, возврат наступает, когда за него берутся."
cnt = {}
for x, ol in o.items():
