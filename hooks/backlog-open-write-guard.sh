#!/usr/bin/env bash
# backlog-open-write-guard.sh — PreToolUse[Edit|Write|MultiEdit] на BACKLOG.md: открытый пункт с зелёной или отсутствующей «Проверкой» не записывается.
# en: PreToolUse on BACKLOG.md edits — refuses to write an OPEN debt item whose check is green or missing at write time.
#
# Результат: у открытого пункта долга красная исполнимая «Проверка» появляется В МОМЕНТ записи — зелёная, отсутствующая либо не разбираемая оболочкой отбивается отказом с именем пункта; незапустившаяся (код 126/127) называется контекстом с именем пункта и словом «неисполнима» и ложится в журнал видом unrunnable; новый открытый пункт рядом с картой корней (ROOTS.md) без строки «**Корень.**» отбивается с именем и ложится в журнал видом rootless; пункт, ставший ☑ этой правкой, чьё закрытие ждёт финального скептика (`backlog_needs_skeptic`: защитный слой hooks/ назван, строки «**Скептик.** opus, …» нет), отбивается с именем и ложится в журнал видом noskeptic (D1137); пункт, ставший ☑ этой правкой, чей абзац «Скептик.» называет находку H/M без строки «**Происхождение.**», сверенной с git и повтором поиска братьев (`hooks/lib/skeptic_origin.py`), отбивается с именем и находкой и ложится в журнал видом noorigin, а «не подтвердилась: <довод>» проходит видом disowned (D1305)
# Проверка результата: bash hooks/tests/test_backlog_open_write_guard.sh даёт 0
#
# Зачем (D264, уровень 4 по ИЗМЕРЕННОЙ точности). Контракт долга: «Проверка» открытого пункта
# красна и исполнима — зелёная значит «закрывай с показанием» либо «команда не о дефекте»,
# отсутствующая — «критерия нет». Страж границы хода `completion-gate` называл это ПОСЛЕ
# записи, и с 3 сентября 2026 копил исходы своих срабатываний (`state/cg-open-fired.jsonl`).
# Замер 13 сентября 2026: 23 срабатывания с исходом — confirmed 18, rewritten 5 (команда
# переписана по собственному предписанию канала), ложных 0. Порог ADR-015 — ложных ниже
# десятой части при n ≥ 20 — пройден, и признак получает отказ в момент записи.
#
# ПРИЗНАК С ОДНИМ ПОСЛЕДСТВИЕМ: в ЗАПИСЫВАЕМОМ тексте есть открытый пункт (☐/◐), чей блок
# «Проверки» НОВ или ИЗМЕНЁН относительно файла на диске, и команда отвечает 0 либо строки
# нет. Продолжение вызова имело бы ровно одно последствие — в долг лёг бы открытый пункт без
# красного критерия. Пункты, чья «Проверка» не менялась, здесь не исполняются: их судит
# completion-gate по сроку, а исполнять весь бэклог на каждой правке значило бы платить
# десятками команд за строку.
#
# НЕИСПОЛНИМАЯ — НЕ КРАСНАЯ (17 сентября 2026, D432, корень R6). Контракт выше требовал
# «красна И ИСПОЛНИМА», а судилась только первая половина: всё, что не 0 и не 124, проходило
# красным. «Команда честно сказала „нет“» и «команду не удалось запустить» шли одним каналом
# — кодом возврата `bash -c`, — а красное у открытого пункта НОРМА, поэтому слитое состояние
# ещё и МОЛЧАЛО: в долг ложился пункт, чей критерий не исполнился ни разу, и следа не было.
# Теперь состояния разведены, а УРОВЕНЬ у двух видов разный — по замеру, а не по тяжести
# (ADR-015):
#  · `syntax` — ОТКАЗ, до запуска, тем же `bash -n -c`, что у брата-здоровяка `completion-gate`
#    (после запуска пришёл бы rc=2, неотличимый от честного «нет»). Последствие одно ПО
#    ПОСТРОЕНИЮ: строка, которую оболочка не разбирает, не исполнится ни в каком состоянии
#    мира. В замере D264 вид есть: 1 срабатывание из 23, исход confirmed.
#  · `unrunnable` (коды 126/127, после запуска) — КОНТЕКСТ с именем пункта и словом
#    «неисполнима» и строка журнала, как у `timeout`; запись бэклога ПРОХОДИТ. Отказом вид не
#    стал по трём измеренным причинам.
#    (1) В журнале исходов `cg-open-fired` его нет вовсе (n=0): `completion-gate.sh:338-346` с
#    2 сентября считает rc=127 у открытого пункта законным и на нём не срабатывает, а ADR-015
#    при знаменателе меньше двадцати решений не принимает.
#    (2) По истории BACKLOG.md (522 коммита, 227 записей новой или изменённой «Проверки»
#    открытого пункта; существование названного файла сверено с деревом того же коммита —
#    статическая нижняя граница) голых `bash SCRIPT` при ещё не написанном SCRIPT — 16, все до
#    6 сентября. У 9 из 16 скрипт позже появился под тем же именем — порядок «сперва
#    „Проверка“, потом скрипт» сработал; у 7 из 16 не появился НИКОГДА, и команда прожила
#    неисполнимой до закрытия пункта другой командой (D200–D203, D247, D253, D256). Под одним
#    признаком две формы с разными последствиями — такой признак обязан оставаться подсказкой.
#    (3) Правило зелёной стороны (D405) порядок «сперва „Проверка“» не запрещает: фикстура
#    `green_<ID>` вправе сама положить недостающий скрипт в свой `CLAUDSOUL_REPO`, и команда
#    под ней позеленеет. Первая редакция этой правки (тот же день) ставила виду отказ и
#    утверждала обратное — «под фикстурой позеленеть не может»; утверждение неверно, отказ
#    снят до замера.
#    Решение 2 сентября тем самым НЕ отменяется: страж говорит лишь, что красной команда не
#    доказана, и называет два выхода с честным кодом 1 — сперва написать скрипт либо объявить
#    отсутствие в самой команде, `test -f SCRIPT || exit 1; …` (форма коммита 968237e).
# Ошибок синтаксиса в истории 0: все 246 команд выборки (227 «Проверок» и 19 условий
# возврата) проходят `bash -n`. Со дня заведения стража (13 сентября) — 40 записей, кодов
# 126/127 — 0; живой долг 17 сентября: 19 открытых, кодов 126/127 — 0.
# ПРЕДЕЛ (назван, не закрыт). Страж видит «не запустилась» только там, где код 126/127
# ДОХОДИТ до него кодом всей строки. То же состояние мира «скрипта или предмета нет»
# маскируется и проходит красным молча: конвейер (`bash НЕТ.sh 2>&1 | tail -1 | grep -q …`),
# цепочка (`nope_cmd; false`, `bash НЕТ.sh || exit 1`), подстановка (`[ "$(nope_cmd)" = ok ]`),
# чужой интерпретатор (`python3 НЕТ.py`, `node НЕТ.js` — свой код, не 127), `grep` по
# отсутствующему файлу (код 2), `. НЕТ.sh`. По той же истории из 26 записей «Проверки» со
# ссылкой на отсутствовавший в том же коммите файл страж увидел бы 16 голых; 4 объявляют
# отсутствие честно (`test -f` / `[ -f ]`), 5 маскируют (`grep` по файлу — D264 дважды,
# `grep … && bash` — D282 дважды, конвейер — D380), 1 называет несуществующее имя намеренно
# (D304). Такой же предел называет у себя брат (`completion-gate.sh:341-344`). Код 127 ИЗНУТРИ
# живого скрипта (зовёт отсутствующий на этой машине инструмент) от «скрипта нет» неотличим и
# называется тоже — исход и там неизвестен.
# Условие снятия предела маскировки: прибор, судящий ИСПОЛНЕННОСТЬ предмета (след запуска
# названного скрипта), а не код строки; до него различает только объявление в самой команде.
# Условие ПОДЪЁМА вида `unrunnable` до отказа — по ADR-015: двадцать исходов в журнале при
# ложных ниже десятой части. Названное препятствие: семейства `backlog-open-write` нет в
# `THROTTLE_KEEP_FAMILIES` (`throttle-lib.sh:86`), журнал стража живёт три дня — копить
# двадцать ему сегодня не на чем.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ. Команда, не уложившаяся в бюджет (`OPEN_WRITE_TIMEOUT`, 20 с;
# ограничитель — `timeout-lib.sh`, общий с раннером и стражем возврата), зелёной не доказана
# и не отбивается — пишется в журнал видом `timeout` и называется контекстом. Правку бэклога
# командой (python-heredoc, sed) страж судит задним числом: его зовёт `bash-write-dispatch.sh`
# с `hook_event_name: PostToolUse` (D492), отказ вырождается в уведомление, а прежней редакцией
# служит последняя закоммиченная. Цена этого пути растёт с незакоммиченными изменёнными пунктами:
# каждая новая версия файла заново исполняет их «Проверки», коммит её сбрасывает; условие
# снятия — прежняя редакция, сохранённая при прошлой подаче. Без jq, python3 или библиотек
# страж молчит и выходит с 0: чужой проект, а не отказ.
#
# Журнал: `state/backlog-open-write-fired-<SID>.jsonl` — семейство `*-fired-*`, читатель у
# него уже есть (`scripts/signal-precision.sh` выводит универсум правилом).
set -uo pipefail
command -v jq >/dev/null 2>&1 || exit 0
command -v python3 >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null) || exit 0
[ -n "$INPUT" ] || exit 0
TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
case "$TOOL" in Edit|Write|MultiEdit) ;; *) exit 0 ;; esac
FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)
# Бэклог узнаётся ФАЙЛОМ, а не формой имени (D1141, корень R3): на ФС без различия регистра (macOS) `…/backlog.md` — тот
# же BACKLOG.md, и литерал имени пропускал правку молча. Иное имя — бэклог, только если это тот же файл, что BACKLOG.md
# рядом (`-ef`: устройство и inode); на ФС с различием регистра `backlog.md` — другой файл и не судится. Дальше страж
# зовёт файл каноническим именем, а прежнюю редакцию из git ищет и под исходным: в дереве git регистр различается всегда,
# и бэклог, записанный туда как `backlog.md`, под `HEAD:./BACKLOG.md` не находится (скептик D1141, L2).
# Пределы: ссылка на бэклог под иным именем в ДРУГОМ каталоге не узнаётся; новый файл под иным именем, пока BACKLOG.md
# рядом нет, не судится (L3, как и до D1141).
_BL_GIVEN=""
if [ "$(basename "$FILE" 2>/dev/null)" != "BACKLOG.md" ]; then
    [ -e "$FILE" ] && [ "$FILE" -ef "$(dirname "$FILE")/BACKLOG.md" ] || exit 0
    _BL_GIVEN=$(basename "$FILE")
    FILE="$(dirname "$FILE")/BACKLOG.md"
fi

_HD=$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)
PATHS_LIB="${PATHS_LIB:-$_HD/paths-lib.sh}"
[ -f "$PATHS_LIB" ] || PATHS_LIB="$HOME/.claude/hooks/paths-lib.sh"
# shellcheck source=/dev/null
[ -f "$PATHS_LIB" ] && . "$PATHS_LIB"
: "${STATE_DIR:=$HOME/.claude/hooks/state}"
BL_LIB="${BL_LIB:-$_HD/backlog-lib.sh}"
[ -f "$BL_LIB" ] || BL_LIB="$HOME/.claude/hooks/backlog-lib.sh"
# shellcheck source=/dev/null
{ [ -f "$BL_LIB" ] && . "$BL_LIB"; } || exit 0
command -v backlog_open_items >/dev/null 2>&1 || exit 0
# Старая библиотека без перевода с сохранением табуляции в «Проверке» — прежний перевод.
command -v backlog_open_items_us >/dev/null 2>&1 || backlog_open_items_us() {
    backlog_open_items "$1" | awk -F'\t' 'BEGIN { OFS = "\037" } { $1 = $1; print }'; }
TO_LIB="${TIMEOUT_LIB:-$_HD/timeout-lib.sh}"
[ -f "$TO_LIB" ] || TO_LIB="$HOME/.claude/hooks/timeout-lib.sh"
# shellcheck source=/dev/null
{ [ -f "$TO_LIB" ] && . "$TO_LIB"; } || exit 0
THR_LIB="${THROTTLE_LIB:-$_HD/throttle-lib.sh}"
[ -f "$THR_LIB" ] || THR_LIB="$HOME/.claude/hooks/throttle-lib.sh"
# shellcheck source=/dev/null
[ -f "$THR_LIB" ] && . "$THR_LIB"
SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)
EVENT=$(printf '%s' "$INPUT" | jq -r '.hook_event_name // ""' 2>/dev/null)
BUDGET="${OPEN_WRITE_TIMEOUT:-20}"

# Новый текст файла — из payload: Write несёт его целиком, Edit/MultiEdit — правками к диску.
# Правка, чей old_string на диске не найден, не пройдёт и без нас — молчим.
# Шаблоном внутри унаследованного TMPDIR (D1198, скептик M2): голый `mktemp -d` на macOS кладёт каталог в системный
# при любом TMPDIR, и рамка, давшая стражу свой TMPDIR, его бы не увидела.
TMPD=$(mktemp -d "${TMPDIR:-/tmp}/owg.XXXXXX" 2>/dev/null) || exit 0
trap 'rm -rf "$TMPD"' EXIT
NEWF="$TMPD/new.md"
printf '%s' "$INPUT" | FILE="$FILE" python3 -c '
import json, os, sys
d = json.load(sys.stdin); ti = d.get("tool_input") or {}; tool = d.get("tool_name")
path = os.environ["FILE"]
try:
    old = open(path, encoding="utf-8").read()
except OSError:
    old = ""
if tool == "Write":
    new = ti.get("content") or ""
else:
    edits = ti.get("edits") if tool == "MultiEdit" else [ti]
    new = old
    for e in edits or []:
        o = e.get("old_string") or ""; n = e.get("new_string") or ""
        if o == "":
            continue
        if o not in new:
            sys.exit(3)
        new = new.replace(o, n) if e.get("replace_all") else new.replace(o, n, 1)
sys.stdout.write(new)' > "$NEWF" 2>/dev/null || exit 0

_us=$(printf '\037')
# Прежняя редакция. На пути инструмента это диск: страж стоит ДО записи. Подача диспетчера идёт
# ПОСЛЕ записи командой (D492) — диск уже несёт новую редакцию, и прежней служит последняя
# закоммиченная; файла в ней нет — нов весь.
OLDF="$FILE"
if [ "$EVENT" = PostToolUse ]; then
    OLDF="$TMPD/old.md"
    git -C "$(dirname "$FILE")" show "HEAD:./$(basename "$FILE")" > "$OLDF" 2>/dev/null \
        || { [ -n "$_BL_GIVEN" ] && git -C "$(dirname "$FILE")" show "HEAD:./$_BL_GIVEN" > "$OLDF" 2>/dev/null; } \
        || : > "$OLDF"
fi
if [ -f "$OLDF" ]; then
    backlog_open_items_us "$OLDF" 2>/dev/null > "$TMPD/old.tsv"
else
    : > "$TMPD/old.tsv"
fi
backlog_open_items_us "$NEWF" 2>/dev/null > "$TMPD/new.tsv"
ROOT_DIR=$(cd "$(dirname "$FILE")" 2>/dev/null && pwd -P)
if command -v throttle_file >/dev/null 2>&1; then
    FIRED=$(throttle_file "$STATE_DIR" backlog-open-write "$SID")
else
    FIRED="$STATE_DIR/backlog-open-write-fired-${SID}.jsonl"
fi
mkdir -p "$STATE_DIR" 2>/dev/null
_journal() {  # <id> <вид>
    if command -v throttle_mark >/dev/null 2>&1; then
        throttle_mark "$FIRED" "${1}|${2}" item "$1" kind "$2" path "$FILE"
    else
        printf '{"ts":"%s","key":"%s|%s","item":"%s","kind":"%s","path":"%s"}\n' \
            "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$1" "$2" "$1" "$2" "$FILE" >> "$FIRED" 2>/dev/null
    fi
}
DENY=""; TIMED=""; UNRUN=""; RINGED=""
while IFS="$_us" read -r id mark kind q root cmd chk; do
    [ -n "$id" ] || continue
    _old=$(awk -F"$_us" -v i="$id" '$1 == i { print "y" $7; exit }' "$TMPD/old.tsv" 2>/dev/null)
    [ "$_old" = "y$chk" ] && continue        # «Проверка» этого пункта не менялась — не наш предмет
    if [ -z "$chk" ]; then
        DENY="$DENY $id (нет строки «Проверка»)"; _journal "$id" missing; continue
    fi
    # Неисполнимость отделяется от красной дважды (D432, довод и замер — в шапке): синтаксис
    # ДО запуска (`bash -n` не исполняет ничего; иначе пришёл бы rc=2, неотличимый от честного
    # отказа команды) — отказ; «не запускается / команды нет» — кодами 126/127 после, и это
    # КОНТЕКСТ, а не отказ: у вида нет замера точности (ADR-015), запись проходит.
    if ! bash -n -c "$chk" >/dev/null 2>&1; then
        DENY="$DENY $id (неисполнима: синтаксис оболочки)"; _journal "$id" syntax; continue
    fi
    # Ограда кольца (D503, ключ — backlog-lib): «Проверка», уже исполняющаяся выше по дереву
    # процессов, второй раз не запускается, вложенность глубже предела — тоже; исход неизвестен,
    # запись не отбивается.
    if command -v backlog_cmd_blocked >/dev/null 2>&1 && backlog_cmd_blocked "$FILE" check "$id" "$chk" >/dev/null; then
        RINGED="$RINGED $id"; _journal "$id" ring; continue
    fi
    # Свой TMPDIR на каждую «Проверку» (D1198) — как у `scripts/backlog-return-check.sh`: запись BACKLOG.md исполняет
    # «Проверки» новых пунктов, и всё, что команда не убрала, оставалось в системном TMPDIR; снимается и после срока.
    # Внутри `$TMPD`: его снимает ловушка выхода стража и при сигнале (скептик D1198, L6).
    _ct=$(mktemp -d "$TMPD/c.XXXXXX" 2>/dev/null) || _ct=""
    # Подмена `mktemp` в нём (D1198): голая форма на macOS иначе уходит мимо TMPDIR.
    _cs=""; [ -n "$_ct" ] && command -v cmd_tmpdir_shim >/dev/null 2>&1 && cmd_tmpdir_shim "$_ct" && _cs="$_ct/.bin"
    ( cd "$ROOT_DIR" && { ! command -v backlog_cmd_env >/dev/null 2>&1 \
          || export BACKLOG_CMD_RUNNING="$(backlog_cmd_env "$FILE" check "$id" "$chk")"; } \
      && { [ -z "$_ct" ] || export TMPDIR="$_ct"; } && { [ -z "$_cs" ] || export PATH="$_cs:$PATH"; } \
      && CLAUDSOUL_REPO="${CLAUDSOUL_REPO:-$ROOT_DIR}" run_with_timeout "$BUDGET" bash -c "$chk" ) >/dev/null 2>&1 </dev/null
    _rc=$?
    [ -n "$_ct" ] && rm -rf "$_ct"
    case "$_rc" in
        0)   DENY="$DENY $id (зелёная)"; _journal "$id" green ;;
        124) TIMED="$TIMED $id"; _journal "$id" timeout ;;
        126|127) UNRUN="$UNRUN $id (неисполнима: rc=${_rc})"; _journal "$id" unrunnable ;;
        *)   ;;
    esac
done < "$TMPD/new.tsv"

# НОВЫЙ ПУНКТ РОЖДАЕТСЯ С КОРНЕМ (решение владельца 9 октября 2026). Рядом с бэклогом лежит карта
# корней (ROOTS.md) — значит открытый пункт, которого не было в прежней редакции, несёт строку
# `**Корень.** R<N>` либо `**Корень.** не дефект — <причина>`. Признак — контракт формы с одним
# последствием: пункт без корня не пройдёт страж слияния (`merge-root-gate.sh`), и узнаётся это
# у слияния, а не при рождении. Здесь, а не отдельным хуком: прежняя и новая редакции, путь
# инструмента и подача задним числом (`bash-write-dispatch.sh`) уже собраны этим стражем, третья
# сборка того же текста была бы копией. Корень берётся у владельца разбора пункта
