#!/usr/bin/env bash
# doc-impact-check.sh — PreToolUse[Bash] на `git commit`: называет документы, описывающие изменённое, и требует решения по документу состояния при правке поведения.
# en: PreToolUse[Bash] on `git commit`: names describing documents; demands a decision on state docs when behaviour changed.
#
# Зачем. Правило «изменил — проверь зависимости и обнови описания» держалось на
# внимательности и не исполнялось: 28 августа 2026 три утверждения в справочниках и
# мастер-копии правил разошлись с деревом, и нашёл это владелец вопросом, а не механизм.
# Полный аудит стоит часы работы агента — поэтому проверка АДРЕСНАЯ: из изменённых файлов
# берётся короткий список, а не предложение обойти дерево.
#
# Почему глубина 0, а не «все зависимые». Замер 28 августа 2026 по 151 механизму:
# документы, описывающие сам изменённый файл, — медиана 2 на изменение; документы всего,
# что от него зависит, — медиана 21. Второе и есть «проверь всё», только автоматическое:
# такой список не читают. Поэтому зависимые называются ИМЕНАМИ (медиана 1), а судить,
# задело ли их описания, — работа для головы.
#
# Уровень — инжект, не отказ, и это ИЗМЕРЕННОЕ решение, а не осторожность: документ,
# упоминающий механизм, не обязан меняться при каждой правке (починка опечатки поведение
# не меняет). Точность отказа здесь не замерена, а отказ без замера — ложный отказ,
# который обходят не думая (case-2026-08-28-enforcement-is-a-property-of-consequence).
#
# Opt-in по наличию индекса: нет `.claude-docs/dep-index.tsv` — хук молчит. Так он не
# кричит в чужом проекте, где документации ещё нет.
#
# Input  (stdin): {tool_name, tool_input, cwd, session_id}
# Output (stdout): {hookSpecificOutput:{additionalContext}} либо пусто
# Exit:  always 0.

set -uo pipefail

SCOPE_LIB="${SCOPE_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/command-scope-lib.sh}"
[ -f "$SCOPE_LIB" ] || SCOPE_LIB="$HOME/.claude/hooks/command-scope-lib.sh"
if [ -f "$SCOPE_LIB" ]; then
    # shellcheck source=/dev/null
    source "$SCOPE_LIB"
else
    is_git_commit() { grep -qE 'git[[:space:]]+commit' <<< "${1:-}"; }
fi
# Библиотека на месте, но без функций (пуста, обрезана) — те же запасные, а не «command not found» в выводе коммита (D1086).
command -v is_git_commit >/dev/null 2>&1 || is_git_commit() { grep -qE 'git[[:space:]]+commit' <<< "${1:-}"; }
command -v executable_part >/dev/null 2>&1 || executable_part() { printf '%s' "${1:-}"; }   # без разбора — сырой текст
command -v executable_commit_dir >/dev/null 2>&1 || executable_commit_dir() { return 2; }    # без разбора — папка сессии

PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
if [ -f "$PATHS_LIB" ]; then source "$PATHS_LIB"; else : "${STATE_DIR:=$HOME/.claude/hooks/state}"; fi
mkdir -p "$STATE_DIR" 2>/dev/null

command -v jq >/dev/null 2>&1 || exit 0
command -v git >/dev/null 2>&1 || exit 0
command -v python3 >/dev/null 2>&1 || exit 0

# ЛОВУШКИ GIT (D1022), их зовёт `commit-trap.sh` в корне рабочего дерева коммита с его индексом (GIT_INDEX_FILE):
#   --pre-commit         — пересборка учёта в индекс коммита: git строит дерево после pre-commit, и только здесь
#                          производный факт ещё входит в этот же коммит;
#   --commit-msg <файл>  — отчёт о документах и решение `doc-state:`, которое читается из готового сообщения (в файле
#                          `-F` и после редактора его текст команды не нёс).
# Файлы — индекс коммита, а не объединение с рабочим деревом; подсказки — в stderr. На PreToolUse страж молчит там, где
# стоят обе ловушки: по тексту команды он судил папку сессии и клал учёт в её индекс, куда коммит не шёл.
TRAP=""; MSGF=/dev/null
case "${1:-}" in
    --commit-msg) TRAP=msg; MSGF="${2:-/dev/null}" ;;
    --pre-commit) TRAP=pre ;;
esac
if [ -n "$TRAP" ]; then
    COMMAND=""; SID="git-trap-$(date '+%Y%m%d')"
    CWD=$(project_git -C "$PWD" rev-parse --show-toplevel 2>/dev/null) || exit 0   # git зовёт ловушку в корне дерева коммита
else
    INPUT=$(cat); [ -n "$INPUT" ] || exit 0
    [ "$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)" = "Bash" ] || exit 0
    COMMAND=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
    is_git_commit "$COMMAND" || exit 0
    CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null); [ -n "$CWD" ] || CWD="$PWD"
    # Каталог КОММИТА — у разбора команды (`cd` и `-C`), а не папка сессии: `cd <другой> && git commit` в обход ловушки
    # клал учёт в индекс папки сессии (D1278). Разбор не ответил (каталог через переменную) — папка сессии, как прежде.
    _CD=$(executable_commit_dir "$CWD" "$COMMAND") && CWD="$_CD"
    SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)
fi
ROOT=$(git -C "$CWD" rev-parse --show-toplevel 2>/dev/null) || exit 0
[ -f "$ROOT/.claude-docs/dep-index.tsv" ] || exit 0
# Прибор проекта исполняется только в рабочей копии репозитория владельца (D518, брат D517): файл с этим именем в
# чужой папке — чужой код, и хук исполнял его на `git commit` агента. paths-lib не нашёлся — функции нет, ответ «нет».
# В ЛЮБОМ ДРУГОМ ПРОЕКТЕ С ОПИСАНИЕМ (`.claude-docs/project-map.json`, шаг 1г, D1089) учёт — его данные, а прибор —
# ClaudSoul (`CLAUDSOUL_ROOT`): код проекта не исполняется вовсе. Без описания — молчим: карты там нет.
# Git ниже идёт через `project_git` (программы из настроек чужого дерева погашены, D515), а diff с содержимым — ещё и
# без внешнего diff и textconv (D517): их агентский `git commit` не исполняет, и хук не добавляет новой поверхности.
if project_owner_copy "$ROOT" "$CWD" 2>/dev/null; then
    INDEXER="${DEP_INDEX_TOOL:-$ROOT/scripts/dep-index.py}"; IX_CMD="python3 scripts/dep-index.py"
else
    [ -f "$ROOT/.claude-docs/project-map.json" ] && [ -n "${CLAUDSOUL_ROOT:-}" ] || exit 0
    command -v project_git >/dev/null 2>&1 || exit 0
    INDEXER="${DEP_INDEX_TOOL:-$CLAUDSOUL_ROOT/scripts/dep-index.py}"; IX_CMD="python3 \"$INDEXER\" --repo \"$ROOT\""
fi
[ -f "$INDEXER" ] || exit 0
# Молчит по одной `commit-msg`: отчёт даёт она; без своей `pre-commit` учёт не пересобирается вовсе, и отчёт ловушки
# называет команду пересборки (скептик D1022: при чужой pre-commit отчёт выходил дважды, а учёт ложился в индекс папки
# сессии).
[ -z "$TRAP" ] && command -v project_commit_trap >/dev/null 2>&1 \
    && project_commit_trap "$ROOT" commit-msg "$COMMAND" && exit 0

# Нулевой разделитель на всём пути: `xargs` без `-0` делит имя по ПРОБЕЛУ, и файл
# «hooks/data lib.sh» приходит в индексатор двумя кусками — свой документ не назван, зато
# объявлен новым механизмом несуществующий «lib.sh». Поймано противником 28 августа 2026;
# в дереве путей с пробелом сейчас ноль, но запрета на них нет.
# `git commit -am` кладёт файлы в индекс только В МОМЕНТ коммита: до него `--cached` пуст,
# и страж молчал целиком. Поэтому берётся объединение индекса и рабочего дерева — так же
# делают соседние хуки того же события (`changelog-reminder`, `docs-family-check`).
# Поймано противником 28 августа 2026.
# `--no-renames`: при переименовании до владельца перечня доходят ОБА пути — прежний остаётся в колонках учёта, и строки,
# которые его называют, иначе не пересобрать (D1076, скептик b4c40167, А3).
STAGED=$( { project_git -C "$ROOT" diff --cached --name-only --no-renames -z 2>/dev/null;
            [ -n "$TRAP" ] || project_git -C "$ROOT" diff --name-only -z 2>/dev/null; } | tr '\0' '\n' | sort -u)
[ -n "$STAGED" ] || exit 0

# Троттл по СОДЕРЖИМОМУ правки, а не по набору имён. Ключ из одних имён глушил стража
# на весь остаток сессии после первого же коммита того же файла: правка комментария
# съедала право высказаться про следующую правку, добавившую публичное имя. При дисциплине
# «одно изменение — один коммит» набор имён повторяется постоянно. Поймано противником
# 28 августа 2026.
# Учёт в ключ не входит: его кладёт в индекс сам хук, и после своей же пересборки тот же набор правок звучал заново
# (D1082: нога T6 держалась тем, что T5 отказывал в пересборке).
KEY=$( { project_git -C "$ROOT" diff --no-ext-diff --no-textconv --cached -- . ':(exclude).claude-docs/dep-index.tsv' 2>/dev/null
         project_git -C "$ROOT" diff --no-ext-diff --no-textconv -- . ':(exclude).claude-docs/dep-index.tsv' 2>/dev/null; } \
    | (command -v md5sum >/dev/null 2>&1 && md5sum || md5) 2>/dev/null | awk '{print $1}')
THROTTLE="$STATE_DIR/doc-impact-${SID}.txt"
if [ -z "$TRAP" ] && [ -f "$THROTTLE" ] && grep -qxF "$KEY" "$THROTTLE" 2>/dev/null; then exit 0; fi

# ─── УЧЁТ ПЕРЕСОБИРАЕТСЯ САМ, А НЕ ПОРУЧАЕТСЯ ЧИТАТЕЛЮ (14 сентября 2026) ──────────────
# Сообщение хука везло ДВЕ вещи с разными последствиями — корень R6, два состояния мира по
# одному проводу. «Описывают изменённое, но не тронуты» — СУЖДЕНИЕ: документ не обязан
# меняться от каждой правки, решать может только голова, и уровень инжекта здесь ИЗМЕРЕН
# (см. шапку). «Новые публичные имена», «новые механизмы без строки», «строки учёта устарели»
# — не суждение, а ПРОИЗВОДНЫЙ ФАКТ: у индекса нет исхода «не задето», он либо совпадает с
# деревом, либо нет. Замер выбирал уровень для ПЕРВОГО смысла и был перенесён на второй без
# проверки — область решения шире его предмета, род L собственного реестра.
# ЦЕНА ИЗМЕРЕНА: за 30 дней 1017 коммитов, индекс тронут в 352, и ПЯТЬДЕСЯТ коммитов чинили
# ТОЛЬКО его — полсотни отдельных заходов после напоминания. Выгрузка индекса — 0,13 с на всё
# дерево, перечень `--stale-by` — 0,05–1,7 с, пересборка названных строк — секунды, полная —
# 16–18 с (замеры 25 октября 2026, D1082, D1083), так что довод «дорого» не держится.
INDEX_REL=".claude-docs/dep-index.tsv"
REBUILT=0; EXPORT_FAILED=0
# КОММИТ ПУТЯМИ (`git commit <пути>`) git собирает во ВРЕМЕННОМ индексе, а основной после коммита пишет таким, каким
# подготовил его до ловушки: учёт, добавленный сюда, вошёл бы в коммит, а основной индекс сохранил бы прежний — и
# следующий коммит молча откатил бы свежий учёт (скептик D1022, воспроизведено). Узнаётся по индексу коммита: не
# основной и не его замок (`-a` и `-i` идут через замок основного); путь основного спрашивается без GIT_INDEX_FILE —
# с ним `--git-path index` отвечает самим индексом коммита. Тогда учёт не пересобирается, а называется.
_abs() { (cd "$(dirname "$1")" 2>/dev/null && printf '%s/%s' "$(pwd -P)" "$(basename "$1")"); }
_mi=$(_abs "$(unset GIT_INDEX_FILE; git -C "$ROOT" rev-parse --path-format=absolute --git-path index 2>/dev/null)")
_gi="$_mi"
if [ -n "${GIT_INDEX_FILE:-}" ]; then
    case "$GIT_INDEX_FILE" in /*) _gi="$GIT_INDEX_FILE" ;; *) _gi="$ROOT/$GIT_INDEX_FILE" ;; esac
    _gi=$(_abs "$_gi")
fi
PATHS_COMMIT=0
[ "$TRAP" = pre ] && [ -n "$_mi" ] && [ "$_gi" != "$_mi" ] && [ "$_gi" != "$_mi.lock" ] && PATHS_COMMIT=1
# ВОПРОС — О ДЕРЕВЕ КОММИТА, И СУДИТСЯ ДЕРЕВО КОММИТА (D1083): перечень и пересборка идут в ВЫГРУЗКЕ индекса коммита
# (`checkout-index`, свой GIT_WORK_TREE), рабочая копия не читается вовсе. Прежде судилась рабочая копия, и каждый круг
# корня R6 добавлял ей поправку: частично застейдженный файл, механизм вне коммита (D1082) — а неотслеживаемый файл,
# которого в коммите нет, всё равно отменял законную пересборку и поручал пересобрать свежий учёт, незастейдженный
# пересобранный учёт судился свежим (скептик по b2beb37f, А1–А6). Свежий учёт кладётся в индекс коммита
# и в рабочую копию (копия выгрузки + `git add`).
# КОМАНДА, КОТОРАЯ САМА ВСЁ ДОБАВЛЯЕТ (`git add -A && git commit`, `commit -a`; режим PreToolUse без ловушек git), —
# исключение: файлы ещё не в индексе, и дерево коммита тогда и есть рабочая копия (коммит 978fb82). Ответ — из ТЕКСТА
# команды. Названный предел того же режима: файл, который команда добавит поимённо (`git add x && git commit`),
# выгрузке не виден. Условие снятия: режим PreToolUse получит разбор файлов `git add` из текста команды либо все копии
# дерева получат ловушки git (`commit-trap.sh --install`), где индекс коммита уже собран.
_adds_all=0
# Ответ «добавит ли команда всё сама» — у владельца разбора: `executable_commit_adds` (command-scope-lib.sh, D1087). Слова
# даёт лексер оболочки, ключи разбираются так, как их разбирает git, эталон — исполнение форм настоящими bash и git
# (`test_commit_adds_oracle.sh`). Прежде здесь стояли свои выражения по тексту, и три раунда подряд (D1084–D1086) починка
# одной формы ломала другую; на таблице эталона прежнее выражение ошибалось в 8 формах из 47. Разбора нет (старая
# установка, нет python3) — «не добавит»: судится выгрузка индекса, как у команды без `add`.
command -v executable_commit_adds >/dev/null 2>&1 && [ -n "$COMMAND" ] \
    && [ -n "$(executable_commit_adds "$COMMAND")" ] && _adds_all=1
JUDGE="$ROOT"; JINDEXER="$INDEXER"; JENV=()
if [ "$_adds_all" -eq 0 ]; then
    _gd=$(git -C "$ROOT" rev-parse --absolute-git-dir 2>/dev/null)
    EXP=$(mktemp -d "${TMPDIR:-/tmp}/doc-impact-exp.XXXXXX" 2>/dev/null) && trap 'rm -rf "$EXP"' EXIT
    if [ -n "${EXP:-}" ] && [ -n "$_gd" ] && [ -n "$_gi" ] \
       && GIT_INDEX_FILE="$_gi" project_git -C "$ROOT" checkout-index -a --prefix="$EXP/" 2>/dev/null; then
        JUDGE="$EXP"; JENV=(GIT_DIR="$_gd" GIT_WORK_TREE="$EXP" GIT_INDEX_FILE="$_gi" PYTHONDONTWRITEBYTECODE=1)
        # Учёт ещё не отслеживается (в индексе коммита его нет) — записанные строки есть только в рабочей копии, и
        # отчёт с перечнем судят по ним; пересборка внесёт учёт в коммит, как прежде.
        [ -f "$EXP/$INDEX_REL" ] || { mkdir -p "$EXP/${INDEX_REL%/*}" && cp "$ROOT/$INDEX_REL" "$EXP/$INDEX_REL"; } 2>/dev/null
        # Правило учёта — тоже дерева коммита: копия прибора из выгрузки (D1080), если он в ней есть.
        case "$INDEXER" in "$ROOT"/*) [ -f "$EXP/${INDEXER#"$ROOT"/}" ] && JINDEXER="$EXP/${INDEXER#"$ROOT"/}" ;; esac
    else
        EXPORT_FAILED=1
    fi
fi
jx() { (cd "$JUDGE" && env ${JENV[@]+"${JENV[@]}"} CLAUDSOUL_REPO="$JUDGE" python3 "$JINDEXER" "$@"); }
# Какое дерево судить, решил хук (`ROOT`), и индексатору это НАЗЫВАЕТСЯ: без `CLAUDSOUL_REPO="$ROOT"` он брал дерево
# из унаследованной переменной и судил, а пересборкой писал учёт чужого дерева (D1076: «Проверка» под окружением стража
# — 19 красных ног `test_doc_impact_check.sh`). Старая редакция переменную может не читать — она и так судит `ROOT`.
# В ловушке git отчёт судит то же дерево коммита, что и перечень (D1084, А1): по рабочей копии одно сообщение называло
# «новые публичные имена», которых в коммите нет, рядом с «учёт пересобран». В режиме PreToolUse коммита ещё нет, и
# файл, который добавит сама команда (`git add x && git commit`), в индексе не виден — там отчёт судит рабочую копию
# (D1085, А2), как и отбор файлов этого режима. Названный предел (D1086, Д3): отчёт этого режима называет и правку,
# которую команда в коммит не добавит. Условие снятия — ловушки git во всех копиях дерева (там отчёт судит выгрузку).
if [ -n "$TRAP" ]; then
    REPORT=$(cd "$JUDGE" && printf '%s' "$STAGED" | tr '\n' '\0' \
        | env ${JENV[@]+"${JENV[@]}"} CLAUDSOUL_REPO="$JUDGE" xargs -0 python3 "$JINDEXER" --impact 2>/dev/null)
else
    REPORT=$(cd "$ROOT" && printf '%s' "$STAGED" | tr '\n' '\0' \
        | CLAUDSOUL_REPO="$ROOT" xargs -0 python3 "$INDEXER" --impact 2>/dev/null)
fi

# ЧТО УСТАРЕЛО, ОТВЕЧАЕТ ВЛАДЕЛЕЦ УЧЁТА — `--stale-by` по файлам коммита (D1082): строки, которые правка сделала
# неверными; пусто — учёт свеж. Прежде пересборку решали фразы отчёта `--impact`: «Пересобрать индекс» звучало и
# сразу после того, как ловушка pre-commit его пересобрала, а правка внутри области данных фраз не давала вовсе.
_staged_args=()
while IFS= read -r _f; do [ -n "$_f" ] && _staged_args+=("$_f"); done <<< "$STAGED"
_stale=""
if [ "$EXPORT_FAILED" -eq 0 ]; then
    _stale=$([ "${#_staged_args[@]}" -gt 0 ] && jx --stale-by "${_staged_args[@]}" 2>/dev/null)
    # Учёт старой редакции режима не знает (код 2): рабочая копия на прежнем коммите, проект со своей копией прибора.
    # Тогда прежние фразы отчёта и отбор по расширению — иначе пересборка молча пропала бы (нога D2 `test_commit_trap.sh`).
    # shellcheck disable=SC2181
    if [ $? -ne 0 ]; then
        case "$REPORT" in
            *"новые публичные имена"*|*"без строки в учёте"*|*"строки учёта устарели"*|*"пересобери учёт"*)
                _stale=$(grep -E '\.(sh|py)$' <<< "$STAGED") ;;
            *) _stale="" ;;
        esac
    fi
fi
STALE=()
while IFS= read -r _f; do [ -n "$_f" ] && STALE+=("$_f"); done <<< "$_stale"
if [ "${#STALE[@]}" -gt 0 ] && [ "$TRAP" != msg ] && [ "$PATHS_COMMIT" -eq 0 ]; then
    # Замок берёт сам индексатор (`save`, scripts/dep-index.py). Отказ пересборки коммит НЕ
    # роняет — хук всегда выходит нулём, — но и не молчит: исход печатается, иначе
    # молчание неотличимо от «учёт свеж».
    if [ "$JUDGE" = "$ROOT" ]; then
        jx --changed "${STALE[@]}" >/dev/null 2>&1 && project_git -C "$ROOT" add -- "$INDEX_REL" >/dev/null 2>&1 && REBUILT=1
    else
        # Учёт коммита ложится и в рабочую копию, и в индекс (`git add` — запись со stat): рабочий учёт, правленый отдельно,
        # иначе оставался бы с откатом строки, и следующий коммит всего правленого уносил его в HEAD (D1084, А3). Учёт —
        # производный файл, и рабочая копия получает его версию для дерева коммита; незакоммиченное в ней пересоберёт
        # следующий коммит.
        if jx --changed "${STALE[@]}" >/dev/null 2>&1 && cp "$EXP/$INDEX_REL" "$ROOT/$INDEX_REL" 2>/dev/null \
           && GIT_INDEX_FILE="$_gi" project_git -C "$ROOT" add -- "$INDEX_REL" >/dev/null 2>&1; then
            REBUILT=1
        fi
    fi
fi

[ -n "$REPORT" ] || [ "$REBUILT" -eq 1 ] || [ "${#STALE[@]}" -gt 0 ] || [ "$EXPORT_FAILED" -eq 1 ] || exit 0

[ -n "$TRAP" ] || printf '%s\n' "$KEY" >> "$THROTTLE" 2>/dev/null

# ── Документ СОСТОЯНИЯ и изменение ПОВЕДЕНИЯ (D209) ───────────────────────────
# Требование обновить документ состояния было привязано к бампу версии
# (`docs-family-check`) либо к появлению нового модуля (`module-doc-check`). Изменение
# поведения существующего механизма не требовало ничего — поэтому модульный док
# обновлялся исправно (у него есть страж), а `docs/architecture.md` и `docs/decisions.md`
# отставали. Замер 29 августа 2026: раздел архитектуры про контур разбора говорил «поводов
# семь» при фактических восьми, а правило лестницы эскалации жило в трёх местах и не имело
# ADR. Нашёл это владелец вопросом, а не механизм.
#
# ПОВЕДЕНИЕ ОТЛИЧАЕТСЯ ОТ КОСМЕТИКИ МАШИННО: в diff остаются строки, не являющиеся
# комментарием и не пустые. Починка опечатки в комментарии документ состояния не трогает —
# и требовать за неё решение значило бы сделать стража фоном.
STATE_DOCS="${DOC_STATE_LIST:-docs/architecture.md docs/decisions.md PLAN.md README.md README.ru.md CLAUDE.md}"

_behaviour_changed() {
    _bc=$( { project_git -C "$ROOT" diff --no-ext-diff --no-textconv --cached -U0 -- '*.sh' '*.py' 2>/dev/null;
             [ -n "$TRAP" ] || project_git -C "$ROOT" diff --no-ext-diff --no-textconv -U0 -- '*.sh' '*.py' 2>/dev/null; } \
           | grep -E '^[+-]' | grep -vE '^(\+\+\+|---)' \
           | sed -E 's/^[+-][[:space:]]*//' \
           | grep -vE '^#' | grep -vE '^$' | head -1)
    [ -n "$_bc" ]
}

DECIDED=0
# Решение наблюдаемо двумя способами: документ состояния в этом же коммите ЛИБО явная
# отметка в сообщении коммита. Второе нужно, потому что «не задето» — законный исход, и
# без наблюдаемого следа он неотличим от «забыл».
grep -qE 'doc-state:' <<< "$COMMAND" && DECIDED=1
# Строки-комментарии сообщения git вырежет — решением они не считаются (скептик D1022).
[ "$TRAP" = msg ] && grep -qE 'doc-state:' <<< "$(grep -v '^#' "$MSGF" 2>/dev/null)" && DECIDED=1

PENDING=""
if [ "$DECIDED" -eq 0 ] && _behaviour_changed; then
    for _d in $STATE_DOCS; do
        grep -qxF "$_d" <<< "$STAGED" && { DECIDED=1; break; }
        grep -qF "$_d" <<< "$REPORT" && PENDING="$PENDING $_d"
    done
    # Решение, принятое документом НИЖЕ по списку, снимает набранное выше (D1093): иначе
    # staged CLAUDE.md давал DECIDED=1, а PLAN.md, набранный до него, всё равно уходил в
    # сообщение «не тронут» и в журнал решений рядом со статусом «decided».
    # Названный предел режима PreToolUse (скептик по 2dbefe5d): STAGED здесь — индекс ВМЕСТЕ с рабочим деревом
    # (ради `commit -am`), поэтому решением засчитывается и документ, правленный, но в коммит не добавляемый.
    # Сужать до индекса нельзя: поимённого разбора `git add x && git commit` нет (см. выше), и ходовая форма снова
    # дала бы ложное «не тронут». Условие снятия — ловушки git в копии дерева (`commit-trap.sh --install`): там STAGED —
    # индекс коммита, и PreToolUse молчит.
    [ "$DECIDED" -eq 1 ] && PENDING=""
fi

# Журнал решений — знаменатель для замера: сколько правок поведения прошло с решением и
# сколько без. Без него «страж сказал» и «страж помог» опять были бы одним утверждением.
if [ "$TRAP" != pre ] && _behaviour_changed && [[ $REPORT == *[!\ ]* ]]; then
    _st=$([ "$DECIDED" -eq 1 ] && printf 'decided' || printf 'undecided')
    jq -cn --arg ts "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" --arg s "$_st" \
           --arg d "$(printf '%s' "${PENDING# }" | tr ' ' ',')" \
        '{ts:$ts, status:$s, docs:$d}' >> "$STATE_DIR/doc-state-${SID}.jsonl" 2>/dev/null || true
fi

if [ "$TRAP" = pre ]; then
    [ "${#STALE[@]}" -gt 0 ] && [ "$PATHS_COMMIT" -eq 1 ] && echo "⚠️ Учёт зависимостей НЕ пересобран: коммит путями собирается мимо основного индекса, и свежий учёт следующий коммит откатил бы. Пересобери и закоммить отдельно: ${IX_CMD} --changed <файлы> && git add $INDEX_REL" >&2
    [ "$REBUILT" -eq 1 ] && echo "✅ Учёт зависимостей пересобран и добавлен в этот коммит ($INDEX_REL)." >&2
    [ "$EXPORT_FAILED" -eq 1 ] && echo "⚠️ Учёт зависимостей НЕ проверен: выгрузка индекса коммита не удалась, а рабочую копию за дерево коммита хук не выдаёт. Сверь после коммита: ${IX_CMD} --check" >&2
    exit 0
fi

MSG="📗 Влияние на документацию — из индекса зависимостей, а не обходом дерева:
${REPORT}

Правило: изменил механизм — реши, задело ли это его описания и описания зависимых,
и обнови их В ЭТОМ ЖЕ коммите. Ничего не задело — так и скажи в ответе, это тоже исход."

if [ "$REBUILT" -eq 1 ]; then
    MSG="$MSG
✅ Учёт пересобран САМ и добавлен в этот коммит ($INDEX_REL): производный факт решения не
требует, и поручать его было нечем. Суждение о документах выше остаётся за тобой."
elif [ "$EXPORT_FAILED" -eq 1 ]; then
    MSG="$MSG
⚠️ Учёт НЕ проверен: выгрузка индекса коммита не удалась, а рабочую копию за дерево коммита хук не выдаёт.
Сверь после коммита: ${IX_CMD} --check"
elif [ "${#STALE[@]}" -gt 0 ]; then
    MSG="$MSG
Пересобрать индекс после правки: ${IX_CMD} --changed <файлы>"
fi

if [[ $PENDING == *[!\ ]* ]]; then
    MSG="$MSG

📘 Поведение механизма изменилось, а документ СОСТОЯНИЯ его описывает и не тронут:${PENDING}
Документ состояния отвечает на вопрос «как есть сейчас», и правка поведения делает его
ответ неверным — в отличие от правки комментария, за которую здесь не спрашивают.
Реши наблюдаемо, БЕЗ ожидания разрешения:
  · задело → добавь документ в этот же коммит;
  · не задело → допиши в сообщение коммита \`doc-state: не задето — <почему>\`."
fi

[ "$TRAP" = msg ] && { printf '%s\n' "$MSG" >&2; exit 0; }
jq -cn --arg m "$MSG" '{hookSpecificOutput: {hookEventName: "PreToolUse", additionalContext: $m}}'
exit 0
