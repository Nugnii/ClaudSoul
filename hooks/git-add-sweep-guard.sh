#!/usr/bin/env bash
# git-add-sweep-guard.sh — PreToolUse[Bash]: спрашивает, когда `git add` каталогом захватывает неотслеживаемые файлы, которых автор команды не называл, и показывает их поимённо.
# en: PreToolUse[Bash] — asks before `git add` stages untracked files the command never named.
#
# Результат: в коммит не уходит файл, которого автор команды не называл и не видел.
# Проверка результата: bash hooks/tests/test_git_add_sweep_guard.sh даёт 0
#
# ЗАЧЕМ. 19 сентября 2026, дважды за одну сессию: `git add -A -- … docs/ …` захватил шесть
# файлов `docs/*.ru.md`, которые владелец ДЕРЖИТ ВНЕ УЧЁТА. Первый раз они уехали в коммит и
# в push, CI упал на них же; второй раз я заметил перед коммитом сам. Между этими двумя
# случаями знание было записано (`case-2026-09-19-add-by-directory-swept-in-what-the-owner-
# kept-out`, связано с `pattern-commit-condition-lives-in-the-command`) и в памяти проекта
# стояло правило «git add только по именам». Не помогло ни то, ни другое: правило уровня 1
# держится ровно до следующей спешки — владелец сказал об этом прямо: «находки-то чинить
# надо, толку что ты их нашёл».
#
# ПРИЗНАК. Команда зовёт `git add`, и среди путей, которые git СОБИРАЕТСЯ добавить (его же
# `--dry-run`), есть НЕОТСЛЕЖИВАЕМЫЙ файл, чьё имя в команде не названо буквально.
# Спрашивается ровно это: «ты назвал каталог, а внутри лежит вот что — точно берём?»
#
# ПОЧЕМУ «СПРАШИВАЕТ», А НЕ «ОТКАЗЫВАЕТ». У признака ДВА последствия, а не одно: добавление
# новых файлов каталогом — законный ход, когда файлы и правда новые и нужные. Уровень 4 в
# этом проекте заводится только на признаке с ОДНИМ последствием и с ИЗМЕРЕННОЙ точностью;
# здесь ни того, ни другого, и честный ярус — вопрос. Условие подъёма до отказа: появится
# замер доли ложных срабатываний по корпусу прошлых вызовов.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ.
#   · Страж видит только вызовы через Bash. Правка индекса иным путём (инструмент харнесса,
#     другая сессия) им не покрыта — тот же предел, что у соседних стражей команды.
#   · Решает `git add --dry-run`: если git не запустился (не репозиторий, нет git), страж
#     МОЛЧИТ и пропускает — «судить нечем» не повод мешать работе.
#   · ПЕРЕЧЕНЬ НЕОТСЛЕЖИВАЕМОГО БЕРЁТСЯ В ТОЙ ЖЕ ЕДИНИЦЕ, ЧТО ЗАХВАТ. Владельцев у него
#     двое — `--dry-run` и `status --porcelain`, — и до 20 сентября 2026 они отвечали
#     по-разному: без `-uall` целиком новый каталог схлопывался в строку `brandnew/`, при
#     `core.quotePath` не-ASCII путь приходил в кавычках с восьмеричными escape. Сверка не
#     совпадала, и «файл не захвачен» было неотличимо от «страж его не разглядел» — корень
#     R6 в самом страже (D471). Оба ключа выставлены явно; менять их — значит вернуть класс.
#   · `git commit -a` сюда не входит: он не добавляет неотслеживаемых файлов.
#   · ГЛОБАЛЬНЫЕ КЛЮЧИ ПЕРЕЧИСЛЕНЫ, А НЕ ВЫВЕДЕНЫ: между `git` и `add` страж узнаёт `-C`,
#     `-c`, `--git-dir=`, `--work-tree=`, `--no-pager`, `--literal-pathspecs`. Форма вне
#     перечня стражу не видна. Это корень R3 в моём собственном признаке, и он назван, а
#     не умолчан; условие снятия — разбор ключей у их владельца, а не список здесь.
#   · КАВЫЧКИ НЕ СНИМАЮТСЯ У ПУТЕЙ. Слова получаются делением по пробелам без подстановок,
#     поэтому `git add "мой файл.md"` распадётся надвое, git их не найдёт и страж
#     ПРОМОЛЧИТ. Промах в сторону тишины выбран сознательно: снимать кавычки означало бы
#     отдать текст непринятой команды оболочке, а это и был дефект первой редакции.
#     У ПРИЗНАКА ОБХОДА единица иная и это не противоречие: там ищется присваивание, и
#     кавычки снимает РАЗБОР владельца (`hooks/lib/write_targets.py`, `shlex`), а не
#     вырезание текстом.
#     ЗДЕСЬ СТОЯЛ ПРЕДЕЛ «вложенные кавычки и `$'…'` вырезанию не по зубам; условие снятия:
#     появится разбор кавычек, не отдающий текст оболочке». ПРЕДЕЛ СНЯТ 20 сентября 2026:
#     разбор появился, страж на него переведён, вырезания текстом больше нет. Предел
#     пережил своё условие на несколько часов — и это ровно тот случай, ради которого
#     заведён `scripts/named-limits.py`: условий снятия в дереве 249, снято за всю историю
#     было два, потому что перечитывать их некому и не по какому поводу.
#   · НАЗВАННЫЙ ПРЕДЕЛ, оставшийся у путей: слова для git получаются делением по пробелам,
#     и разбор владельца к ним НЕ применён — `git add "мой файл.md"` распадётся надвое,
#     git их не найдёт, страж промолчит. Промах в сторону тишины.
#     Условие снятия: пути для `--dry-run` станут браться у того же разбора, что и обход,
#     и страж СПРОСИТ на захвате, названном путём в кавычках с пробелом.
#     Проверка снятия судит ПОВЕДЕНИЕ, а не слово в файле: первая её редакция искала
#     `grep`-ом имя функции разбора и позеленела мгновенно — имя стоит у признака обхода,
#     к путям отношения не имеющего. Прибор назвал это «условие наступило» на пустом месте,
#     и слепую проверку поймал он же, в первый свой прогон.
#     Проверка снятия: `bash hooks/tests/fixtures/limit_quoted_path.sh`
#   · Судится ТЕКСТ команды. Путь, собранный переменной (`git add "$f"`), стражу неизвестен:
#     он увидит слово `"$f"`, git его не найдёт, страж промолчит.
#
# ПОЧЕМУ ЗДЕСЬ НЕТ `eval` И НЕ БУДЕТ. Первая редакция звала `eval "git add --dry-run $ARGS"`.
# Скептик 19 сентября 2026 показал прогоном: `git add $(touch /tmp/PWNED)` создавал файл ДО
# решения владельца, обратные кавычки — тоже, а `git add docs > docs/OOPS.txt` писал в
# рабочее дерево, потому что страж перед этим делал `cd` в каталог проекта. Шапка в тот
# момент обещала «худшее — лишний вопрос». Страж на PreToolUse судит команду, которую ещё
# не одобрили: её текст — ДАННЫЕ, и оболочке он не отдаётся ни на одном шаге.
#
# Вход  (stdin): payload PreToolUse
# Выход (stdout): {hookSpecificOutput:{hookEventName, permissionDecision, permissionDecisionReason}}
# Код:  всегда 0; вопрос выражается полем permissionDecision, а не кодом.

set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat); [ -z "$INPUT" ] && exit 0
TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
[ "$TOOL" = "Bash" ] || exit 0
CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
[ -n "$CMD" ] || exit 0
# ПРИЗНАК ВЫЗОВА. Между `git` и `add` стоят глобальные ключи (`-C <путь>`, `-c k=v`,
# `--git-dir=`), поэтому слово `add` ищется не вплотную; перечень ключей ОГРАНИЧЕН и это
# названный предел — форма вне перечня стражу не видна. Пробелов между словами бывает
# больше одного. Прежняя редакция спрашивала подстроку `"git add"` и молчала на
# `git -C . add` и на `git␣␣add` (находка скептика 19 сентября 2026).
GIT_ADD_RE='(^|[;&|(){}]|^[[:space:]]|[[:space:]])git([[:space:]]+(-C[[:space:]]+[^[:space:]]+|-c[[:space:]]+[^[:space:]]+|--git-dir=[^[:space:]]+|--work-tree=[^[:space:]]+|--no-pager|--literal-pathspecs))*[[:space:]]+add([[:space:]]|$)'
grep -qE "$GIT_ADD_RE" <<< "$CMD" || exit 0

# ОСОЗНАННЫЙ ОБХОД СПРАШИВАЕТСЯ У ВЛАДЕЛЬЦА РАЗБОРА, А НЕ РАЗБИРАЕТСЯ ЗДЕСЬ (20 сентября
# 2026, поправка владельца «прежде чем менять, пойми, почему было принято такое решение и
# на что изменение повлияет»).
#
# Здесь 19-20 сентября стояла СВОЯ копия разбора: `sed` снимал комментарии и кавычки,
# `awk` — тела heredoc, и уже в остатке искался литерал. Противник пробил её ШЕСТЬЮ
# способами за один прогон, в обе стороны: heredoc с кавычками в метке (в дереве 604 таких
# против 230 без), односложная строка в теле, экранированная кавычка — страж МОЛЧАЛ на
# настоящем захвате; решётка внутри кавычек, метка с цифрой, арифметический сдвиг —
# законный обход переставал сниматься, и страж мешал работе.
#
# Все шесть — не шесть дефектов, а один: у факта «что здесь исполнит оболочка» в дереве
# УЖЕ БЫЛ владелец — `hooks/lib/write_targets.py`, — и правило, указывающее на него,
# записано в `command-scope-lib.sh:330`: «разбирать кавычки надо РАЗБОРОМ (`shlex`), а не
# вырезанием». Копия была родом K реестра и корнем R1: один факт, два владельца,
# расходящиеся молча. Вторая редакция вырезания стала бы третьей попыткой в том же классе.
#
# Теперь вопрос задан владельцу режимом `--prefix-env`: «какое присваивание стоит перед
# какой командой». Проверяется РАВЕНСТВО токена и имя команды — упоминание в прозе этому
# не удовлетворяет ни в одной форме, разбирать их незачем.
#
# НЕТ РАЗБОРА — СТРАЖ СПРАШИВАЕТ. Код 2 («нет python3 либо разбора») не молчание: промах
# уводится в сторону ВОПРОСА, потому что цена лишнего вопроса — секунда, а цена молчания
# измерена дважды за сессию 19 сентября шестью файлами в чужом коммите.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ: разбирается ЛЕКСИКА, а не грамматика (предел самого владельца —
# подстановка команд и раскрытие переменных до исполнения не имеют). Обход перед ЛЮБОЙ
# командой `git` снимает вопрос у всех `git add` строки, а не только у соседнего; условие
# снятия — признак переедет внутрь посегментного цикла ниже. Присваивание через `export`
# обходом не считается: это не позиция команды.
CS_LIB="${CS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/command-scope-lib.sh}"
if [ -f "$CS_LIB" ]; then
    # shellcheck source=/dev/null
    . "$CS_LIB" 2>/dev/null || true
fi
# git в папке сессии — через project_git (D519): голый git исполняет программы из её настроек.
_PL="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/paths-lib.sh"
[ -f "$_PL" ] || _PL="$HOME/.claude/hooks/paths-lib.sh"
# shellcheck source=/dev/null
[ -f "$_PL" ] && . "$_PL" 2>/dev/null
command -v project_git >/dev/null 2>&1 || project_git() { git "$@"; }   # без paths-lib — голый git (предел D515)
if declare -f executable_prefix_env >/dev/null 2>&1; then
    if PREFIX_ENV=$(executable_prefix_env "$CMD"); then
        while IFS=$'\t' read -r _assign _head; do
            [ "$_assign" = "CLAUDSOUL_ALLOW_ADD_SWEEP=1" ] || continue
            [ "$_head" = "git" ] || continue
            exit 0
        done <<< "$PREFIX_ENV"
    fi
fi

CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
[ -n "$CWD" ] && [ -d "$CWD" ] || CWD="$PWD"
cd "$CWD" 2>/dev/null || exit 0
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

# ТЕКСТ НЕПРИНЯТОЙ КОМАНДЫ — НЕ ПРОГРАММА, А ДАННЫЕ. Оболочке он не отдаётся ни на одном
# шаге: слова получаются `read -ra` (одно только деление по пробелам, без подстановок) и
# уходят в git МАССИВОМ. Первая редакция звала `eval "git add … $ADD_ARGS"`, и скептик
# 19 сентября 2026 показал прогоном, что `git add $(touch /tmp/PWNED)` создаёт файл ДО
# решения владельца, а `git add docs > docs/OOPS.txt` пишет в рабочее дерево. Страж на
# PreToolUse обязан судить команду, а не исполнять её.
#
# НАЗВАННЫЙ ПРЕДЕЛ деления без подстановок: кавычки остаются символами слова, поэтому
# `git add "мой файл.md"` распадётся на два слова, git их не найдёт (`--ignore-missing`)
# и страж промолчит. Это промах в сторону ТИШИНЫ, а не в сторону исполнения.
#
# Вызовов `git add` в строке бывает несколько, и разбираются ВСЕ: прежний жадный
# `sed 's/.*git add //'` брал последний, и `git add -A -- docs && git add файл` проходило
# молча — та самая форма, ради которой страж написан.
DRY=""
while IFS= read -r seg; do
    [ -n "$seg" ] || continue
    args=${seg#*add}
    [ -n "$args" ] || continue
    unset WORDS
    read -ra WORDS <<< "$args"
    [ "${#WORDS[@]}" -gt 0 ] || continue
    # КЛЮЧ, ЧИТАЮЩИЙ ЧУЖОЙ ФАЙЛ, В СУД НЕ ПОПАДАЕТ (20 сентября 2026, находка противника).
    # Слова уходят в git массивом и оболочке не отдаются — это выстояло, — но среди них
    # бывает ключ САМОГО git: `--pathspec-from-file=/tmp/x` заставлял стража прочитать файл
    # ВНЕ репозитория, а тот же ключ на FIFO вешал хук PreToolUse навсегда (прогон
    # противника: код 142 по будильнику на 15 с). Последствие не исполнение, а блокировка
    # сессии на непринятой команде. Ключ отбрасывается вместе со значением; предел назван:
    # отбрасывается перечень из двух форм, и если git заведёт третью, страж её не узнает.
    unset SAFE; SAFE=()
    _skip_next=0
    for _w in "${WORDS[@]}"; do
        if [ "$_skip_next" = "1" ]; then _skip_next=0; continue; fi
        case "$_w" in
            --pathspec-from-file) _skip_next=1; continue ;;
            --pathspec-from-file=*|--pathspec-file-nul) continue ;;
        esac
        SAFE+=("$_w")
    done
    [ "${#SAFE[@]}" -gt 0 ] || continue
    out=$(project_git add --dry-run --ignore-missing "${SAFE[@]}" 2>/dev/null) || continue
    [ -n "$out" ] && DRY="${DRY}${out}"$'\n'
done <<EOF
$(grep -oE "$GIT_ADD_RE[^;&|]*" <<< "$CMD")
EOF
[ -n "$DRY" ] || exit 0

# Перечень берётся В ТОЙ ЖЕ ЕДИНИЦЕ, что у `--dry-run`: `-uall` раскрывает целиком
# новый каталог поимённо, `core.quotePath=false` снимает восьмеричные escape.
# ПЕРЕЧЕНЬ БЕРЁТСЯ ЧЕРЕЗ `-z`, А НЕ ЧЕРЕЗ `core.quotePath=false` (20 сентября 2026, третий
# случай одного класса). Ключ `quotePath` снимает восьмеричные escape у не-ASCII, но путь
# С ПРОБЕЛОМ git берёт в кавычки НЕЗАВИСИМО от него: `?? "docs/мой файл.md"`. Сверка
# `grep -qxF` с поимённым выводом `--dry-run` не совпадала, и страж молчал на любом
# неотслеживаемом файле, чьё имя несёт пробел. `-z` отдаёт пути сырыми и разделяет NUL —
# кавычек нет вовсе. Приём взят у брата `hooks/rework-detector.sh:153`, который закрыл тот
# же класс раньше и иначе; `quotePath` оставлен, потому что вреда от него нет, а читателю
# видно оба ключа сразу. Найдено не глазом: проверкой снятия названного предела этого же
# файла, на её первом прогоне.
UNTRACKED=$(project_git -c core.quotePath=false status --porcelain -z -uall 2>/dev/null \
            | tr '\0' '\n' | sed -n 's/^?? //p')
[ -n "$UNTRACKED" ] || exit 0

SWEPT=""
while IFS= read -r line; do
    [ -n "$line" ] || continue
    # Строки вида: add 'путь'
    path=$(printf '%s' "$line" | sed -n "s/^add '\(.*\)'$/\1/p")
    [ -n "$path" ] || continue
    # Here-string, а не конвейер: `grep -q` выходит на первом совпадении, производитель
    # получает SIGPIPE, и под `pipefail` УСПЕШНАЯ проверка прочиталась бы как провал.
    # Поймано стражем переносимости в момент написания ЭТОГО файла.
    grep -qxF "$path" <<< "$UNTRACKED" || continue   # уже отслеживается — не предмет
    case "$CMD" in *"$path"*) continue ;; esac                   # назван буквально — автор знал
    SWEPT="${SWEPT}${path}"$'\n'
done <<EOF
$DRY
EOF

[ -n "$SWEPT" ] || exit 0

N=$(printf '%s' "$SWEPT" | grep -c . )
LIST=$(printf '%s' "$SWEPT" | head -12 | sed 's/^/  · /')
[ "$N" -gt 12 ] && LIST="${LIST}"$'\n'"  · …и ещё $((N - 12))"

REASON="git add захватит $N неотслеживаемых файл(ов), которых команда не называла:
$LIST

Назови нужные файлы поимённо — или, если берёшь их осознанно, поставь в команду
CLAUDSOUL_ALLOW_ADD_SWEEP=1. Повод: 19 сентября 2026 такой захват дважды за сессию унёс в
коммит шесть docs/*.ru.md, которые владелец держит вне учёта."

jq -cn --arg r "$REASON" '{hookSpecificOutput: {hookEventName: "PreToolUse",
    permissionDecision: "ask", permissionDecisionReason: $r}}'
exit 0
