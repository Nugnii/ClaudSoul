#!/usr/bin/env bash
# deny-mark-lib.sh — ВЛАДЕЛЕЦ имени состояния «вызов отказан стражем».
# Результат: читатель расшифровки отличает решение стража от упавшей команды, спросив ОДНО
#            выражение, а не выписав литерал у себя; страж с новым текстом отказа виден
#            читателю в тот же день, потому что перечень маркеров один на дерево
# Проверка результата: bash hooks/tests/test_deny_mark_lib.sh даёт 0
# ПРЕФИКСЫ: deny_mark_
#
# Зачем (D421, 16 сентября 2026). У состояния не было владельца: десять стражей писали маркер
# отказа литералом каждый свой, четыре потребителя читали литералом каждый свой — и новый вид
# отказа оставался невидим для всех сразу. Корень R1 карты («имя состояния собрано литералом на
# каждом конце связи отдельно»), НЕ R6: гипотеза пункта о слитности канала `is_error` отвергнута
# дробью — при подъёме к каналу она падает с 10 из 14 до 1 из 3, а владелец `is_error` лежит вне
# дерева (харнесс), и реестр по нему непостроим.
#
# ПЕРЕЧЕНЬ ВЫВЕДЕН ИЗ ДВУХ ИСТОЧНИКОВ, И ОДНОГО БЫЛО БЫ МАЛО. Замер по корпусу 16 сентября 2026
# (1283 ошибочных блока tool_result): отказов 411 — `⛔ ОТКАЗ` 378, `🛑` 27, `🚫` 6. Чтение кода
# дало ЧЕТВЁРТОЕ написание, которого в корпусе нет вовсе: `secret-guard:118` пишет `⛔ Секрет…`,
# `publish-guard:77` — `⛔ Необратимая публикация…`, оба без слова ОТКАЗ. Перечень, снятый только
# с мира, промахнулся бы по двум стражам из десяти; снятый только с кода — не знал бы долей.
#
# ТОЧНОСТЬ ИЗМЕРЕНА, А НЕ ОБЪЯВЛЕНА: выражение ниже даёт 413 совпадений на 1283 ошибочных блока,
# и НИ ОДНО не оказалось чужим текстом — все 413 суть тексты известных стражей (ложных 0).
#
# ЯКОРЬ ОБЯЗАТЕЛЕН, И ЭТО НЕ СТИЛЬ. Маркеры не редки: `🛑` стоит в теле инжектов знаний
# («🛑 Blocker: …»), попадающих и в вывод НАСТОЯЩИХ провалов. Поэтому выражение судит НАЧАЛО
# текста блока (`\A`), а не вхождение куда угодно. Следствие названо вслух: потребитель без
# блочного разбора пользоваться этим владельцем НЕ может. Таким был `scripts/signal-precision.sh`:
# он грепал файл расшифровки целиком, а с D423 считает отказы блочным разбором (`:218-228`).
# Судьба двух других читателей записана в D421, а не умолчана.
#
# СИНТАКСИС ОДИН НА ДВА ДВИЖКА. `\A` и `\s` понимают и Oniguruma (jq `test`), и питоновский `re`,
# поэтому выражение не переписывается на каждом конце — иначе у имени снова стало бы два владельца.
#
# КОНТРПРИМЕР: отказ, чей текст НЕ начинается с маркера, признаком не ловится, и это известно.
# Маркер в середине вывода настоящего провала («Exit code 1 … 🛑 Blocker: x») не ловится НАМЕРЕННО —
# ради этого и стоит якорь. Страж, написавший отказ без ⛔/🛑/🚫, не ловится по ПРЕДЕЛУ перечня: он
# выведен из корпуса и кода 16 сентября 2026 и пополняется вместе с новым стражем (пишущий конец
# держит `hooks/tests/test_deny_mark_lib.sh`). Строка дописана 17 сентября 2026: без неё сверщик
# `test_signal_has_counterexample.sh` краснил дерево, а выборочный прогон его не выбирал.
# ПРЕФИКС ХАРНЕССА (D527, 11 октября 2026). С 26 сентября 2026 харнесс кладёт отказ в расшифровку
# как `PreToolUse:<инструмент> hook error: ⛔ …`: замер по 320 расшифровкам — до 25 сентября отказы
# голые, с 26-го только с префиксом (≈ 370 за 26.09–11.10), и выражение без него не узнало ни
# одного — error-tracker считал отказы провалами. Префикс допускается ровно в начале: якорь цел.
DENY_MARK_RE="${DENY_MARK_RE:-\\A\\s*(PreToolUse:[A-Za-z_]+ hook error:\\s*)?(⛔|🛑|🚫)}"

# Маркеры поодиночке — для стража письма (тест проверяет, что новый страж взял один из них).
DENY_MARK_CHARS="${DENY_MARK_CHARS:-⛔ 🛑 🚫}"

deny_mark_is_denial() {   # deny_mark_is_denial <текст> → 0 решение стража, 1 не оно, 2 спросить нечем
    command -v jq >/dev/null 2>&1 || return 2
    jq -e -n --arg t "${1-}" --arg re "$DENY_MARK_RE" '$t | test($re)' >/dev/null 2>&1
}
