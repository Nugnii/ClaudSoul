#!/bin/bash
# state-lock-lib.sh — общий замок для файлов состояния и правки под ним.
# en: shared mutual exclusion for state files, plus the read-modify-write helpers.
#
# ПРЕФИКСЫ: atomic_ drain_ lock_ with_ write_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
#
# Результат: у файла состояния, который правят несколько ходов сразу, окно read→write
#            закрыто замком — из N одновременных правок в файле остаются все N
# Проверка результата: bash hooks/tests/test_state_lock.sh даёт 0
#
# Зачем (род H, замер 4 сентября 2026). Тринадцать хуков читали общий файл целиком,
# правили в памяти и клали обратно. Между чтением и записью писателей не сериализовало
# ничто, и последний побеждал: восемь одновременных границ хода в `completion-gate.sh`
# оставляли 4-7 записей из 8. Правок было тринадцать, потому что общего помощника не
# существовало — каждый писатель решал задачу сам. Здесь он один.
#
# ЗАМОК — КАТАЛОГ `<путь>.lock` рядом с самим файлом (тот же каталог, значит те же права и та же ФС), а ВЗЯТ он тем,
# кто ИСКЛЮЧИТЕЛЬНО создал в нём `owner` (`set -C` — проверку делает сам bash, флагом O_EXCL). Одного `mkdir` мало
# (D1320): `mkdir` из uutils — coreutils `ubuntu-26.04` — отвечает 0 обоим соперникам (175 пар из 200), а GNU и BSD
# исключительны. Два одновременных `( set -C; printf … > f )` — 0 пар из 200 и на bash 3.2.57 (macOS), и на 5.3.9.
# `flock` на macOS отсутствует.
#
# ЗАМОК НЕ ЖДЁТ ВЕЧНО. Хук стоит на пути каждого вызова инструмента: зависший замок
# остановил бы сессию. После CLAUDSOUL_LOCK_TRIES проб (по умолчанию 100 × 20 мс = 2 с)
# работа продолжается БЕЗ замка — то есть ровно так, как она шла до этой библиотеки.
# Брошенный замок срывается: без этого один убитый хук запирал бы файл навсегда. Брошен —
# это владелец мёртв (`owner` внутри каталога, D500), а без владельца — старше
# CLAUDSOUL_LOCK_STALE_S (30 с); замок живого владельца не срывается по возрасту.
#
# Питоновская половина того же протокола (то же имя `<путь>.lock`, тот же `mkdir`) —
# в `hooks/lib/injection-log-rotate.py`: ротатор журнала подач живёт в питоне, а его
# писатель-аппендер в оболочке, и замок обязан быть у них общим.

PORTABLE_LIB_SL="${PORTABLE_LIB_SL:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/portable-lib.sh}"
[ -f "$PORTABLE_LIB_SL" ] || PORTABLE_LIB_SL="$HOME/.claude/hooks/portable-lib.sh"
# shellcheck source=/dev/null
if [ -f "$PORTABLE_LIB_SL" ]; then . "$PORTABLE_LIB_SL"; fi

# Взятые нами замки: `lock_release` снимает только свой. Иначе ход, не получивший замок
# по таймауту, сорвал бы чужой на выходе — и окно стало бы шире, чем без замка вовсе.
_SL_HELD=" "
# Токен владельца — у процесса: «pid случайное». Пишется в `<путь>.lock/owner` при взятии.
_SL_TOKEN="$$.${RANDOM}${RANDOM}"

# ЖИВОСТЬ, А НЕ ВОЗРАСТ; СРЫВ ИСКЛЮЧИТЕЛЕН; СНИМАЕТСЯ ТОЛЬКО СВОЙ (D500, 2 октября 2026). Возраст
# каталога держатель не обновляет, поэтому событие дольше порога теряло замок при ЖИВОМ держателе,
# и второе шло параллельно; срыв «прочёл возраст → rmdir → mkdir» не атомарен — сосед, сорвавший
# первым и взявший свежий замок, терял его от второго срыва; выход держателя снимал замок по ИМЕНИ,
# то есть чужой. Теперь замок с живым владельцем (`owner`: «pid токен») не брошен; потолок — десять
# порогов от записи `owner` (повторно занятый PID); без владельца — по возрасту каталога, как прежде.
# Срыв: право на него — `.break/by`, его создаёт ОДИН (D1320); внутри он сверяет, что экземпляр тот же
# (inode и строка владельца), и только тогда сносит. Переименование в «могилу» не годилось: путь на
# миг свободен, и при залпе из 30 событий в это окно успевал третий. Освобождение — по токену.
_lock_ino() { stat -L -c '%i' "$1" 2>/dev/null || stat -L -f '%i' "$1" 2>/dev/null; }
_lock_age() {  # <путь> → возраст в секундах; нет пути — -1
    local m; m=$(file_mtime "$1" 2>/dev/null || echo 0)
    case "${m:-}" in ''|*[!0-9]*) m=0 ;; esac
    if [ "$m" -gt 0 ]; then echo $(( $(date +%s) - m )); else echo -1; fi
}
_lock_owner() {  # <каталог> → строка владельца; файла нет — пусто; есть, но не прочитан — «?»
    [ -e "$1/owner" ] || return 0
    head -n 1 "$1/owner" 2>/dev/null || printf '?'
}
_lock_abandoned() {  # <каталог> <строка владельца> → 0, если замок брошен
    local d="$1" pid stale="${CLAUDSOUL_LOCK_STALE_S:-30}"
    case "$stale" in ''|*[!0-9]*) stale=30 ;; esac
    pid="${2%% *}"
    case "$pid" in
        '?') [ "$(_lock_age "$d/owner")" -gt $((stale * 10)) ] ;;   # живость неизвестна — только потолок
        ''|*[!0-9]*) [ "$(_lock_age "$d")" -gt "$stale" ] ;;
        *) [ "$(_lock_age "$d/owner")" -gt $((stale * 10)) ] || ! kill -0 "$pid" 2>/dev/null ;;
    esac
}

# lock_acquire <путь> → 0 замок взят, 1 не взят (вызывающий продолжает без него)
#
# Ни одна ветвь не заканчивается «голым» ложным условием: три хука-потребителя стоят
# под `set -e`, и такая ветвь уронила бы весь хук вместо того, чтобы вернуть 1.
lock_acquire() {
    local target="${1:-}" i=0 d ino own
    [ -n "$target" ] || return 1
    d="${target}.lock"
    while :; do
        # Захват — ИСКЛЮЧИТЕЛЬНОЕ создание `owner` (D1320): `mkdir` из uutils (coreutils `ubuntu-26.04`) отвечает 0 обоим
        # соперникам. Не создался `owner` — ждём, как при занятом, если он уже есть (соперник взял первым) ИЛИ каталога
        # нет (соперник взял и уже отпустил в то же окно: «нет owner — замок наш» давал фантом без каталога, и третий
        # брал настоящий — скептик opus D1320, H1). Каталог есть, а `owner` не создать — запись не удалась сама (права,
        # диск), и замок наш, как было до D1320.
        if mkdir "$d" 2>/dev/null; then
            ( set -C; printf '%s %s\n' "$$" "$_SL_TOKEN" > "$d/owner" ) 2>/dev/null && break
            [ -e "$d/owner" ] || [ ! -d "$d" ] || break
        fi
        # Экземпляр замка фиксируется ДО суда: подменённый между судом и сносом опознаётся по inode.
        ino=$(_lock_ino "$d"); own=$(_lock_owner "$d")
        if [ -n "$ino" ] && _lock_abandoned "$d" "$own"; then
            # Право на срыв — тоже исключительное создание (`.break/by`), а не голый `mkdir` (D1320).
            if mkdir "$d/.break" 2>/dev/null && ( set -C; : > "$d/.break/by" ) 2>/dev/null; then
                if [ "$(_lock_ino "$d")" = "$ino" ] && [ "$(_lock_owner "$d")" = "$own" ]; then
                    rm -rf "$d" 2>/dev/null; continue
                fi
                rm -f "$d/.break/by" 2>/dev/null; rmdir "$d/.break" 2>/dev/null
            elif [ "$(_lock_age "$d/.break")" -gt "${CLAUDSOUL_LOCK_STALE_S:-30}" ] 2>/dev/null; then
                rm -f "$d/.break/by" 2>/dev/null; rmdir "$d/.break" 2>/dev/null   # срывавший упал, не доделав
            fi
        fi
        i=$((i + 1))
        if [ "$i" -ge "${CLAUDSOUL_LOCK_TRIES:-100}" ]; then return 1; fi
        sleep "${CLAUDSOUL_LOCK_NAP:-0.02}" 2>/dev/null || sleep 1
    done
    _SL_HELD="${_SL_HELD}${target} "
    return 0
}

# lock_release <путь> — снять СВОЙ замок; чужой не трогается — ни не взятый нами, ни взятый
# другим после того, как наш сорвали как брошенный.
lock_release() {
    local target="${1:-}" d own
    [ -n "$target" ] || return 0
    case "$_SL_HELD" in
        *" $target "*) ;;
        *) return 0 ;;
    esac
    _SL_HELD="${_SL_HELD/ $target / }"
    d="${target}.lock"
    own=$(awk 'NR == 1 { print $2 }' "$d/owner" 2>/dev/null)
    [ -z "$own" ] || [ "$own" = "$_SL_TOKEN" ] || return 0
    rm -f "$d/owner" 2>/dev/null
    # Отступающий срывающий мог на миг положить `.break` внутрь — вторая попытка после паузы.
    rmdir "$d" 2>/dev/null || { sleep 0.05 2>/dev/null; rmdir "$d" 2>/dev/null; } || true
    return 0
}

# with_lock <путь> <команда...> — выполнить команду, держа замок на файле.
# Код возврата — команды, а не замка: не взятый замок работу не отменяет.
with_lock() {
    local target="${1:-}" rc=0
    shift || return 0
    lock_acquire "$target" || true
    "$@" || rc=$?
    lock_release "$target"
    return "$rc"
}

# atomic_filter <файл> <фильтр...> — заменить файл выводом фильтра, под замком.
# Файл подаётся фильтру на stdin (jq/awk/sed без аргумента-файла читают именно его).
# Промежуточный файл — рядом с целью, поэтому `mv` здесь переименование, а не копия.
# Ненулевой код фильтра оставляет файл нетронутым.
atomic_filter() {
    local target="${1:-}" tmp rc=0
    shift || return 1
    [ -n "$target" ] && [ -f "$target" ] || return 1
    tmp="${target}.tmp.$$"
    lock_acquire "$target" || true
    if "$@" <"$target" >"$tmp" 2>/dev/null; then
        mv "$tmp" "$target" 2>/dev/null || rc=1
    else
        rc=1
        rm -f "$tmp" 2>/dev/null
    fi
    lock_release "$target"
    return "$rc"
}

# write_if_changed <файл> <значение> → 0 записано, 1 значение уже было тем же.
# Сравнение и запись — под одним замком: два хода одного сеанса (инструменты идут
# параллельно) иначе оба видят старое значение и оба считают, что изменили они.
write_if_changed() {
    local target="${1:-}" value="${2:-}" cur="" rc=1
    [ -n "$target" ] || return 1
    lock_acquire "$target" || true
    if [ -f "$target" ]; then cur=$(cat "$target" 2>/dev/null || true); fi
    if [ "$cur" != "$value" ]; then
        # Решение «изменилось» отдаётся по РАЗНИЦЕ значений, а не по успеху записи:
        # хук печатает по нему сообщение, и непишущийся каталог состояния не должен
        # молча отменять сообщение — до правки оно печаталось независимо от записи.
        printf '%s' "$value" >"$target" 2>/dev/null || true
        rc=0
    fi
    lock_release "$target"
    return "$rc"
}

# drain_file <файл> — напечатать содержимое и опустошить файл одним движением.
# Переименование, а не `cat` + обрезка: писатель, открывший путь ПОСЛЕ него, заводит
# свежий файл и не теряется вовсе — обрезка же съедает всё, что дописано между чтением
# и ею. Пустой вывод и код 0, если файла нет.
drain_file() {
    local target="${1:-}" tmp
    [ -n "$target" ] || return 0
    [ -s "$target" ] || return 0
    tmp="${target}.drain.$$"
    lock_acquire "$target" || true
    mv "$target" "$tmp" 2>/dev/null || tmp=""
    lock_release "$target"
    [ -n "$tmp" ] || return 0
    cat "$tmp" 2>/dev/null
    rm -f "$tmp" 2>/dev/null
    return 0
}
