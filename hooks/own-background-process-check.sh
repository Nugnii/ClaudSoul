#!/usr/bin/env bash
# own-background-process-check.sh — Stop: свой фоновый сервер, живой на границе хода, называется в том же ходе.
# en: Stop hook — names this session's background tasks that still listen on a TCP port at turn end.
#
# Результат: фоновая задача этой сессии, держащая порт TCP на прослушивании, на границе хода названа
#            агенту (ход продолжается), раз на задачу; процессы чужих сессий не называются
# Проверка результата: bash hooks/tests/test_own_background_process_reported.sh даёт 0
#
# Повод — D1313. В ProjectA_NEW трижды за четыре дня (12, 14, 15 ноября 2026) владелец сам находил
# процесс, поднятый агентом ради проверки и пережившие её: `npm run dev` на 3000, `next dev -p 3100`
# 9 ч 40 мин, два цикла `until grep`. Правило «свой процесс гашу сам» лежало в памяти проекта
# текстом и не удержало (pattern-own-background-process-outlives-its-purpose). Все три — задачи
# `run_in_background`.
#
# ПОЧЕМУ ПОРТ, А НЕ «ЗАДАЧА ЖИВА». Реплей 30 расшифровок (17 ноября 2026): границ хода 443, из них
# с живой фоновой задачей 318 — законный порядок «запустил набор фоном, жду уведомления» почти
# всегда оставляет задачу живой на границе, и признак «жива» перезапускал бы каждый второй ход.
# Задач-серверов (по тексту команды), живых на границе, — 43 на те же 30 сессий; под порт попадают
# оба случая с dev-сервером. Правило владельца («ты не стопоришь сервера которые поднимаешь») о
# серверах и говорит: живой свой сервер на границе хода — нарушение, если владелец не просил оставить.
#
# ПРИЗНАК «СВОЯ ЗАДАЧА» — из ядра, не из текста. Харнесс запускает каждую команду Bash прямым
# потомком процесса сессии, и вывод её идёт в файл `<scratch>/tasks/<id>.output` (замер 17 ноября:
# fd 1 у оболочки задачи и у её `sleep`). Корень — ближайший предок хука с именем `claude`; потомок
# корня с fd 1 на файле задачи — задача этой сессии, всё её поддерево — её процессы. Процессы чужой
# сессии висят под другим корнем; серверы MCP — потомки корня, но их вывод — труба, не файл задачи.
#
# Предшественник `mcp-orphan-reap.sh` (SessionEnd) ОСТАЁТСЯ: он снимает серверы MCP с мёртвым
# родителем, этот — называет живые серверы задач, пока сессия идёт. Признак и момент разные,
# устройство «своё по признаку из ядра, чужое не трогать» общее.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ.
#   · Цикл ожидания без порта (третий случай повода) не ловится: «жива на границе» без порта — шум
#     выше (318 из 443). Его держит правило в самой команде: выход и по концу продюсера.
#   · Отвязанный процесс — `cmd &` внутри команды, `nohup … &`, `setsid` — уходит под launchd (ppid 1)
#     и из дерева сессии выпадает: в ядре macOS метки сессии у него нет (окружение `ps -E` чужих
#     процессов не показывает). В трёх случаях повода таких 0; по всем расшифровкам 17 ноября —
#     `nohup` в 5 фоновых командах из 2637, `setsid`/`disown` в 0.
#   · `exec сервер > журнал` в фоновой задаче: сервер сам становится прямым потомком корня с выводом
#     мимо файла задачи и не узнаётся. В расшифровках 0 из 2637 (`exec` без перенаправления — 1, его
#     вывод — файл задачи, он ловится).
#   · Признак завязан на форму харнесса `tasks/<id>.output` (2.1.325, замер 17 ноября). Сменится
#     форма — хук онемеет, и `--dry-run` скажет «0», а не «не измерено»; наблюдений смены — 0.
#   · Команда переднего плана фонового субагента, держащая порт на границе хода родителя, тоже
#     будет названа — раз на задачу.
#   · Нет `lsof` — не измерено: в режиме хука молчит, в `--dry-run` говорит кодом 2.
#
# Канал: `additionalContext` на Stop продолжает ход — так агент гасит сервер, пока владелец ещё
# здесь, а не через 9 часов. Повтор держит дроссель по ключу ЗАДАЧИ, а не «задача:порт»: набор
# тестов, чьи тесты слушают порт 0, на каждой границе показывал бы новый порт, и ключ с портом
# продолжал бы ход заново на каждой границе до конца прогона (скептик D1313, H1). Постоянное
# состояние (сервер оставлен по просьбе) звучит один раз, а не на каждом ходу.
set -uo pipefail

DRY=0
for a in "$@"; do
    case "$a" in
        --dry-run) DRY=1 ;;
        *) echo "usage: $0 [--dry-run]" >&2; exit 2 ;;
    esac
done

INPUT=""
[ "$DRY" -eq 1 ] || INPUT=$(cat)

# Три состояния прибора: «не измерено» в сухом прогоне — код 2 и строка; в хуке — молчание,
# потому что на Stop постоянная жалоба перезапускала бы каждый ход.
unmeasured() {
    [ "$DRY" -eq 1 ] && { printf 'НЕ ИЗМЕРЕНО: %s\n' "$1"; exit 2; }
    exit 0
}

LSOF="${OWN_BG_LSOF:-lsof}"
command -v "$LSOF" >/dev/null 2>&1 || unmeasured "нет lsof"
[ "$DRY" -eq 1 ] || command -v jq >/dev/null 2>&1 || exit 0

PSTABLE=$(ps -ww -eo pid=,ppid=,etime=,args= 2>/dev/null)
[ -n "$PSTABLE" ] || unmeasured "таблица процессов пуста"

# Корень — процесс сессии. Хук бывает внуком (`sh -c` между), поэтому вверх по предкам.
ROOT="${OWN_BG_ROOT_PID:-}"
if [ -z "$ROOT" ]; then
    p=$PPID
    for _ in 1 2 3 4 5 6 7 8; do
        read -r _pid ppid _et a1 a2 _rest <<< "$(awk -v p="$p" '$1 == p' <<< "$PSTABLE")"
        [ -n "${_pid:-}" ] || break
        if [ "${a1##*/}" = claude ] || [ "${a2##*/}" = claude ]; then ROOT=$p; break; fi
        p=$ppid
        case "$p" in ''|0|1) break ;; esac
    done
fi
[ -n "$ROOT" ] && awk -v r="$ROOT" '$1 == r { f = 1 } END { exit !f }' <<< "$PSTABLE" \
    || unmeasured "процесс сессии не найден среди предков хука"

CHILDREN=$(awk -v r="$ROOT" '$2 == r { printf "%s%s", s, $1; s = "," }' <<< "$PSTABLE")
[ -n "$CHILDREN" ] || exit 0

# Оболочки задач: прямой потомок корня, у которого fd 1 — файл `tasks/<id>.output`.
TASKS=$("$LSOF" -a -p "$CHILDREN" -d 1 -Fpn 2>/dev/null | awk '
    /^p/ { pid = substr($0, 2) }
    /^n/ { n = split(substr($0, 2), seg, "/")
           if (n >= 2 && seg[n-1] == "tasks" && seg[n] ~ /\.output$/) { sub(/\.output$/, "", seg[n]); printf "%s:%s ", pid, seg[n] } }')
[ -n "$TASKS" ] || { [ "$DRY" -eq 1 ] && echo "серверов своих задач: 0"; exit 0; }

# Всё поддерево каждой задачи: «pid id».
MEMBERS=$(awk -v tasks="$TASKS" '
    { par[$1] = $2 }
    END {
        n = split(tasks, t, " ")
        for (i = 1; i <= n; i++) { split(t[i], kv, ":"); own[kv[1]] = kv[2] }
        for (p in par) { q = p; d = 0
            while (!(q in own) && (q in par) && d < 64) { q = par[q]; d++ }
            if (q in own) print p, own[q] }
    }' <<< "$PSTABLE")
PIDS=$(awk '{ printf "%s%s", s, $1; s = "," }' <<< "$MEMBERS")

# Слушающие порты процессов задач: «pid порт», без повторов (IPv4 и IPv6 одного порта — одна строка).
LISTEN=$("$LSOF" -nP -a -p "$PIDS" -iTCP -sTCP:LISTEN -Fpn 2>/dev/null | awk '
    /^p/ { pid = substr($0, 2) }
    /^n/ { port = $0; sub(/.*:/, "", port); if (!seen[pid " " port]++) print pid, port }')
[ -n "$LISTEN" ] || { [ "$DRY" -eq 1 ] && echo "серверов своих задач: 0"; exit 0; }

# Строка на ЗАДАЧУ (ключ дросселя — номер задачи, см. шапку, «Канал»): порты списком, pid, возраст, команда
# первого слушающего процесса.
FOUND=$( { sed 's/^/P /' <<< "$PSTABLE"; sed 's/^/M /' <<< "$MEMBERS"; sed 's/^/L /' <<< "$LISTEN"; } | awk '
    $1 == "P" { et[$2] = $4; a = $0; sub(/^P +[0-9]+ +[0-9]+ +[^ ]+ +/, "", a); args[$2] = substr(a, 1, 110); next }
    $1 == "M" { id[$2] = $3; next }
    $1 == "L" && ($2 in id) { t = id[$2]
        if (!(t in pid)) { pid[t] = $2; order[++n] = t }
        if (!((t SUBSEP $3) in seen)) { seen[t, $3] = 1; ports[t] = ports[t] (ports[t] == "" ? "" : ", ") ":" $3 } }
    END { for (i = 1; i <= n; i++) { t = order[i]
        printf "%s\t  · задача %s · порт %s · pid %s · живёт %s · %s\n", t, t, ports[t], pid[t], et[pid[t]], args[pid[t]] } }')
[ -n "$FOUND" ] || { [ "$DRY" -eq 1 ] && echo "серверов своих задач: 0"; exit 0; }

if [ "$DRY" -eq 1 ]; then
    printf 'свои фоновые серверы на границе хода:\n%s\n' "$(cut -f2- <<< "$FOUND")"
    exit 1
fi

# Дроссель «задача» на сессию. Без библиотеки — без дросселя: тогда повтор каждый ход, и это
# хуже, чем промолчать, поэтому молчим.
STATE_DIR="${STATE_DIR:-$HOME/.claude/hooks/state}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for _lib in paths-lib.sh throttle-lib.sh; do
    if [ -f "$HERE/$_lib" ]; then . "$HERE/$_lib"
    elif [ -f "$HOME/.claude/hooks/$_lib" ]; then . "$HOME/.claude/hooks/$_lib"
    fi
done
command -v throttle_file >/dev/null 2>&1 && command -v resolve_session_id >/dev/null 2>&1 || exit 0
mkdir -p "$STATE_DIR" 2>/dev/null || exit 0
THR=$(throttle_file "$STATE_DIR" own-bg-server "$(resolve_session_id "$INPUT")")

LINES=""
while IFS=$'\t' read -r key line; do
    [ -n "$key" ] || continue
    throttle_seen "$THR" "$key" && continue
    throttle_mark "$THR" "$key" 2>/dev/null
    # Отметка не легла (каталог только для чтения, диск полон) — молчим: без неё та же строка
    # звучала бы на каждой границе и перезапускала ход без конца.
    throttle_seen "$THR" "$key" || continue
    LINES="$LINES$line"$'\n'
done <<< "$FOUND"
[ -n "$LINES" ] || exit 0

MSG="🔌 Свой фоновый сервер жив на границе хода (D1313): процесс, поднятый ради проверки, гасит та же работа, а не владелец.
${LINES}Не нужен — погаси по PID (\`kill <pid>\`), не по образцу текста команды. Нужен (владелец просил оставить, на нём идёт прогон) — назови в итоге хода, зачем и кто погасит. По этой задаче повтора не будет."
jq -cn --arg m "$MSG" '{hookSpecificOutput: {hookEventName: "Stop", additionalContext: $m}}'
exit 0
