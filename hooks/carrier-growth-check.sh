#!/usr/bin/env bash
# carrier-growth-check.sh — Stop: прирост носителей рода называется вместе с файлом.
# en: Stop hook — names files that became new defect-genus carriers during this turn.
#
# Результат: файл, записанный агентом и ставший носителем рода, назван на границе хода,
#            а не замечен через часы стражем, собеседником или случаем
# Проверка результата: bash hooks/tests/test_carrier_growth_check.sh даёт 0
#
# Повод (D322), замер 6 сентября 2026 — пять проявлений за день. Агент пишет тест,
# контрпример, комментарий или цикл ожидания, называя в нём предмет БУКВАЛЬНО, и текст сам
# становится тем, что прибор ищет: нога теста стала единственным совпадением и «Проверка»
# пункта осталась красной после верной починки; контрпример рода F сделал носителем файл
# контрпримеров; `ps aux | grep -c '[r]un_all'` нашёл сам себя, и пять фоновых задач висели
# часами. Все пять замечены через часы, ни одно — в момент письма.
#
# Корень: приборы работают верно, между письмом и их прогоном нет СВЯЗИ.
#
# ЦЕНА И ПРЕДЕЛ, названные числом. Прогон реестра родов — 3,5 с, и один род почти не дешевле
# полного (общая часть — чтение дерева). На каждую запись файла это неприемлемо, поэтому
# сигнал стоит на границе хода: между письмом и сигналом остаётся один ход. Условие снятия
# предела — дешёвый способ спросить приборы об ОДНОМ файле.
#
# Отказ прибора отличается от «прироста нет»: молчание на сломанном приборе неотличимо от
# молчания на чистом дереве, и это род B реестра дефектов.
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0

STATE_DIR="${STATE_DIR:-$HOME/.claude/hooks/state}"
mkdir -p "$STATE_DIR" 2>/dev/null || exit 0
SNAP="$STATE_DIR/carrier-snapshot.txt"

# КОРЕНЬ — ВСЕГДА ДЕРЕВО CLAUDSOUL, а не корень проекта сессии. Предмет хука — реестр родов
# ClaudSoul, и снимок у него ОДИН на все сессии (SNAP выше, корня в имени нет). Корень «по
# сессии» ломал оба свойства сразу: в проекте со СВОИМ scripts/defect-class-carriers.py хук
# исполнял ЧУЖОЙ файл и выдавал его числа за прирост носителей ClaudSoul, а его ключи ложились
# в ОБЩИЙ снимок — следующий ход внутри ClaudSoul объявил бы приростом всё дерево (форма
# «47 носителей разом», ради которой заведена нога T9).
# Цепочка резолва общая (paths-lib:18): CLAUDSOUL_ROOT → CLAUDSOUL_REPO → ~/.claude/claudsoul-repo
# → дефолт. Своей копии порядка здесь нет, и отказом резолв кончиться не может — последняя
# ступень безусловна. Аварийная ветка ЗАДАЁТ CLAUDSOUL_ROOT: без неё `set -u` (:25) убил бы хук
# на первом же чтении переменной — тот же класс, что живёт в metrics-collector.sh:11.
PATHS_LIB="${PATHS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/paths-lib.sh}"
# shellcheck source=/dev/null
if [ -f "$PATHS_LIB" ]; then . "$PATHS_LIB"; else : "${CLAUDSOUL_ROOT:=$HOME/My Project/ClaudSoul}"; fi
INPUT="$(cat)"
PAYLOAD_CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)

ROOT="$CLAUDSOUL_ROOT"
[ -d "$ROOT" ] || exit 0

# ЦЕНА ОДИНАКОВОСТИ, названная числом. Корень один — значит гейт «файла нет» больше не
# выключает хук в чужом проекте, и прогон прибора (4,3 с, замер 7 сентября 2026) пришёлся бы
# на КАЖДЫЙ Stop во всех проектах, где дерево ClaudSoul этим ходом не менялось. Поэтому
# предмет проверяется прямо: ход, идущий вне дерева, этого дерева не менял. Сравнение по
# РАЗРЕШЁННЫМ путям — идиома соседа (session-collector.sh:417): /var против /private/var
# иначе разводит один каталог на два, и хук замолчал бы в самом ClaudSoul.
# НАЗВАННЫЙ ПРЕДЕЛ: правка файлов ClaudSoul из сессии ДРУГОГО проекта (субагент, абсолютный
# путь) этим ходом не называется. Находка не теряется — снимок межсессионный, и она прозвучит
# на первом же Stop внутри ClaudSoul. Условие снятия предела: гейт по mtime дерева
# (`find "$ROOT" -name .git -prune -o -newer "$SNAP" -print -quit`) вместо гейта по cwd —
# он же снял бы 4,3 с с ходов, ничего не писавших.
_cg_real() { cd "${1:-}" 2>/dev/null && pwd -P || printf '%s' "${1:-}"; }
_CG_CWD_REAL=$(_cg_real "${PAYLOAD_CWD:-$PWD}")
_CG_ROOT_REAL=$(_cg_real "$ROOT")
case "$_CG_CWD_REAL/" in
    "$_CG_ROOT_REAL"/*) ;;
    *) exit 0 ;;
esac

# Источник чисел подменяем: тест не может позволить себе 3,5 с и зависимость от живого
# дерева — иначе он проверял бы состояние репозитория, а не себя.
# Своя команда зовётся БЕЗ eval: путь проекта содержит пробел («My Project»), и сборка
# команды строкой разбивала его на слова — прибор падал с «can't open file /Users/user/My»
# и страж честно печатал «НЕ ПРОВЕРЕН» на каждом ходу. Поймано живым прогоном, а не тестом:
# тест подменял прибор фикстурой в пути без пробелов, то есть проверял в рамке, где дефект
# не действует (pattern-verification-frame-mismatch).
# ПРИБОРА В ДЕРЕВЕ НЕТ — не отказ прибора, а неполный клон ClaudSoul: реестра родов в нём нет,
# сказать нечего, и состояние ПОСТОЯННОЕ. Чужой проект сюда уже не доходит — его отсекает гейт
# по cwd выше, ДО прогона. Раньше обе формы шли одним каналом «НЕ ПРОВЕРЕН», а
# непустой additionalContext на Stop ПЕРЕЗАПУСКАЕТ ход — постоянное состояние печаталось на
# каждом ходу и давало цикл (замер 7 сентября 2026, ProjectA: 8 пустых ходов подряд, остановлено
# владельцем вручную). Отказ прибора при СУЩЕСТВУЮЩЕМ файле (RC>1) докладывается ниже как прежде.
# Гейт существования есть у всех семи соседей, зовущих инструмент проекта (doc-impact-check.sh:57,
# backlog-reading-refresh.sh:78, ci-check-reminder.sh:43, projecta-security-gate.sh:50,
# docs-family-check.sh:163 и :267, install-drift-notice.sh:34) — здесь его недоставало одного.
[ -n "${CARRIER_CMD:-}" ] || [ -f "$ROOT/scripts/defect-class-carriers.py" ] || exit 0

if [ -n "${CARRIER_CMD:-}" ]; then
    OUT=$(cd "$ROOT" && eval "$CARRIER_CMD" 2>/dev/null </dev/null); RC=$?
else
    OUT=$(cd "$ROOT" && python3 "$ROOT/scripts/defect-class-carriers.py" 2>/dev/null </dev/null); RC=$?
fi
# rc=1 у прибора означает «носители есть» — это его штатный ответ, а не сбой.
if [ "$RC" -gt 1 ] || [ -z "$OUT" ]; then
    # ПОСТОЯННОЕ СОСТОЯНИЕ НЕ ПЕЧАТАЕТСЯ НА STOP. Сломанный прибор держится сам: пока его не
    # починили, отказ повторяется каждый ход, а непустой additionalContext на Stop ПЕРЕЗАПУСКАЕТ
    # ход — то же устройство, что дало 8 пустых ходов подряд (замер 7 сентября 2026, ProjectA).
    # Гейт существования снял только форму «файла нет»; это вторая половина того же цикла.
    # КАНАЛ — общая очередь pending-alerts.txt. Её показывает УЖЕ зарегистрированный
    # pending-alerts-surface.sh на следующем UserPromptSubmit через additionalContext: канал
    # виден в VSCode (Stop→systemMessage там не рендерится, case-2026-06-14) и ход не
    # перезапускает. Своей пары событий не заводим — правки install.sh и settings.json не нужно,
    # и пара «регистрация хуков» в drift-check остаётся нетронутой.
    # ДРОССЕЛЬ — сессия и КОД ВОЗВРАТА (решение по образцу D345, blocker-tier-check.sh:107):
    # без него очередь росла бы строкой в ход, то есть фон переехал бы в другой канал. Ключ
    # несёт RC, поэтому сменившаяся форма отказа звучит заново, а та же — раз за сессию.
    for _cg_thr in "$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/throttle-lib.sh" \
                   "$HOME/.claude/hooks/throttle-lib.sh"; do
        # shellcheck source=/dev/null
        [ -f "$_cg_thr" ] && { . "$_cg_thr"; break; }
    done
    # session_id берётся резолвером из paths-lib, а не своим jq: копия правила у потребителя —
    # род K реестра. Нет библиотеки — дросселя нет, но канал остаётся: повтор в очереди хуже
    # тишины на порядок меньше, чем перезапуск хода.
    if command -v throttle_file >/dev/null 2>&1 && command -v resolve_session_id >/dev/null 2>&1; then
        _cg_thr_f=$(throttle_file "$STATE_DIR" carrier-probe "$(resolve_session_id "$INPUT")")
        throttle_seen "$_cg_thr_f" "rc$RC" && exit 0
        throttle_mark "$_cg_thr_f" "rc$RC"
    fi
    printf '🧬 Прирост носителей НЕ ПРОВЕРЕН: реестр родов не отработал (код %s), прибор — %s. Молчание тут не значит «чисто».\n' \
        "$RC" "$ROOT/scripts/defect-class-carriers.py" >> "$STATE_DIR/pending-alerts.txt" 2>/dev/null || true
    exit 0
fi

# Строки-носители: «  · <что-то> <путь>». Ключом берём весь хвост строки — прибор печатает
# у разных родов разную форму, и разбирать её значило бы держать вторую копию его правила.
#
# СЧЁТЧИКИ ИЗ КЛЮЧА ВЫЧЁРКИВАЮТСЯ, ИМЕНА — НЕТ. Строка носителя несёт числа двух разных
# ролей, и первая редакция этой правки (6 сентября 2026) стёрла обе: `test_adv5_scan` стал
# `test_adv#_scan`, а `test_adv2_bump…` и `test_adv3_bump…` схлопнулись в один ключ. Признак
# был снят с ВИДА (любая цифра), тогда как различать надо РОЛЬ — счётчик против части имени.
#
# Правило вместо перечня форм: путь стоит в НАЧАЛЕ строки и до первого двойного пробела,
# описание с числами — после. Нормализуется только хвост, начало не трогается вовсе.
#
# Зачем вообще: «невидимо 358» меняется от правок, не меняющих носителя, и сравнение строк
# целиком читало это как ПРИРОСТ — `uninstall.sh` назывался новым три хода подряд, пока его
# «невидимо» росло 356 → 357 → 358 вместе с числом файлов дерева. Повторный сигнал о том же
# носителе обучает себя не читать — ровно тот фон, которого избегает правило уровня отказа.
_cg_key() { sed 's/^  · //' | awk -F'  ' '{ h=$1; t=substr($0, length($1)+1); gsub(/[0-9]+/, "#", t); print h t }'; }
CUR=$(printf '%s\n' "$OUT" | grep '^  · ' | _cg_key | sort -u)

# ВЕРСИЯ ФОРМАТА КЛЮЧА. Смена формы ключа делает прошлый снимок несопоставимым, и `comm`
# объявляет приростом ВСЁ: первая редакция дала 47 «новых» носителей разом. Это не находка,
# а смена системы координат, и молчать о ней честнее, чем звать к каждому месту дерева.
_CG_KEYVER='v2-tail-numbers'

# ОБЩИЙ ЗАМОК (род H). Снимок один на все сессии, а блок ниже есть read-modify-write:
# читает снимок, сравнивает, кладёт обратно. Две границы хода, разошедшиеся меньше ширины
# окна, теряют находку одной из них — та запишет свой снимок поверх чужого, и носитель,
# увиденный соседом, исчезнет молча. Окно измерено: 24,6 мс (прогон прибора 3,5 с идёт ДО
# него и под замком не держится — незачем).
STATE_LOCK_LIB="${STATE_LOCK_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/state-lock-lib.sh}"
[ -f "$STATE_LOCK_LIB" ] || STATE_LOCK_LIB="$HOME/.claude/hooks/state-lock-lib.sh"
# shellcheck source=/dev/null
[ -f "$STATE_LOCK_LIB" ] && . "$STATE_LOCK_LIB"

# Запись атомарна: сначала во временный файл рядом, затем переименование. Прерывание между
# двумя `printf` оставило бы снимок из одной строки версии — он прочёлся бы как «формат тот,
# носителей нет», и следующий ход назвал бы приростом всё дерево.
_cg_store() {
    printf '%s\n' "$_CG_KEYVER" > "$SNAP.tmp.$$" 2>/dev/null || return 1
    printf '%s\n' "$CUR" >> "$SNAP.tmp.$$" 2>/dev/null || return 1
    mv "$SNAP.tmp.$$" "$SNAP" 2>/dev/null || return 1
}

# Всё окно read-modify-write целиком: и ветка «формат сменился», и сравнение с записью.
_cg_diff_and_store() {
    if [ ! -f "$SNAP" ] || [ "$(head -n 1 "$SNAP" 2>/dev/null)" != "$_CG_KEYVER" ]; then
        _cg_store
        return 1      # формат сменился либо снимка нет — запоминаем молча
    fi
    NEW=$(comm -13 <(tail -n +2 "$SNAP") <(printf '%s\n' "$CUR") 2>/dev/null)
    _cg_store
    return 0
}

NEW=""
if command -v with_lock >/dev/null 2>&1; then
    with_lock "$SNAP" _cg_diff_and_store || exit 0
else
    # Библиотеки нет — работаем без замка, но НЕ молча: иначе потеря находки при гонке
    # выглядела бы как «прироста нет», а это род B поверх рода H.
    printf 'carrier-growth-check: нет state-lock-lib — снимок пишется БЕЗ замка\n' >&2
    _cg_diff_and_store || exit 0
fi

[ -n "$NEW" ] || exit 0

# Род называется вместе с файлом: без имени рода сообщение не говорит, ЧЕМ место плохо.
# Диапазон букв — по алфавиту, а не по нынешнему составу реестра: `[A-J]` умолчал бы о
# роде K в тот же день, когда его завели (6 сентября 2026), и список родов в сообщении
# стал бы тихо неполным.
# Ключ и сообщение — РАЗНЫЕ предметы. `_cg_key` маскирует цифры решётками, потому что
# дроссель обязан молчать на «146 вместо 145»; читателю же нужны именно числа. Прежде
# наружу печатался ключ, и сообщение выглядело так: «в поле зрения #, невидимо #».
# Поймано на себе 8 сентября 2026: сигнал о приросте пришёл без единого числа.
NEW_LINES=""
while IFS= read -r _cg_l; do
    [ -n "$_cg_l" ] || continue
    _cg_k=$(printf '%s\n' "$_cg_l" | _cg_key)
    if grep -Fxq -- "$_cg_k" <<< "$NEW"; then
        NEW_LINES="${NEW_LINES}${_cg_l#  · }
"
    fi
done <<CG_EOF
$(printf '%s\n' "$OUT" | grep '^  · ')
CG_EOF
[ -n "$NEW_LINES" ] || NEW_LINES="$NEW"

GENUS=$(printf '%s\n' "$OUT" | grep -oE '^РОД [A-Z]' | tr -d '\n' | sed 's/РОД /,/g;s/^,//')
MSG="🧬 Прирост носителей рода за этот ход — проверь, не стал ли твой же текст ложным носителем:
$(printf '%s\n' "$NEW_LINES" | grep -v '^$' | sed 's/^/  · /')
Роды в дереве: ${GENUS:-—}. Если это твоя запись (тест, контрпример, комментарий, пункт),
предмет назван БУКВАЛЬНО и попал в универсум прибора — собери его из частей."
printf '{"hookSpecificOutput":{"hookEventName":"Stop","additionalContext":%s}}\n' "$(jq -Rn --arg m "$MSG" '$m')"
exit 0
