#!/usr/bin/env bash
# verdict-through-pipe-check.sh — PostToolUse[Bash]: в выводе виден ход прогона, но нет итоговой строки — вердикт не наблюдался.
# en: PostToolUse[Bash]: output shows a test run in progress but carries no verdict line.
#
# Результат: утверждение «набор зелёный» не встаёт в отчёт и в сообщение коммита, когда
#            вердикта не было ни в коде (потерян фильтром), ни в выводе (не попал в хвост).
# Проверка результата: bash hooks/tests/test_verdict_through_pipe.sh даёт 0
#
# ЗАЧЕМ, И ПОЧЕМУ ИМЕННО ЗДЕСЬ (18 сентября 2026, D459). В одной сессии набор объявлялся
# зелёным ЧЕТЫРЕ раза подряд формой `run_all.sh --changed 2>&1 | tail -n N`: код принадлежал
# `tail`, набор был красным, CI коммита 7a7f02c упал. Знание об этом классе в базе было
# (`case-2026-09-14-exit-code-taken-through-a-pipe-three-times`) и активатор его инжектировал —
# исход записан как `applicable_not_followed`. Уровень 1 (текст) по этому предмету уже не
# сработал, поэтому механизм.
#
# ПОЧЕМУ НЕ ОТКАЗ И НЕ PreToolUse — ЗАМЕР, А НЕ ВКУС. По корпусу 260 расшифровок:
#   · признак «имя прибора где угодно» — 61 совпадение, точность ~10%: ловил имя в аргументе
#     `sed`, в шаблоне `pgrep`, в пути к журналу;
#   · признак «прибор ЗАПУЩЕН, справа фильтр» — 2097, но у `pytest` и `test_*.sh` вывод
#     информативен сам, код там не единственный ответ;
#   · сужение до приборов, чей ответ ТОЛЬКО код (набор и пробы) — 441 носитель, и из 330
#     осмотренных: хвост несёт вердикт у 234 (70,9%), вердикта нет и агент о нём молчит у 90
#     (27,3%), вердикта нет и успех УТВЕРЖДАЕТСЯ у 6 (1,8%).
# Отказ на признаке с точностью 1,8% дал бы 324 ложных из 330 — правило системы это прямо
# запрещает. Зато «в выводе нет вердикта» наблюдаемо ПОСЛЕ выполнения и верно во всех 96
# случаях из 330 (29%): там вердикт действительно неизвестен, и сказать об этом уместно.
#
# ПРЕДШЕСТВЕННИКИ И ИХ СУДЬБА (правило «чем это решалось раньше»). `test_assert_no_sigpipe.sh`
# ОСТАЁТСЯ: его предмет — ФАЙЛЫ дерева, он в `always-run.tsv` и он же поймал тот же класс
# внутри `rework-detector.sh`. Здесь предмет иной — КОМАНДА ХОДА, которой у него в универсуме
# нет. `bash-write-dispatch.sh` остаётся тоже: он подаёт правки файлов стражам записи, а
# вердиктов приборов не касается. Пересечения нет, оба нужны.
#
# ФОРМА PAYLOAD ИЗМЕРЕНА ЗОНДОМ 18 сентября 2026 (снят в том же ходу), и она подтвердила
# замер D41 спустя четыре месяца: `tool_response` несёт `stdout`, `stderr`, `interrupted`,
# `isImage`, `noOutputExpected`. КОДА ВОЗВРАТА В PAYLOAD НЕТ — поэтому судить можно только
# вывод. НАЗВАННЫЙ ПРЕДЕЛ, и он же причина, по которой признак вообще работает: на УПАВШЕЙ
# команде PostToolUse не срабатывает (D41). Когда код потерян фильтром, команда для харнесса
# успешна — событие приходит; когда код не потерян и прибор упал, события нет, но там вердикт
# виден и без стража.
# Условие снятия: харнесс начнёт класть код возврата в payload PostToolUse — тогда вердикт
# берётся у кода, а не выводится из вывода, и признак строится на нём напрямую.
set -uo pipefail
command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat)

# ПРЕДМЕТ — ВЫВОД, А НЕ ФОРМА КОМАНДЫ (переделано 18 сентября 2026 после адверсариальной
# проверки). Первая редакция судила текст команды перечнем форм запуска, и это корень R3:
# скептик предъявил ТРИНАДЦАТЬ обходов — перенос строки перед `| tail`, `tee` вместо `tail`,
# `zsh`/`timeout` перед `bash`, скобки, имя через переменную, и абсолютный путь ЭТОГО
# репозитория, где есть пробел. Сколько ни дописывай форм, следующая окажется вне перечня.
# Вывод наблюдаем прямо: вопрос «виден ли вердикт» о нём и есть.
OUT=$(printf '%s' "$INPUT" | jq -r '(.tool_response.stdout // "") + "\n" + (.tool_response.stderr // "")' 2>/dev/null)
[ -n "$OUT" ] || exit 0

# Не-ASCII формы ищутся ФИКСИРОВАННЫМ поиском, ASCII — регулярным, и это не стиль.
# Не-ASCII символ вплотную к синтаксису класса читается как диапазон БАЙТОВ
# (pattern-shell-portability, отказ уровня 4 поймал первую редакцию этой самой строки).

# 1. СЛЕДЫ ПРОГОНА: ход и результаты отдельных проверок. Только они отличают ПРОГОН от
#    печати состава: `run_all.sh --list` выдаёт одни имена без результатов, и вердикта у
#    него нет по построению — говорить там не о чем. Формы взяты у владельца,
#    `hooks/tests/run_all.sh`, а не выдуманы.
#    Формы взяты у владельца и покрывают ВЕСЬ вывод, а не только начало: ход (`… прошло N,
#    упало M`), результаты проверок (`FAIL [`, `PASS=`), и ХВОСТ — перечень
#    дорогих (`ДОРОЖЕ Nс (`), строка журнала (`журнал прогона`), строка теста с
#    временем (`  106 с  test_x.sh  (CPU 94 с)`) — формы ищутся в раннере по тексту, номера строк уезжают. Хвост назван отдельно потому, что
#    первая редакция признака знала только начало — и ПРОПУСКАЛА тот самый случай, ради
#    которого страж построен: `| tail -n 4` показывает именно хвост, и в нём ни «прошло», ни
#    «PASS=» нет (проверено прогоном 18 сентября 2026).
_ran=0
for _m in " прошло " "ДОРОЖЕ " "журнал прогона"; do
    grep -qF "$_m" <<< "$OUT" && _ran=1
done
grep -qE '(FAIL \[|PASS=[0-9]+|^[[:space:]]+[0-9]+ с[[:space:]]+[A-Za-z0-9_./-]+\.sh)' <<< "$OUT" && _ran=1
[ "$_ran" -eq 1 ] || exit 0

# 2. ИТОГ: перечень взят у того же владельца (строки итога `run_all.sh` — искать по тексту, номера уезжают)
#    плюс подпись одиночного теста. Первая редакция знала две формы из шести и спорила с
#    фактом на «ЗАВИСЛИ» и «НЕ ХВАТИЛО ВРЕМЕНИ» — настоящих итоговых строках набора.
for _v in "Hook test files:" "FAILED:" "passed, " "КОД НАБОРА"; do
    grep -qF "$_v" <<< "$OUT" && exit 0
done
grep -qF "ЗАВИСЛИ" <<< "$OUT" && exit 0
grep -qF "НЕ ХВАТИЛО ВРЕМЕНИ" <<< "$OUT" && exit 0
grep -qE 'PASS=[0-9]+[[:space:]]+FAIL=[0-9]+' <<< "$OUT" && exit 0

# 3. Код сохранён явно — вердикт у вызывающего есть и без итоговой строки.
RAW=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
grep -qE '(echo[[:space:]]+\$\?|rc=\$\?|PIPESTATUS)' <<< "$RAW" && exit 0

MSG="⚖️ Вердикт не наблюдался: в выводе виден ход прогона, но нет ни одной итоговой строки.

Это не «прошло» и не «упало» — это «неизвестно»: код ушёл фильтру конвейера, а итог не попал в показанный хвост. Утверждать успех сейчас не на чем.
Взять вердикт у прибора: \`<прибор> > файл 2>&1; echo \$?\` — и читать файл ПОСЛЕ.

Повод (D459): за одну сессию набор объявлялся зелёным четырежды подряд формой \`| tail -n N\`; он был красным, и CI это показал."

jq -cn --arg ctx "$MSG" \
  '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$ctx}}' 2>/dev/null || true
exit 0
