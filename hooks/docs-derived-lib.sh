#!/usr/bin/env bash
# docs-derived-lib.sh — ЕДИНСТВЕННОЕ определение производного документа: переводной версии, пересобираемой из источника.
#
# ПРЕФИКСЫ: docs_derived_
# Объявление пространства имён — сверяет `hooks/lib-prefix-guard.sh` при записи файла;
# имя с ведущим `_` считается внутренним и под правило не подпадает.
#
# Результат: у производного документа один признак — строка `<!-- derived-from: <источник>@<хеш> -->`
#            в первых пяти строках, и все читатели узнают его состояние одной функцией
# Проверка результата: bash hooks/tests/test_docs_derived.sh даёт 0
#
# Зачем (14 сентября 2026, решение владельца). В работе живёт одна языковая версия — русская;
# английская пересобирается перед публикацией. До этого дня обе версии правились в связке
# (39 коммитов README из 40 тронули оба файла), и реестр чисел держал по 59 строк на каждый
# язык. Правило «вторая версия не участвует в работе» без механизма означало бы одно из двух:
# либо сверщики краснеют на отставшем переводе в каждой сессии, либо отставший перевод уходит
# наружу. Здесь третье: отставание ЗАПИСАНО в самом файле хешем источника; сверщики в работе
# пропускают отставший производный и называют это числом; публикация на отставшем ОТКАЗЫВАЕТ
# поимённо (scripts/docs-derived-check.sh, предусловие scripts/publish-public.sh).
#
# ЧЕМ РЕШАЛОСЬ РАНЬШЕ (правило «новый механизм начинается с вопроса, чем это решалось»):
#   · scripts/docs-duplicates.sh выводит язык документа перевесом букв и в своей шапке называет
#     условие снятия этого предела — «появится явное объявление языка в самом документе (поле
#     шапки)». Эта шапка и есть такое объявление. Судьба предшественника: ОСТАЁТСЯ, и новый
#     механизм его не зовёт; подключение сверщика дублей к объявлению — отдельный заход, здесь
#     не делается, и это названо.
#   · scripts/regen-readme-skills.sh собирает автотаблицы справочника в ОБЕ языковые версии
#     из исходников — это генерация, а не перевод; остаётся: перевод касается прозы, таблицы
#     регенерируются поверх.
#   · scripts/count-stats.sh патчит строку чисел в обоих README — остаётся тем же доводом.
#
# ХЕШ — `git hash-object` источника, первые 12 знаков: содержимое, а не время; считается без
# репозитория (тесты в песочнице) и одинаково на macOS и Linux. Путь источника в шапке —
# относительно корня репозитория, как в индексе зависимостей. Корень: DOCS_DERIVED_ROOT,
# иначе верх git у каталога файла, иначе сам каталог.
#
# СОСТОЯНИЯ (docs_derived_state): none — шапки нет, документ не производный; fresh — хеш
# совпал; stale — источник ушёл вперёд; broken — шапка есть, а источника нет или не читается.
# Коды 0/0/1/2 — «сломан» и «отстал» разными кодами, три состояния прибора.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ. Хеш ловит ЛЮБУЮ правку источника, включая правку одной цифры генератором
# count-stats: производный станет «отставшим» и потребует пересборки, хотя перевод прозы не
# менялся. Это принято сознательно — различать «изменилась цифра» и «изменилась проза» значило
# бы держать второй хеш по нормализованному тексту, и первую же ошибку нормализации никто бы не
# увидел. Стамп при отсутствии шапки ставит её ПЕРВОЙ строкой; документ с YAML-шапкой (`---`)
# получил бы комментарий выше неё — таких документов среди производных нет, и это не ловится.
#
# Контракт функций: чистые чтения; мир меняет только docs_derived_stamp, и она названа.
#
# ЗАМОК (род H, поймано прибором родов в час написания). `docs_derived_stamp` правит README и
# справочник — файлы, в которые пишут и другие механизмы (`count-stats.sh:180` под замком,
# `docs-refresh-claims.sh` из python). Временный файл с `mv` даёт атомарность ОДНОГО писателя;
# от потери ЧУЖОЙ правки защищает только общий замок, и единица блокировки — ФАЙЛ, то же имя,
# что берут соседи. Библиотеки замка нет — правка идёт без него и это СКАЗАНО вслух, а не
# подразумевается: молчание тут неотличимо от «замок взят».
STATE_LOCK_LIB="${STATE_LOCK_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/state-lock-lib.sh}"
[ -f "$STATE_LOCK_LIB" ] || STATE_LOCK_LIB="$HOME/.claude/hooks/state-lock-lib.sh"
# shellcheck source=/dev/null
[ -f "$STATE_LOCK_LIB" ] && . "$STATE_LOCK_LIB"
command -v lock_acquire >/dev/null 2>&1 || {
    printf 'docs-derived-lib: нет state-lock-lib — штамп ставится БЕЗ замка\n' >&2
    lock_acquire() { :; }; lock_release() { :; }
}

docs_derived_header() {   # <файл> → строка шапки derived-from из первых пяти строк; код 1 — её нет
    [ -f "${1:-}" ] || return 1
    _ddl=$(awk 'NR<=5 && /^<!-- derived-from: [^ @]+@[0-9a-f]+ -->/ {print; exit}' "$1" 2>/dev/null)
    [ -n "$_ddl" ] || return 1
    printf '%s\n' "$_ddl"
}

docs_derived_source() {   # <файл> → путь источника относительно корня; код 1 — не производный
    _dds=$(docs_derived_header "${1:-}") || return 1
    printf '%s\n' "$_dds" | sed -E 's/^<!-- derived-from: ([^ @]+)@([0-9a-f]+) -->.*/\1/'
}

docs_derived_recorded_hash() {   # <файл> → хеш из шапки; код 1 — шапки нет
    _ddr=$(docs_derived_header "${1:-}") || return 1
    printf '%s\n' "$_ddr" | sed -E 's/^<!-- derived-from: ([^ @]+)@([0-9a-f]+) -->.*/\2/'
}

docs_derived_hash() {   # <путь> → первые 12 знаков git hash-object; код 1 — файла нет
    [ -f "${1:-}" ] || return 1
    # Без фильтров (D517): с ними hash-object исполнял clean-фильтр из настроек репозитория, в
    # котором стоит каталог процесса, — у стража docs-family-check это чужая папка сессии на
    # `git commit` агента. У ClaudSoul атрибутов нет, хеши в шапках от этого не меняются.
    git hash-object --no-filters -- "$1" 2>/dev/null | cut -c1-12
}

docs_derived_root() {   # <файл> → корень, от которого читается путь источника
    if [ -n "${DOCS_DERIVED_ROOT:-}" ]; then printf '%s\n' "$DOCS_DERIVED_ROOT"; return 0; fi
    _ddd=$(cd "$(dirname "${1:-.}")" 2>/dev/null && pwd) || return 1
    git -C "$_ddd" rev-parse --show-toplevel 2>/dev/null || printf '%s\n' "$_ddd"
}

docs_derived_state() {   # <файл> → none|fresh|stale|broken; коды 0/0/1/2
    _ddsrc=$(docs_derived_source "${1:-}") || { printf 'none\n'; return 0; }
    _ddroot=$(docs_derived_root "$1") || { printf 'broken\n'; return 2; }
    [ -f "$_ddroot/$_ddsrc" ] || { printf 'broken\n'; return 2; }
    _ddwant=$(docs_derived_hash "$_ddroot/$_ddsrc") || { printf 'broken\n'; return 2; }
    [ -n "$_ddwant" ] || { printf 'broken\n'; return 2; }
    _ddhave=$(docs_derived_recorded_hash "$1")
    if [ "$_ddwant" = "$_ddhave" ]; then printf 'fresh\n'; return 0; fi
    printf 'stale\n'; return 1
}

docs_derived_stamp() {   # <производный> <источник-относительно-корня> — пишет/обновляет шапку; код 2 — не смог
    _ddf="${1:-}"; _ddsrc="${2:-}"
    [ -f "$_ddf" ] && [ -n "$_ddsrc" ] || return 2
    _ddroot=$(docs_derived_root "$_ddf") || return 2
    [ -f "$_ddroot/$_ddsrc" ] || return 2
    _ddhash=$(docs_derived_hash "$_ddroot/$_ddsrc") || return 2
    [ -n "$_ddhash" ] || return 2
    _ddline="<!-- derived-from: ${_ddsrc}@${_ddhash} -->"
    _ddtmp="$_ddf.tmp.$$"
    # Замок на том же имени, что у соседних писателей файла (род H): окно чтение→запись
    # закрыто, временный файл рядом с целью держит `mv` переименованием в пределах раздела.
    lock_acquire "$_ddf"
    if docs_derived_header "$_ddf" >/dev/null 2>&1; then
        awk -v line="$_ddline" 'NR<=5 && !done && /^<!-- derived-from: / {print line; done=1; next} {print}' "$_ddf" > "$_ddtmp" \
            || { rm -f "$_ddtmp"; lock_release "$_ddf"; return 2; }
    else
        { printf '%s\n' "$_ddline"; cat "$_ddf"; } > "$_ddtmp" || { rm -f "$_ddtmp"; lock_release "$_ddf"; return 2; }
    fi
    mv "$_ddtmp" "$_ddf"; _ddrc=$?
    lock_release "$_ddf"
    return $_ddrc
}

docs_derived_list() {   # <корень> → отслеживаемые производные документы, по одному на строку, относительно корня
    # Корень ОБЯЗАТЕЛЕН. Умолчание брало его у каталога ПРОЦЕССА: у библиотеки хука payload
    # с полем .cwd, а каталог процесса ей не вход (D275, класс третьей волны). Потребитель
    # один и корень передаёт сам (scripts/docs-derived-check.sh:71) — ветка была мёртвой.
    _ddlr="${1:-}"
    [ -d "$_ddlr" ] || return 2
    git -C "$_ddlr" ls-files -- '*.md' 2>/dev/null | while IFS= read -r _ddp; do
        docs_derived_header "$_ddlr/$_ddp" >/dev/null 2>&1 && printf '%s\n' "$_ddp"
    done
    return 0
}
