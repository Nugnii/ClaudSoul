#!/usr/bin/env bash
# portable-lib.sh — команды, у которых на BSD и GNU разный синтаксис.
#
# Повод конкретный. CI на Ubuntu падал одиннадцатью тестами хуков, при том что на машине
# разработки все были зелёными. Первая же строка причин после того, как раннер научился их
# печатать: `date: invalid option -- 'j'`. Ключ `-j` есть у BSD date (macOS) и отсутствует
# у GNU date (Linux); то же с `stat -f` против `stat -c`.
#
# Замер до починки: 15 вызовов `date -j` и 8 вызовов `stat -f` в девяти файлах хуков.
# Каждый из них работал ровно на одной системе — а проект объявляет себя устанавливаемым
# на чистую машину, и `install.sh` про операционную систему ничего не спрашивает.
#
# Почему библиотека, а не правка по месту: 23 вызова — это 23 копии условия, и первая же
# правка условия разойдётся с остальными. В проекте уже есть образец такой развязки —
# `hash-lib.sh` выбирает между `md5sum` и `md5`. Здесь то же самое для времени и файлов.
#
# Порядок проб везде GNU → BSD, а не наоборот: цель — чтобы чужая машина работала, а на
# машине разработки достаточно, чтобы работала вторая ветка. Обратный порядок дал бы
# зелёное локально и красное всюду, то есть ровно ту рамку проверки, из-за которой
# расхождение и жило (`pattern-verification-frame-mismatch`).
#
# Функции:
#   iso_epoch  <метка> [формат]  → секунды эпохи, 0 если разобрать не удалось
#   file_mtime <путь>            → время изменения в секундах, 0 если файла нет

# iso_epoch "2026-07-29T04:12:00Z"            → эпоха (UTC, суффикс Z)
# iso_epoch "2026-07-29T04:12:00"             → эпоха (локальное время)
# iso_epoch "2026-07-29 04:12" "%Y-%m-%d %H:%M" → эпоха по явному формату
#
# Суффикс `Z` различает шкалы. `correction-fired` пишет UTC с `Z`, а `injection-log`
# до v1.12.0 писал локальное время без суффикса — на машине с +02:00 наивный джойн двух
# логов разъехался бы на два часа, а с переходом на летнее время плавал бы.
iso_epoch() {
    local ts="${1:-}" fmt="${2:-}"
    [ -n "$ts" ] || { echo 0; return; }

    if [ -n "$fmt" ]; then
        date -d "$ts" +%s 2>/dev/null && return
        date -j -f "$fmt" "$ts" +%s 2>/dev/null && return
        echo 0; return
    fi

    # Голая дата приводится к полуночи явно. Иначе BSD `date -j -f "%Y-%m-%d"` заполняет
    # неуказанные поля ТЕКУЩИМ временем суток и молча возвращает «сегодня в 05:12» вместо
    # начала дня — разбор выглядит успешным, а значение выдумано. GNU date в том же случае
    # даёт полночь, то есть две системы расходились бы на случайную величину до суток.
    case "$ts" in
        [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ts="${ts}T00:00:00" ;;
    esac

    case "$ts" in
        *Z)
            date -u -d "$ts" +%s 2>/dev/null && return
            date -u -j -f "%Y-%m-%dT%H:%M:%SZ" "$ts" +%s 2>/dev/null && return
            ;;
        *)
            date -d "$ts" +%s 2>/dev/null && return
            date -j -f "%Y-%m-%dT%H:%M:%S" "$ts" +%s 2>/dev/null && return
            date -j -f "%Y-%m-%d" "$ts" +%s 2>/dev/null && return
            ;;
    esac
    echo 0
}

# file_mtime <путь> → время изменения в секундах эпохи, 0 если файла нет или не читается.
# Ноль вместо пустоты намеренно: все потребители считают возраст вычитанием, и пустая
# строка превратила бы арифметику в синтаксическую ошибку, а ноль даёт «очень старый» —
# то есть ошибку в безопасную сторону.
file_mtime() {
    local f="${1:-}"
    [ -n "$f" ] && [ -e "$f" ] || { echo 0; return; }
    stat -c %Y "$f" 2>/dev/null && return
    stat -f %m "$f" 2>/dev/null && return
    echo 0
}

# to_lower <текст> → тот же текст в нижнем регистре, включая кириллицу.
#
# `tr '[:upper:]' '[:lower:]'` для кириллицы работает ТОЛЬКО на BSD. GNU tr обрабатывает
# ввод побайтно и многобайтовые символы не сворачивает ни в какой локали — проверено, что
# `LC_ALL=C.UTF-8` не помогает, это разница реализаций, а не настройки:
#
#   printf 'Подожди' | tr '[:upper:]' '[:lower:]'
#   macOS  → подожди        debian → Подожди
#
# Цена этого различия высокая: каждый детектор, который приводит реплику к нижнему регистру
# и ищет русские слова, на Linux молча не срабатывает — включая `trust-guard`, где ломаются
# сразу и распознавание согласия, и распознавание разрушительного намерения.
#
# Два пути, а не один. Основной — арифметика по кодовым точкам в jq: 1040..1071 (А-Я) +32,
# 1025 (Ё) → 1105 (ё), плюс `ascii_downcase` для латиницы. Он точен и от локали не зависит.
# Запасной — побайтовая замена через sed: нужен там, где jq недоступен, а хук обязан
# деградировать молча, а не выключаться.
#
# Отвергнутые замены, каждая проверена: `grep -iF` — BSD grep не складывает кириллицу ни
# в одной локали; `${var,,}` — bash 3.2 на macOS такого не знает, а bash 5 не берёт
# кириллицу; `tolower` в mawk — только ASCII; `sed y/…/…/` в локали C даёт мусор.
# Отвергнут и третий приём, встретившийся в проекте, — перечислять оба написания в шаблоне
# («затем|Затем»): он покрывает только заглавную первую букву и промахивается на «ЗАТЕМ».
to_lower() {
    local s="${1:-}"
    [ -n "$s" ] || return 0
    if command -v jq >/dev/null 2>&1; then
        local out
        out=$(printf '%s' "$s" | jq -Rsr 'ascii_downcase | explode
              | map(if . >= 1040 and . <= 1071 then . + 32 elif . == 1025 then 1105 else . end)
              | implode' 2>/dev/null)
        # jq добавляет перевод строки к результату -Rsr; исходная строка его не содержала.
        if [ -n "$out" ]; then printf '%s' "${out%$'\n'}"; return 0; fi
    fi
    printf '%s' "$s" | tr '[:upper:]' '[:lower:]' | sed \
        -e 's/А/а/g' -e 's/Б/б/g' -e 's/В/в/g' -e 's/Г/г/g' -e 's/Д/д/g' \
        -e 's/Е/е/g' -e 's/Ё/ё/g' -e 's/Ж/ж/g' -e 's/З/з/g' -e 's/И/и/g' \
        -e 's/Й/й/g' -e 's/К/к/g' -e 's/Л/л/g' -e 's/М/м/g' -e 's/Н/н/g' \
        -e 's/О/о/g' -e 's/П/п/g' -e 's/Р/р/g' -e 's/С/с/g' -e 's/Т/т/g' \
        -e 's/У/у/g' -e 's/Ф/ф/g' -e 's/Х/х/g' -e 's/Ц/ц/g' -e 's/Ч/ч/g' \
        -e 's/Ш/ш/g' -e 's/Щ/щ/g' -e 's/Ъ/ъ/g' -e 's/Ы/ы/g' -e 's/Ь/ь/g' \
        -e 's/Э/э/g' -e 's/Ю/ю/g' -e 's/Я/я/g'
}

# reverse_lines <файл> → строки файла в обратном порядке.
#
# `tail -r` есть только у BSD; у GNU обратный вывод делает `tac`, которого нет на macOS.
# Молчаливая цена различия: `reformulation-tracker` читает так последнее сообщение агента,
# и на Linux `tail -r` падает, вывод пуст — триггеры FORWARD и PROPOSAL не срабатывали
# никогда. Тест это показывал, но только в контейнере: на машине разработки всё зелено.
reverse_lines() {
    local f="${1:-}"
    [ -n "$f" ] && [ -f "$f" ] || return 0
    tac "$f" 2>/dev/null && return 0
    tail -r "$f" 2>/dev/null && return 0
    return 0
}

# pad_words <текст> → текст, где знаки препинания заменены пробелами, пробелы схлопнуты,
# а строка обрамлена пробелами. Нужен, чтобы искать слово точной подстрокой `" $слово "`
# вместо регулярного выражения с границей слова.
#
# Почему не регулярное выражение. Граница слова через класс символов с кириллицей
# (`[^а-яё]`) непереносима: GNU grep отвергает такой диапазон в локали `C.UTF-8` с ошибкой
# «Invalid collation character», совпадения нет, детектор молча замолкает. Замена пробелами
# трогает только ASCII-пунктуацию, кириллицу не касается и от локали не зависит.
#
# Зачем вообще граница. Короткие маркеры в словарях детекторов — подстроки обычных слов:
# «да» в «дальше», «данные», «два»; «нет» в «нету»; «не то» в «не только» (этот случай
# уже стоил ложного «Пользователь КОРРЕКТИРУЕТ» на согласии); «no» в «not», «now», «know».
# Совпадение по подстроке — не то же, что совпадение по смыслу.
pad_words() {
    # Пунктуация вычищается `tr` по ASCII-набору, а не классом символов в `sed`.
    # Первая версия ставила класс `[...—–-]` с длинным и средним тире: они многобайтовые,
    # рядом с `-` читаются как диапазон байтов, и GNU sed в контейнере СЪЕДАЛ байты
    # кириллицы — «Да» превращалось в «\xNN а». На macOS то же выражение работало.
    # `tr` с ASCII-набором байт-безопасен: все байты кириллицы ≥ 0x80 и в набор не входят.
    # Тире заменяются отдельно, литералами, без скобок.
    printf ' %s ' "$(printf '%s' "${1:-}" \
        | tr '\n\t' '  ' \
        | tr '][(){}<>.,;:!?"`~@#$%^&*+=|\\/-' ' ' \
        | sed -e 's/—/ /g' -e 's/–/ /g' -e 's/…/ /g' \
        | tr -s ' ')"
}
