# rc_env_is_real — код 0, если инструмент работает в НАСТОЯЩЕМ окружении, а не в фикстуре.
#
# Повод измерен 29 августа 2026 на первом же прогоне: адверсариальные тесты гоняют
# `drift-check.sh` с подменёнными `CLAUDSOUL_REPO`/`CLAUDE_HOME`, и его BROKEN на подложном
# дереве завёл ДВА ложных повода в настоящем состоянии. Прогон в фикстуре — не событие
# мира: он ничего не утверждает о системе, он проверяет сам инструмент.
#
# Признак — правило, а не перечень, и судит он ПРОИСХОЖДЕНИЕ пути, а не имя переменной:
# окружение фикстурное, когда переопределённый путь частного происхождения — под временным
# корнем (TMPDIR, /tmp, /var/folders, /dev/shm) либо несуществующий; фикстуры этого дерева
# живут в `mktemp`, и новому тесту ничего не нужно знать об этом правиле. До 13 сентября 2026
# фикстурой считалось само НАЛИЧИЕ переменной: у пользователя с экспортированным
# CLAUDSOUL_REPO (документированная настройка, bin/resolve-claudsoul-repo.sh) контур поводов
# D200 был мёртв молча — красный CI своего коммита не записывался (прожарка свидетелей,
# раунд 2, атака 1). Признак, снятый с имени, различал форму, а не роль.
#
# ПРИЗНАК «ЧАСТНОЕ ПРОИСХОЖДЕНИЕ» ДЕРЖИТ ЭТА ФУНКЦИЯ ОДНА (D1013, 23 октября 2026). Её спрашивают и
# писатели, не пускающие след фикстуры в живой каталог (D1011): `hooks/backlog-reading-refresh.sh`,
# `scripts/backlog-archive.sh`, `scripts/calibrate.py`, `scripts/defect-class-carriers.py`. До того у
# каждого был свой перечень без `/dev/shm`, и сменить корни значило править пять мест. Имя публичное,
# потому что зовут из других файлов; питон зовёт подоболочкой — `bash -c '. lib; rc_path_is_private "$1"'`.
# Сам перечень корней — у `wt_temp_roots` (hooks/lib/write-target-lib.sh, D1112): его же спрашивает страж
# записи, и у двух копий ответ расходился по написанию пути. Сверх перечня здесь — $TMPDIR (фикстуры живут в
# `mktemp`); страж его не берёт, ему корень из окружения хука опасен. Библиотеки нет либо в ней нет `wt_temp_roots`
# (старая редакция рядом с новой этой) — путь частный: след фикстуры в живой каталог тогда не уйдёт. НАЗВАННЫЙ
# ПРЕДЕЛ: у хука `backlog-reading-refresh.sh` недостижимый признак значит «живой», и при старой библиотеке рядом
# с новой этой он уведёт состояние во временный каталог; установщик такого не допускает — библиотеки переносятся
# первыми (D1166), а `scripts/sync-drifted.sh` называет обе (скептик D1112, M3).
_RC_WT_LIB="${_RC_WT_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/lib/write-target-lib.sh}"
[ -f "$_RC_WT_LIB" ] || _RC_WT_LIB="$HOME/.claude/hooks/lib/write-target-lib.sh"
rc_path_is_private() {   # <путь> → 0, если частного происхождения (временный корень / нет каталога)
    local p="$1" d real t tr
    [ -n "$p" ] || return 1
    command -v wt_temp_roots >/dev/null 2>&1 || . "$_RC_WT_LIB" 2>/dev/null
    command -v wt_temp_roots >/dev/null 2>&1 || return 0
    if [ -d "$p" ]; then d="$p"; else d="${p%/*}"; [ "$d" = "$p" ] && d=.; fi
    real=$(cd -- "$d" 2>/dev/null && pwd -P) || return 0
    # $TMPDIR — одним словом в кавычках (перевод строки в нём не делит перечень), перечень — литералами без пробелов.
    # Без heredoc: при закрытой ФС он не создаёт временный файл, и обход молча пуст — ответ «живой» для фикстуры
    # (скептик D1112, второй круг, M2).
    local IFS=$' \t\n'
    for t in "${TMPDIR:-/tmp}" $(wt_temp_roots); do
        tr=$(cd -- "$t" 2>/dev/null && pwd -P) || continue
        case "$real" in "$tr"|"$tr"/*) return 0 ;; esac
    done
    return 1
}
rc_env_is_real() {
    [ -z "${CLAUDSOUL_REPO:-}" ] || ! rc_path_is_private "$CLAUDSOUL_REPO" || return 1
    [ -z "${CLAUDE_HOME:-}" ] || ! rc_path_is_private "$CLAUDE_HOME" || return 1
    [ -z "${BACKLOG_FILE:-}" ] || ! rc_path_is_private "$BACKLOG_FILE" || return 1
    return 0
}

# rc_note_event <state_dir> <род> <подробность> — записать внешний повод.
# Дедуп по паре (род, подробность) НЕЗАВИСИМО от статуса: событие с той же деталью,
# однажды закрытое исходом, не перезаводится. Дедуп только против открытых давал петлю
# (D227): продюсер со скользящим окном (hotfix-repeat читает последние 10 коммитов)
# перезаводил закрытое событие каждым сканом — «publish-public.sh» заведён трижды за
# вечер при двух записанных вердиктах, исход не гасил ничего.
# НАЗВАННЫЙ ПРЕДЕЛ: новая НАСТОЯЩАЯ серия с той же деталью тоже не заведётся — деталь
# и есть идентичность события. Снимется, когда деталь понесёт границы окна (диапазон
# коммитов, номер прогона): тогда новая серия даст новую деталь сама.
# rc_project_of [каталог] — корень проекта, которому принадлежит событие.
#
# Журнал событий ОДИН на все проекты (продюсеры-скрипты не знают идентификатора сессии,
# см. выше), и до 9 сентября 2026 в записи не было ничего, что отличило бы проект от
# проекта. Наблюдаемая цена: в живом журнале 62 записи, 9 из них про чужой проект
# (`web/lib/…`, `pult/…`), и различить их можно было только УГАДАВ по форме пути.
# Признак ВЫВОДИТСЯ (подъём к корню), а не перечисляется: список проектов, записанный
# здесь, разошёлся бы с миром на первом же новом проекте.
rc_project_of() {
    _rc_pd="${1:-$PWD}"
    # Библиотека путей подгружается ЗДЕСЬ, а не предполагается у вызывающего (10 сентября
    # 2026). Прежде ответ зависел от того, загрузил ли её позвавший, и способов получалось
    # три: гейт брал `find_project_root` (поднимается к ближайшему `.git` ИЛИ `CLAUDE.md`),
    # `ci-status.sh` и `backlog-recheck.sh` — `git rev-parse` (только git-корень), потому что
    # paths-lib не грузили вовсе. В проекте с каталожным CLAUDE.md — монорепо, `apps/web` —
    # ответы расходятся: писатель кладёт событие под один ключ, читатель ищет под другим, и
    # сигнал `event` умирает МОЛЧА, без единой ошибки. Найдено прожаркой на подставном дереве.
    # Ключ обязан быть один; какой именно — вопрос второй, и выбран более узкий: `CLAUDE.md`
    # в подкаталоге означает отдельный договор, значит и отдельный долг.
    if ! command -v find_project_root >/dev/null 2>&1; then
        _rc_pl="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/paths-lib.sh"
        [ -f "$_rc_pl" ] || _rc_pl="$HOME/.claude/hooks/paths-lib.sh"
        # shellcheck source=/dev/null
        [ -f "$_rc_pl" ] && . "$_rc_pl" 2>/dev/null || true
    fi
    if command -v find_project_root >/dev/null 2>&1; then
        _rc_pr=$(find_project_root "$_rc_pd" 2>/dev/null)
        [ -n "${_rc_pr:-}" ] && { printf '%s' "$_rc_pr"; return 0; }
    fi
    # `git -C "$каталог"`, а не `cd … && git`: каталог процесса хуку не вход — у него есть
    # payload с `.cwd`. Класс «вход берётся из окружения процесса вместо payload сессии»
    # приходил в дерево трижды (D275), и страж `test_payload_cwd_root` ловит именно ФОРМУ
    # голого вызова: `cd` перед ним функционально равен `-C`, но признак судит построчно,
    # а не по смыслу, и это названный там предел. Заодно `-C` не двигает каталог процесса.
    _rc_pr=$(git -C "$_rc_pd" rev-parse --show-toplevel 2>/dev/null)
    [ -n "${_rc_pr:-}" ] && { printf '%s' "$_rc_pr"; return 0; }
    printf '%s' "$_rc_pd"
}

rc_note_event() {
    _rc_sd="${1:-}"; _rc_kind="${2:-}"; _rc_detail="${3:-}"
    [ -n "$_rc_sd" ] && [ -n "$_rc_kind" ] || return 0
    rc_env_is_real || return 0
    mkdir -p "$_rc_sd" 2>/dev/null || return 0
    _rc_ef="$_rc_sd/$RC_EVENTS_FILE_NAME"
    _rc_proj="${RC_EVENT_PROJECT:-$(rc_project_of)}"
    # Дедуп — только среди ОТКРЫТЫХ и только СВОЕГО проекта. Прежде он смотрел на весь
    # файл независимо от статуса, и это делало сигнал `event` мёртвым по построению:
    # закрытое событие с той же деталью не заводилось больше НИКОГДА. Наблюдаемо —
    # 62 записи, все 62 `closed`, открытых ноль. Событие мира, случившееся снова, есть
    # новое событие: тот же файл, чинённый повторно, — ровно тот повод, ради которого
    # журнал и заведён.
    if [ -f "$_rc_ef" ] && jq -e --arg k "$_rc_kind" --arg d "$_rc_detail" --arg p "$_rc_proj" \
            'select(.status == "open" and .kind == $k and .detail == $d
                    and ((.project // "") == $p or (.project // "") == ""))' \
            "$_rc_ef" >/dev/null 2>&1; then
        return 0
    fi
    # Дозапись идёт ПОД ТЕМ ЖЕ ЗАМКОМ, что и закрытие (10 сентября 2026, находка противника).
    # Закрыватель `rc_close_events` работает через `atomic_filter`: снимок → фильтр → `mv`.
    # Запись, легшая между снимком и переименованием, затиралась МОЛЧА — повод исчезал, и
    # никакой счётчик об этом не знал. Атомарность дозаписи здесь не спасает: она защищает
    # от разрыва строки, а не от замены файла целиком.
    # Писатели и закрыватель — РАЗНЫЕ процессы: revert-signal (PostToolUse), subagent-outcome
    # (SubagentStop), ci-status и backlog-recheck (launchd) против declared-problem-recorded
    # (Stop), — поэтому одновременность правдоподобна; частота НЕ ИЗМЕРЕНА, и это записано.
    # Правило дерева требует, чтобы ОБЕ половины протокола брали ОДНО имя замка (род H);
    # здесь была взята одна: замок пришёл к закрывателю отдельной правкой, писателя не тронули.
    # ТЕРПЕНИЕ ЗАМКА поднято намеренно (10 сентября 2026). `with_lock` объявляет: «не взятый
    # замок работу не отменяет» — то есть при исчерпании попыток команда идёт БЕЗ замка и
    # молча. Для дозаписи это означает ту самую потерю, ради которой замок и брался.
    # Замер на воспроизведении гонки: со штатными 100 попытками (×0.02 с = 2 с) тест
    # проходил 1 раз из 5, с запасом — 5 из 5. Ждать здесь дёшево: дозапись одной строки
    # мгновенна, а закрыватель держит замок доли секунды, поэтому исчерпание запаса означает
    # уже не занятость, а поломку.
    # НАЗВАННЫЙ ПРЕДЕЛ: при полном исчерпании запись всё равно идёт (данные важнее тишины) и
    # может совпасть с переписыванием. Условие снятия: закрыватель начнёт сверять файл до и
    # после фильтра и повторять при изменении — тогда потеря станет невозможна по построению,
    # а не менее вероятна.
    if command -v with_lock >/dev/null 2>&1; then
        CLAUDSOUL_LOCK_TRIES="${CLAUDSOUL_LOCK_TRIES:-500}" with_lock "$_rc_ef" _rc_append_event
    else
        _rc_append_event
    fi
}

# Тело дозаписи вынесено, чтобы его можно было передать `with_lock` как команду.
# Переменные `_rc_*` глобальны для библиотеки, поэтому аргументов не требуется.
_rc_append_event() {
    jq -cn --arg ts "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" --arg k "$_rc_kind" --arg d "$_rc_detail" \
           --arg p "$_rc_proj" \
        '{ts:$ts, kind:$k, detail:$d, project:$p, status:"open"}' >> "$_rc_ef" 2>/dev/null || true
}

# rc_open_events <state_dir> [проект] — открытые поводы СВОЕГО проекта, по одному в строке
# «род: подробность». Без второго довода проект берётся у текущего каталога.
#
# Запись без поля `project` (заведена до 9 сентября 2026) принадлежит всем: скрыть её
# значило бы потерять историю, а показать — худшее, что может случиться, это лишний повод
# по своему же прошлому. Все такие записи на момент правки закрыты.
rc_open_events() {
    _rc_ef="${1:-}/$RC_EVENTS_FILE_NAME"
    [ -f "$_rc_ef" ] || return 0
    _rc_p="${2:-${RC_EVENT_PROJECT:-$(rc_project_of)}}"
    jq -r --arg p "$_rc_p" \
        'select(.status == "open" and ((.project // "") == $p or (.project // "") == ""))
         | "\(.kind): \(.detail)"' "$_rc_ef" 2>/dev/null
}

# rc_close_events <state_dir> [проект] — пометить закрытыми открытые поводы СВОЕГО проекта.
#
# Прежде гасились ВСЕ открытые записи файла разом: запись пункта долга в одном проекте
# закрывала события всех остальных, ни одно из которых никто не разбирал. Это половина
# причины, по которой в живом журнале не осталось ни одного открытого события.
# НАЗВАННЫЙ ПРЕДЕЛ: гашение остаётся групповым внутри проекта — гейт ключует не событие,
# а КОНТРОЛЬНУЮ СУММУ ГРУППЫ из трёх (`five-whys-gate.sh:382`), и связать закрытие с
# конкретным поводом нечем. Условие снятия: гейт понесёт ключи самих событий, а не их
# склейки; тогда закрывается ровно показанное.
rc_close_events() {
    _rc_ef="${1:-}/$RC_EVENTS_FILE_NAME"
    [ -f "$_rc_ef" ] || return 0
    _rc_p="${2:-${RC_EVENT_PROJECT:-$(rc_project_of)}}"
    atomic_filter "$_rc_ef" jq -c --arg p "$_rc_p" \
        'if .status == "open" and ((.project // "") == $p or (.project // "") == "")
         then .status = "closed" else . end' || true
}

# rc_note_detection <state_dir> <sid> <страж> <said|muted|unread|satisfied> — знаменатель стража (D205).
#
# ТРЕТЬЕ ЗНАЧЕНИЕ (5 сентября 2026). `unread` — страж промолчал не по решению, а потому что
# ВХОД не прочитался (у `user-correction-guard` — слурп расшифровки). Событием знаменателя
# такая запись НЕ является: считать непрочитанный ход измеренной тишиной значит мерить
# работу прибора вместо частоты предмета. Оба читателя обязаны отбирать записи по
# `said|muted` ЯВНО — `scripts/violation-class.sh:37` делал так всегда, у
# `scripts/detection-share.sh` отбора НЕ БЫЛО, и записи без подписи попадали в `$raw`,
# раздувая `n` на каждом вызове инструмента. Заводя четвёртое значение — проверь обоих.
#
# ЧЕТВЁРТОЕ ЗНАЧЕНИЕ (9 сентября 2026, D372). `satisfied` — признак совпал, а УСЛОВИЕ, ради
# которого страж существует, оказалось выполнено: у `code-review-reminder` крупный дифф идёт
# в коммит, и адверсариальный прогон в сессии уже был. От `muted` это отличается предметом,
# а не громкостью: там предмет не разобран и молчание случайно (троттл), здесь событие мира
# случилось и кончилось хорошо. Слить их значило бы потерять единственную величину, ради
# которой знаменатель и заводится, — долю «ушло БЕЗ прогона».
#
# Проверка обоих читателей, предписанная строкой выше, сделана чтением 9 сентября 2026:
# `scripts/detection-share.sh:50` и `scripts/violation-class.sh:38` отбирают
# `.act == "said" or .act == "muted"` ЯВНО, поэтому их числа не сдвигаются. Правки им не
# потребовалось — но проверка обязана быть сделана, а не предположена: у `detection-share`
# такого отбора НЕ БЫЛО ещё 5 сентября, и молчаливое добавление значения тогда раздуло бы
# знаменатель. Замер, ради которого значение заведено, читает `said+muted+satisfied`
# (`scripts/adversary-before-commit.sh`).
#
# Зачем. Журналы `*-fired-<SID>.jsonl` пишутся ПОСЛЕ решения сказать, поэтому по ним
# нельзя посчитать долю «сказал против промолчал»: знаменатель отсутствует по построению.
# Ровно этот дефект чинили у гейта разбора (D112) — там успех стража не попадал в журнал,
# и доля «без исхода» была завышена. Здесь тот же корень у четырёх соседей: предмет учёта
# задан работой стража, а не событием мира.
#
# СОБЫТИЕ — это «признак совпал», а не «страж заговорил». Совпал и заговорил → `said`;
# совпал и промолчал по троттлу → `muted`. Знаменатель = сумма обоих.
#
# КОНТРПРИМЕР: ход, где признак НЕ совпал, событием не является и в знаменатель не идёт —
# иначе доля считалась бы от числа вызовов инструмента, то есть от объёма работы, а не от
# частоты предмета.
#
# ПОДПИСЬ (пятый аргумент, 30 августа 2026). Первый прогон замера дал у двух стражей «сказал
# 14% и 16%» — и оба раза «промолчал» был ПОВТОРОМ ТОЙ ЖЕ ПОДПИСИ: у user-correction-guard
# одна реплика собеседника пересчитывается на каждом вызове инструмента (тот же хеш), у
# rework-detector — тот же файл в той же сессии. Знаменатель снова оказался объёмом работы, а
# не частотой предмета — ровно тот контрпример, что назван строкой выше. Событие — это
# РАЗНАЯ подпись: замер detection-share сводит записи по (страж, подпись), и «промолчал»
# считается только у подписи, которая не прозвучала ни разу. Запись без подписи считается
# по-старому — старые журналы читаются.
rc_note_detection() {
    _rc_sd="${1:-}"; _rc_sid="${2:-}"; _rc_guard="${3:-}"; _rc_act="${4:-}"; _rc_sig="${5:-}"
    [ -n "$_rc_sd" ] && [ -n "$_rc_sid" ] && [ -n "$_rc_guard" ] && [ -n "$_rc_act" ] || return 0
    command -v jq >/dev/null 2>&1 || return 0
    mkdir -p "$_rc_sd" 2>/dev/null || return 0
    jq -cn --arg ts "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" --arg g "$_rc_guard" --arg a "$_rc_act" --arg s "$_rc_sig" \
        '{ts:$ts, guard:$g, act:$a} + (if $s == "" then {} else {sig:$s} end)' \
        >> "$_rc_sd/detection-${_rc_sid}.jsonl" 2>/dev/null || true
}

