#!/usr/bin/env bash
# root-cause-lib.sh — ЕДИНСТВЕННОЕ определение общих вычислений контура разбора причин.
#
# Результат: ключ хода, последний блок речи и счёт «почему» вычисляются в одном месте;
#            копий этих формул в хуках ноль
# Проверка результата: bash hooks/tests/test_root_cause_lib.sh даёт 0
#
# Зачем. До 29 августа 2026 формула ключа хода (cksum последней реплики собеседника)
# существовала ДВУМЯ копиями: five-whys-gate.sh писал ею журнал срабатываний, а
# declared-problem-recorded.sh читал тот журнал своей копией той же формулы. Комментарий
# в читателе называл это прямо: «расходятся молча — и связь порвётся без единого
# падения». Класс уже отказывал в этом проекте: 28 августа три стража бэклога сутки
# молчали, потому что каждый держал СВОЮ копию признака пункта (повод backlog-lib.sh).
# Библиотека строится по тому же образцу: одно определение, потребители источают.
#
# КОНТРПРИМЕР: сигнальные блоки гейта (какие файлы состояния слушать) сюда не выносятся
# этой правкой — у них своя граница выноса (порядок KINDS несёт семантику дедупа),
# см. план модуля root-cause.
#
# Контракт функций: чистые вычисления, мир не меняют; на нечитаемом/пустом входе печатают
# пусто (или 0 у счётчиков) и возвращают 0 — деградация без падения. jq обязателен у
# ВЫЗЫВАЮЩЕГО: хук без jq выходит раньше, чем дойдёт сюда.
# Источать можно многократно (идемпотентно).

# rc_turn_key <transcript> — метка хода: cksum последней непустой реплики собеседника.
# Ею гейт подписывает журнал срабатываний, ею же сверщик находит срабатывания этого хода.
rc_turn_key() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    jq -rs '
        def role(x): x.message.role // x.role // "";
        def get_text(x):
            (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then ($c | map(select(.type == "text") | .text) | join(" "))
            elif ($c | type) == "string" then $c else "" end;
        [ .[] | select(role(.) == "user") | get_text(.) | select(. != "") ] | last // ""
    ' "$_rc_t" 2>/dev/null | cksum 2>/dev/null | awk '{print $1}'
}

# rc_last_block <transcript> — последний блок речи агента после последней реплики
# собеседника. Признак находки читается по нему, а не по всему окну хода: слово находки,
# однажды сказанное, оставалось бы в окне до конца хода, и все последующие находки
# сливались бы с первой (диагноз 28 августа 2026, индексы 1055/1159).
rc_last_block() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    jq -rs '
        def role(x): x.message.role // x.role // "";
        def get_text(x):
            (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then ($c | map(select(.type == "text") | .text) | join("\n"))
            elif ($c | type) == "string" then $c else "" end;
        . as $items | (length) as $n |
        ([range(0; $n) | ($n - 1 - .)
          | select(role($items[.]) == "user" and ((get_text($items[.]) // "") | length > 0))]
          | first) as $pu |
        ([range((if $pu == null then 0 else $pu + 1 end); $n) | $items[.]
          | select(role(.) == "assistant") | get_text(.) | select(. != "")] | last // "")
    ' "$_rc_t" 2>/dev/null
}

# RC_KINDS_RE — все СРОДЫ поводов, которые гейт пишет в журнал `five-whys-<SID>.seen`.
# До 29 августа 2026 след разбора проверялся ровно у одного срода — `discovery:`. В живых
# журналах при этом: daily 126, repeat 59, discovery 36, correction 6, streak 4 — то есть у
# 195 срабатываний из 231 исход не проверял никто, и «заметил и ничего не сделал» было
# неотличимо от «сделал». Перечень сродов держится здесь, а не в потребителе: продюсер и
# потребитель уже расходились молча на ключе хода.
RC_KINDS_RE="${RC_KINDS_RE:-rework:|correction:|question:|streak:|repeat:|daily:|discovery:|event:}"

# rc_signals_of_turn <журнал> <ключ хода> — сроды поводов, сработавших в ЭТОМ ходе,
# по одному в строке (без двоеточия). Пусто — поводов в ходе не было.
rc_signals_of_turn() {
    _rc_j="${1:-}"; _rc_k="${2:-}"
    [ -n "$_rc_j" ] && [ -f "$_rc_j" ] && [ -n "$_rc_k" ] || return 0
    grep "^turn:${_rc_k}|" "$_rc_j" 2>/dev/null \
        | grep -oE "$RC_KINDS_RE" 2>/dev/null \
        | sed 's/:$//' | sort -u
}

# RC_OUTCOMES — закрытый список исходов повода разбора, единственное их определение.
# Наблюдаемые автоматом (кто пишет — в скобках):
#   chain-spoken — цепочка произнесена, страж пропустил работу дальше (five-whys-gate)
#   deferred     — правка отложена отказом, вызов не выполнен (five-whys-gate)
#   recorded     — носитель изменился после начала хода (declared-problem-recorded)
#   none         — ничего из перечисленного (declared-problem-recorded)
# Называемые агентом через `scripts/outcome.sh` (наблюдением их не отличить от бездействия):
#   fixed | debt | knowledge | disproved
# Первые три автоматических означают «ход дела изменился», `none` — нет; на этом различии
# стоит замер `outcome-share.sh`. До 29 августа 2026 список существовал двумя редакциями:
# доккомментарий перечислял пять значений, а автомат писал шестое (`recorded`).
RC_OUTCOMES="chain-spoken deferred recorded none fixed debt knowledge disproved"
RC_OUTCOMES_ACTED="chain-spoken deferred recorded fixed debt knowledge"

# rc_log_outcome <state_dir> <sid> <ключ хода> <сигнал> <исход> [ссылка]
#   Дописывает строку в журнал исходов `outcome-<SID>.jsonl`. Значения — из RC_OUTCOMES.
#
# Зачем журнал (D112). Прежний журнал стража писал СРАБАТЫВАНИЯ и не писал ИСХОДЫ: по нему
# нельзя было ответить, изменилось ли хоть что-то после напоминания, — а замер 28 августа
# 2026 показал, что напоминание читается и не меняет действия (минимум 9 случаев из 19).
# «Страж сработал» и «страж помог» — разные утверждения, и второе до сих пор не считалось.
# Исход определяется НАБЛЮДАЕМО (изменился носитель), а не декларацией агента; единственный
# агентский вход — вердикт «показалось», и его доля есть замер точности сигнала, а не повод
# воспитывать исполнителя.
rc_log_outcome() {
    _rc_sd="${1:-}"; _rc_sid="${2:-}"; _rc_key="${3:-}"
    _rc_sig="${4:-}"; _rc_out="${5:-}"; _rc_ref="${6:-}"; _rc_tr="${7:-}"
    [ -n "$_rc_sd" ] && [ -n "$_rc_sid" ] && [ -n "$_rc_sig" ] && [ -n "$_rc_out" ] || return 0
    mkdir -p "$_rc_sd" 2>/dev/null || return 0
    _rc_f="$_rc_sd/outcome-${_rc_sid}.jsonl"
    # Идемпотентность по ходу и сигналу: Stop срабатывает не единожды за ход, и без этого
    # один и тот же исход умножался бы, перекашивая доли в замере.
    if [ -f "$_rc_f" ] && grep -q "\"key\":\"${_rc_key}\",\"signal\":\"${_rc_sig}\"" "$_rc_f" 2>/dev/null; then
        return 0
    fi
    # След разбора (D211) — седьмой аргумент, JSON-объект от rc_trace. Без него поля `trace`
    # в записи нет: старые читатели берут только .signal/.outcome и не замечают разницы.
    # Порядок ключей сохранён: дедуп выше ищет подстроку `"key":…,"signal":…`.
    if [ -n "$_rc_tr" ] && ! printf '%s' "$_rc_tr" | jq -e 'type == "object"' >/dev/null 2>&1; then
        _rc_tr=""
    fi
    jq -cn --arg ts "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" --arg k "${_rc_key:-0}" \
           --arg s "$_rc_sig" --arg o "$_rc_out" --arg r "$_rc_ref" --arg t "$_rc_tr" \
        '{ts:$ts, key:$k, signal:$s, outcome:$o, ref:$r}
         + (if $t == "" then {} else {trace: ($t | fromjson)} end)' >> "$_rc_f" 2>/dev/null || true
}

# ── Внешние поводы разбора (D200-D203) ────────────────────────────────────────
# Мир подаёт поводы, которых в сессии не видно: красный прогон СВОЕГО коммита, откат
# коммита, воскресшее закрытие пункта, сбой самой проверки дрейфа. Зрелые практики
# запускают разбор не только на ущерб и повтор, но и на «включение механизма
# реагирования» (Google SRE: откат релиза обязывает к postmortem) и на «класс события
# независимо от исхода» (sentinel events). У нас такие события НАБЛЮДАЛИСЬ и никуда не
# вели: `ci-status.sh` печатал исход, `backlog-recheck.sh` находил воскресшие пункты,
# `drift-check.sh` отличал BROKEN от DRIFT — и всё это оставалось строкой в отчёте.
#
# ПОЧЕМУ ОДИН НОСИТЕЛЬ, А НЕ ЧЕТЫРЕ ХУКА. Продюсеры разной природы: два из них —
# скрипты по расписанию, они не знают идентификатора сессии и не могут писать
# `<что-то>-<SID>.jsonl`. Поэтому файл общий и без SID, а гейт читает его как ОДИН срод
# `event`: добавлять четыре срода значило бы четырежды повторить одно устройство.
#
# ЖИЗНЬ СОБЫТИЯ. Открыто → гейт называет его поводом → исход записан → закрыто. Без
# закрытия событие висело бы вечно и стало бы фоном; закрывает его сверщик на Stop,
# когда исход хода определён.
RC_EVENTS_FILE_NAME="${RC_EVENTS_FILE_NAME:-pending-events.jsonl}"

# rc_env_is_real — код 0, если инструмент работает в НАСТОЯЩЕМ окружении, а не в фикстуре.
#
# Повод измерен 29 августа 2026 на первом же прогоне: адверсариальные тесты гоняют
# `drift-check.sh` с подменёнными `CLAUDSOUL_REPO`/`CLAUDE_HOME`, и его BROKEN на подложном
# дереве завёл ДВА ложных повода в настоящем состоянии. Прогон в фикстуре — не событие
# мира: он ничего не утверждает о системе, он проверяет сам инструмент.
#
# Признак — правило, а не перечень: окружение считается настоящим, когда ни один из путей
# не переопределён извне. Тест, подменяющий пути, автоматически перестаёт заводить поводы,
# и новому тесту ничего не нужно знать об этом правиле.
rc_env_is_real() {
    [ -z "${CLAUDSOUL_REPO:-}" ] || return 1
    [ -z "${CLAUDE_HOME:-}" ] || return 1
    [ -z "${BACKLOG_FILE:-}" ] || return 1
    return 0
}

# rc_note_event <state_dir> <род> <подробность> — записать внешний повод.
# Дедуп по паре (род, подробность) НЕЗАВИСИМО от статуса: событие с той же деталью,
# однажды закрытое исходом, не перезаводится. Дедуп только против открытых давал петлю
# (D227): продюсер со скользящим окном (hotfix-repeat читает последние 10 коммитов)
# перезаводил закрытое событие каждым сканом — «publish-public.sh» заведён трижды за
# вечер при двух записанных вердиктах, исход не гасил ничего.
# НАЗВАННЫЙ ПРЕДЕЛ: новая НАСТОЯЩАЯ серия с той же деталью тоже не заведётся — деталь
# и есть идентичность события. Снимется, когда деталь понесёт границы окна (диапазон
# коммитов, номер прогона): тогда новая серия даст новую деталь сама.
rc_note_event() {
    _rc_sd="${1:-}"; _rc_kind="${2:-}"; _rc_detail="${3:-}"
    [ -n "$_rc_sd" ] && [ -n "$_rc_kind" ] || return 0
    rc_env_is_real || return 0
    mkdir -p "$_rc_sd" 2>/dev/null || return 0
    _rc_ef="$_rc_sd/$RC_EVENTS_FILE_NAME"
    if [ -f "$_rc_ef" ] && grep -q "\"kind\":\"${_rc_kind}\",\"detail\":\"${_rc_detail}\"" "$_rc_ef" 2>/dev/null; then
        return 0
    fi
    jq -cn --arg ts "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" --arg k "$_rc_kind" --arg d "$_rc_detail" \
        '{ts:$ts, kind:$k, detail:$d, status:"open"}' >> "$_rc_ef" 2>/dev/null || true
}

# rc_open_events <state_dir> — открытые поводы, по одному в строке «род: подробность».
rc_open_events() {
    _rc_ef="${1:-}/$RC_EVENTS_FILE_NAME"
    [ -f "$_rc_ef" ] || return 0
    jq -r 'select(.status == "open") | "\(.kind): \(.detail)"' "$_rc_ef" 2>/dev/null
}

# rc_close_events <state_dir> — пометить все открытые поводы закрытыми (исход записан).
rc_close_events() {
    _rc_ef="${1:-}/$RC_EVENTS_FILE_NAME"
    [ -f "$_rc_ef" ] || return 0
    _rc_tmp="${_rc_ef}.tmp$$"
    jq -c 'if .status == "open" then .status = "closed" else . end' "$_rc_ef" > "$_rc_tmp" 2>/dev/null \
        && mv "$_rc_tmp" "$_rc_ef" 2>/dev/null || rm -f "$_rc_tmp" 2>/dev/null
}

# rc_note_detection <state_dir> <sid> <страж> <said|muted> — знаменатель стража (D205).
#
# Зачем. Журналы `*-fired-<SID>.jsonl` пишутся ПОСЛЕ решения сказать, поэтому по ним
# нельзя посчитать долю «сказал против промолчал»: знаменатель отсутствует по построению.
# Ровно этот дефект чинили у гейта разбора (D112) — там успех стража не попадал в журнал,
# и доля «без исхода» была завышена. Здесь тот же корень у четырёх соседей: предмет учёта
# задан работой стража, а не событием мира.
#
# СОБЫТИЕ — это «признак совпал», а не «страж заговорил». Совпал и заговорил → `said`;
# совпал и промолчал по троттлу → `muted`. Знаменатель = сумма обоих.
#
# КОНТРПРИМЕР: ход, где признак НЕ совпал, событием не является и в знаменатель не идёт —
# иначе доля считалась бы от числа вызовов инструмента, то есть от объёма работы, а не от
# частоты предмета.
#
# ПОДПИСЬ (пятый аргумент, 30 августа 2026). Первый прогон замера дал у двух стражей «сказал
# 14% и 16%» — и оба раза «промолчал» был ПОВТОРОМ ТОЙ ЖЕ ПОДПИСИ: у user-correction-guard
# одна реплика собеседника пересчитывается на каждом вызове инструмента (тот же хеш), у
# rework-detector — тот же файл в той же сессии. Знаменатель снова оказался объёмом работы, а
# не частотой предмета — ровно тот контрпример, что назван строкой выше. Событие — это
# РАЗНАЯ подпись: замер detection-share сводит записи по (страж, подпись), и «промолчал»
# считается только у подписи, которая не прозвучала ни разу. Запись без подписи считается
# по-старому — старые журналы читаются.
rc_note_detection() {
    _rc_sd="${1:-}"; _rc_sid="${2:-}"; _rc_guard="${3:-}"; _rc_act="${4:-}"; _rc_sig="${5:-}"
    [ -n "$_rc_sd" ] && [ -n "$_rc_sid" ] && [ -n "$_rc_guard" ] && [ -n "$_rc_act" ] || return 0
    command -v jq >/dev/null 2>&1 || return 0
    mkdir -p "$_rc_sd" 2>/dev/null || return 0
    jq -cn --arg ts "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" --arg g "$_rc_guard" --arg a "$_rc_act" --arg s "$_rc_sig" \
        '{ts:$ts, guard:$g, act:$a} + (if $s == "" then {} else {sig:$s} end)' \
        >> "$_rc_sd/detection-${_rc_sid}.jsonl" 2>/dev/null || true
}

# rc_doctrine_full — полный порядок разбора, каким его инжектирует гейт.
# ЕДИНСТВЕННЫЙ машинный источник текста доктрины. До 29 августа 2026 порядок существовал
# ТРЕМЯ редакциями: five-whys-gate (полная, свежая), error-tracker:127 (без шага «вширь по
# проявлениям» — порядок, отменённый 28 августа) и rework-detector:171 (свои пять готовых
# «почему» — фикс-глубина, отменённая /retro 3.1). Два хука в одной сессии говорили разное.
# Человеческие носители (rules/CLAUDE.md Step 2, /retro Step 3, /adversary Step 4) вызвать
# функцию не могут — их держит drift-тест по коротким маркерам.
rc_doctrine_full() {
    cat <<'RC_DOCTRINE'
ПОРЯДОК: ВШИРЬ ПО ПРОЯВЛЕНИЯМ → ВГЛУБЬ ОТ КАЖДОГО → СВЕРКА → БРАТЬЯ КОРНЯ → ЗАВИСИМОСТИ.
Порядок — не стилистика, он решает исход.

1) ВШИРЬ ПО ПРОЯВЛЕНИЯМ: где ещё виден ТОТ ЖЕ признак. Каждое место с адресом —
   файл:строка, прогон, лог. Без адреса пункт не считается. Перечень ВЕРСИЙ причины
   («какие бывают причины») сюда НЕ относится: он исполним без данных и потому съедает
   разбор. Одно проявление — шаг пуст, иди дальше.
2) ВГЛУБЬ от 2-5 максимально РАЗНЫХ проявлений, каждая цепочка отдельно. Каждое «почему»
   задаётся К ОТВЕТУ на предыдущее, а не к симптому. Спуск идёт ДВУМЯ линиями: «почему
   сломалось здесь» (вдоль исполнения) и «откуда пришло то, из чего считали» (вдоль
   данных) — перечисли ВСЕ входы узла и спроси о каждом, был ли он верен. Узел, исправно
   посчитавший неверный вход, НЕ корень: подай верный вход — симптом исчезнет, хотя узел
   не менялся; спускайся к источнику. Источников бывает несколько, и все настоящие.
   ОСТАНОВКА — ПО ПРИЗНАКУ КОРНЯ, А НЕ ПО ЧИСЛУ ЗВЕНЬЕВ (3-7 — ориентир, не критерий):
   · не выше ли: убери это звено — и симптом не мог бы возникнуть НИ ОДНИМ путём, а не
     только тем, который наблюдали. Даёт НЕОБХОДИМОСТЬ звена, а не корень, и легчает
     при подъёме;
   · специфичность — единственный тест, ТЯЖЕЛЕЮЩИЙ при подъёме: реестр мест, N со звеном,
     M из них с симптомом; дробь предъявляется числом. Шаг вверх, роняющий дробь, и есть
     шаг ЗА корень. M<N без названного разделителя — разбор не закончен;
   · не проскочил ли ниже: звено объясняет всё одинаково общо и НЕ предсказывает, где
     признак появится в третий раз — это общий знаменатель формулировки, вернись выше;
   · действенность: на этом уровне формулируется ПРИЗНАК, у которого продолжение вызова
     имеет ОДНО последствие, и назван адрес отказа. Свалились формы с разными
     последствиями — узел взят выше корня.
3) СВЕРКА: схождение доказывает РОДСТВО, а не корень — у узла с несколькими входами
   (сумматор, журнал, отчёт) сходится что угодно. Разошлись — по умолчанию КОРНЕЙ
   НЕСКОЛЬКО, у каждого своя починка; подъём к общему узлу — только если его дробь не
   упала против ветвей.
4) БРАТЬЯ КОРНЯ (вбок): где ещё действует корень ТОГО ЖЕ УСТРОЙСТВА — включая места, где
   симптома ещё не видно и тесты зелёные. Способ добычи: scripts/defect-class-carriers.py,
   поиск по устройству, scripts/dep-index.py --impact. Каждый брат с адресом.
5) ЗАВИСИМОСТИ КОРНЯ (вниз): что ещё на нём держится. Эта карта не кончается разбором —
   после починки она же чек-лист регрессии: правка корня ломает опиравшееся на прежнее
   поведение, включая костыли поверх дефекта.

Симптом чинится там, где заметили; причина — там, где возникла. 28 августа 2026 один
дефект (не-ASCII путь скилла) онемил пять стражей подряд, и каждого чинили отдельным
заходом. Повтор бывает и в успехах: три зелёных прогона одного файла — тоже признак.
RC_DOCTRINE
}

# rc_doctrine_short — та же доктрина в четырёх строках, для хуков, у которых разбор не
# единственная тема сообщения (error-tracker, rework-detector).
rc_doctrine_short() {
    cat <<'RC_DOCTRINE_SHORT'
ВШИРЬ ПО ПРОЯВЛЕНИЯМ (где ещё виден тот же признак, каждое с адресом) → ВГЛУБЬ цепочкой
«почему» от 2-5 самых разных, каждое к ОТВЕТУ на предыдущее, и отдельной линией по ВХОДАМ
(«откуда данные, на которых сломалось») → СВЕРКА схождения → БРАТЬЯ КОРНЯ (то же
устройство там, где симптома ещё не видно) → ЗАВИСИМОСТИ корня, они же чек-лист регрессии
после починки.
Остановка — по признаку корня, не по числу звеньев: убери звено — симптом не мог бы
возникнуть НИ ОДНИМ путём; дробь «мест со звеном / из них с симптомом» не падает при
