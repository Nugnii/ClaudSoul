#!/usr/bin/env bash
# root-cause-lib.sh — ЕДИНСТВЕННОЕ определение общих вычислений контура разбора причин.
#
# ПРЕФИКСЫ: rc_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
#
# Результат: ключ хода, последний блок речи и счёт «почему» вычисляются в одном месте;
#            копий этих формул в хуках ноль
# Проверка результата: bash hooks/tests/test_root_cause_lib.sh даёт 0
#
# Зачем. До 29 августа 2026 формула ключа хода (cksum последней реплики собеседника)
# существовала ДВУМЯ копиями: five-whys-gate.sh писал ею журнал срабатываний, а
# declared-problem-recorded.sh читал тот журнал своей копией той же формулы. Комментарий
# в читателе называл это прямо: «расходятся молча — и связь порвётся без единого
# падения». Класс уже отказывал в этом проекте: 28 августа три стража бэклога сутки
# молчали, потому что каждый держал СВОЮ копию признака пункта (повод backlog-lib.sh).
# Библиотека строится по тому же образцу: одно определение, потребители источают.
#
# КОНТРПРИМЕР: сигнальные блоки гейта (какие файлы состояния слушать) сюда не выносятся
# этой правкой — у них своя граница выноса (порядок KINDS несёт семантику дедупа),
# см. план модуля root-cause.
#
# Контракт функций: чистые вычисления, мир не меняют; на нечитаемом/пустом входе печатают
# пусто (или 0 у счётчиков) и возвращают 0 — деградация без падения. jq обязателен у
# ВЫЗЫВАЮЩЕГО: хук без jq выходит раньше, чем дойдёт сюда.
# Источать можно многократно (идемпотентно).

# Общий замок и правка под ним (род H): журнал поводов разбора общий на сессию.
STATE_LOCK_LIB="${STATE_LOCK_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/state-lock-lib.sh}"
[ -f "$STATE_LOCK_LIB" ] || STATE_LOCK_LIB="$HOME/.claude/hooks/state-lock-lib.sh"
# shellcheck source=/dev/null
if [ -f "$STATE_LOCK_LIB" ]; then . "$STATE_LOCK_LIB"; fi
# Окно текущего хода (D498): читатели хода ниже берут расшифровку от последней реплики
# владельца, а не целиком. Граница у них шире (любая запись user без isMeta), поэтому их
# собственная граница лежит в окне. Библиотеки нет — окно вырождается в файл целиком.
INPUT_LIB="${INPUT_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/hook-input-lib.sh}"
[ -f "$INPUT_LIB" ] || INPUT_LIB="$HOME/.claude/hooks/hook-input-lib.sh"
# shellcheck source=/dev/null
if [ -f "$INPUT_LIB" ]; then . "$INPUT_LIB"; fi
command -v transcript_turn_window >/dev/null 2>&1 || transcript_turn_window() { cat "${1:-/dev/null}"; }
command -v transcript_fold >/dev/null 2>&1 || transcript_fold() {
    [ -f "${1:-}" ] && [ $# -gt 3 ] || return 1; _rc_ff="$1"; shift 3
    transcript_turn_window "$_rc_ff" | "$@" /dev/null; }

# RC_TURN_STEP — шаг свёртки текущего хода: {k: текст последней записи user с текстом (не
# isMeta), t: [непустые тексты агента после неё]}. ЕДИНСТВЕННОЕ определение границы хода у
# rc_turn_key, rc_last_block и rc_turn_text (до 2 октября 2026 у каждого была своя копия,
# корень R1). Граница шире реплики владельца — уведомление задачи, сводка сжатия тоже её
# сбрасывают — и лежит внутри окна хода, с которого начинается свёртка.
# Тексты блоков склеиваются: метка — пробелом, речь — переводом строки (как было).
# Ошибка разбора текста агента ловится ВНУТРИ записи (флаг `bad`, сбрасывается границей): прежние
# читатели разбирали текст агента только ПОСЛЕ границы, а свёртка — каждой записи, и ошибка jq в
# записи до границы роняла всю свёртку (противник свёртки, атака 2). Флаг после границы — тексты
# хода пусты, как пусто было у упавшего прежнего разбора; метка хода текст агента не читает.
# РЕЧЬ ЧЕРЕЗ ВЫЗОВ (D484, 3 октября 2026): тело вызова Bash `: <<'CHAIN'` … `CHAIN` (команда-пустышка)
# идёт в текст хода наравне с текстом агента. С Opus 5.5 промежуточная речь ложится в расшифровку
# пересказом записи `thinking` — запись `text` у 8–14% сообщений с вызовом (у Opus 5 — 53–82%), —
# и цепочка, сказанная текстом, чаще всего не видна; вход вызова расшифровка хранит дословно.
# Разбор канала ловит свою ошибку сам: сбой одной записи не роняет свёртку (урок класса 2).
# Граница — запись user по `turn_user` (`HIL_TURN_USER_JQ`, D1153): служебная запись `api-request-blob` с ролью user
# ход не делит. Библиотеки нет — границы нет, ход — всё окно от реплики.
RC_TURN_STEP="${HIL_TURN_USER_JQ:-def turn_user: false;}"'
    def role(x): x.message.role // x.role // "";
    def get_text(x; sep):
        (x.message.content // x.content // []) as $c |
        if ($c | type) == "array" then ($c | map(select(.type == "text") | .text) | join(sep))
        elif ($c | type) == "string" then $c else "" end;
    def chains(x):
        [ (x.message.content // [])[]? | select(type == "object" and .type == "tool_use" and .name == "Bash")
          | (.input.command // "") | strings
          | capture("^\\s*:\\s*<<-?\\s*\\x27CHAIN\\x27\\n(?<b>[\\s\\S]*?)\\n\\s*CHAIN\\s*$").b ];
    def speech(x; sep):
        (x.message.content // x.content // []) as $c |
        if ($c | type) == "array" then
            ($c | map(if .type == "text" then .text
                      elif .type == "thinking" and ((.thinking // "") | length > 0) then .thinking
                      else empty end) | join(sep))
        elif ($c | type) == "string" then $c else "" end;
    reduce inputs as $r (($a[0] // {k: "", t: [], bad: false});
        if ($r | turn_user)
        then {k: get_text($r; " "), id: ($r.uuid // ""), t: [], bad: false}
        elif role($r) == "assistant" then
            (try speech($r; "\n") catch null) as $x
            | (if $x == null then .bad = true elif $x != "" then .t += [$x] else . end)
            | .t += (try chains($r) catch [])
        else . end)'
# rc_turn_digest <transcript> — свёртка хода по дописанным байтам (D498): на долгом ходе
# цена вызова — дописанное с прошлого вызова, а не весь ход.
rc_turn_digest() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    transcript_fold "$_rc_t" rc-turn turn jq -cn "$RC_TURN_STEP" --slurpfile a 2>/dev/null
}

# rc_turn_key <transcript> — метка хода: cksum идентификатора и текста последней непустой реплики собеседника.
# Идентификатор записи (`uuid`, он есть у каждой записи расшифровки) различает ходы с одинаковой репликой («продолжай» →
# «продолжай»): по одному тексту у них были общий якорь исходов, общие живые поводы и общая пара журнала исходов (D1130,
# скептик L4). Свёртка хранит только текущий ход, поэтому порядковый номер реплики из неё не взять. Записи без `uuid`
# (фикстуры) — прежний ключ по тексту.
# Ею гейт подписывает журнал срабатываний, ею же сверщик находит срабатывания этого хода.
rc_turn_key() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    rc_turn_digest "$_rc_t" | jq -r 'if (.id // "") == "" then .k else "\(.id)|\(.k)" end' 2>/dev/null | cksum 2>/dev/null | awk '{print $1}'
}

# rc_last_block <transcript> — последний блок речи агента после последней реплики
# собеседника. Признак находки читается по нему, а не по всему окну хода: слово находки,
# однажды сказанное, оставалось бы в окне до конца хода, и все последующие находки
# сливались бы с первой (диагноз 28 августа 2026, индексы 1055/1159).
rc_last_block() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    rc_turn_digest "$_rc_t" | jq -r 'if .bad then empty else (.t | last // "") end' 2>/dev/null
}

# RC_KINDS_RE — все СРОДЫ поводов, которые гейт пишет в журнал `five-whys-<SID>.seen`.
# До 29 августа 2026 след разбора проверялся ровно у одного срода — `discovery:`. В живых
# журналах при этом: daily 126, repeat 59, discovery 36, correction 6, streak 4 — то есть у
# 195 срабатываний из 231 исход не проверял никто, и «заметил и ничего не сделал» было
# неотличимо от «сделал». Перечень сродов держится здесь, а не в потребителе: продюсер и
# потребитель уже расходились молча на ключе хода.
#
# 9 сентября 2026 сюда добавлен `notfollowed:` — девятый срод. Гейт заводил его с 6 сентября
# (`five-whys-gate.sh:277`), а перечень-владелец не знал: следствие механическое и измеренное —
# 0 записей исхода из 1035, срод был невидим и сверщику (`declared-problem-recorded.sh:76`),
# и своду незакрытого (`hooks/lib/open-findings-lib.sh:67`). Это тот самый род, ради которого
# перечень и держится в одном месте: писатель объявил ключ, читатель о нём не узнал.
#
# 13 сентября 2026 добавлен `self_repeat:` — одиннадцатый срод (D325, корень R2): агент сам
# называет повтор («это пятый раз за день», «второй раз подряд», «тот же класс»), и до этого
# дня фраза не запускала ничего — среди поводов её не было, слово о повторе служило
# завершением темы. Словарь маркера — RC_SELF_REPEAT_RE ниже; им же меряет реплей
# `scripts/self-repeat-replay.py`, чтобы у формы был один владелец.
# `daily:` снят 13 сентября 2026 (D358): суточный повтор знания ушёл из гейта в очередь отложенных
# уведомлений, писателя срода в дереве нет, а перечень без писателя — мёртвая запись
# (test_kinds_writer_reader_parity). Записи `daily:` в журналах до этой даты читателями перечня
# не различаются намеренно: их предмет — сутки, а не ход, и в доли по ходам они не входят.
RC_KINDS_RE="${RC_KINDS_RE:-rework:|correction:|question:|streak:|repeat:|notfollowed:|discovery:|event:|breakage:|self_repeat:}"
# RC_STANDING_KINDS — сроды СТОЯЧИЕ: отказа не дают и исхода не требуют, только называются (D1214). Владелец перечня один —
# здесь, рядом с перечнем всех сродов: страж берёт его отсюда (`FWG_STANDING`, `five-whys-gate.sh`), а свод «поводов без
# исхода» (`hooks/lib/open-findings-lib.sh`) стоячих не считает и не зовёт доводить до исхода (D1256, корень R6: прежде
# их `deferred` шёл в «отложено» наравне с видами, державшими отказ).
RC_STANDING_KINDS="${RC_STANDING_KINDS:-event question breakage self_repeat}"

# RC_SELF_REPEAT_RE — маркер повтора в СОБСТВЕННОЙ речи агента. Формы взяты из замера 6 сентября
# 2026 по расшифровке живой сессии (блоков речи 350, с маркером 20, настоящих 15): счёт повторов
# «N-й раз», «второй/третий раз (подряд)», «тот же класс», «того же дня». Точность сырого признака
# 15 из 20 = 75% — четверть ложных («подтверждение» о счётчике знания, «за сессию» о материале),
# поэтому срод СТОЯЧИЙ: напоминает, отказа не даёт. Текст подаётся в нижнем регистре (to_lower).
# У СЛОВАРЯ ДВА ДВИЖКА: grep -E в гейте и Python `re` в реплее. Форма обязана быть верна в обоих:
# кириллический диапазон `[а-я]` отвергает GNU grep в C.UTF-8 («Invalid collation character»,
# CI 05a7965), POSIX-класс `[[:space:]]` не знает Python (читает как набор букв). Отсюда `[^ ]*`.
RC_SELF_REPEAT_RE="${RC_SELF_REPEAT_RE:-[0-9]+-?(й|ой|ий|ый) раз|(втор|трет|четвёрт|четверт|пят|шест|седьм|восьм|девят|десят)[^ ]* раз|раз подряд|тот же класс|того же класса|того же дня}"

# rc_signals_of_turn <журнал> <ключ хода> — сроды поводов, сработавших в ЭТОМ ходе,
# по одному в строке (без двоеточия). Пусто — поводов в ходе не было.
rc_signals_of_turn() {
    _rc_j="${1:-}"; _rc_k="${2:-}"
    [ -n "$_rc_j" ] && [ -f "$_rc_j" ] && [ -n "$_rc_k" ] || return 0
    grep "^turn:${_rc_k}|" "$_rc_j" 2>/dev/null \
        | grep -oE "$RC_KINDS_RE" 2>/dev/null \
        | sed 's/:$//' | sort -u
}

# RC_OUTCOMES — закрытый список исходов повода разбора, единственное их определение.
# Наблюдаемые автоматом (кто пишет — в скобках):
#   chain-spoken — цепочка произнесена, страж пропустил работу дальше (five-whys-gate)
#   looked       — отказ снят осмотром без следа разбора (five-whys-gate, 4–23 октября 2026, D513);
#                  с D1035 не пишется — снятие названным исходом пишет `recorded`; в списке
#                  остаётся ради журналов того времени
#   deferred     — правка отложена отказом, вызов не выполнен (five-whys-gate)
#   recorded     — исход хода СВЕРЕН с записью разбора (`rc_record_verdict`): страж при снятии отказа
#                  и сверщик на Stop за сверенную строку `manual-` хода (five-whys-gate, declared-problem-recorded)
#   touched      — носитель тронут или механизм правлен в ходе, исход не сверен (declared-problem-recorded,
#                  с 26 октября 2026, D1107: до этого сверщик писал это же наблюдение словом `recorded`, и
#                  замер долей не отличал сверенный исход от любой правки бэклога — корень R6)
#   none         — ничего из перечисленного (declared-problem-recorded)
# Называемые агентом через `scripts/outcome.sh` (наблюдением их не отличить от бездействия):
#   fixed | debt | knowledge | disproved
# Первые три автоматических означают «ход дела изменился», `none` — нет; на этом различии
# стоит замер `outcome-share.sh`. До 29 августа 2026 список существовал двумя редакциями:
# доккомментарий перечислял пять значений, а автомат писал шестое (`recorded`).
RC_OUTCOMES="chain-spoken looked deferred recorded touched none fixed debt knowledge disproved"
RC_OUTCOMES_ACTED="chain-spoken looked deferred recorded touched fixed debt knowledge"

# rc_log_outcome <state_dir> <sid> <ключ хода> <сигнал> <исход> [ссылка]
#   Дописывает строку в журнал исходов `outcome-<SID>.jsonl`. Значения — из RC_OUTCOMES.
#
# Зачем журнал (D112). Прежний журнал стража писал СРАБАТЫВАНИЯ и не писал ИСХОДЫ: по нему
# нельзя было ответить, изменилось ли хоть что-то после напоминания, — а замер 28 августа
# 2026 показал, что напоминание читается и не меняет действия (минимум 9 случаев из 19).
# «Страж сработал» и «страж помог» — разные утверждения, и второе до сих пор не считалось.
# Исход определяется НАБЛЮДАЕМО (изменился носитель), а не декларацией агента; единственный
# агентский вход — вердикт «показалось», и его доля есть замер точности сигнала, а не повод
# воспитывать исполнителя.
rc_log_outcome() {
    _rc_sd="${1:-}"; _rc_sid="${2:-}"; _rc_key="${3:-}"
    _rc_sig="${4:-}"; _rc_out="${5:-}"; _rc_ref="${6:-}"; _rc_tr="${7:-}"; _rc_tk="${8:-}"
    [ -n "$_rc_sd" ] && [ -n "$_rc_sid" ] && [ -n "$_rc_sig" ] && [ -n "$_rc_out" ] || return 0
    mkdir -p "$_rc_sd" 2>/dev/null || return 0
    _rc_f="$_rc_sd/outcome-${_rc_sid}.jsonl"
    # Идемпотентность по ходу и сигналу: Stop срабатывает не единожды за ход, и без этого
    # один и тот же исход умножался бы, перекашивая доли в замере.
    # ПЕРЕХОДЫ ПАРЫ (ход, вид) — по её ПОСЛЕДНЕМУ исходу. Отказ пишет `deferred`, снятие того же хода — разбором
    # (`chain-spoken`), осмотром (`looked`, 4–23 октября) или сверенным исходом (`recorded`, D1035), сверщик на Stop —
    # `touched` (носитель тронут, исход не сверен, D1107). Без перехода «отложено и брошено» и «отложено, снято, пропущено»
    # давали бы одно значение (D1034, корень R6). Сейчас:
    #   · повтор последнего исхода отброшен (D1125: повтор — по последнему, а не по любому);
    #   · поверх `deferred` проходят снятия и `touched` (D1111);
    #   · поверх `touched` — снятия и отказ, пришедший позже: Stop бывает в ходе не единожды (D1119);
    #   · поверх снятия — только отказ: это отказ ДРУГОГО повода того же вида в ходе (D1126; единица снятия — повод, D1116);
    #   · `none` сверщика поверх пары не ложится: иначе отказ пропал бы из отчёта.
    # Читатели, считающие записи ходами, сворачивают пару к последнему исходу (`scripts/outcome-share.sh`, разметка ANNOT);
    # сводка открытого (`hooks/lib/open-findings-lib.sh`) гасит отказ снятием своей пары.
    if [ -f "$_rc_f" ] && grep -q "\"key\":\"${_rc_key}\",\"signal\":\"${_rc_sig}\"" "$_rc_f" 2>/dev/null; then
        case "$_rc_out" in chain-spoken|looked|recorded|touched|deferred) ;; *) return 0 ;; esac
        # Счёт, а не статус трубы: `-q` у второго grep рвал бы трубу первому, и под pipefail
        # пара отвечала бы 141 — и снятие писалось бы дважды.
        _rc_pair=$(grep "\"key\":\"${_rc_key}\",\"signal\":\"${_rc_sig}\"" "$_rc_f" 2>/dev/null)
        # Повтор — совпадение с ПОСЛЕДНИМ исходом пары, а не с любым (D1125, скептик M1): в паре с одними deferred/touched
        # последний исход — deferred (тогда отказ — повтор) или touched (тогда отказ — позднейший, после Stop, и ложится).
        # Прежняя проверка «исход уже есть в паре» теряла второй отказ в цепочке deferred→touched→deferred.
        _rc_last=$(printf '%s\n' "$_rc_pair" | tail -n 1 | grep -oE '"outcome":"[a-z-]+"' | cut -d'"' -f4)
        [ "$_rc_last" = "$_rc_out" ] && return 0
        # После снятия пара закрыта для всего, кроме отказа: отказ здесь — ДРУГОГО повода того же вида в этом ходе (D1126,
        # скептик M2). Единица снятия — повод (D1116), а журнал ведётся по паре (ход, вид); прежнее правило «пара со снятием
        # закрыта» отбрасывало отказ второй находки после снятия первой, и замер считал ход сверенным.
        case "$_rc_last" in chain-spoken|looked|recorded) [ "$_rc_out" = deferred ] || return 0 ;; esac
    fi
    # След разбора (D211) — седьмой аргумент, JSON-объект от rc_trace. Без него поля `trace`
    # в записи нет: старые читатели берут только .signal/.outcome и не замечают разницы.
    # Порядок ключей сохранён: дедуп выше ищет подстроку `"key":…,"signal":…`.
    if [ -n "$_rc_tr" ] && ! printf '%s' "$_rc_tr" | jq -e 'type == "object"' >/dev/null 2>&1; then
        _rc_tr=""
    fi
    # Метка редакции `v` (D1111): с D1107 `recorded` значит «исход сверен», а прежние записи того же слова — «носитель
    # тронут». Без метки два смысла в журнале неразличимы, и замер долей считал 2067 прежних записей сверенными (R6).
    # Поле в конце записи: дедуп выше ищет подстроку `"key":…,"signal":…`, порядок первых ключей сохранён.
    # Поводы исхода `toks` (D1116) — восьмой аргумент, токены через «|»: исход `outcome.sh` относится к тем находкам,
    # против которых его приняла сверка, и страж снимает им отказ только по такой строке. Без аргумента поля нет.
    jq -cn --arg ts "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" --arg k "${_rc_key:-0}" \
           --arg s "$_rc_sig" --arg o "$_rc_out" --arg r "$_rc_ref" --arg t "$_rc_tr" --arg tk "$_rc_tk" \
        '{ts:$ts, key:$k, signal:$s, outcome:$o,
          ref:($r | if length > 400 then .[0:400] + "…" else . end)}
         + (if $t == "" then {} else {trace: ($t | fromjson)} end) + {v: 2}
         + (if $tk == "" then {} else {toks: ($tk | split("|") | map(select(. != "")))} end)' >> "$_rc_f" 2>/dev/null || true
}

