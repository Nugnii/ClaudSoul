# Третий носитель того же признака записи, что `redirect_bare` в `command-scope-lib.sh`.
# Функцию сюда не позвать — признак живёт внутри программы jq, — поэтому вынесены не строки,
# а два условия, и оба сформулированы отрицанием, а не перечнем:
#   · «>» не перенаправляет, если рядом стоит «=» или «-» — это оператор чужого языка
#     (>=, >>=, ->, =>). Замер 10 сентября 2026: из 3374 команд, признанных записью, 112
#     (3,3%) держались единственно на этом. Oniguruma в jq умеет lookbehind, проверено;
#   · `mv`/`cp` — имя КОМАНДЫ, а не подстрока: без границы слева сюда попадали `grep "cp .*lib"`
#     и всякий путь, где эти две буквы стоят внутри слова.
# НАЗВАННЫЙ ПРЕДЕЛ: кавычки здесь не снимаются (в отличие от `redirect_bare`) — признак
# читает сырую команду, поэтому запись, поминаемая внутри строки-аргумента, всё ещё считается
# правкой мира. Замер критика: 89 таких из 861 осмотров, из них 5 без единой формы записи
# вне кавычек. Условие снятия: разбор области команды переедет в jq либо учёт исхода станет
# звать shell-функцию до входа в jq.
# Перенаправление в `/dev/null` — не запись (D1329): с ним вся команда шла в цели правки, и чтение хука или бэклога
# с `2>/dev/null` становилось «починкой механизма» либо «пунктом долга». Замер по 3 840 ходам 400 расшифровок: у 165
# исход держался только на этом. `>` в классе после пробелов не даёт `>>/dev/null` совпасть со второго знака.
RC_OUT_WRITE_RE='((?<![-=])>>?(?!=)(?![ ]*/dev/null)[ ]*[^ |&>]|sed -i|[ ]tee[ ]|^tee[ ]|git[ ]+commit|(^|[ |;&(])(mv|cp)[ ])'
rc_outcome_observed() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 1
    # Владельца перечня кода нет — отвечаем «не наблюдал», а не судим по своей копии:
    # третье состояние прибора («мерить нечем») отличимо от «исхода не было».
    [ -n "${RC_OUT_MECH_RE:-}" ] || return 1
    _rc_kinds=$(transcript_turn_window "$_rc_t" wide | jq -rs \
        --arg kn "$RC_OUT_KNOWLEDGE_RE" --arg db "$RC_OUT_DEBT_RE" \
        --arg mc "$RC_OUT_MECH_RE" --arg wr "$RC_OUT_WRITE_RE" --arg ls "$(rc_resolution_kinds)" "${HIL_TURN_USER_JQ:-def turn_user: false;}"'
        def role(x): x.message.role // x.role // "";
        def blocks(x): (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then $c else [] end;
        def get_text(x): (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then ($c | map(select(.type == "text") | .text) | join("\n"))
            elif ($c | type) == "string" then $c else "" end;
        . as $items | (length) as $n |
        ([range(0; $n) | ($n - 1 - .)
          | select($items[.] | turn_user)]
          | first) as $pu |
        (if $pu == null then 0 else $pu + 1 end) as $from |
        [range($from; $n) | $items[.]] as $seg |
        # тексты, которые АГЕНТ произнёс в этом ходе — только для вердикта «показалось». Речь —
        # текст и непустой пересказ `thinking`: с Opus 5.5 промежуточная речь ложится в расшифровку
        # пересказом, и вердикт, сказанный по ходу, иначе не виден (D505, решение владельца 3 октября 2026).
        ([$seg[] | select(role(.) == "assistant") | blocks(.)[]
          | if .type == "text" then (.text // "")
            elif .type == "thinking" and ((.thinking // "") | length > 0) then .thinking
            else empty end] | join("\n")) as $txt |
        # цели правки: file_path у файловых инструментов, команда у Bash при форме записи. Правку от чтения отличает
        # УСТРОЙСТВО входа, а не имя инструмента: вызов правки несёт то, что пишет, — ключ `content`, `edits` либо
        # `new_…` (`new_string`; `new_str` несут только служебные копии запроса `api-request-blob` — D1343, D1346). Прочитанный
        # хук или бэклог исходом не считается (D1329: у 4 ходов из 3 840 исход держался на чтении); публикация файла
        # (путь и подпись) — тоже.
        ([$seg[] | select(role(.) == "assistant") | blocks(.)[]
          | select(.type == "tool_use" and (.input | type) == "object")
          | if (.input.file_path // "") != "" then
                (if (.input | keys | any(test("^(content$|edits$|new_)"))) then .input.file_path else empty end)
            elif ((.input.command // "") | test($wr)) then (.input.command // "")
            else empty end] | join("\n")) as $tgt |
        [ (if ($tgt | test($kn)) then "запись знания" else empty end),
          (if ($tgt | test($db)) then "пункт долга" else empty end),
          (if ($tgt | test($mc)) then "починка механизма" else empty end),
          # Вердикт — слово «показалось» не в отрицании, не перед словом на той же строке («показалось достаточно») и
          # не в дословном пересказе закрытого списка исходов, который печатают сами стражи (D1329). ПРЕДЕЛ: речь
          # двусмысленна («показалось, что…» проходит); условие снятия — вердикт читается по журналу `outcome.sh`.
          (if ($txt | split($ls) | join("") | test("(?<!не\\s)показалось(?![ ]+\\w)"; "i")) then "вердикт «показалось»" else empty end) ]
        | join(" · ")
    ' 2>/dev/null)
    [ -n "${_rc_kinds:-}" ] || return 1
    printf '%s' "$_rc_kinds"
}

