# why=4, heads=4, roots=22 — критерий проходит.
#
# Усиливать распознавание форм бесполезно: цитата и настоящая цепочка состоят из ОДНИХ И
# ТЕХ ЖЕ форм. Пробовали иначе — требовать адрес на записывающем вызове; отвергнуто
# замером: реплей по журналу исходов дал 16 засчитанных цепочек, адрес есть у 14, то есть
# 2 настоящие получили бы ложный отказ. И глубже: признак «нет адреса» несёт ДВА разных
# последствия — обход и короткая законная цепочка о предмете вне дерева, — а значит взят
# выше корня (`case-2026-08-28-enforcement-is-a-property-of-consequence`).
#
# Корень не в критерии, а в его ВХОДЕ: узел, исправно посчитавший неверный вход, корнем не
# является. Подай верный вход — симптом исчезнет без правки узла. Та же форма, что D87, где
# из реплики собеседника вырезается чужая речь: здесь из текста хода вырезается
# процитированное правило.
#
# Порог длины строки: короткие строки совпадают случайно («- ☐», «**Результат.**»).
# Цена замерена, а не прикинута: 18 мс на вызов (10 прогонов, 180 мс). Кэша нет намеренно —
# на фоне нескольких вызовов jq в том же страже это не тот порядок, ради которого стоит
# заводить ещё один файл состояния и его инвалидацию.
# НАЗВАННЫЙ ПРЕДЕЛ: вырезается дословное ПОСТРОЧНО. Пересказ своими словами не ловится и
# ловиться этим способом не может; переклеенная в один абзац цитата — тоже, там строки уже
# не те. Замеренный случай обхода был копией с переносами, и он закрыт. Условие снятия —
# когда у пересказа появится наблюдаемый признак, отличный от форм самой доктрины.
rc_strip_quoted_doctrine() {
    _rcd_src="${RC_DOCTRINE_SRC:-$HOME/.claude/CLAUDE.md}"
    if [ ! -f "$_rcd_src" ]; then cat; return 0; fi
    _rcd_f=$(mktemp 2>/dev/null) || { cat; return 0; }
    # Длина в СИМВОЛАХ, а не байтах: у кириллической строки из 40 символов 70+ байт, и
    # байтовый порог берёт вдвое больше строк, чем задумано.
    #
    # До 10 сентября 2026 здесь стоял `awk length($0)`, а он в BSD awk (macOS) считает
    # БАЙТЫ — то есть код делал ровно то, что комментарий над ним запрещал. Замер по
    # `~/.claude/CLAUDE.md`: «длинными» признаны 377 строк по байтам против 349 по символам,
    # то есть 28 КОРОТКИХ строк правил вырезались из текста хода как «процитированная
    # доктрина» — среди них `## Таймштамп-канарейка` (22 символа) и `Допустимые источники:`
    # (21). Последствие ложного вырезания обратное задуманному: формы разбора, случайно
    # совпавшие с короткой строкой правил, исчезали до подсчёта, и критерий недосчитывал
    # произнесённое. Найдено прожаркой; сама подмена предмета — `pattern-subject-of-measurement-mismatch`.
    #
    # `perl -CSD` вместо `awk`: gawk с символьной семантикой есть не везде, а perl уже
    # служит в дереве заменой отсутствующему `timeout` (pattern-shell-portability).
    perl -CSD -ne 'chomp; print "$_\n" if length($_) >= 40' "$_rcd_src" > "$_rcd_f" 2>/dev/null
    if [ -s "$_rcd_f" ]; then
        grep -vxF -f "$_rcd_f" 2>/dev/null || cat
    else
        cat
    fi
    rm -f "$_rcd_f" 2>/dev/null
}

rc_trace() {
    rc_turn_text "${1:-}" | rc_trace_text
}

# rc_trace_text — след разбора для ПРОИЗВОЛЬНОГО текста со stdin, тот же JSON.
# Выделен из rc_trace 4 сентября 2026: замеру `stopper-effect` нужен отрезок речи ПОСЛЕ
# конкретного отказа, а не последний ход расшифровки, и он держал СВОЮ копию критерия
# («почему» ≥ 3) — ту, которую ADR-017 отменил 30 августа. Копия определения, у которого
# есть канонический дом, расходится с ним молча: замер отчитывался 34% там, где по канону
# 91%. Вырезание процитированной доктрины стоит здесь, а не у вызывающего, — иначе каждый
# новый вызывающий забудет его так же.
rc_trace_text() {
    _rc_txt=$(rc_strip_quoted_doctrine)
    printf '%s' "${_rc_txt:-}" | jq -Rsc \
        --arg addr "$RC_TRACE_ADDR_RE" --arg frac "$RC_TRACE_FRAC_RE" \
        --arg root "$RC_TRACE_ROOT_RE" --arg heads "$RC_TRACE_HEADS" \
        --arg input "$RC_TRACE_INPUT_RE" '
        . as $t |
        { why:    ([$t | match("почему"; "gi")] | length),
          addr:   ([$t | match($addr; "g") | .string | sub(".*/"; "")] | unique | length),
          frac:   ([$t | match($frac; "g")
                    | select((.captures[0].string | tonumber) < (.captures[1].string | tonumber))] | length),
          roots:  ([$t | match($root; "gi")] | length),
          heads:  ([($heads | split("|"))[] as $h | select($t | test($h; "i"))] | length),
                    # Обе стрелки, а не одна (11 сентября 2026). Счётчик искал ТОЛЬКО «←»,
          # тогда как доктрина, которой учит сам гейт, печатает «→»: в rules/CLAUDE.md
          # «←» встречается 0 раз против 27 «→», а в корпусе одной сессии агента —
          # 11 против 303. То есть 96% произнесённых стрелок ветвь не видела, и разбор
          # засчитывался только по другим ветвям формулы. Корень R1: символ собран
          # литералом на каждом конце связи отдельно — писатель доктрины и её читатель.
          arrows: ([$t | match("←|→"; "g")] | length),
          inputs: ([$t | match($input; "gi")] | length) }
    ' 2>/dev/null || printf '{"why":0,"addr":0,"frac":0,"roots":0,"heads":0,"arrows":0,"inputs":0}'
}

# rc_chain_spoken <trace-json> [min_why] — код 0, если разбор в ходе БЫЛ. ЕДИНСТВЕННОЕ
# определение «цепочка произнесена»: слово «почему» не меньше min_why (по умолчанию 3) ИЛИ
# два и больше заголовков шаблона ИЛИ спуск стрелками (три и больше «←») ИЛИ реестр мест —
# два адреса, дробь N < M и слово «корень». Та же формула на jq стоит в outcome-share.sh
# (доля поводов со следом); test_outcome_journal сверяет обе на одном наборе.
# Замер критерия на корпусе: сверх «почему ≥ 3» (57 ходов) заголовки добавляют 3 хода,
# стрелки — 2, реестр с корнем — 5; ложных среди них 1. Из трёх живых отказов гейта
# критерий снял бы один — и тот был ложным: разделы «Вширь…/Вглубь…», спуск «←», «почему» ноль.
# RC_JQ_CHAIN — определение «цепочка произнесена» на jq, ЕДИНСТВЕННОЕ в дереве.
#
# Прежде оно жило двумя копиями: здесь и в `scripts/outcome-share.sh:64-66`, и 9 сентября
# 2026 они разошлись на первой же правке — ровно как предсказывает род K реестра («правило
# вынесено в модуль, копия у потребителя осталась»). Разрыв поймал страж `test_outcome_journal`
# T14d словами «библиотека не признаёт след, который засчитал замер». Теперь потребитель
# источает библиотеку и берёт выражение отсюда; порог передаётся как `--argjson m`.
RC_JQ_CHAIN="${RC_JQ_CHAIN:-def chain(t): t != null and (
    ((t.addr // 0) >= 1)
    and ((t.why // 0) >= (\$m // 3) or (t.heads // 0) >= 2 or (t.arrows // 0) >= 3
         or ((t.frac // 0) >= 1 and (t.roots // 0) >= 1)));}"

rc_chain_spoken() {
    _rc_j="${1:-}"; _rc_min="${2:-3}"
    [ -n "$_rc_j" ] || return 1
    # АДРЕС ОБЯЗАТЕЛЕН ВО ВСЕХ ВЕТВЯХ (9 сентября 2026). Прежде критерий был чистой
    # дизъюнкцией, и три её ветви — «почему», заголовки, стрелки — проходились ПРИ НУЛЕ
    # адресов. Цена названа в D323: дословная цитата доктрины даёт why=4, heads=4, addr=0,
    # то есть снимала отказ, ничего не разобрав; и разбор с подменённой дробью (объявлено
    # «5 из 5» при настоящей «1 из 65») гейт пропустил, потому что формы были произнесены.
    # Доктрина, которую этот же файл печатает при отказе, говорит: «Каждое место с
    # адресом — файл:строка, прогон, лог. Без адреса пункт не считается».
    #
    # Порог именно ОДИН адрес, а не два: доктрина признаёт законным разбор с единственным
    # проявлением («одно проявление — шаг пуст, иди дальше»), и требовать двух значило бы
    # запрещать честный случай. Замер по 976 следам в живых журналах: старый критерий
    # проходят 163, `addr>=1` — 135 (отсекает 28, 17%), `addr>=2` — 78 (отсекает 52%).
    # Отсекаются ровно те, где адресов НЕТ ВОВСЕ, — то есть разбор был речью.
    #
    # НАЗВАННЫЙ ПРЕДЕЛ: адрес проверяется на присутствие, а не на отношение к делу — можно
    # назвать файл:строку, не имеющую к разбору касательства. Условие снятия: адрес станет
    # сверяться с целью правки или с реестром мест, предъявленным командой.
    printf '%s' "$_rc_j" | jq -e --argjson m "$_rc_min" "$RC_JQ_CHAIN"' chain(.)' >/dev/null 2>&1
}

# rc_why_count <transcript> — сколько раз в ответах агента ПОСЛЕ последней реплики
# собеседника встречается слово «почему». Считается той же формулой, что поле `why` следа:
# два счётчика одного слова расходились бы молча (регистр кириллицы у grep -i зависит от
# локали, у Oniguruma — нет). Печатает число, всегда цифры.
rc_why_count() {
    _rc_n=$(rc_trace "${1:-}" | jq -r '.why // 0' 2>/dev/null)
    case "${_rc_n:-}" in ''|*[!0-9]*) _rc_n=0 ;; esac
    printf '%s' "$_rc_n"
}
