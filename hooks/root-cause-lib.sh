# rc_turn_text <transcript> — весь текст агента ПОСЛЕ последней реплики собеседника.
# Разбор из прошлого хода к нынешнему повтору не относится — потому граница та же, что у
# rc_turn_key. Единственный экстрактор текста хода: rc_why_count и rc_trace берут его отсюда.
rc_turn_text() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    jq -rs '
        def role(x): x.message.role // x.role // "";
        def get_text(x):
            (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then
                ($c | map(select(.type == "text") | .text) | join("\n"))
            elif ($c | type) == "string" then $c
            else "" end;
        . as $items | (length) as $n |
        ([range(0; $n) | ($n - 1 - .)
          | select(role($items[.]) == "user" and
                   ((get_text($items[.]) // "") | length > 0))]
          | first) as $pu |
        if $pu == null then
            ([range(0; $n) | $items[.] | select(role(.) == "assistant")]
             | map(get_text(.)) | map(select(. != "")) | join("\n"))
        else
            ([range($pu + 1; $n) | $items[.] | select(role(.) == "assistant")]
             | map(get_text(.)) | map(select(. != "")) | join("\n"))
        end
    ' "$_rc_t" 2>/dev/null
}

# ── След разбора (D211) ───────────────────────────────────────────────────────
# До 30 августа 2026 единственным машинным признаком «разбор был» служил счёт слова
# «почему», и доктрина ADR-016 (реестр мест с дробью, входы узла, объявленный корень)
# жила только в тексте ответа: связный разбор без этого слова был неотличим от его
# отсутствия, а пять пустых «почему» считались разбором. Формы ниже выбраны РЕПЛЕЕМ по
# корпусу (33 расшифровки, 486 ходов с текстом агента), а не по вкусу: настоящие цепочки без
# слова «почему» в корпусе выглядят как заголовки шаблона гейта («Вширь…/Вглубь…») и спуск
# стрелками «←»; сочетание «адреса + дробь» само по себе ловило отчёты о правках («7 из 7
# покрыты», таблицы пунктов) — 4 ложных из 9, — и потому считается цепочкой только вместе
# со словом «корень». Дробь берётся лишь в форме «N из M» с N < M: прочие формы доктрины
# («M = N», «M<N») в речи не встретились ни разу из 160, а «N из N» на 35% — отчёты о прогонах.
#
# НАЗВАННЫЙ ПРЕДЕЛ. Это формы, а не мысль; цена ложного «след есть» — ПРАВКА, ПРОШЕДШАЯ БЕЗ
# ЦЕПОЧКИ, потому что критерий стоит в гейте, а не только в замере. Полного перечня форм не
# бывает (pattern-subject-checked-by-enumeration); список дополняется измеренными промахами.
# Условие снятия: след разбора будет записываться не из речи (реестр мест и входы — файлом
# или командой), и считать формы в тексте станет незачем.
# КОНТРПРИМЕР: «121 из 121» (N = M) дробью не считается; дата «30/08» и «3 из 7» без адресов
# и корня цепочкой не считаются; «проверено» не считается входом («верен» с границей слова).
# Регэкспы — Oniguruma внутри jq, а не grep: `\b`, `[^а-яё]` и регистр кириллицы там одинаковы
# на macOS и Linux, у BSD/GNU grep — нет (pattern-shell-portability).
RC_TRACE_ADDR_RE='[A-Za-z0-9_./-]+\.(sh|py|md|js|ts|json|tsv|yml|yaml|toml|txt):[0-9]+'
RC_TRACE_FRAC_RE='\b([0-9]+) из ([0-9]+)\b'
RC_TRACE_ROOT_RE='корень|корни|корней|корня|корнем'
RC_TRACE_HEADS='вширь|вглубь|сверка|братья корня|зависимости'
RC_TRACE_INPUT_RE='вход[^\s]*[^.\n]{0,80}(^|[^а-яё])(не)?вер(ен|ны)([^а-яё]|$)'

# rc_trace <transcript> — след разбора в тексте хода, компактный JSON:
#   {"why":N,"addr":N,"frac":N,"roots":N,"heads":N,"arrows":N,"inputs":N}
#   why — слово «почему»; addr — РАЗНЫЕ адреса файл:строка (нормализованы до basename:строка,
#   иначе `hooks/x.sh:65` и `x.sh:65` — два места); frac — дроби «N из M» с N < M; roots —
#   словоформы «корень»; heads — РАЗНЫЕ заголовки шаблона доктрины; arrows — «←»; inputs —
#   «вход… верен/неверен» (только счётчик: измеренный вклад в критерий — 0 ходов).
# На пустом/нечитаемом входе — все нули, код 0.
rc_trace() {
    _rc_txt=$(rc_turn_text "${1:-}")
    printf '%s' "${_rc_txt:-}" | jq -Rsc \
        --arg addr "$RC_TRACE_ADDR_RE" --arg frac "$RC_TRACE_FRAC_RE" \
        --arg root "$RC_TRACE_ROOT_RE" --arg heads "$RC_TRACE_HEADS" \
        --arg input "$RC_TRACE_INPUT_RE" '
        . as $t |
        { why:    ([$t | match("почему"; "gi")] | length),
          addr:   ([$t | match($addr; "g") | .string | sub(".*/"; "")] | unique | length),
          frac:   ([$t | match($frac; "g")
                    | select((.captures[0].string | tonumber) < (.captures[1].string | tonumber))] | length),
          roots:  ([$t | match($root; "gi")] | length),
          heads:  ([($heads | split("|"))[] as $h | select($t | test($h; "i"))] | length),
          arrows: ([$t | match("←"; "g")] | length),
          inputs: ([$t | match($input; "gi")] | length) }
    ' 2>/dev/null || printf '{"why":0,"addr":0,"frac":0,"roots":0,"heads":0,"arrows":0,"inputs":0}'
}

# rc_chain_spoken <trace-json> [min_why] — код 0, если разбор в ходе БЫЛ. ЕДИНСТВЕННОЕ
# определение «цепочка произнесена»: слово «почему» не меньше min_why (по умолчанию 3) ИЛИ
# два и больше заголовков шаблона ИЛИ спуск стрелками (три и больше «←») ИЛИ реестр мест —
# два адреса, дробь N < M и слово «корень». Та же формула на jq стоит в outcome-share.sh
# (доля поводов со следом); test_outcome_journal сверяет обе на одном наборе.
# Замер критерия на корпусе: сверх «почему ≥ 3» (57 ходов) заголовки добавляют 3 хода,
# стрелки — 2, реестр с корнем — 5; ложных среди них 1. Из трёх живых отказов гейта
# критерий снял бы один — и тот был ложным: разделы «Вширь…/Вглубь…», спуск «←», «почему» ноль.
rc_chain_spoken() {
    _rc_j="${1:-}"; _rc_min="${2:-3}"
    [ -n "$_rc_j" ] || return 1
    printf '%s' "$_rc_j" | jq -e --argjson m "$_rc_min" '
        (.why // 0) >= $m or (.heads // 0) >= 2 or (.arrows // 0) >= 3
        or ((.addr // 0) >= 2 and (.frac // 0) >= 1 and (.roots // 0) >= 1)
    ' >/dev/null 2>&1
}

# rc_why_count <transcript> — сколько раз в ответах агента ПОСЛЕ последней реплики
# собеседника встречается слово «почему». Считается той же формулой, что поле `why` следа:
# два счётчика одного слова расходились бы молча (регистр кириллицы у grep -i зависит от
# локали, у Oniguruma — нет). Печатает число, всегда цифры.
rc_why_count() {
    _rc_n=$(rc_trace "${1:-}" | jq -r '.why // 0' 2>/dev/null)
    case "${_rc_n:-}" in ''|*[!0-9]*) _rc_n=0 ;; esac
    printf '%s' "$_rc_n"
}
