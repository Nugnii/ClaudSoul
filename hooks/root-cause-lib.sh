# СНИМОК НА МОМЕНТ ПОВОДА (D1108, скептик H1, M9; D1115). Свежесть записи судилась временем изменения файла: любая
# правка бэклога делала «свежим» любой незакоммиченный пункт, вне git — любой, а знание «свежело» от правки счётчиков
# подтверждений. Теперь при первом взгляде на повод страж записывает СОСТОЯНИЕ бэклогов (проекта сессии, ClaudSoul, а
# при первой записи — проекта цели) и перечня имён знаний на этот момент.
# У КАЖДОГО ПОВОДА СВОЙ ПЕРЕЧЕНЬ (D1115, скептик H1, M1, L1). Прежде id снимка был cksum содержимого: у поводов с тем же
# содержимым снимок был общий, и бэклог проекта цели, дописанный в него при первой записи первого повода, отвечал и за
# второй — старый пункт снимал отказ нового; отсутствие бэклога у цели не запоминалось, а нечитаемый ложился пустым
# файлом. Теперь id — cksum токена повода, перечень — строки журнала стража:
#   snapbl|<id>|<канонический путь бэклога>|<состояние>|   snaples|<id>|<состояние>|
# Состояние — `absent` (файла нет), `unread` (не прочитан: нет права, не устоялся, прочитан пустым при непустом файле)
# либо cksum содержимого. Содержимое лежит одним файлом на одинаковый текст (`five-whys-<SID>.snap-<cksum>.blob.gz`,
# плоско, с сессией в имени; их убирает уборка состояния по правилу тишины сессии — D1117): поводов за сессию по 200
# журналам — медиана 23, максимум 565, и копия бэклога ClaudSoul (100 КБ) на каждый дала бы до 56 МБ.
# СЖАТО (D1314). Снимки бэклога — 173 МБ из 200 в каталоге состояния 17 ноября 2026 (1 272 копии по ~100 КБ), и каталог
# после плановой уборки вышел за порог объёма в третий раз. Читатель берёт из копии блок одного пункта, поэтому смысл
# сверки не меняется, а gzip даёт в 3,6 раза меньше по байтам на 200 разных снимках (по месту на диске живого
# каталога — в 3,25: блоки по 4 КБ). Id — cksum НЕсжатого текста, как прежде:
# совпадение содержимого по-прежнему одно имя. Прежняя форма `.blob` (без сжатия) читается — она доживает до уборки.
_rc_snap_put() {   # <основа журнала> — stdin кладётся содержимым снимка (одним файлом на одинаковый текст); stdout — cksum
    _sp_t=$(mktemp "${TMPDIR:-/tmp}/rc-snap.XXXXXX") || return 1
    # Обрыв записи (диск полон) — снимка нет, а не снимок усечённого текста под своим cksum (скептик D1314, M3).
    cat > "$_sp_t" || { rm -f "$_sp_t"; return 1; }
    _sp_c=$(cksum < "$_sp_t" | awk '{print $1}')
    _sp_f="$1.snap-${_sp_c}.blob"
    # Запись через временное имя и `mv`: оборванный gzip не должен лечь снимком под окончательным именем.
    if [ ! -f "$_sp_f.gz" ] && [ ! -f "$_sp_f" ]; then
        gzip -c < "$_sp_t" > "$_sp_f.gz.$$" 2>/dev/null && mv -f "$_sp_f.gz.$$" "$_sp_f.gz" 2>/dev/null
        rm -f "$_sp_f.gz.$$"
    fi
    rm -f "$_sp_t"
    { [ -f "$_sp_f.gz" ] || [ -f "$_sp_f" ]; } && printf '%s' "$_sp_c"
}

_rc_has_line() {   # <текст> <строка> → 0 — строка есть в тексте; 1 — нет; 2 — сверить не удалось
    # Без here-string и без трубы (скептик D1314, M1): в bash 3.2 here-string пишется во временный файл, и отказ записи
    # давал grep код 1 — «строки нет», то есть исход принимался вместо отказа. Труба с `grep -q` на тексте больше её
    # буфера (перечень знаний ~55 КБ) роняет пишущего по SIGPIPE.
    # Текст идёт awk ПОДСТАНОВКОЙ ПРОЦЕССА, а не строкой окружения (D1319): у Linux одна строка окружения не длиннее
    # 128 КБ, и за этим пределом awk не запускался вовсе. awk читает текст до конца (раннего выхода нет — пишущему
    # не о чем получить SIGPIPE) и отвечает СЛОВОМ, а не кодом: «нет» засчитывается, только когда последней пришла
    # метка конца, — оборванный текст, несозданная подстановка и незапущенный awk дают 2, а не «строки нет».
    _hl_v=$(_RC_HN="$2" awk '{ if (l == ENVIRON["_RC_HN"] && NR > 1) f = 1; l = $0 }
        END { if (l != "\001rc-end") print "?"; else print (f ? "Y" : "N") }' <(printf '%s\n\001rc-end\n' "$1") 2>/dev/null)
    case "$_hl_v" in Y) return 0 ;; N) return 1 ;; *) return 2 ;; esac
}

_rc_snap_read() {   # <основа журнала> <cksum> → содержимое снимка в stdout; 1 — снимка нет или он не читается
    if [ -f "$1.snap-$2.blob.gz" ]; then gzip -dc "$1.snap-$2.blob.gz" 2>/dev/null
    elif [ -f "$1.snap-$2.blob" ]; then cat "$1.snap-$2.blob"
    else return 1
    fi
}

_rc_snap_backlog() {   # <журнал> <id снимка> <бэклог, канонический путь> — состояние бэклога в перечень повода, если его там нет
    # Запись есть и это не `unread` — состояние снято; `unread` пересматривается (D1128, скептик M4): временный отказ чтения
    # при первом взгляде (нет права, «не устоялся», пока бэклог пишет соседняя сессия) иначе запирал повод на всю сессию.
    # Действует ПОСЛЕДНЯЯ строка пары (повод, бэклог) — пересмотр дописывает, а не правит.
    # Строка дописывается только при СМЕНЕ состояния (D1135): пока бэклог не читается, пересмотр на каждом вызове стража
    # иначе дописывал бы ту же строку `unread`, и журнал `.seen`, хранимый без окна, рос бы по числу вызовов.
    _sb_last=$(_RC_S="$2" _RC_C="$3" awk -F'|' '$1 == "snapbl" && $2 == ENVIRON["_RC_S"] && $3 == ENVIRON["_RC_C"] { v = $4 } END { print v }' "$1" 2>/dev/null)
    case "$_sb_last" in ''|unread) ;; *) return 0 ;; esac
    if [ ! -e "$3" ]; then _sb_v=absent
    elif [ ! -r "$3" ]; then _sb_v=unread
    else
        # `backlog_read` отвечает кодом 0 и пустотой и на нечитаемый файл: пустота при непустом файле — тоже `unread`.
        _sb_t=$(mktemp "${TMPDIR:-/tmp}/rc-snap.XXXXXX") || return 0
        _sb_v=unread
        if backlog_read "$3" > "$_sb_t" 2>/dev/null && { [ -s "$_sb_t" ] || [ ! -s "$3" ]; }; then
            _sb_v=$(_rc_snap_put "${1%.seen}" < "$_sb_t"); [ -n "$_sb_v" ] || _sb_v=unread
        fi
        rm -f "$_sb_t"
    fi
    [ "$_sb_v" = "$_sb_last" ] && return 0
    printf 'snapbl|%s|%s|%s|\n' "$2" "$3" "$_sb_v" >> "$1" 2>/dev/null
    # Состав архива — в тот же миг, что и первый снимок бэклога (D1255): позже он описывал бы другой мир.
    [ -z "$_sb_last" ] && _rc_snap_archive "$1" "$2" "$3"
    return 0
}

_rc_snap_archive() {   # <журнал> <id снимка> <бэклог, канонический путь> — номера пунктов архива рядом, один раз на пару
    # Свежесть пункта, не найденного в снимке бэклога, различает «лежал в архиве уже на момент повода» и «записан после
    # повода и унесён архиватором» только по составу архива тогда (D1255, корень R6). Архив — сосед бэклога, как у
    # сверки исхода ниже; номера — `backlog_ids`; нестабильный архив (код 2) не снимается — строки нет, свежесть судится
    # как до D1255. Нечитаемый архив — тоже без строки: `backlog_ids` отдаёт на нём пустоту с кодом 0, а пустота тут не
    # «архив пуст» (пустой читаемый архив — законное «номеров нет»). Номера
    # архива кэшируются в журнале строкой `archids|<cksum архива>|<снимок>|`: `backlog_ids` на 5 МБ — полсекунды в
    # синхронном PreToolUse, cksum — сотые; архив, сменившийся за подсчёт, в кэш не ложится.
    _RC_S="$2" _RC_C="$3" awk -F'|' '$1 == "snaparch" && $2 == ENVIRON["_RC_S"] && $3 == ENVIRON["_RC_C"] { f = 1 } END { exit !f }' "$1" 2>/dev/null && return 0
    _sa_a="$(dirname "$3")/BACKLOG-archive.md"
    if [ ! -e "$_sa_a" ]; then _sa_v=absent
    else
        [ -r "$_sa_a" ] || return 0
        _sa_k=$(cksum < "$_sa_a" 2>/dev/null) || return 0
        _sa_v=$(_RC_K="$_sa_k" awk -F'|' '$1 == "archids" && $2 == ENVIRON["_RC_K"] { v = $3 } END { print v }' "$1" 2>/dev/null)
        if [ -z "$_sa_v" ]; then
            _sa_ids=$(backlog_ids "$_sa_a" 2>/dev/null) || return 0
            [ "$(cksum < "$_sa_a" 2>/dev/null)" = "$_sa_k" ] || return 0
            _sa_v=$(printf '%s\n' "$_sa_ids" | _rc_snap_put "${1%.seen}"); [ -n "$_sa_v" ] || return 0
            printf 'archids|%s|%s|\n' "$_sa_k" "$_sa_v" >> "$1" 2>/dev/null
        fi
    fi
    printf 'snaparch|%s|%s|%s|\n' "$2" "$3" "$_sa_v" >> "$1" 2>/dev/null
}

_rc_snap_take() {   # <журнал> <каталог сессии> <токен> → id снимка этого повода; пусто — снимок не собрался
    _rc_need_backlog_lib || return 0
    _sk_id=$(printf '%s' "${3:-}" | cksum | awk '{print $1}')
    [ -n "$_sk_id" ] || return 0
    for _sk_d in "$(rc_project_of "$2")" "${CLAUDSOUL_ROOT:-}"; do
        [ -n "$_sk_d" ] && [ -d "$_sk_d" ] || continue
        _rc_snap_backlog "$1" "$_sk_id" "$(cd "$_sk_d" 2>/dev/null && pwd -P)/BACKLOG.md"
    done
    if ! _RC_S="$_sk_id" awk -F'|' '$1 == "snaples" && $2 == ENVIRON["_RC_S"] { f = 1; exit } END { exit !f }' "$1" 2>/dev/null; then
        _sk_l="${LESSONS_DIR:-$HOME/.claude/global-lessons}"
        _sk_v=$({ ls "$_sk_l" 2>/dev/null; ls "$_sk_l/_drafts" 2>/dev/null; } | sed -n 's/\.md$//p' | sort -u | _rc_snap_put "${1%.seen}")
        printf 'snaples|%s|%s|\n' "$_sk_id" "${_sk_v:-unread}" >> "$1" 2>/dev/null
    fi
    printf '%s' "$_sk_id"
}

rc_occasion_note() {   # <журнал> <ключ хода> <токен> <каталог> [<текст предмета>] — повод замечен в ходе
    # Первый взгляд — `seen-at`, снимок (`snap|`) и пути предмета; пути из текста находки — только те, что есть на
    # диске (слово с «/» и расширением, разрешённое от корня проекта): иначе отношение судилось бы к мусору из речи.
    _on_f="$1"; _on_k="$2"; _on_t="$3"; _on_d="$4"; _on_x="${5:-}"
    [ -n "$_on_f" ] && [ -n "$_on_t" ] || return 0
    if ! _RC_T="$_on_t" awk -F'|' '$1 == "seen-at" && $2 == ENVIRON["_RC_T"] { f = 1; exit } END { exit !f }' "$_on_f" 2>/dev/null; then
        rc_seen_at "$_on_f" "$_on_t" >/dev/null
        _on_s=$(_rc_snap_take "$_on_f" "$_on_d" "$_on_t")
        [ -n "$_on_s" ] && printf 'snap|%s|%s|\n' "$_on_t" "$_on_s" >> "$_on_f" 2>/dev/null
        _on_b=$(cd "$(rc_project_of "$_on_d")" 2>/dev/null && pwd -P)
        { _rc_subject_paths "$_on_t"
          printf '%s\n' "$_on_x" | grep -oE "[^[:space:]\`'\"()<>|,;]*/[^[:space:]\`'\"()<>|,;]*\.[A-Za-z0-9]+" | sed -E 's/[.,:;!?]+$//'
        } | awk 'NF && !s[$0]++' | while IFS= read -r _on_p; do
            _on_a=$(_rc_abs "$_on_p" "${_on_b:-$_on_d}")
            [ -e "$_on_a" ] && printf 'subj|%s|%s|\n' "$_on_t" "$_on_a" >> "$_on_f" 2>/dev/null
        done
    fi
    # Повод уже виден, а бэклог в его снимке «не прочитан» — снимаем заново (D1128): последняя строка пары решает.
    if _rc_need_backlog_lib; then
        _on_sid=$(_RC_T="$_on_t" awk -F'|' '$1 == "snap" && $2 == ENVIRON["_RC_T"] { print $3; exit }' "$_on_f" 2>/dev/null)
        [ -n "$_on_sid" ] && _RC_S="$_on_sid" awk -F'|' '$1 == "snapbl" && $2 == ENVIRON["_RC_S"] { v[$3] = $4 } END { for (c in v) if (v[c] == "unread") print c }' "$_on_f" 2>/dev/null \
            | while IFS= read -r _on_c; do [ -n "$_on_c" ] && _rc_snap_backlog "$_on_f" "$_on_sid" "$_on_c"; done
    fi
    grep -qxF "live|turn:${_on_k}|${_on_t}|${_on_d}|" "$_on_f" 2>/dev/null \
        || printf 'live|turn:%s|%s|%s|\n' "$_on_k" "$_on_t" "$_on_d" >> "$_on_f" 2>/dev/null
}

rc_occasion_target() {   # <журнал> <токен> <абсолютная цель> — ПЕРВАЯ цель записи при поводе; следующие не пишутся
    [ -n "${3:-}" ] || return 0
    # Свидетель зелёной стороны — учёт долга, жанр BACKLOG (D520; так его считают rework-detector и revert-signal): нога
    # `green_<ID>` идёт следом за записью пункта, и, став целью, отбивала исход по этому же пункту как «запись о другом» (D1165).
    case "$3" in */hooks/tests/test_backlog_green_side.sh) return 0 ;; esac
    _RC_T="${2:-}" awk -F'|' '$1 == "target" && $2 == ENVIRON["_RC_T"] { f = 1; exit } END { exit !f }' "$1" 2>/dev/null && return 0
    printf 'target|%s|%s|\n' "${2:-}" "$3" >> "$1" 2>/dev/null
    # Бэклог проекта ЦЕЛИ (правка в другом проекте) записывается в перечень ЭТОГО повода, если его там нет: состояние на
    # момент первой записи, и отсутствие бэклога тоже (D1115, M1). НАЗВАННЫЙ ПРЕДЕЛ: пункт, записанный в чужой проект
    # между первым взглядом и первой записью, будет сочтён прежним.
    _ot_s=$(_RC_T="${2:-}" awk -F'|' '$1 == "snap" && $2 == ENVIRON["_RC_T"] { print $3; exit }' "$1" 2>/dev/null)
    _ot_d=$(rc_project_of "$(dirname "$3")")
    if [ -n "$_ot_s" ] && [ -n "$_ot_d" ] && [ -d "$_ot_d" ] && _rc_need_backlog_lib; then
        _rc_snap_backlog "$1" "$_ot_s" "$(cd "$_ot_d" 2>/dev/null && pwd -P)/BACKLOG.md"
    fi
    return 0
}

rc_occasion_ctx() {   # <журнал> <род> [<ключ хода>] [<токен>] → `ctx|turn:K|<каталог>|<пути через ␟>|<токен@эпоха@снимок␟…>|<основа снимков>|`
    # Перечни — через ␟ (\037), а не «;»: «;» бывает в пути, и токен переработки `a;b.sh` резался на обрезки (D1127, скептик M3).
    # Ход — названный, иначе последний, где повод этого рода жив; пусто — живого повода рода нет (судится только форма).
    # Токен назван — контекст одного повода (D1116): исход судится против своей находки, а не всех находок рода в ходе.
    _RC_K="${2:-}" _RC_W="${3:-}" _RC_O="${4:-}" _RC_B="${1%.seen}" awk -F'|' '
        BEGIN { k = ENVIRON["_RC_K"]; want = ENVIRON["_RC_W"]; one = ENVIRON["_RC_O"]; base = ENVIRON["_RC_B"] }
        function kind(t,   p) { split(t, p, ":"); return p[1] }
        $1 == "seen-at" { ep[$2] = $3 }
        $1 == "snap"    { if (!($2 in sn)) sn[$2] = $3 }
        $1 == "subj"    { sp[$2] = sp[$2] (sp[$2] == "" ? "" : "\037") $3 }
        $1 == "target"  { if (!($2 in tg)) tg[$2] = $3 }
        $1 == "live" && kind($3) == k && (one == "" || $3 == one) {
            t = $2; sub(/^turn:/, "", t)
            if (want != "" && t != want) next
            if (!((t, $3) in seen)) { seen[t, $3] = 1; lt[t] = lt[t] (lt[t] == "" ? "" : "\n") $3 }
            if (!(t in cwd)) cwd[t] = $4
            last = t }
        END { t = (want != "" ? want : last); if (t == "" || lt[t] == "") exit
              n = split(lt[t], toks, "\n"); paths = ""; tk = ""
              for (i = 1; i <= n; i++) { x = toks[i]
                  if (x in tg) paths = paths (paths == "" ? "" : "\037") tg[x]
                  if (x in sp) paths = paths (paths == "" ? "" : "\037") sp[x]
                  tk = tk (tk == "" ? "" : "\037") x "@" ep[x] "@" sn[x] }
              printf "ctx|turn:%s|%s|%s|%s|%s|", t, cwd[t], paths, tk, base }' "$1" 2>/dev/null
}

# «У повода есть принятый исход» — одно правило у стража разбора и у команды исхода (D1292, корень R6). Прежде команда
# держала свою копию с окном «после якоря ТЕКУЩЕГО хода» (D1139), а страж расширил своё до якоря первого хода, где повод
# жив (D1243), и читал память зачёта: повод, закрытый в прошлом ходе, страж считал снятым, а команда — открытым, и
# «показалось» о новом поводе ложилось на закрытый (ProjectA, 10 ноября 2026).
rc_streak_token() {   # <флаг полосы `error_streak_fired_*`> → число в имени повода полосы `streak:<число>`
    # Длина серии И начало серии (D1293, корень R6): длина одна у всех полос из двух провалов, и вторая полоса сессии
    # носила имя первой — память зачёта первой снимала её отказ молча. Начало серии пишет владелец флага, error-tracker,
    # в `<флаг>.since` при заведении флага и снимает вместе с ним. Не время флага: флаг переписывается на каждой смене
    # длины, и спад той же полосы 3→2 давал новое имя и новый отказ (скептик opus H1: 45 спадов в 22 сессиях).
    # Нет `.since` (error-tracker до D1293) — имя по одной длине, постоянное, как до D1293.
    { cat "${1:-}"; printf '|'; cat "${1:-}.since"; } 2>/dev/null | cksum | awk '{print $1}'
}

rc_chain_ok_tokens() {   # <журнал стража> → поводы из памяти зачёта `chain-ok|<токен>|…|` построчно
    grep '^chain-ok|' "$1" 2>/dev/null | tr '|' '\n' | grep -v '^chain-ok$' | grep -v '^$' | sort -u
}

rc_token_outcome_line() {   # <журнал стража> <журнал исходов> <токен> <якорь текущего хода> → «исход<TAB>ref» новейшей строки `manual-`, называющей повод
    # Окно — от якоря первого хода, где повод жив (D1243, скептик opus M1): исход, принятый в конце прошлого хода без
    # следующей записи, иначе отсекался бы. Новейшая строка (D1109, L2): прежние отвергнутые не сверяются заново.
    # Строку не судит — сверку против контекста повода делает вызывающий (`rc_record_verdict`).
    _tl_cur="${4:-0}"; case "$_tl_cur" in ''|*[!0-9]*) _tl_cur=0 ;; esac
    _tl_from=$(_RC_T="${3:-}" awk -F'|' '$1 == "live" && $3 == ENVIRON["_RC_T"] { print $2; exit }' "$1" 2>/dev/null)
    [ -z "$_tl_from" ] || _tl_from=$(grep -F "outfrom|${_tl_from}|" "$1" 2>/dev/null | head -1 | cut -d'|' -f3)
    case "${_tl_from:-}" in ''|*[!0-9]*) _tl_from="$_tl_cur" ;; esac
    [ "$_tl_from" -le "$_tl_cur" ] || _tl_from="$_tl_cur"
    tail -n "+$((_tl_from + 1))" "$2" 2>/dev/null \
        | grep "\"key\":\"manual-[0-9]*\",\"signal\":\"${3%%:*}\"" \
        | jq -r --arg t "${3:-}" 'select(any((.toks // [])[]; . == $t)) | [.outcome, .ref] | @tsv' 2>/dev/null | tail -1
}

rc_token_accepted() {   # <журнал стража> <журнал исходов> <токен> <якорь текущего хода> <ключ хода> → 0 принят; 1 исхода нет; 2 не принят (причина — stdout)
    # «Исход по поводу принят» — память зачёта (`chain-ok`) либо новейшая строка `manual-` о поводе, сверенная тем же
    # правилом, что у стража (`rc_record_verdict` против контекста повода в этом ходе). Одно правило у стража, команды
    # исхода и сверщика на Stop (D1360, корень R6): сверщик знал только память зачёта, а её страж пишет по принятой строке
    # лишь на следующей записи с правом на отказ, — и между ними напоминание просило исход, который команда отбивала
    # «уже принят». Причина отказа — в форме текста отказа стража: «<исход> «<довод>»: <почему>».
    grep -qxF -- "${3:-}" <<< "$(rc_chain_ok_tokens "$1")" && return 0   # не трубой: `grep -q` под pipefail рвёт её (SIGPIPE)
    _ta_l=$(rc_token_outcome_line "$1" "$2" "${3:-}" "${4:-0}")
    [ -n "$_ta_l" ] || return 1
    IFS="$(printf '\t')" read -r _ta_o _ta_r <<< "$_ta_l"
    # Контекст не собрался — не принят, а не принят по форме (D1129): пустой контекст у сверки значит «повода нет».
    _ta_c=$(rc_occasion_ctx "$1" "${3%%:*}" "${5:-0}" "$3")
    [ -n "$_ta_c" ] || { printf '%s «%s»: контекст повода не собран — запись не сверить с поводом' "$_ta_o" "$_ta_r"; return 2; }
    _ta_w=$(rc_record_verdict "$_ta_o" "${3%%:*}" "$_ta_r" "$_ta_c") && return 0
    printf '%s «%s»: %s' "$_ta_o" "$_ta_r" "$_ta_w"; return 2
}

_rc_abs() {   # <путь> [<база>] → канонический абсолютный путь (каталог существует), иначе путь как есть
    _ra_p="$1"
    case "$_ra_p" in "~/"*) _ra_p="$HOME/${_ra_p#\~/}" ;; /*) ;; *) _ra_p="${2:-$PWD}/$_ra_p" ;; esac
    _ra_d=$(cd "$(dirname "$_ra_p")" 2>/dev/null && pwd -P) && { printf '%s/%s' "$_ra_d" "$(basename "$_ra_p")"; return 0; }
    printf '%s' "$_ra_p"
}

_rc_addr_resolve() {   # <путь:строка> <базы построчно> → абсолютный путь, если файл есть и строка в пределах
    _ar_p="${1%:*}"; _ar_n="${1##*:}"
    case "$_ar_n" in ''|*[!0-9]*) return 1 ;; esac
    [ "$_ar_n" -ge 1 ] || return 1
    while :; do
        case "$_ar_p" in
            "~/"*|/*) _ar_c=$(_rc_abs "$_ar_p")
                      [ -f "$_ar_c" ] && [ "$_ar_n" -le "$(awk 'END { print NR }' "$_ar_c" 2>/dev/null)" ] && { printf '%s' "$_ar_c"; return 0; } ;;
            *) while IFS= read -r _ar_b; do
                   [ -n "$_ar_b" ] || continue
                   _ar_c=$(_rc_abs "$_ar_p" "$_ar_b")
                   [ -f "$_ar_c" ] && [ "$_ar_n" -le "$(awk 'END { print NR }' "$_ar_c" 2>/dev/null)" ] && { printf '%s' "$_ar_c"; return 0; }
               done <<< "$2" ;;
        esac
        # Абсолютный путь с пробелом («My Project») выражение адреса режет: отбрасываем ведущие компоненты, пока
        # остаток не разрешится от базы. Голое имя файла остатком не бывает (D1110): `foo/x.sh` иначе разрешался бы
        # в чужой `x.sh` у корня проекта.
        case "$_ar_p" in */*/*) _ar_p="${_ar_p#*/}" ;; *) return 1 ;; esac
    done
}

# Адрес проявления «путь:строка» в тексте пункта (D1110): путь — любое слово без пробела, кавычек, скобок и разделителей
# перечня, а не латиница с точкой — кириллический каталог тоже путь. Мусор вроде «10:12» отсеивает разрешимость.
RC_ADDR_RE="[^[:space:]\`'\"()<>|,;]+:[0-9]+"

_rc_subject_paths() {   # <токены через ␟ (\037) с хвостами @…> → пути предмета повода построчно, по УСТРОЙСТВУ токена
    # D1110 (скептик H2): путь переработки выдёргивался выражением, срезавшим ведущий «/», а в мире все такие токены
    # абсолютные (1918 из 1918 в 30 журналах) — отношение к предмету переработки было мертво. Токен переработки —
    # `rework:<путь>:<ступень>`: путь между родом и последним двоеточием, пробелы в нём законны.
    # Перевод строки в конце обязателен: `read` на последней строке без него тело цикла не исполняет.
    printf '%s\n' "${1:-}" | tr '\037' '\n' | sed -E 's/(@[0-9A-Za-z]*)+$//' | while IFS= read -r _sp_t; do
        [ -n "$_sp_t" ] || continue
        case "$_sp_t" in
            rework:*) _sp_p="${_sp_t#rework:}"; printf '%s\n' "${_sp_p%:*}" ;;
            *) printf '%s\n' "${_sp_t#*:}" | grep -oE '(~?/)?([A-Za-z0-9_.~-]+/)*[A-Za-z0-9_.-]+\.[A-Za-z0-9]+' ;;
        esac
    done
}

_rc_text_names_path() {   # <текст> <путь от корня проекта> → 0, если путь назван в тексте ЦЕЛЫМ словом
    # Подстрока засчитывала `subhooks/x.sh` за `hooks/x.sh` (скептик D1106, M1); слово — от пробела до пробела, без
    # хвоста адреса «:N» и знаков препинания.
    # НАЗВАННЫЙ ПРЕДЕЛ (скептик D1108, L4): новый файл с пробелом в пути от корня проекта (`hooks/new file.sh`) целым
    # словом не назвать — отношение к такой цели держит только адрес существующего файла.
    # Здесь-строка, а не труба в `grep -q`: под pipefail ранний выход рвал бы трубу `sed`, и совпадение читалось бы
    # кодом 141 как «нет» (страж `test_assert_no_sigpipe`).
    _tn_w=$(printf '%s\n' "${1:-}" | grep -oE "[^[:space:]\`'\"()<>|,;]+" | sed -E 's/(:[0-9]+([-,][0-9]+)*)?[.,:;!?]*$//')
    grep -qxF -- "${2:-}" <<< "$_tn_w"
}

_rc_trim_tail() { awk '{ l[NR] = $0 } END { n = NR; while (n > 0 && l[n] ~ /^[[:space:]]*$/) n--; for (i = 1; i <= n; i++) print l[i] }'; }

_rc_block_fresh_snap() {   # <бэклог> <ID> <текст блока сейчас> <основа снимков> <id снимка> → 0 свеж; 1 прежний; 2 снимка нет; 3 не прочитан; 4 в архиве, в снимке бэклога нет
    # Свеж — блока не было в бэклоге на момент повода (или бэклога не было вовсе) либо он с тех пор изменился (D1108,
    # D1115). Пункт, найденный в АРХИВЕ, сверяется с бэклогом снимка: был там и не менялся — прежний (1), дописка его
    # освежит; не был вовсе (4) — дописка свежим его не сделает никогда, у отказа другой совет (D1213). Код 4 покрывает
    # два состояния: пункт лежал в архиве уже тогда либо записан после повода и унесён в архив до сверки — состава архива
    # снимок не несёт, и различить их нечем (D1255, скептик opus по 3ec8907a, M1); текст отказа называет наблюдаемое.
    [ -n "${5:-}" ] || return 2
    _bs_c="$(cd "$(dirname "$1")" 2>/dev/null && pwd -P)/BACKLOG.md"
    _bs_v=$(_RC_S="$5" _RC_C="$_bs_c" awk -F'|' '$1 == "snapbl" && $2 == ENVIRON["_RC_S"] && $3 == ENVIRON["_RC_C"] { v = $4 } END { print v }' "${4}.seen" 2>/dev/null)
    case "$_bs_v" in
        '') return 2 ;;
        unread) return 3 ;;
        absent) _bs_then="" ;;
        *) # Выборка блока берёт только обычный файл (`backlog_item_block`, `-f`) — снимок раскрывается во временный.
           _bs_t=$(mktemp "${TMPDIR:-/tmp}/rc-snapbl.XXXXXX") || return 2
           _rc_snap_read "$4" "$_bs_v" > "$_bs_t" || { rm -f "$_bs_t"; return 2; }
           _bs_then=$(backlog_item_block "$_bs_t" "$2" | tail -n +2 | _rc_trim_tail); rm -f "$_bs_t" ;;
    esac
    if [ -z "$_bs_then" ]; then
        # Состав архива на момент повода (D1255): номер там был — пункт прежний, где бы он ни лежал сейчас (4); не было —
        # свежий, и перенос архиватором исход не отзывает. Снимок без строки архива (до D1255) — как прежде.
        _bs_a=$(_RC_S="$5" _RC_C="$_bs_c" awk -F'|' '$1 == "snaparch" && $2 == ENVIRON["_RC_S"] && $3 == ENVIRON["_RC_C"] { v = $4 } END { print v }' "${4}.seen" 2>/dev/null)
        case "$_bs_a" in
            absent) return 0 ;;
            '') ;;
            *) if _bs_x=$(_rc_snap_read "$4" "$_bs_a"); then
                   _rc_has_line "$_bs_x" "$2"
                   case $? in 0) return 4 ;; 1) return 0 ;; *) return 2 ;; esac
               fi ;;
        esac
        case "$1" in */BACKLOG.md) return 0 ;; esac
        return 4
    fi
    [ "$_bs_then" != "$(printf '%s\n' "$3" | _rc_trim_tail)" ]
}

# Причина непринятого исхода — ПЕРВАЯ найденная (D1109, скептик M6): каталоги идут от проекта отказа к ClaudSoul, и
# одноимённый пункт ClaudSoul (номера проектов почти все есть и там) затирал причину пункта проекта.
_rv_fail() { [ -n "${_rv_bad:-}" ] || _rv_bad="$1"; }

# rc_record_verdict <исход> <род> <текст исхода> [<строка ctx|…| от rc_occasion_ctx>] — 0, если исход указывает на запись разбора,
# сверенную с миром; иначе 1 и причина в stdout. Без строки отказа судится форма (корень из карты, разрешимый адрес),
# свежесть и отношение — только против отказа: снимать без отказа нечего, а страж при правке сверяет заново.
rc_record_verdict() {
    _rv_out="${1:-}"; _rv_kind="${2:-}"; _rv_why="${3:-}"; _rv_ctx="${4:-}"
    [ "$_rv_out" = disproved ] && return 0
    command -v rc_project_of >/dev/null 2>&1 && rc_project_of "$PWD" >/dev/null 2>&1   # грузит paths-lib
    _rc_need_backlog_lib || { echo "нет backlog-lib.sh — запись не сверить"; return 1; }
    _rv_cwd=""; _rv_paths=""; _rv_toks=""; _rv_ep=""; _rv_sn=""; _rv_sb=""
    if [ -n "$_rv_ctx" ]; then
        # Поле 4 — пути отношения (первые цели записи и пути предмета) через «;», абсолютные (`rc_occasion_ctx`).
        _rv_cwd=$(printf '%s' "$_rv_ctx" | cut -d'|' -f3); _rv_paths=$(printf '%s' "$_rv_ctx" | cut -d'|' -f4 | tr '\037' '\n' | awk 'NF && !s[$0]++')
        _rv_toks=$(printf '%s' "$_rv_ctx" | cut -d'|' -f5); _rv_sb=$(printf '%s' "$_rv_ctx" | cut -d'|' -f6)
        # Повод рода с самым ранним первым взглядом: его эпоха и его снимок (D1108). Токен — «<род:предмет>@<эпоха>@<снимок>».
        read -r _rv_ep _rv_sn < <(printf '%s\n' "$_rv_toks" | tr '\037' '\n' | awk -v k="$_rv_kind" '
            NF { n = split($0, a, "@"); s = a[n]; e = a[n - 1]; split($0, p, ":")
                 if (e !~ /^[0-9]+$/) next
                 if (ae == "" || e + 0 < ae + 0) { ae = e; as = s }
                 if (p[1] == k && (me == "" || e + 0 < me + 0)) { me = e; ms = s } }
            END { if (me != "") print me, ms; else print ae, as }')
    fi
    if [ "$_rv_out" = knowledge ]; then
        _rv_ld="${LESSONS_DIR:-$HOME/.claude/global-lessons}"; _rv_bad=""
        for _rv_n in $(printf '%s' "$_rv_why" | grep -oE '(case|pattern|principle)-[A-Za-z0-9_-]+'); do
            for _rv_f in "$_rv_ld/$_rv_n.md" "$_rv_ld/_drafts/$_rv_n.md"; do
                [ -f "$_rv_f" ] || continue
                [ -z "$_rv_ep" ] && return 0
                # Исход «знание» — НОВАЯ запись (D1108, решение владельца 26 октября 2026): её имени не было в снимке на
                # момент повода. Время файла не годится — его двигают счётчики подтверждений (49 файлов за 2 дня).
                _rv_lv=$(_RC_S="$_rv_sn" awk -F'|' '$1 == "snaples" && $2 == ENVIRON["_RC_S"] { print $3; exit }' "${_rv_sb}.seen" 2>/dev/null)
                [ -n "$_rv_sn" ] && [ -n "$_rv_lv" ] && [ "$_rv_lv" != unread ] && _rv_lx=$(_rc_snap_read "$_rv_sb" "$_rv_lv") || { _rv_fail "снимка базы знаний на момент повода нет — свежесть знания $_rv_n не сверить"; continue; }
                _rc_has_line "$_rv_lx" "$_rv_n"
                case $? in
                    1) return 0 ;;
                    2) _rv_fail "снимок базы знаний на момент повода не сверить — свежесть знания $_rv_n не установлена"; continue ;;
                esac
                _rv_fail "знание $_rv_n было в базе до того, как страж увидел повод: исход «знание» — новая запись этого разбора (/learn)"
            done
        done
        echo "${_rv_bad:-исход «knowledge» называет существующую запись базы знаний (case-/pattern-/principle-…) — её нет}"
        return 1
    fi
    # Номер — без хвостовой пунктуации («записано в D9912.», D1110).
    _rv_ids=$(printf '%s' "$_rv_why" | grep -oE "$BACKLOG_ID_TOKEN_RE" | sed -E 's/[.-]+$//' | sort -u)
    [ -n "$_rv_ids" ] || { echo "исход «${_rv_out}» называет пункт долга D<N> с корнем из карты и адресом проявления — номера в тексте нет"; return 1; }
    _rv_cs="${CLAUDSOUL_ROOT:-}"
    _rv_tabs=$(while IFS= read -r _rv_p; do [ -n "$_rv_p" ] && _rc_abs "$_rv_p" "${_rv_cwd:-$PWD}" && echo; done <<< "$_rv_paths")
    # Каталоги поиска: проект отказа, проекты путей отношения (правка в другом проекте, D1110), проект вызова, ClaudSoul.
    _rv_dirs=$(printf '%s\n' "$( [ -n "$_rv_cwd" ] && rc_project_of "$_rv_cwd")" \
        "$(while IFS= read -r _rv_p; do [ -n "$_rv_p" ] && rc_project_of "$(dirname "$_rv_p")" && echo; done <<< "$_rv_tabs")" \
        "$(rc_project_of "$PWD")" "$_rv_cs" | awk 'NF && !s[$0]++')
    # Номера — только те, что есть в бэклогах поиска (D1110, скептик L2): каждое слово вида x86/utf8 иначе стоило полного
    # разбора бэклога и архива в каждом каталоге.
    _rv_known=$(while IFS= read -r _rv_d; do
        [ -n "$_rv_d" ] || continue
        for _rv_f in "$_rv_d/BACKLOG.md" "$_rv_d/BACKLOG-archive.md"; do [ -f "$_rv_f" ] && backlog_ids "$_rv_f" 2>/dev/null; done
    done <<< "$_rv_dirs" | sort -u)
    _rv_cand="$_rv_ids"
    _rv_ids=$(printf '%s\n' "$_rv_ids" | grep -xF -f <(printf '%s\n' "$_rv_known") 2>/dev/null)
    [ -n "$_rv_ids" ] || { echo "пункт $(printf '%s' "$_rv_cand" | paste -sd, -) не найден ни в бэклоге проекта, ни в бэклоге ClaudSoul"; return 1; }
    # Базы разрешения адреса: каталог бэклога, проекты отказа, цели и вызова, ClaudSoul.
    _rv_bases="$_rv_dirs"
    # Цели отношения: цель отказанной правки и пути предмета повода — по устройству токена (`_rc_subject_paths`).
    _rv_tg="$_rv_tabs"
    # Корень проекта — каноническим путём, как и цель (`_rc_abs`): иначе `/var/…` не вычитается из `/private/var/…`.
    _rv_tbase=$( [ -n "$_rv_cwd" ] && cd "$(rc_project_of "$_rv_cwd")" 2>/dev/null && pwd -P)
    while IFS= read -r _rv_sp; do
        [ -n "$_rv_sp" ] || continue
        _rv_tg="${_rv_tg}${_rv_tg:+
}$(_rc_abs "$_rv_sp" "${_rv_tbase:-${_rv_cwd:-$PWD}}")"
    done < <(_rc_subject_paths "$_rv_toks")
    _rv_bad=""; _rv_seen=""
    for _rv_id in $_rv_ids; do
        while IFS= read -r _rv_d; do
            [ -n "$_rv_d" ] || continue
            for _rv_f in "$_rv_d/BACKLOG.md" "$_rv_d/BACKLOG-archive.md"; do
                _rv_blk=$(backlog_item_block "$_rv_f" "$_rv_id") || continue
                _rv_seen="$_rv_id"
                _rv_s=$(printf '%s\n' "$_rv_blk" | head -1 | cut -f1); _rv_e=$(printf '%s\n' "$_rv_blk" | head -1 | cut -f2)
                _rv_txt=$(printf '%s\n' "$_rv_blk" | tail -n +2)
                _rv_root=$(printf '%s\n' "$_rv_txt" | backlog_root_of)
                case "$_rv_root" in
                    "не дефект") ;;
                    R[0-9]*)
                        _rv_r=$(printf '%s' "$_rv_root" | grep -oE '^R[0-9]+')
                        _rv_map="$_rv_d/ROOTS.md"; [ -f "$_rv_map" ] || _rv_map="$_rv_cs/ROOTS.md"
                        [ -f "$_rv_cs/scripts/root-map.py" ] || { _rv_fail "нет прибора карты корней (${_rv_cs:-?}/scripts/root-map.py) — корень пункта $_rv_id не сверить"; continue; }
                        ROOTS_MAP="$_rv_map" python3 "$_rv_cs/scripts/root-map.py" --has "$_rv_r" >/dev/null 2>&1; _rv_rc=$?
                        if [ "$_rv_rc" -eq 1 ]; then _rv_fail "у пункта $_rv_id корень $_rv_r, а в карте ($_rv_map) такой карточки нет"; continue; fi
                        if [ "$_rv_rc" -ne 0 ]; then _rv_fail "карта корней ($_rv_map) не читается — корень пункта $_rv_id не сверить"; continue; fi ;;
                    "") _rv_fail "у пункта $_rv_id нет строки «**Корень.**» (R<N> из карты либо «не дефект»)"; continue ;;
                    *) _rv_fail "у пункта $_rv_id корень «${_rv_root} …» — это не корень: R<N> из карты либо «не дефект»"; continue ;;
                esac
                _rv_res=""
                while IFS= read -r _rv_a; do
                    [ -n "$_rv_a" ] || continue
                    _rv_c=$(_rc_addr_resolve "$_rv_a" "$(printf '%s\n%s\n' "$_rv_d" "$_rv_bases")") && _rv_res="${_rv_res}${_rv_res:+
}${_rv_c}"
                done < <(printf '%s\n' "$_rv_txt" | grep -oE "$RC_ADDR_RE" | awk '!s[$0]++')
                [ -n "$_rv_res" ] || { _rv_fail "у пункта $_rv_id нет адреса проявления «путь:строка», который разрешается (файл есть, строка в пределах)"; continue; }
                if [ -n "$_rv_ep" ]; then
                    _rc_block_fresh_snap "$_rv_f" "$_rv_id" "$_rv_txt" "$_rv_sb" "$_rv_sn"; _rv_fr=$?
                    [ "$_rv_fr" -eq 2 ] && { _rv_fail "снимка бэклога на момент повода нет — свежесть пункта $_rv_id не сверить"; continue; }
                    [ "$_rv_fr" -eq 3 ] && { _rv_fail "бэклог $(dirname "$_rv_f")/BACKLOG.md не прочитан, когда страж увидел повод, — свежесть пункта $_rv_id не сверить"; continue; }
                    [ "$_rv_fr" -eq 4 ] && case "$_rv_f" in */BACKLOG.md) ;; *) false ;; esac && { _rv_fail "пункт $_rv_id лежал в архиве уже на момент повода и возвращён в BACKLOG.md — это прежний пункт; повод снимет новый пункт (со ссылкой на $_rv_id) либо новая запись знания"; continue; }
                    [ "$_rv_fr" -eq 4 ] && { _rv_fail "пункт $_rv_id найден в архиве, а в снимке бэклога на момент повода его не было, — дописка в архивный блок свежим его не сделает; повод снимет новый пункт (со ссылкой на $_rv_id) либо новая запись знания"; continue; }
                    [ "$_rv_fr" -eq 0 ] || {
                        _rv_fail "пункт $_rv_id записан до того, как страж увидел повод, — это запись не этого разбора; допиши в него проявление этого повода либо заведи новый"; continue; }
                    if [ -n "$_rv_tg" ]; then
                        _rv_rel=0
                        while IFS= read -r _rv_t; do
                            [ -n "$_rv_t" ] || continue
                            grep -qxF -- "$_rv_t" <<< "$_rv_res" && { _rv_rel=1; break; }
                            # Цель, которой ещё нет на диске (новый файл), узнаётся по пути от корня проекта, названному в
                            # тексте пункта целым словом; у существующей цели совпадать обязан адрес (D1110, скептик M1).
                            if [ ! -e "$_rv_t" ]; then
                                _rv_tr="${_rv_t#"${_rv_tbase:-/nonexistent}"/}"
                                [ "$_rv_tr" != "$_rv_t" ] && _rc_text_names_path "$_rv_txt" "$_rv_tr" && { _rv_rel=1; break; }
                            fi
                        done <<< "$_rv_tg"
                        [ "$_rv_rel" -eq 1 ] || { _rv_fail "адреса пункта $_rv_id не совпадают ни с первой целью записи, ни с предметом повода ($(printf "%s" "$_rv_tabs" | paste -sd, - | sed "s|^$|—|")) — это запись о другом"; continue; }
                    fi
                fi
                return 0
            done
        done <<< "$_rv_dirs"
    done
    [ -n "$_rv_seen" ] || _rv_bad="пункт $(printf '%s' "$_rv_ids" | paste -sd, -) не найден ни в бэклоге проекта, ни в бэклоге ClaudSoul"
    echo "$_rv_bad"
    return 1
}
