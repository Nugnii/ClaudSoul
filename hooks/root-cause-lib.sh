# rc_is_outcome_carrier <путь> — код 0, если запись по этому пути ЕСТЬ называние исхода.
#
# Правило сопоставления живёт ЗДЕСЬ, рядом с перечнем, а не у потребителя (10 сентября 2026,
# находка противника). Гейт применял выражение к пути ЦЕЛИКОМ голым `grep -qE`, и
# освобождение от отказа доставалось всякому пути, где шаблон встретился ПОДСТРОКОЙ:
#   ~/.claude/plans/../../hooks/five-whys-gate.sh   — восхождение уводит в дерево механизмов
#   hooks/SESSION.md.bak.sh                         — «SESSION.md» внутри имени
#   hooks/global-lessons/state-lock-lib.sh          — «global-lessons/» не тем компонентом
#   hooks/BACKLOGGER.md.sh                          — «BACKLOG…md» внутри имени
# Последствие ОДНО и оно тяжёлое: правка механизма при неразобранном поводе проходит мимо
# отказа уровня 4. Соседнее освобождение (`hooks/lib/write-target-lib.sh:56`) восхождение
# отбивает явно и комментарием описывает ровно этот сценарий — правка туда не дошла.
#
# Различаются ДВА рода носителей, и путать их нельзя:
#   · файл  (`BACKLOG*.md`, `SESSION.md`) — совпадает БАЗОВОЕ ИМЯ целиком;
#   · каталог (`global-lessons`, `.claude/plans`) — совпадает КОМПОНЕНТ пути целиком.
# Восхождение `..` снимает освобождение всегда: нормализовать путь без обращения к файловой
# системе нельзя, а обращаться в хуке ради этого не стоит (тот же довод, что у соседа).
rc_is_outcome_carrier() {
    _rc_p="${1:-}"
    [ -n "$_rc_p" ] || return 1
    case "$_rc_p" in
        */../*|*/..|../*|..) return 1 ;;
    esac
    _rc_base="${_rc_p##*/}"
    # Файловые носители: базовое имя целиком.
    case "$_rc_base" in
        SESSION.md) return 0 ;;
        BACKLOG.md|BACKLOG-*.md) return 0 ;;
    esac
    # Каталожные носители: компонент пути целиком И НА СВОЁМ МЕСТЕ. Голое `*/global-lessons/*`
    # засчитывало `hooks/global-lessons/state-lock-lib.sh` — подкаталог внутри дерева
    # механизмов, а не базу знаний (вторая половина той же находки). База живёт под
    # `.claude/`, план — под `.claude/plans/`; `LESSONS_DIR` уважается, если объявлена.
    case "/$_rc_p/" in
        */.claude/global-lessons/*) return 0 ;;
        */.claude/plans/*)          return 0 ;;
    esac
    if [ -n "${LESSONS_DIR:-}" ]; then
        case "$_rc_p" in
            "$LESSONS_DIR"/*) return 0 ;;
        esac
    fi
    return 1
}

RC_OUT_KNOWLEDGE_RE='global-lessons/'
RC_OUT_DEBT_RE='BACKLOG[A-Za-z-]*\.md'
# Граница слева — «не буква пути», а не «слэш или начало строки»: в команде Bash путь стоит
# после пробела (`sed -i … hooks/x.sh`), и якорь по слэшу видел бы только абсолютные пути
# файловых инструментов — та самая слепота к способу работы, ради которой команда и читается.
RC_OUT_MECH_RE='(^|[^A-Za-z0-9_.-])(hooks|scripts|mcp-server|lib|bin)/[^ "]*\.(sh|py|js|ts)'
# Третий носитель того же признака записи, что `redirect_bare` в `command-scope-lib.sh`.
# Функцию сюда не позвать — признак живёт внутри программы jq, — поэтому вынесены не строки,
# а два условия, и оба сформулированы отрицанием, а не перечнем:
#   · «>» не перенаправляет, если рядом стоит «=» или «-» — это оператор чужого языка
#     (>=, >>=, ->, =>). Замер 10 сентября 2026: из 3374 команд, признанных записью, 112
#     (3,3%) держались единственно на этом. Oniguruma в jq умеет lookbehind, проверено;
#   · `mv`/`cp` — имя КОМАНДЫ, а не подстрока: без границы слева сюда попадали `grep "cp .*lib"`
#     и всякий путь, где эти две буквы стоят внутри слова.
# НАЗВАННЫЙ ПРЕДЕЛ: кавычки здесь не снимаются (в отличие от `redirect_bare`) — признак
# читает сырую команду, поэтому запись, поминаемая внутри строки-аргумента, всё ещё считается
# правкой мира. Замер критика: 89 таких из 861 осмотров, из них 5 без единой формы записи
# вне кавычек. Условие снятия: разбор области команды переедет в jq либо учёт исхода станет
# звать shell-функцию до входа в jq.
RC_OUT_WRITE_RE='((?<![-=])>>?(?!=)[ ]*[^ |&]|sed -i|[ ]tee[ ]|^tee[ ]|git[ ]+commit|(^|[ |;&(])(mv|cp)[ ])'
rc_outcome_observed() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 1
    _rc_kinds=$(jq -rs \
        --arg kn "$RC_OUT_KNOWLEDGE_RE" --arg db "$RC_OUT_DEBT_RE" \
        --arg mc "$RC_OUT_MECH_RE" --arg wr "$RC_OUT_WRITE_RE" '
        def role(x): x.message.role // x.role // "";
        def blocks(x): (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then $c else [] end;
        def get_text(x): (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then ($c | map(select(.type == "text") | .text) | join("\n"))
            elif ($c | type) == "string" then $c else "" end;
        . as $items | (length) as $n |
        ([range(0; $n) | ($n - 1 - .)
          | select(role($items[.]) == "user" and ((($items[.]).isMeta // false) | not) and ((get_text($items[.]) // "") | length > 0))]
          | first) as $pu |
        (if $pu == null then 0 else $pu + 1 end) as $from |
        [range($from; $n) | $items[.]] as $seg |
        # тексты, которые АГЕНТ произнёс в этом ходе — только для вердикта «показалось»
        ([$seg[] | select(role(.) == "assistant") | get_text(.)] | join("\n")) as $txt |
        # цели правки: file_path у файловых инструментов, команда у Bash при форме записи
        ([$seg[] | select(role(.) == "assistant") | blocks(.)[]
          | select(.type == "tool_use")
          | if (.input.file_path // "") != "" then .input.file_path
            elif ((.input.command // "") | test($wr)) then (.input.command // "")
            else empty end] | join("\n")) as $tgt |
        [ (if ($tgt | test($kn)) then "запись знания" else empty end),
          (if ($tgt | test($db)) then "пункт долга" else empty end),
          (if ($tgt | test($mc)) then "починка механизма" else empty end),
          (if ($txt | test("показалось"; "i")) then "вердикт «показалось»" else empty end) ]
        | join(" · ")
    ' "$_rc_t" 2>/dev/null)
    [ -n "${_rc_kinds:-}" ] || return 1
    printf '%s' "$_rc_kinds"
}

# rc_turn_text <transcript> — весь текст агента ПОСЛЕ последней реплики собеседника.
# Разбор из прошлого хода к нынешнему повтору не относится — потому граница та же, что у
# rc_turn_key. Единственный экстрактор текста хода: rc_why_count и rc_trace берут его отсюда.
rc_turn_text() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    jq -rs '
        def role(x): x.message.role // x.role // "";
        def get_text(x):
            (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then
                ($c | map(select(.type == "text") | .text) | join("\n"))
            elif ($c | type) == "string" then $c
            else "" end;
        . as $items | (length) as $n |
        ([range(0; $n) | ($n - 1 - .)
          | select(role($items[.]) == "user" and ((($items[.]).isMeta // false) | not) and
                   ((get_text($items[.]) // "") | length > 0))]
          | first) as $pu |
        if $pu == null then
            ([range(0; $n) | $items[.] | select(role(.) == "assistant")]
             | map(get_text(.)) | map(select(. != "")) | join("\n"))
        else
            ([range($pu + 1; $n) | $items[.] | select(role(.) == "assistant")]
             | map(get_text(.)) | map(select(. != "")) | join("\n"))
        end
    ' "$_rc_t" 2>/dev/null
}

