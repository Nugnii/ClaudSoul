# rc_is_record_target <путь> — код 0, если запись по этому пути НЕ правит механизм: расширение из
# RC_RECORD_EXT; базовое имя не SKILL.md / CLAUDE.md / AGENTS.md (документы, ведущие поведение);
# компонента пути не rules / skills / templates (правила, скиллы, шаблоны — тоже поведение);
# восхождения `..` нет (довод тот же, что у соседа выше). Повод: с 4 октября 2026 гейт отбил 25
# правок документов файловым инструментом, из них 5 — память проекта; роль «правит ли механизм»
# решалась формой «есть ли запись» (корень R3).
rc_is_record_target() {
    _rc_p="${1:-}"
    [ -n "$_rc_p" ] || return 1
    case "$_rc_p" in */../*|*/..|../*|..) return 1 ;; esac
    _rc_base="${_rc_p##*/}"
    case "$_rc_base" in SKILL.md|CLAUDE.md|CLAUDE.local.md|AGENTS.md) return 1 ;; esac
    case "/$_rc_p/" in */rules/*|*/skills/*|*/templates/*) return 1 ;; esac
    # Каталог настроек `.claude/` (D1329): записью там считается только то, что лежит в носителях записей, — всё
    # прочее ведёт поведение (commands, agents, скиллы в месте установки и каталоги, которых ещё нет). Перечень
    # положительный, как у расширений: ошибается в сторону отказа. Судится хвост после ПЕРВОГО `.claude/`.
    # Замер по 25 878 целям правок 400 расшифровок: ответ меняется у 3 (agents/lean.md и дважды skills-catalog.md).
    case "/$_rc_p" in */.claude/*)
        _rc_tail="/$_rc_p"; _rc_tail="${_rc_tail#*/.claude/}"
        case "$_rc_tail" in global-lessons/*|plans/*|projects/*|hooks/state/*) ;; *) return 1 ;; esac ;;
    esac
    _rc_ext="${_rc_base##*.}"
    [ "$_rc_ext" != "$_rc_base" ] || return 1
    # Строка-вход, а не труба: `printf | grep -q` под pipefail отвечает 141 при раннем выходе
    # читателя (сметчик hooks/tests/test_assert_no_sigpipe.sh).
    grep -qxE "$RC_RECORD_EXT" <<< "$_rc_ext"
}

