#!/usr/bin/env bash
# root-cause-lib.sh — ЕДИНСТВЕННОЕ определение общих вычислений контура разбора причин.
#
# ПРЕФИКСЫ: rc_
# Объявление пространства имён (11 сентября 2026, D390). Функция этой библиотеки
# носит один из названных префиксов; имя с ведущим `_` считается внутренним и под
# правило не подпадает. Сверяет `hooks/lib-prefix-guard.sh` при записи файла.
# Список собран ИЗ ФАКТА, а не придуман: он фиксирует нынешнее состояние, чтобы
# разнобой не рос дальше — из 21 библиотеки с 3+ функциями лишь 10 держали 80%+
# имён под одним префиксом, а объявления не было ни у одной из 29.
#
# Результат: ключ хода, последний блок речи и счёт «почему» вычисляются в одном месте;
#            копий этих формул в хуках ноль
# Проверка результата: bash hooks/tests/test_root_cause_lib.sh даёт 0
#
# Зачем. До 29 августа 2026 формула ключа хода (cksum последней реплики собеседника)
# существовала ДВУМЯ копиями: five-whys-gate.sh писал ею журнал срабатываний, а
# declared-problem-recorded.sh читал тот журнал своей копией той же формулы. Комментарий
# в читателе называл это прямо: «расходятся молча — и связь порвётся без единого
# падения». Класс уже отказывал в этом проекте: 28 августа три стража бэклога сутки
# молчали, потому что каждый держал СВОЮ копию признака пункта (повод backlog-lib.sh).
# Библиотека строится по тому же образцу: одно определение, потребители источают.
#
# КОНТРПРИМЕР: сигнальные блоки гейта (какие файлы состояния слушать) сюда не выносятся
# этой правкой — у них своя граница выноса (порядок KINDS несёт семантику дедупа),
# см. план модуля root-cause.
#
# Контракт функций: чистые вычисления, мир не меняют; на нечитаемом/пустом входе печатают
# пусто (или 0 у счётчиков) и возвращают 0 — деградация без падения. jq обязателен у
# ВЫЗЫВАЮЩЕГО: хук без jq выходит раньше, чем дойдёт сюда.
# Источать можно многократно (идемпотентно).

# Общий замок и правка под ним (род H): журнал поводов разбора общий на сессию.
STATE_LOCK_LIB="${STATE_LOCK_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/state-lock-lib.sh}"
[ -f "$STATE_LOCK_LIB" ] || STATE_LOCK_LIB="$HOME/.claude/hooks/state-lock-lib.sh"
# shellcheck source=/dev/null
if [ -f "$STATE_LOCK_LIB" ]; then . "$STATE_LOCK_LIB"; fi
# rc_turn_key <transcript> — метка хода: cksum последней непустой реплики собеседника.
# Ею гейт подписывает журнал срабатываний, ею же сверщик находит срабатывания этого хода.
rc_turn_key() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    jq -rs '
        def role(x): x.message.role // x.role // "";
        def get_text(x):
            (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then ($c | map(select(.type == "text") | .text) | join(" "))
            elif ($c | type) == "string" then $c else "" end;
        [ .[] | select(role(.) == "user" and ((.isMeta // false) | not)) | get_text(.) | select(. != "") ] | last // ""
    ' "$_rc_t" 2>/dev/null | cksum 2>/dev/null | awk '{print $1}'
}

# rc_last_block <transcript> — последний блок речи агента после последней реплики
# собеседника. Признак находки читается по нему, а не по всему окну хода: слово находки,
# однажды сказанное, оставалось бы в окне до конца хода, и все последующие находки
# сливались бы с первой (диагноз 28 августа 2026, индексы 1055/1159).
rc_last_block() {
    _rc_t="${1:-}"
    [ -n "$_rc_t" ] && [ -f "$_rc_t" ] || return 0
    jq -rs '
        def role(x): x.message.role // x.role // "";
        def get_text(x):
            (x.message.content // x.content // []) as $c |
            if ($c | type) == "array" then ($c | map(select(.type == "text") | .text) | join("\n"))
            elif ($c | type) == "string" then $c else "" end;
        . as $items | (length) as $n |
        ([range(0; $n) | ($n - 1 - .)
          | select(role($items[.]) == "user" and ((($items[.]).isMeta // false) | not) and ((get_text($items[.]) // "") | length > 0))]
          | first) as $pu |
        ([range((if $pu == null then 0 else $pu + 1 end); $n) | $items[.]
          | select(role(.) == "assistant") | get_text(.) | select(. != "")] | last // "")
    ' "$_rc_t" 2>/dev/null
}

# RC_KINDS_RE — все СРОДЫ поводов, которые гейт пишет в журнал `five-whys-<SID>.seen`.
# До 29 августа 2026 след разбора проверялся ровно у одного срода — `discovery:`. В живых
# журналах при этом: daily 126, repeat 59, discovery 36, correction 6, streak 4 — то есть у
# 195 срабатываний из 231 исход не проверял никто, и «заметил и ничего не сделал» было
# неотличимо от «сделал». Перечень сродов держится здесь, а не в потребителе: продюсер и
# потребитель уже расходились молча на ключе хода.
#
# 9 сентября 2026 сюда добавлен `notfollowed:` — девятый срод. Гейт заводил его с 6 сентября
# (`five-whys-gate.sh:259`), а перечень-владелец не знал: следствие механическое и измеренное —
# 0 записей исхода из 1035, срод был невидим и сверщику (`declared-problem-recorded.sh:76`),
# и своду незакрытого (`hooks/lib/open-findings-lib.sh:67`). Это тот самый род, ради которого
# перечень и держится в одном месте: писатель объявил ключ, читатель о нём не узнал.
#
# 13 сентября 2026 добавлен `self_repeat:` — одиннадцатый срод (D325, корень R2): агент сам
# называет повтор («это пятый раз за день», «второй раз подряд», «тот же класс»), и до этого
# дня фраза не запускала ничего — среди поводов её не было, слово о повторе служило
# завершением темы. Словарь маркера — RC_SELF_REPEAT_RE ниже; им же меряет реплей
# `scripts/self-repeat-replay.py`, чтобы у формы был один владелец.
# `daily:` снят 13 сентября 2026 (D358): суточный повтор знания ушёл из гейта в очередь отложенных
# уведомлений, писателя срода в дереве нет, а перечень без писателя — мёртвая запись
# (test_kinds_writer_reader_parity). Записи `daily:` в журналах до этой даты читателями перечня
# не различаются намеренно: их предмет — сутки, а не ход, и в доли по ходам они не входят.
RC_KINDS_RE="${RC_KINDS_RE:-rework:|correction:|question:|streak:|repeat:|notfollowed:|discovery:|event:|breakage:|self_repeat:}"

# RC_SELF_REPEAT_RE — маркер повтора в СОБСТВЕННОЙ речи агента. Формы взяты из замера 6 сентября
# 2026 по расшифровке живой сессии (блоков речи 350, с маркером 20, настоящих 15): счёт повторов
# «N-й раз», «второй/третий раз (подряд)», «тот же класс», «того же дня». Точность сырого признака
# 15 из 20 = 75% — четверть ложных («подтверждение» о счётчике знания, «за сессию» о материале),
# поэтому срод СТОЯЧИЙ: напоминает, отказа не даёт. Текст подаётся в нижнем регистре (to_lower).
# У СЛОВАРЯ ДВА ДВИЖКА: grep -E в гейте и Python `re` в реплее. Форма обязана быть верна в обоих:
# кириллический диапазон `[а-я]` отвергает GNU grep в C.UTF-8 («Invalid collation character»,
# CI 05a7965), POSIX-класс `[[:space:]]` не знает Python (читает как набор букв). Отсюда `[^ ]*`.
RC_SELF_REPEAT_RE="${RC_SELF_REPEAT_RE:-[0-9]+-?(й|ой|ий|ый) раз|(втор|трет|четвёрт|четверт|пят|шест|седьм|восьм|девят|десят)[^ ]* раз|раз подряд|тот же класс|того же класса|того же дня}"

# rc_signals_of_turn <журнал> <ключ хода> — сроды поводов, сработавших в ЭТОМ ходе,
# по одному в строке (без двоеточия). Пусто — поводов в ходе не было.
rc_signals_of_turn() {
    _rc_j="${1:-}"; _rc_k="${2:-}"
    [ -n "$_rc_j" ] && [ -f "$_rc_j" ] && [ -n "$_rc_k" ] || return 0
    grep "^turn:${_rc_k}|" "$_rc_j" 2>/dev/null \
        | grep -oE "$RC_KINDS_RE" 2>/dev/null \
        | sed 's/:$//' | sort -u
}

