#!/usr/bin/env bash
# mechanism-has-consumer.sh — PreToolUse[Bash] на `git commit`: механизм, которого никто не зовёт, называется ДО фиксации.
# en: PreToolUse[Bash] on `git commit`: names a mechanism nobody invokes, before it is committed.
#
# Результат: файл в scripts/, у которого нет ни исполнителя в коде, ни строки в реестре замеров, не уезжает в коммит молча
# Проверка результата: bash hooks/tests/test_mechanism_has_consumer.sh даёт 0
#
# МЕХАНИЗИРУЕТ ТЕКСТОВОЕ ПРАВИЛО. «Инструмент без результата — не инструмент» существовало
# только текстом и не держало: 10 сентября 2026 написан `scripts/root-map.py` с зелёным
# тестом и коммитом — и не подключён ни к чему; поймал собеседник вопросом «карту то ты
# построил, а механизм к проверке подключил?».
#
# ЦЕНА ТЕКСТОВОГО УРОВНЯ ИЗМЕРЕНА, а не предположена: разряд «знание было уместно и не
# применено» — 38 случаев; замер 28 августа 2026 — минимум в девяти случаях из девятнадцати
# знание было в контексте В МОМЕНТ ДЕЙСТВИЯ и всё равно не применилось.
#
# ДРОБЬ на 10 сентября 2026: скриптов 65, без исполнителя в коде 14, из них 9 подключены
# реестром замеров (законно) — остаётся 5 без потребителя вовсе:
# ab-authorization-replay.sh, doc-figures.sh, five-whys-attribution-replay.py,
# reader-field-sweep.py, smoke-test.sh. Это 5 из 65 (7,7%).
#
# ПОЧЕМУ ГОВОРИТ, А НЕ ОТКАЗЫВАЕТ. У признака НЕ одно последствие: пять живых носителей
# показывают, что «нет исполнителя» бывает законным — CLI для владельца, разовый реплей.
# Уровень 4 ставится только там, где последствие одно, поэтому здесь уровень 3: сказать и
# дать назвать исход. Условие подъёма: появится способ отличить «CLI для владельца» от
# «забыл подключить» — например, объявленная в шапке роль.
#
# ПОТРЕБИТЕЛЬ — ИСПОЛНЕНИЕ, А НЕ УПОМИНАНИЕ. Первая редакция признака считала потребителем
# любое совпадение имени и дала 0 из 65: имя прибора встречалось в комментариях его же
# проб. Признак снят с РОЛИ строки (исполняется ли), а не с факта совпадения.
#
# Input  (stdin): {tool_name, tool_input, cwd} (PreToolUse JSON)
# Output (stdout): {hookSpecificOutput.additionalContext} либо пусто
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
INPUT=$(cat 2>/dev/null || true)
[ -n "$INPUT" ] || exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
[ "$TOOL" = "Bash" ] || exit 0
CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
grep -qE '(^|[;&|[:space:]])git[[:space:]]+([^|;&]*[[:space:]])?commit([[:space:]]|$)' <<< "$CMD" || exit 0

CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
[ -n "$CWD" ] || CWD="$PWD"
ROOT=$(git -C "$CWD" rev-parse --show-toplevel 2>/dev/null) || exit 0
[ -n "$ROOT" ] || exit 0

# Только НОВЫЕ механизмы: правка существующего потребителя не меняет.
NEW=$(git -C "$ROOT" diff --cached --name-only --diff-filter=A 2>/dev/null \
      | grep -E '^scripts/[^/]+\.(sh|py)$' || true)
[ -n "$NEW" ] || exit 0

REGISTRY="$ROOT/scripts/measurements.tsv"
ORPHANS=""
while IFS= read -r path; do
    [ -n "$path" ] || continue
    name="${path##*/}"
    esc=$(printf '%s' "$name" | sed 's/\./\\./g')
    # Исполнитель: имя после интерпретатора в СТРОКЕ КОДА (не в комментарии) любого файла
    # дерева, кроме самого себя. Ответ берётся у подстановки, а не у кода возврата: `grep`
    # при нуле находок отдаёт 1, и код возврата тут ничего не означает (D371).
    # Граница слева — «не буква пути»: без неё `status.sh` находился внутри `ci-status.sh`,
    # и сирота молчала (находка противника 10 сентября 2026). Тот же приём, что у
    # `RC_OUT_MECH_RE` в root-cause-lib.
    # ТЕСТ — НЕ ПОТРЕБИТЕЛЬ (10 сентября 2026, находка противника). Область включала
    # `hooks/tests/`, потому что каталог лежит внутри `hooks`, и всякая проба засчитывалась
    # исполнителем. Последствие названо самим противником: `scripts/root-map.py` —
    # мотивирующий случай ЭТОГО стража («написан с зелёным тестом и не подключён ни к
    # чему») — имеет `hooks/tests/test_root_map.sh`, и страж не поймал бы того, ради чего
    # написан. Тест проверяет прибор, а не потребляет его результат: «инструмент без
    # результата» остаётся без результата, даже если проба зелена.
    # Проверено перед правкой: оба прибора с одними пробами (`root-map.py`,
    # `docs-concepts-check.sh`) стоят в реестре замеров, то есть настоящий потребитель у них
    # есть и ложной сиротой никто не станет.
    # Заодно отменяется вчерашняя правка `test_docs_concepts.sh`, где вызов был переписан на
    # `bash "$CHK"` ради видимости стражу: она лечила симптом — признак, а не область.
    hits=$(git -C "$ROOT" grep -n -I -E "(bash|sh|python3|python)[[:space:]]+[^|;]*(^|[^A-Za-z0-9_.-])${esc}" \
             -- hooks scripts install.sh ':!hooks/tests' 2>/dev/null \
           | grep -v "^${path}:" | grep -vE '^[^:]+:[0-9]+:[[:space:]]*#' | head -1 || true)
    [ -n "$hits" ] && continue
    # Реестр замеров — законный потребитель: прибор зовётся по сроку, а не из кода.
    # В реестре — тоже целое имя: `grep -qF "status.sh"` находил его внутри `ci-status.sh`,
    # который в живом реестре стоит, и новый прибор с общим хвостом молча числился покрытым.
    [ -f "$REGISTRY" ] && grep -qE "(^|[^A-Za-z0-9_.-])${esc}([^A-Za-z0-9_.-]|$)" "$REGISTRY" 2>/dev/null && continue
    ORPHANS="${ORPHANS}${ORPHANS:+, }${path}"
done <<< "$NEW"

[ -n "$ORPHANS" ] || exit 0

MSG="🔌 Механизм без потребителя: ${ORPHANS}

Файл уезжает в коммит, и его никто не зовёт: ни строкой кода, ни реестром замеров
(scripts/measurements.tsv). «Инструмент без результата — не инструмент»: замер без
изменения и находка без починки суть трата.

Исполнимо без разрешения — назови потребителя ОДНИМ из трёх:
  · строка в scripts/measurements.tsv (id, период, команда, что меряет) — если прибор идёт по сроку;
  · вызов из хука или скрипта — если он часть чужого хода;
  · шапка файла говорит, что это CLI владельца — тогда потребитель человек, скажи это вслух.

Дробь на 10 сентября 2026: 5 приборов из 65 живут без потребителя (7,7%)."

jq -cn --arg m "$MSG" '{hookSpecificOutput:{hookEventName:"PreToolUse", additionalContext:$m}}' 2>/dev/null || true
exit 0
