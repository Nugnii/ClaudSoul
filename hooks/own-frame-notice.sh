#!/usr/bin/env bash
# own-frame-notice.sh — PreToolUse[Bash]: своя рамка замера строится молча, и подсказка спрашивает про владельца факта.
# en: PreToolUse on Bash — building an ad-hoc measurement script prompts for the instrument that already records the fact.
#
# Результат: строя свой замер, автор видит вопрос «какой прибор уже пишет этот факт»
#            ДО того, как рамка построена, а не после того, как она соврала
# Проверка результата: bash hooks/tests/test_own_frame_notice.sh даёт 0
#
# Правило живёт в .claude/rules/claudsoul-hooks.md, § «Замер начинается с вопроса „кто уже это записал"»;
# здесь его механическая половина. До 21 сентября 2026 правило держалось ТОЛЬКО текстом,
# и замер того дня показал, чего это стоит: за одну сессию своя рамка строилась трижды при
# живых приборах с тем же предметом.
# · рамка `measure.sh` написана при живом `scripts/behavior-condition-probe.sh` — и
#   повторила его же дефект: код 0 не отличён от честного SKIP, девять свидетелей оболганы;
# · осмотр уплывших адресов начат при живом `scripts/docs-address-drift.py`, чья шапка
#   (:222-230) УЖЕ называла этот самый случай намеренно историческим;
# · контроль работы судил пустоту stdout, тогда как режим `--contrast` того же прибора
#   показывает оба канала рядом — нога покраснела на живом дереве.
# В тот же день запись `pattern-owner-of-the-fact-was-not-asked` закрыта исходом
# `applicable_not_followed`: знание висело в контексте и не было применено ДВАЖДЫ.
#
# ПОЧЕМУ ПОДСКАЗКА, А НЕ ОТКАЗ. У признака «строится свой скрипт» последствий два: прибора
# может не быть вовсе, и тогда своя рамка — единственная дорога (так был добыт `agent_id`
# 17 сентября 2026, когда в следах его не писал никто). Уровень 4 ставится на признак с
# одним последствием; здесь его нет, и отказ отверг бы законную работу.
#
# ПРИЗНАК УЗОК, И ЭТО ИЗМЕРЕНО владельцем корпуса (`scripts/signal-precision-corpus.py`,
# 21 сентября 2026): вызовов Bash.command 40582, совпадений 34 — 0,08%. Подсказка звучит
# втрое реже раза на сессию, поэтому дросселя по составу не заводится: хватает дедупа хода.
#
# НАЗВАННЫЙ ПРЕДЕЛ: судится ФОРМА команды (heredoc в файл `.sh` внутри scratchpad), а не
# намерение. Свой скрипт, собранный иначе — `printf` построчно, `python3 - <<PY`, правка
# через Write, — признаком не ловится. Условие снятия: замер покажет, какая доля своих
# рамок строится не этой формой; если больше трети, признак расширяется по тому же замеру.
set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0
PAYLOAD=$(cat 2>/dev/null || true)
[ -n "$PAYLOAD" ] || exit 0

TOOL=$(printf '%s' "$PAYLOAD" | jq -r '.tool_name // empty' 2>/dev/null) || exit 0
[ "$TOOL" = "Bash" ] || exit 0
CMD=$(printf '%s' "$PAYLOAD" | jq -r '.tool_input.command // empty' 2>/dev/null) || exit 0
[ -n "$CMD" ] || exit 0

# Признак: heredoc, пишущий скрипт оболочки во временный каталог сессии.
# HERE-STRING, А НЕ ТРУБА: под `pipefail` `grep -q` выходит на первом совпадении, producer
# получает SIGPIPE, статус конвейера 141 — и УСПЕШНОЕ совпадение читается как провал, то есть
# хук молчит именно тогда, когда обязан говорить. Приём был перенесён из образца
# `agent-model-notice.sh`, где та же форма верна, потому что там нет этой проверки под
# pipefail: форма скопирована, условие её верности — нет. Поймано своим же сторожем
# `hooks/tests/test_assert_no_sigpipe.sh` в час написания хука; в дереве это место было одно.
grep -qE 'cat >[^|]*scratchpad[^ ]*\.sh[[:space:]]*<<' <<< "$CMD" || exit 0

# ДЕДУП ПО ПРЕДМЕТУ, А НЕ ПО СЕССИИ (поправка владельца 21 сентября 2026: «в ход может быть
# несколько разборов»). Первая редакция глушила подсказку на всю сессию — и вторая рамка,
# построенная в том же ходу про ДРУГОЙ предмет, проходила молча, хотя вопрос о владельце
# факта у неё свой. Ключ — ИМЯ строящейся рамки: правки одной и той же молчат, новая рамка
# спрашивает заново, сколько бы разборов ни шло в ходу.
STATE_DIR="${STATE_DIR:-$HOME/.claude/hooks/state}"
SID=$(printf '%s' "$PAYLOAD" | jq -r '.session_id // empty' 2>/dev/null)
SID=${SID:-${CLAUDE_CODE_SESSION_ID:-unknown}}
# Имя рамки берётся из той же формы, что подняла признак; пусто — ключом служит вся команда.
FRAME=$(printf '%s' "$CMD" | grep -oE 'scratchpad[^ ]*\.sh' | head -1)
FRAME_KEY=$(printf '%s' "${FRAME:-$CMD}" | cksum 2>/dev/null | awk '{print $1}')
MARK="$STATE_DIR/own-frame-notice-${SID}-${FRAME_KEY:-0}"
[ -e "$MARK" ] && exit 0
mkdir -p "$STATE_DIR" 2>/dev/null && : > "$MARK" 2>/dev/null || true

jq -cn --arg m "🔎 Строится СВОЯ рамка замера. Прежде чем судить по ней: назови прибор, который уже пишет этот факт (состояние в hooks/state, журналы, имена и ключи дедупа, scripts/*.py|sh), и прочитай ответ у него. Прибора нет — так и скажи, и рамка законна. Прибор есть — перенеси в неё ЕГО различения: они накоплены на прошлых ошибках, и своя рамка их не наследует (21 сентября 2026: код 0 не отличён от честного SKIP — девять свидетелей оболганы зря)." \
  '{hookSpecificOutput:{hookEventName:"PreToolUse",additionalContext:$m}}'
exit 0
