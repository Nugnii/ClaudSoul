# Сессионная ветка зовёт ТУ ЖЕ функцию, что и ветка хода. До 11 сентября 2026 здесь лежала
# её дословная копия — и несла тот же дефект D396, который иначе чинился бы вторым заходом.
# Добавлен ЖУРНАЛ ИСХОДОВ: запись в общий носитель (бэклог ClaudSoul из чужого проекта, база
# знаний) видна ДЕЙСТВИЯМИ хода, а ходов в сессии много, и действия прошлых из нынешней
