}

# ── Журнал ИСХОДОВ, а не срабатываний (D112) ──────────────────────────────────
# Исход определяется наблюдаемо: изменился носитель после начала хода — значит повод
# чем-то кончился; не изменился — `none`. Декларация агента исходом не
# считается: «сказано» и «сохранено» в тексте ответа выглядят одинаково, и именно на этом
# различии стоит весь хук. Вердикт «показалось» пишется отдельной командой
# `scripts/outcome.sh` — он единственный, который наблюдением не отличить от бездействия.
# ДВА НАБЛЮДЕНИЯ — ДВА ЗНАЧЕНИЯ (D1107, решение владельца 26 октября 2026, корень R6). Носитель тронут или механизм
# правлен — `touched`; исход хода сверен с записью разбора тем же правилом, что у стража (`rc_record_verdict`), —
# `recorded`. До этого оба писались словом `recorded`, и замер долей не отличал сверенный исход от строки «- ☐ D1 что-то».
# Напоминание и гашение событий ведут себя как прежде: им достаточно `touched` (починка механизма — исход, D323).
turn_outcome_verified() {   # <род> → 0, если в ходе назван исход этого рода, прошедший сверку
    command -v rc_record_verdict >/dev/null 2>&1 || return 1
    _tv_j="$STATE/outcome-${SID}.jsonl"
    [ -f "$_tv_j" ] || return 1
    # Контекст — повод этого рода, живой в ЭТОМ ходе (D1109): первые взгляды, первая цель записи, пути предмета.
    _tv_ctx=$(rc_occasion_ctx "$JOURNAL" "$1" "$TURN_KEY")
    # Судятся строки ПОСЛЕ последнего отказа пары (D1126): отказ другого повода того же вида, пришедший после сверенного
    # исхода первого, иначе закрывался бы чужой строкой исхода.
    _tv_after=$(grep -n "\"key\":\"${TURN_KEY}\",\"signal\":\"$1\"" "$_tv_j" 2>/dev/null | grep '"outcome":"deferred"' | tail -n 1 | cut -d: -f1)
    case "${_tv_after:-}" in ''|*[!0-9]*) _tv_after=0 ;; esac
    while IFS="$(printf '\t')" read -r _tv_o _tv_r; do
        [ -n "$_tv_o" ] || continue
        ( cd "${CWD:-$PWD}" 2>/dev/null; rc_record_verdict "$_tv_o" "$1" "$_tv_r" "$_tv_ctx" ) >/dev/null 2>&1 && return 0
    done < <(jq -r --argjson s "$TURN_START" --arg g "$1" '
        select(((.key // "") | tostring | startswith("manual-")) and .signal == $g
               and (((.ts // "") | try fromdateiso8601 catch 0) >= $s)) | [.outcome, (.ref // "")] | @tsv' < <(tail -n "+$((_tv_after + 1))" "$_tv_j") 2>/dev/null)
    # Снятие отказа стражем в этом ходе — исход, уже сверенный тем же правилом; судится ПОСЛЕДНИЙ исход пары (D1126).
    jq -se --arg k "$TURN_KEY" --arg g "$1" '[.[] | select((.key | tostring) == $k and .signal == $g)] | (last // {}) | .outcome == "recorded"' "$_tv_j" >/dev/null 2>&1
}
if [ "$TURN_FINDS" -gt 0 ] && [ "$TURN_START" -gt 0 ] && [ -n "${TURN_KEY:-}" ]; then
    if turn_outcome_seen "$TURN_START"; then _TURN_OUTCOME="touched"; else _TURN_OUTCOME="none"; fi
    # След разбора (D211) пишется вместе с исходом: по нему замер считает долю поводов, где
    # разбор оставил проверяемые формы, а не только долю с записанным исходом.
    _TRACE=$(rc_trace "$TRANSCRIPT")
    # Предмет пишется рядом с исходом: без него запись говорит, ЧТО повод был, и не
    # говорит, КАКОЙ — вернуться к нему нечем. Для находки предмет есть только в речи хода
    # (итог из поля входа, без поля — `rc_last_block`), для остальных родов — в строке журнала гейта, где стоит имя знания
    # или деталь события.
    # Из строк хода без закрытых поводов (D1357, L2 скептика): закрытый повод предметом строки исхода не становится.
    _DPR_LINE=$(tail -n 1 <<< "${_TURN_LINES:-}")
    for _sig in ${TURN_SIGNALS:-}; do
        case "$_sig" in
            discovery|self_repeat) _DPR_SUBJ=$(printf '%s\n' "$_DPR_LAST" | tr '\n' ' ') ;;
            *)         _DPR_SUBJ="$_DPR_LINE" ;;
        esac
        _sig_out="$_TURN_OUTCOME"
        # Последний исход пары — отказ (D1126): «носитель тронут» засчитывается, только если он менялся ПОСЛЕ отказа, —
        # правка до него была работой по другому поводу того же вида, и отказ остаётся открытым (none поверх него не ложится).
        _dts=$(grep "\"key\":\"${TURN_KEY}\",\"signal\":\"${_sig}\"" "$STATE/outcome-${SID}.jsonl" 2>/dev/null | tail -n 1 \
            | jq -r 'select(.outcome == "deferred") | .ts | fromdateiso8601' 2>/dev/null)
        case "${_dts:-}" in ''|*[!0-9]*) _dts=0 ;; esac
        if [ "$_sig_out" = touched ] && [ "$_dts" -gt "$TURN_START" ]; then carrier_touched_after "$_dts" || _sig_out="none"; fi
        turn_outcome_verified "$_sig" && _sig_out="recorded"
        rc_log_outcome "$STATE" "$SID" "$TURN_KEY" "$_sig" "$_sig_out" "$_DPR_SUBJ" "$_TRACE"
    done
    # Внешние поводы (красный прогон, откат, воскресший пункт, сбой проверки дрейфа)
    # гасятся, когда исход записан: иначе событие висело бы открытым вечно и стало бы
    # фоном — гейт называл бы его поводом в каждом ходе до конца времён. Гасим на
    # `touched` (до D1107 — то же наблюдение под словом `recorded`): «ничего не сделано» повод не закрывает.
    if [ "$_TURN_OUTCOME" = "touched" ] && command -v rc_close_events >/dev/null 2>&1; then
        # Проект сессии, а не каталог процесса: гасится то, что этому проекту и
        # показывали. Прежде гасились события всех проектов разом.
        rc_close_events "$STATE" "$(rc_project_of "${CWD:-$PWD}")"
    fi
fi
# Исход срода, закрытого в ЭТОМ ходе сверенной строкой `manual-` (D1360): строка хода закрытых поводов в ветку выше не
# идёт, а `recorded` за сверенный исход хода пишет только этот хук. Закрытый в прошлом ходе строки не получает (как
# `chain-ok`, D1357); закрытый стражем в этом ходе — уже `recorded` у стража, повтор `rc_log_outcome` отбросит.
if [ -n "${TURN_SIGNALS_SHUT:-}" ] && [ "$TURN_START" -gt 0 ] && [ -n "${TURN_KEY:-}" ]; then
    for _sig in $TURN_SIGNALS_SHUT; do
        turn_outcome_verified "$_sig" || continue
        case "$_sig" in
            discovery|self_repeat) _DPR_SUBJ=$(printf '%s\n' "$_DPR_LAST" | tr '\n' ' ') ;;
            *)         _DPR_SUBJ=$(grep -F "|${_sig}:" <<< "${_TURN_RAW:-}" | tail -n 1) ;;
        esac
        rc_log_outcome "$STATE" "$SID" "$TURN_KEY" "$_sig" recorded "$_DPR_SUBJ" "$(rc_trace "$TRANSCRIPT")"
    done
fi

if [ "$TURN_FINDS" -gt 0 ] && [ "$TURN_START" -gt 0 ] && ! turn_outcome_seen "$TURN_START"; then
    _WHAT_FIRED="${TURN_SIGNALS:-повод разбора}"
    MSG_TURN="📌 В ЭТОМ ходе сработал гейт разбора ($TURN_FINDS раз; поводы: ${_WHAT_FIRED% }), а исхода не видно: бэклог проекта не менялся, и в действиях хода нет ни записи в носитель, ни починки механизма.

Разбор — не исход. Исход это состояние мира, и он называется из закрытого списка:
$(rc_resolution_kinds).

Решением считается и МЕХАНИЗМ, не дающий проблеме возникнуть: тогда у пункта названы
измеримый результат и команда проверки. «Жду слова» без названного плана исходом не
является: закроется вкладка — не останется ничего.
Признал повод ложным — так и запиши: bash scripts/outcome.sh disproved <сигнал> \"<чем опровергнуто>\""
    # Ключ дросселя — состав повода: сроды хода и их число, а не текст сообщения.
    dpr_surface "turn:${_WHAT_FIRED% }:${TURN_FINDS}" "$MSG_TURN"
    exit 0
fi

START=""
for f in "$STATE"/*"$SID"*; do
    [ -e "$f" ] || continue
    m=$(mtime_of "$f")
