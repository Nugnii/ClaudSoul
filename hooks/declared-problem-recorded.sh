#
# НАЗВАННЫЙ ПРЕДЕЛ: правка, сделанная субагентом, в след хода не попадает — его действия
# лежат в отдельной расшифровке. Для бэклога проекта дыру закрывает mtime, для общих
# носителей — нет: там запись субагента даст ложное напоминание.
# Условие снятия: расшифровки субагентов станут читаться вместе с расшифровкой хода.
