if [ -z "$LOCAL_BACKLOG" ] && [ -n "$CWD" ] && command -v find_project_root >/dev/null 2>&1; then
    _root=$(find_project_root "$CWD")
    [ -n "$_root" ] && [ -f "$_root/BACKLOG.md" ] && LOCAL_BACKLOG="$_root/BACKLOG.md"
fi

# dpr_surface <ключ дросселя> <текст> — доставить сообщение так, чтобы его прочитал ХОД.
#
# Повод, измеренный внутри системы (`hooks/error-tracker.sh:44-47`): «15 срабатываний
# прежней версии ушли в один только `systemMessage`, и ни на одно из них ход не
# отреагировал — записи `hook_system_message` в поток сообщений не попадают». То есть
# страж, чей единственный выход `systemMessage`, СРАБАТЫВАЕТ, но не ДЕЙСТВУЕТ; в
# VSCode-расширении этот канал вдобавок не рендерится и равен молчанию.
#
# Прямой `additionalContext` здесь незаконен: непустой контекст на Stop перезапускает ход.
# Канал — файл напоминаний своей сессии `stop-signals-<sid>.txt` и рядом `stop-signals-<sid>.project`
# с корнем проекта. Показывает их `pending-alerts-surface.sh`: свой — на следующей реплике той же
# сессии, чужой — сессии того же проекта, когда своя уже не жива (вкладку закрыли, /clear). Дроссель
# по СОСТАВУ (сроды хода и число), а не по телу: «поводов стало 4 вместо 3» звучать не должно,
# «появился срод, которого не было» — обязано. Образец — `carrier-growth-check.sh:106-119`.
# Прежние каналы и почему ушли. Общая очередь `pending-alerts.txt` (до D1044) опустошается репликой
# ЛЮБОЙ сессии: скептик D1041 застал напоминание о своём итоге у чужой, параллельной сессии.
# `startup-signals-<sid>.txt` (D1044) обнуляется стартом той же сессии — compact стирал напоминание,
# а закрытая вкладка не отдавала его никому (скептик D1044, D1047): один файл нёс сигналы старта и
# напоминание хода, у которых разная жизнь (корень R6).
dpr_surface() {
    _dpr_key="${1:-}"; _dpr_msg="${2:-}"
    [ -n "$_dpr_msg" ] || return 0
    # systemMessage СНЯТ 12 сентября 2026. Здесь стояло «остаётся: владельцу в терминале он
    # виден, и это не мешает очереди» — мешало: в мобильном клиенте канал рендерится
    # ПОСТРОЧНО, и текст в четыре абзаца превращался в дюжину строк на экране владельца.
    # Сообщение адресовано агенту и целиком уходит в очередь ниже.
    for _dpr_thr in "$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd)/throttle-lib.sh" \
                    "$HOME/.claude/hooks/throttle-lib.sh"; do
        # shellcheck source=/dev/null
        [ -f "$_dpr_thr" ] && { . "$_dpr_thr"; break; }
    done
    if command -v throttle_file >/dev/null 2>&1; then
        _dpr_tf=$(throttle_file "$STATE" declared-problem "${SID:-unknown}")
        throttle_seen "$_dpr_tf" "$_dpr_key" && return 0
        throttle_mark "$_dpr_tf" "$_dpr_key"
    fi
    # Владелец записи в канал своей сессии — `session_alert` (`paths-lib.sh`, D1304); прежде здесь стояла своя копия.
    if command -v session_alert >/dev/null 2>&1; then
        session_alert "$STATE" "${SID:-}" "${CWD:-}" "$_dpr_msg"
    else
        printf '%s\n' "$_dpr_msg" >> "$STATE/stop-signals-${SID}.txt" 2>/dev/null || true
    fi
}

# ── НАХОДКА ИТОГА БЕЗ ИСХОДА (D1041; договор пометки — D1046, 24 октября 2026) ────────────
# Поправка владельца дословно: «меня смущает, когда ты пишешь «что найдено». Иногда создаётся
# впечатление, что это требует исправления, но ты это забудешь, потому что не записал в
# бэклог, а я точно забуду». Ветки ниже судят повод из журнала гейта и «бэклог менялся после
# начала хода» — в ходе, где бэклог правили по ЛЮБОМУ поводу, они отвечают «записано», а
# находка итога остаётся без судьбы (корень R6). Здесь предмет — сам пункт раздела «Что
# найдено» итогового текста хода (поле входа Stop `last_assistant_message`, без поля — rc_last_block, D1210).
# ДОГОВОР ПОМЕТКИ (решение владельца 24 октября 2026, D1046). У каждой находки раздела стоит
# пометка исхода `→ <исход>` из закрытого списка: `→ D<N>` / `→ B<N>` (пункт долга; B — бэклог
# соседнего проекта, хук глобальный) · `→ починено <коммит>` · `→ держит <механизм>` · `→ не
# требует: <почему>` · `→ вопрос задан` · `→ знание <имя>`. Сверщик ищет только пометку. Две
# прежние редакции (D1041, D1044) угадывали исход по словам прозы — «Исправил», «записано»,
# «починю», «содержит», — и каждый из трёх кругов финального скептика находил новые формы в обе
# стороны (корень R3: роль решается перечнем форм). Пометка снимает угадывание, а писать её
# напоминает этот же хук.
# Раздел — форма итога из правил. Заголовок — строка, которая начинается (после `#`, `**`, `*`,
# `_`; после маркера списка — только с разметкой) словами «Что найдено» / «Что нашлось» / «Что
# обнаружено» / «Что я нашёл» / «Находки» / «Находка» с любым уточнением, с заглавной буквы; без
# разметки после маркера — итог списком частей («- Что найдено: …», «- Находка: …», «- Что найдено — …»)
# без отступа и вне открытого раздела. Текст ПОСЛЕ заголовка (`**Что найдено:** текст`, `Что найдено:
# текст`) — сам пункт, а текст без точки в конце при пунктах глубже заголовка — вводная; уточнение внутри
# жирного — нет. Пункт — строка списка (`-`, `*`, `+`, `•`, `–`, `N.`, `N)`) с продолжением либо абзац вне
# списка; пункт глубже первого пункта раздела и абзац после пункта — его продолжение. Вводная строка на «:»
# пунктом не считается. Раздел кончается заголовком того же или старшего уровня, подзаголовком с названием
# другой части итога целиком, меткой другой части в начале строки (название целиком с хвостом формы итога из
# закрытого списка; жирная — на уровне пунктов раздела, и с текстом на той же строке; простым текстом — только
# в итоге списком частей; абзацы «Что дальше:» и «Что ждёт <хвост>:» — везде), жирной строкой целиком вне
# `#`-раздела или строкой 🕐; таблица, цитата и блок кода раздел не закрывают и не судятся.
# НАЗВАННЫЕ ПРЕДЕЛЫ. (1) Пометка — форма: `→ D1046`, поставленный не к той находке, сойдёт за
# исход; так же стрелка в прозе («D1041 → D1044 сломал», «A -> держит B, а хук X молчит»). Стрелка принимается
# и ASCII `->` (с номером — только в конце строки пункта, D1056, D1059). Двузначные
# формы оставлены (D1051): «Проверки:» простым текстом раздела не закрывает — вводная строка на «:»
# выглядит так же; хвост «**Что найдено**, коротко» и строка `*Канал*` читаются пунктами. (2) Таблица в разделе не судится. (3) Абзац, закрывающий итог после последнего пункта,
# читается продолжением пункта. (4) Строка вне итога, начатая словами «Что найдено», откроет
# раздел. (6) Формы финального скептика D1051 (D1056), оставленные: «Нового нет. <пояснение>» называется
# находкой — по договору пометки пояснение и есть содержание; жирная строка-метка под жирным заголовком
# закрывает раздел; абзац между пунктами читается продолжением предыдущего; «—» маркером списка не считается.
# (7) Формы финального скептика D1059 (D1062), оставленные: значок перед меткой («🔜 **Что дальше:**») метки не
# делает, и пункты той части называются находками — правило значка в awk macOS съедало и кириллическое слово
# («Раздел **Что дальше** устарел»), теряя находку; хвост метки вне закрытого списка («**Что ждёт вас сегодня:**»)
# читается находкой; итог «- Находка: …» называет находками и следующие пункты прозы («- Причина: …»); вводная
# с точкой в конце («- Что найдено: три дефекта.») называется находкой.
# (5) Без поля входа (событие не Stop или поле пусто) итог с оборванной последней строкой расшифровки не
# читается вовсе — так устроен общий `rc_last_block`; на Stop итог берётся из поля (D1210). Условие снятия (5) —
# дочитывание расшифровки в `rc_turn_digest`.
dpr_orphan_findings() {   # <текст итога> → первые строки пунктов без исхода, по одной на строку
    printf '%s\n' "${1:-}" | awk -v nb="$(printf '\302\240')" '
        function close_item(   n, w, k, h) {
            if (item == "") return
            # Варианты написания перечислены, а не сведены tolower: tolower на кириллице есть не во
            # всех awk, а не-ASCII внутри класса `[…]` читается диапазоном БАЙТОВ.
            # «Находок нет» — ответ, а не находка, только целиком: без вложенных пунктов и без единого слова после
            # («Ничего нового, кроме одного: …», «Ничего нового. Но хук X падает» — находки; D1048, D1056).
            # ASCII `->` с номером — только в конце СТРОКИ пункта (`imark`, D1059): «A1 -> B12 считает неверно» —
            # проза (D1056), а `-> D1057 (средняя)`, `-> D1058, D1059` и пометка перед вложенным пунктом — исход.
            if (imark || item ~ arrow || item ~ /→[[:space:]]*([DB][0-9]+|(Пункт|пункт)[^ ]* [^ ]+|(Починено|починено)( в| коммитом)?[: (]+[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]|(Держит|держит) [^ ]+|(Не|не) требует[^ ]* +[^ ]+|(Вопрос|вопрос) задан|(Знание|знание) [^ ]+)/ ||
                item ~ /->[[:space:]]*((Починено|починено)( в| коммитом)?[: (]+[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]|(Держит|держит) [^ ]+|(Не|не) требует[^ ]* +[^ ]+|(Вопрос|вопрос) задан|(Знание|знание) [^ ]+)/ ||
                (!sub_items && item ~ ("^[[:space:]]*(" nothing ")[.!]?[[:space:]]*$"))) {
                item = ""; head = ""; imark = 0; return
            }
            # Пункт, начатый ответом «ничего нового» и продолженный, назван по продолжению (D1059): строка
            # «ничего нового.» не говорит, какая находка осталась без судьбы.
            if (head ~ ("^[[:space:]]*(" nothing ")[.!]?[[:space:]]*$")) {
                h = item; sub("^[[:space:]]*(" nothing ")[.!]?[[:space:]]*", "", h)
                sub("^" lm "[[:space:]]+", "", h)
                if (h != "") head = h
            }
            # Первая строка пункта, около 400 знаков, целыми словами. Не substr: в байтовом awk он режет
            # посреди буквы, а в многобайтном (локаль UTF-8) обрезок валит следующую регулярку —
            # «towc: multibyte conversion failure» на 52 итогах корпуса D1044.
            if (length(head) > 400) {
                n = split(head, w, / /); head = w[1]
                for (k = 2; k <= n && length(head) + length(w[k]) < 400; k++) head = head " " w[k]
                if (k <= n) head = head " …"
            }
            print head
            item = ""; head = ""; imark = 0
        }
        # Части итога, кроме «Что найдено» (форма итога — правила): их метка закрывает раздел. Метка — название
        # части ЦЕЛИКОМ с хвостом формы итога из закрытого списка (« вас», « тебя», « владельца», « вашего решения»
        # у «ждёт»; « и что нет», «, а что нет», « за сессию» у «изменилось» и прочих) и знаком конца (`:`, `.`, `?`,
        # `!`, ` —`): «**Что ждёт вас:**», «**Что дальше?**», «**Что изменилось.**» — метки; «**Что осталось сломанным:**»,
        # «**Что идёт не так:**», «**Что ждёт исправления:**», «### Что дальше ломается» — находки (D1056, D1059, D1062).
        BEGIN { parts = "(Что|ЧТО) (ждёт|ждет)( вас| тебя| владельца| вашего решения)?|(Что|ЧТО) (дальше|ДАЛЬШЕ|не менялось|не изменилось)|(Что|ЧТО) (изменилось|сделано|идёт|осталось)( и что нет|, а что нет| за сессию)?|Дальше|ДАЛЬШЕ"
                pend = "[[:space:]]*(—|[.:?!])?[[:space:]]*"
                mk = "(\\*\\*|__)"
                blabel = "(" mk "(" parts ")" pend mk "|" mk "(" parts ")" mk "[.:])"
                lm = "((-|[*+]|•|–)|[0-9]+[.)])"
                plabel = "(" parts ")(:|" pend "$)"
                nothing = "(Пока |пока )?(Ничего|ничего) (нового|не найдено|не нашлось|существенного)|(Нового нет|нового нет)|(Нет|нет)"
                arrow = "->[[:space:]]*((Пункт|пункт)[^ ]* )?[DB][0-9]+([,;][[:space:]]*[DB][0-9]+)*([[:space:]]*\\([^)]*\\))?[).,;]*[[:space:]]*$" }
        # Пометка `->` с номером в конце ПЕРВОЙ строки пункта действует, пока к пункту прибавляются только вложенные
        # пункты (`- Хук X молчит -> D1056` и подробность ниже); строка-продолжение прозой её снимает
        # («D1041 -> D1044⏎  хук X перестал …» — проза), и тогда судится конец пункта целиком (D1062).
        function open_item(text, k) { close_item(); item = text; head = text; kind = k; sub_items = 0; imark = (text ~ arrow) }
        function indent_of(s) { match(s, /^[[:space:]]*/); return RLENGTH }
        { sub(/\r$/, ""); gsub(nb, " ") }
        /^[[:space:]]*(```|~~~)/ {
            fm = ($0 ~ /^[[:space:]]*```/) ? "b" : "t"
            if (!infence) { infence = 1; fmark = fm } else if (fm == fmark) infence = 0
            next
        }
        infence { next }
        # Маркеры списка — чередованием, а не классом: `•` и `–` внутри `[…]` байтовый awk (локаль C,
        # mawk раннера CI) читает набором байтов, и пункт `• x` не узнаётся (D1048).
        # Пункт списка — заголовок только с разметкой (`- **Что найдено:**`, `- ## …`): «- Находка в хуке X»
        # и «1. Находки скептика разобрать» — пункты (в корпусе 948 итогов голых заголовков-пунктов 0 из 2); без разметки
        # заголовок — только итог списком частей: «- Что найдено: текст», «- Находка: …», «- Что найдено — …» (D1056,
        # D1059), без отступа и только вне открытого раздела (`lsec`): вложенное «- Находки: …» в другой части итога и
        # «- Находки: …» внутри раздела «Что найдено» раздела не открывают.
        /^[[:space:]]*((#+[[:space:]]*)?(\*\*\*|\*\*|__|\*|_)?|((-|[*+]|•|–)|[0-9]+[.)])[[:space:]]+(#+[[:space:]]*(\*\*\*|\*\*|__|\*|_)?|\*\*\*|\*\*|__|\*|_))[[:space:]]*((Что|ЧТО) (найдено|нашлось|обнаружено|я нашёл|я нашел|НАЙДЕНО|НАШЛОСЬ)|Находки|Находка|НАХОДКИ)/ ||
        (!insec && /^((-|[*+]|•|–)|[0-9]+[.)])[[:space:]]+((Что|ЧТО) (найдено|нашлось|обнаружено|я нашёл|я нашел)|Находки|Находка|НАХОДКИ)(:|[[:space:]]+—)/) {
            close_item(); insec = 1; blank = 0; base = -1; oind = indent_of($0)
            lsec = ($0 ~ ("^" lm "[[:space:]]+[^#*_[:space:]]"))
            s = $0; sub(/^[[:space:]]*/, "", s); hl = match(s, /^#+/) ? RLENGTH : 0
            sub(/^(((-|[*+]|•|–)|[0-9]+[.)])[[:space:]]+)?(#+[[:space:]]*)?/, "", s)
            # Текст ПОСЛЕ заголовка: за закрывающей разметкой жирного/курсива, за « — » сразу после слов либо за
            # первым «:». Только sub по регулярке, без index/substr: их единицы в многобайтном awk расходятся.
            rest = s
            if (hl > 0) rest = ""
            else if (rest ~ /^(\*\*\*|\*\*|__)/) { if (!sub(/^(\*\*\*|\*\*|__)[^*_]*(\*\*\*|\*\*|__)/, "", rest)) rest = "" }
            else if (rest ~ /^(\*|_)/) { if (!sub(/^(\*|_)[^*_]*(\*|_)/, "", rest)) rest = "" }
            else if (sub(/^((Что|ЧТО) (найдено|нашлось|обнаружено|я нашёл|я нашел)|Находки|Находка|НАХОДКИ)[[:space:]]+—/, "", rest)) ;
            else if (!sub(/^[^:]*:/, "", rest)) rest = ""
            sub(/^[*_:. ]+/, "", rest); sub(/[*_ ]+$/, "", rest); sub(/^(—|–|-)[[:space:]]*/, "", rest)
            if (rest != "" && rest !~ /:$/ && rest !~ /^\(/) open_item(rest, "head")
            next
        }
        !insec { next }
        /^🕐/ { close_item(); insec = 0; next }
        /^[[:space:]]*#+([[:space:]]|$)/ {
            close_item(); s = $0; sub(/^[[:space:]]*/, "", s); match(s, /^#+/)
            # Подзаголовок, называющий другую часть итога ЦЕЛИКОМ, закрывает раздел на любом уровне: `### Что дальше`
            # под `##` (D1059); «### Что дальше ломается после D1040» — подзаголовок находки (D1062).
            if (hl == 0 || RLENGTH <= hl || s ~ ("^#+[[:space:]]*(" parts ")" pend "$")) insec = 0
            next
        }
        # Метка другого раздела. Под `#`-разделом жирная строка — подзаголовок, раздела не закрывает, кроме метки,
        # называющей другую часть итога (`**Что дальше:**`, D1051). Метка части закрывает раздел и с текстом на той же
        # строке (`**Что изменилось.** Сверщик строже.`, D1059) — но только в начале строки: «Раздел **Что дальше**
        # в README устарел» — находка (значок или слово впереди метку не делают, D1062).
        $0 ~ ("^" blabel) ||
            (hl == 0 && (/^(\*\*|__)[^*_]*(\*\*|__)[.:]?[[:space:]]*$/ || /^(\*\*|__)[^*_]*(:(\*\*|__)|(\*\*|__):)/)) { close_item(); insec = 0; next }
        # Пункт-метка закрывает раздел, только когда названа другая часть итога (форма итога — правила):
        # `- **Что дальше:**` — метка, `- **Что ломается:** …` и `- **Что ещё:** …` — находки (D1048). Без разметки
        # метка закрывает только итог списком частей и только на его уровне (D1059): вложенное «- Что сделано: …»
        # внутри находки и «- Что изменилось: формат сломал разбор» под заголовком «Что найдено» — находки. Жирная
        # пункт-метка — тоже только на уровне пунктов раздела: вложенное «- **Что сделано:** …» — продолжение находки.
        # Абзац «Что дальше:» и «Что ждёт <хвост формы>:» (двоеточие сразу за названием) закрывает раздел любой формы,
        # остальные части — только итог списком; «Что ждёт хук при пустом stdin: …» — находка (D1062).
        ($0 ~ ("^[[:space:]]*" lm "[[:space:]]+" blabel) && (base < 0 || indent_of($0) <= base)) || /^(Что|ЧТО) [^.]*:[[:space:]]*$/ ||
            (lsec && $0 ~ ("^" lm "[[:space:]]+" plabel)) || (lsec && $0 ~ ("^(" parts "):")) ||
            $0 ~ "^((Что|ЧТО) (дальше|ДАЛЬШЕ)|(Что|ЧТО) (ждёт|ждет)( вас| тебя| владельца| вашего решения)?):" { close_item(); insec = 0; next }
        /^[[:space:]]*(\||>)/ { next }
        /^[[:space:]]*[-*_][[:space:]]*[-*_][[:space:]]*[-*_][-*_[:space:]]*$/ { blank = 1; next }
        /^[[:space:]]*$/ { blank = 1; next }
        /^[[:space:]]*((-|[*+]|•|–)|[0-9]+[.)])[[:space:]]/ {
            ind = indent_of($0)
            # Текст заголовка без точки в конце («- Что найдено: три дефекта», «**Что найдено:** три дефекта»), за
            # которым идут пункты глубже самого заголовка, — вводная, не находка (D1059). Текст с точкой («хук X падает
            # на пустом вводе.») — сама находка, и вложенные пункты — её продолжение (D1062).
            if (kind == "head" && item != "" && ind > oind && head !~ /[.!?…][[:space:]]*$/) { item = ""; head = ""; imark = 0; kind = "" }
            if (item != "" && base >= 0 && ind > base) { item = item " " $0; sub_items = 1; blank = 0; next }
            if (base < 0 || ind < base) base = ind
            t = $0; sub(/^[[:space:]]*((-|[*+]|•|–)|[0-9]+[.)])[[:space:]]+/, "", t); open_item(t, "list"); blank = 0; next
        }
        /^[[:space:]]+[^[:space:]]/ && item != "" { item = item " " $0; imark = 0; blank = 0; next }
        {
            if (item != "" && (kind == "list" || !blank)) { item = item " " $0; imark = 0; blank = 0; next }
            t = $0; sub(/[*_[:space:]]+$/, "", t); close_item(); blank = 0
            if (t !~ /:$/) open_item($0, "para")
        }
        END { close_item() }
    '
}
