STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"

# ── У ВРЕМЕНИ ФАЙЛА ОСТАЛСЯ ОДИН НОСИТЕЛЬ — БЭКЛОГ ПРОЕКТА СЕССИИ (D396) ──────
# Время изменения говорит «файл трогали», а не «трогал ЭТОТ ход». У бэклога ClaudSoul и у
# базы знаний писателей много: параллельная сессия, архиватор, пересчёт показаний, механизм
# симметрии ссылок. Измерено 11 сентября 2026 тремя состояниями: при сессии в чужом проекте
# достаточно было СОСЕДУ тронуть бэклог ClaudSoul, чтобы ход зачёлся исходом, — два разных
# состояния мира отвечали одним значением (корень R6 карты).
#
# Кросс-проектность при этом законна и не снята: агент, работая в проекте X, вправе записать
# проблему ClaudSoul в его бэклог. Такая запись видна ДЕЙСТВИЯМИ хода — `rc_outcome_observed`
# ловит `BACKLOG*.md` и `global-lessons/` по любому пути, и признаком служит сам вызов
# инструмента, а не состояние файла. Потому общие носители ушли туда, а mtime остался у
