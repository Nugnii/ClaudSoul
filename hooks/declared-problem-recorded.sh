# дереве ClaudSoul? Тогда «записано» ложно: этот пункт не увидит ни одна сессия ClaudSoul и
# не исполнит его «Проверку».
#
# Замер по носителям (18 сентября 2026). В бэклоге соседнего проекта 24 открытых пункта и 8
# в архиве; предметом ClaudSoul были ЧЕТЫРЕ, и все четыре сняты руками 16 сентября после
# того, как их заметил владелец: B0-MIGR, B20, B21, B22. Три последних стали пунктами D416,
# D417 и D418 и чинились уже здесь. Пока их не заметили, страж «записано» их пропускал:
# он смотрит mtime бэклога ПРОЕКТА и не спрашивает, чей предмет записан.
#
# Предмет опознаётся по строкам, ДОБАВЛЕННЫМ в бэклог проекта за ход, перечнем форм — имя хука,
# слово ClaudSoul, домашний каталог установки (D521). До 11 октября 2026 перечень искался в речи
# хода, и речь с пунктом расходились в обе стороны: «страж ClaudSoul отказал» поднимало тревогу за
# пункт о своём коде, а пункт о хуке ClaudSoul при ответе без этого слова проходил молча. Замер по
# пункту: в действующих бэклогах трёх соседних проектов строк с признаком 0, в архиве ProjectA
# 13: заголовок архива, указатель на D60/D61 и строки трёх пунктов, перенесённых в ClaudSoul.
# «Добавлено за ход» — СОСТОЯНИЕ, а не история: строки файла на диске сверх строк файла на начало
# хода (счётная разность: копия уже бывшей строки — тоже добавление). Файл на начало хода — blob из
# коммита, на который HEAD указывал в TURN_START: ПРЕЖНЕЕ значение первой записи журнала ссылок
# после начала хода (amend и rebase журнал не переписывают, сборщик мусора режет только старые
# записи); записей после начала хода нет — HEAD не двигался, база HEAD; прежнее значение нулевое —
# репозиторий рождён в ходу, база пуста. Две первые редакции скептик сломал: по патчу (`diff HEAD` +
# `log --since`) — разбор строк патча, вид патча из настроек репозитория, «добавлено» по датам
# коммитера; по новейшей записи журнала не позже начала хода — усечённый журнал читался как
# «репозиторий рождён в ходу», отказ git — как «файла нет в коммите», `tr` и `grep -f` рвались на
# неверном байте и длинной строке, `grep -f` квадратичен. Здесь патча нет: blob читается `cat-file`
# без фильтров, рабочая копия — с диска, разность — одним `awk` в байтовой локали.
# Уровень остаётся ПОДСКАЗКОЙ.
# НАЗВАННЫЕ ПРЕДЕЛЫ. (1) Пункт, перенесённый по совету самой тревоги, оставляет в бэклоге проекта
# строки со словом ClaudSoul (заголовок со снятой меткой, «Перенесено в бэклог ClaudSoul как
# D418» — в архиве ProjectA таких три): на ходу переноса тревога повторится. Так было и при речи.
# Условие снятия: запись в бэклог ClaudSoul станет видна действиям хода С АДРЕСОМ
# (rc_outcome_observed отдаёт вид исхода, а не путь). (2) Файл, которого нет в коммите начала хода
# (не отслеживается, рождён в ходу), судится целиком; незакоммиченное с прошлых ходов считается
# добавленным. (3) Молчит, когда судить нечем: каталог вне git, git отказывается читать репозиторий
# (чужой владелец), коммитов нет, бэклог — симлинк (blob симлинка — путь цели, а не содержимое).
# (4) Имя в git в другом регистре (Backlog.md на APFS) — судится целиком: в четырёх соседних
# проектах имя везде BACKLOG.md. (5) Коммит с подменённой GIT_COMMITTER_DATE пишет в журнал
# подменённое время; таб внутри имени автора сбивает разбор строки журнала. (6) Журнал ссылок не
# файлом (reftable — по умолчанию с Git 3.0) или выключен — база HEAD, пункт, закоммиченный в
# ходу, не виден. (7) Бэклог под фильтром clean/smudge (git-crypt, LFS) — молчит: blob в форме
# хранилища, а фильтры репозитория project_git не исполняет. Условие снятия (2)-(7): хук начала
# хода будет снимать копию бэклога проекта; (6) — ещё и Git 3.0 в окружении владельца.
# Бэклог самого ClaudSoul опознаётся владельцем факта project_owner_copy (главная копия и её
# worktree, корень с «/» на конце, симлинк), а не сравнением строк: строковая сверка называла
# чужим бэклог ClaudSoul в worktree — скептик, раунд 3.
dpr_foreign_carrier() {
    _dfc_cs="${CLAUDSOUL_ROOT:-}"
    [ -n "$_dfc_cs" ] && [ -n "${LOCAL_BACKLOG:-}" ] && [ -f "$LOCAL_BACKLOG" ] || return 1
    [ "$LOCAL_BACKLOG" = "$_dfc_cs/BACKLOG.md" ] && return 1
    command -v project_git >/dev/null 2>&1 || return 1
    command -v project_owner_copy >/dev/null 2>&1 && project_owner_copy "$(dirname "$LOCAL_BACKLOG")" && return 1
    # Чтение СНАЧАЛА, поиск потом: `grep -q` закрывает поток на первом совпадении, писатель
    # получает SIGPIPE, и под `pipefail` утверждение врёт при нагрузке. Переменные GIT_* окружения
    # сняты внутри подстановки: GIT_DIR и GIT_INDEX_FILE бьют `-C` и подменяют репозиторий.
    _dfc_add=$(
        unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_COMMON_DIR GIT_OBJECT_DIRECTORY
        [ -L "$LOCAL_BACKLOG" ] && exit 0
        _d=$(dirname "$LOCAL_BACKLOG"); _f=$(basename "$LOCAL_BACKLOG"); _base=HEAD; _has=""
        case "${TURN_START:-}" in (''|*[!0-9]*) ;; (*)
            _log=$(project_git -C "$_d" rev-parse --git-path logs/HEAD 2>/dev/null)
            case "$_log" in ('') ;; (/*) ;; (*) _log="$_d/$_log" ;; esac
            if [ -f "$_log" ]; then
                _old=$(LC_ALL=C awk -F'\t' -v ts="$TURN_START" \
                    '{ n = split($1, a, " "); if (n >= 2 && a[n-1] + 0 > ts + 0) { print a[1]; exit } }' "$_log")
                case "$_old" in ('') ;; (*[!0]*) _base=$_old ;; (*) _base="" ;; esac
            fi ;;
        esac
        if [ -n "$_base" ]; then
            project_git -C "$_d" rev-parse -q --verify "$_base^{commit}" >/dev/null 2>&1 || exit 0
            case "$(project_git -C "$_d" check-attr filter -- "$_f" 2>/dev/null)" in
                (*': filter: unspecified') ;; (*) exit 0 ;;
            esac
            if [ -n "$(project_git -C "$_d" ls-tree --name-only "$_base" -- "$_f" 2>/dev/null)" ]; then
                project_git -C "$_d" cat-file -e "$_base:./$_f" 2>/dev/null || exit 0
                _has=1
            fi
        fi
        LC_ALL=C awk 'FILENAME == ARGV[1] { sub(/\r$/, ""); c[$0]++; next } { sub(/\r$/, "") } !(c[$0]-- > 0)' \
            <([ -n "$_has" ] && project_git -C "$_d" cat-file blob "$_base:./$_f" 2>/dev/null) <({ backlog_read "$LOCAL_BACKLOG" 2>/dev/null || cat -- "$LOCAL_BACKLOG" 2>/dev/null; })
    )
    LC_ALL=C grep -qE 'hooks/[a-z0-9_-]+\.sh|ClaudSoul|\.claude/hooks' <<< "$_dfc_add" 2>/dev/null
}

turn_outcome_seen() {
    if carrier_touched_after "$1"; then
        if dpr_foreign_carrier; then
            dpr_surface "foreign-carrier" "📌 Находка записана НЕ В ТОТ носитель: предмет лежит в дереве ClaudSoul, а пункт ушёл в бэклог этого проекта.

Такой пункт не увидит ни одна сессия ClaudSoul и не исполнит его «Проверку»: страж «записано» смотрит, менялся ли бэклог проекта, и не спрашивает, ЧЕЙ предмет записан. Так уехали четыре пункта соседнего проекта, и заметил их владелец, а не механизм.

Исход засчитывается изменением бэклога ClaudSoul. Перенеси пункт туда, а здесь оставь снятым с указанием, куда он ушёл."
            return 1
        fi
        return 0
    fi
    command -v rc_outcome_observed >/dev/null 2>&1 || return 1
