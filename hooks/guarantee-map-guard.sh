    # Разбору — СЫРЫЕ строки блока из файла по его номерам: в BODY забор кода снят, и адрес внутри него не виден (M2).
    LABEL=$(python3 -c "$GM_PY" "$REL" "$BASE" "$STEM" "$FILE" "$ROOT" "$SNAP" "$RANGE" 2>/dev/null)
    [ -n "$LABEL" ] && HITS="${HITS}${HITS:+; }${ID} («${LABEL}»)"
