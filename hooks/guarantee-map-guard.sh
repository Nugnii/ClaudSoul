import os, re, sys
rel, base, stem, file_abs, root, bl, rng = sys.argv[1:8]
st, last_line = (int(x) for x in rng.split("\t"))
body = open(bl, encoding="utf-8", errors="replace").read().split("\n")[st:last_line]

# АДРЕС — путь, извлечённый из текста, а не подстрока (M5): прогон знаков пути целиком, «..» и «./» сведены, регистр не
# различается (файловая система macOS его не различает), абсолютный путь — по корню проекта. Слева «$» или «{» —
# переменная оболочки («$README»), а не файл (третий круг, M1). Имя без расширения — точное и с учётом регистра. mb-ok
RUN = re.compile(r"[A-Za-z0-9_./~-]+")
ABS = {a.lower() for a in (file_abs, os.path.join(root, rel))}
def names(text):
    low = text.lower()
    for a in ABS:
        i = low.find(a)
        while i >= 0:
            j = i + len(a)
            post = text[j] if j < len(text) else " "
            nxt = text[j + 1] if j + 1 < len(text) else " "
            if not (post.isalnum() or post in "_/-" or (post == "." and nxt.isalnum())):
                return True
            i = low.find(a, i + 1)
    for m in RUN.finditer(text):
        i = m.start()
        # «$x» и «${x}» — переменная; голая «{» — список путей «{hooks/x.sh,hooks/y.sh}» (второй круг, L2). mb-ok
        if i and (text[i - 1] == "$" or (text[i - 1] == "{" and i > 1 and text[i - 2] == "$")):
            continue
        s = m.group(0).rstrip(".")
        if "/" in s:
            if os.path.normpath(s).lower() == rel.lower():
                return True
        # Голое имя с расширением — без регистра; без расширения — точно: «version» в прозе не «VERSION» (второй круг, L3).
        elif s and (s == base or ("." in base and s.lower() == base.lower()) or (stem and s == stem)):
            return True
    return False

# РОЛЬ — по метке: отчёт круга — скептик, противник, прожарка (M3); «Карта гарантий…» — всегда карта, даже со
# «скептиком» в метке (M4); регистр метки и слова «прогон» не важен (L7); команда-заглушка «<…>» — не прогон (L1).
ROLE = re.compile(r"скептик|противник|прожарк", re.I)
CMD = re.compile(r"прогон[^\x60]*\x60([^\x60]+)\x60", re.I)
def is_map(lab):
    return lab.strip().lower().startswith("карта гарантий")

# АБЗАЦ — от метки до следующей метки (M2): пустая строка и забор кода его не рвут; внутри забора меток нет. Метка —
# «**…**» в начале строки; пунктом списка — только с ролью (находка или карта), иначе «- **H1** — …» внутри находки и
# подпункт карты рвали бы абзац; подзаголовок — без отступа, иначе «      # шаг» в находке (второй круг, L1).
LAB = re.compile(r"^\s*\*\*(.+?)\*\*")
ITEM = re.compile(r"^\s*[-*+]\s+\*\*(.+?)\*\*")
HDR = re.compile(r"^#{1,6}\s+(.+?)\s*$")
FENCE = re.compile(r"^\s*(\x60\x60\x60|~~~)")
def label(line):
    m = LAB.match(line) or HDR.match(line)
    if m:
        return m.group(1)
    m = ITEM.match(line)
    if m and (ROLE.search(m.group(1)) or is_map(m.group(1))):
        return m.group(1)
    return None
paras, cur, fence = [], None, False
for line in body:
    lab = None
    if FENCE.match(line):
        fence = not fence
    elif not fence:
        lab = label(line)
    if lab is not None:
        if cur:
            paras.append(cur)
        cur = [lab, line]
    elif cur:
        cur[1] += "\n" + line
if cur:
    paras.append(cur)

last = -1
for k, (lab, text) in enumerate(paras):
    if not is_map(lab) and ROLE.search(lab) and names(text):
        last = k
if last < 0:
    sys.exit(0)
if any(is_map(lab) and names(text) and any(not re.fullmatch(r"\s*<[^\x60]*>\s*", c) for c in CMD.findall(text))
       for lab, text in paras[last + 1:]):
    sys.exit(0)
print(paras[last][0][:90])
