#!/usr/bin/env bash
# undefined-function-check.sh — PostToolUse[Bash|Write|Edit|MultiEdit]: вызов функции, которой нет, называется в момент записи файла, а не в рантайме.
# en: PostToolUse on shell-file writes: reports calls to functions defined nowhere in the tree or PATH.
#
# Результат: в записанном shell-файле нет вызовов функций, не определённых ни в нём,
#            ни в деревe репозитория, ни в PATH
# Проверка результата: bash hooks/tests/test_undefined_function_guard.sh даёт 0
#
# Зачем (D318). Оболочка не проверяет существование функции при разборе: вызов
# несуществующего имени синтаксически верен, проходит `bash -n`, и всплывает лишь в
# рантайме общим ненулевым кодом — неотличимым от «функция отработала с ошибкой».
# Повод измерен 6 сентября 2026: `scripts/sync-drifted.sh` звал `_cm_merge_into`, которого
# не существует. Имя было достроено по образцу соседнего `_cm_write_managed_block`,
# увиденного у ПОТРЕБИТЕЛЯ библиотеки (`hooks/tests/drift-check.sh`), а сама библиотека
# (`lib/claude-md-merge.sh`, где функция зовётся `sync_claude_md`) прочитана не была.
# Скрипт печатал «слияние не удалось», прибор был зелёным, и пара «правила» не работала.
# Дробь того же хода: где интерфейс брался из первоисточника — ошибок 0, где из вторичного
# источника или по памяти — 5 из 5 неверны.
#
# ПРЕДМЕТ — ИЗМЕНЁННЫЙ ФАЙЛ, А НЕ ИМЯ ИНСТРУМЕНТА (D311, род J реестра). Оболочка пишет
# скрипты heredoc-ом ровно так же, как их пишет Write, — и повод этого хука родился именно
# в записи через `python3 - <<PY`. Поэтому при `Bash` целями становятся файлы `*.sh` новее
# отметки прохода, а сторож `find` отсекает вызовы, при которых ничего не менялось.
#
# ПОЧЕМУ ИНЖЕКТ, А НЕ ОТКАЗ. Отказ возможен только до записи, а предмет наблюдаем после:
# у `Bash` содержимого будущего файла в `tool_input` нет вовсе. Уровень 3, и это названо,
# а не умолчано. Условие снятия: появится вход, несущий содержимое ДО записи для всех трёх
# путей (Write/Edit/MultiEdit — есть уже, Bash — нет), тогда проверка переедет на PreToolUse
# и станет отказом, как того требует правило выбора уровня.
#
# ЧЕМ ВЫРЕЗАЕТСЯ ЧУЖОЙ ЯЗЫК. `executable_part` из `hooks/command-scope-lib.sh` — та же
# библиотека, что отделяет команду от аргументов у соседей. Без неё сырой признак дал на
# этом дереве 65 ложных: `min_id` (python), `in_fm` (awk), `ascii_downcase` (jq) стоят в
# начале строки внутри heredoc и кавычек и выглядят как вызовы.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ:
#   · проверяются только имена С ПОДЧЁРКИВАНИЕМ — стиль функций этого проекта; вызов
#     `emit` или `ok` не рассматривается, потому что короткие имена без подчёркивания
#     неотличимы от внешних утилит без обращения к PATH на каждое слово;
#   · вызов ловится и БЕЗ аргументов: требование пробела после имени пропускало
#     `my_helper` на отдельной строке, и нога «своя функция» была зелена по неверной
#     причине — имя не извлекалось вовсе (поймано мутацией 6 сентября 2026);
#   · динамическое имя (`"$fn"`, `${fn}`) не проверяется: значение неизвестно до
#     исполнения, и статический отказ на нём был бы ложным по построению;
#   · функция из библиотеки ВНЕ репозитория ClaudSoul видна не будет и даст ложную
#     тревогу. Замер на живом дереве: 0 таких при 513 определённых функциях.
#
# Input  (stdin): {session_id, tool_name, tool_input} (PostToolUse JSON)
# Output (stdout): {hookSpecificOutput:{hookEventName, additionalContext}} либо пусто
# Exit:  always 0 (degrade gracefully).

set -uo pipefail

command -v jq >/dev/null 2>&1 || exit 0

INPUT=$(cat)
[ -z "$INPUT" ] && exit 0

TOOL=$(printf '%s' "$INPUT" | jq -r '.tool_name // ""' 2>/dev/null)
case "$TOOL" in
    Write|Edit|MultiEdit|Bash) ;;
    *) exit 0 ;;
esac

_self_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd -P)
# АДРЕС CLAUDSOUL — У CLAUDSOUL, А НЕ У МЕСТА ФАЙЛА (D497, ADR-018). Установленная копия живёт в
# ~/.claude/hooks, и корень «каталог выше хука» был ~/.claude: 110 тыс. файлов, не git-репозиторий.
# Обход шёл на каждое событие Bash (0,35 с при обычной нагрузке, до 1 с под нагрузкой), а судить
# было нечего — файлы проекта лежат вне ~/.claude, и универсум определений оттуда пуст (нога T13).
# Цепочка — та же, что у соседей: CLAUDSOUL_REPO → CLAUDSOUL_ROOT/указатель (`paths-lib.sh`) →
# место файла последним.
REPO="${CLAUDSOUL_REPO:-}"
if [ -z "$REPO" ] || [ ! -d "$REPO/hooks" ]; then
    REPO=""
    # shellcheck source=/dev/null
    [ -f "$_self_dir/paths-lib.sh" ] && . "$_self_dir/paths-lib.sh" 2>/dev/null && REPO="${CLAUDSOUL_ROOT:-}"
    [ -n "$REPO" ] && [ -d "$REPO/hooks" ] || REPO=$(cd -- "$_self_dir/.." 2>/dev/null && pwd -P)
fi
[ -d "$REPO/hooks" ] || exit 0

SCOPE_LIB="$_self_dir/command-scope-lib.sh"
[ -f "$SCOPE_LIB" ] || SCOPE_LIB="$REPO/hooks/command-scope-lib.sh"
# Библиотека обязательна: без неё остаётся сырой признак, дававший 65 ложных на этом же
# дереве. Отказ называется в stderr, а не подменяется тихой работой (род B реестра).
if [ ! -f "$SCOPE_LIB" ]; then
    printf 'undefined-function-check: нет %s — проверка НЕ ВЫПОЛНЕНА\n' "$SCOPE_LIB" >&2
    exit 0
fi
# shellcheck source=/dev/null
. "$SCOPE_LIB" 2>/dev/null || exit 0

# ── Вызов файла, которого нет (11 сентября 2026) ──────────────────────────────
# Вторая половина того же предмета: имя, взятое из ОБРАЗЦА, а не из источника. Прежде
# проверялись только имена функций в записанных файлах, и весь класс «запускаю скрипт,
# которого нет» проходил мимо: за одну сессию агента 12 выдуманных имён, из них в поле
# зрения хука попало 0. Замер по корпусу: 6088 вызовов вида `bash <файл>`, у 36 файла не
# существовало; 4 из них законны — файл создаётся тем же вызовом, — значит с клаузой
# точность 32 из 32. Последствие ровно одно: вызов упадёт, ничего не сделав.
#
# КОНТРПРИМЕР, который обязан проходить: `cat > /tmp/x.sh <<EOF … EOF; bash /tmp/x.sh`.
# ПРЕДЕЛ: путь из переменной (`bash "$F"`) статически непроверяем и пропускается.
# ОБЛАСТЬ ПОИСКА — у владельца (`executable_call_targets`, D424): вызовом считается лишь то,
# что стоит в позиции команды по РАЗБОРУ, а не то, что похоже на вызов где-то в тексте.
if [ "$TOOL" = "Bash" ]; then
    _ufc_cmd=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // ""' 2>/dev/null)
    # Команда, исполняемая НЕ на этом хосте (`docker run|exec`, `podman`, `ssh`, `kubectl exec`),
    # судится по чужому дереву: `bash test_x.sh` внутри `docker run … bash -c '…'` дважды объявлен
    # несуществующим 12 сентября 2026 при живом файле в контейнере. Текст после маркера
    # отсекается ДО поиска путей; perl — потому что команда многострочная, а `.*` в sed строк
    # не пересекает. Нет perl — судится вся команда, как прежде.
    _ufc_scan=$(printf '%s' "$_ufc_cmd" | perl -0pe 's/(docker\s+(run|exec)|podman\s+(run|exec)|kubectl\s+exec|(^|\s)ssh\s).*//s' 2>/dev/null) || _ufc_scan="$_ufc_cmd"
    _ufc_cwd=$(printf '%s' "$INPUT" | jq -r '.cwd // ""' 2>/dev/null)
    [ -n "$_ufc_cwd" ] || _ufc_cwd="$PWD"
    # Ведущий `cd` в самой команде перебивает cwd из полезной нагрузки: относительный путь
    # разрешается ОТТУДА, куда команда перешла, а не откуда её позвали. Замер 11 сентября
    # 2026: из 4685 вызовов `bash <файл>` в корпусе 4129 (88%) начинаются с `cd`, и без
    # этой ветки страж судил бы их относительно чужого каталога. Поймано на себе в первый
    # же день работы стража: он объявил несуществующим `hooks/knowledge-counter-bump.sh`
    # при живом файле, потому что сессия шла из ~/.claude/global-lessons.
    _ufc_lead=$(printf '%s' "$_ufc_cmd" | sed -n '1s/^[[:space:]]*cd[[:space:]]\{1,\}["'"'"']\{0,1\}\([^"'"'"';&|]*\)["'"'"']\{0,1\}.*/\1/p')
    case "$_ufc_lead" in
        "~"*) _ufc_lead="$HOME${_ufc_lead#\~}" ;;
    esac
    # У КАНАЛА ТРИ СОСТОЯНИЯ, А БЫЛО ДВА (D422, корень R6, 16 сентября 2026). Прежде и
    # «перехода не было», и «переход был, а куда — не выяснили» оставляли `_ufc_cwd` равным
    # каталогу сессии, и утверждение об отсутствии файла выносилось так, будто каталог
    # известен. Формы неудачи ТРИ, и найдены они прогоном, а не рассуждением:
    #   · подстановка — `cd "$(cat ~/.claude/claudsoul-repo)" && bash <относительный путь>`;
    #   · ХВОСТОВОЙ ПРОБЕЛ — выражение выше жадно берёт всё до `&`, и `cd hooks && …` даёт
    #     «hooks » с пробелом, на котором `-d` отвечает ложью о живом каталоге;
    #   · ОТНОСИТЕЛЬНАЯ ЦЕЛЬ — `-d` проверял её относительно каталога ПРОЦЕССА ХУКА, а не
    #     относительно cwd полезной нагрузки, то есть отвечал про посторонний каталог.
    # Третья форма и есть причина, по которой заплаты «третьего состояния» одной мало: там
    # эвристика отвечает УВЕРЕННО и уверенно неверно.
    _ufc_lead=${_ufc_lead%"${_ufc_lead##*[![:space:]]}"}
    # Признак «ведущий переход БЫЛ» — через `case`, а не sed: BSD sed на macOS не понимает
    # альтернацию `\|` в BRE, и признак умер бы молча (pattern-shell-portability, conf 5).
    # Пробельный символ взят КЛАССОМ: голый табулятор в шаблоне `case` разрывает слово, и
    # оболочка падает на разборе (проверено — первая редакция этой строки так и упала).
    _ufc_cd_seen=""
    _ufc_head=${_ufc_cmd#"${_ufc_cmd%%[![:space:]]*}"}
    case "$_ufc_head" in
        cd[[:space:]]*|pushd[[:space:]]*|"(cd"[[:space:]]*|"(pushd"[[:space:]]*) _ufc_cd_seen=1 ;;
    esac
    _ufc_abs=""
    case "$_ufc_lead" in
        "")  : ;;
        /*)  _ufc_abs="$_ufc_lead" ;;
        *)   _ufc_abs="$_ufc_cwd/$_ufc_lead" ;;
    esac
    _ufc_cwd_known=1
    if [ -n "$_ufc_abs" ] && [ -d "$_ufc_abs" ]; then
        _ufc_cwd="$_ufc_abs"
    elif [ -n "$_ufc_cd_seen" ]; then
        _ufc_cwd_known=0
    fi
    # ОБЛАСТЬ ПОИСКА ОБЪЯВЛЕНА (D424, корень R3, 16 сентября 2026). Прежде путь искался
    # grep-ом по СЫРОЙ команде, и путь внутри кавыченного аргумента объявлялся вызовом:
    # `jq -nc --arg c "cd x && bash tests/net.sh" "{}"` давало «Запускается файл, которого
    # нет». Поймано на СЕБЕ дважды — предупреждение выходило на командах, которыми
    # проверялась починка D422, и на комментарии внутри самой этой починки.
    # Владелец сужения назван в шапке этого файла (:31) и зовётся ниже дважды — а здесь
    # не звался. Это брат D420: тот же корень, соседний хук.
    # Разбор, А НЕ `executable_part`: он вырезает кавычки вместе с ЦЕЛЬЮ (`bash "x.sh"` →
    # `bash  `), и замер по корпусу дал 195 таких путей — 4,2% отзыва. Довод целиком —
    # в `command-scope-lib.sh` у `executable_call_targets`.
    # «СПРОСИТЬ НЕЧЕМ» — не «вызовов нет»: код 2 называется в stderr, а не гасится тишиной
    # (род B реестра). Потребитель инжектит текст, поэтому промах даёт ПРОПУСК.
    _ufc_paths=$(executable_call_targets "$_ufc_scan"); _ufc_rc=$?
    if [ "$_ufc_rc" -eq 2 ]; then
        printf 'undefined-function-check: разбор вызовов недоступен (нет python3 либо lib/write_targets.py) — запускаемые файлы НЕ ПРОВЕРЕНЫ\n' >&2
        _ufc_paths=""
    fi
    _ufc_missing=""
    while IFS= read -r _ufc_p; do
        [ -n "$_ufc_p" ] || continue
        case "$_ufc_p" in *.sh|*.py) ;; *) continue ;; esac   # предмет — shell и python
        case "$_ufc_p" in *'$'*|*'~'*) continue ;; esac   # переменная либо тильда — не судим
        # файл создаётся ЭТИМ же вызовом раньше по тексту — законно
        _ufc_base=${_ufc_p##*/}
        printf '%s' "$_ufc_cmd" | sed "s|bash[[:space:]]*$_ufc_p.*||" \
            | grep -qE "(cat|tee|printf|echo|cp|mv|install)[^\n]*$_ufc_base|>[[:space:]]*$_ufc_p" && continue
        case "$_ufc_p" in
            /*) [ -f "$_ufc_p" ] || _ufc_missing="$_ufc_missing $_ufc_p" ;;
            *)  # каталог не установлен — предмет не определён, и это МОЛЧАНИЕ, а не вердикт
                [ "$_ufc_cwd_known" -eq 1 ] || continue
                # ПЕРЕХОД ДО ВЫЗОВА, А НЕ В ГОЛОВЕ (D1028, 22 октября 2026). Каталог брался из ведущего `cd`, и в
                # `cd A && …; cd B && bash rel.sh` путь судился от A: живой файл объявлялся несуществующим. Переходов
                # в позиции команды ДО вызова больше, чем ведущий, — каталог пути неизвестен, молчание (третье
                # состояние D422). Первая редакция считала всю команду, и `cd sub && bash none.sh && cd -` замолкало
                # там, где каталог известен (скептик: 425 из 11 580 вызовов). Префикс — до ПОСЛЕДНЕГО вхождения пути:
                # первое бывает в кавычках (`echo "… a.sh" && cd sub && bash a.sh`), и обрыв в кавычке прятал переход;
                # ошибка так уходит в молчание. Кавычки и heredoc вырезает владелец `executable_part`.
                if command -v executable_part >/dev/null 2>&1; then
                    _ufc_ncd=$(executable_part "${_ufc_scan%"$_ufc_p"*}" | grep -oE '(^|[;&|(])[[:space:]]*(cd|pushd)([[:space:]]|$)' | wc -l | tr -d ' ')
                    [ "${_ufc_ncd:-0}" -gt "${_ufc_cd_seen:-0}" ] && continue
                fi
                [ -f "$_ufc_cwd/$_ufc_p" ] || _ufc_missing="$_ufc_missing $_ufc_p" ;;
        esac
    done <<UFC_PATHS
$_ufc_paths
UFC_PATHS
    if [[ $_ufc_missing == *[!\ ]* ]]; then
        printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","additionalContext":%s}}\n' \
            "$(jq -Rn --arg m "$_ufc_missing" \
               '"⚠️ Запускается файл, которого нет:" + $m + ". Имя взято из образца, а не из источника — прочитай каталог (ls/git ls-files) прежде чем звать. Вызов упадёт, ничего не сделав."')"
    fi
fi

# На PreToolUse предмет хука — только запуск файла, которого нет (выше): записанные командой файлы
# судятся ПОСЛЕ неё. Прежде событие ДО команды доходило сюда же — второй обход на каждую команду, и
# метка двигалась раньше, чем команда писала (D497).
[ "$(printf '%s' "$INPUT" | jq -r '.hook_event_name // ""' 2>/dev/null)" = "PreToolUse" ] && exit 0

# ── Цели ──────────────────────────────────────────────────────────────────────
# Метка — своя у сессии (D497): общая на все сессии двигалась чужим событием, и правка этой сессии
# уходила в проверку соседней — находку получал не тот, кто писал.
_ufc_sid=$(printf '%s' "$INPUT" | jq -r '.session_id // "unknown"' 2>/dev/null)
_ufc_sid=$(printf '%s' "$_ufc_sid" | tr -c 'A-Za-z0-9_-' '_')
STAMP="${CLAUDSOUL_STATE_DIR:-${STATE_DIR:-$HOME/.claude/hooks/state}}/undefined-function-scan-${_ufc_sid:-unknown}.stamp"
TARGETS=()
if [ "$TOOL" = "Bash" ]; then
    if [ ! -f "$STAMP" ]; then
        mkdir -p "$(dirname "$STAMP")" 2>/dev/null && : > "$STAMP" 2>/dev/null
        exit 0
    fi
    # Кандидаты — у учёта git корня (`*.sh` учтённые и неучтённые неигнорируемые), а не обходом
    # дерева: цена — по числу скриптов проекта, а не по всему каталогу. Корень не git — прежний обход.
    while IFS= read -r _f; do
        [ -n "$_f" ] && TARGETS+=("$_f")
    done < <( { git -C "$REPO" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
                && ( cd "$REPO" && git ls-files -z --cached --others --exclude-standard -- '*.sh' 2>/dev/null \
                     | xargs -0 -r sh -c 'for f; do [ "$f" -nt "$0" ] && printf "%s/%s\n" "$PWD" "$f"; done' "$STAMP" ); } \
              || find "$REPO" -name '*.sh' -newer "$STAMP" -not -path '*/.git/*' -print 2>/dev/null )
    : > "$STAMP" 2>/dev/null || true
    [ ${#TARGETS[@]} -gt 0 ] || exit 0
else
    FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // ""' 2>/dev/null)
    [ -n "$FILE" ] || exit 0
    TARGETS=("$FILE")
fi

KEPT=()
for _t in "${TARGETS[@]}"; do
    case "$_t" in *.sh) ;; *) continue ;; esac
    [ -f "$_t" ] && KEPT+=("$_t")
done
[ ${#KEPT[@]} -gt 0 ] || exit 0

# ── Универсум определений: всё дерево репозитория плюс сам файл ───────────────
# Дерево целиком, а не только подключённые библиотеки: подключение часто идёт по
# переменной (`. "$PATHS_LIB"`), путь статически неизвестен, и разбор его был бы гаданием.
# Эталон чистится ТАК ЖЕ, как цель. Сырой `grep` по файлам видит определения внутри тел
# heredoc — например фикстуру `my_local_helper() { … }` в тесте этого самого хука — и
# записывает их в универсум как настоящие. Замер 6 сентября 2026: сырой список 509 имён,
# честный 228; половина «функций» существовала только внутри чужого языка. Симптом: вызов
# несуществующей функции молчал, если такое же имя стояло в чьей-то фикстуре.
# Цена честной сборки — 0.68 с против 0.02 с, и платится она ТОЛЬКО когда `.sh` реально
# изменён: сторож целей стоит выше и отсекает вызовы, при которых сборка не нужна.
# Кеш обязателен, а не оптимизация: честная сборка стоит 0.68 с, и без кеша прогон
# прибора по 200 файлам дерева уходил за две минуты. Инвалидация — по свежести: любой
# `.sh` новее кеша означает, что универсум мог измениться. Проверка свежести стоит 0.00 с.
DEFS_CACHE="${CLAUDSOUL_STATE_DIR:-${STATE_DIR:-$HOME/.claude/hooks/state}}/undefined-function-defs.txt"
# Кеш привязан к ОТПЕЧАТКУ СБОРЩИКА, а не только к свежести дерева. Иначе изменённый
# сборщик читает эталон, собранный прежней редакцией, и работает по чужим данным: замер
# 6 сентября 2026 — мутация «эталон сырым grep» проходила прибор насквозь именно так,
# потому что кеш остался от честной версии. Отпечаток — `cksum` самого файла: переносим,
# в отличие от `stat` и `md5sum`.
_fp="#src $(cksum < "${BASH_SOURCE[0]:-$0}" 2>/dev/null | tr -s ' ' | cut -d' ' -f1,2)"

# Пересборка стоит 2.4 с, поэтому она привязана не к правке файла, а к ПОДОЗРЕНИЮ.
# Инвалидация по свежести дерева означала бы пересборку на каждой правке `.sh` — то есть
# 2.4 с в самой частой операции этого проекта. Здесь наоборот: в норме кеш только читается
# (0.07 с), а устаревание проявляется единственным способом — именем, которого в кеше нет.
# Тогда эталон пересобирается и находка ПЕРЕПРОВЕРЯЕТСЯ; ложная тревога от устаревшего
# кеша исчезает сама, а настоящая остаётся. Отпечаток сборщика в первой строке всё равно
# сверяется: изменённый сборщик обязан собрать заново, иначе он работает по чужим данным
# (замер 6 сентября 2026 — мутация «эталон сырым grep» проходила прибор насквозь именно
# так, потому что кеш остался от честной редакции).
_build_defs() {
    mkdir -p "$(dirname "$DEFS_CACHE")" 2>/dev/null
    printf '%s\n' "$_fp" > "$DEFS_CACHE.tmp" 2>/dev/null
    # Универсум ВЫВОДИТСЯ из индекса git, а не перечисляется globами оболочки (род F).
    # Шаблон оболочки не спускается в подкаталоги: замер 6 сентября 2026 — мимо перечня
    # шли 9 файлов scripts/ablation/ и 4 файла hooks/tests/. Здесь это не молчание, а
    # ЛОЖНАЯ тревога: функция, определённая в непросмотренном файле, объявляется
    # несуществующей. Библиотека живёт в hooks/lib/ (устанавливается), а не в hooks/tests/.
    _ul="$REPO/hooks/lib/universe-lib.sh"
    if [ -f "$_ul" ]; then
        # shellcheck source=/dev/null
        UNIVERSE_ROOT="$REPO" . "$_ul"
        _files=$(UNIVERSE_ROOT="$REPO" universe_shell_all 2>/dev/null)
    else
        _files=""
    fi
    # Своей ветки «универсум пуст» здесь НЕТ намеренно: пустой список даёт пустой DEFS, а
    # его перехватывает единственная ветка отказа ниже («универсум определений пуст»).
    # Вторая проверка была написана и убрана в тот же час: мутация «снять её» не меняла
    # наблюдаемого поведения — верный признак дубля, а не защиты. Заодно она вносила свой
    # дефект (необъявленная DEFS под `set -u` роняла хук, и отказ выглядел как тишина).
    # Универсум пуст — прибор ослеп, и СТАРЫЙ снимок здесь опаснее пустого: он выглядит
    # полным справочником и объявляет несуществующим всё, что появилось после его сборки.
    # Так и случилось 7 сентября 2026: страж живёт ещё и в установленной копии
    # ~/.claude/hooks, где CLAUDSOUL_REPO не задан, корень выводится из расположения файла
    # и указывает на ~/.claude — а это не git-репозиторий, универсум оттуда 0 файлов против
    # 519 из проекта. Обещание самоисцеления кеша («имя, которого нет → пересобрать и
    # перепроверить») там не исполнялось: пересборка молчала, `mv` не выполнялся, DEFS
    # перечитывался из прежнего снимка, и живая rc_outcome_observed (root-cause-lib.sh:343)
    # объявлялась несуществующей. Отказ обязан быть НАЗВАН — этим же занимается ветка ниже.
    if [ -z "${_files:-}" ]; then
        DEFS=""
        return 1
    fi
    for _rel in $_files; do
        # ТЕСТ ДРУГОЙ ТЕСТ НЕ ПОДКЛЮЧАЕТ (D1038, 23 октября 2026): из hooks/tests/ тесты подключают только universe-lib.sh,
        # поэтому определение в чужом тесте вызова не обеспечивает. Пока тесты входили в универсум, `assert_eq` из
        # десятков тестов засчитывала вызов в test_startup_signals.sh, где её не было, — четыре проверки падали мимо
        # счётчика. Свои функции проверяемого файла учитывает `_own` ниже.
        case "$_rel" in hooks/tests/test_*.sh) continue ;; esac
        _d="$REPO/$_rel"
        [ -f "$_d" ] || continue
        executable_part "$(cat "$_d")" 2>/dev/null
    done | grep -oE '^[[:space:]]*[A-Za-z_][A-Za-z0-9_]*[[:space:]]*\(\)' \
         | tr -d ' \t()' | sort -u >> "$DEFS_CACHE.tmp" 2>/dev/null \
      && mv "$DEFS_CACHE.tmp" "$DEFS_CACHE" 2>/dev/null
    DEFS=$(tail -n +2 "$DEFS_CACHE" 2>/dev/null)
}

if [ ! -f "$DEFS_CACHE" ] || [ "$(head -n 1 "$DEFS_CACHE" 2>/dev/null)" != "$_fp" ]; then
    _build_defs
else
    DEFS=$(tail -n +2 "$DEFS_CACHE" 2>/dev/null)
fi
# Пустой универсум — отказ проверки, а не «всё чисто»: без эталона каждое имя выглядит
# отсутствующим, и хук залил бы ход ложными тревогами (род B реестра).
if [ -z "$DEFS" ]; then
    printf 'undefined-function-check: универсум определений пуст — проверка НЕ ВЫПОЛНЕНА\n' >&2
    exit 0
fi

MSG=""
_rebuilt=0
for _f in "${KEPT[@]}"; do
    _src=$(cat "$_f" 2>/dev/null) || continue
    _exec=$(executable_part "$_src" 2>/dev/null) || continue
    _own=$(printf '%s' "$_src" | grep -oE '^[[:space:]]*[A-Za-z_][A-Za-z0-9_]*[[:space:]]*\(\)' \
           | tr -d ' \t()' | sort -u)
    _found=""
    while IFS= read -r _name; do
        [ -n "$_name" ] || continue
        grep -qxF "$_name" <<< "$DEFS" && continue
        grep -qxF "$_name" <<< "$_own" && continue
        command -v "$_name" >/dev/null 2>&1 && continue
        _found="$_found $_name"
    done <<< "$(printf '%s' "$_exec" \
        | grep -oE '(^|[;&|{]|\( |then |else |do )[[:space:]]*[a-z_][a-z0-9_]*_[a-z0-9_]+([[:space:]]|$)' \
        | grep -oE '[a-z_][a-z0-9_]*_[a-z0-9_]+' | sort -u)"
    if [ -n "$_found" ]; then
        # Подозрение — повод обновить эталон, а не кричать. Имя могло появиться в дереве
        # после последней сборки; пересобираем и оставляем только то, что не нашлось и
        # в свежем универсуме.
        if [ "$_rebuilt" -eq 0 ]; then
            if ! _build_defs; then
                # Тот же отказ, что при старте: без эталона каждое имя выглядит
                # отсутствующим, и продолжение залило бы ход ложными тревогами.
                printf 'undefined-function-check: универсум определений пуст — проверка НЕ ВЫПОЛНЕНА\n' >&2
                exit 0
            fi
            _rebuilt=1
        fi
        _still=""
        for _name in $_found; do
            grep -qxF "$_name" <<< "$DEFS" && continue
            _still="$_still $_name"
        done
        if [ -n "$_still" ]; then
            MSG="${MSG}${MSG:+
}   $(basename "$_f"):$_still"
        fi
    fi
done

[ -n "$MSG" ] || exit 0

jq -n --arg ctx "⚠️ Вызов функции, определения которой нет ни в дереве, ни в PATH:
${MSG}
   Оболочка такой вызов не проверяет: он синтаксически верен и всплывёт лишь в рантайме
   общим ненулевым кодом, неотличимым от «функция отработала с ошибкой» (D318).
   Частая причина: имя достроено по образцу соседнего, увиденного у ПОТРЕБИТЕЛЯ библиотеки,
   а сама библиотека не открыта. Прочитай первоисточник и сверь имя и порядок аргументов." \
    '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$ctx}}' 2>/dev/null
exit 0
