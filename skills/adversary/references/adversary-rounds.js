if (!args || !args.subject || !args.testPath || !args.runCmd) {
  throw new Error('adversary-rounds: нужны args.subject, args.testPath, args.runCmd')
}
const ROUNDS = Number.isInteger(args.rounds) && args.rounds > 0 ? args.rounds : 3
const BOUNDS = args.bounds ? `${args.bounds}\n\n` : ''
const fill = (s, from, to) => s.split(from).join(to)

const criticPrompt = (r, closed) => BOUNDS
  + fill(fill(fill(CRITIC, '<ПРЕДМЕТ>', args.subject),
      '<ПУТЬ ДЛЯ ТЕСТОВ>', fill(args.testPath, '<раунд>', String(r))),
      '<КОМАНДА ЗАПУСКА>', args.runCmd)
  + `\n\nПриёмы атаки (чем бить; это ПРИЁМЫ, а не классы дефектов):\n${TECHNIQUES}`
  + `\n\nУже ЗАКРЫТЫЕ классы — новый вход в них помечай «ВХОД ЗАКРЫТОГО КЛАССА: <класс>», а не новой находкой: ${closed || 'нет'}`

const AUTHOR_SCHEMA = { type: 'object', properties: {
  summary: { type: 'string', description: 'правка корня по шагам, инварианты: красные до, зелёные после; прогон карты зависимостей' },
  closedClasses: { type: 'string', description: 'какие классы дефектов правка закрыла (для критика)' },
}, required: ['summary', 'closedClasses'] }
const CRITIC_SCHEMA = { type: 'object', properties: {
  attacks: { type: 'string', description: 'все атаки в формате /adversary Step 1' },
  reproduced: { type: 'integer', description: 'сколько атак воспроизведено КРАСНЫМ тестом' },
  sameRoot: { type: 'integer', description: 'сколько воспроизведённых атак с меткой [тот же корень R<N>]' },
  ruleChoice: { type: 'integer', description: 'сколько воспроизведённых атак вида rule_choice — ожидание задано выбранным правилом, данные его не определяют' },
  coverage: { type: 'string', description: 'ПОКРЫТИЕ: реально прочитанные файлы и что из предмета не проверено, с причиной' },
}, required: ['attacks', 'reproduced', 'sameRoot', 'ruleChoice', 'coverage'] }
const CLASS_SCHEMA = { type: 'object', properties: {
  classes: { type: 'string', description: 'классы: имя, атаки с адресами, корзина; для нового — проявления, цепочки «почему» двумя линиями, сверка, корень с дробью M из N, братья, карта зависимостей, дизайн ОДНОЙ правки; для входа закрытого класса — почему корень его не закрыл' },
  newClasses: { type: 'integer' },
  closedClassEntries: { type: 'integer', description: 'воспроизведённых входов в УЖЕ закрытые классы' },
  fixPlan: { type: 'string', description: 'по одной правке на корень, с инвариантом, который её проверяет' },
}, required: ['classes', 'newClasses', 'closedClassEntries', 'fixPlan'] }
const FIX_SCHEMA = { type: 'object', properties: {
  summary: { type: 'string', description: 'правки по корням, сколько красных тестов гасит каждая, регрессия по карте' },
  closedClasses: { type: 'string' },
}, required: ['summary', 'closedClasses'] }

let closed = args.closed || ''
const rounds = []
let stop = `лимит ${ROUNDS} раундов`

if (args.author) {
  const a = await agent(`${BOUNDS}ТЫ — АВТОР ПРАВКИ КОРНЯ (${SKILL}, Step 5 — прочитай его). ${args.author}\n\nПравка адресуется корню, а не атаке; тест инварианта КРАСНЫЙ до правки (покажи), зелёный после; карта зависимостей из Step 4д — чек-лист регрессии.`,
    { label: 'author', phase: 'Author', schema: AUTHOR_SCHEMA, model: 'sonnet', agentType: 'lean' })
  if (a) closed = [closed, a.closedClasses].filter(Boolean).join('; ')
  else log('автор не вернул отчёт — раунды идут по текущему коду')
}

for (let r = 1; r <= ROUNDS; r++) {
  const critic = await agent(criticPrompt(r, closed), { label: `critic-r${r}`, phase: 'Critic', schema: CRITIC_SCHEMA, model: 'opus', agentType: 'lean' })
  if (!critic) { stop = `раунд ${r}: критик не вернул результат — это отказ инструмента, а не «атак нет»`; rounds.push({ r }); break }
  // «Атак нет» без покрытия неотличимо от «не смотрел» (правило из openai/codex-security, решение владельца 18.11.2026).
  if (critic.reproduced === 0) {
    stop = critic.coverage ? `раунд ${r}: атак нет; покрытие: ${critic.coverage}`
      : `раунд ${r}: критик сказал «атак нет», но не назвал покрытие — это «не смотрел», а не «чисто»`
    rounds.push({ r, critic }); break
  }
  // Атака вида rule_choice — ожидание задано правилом, которого данные не определяют (D523): правка
  // подобрала бы следующее правило, и следующий раунд нашёл бы ему контрпример (ProjectA B28, B463).
  // Такие атаки в разбор и правку не идут; дефекты раунда чинятся, следующего раунда нет.
  const ruleChoice = Number.isInteger(critic.ruleChoice) ? critic.ruleChoice : 0
  const ruleStop = `раунд ${r}: ${ruleChoice} атак вида rule_choice — ожидание не следует из данных; стоп раундов, вопрос владельцу о выборе правила с вариантами и ценой`
  if (ruleChoice > 0 && ruleChoice >= critic.reproduced) { stop = ruleStop; rounds.push({ r, critic }); break }
  // Третий раунд снова принёс форму ТОГО ЖЕ корня — точечные правки устройство не закрывают;
  // правки нет, решение о переделке на уровне класса — за владельцем (решение 9 октября 2026).
  if (r >= 3 && critic.sameRoot > 0) { stop = `раунд ${r}: снова тот же корень (${critic.sameRoot} атак) — стоп раундов, вопрос владельцу о переделке на уровне класса`; rounds.push({ r, critic }); break }

  const cls = await agent(`${BOUNDS}ТЫ СВОДИШЬ находки противника в КЛАССЫ и спускаешься к корню каждого — ${SKILL}, Step 3 и Step 4 целиком, прочитай их прежде разбора. Код продукта не правишь; тесты атак запускать можно. Класс — РОД дефекта, а не место. Атака без красного теста — «не воспроизведена»; «не дефект» закрывается только зелёным тестом, закрепляющим поведение. Уже закрытые классы: ${closed || 'нет'} — вход в закрытый класс получает ответ «почему корень его не закрыл», а не заплатку. Атаки с «Вид: rule_choice» в классы НЕ входят и правки не получают — корзина «Выбор правила» (Step 3), решает владелец.\n\nАтаки противника:\n${critic.attacks}`,
    { label: `classes-r${r}`, phase: 'Classes', schema: CLASS_SCHEMA, model: 'sonnet', agentType: 'lean' })
  if (!cls) { stop = `раунд ${r}: разбор классов не вернул результат`; rounds.push({ r, critic }); break }
  if (cls.newClasses === 0 && cls.closedClassEntries === 0) { stop = ruleChoice > 0 ? ruleStop : `раунд ${r}: ни нового класса, ни входа в закрытый — только стиль или невоспроизведённое`; rounds.push({ r, critic, cls }); break }

  const fix = await agent(`${BOUNDS}ТЫ — АВТОР (${SKILL}, Step 5 — прочитай его). Чини по КЛАССАМ, не по атакам: одна правка на корень, в общем месте, через которое идут все вызывающие. Тесты атак — ПРОВЕРКА правки, а не её план; назови, сколько красных тестов гасит каждая правка (правок столько же, сколько атак, — признак симптома). Вход закрытого класса — чини КОРЕНЬ по разбору «почему не закрыл». После правки — прогон карты зависимостей и всех тестов атак.\n\nКлассы:\n${cls.classes}\n\nПлан:\n${cls.fixPlan}`,
    { label: `rootfix-r${r}`, phase: 'RootFix', schema: FIX_SCHEMA, model: 'sonnet', agentType: 'lean' })
  rounds.push({ r, critic, cls, fix })
  if (fix && fix.closedClasses) closed = [closed, fix.closedClasses].filter(Boolean).join('; ')
  if (!fix) { stop = `раунд ${r}: правка не вернула отчёт`; break }
  if (ruleChoice > 0) { stop = ruleStop; break }
  if (cls.newClasses === 0) { stop = `раунд ${r}: нового класса нет — входы закрытых классов отработаны вопросом к корню`; break }
}

log(`стоп: ${stop}`)
return { stop, closed, rounds }
