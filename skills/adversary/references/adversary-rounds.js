// Шаги 1–6 скилла /adversary для прогона АГЕНТАМИ (D485). Скилл описывает цикл для автора в одном
// контексте; цикл агентов, собранный с нуля, пропускал шаги 3–6: бриф чинящего «почини код так,
// чтобы тест позеленел» сделал единицей починки АТАКУ, и раунды не сходились (ProjectA, 27 сентября
// 2026: B33 — 5→6→8 атак, B34 — 3→4→4, регрессии раунда 2 в обоих). Здесь сведение в классы,
// спуск к корню и стоп по классу стоят в коде и пропуститься не могут.
//
// Зов — из скилла: Workflow({ scriptPath: '<HOME>/.claude/commands/adversary/references/adversary-rounds.js',
// args: { subject, testPath, runCmd, bounds?, author?, closed?, rounds? } }).
//   subject  — путь и что код делает, без оценок (подставляется в <ПРЕДМЕТ>);
//   testPath — куда класть тесты атак; `<раунд>` в нём заменяется номером раунда;
//   runCmd   — чем запустить тест;
//   bounds   — границы проекта для КАЖДОГО агента: рабочая копия, запреты, правила коммитов;
//   author   — бриф правки корня по готовому разбору (Step 5 до первого раунда), если он есть;
//   closed   — уже закрытые классы; rounds — предел раундов, по умолчанию 3.
// Предел: один предмет на прогон; несколько предметов — несколько вызовов.
// Агенты-разборщики и чинящие читают шаги сами — у текста скилла один владелец. Промпт критика и
// приёмы атаки — копии ниже: критик не должен читать ничего, кроме предмета.
