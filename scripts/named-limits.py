#!/usr/bin/env python3
# Результат: предел, чьё условие снятия НАСТУПИЛО, назван адресом и командой; предел без
#            исполнимого условия назван отдельно — это долг перевода, а не находка.
# Проверка результата: bash hooks/tests/test_named_limits.sh даёт 0
#
# Строки договора стоят КОММЕНТАРИЕМ, а не в строке документации: страж
# `hooks/tests/test_instrument_contract.sh:48` требует `^#\s*Результат:` и разбирает файл
# построчно, без разбора языка. Форма — часть договора, а не вкус.
r"""named-limits.py — НАСТУПИЛО ЛИ условие снятия названного предела. Не «смотрели ли».

ЗАЧЕМ (20 сентября 2026, вопрос владельца: «а будет ли когда-нибудь предел снят? если
архивы не поднимаются, там может быть много другого с пределами, которые уже можно
снимать»). Замер того часа: объявлений предела в дереве 439, коммитов за всю историю, где
предел СНЯТ, — два. Замеров, пересматривающих пределы, ноль из 110.

КОРЕНЬ, И ОН БРАТ УЖЕ ПОЧИНЕННОГО. Условие снятия пишется ПРОЗОЙ О БУДУЩЕМ МИРЕ: «появится
замер точности», «появится разбор кавычек». У такой записи нет адреса — исполнить её
нельзя, и тот, кто через месяц построит этот самый разбор, не узнает, что на него ждали.
Ровно этот корень назван и закрыт 27 августа 2026 для ПУНКТОВ ДОЛГА:
`scripts/backlog-return-check.sh` — «условие возврата записывалось ПРОЗОЙ С ДАТОЙ, а
читалось как нынешнее состояние»; там из девяти условий два оказались невыполнимыми по
построению. Предел — та же сущность (условие пересмотра), и он единственный остался на
прозе. Поэтому у пунктов возврат работает, а у пределов — 2 из 439.

ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ПРИБОРА БЫЛА СИМПТОМОМ, и это записано, чтобы не вернулось: она
вела реестр «кто пересмотрен, кто нет» и давала очередь из 249 записей, которую разгребают
ГЛАЗАМИ. То есть заводила вторую очередь той же болезни — объявление без исполнителя.
Владелец остановил словами «опять симптом правишь».

ЧТО ЗДЕСЬ ВМЕСТО НЕГО. У предела рядом с условием стоит КОМАНДА, и её зелёный код значит
«мир стал таким, при котором предел держаться перестал». Форма записи — три строки подряд:
слова «НАЗВАННЫЙ» и «ПРЕДЕЛ» с двоеточием и тем, чего именно не умеет механизм; строка
«Условие снятия:» с прозой для человека; строка «Проверка снятия:» с командой в обратных
кавычках и «→ 0». Образец формы здесь записан словами, а не тремя строками: с D1341 прибор
читает строки документации, и буквальный образец был бы его же объявлением с командой-заглушкой.

Прибор исполняет эти команды и называет те, что позеленели. Направление обратное «Проверке»
пункта долга и это НАМЕРЕННО: там красное значит «дефект жив», здесь зелёное значит
«ограничение больше не нужно».

ЧЕГО ПРИБОР НЕ ДЕЛАЕТ. Он не снимает предел сам: снятие — правка механизма и его шапки,
решение автора. Он отвечает на единственный вопрос, который раньше не задавал никто:
у КАКИХ пределов мир уже изменился.

НАЗВАННЫЙ ПРЕДЕЛ САМОГО ПРИБОРА: он видит только пределы с «Проверкой снятия». Прозаические
условия он НЕ судит и не притворяется, что судит, — он их перечисляет отдельно как долг
перевода, с адресом каждого.
ВТОРОЙ НАЗВАННЫЙ ПРЕДЕЛ (20 сентября 2026, по первому же прогону): прибор судит КОД команды
и не отличает зрячую проверку от слепой. Обе ложные находки первого прогона были слепыми по
разным устройствам — одна зеленела оттого, что не отработала (producer код 2 в конвейере),
вторая оттого, что искала имя и находила его в строке СОБСТВЕННОГО объявления. Первое
устройство закрыто формой (`pipefail` + цепочка присваиваний), второе — нет: отличить
«ищет в мире» от «ищет в себе» автоматом нельзя, ровно как в договоре пункта долга, где
слепая «Проверка» помечается ЛИТЕРАЛОМ руками автора (`BACKLOG_FORM_PROXY_RE`,
`hooks/backlog-lib.sh:250`).
Механизма метки здесь НЕ заведено намеренно: исполнимых проверок снятия четыре, и метка на
четырёх — реестр ради реестра. Заводить, когда их станет столько, что прогон глазами
перестанет быть дешевле.
Условие снятия: исполнимых проверок снятия станет больше двадцати.
Проверка снятия: `_n=$(python3 scripts/named-limits.py | sed -n 's/.*исполнимой проверкой снятия: \([0-9]*\).*/\1/p') && [ -n "$_n" ] && test "$_n" -gt 20`

ПЕРВЫЙ НАЗВАННЫЙ ПРЕДЕЛ.
Условие снятия: доля пределов с исполнимой проверкой дойдёт до единицы — тогда перечень
долга опустеет сам, и режим `--untranslated` станет пустым по построению.
Проверка снятия: `python3 scripts/named-limits.py --untranslated | grep -c . ; test $(python3 scripts/named-limits.py --untranslated | grep -c .) -eq 0`

Режимы:
  (без ключей)      сводка числом
  --check           код 1, если у какого-то предела условие НАСТУПИЛО
  --untranslated    пределы без исполнимой проверки снятия: адрес и текст (долг перевода)
  --no-exit         файлы, объявившие предел без условия снятия (зовётся набором)
"""
import os
import pathlib
import re
import subprocess
import sys

# Исполнение «Проверки снятия» со сроком — правило исполнителей `hooks/lib/bounded_run.py` (D1199): до него здесь
# стоял `subprocess.run(…, timeout=)`, снимавший по сроку только `bash -c`, а внуки команды жили дальше.
_LIB = pathlib.Path(__file__).resolve().parent.parent / "hooks" / "lib"
if not (_LIB / "bounded_run.py").exists():
    _LIB = pathlib.Path.home() / ".claude/hooks/lib"
sys.path.insert(0, str(_LIB))
import bounded_run  # noqa: E402

# ВЛАДЕЛЕЦ ПРИЗНАКА «ЧТО ЕСТЬ НАЗВАННЫЙ ПРЕДЕЛ». Выражения перенесены сюда 20 сентября 2026
# из `hooks/tests/test_named_limit_has_exit.sh`; тест зовёт этот прибор и своей копии не
# держит — два владельца одного признака разошлись бы молча (род K реестра, корень R1).
DECLARE = re.compile(r'НАЗВАННЫЙ\s+ПРЕДЕЛ|Названный\s+предел|\*\*Названный\s+предел|'
                     r'назван\s+предел|предел\s+назван')
_W = r'[\s#*/-]+'
EXIT = re.compile(r'словие' + _W + r'снятия|нимается,' + _W + r'когда|Снимается|пока' + _W +
                  r'не' + _W + r'появ|как' + _W + r'только' + _W + r'появ|перестаёт' + _W +
                  r'держаться,' + _W + r'когда')
REFERENCE = re.compile(r'предел\s+(?:назван|объявлен)\s+(?:в|у)\s')
# Команда снятия: строка «Проверка снятия:» и команда в обратных кавычках. Форма взята у
# брата — «Проверка возврата» пункта долга, — чтобы читателю не пришлось учить вторую.
CHECK_LINE = re.compile(r'Проверка\s+снятия[:.]?' + _W + r'`([^`]+)`')

CHRONICLES = {"CHANGELOG.md", "внутренний архив (не публикуется)", "BACKLOG-archive.md", "SESSION.md"}
BUDGET = int(os.environ.get("NAMED_LIMIT_CHECK_TIMEOUT", "20"))


def repo_root():
    r = os.environ.get("CLAUDSOUL_REPO")
    if r:
        return r
    return subprocess.run(["git", "rev-parse", "--show-toplevel"],
                          capture_output=True, text=True).stdout.strip()


REPO = repo_root()


def tracked_files():
    # Учтённые ПЛЮС новые неигнорируемые (D1240): голый `git ls-files` не видит файла до `git add`, и прогон перед
    # коммитом был зелёным там, где CI на том же коммите красный. Форма та же, что у `test_dep_index_test_link_role.sh`.
    out = subprocess.run(["git", "-C", REPO, "ls-files", "--cached", "--others", "--exclude-standard"],
                         capture_output=True, text=True)
    if out.returncode != 0:
        return []
    return [f for f in out.stdout.split("\n") if f]


def _py_prose_rows(text):
    """Номера строк .py, где стоит ПРОЗА АВТОРА: комментарий на всю строку и строка документации. None — файл не
    разобрался (обрывок, синтаксис новее интерпретатора) либо владельца признака нет рядом: зовущий берёт прежний вид.

    Роль строки называет разборщик языка, а не её вид (D1341, корень R3). Прежний признак «строка начинается с #»
    ошибался в обе стороны: предел в строке документации был невидим — так объявлены пределы самого прибора, и 37 строк
    в 12 файлах дерева прибор не судил вовсе, — а `#`-строка внутри многострочного литерала с данными шла объявлением.
    Строки документации — у владельца, `py_prose_rows` в `hooks/lib/project_map.py` (D1286): тот же разбор, что у карты
    и учёта зависимостей; комментарий — токен COMMENT, открывающий свою строку.
    """
    import io
    import tokenize
    try:
        import project_map
        rows = project_map.py_prose_rows(text)
    except Exception:  # noqa: BLE001 — владельца нет (копия прибора в песочнице) либо он не загрузился
        return None
    if rows is None:
        return None
    rows = set(rows)
    try:
        for tok in tokenize.generate_tokens(io.StringIO(text).readline):
            if tok.type == tokenize.COMMENT and not tok.line[:tok.start[1]].strip():
                rows.add(tok.start[0])
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return None
    return rows


def _sh_fixture_rows(text):
    """Номера строк .sh внутри heredoc, ПИШУЩЕГОСЯ В ФАЙЛ: это текст фикстуры, а не комментарий этого файла (D1341).

    Признак «heredoc после перенаправления в файл» — у владельца, `_f_code` в `scripts/defect-class-carriers.py`
    (`F_HEREDOC`, `F_REDIR`); своей копии здесь нет. Heredoc, отданный интерпретатору (`python3 - <<'PY'`), кодом и
    остаётся: комментарий в нём — настоящий. Нет владельца рядом (копия прибора в песочнице) — пустое множество.
    """
    global _HEREDOC_OWNER
    if _HEREDOC_OWNER is None:   # владелец грузится один раз на прогон, а не на каждый файл (скептик D1341, L3)
        try:
            import importlib.util
            p = pathlib.Path(__file__).resolve().parent / "defect-class-carriers.py"
            spec = importlib.util.spec_from_file_location("defect_class_carriers", p)
            owner = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(owner)
            _HEREDOC_OWNER = (owner.F_HEREDOC, owner.F_REDIR)
        except Exception:  # noqa: BLE001 — владельца нет либо он не загрузился: прежнее поведение, без исключения
            _HEREDOC_OWNER = ()
    if not _HEREDOC_OWNER:
        return set()
    heredoc, redir = _HEREDOC_OWNER
    rows, mark, pending = set(), None, []
    for i, line in enumerate(text.split("\n"), 1):
        if mark is not None:
            if line.strip() == mark:
                rows.update(pending)   # тело — фикстура, только когда метка ЗАКРЫЛАСЬ: незакрытая слепила хвост файла
                mark, pending = None, []
            else:
                pending.append(i)
            continue
        # У владельца строка-комментарий снимается ДО поиска начала heredoc (`_f_code`): комментарий, цитирующий
        # форму (`# cat > a <<A …`), открывал «фикстуру» до конца файла, и настоящее объявление ниже терялось
        # (скептик D1341, H1: `hooks/detection-signals-lib.sh:1017`).
        if line.lstrip().startswith("#"):
            continue
        m = heredoc.search(line)
        if m and redir.search(line[:m.start()]):
            mark = m.group(1)
    return rows


_HEREDOC_OWNER = None
# Текст фикстуры бывает только в тестах и пробах: вне их heredoc, пишущийся в файл, — программа самого автора, которую
# скрипт затем исполняет (`scripts/backlog-recheck.sh` пишет питон во временный файл), и её комментарий — настоящее
# объявление (скептик D1341, H2). Каталог тот же, что у исключения тестов атак выше по признаку.
_FIXTURE_HOME = "hooks/tests/"


def declared_lines(rel, text):
    """Строки, объявляющие СВОЙ предел, со всеми исключениями признака.

    Исключения перенесены из сканера вместе с поводами: хроника предел пересказывает, а не
    объявляет; в тесте атаки предел принадлежит подложной фикстуре; значение YAML — пересказ
    в провенансе; в коде объявление стоит прозой автора (комментарий, строка документации), а
    строка кода с той же фразой это данные (сообщение утверждения, регулярка стража, строка
    вывода, текст фикстуры в heredoc).
    """
    if pathlib.Path(rel).name in CHRONICLES or re.match(r'hooks/tests/test_adv', rel):
        return []
    code = rel.endswith((".sh", ".py"))
    prose = _py_prose_rows(text) if rel.endswith(".py") else None
    fixture = _sh_fixture_rows(text) if rel.endswith(".sh") and rel.startswith(_FIXTURE_HOME) else set()
    out = []
    for i, line in enumerate(text.split("\n"), 1):
        if not DECLARE.search(line):
            continue
        if re.match(r'\s+\w+:\s*"', line):
            continue
        if prose is not None:
            if i not in prose:
                continue
        elif code and (not re.match(r'\s*#', line) or i in fixture):
            continue
        out.append((i, line))
    return out


def find_limits():
    """Каждое объявление предела: адрес, есть ли условие прозой, есть ли команда снятия."""
    found = []
    for rel in tracked_files():
        try:
            text = (pathlib.Path(REPO) / rel).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        decl = declared_lines(rel, text)
        if not decl:
            continue
        lines = text.split("\n")
        file_has_exit = bool(EXIT.search(text))
        if not file_has_exit and REFERENCE.search(text) and not re.search(
                r'НАЗВАННЫЙ ПРЕДЕЛ|\*\*Названный предел', text):
            continue
        for i, line in decl:
            # Команда ищется В ОКНЕ под объявлением: у файла их бывает несколько, и
            # общефайловый поиск приписал бы чужую команду соседнему пределу.
            window = "\n".join(lines[max(0, i - 2):i + 14])
            m = CHECK_LINE.search(window)
            found.append({
                "file": rel, "line": i,
                "has_exit": bool(EXIT.search(window)) or file_has_exit,
                "cmd": m.group(1) if m else None,
                "text": line.strip()[:150],
            })
    return found


def run_check(cmd):
    """Исполнить команду снятия с бюджетом времени. → (код, что случилось).

    Бюджет обязателен: команда произвольна, а прибор зовётся в наборе. Срыв срока — СВОЙ
    исход, а не «не наступило»: это тот же R6, который чинили у брата (`backlog-return-check`).
    """
    try:
        # PIPEFAIL ЗДЕСЬ НЕ СТАВИТСЯ, И ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЧТЕНО (20 сентября 2026).
        #
        # Он был поставлен утром того же дня против команды снятия, зеленевшей на producer'е
        # с кодом 2. Замер вечера показал: пользы НОЛЬ, потому что тот случай прятался не в
        # конвейере, а в подстановке — `test "$(producer | wc -l)" -eq 0`, где код подстановки
        # теряется в аргументе и никаким pipefail не достаётся. Случай починен формой команды
        # (цепочка ПРИСВАИВАНИЙ), и это единственная дорога.
        #
        # Риск же измерен на 302 командах «Проверки» обоих файлов долга: вердикт под pipefail
        # меняют ТРИ, и все три ложно. Идиома у всех одна — `grep -c … | grep -qx 0`, то есть
        # «совпадений ноль»: `grep -c` при нуле выходит ЕДИНИЦЕЙ, и pipefail роняет честную
        # проверку. Для проверки снятия направление обратное, и цена та же: настоящее
        # «условие НАСТУПИЛО» прочлось бы как «предел держится», то есть находка потерялась бы
        # молча. Идиома в дереве обычна, так что это не гипотеза.
        # Свой TMPDIR (D1198), своя сессия команды и снятие её группы по сроку — правило исполнителей (D1199).
        # ВЛОЖЕННЫЙ ВЫЗОВ ПРОВЕРОК НЕ ИСПОЛНЯЕТ (D1341): проверка снятия собственного предела прибора зовёт сам прибор
        # (`python3 scripts/named-limits.py | sed …`), и с того дня, как пределы из строки документации стали видны,
        # безымянный вложенный вызов исполнил бы ту же проверку снова — кольцо процессов до срока. Метка в окружении
        # команды — та же дорога, что `BACKLOG_CHECKS_NESTED` у «Проверок» пунктов долга (D502).
        r = bounded_run.run_bounded(cmd, BUDGET, cwd=REPO, env={**os.environ, "NAMED_LIMITS_NESTED": "1"},
                                    prefix="nl.", capture=True)
        # КОД 2 — «СУДИТЬ НЕЧЕМ», А НЕ «НЕ НАСТУПИЛО» (поймано на первом же прогоне этого
        # прибора). Проверка снятия отвечает 2, когда рамка не собралась: нет jq, нет git,
        # механизм не на месте. Сложить это с «предел держится» значило бы пустить два
        # состояния мира по одному проводу — корень R6, тот самый, от которого прибор
        # предостерегает в шапке. Новый прибор нёс дефект из реестра, ради которого строился.
        if r.returncode == 2:
            return None, "СУДИТЬ НЕЧЕМ (код 2): " + (r.stderr.strip().split("\n")[-1][:90] or "рамка не собралась")
        if r.returncode >= 126:
            return None, f"НЕ ЗАПУСТИЛАСЬ (код {r.returncode})"
        return r.returncode, "исполнена"
    except subprocess.TimeoutExpired:
        return None, f"СРОК ИСТЁК ({BUDGET} с)"
    except OSError as e:
        return None, f"НЕ ЗАПУСТИЛАСЬ: {e}"


def main():
    # SIGTERM и SIGHUP — выход исключением: у команды снятия своя сессия, и группу её снимает `bounded_run.run_bounded` (D1199).
    bounded_run.trap_signals()
    args = sys.argv[1:]
    if not REPO:
        print("named-limits: корень репозитория не определён — судить нечем", file=sys.stderr)
        return 2
    limits = find_limits()
    if not limits:
        print("named-limits: не найдено ни одного объявления — прибор не отработал",
              file=sys.stderr)
        return 2

    translated = [x for x in limits if x["cmd"]]
    untranslated = [x for x in limits if not x["cmd"]]

    if "--no-exit" in args:
        by_file = {}
        for x in limits:
            by_file.setdefault(x["file"], []).append(x)
        bad = [f for f, xs in sorted(by_file.items()) if not any(y["has_exit"] for y in xs)]
        print(f"названных пределов с условием снятия: {len(by_file) - len(bad)}, "
              f"БЕЗ условия снятия: {len(bad)}")
        for f in bad:
            print(f"  · {f}")
        return 1 if bad else 0

    if "--untranslated" in args:
        for x in untranslated:
            print(f"{x['file']}:{x['line']}\t{x['text']}")
        return 0

    arrived, broken = [], []
    if os.environ.get("NAMED_LIMITS_NESTED") == "1" and ("--check" in args or not args):
        # Счёт объявлений отдаётся, проверки не исполняются: исход вложенного вызова — «не судили», а не «не наступило».
        print(f"названных пределов: {len(limits)}; с исполнимой проверкой снятия: "
              f"{len(translated)}; прозой (долг перевода): {len(untranslated)}")
        print("вложенный вызов из проверки снятия: проверки не исполнялись")
        return 2 if "--check" in args else 0
    if "--check" in args or not args:
        for x in translated:
            rc, how = run_check(x["cmd"])
            if rc is None:
                broken.append((x, how))
            elif rc == 0:
                arrived.append(x)

    print(f"названных пределов: {len(limits)}; с исполнимой проверкой снятия: "
          f"{len(translated)}; прозой (долг перевода): {len(untranslated)}")
    if "--check" in args or not args:
        print(f"условие НАСТУПИЛО: {len(arrived)}; проверка не отработала: {len(broken)}")

    # НАХОДКА ВИДНА В ОБОИХ РЕЖИМАХ, РАЗЛИЧАЕТСЯ ТОЛЬКО КОД (20 сентября 2026).
    # Здесь стоял выход `return 0` ДО перечня адресов: безымянный режим исполнял все
    # команды снятия и выбрасывал найденное, печатая одно число. Первый же прогон дал
    # «условие НАСТУПИЛО: 2; проверка не отработала: 1» — и ни одного адреса, то есть
    # работа сделана, а потребителя у результата нет (корень R2, тот самый класс, ради
    # которого прибор и строился). Режимы обязаны различаться ПРАВОМ ОТКАЗА, а не
    # молчанием: набор зовёт `--check` и хочет код, человек зовёт без ключей и хочет адрес.
    for x, how in broken:
        print(f"  ⚠ {x['file']}:{x['line']} — проверка снятия {how}", file=sys.stderr)
    if arrived:
        print("\nУсловие снятия НАСТУПИЛО — предел пора снимать либо переписывать:")
        for x in arrived:
            print(f"  · {x['file']}:{x['line']}")
            print(f"    {x['text']}")
    if "--check" not in args:
        return 0
    if arrived:
        return 1
    # Сорванная проверка — не «не наступило»: исход неизвестен, и молчание тут было бы
    # тем же R6, что чинили у брата.
    return 1 if broken else 0


if __name__ == "__main__":
    sys.exit(main())
