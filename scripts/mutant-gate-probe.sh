#!/usr/bin/env bash
# mutant-gate-probe.sh — мутирующий тест ДОКАЗЫВАЕТ, что мутация состоялась.
# en: probes mutating tests by neutralising their own needle; an honest test must redden.
#
# Результат: у каждого теста, который портит файл подстрокой, стоит гейт применения —
#            с обезвреженной иглой тест краснеет, а не проходит молча; вакуумных ноль.
# Проверка результата: bash hooks/tests/test_mutant_gate_probe.sh даёт 0 — прибор краснеет
#            на подложенном тесте без гейта и молчит на тесте с гейтом.
#
# Зачем (D412). Пункт объявлял девять носителей, а осмотр дал ноль: дерево доказывает
# применение мутации тремя формами, а признак пункта знал одну. Признак читал ТЕКСТ теста и
# потому был помечен «судит по форме» — такое закрытие архиватор не переносит, и правило
# верное: слово в тексте не доказывает поведения. Этот прибор судит ПОВЕДЕНИЕ: он портит
# иглу самого теста и смотрит, заметит ли тест, что портить стало нечего.
#
# УСТРОЙСТВО. Игла обезвреживается в ДВУХ формах: объявленной переменной (`needle = '…'`) и
# литералом первого аргумента замены. Копия теста кладётся РЯДОМ с оригиналом (имя не
# начинается с `test_`, раннер её не берёт) — иначе `dirname $0` уедет и тест не найдёт ни
# библиотек, ни своих фикстур.
#
# НАЗВАННЫЙ ПРЕДЕЛ: судятся тесты, у которых ЕСТЬ гейт применения — по нему же они и
# опознаются. Мутант без гейта прибору не виден ПО ПОСТРОЕНИЮ: именно его отсутствие и есть
# дефект, а узнать мутанта без гейта от постройки фикстуры по тексту нельзя (проверено
# осмотром: из десяти тестов с иглой-литералом девять строят фикстуру). Условие снятия:
# появится признак, различающий РОЛЬ правки — испытание против постройки, — а не её форму.
#
# Код возврата: 0 — вакуумных нет; 1 — есть; 2 — прибор сломан (тестов не найдено, нет python3).
set -uo pipefail

_self=$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd -P)
REPO="${CLAUDSOUL_REPO:-$(cd -- "$_self/.." 2>/dev/null && pwd -P)}"
cd "$REPO" 2>/dev/null || { echo "BROKEN: корень не разрешён"; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "BROKEN: нет python3"; exit 2; }

# УНИВЕРСУМ — МУТАНТЫ ИСПЫТАНИЯ, А НЕ ВСЯКАЯ ПРАВКА ПОДСТРОКОЙ. Тест, который строит
# фикстуру через `.replace(`, портит файл, созданный им самим: обезвреживать там нечего, и
# счёт по «правит подстрокой» дал бы 18 при классе в 9. Разделитель назван и измерен
# 14 сентября 2026: из десяти тестов с иглой-литералом девять строят фикстуру, один несёт
# гейт применения. Мутанта узнаём по ГЕЙТУ — словам отказа при отсутствии места мутации.
GATE='нет места мутации|мутант не соб|мутант не примен'
TESTS=$(grep -lE "$GATE" hooks/tests/test_*.sh 2>/dev/null)
[ -n "$TESTS" ] || { echo "BROKEN: мутирующих тестов с гейтом применения не найдено"; exit 2; }

TOTAL=0
VACUOUS=0
NAMES=""
while IFS= read -r t; do
    [ -n "$t" ] || continue
    TOTAL=$((TOTAL + 1))
    # ИМЯ ПРОБЫ УНИКАЛЬНО ПО ПРОЦЕССУ. Файл ложится в ЖИВОЙ каталог тестов (иначе уедет
    # `dirname $0` и тест не найдёт своих фикстур), а сессий в репозитории бывает несколько:
    # общее имя — общее состояние без замка, род H. Номер процесса разводит прогоны.
    probe="$(dirname "$t")/.probe_$$_$(basename "$t")"
    python3 - "$t" "$probe" <<'PYNEEDLE' || { rm -f "$probe"; continue; }
import re, sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src, encoding="utf-8").read()
s2 = re.sub(r"needle = '[^']*'", "needle = 'ZZZ_NET_TAKOGO_MESTA'", s, count=1)
if s2 == s:
    # ВТОРАЯ ФОРМА: игла стоит литералом прямо в вызове замены. Обезвреживаем первый
    # аргумент — тот, который ищут в файле. Форма найдена осмотром десяти тестов, где
    # переменной `needle` нет (14 сентября 2026).
    s2 = re.sub(r"\.replace\((['\"])(?:(?!\1).){4,}?\1", ".replace('ZZZ_NET_TAKOGO_MESTA'", s, count=1)
if s2 == s:
    sys.exit(1)
open(dst, "w", encoding="utf-8").write(s2)
PYNEEDLE
    if [ -f "$probe" ]; then
        bash "$probe" >/dev/null 2>&1
        rc=$?
        rm -f "$probe"
        if [ "$rc" -eq 0 ]; then
            VACUOUS=$((VACUOUS + 1))
            NAMES="${NAMES}${NAMES:+ }$(basename "$t")"
        fi
    fi
done <<EOF
$TESTS
EOF

echo "мутантов испытания (гейт применения есть): $TOTAL; вакуумных (не заметили, что мутировать нечего): $VACUOUS"
[ "$VACUOUS" -eq 0 ] || echo "  вакуумные: $NAMES"
[ "$VACUOUS" -eq 0 ]
