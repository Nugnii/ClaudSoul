#!/usr/bin/env bash
# critic-rounds-before-publish.sh — доля необратимых публикаций, которым предшествовал раунд свежего критика.
#
# Результат: у каждой публикации в журнале есть свидетельство раунда свежего критика — тесты атак
#            hooks/tests/test_adv*, добавленные коммитами после предыдущей публикации; публикаций
#            с записанным пропуском (--no-critic) или без свидетельства ноль
# Проверка результата: bash scripts/critic-rounds-before-publish.sh даёт 0, когда раунд есть у каждой
#            публикации журнала; 1 — есть публикации без раунда (названы); 2 — журнала публикаций нет
#            либо нечем читать
#
# Зачем (D331). Правило `pattern-multi-round-adversarial-review` (confidence 4) не исполнялось ни
# разу за 35 необратимых публикаций (замер 6 сентября 2026 по расшифровкам: 9 сессий, 0 раундов).
# Исполнитель — гейт `publish-public.sh`: перед --push он требует свидетельство раунда и пишет
# журнал `state/publications.jsonl` (одна строка на публикацию: критик `rounds` со счётом тестов
# атак либо `skipped`). Этот замер читает журнал и называет долю числом.
#
# ПОЧЕМУ СВИДЕТЕЛЬСТВО — ФАЙЛЫ, А НЕ ВЫЗОВ. D331 исключил зачёт любого вызова критика в той же
# сессии: знание требует свежего контекста. Тесты атак пишет субагент скилла `/adversary` в чистом
# контексте — свежесть встроена в артефакт и остаётся в дереве навсегда. Названный предел: тест
# `test_adv*`, написанный рукой, признак не отличит от теста субагента. Условие снятия: появится
# журнал вызовов Agent с промптом противника (хук на PreToolUse[Agent]) — тогда свидетельством
# станет сам вызов, а файлы — его подтверждением.
#
# ПРЕДМЕТА НЕТ — код 2, а не зелёное: 35 публикаций до 13 сентября 2026 журнала не имели и в
# долю не входят; пока журнал пуст, замер честно говорит «не измерено».
set -uo pipefail
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
J="${PUBLICATIONS_JOURNAL:-$STATE/publications.jsonl}"
command -v jq >/dev/null 2>&1 || { echo "critic-rounds-before-publish: нужен jq — не измерено" >&2; exit 2; }
[ -s "$J" ] || { echo "ПРЕДМЕТА НЕТ: журнала публикаций нет или он пуст ($J) — его заводит первая публикация publish-public.sh --push"; exit 2; }

N=$(grep -c . "$J" || true)
WITH=$(jq -c 'select((.critic // "") == "rounds" and ((.evidence // 0) | tonumber) >= 1)' "$J" 2>/dev/null | grep -c . || true)
PARSED=$(jq -c '.' "$J" 2>/dev/null | grep -c . || true)
BROKEN=$(( N - PARSED ))
WITHOUT=$(( PARSED - WITH ))
pct=0; [ "$N" -gt 0 ] && pct=$(( WITH * 100 / N ))
# Поле `suite` читается ЗДЕСЬ ЖЕ, а не заводится про запас: запись без читателя — род G,
# и прибор родов поймал её в час, когда поле появилось. Прогон набора по снимку — вторая
# половина того же вопроса «что проверили перед необратимым действием», поэтому владелец
# счёта один. Строки без поля (публикации до 15 сентября 2026) считаются отдельно: «поля не
# было» и «набор пропущен» — разные вещи, и валить их в одно значило бы завести род G заново.
SUITE_RUN=$(jq -c 'select((.suite // "") == "run")' "$J" 2>/dev/null | grep -c . || true)
SUITE_SKIP=$(jq -c 'select((.suite // "") == "skipped")' "$J" 2>/dev/null | grep -c . || true)
SUITE_NONE=$(jq -c 'select((.suite // "") == "")' "$J" 2>/dev/null | grep -c . || true)
echo "публикаций в журнале: ${N}; с раундом свежего критика: ${WITH} (${pct}%); без раунда: ${WITHOUT}; битых строк: ${BROKEN}"
echo "  набор по снимку: прогнан ${SUITE_RUN}; пропущен осознанно ${SUITE_SKIP}; поля не было ${SUITE_NONE}"
if [ "$WITHOUT" -gt 0 ] || [ "$BROKEN" -gt 0 ]; then
    [ "$WITHOUT" -gt 0 ] && {
        echo "  без раунда (ts · тег · критик · свидетельство):"
        jq -r 'select(((.critic // "") != "rounds") or (((.evidence // 0) | tonumber) < 1)) | "    · \(.ts // "?") · \(.tag // "?") · \(.critic // "?") · \(.evidence // 0)"' "$J" 2>/dev/null
    }
    [ "$BROKEN" -gt 0 ] && echo "  битых строк журнала: ${BROKEN} — не «без раунда», а нечитаемо"
    echo "[замер: находки, не сбой]"
    exit 1
fi
exit 0
