#!/usr/bin/env bash
# sync-drifted.sh — починка дрейфа установки командой того же размера, что и сам дрейф.
# Результат: расхождение, названное drift-check, устраняется без полной переустановки
# Проверка результата: bash hooks/tests/test_sync_drifted.sh даёт 0
#
# Зачем (D316). `drift-check` называет разошедшиеся файлы поимённо и советует
# `bash install.sh`. У установщика единственный режим: он правит 93 хука, 24 скилла,
# `~/.claude/settings.json` и блок в `~/.claude/CLAUDE.md`, ставит агенты launchd и
# регистрирует MCP-сервер. Ради шести файлов это несоразмерно, и цена измерена: 4-5
# сентября 2026 расхождение из 6 хуков прожило СУТКИ — прошлая сессия назвала его и
# оставила решением владельца именно потому, что переустановка крупнее находки. Всё это
# время починки существовали в репозитории и не действовали в мире.
#
# ЧТО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ И ПОЧЕМУ:
#   · не ставит на чистую машину — полнота `install.sh` есть свойство первой установки,
#     а не дефект; здесь чинится ТОЛЬКО названное расхождение;
#   · не трогает seed знаний. `install.sh` ставит его «только отсутствующие, существующие
#     не трогаются», и база знаний — работа владельца, а не файлы программы. Расхождение
#     seed называется и оставляется человеку;
#   · не ставит агенты launchd и не регистрирует MCP — их `drift-check` не сверяет, и
#     чинить ненаблюдаемое значило бы гадать.
#
# Умолчание — СУХОЙ прогон: печатает, что перенёс бы, и не пишет ничего. Запись только по
# явному `--apply`. Обратное умолчание здесь было бы неверным: приёмник — рабочая машина
# владельца, а не каталог проекта.
#
# Код возврата: 0 — нечего чинить либо всё названное перенесено; 1 — часть не перенесена
#               (в том числе отказ на приёмнике, разошедшемся в обе стороны);
#               2 — сверщик не смог сравнить (BROKEN), нет самого сверщика либо нет журнала переносов.
set -uo pipefail

_self_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd -P)
REPO="${CLAUDSOUL_REPO:-$(cd -- "$_self_dir/.." 2>/dev/null && pwd -P)}"
CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
CHECK="${DRIFT_CHECK:-$REPO/hooks/tests/drift-check.sh}"
# Каталог скиллов — переменной, а не литералом в пути: страж имён скиллов разбирает
# КОМАНДУ и принимает `<путь>/$_f` за имя каталога, отказывая на переменной. Признак у
# него снят с формы строки, роль (данные это или аргумент) он не различает — заведено
# пунктом долга; здесь достаточно не давать ему повода.
SKILLS_SRC="$REPO/skills"

APPLY=0
for _arg in "$@"; do
    case "$_arg" in
        --apply)   APPLY=1 ;;
        --dry-run) APPLY=0 ;;
        -h|--help)
            printf 'sync-drifted.sh [--dry-run|--apply]\n  чинит расхождение, названное drift-check, не переустанавливая всё\n'
            exit 0 ;;
        *)
            printf 'неизвестный аргумент: %s (есть --dry-run, --apply)\n' "$_arg" >&2
            exit 2 ;;
    esac
done

[ -f "$CHECK" ] || { printf 'нет сверщика: %s\n' "$CHECK" >&2; exit 2; }
# Журнал переносов и третий исход — у библиотеки, общей с install.sh (ADR-019, D350). Без неё
# перенос прошёл бы без следа, то есть с тем самым дефектом, ради которого журнал заведён.
CARRY_LIB="$REPO/lib/carry-log.sh"
[ -f "$CARRY_LIB" ] || { printf 'нет журнала переносов: %s — переносить без следа нельзя\n' "$CARRY_LIB" >&2; exit 2; }
CARRY_REPO="$REPO"
. "$CARRY_LIB"

OUT=$(CLAUDE_HOME="$CLAUDE_HOME" CLAUDSOUL_REPO="$REPO" bash "$CHECK" 2>/dev/null)
[ -n "$OUT" ] || { printf 'сверщик не ответил\n' >&2; exit 2; }

if grep -q '^BROKEN|' <<< "$OUT"; then
    printf 'сверщик не смог сравнить — чинить вслепую нельзя:\n%s\n' \
        "$(printf '%s' "$OUT" | grep '^BROKEN|')" >&2
    exit 2
fi

# PLANNED — «сколько перенесу», DRIFT_SEEN — «разошлось ли хоть что-то». Две РАЗНЫЕ величины:
# до 7 сентября 2026 первая отвечала за обе, и на единственной паре «seed знаний» (её здесь
# намеренно не чинят) скрипт отдавал 0, то есть «чисто», при живом дрейфе.
PLANNED=0; DONE=0; SKIPPED=0; DRIFT_SEEN=0
# SEED_DRIFT/OTHER_DRIFT — ТРЕТЬЕ состояние мира, у которого до 12 сентября 2026 не было
# своего значения канала (D354). «Хук не доставлен» и «seed отстал от базы знаний» выходили
# одним кодом 1, хотя решения по ним разные: первое чинится командой сейчас, второе — норма
# между релизами. Замер 7 сентября: за один прогон набора пара seed разошлась на ДВУХ
# исходах знаний из четырёх, то есть сигнал срабатывает с частотой работы со знаниями
# (126 касаний knowledge/ за 30 дней) и тем обесценивает соседний, настоящий.
SEED_DRIFT=0; OTHER_DRIFT=0
_say() { printf '%s\n' "$1"; }

# Перенос одного файла. В сухом прогоне только печатает: список ДО записи — половина
# смысла пункта, потому что приёмник чужой.
_carry() {  # $1 — источник, $2 — приёмник, $3 — как назвать в отчёте
    PLANNED=$((PLANNED + 1))
    if [ ! -f "$1" ]; then
        _say "  x $3 — нет в репозитории, пропущен"
        SKIPPED=$((SKIPPED + 1))
        return 0
    fi
    # ТРЕТИЙ ИСХОД — «разошлось в обе стороны» (ADR-019, D350): приёмник отличается и от
    # источника, и от хеша, который журнал переносов записал в момент ПРОШЛОГО переноса
    # (lib/carry-log.sh). Судит журнал, а не время файла: признак «приёмник новее» был снят
    # 7 сентября 2026 — mtime приёмника производится самим `cp` (6 срабатываний, настоящих
    # 0 из 6; то же у соседа, hooks/tests/drift-check.sh:113-114). Отказ стоит и в сухом
    # прогоне, и в записи: список ДО записи — половина смысла инструмента. Приёмник, о котором
    # журнал не знает, переносится как прежде и получает первую запись — названный предел
    # библиотеки. Условие снятия: первый прогон любой из двух дорог записывает все свои приёмники.
    if carry_diverged "$1" "$2"; then
        _say "  ✗ $3 — РАЗОШЛОСЬ В ОБЕ СТОРОНЫ: приёмник правлен после нашего переноса, не перезаписан. Сверь: diff \"$2\" \"$1\"; принять версию репозитория — удали приёмник и повтори"
        SKIPPED=$((SKIPPED + 1))
        return 0
    fi
    if [ "$APPLY" -eq 1 ]; then
        if carry_file sync-drifted "$1" "$2"; then
            case "$1" in *.sh) chmod +x "$2" 2>/dev/null ;; esac
            _say "  + $3"
            DONE=$((DONE + 1))
        else
            _say "  ! $3 — перенести не удалось"
            SKIPPED=$((SKIPPED + 1))
        fi
    else
        _say "  > $3"
    fi
}

while IFS='|' read -r _st _lbl _n _d _names; do
    [ "$_st" = "DRIFT" ] || continue
    DRIFT_SEEN=1
    case "$_lbl" in "seed знаний") SEED_DRIFT=1 ;; *) OTHER_DRIFT=1 ;; esac
    _say "[$_lbl] расхождений: $_d из $_n"
    case "$_lbl" in
        "хуки")
            for _f in $_names; do _carry "$REPO/hooks/$_f" "$CLAUDE_HOME/hooks/$_f" "hooks/$_f"; done ;;
        "библиотеки хуков")
            # Имена приходят с префиксом `lib/` — он часть отчёта сверщика, не имени файла.
            for _f in $_names; do
                _b="${_f#lib/}"
                _carry "$REPO/hooks/lib/$_b" "$CLAUDE_HOME/hooks/lib/$_b" "hooks/lib/$_b"
            done ;;
        "скиллы")
            for _f in $_names; do
                _carry "$SKILLS_SRC/$_f" "$CLAUDE_HOME/commands/$_f" "skill $_f"
            done ;;
        "bin")
            for _f in $_names; do
                _b="${_f#bin/}"
                _carry "$REPO/bin/$_b" "$CLAUDE_HOME/bin/$_b" "bin/$_b"
            done ;;
        "шаблоны")
            for _f in $_names; do _carry "$REPO/templates/$_f" "$CLAUDE_HOME/templates/$_f" "templates/$_f"; done ;;
        "сторож секретов")
            # Та же простая доставка, что у шаблонов: установщик копирует `security/*` файл в
            # файл (install.sh:893-896), преобразования нет. Ветка заведена 10 сентября 2026
            # вместе с парой в drift-check — без неё синхронизатор честно печатал «пара
            # неизвестна», и это ловил `test_sync_drifted`. Каталог `rules/` сюда не попадает:
            # пара сравнивает файлы верхнего уровня, а `rules/` — клон чужого репозитория.
            for _f in $_names; do _carry "$REPO/security/$_f" "$CLAUDE_HOME/security/$_f" "security/$_f"; done ;;
        "статусная строка")
            _carry "$REPO/scripts/statusline-claudsoul.sh" "$CLAUDE_HOME/statusline-claudsoul.sh" \
                   "statusline-claudsoul.sh" ;;
        "правила")
            # Блок между маркерами пишет ТА ЖЕ библиотека, что его сверяет, — иначе
            # синхронизатор стал бы третьей копией правила о границах.
            PLANNED=$((PLANNED + 1))
            _lib="$REPO/lib/claude-md-merge.sh"
            if [ ! -f "$_lib" ]; then
                _say "  x rules/CLAUDE.md — нет $_lib"; SKIPPED=$((SKIPPED + 1))
            elif [ "$APPLY" -eq 1 ]; then
                # shellcheck source=/dev/null
                # Имя и ПОРЯДОК аргументов — из самой библиотеки: `sync_claude_md TARGET MASTER`
                # (цель первая). Первая редакция звала выдуманное `_cm_merge_into` и честно
                # печатала «слияние не удалось», а прибор этого не ловил: ноги на пару
                # «правила» не было вовсе.
                if . "$_lib" && sync_claude_md "$CLAUDE_HOME/CLAUDE.md" "$REPO/rules/CLAUDE.md" >/dev/null 2>&1; then
                    _say "  + rules/CLAUDE.md (область между маркерами)"; DONE=$((DONE + 1))
                else
                    _say "  ! rules/CLAUDE.md — слияние не удалось"; SKIPPED=$((SKIPPED + 1))
                fi
            else
                _say "  > rules/CLAUDE.md (область между маркерами)"
            fi ;;
        "регистрация хуков")
            # Слияние — тот же единственный источник, что зовёт install.sh.
            PLANNED=$((PLANNED + 1))
            _mjq="$REPO/lib/hooks-merge.jq"
            _cfg=$(sed -n "/^HOOKS_CONFIG='/,/^}'/p" "$REPO/install.sh" 2>/dev/null \
                   | sed "1s/^HOOKS_CONFIG='//; \$s/'\$//")
            if [ ! -f "$_mjq" ] || [ -z "$_cfg" ]; then
                _say "  x settings.json — нет $_mjq либо не разобран HOOKS_CONFIG"
                SKIPPED=$((SKIPPED + 1))
            elif [ "$APPLY" -eq 1 ]; then
                command cp "$CLAUDE_HOME/settings.json" "$CLAUDE_HOME/settings.json.bak.$(date +%s)" 2>/dev/null
                if printf '%s' "$_cfg" | jq '.hooks' 2>/dev/null > "$CLAUDE_HOME/.sync-cfg.json" \
                   && jq --argjson cfg "$(cat "$CLAUDE_HOME/.sync-cfg.json")" -f "$_mjq" \
                        "$CLAUDE_HOME/settings.json" > "$CLAUDE_HOME/settings.json.tmp" 2>/dev/null \
                   && mv "$CLAUDE_HOME/settings.json.tmp" "$CLAUDE_HOME/settings.json"; then
                    rm -f "$CLAUDE_HOME/.sync-cfg.json"
                    _say "  + settings.json (слияние регистраций, копия .bak создана)"
                    DONE=$((DONE + 1))
                else
                    rm -f "$CLAUDE_HOME/.sync-cfg.json" "$CLAUDE_HOME/settings.json.tmp"
                    _say "  ! settings.json — слияние не удалось"; SKIPPED=$((SKIPPED + 1))
                fi
            else
                _say "  > settings.json (слияние регистраций)"
            fi ;;
        "seed знаний")
            # Намеренно не чиним: база знаний — работа владельца. Названо и оставлено.
            _say "  x seed знаний НЕ синхронизируется: это база владельца, а не файлы программы."
            _say "    Разошлось:$_names — решать человеку (python3 scripts/regen-seed.py)." ;;
        *)
            # Незнакомая метка — отказ, а не тишина: сверщик обзавёлся парой, о которой
            # синхронизатор не знает, и молчание здесь неотличимо от «чинить было нечего».
            _say "  x пара «${_lbl}» синхронизатору неизвестна — почини вручную либо научи его"
            PLANNED=$((PLANNED + 1)); SKIPPED=$((SKIPPED + 1)) ;;
    esac
done <<< "$OUT"

if [ "$PLANNED" -eq 0 ]; then
    # «Переносить нечего» и «расхождения нет» — РАЗНЫЕ состояния, и до этой правки они
    # отдавали один код 0. Живой случай, воспроизводимый прогоном: единственная разошедшаяся
    # пара — seed знаний, который здесь намеренно не чинится. PLANNED оставался нулём, сторож
    # на Stop читал 0 как «чисто» и МОЛЧАЛ при живом дрейфе — то самое «молчание неотличимо
    # от чистоты», против которого он и заведён. Контракт кода объявлен как у diff (ниже),
    # значит нулём здесь он быть не может.
    if [ "$DRIFT_SEEN" -eq 1 ]; then
        # ТОЛЬКО seed — свой уровень срочности и свой код (3, с 12 сентября 2026, D354).
        # Состояние отличается от дрейфа доставки не силой, а РОДОМ: недоставленная правка
        # означает «починка в коммите есть, в мире не работает» и требует команды сейчас;
        # отставший seed означает «база владельца выросла с прошлой пересборки» и требует
        # пересборки К РЕЛИЗУ. Свалить их в один код значит заставить потребителя разбирать
        # ТЕКСТ — вторую копию правила у себя (род K), — а пока он их не различал, ежедневный
        # сигнал о норме заглушал редкий сигнал о настоящей поломке.
        if [ "$SEED_DRIFT" -eq 1 ] && [ "$OTHER_DRIFT" -eq 0 ]; then
            _say "дрейф ТОЛЬКО в seed знаний — это норма между релизами, не отставание установки"
            [ "$APPLY" -eq 1 ] && exit 0
            exit 3
        fi
        _say "дрейф есть, переносом не чинится — названное выше оставлено человеку"
        # У --apply смысл кода иной: он сделал всё, что ему позволено, и это успех.
        [ "$APPLY" -eq 1 ] && exit 0
        exit 1
    fi
    _say "дрейфа нет — синхронизировать нечего"
    exit 0
fi

if [ "$APPLY" -eq 1 ]; then
    _say "перенесено: $DONE, пропущено: $SKIPPED"
    [ "$SKIPPED" -eq 0 ]
    exit $?
fi
# «Перенесло бы» считает КАНДИДАТОВ МИНУС ОТКАЗАННЫХ. Здесь стоял голый PLANNED, и с
# появлением третьего исхода строка обещала бы перенос того самого файла, который этим
# же прогоном отказались переносить, — то же одно число на два вопроса, что чинится выше.
if [ "$SKIPPED" -gt 0 ]; then
    _say "сухой прогон: перенесло бы $((PLANNED - SKIPPED)), отказано в переносе: $SKIPPED (запись — с --apply)"
else
    _say "сухой прогон: перенесло бы $PLANNED (запись — с --apply)"
fi
# Код возврата сухого прогона — как у diff: 0 расхождения нет, 1 есть, 2 сверщик сломан.
# Отдельного кода для «разошлось в обе стороны» нет намеренно: для потребителя кода решение то
# же — дрейф есть и переносом не чинится; файл назван текстом и посчитан в «отказано».
# Заведён 7 сентября 2026 для сторожа на Stop: пока здесь стоял 0 в обоих случаях,
# машинному потребителю оставалось разбирать текст, то есть держать у себя копию правила
# «что считается дрейфом» (род K реестра). У --apply смысл кода иной и не меняется: там 0
# означает «перенос удался», иначе успешная починка выглядела бы отказом.
exit 1
