#!/usr/bin/env bash
# outcome-share.sh — доля срабатываний гейта разбора, за которыми последовал исход.
#
# Результат: по каждому сроду повода названо число срабатываний и доля с исходом,
#            отличным от `none` — «страж сработал» и «страж помог» перестают быть
#            одним утверждением
# Проверка результата: bash scripts/outcome-share.sh печатает строку по каждому сроду и
#            даёт 0, когда журналов нет или у всех сродов доля исходов не ниже порога
#
# Зачем (D112). Журнал стража писал СРАБАТЫВАНИЯ и не писал ИСХОДЫ: слепое пятно накрывало
# 205 правок из 315 (65%). Замер 28 августа 2026: из 19 случаев «знание было уместно и не
# применено» минимум в 9 знание находилось в контексте В МОМЕНТ ДЕЙСТВИЯ — то есть
# напоминание читалось и не меняло действия. Считать надо долю изменённых действий, а не
# срабатывания.
#
# ЧТО РЕШАЕТ ЭТО ЧИСЛО. Доля `none` выше половины при доле ложных ниже десятой части — повод
# поднять сроду уровень принуждения (лестница: инжект → инжект с журналом → блок завершения
# хода → отказ). Доля ложных выше четверти — повод СУЗИТЬ признак, а не поднимать уровень
# (case-2026-08-28-enforcement-is-a-property-of-consequence: 40 отказов, из них 32 ложных).
# Решение принимает владелец; скрипт даёт число и называет, чего оно требует.
#
# ОКНО СЧИТАЕТСЯ В СЕССИЯХ, А НЕ В ДНЯХ. Ритм работы неравномерный: двенадцать сессий за
# сутки и полгода тишины — одинаково нормальны. Календарное окно в первом случае считает
# двенадцатую часть работы, во втором — ноль, и оба раза врёт.
#
# СЛЕД РАЗБОРА (D211). Записи с полем `trace` (rc_trace) дают второе число: долю поводов,
# где разбор оставил проверяемые формы доктрины — а не только долю с записанным исходом.
# Формула «след есть» та же, что rc_chain_spoken в root-cause-lib (единственное определение;
# test_outcome_journal сверяет обе на одном наборе). Находка: записей со следом ≥ MIN_N и
# доля ниже базы — «доктрина держится текстом, а текст не исполняется». База 13% — доля ходов
# с цепочкой по корпусу 33 расшифровок на 30 августа 2026 (замерено реплеем, не назначено).
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${OUTCOME_SHARE_SESSIONS:-20}"      # сколько последних сессий берём
MIN_N="${OUTCOME_SHARE_MIN_N:-20}"            # порог знаменателя: меньше — вывод «мало данных»
TRACE_BASE="${OUTCOME_SHARE_TRACE_BASE:-13}"  # база доли со следом, % (корпус 30.08.2026)
command -v jq >/dev/null 2>&1 || { echo "нет jq"; exit 0; }

# Последние N журналов исходов по времени изменения — по одному на сессию.
# Список держится массивом, а не строкой: каталог состояния задаётся извне (STATE_DIR) и
# может лежать по пути с пробелом — неквотированное расширение строки порвало бы путь на
# части, и замер молча считал бы ноль. Тот же дефект в тот же час нашёлся у
# `backlog-touch-check.sh`: живой путь проекта содержит пробел («My Project»).
FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/outcome-*.jsonl 2>/dev/null | head -n "$SESSIONS")
EOF
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "журналов исходов нет: контур ещё не наработал данных (STATE=$STATE)"
    exit 0
fi

N_SESSIONS=${#FILES[@]}
echo "Доля исходов по сродам поводов (последние $N_SESSIONS сессий, порог знаменателя $MIN_N):"

# Знаменатель — ВСЕ записанные исходы срода, включая успехи стража (`chain-spoken` —
# цепочка произнесена) и отложенные правки (`deferred` — отказ не выполнил вызов). Без них
# в счёт шли бы только неудачи, и доля «без исхода» была бы завышена по построению.
# «след есть» — та же формула, что rc_chain_spoken (root-cause-lib.sh): слово «почему» ≥ 3,
# либо два заголовка шаблона, либо три «←», либо реестр мест (два адреса, дробь N<M, корень).
JQ_CHAIN='def chain(t): t != null and (
    (t.why // 0) >= 3 or (t.heads // 0) >= 2 or (t.arrows // 0) >= 3
    or ((t.addr // 0) >= 2 and (t.frac // 0) >= 1 and (t.roots // 0) >= 1));'
REPORT=$(jq -rs --argjson minn "$MIN_N" "$JQ_CHAIN"'
    group_by(.signal)
    | map({
        signal: .[0].signal,
        n: length,
        none: (map(select(.outcome == "none")) | length),
        disproved: (map(select(.outcome == "disproved")) | length),
        traced: (map(select(.trace != null)) | length),
        chained: (map(select(chain(.trace))) | length)
      })
    | map(. + {
        share_none: (if .n > 0 then (.none * 100 / .n | floor) else 0 end),
        share_false: (if .n > 0 then (.disproved * 100 / .n | floor) else 0 end),
        share_trace: (if .traced > 0 then (.chained * 100 / .traced | floor) else null end)
      })
    | sort_by(-.n)
    | .[]
    | "  \(.signal): срабатываний \(.n), без исхода \(.share_none)%, ложных \(.share_false)%"
      + (if .share_trace == null then ", след не записан"
         else ", след разбора \(.share_trace)% (\(.chained) из \(.traced))" end)
      + (if .n < $minn then "  — мало данных, решения не принимаются"
         elif .share_false > 25 then "  — СУЗИТЬ признак: ложных больше четверти"
         elif .share_none > 50 then "  — поднять уровень: читается и не меняет действий"
         else "  — уровень соответствует" end)
' "${FILES[@]}" 2>/dev/null)
printf '%s\n' "$REPORT"

# Итог по следу — одной строкой на все сроды: доля поводов, где разбор оставил формы доктрины.
TRACE_LINE=$(jq -rs --argjson base "$TRACE_BASE" "$JQ_CHAIN"'
    (map(select(.trace != null)) | length) as $tr
    | (map(select(chain(.trace))) | length) as $ch
    | (map(select(.trace != null and (.trace.addr // 0) >= 2 and (.trace.frac // 0) >= 1)) | length) as $reg
    | if $tr == 0 then "поводов со следом: след ещё не записывался (поле trace появилось 30.08.2026)"
      else "поводов со следом: \($ch) из \($tr) (\($ch * 100 / $tr | floor)%; реестр мест с дробью — \($reg); база корпуса 30.08: \($base)%)" end
' "${FILES[@]}" 2>/dev/null)
printf '%s\n' "$TRACE_LINE"

# Находка сообщается КОДОМ ВОЗВРАТА, а не только текстом: `measurement-due.sh` различает
# «находок нет» и «есть» именно по коду (0/1), а вывод замера глушит. До 29 августа 2026
# здесь стоял безусловный `exit 0` — замер печатал вердикт «поднять уровень», и реестр
# замеров об этом никогда не узнавал. Тот же род, что и дыра, ради которой замер заведён:
# предмет инструмента был задан его выводом, а не состоянием мира.
#
# Число находок считает jq по тем же данным, а не grep по человеческому тексту: маркер для
# машины обязан быть машинным. Иначе перевод строки вердикта на другой язык или правка
# формулировки молча выключают код возврата — признак, стоящий на форме чужого текста.
FINDINGS=$(jq -rs --argjson minn "$MIN_N" --argjson base "$TRACE_BASE" "$JQ_CHAIN"'
    (group_by(.signal)
     | map({n: length,
            none: (map(select(.outcome == "none")) | length),
            disproved: (map(select(.outcome == "disproved")) | length)})
     | map(select(.n >= $minn
                  and ((.disproved * 100 / .n) > 25 or (.none * 100 / .n) > 50)))
     | length) as $levels
    # Находка по следу — одна на все сроды: записей со следом не меньше порога знаменателя,
    # а доля с цепочкой ниже базы корпуса. До порога — печать без кода.
    | (map(select(.trace != null)) | length) as $tr
    | (map(select(chain(.trace))) | length) as $ch
    | $levels + (if $tr >= $minn and ($ch * 100 / $tr) < $base then 1 else 0 end)
' "${FILES[@]}" 2>/dev/null)
case "${FINDINGS:-}" in ''|*[!0-9]*) FINDINGS=0 ;; esac

# [замер: находки, не сбой] — метка для error-tracker: ненулевой код здесь не провал.
if [ "$FINDINGS" -gt 0 ]; then
    echo "[замер: находки, не сбой] решений к принятию: $FINDINGS — см. строки выше (уровень срода либо след разбора ниже базы)"
    exit 1
fi
exit 0
