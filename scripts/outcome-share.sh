#!/usr/bin/env bash
# outcome-share.sh — доля срабатываний гейта разбора, за которыми последовал исход.
#
# Результат: по каждому сроду повода названо число срабатываний и доля с исходом,
#            отличным от `none` — «страж сработал» и «страж помог» перестают быть
#            одним утверждением
# Проверка результата: bash scripts/outcome-share.sh печатает строку по каждому сроду и
#            даёт 0, когда журналов нет или у всех сродов доля исходов не ниже порога
#
# Зачем (D112). Журнал стража писал СРАБАТЫВАНИЯ и не писал ИСХОДЫ: слепое пятно накрывало
# 205 правок из 315 (65%). Замер 28 августа 2026: из 19 случаев «знание было уместно и не
# применено» минимум в 9 знание находилось в контексте В МОМЕНТ ДЕЙСТВИЯ — то есть
# напоминание читалось и не меняло действия. Считать надо долю изменённых действий, а не
# срабатывания.
#
# ЧТО РЕШАЕТ ЭТО ЧИСЛО. Доля `none` выше половины при доле ложных ниже десятой части — повод
# поднять сроду уровень принуждения (лестница: инжект → инжект с журналом → блок завершения
# хода → отказ). Доля ложных выше четверти — повод СУЗИТЬ признак, а не поднимать уровень
# (case-2026-08-28-enforcement-is-a-property-of-consequence: 40 отказов, из них 32 ложных).
# Решение принимает владелец; скрипт даёт число и называет, чего оно требует.
#
# ОКНО СЧИТАЕТСЯ В СЕССИЯХ, А НЕ В ДНЯХ. Ритм работы неравномерный: двенадцать сессий за
# сутки и полгода тишины — одинаково нормальны. Календарное окно в первом случае считает
# двенадцатую часть работы, во втором — ноль, и оба раза врёт.
#
# СЛЕД РАЗБОРА (D211). Записи с полем `trace` (rc_trace) дают второе число: долю поводов,
# где разбор оставил проверяемые формы доктрины — а не только долю с записанным исходом.
# Формула «след есть» та же, что rc_chain_spoken в root-cause-lib (единственное определение;
# test_outcome_journal сверяет обе на одном наборе). Находка: записей со следом ≥ MIN_N и
# доля ниже базы — «доктрина держится текстом, а текст не исполняется». База 13% — доля ходов
# с цепочкой по корпусу 33 расшифровок на 30 августа 2026 (замерено реплеем, не назначено).
set -uo pipefail

# РЕЖИМ. Без аргумента — человеческий отчёт (как прежде). `--gate-chain-share` печатает
# ОДНО число: долю поводов нынешнего гейта, где разбор оставил формы доктрины. Заведён
# 13 сентября 2026 для «Проверки» D358, которая до того считала ту же долю СВОИМ `cat` по
# всем журналам — вторая реализация мимо владельца формулы (род K), и расходилась с ним
# дважды: окном (все 64 журнала против последних 20 сессий) и знаменателем.
MODE=""
EXCLUDE_NEWEST=0
for _arg in "$@"; do
    case "$_arg" in
        --gate-chain-share) MODE="gate-chain-share" ;;
        # `--exclude-newest` — условие ЗАКРЫТИЯ, а не показания (решение владельца
        # 13 сентября 2026). Замер того дня: показание дошло до 30 при пороге 30, но без
        # журнала той самой сессии, которая собиралась закрывать пункт, оно равнялось 29 —
        # переход через порог держался на 8 поводах со следом и 5 цепочках этой сессии
        # (62% против средних). Закрытие по данным, которые произвёл сам закрывающий,
        # воскресает в ближайшую тихую сессию, а воскресшее закрытие — отдельный повод
        # разбора. Самый свежий журнал и есть журнал текущей сессии: он пишется прямо
        # сейчас. Названный предел: при ручном прогоне много позже самым свежим окажется
        # чужой журнал, и тогда флаг просто отбрасывает одну сессию — сторона осторожная.
        # Условие снятия: в рамке прогона появится идентификатор текущей сессии
        # (`CLAUDE_CODE_SESSION_ID` виден хукам, но не ручному вызову) — тогда исключать
        # можно будет ИМЕННО её журнал по имени, а не самый свежий по времени правки.
        --exclude-newest) EXCLUDE_NEWEST=1 ;;
        "") ;;
        *) echo "outcome-share: неизвестный аргумент: $_arg (есть --gate-chain-share и --exclude-newest)" >&2; exit 2 ;;
    esac
done

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${OUTCOME_SHARE_SESSIONS:-20}"      # сколько последних сессий берём
MIN_N="${OUTCOME_SHARE_MIN_N:-20}"            # порог знаменателя: меньше — вывод «мало данных»
TRACE_BASE="${OUTCOME_SHARE_TRACE_BASE:-13}"  # база доли со следом, % (корпус 30.08.2026)
command -v jq >/dev/null 2>&1 || { echo "outcome-share: нет jq — не измерено"; exit 2; }

# Последние N журналов исходов по времени изменения — по одному на сессию.
# Список держится массивом, а не строкой: каталог состояния задаётся извне (STATE_DIR) и
# может лежать по пути с пробелом — неквотированное расширение строки порвало бы путь на
# части, и замер молча считал бы ноль. Тот же дефект в тот же час нашёлся у
# `backlog-touch-check.sh`: живой путь проекта содержит пробел («My Project»).
FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/outcome-*.jsonl 2>/dev/null | { [ "$EXCLUDE_NEWEST" = "1" ] && tail -n +2 || cat; } | head -n "$SESSIONS")
EOF
if [ "${#FILES[@]}" -eq 0 ]; then
    # В машинном режиме пустота — НЕ ИЗМЕРЕНО (код 2), а не зелёное: потребитель числа
    # обязан отличить «доля ниже порога» от «считать было нечего».
    [ "$MODE" = "gate-chain-share" ] && { echo "outcome-share: журналов исходов нет (STATE=$STATE)" >&2; exit 2; }
    echo "журналов исходов нет: контур ещё не наработал данных (STATE=$STATE)"
    exit 0
fi

N_SESSIONS=${#FILES[@]}
# В машинном режиме человеческий заголовок не печатается: потребитель числа получил бы
# две строки, и `[ "$S" -ge 30 ]` сломался бы на первой. Поймано первым же прогоном режима.
[ "$MODE" = "gate-chain-share" ] || \
    echo "Доля исходов по сродам поводов (последние $N_SESSIONS сессий, порог знаменателя $MIN_N):"

# Знаменатель — ВСЕ записанные исходы срода, включая успехи стража (`chain-spoken` —
# цепочка произнесена) и отложенные правки (`deferred` — отказ не выполнил вызов). Без них
# в счёт шли бы только неудачи, и доля «без исхода» была бы завышена по построению.
# «след есть» — формула БЕРЁТСЯ У ВЛАДЕЛЬЦА (`RC_JQ_CHAIN` в hooks/root-cause-lib.sh), а не
# переписывается здесь. Своя копия жила тут до 9 сентября 2026 и разошлась с оригиналом на
# первой же правке критерия — род K реестра дефектов. Разрыв поймал страж
# `test_outcome_journal` T14d: «библиотека не признаёт след, который засчитал замер».
_OS_RC_LIB="${RC_LIB:-$(cd "$(dirname "$0")/../hooks" 2>/dev/null && pwd)/root-cause-lib.sh}"
[ -f "$_OS_RC_LIB" ] || _OS_RC_LIB="$HOME/.claude/hooks/root-cause-lib.sh"
if [ -f "$_OS_RC_LIB" ]; then
    # shellcheck source=/dev/null
    . "$_OS_RC_LIB"
fi
# Отсутствие источника — поломка, а не повод считать по своей редакции: молчаливый откат
# на копию вернул бы ровно тот дефект, ради которого правило вынесено.
[ -n "${RC_JQ_CHAIN:-}" ] || { echo "BROKEN: нет RC_JQ_CHAIN — источник формулы недоступен ($_OS_RC_LIB)" >&2; exit 2; }
JQ_CHAIN="$RC_JQ_CHAIN"

# ── Машинное число (D358) ────────────────────────────────────────────────────
# Предмет: доля поводов НЫНЕШНЕГО гейта, за которыми последовал разбор.
# · `daily` из счёта исключён — с 13 сентября 2026 он не сигнал гейта, а строка суточной
#   очереди; его записи в старых журналах говорят о ПРЕЖНЕМ приборе.
# · Знаменатель — записи СО СЛЕДОМ, а не все исходы. Запись без поля `trace` (журналы до
#   30 августа 2026) не судится вовсе, и считать её как «цепочки не было» значит красить
#   НЕ ИЗМЕРЕНО в красное — ровно то различение, на котором стоит корень R6.
# · Окно — общее с отчётом (OUTCOME_SHARE_SESSIONS сессий): периодичность в единицах
#   РАБОТЫ, а не календаря.
# ЕДИНИЦА ЗНАМЕНАТЕЛЯ — ПОВОД, А НЕ ХОД (D358, носитель 3, 14 сентября 2026).
# Шапка этого режима объявляет предметом «долю ПОВОДОВ», а считалось по записям, и запись
# пишется РАЗ В ХОД: повод, живущий всю сессию, попадал в знаменатель столько раз, сколько
# ходов прожил. Замер: 162 записи исхода `correction` от 11 отпечатков поправки — раздутие
# 14,7x, и у одной сессии 31 запись на одну поправку. Смещение однонаправленное: неразобранный
# долгий повод считается тридцать раз против тебя, разобранный — один раз за, поэтому доля
# становилась функцией ДЛИНЫ СЕССИИ, а не поведения. Числа на одном окне: по ходам 307 из 785,
# по поводам 210 из 353. Ни окно, ни порог, ни формула следа при этом не тронуты — сменилась
# только единица, и сменилась на ту, что объявлена в тексте самого прибора (род L).
# Отпечаток повода берётся у ВЛАДЕЛЬЦА — журнала гейта `five-whys-<SID>.seen`, где строка
# хода несёт `<срод>:<отпечаток>`; своей копии правила тут нет. Повод, отпечаток которого не
# нашёлся, считается по ходу (прежнее поведение) и НАЗЫВАЕТСЯ числом в поток ошибок: молчание
# тут было бы неотличимо от «все поводы опознаны».
ANNOT=$(python3 - "$STATE" "${FILES[@]}" <<'PYANN'
import json, sys, os, glob
state, files = sys.argv[1], sys.argv[2:]
subj = {}
for fp in glob.glob(os.path.join(glob.escape(state), "five-whys-*.seen")):
    sid = os.path.basename(fp)[len("five-whys-"):-len(".seen")]
    try: fh = open(fp, encoding="utf-8", errors="ignore")
    except OSError: continue
    with fh:
        for line in fh:
            if not line.startswith("turn:"): continue
            key, _, rest = line[len("turn:"):].partition("|")
            for part in rest.split("|"):
                if ":" in part:
                    sig, val = part.split(":", 1)
                    subj[(sid, key, sig)] = val.strip()
miss = 0
n_anon = 0
for fp in files:
    sid = os.path.basename(fp)[len("outcome-"):-len(".jsonl")]
    try: fh = open(fp, encoding="utf-8", errors="ignore")
    except OSError: continue
    with fh:
        for line in fh:
            try: r = json.loads(line)
            except Exception: continue
            sig = r.get("signal") or ""
            key = str(r.get("key", ""))
            s = subj.get((sid, key, sig)) if key else None
            if s is None:
                miss += 1
                # Запись БЕЗ ключа сгруппировать не с чем, и класть их в один повод значит
                # выдумать группировку: двадцать неразличимых записей схлопнулись бы в один
                # повод и уронили знаменатель ниже порога (поймано ногой D358 зелёной стороны
                # 14 сентября 2026). Поэтому безключевая запись — свой собственный повод.
                s = ("turn:" + key) if key else ("rec:%d" % n_anon)
                n_anon += 1
            r["_occasion"] = sid + "|" + sig + "|" + s
            print(json.dumps(r, ensure_ascii=False))
print(miss, file=sys.stderr)
PYANN
) || { echo "BROKEN: разметка поводов не состоялась" >&2; exit 2; }

if [ "$MODE" = "gate-chain-share" ]; then
    PAIR=$(printf '%s\n' "$ANNOT" | jq -rs --argjson m 3 "$JQ_CHAIN"'
        [.[] | select((.signal // "") != "daily" and .trace != null)]
        | group_by(._occasion) as $oc
        | [$oc[] | select(any(.[]; chain(.trace)))] as $ch
        | "\($ch | length) \($oc | length)"
    ' 2>/dev/null)
    # Пустой ответ — ОТКАЗ СЧЁТА, а не ноль: тот же род B, что у счёта находок ниже.
    case "$PAIR" in
        ''|*[!0-9\ ]*) echo "BROKEN: счёт доли не состоялся — jq не вернул пары чисел" >&2; exit 2 ;;
    esac
    CH=${PAIR%% *}; TR=${PAIR##* }
    if [ "${TR:-0}" -lt "$MIN_N" ]; then
        echo "outcome-share: записей со следом $TR при пороге знаменателя $MIN_N — НЕ ИЗМЕРЕНО" >&2
        exit 2
    fi
    echo $(( CH * 100 / TR ))
    exit 0
fi
# Отчёт считает СРАБАТЫВАНИЯ (ходы) — так и написано в его строке; рядом печатается число
# ПОВОДОВ, потому что читатель иначе примет одно за другое, а расходятся они в разы
# (14 сентября 2026: correction 117 срабатываний на 14 поводов).
REPORT=$(printf '%s\n' "$ANNOT" | jq -rs --argjson minn "$MIN_N" --argjson m 3 "$JQ_CHAIN"'
    group_by(.signal)
    | map({
        signal: .[0].signal,
        n: length,
        occ: ([.[]._occasion] | unique | length),
        none: (map(select(.outcome == "none")) | length),
        disproved: (map(select(.outcome == "disproved")) | length),
        traced: (map(select(.trace != null)) | length),
        chained: (map(select(chain(.trace))) | length)
      })
    | map(. + {
        share_none: (if .n > 0 then (.none * 100 / .n | floor) else 0 end),
        share_false: (if .n > 0 then (.disproved * 100 / .n | floor) else 0 end),
        share_trace: (if .traced > 0 then (.chained * 100 / .traced | floor) else null end)
      })
    | sort_by(-.n)
    | .[]
    | "  \(.signal): срабатываний \(.n) (поводов \(.occ)), без исхода \(.share_none)%, ложных \(.share_false)%"
      + (if .share_trace == null then ", след не записан"
         else ", след разбора \(.share_trace)% (\(.chained) из \(.traced))" end)
      + (if .n < $minn then "  — мало данных, решения не принимаются"
         elif .share_false > 25 then "  — СУЗИТЬ признак: ложных больше четверти"
         elif .share_none > 50 then "  — поднять уровень: читается и не меняет действий"
         else "  — уровень соответствует" end)
' 2>/dev/null)
printf '%s\n' "$REPORT"

# Итог по следу — одной строкой на все сроды: доля поводов, где разбор оставил формы доктрины.
# Итоговая строка говорит «поводов» — значит и считает ПОВОДЫ, а не записи. До 14 сентября
# 2026 она печатала «поводов со следом: 243 из 857» по записям, то есть по ходам: тот же
# разрыв между словом и предметом, что чинился в машинном режиме двумя экранами выше.
TRACE_LINE=$(printf '%s\n' "$ANNOT" | jq -rs --argjson base "$TRACE_BASE" --argjson m 3 "$JQ_CHAIN"'
    [.[] | select(.trace != null)] | group_by(._occasion) as $oc
    | ($oc | length) as $tr
    | ([$oc[] | select(any(.[]; chain(.trace)))] | length) as $ch
    | ([$oc[] | select(any(.[]; (.trace.addr // 0) >= 1 and (.trace.frac // 0) >= 1))] | length) as $reg
    | if $tr == 0 then "поводов со следом: след ещё не записывался (поле trace появилось 30.08.2026)"
      else "поводов со следом: \($ch) из \($tr) (\($ch * 100 / $tr | floor)%; реестр мест с дробью — \($reg); база корпуса 30.08: \($base)%)" end
' 2>/dev/null)
printf '%s\n' "$TRACE_LINE"

# Находка сообщается КОДОМ ВОЗВРАТА, а не только текстом: `measurement-due.sh` различает
# «находок нет» и «есть» именно по коду (0/1), а вывод замера глушит. До 29 августа 2026
# здесь стоял безусловный `exit 0` — замер печатал вердикт «поднять уровень», и реестр
# замеров об этом никогда не узнавал. Тот же род, что и дыра, ради которой замер заведён:
# предмет инструмента был задан его выводом, а не состоянием мира.
#
# Число находок считает jq по тем же данным, а не grep по человеческому тексту: маркер для
# машины обязан быть машинным. Иначе перевод строки вердикта на другой язык или правка
# формулировки молча выключают код возврата — признак, стоящий на форме чужого текста.
FINDINGS=$(jq -rs --argjson minn "$MIN_N" --argjson base "$TRACE_BASE" --argjson m 3 "$JQ_CHAIN"'
    (group_by(.signal)
     | map({n: length,
            none: (map(select(.outcome == "none")) | length),
            disproved: (map(select(.outcome == "disproved")) | length)})
     | map(select(.n >= $minn
                  and ((.disproved * 100 / .n) > 25 or (.none * 100 / .n) > 50)))
     | length) as $levels
    # Находка по следу — одна на все сроды: записей со следом не меньше порога знаменателя,
    # а доля с цепочкой ниже базы корпуса. До порога — печать без кода.
    | (map(select(.trace != null)) | length) as $tr
    | (map(select(chain(.trace))) | length) as $ch
    | $levels + (if $tr >= $minn and ($ch * 100 / $tr) < $base then 1 else 0 end)
' "${FILES[@]}" 2>/dev/null)
# Пустой ответ — ОТКАЗ СЧЁТА, а не «находок ноль». 9 сентября 2026 правка формулы
# передала порог в два вызова jq из трёх; третий падал на «$m is not defined», `2>/dev/null`
# глушил ошибку, FINDINGS пустел и молча становился нулём — то есть замер сообщал «всё в
# порядке» именно потому, что сломался. Род B реестра: отказ обязан быть виден.
# Нечисловой ответ (мусор) от пустого отличается: первый — данные не той формы, второй —
# счёт не состоялся; сваливать их в один ноль значит терять единственный признак поломки.
if [ -z "${FINDINGS:-}" ]; then
    echo "BROKEN: счёт находок не состоялся — jq не вернул числа (проверь аргументы формулы)" >&2
    exit 2
fi
case "$FINDINGS" in *[!0-9]*) FINDINGS=0 ;; esac

# [замер: находки, не сбой] — метка для error-tracker: ненулевой код здесь не провал.
if [ "$FINDINGS" -gt 0 ]; then
    echo "[замер: находки, не сбой] решений к принятию: $FINDINGS — см. строки выше (уровень срода либо след разбора ниже базы)"
    exit 1
fi
exit 0
