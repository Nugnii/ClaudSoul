#!/usr/bin/env bash
# dead-sensor-check.sh — признаки, молчащие за окно: сенсор мёртв или мир чист.
#
# Результат: назван список признаков, у которых за окно в N сессий ноль срабатываний, и
#            по каждому видно, чем это отличается от исправной тишины
# Проверка результата: bash scripts/dead-sensor-check.sh печатает список и даёт 1, когда
#            есть признаки без единого срабатывания при непустом состоянии
#
# Зачем (D204). Признак, не сработавший НИ РАЗУ, неотличим от исправного: он молчит, и
# молчание читается как «нарушений нет». Замер 29 августа 2026: `fix-level-check` за 33 дня
# накопления состояния не создал ни одного файла — и обнаружено это было ручным разбором,
# а не механизмом. В практике высоконадёжных организаций период БЕЗ отчётов сам по себе
# считается тревогой: либо сенсор мёртв, либо о находках молчат.
#
# ЧТО ЭТОТ СКРИПТ НЕ УТВЕРЖДАЕТ. Ноль срабатываний не доказывает поломку: мир мог быть
# чист. Скрипт даёт ЗНАМЕНАТЕЛЬ для решения, а не вердикт: рядом с молчащим признаком
# печатается, сколько сессий он прожил молча и сколько срабатываний у соседей за то же
# окно. Соседи с сотнями срабатываний при нуле у этого — вот что делает тишину подозрительной.
#
# ОКНО В СЕССИЯХ, А НЕ В ДНЯХ: ритм работы неравномерный, календарное окно врёт в обе стороны.
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
LESSONS="${LESSONS_DIR:-$HOME/.claude/global-lessons}"
SESSIONS="${DEAD_SENSOR_SESSIONS:-40}"
command -v jq >/dev/null 2>&1 || { echo "нет jq"; exit 0; }

# Все признаки, объявленные в знаниях: имя сигнала — единственный источник списка.
# Брать список из журналов нельзя по построению: молчащего признака там нет, и именно
# его мы ищем. Тот же класс, что искали в D112: предмет обязан быть шире наблюдений.
# META.md — описание формата, его примеры признаков ни в одном знании не живут: первый
# прогон (30 августа 2026) назвал молчащим `destructive_bash_on_shared_state`, который
# существует только как пример в схеме. Перечень берётся из знаний, а не из документа о них.
DECLARED=$(ls "$LESSONS"/*.md 2>/dev/null | grep -v '/META\.md$' | xargs grep -ho '"name"[[:space:]]*:[[:space:]]*"[a-z0-9_]*"' 2>/dev/null \
    | sed 's/.*"\([a-z0-9_]*\)"$/\1/' | sort -u)
if [ -z "$DECLARED" ]; then
    echo "объявленных признаков не найдено (LESSONS=$LESSONS)"
    exit 0
fi

FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/blocker-fired-*.jsonl 2>/dev/null | head -n "$SESSIONS")
EOF
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "журналов срабатываний нет: сравнивать не с чем (STATE=$STATE)"
    exit 0
fi

FIRED=$(jq -rs 'map(.signal // empty) | unique | .[]' "${FILES[@]}" 2>/dev/null)
TOTAL=$(jq -rs 'length' "${FILES[@]}" 2>/dev/null)
case "${TOTAL:-}" in ''|*[!0-9]*) TOTAL=0 ;; esac

echo "Молчащие признаки (окно ${#FILES[@]} сессий, всего срабатываний в окне: $TOTAL):"
SILENT=0
while IFS= read -r sig; do
    [ -n "$sig" ] || continue
    if ! grep -qxF "$sig" <<< "$FIRED"; then
        SILENT=$((SILENT + 1))
        echo "  · $sig — ни одного срабатывания"
    fi
done <<EOF
$DECLARED
EOF

if [ "$SILENT" -eq 0 ]; then
    echo "  молчащих нет: каждый объявленный признак сработал хотя бы раз"
    exit 0
fi
echo ""
echo "Это ЗНАМЕНАТЕЛЬ, а не вердикт: тишина может быть правдой о мире. Решение по каждому —"
echo "сузить признак, расширить его либо записать вердикт о невыразимости (пункт долга)."
echo "Способ проверить, жив ли признак, не дожидаясь срабатывания: реплей по корпусу —"
echo "образцы scripts/fix-level-replay.py и scripts/question-survival.py."
# [замер: находки, не сбой] — метка для error-tracker: ненулевой код здесь не провал.
exit 1
