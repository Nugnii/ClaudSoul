#!/usr/bin/env bash
# measurement-due.sh — у любого замера есть срок, и просроченный поднимается сам.
# Результат: просроченных замеров нет: каждый прогнан в свой срок
# Проверка результата: bash scripts/measurement-due.sh — «просроченных нет»
#
#
# Повод, названный собеседником дословно: «ну и толку что ты мерил, а пока я не сказал —
# не мерил? А если бы вообще не вспомнил? Всё что меряют должно дедлайн иметь».
#
# Он про конкретный случай: замер «становится ли знание инструментом» дал 1,4%, но случился
# только потому, что о нём спросили. Без вопроса не случился бы, и отсутствия никто бы не
# заметил — у измерения не было ни владельца, ни срока. Замер, который держится на чьей-то
# памяти, это не механизм, а намерение.
#
# Что делает: читает `scripts/measurements.tsv`, для каждой строки с ненулевым периодом
# сравнивает дату последнего прогона с сегодняшней и запускает просроченные. Дата прогона
# хранится отдельным файлом на замер, потому что содержимое отчётов у всех разное, а вот
# факт «прогонялось тогда-то» одинаков и должен читаться единообразно.
#
# Строки с периодом 0 перечислены намеренно: они запускаются по событию (Stop, launchd),
# в просрочку не попадают, но должны быть видны — иначе список замеров неполон, и по нему
# нельзя судить, что вообще меряется.
#
# Код возврата САМОГО скрипта: 0 — просроченных нет либо все отработали; 1 — есть замеры,
# которые не СМОГЛИ отработать. Находка замера отказом не считается — см. пояснение ниже.

set -uo pipefail

# Язык окружения для команд замеров (D1347, 21 ноября 2026). launchd даёт заданию один PATH — ни LANG, ни LC_*; в таком
# окружении оболочка меряет длину строки байтами, `grep -i` не сворачивает регистр кириллицы, класс `[^»]` читается
# побайтно, и свидетели, зелёные в любой сессии, приходили в отчёты замеров красными (три теста каждую ночь). Сессии
# Claude Code так не живут: язык настроен у каждой. Признак с одним последствием — язык не назван ВООБЩЕ; названный
# (в том числе `LC_ALL=C` рамки теста) не трогается. Значение — первое живое на машине: `C.UTF-8` (рамка CI и
# контейнера), иначе `en_US.UTF-8`; живое — то, под которым двухбайтовая буква считается одним знаком. Ни одно не
# живо — окружение остаётся прежним.
if [ -z "${LC_ALL:-}${LC_CTYPE:-}${LANG:-}" ]; then
    for _ml in C.UTF-8 en_US.UTF-8; do
        _mw=$( { LC_ALL=$_ml; _mx=$'\xd1\x8f'; printf '%s' "${#_mx}"; } 2>/dev/null )
        [ "$_mw" = 1 ] && { export LANG="$_ml"; break; }
    done
fi

REPO="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/.." 2>/dev/null && pwd -P)}"
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
# Подмена `mktemp` для команд реестра (`cmd_tmpdir_shim`, D1198) — у библиотеки сроков; её нет — замеры без подмены.
_TL="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/../hooks" 2>/dev/null && pwd)/timeout-lib.sh"
[ -f "$_TL" ] || _TL="$HOME/.claude/hooks/timeout-lib.sh"
# shellcheck source=/dev/null
[ -f "$_TL" ] && . "$_TL"
REGISTRY="${MEASUREMENT_REGISTRY:-$REPO/scripts/measurements.tsv}"
RUNS="$STATE/measurement-runs"

# Контур разбора: находка замера обязана стать ПОВОДОМ, а не строкой в выводе (10 сентября
# 2026). Разбор, который к этому привёл: все десять сродов повода ждут СОБЫТИЯ — правка
# случилась, команда упала, реплика пришла, — и ни один не имеет предметом ОТСУТСТВИЕ.
# Отсутствие не происходит, поэтому сигнала не рождает: приборы полноты (docs-inventory,
# guards-provable, drift-pairs-cover, docs-concepts-check) говорят, только когда их
# запускают, и их находка умирала в файле вывода. Здесь она превращается в событие мира —
# тот единственный вход, который контур умеет слушать.
# Библиотеки нет — замеры всё равно прогоняются: измерить и сказать в отчёте лучше, чем не мерить.
# Единица «прошедшего» берётся у ОДНОГО источника, а не считается здесь заново (D234).
# Библиотеки нет — ниже календарный фоллбек, тот же, что был до 10 сентября 2026.
FSRS_LIB="${FSRS_LIB:-$REPO/hooks/fsrs-lib.sh}"
[ -f "$FSRS_LIB" ] || FSRS_LIB="$HOME/.claude/hooks/fsrs-lib.sh"
# shellcheck source=/dev/null
[ -f "$FSRS_LIB" ] && . "$FSRS_LIB" 2>/dev/null || true

RC_LIB="${RC_LIB:-$REPO/hooks/root-cause-lib.sh}"
[ -f "$RC_LIB" ] || RC_LIB="$HOME/.claude/hooks/root-cause-lib.sh"
# shellcheck source=/dev/null
[ -f "$RC_LIB" ] && . "$RC_LIB" 2>/dev/null || true
MODE="${1:-run}"          # run — запускать просроченные; check — только назвать

# Режим сверяется с перечнем: неизвестное значение НЕ означает умолчание. До 1 сентября
# 2026 `MODE="${1:-run}"` не различал «не указан» и «указан неверно», и любой аргумент
# мимо перечня выполнял разрушительную ветку. Замер на фикстуре: из пяти написаний
# (`check`, `--check`, `--bogus`, пусто, `run`) перенос выполняли ЧЕТЫРЕ — то есть просьба
# проверить меняла файл. Имена режима у соседей разошлись (`check` у архиватора и
# measurement-due, `--check` у пересчётчика показаний и сверки чисел), поэтому принимаются
# оба написания, а всё прочее отбивается кодом 2.
case "$MODE" in
    run|--run)     MODE=run ;;
    check|--check) MODE=check ;;
    *) echo "применение: $(basename "$0") [run|check]" >&2; exit 2 ;;
esac

# ДВЕРЬ ВЛОЖЕННОСТИ (D321, 9 сентября 2026). Этот бегун исполняет ПРОИЗВОЛЬНЫЕ команды из
# реестра. Команда может дойти до Stop-хука, а `session-collector.sh:491` зовёт бегуна —
# кольцо «бегун → команда замера → session-collector → бегун». Сегодня кольца нет только
# потому, что вызов на Stop сделан режимом `check`, где команды не исполняются вовсе
# (`:110`): инвариант держится ОДНИМ словом в одной строке, и правка из трёх букв
# возвращает шторм 1 сентября 2026 (2225 процессов, load 16.5).
#
# Маркер здесь СВОЙ, а не `BACKLOG_CHECKS_NESTED`. Тот означает «ты внутри «Проверки»
# пункта долга», и раздача его всем командам подряд означала бы одно значение на два
# предмета: в реестре есть замер `backlog-archive` с командой `scripts/backlog-archive.sh
# run`, и под чужим маркером архиватор вышел бы на своей двери (`backlog-archive.sh:82`),
# получив зелёную отметку и не перенеся ничего. Замер, зелёный оттого, что не работал, —
# ровно тот класс, ради которого заведён код 2 «ПРЕДМЕТА НЕТ».
#
# Маркер несёт РЕЕСТР, а не «да» (D1218). Значение `1` отвечало одинаково на «я внутри замера по этому реестру» и на
# «тест зовёт бегуна как предмет на своей фикстуре»: набор под замером `suite-world-locale` выходил у тестов бегуна на
# этой двери, красный ложно. Первая починка сняла маркер в раннере набора — и вместе с ним дверь кольца «замер → набор →
# тест → замер» (скептик opus по c1a390fc, M1: рекурсия без предела). Теперь дверь — только на том же реестре: тест со
# своим реестром исполняется и под командой замера, вложенный прогон того же реестра останавливается.
_REG_ID=$(cd "$(dirname "$REGISTRY")" 2>/dev/null && printf '%s/%s' "$(pwd -P)" "$(basename "$REGISTRY")") || _REG_ID=$REGISTRY
if [ "$MODE" = run ] && [ "${MEASURE_DUE_NESTED:-}" = "$_REG_ID" ]; then
    echo "Вложенный прогон из команды замера — исполнение пропущено."
    exit 0
fi
export MEASURE_DUE_NESTED="$_REG_ID"


[ -f "$REGISTRY" ] || { echo "measurement-due: нет реестра $REGISTRY" >&2; exit 2; }

# ID УНИКАЛЕН, и это проверяется, а не подразумевается (10 сентября 2026). Отметка прогона
# зовётся именем замера (`$RUNS/<id>`), поэтому два замера под одним id делят одну отметку:
# прогнали первый — второй считается свежим и не запускается НИКОГДА, оставаясь в отчёте
# исправным. Так прожил `signal-precision` с периодом 90 — второй строкой к периоду 14.
# Признак с одним последствием: замер молча не выполняется, — потому код 2, а не строка
# в выводе. Нашла это не проверка, а ручное сравнение календаря с опытом: реестр читали
# семь раз за день и ни разу не спросили, уникален ли ключ.
_dups=$(awk -F'\t' '!/^#/ && NF>1 && $1!="" {c[$1]++} END {for (k in c) if (c[k]>1) printf "%s (×%d) ", k, c[k]}' "$REGISTRY" 2>/dev/null)
if [ -n "${_dups:-}" ]; then
    echo "measurement-due: в реестре повторяются id: ${_dups}— отметка прогона у них общая, и все, кроме первого, не запускаются никогда" >&2
    exit 2
fi
mkdir -p "$RUNS" 2>/dev/null

_today_epoch=$(date +%s)
OVERDUE=0
UNPARSED=0
PARSED=0
FAILED=0
FOUND=0
RAN=0
EVENT=0
SKIPPED_NOCMD=0

# `|| [ -n "$id" ]`: `read` отдаёт ложь на последней строке без завершающего перевода, и
# замер, стоящий в реестре последним, был невидим бегуну — но видим всем счётчикам строк
# (класс D296; на самом реестре это уже случалось). Теперь такая строка обрабатывается.
# Строка читается ЦЕЛИКОМ и делится по табам вручную. `read` с `IFS=$'\t'` схлопывает
# подряд идущие разделители (таб — пробельный символ), поэтому пустая колонка исчезала и
# поля съезжали влево: описание попадало в поле команды и ИСПОЛНЯЛОСЬ — «НЕ ВЫПОЛНЕН
# (код 127)» вместо «команда пуста». Реестр объявлен TSV, и читать его надо как TSV (D303).
while IFS= read -r _line || [ -n "${_line:-}" ]; do
    id=${_line%%$'\t'*};      _rest=${_line#*$'\t'}
    period=${_rest%%$'\t'*};  _rest=${_rest#*$'\t'}
    cmd=${_rest%%$'\t'*};     what=${_rest#*$'\t'}
    # Строка без четырёх колонок: подстановки выше вернули бы одно и то же значение.
    case "$_line" in *$'\t'*$'\t'*$'\t'*) ;; *) cmd=""; what="${what:-}" ;; esac
    case "$id" in ''|'#'*) continue ;; esac
    [ -n "${period:-}" ] || continue
    # Строка, не разобравшаяся в TSV, НАЗЫВАЕТСЯ (10 сентября 2026, находка противника).
    # Прежде голый `continue` уносил её молча: замер выпадал из расписания навсегда, счётчики
    # о нём не знали, и «просрочено: 1» вместо двух выглядело нормой. D303 чинил здесь
    # схлопывание пустых колонок; «строка не разобралась» осталась немой.
    PARSED=$((PARSED + 1))
    # ЕДИНИЦА СРОКА — та, в которой этот замер нарабатывает предмет (решение владельца
    # 12 сентября 2026): «N» — дни опыта, «Nc» — коммиты с последнего прогона. Набор в чистой
    # рамке устаревает от коммитов, а не от сессий: 569 коммитов за 12 дней прошли «не
    # просроченными» при периоде 30 (case-2026-09-12-clean-frame-unchecked-while-commits-piled-up).
    unit=days
    case "$period" in *c) unit=commits; period=${period%c} ;; esac
    case "$period" in
        ''|*[!0-9]*)
            printf '  ✗ строка реестра не разобрана (период «%s» не число): %s\n' \
                "${period:-пусто}" "$(printf '%s' "$id" | cut -c1-60)" >&2
            UNPARSED=$((UNPARSED + 1))
            continue ;;
    esac

    if [ "$period" -eq 0 ]; then
        EVENT=$((EVENT + 1))
        continue
    fi

    stamp="$RUNS/$id"
    if [ -f "$stamp" ]; then
        last=$(cat "$stamp" 2>/dev/null)
        case "$last" in ''|*[!0-9]*) last=0 ;; esac
    else
        last=0
    fi
    # Отметка из будущего (переставленные часы, чужая запись) давала ОТРИЦАТЕЛЬНЫЙ возраст:
    # замер вечно «свежий», из просрочки исчезал навсегда, и ничто этого не называло.
    # Такая отметка недействительна — считаем, что прогона не было (D303).
    if [ "$last" -gt "$_today_epoch" ]; then
        printf '  ⚠️ %-22s отметка прогона из БУДУЩЕГО — считаю, что замер не выполнялся\n' "$id"
        last=0
    fi
    # ПРОШЕДШЕЕ — ДНИ ОПЫТА, НЕ КАЛЕНДАРЯ (D234, 10 сентября 2026). Замер устаревает
    # оттого, что мир двигался, а мир двигают сессии, а не обороты Земли: за день можно
    # переписать дерево, а можно год не открывать компьютер. Календарный срок в первом
    # случае молчит, во втором кричит — оба раза неверно. На этой машине разница
    # четырёхкратная: 30 календарных дней = 8 дней опыта.
    # Счётчика нет (чистая установка, CI) — календарный фоллбек, прежнее поведение.
    age_days=""
    if command -v fsrs_experience_days_since_epoch >/dev/null 2>&1; then
        age_days=$(fsrs_experience_days_since_epoch "$last" 2>/dev/null)
    fi
    case "${age_days:-}" in
        ''|*[!0-9]*) age_days=$(( (_today_epoch - last) / 86400 )) ;;
    esac
    _uw="дн. опыта"
    if [ "$unit" = commits ]; then
        _uw="коммитов"
        _sha=$(cat "$RUNS/$id.sha" 2>/dev/null)
        age_days=""
        [ -n "$_sha" ] && age_days=$(git -C "$REPO" rev-list --count "$_sha..HEAD" 2>/dev/null)
        # Нет отметки коммита либо git её не знает (история переписана) — прогона в этой
        # единице не было: замер просрочен, а не вечно свеж.
        case "${age_days:-}" in ''|*[!0-9]*) age_days=$period; last=0 ;; esac
    fi

    if [ "$age_days" -lt "$period" ]; then
        continue
    fi

    OVERDUE=$((OVERDUE + 1))
    if [ "$last" -eq 0 ]; then
        when="ни разу"
    else
        when="${age_days} ${_uw} назад"
    fi
    printf '  просрочен: %-22s (период %s %s, последний прогон: %s) — %s\n' "$id" "$period" "$_uw" "$when" "${what:-}"

    [ "$MODE" = "check" ] && continue

    # Команда, закомментированная целиком, — НЕ команда. `eval` на ней исполняется в
    # пустоту, отдаёт 0 и отчитывается «выполнен, находок нет», после чего замер получает
    # отметку прогона и исчезает из просрочки НАВСЕГДА. Молчание тут значит «его никто не
    # звал», а не «находок нет» (D303).
    # Проверка стоит ПОСЛЕ подсчёта просрочки намеренно: такой замер обязан остаться в
    # очереди и называться на каждом прогоне. Пропуск до счётчика убирал бы его из вида —
    # тот же исход, что ложное «выполнен», только тише.
    case "${cmd:-}" in
        ''|'#'*)
            printf '    → НЕ ИСПОЛНЕН: команда пуста либо закомментирована; отметка не ставится\n'
            SKIPPED_NOCMD=$((SKIPPED_NOCMD + 1))
            continue
            ;;
    esac

    # Код возврата замера различает ТРИ вещи, а не две:
    #   0     — отработал, находок нет;
    #   1     — отработал и НАШЁЛ проблему (для того и заведён);
    #   ≥ 2   — не смог отработать (нет входа, нет зависимости, разбор упал).
    #
    # Прежняя версия считала ошибкой любой ненулевой код и не ставила отметку. Значит
    # замер, чья задача — краснеть на найденной проблеме, отметки не получал НИКОГДА
    # и висел вечно просроченным. Обнаружено на собственном `escalation-age`: заявке
    # 99 дней, он честно вернул 1, и это прочиталось как «команда сломалась».
    #
    # Отметка ставится и при 0, и при 1: замер выполнен в обоих случаях. Различие
    # находки и отказа — то же различие, что между «нет расхождения» и «не измеряли».
    #
    # Вывод замера СОХРАНЯЕТСЯ рядом с отметкой, а не уходит в /dev/null. Код возврата
    # говорит лишь «находка есть»; сама находка живёт в ТЕКСТЕ. До 3 сентября 2026 здесь
    # стояло `>/dev/null 2>&1`, а ниже печаталось «смотри вывод замера» — отсылка к
    # входу, который этот же узел и выбросил. Цена измерена: недельный `state-prune`
    # вернул 1 с текстом «за окном 51 файл, семь семейств», бегун поставил отметку, текст
    # не прочитал никто, и находка прожила неделю невидимой (D274, второй элемент
    # минимального набора отказа). В каталоге на 3 сентября 2026 — 48 отметок и НОЛЬ
    # файлов с текстом. Двое соседей предел уже обошли собственными артефактами
    # (`dose-response.sh:26`, `violation-class.sh:20` — оба ссылаются на это глушение
    # дословно), остальные 45 замеров реестра из 47 — нет. Образец решения свой:
    # `hooks/tests/run_all.sh:44`, тот же дефект починен там в v1.14.3.
    #
    # Файл открывается ЗАРАНЕЕ и отдельной строкой: при каталоге состояния только на
    # чтение перенаправление отдаёт код 1, и чистый замер прочитался бы как находка.
    # Перезапись `>`, не дозапись: иначе файл растёт на каждом прогоне (T8b).
    _out="$RUNS/$id.out"
    : > "$_out" 2>/dev/null || _out=/dev/null
    # stdin закрыт: замер, читающий его (`cat`, `jq` без файла), выедал остаток реестра из
    # трубы цикла, и следующие замеры не запускались И НЕ НАЗЫВАЛИСЬ — пропажа выглядела
    # как «их там нет».
    # Свой TMPDIR на каждый замер (D1198) — как у `scripts/backlog-return-check.sh`: бегун идёт ежедневно, и всё, что
    # команда реестра не убрала, оставалось в системном TMPDIR.
    _mt=$(mktemp -d "${TMPDIR:-/tmp}/md.XXXXXX" 2>/dev/null) || _mt=""   # шаблоном: голый мимо TMPDIR (скептик D1198, M2)
    _ms=""; [ -n "$_mt" ] && command -v cmd_tmpdir_shim >/dev/null 2>&1 && cmd_tmpdir_shim "$_mt" && _ms="$_mt/.bin"
    ( cd "$REPO" && { [ -z "$_mt" ] || export TMPDIR="$_mt"; } && { [ -z "$_ms" ] || export PATH="$_ms:$PATH"; } && eval "$cmd" > "$_out" 2>&1 < /dev/null )
    _rc=$?
    [ -n "$_mt" ] && rm -rf "$_mt"
    # Непойманное исключение питона — тоже код 1, а 1 здесь «находки»: шесть замеров без
    # `hooks/lib` падали ImportError и засчитывались выполненными «с находками» (D1157, R6).
    # Трасса в выводе при коде 1 — сбой прибора; ищется в любом месте строки: заголовок группы
    # исключений (`  + Exception Group Traceback`), вывод без сброса перед трассой и отступ
    # обёртки ставят её не с начала (скептик D1157, L2). Предел — падение без трассы в выводе:
    # SyntaxError главного файла, `sys.exit("строка")`, `2>/dev/null || exit 1`, файл вывода не
    # открылся (`/dev/null`); в 22 питон-строках реестра таких форм нет (1 ноября 2026).
    _crash=""
    [ "$_rc" -eq 1 ] && grep -q 'Traceback (most recent call last):' "$_out" 2>/dev/null \
        && _crash=", питон упал — трасса в выводе"
    # Код 3 — находки ВТОРОГО РОДА по контракту прибора (13 сентября 2026, D377): реестр или
    # объявление устарели, а не числа мира. Замер выполнен, находки есть — но иные, и это
    # печатается словами; читать 3 как «не выполнен» значило бы снова один канал на два состояния.
    if [ -z "$_crash" ] && { [ "$_rc" -le 1 ] || [ "$_rc" -eq 3 ]; }; then
        printf '%s\n' "$_today_epoch" > "$stamp"
        git -C "$REPO" rev-parse HEAD > "$RUNS/$id.sha" 2>/dev/null || true   # для единицы «Nc»
        RAN=$((RAN + 1))
        if [ "$_rc" -eq 0 ]; then
            printf '    → выполнен, находок нет\n'
        else
            if [ "$_rc" -eq 3 ]; then
                printf '    → выполнен, ЕСТЬ НАХОДКИ второго рода (код 3: реестр или объявление устарели) — вывод: %s\n' "$_out"
            else
                printf '    → выполнен, ЕСТЬ НАХОДКИ — вывод: %s\n' "$_out"
            fi
            FOUND=$((FOUND + 1))
            # Повод контура. Деталь несёт id замера и ПЕРВУЮ содержательную строку вывода:
            # по ней повод узнаётся в журнале и не сливается с прошлым прогоном того же
            # замера. Дедуп `rc_note_event` идёт по паре (род, деталь) среди ОТКРЫТЫХ своего
            # проекта, поэтому та же находка на следующей неделе повода не задвоит, а
            # изменившаяся заведёт новый — как и положено.
            if command -v rc_note_event >/dev/null 2>&1; then
                _first=$(grep -vE '^[[:space:]]*$' "$_out" 2>/dev/null | head -1 | cut -c1-120)
                # Адрес повода — репозиторий, чей реестр прогоняется, а не каталог процесса (D1350): launchd запускает
                # задание из «/», и повод с таким адресом не доходил ни до одной сессии — 108 из 148 на 21 ноября 2026.
                RC_EVENT_PROJECT="${RC_EVENT_PROJECT:-$REPO}" \
                    rc_note_event "$STATE" "measure-found" "${id}: ${_first:-находки без вывода}" \
                    2>/dev/null || true
            fi
        fi
    else
        FAILED=$((FAILED + 1))
        # Адрес артефакта, а не текст команды: вывод УЖЕ сохранён строкой выше, и у
        # отказавшего замера доказательство есть — оно просто не называлось. У находки
        # адрес печатался, у отказа нет: та же асимметрия, что чинил D281 (D295).
        printf '    → НЕ ВЫПОЛНЕН (код %s%s) — вывод: %s\n' "$_rc" "$_crash" "$_out"
    fi
done < "$REGISTRY"

# Ноль РАЗОБРАННЫХ строк — отказ прибора, а не «просроченных нет» (10 сентября 2026,
# находка противника). Отсутствие файла ловилось (`exit 2`), пустой по данным реестр — нет:
# реестр из одних комментариев, обрезанный при выгрузке или неверный MEASUREMENT_REGISTRY,
# указывающий на существующий, но не тот файл, давали зелёное «просроченных нет».
# Правило в дереве уже действует у соседей: `docs-concepts-check.sh` при пустом реестре
# даёт 2, `drift-check.sh` — BROKEN. «Сравнили ноль» нигде не считается успехом.
if [ "${PARSED:-0}" -eq 0 ] && [ "${UNPARSED:-0}" -eq 0 ]; then
    echo "measurement-due: в реестре нет ни одной разобранной строки ($REGISTRY) — это отказ прибора, а не «просроченных нет»" >&2
    exit 2
fi

if [ "$OVERDUE" -eq 0 ]; then
    echo "Замеры по расписанию: просроченных нет (по событию: ${EVENT})."
else
    # `без команды` в итоге обязателен: поле, которое пишется и не читается, объявляет
    # различение, которого в мире нет (род G реестра дефектов). Проверено на этой же
    # правке — счётчик был заведён и полминуты прожил без читателя.
    _nocmd_tail=""
    [ "${SKIPPED_NOCMD:-0}" -gt 0 ] && _nocmd_tail=", без исполнимой команды: ${SKIPPED_NOCMD}"
    echo "Замеров просрочено: ${OVERDUE}, выполнено: ${RAN} (с находками: ${FOUND}), не удалось: ${FAILED} (по событию: ${EVENT})${_nocmd_tail}."
fi

[ "$FAILED" -eq 0 ]
