#!/usr/bin/env bash
# measurement-due.sh — у любого замера есть срок, и просроченный поднимается сам.
# Результат: просроченных замеров нет: каждый прогнан в свой срок
# Проверка результата: bash scripts/measurement-due.sh — «просроченных нет»
#
#
# Повод, названный собеседником дословно: «ну и толку что ты мерил, а пока я не сказал —
# не мерил? А если бы вообще не вспомнил? Всё что меряют должно дедлайн иметь».
#
# Он про конкретный случай: замер «становится ли знание инструментом» дал 1,4%, но случился
# только потому, что о нём спросили. Без вопроса не случился бы, и отсутствия никто бы не
# заметил — у измерения не было ни владельца, ни срока. Замер, который держится на чьей-то
# памяти, это не механизм, а намерение.
#
# Что делает: читает `scripts/measurements.tsv`, для каждой строки с ненулевым периодом
# сравнивает дату последнего прогона с сегодняшней и запускает просроченные. Дата прогона
# хранится отдельным файлом на замер, потому что содержимое отчётов у всех разное, а вот
# факт «прогонялось тогда-то» одинаков и должен читаться единообразно.
#
# Строки с периодом 0 перечислены намеренно: они запускаются по событию (Stop, launchd),
# в просрочку не попадают, но должны быть видны — иначе список замеров неполон, и по нему
# нельзя судить, что вообще меряется.
#
# Код возврата САМОГО скрипта: 0 — просроченных нет либо все отработали; 1 — есть замеры,
# которые не СМОГЛИ отработать. Находка замера отказом не считается — см. пояснение ниже.

set -uo pipefail

REPO="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/.." 2>/dev/null && pwd -P)}"
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
REGISTRY="${MEASUREMENT_REGISTRY:-$REPO/scripts/measurements.tsv}"
RUNS="$STATE/measurement-runs"
MODE="${1:-run}"          # run — запускать просроченные; check — только назвать

[ -f "$REGISTRY" ] || { echo "measurement-due: нет реестра $REGISTRY" >&2; exit 2; }
mkdir -p "$RUNS" 2>/dev/null

_today_epoch=$(date +%s)
OVERDUE=0
FAILED=0
FOUND=0
RAN=0
EVENT=0

while IFS=$'\t' read -r id period cmd what; do
    case "$id" in ''|'#'*) continue ;; esac
    [ -n "${period:-}" ] || continue
    case "$period" in ''|*[!0-9]*) continue ;; esac

    if [ "$period" -eq 0 ]; then
        EVENT=$((EVENT + 1))
        continue
    fi

    stamp="$RUNS/$id"
    if [ -f "$stamp" ]; then
        last=$(cat "$stamp" 2>/dev/null)
        case "$last" in ''|*[!0-9]*) last=0 ;; esac
    else
        last=0
    fi
    age_days=$(( (_today_epoch - last) / 86400 ))

    if [ "$age_days" -lt "$period" ]; then
        continue
    fi

    OVERDUE=$((OVERDUE + 1))
    if [ "$last" -eq 0 ]; then
        when="ни разу"
    else
        when="${age_days} дн. назад"
    fi
    printf '  просрочен: %-22s (период %s дн., последний прогон: %s) — %s\n' "$id" "$period" "$when" "${what:-}"

    [ "$MODE" = "check" ] && continue

    # Код возврата замера различает ТРИ вещи, а не две:
    #   0     — отработал, находок нет;
    #   1     — отработал и НАШЁЛ проблему (для того и заведён);
    #   ≥ 2   — не смог отработать (нет входа, нет зависимости, разбор упал).
    #
    # Прежняя версия считала ошибкой любой ненулевой код и не ставила отметку. Значит
    # замер, чья задача — краснеть на найденной проблеме, отметки не получал НИКОГДА
    # и висел вечно просроченным. Обнаружено на собственном `escalation-age`: заявке
    # 99 дней, он честно вернул 1, и это прочиталось как «команда сломалась».
    #
    # Отметка ставится и при 0, и при 1: замер выполнен в обоих случаях. Различие
    # находки и отказа — то же различие, что между «нет расхождения» и «не измеряли».
    ( cd "$REPO" && eval "$cmd" >/dev/null 2>&1 )
    _rc=$?
    if [ "$_rc" -le 1 ]; then
        printf '%s\n' "$_today_epoch" > "$stamp"
        RAN=$((RAN + 1))
        if [ "$_rc" -eq 0 ]; then
            printf '    → выполнен, находок нет\n'
        else
            printf '    → выполнен, ЕСТЬ НАХОДКИ — смотри вывод замера\n'
            FOUND=$((FOUND + 1))
        fi
    else
        FAILED=$((FAILED + 1))
        printf '    → НЕ ВЫПОЛНЕН (код %s): %s\n' "$_rc" "$cmd"
    fi
done < "$REGISTRY"

if [ "$OVERDUE" -eq 0 ]; then
    echo "Замеры по расписанию: просроченных нет (по событию: ${EVENT})."
else
    echo "Замеров просрочено: ${OVERDUE}, выполнено: ${RAN} (с находками: ${FOUND}), не удалось: ${FAILED} (по событию: ${EVENT})."
fi

[ "$FAILED" -eq 0 ]
