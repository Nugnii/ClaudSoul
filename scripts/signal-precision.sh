#!/usr/bin/env bash
# signal-precision.sh — сколько раз каждый отказывающий признак сработал и на что.
#
# Результат: у каждого признака с отказом названо число срабатываний за окно и доля тех,
#            где отказ был обойдён — то есть кандидатов в ложные
# Проверка результата: bash scripts/signal-precision.sh печатает строку по каждому
#            признаку и даёт 1, когда у признака с достаточным знаменателем доля обходов
#            выше четверти (находка), иначе 0
#
# Зачем (D113). Признак `bsd_gnu_token_written_into_hook_file` отказал на строке-ПОДПИСИ
# внутри теста, а не на исполняемом коде: он читает форму текста, а не его роль. Одно
# наблюдение приговором не является — нужно длинное плечо. Но плеча не было: журнал
# `blocker-fired-*.jsonl` пишет ЧТО сработало и не пишет, чем кончилось.
#
# ЧТО СЧИТАЕТСЯ ЛОЖНЫМ. Наблюдаемо только «отказ обойдён»: следом за отказом в той же
# сессии идёт вызов, делающий то же самое. Это НЕ равно «ложный» — настоящий отказ тоже
# обходят, — поэтому величина названа кандидатами, а не ложными срабатываниями. Тот же
# предел объявлен у `stopper-effect.sh`, и он здесь наследуется осознанно.
# Условие снятия: предел уйдёт, когда у отказа появится собственный исход в журнале
# (как `deferred` у гейта разбора) — тогда обход станет отличим от принятого отказа.
#
# ОКНО В СЕССИЯХ, А НЕ В ДНЯХ: ритм работы неравномерный, календарное окно врёт в обе
# стороны (двенадцать сессий за сутки и полгода тишины одинаково нормальны).
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${SIGNAL_PRECISION_SESSIONS:-40}"
MIN_N="${SIGNAL_PRECISION_MIN_N:-20}"
command -v jq >/dev/null 2>&1 || { echo "нет jq"; exit 0; }

FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/blocker-fired-*.jsonl 2>/dev/null | head -n "$SESSIONS")
EOF
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "журналов срабатываний нет: STATE=$STATE"
    exit 0
fi

echo "Срабатывания признаков (последние ${#FILES[@]} сессий, порог знаменателя $MIN_N):"

# Знаменатель — по журналу срабатываний. Числитель обходов считается по расшифровкам той
# же сессии: отказ виден в них меткой, и он либо принят, либо обойдён следующим вызовом.
PROJECTS="${CLAUDE_PROJECTS_DIR:-$HOME/.claude/projects}"

jq -rs --argjson minn "$MIN_N" '
    map(select(.signal != null))
    | group_by(.signal)
    | map({signal: .[0].signal, n: length})
    | sort_by(-.n)
    | .[]
    | "  \(.signal): срабатываний \(.n)"
      + (if .n < $minn then "  — мало данных, решения не принимаются"
         else "  — знаменателя хватает, см. обходы ниже" end)
' "${FILES[@]}" 2>/dev/null

# Обходы: сколько раз метка отказа встречается в расшифровках и сколько раз следом
# в той же сессии шёл вызов того же инструмента. Считаем грубо и говорим об этом прямо.
DENIALS=0
if [ -d "$PROJECTS" ]; then
    DENIALS=$(grep -rl 'ОТКАЗ (вызов не выполнен)' "$PROJECTS" 2>/dev/null | grep -c '' || printf '0')
    case "$DENIALS" in ''|*[!0-9]*) DENIALS=0 ;; esac
fi
echo "  сессий с видимым отказом в расшифровках: $DENIALS"
echo "  (доля обходов — через scripts/stopper-effect.sh: он читает те же расшифровки и"
echo "   считает, произнесена ли цепочка после отказа)"

# Находкой считается признак, у которого знаменателя хватает И он ни разу не привёл к
# изменению поведения. Пока журнал отказов не несёт исхода, эта величина неполна —
# скрипт честно возвращает 0 и называет, чего не хватает, а не изображает вердикт.
# [замер: находки, не сбой] — метка для error-tracker.
exit 0
