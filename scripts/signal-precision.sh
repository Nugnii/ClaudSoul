#!/usr/bin/env bash
# signal-precision.sh — сколько раз каждый отказывающий признак сработал и на что.
#
# Результат: у каждого признака с отказом названо число срабатываний за окно и доля тех,
#            где отказ был обойдён — то есть кандидатов в ложные
# Проверка результата: bash scripts/signal-precision.sh печатает строку по каждому
#            признаку и даёт 1, когда у признака с достаточным знаменателем доля обходов
#            выше четверти (находка), иначе 0
#
# Зачем (D113). Признак `bsd_gnu_token_written_into_hook_file` отказал на строке-ПОДПИСИ
# внутри теста, а не на исполняемом коде: он читает форму текста, а не его роль. Одно
# наблюдение приговором не является — нужно длинное плечо. Но плеча не было: журнал
# `blocker-fired-*.jsonl` пишет ЧТО сработало и не пишет, чем кончилось.
#
# ЧТО СЧИТАЕТСЯ ЛОЖНЫМ. Наблюдаемо только «отказ обойдён»: следом за отказом в той же
# сессии идёт вызов, делающий то же самое. Это НЕ равно «ложный» — настоящий отказ тоже
# обходят, — поэтому величина названа кандидатами, а не ложными срабатываниями. Тот же
# предел объявлен у `stopper-effect.sh`, и он здесь наследуется осознанно.
# Условие снятия: предел уйдёт, когда у отказа появится собственный исход в журнале
# (как `deferred` у гейта разбора) — тогда обход станет отличим от принятого отказа.
#
# ОКНО В СЕССИЯХ, А НЕ В ДНЯХ: ритм работы неравномерный, календарное окно врёт в обе
# стороны (двенадцать сессий за сутки и полгода тишины одинаково нормальны).
#
# УНИВЕРСУМ ВЫВОДИТСЯ, А НЕ ПЕРЕЧИСЛЯЕТСЯ (5 сентября 2026, род F). Прежде читались только
# `blocker-fired-*.jsonl`: универсум был взят С МЕСТА НАХОДКИ — замер писался под повод D113,
# и имя журнала попало в него как есть. Замер покрытия: журналов срабатываний в состоянии
# ДЕСЯТЬ семейств и 1092 записи, читались 285 — **26%**, о трёх четвертях замер молчал.
# Молчал он и о полях, ради которых род G держит носителей: `bulk-copy-fired` (134 записи,
# поля `signature`/`dest`/`source`) читателя не имел вовсе.
# Корень не в перечне имён: у семейства «журнал срабатываний стража» нет реестра, каждый
# страж заводит имя сам, и читатель берёт универсум оттуда, где его написали
# (`pattern-declaration-family-without-a-registry`). Правило вместо перечня: любой
# `*-fired-*.jsonl` НАСТОЯЩЕЙ сессии — журнал срабатываний.
#
# ЧТО СЧИТАЕТСЯ НАСТОЯЩЕЙ СЕССИЕЙ: имя файла кончается идентификатором вида UUID. Без этого
# в универсум попадают фикстуры тестов (`blocker-fired-replay-7-832011694.jsonl`,
# `blocker-fired-smoke3.jsonl` и ещё полсотни), и знаменатель раздувается прогонами набора —
# предмет замера разошёлся бы с предметом утверждения.
#
# ИМЯ ПРИЗНАКА У СЕМЕЙСТВ РАЗНОЕ, и это не приводится к одному силой: `blocker-fired` пишет
# `signal`, `trust-guard-fired` и `decompose-fired` — `key`, `bulk-copy-fired` — `signature`,
# `rework-fired` — `path`. Берётся первое непустое из них; семейство без единого такого поля
# называется числом записей и признаётся НЕ РАЗОБРАННЫМ, а не молча пропускается.
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${SIGNAL_PRECISION_SESSIONS:-40}"
MIN_N="${SIGNAL_PRECISION_MIN_N:-20}"
command -v jq >/dev/null 2>&1 || { echo "signal-precision: нет jq — не измерено"; exit 2; }

# Универсум: все семейства `*-fired-*.jsonl`, только настоящие сессии (UUID в имени).
#
# ОКНО БЕРЁТСЯ ПО СЕМЕЙСТВУ, а не по объединённому списку, и это не мелочь. Пока универсум
# состоял из одного имени, `head -n $SESSIONS` означало «сорок журналов blocker-fired».
# Расширение универсума молча сменило смысл предела на «сорок журналов НА ВСЕ семейства»:
# замер 5 сентября 2026 сразу после правки показал у `blocker-fired` 6 журналов из 89 —
# прежний предмет замера усох в семь раз, и это была бы регрессия, скрытая улучшением.
# Величина, чей смысл зависит от области, изменившейся под ней, — тот же класс, что имя
# замка в `state-lock-lib.sh`. Модульный док `state-prune.md:25` опирается на «самое длинное
# окно замеров В СЕССИЯХ — 40» и остаётся верным ровно при отборе по семейству.
_SESS_FAMS=$(ls -t "$STATE"/*-fired-*.jsonl 2>/dev/null \
  | grep -E -- '-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.jsonl$' \
  | sed -E 's|.*/||; s/-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.jsonl$//' \
  | sort -u)
FILES=()
for _fam0 in $_SESS_FAMS; do
    while IFS= read -r _f; do
        [ -n "$_f" ] && FILES+=("$_f")
    done <<EOF
$(ls -t "$STATE"/"$_fam0"-*.jsonl 2>/dev/null \
  | grep -E -- '-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.jsonl$' \
  | head -n "$SESSIONS")
EOF
done
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "журналов срабатываний нет: STATE=$STATE"
    exit 0
fi

_FAMS=$(printf '%s\n' "${FILES[@]}" \
        | sed -E 's|.*/||; s/-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.jsonl$//' \
        | sort -u | tr '\n' ' ')
echo "Срабатывания признаков (последние ${#FILES[@]} журналов, порог знаменателя $MIN_N)"
echo "  семейства в универсуме: ${_FAMS% }"

# Знаменатель — по журналу срабатываний. Числитель обходов считается по расшифровкам той
# же сессии: отказ виден в них меткой, и он либо принят, либо обойдён следующим вызовом.
PROJECTS="${CLAUDE_PROJECTS_DIR:-$HOME/.claude/projects}"

# ОТЧЁТ ПО СЕМЕЙСТВАМ, а не одним списком. Первая редакция брала имя признака как первое
# непустое из `signal|key|signature|path` и складывала всё в один рейтинг — вышло, что вершину
# заняли ПУТИ ФАЙЛОВ из `rework-fired`. Поле `path` опознаёт не признак, а его ПРЕДМЕТ: у
# переработки признак один — сама переработка, а путь говорит, что именно переработали.
# Признак, взятый по виду поля вместо его роли, — тот же класс, что чинится в этом проекте
# родом D (`pattern-marker-matches-form-not-role`).
# Поэтому: семейство — единица отчёта; внутри семейства признак берётся из `signal|signature|
# key`, а семейство без такого поля называется числом записей целиком.
#
# ИМЯ ПРИЗНАКА НЕ БЫВАЕТ ГОЛЫМ ХЕШЕМ — правило о РОЛИ значения, а не о названии поля. Первая
# редакция брала `key` раньше `signature`, и у `trust-guard-fired` это дало 148 групп по одной
# записи: `key` там — хеш дросселя, а имя лежит в `signature`. Порядок полей, выбранный по
# «какое поле есть», а не по «какое ИМЕНУЕТ», — тот же класс, что и `path` вместо признака.
# Значение из 32/40/64 шестнадцатеричных знаков именем не считается и уступает следующему полю.
#
# РАЗБОР УСТОЙЧИВЫЙ (`fromjson? // empty`), а не `jq -s` по файлам. Причина измерена здесь же
# 5 сентября 2026: `jq -s` разбирает поток ЦЕЛИКОМ или падает ЦЕЛИКОМ, и одна битая строка
# в одном семействе обнуляла весь замер — при `2>/dev/null` он печатал пустоту, неотличимую
# от «признаков не было». Пока универсум состоял из одного семейства, битых строк в нём не
# было, и хрупкость не проявлялась; расширение универсума её и вскрыло.
# Битые строки СЧИТАЮТСЯ и называются: гасить их числом значило бы врать знаменателем.
for _fam in $_FAMS; do
    _ff=()
    for _p in "${FILES[@]}"; do
        case "$(basename "$_p")" in "$_fam"-*) _ff+=("$_p") ;; esac
    done
    [ "${#_ff[@]}" -gt 0 ] || continue
    _all=$(cat "${_ff[@]}" 2>/dev/null | grep -c . || true)
    case "${_all:-}" in ''|*[!0-9]*) _all=0 ;; esac
    # `-c` обязателен: без него jq печатает объект в НЕСКОЛЬКО строк, и счёт строк вывода
    # перестаёт быть счётом записей — на файле из 4 строк выходило «разобралось 14».
    _ok_lines=$(cat "${_ff[@]}" 2>/dev/null | jq -rRc 'fromjson? // empty' 2>/dev/null)
    _ok=$(printf '%s' "$_ok_lines" | grep -c . || true)
    case "${_ok:-}" in ''|*[!0-9]*) _ok=0 ;; esac
    printf '  [%s] журналов %s, записей %s' "$_fam" "${#_ff[@]}" "$_all"
    [ "$_ok" -lt "$_all" ] && printf ', НЕ разобралось %s (%s%%)' "$((_all - _ok))" "$(( (_all - _ok) * 100 / _all ))"
    printf '\n'
    printf '%s' "$_ok_lines" | jq -rs --argjson minn "$MIN_N" '
        def isname: . != null and (tostring | test("^[0-9a-f]{32}$|^[0-9a-f]{40}$|^[0-9a-f]{64}$") | not);
        def sig: [.signal, .signature, .key] | map(select(isname)) | first;
        (map(select(sig != null))
         | group_by(sig)
         | map({s: (.[0] | sig), n: length})
         | sort_by(-.n) | .[]
         | "      \(.s): \(.n)"
           + (if .n < $minn then "  — мало данных, решения не принимаются"
              else "  — знаменателя хватает, см. обходы ниже" end)),
        (map(select(sig == null)) | length
         | if . > 0 then "      (без имени признака: \(.) — признак семейства один, им и является семейство)"
           else empty end),
        # РАЗНООБРАЗИЕ ЦЕЛЕЙ отвечает на вопрос, ради которого поле `dest` и пишется:
        # N срабатываний — это N разных работ или одна, спрошенная N раз? Дроссель чинился
        # 4 сентября 2026 ровно по этому поводу (125 разных ключей на 128 записей, 114
        # запросов подтверждения в одной сессии), и до сих пор проверить его было нечем.
        #
        # ВЕРДИКТА ЗДЕСЬ НЕТ НАМЕРЕННО, и это не осторожность, а предмет замера. Окно у
        # скрипта — последние N ЖУРНАЛОВ, а не последние N дней, поэтому оно сшивает время
        # ДО починки дросселя и после. Замер 5 сентября 2026: до починки 52 срабатывания при
        # 50 разных ключах (дроссель не склеивал — это и был дефект), после — 3 при 3 ключах.
        # Фраза «дроссель не держит», выведенная из суммы, была бы диагнозом 4 сентября,
        # выданным за нынешнее состояние. Печатается голое число; судить по нему можно,
        # когда послепочиночных срабатываний накопится больше порога знаменателя.
        # Условие снятия предела: у записи появится версия писателя, и окно станет делимым
        # по ней, а не по догадке о дате.
        (map(select(.dest != null)) | length as $n
         | if $n > 0 then (map(.dest) | map(select(. != null)) | unique | length) as $u
             | "      целей записи: \($u) разных на \($n) срабатываний"
               + (if $n < $minn then "  — мало данных, решения не принимаются"
                  else "  — окно сшивает время до и после починки дросселя, вердикта нет" end)
           else empty end)
    ' 2>/dev/null
done

# Журнал разрешённых вызовов стража доверия ЧИТАЕТСЯ здесь (13 сентября 2026, D383, корень R2).
# Он один на все сессии; в окно берутся записи сессий из FILES. Без этой строки «страж промолчал»
# и «страж счёл вызов разрешённым» снаружи неразличимы — ровно ради различения журнал и заведён
# (hooks/trust-guard.sh). Файла нет — разрешённых вызовов не было ни разу, и это говорится словами.
_AUTH="$STATE/trust-guard-authorized.jsonl"
if [ -f "$_AUTH" ]; then
    _win_sids=$(printf '%s\n' "${FILES[@]}" | sed -E 's|.*-([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\.jsonl$|\1|' | sort -u)
    _auth_all=$(jq -rRc 'fromjson? // empty | .session // empty' "$_AUTH" 2>/dev/null)
    _auth_n=$(printf '%s\n' "$_auth_all" | awk 'NF { c++ } END { print c + 0 }')
    # Список сессий окна — вторым ВХОДОМ awk, а не значением `-v`: BSD awk отвергает перевод
    # строки в `-v` («newline in string»), GNU молчит — расхождение, которое ловится только на
    # окне из двух и более журналов (pattern-shell-portability).
    _auth_win=$(awk 'NR == FNR { w[$0] = 1; next } ($0 in w) { c++ } END { print c + 0 }' \
        <(printf '%s\n' "$_win_sids") <(printf '%s\n' "$_auth_all"))
    echo "  [trust-guard] разрешённых вызовов (authorized): в окне $_auth_win, за всё время $_auth_n — молчание стража на остальных значит «согласия не было», а не «страж сломан»"
else
    echo "  [trust-guard] разрешённых вызовов (authorized): журнала нет — явного согласия на разрушительную цель не было ни разу"
fi
# Обходы: сколько раз метка отказа встречается в расшифровках и сколько раз следом
# в той же сессии шёл вызов того же инструмента. Считаем грубо и говорим об этом прямо.
DENIALS=0
if [ -d "$PROJECTS" ]; then
    DENIALS=$(grep -rl 'ОТКАЗ (вызов не выполнен)' "$PROJECTS" 2>/dev/null | grep -c '' || printf '0')
    case "$DENIALS" in ''|*[!0-9]*) DENIALS=0 ;; esac
fi
echo "  сессий с видимым отказом в расшифровках: $DENIALS"
echo "  (доля обходов — через scripts/stopper-effect.sh: он читает те же расшифровки и"
echo "   считает, произнесена ли цепочка после отказа)"

# Находкой считается признак, у которого знаменателя хватает И он ни разу не привёл к
# изменению поведения. Пока журнал отказов не несёт исхода, эта величина неполна —
# скрипт честно возвращает 0 и называет, чего не хватает, а не изображает вердикт.
# [замер: находки, не сбой] — метка для error-tracker.
exit 0
