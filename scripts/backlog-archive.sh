        # «под» предыдущим разделом, и раздел БЕЗ единого пункта под ним уезжал в архив
        # вместе с прозой — тот самый исход, который условие ниже объявило невозможным.
        if nb[3] and nb[3] <= b[1]:
            break
        if nb[0] == "item":
            # Задержанный показанием закрытый пункт остаётся в рабочем файле — значит
            # и заголовок над ним остаётся: для этого счёта он такой же живой, как ☐.
            if nb[1] in OPEN or j in blocked:
                found_open = True
            else:
                found_done = True
    keep_heading[i] = found_open or not found_done

