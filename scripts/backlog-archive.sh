# там, где его не запускали: носитель долга есть у 4 корней из 30.
# Порядок: явное переопределение → долг проекта по cwd → ClaudSoul как дом скрипта.
# Соседи по контуру ходят тем же подъёмом (`find_project_root` в declared-problem-recorded,
