            # красная (rc=125)». Утверждения разные: «мир не таков, как объявлено» против
            # «посмотреть не удалось, исход НЕИЗВЕСТЕН», и лечатся они разным — первое
            # починкой мира, второе сроком или удешевлением команды. Воспроизведено на
            # фикстуре с `sleep 30` при BACKLOG_CHECK_TIMEOUT=2.
            # Брат-здоровяк того же устройства стоял рядом с августа:
            # `scripts/backlog-return-check.sh:161-179` различает срыв срока отдельным
            # исходом («СРОК ИСТЁК … пункт НЕ проверен»). Архиватор от него отстал.
            # Перенос блокируется во ВСЕХ трёх случаях — непроверенное закрытие не уезжает
            # в архив так же, как опровергнутое, — разнится только то, что сказано вслух.
            _to = int(os.environ.get("BACKLOG_CHECK_TIMEOUT", "120"))
            disp = " ".join(cmd.split())
            # ОГРАДА КОЛЬЦА (D503, правило ключа — `hooks/backlog-lib.sh`). Команда, уже
            # исполняющаяся выше по дереву процессов, второй раз не запускается, и вложенность
            # глубже предела — тоже: маркер вложенности снимают свидетели и тесты (D334), поэтому кольцо держит ключ.
            # Ключ снимают только тесты самой ограды: на 29 октября 2026 — 25 файлов (18 `*cmdring*`, пробы
            # D514–D519 и два теста с бэклогом-фикстурой), тесты, зовущие архиватор по делу, его не трогают (D1179, L2).
            _why, _run = _bc_blocked(str(backlog), "check", iid, m.group(1))
            if _why:
                unproven.append((iid, f"☑, а его «Проверка» НЕ ИСПОЛНЕНА — {_why} (D503); исход неизвестен: `{disp[:90]}`"))
                blocked.add(i)
                break
            _env = dict(os.environ, BACKLOG_CHECKS_NESTED="1")
            if _run is not None:
                _env["BACKLOG_CMD_RUNNING"] = _run
            # Свой TMPDIR (D1198), своя сессия команды и снятие её группы по сроку и при любом исключении (D1180) —
            # правило исполнителей `hooks/lib/bounded_run.py` (D1199), то же, что у `hooks/completion-gate.sh`.
            try:
                rc = bounded_run.run_bounded(cmd, _to, cwd=str(backlog.parent), env=_env, prefix="ba.").returncode
            except subprocess.TimeoutExpired:
                unproven.append((iid, f"☑, а его «Проверка» НЕ ПРОВЕРЕНА: срок истёк ({_to} с, BACKLOG_CHECK_TIMEOUT) — исход неизвестен, вердикта нет: `{disp[:90]}`"))
                blocked.add(i)
                break
            except Exception as e:
                unproven.append((iid, f"☑, а его «Проверка» НЕ ПРОВЕРЕНА: запустить не удалось ({type(e).__name__}) — исход неизвестен, вердикта нет: `{disp[:90]}`"))
                blocked.add(i)
                break
            if rc != 0:
                unproven.append((iid, f"☑, а его же «Проверка» красная (rc={rc}): `{disp[:90]}`"))
                blocked.add(i)
                break

