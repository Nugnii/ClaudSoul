    exit 0
fi

[ -f "$BACKLOG" ] || { echo "backlog-archive: нет $BACKLOG" >&2; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "backlog-archive: нужен python3" >&2; exit 2; }

# Признак пункта берётся у общей библиотеки, а не пишется здесь заново. Своя копия
# (питоновский `ITEM_RE`) стояла тут до 3 сентября 2026 — при том, что комментарий рядом
# уже называл `hooks/backlog-lib.sh` единственным определением. Копия и разошлась: правки
# признака в библиотеке до архиватора не доезжали. Порядок поиска — сначала рядом с собой,
# потом в установленном каталоге (гоча проекта: на чистой машине обратный порядок молча
# выключает читателя).
_BL_LIB="$REPO/hooks/backlog-lib.sh"
[ -f "$_BL_LIB" ] || _BL_LIB="$HOME/.claude/hooks/backlog-lib.sh"
# shellcheck source=hooks/backlog-lib.sh
. "$_BL_LIB" 2>/dev/null
command -v backlog_item_re >/dev/null 2>&1 || {
    echo "backlog-archive: нет определения пункта ($_BL_LIB) — переносить вслепую нельзя" >&2
