fi
REPO="${CLAUDSOUL_REPO:-${_BA_LOCAL:-$_BA_HOME}}"
BACKLOG="${BACKLOG_FILE:-$REPO/BACKLOG.md}"
ARCHIVE="${BACKLOG_ARCHIVE:-$REPO/BACKLOG-archive.md}"
MODE="${1:-run}"          # run — переносить; check — только сказать, сколько накопилось

# Режим сверяется с перечнем: неизвестное значение НЕ означает умолчание. До 1 сентября
# 2026 `MODE="${1:-run}"` не различал «не указан» и «указан неверно», и любой аргумент
# мимо перечня выполнял разрушительную ветку. Замер на фикстуре: из пяти написаний
# (`check`, `--check`, `--bogus`, пусто, `run`) перенос выполняли ЧЕТЫРЕ — то есть просьба
# проверить меняла файл. Имена режима у соседей разошлись (`check` у архиватора и
# measurement-due, `--check` у пересчётчика показаний и сверки чисел), поэтому принимаются
# оба написания, а всё прочее отбивается кодом 2.
case "$MODE" in
    run|--run)     MODE=run ;;
    check|--check) MODE=check ;;
    *) echo "применение: $(basename "$0") [run|check]" >&2; exit 2 ;;
esac


# Дверь вложенности. Команда «Проверки» пункта может сама дойти до Stop-хука (тесты
# session-collector и карточки вердикта его исполняют), а Stop-хук зовёт этот архиватор —
# без двери кольцо «архиватор → тест пункта → session-collector → архиватор» плодило
# процессы до исчерпания машины (2026-09-01: 2225 процессов, load 16.5; своп 15.8/16 ещё
# утром 31.08). Маркер ставится ниже в окружение команд «Проверки»: вложенному прогону
# переносить нечего — суждение о переносе уже идёт уровнем выше.
if [ "${BACKLOG_CHECKS_NESTED:-0}" = "1" ]; then
