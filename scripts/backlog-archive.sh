# из библиотеки): первый токен «буквы + номер» в заголовке пункта, разметка `**` снята.
# Своя копия — `re.search(r'D(\d+)', …)` — стояла тут до 3 сентября 2026 и была тем же
# дефектом уровнем ниже: номер брался по ВИДУ, любой D-номер строки. На пункте
# «- ☑ **X1** Закрыт по образцу D284» гейт винил D284 — чужой ЖИВОЙ открытый пункт, — а
# настоящего X1 не называл ни разу.
#
# ПОРОГ действует только там, где есть чем доказать возраст: `D` + число ниже MIN_ID.
# Идентификатор вне D-нумерации (`X1`, `TASK-003a`, `R1.1` — шапка библиотеки объявляет их
# законными, в архиве таких 30 из 255) возраста не сообщает, и до 3 сентября 2026 он
# проезжал гейт ЦЕЛИКОМ: закрытие без единой строки показания уходило в архив молча.
# Направление выбрано по цене ошибки: ложный отказ громкий и снимается одной строкой
# («допиши показание либо верни ◻»), ложный пропуск — тихая потеря свидетельства.
# Замер на живом BACKLOG.md: пунктов вне D-нумерации 0 из 16, то есть цена сегодня нулевая.
MIN_ID = int(os.environ.get("BACKLOG_CONTRACT_MIN_ID", "200"))
def _item_id(block):
    m = ID_TOKEN_RE.search(block[2][0].replace("*", ""))
    return m.group(0) if m else None

def _predates_contract(iid):
    # Шаблон — из библиотеки (13 сентября 2026): своя копия стояла здесь и у гейта закрытия,
    # оба объявляли правило единым, и они разошлись на `D42a` — префиксная форма считала
    # его историческим, строгая нет.
    m = re.match(os.environ["BACKLOG_ID_NUM_RE"], iid)
    return bool(m) and int(m.group(1)) < MIN_ID

