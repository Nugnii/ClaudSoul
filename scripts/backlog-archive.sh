            # Долг проекта берётся ТОЛЬКО если он есть: пустой файл заводить нечего, а
            # молчаливый откат на ClaudSoul — ровно тот дефект, что здесь чинится.
            [ -n "${_BA_ROOT:-}" ] && [ "$_BA_ROOT" != "$_BA_HOME" ] && [ -f "$_BA_ROOT/BACKLOG.md" ] \
