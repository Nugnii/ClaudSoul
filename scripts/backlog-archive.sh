BACKLOG_ITEM_RE="$(backlog_item_re)"
# Библиотека СТАРШЕ этого скрипта — тоже отказ, а не умолчание. Установленная копия
# (`~/.claude/hooks/backlog-lib.sh`) обновляется отдельным шагом (install.sh), и «новый
# скрипт при старой библиотеке» — штатное промежуточное состояние машины, а не выдумка:
# для стражей этот класс уже описан тестом
# `hooks/tests/test_attack8_new_hook_old_lib_falls_to_blind_fallback.sh`.
# Цена умолчания здесь не «чуть хуже»: без снятия заборов кода образец разметки в теле
# открытого пункта читается настоящим пунктом и уезжает в архив. Отсутствующая часть
# библиотеки — признак с одним последствием, и адрес отказа здесь же.
for _need in BACKLOG_ID_TOKEN_RE BACKLOG_CHECK_RE BACKLOG_FORM_PROXY_RE BACKLOG_ID_NUM_RE; do
    eval "_v=\${$_need:-}"
    [ -n "$_v" ] || {
