_MARKS = "".join(DONE + OPEN)
ITEM_RE = re.compile(os.environ["BACKLOG_ITEM_RE"])
ID_TOKEN_RE = re.compile(os.environ["BACKLOG_ID_TOKEN_RE"])

def item_mark(line):
    if not ITEM_RE.match(line):
        return None
    m = re.search(rf'[{_MARKS}]', line)
    return m.group(0) if m else None

# Опора сверки перед переносом и строки — из ОДНОГО снимка, снятого оболочкой до замка и до снятия
# заборов (argv[5]; D1000, см. «ПЕРЕНОС ПО УСТАРЕВШЕЙ КОПИИ» ниже): прочитанный здесь заново файл мог
# уже отличаться от того, по которому собран `masked`. Строки декодируются так же, как `read_text`
