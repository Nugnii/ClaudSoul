command -v with_lock >/dev/null 2>&1 || with_lock() { shift; "$@"; }
# Бэклог во временной папке — фикстура теста (D1011); временный ли путь, решает владелец перечня корней
# `rc_path_is_private` (`hooks/root-cause-lib.sh`, D1013), а не своя копия. Библиотека берётся у дома скрипта, а не
