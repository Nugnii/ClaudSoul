# Какие заголовки уцелеют. Заголовок уезжает в архив ТОЛЬКО когда он опустел: под ним
# есть закрытые пункты и нет открытых. Заголовок, из-под которого ничего не переносится
# (открытые пункты либо пунктов нет вовсе), остаётся в рабочем файле.
# Считаем от заголовка до следующего заголовка того же или более высокого уровня.
#
# Прежнее условие было `есть открытый пункт`, и заголовок БЕЗ пунктов не проходил ни его,
# ни ветку переноса ниже (она выводит стек заголовков только вместе с закрытым пунктом) —
# такой заголовок исчезал вместе со своим текстом из ОБОИХ файлов. Условия «остаться» и
# «уехать» не покрывали вход целиком, и разница между ними была не ошибкой ввода, а дырой:
# третий исход — пропажа — не назывался нигде.
keep_heading = [False] * len(blocks)
