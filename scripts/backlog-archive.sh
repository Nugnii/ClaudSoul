backlog, archive, mode = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]

DONE = ("☑", "⊘")
OPEN = ("☐", "◐")

# Опознание пункта — ОДНО на всю систему, из `hooks/backlog-lib.sh`; здесь оно
# принимается готовым выражением через окружение. Отражения признака тут больше нет:
