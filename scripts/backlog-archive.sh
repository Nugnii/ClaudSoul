    }
done
command -v backlog_strip_fenced >/dev/null 2>&1 || {
    echo "backlog-archive: библиотека $_BL_LIB старше скрипта (нет backlog_strip_fenced) — перенос отменён" >&2
    exit 2
}
export BACKLOG_ITEM_RE BACKLOG_ID_TOKEN_RE BACKLOG_CHECK_RE BACKLOG_FORM_PROXY_RE BACKLOG_ID_NUM_RE
# Ограда кольца (D503): разделитель и предел глубины — у библиотеки. Старая библиотека без них —
# ограды нет, как было до неё, а перенос идёт: ограда страхует исполнение, а не разбор пункта.
[ -n "${BACKLOG_CMD_SEP:-}" ] && export BACKLOG_CMD_SEP BACKLOG_CMD_FSEP BACKLOG_CMD_DEPTH_MAX

# ЗАБОР КОДА СНИМАЕТ БИБЛИОТЕКА, А НЕ ЭТОТ СКРИПТ. До 3 сентября 2026 здесь стояла ВТОРАЯ
# копия правила — питоновский `FENCE_RE` с одноразрядным `in_fence = not in_fence`, — при
# том что тем же днём из этого файла убрали две другие частные копии (признак пункта и
# признак идентификатора) именно за то, что копии расходятся молча. Эта разошлась в тот же
# день: библиотека уже помнила, каким маркером забор открыт, а копия переворачивала бит на
# каждой похожей строке. Замер на фикстуре с `~~~` внутри ``` : архиватор унёс в архив
# ЖИВОЙ открытый пункт вместе с разделом (rc=0, «Перенесено: 1»), а `backlog_ids` на том же
# входе отдавал оба пункта верно.
#
# Разбор ниже читает ДВА потока одних и тех же строк: `masked` (заборы сняты библиотекой,
# нумерация сохранена — внутри забора пустая строка) решает РОЛЬ строки, исходные `lines`
# идут в вывод. Так правило забора остаётся ровно в одном носителе.
MASKED="$(mktemp)" || { echo "backlog-archive: нет временного файла" >&2; exit 2; }
RAWSNAP="$(mktemp)" || { rm -f "$MASKED"; echo "backlog-archive: нет временного файла" >&2; exit 2; }
trap 'rm -f "$MASKED" "$RAWSNAP"' EXIT HUP INT TERM
# СНИМОК ОДИН, И ОН ПЕРВЫЙ (D1000, противник 18 октября 2026). Сверка перед переносом сравнивает
# файл с тем, ИЗ ЧЕГО собран перенос. Прежде `masked` брался отсюда, до замка, а байты для сверки —
# питоном уже после замка (ждёт до 2 с): правка, легшая в это окно, сверку проходила, а роли строк
# свежего текста решались по старому снимку — воспроизведено: пункт, переоткрытый в это окно
# (☑ → ◐), уехал в архив открытым. Теперь байты копируются ПЕРВЫМИ, `masked` строится из копии, и
# питон берёт из неё и строки, и опору сверки.
cp -f "$BACKLOG" "$RAWSNAP" 2>/dev/null || { echo "backlog-archive: снимок $BACKLOG не снят" >&2; exit 2; }
backlog_strip_fenced < "$RAWSNAP" > "$MASKED"

# Правка под замком (род H). Блок ниже держит ДВА окна read→write: BACKLOG.md
# (`read_text` → `write_text`) и архив (`read_text` → `write_text`), и оба входят в одну
