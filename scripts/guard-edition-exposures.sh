#!/usr/bin/env bash
# guard-edition-exposures.sh <срез UTC> <метка редакции> — обрывы фильтра API после отказа стража разбора
# данной редакции, со среза времени её переноса в установку.
#
# Результат: обрыв `reasoning_extraction` сразу после отказа стража новой редакции не остаётся
#            незамеченным до того дня, когда о нём вспомнят: замер стоит в реестре со сроком,
#            находка становится событием мира (measurement-due → measure-found)
# Проверка результата: bash hooks/tests/test_guard_edition_exposures.sh даёт 0 — три состояния различены на заглушке
#            прибора; живой замер: bash scripts/guard-edition-exposures.sh 2026-10-23T13:57:32Z D1035 — код 0
#            (обрывов нет), 1 (обрыв есть, откат назван), 2 (нечем мерить)
#
# Повод (23 октября 2026, слово владельца «я забуду замерить»): после переноса редакции D1033 замер
# обрывов держался на памяти — строка «мерить exposures.py завтра» в SESSION.md; редакция дала два
# обрыва за полтора часа, и заметил их владелец, а не прибор. Замер без срока — не замер
# (`scripts/measurement-due.sh`): у этой строки реестра период один день опыта.
#
# Прибор обрывов (`.claude-docs/safeguard-block/exposures.py`) локален: читает расшифровки сессий и
# печатает только метаданные; в чужом дереве его нет — тогда код 2, а не ложный ноль.
# Пороги вывода — из журнала разбора обрывов (9-д1, 5 октября 2026): для вывода на уровне 5% против
# сводной прежней доли обрывов 11,2% нужно 26 проб отказом хука; против ранней редакции (3,7%) — 80.
set -uo pipefail
FROM="${1:-}"; EDITION="${2:-}"
[ -n "$FROM" ] && [ -n "$EDITION" ] || { echo "применение: $(basename "$0") <срез UTC, напр. 2026-10-23T13:57:32Z> <метка редакции, напр. D1035>" >&2; exit 2; }
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PROBER="$ROOT/.claude-docs/safeguard-block/exposures.py"
[ -f "$PROBER" ] || { echo "нечем мерить: прибора обрывов нет ($PROBER — локальный, вне git)"; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "нечем мерить: нет python3"; exit 2; }
OUT=$(python3 "$PROBER" "$FROM" 2>/dev/null) || { echo "нечем мерить: прибор обрывов упал"; exit 2; }
# Строки проб: 8 колонок через « | »; путь — шестая, редакция — седьмая, исход — восьмая (БЛОК / принят).
# Пробы считаются по ярлыку редакции; ОБРЫВЫ — под любым ярлыком после среза: срез и есть время, с
# которого в установке живёт эта редакция, а ярлык содержимого бывает двусмысленным (прочитанный
# исходник стража несёт фразы нескольких редакций — обрыв субагента 23 октября 11:34 лёг под «новая»).
ALL=$(printf '%s\n' "$OUT" | awk -F' \\| ' 'NF == 8')
ROWS=$(printf '%s\n' "$ALL" | awk -F' \\| ' -v e="$EDITION" '$7 == e')
N=$(printf '%s' "$ROWS" | grep -c . || true)
HOOK=$(printf '%s' "$ROWS" | LC_ALL=C awk -F' \\| ' '$6 == "отказ хука"' | grep -c . || true)
CONTENT=$(printf '%s' "$ROWS" | LC_ALL=C awk -F' \\| ' '$6 == "содержимое"' | grep -c . || true)
BLOCKS=$(printf '%s' "$ALL" | LC_ALL=C awk -F' \\| ' '$8 == "БЛОК"' | grep -c . || true)
LEFT=$(( 26 - HOOK )); [ "$LEFT" -lt 0 ] && LEFT=0
echo "редакция ${EDITION} со среза ${FROM}: проб ${N} (отказом хука ${HOOK}, содержимым ${CONTENT}), обрывов после среза ${BLOCKS}; до вывода на уровне 5% против прежней доли 11,2% нужно 26 проб отказом хука — осталось ${LEFT}"
if [ "${BLOCKS:-0}" -gt 0 ]; then
    echo "ОБРЫВ после среза (живая редакция ${EDITION}):"
    printf '%s\n' "$ALL" | LC_ALL=C awk -F' \\| ' '$8 == "БЛОК" {print "  " $0}'
    echo "Откат: git checkout fef6037a -- hooks/five-whys-gate.sh; rm ~/.claude/hooks/five-whys-gate.sh; bash scripts/sync-drifted.sh --apply; строка ИСХОД в .claude-docs/safeguard-block/journal.md"
    exit 1
fi
exit 0
