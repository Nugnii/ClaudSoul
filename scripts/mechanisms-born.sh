#!/usr/bin/env bash
# mechanisms-born.sh — сколько механизмов система породила за окно и сколько из них
# Результат: ПРИБОР, не инструмент. Число за окно. Решение, которое оно меняет: продолжать ли текущую фазу ablation или менять дизайн (D96); срок решения — закрытие следующей фазы
# Проверка результата: bash scripts/mechanisms-born.sh 30 — доля «из знания» напечатана и внесена в дизайн фазы
#
# родились ИЗ ЗНАНИЯ, а не из желания фичи.
#
# Кандидат (3) из BACKLOG D96, выбранный по итогу закрытой фазы ablation. Пункт спрашивает:
# «становится ли система лучше оттого, что учится» — на это контрасты троек не отвечают,
# потому что их единица наблюдения ЗАДАЧА, а эффект самообучения имеет период дни-недели.
# Здесь единица — ПЕРИОД. Замер пассивный, по §8.2 протокола: мониторинг, не доказательство
# причинного эффекта. Троек не требует вовсе — а их за всю фазу main-1 было ноль
# (`journal.sh funnel`: registered 2, completed 0), и это решило выбор кандидата.
#
# Механизм = новый исполняемый файл в hooks/ или scripts/ (тесты не в счёт: они охраняют
# механизм, а не являются им). Признак «родился из знания» — введший его коммит ссылается
# на пункт долга (D<цифры>) либо на запись базы (case-/pattern-/principle-). Признак
# наблюдаемый: он в тексте коммита, а не в суждении о намерении.
#
# Что этот замер НЕ говорит — две границы, обе важны, чтобы не принять его за другой замер:
#   1. Он не отделяет механизм, который ПОМОГ, от механизма, который просто написан.
#      Доля «из знания» — про происхождение, не про пользу.
#   2. Он слабее поля `preceded_artifact` в базе знаний. Там вопрос: существовало ли знание
#      РАНЬШЕ артефакта (замер 2026-07-29 дал 0 из 8 хуков). Здесь вопрос мягче: ссылается
#      ли вводящий коммит на записанное рассуждение — а пункт долга мог быть заведён в той
#      же сессии, что и механизм. То есть высокая доля здесь НЕ означает, что знание
#      предшествовало; она означает, что построенное прослеживается до записанного повода.
#
# Использование: scripts/mechanisms-born.sh [дней]   (умолчание 30)
# Exit: 0 — прогон состоялся; 1 — за окно не родилось ни одного механизма из знания.
set -uo pipefail

DAYS="${1:-30}"
case "$DAYS" in ''|*[!0-9]*) echo "mechanisms-born: нужно число дней" >&2; exit 2 ;; esac

REPO=$(git rev-parse --show-toplevel 2>/dev/null) || { echo "не в репозитории" >&2; exit 2; }
cd "$REPO" || exit 2

SINCE="${DAYS} days ago"
TOTAL=0; FROM_KNOWLEDGE=0; LIST=""

# Новые исполняемые файлы механизмов за окно. --diff-filter=A — только добавленные.
FILES=$(git log --since="$SINCE" --diff-filter=A --name-only --pretty=format: -- hooks/ scripts/ 2>/dev/null \
        | grep -E '\.(sh|py)$' | grep -v '/tests/' | sort -u)

for f in $FILES; do
    [ -n "$f" ] || continue
    TOTAL=$((TOTAL + 1))
    # Сообщение коммита, ВВЕДШЕГО файл (последний в списке — самый ранний).
    MSG=$(git log --diff-filter=A --format='%s%n%b' -- "$f" 2>/dev/null | tail -40)
    if grep -qE '(^|[^A-Za-z])D[0-9]{1,4}([^0-9]|$)|case-[0-9]{4}-|pattern-[a-z]|principle-[a-z]' <<< "$MSG"; then
        FROM_KNOWLEDGE=$((FROM_KNOWLEDGE + 1))
        LIST="$LIST  ← $f"$'\n'
    fi
done

echo "МЕХАНИЗМЫ, ПОРОЖДЁННЫЕ ЗА ОКНО (${DAYS} дн.)"
echo "  новых механизмов      : $TOTAL"
echo "  из них родились из знания : $FROM_KNOWLEDGE"
if [ "$TOTAL" -gt 0 ]; then
    echo "  доля                  : $(( FROM_KNOWLEDGE * 100 / TOTAL ))%"
fi
[ -n "$LIST" ] && { echo "  что именно:"; printf '%s' "$LIST"; }
echo
echo "Единица наблюдения — период, не задача (D96). Признак происхождения — ссылка на пункт"
echo "долга или запись базы в тексте вводящего коммита; про пользу механизма замер молчит."
echo "Слабее, чем preceded_artifact: повод мог быть записан в той же сессии, что и механизм."

if [ "$FROM_KNOWLEDGE" -eq 0 ]; then
    echo "[замер: находки, не сбой] — за окно ни один механизм не сослался на знание"
    exit 1
fi
exit 0
