#!/usr/bin/env bash
# backlog-return-check.sh — не наступило ли условие возврата у ОТКРЫТОГО пункта долга.
# Результат: у каждого ОТКРЫТОГО пункта есть исполнимое условие возврата либо явная пометка «решение»
# Проверка результата: bash scripts/backlog-return-check.sh даёт 0
#
# en: has an OPEN debt item's return condition already fired?
#
# Зеркало к `backlog-recheck.sh`. Тот проверяет, что ЗАКРЫТОЕ осталось закрытым; этот —
# что ОТКРЫТОЕ ещё имеет право быть открытым. Между ними была дыра, и она объясняет, почему
# долг только рос: пункты входили, а проверять, могут ли они выйти, было некому.
#
# Повод измерен 27 августа 2026 проходом по девяти открытым пунктам. Два условия из девяти
# оказались НЕВЫПОЛНИМЫМИ ПО ПОСТРОЕНИЮ:
#   D71 «доля разметки перевалит за 50%» — весь ~/.claude/usage-data датирован 2026-08-21
#       18:31 одним разовым выгрузом; доля не растёт, потому что её ничто не производит.
#   D92 «выборка дорастёт до десяти реплик с зачином-двоеточием» — пункт сам говорит, что
#       «счёт зачинов добавляется одной строкой», и строка так и не была добавлена.
# Оба ждали события, которого не могло случиться. Это тот же класс, что закрытая в тот же
# день фаза ablation: запрет держался на флаге, а не на данных, и охранял пустоту.
#
# Корень, который закрывает этот скрипт: условие возврата записывалось ПРОЗОЙ С ДАТОЙ, а
# читалось как нынешнее состояние. Текстовое условие может ссылаться на замер, которого не
# существует, и молчать об этом годами; запускаемое — падает на первом же прогоне.
#
# Контракт пункта. Внутри блока открытого пункта одна из двух строк:
#   **Проверка возврата:** `<команда>`     — exit 0 = условие наступило, иначе нет
#   **Проверка возврата:** решение         — условие не событие, а слово владельца
# Ни одной — пункт попадает в раздел «проверки нет», и это дефект пункта, а не скрипта.
# Строка НАЧИНАЕТ строку файла (после отступа). То же сочетание в середине предложения —
# цитата описания, а не контракт, и последствие у неё ровно одно: командой она не является.
#
# Команды берутся из BACKLOG.md того же репозитория — тот же уровень доверия, что Makefile.
#
# Использование: scripts/backlog-return-check.sh [--quiet]
# Exit: 0 — прогон состоялся; 1 — есть пункты БЕЗ проверки (дефект ведения).
set -uo pipefail

REPO=$(git rev-parse --show-toplevel 2>/dev/null) || REPO="$(cd "$(dirname "$0")/.." && pwd)"
B="$REPO/BACKLOG.md"
[ -f "$B" ] || { echo "backlog-return-check: нет $B" >&2; exit 2; }

QUIET=0
[ "${1:-}" = "--quiet" ] && QUIET=1

FIRED=""; WAITING=""; DECISION=""; NOCHECK=""; TIMED=""
# БЮДЖЕТ ВРЕМЕНИ НА КОМАНДУ ПУНКТА (D369, корень R6). Команда пункта чужая, и цена у неё
# любая: 8 сентября 2026 в «Проверку возврата» D368 попал запуск всего набора — страж честно
# ждал 300 с, и наружу выходило «назвал 0 пунктов», та же строка, что при «проверять нечего».
# Срыв срока — ОТДЕЛЬНЫЙ исход с именем пункта; ограничитель — библиотека `hooks/timeout-lib.sh`,
# общая со сторожем набора: копия здесь была бы носителем рода K. Без библиотеки исполнять чужие
# команды без срока нельзя — код 2, а не тишина.
RETURN_CHECK_TIMEOUT="${RETURN_CHECK_TIMEOUT:-30}"
if [ -n "${TIMEOUT_LIB:-}" ]; then _TO_LIB="$TIMEOUT_LIB"
else
    # От каталога СКРИПТА, а не от REPO: страж запускается и в чужом репозитории (песочницы
    # тестов, проект сессии), где hooks/ нет; так же берётся и backlog-lib ниже.
    _TO_LIB="$(cd "$(dirname "$0")/../hooks" 2>/dev/null && pwd)/timeout-lib.sh"
    [ -f "$_TO_LIB" ] || _TO_LIB="$HOME/.claude/hooks/timeout-lib.sh"
fi
[ -f "$_TO_LIB" ] || { echo "backlog-return-check: нет timeout-lib.sh ($_TO_LIB) — команды пунктов без бюджета времени исполнять нельзя" >&2; exit 2; }
# shellcheck source=/dev/null
. "$_TO_LIB"

# Опознание пункта — из общей библиотеки, а не своей копией признака: копия здесь уже
# отказала. С 28 августа 2026 пункты верстаются заголовком, и этот страж видел НОЛЬ
# открытых пунктов, то есть условия возврата не проверялись ни у одного.
_BL_LIB="$(cd "$(dirname "$0")/../hooks" 2>/dev/null && pwd)/backlog-lib.sh"
[ -f "$_BL_LIB" ] || _BL_LIB="$HOME/.claude/hooks/backlog-lib.sh"
# shellcheck source=hooks/backlog-lib.sh
. "$_BL_LIB"

# Библиотека СТАРШЕ этого скрипта — отказ, а не умолчание. Установленная копия
# (`~/.claude/hooks/backlog-lib.sh`) обновляется отдельным шагом install.sh, и «новый
# скрипт при старой библиотеке» — штатное промежуточное состояние машины. Без забора
# `backlog_strip_fenced` не нашлась бы, конвейер отдал бы ПУСТО, и страж объявил бы, что
# открытых пунктов нет вовсе, кодом 0. Признак с одним последствием, адрес отказа здесь же
# (тот же приём стоит в `scripts/backlog-archive.sh`).
command -v backlog_strip_fenced >/dev/null 2>&1 || {
    echo "backlog-return-check: библиотека $_BL_LIB старше скрипта (нет backlog_strip_fenced)" >&2
    exit 2
}
# Второе имя того же забора (12 сентября 2026): разбор пункта на поля переехал в
# `backlog_open_items`, и старая библиотека без неё дала бы пустой конвейер и код 0 —
# «открытых пунктов нет» при живом долге. Оба имени держатся намеренно: нога 23 теста
# вырезает `backlog_strip_fenced`, и забор с одним новым именем позеленел бы вхолостую.
command -v backlog_open_items >/dev/null 2>&1 || {
    echo "backlog-return-check: библиотека $_BL_LIB старше скрипта (нет backlog_open_items)" >&2
    exit 2
}

# Пункты разбираются БЛОКАМИ, а не перечнем идентификаторов, и роль строки задаётся её
# положением в блоке, а не видом. Прежняя редакция брала идентификаторы потоком и
# восстанавливала блок обратным поиском `$0 ~ i` — то есть ПОДСТРОЧНЫМ сравнением:
# строка `- ☐ **D280**` удовлетворяла шаблону `D28`, а `- ☐ **D284** … — родня D279` —
# шаблону `D279`, и страж читал условие ЧУЖОГО пункта (прожарка 3 сентября 2026, атака 4).
# Тем же устройством пункт без D-номера (`- ☐ **R7.1**`) не попадал в цикл вовсе и не
# проверялся ни разу, а страж выходил нулём (атака a2). Блок несёт свою голову с собой,
# поэтому обратный поиск по идентификатору не нужен вообще.
#
# Контрактная строка — ЯКОРЕМ НА НАЧАЛО СТРОКИ (после отступа), и это не стиль.
# `grep -m1 -F` находил литерал ГДЕ УГОДНО, включая прозу пункта, а `sed` брал следующую
# пару обратных кавычек за команду и отдавал её в `bash -c`: пункт, у которого условия
# возврата нет вовсе, объявлялся зелёным, а процитированная в его же теле команда
# исполнялась (атака 5). Тот же корень закрыт 1 сентября в `scripts/backlog-archive.sh:166`
# и `hooks/completion-gate.sh:163` по поводу D244 — до этого брата якорь не дошёл.
# Слово `решение` читается тоже ПОСЛЕ литерала, а не где угодно в строке: иначе команда
# `grep решение …` была бы принята за слово владельца.
#
# Идентификатор — общей функцией библиотеки от ГОЛОВЫ блока, не своей копией признака:
# копия здесь уже расходилась молча (T6 в test_backlog_item_shape, 3 сентября 2026).
#
# У БЛОКА ГРАНИЦ ТРИ, А НЕ ОДНА. Прежняя редакция закрывала блок только следующей строкой
# пункта, поэтому блок последнего пункта раздела тянулся до конца файла, поглощая
# заголовки и прозу: контрактная строка ПОЯСНИТЕЛЬНОГО раздела ниже приписывалась пункту
# выше, и пункт без условия объявлялся зелёным (прожарка 3 сентября 2026, атака N2).
# Границы теперь называют структуру документа целиком:
#   · строка пункта ОТКРЫВАЕТ блок;
#   · заголовок-СОСЕД, пунктом не являющийся, ЗАКРЫВАЕТ его;
#   · строки внутри забора кода — текст, а не структура, и не рассматриваются вовсе.
# Третья граница закрывает атаку N1: шапка самого BACKLOG.md цитирует контракт образцом
# внутри забора (строки 18-22), и такой образец исполнялся как настоящее условие.
# Она же отменяет пункт, нарисованный внутри забора примером.
#
# ЗАБОР — БИБЛИОТЕЧНЫЙ, СВОЕЙ КОПИИ ПРИЗНАКА ЗДЕСЬ НЕТ. Первая редакция этой правки
# написала границу инлайном (`/^[[:space:]]*```/`) — то есть завела ТРЕТЬЮ копию признака,
# и она оказалась уже владельца: библиотека знает обе формы забора (```  и ~~~), а копия
# знала одну. Следствия замерены проверкой 3 сентября 2026: контракт, процитированный
# внутри `~~~`, исполнялся (V1), а пункт, нарисованный там же, разбирался как настоящий
# (V4). Забор снимается ПОТОКОМ, до awk, той самой функцией библиотеки, которой его
# снимают `backlog_ids` и архиватор, — тогда расходиться нечему.
#
# ЗАГОЛОВОК ЗАКРЫВАЕТ БЛОК ПО РОЛИ, А НЕ ПО ВИДУ. Первая редакция закрывала блок на
# ЛЮБОЙ строке с решётками, и подзаголовок ВНУТРИ пункта заголовочной вёрстки
# (`#### Подробности` под `### D820 ☐ …`) отрезал пункт от его же условия: пункт с
# исполнимой командой объявлялся дефектом ведения (V3, регрессия того же дня). Роль
# различается уровнем: у пункта-заголовка уровня L закрывают заголовки уровня ≤ L
# (сосед либо старший), а более глубокие суть его собственные подразделы; у пункта
# списочной вёрстки своего уровня нет, и его закрывает любой заголовок.
#
# СТАТУС — ПЕРВОЙ МЕТКОЙ СТРОКИ, а не наличием метки где угодно. Прежнее `$0 ~ OPEN_RE`
# у заголовочной вёрстки принимало метку в любом месте строки, и ЗАКРЫТЫЙ пункт, чей
# заголовок поминает прежнее состояние («### D905 ☑ done … (было ◐)»), читался открытым
# (атака N3). Библиотека этот разрыв уже назвала и завела для него сито
# `backlog_status_is`; awk обходит файл целиком и построчно звать оболочку не может,
# поэтому здесь применяется то же ПРАВИЛО на константах библиотеки — набор меток и их
# альтернация берутся у неё, своей копии признака не заводится.
# РАЗБОР ЖИВЁТ В БИБЛИОТЕКЕ (12 сентября 2026): awk со всеми границами выше перенесён в
# `backlog_open_items` (hooks/backlog-lib.sh) — коллектору на Stop понадобился тот же
# разбор, и вторая копия разошлась бы молча (D305). Довод к каждой границе оставлен здесь,
# где он был доказан прожаркой; сама реализация — одна.
# РАЗДЕЛИТЕЛЬ ДЛЯ `read` — \037, не табуляция. Библиотека отдаёт TSV, но у большинства
# пунктов очередь и корень пусты, а для `read` табуляция — ПРОБЕЛЬНЫЙ разделитель: подряд
# идущие пустые поля схлопываются, команда уезжает в переменную корня, `bash -c ""` даёт 0
# — и каждый пункт объявляется «НАСТУПИЛО» (8 красных ног, первый прогон 12 сентября 2026).
# awk с -F"\t" пустые поля хранит; он и переставляет разделитель на непробельный.
while IFS="$(printf '\037')" read -r id mark kind q root cmd chk; do   # chk — «Проверка.», здесь не нужна, но поле занято (D264)
    [ -n "$id" ] || continue
    case "$kind" in
        decision) DECISION="$DECISION $id" ;;
        cmd)
            ( cd "$REPO" && run_with_timeout "$RETURN_CHECK_TIMEOUT" bash -c "$cmd" ) >/dev/null 2>&1 </dev/null
            _rc=$?
            case "$_rc" in
                0)   FIRED="$FIRED $id" ;;
                124) TIMED="$TIMED $id" ;;
                *)   WAITING="$WAITING $id" ;;
            esac ;;
        *) NOCHECK="$NOCHECK $id" ;;
    esac
done < <(backlog_open_items "$B" | awk -F'\t' 'BEGIN { OFS = "\037" } { $1 = $1; print }')

if [ "$QUIET" -eq 0 ]; then
    echo "Условия возврата открытых пунктов:"
    [ -n "${FIRED# }" ]    && echo "  ✅ НАСТУПИЛО — пора закрывать или двигать:$FIRED"
    [ -n "${WAITING# }" ]  && echo "  ⏳ ещё нет:$WAITING"
    [ -n "${DECISION# }" ] && echo "  🧑 ждут решения владельца, не события:$DECISION"
    if [ -n "${TIMED# }" ]; then
        echo "  ⚠️  СРОК ИСТЁК (${RETURN_CHECK_TIMEOUT} с на команду, RETURN_CHECK_TIMEOUT) — исход неизвестен, пункт НЕ проверен:$TIMED"
        echo "     Команда пункта дороже бюджета стража. Дай ей срок либо замени дешёвой проверкой."
    fi
    if [ -n "${NOCHECK# }" ]; then
        echo "  ⚠️  ПРОВЕРКИ НЕТ:$NOCHECK"
        echo "     Условие держится прозой. Оно может ссылаться на замер, которого не"
        echo "     существует, и молчать об этом сколько угодно — так вышло с D71 и D92."
        echo "     Допиши в пункт: **Проверка возврата:** \`<команда>\` либо \`решение\`."
    fi
fi

[ -z "${NOCHECK# }" ] && [ -z "${TIMED# }" ]
