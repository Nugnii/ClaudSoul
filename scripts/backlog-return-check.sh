#!/usr/bin/env bash
# backlog-return-check.sh — не наступило ли условие возврата у ОТКРЫТОГО пункта долга.
# Результат: у каждого ОТКРЫТОГО пункта есть исполнимое условие возврата либо явная пометка «решение»
# Проверка результата: bash scripts/backlog-return-check.sh даёт 0
#
# en: has an OPEN debt item's return condition already fired?
#
# Зеркало к `backlog-recheck.sh`. Тот проверяет, что ЗАКРЫТОЕ осталось закрытым; этот —
# что ОТКРЫТОЕ ещё имеет право быть открытым. Между ними была дыра, и она объясняет, почему
# долг только рос: пункты входили, а проверять, могут ли они выйти, было некому.
#
# Повод измерен 27 августа 2026 проходом по девяти открытым пунктам. Два условия из девяти
# оказались НЕВЫПОЛНИМЫМИ ПО ПОСТРОЕНИЮ:
#   D71 «доля разметки перевалит за 50%» — весь ~/.claude/usage-data датирован 2026-08-21
#       18:31 одним разовым выгрузом; доля не растёт, потому что её ничто не производит.
#   D92 «выборка дорастёт до десяти реплик с зачином-двоеточием» — пункт сам говорит, что
#       «счёт зачинов добавляется одной строкой», и строка так и не была добавлена.
# Оба ждали события, которого не могло случиться. Это тот же класс, что закрытая в тот же
# день фаза ablation: запрет держался на флаге, а не на данных, и охранял пустоту.
#
# Корень, который закрывает этот скрипт: условие возврата записывалось ПРОЗОЙ С ДАТОЙ, а
# читалось как нынешнее состояние. Текстовое условие может ссылаться на замер, которого не
# существует, и молчать об этом годами; запускаемое — падает на первом же прогоне.
#
# Контракт пункта. Внутри блока открытого пункта одна из двух строк:
#   **Проверка возврата:** `<команда>`     — exit 0 = условие наступило, иначе нет
#   **Проверка возврата:** решение         — условие не событие, а слово владельца
# Ни одной — пункт попадает в раздел «проверки нет», и это дефект пункта, а не скрипта.
#
# Команды берутся из BACKLOG.md того же репозитория — тот же уровень доверия, что Makefile.
#
# Использование: scripts/backlog-return-check.sh [--quiet]
# Exit: 0 — прогон состоялся; 1 — есть пункты БЕЗ проверки (дефект ведения).
set -uo pipefail

REPO=$(git rev-parse --show-toplevel 2>/dev/null) || REPO="$(cd "$(dirname "$0")/.." && pwd)"
B="$REPO/BACKLOG.md"
[ -f "$B" ] || { echo "backlog-return-check: нет $B" >&2; exit 2; }

QUIET=0
[ "${1:-}" = "--quiet" ] && QUIET=1

FIRED=""; WAITING=""; DECISION=""; NOCHECK=""

# Опознание пункта — из общей библиотеки, а не своей копией признака: копия здесь уже
# отказала. С 28 августа 2026 пункты верстаются заголовком, и этот страж видел НОЛЬ
# открытых пунктов, то есть условия возврата не проверялись ни у одного.
_BL_LIB="$(cd "$(dirname "$0")/../hooks" 2>/dev/null && pwd)/backlog-lib.sh"
[ -f "$_BL_LIB" ] || _BL_LIB="$HOME/.claude/hooks/backlog-lib.sh"
# shellcheck source=hooks/backlog-lib.sh
. "$_BL_LIB"

# Идентификаторы открытых пунктов в порядке появления.
IDS=$(grep -E "$(backlog_item_re "$BACKLOG_OPEN_MARKS")" "$B" | grep -oE 'D[0-9]+')
ITEM_RE=$(backlog_item_re)

for id in $IDS; do
    # Блок пункта: от его строки до строки СЛЕДУЮЩЕГО пункта (граница по пункту, не по
    # маркеру конца раздела — правка по диапазону уносила соседей, см. D91).
    BLOCK=$(awk -v i="$id" -v re="$ITEM_RE" '
        $0 ~ re && $0 ~ i { p=1 }
        p && $0 ~ re && $0 !~ i { exit }
        p { print }' "$B")

    LINE=$(printf '%s\n' "$BLOCK" | grep -m1 -F '**Проверка возврата:**' || true)
    if [ -z "$LINE" ]; then
        NOCHECK="$NOCHECK $id"
        continue
    fi
    # Решение владельца — не событие, проверять нечего.
    case "$LINE" in *'решение'*) DECISION="$DECISION $id"; continue ;; esac

    CMD=$(printf '%s\n' "$LINE" | sed -E 's/.*\*\*Проверка возврата:\*\*[[:space:]]*`(.*)`.*/\1/')
    if [ -z "$CMD" ] || [ "$CMD" = "$LINE" ]; then
        NOCHECK="$NOCHECK $id"
        continue
    fi
    if ( cd "$REPO" && bash -c "$CMD" ) >/dev/null 2>&1; then
        FIRED="$FIRED $id"
    else
        WAITING="$WAITING $id"
    fi
done

if [ "$QUIET" -eq 0 ]; then
    echo "Условия возврата открытых пунктов:"
    [ -n "${FIRED# }" ]    && echo "  ✅ НАСТУПИЛО — пора закрывать или двигать:$FIRED"
    [ -n "${WAITING# }" ]  && echo "  ⏳ ещё нет:$WAITING"
    [ -n "${DECISION# }" ] && echo "  🧑 ждут решения владельца, не события:$DECISION"
    if [ -n "${NOCHECK# }" ]; then
        echo "  ⚠️  ПРОВЕРКИ НЕТ:$NOCHECK"
        echo "     Условие держится прозой. Оно может ссылаться на замер, которого не"
        echo "     существует, и молчать об этом сколько угодно — так вышло с D71 и D92."
        echo "     Допиши в пункт: **Проверка возврата:** \`<команда>\` либо \`решение\`."
    fi
fi

[ -z "${NOCHECK# }" ]
