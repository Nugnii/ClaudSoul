#!/usr/bin/env bash
# measure-linux-parity.sh — проходит ли набор на машине БЕЗ установленного ClaudSoul.
# Результат: набор тестов зелёный на машине без установленного ClaudSoul
# Проверка результата: bash scripts/measure-linux-parity.sh даёт 0
#
#
# Отдельным скриптом, потому что у замера должен быть исполнимый вид: строка в реестре
# `scripts/measurements.tsv` обязана указывать на команду, а не на инструкцию в документации.
# Рецепт живёт ТОЛЬКО здесь; docs/development.md на него ссылается. До 12 сентября 2026 копия
# рецепта стояла и там и разошлась со скриптом в день, когда рецепт выровняли (R1).
set -uo pipefail
# Каталог скрипта — подстановкой параметра, без `dirname`: в урезанном PATH свидетеля внешней
# команды нет, подстановка вырождалась в `cd -- "/.."`, REPO становился `/`, и в контейнер
# монтировался корень диска (прожарка 13 сентября 2026, атака 5).
_self="${BASH_SOURCE[0]:-$0}"; _self_dir="${_self%/*}"; [ "$_self_dir" = "$_self" ] && _self_dir=.
REPO="${CLAUDSOUL_REPO:-$(cd -- "$_self_dir/.." 2>/dev/null && pwd -P)}"
# Корень обязан быть деревом ClaudSoul: монтировать наугад найденный каталог нельзя.
[ -f "$REPO/hooks/tests/run_all.sh" ] || { echo "measure-linux-parity: корень дерева не найден (${REPO:-пусто}) — не измерено"; exit 2; }
# Без docker замер НЕ ИЗМЕРЕН (код 2), а не зелёный: «пропущен» с кодом 0 читался планировщиком как успех.
command -v docker >/dev/null 2>&1 || { echo "measure-linux-parity: docker недоступен — не измерено"; exit 2; }
# Дерево едет в контейнер ПОТОКОМ на вход `docker run -i`, а не монтированием папки этой машины (D1355, решение
# владельца 22 ноября 2026 «Дерево потоком»). С `-v "$PWD":/repo` docker, направленный на другую машину (контекст
# `server` — домашний сервер владельца — либо DOCKER_HOST=ssh://…), смонтировал бы там пустую папку с тем же путём,
# поэтому такой docker был «не измерено»: набор в чистой рамке не мерился вовсе, и стоял гейт публикации. Потоку
# безразлично, где демон. Состав — отслеживаемые и неигнорируемые файлы плюс `.git` (тестам он нужен), то есть рамка CI:
# чистый checkout тоже без игнорируемого. Замер того же дня: 84 МБ потока против 543 МБ папки целиком.
command -v git >/dev/null 2>&1 && command -v tar >/dev/null 2>&1 \
  || { echo "measure-linux-parity: нет git или tar — дерево в контейнер не передать; не измерено"; exit 2; }
docker info >/dev/null 2>&1 || { echo "measure-linux-parity: демон docker не запущен — не измерено"; exit 2; }
cd "$REPO" || exit 2
# Рамка контейнера — та же, что у раннера GitHub, иначе замер мерит не «машину без ClaudSoul»,
# а свойства своего контейнера: 12 сентября 2026 он дал 35 красных при зелёном CI на том же
# дереве — 21 раз `No module named 'yaml'` (python3-yaml на раннере есть) и тесты прав, которые
# root игнорирует (T2d «read-only не сработал»). Поэтому: python3-yaml и непривилегированный
# пользователь. perl нужен сверщику понятий и вырезанию доктрины.
# Второй заход того же дня (D404), 5 красных → 0. procps: `pgrep -P` снимает дерево сторожа
# (run_all.sh:103) — без него `sleep` сторожа переживает родителя, держит трубу подстановки
# `$(run_all.sh)` в test_run_all_parallel, и тест висит до срока; `ps -p` судит живость сессии
# (session-registry-lib.sh:120). LANG=C.UTF-8: локаль образа POSIX, и `grep -i` не сворачивает
# регистр кириллицы, тогда как на раннере C.UTF-8 (тесты доктрины с `grep -qi` там зелёные).
# Образ — та же версия Ubuntu, что `runs-on` в `.github/workflows/tests.yml` (D1316): до 18 ноября 2026 здесь
# стоял `debian:stable-slim` с GNU coreutils, а метка раннера `ubuntu-latest` молча переехала на 26.04, где coreutils
# на Rust (uutils 0.10.0) — `mkdir` неисключителен, `cksum` экранирует имена, `date` не берёт 9999 год, — и три теста
# краснели только на CI. Равенство образа и метки сверяет `hooks/tests/test_measure_linux_parity.sh` (T6).
# Оставлено одно расхождение, названное. awk здесь mawk (умолчание Debian и Ubuntu), побайтовый: скобка
# `[Бб]` в нём не совпадает с двухбайтовой буквой, а awk раннера совпадает. Это более строгая
# рамка, а не шум: 12 сентября она нашла дефект module-context-inject.sh:90.
# С 22 ноября 2026 этим рецептом гонит набор и CI (шаг `Hook tests` в tests.yml), поэтому gitleaks ставится здесь, а
# не шагом workflow: без него страж секретов выходит без решения, и слой секретов в чистой рамке не мерится (решение
# владельца 12 сентября 2026). Версия та же, что стояла в workflow; архив по архитектуре контейнера (x64 на сервере,
# arm64 на Mac); конфиг страж берёт из security/gitleaks.toml дерева, когда ~/.claude/security нет. Не скачался —
# строка «не поставлен», тест стража назовёт пропуск. На CI (`CI` задан) журнал набора
# идёт наружу целиком и по ходу, а не сводкой в конце: разбор упавшего прогона идёт по журналу задачи, а задача,
# молчащая полчаса, неотличима от зависшей.
# Поток: список файлов — у git (с NUL-разделителем: в именах бывают пробелы), архив — tar с `--null -T -`, который
# понимают и bsdtar macOS, и GNU tar сервера; `COPYFILE_DISABLE` и `--no-xattrs` не дают macOS вложить `._`-файлы и
# расширенные атрибуты. Ошибки tar этой машины (файл исчез посреди чтения — фоновые хуки берут и снимают замки) идут в
# stderr как есть: копия неполна — и это названо, а прогон идёт. Код замера — код контейнера, третьего звена трубы:
# под `pipefail` код всей трубы дал бы tar, убитый SIGPIPE, если контейнер не дочитал вход.
{ git ls-files -z -co --exclude-standard; printf '.git\0'; } \
  | COPYFILE_DISABLE=1 tar --null --no-xattrs -T - -cf - \
  | docker run --rm -i -e CI -w /work ubuntu:26.04 bash -c '
  # Распаковка ПЕРВОЙ: вход — поток дерева, и всё, что читает stdin раньше tar, съело бы его начало.
  # «Ignoring unknown extended header keyword» — заголовки bsdtar, которых GNU tar не знает; не ошибка.
  mkdir -p /work && tar -xf - -C /work 2>/tmp/tar.err \
    || echo "measure-linux-parity: распаковка дерева неполна: $(grep -v "unknown extended header" /tmp/tar.err | head -3 | tr "\n" " ")"
  apt-get update -qq >/dev/null 2>&1 </dev/null && apt-get install -y -qq jq git python3 python3-yaml perl procps curl ca-certificates >/dev/null 2>&1 </dev/null
  a=$(dpkg --print-architecture); [ "$a" = amd64 ] && a=x64
  curl -fsSL "https://github.com/gitleaks/gitleaks/releases/download/v8.30.1/gitleaks_8.30.1_linux_${a}.tar.gz" | tar -xz -C /usr/local/bin gitleaks 2>/dev/null \
    || echo "measure-linux-parity: gitleaks не поставлен — слой секретов не измерен"
  useradd -m tester 2>/dev/null
  # Строка `FAILED:<имена>` сводки (run_all.sh:495) сохраняется: `tail -2` оставлял только код,
  # и замер 12 сентября 2026 сказал «ЕСТЬ НАХОДКИ», не назвав ни одного теста
  # (case-2026-09-11-result-lived-only-in-the-output). Код выхода — код раннера.
  # Дерево ЖИВОЕ: фоновые хуки хозяина в это время берут и снимают замки (`BACKLOG.md.lock`). Когда копию делал cp,
  # исчезнувший посреди копии каталог давал код ошибки, `&&` пропускал chown, и тесты шли без права записи в /work —
  # 30 ложных падений 20 октября 2026. Поэтому неполнота потока называется, а chown идёт всегда. `git archive` не
  # годится: тестам нужен `.git`.
  chown -R tester /work
  run() { su tester -c "cd /work/hooks/tests && LANG=C.UTF-8 bash run_all.sh"; }
  if [ -n "${CI:-}" ]; then run 2>&1 | tee /tmp/run.log; rc=${PIPESTATUS[0]}
  # Сводка «Hook test files:» берётся по имени, а не `tail -2`: с 11 сентября 2026 (edbcd218) после неё run_all.sh
  # печатает список тестов дороже 20 с, и хвост был списком — зелёный замер выходил без числа (D1355). Сводки нет
  # (прогон оборвался до неё) — хвост, как прежде.
  else run > /tmp/run.log 2>&1; rc=$?; grep -E "^FAILED:" /tmp/run.log; grep -E "^Hook test files:" /tmp/run.log || tail -2 /tmp/run.log; fi; exit $rc'
exit "${PIPESTATUS[2]}"
