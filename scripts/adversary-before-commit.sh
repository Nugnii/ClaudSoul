#!/usr/bin/env bash
# adversary-before-commit.sh — доля крупных кодовых коммитов, ушедших без адверсариального прогона.
#
# Результат: названо число — сколько РАЗНЫХ крупных кодовых диффов пошло в коммит и в
#            скольких из них адверсариального прогона в сессии не было
# Проверка результата: bash scripts/adversary-before-commit.sh печатает обе величины и даёт 1,
#            когда доля без прогона выше половины при достаточном знаменателе
#
# Зачем (D372). Правило «перед сдачей — свежий критик» держал один хук уровня инжект, и
# спросить «а исполняется ли оно» было нечем: `code-review-reminder` выходил из ветки
# «прогон был» ДО единственной записи на диск, поэтому на диске жил только числитель
# (52 файла, 77 строк голых md5, читателей ноль). Знаменателя не существовало по
# построению — тот самый дефект, что описан в `hooks/root-cause-lib.sh` про `*-fired-*`.
#
# ЧТО РЕШАЕТ ЭТО ЧИСЛО. Оно — вход в лестницу ADR-015: доля без прогона выше половины при
# доле ложных ниже десятой части есть повод поднять уровень принуждения. Само по себе оно
# уровень не поднимает: у признака «крупный дифф без прогона» последствие не одно, а хук
# сознательно ошибается в сторону лишнего напоминания (`code-review-reminder.sh` шапка),
# что прямо противоположно условию уровня 4. Число отвечает «исполняется ли правило», а
# не «пора ли отказывать».
#
# ЕДИНИЦА СЧЁТА — РАЗНЫЙ ДИФФ, А НЕ ВЫЗОВ. Событие берётся по подписи (хеш кодовой части
# диффа) внутри сессии, и у подписи считается ПЕРВАЯ запись по времени: вопрос замера —
# «когда этот дифф впервые пошёл в коммит, прогон уже был?». Считать все записи значило бы
# мерить объём работы (сколько раз агент позвал `git commit`), а не частоту предмета.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ.
#  1. Прогон засчитывается ЛЮБОЙ в той же сессии, без проверки свежести контекста критика.
#     D331 объявил такой зачёт недостаточным для необратимых публикаций; здесь предмет
#     другой (коммит откатывается), но допущение то же и называется, а не подразумевается.
#  2. Прогон из ДРУГОЙ сессии засчитывается стражем с 13 сентября 2026 (D373), если случился
#     после времени HEAD; в знаменатель он приходит как `satisfied` без пометки — откуда был
#     прогон, различает ретро-прогон (`adversary-replay.sh`), а не этот замер. Записи старше
#     этой даты несут прежнее смещение: «без прогона» завышено.
#  3. Записи без подписи (журналы старше 9 сентября 2026) считаются по одной за запись —
#     дедуп по диффу к ним неприменим. Их число печатается отдельно, чтобы «ноль» не
#     оказался тишиной прибора.
#  4. Целостность пары фаз читается по следствию, а не по регистрации (D374): немая вторая
#     половина видна лишь когда ожидания есть, а записей нет. Половина, теряющая ЧАСТЬ
#     записей, даёт только мягкий сигнал «ожиданий больше подтверждённых», без кода.
#     Условие снятия: у ожидания появится собственный исход в журнале (запись отменённого
#     коммита отдельно от подтверждённого) — тогда потеря части записей станет считаемой.
#
# ОКНО В СЕССИЯХ, А НЕ В ДНЯХ: ритм работы неравномерный.
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${ADVERSARY_COMMIT_SESSIONS:-20}"
MIN_N="${ADVERSARY_COMMIT_MIN_N:-20}"
GUARD="code-review-reminder"
command -v jq >/dev/null 2>&1 || { echo "adversary-before-commit: нет jq — не измерено"; exit 2; }

FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/detection-*.jsonl 2>/dev/null | head -n "$SESSIONS")
EOF
# --- Целостность пары фаз (D374). Страж на PreToolUse пишет ожидание в crr-pending-<SID>.jsonl,
# а в знаменатель его переводит вторая половина — code-review-outcome.sh на PostToolUse. Второй
# половины может не быть (не зарегистрирована, сломана), и тогда «меньше событий» неотличимо от
# «столько было». Признак здесь ПОВЕДЕНЧЕСКИЙ, а не чтение settings.json: регистрацию сверяет
# drift-check (пара «регистрация хуков»), здесь читается СЛЕДСТВИЕ — ожидания копятся, а в
# журнал не попадает ничего. Ожидание без исхода само по себе законно: коммит отменён или упал
# (7% вызовов в корпусе), поэтому число печатается всегда, а кодом 2 отвечает лишь сочетание
# «ожидания есть, записей стража нет». Окно — то же, что у журналов: файлы ожидания старше
# самого старого журнала окна не считаются.
PEND_LINES=0; PEND_FILES=0
_OLDEST=""
[ "${#FILES[@]}" -gt 0 ] && _OLDEST="${FILES[$(( ${#FILES[@]} - 1 ))]}"
for _p in "$STATE"/crr-pending-*.jsonl; do
    [ -s "$_p" ] || continue
    if [ -n "$_OLDEST" ] && [ "$_p" -ot "$_OLDEST" ]; then continue; fi
    _c=$(grep -c . "$_p" 2>/dev/null); case "${_c:-}" in ''|*[!0-9]*) _c=0 ;; esac
    PEND_LINES=$(( PEND_LINES + _c )); PEND_FILES=$(( PEND_FILES + 1 ))
done
_pending_report() {
    echo "  ожиданий без исхода (crr-pending: PreToolUse без подтверждённого коммита): $PEND_LINES строк в $PEND_FILES сессиях"
}
_second_half_mute() {
    echo "  ВТОРАЯ ПОЛОВИНА ПАРЫ НЕ СРАБАТЫВАЕТ: ожидания копятся, а в знаменатель не попало ни одной записи —"
    echo "  code-review-outcome.sh их не переводит; проверь регистрацию (drift-check, пара «регистрация хуков»)"
}
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "журналов признаков нет: замерять нечего (STATE=$STATE)"
    if [ "$PEND_LINES" -gt 0 ]; then
        _pending_report; _second_half_mute; exit 2
    fi
    exit 0
fi

# Посессионно, а не одним слурпом: подпись — хеш диффа, и один и тот же дифф в двух
# сессиях есть ДВА события. Идентификатор сессии живёт в имени файла, а не в записи,
# поэтому дедуп по подписи законен только внутри файла (тот же приём — violation-class.sh).
NORUN=0
RUN=0
NOSIG=0
UNREADABLE=0
_CLEAN=$(mktemp) || { echo "нет временного файла"; exit 2; }
trap 'rm -f "$_CLEAN"' EXIT
for _f in "${FILES[@]}"; do
    # ЧИСТКА ПЕРЕД СЛУРПОМ. Прежде стояло `... ) || continue`: одна оборванная строка
    # роняла разбор ВСЕЙ сессии, и её читаемые события исчезали из знаменателя молча —
    # прибор печатал меньшее «всего» и заключал «правило исполняется». Это ровно то
    # различение «нет» против «не измерил», ради которого написана нога T3 теста.
    # Канон идиомы — `scripts/injection-outcome.sh`. Поймано противником 9 сентября 2026.
    jq -cRn 'inputs | fromjson? // empty' "$_f" > "$_CLEAN" 2>/dev/null
    if [ -s "$_f" ] && [ ! -s "$_CLEAN" ]; then
        UNREADABLE=$(( UNREADABLE + 1 ))
        continue
    fi
    _acts=$(jq -rs --arg g "$GUARD" '
        map(select(.guard == $g and (.sig // "") != ""))
        | sort_by(.ts) | group_by(.sig) | map(.[0].act) | .[]
    ' "$_CLEAN" 2>/dev/null) || { UNREADABLE=$(( UNREADABLE + 1 )); continue; }
    while IFS= read -r _a; do
        case "$_a" in
            satisfied) RUN=$(( RUN + 1 )) ;;
            said|muted) NORUN=$(( NORUN + 1 )) ;;
        esac
    done <<EOF
$_acts
EOF
    _n=$(jq -rs --arg g "$GUARD" 'map(select(.guard == $g and (.sig // "") == "")) | length' "$_CLEAN" 2>/dev/null)
    case "${_n:-}" in ''|*[!0-9]*) _n=0 ;; esac
    NOSIG=$(( NOSIG + _n ))
done

TOTAL=$(( NORUN + RUN ))
echo "Крупные кодовые диффы, ушедшие в коммит (последние ${#FILES[@]} сессий):"
if [ "$TOTAL" -eq 0 ]; then
    echo "  записей стража $GUARD нет (без подписи: $NOSIG)"
    _pending_report
    [ "$UNREADABLE" -gt 0 ] && { echo "  ЖУРНАЛОВ НЕ ПРОЧИТАНО: $UNREADABLE — это не «нет событий», а «не измерено»"; exit 2; }
    if [ "$PEND_LINES" -gt 0 ]; then
        _second_half_mute; exit 2
    fi
    exit 0
fi
# Доля печатается округлённой ВНИЗ, но решение принимается по точному сравнению: при
# 101 из 200 усечение даёт ровно 50, порог `-gt 50` не срабатывает, и замер объявляет
# «правило исполняется» на большинстве без прогона. Поймано противником 9 сентября 2026
# (атака 7). Полоса обратного вывода начинается с TOTAL=101 и с ростом знаменателя не
# исчезает — значит это не «маловероятно», а неверно.
SHARE=$(( NORUN * 100 / TOTAL ))
echo "  всего: $TOTAL, без адверсариального прогона: $NORUN ($SHARE%), с прогоном: $RUN"
_pending_report
[ "$PEND_LINES" -gt "$TOTAL" ] && echo "  ожиданий больше подтверждённых коммитов — либо коммиты массово отменяются, либо вторая половина срабатывает не всегда"
[ "$NOSIG" -gt 0 ] && echo "  записей без подписи (дедуп неприменим, в доле не учтены): $NOSIG"
[ "$UNREADABLE" -gt 0 ] && echo "  ЖУРНАЛОВ НЕ ПРОЧИТАНО: $UNREADABLE — доля посчитана по неполной выборке"

if [ "$TOTAL" -lt "$MIN_N" ]; then
    echo "  — мало данных, решения не принимаются (порог $MIN_N)"
    exit 0
fi
if [ $(( NORUN * 2 )) -gt "$TOTAL" ]; then
    echo "[замер: находки, не сбой] больше половины крупных диффов уходит в коммит без прогона —"
    echo "по ADR-015 это первый из трёх порогов подъёма уровня; второй (доля ложных ниже"
    echo "десятой части) меряется отдельно, ретро-прогоном по корпусу расшифровок"
    exit 1
fi
echo "  — правило исполняется в большинстве случаев"
exit 0
