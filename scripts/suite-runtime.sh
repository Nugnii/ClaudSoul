#!/usr/bin/env bash
# suite-runtime.sh — длительность полного набора тестов держится замером, а не памятью.
#
# Результат: число «полный набор бежит N» в документах равно последнему ИЗМЕРЕННОМУ значению
# Проверка результата: bash scripts/suite-runtime.sh --check даёт 0, когда число документа
#            совпадает с артефактом последнего замера (расхождение больше допуска — код 1)
#
# Зачем (8 сентября 2026). Владелец спросил: «как долго должен полный прогон работать и
# сколько там всего в нём?» Документ отвечал «4 мин 40 с», прогон в тот же час занял 11 мин
# 12 с при 366 тестах и нагрузке 3,9 — вдвое дольше. Число было прозой без команды и
# устаревало незаметно: каждый новый тест добавляет секунды, а строка в документе остаётся.
# Тот же класс, что реестр `doc-claims` закрывает для счётных величин, — только здесь
# величина временная, и в реестр её никто не внёс.
#
# ПРИЗНАК ПРОМАХА БЫЛ ПЕРЕД ГЛАЗАМИ. За сессию набор запускался трижды и трижды не уложился
# в 600-секундный предел вызова, уходя в фон. Каждый раз это читалось как «долго идёт», а не
# как «противоречит записанному числу»: у числа не было носителя, с которым его сверяют.
#
# ЧТО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ. Не правит документы: число временное, его формат в прозе
# («4 мин 40 с») не машинный, и подстановка регуляркой ломала бы фразу. Скрипт НАЗЫВАЕТ
# расхождение и печатает готовую строку — правка остаётся решением человека.
#
# НАЗВАННЫЙ ПРЕДЕЛ. Замер зависит от машины и её нагрузки: 11 мин 12 с получены при load 3,9,
# на свободной машине выйдет меньше. Поэтому допуск широкий (±40%), а в артефакт кладётся и
# нагрузка — по ней видно, стоит ли верить числу. Условие снятия: замеры начнут делаться на
# известной машине в известном состоянии (CI), и допуск сузится до реального разброса.
set -uo pipefail

REPO="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/.." 2>/dev/null && pwd -P)}"
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
ART="$STATE/suite-runtime.json"
# Документы НЕ перечисляются: множество выводится поиском фразы по дереву (род F —
# «универсум перечислен, а не выведен»). Первая редакция знала один файл, а число стояло в
# двух: `tool-gate-check.md` и `install-drift-notice.md` — второй нашёлся поиском братьев.
docs_with_claim() {
    (cd "$REPO" && git ls-files '*.md' 2>/dev/null) | while IFS= read -r rel; do
        [ -n "$rel" ] || continue
        case "$rel" in *CHANGELOG*|*archive*|SESSION.md) continue ;; esac   # хроника не правится
        # Две формы, обе взяты ИЗ ДЕРЕВА, а не придуманы: «бежит N мин M с»
        # (tool-gate-check.md) и «в полном наборе (N мин M с)» (install-drift-notice.md).
        # Первая редакция знала одну и нашла один носитель из двух — признак был уже
        # предмета, и это поймано поиском братьев, а не тестом.
        grep -qE 'бежит [0-9]{1,} мин [0-9]{1,} с|наборе \([0-9]{1,} мин [0-9]{1,} с' \
            "$REPO/$rel" 2>/dev/null && printf '%s\n' "$rel"
    done
}
MODE="${1:-run}"

case "$MODE" in
    run|--check) ;;
    *) echo "неизвестный режим: $MODE (есть run, --check)"; exit 2 ;;
esac

# Число из документа: «бежит 4 мин 40 с».
doc_seconds() {
    [ -f "$1" ] || { echo ""; return 0; }
    sed -n -e 's/.*бежит \([0-9]\{1,\}\) мин \([0-9]\{1,\}\) с.*/\1 \2/p' \
           -e 's/.*наборе (\([0-9]\{1,\}\) мин \([0-9]\{1,\}\) с.*/\1 \2/p' "$1" | head -1 \
        | awk '{ if (NF == 2) print $1 * 60 + $2 }'
}

if [ "$MODE" = "run" ]; then
    command -v python3 >/dev/null 2>&1 || { echo "нет python3 — мерить нечем"; exit 2; }
    TESTS=$(cd "$REPO" && ls hooks/tests/test_*.sh 2>/dev/null | grep -c '') || TESTS=0
    # НАГРУЗКА СНИМАЕТСЯ ДО СТАРТА, а не после (11 сентября 2026). Предмет порога — «мешали
    # ли СОСЕДИ», а мерилось «сколько было в конце», куда входит нагрузка самого набора.
    # Пока набор шёл в один поток, он добавлял около единицы и подмена не замечалась; с
    # включённой параллелью он добавляет столько, сколько потоков, и порог 5 стал недостижим
    # ПО ПОСТРОЕНИЮ: прогон в 8 потоков заканчивается при 6,01 всегда, каким бы свободным ни
    # было начало. Замер отказывался записываться, сам будучи исправным.
    # Нагрузка ПОСЛЕ остаётся в артефакте справкой: по ней видно, сколько добавил сам набор.
    LOAD=$(uptime 2>/dev/null | sed 's/.*averages*: //' | awk '{print $1}' | tr -d ',')
    START=$(python3 -c 'import time;print(time.time())')
    (cd "$REPO" && bash hooks/tests/run_all.sh >/dev/null 2>&1)
    END=$(python3 -c 'import time;print(time.time())')
    SECS=$(python3 -c "print(int($END - $START))")
    LOAD_AFTER=$(uptime 2>/dev/null | sed 's/.*averages*: //' | awk '{print $1}' | tr -d ',')
    mkdir -p "$STATE" 2>/dev/null
    # ЗАМЕР НА ЗАНЯТОЙ МАШИНЕ — НЕ ЗАМЕР, и это установлено числом 8 сентября 2026: при
    # нагрузке 3,6 набор дал 9 мин 43 с, при 6,19 (работала вторая сессия) — 16 мин 13 с,
    # то есть +67% при допуске ±40%. Прибор клал `load` в артефакт как справку, и вердикт от
    # неё не зависел: «измерил» было неотличимо от «измерил в негодных условиях» (род B).
    # Образец решения взят из дерева — нога t0 в hooks/tests/test_attack_r3_quadratic_gsub.sh
    # объявляет собственный замер недостоверным ровно так же.
    # ПОРОГ выведен из наблюдений, а не выбран: достоверные замеры этой машины (10 ядер)
    # снимались при 3,6-4,3; недостоверный — при 6,19. Половина ядер лежит в этом зазоре.
    # Условие уточнения: замеры начнут делаться на машине с известной загрузкой (CI) —
    # порог заменяется её проверкой.
    _LOAD_MAX="${SUITE_RUNTIME_LOAD_MAX:-5}"
    _load_int=$(printf '%s' "${LOAD:-0}" | awk -F'[.,]' '{print $1 + 0}')
    if [ "${_load_int:-0}" -ge "$_LOAD_MAX" ] 2>/dev/null; then
        printf 'полный набор: %s тест(ов), %d мин %02d с — но нагрузка %s при пороге %s.\n' \
            "$TESTS" "$((SECS / 60))" "$((SECS % 60))" "${LOAD:-?}" "$_LOAD_MAX"
        printf 'замер НЕ ЗАПИСАН: на занятой машине он измеряет соседей, а не набор.\n'
        printf 'повтори на свободной машине либо подними порог явно (SUITE_RUNTIME_LOAD_MAX).\n'
        exit 2
    fi
    printf '{"date":"%s","seconds":%s,"tests":%s,"load":"%s","load_after":"%s"}\n' \
        "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$SECS" "$TESTS" "${LOAD:-?}" "${LOAD_AFTER:-?}" \
        > "$ART" 2>/dev/null
    printf 'полный набор: %s тест(ов), %d мин %02d с (нагрузка соседей на старте %s, в конце %s)\n' \
        "$TESTS" "$((SECS / 60))" "$((SECS % 60))" "${LOAD:-?}" "${LOAD_AFTER:-?}"
fi

# --check (и хвост `run`): сверка со ВСЕМИ документами, несущими утверждение.
if [ ! -f "$ART" ]; then
    # Отсутствие замера — не «совпало»: говорим и выходим успехом, потому что мерить нечем,
    # а не потому, что всё хорошо (род B: «не смог» отличается от «прочитал»).
    echo "замера ещё не было — число документа НЕ ПРОВЕРЕНО (сделать: bash scripts/suite-runtime.sh run)"
    exit 0
fi
# Пробел после двоеточия допускается: JSON его разрешает, и артефакт, записанный любым
# другим писателем (python, jq), становился «нечитаемым» — то есть прибор объявлял себя
# сломанным на верных данных. Поймано в тот же час, когда артефакт переписали python'ом.
ART_S=$(sed -n 's/.*"seconds"[[:space:]]*:[[:space:]]*\([0-9]\{1,\}\).*/\1/p' "$ART" | head -1)
[ -n "$ART_S" ] || { echo "артефакт $ART нечитаем — замер СЛОМАН, а не чист"; exit 2; }
# ЗАМЕР ПРОТУХАЕТ ПО РАБОТЕ, А НЕ ПО КАЛЕНДАРЮ (11 сентября 2026, корень R4). Артефакт
# несёт поле `tests` — сколько файлов было НА МОМЕНТ ЗАМЕРА, — и до этого дня его никто не
# читал: срок держался периодом 30 дней в `measurements.tsv`. Между тем предмет растёт
# коммитами, а не сутками: 8 сентября 368 тестов и 564 с, 11 сентября 434 теста и вдвое
# дольше, и календарный срок ещё не вышел — число документа врало законно. Признак с одним
# последствием: файлов стало больше, чем было при замере, значит измеренная величина
# относится к другому набору.
ART_T=$(sed -n 's/.*"tests"[[:space:]]*:[[:space:]]*\([0-9]\{1,\}\).*/\1/p' "$ART" | head -1)
# Нагрузка НА СТАРТЕ и В КОНЦЕ читаются обе, и разность НАЗЫВАЕТСЯ: сколько машины занял сам
# набор. Без этого чтения поле `load_after` осталось бы объявлением без исполнителя (род G) —
# записанным и никем не читаемым. Число говорит дело: оно показывает, сколько потоков набор
# реально загрузил, и объясняет, почему прогон на занятой машине растягивается.
_l0=$(sed -n 's/.*"load"[[:space:]]*:[[:space:]]*"\([0-9.]*\)".*/\1/p' "$ART" | head -1)
_l1=$(sed -n 's/.*"load_after"[[:space:]]*:[[:space:]]*"\([0-9.]*\)".*/\1/p' "$ART" | head -1)
if [ -n "$_l0" ] && [ -n "$_l1" ]; then
    printf 'нагрузка при замере: соседи %s на старте, %s в конце — сам набор добавил %s\n' \
        "$_l0" "$_l1" "$(awk -v a="$_l0" -v b="$_l1" 'BEGIN{printf "%.2f", b - a}')"
fi
NOW_T=$(cd "$REPO" && ls hooks/tests/test_*.sh 2>/dev/null | grep -c '') || NOW_T=0
if [ -n "$ART_T" ] && [ "$NOW_T" -gt 0 ] && [ "$NOW_T" -ne "$ART_T" ]; then
    printf 'ЗАМЕР УСТАРЕЛ ПО ПРЕДМЕТУ: мерили %s тестов, сейчас %s — величина относится к другому набору\n' \
        "$ART_T" "$NOW_T"
    printf 'перемерь: bash scripts/suite-runtime.sh run\n'
    exit 1
fi
DOCS=$(docs_with_claim)
if [ -z "$DOCS" ]; then
    echo "ни в одном документе нет фразы «бежит N мин M с» — утверждение исчезло из дерева"
    exit 1
fi
TOL=$(( ART_S * 40 / 100 ))
RC=0
while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    DOC_S=$(doc_seconds "$REPO/$rel")
    [ -n "$DOC_S" ] || continue
    DIFF=$(( ART_S > DOC_S ? ART_S - DOC_S : DOC_S - ART_S ))
    if [ "$DIFF" -le "$TOL" ]; then
        printf 'совпадает: %s — измерено %d мин %02d с, в документе %d мин %02d с\n' \
            "$rel" "$((ART_S / 60))" "$((ART_S % 60))" "$((DOC_S / 60))" "$((DOC_S % 60))"
    else
        printf 'РАСХОЖДЕНИЕ: %s — измерено %d мин %02d с, в документе %d мин %02d с (допуск ±40%%)\n' \
            "$rel" "$((ART_S / 60))" "$((ART_S % 60))" "$((DOC_S / 60))" "$((DOC_S % 60))"
        printf 'правь строку в %s на: «бежит %d мин %02d с»\n' "$rel" "$((ART_S / 60))" "$((ART_S % 60))"
        RC=1
    fi
done <<EOF
$DOCS
EOF
exit "$RC"
