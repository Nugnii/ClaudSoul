#!/usr/bin/env bash
# docs-inventory.sh — документация описывает то, что есть, и только то, что есть.
#
# Результат: ни одного механизма дерева без упоминания в документах И ни одного имени
#            файла в документах без файла в дереве.
# Проверка результата: bash scripts/docs-inventory.sh даёт 0.
#
# Повод. 28 августа 2026 собеседник спросил, внесена ли работа сессии в документацию. Замер:
# семь новых механизмов упомянуты в architecture.md, README и CLAUDE.md НОЛЬ раз. Обновились
# только автогенерируемые числа и бейджи версий. Стражи документации были узкими:
# docs-family-check срабатывает лишь при бампе версии и проверяет, что пять файлов ТРОНУТЫ
# коммитом; module-doc-check — только появление нового модуля. Проверки «документ описывает
# то, что есть» не было ни одной.
#
# Две стороны считаются раздельно намеренно. Прямая (механизм есть, описания нет) — это
# отставание документа. Обратная (описание есть, механизма нет) — мёртвый участок, и он
# опаснее: читатель верит в механизм, которого нет, и строит на нём решения.
#
# КОНТРПРИМЕР: страж ловит ИМЯ механизма (без расширения) и потому засчитает упоминание
# в любом контексте — даже «этот хук удалён». Наличие имени в тексте не означает, что текст
# описывает механизм ВЕРНО; это проверка присутствия, не соответствия.
#
# Второй контрпример: страж ловит имена ФАЙЛОВ. Обобщающее утверждение прозой, ни одного файла не
# называющее — «пять хуков могут прервать вызов, четыре спрашивают, один отказывает», — он
# не проверяет. Именно такое и разошлось с деревом 28 августа: у прозы нет генератора,
# поэтому она стареет молча, тогда как таблицы перезаписываются из исходников.
set -uo pipefail

# Библиотека берётся ТАМ, ГДЕ ЛЕЖИТ СКРИПТ, а не в судимом дереве: судить можно чужую
# фикстуру без hooks/lib, и тогда признак молча выключался бы — поймано на себе фикстурой
# свидетеля в час написания. Судимое дерево задаётся отдельно, через UNIVERSE_ROOT.
_di_self=$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/.." && pwd -P)
REPO="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/.." && pwd -P)}"
cd "$REPO" || exit 2

# НЕПОЛНОЕ ДЕРЕВО. Публичный снимок изымает внутренние файлы и часть документов НЕЗАВИСИМО
# друг от друга, и оттого две находки ниже становятся следствием самого изъятия, а не
# расхождения дерева с документацией: «механизм без описания» (описывавший документ изъят)
# и «мёртвый участок» (описание есть, механизм изъят). В снимке они НАЗЫВАЮТСЯ, но кода не
# держат: полноту неполного дерева судить нечем. Прочие находки — мёртвые ссылки, рычаги,
# уплывшие адреса — остаются с кодом: они о том, что в снимке ЕСТЬ.
UNIVERSE_ROOT="$REPO"; . "$_di_self/hooks/lib/universe-lib.sh" 2>/dev/null || true
PARTIAL=0
if command -v universe_partial_tree >/dev/null 2>&1 && universe_partial_tree; then PARTIAL=1; fi

# Носитель описания — документ СОСТОЯНИЯ. Хроника (CHANGELOG, SESSION, BACKLOG,
# датированные разборы) называет всякий механизм по построению: он там появляется в день
# заведения. Засчитать её носителем — получить страж, который зелен всегда.
DOCS=$(git ls-files '*.md' 2>/dev/null | grep -vE '_drafts/|(^|/)(CHANGELOG|SESSION|BACKLOG|BACKLOG-archive)\.md$|-20[0-9][0-9]-[0-9][0-9]-[0-9][0-9]\.md$')
# Обратная сторона сверяется по УЗКОМУ набору: там ищутся имена файлов в тексте, и старый
# разбор, называющий снятый механизм, — законная хроника, а не мёртвый участок.
DOCS_BACK="docs/reference.md docs/reference.ru.md docs/architecture.md README.md README.ru.md CLAUDE.md"
# Производный документ (перевод с шапкой derived-from), отставший от источника, из обратной
# сверки исключается и называется (14 сентября 2026): его мёртвые упоминания — отставание
# ПЕРЕВОДА, а не документации, и лечатся пересборкой перед публикацией, где он сверится снова.
_stale_derived=""
[ -f scripts/docs-derived-check.sh ] && _stale_derived=$(bash scripts/docs-derived-check.sh stale 2>/dev/null | tr '\n' ' ')
_kept=""
for _d in $DOCS_BACK; do case " $_stale_derived " in *" $_d "*) ;; *) _kept="$_kept $_d" ;; esac; done
DOCS_BACK="${_kept# }"
missing_fwd=""
dead_back=""
libs=0
registry=0
# Знаменатели зелёных вердиктов. Отсутствие НАХОДОК и отсутствие ПРЕДМЕТА печатались
# одинаково, а один раз уже разошлись: комментарий ниже фиксирует 13 механизмов замера
# аблации, не проверявшихся вовсе при отчёте «все механизмы дерева упомянуты».
checked_mech=0
checked_ment=0
checked_link=0

# Что считать механизмом — ПРАВИЛО О ФАЙЛЕ, не перечень мест. До 28 августа 2026 здесь
# стоял список `hooks/*.sh scripts/*.sh scripts/*.py`, снятый с тогдашнего состава дерева.
# Он не спускался в подпапки, и 13 механизмов замера аблации не проверялись вовсе — отчёт
# при этом гласил «все механизмы дерева упомянуты». Тот же класс, что маска мест в
# module-doc-check: предмет проверки задан тем, ГДЕ его нашли, а не тем, ЧТО он такое.
# Один проход по документам вместо поиска на каждую пару «механизм × документ». Стемы
# берутся у тех же файлов и по тем же правилам, что в цикле ниже, — список собирается
# одним и тем же `git ls-files`, поэтому расхождению взяться неоткуда.
_STEMS=$(mktemp); _HITS=$(mktemp)
for f in $(git ls-files '*.sh' '*.py' 2>/dev/null); do
    case "$f" in */tests/*|tests/*|scripts/publish/*|templates/*) continue ;; esac
    case "$f" in *-lib.sh|*/lib/*|lib/*|*/__init__.py) continue ;; esac
    nm=$(basename "$f"); printf '%s\n' "${nm%.*}"
done | sort -u > "$_STEMS"
# `grep -o -F -f` есть и в BSD, и в GNU (pattern-shell-portability). Документов сотни —
# передаём их через xargs, чтобы не упереться в предел длины команды.
printf '%s\n' $DOCS | xargs grep -ohF -f "$_STEMS" 2>/dev/null | sort -u > "$_HITS"
_MENTIONED="|$(tr '\n' '|' < "$_HITS")"
rm -f "$_STEMS" "$_HITS" 2>/dev/null

for f in $(git ls-files '*.sh' '*.py' 2>/dev/null); do
    [ -f "$f" ] || continue
    # Библиотеки и составные части исключены осознанно: справочник документирует МЕХАНИЗМЫ,
    # а `*-lib.sh`, `lib/`, `__init__.py` — внутренние части, которые проект считает числом
    # в CLAUDE.md («N хуков + M библиотек»), но поимённо наружу не описывает. Считаются
    # отдельно ниже, чтобы исключение было видимым, а не спрятанным.
    case "$f" in */tests/*|tests/*|scripts/publish/*|templates/*) continue ;; esac
    case "$f" in *-lib.sh|*/lib/*|lib/*|*/__init__.py) libs=$((libs + 1)); continue ;; esac
    # Ищем имя БЕЗ расширения: справочник называет механизмы «five-whys-gate», а не
    # «five-whys-gate.sh». Первая версия искала форму из файловой системы и насчитала 77
    # «неописанных» при живых упоминаниях — признак строился от формы ИСТОЧНИКА, а не от
    # формы ЦЕЛИ. Поймано сверкой с документом до отчёта.
    name=$(basename "$f"); stem="${name%.*}"
    checked_mech=$((checked_mech + 1))
    # УПОМЯНУТЫЕ ИМЕНА СОБРАНЫ ОДНИМ ПРОХОДОМ, а не поиском на каждую пару (11 сентября 2026).
    # Прежде здесь стоял вложенный цикл: 703 файла × 221 документ — до 78 тысяч вызовов
    # `grep`, и прибор шёл 26 секунд. Предмет от этого не меняется: вопрос «упомянуто ли имя
    # ХОТЬ ГДЕ-ТО», и в каком именно документе — не спрашивается (прежний цикл сам обрывался
    # первым `break`). Множество строится один раз в `_MENTIONED` выше.
    found=0
    case "$_MENTIONED" in *"|$stem|"*) found=1 ;; esac
    # Реестр замеров — ПОЛНОЦЕННЫЙ носитель описания для инструмента-замера: там у каждого
    # своя строка с назначением и сроком, и она машинно читаема. Не засчитать его значило бы
    # объявить неописанным 21 скрипт, у которого описание есть, — предмет замера не тот.
    if [ "$found" -eq 0 ] && [ -f scripts/measurements.tsv ]; then
        grep -qF "$name" scripts/measurements.tsv && { registry=$((registry + 1)); continue; }
    fi
    [ "$found" -eq 0 ] && missing_fwd="$missing_fwd $name"
done

for d in $DOCS_BACK; do
    [ -f "$d" ] || continue
    # Имя берётся ЦЕЛИКОМ, с границей слева: без неё разбор вытаскивал хвосты длинных
    # имён — `cli_search.py` давал «search.py», `img.shields.io` давал «img.sh»,
    # `./install.sh` давал «all.sh». Пять ложных из семи. Подстрока вместо целого токена —
    # тот же класс, что «упоминание против исполнения», чиненный в это же утро.
    # Имя берётся ЦЕЛИКОМ, с границей С ОБЕИХ СТОРОН. Без левой границы разбор вытаскивал
    # хвосты длинных имён (`cli_search.py` → «search.py»); без правой — куски доменов
    # (`img.shields.io` → «img.sh»). Слэш границей СЧИТАЕТСЯ законной: `hooks/foo.sh` —
    # обычная форма упоминания, и первая попытка её запретить убила настоящую находку.
    names=$(grep -oE '(^|[^A-Za-z0-9_.-])[a-z][a-z0-9-]*\.(sh|py)([^A-Za-z0-9_-]|$)' "$d" \
            | grep -oE '[a-z][a-z0-9-]*\.(sh|py)' | sort -u)
    for nm in $names; do
        checked_ment=$((checked_ment + 1))
        # Существование проверяется по ВСЕМУ дереву, а не по перечню каталогов: первая
        # версия смотрела в hooks/scripts/lib и объявила мёртвым `install.sh`, лежащий в
        # корне. Перечень каталогов — тот же перечень форм, что уже подводил четырежды.
        # Существование — по файловой системе, а не по индексу git: `git ls-files` не видит
        # ещё не закоммиченный файл и объявляет мёртвым живое. Поймано на docs-duplicates.sh
        # через минуту после его написания.
        if [ -z "$(find . -name "$nm" -not -path './.git/*' -print -quit 2>/dev/null)" ]; then
            case " $dead_back " in *" $nm "*) ;; *) dead_back="$dead_back $nm" ;; esac
        fi
    done
done

# --- Третья сторона: markdown-ссылка на файл, которого нет. Мёртвый участок того же
# рода, что упоминание имени: читатель идёт по ссылке и не находит обещанного.
dead_links=""
for d in $DOCS; do
    [ -f "$d" ] || continue
    base=$(dirname "$d")
    # Построчно, а не пословно: цель с ПРОБЕЛОМ внутри — одна ссылка, и отсеивается
    # целиком. Разбиение по словам рвало `<абс.путь к entity-media.md>` на три «ссылки»
    # и объявляло мёртвыми две из них.
    # Подстановка `$(...)` вокруг этого цикла невозможна: системный bash macOS — 3.2,
    # он не разбирает `case` внутри `$( )` (закрывающая скобка образца рвёт подстановку).
    # Отсюда подстановка процесса и накопление в текущей оболочке.
    while IFS= read -r lk; do
        # Проверяема ссылка, только если ведёт ВНУТРЬ дерева. `~`, абсолютный путь и выход
        # через `../` за корень — это машина собеседника, а не репозиторий: сверять не с чем.
        # Угловая скобка — заполнитель в примере, а не путь.
        case "$lk" in http*|mailto*|"~"*|/*|*[\<\>]*) continue ;; esac
        checked_link=$((checked_link + 1))
        # ЦЕНА, ИЗМЕРЕННАЯ 4 сентября 2026: один старт интерпретатора ~0,25 с, ссылок 93 —
        # это ~23 с из 27 с всего прогона. Дешёвая замена существует (одна пакетная
        # нормализация вместо вызова на ссылку), но она НЕ сделана намеренно: в тот же час
        # правка ради скорости, сделанная по догадке о вкладе, оказалась ЗАМЕДЛЕНИЕМ
        # (`find -exec basename` форкал на каждый файл: 12,8 с против 5 с у 87 вызовов
        # `find`). Следующая правка здесь допустима только после замера вклада ДО неё.
        norm=$(python3 -c 'import os,sys; print(os.path.normpath(os.path.join(sys.argv[1], sys.argv[2])))' "$base" "$lk" 2>/dev/null) || continue
        case "$norm" in ../*) continue ;; esac
        if [ ! -e "$lk" ] && [ ! -e "$norm" ]; then
            case " $dead_links " in *" $lk "*) ;; *) dead_links="$dead_links $lk" ;; esac
        fi
    done < <(grep -oE '\]\(([^)#]+\.(md|sh|py|json))' "$d" | sed 's/^](//' | sort -u)
done

echo "ДОКУМЕНТАЦИЯ ПРОТИВ ДЕРЕВА"
if [ -n "${missing_fwd# }" ]; then
    echo "  механизм есть, описания нет ($(printf '%s' "$missing_fwd" | wc -w | tr -d ' ')):"
    for n in $missing_fwd; do echo "      · $n"; done
else
    echo "  все механизмы дерева упомянуты (проверено механизмов: ${checked_mech})"
fi
echo "  библиотек (*-lib.sh) исключено: $libs — считаются числом, не поимённо"
echo "  описано в реестре замеров: $registry — там назначение и срок у каждого"
if [ -n "${dead_back# }" ]; then
    echo "  МЁРТВЫЙ УЧАСТОК — описание есть, файла нет ($(printf '%s' "$dead_back" | wc -w | tr -d ' ')):"
    for n in $dead_back; do echo "      · $n"; done
else
    echo "  мёртвых упоминаний нет (проверено упоминаний: ${checked_ment})"
fi
[ -n "${_stale_derived% }" ] && echo "  производных документов, отставших от источника, из обратной сверки исключено: $(printf '%s' "$_stale_derived" | wc -w | tr -d ' ') — ${_stale_derived% }(пересборка перед публикацией: bash scripts/docs-derived-check.sh)"

# --- Четвёртая сторона: ИМЯ РЫЧАГА, которого нет (D385, 11 сентября 2026) ---------
# Зеркало третьей: там ссылка ведёт в никуда, здесь имя настройки ведёт в никуда. Повод:
# `CLAUDE.md` называл дроссель `BACKLOG_READINGS_MIN_S`, а в дереве живёт
# `BACKLOG_READINGS_EVERY_TURNS` — читатель, которому нужно поменять срок, экспортировал бы
# имя, которого нет, и не заметил бы, что ничего не изменилось. `docs-inventory` ловил имена
# ФАЙЛОВ и такое не видел по построению.
# Замер того дня: имён заглавными в бэктиках — 7, живых 6, мёртвых 0 после починки.
# КОНТРПРИМЕР, который обязан проходить: имя ГИПОТЕТИЧЕСКОГО рычага в разделе о будущем
# (`LANG_RULE` в «примерах потенциальных будущих output-scanners») — оно ничего не обещает
# читателю сегодня. Отсекается по словам-маркерам будущего в той же строке.
dead_knobs=""
checked_knob=0
# Прибор обязан отличать «имени нет в коде» от «искать нечем»: в копии дерева без .git
# `git grep` не работает ВОВСЕ, и первая редакция объявила мёртвыми 7 живых имён — род B
# реестра («отказ чтения неотличим от пустоты»). Поймано собственным контролем.
knob_search_ok=1
git rev-parse --git-dir >/dev/null 2>&1 || knob_search_ok=0
# Набор УЗКИЙ — тот же, что у обратной стороны: обещание читателю про рычаг живёт в
# документах «взгляда снаружи», а в модульных доках и разборах имя может быть хроникой.
# Поиск по слову (`-w`), а не по `\b`: обратная косая внутри двойных кавычек съедается
# оболочкой до grep, и живые имена объявлялись мёртвыми — 111 из 111 на первом прогоне.
[ "$knob_search_ok" -eq 1 ] && for d in $DOCS_BACK; do
    [ -f "$d" ] || continue
    while IFS= read -r line; do
        case "$line" in
            *будущ*|*потенциальн*|*candidate*|*гипотет*) continue ;;
        esac
        for kn in $(printf '%s' "$line" | grep -oE '`[A-Z][A-Z0-9_]{4,}`' | tr -d '`'); do
            checked_knob=$((checked_knob + 1))
            git grep -qw "$kn" -- '*.sh' '*.py' 2>/dev/null && continue
            case " $dead_knobs " in *" $kn "*) ;; *) dead_knobs="$dead_knobs $kn" ;; esac
        done
    done < "$d"
done

if [ "$knob_search_ok" -eq 0 ]; then
    echo "  имена рычагов НЕ ПРОВЕРЕНЫ — нет git-контекста, искать в коде нечем"
elif [ -n "${dead_knobs# }" ]; then
    echo "  МЁРТВОЕ ИМЯ РЫЧАГА — в документе есть, в коде нет ($(printf '%s' "$dead_knobs" | wc -w | tr -d ' ')):"
    for n in $dead_knobs; do echo "      · $n"; done
else
    echo "  мёртвых имён рычагов нет (проверено имён: ${checked_knob})"
fi

# --- Пятая сторона: АДРЕС, уплывший со строки (11 сентября 2026) -----------------
# Документ обещает «смотри файл:строку», и связь держится СОВПАДЕНИЕМ ЧИСЛА, которое ничто
# не сверяет: правка описываемого файла сдвигает строки, документ остаётся прежним и молча
# врёт. Повод — собственная правка того же дня: `hooks/backlog-reading-refresh.sh` вырос на
# 24 строки, и два документа (`.claude-docs/modules/tool-gate-check.md`, шапка
# `hooks/tool-gate-check.sh`) стали указывать мимо. Замер по дереву: адресов 58, уплывших 5.
# ПРИЗНАК СЛАБЫЙ, и это названо числом: ловится адрес ЗА КОНЦОМ файла и адрес НА ПУСТОЙ
# строке. Адрес, уплывший на другую непустую строку, не ловится вовсе — именно таким был
# повод (:77 → :101). Нижняя оценка, а не полнота; условие усиления — сверка ТЕКСТА строки
# с тем, что о ней сказано, а для этого у адреса должна быть объявлена цитата.
# Файла нет вовсе — молчим: это вторая сторона выше, у неё свой счётчик.
# Цена держится ОДНИМ вызовом интерпретатора на весь раздел, а не вызовом на адрес:
# замер 4 сентября 2026 в этом же файле — старт python3 ~0,25 с, и 58 стартов дали бы +14 с.
dead_addrs=""
checked_addr=0
addr_ok=1
_addr_out=$(printf '%s\n' $DOCS | python3 -c '
import sys, re, os
docs = [l.strip() for l in sys.stdin if l.strip()]
index = {}
for root, dirs, files in os.walk("."):
    dirs[:] = [d for d in dirs if d != ".git"]
    for fn in files:
        if fn.endswith((".sh", ".py")):
            index.setdefault(fn, []).append(os.path.relpath(os.path.join(root, fn), "."))
pat = re.compile(r"([A-Za-z0-9_./-]+[.](?:sh|py)):([0-9]+)")
n = 0
bad = []
for d in docs:
    try:
        lines = open(d, encoding="utf-8", errors="replace").read().splitlines()
    except OSError:
        continue
    for ln, line in enumerate(lines, 1):
        for m in pat.finditer(line):
            name, num = m.group(1), int(m.group(2))
            if os.path.isfile(name):
                path = name
            else:
                cands = index.get(os.path.basename(name), [])
                exact = [c for c in cands if c.endswith("/" + name)]
                cands = exact or cands
                # Имя, ведущее к двум файлам, не судится: адрес неразрешим, а не неверен.
                if len(cands) != 1:
                    continue
                path = cands[0]
            try:
                src = open(path, encoding="utf-8", errors="replace").read().splitlines()
            except OSError:
                continue
            n += 1
            if num > len(src):
                bad.append("%s:%d -> %s:%d (за концом, строк %d)" % (d, ln, name, num, len(src)))
            elif not src[num - 1].strip():
                bad.append("%s:%d -> %s:%d (пустая строка)" % (d, ln, name, num))
print("OK %d" % n)
for b in bad:
    print(b)
' 2>/dev/null) || _addr_out=""
case "$_addr_out" in
    OK*) checked_addr=$(printf '%s' "$_addr_out" | head -1 | tr -dc '0-9') ;;
    *)   addr_ok=0 ;;
esac
[ "$addr_ok" -eq 1 ] && dead_addrs=$(printf '%s' "$_addr_out" | tail -n +2)

if [ "$addr_ok" -eq 0 ]; then
    echo "  адреса строк НЕ ПРОВЕРЕНЫ — разбор не отработал, сверять нечем"
elif [ -n "$dead_addrs" ]; then
    echo "  УПЛЫВШИЙ АДРЕС — документ указывает мимо ($(printf '%s\n' "$dead_addrs" | wc -l | tr -d ' ')):"
    printf '%s\n' "$dead_addrs" | sed 's/^/      · /'
else
    echo "  уплывших адресов нет (проверено адресов: ${checked_addr})"
fi

if [ -n "${dead_links# }" ]; then
    echo "  МЁРТВАЯ ССЫЛКА — ведёт в никуда ($(printf '%s' "$dead_links" | wc -w | tr -d ' ')):"
    for n in $dead_links; do echo "      · $n"; done
else
    echo "  мёртвых ссылок нет (проверено ссылок: ${checked_link})"
fi

if [ "$PARTIAL" = 1 ]; then
    # ПРЕДМЕТА НЕТ — не «находок нет». Сверка отвечает на вопрос «документация описывает то,
    # что есть, и только то, что есть», а в СРЕЗЕ обе стороны урезаны независимо: остаётся док
    # про изъятый механизм, механизм без изъятого дока, ссылка на неопубликованный файл. Всё
    # это следствие изъятия, а не расхождения. Находки печатаются советом, код — 0, и причина
    # названа: молчаливый ноль был бы неотличим от «сверили и чисто».
    echo "  [неполное дерево (.public-snapshot): сверка документации с деревом неприменима —"
    echo "   находки выше суть следствие изъятия внутренних файлов, а не расхождения]"
    exit 0
fi

if [ -n "${missing_fwd# }" ] || [ -n "${dead_back# }" ] || [ -n "${dead_links# }" ] || [ -n "${dead_knobs# }" ] || [ -n "$dead_addrs" ]; then
    echo "[замер: находки, не сбой]"
    exit 1
fi
exit 0
