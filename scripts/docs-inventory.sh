#!/usr/bin/env bash
# docs-inventory.sh — документация описывает то, что есть, и только то, что есть.
#
# Результат: ни одного механизма дерева без упоминания в документах И ни одного имени
#            файла в документах без файла в дереве.
# Проверка результата: bash scripts/docs-inventory.sh даёт 0.
#
# Повод. 28 августа 2026 собеседник спросил, внесена ли работа сессии в документацию. Замер:
# семь новых механизмов упомянуты в architecture.md, README и CLAUDE.md НОЛЬ раз. Обновились
# только автогенерируемые числа и бейджи версий. Стражи документации были узкими:
# docs-family-check срабатывает лишь при бампе версии и проверяет, что пять файлов ТРОНУТЫ
# коммитом; module-doc-check — только появление нового модуля. Проверки «документ описывает
# то, что есть» не было ни одной.
#
# Две стороны считаются раздельно намеренно. Прямая (механизм есть, описания нет) — это
# отставание документа. Обратная (описание есть, механизма нет) — мёртвый участок, и он
# опаснее: читатель верит в механизм, которого нет, и строит на нём решения.
#
# КОНТРПРИМЕР: страж ловит ИМЯ механизма (без расширения) и потому засчитает упоминание
# в любом контексте — даже «этот хук удалён». Наличие имени в тексте не означает, что текст
# описывает механизм ВЕРНО; это проверка присутствия, не соответствия.
#
# Второй контрпример: страж ловит имена ФАЙЛОВ. Обобщающее утверждение прозой, ни одного файла не
# называющее — «пять хуков могут прервать вызов, четыре спрашивают, один отказывает», — он
# не проверяет. Именно такое и разошлось с деревом 28 августа: у прозы нет генератора,
# поэтому она стареет молча, тогда как таблицы перезаписываются из исходников.
set -uo pipefail

REPO="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/.." && pwd -P)}"
cd "$REPO" || exit 2

# Носитель описания — документ СОСТОЯНИЯ. Хроника (CHANGELOG, SESSION, BACKLOG,
# датированные разборы) называет всякий механизм по построению: он там появляется в день
# заведения. Засчитать её носителем — получить страж, который зелен всегда.
DOCS=$(git ls-files '*.md' 2>/dev/null | grep -vE '_drafts/|(^|/)(CHANGELOG|SESSION|BACKLOG|BACKLOG-archive)\.md$|-20[0-9][0-9]-[0-9][0-9]-[0-9][0-9]\.md$')
# Обратная сторона сверяется по УЗКОМУ набору: там ищутся имена файлов в тексте, и старый
# разбор, называющий снятый механизм, — законная хроника, а не мёртвый участок.
DOCS_BACK="docs/reference.md docs/reference.ru.md docs/architecture.md README.md README.ru.md CLAUDE.md"
missing_fwd=""
dead_back=""
libs=0
registry=0

# Что считать механизмом — ПРАВИЛО О ФАЙЛЕ, не перечень мест. До 28 августа 2026 здесь
# стоял список `hooks/*.sh scripts/*.sh scripts/*.py`, снятый с тогдашнего состава дерева.
# Он не спускался в подпапки, и 13 механизмов замера аблации не проверялись вовсе — отчёт
# при этом гласил «все механизмы дерева упомянуты». Тот же класс, что маска мест в
# module-doc-check: предмет проверки задан тем, ГДЕ его нашли, а не тем, ЧТО он такое.
for f in $(git ls-files '*.sh' '*.py' 2>/dev/null); do
    [ -f "$f" ] || continue
    # Библиотеки и составные части исключены осознанно: справочник документирует МЕХАНИЗМЫ,
    # а `*-lib.sh`, `lib/`, `__init__.py` — внутренние части, которые проект считает числом
    # в CLAUDE.md («N хуков + M библиотек»), но поимённо наружу не описывает. Считаются
    # отдельно ниже, чтобы исключение было видимым, а не спрятанным.
    case "$f" in */tests/*|tests/*|scripts/publish/*|templates/*) continue ;; esac
    case "$f" in *-lib.sh|*/lib/*|lib/*|*/__init__.py) libs=$((libs + 1)); continue ;; esac
    # Ищем имя БЕЗ расширения: справочник называет механизмы «five-whys-gate», а не
    # «five-whys-gate.sh». Первая версия искала форму из файловой системы и насчитала 77
    # «неописанных» при живых упоминаниях — признак строился от формы ИСТОЧНИКА, а не от
    # формы ЦЕЛИ. Поймано сверкой с документом до отчёта.
    name=$(basename "$f"); stem="${name%.*}"
    found=0
    for d in $DOCS; do
        [ -f "$d" ] || continue
        if grep -qF "$stem" "$d"; then found=1; break; fi
    done
    # Реестр замеров — ПОЛНОЦЕННЫЙ носитель описания для инструмента-замера: там у каждого
    # своя строка с назначением и сроком, и она машинно читаема. Не засчитать его значило бы
    # объявить неописанным 21 скрипт, у которого описание есть, — предмет замера не тот.
    if [ "$found" -eq 0 ] && [ -f scripts/measurements.tsv ]; then
        grep -qF "$name" scripts/measurements.tsv && { registry=$((registry + 1)); continue; }
    fi
    [ "$found" -eq 0 ] && missing_fwd="$missing_fwd $name"
done

for d in $DOCS_BACK; do
    [ -f "$d" ] || continue
    # Имя берётся ЦЕЛИКОМ, с границей слева: без неё разбор вытаскивал хвосты длинных
    # имён — `cli_search.py` давал «search.py», `img.shields.io` давал «img.sh»,
    # `./install.sh` давал «all.sh». Пять ложных из семи. Подстрока вместо целого токена —
    # тот же класс, что «упоминание против исполнения», чиненный в это же утро.
    # Имя берётся ЦЕЛИКОМ, с границей С ОБЕИХ СТОРОН. Без левой границы разбор вытаскивал
    # хвосты длинных имён (`cli_search.py` → «search.py»); без правой — куски доменов
    # (`img.shields.io` → «img.sh»). Слэш границей СЧИТАЕТСЯ законной: `hooks/foo.sh` —
    # обычная форма упоминания, и первая попытка её запретить убила настоящую находку.
    names=$(grep -oE '(^|[^A-Za-z0-9_.-])[a-z][a-z0-9-]*\.(sh|py)([^A-Za-z0-9_-]|$)' "$d" \
            | grep -oE '[a-z][a-z0-9-]*\.(sh|py)' | sort -u)
    for nm in $names; do
        # Существование проверяется по ВСЕМУ дереву, а не по перечню каталогов: первая
        # версия смотрела в hooks/scripts/lib и объявила мёртвым `install.sh`, лежащий в
        # корне. Перечень каталогов — тот же перечень форм, что уже подводил четырежды.
        # Существование — по файловой системе, а не по индексу git: `git ls-files` не видит
        # ещё не закоммиченный файл и объявляет мёртвым живое. Поймано на docs-duplicates.sh
        # через минуту после его написания.
        if [ -z "$(find . -name "$nm" -not -path './.git/*' -print -quit 2>/dev/null)" ]; then
            case " $dead_back " in *" $nm "*) ;; *) dead_back="$dead_back $nm" ;; esac
        fi
    done
done

# --- Третья сторона: markdown-ссылка на файл, которого нет. Мёртвый участок того же
# рода, что упоминание имени: читатель идёт по ссылке и не находит обещанного.
dead_links=""
for d in $DOCS; do
    [ -f "$d" ] || continue
    base=$(dirname "$d")
    # Построчно, а не пословно: цель с ПРОБЕЛОМ внутри — одна ссылка, и отсеивается
    # целиком. Разбиение по словам рвало `<абс.путь к entity-media.md>` на три «ссылки»
    # и объявляло мёртвыми две из них.
    # Подстановка `$(...)` вокруг этого цикла невозможна: системный bash macOS — 3.2,
    # он не разбирает `case` внутри `$( )` (закрывающая скобка образца рвёт подстановку).
    # Отсюда подстановка процесса и накопление в текущей оболочке.
    while IFS= read -r lk; do
        # Проверяема ссылка, только если ведёт ВНУТРЬ дерева. `~`, абсолютный путь и выход
        # через `../` за корень — это машина собеседника, а не репозиторий: сверять не с чем.
        # Угловая скобка — заполнитель в примере, а не путь.
        case "$lk" in http*|mailto*|"~"*|/*|*[\<\>]*) continue ;; esac
        norm=$(python3 -c 'import os,sys; print(os.path.normpath(os.path.join(sys.argv[1], sys.argv[2])))' "$base" "$lk" 2>/dev/null) || continue
        case "$norm" in ../*) continue ;; esac
        if [ ! -e "$lk" ] && [ ! -e "$norm" ]; then
            case " $dead_links " in *" $lk "*) ;; *) dead_links="$dead_links $lk" ;; esac
        fi
    done < <(grep -oE '\]\(([^)#]+\.(md|sh|py|json))' "$d" | sed 's/^](//' | sort -u)
done

echo "ДОКУМЕНТАЦИЯ ПРОТИВ ДЕРЕВА"
if [ -n "${missing_fwd# }" ]; then
    echo "  механизм есть, описания нет ($(printf '%s' "$missing_fwd" | wc -w | tr -d ' ')):"
    for n in $missing_fwd; do echo "      · $n"; done
else
    echo "  все механизмы дерева упомянуты"
fi
echo "  библиотек (*-lib.sh) исключено: $libs — считаются числом, не поимённо"
echo "  описано в реестре замеров: $registry — там назначение и срок у каждого"
if [ -n "${dead_back# }" ]; then
    echo "  МЁРТВЫЙ УЧАСТОК — описание есть, файла нет ($(printf '%s' "$dead_back" | wc -w | tr -d ' ')):"
    for n in $dead_back; do echo "      · $n"; done
else
    echo "  мёртвых упоминаний нет"
fi

if [ -n "${dead_links# }" ]; then
    echo "  МЁРТВАЯ ССЫЛКА — ведёт в никуда ($(printf '%s' "$dead_links" | wc -w | tr -d ' ')):"
    for n in $dead_links; do echo "      · $n"; done
else
    echo "  мёртвых ссылок нет"
fi

if [ -n "${missing_fwd# }" ] || [ -n "${dead_back# }" ] || [ -n "${dead_links# }" ]; then
    echo "[замер: находки, не сбой]"
    exit 1
fi
exit 0
