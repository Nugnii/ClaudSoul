#!/usr/bin/env bash
# state-prune.sh — состояние не растёт монотонно: файлы мёртвых сессий и лишние копии.
# Результат: нет посессионных файлов старше окна замеров; копии сверх трёх свежих на базу
#            названы и ждут решения владельца (без --include-backups не трогаются)
# Проверка результата: bash scripts/state-prune.sh | grep -q 'за окном хранения ([0-9]* на семейство): 0,'
#
# Повод (D252). Замер 1 сентября 2026: 2559 файлов и 36 МБ при порогах 3000 / 40 МБ — 85% и
# 90%. Темп с 15 апреля около 18 файлов в день, то есть порог берётся примерно через месяц,
# и замер краснеет без того, кто его чинит. Инструмент, который только называет число, —
# не инструмент: результат есть состояние мира, а не работа прибора.
#
# ЧТО МОЖНО УБИРАТЬ, А ЧТО НЕЛЬЗЯ — разделитель назван и проверен, а не угадан.
#
# 1. Окно замеров. Самое длинное окно в СЕССИЯХ — 40 (`signal-precision.sh:56`,
#    `dead-sensor-check.sh`). Число 200 в
#    `knowledge-activator.sh` относится к общему журналу инжектов, а не к посессионным файлам.
#    Порог хранения 60 покрывает все известные окна с запасом; уменьшать его — значит резать
#    вход замерам.
#
# 2. ОЧЕРЕДЬ ≠ ВЫБОРКА. Файл, который держит НЕЗАКРЫТЫЙ долг (исход, о котором ещё напомнят),
#    очередью и остаётся: у него нет окна, у него есть незакрытые записи. Такие семейства
#    исключены поимённо ниже. Выборка (журнал срабатываний, из которого считают долю)
#    подрезается по числу — старое за окном на долю уже не влияет.
#
# 3. Живая сессия не трогается никогда, даже если её файлы старые: источник — реестр
#    ~/.claude/sessions (записи `active/`, метки `live/`), а живость — признак процесса,
#    а не наличие записи (D337, см. ниже).
#
# 4. Сессия в тишине уходит из семейства, где она вне KEEP последних (D1006, решение владельца
#    19 октября 2026). Окно «KEEP свежих на семейство» не наполняется у семейства, где после
#    идентификатора сессии стоит ключ (`module-ctx-<sid>-<md5>.flag`, `own-frame-notice-<sid>-<n>`,
#    хвост корня у диспетчера): каждый ключ — своя семья из одного-двух файлов, и файл живёт вечно
#    (437 таких семей 19 октября; 1 октября у флагов диспетчера — 33 548). Поэтому файл сессии
#    уходит, когда сессия не жива, ни один её файл не моложе IDLE дней и она не входит в KEEP
#    последних сессий своей ГРУППЫ имён: основа (часть до идентификатора) плюс хвост, где ключи
#    (хеш, счётчик) сведены к одному знаку. Все ключи семейства — одна группа, а постоянный хвост
#    различает семейства одной основы (`semantic-prefetch-<sid>.json` и `.json.prompt`).
#    РАНГ — ВНУТРИ ГРУППЫ, А НЕ ПО КАТАЛОГУ, и это измерено потерей. Первая редакция брала KEEP
#    последних сессий всего каталога, и журнал, который пишется не в каждой сессии, терял глубину:
#    прогон 19 октября оставил `correction-fired` 29 сессий при окне читателя 40
#    (`signal-precision.sh:56`), `doc-state` 9 и `backlog-stale-read` 4 при окне 20 файлов
#    (`doc-state-decisions.sh:23`, `backlog-stale-reads.sh:25`). Резервной копии не было, окна
#    наполняются заново. Ранг по группе оставляет каждому семейству KEEP его последних сессий —
#    больше любого окна читателя; ранг по одной основе делил окно между её семействами, и редкое
#    вытеснялось частым. Найдено финальным скептиком (воспроизведено на macOS, mawk, gawk).
#    Ключ из букв (не хеш и не число) дал бы по группе на ключ, и такие файлы росли бы до сигнала
#    `state-size.sh`: рост, а не потеря, — сторона ошибки выбрана намеренно. Замер 20 октября: ни
#    одна основа живого каталога так не дробится.
#    Календарь здесь законен: предмет — вернётся ли человек к сессии, а это время его простоя
#    (замер по 350 расшифровкам: 348 возобновлений короче 14 дней, два — 21 и 34,6 дня).
#    Свежесть берётся у ВСЕХ файлов сессии, а не у файлов семейства: у однажды записанных
#    (`backlog-snapshot-`, флаги по ключу) время — старт сессии, а возобновление обновляет
#    `startup-signals-<sid>.txt`. Не считаются только `disagreement-pending` и
#    `output-violations`: их дописывают за чужие сессии фоном (`dis_expire_old`).
#    Свежесть не вычислена (ручка IDLE не число, отказ find) — уборка не исполняется: пустой
#    список свежих читался бы как «все в тишине», и удалялось бы свежее.
#    Названные пределы: живость — метка `live/` не старше 120 минут, и открытая сессия, молчавшая
#    дольше IDLE дней, защиты не получает (условие снятия: признак живости увидит процесс);
#    сессия уходит из одного семейства и остаётся в другом, поэтому у сессии, возобновлённой после
#    IDLE дней, `declared-problem-recorded.sh:347-353` возьмёт начало сессии позже настоящего.
#
# Как пересобрать список семейств, читаемых ЧЕРЕЗ сессии (если добавится новый механизм):
#   grep -rhoE '/[a-z][a-z0-9_-]*[-_]\*\.?[a-z]*' hooks/*.sh scripts/*.sh scripts/*.py \
#     | sed 's|^/||' | sort -u
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
KEEP="${STATE_PRUNE_KEEP:-60}"
IDLE="${STATE_PRUNE_IDLE_DAYS:-14}"   # дни тишины, после которых файлы сессии уходят (пункт 4)
SNAP_IDLE="${STATE_PRUNE_SNAP_IDLE_DAYS:-3}"   # дни тишины, после которых уходят снимки стража разбора (пункт 5)
APPLY=0; INCLUDE_BAKS=0
BAK_KEEP="${STATE_PRUNE_BAK_KEEP:-3}"
# РУЧКИ — ЦЕЛЫЕ ЧИСЛА, иначе отказ. Нечисло давало в awk строковое сравнение («1x» снимал 59 из 70
# свежих файлов), «00» в find — «моложе 0 дней», и пустой список свежих читался как «все в тишине»;
# «2w» BSD find понимает, GNU — нет. Найдено вторым кругом финального скептика D1006. Нули в начале
# снимаются `10#`, чтобы «08» не стало восьмеричной ошибкой. Больше 18 значащих цифр арифметика bash
# сворачивает по модулю 2^64 («18446744073709551617» → 1, с --apply это удаление) — третий круг.
_int_knob() {  # _int_knob <имя> <значение> <минимум>
    local v="${2#"${2%%[!0]*}"}"
    case "$2" in ''|*[!0-9]*) ;; *) [ "${#v}" -le 18 ] && [ "$((10#$2))" -ge "$3" ] && return 0 ;; esac
    echo "state-prune: $1=«${2}» — не целое число от $3 (до 18 значащих цифр); уборка не исполнена"
    exit 2
}
_int_knob STATE_PRUNE_KEEP "$KEEP" 1
_int_knob STATE_PRUNE_IDLE_DAYS "$IDLE" 1
_int_knob STATE_PRUNE_SNAP_IDLE_DAYS "$SNAP_IDLE" 1
_int_knob STATE_PRUNE_BAK_KEEP "$BAK_KEEP" 0
KEEP=$((10#$KEEP)); IDLE=$((10#$IDLE)); BAK_KEEP=$((10#$BAK_KEEP)); SNAP_IDLE=$((10#$SNAP_IDLE))
for a in "$@"; do
    case "$a" in
        --apply) APPLY=1 ;;
        --include-backups) INCLUDE_BAKS=1 ;;
        --dry-run) ;;
        *) echo "usage: $0 [--dry-run|--apply] [--include-backups]"; exit 2 ;;
    esac
done
[ -d "$STATE" ] || { echo "каталога состояния нет: $STATE"; exit 0; }

# ХРАНИМЫЕ ЦЕЛИКОМ — семейства, чьё число «за всё время» читают сырым по маске, и очередь
# незакрытого долга. Разбор читателей 19 октября 2026 (D1006, 9 искателей и 9 скептиков):
#   disagreement-pending — открытые ключи и доля закрытых в README (dis_stats → metrics.md);
#   output-violations    — три публикуемых ряда README (всего, по месяцам, на сессию);
#   blocker-fired, trust-guard-fired — числа README (scripts/doc-figures.sh:171-178);
#   five-whys, outcome   — свод незакрытых поводов за всё время (hooks/lib/open-findings-lib.sh:124,168);
#                          у five-whys — журнал `.seen`; снимки `.snap-` в хранение не входят (D1117, ниже).
#   detection            — доля «сказано» у violation-class: без потерь нужны 147 журналов из 157.
# Любое частичное удаление у них сдвигает опубликованное число, поэтому за окном они не удаляются, а уходят в АРХИВ
# семейства (`hooks/lib/state_archive.py`, D1008, решение владельца 29 октября 2026 «архив строк на семейство»):
# строки файла переносятся в `archive/<семейство>.tsv`, файл удаляется, читатели читают «архив + живые файлы», и
# формула числа остаётся у них. Окно — то же, что у прочих семейств; числа до и после переноса одни и те же
# (`hooks/tests/test_state_archive_readers.sh`; на копии живого каталога 29 октября — 1861 файл в архив, ни одно
# число не сдвинулось, по 60 сессий на семейство).
# Прежний довод «все эти семейства меньше 100 файлов» был объявлением без сверки: в день правки у
# десяти из шестнадцати их было больше сотни (blocker-fired — 992). Девять вышли из списка, потому
# что их читатели берут свою сессию или окно не длиннее 40 сессий: rework-fired, correction-fired,
# compile-reminded, compile-counted, question-open, narrative-pending, doc-state, intrusiveness,
# backlog-stale-read.
KEEP_FAMILIES='disagreement-pending|output-violations|blocker-fired|trust-guard-fired|detection|outcome|five-whys'

# Имена в реестре живых сессий — `<sid>.json`, а файлы состояния зовутся `<sid>`,
# `response-<sid>.jsonl`, `session-speaker_<sid>`. Регулярка `<sid>.json` совпадала только
# там, где после sid идёт точка, — то есть ЧЕТЫРЕ семейства из семи (`session-speaker_`,
# `knowledge-capture-`, `knowledge-capture-marker-`, `itr_event_last_fire_`) живой сессией
# не защищались вовсе. Пока прибор бегал сухим, это было безвредно; при исполняющем режиме
# уборка сносила бы состояние ИДУЩЕГО разговора (D274). Расширение снимается, остаётся sid.
#
# Живость решается ПРИЗНАКОМ процесса, а не наличием записи (D337, корень R3). Признак один
# на систему и живёт у реестра — `sr_record_alive` (hooks/session-registry-lib.sh): за
# числовым sid стоит процесс, за UUID — свежая метка `live/<sid>.json`. Читаются ОБА
# каталога: после первого Stop накопитель `active/<sid>.json` унесён в реестр, и параллельная
# сессия видна только меткой — по одному `active/` она не защищалась вовсе. Запись без
# признака (фикстура прогона, брошенный накопитель) защиты не получает и называется числом.
# Замер 6 сентября 2026: в `active/` 3 записи, 2 из них фикстуры (`perf.json`, `probe.json`)
# — обе защищали файлы, которых нет. Сами записи прибор не удаляет: это предмет
# `sr_cleanup_stale`, и срок там свой (накопитель хода нельзя снести раньше, чем finalize
# унесёт его в реестр).
ACTIVE=""; ORPHANS=""; ORPHAN_N=0
SR_LIB="$(cd "$(dirname "$0")/.." 2>/dev/null && pwd)/hooks/session-registry-lib.sh"
[ -f "$SR_LIB" ] || SR_LIB="$HOME/.claude/hooks/session-registry-lib.sh"
if [ -f "$SR_LIB" ]; then
    # shellcheck source=/dev/null
    . "$SR_LIB"
    while IFS= read -r _f; do
        [ -n "$_f" ] || continue
        _sid=$(basename "$_f" .json)
        case "|$ACTIVE|$ORPHANS|" in *"|$_sid|"*) continue ;; esac
        if sr_record_alive "$_sid"; then
            ACTIVE="${ACTIVE:+$ACTIVE|}$_sid"
        else
            ORPHANS="${ORPHANS:+$ORPHANS|}$_sid"; ORPHAN_N=$((ORPHAN_N + 1))
        fi
    done <<EOF
$(find "$SR_ACTIVE_DIR" "$(_sr_live_dir)" -maxdepth 1 -type f -name '*.json' 2>/dev/null | sort)
EOF
elif [ -d "$HOME/.claude/sessions/active" ]; then
    # Библиотеки нет — признака процесса взять неоткуда; это состояние «прибор сломан», и
    # оно называется, а не глотается: молчание здесь читалось бы как «фикстур нет».
    echo "библиотеки реестра нет ($SR_LIB): живость по наличию записи, без признака процесса"
    ACTIVE=$(ls "$HOME/.claude/sessions/active" 2>/dev/null | sed 's/\.json$//' | tr '\n' '|' | sed 's/|$//')
fi

SID_RE='[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
TMP=$(mktemp -d) || exit 0
trap 'rm -rf "$TMP"' EXIT

# Семейство = имя файла с вырезанным идентификатором сессии. Файл без идентификатора
# посессионным не является и не рассматривается вовсе.
# Суффикс актора (`.agent-<id>`) вырезается ВМЕСТЕ с идентификатором сессии: иначе каждый
# субагент даёт СВОЮ семью из одного файла, окно `KEEP` не заполняется никогда, и
# посессионное состояние агентов растёт без предела — при том что подрезание его и есть
# предмет этого скрипта. Найдено адверсариальной проверкой 18 сентября 2026, когда суффикс
# появился у `rework-<sid>`, `rework-world-<sid>` и `error_streak_fired_<sid>`: замер на 70
# файлах дал 30 подрезаемых без суффикса и 0 с ним.
# ОДИН ПРОХОД (D1006, 19 октября 2026). Прежде на каждый файл каталога порождались grep и
# sed, а на каждое семейство — awk по всему списку: при 7 тыс. файлах и 680 семействах сухой
# прогон шёл больше двух минут. `ls -t` даёт порядок свежести, sed отделяет идентификатор
# сессии табуляцией, awk решает за один проход. ponytail: заменяется первый идентификатор в
# имени — имён с двумя в каталоге нет (замер того же дня: 0 из 7 тыс.).
TOTAL=0; FILES="$TMP/doomed.txt"; : > "$FILES"; IDLED="$TMP/idle.txt"; : > "$IDLED"
ARCH="$TMP/archive.txt"; : > "$ARCH"   # «семейство ⇥ имя» — хранимые за окном, в архив семейства (D1008)
TAB=$(printf '\t')
# Сессии со свежим файлом (пункт 4 шапки): ни один файл моложе IDLE дней — сессия в тишине.
BG_FAMILIES='disagreement-pending|output-violations'
# `-H`: каталог состояния бывает ссылкой, и без флага find в стартовую ссылку не входит —
# список свежих выходил пустым при живых файлах (воспроизведено финальным скептиком).
if ! find -H "$STATE" -maxdepth 1 -type f -mtime "-$IDLE" > "$TMP/fresh.raw" 2>/dev/null; then
    echo "state-prune: свежесть сессий не вычислена (find по $STATE отказал) — уборка не исполнена"
    exit 2
fi
sed 's|.*/||' "$TMP/fresh.raw" | grep -Ev "^($BG_FAMILIES)-" | grep -oE "$SID_RE" | sort -u > "$TMP/fresh.txt"
# 5. СНИМОК СТРАЖА РАЗБОРА живёт, пока к его поводу ещё пишут исход (D1225). Замер 7 ноября 2026 по журналам исходов:
#    из 2185 поводов с исходом самый поздний закрыт через 44,3 ч после первой записи, позже 48 ч — ни одного. Снимок
#    содержимого общий для поводов сессии с тем же текстом, поэтому срок — тишина СЕССИИ, а не возраст файла: в живой
#    сессии новый повод берёт старый снимок. По правилу тишины в 14 дней (пункт 4) снимки копились до ~150 МБ при приросте
#    около 80 файлов и 11 МБ в сутки. Календарь законен по той же причине, что в пункте 4.
#    Тот же срок — у КЛЮЧЕЙ ПОДСКАЗКИ СВЯЗЕЙ (`impact-inject-<sid>[.agent-<id>].keys`, строка на показанный файл; D1274,
#    D1300): их читает только `hooks/impact-inject.sh` той же сессии («карточку этого файла уже показали»). До D1300 это
#    был флаг на каждый файл (`impact-inject-<sid>-<ключ файла>.flag`) — он уходит, как только установленный хук пишет
#    ключи (тогда читателя у формата нет), а до переноса живёт сроком снимков; такой флаг держал
#    по правилу пункта 4 все сессии двух недель — 10 ноября 2026 3001 флаг, после уборки 6705 файлов при пороге 6000.
#    Цена ошибки — карточка, показанная ещё раз в сессии, возобновлённой после трёх суток тишины.
if ! find -H "$STATE" -maxdepth 1 -type f -mtime "-$SNAP_IDLE" > "$TMP/snapfresh.raw" 2>/dev/null; then
    echo "state-prune: свежесть сессий для снимков не вычислена (find по $STATE отказал) — уборка не исполнена"
    exit 2
fi
sed 's|.*/||' "$TMP/snapfresh.raw" | grep -Ev "^($BG_FAMILIES)-" | grep -oE "$SID_RE" | sort -u > "$TMP/snapfresh.txt"
# Прежние флаги подсказки связей по ключу снимаются, только когда УСТАНОВЛЕННЫЙ хук уже пишет ключи строками (D1300,
# скептик H1): уборка исполняется из репозитория, а флаги читает установленная копия — до переноса снятие флага давало
# живой сессии повтор карточки. Признак готовности — строка файла ключей в установленном хуке (как библиотека архива
# ниже, пункт про архив семейств).
II_HOOK="${STATE_PRUNE_II_HOOK:-$HOME/.claude/hooks/impact-inject.sh}"
II_READY=0
grep -qF 'impact-inject-${SID}${_II_ACTOR}.keys' "$II_HOOK" 2>/dev/null && II_READY=1
ls -tp "$STATE" 2>/dev/null | grep -v '/$' | grep -E "$SID_RE" \
  | sed -E "s/($SID_RE)/$TAB\1$TAB/" \
  | awk -F'\t' -v keep="$KEEP" -v keepre="^($KEEP_FAMILIES)\$" -v bgre="^($BG_FAMILIES)\$" \
        -v freshf="$TMP/fresh.txt" -v snapf="$TMP/snapfresh.txt" -v idlef="$IDLED" -v archf="$ARCH" -v iiready="$II_READY" \
        -v deadre='^(bash-dispatch-(queue|mark)-<sid>|bash-dispatch-done-<sid>.*)$' '
    BEGIN { while ((getline l < freshf) > 0) fresh[l] = 1; close(freshf)
            while ((getline l < snapf) > 0) snapfresh[l] = 1; close(snapf) }
    {
        name = $1 $2 $3; sid = $2
        fam = $1 "<sid>" $3; gsub(/\.agent-[A-Za-z0-9_-]+/, "", fam)
        s = fam; sub(/<sid>.*/, "", s); sub(/[-_]$/, "", s)
        # Ранг сессии ВНУТРИ ОСНОВЫ (пункт 4) — по её свежайшему файлу: `ls -t` даёт его первой
        # встречей. Группа ранга — основа плюс хвост, где ключи (хеш, счётчик, корень) сведены к
        # одному знаку: все ключи семейства — одна группа, а постоянный хвост различает семейства с
        # общей основой (`.json` против `.json.prompt`) — иначе редкое делило бы ранг с частым.
        t = $3; gsub(/\.agent-[A-Za-z0-9_-]+/, "", t)
        gsub(/[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]+/, "#", t); gsub(/[0-9]+/, "#", t)
        g = $1 "<sid>" t; k0 = g SUBSEP sid
        if (!(k0 in srank)) srank[k0] = ++sn[g]
        # Снимок стража (`five-whys-<sid>.snap-…`, D1108/D1115) — другой предмет под приставкой хранимого семейства
        # (D1117, корень R3): читатели семейства берут только журнал `.seen` (open-findings-lib, outcome-share,
        # delivery-miss), а снимок нужен лишь сверке исхода своей сессии. Уходит он по правилу тишины сессии (ниже):
        # окно семейства его не берёт — cksum в имени делает у каждого снимка своё семейство.
        # Пункт 5 шапки: снимок сессии, молчащей дольше SNAP_IDLE дней, уходит без окна и ранга.
        # Прежний флаг подсказки связей по ключу файла (`impact-inject-<sid>[.agent-…]-<ключ>.flag`) уходит и у свежей
        # сессии, когда установленный хук пишет ключи строками (`impact-inject-<sid>[.agent-<id>].keys`, D1300): тогда
        # читателя у этого формата нет. Без готовности установки флаг живёт по правилу тишины сессии, как раньше.
        if (iiready == 1 && $1 == "impact-inject-" && $3 ~ /\.flag$/) { print name; next }
        if (($3 ~ /^\.snap-/ || $1 == "impact-inject-") && !(sid in snapfresh)) { print name; next }
        if (s ~ keepre && $3 !~ /^\.snap-/) {
            # Хранимые «за всё время» за окном не удаляются, а уходят в архив семейства (D1008): окно то же, что у
            # прочих, а строки остаются читателям «архив + живые файлы» (`hooks/lib/state_archive.py`). В архив —
            # только форма члена (`member`): чужое имя срывало перенос семейства (скептик, L1); прочее хранится.
            ext = (s == "five-whys") ? "seen" : "jsonl"
            if ($3 !~ ("^(\\.agent-[A-Za-z0-9_-]+)?\\." ext "$")) next
            if (!(sid in fresh) && srank[k0] > keep) { print s "\t" name > archf; next }
            if (fam ~ /-fired-<sid>\.jsonl$/) {
                k = fam SUBSEP sid
                if (!(k in fr)) fr[k] = ++fn[fam]
                if (fr[k] > keep) print s "\t" name > archf
                next
            }
            if (++n[fam] > keep) print s "\t" name > archf
            next
        }
        # МЁРТВОЕ СЕМЕЙСТВО — БЕЗ ОКНА (D1006). Окно «KEEP свежих» не убывает у семейства, где
        # файлов меньше KEEP: прежняя редакция диспетчера записи командой (ключ — одна
        # сессия, без хвоста корня; флаги пар `done-`) читателя не имеет с 1 октября 2026
        # (`hooks/bash-write-dispatch.sh` пишет и читает только `<sid>-<корень>`), и 31
        # очередь — 13,9 МБ — жила вечно. Живые сессии по-прежнему защищает фильтр ниже.
        if (fam ~ deadre) { print name; next }
        if (!(sid in fresh) && srank[k0] > keep) { print name; print name > idlef; next }
        # ЖУРНАЛ СРАБАТЫВАНИЙ СЧИТАЕТ СЕССИИ, а не файлы: его читатель `signal-precision.sh:56`
        # берёт 40 СЕССИЙ на семейство, а у сессии с субагентами журналов несколько — 60 файлов
        # `rework-fired` давали около 19 сессий. Универсум тот же, что у читателя
        # (`signal-precision.sh:82-85`): `*-fired-<sid>[.agent-<id>].jsonl`. Прочие семейства считают
        # файлы: их читатели берут свою сессию или 20 свежих файлов, а счёт сессиями умножил бы
        # агентские семейства (`rework-`, `partial-read-`) вчетверо без читателя, которому это нужно.
        if (fam ~ /-fired-<sid>\.jsonl$/) {
            k = fam SUBSEP sid
            if (!(k in fr)) fr[k] = ++fn[fam]
            if (fr[k] > keep) print name
            next
        }
        if (++n[fam] > keep) print name
    }' > "$FILES"

