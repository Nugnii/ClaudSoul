def _is_num(v):
    """Число, а не bool: у вопроса «что считать числом» в файле один владелец (`_num` и листья)."""
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _num(d, key):
    """Число из словаря либо None: отсутствующее поле — «неизвестно», а не 0 (D436).

    Прежнее `.get(key, 0) or 0` отвечало нулём и на «поля нет», и на «поле равно 0»."""
    v = d.get(key) if isinstance(d, dict) else None
    return v if _is_num(v) else None


def _seg(key):
    """Имя ключа источника как сегмент пути в записи (D437, поправки скептика 17 сентября 2026).

    До D437 ключи result.json в запись не попадали вовсе — шли только числа четырёх названных полей;
    теперь ключ источника становится ключом записи, и у этого входа два отказа, оба воспроизведены.
    (а) ПАДЕНИЕ ДО ЗАПИСИ: ключ с одиночным суррогатом (`"\\ud800"` json.loads принимает) давал
    UnicodeEncodeError на `f.write` — прогон выпадал из журнала, тот самый исход, что чинил D436, а
    парсер из 4551354 на том же входе запись писал. Знак заменяется своим текстовым видом `\\ud800`
    (backslashreplace). Писать запись с ensure_ascii НЕЛЬЗЯ: escape одиночного суррогата — законный
    JSON для Python, а jq 1.7.1 на нём отказывает, и `jq -s` теряет ВЕСЬ журнал, а не одну строку
    (замер того же дня: «Invalid \\uXXXX\\uXXXX surrogate pair escape»).
    (б) МОЛЧАЛИВАЯ ПОТЕРЯ: ключ `a.b` и вложенный `a: {b}` давали ОДИН путь, и второй лист затирал
    первый (замер: из 5 и 9 в записи оставалась пятёрка). Буквальные `\\` и `.` экранируются
    обратной чертой, и путь однозначен по построению: разбиение по неэкранированным точкам
    возвращает ровно имена источника, индекс списка и ключ-цифра у одного родителя не встречаются, а
    буквальный текст `\\ud800` в источнике (черта удвоена) с заменённым суррогатом не совпадает.
    У имён без точки, черты и суррогата — в замере это 15 путей из 15 — сегмент равен имени.
    Названный предел: закрыт вход КЛЮЧЕЙ источника; `task_id` и `arm` приходят из argv, и имя
    каталога не из UTF-8 роняет запись так же, как до D436, — оператор задаёт их сам. Условие снятия:
    идентификаторы начнёт порождать механизм, а не рука, — тогда тот же приём у `main`."""
    return (key.replace("\\", "\\\\").replace(".", "\\.")
            .encode("utf-8", "backslashreplace").decode("utf-8"))


def _numeric_leaves(root, value):
    """Все числовые листья структуры: {путь источника через точку: число} (D437 — см. шапку).

    Стек, а не рекурсия: итог из тысячи вложенных скобок json.loads ещё разбирает, а рекурсивный
    обход уронил бы парсер ДО записи — прогон выпал бы из журнала (тот же исход, что чинил D436).
    Ветвление по типам — не перечень форм с открытым концом: универсум закрыт форматом, json.loads
    отдаёт только словарь, список, число, строку, bool и None."""
    out, stack = {}, [(root, value)]
    while stack:
        path, v = stack.pop()
        if isinstance(v, dict):
            stack.extend((f"{path}.{_seg(k)}", x) for k, x in v.items())
        elif isinstance(v, list):
            stack.extend((f"{path}.{i}", x) for i, x in enumerate(v))
        elif _is_num(v):
            out[path] = v
    return dict(sorted(out.items()))


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: parse-transcript.py <task_id> <arm>")
    task_id, arm = sys.argv[1], sys.argv[2]
    base = Path(os.environ.get("ABLATION_DIR", Path.home() / ".claude" / "ablation"))
    run = base / "runs" / task_id / arm
    if not run.is_dir():
        sys.exit(f"parse: прогона {task_id}/{arm} нет")

    # Значения из result.json НЕИЗВЕСТНЫ, пока файл не прочитан (D436 — см. шапку).
    tokens_in = tokens_out = turns = duration_ms = None
    source_numbers = {}
    usage_state = "unknown"
    result_file = run / "result.json"
    if result_file.is_file():
        try:
            res = json.loads(result_file.read_text())
        except Exception:
            # Exception, а не перечень форм: в теле try одна операция — прочесть и разобрать, —
            # и у ЛЮБОГО её отказа последствие одно: файл есть, чисел из него нет. Перечень
            # дважды оказывался неполон: UnicodeDecodeError ронял парсер до записи при
            # `(JSONDecodeError, OSError)`, RecursionError (итог из 200 000 скобок) — при
            # `(ValueError, OSError)`. Метрики частичны — транскрипты ниже всё равно считаются.
            usage_state = "corrupt"
        else:
            usage = res.get("usage") if isinstance(res, dict) else None
            tokens_in, tokens_out = _num(usage, "input_tokens"), _num(usage, "output_tokens")
            turns, duration_ms = _num(res, "num_turns"), _num(res, "duration_ms")
            # Названные выше четыре поля — для прежних читателей; ВСЁ числовое из итога идёт в
            # запись отдельно и целиком (D437): что есть стоимость, решает источник, а не перечень.
            source_numbers = _numeric_leaves("result", res)
            usage_state = "measured" if None not in (tokens_in, tokens_out) else "no_usage"
    if usage_state != "measured":
        # Оператор зовёт парсер рукой и смотрит в терминал: молчание читалось бы как «чисто».
        print(f"parse-transcript: стоимость {task_id}/{arm} НЕИЗВЕСТНА (usage={usage_state}) — "
              "неизвестное в записи null, а не 0", file=sys.stderr)

    all_commands = failed_commands = denials = unparsed = lines_read = 0
    for jf in run.glob("home/.claude/projects/*/*.jsonl"):
        # errors="replace": байт не из UTF-8 прежде ронял парсер ДО записи (прогон выпадал из
        # журнала); теперь такая строка не разберётся как JSON и попадёт в `unparsed` ниже.
        try:
            text = jf.read_text(errors="replace")
        except OSError:
            # ponytail: нечитаемый файл (нет прав, каталог с именем *.jsonl) идёт в тот же
            # счётчик, что и строка, — единицы смешаны намеренно; отдельное поле заводить,
            # когда появится потребитель, которому различие нужно. Прежде — падение до записи.
            unparsed += 1
            continue
        # split("\n"), а не splitlines(): строка JSONL кончается на \n и только на него, а
        # splitlines() режет ещё и по U+2028/U+0085/\x0c — JSON.stringify их не экранирует, и
        # законная строка с таким знаком в тексте распадалась на две потерянные вместе с её
        # tool_use (замер скептика: all_commands 0, потерь 2 при одной настоящей строке).
        for line in text.split("\n"):
            if not line.strip():
                continue
            try:
                item = json.loads(line)
            except ValueError:
                item = None
            if not isinstance(item, dict):
                # Тот же корень на втором входе (D436): неразобранная строка вносила в счёт
                # команд ноль молча, а оборванная последняя строка — ровно то, что оставляет
                # убитый запуск. Счёт остаётся нижней границей, но теперь НАЗВАННОЙ. Строка,
                # разобранная НЕ в словарь (`[]`, `null`, `5`), прежде роняла парсер до записи.
                unparsed += 1
                continue
            lines_read += 1
            msg = item.get("message")
            content = msg.get("content") if isinstance(msg, dict) else None
            if not isinstance(content, list):
                continue
            for block in content:
                if not isinstance(block, dict):
                    continue
                if block.get("type") == "tool_use":
                    all_commands += 1
                if block.get("type") == "tool_result" and block.get("is_error"):
                    # Решение стража — исход, а не провал: вызов НЕ исполнялся.
                    try:
                        denial = is_denial(result_text(block))
                    except DenyMarkUnavailable as e:
                        sys.exit(f"parse-transcript: владельца маркера отказа не спросить ({e}) — "
                                 "метрика плеча была бы смещена молча")
                    if denial:
                        denials += 1
                    else:
                        failed_commands += 1

    if not lines_read:
        # Ни одной разобранной строки — счёта команд НЕТ, а не «ноль команд» (см. шапку).
        all_commands = failed_commands = denials = None
        print(f"parse-transcript: счёт команд {task_id}/{arm} НЕИЗВЕСТЕН — из транскриптов "
              f"песочницы не разобрано ни строки (потеряно: {unparsed}); в записи null, а не 0",
              file=sys.stderr)

    metrics = {
        "e": "arm_metrics", "id": task_id, "arm": arm,
        "ts": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "tokens_in": tokens_in, "tokens_out": tokens_out, "usage": usage_state,
        "turns": turns, "duration_ms": duration_ms,
        **source_numbers,
        "all_commands": all_commands, "failed_commands": failed_commands,
        "transcript_lines": lines_read, "transcript_unparsed": unparsed,
        # Величина ВИДИМА, а не растворена: сколько ошибочных блоков были решениями стражей.
        "denials": denials,
    }
    with (base / "journal.jsonl").open("a") as f:
        f.write(json.dumps(metrics, ensure_ascii=False, separators=(",", ":")) + "\n")
    print(json.dumps(metrics, ensure_ascii=False))


if __name__ == "__main__":
    main()
