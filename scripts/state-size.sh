#!/usr/bin/env bash
# state-size.sh — объём каталога состояния и что в нём копится.
# Результат: в каталоге состояния нет разрастания без уборки
# Проверка результата: bash scripts/state-size.sh даёт 0
#
#
# Повод (D44). Ни размер каталога, ни число файлов не измерял ни один скрипт, строки в
# реестре не было. На момент заведения: 1522 файла / 12,8 МБ, при этом
# `knowledge-activator.sh:126-127` делает два `find` по всему каталогу на КАЖДОМ
# PreToolUse, а `intrusiveness-tracker.sh:100` — на каждом UserPromptSubmit.
#
# Оговорка из проверки, и она важна: замерено 20 мс на вызов при 1522 файлах — то есть
# объём СЕГОДНЯ безвреден. Именно поэтому его никто не увидит, когда он перестанет быть
# безвредным. Смысл этой строки не в текущем числе, а в том, чтобы рост стал видимым.
#
# Код возврата: 0 — в пределах порога; 1 — превышен.

set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
MAX_FILES="${STATE_MAX_FILES:-3000}"
MAX_MB="${STATE_MAX_MB:-40}"

[ -d "$STATE" ] || { echo "state-size: нет каталога $STATE" >&2; exit 2; }

FILES=$(find "$STATE" -type f 2>/dev/null | grep -c '' || true)
KB=$(du -sk "$STATE" 2>/dev/null | awk '{print $1}')
# Отказ `du` — не «ноль килобайт». Ноль правдив там, где читается СЧЁТ; здесь читается
# ЗАМЕР, и его отсутствие значит «не измерено», а не «пусто». Прежде отказ печатался как
# «0 МБ», то есть замер отчитывался о состоянии, которого не видел.
if [ -z "${KB:-}" ]; then
    echo "state-size: du не смог измерить $STATE — размер НЕ ИЗВЕСТЕН, порог не проверялся" >&2
    exit 2
fi
MB=$(( KB / 1024 ))

echo "Каталог состояния: ${FILES} файлов, ${MB} МБ (пороги: ${MAX_FILES} / ${MAX_MB} МБ)"
echo "Крупнейшие семейства:"
# Имя семейства = имя файла без идентификатора сессии и без даты.
find "$STATE" -maxdepth 1 -type f 2>/dev/null \
  | sed 's|.*/||' \
  | sed -E 's/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/<sid>/g; s/[0-9]{6,}/<n>/g' \
  | sort | uniq -c | sort -rn | head -8 | awk '{printf "  %5d  %s\n", $1, $2}'

RC=0
if [ "${FILES:-0}" -gt "$MAX_FILES" ]; then
    echo "⚠️ файлов больше порога — что-то копится без уборки"
    RC=1
fi
if [ "${MB:-0}" -gt "$MAX_MB" ]; then
    echo "⚠️ объём больше порога"
    RC=1
fi
exit "$RC"
