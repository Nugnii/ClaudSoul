#!/usr/bin/env bash
# state-size.sh — объём каталога состояния и что в нём копится.
# Результат: в каталоге состояния нет разрастания без уборки
# Проверка результата: bash scripts/state-size.sh даёт 0
#
#
# Повод (D44). Ни размер каталога, ни число файлов не измерял ни один скрипт, строки в
# реестре не было. На момент заведения: 1522 файла / 12,8 МБ, при этом
# `knowledge-activator.sh:194-195` делает два `find` по всему каталогу на КАЖДОМ
# PreToolUse, а `intrusiveness-tracker.sh:100` — на каждом UserPromptSubmit.
#
# Оговорка из проверки, и она важна: замерено 20 мс на вызов при 1522 файлах — то есть
# объём СЕГОДНЯ безвреден. Именно поэтому его никто не увидит, когда он перестанет быть
# безвредным. Смысл этой строки не в текущем числе, а в том, чтобы рост стал видимым.
#
# Код возврата: 0 — в пределах порога; 1 — превышен.

set -uo pipefail

# ПОРОГИ — ПО УСТАНОВИВШЕМУСЯ РЕЖИМУ (D1006, решение владельца 19 октября 2026). Прежние 3000 / 40 МБ
# стояли со дня заведения и были недостижимы при честной уборке: после неё каталог держит около
# 4 400 файлов / 66 МБ — семь хранимых целиком семейств (их числа «за всё время» стоят в README и в
# своде незакрытых поводов, ~2 000 файлов), журнал инжектов на 200 сессий (18,8 МБ) и посессионное
# состояние последних 14 дней. 6000 / 90 МБ были зелёными после уборки и краснели бы примерно через два месяца:
# хранимые растут на ~28 файлов в день, и красный значит «пора перевести их числа на накопительный
# счётчик» (условие снятия в `scripts/state-prune.sh`, KEEP_FAMILIES).
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
MAX_FILES="${STATE_MAX_FILES:-6000}"
# Объём пересчитан 7 ноября 2026 (D1225, решение владельца того же дня — 160 МБ): писатель снимков стража разбора
# (D1108) появился 26 октября, после порога 90 МБ, и при сроке снимка «три дня тишины сессии» (`scripts/state-prune.sh`,
# пункт 5) держит около 40 МБ — 327 файлов 14 сессий в тот день. Прочее после уборки — около 75 МБ (66 МБ 19 октября и
# рост журналов). Мера — занятое на диске (`du`), а не байты: после уборки около 130 МБ при 115 МБ байтов, прирост около
# 0,5 МБ в сутки — 160 краснеет примерно через два месяца, как задумано 19 октября. Файлов после уборки около 5 800 —
# порог 6000 прежний, его краснота по-прежнему значит «перевести хранимые на счётчик».
MAX_MB="${STATE_MAX_MB:-160}"
# Порог — целое число до 18 значащих цифр, иначе код 2: `[ -gt ]` на нечисле и на числе больше int64
# падает, ветка превышения не берётся, и замер отвечал 0, ничего не сравнив (второй и третий круги
# финального скептика D1006).
for _k in "STATE_MAX_FILES=$MAX_FILES" "STATE_MAX_MB=$MAX_MB"; do
    _v="${_k#*=}"; _s="${_v#"${_v%%[!0]*}"}"
    case "$_v" in ''|*[!0-9]*) _s=x ;; esac
    case "$_s" in x|???????????????????*) echo "state-size: ${_k%%=*}=«${_v}» — не целое число до 18 значащих цифр; порог не проверялся" >&2; exit 2 ;; esac
done

[ -d "$STATE" ] || { echo "state-size: нет каталога $STATE" >&2; exit 2; }

FILES=$(find "$STATE" -type f 2>/dev/null | grep -c '' || true)
KB=$(du -sk "$STATE" 2>/dev/null | awk '{print $1}')
# Отказ `du` — не «ноль килобайт». Ноль правдив там, где читается СЧЁТ; здесь читается
# ЗАМЕР, и его отсутствие значит «не измерено», а не «пусто». Прежде отказ печатался как
# «0 МБ», то есть замер отчитывался о состоянии, которого не видел.
if [ -z "${KB:-}" ]; then
    echo "state-size: du не смог измерить $STATE — размер НЕ ИЗВЕСТЕН, порог не проверялся" >&2
    exit 2
fi
MB=$(( KB / 1024 ))

echo "Каталог состояния: ${FILES} файлов, ${MB} МБ (пороги: ${MAX_FILES} / ${MAX_MB} МБ)"
echo "Крупнейшие семейства:"
# Имя семейства = имя файла без идентификатора сессии, без суффикса актора и без даты.
# Суффикс актора снимается ТАК ЖЕ, как в scripts/state-prune.sh: семья считается по
# ПРЕДМЕТУ файла, а не по тому, кто его писал. Без этой клаузы каждый субагент давал
# СВОЮ группу из одной строки — замер 18 сентября 2026: 38 одиночек `.agent-<id>`
# вытесняли из восьмёрки крупнейших настоящую семью `rework-rerun-<sid>.txt` из 23
# файлов, то есть отчёт о размере состояния прятал самое крупное за самым дробным.
find "$STATE" -maxdepth 1 -type f 2>/dev/null \
  | sed 's|.*/||' \
  | sed -E 's/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/<sid>/g; s/\.agent-[A-Za-z0-9_-]+//g; s/[0-9]{6,}/<n>/g' \
  | sort | uniq -c | sort -rn | head -8 | awk '{printf "  %5d  %s\n", $1, $2}'

RC=0
if [ "${FILES:-0}" -gt "$MAX_FILES" ]; then
    echo "⚠️ файлов больше порога — что-то копится без уборки"
    RC=1
fi
if [ "${MB:-0}" -gt "$MAX_MB" ]; then
    echo "⚠️ объём больше порога"
    RC=1
fi
exit "$RC"
