#!/usr/bin/env bash
# outcome.sh — записать исход повода разбора, который наблюдением не отличить от бездействия.
#
# Результат: у повода, признанного ложным, в журнале исходов стоит `disproved` с причиной,
#            а не `none` — доля ложных срабатываний считается, а не угадывается
# Проверка результата: bash hooks/tests/test_outcome_journal.sh даёт 0
#
# Зачем отдельная команда. Исход повода сверщик `declared-problem-recorded.sh` определяет
# НАБЛЮДАЕМО: изменился носитель после начала хода — `touched`, не изменился — `none`; `recorded` — только за исход
# этой команды, прошедший сверку (D1107).
# Один исход так не увидеть: вердикт «показалось» выглядит ровно как бездействие. Он и
# нужен здесь — не как поблажка исполнителю, а как ЗАМЕР: доля `disproved` есть точность
# признака. Больше четверти — сигнал сужается, а не исполнитель воспитывается
# (case-2026-08-28-enforcement-is-a-property-of-consequence: 40 отказов, 32 ложных).
#
# Применение:
#   bash scripts/outcome.sh disproved <сигнал> "<чем опровергнуто>"
#   bash scripts/outcome.sh fixed     <сигнал> "<что починено>"
#   bash scripts/outcome.sh debt      <сигнал> "<D-номер>"
#   bash scripts/outcome.sh knowledge <сигнал> "<имя знания>"
# Сигнал — один из сродов: rework correction question streak repeat discovery event (daily — до 13 сентября 2026, D358)
# (единственное определение перечня — RC_KINDS_RE в hooks/root-cause-lib.sh).
# Сессия берётся из DIS_SESSION либо CLAUDE_CODE_SESSION_ID; ключ хода — `manual`, потому
# что расшифровка команде недоступна: запись руками отличима от записи механизмом.
set -uo pipefail

OUT="${1:-}"; SIG="${2:-}"; WHY="${3:-}"

# `list` — предъявить незакрытое, прежде чем закрывать. Без него команда требовала назвать
# исход поводу, которого не показывала: замер 9 сентября 2026 — 954 записи в журналах
# исходов, предмет назван в 4 (0,4%), а свод требовал «довести до исхода» 147 поводов.
# Перечень берётся у того же прибора, что и счёт в своде (`of_open_list`), а не считается
# заново: две редакции правила зачёта разошлись бы при первой правке.
if [ "$OUT" = "list" ]; then
    OF_LIB="${OF_LIB:-$(cd "$(dirname "$0")/../hooks" 2>/dev/null && pwd)/lib/open-findings-lib.sh}"
    [ -f "$OF_LIB" ] || OF_LIB="$HOME/.claude/hooks/lib/open-findings-lib.sh"
    [ -f "$OF_LIB" ] || { echo "нет open-findings-lib.sh — перечень незакрытого недоступен" >&2; exit 1; }
    # shellcheck source=/dev/null
    . "$OF_LIB"
    of_open_list "${STATE_DIR:-$HOME/.claude/hooks/state}"
    exit $?
fi

case "$OUT" in
    disproved|fixed|debt|knowledge) ;;
    *) echo "применение: bash scripts/outcome.sh {list|disproved|fixed|debt|knowledge} [<сигнал>] [\"<чем>\"]" >&2; exit 2 ;;
esac
[ -n "$WHY" ] || { echo "не названа причина: исход без основания не считается" >&2; exit 2; }

RC_LIB="${RC_LIB:-$(cd "$(dirname "$0")/../hooks" 2>/dev/null && pwd)/root-cause-lib.sh}"
[ -f "$RC_LIB" ] || RC_LIB="$HOME/.claude/hooks/root-cause-lib.sh"
[ -f "$RC_LIB" ] || { echo "нет root-cause-lib.sh — журнал исходов недоступен" >&2; exit 1; }
# shellcheck source=/dev/null
. "$RC_LIB"
[ -n "$SIG" ] || { echo "не назван сигнал ($(printf '%s' "$RC_KINDS_RE" | tr -d :))" >&2; exit 2; }

# ИСХОД СУДИТСЯ ПО ЗАПИСИ, А НЕ ПО ТЕКСТУ (D1104, решение владельца 26 октября 2026, корень R5). Прежде принимался
# любой непустой текст, и отказ стража разбора снимался заявлением: по 213 сессиям у 4855 исходов из 5974 цепочки нет.
# Требовать произнесённую цепочку нельзя — защита API обрывает такие ответы (ADR-022; D1033 откатан за полтора часа).
# Поэтому исход обязан указывать на РЕЗУЛЬТАТ разбора, записанный в мир и проверяемый машинно:
#   · fixed / debt — пункт долга D<N> (в бэклоге проекта либо ClaudSoul) со строкой корня (R<N> либо «не дефект») и
#     хотя бы одним адресом проявления «путь:строка» в блоке пункта;
#   · knowledge — существующая запись базы знаний (case-/pattern-/principle-…);
#   · disproved — довод, как прежде: доля «показалось» есть замер точности признака.
# Сверка живёт у библиотеки (`rc_record_verdict`, D1106), а не здесь: тем же правилом её повторяет страж, прежде чем
# снять отказ, — читатель журнала, веривший любой строке `manual-`, обходился прямым вызовом `rc_log_outcome`. Запись
# обязана быть СВЕЖЕЙ (правлена после того, как страж впервые увидел повод) и ОТНОСИТЬСЯ к поводу (адрес — цель
# отказанной правки или предмет повода): прежняя редакция принимала любой старый пункт с корнем и адресом.
STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SID="${DIS_SESSION:-${CLAUDE_CODE_SESSION_ID:-manual}}"
SEEN=$(rc_seen_file "$STATE" "$SID")
# Контекст — повод этого рода, живой в последнем ходе, где страж его видел (D1109): первые взгляды, первая цель записи
# и пути предмета; не «последний отказ рода в сессии», который судил исход второго хода по цели первого.
CTX=$(rc_occasion_ctx "$SEEN" "$SIG")
export CLAUDSOUL_ROOT="${CLAUDSOUL_ROOT:-$(cd "$(dirname "$0")/.." 2>/dev/null && pwd)}"
# Исход судится против КАЖДОЙ живой находки рода в ходе отдельно, и в запись идут те, против которых он принят (D1116,
# скептик H2): прежде сверка шла против всех находок рода разом, и пункт о первой снимал отказ второй. Живого повода
# нет — судится форма, и строка не относится ни к одной находке: снять ею нечего.
TOKS=""; _rec=""; _skip=""
# Находка, у которой уже есть принятый исход, повторно не судится (D1139, корень R6): прежде «живая в ходе» значило и
# «снята пунктом», и «не названа», и «показалось» о второй находке ложилось и на первую — замер доли «показалось»
# читал решённую находку ложной. «Принятый исход» — по правилу стража, у библиотеки (D1292): память зачёта
# (`rc_chain_ok_tokens`) либо новейшая строка `manual-`, называющая находку, от якоря первого хода, где она жива
# (`rc_token_outcome_line`), — прежде здесь стояла своя копия с окном «только этот ход», и находку, закрытую в прошлом
# ходе, «показалось» о новой переписывало (ProjectA, 10 ноября 2026). Строка принимается, только если проходит ту же
# сверку, что у стража (`rc_record_verdict` против контекста находки): строку можно положить в журнал и мимо этой
# команды, и страж ей не верит (D1106, M1) — не верит и здесь. Сборка правила — `rc_token_accepted` (D1360): здесь она
# стояла второй копией стражевой, а сверщик на Stop знал только память зачёта.
_of=$(grep '^outfrom|' "$SEEN" 2>/dev/null | tail -1 | cut -d'|' -f3)
if [ -n "$CTX" ]; then
    _ct=$(printf '%s' "$CTX" | cut -d'|' -f2); _ct="${_ct#turn:}"
    while IFS= read -r _t; do
        [ -n "$_t" ] || continue
        # Контекст живого повода не собрался — не принят, а не принят по форме (D1129): пустой контекст значит «повода нет».
        _tc=$(rc_occasion_ctx "$SEEN" "$SIG" "$_ct" "$_t")
        if [ -z "$_tc" ]; then _skip="${_skip}${_t} — контекст повода не собран, запись не сверить с поводом
"; continue; fi
        if rc_token_accepted "$SEEN" "$STATE/outcome-${SID}.jsonl" "$_t" "$_of" "$_ct" >/dev/null 2>&1; then
            _skip="${_skip}${_t} — исход уже принят
"; continue; fi
        if _r=$(rc_record_verdict "$OUT" "$SIG" "$WHY" "$_tc"); then
            TOKS="${TOKS}${TOKS:+|}${_t}"
        else
            _skip="${_skip}${_t} — ${_r}
"
        fi
    done < <(printf '%s' "$CTX" | cut -d'|' -f5 | tr '\037' '\n' | sed -E 's/@[^@]*@[^@]*$//')   # перечень — через ␟ (D1127)
    # Причина — С ИМЕНЕМ ПОВОДА (D1243, скептик opus H1): прежде токен срезался, и «уже принят» о снятом поводе склеивался с
    # «запись старше повода» об открытом — агент читал «уже принят» и переписывал ту же запись (Biznes-sovetnik,
    # 4 ноября 2026). Путь повтора — базовым именем, как в тексте отказа стража; «уже принят» — в конце.
    _rec=$(printf '%s' "$_skip" | grep . | sed -E 's#^rework:[^ ]*/([^/ ]+):([0-9]+) — #rework:\1:\2 — #' \
        | awk '/ — исход уже принят$/ { a[++n] = $0; next } !s[$0]++ { print } END { for (i = 1; i <= n; i++) print a[i] }' \
        | awk 'NR > 1 { printf "; " } { printf "%s", $0 }')   # склейка не трогает «;» внутри причины (скептик opus по 3ec8907a)
    [ -n "$TOKS" ]; _rrc=$?
else
    _rec=$(rc_record_verdict "$OUT" "$SIG" "$WHY" ""); _rrc=$?
fi
if [ "$_rrc" -ne 0 ]; then
    printf 'исход не записан: %s.\nИсход ссылается на запись разбора в мире (пункт долга с корнем из карты и адресом проявления, запись знания), сделанную для этого повода, а не на слова.\n' \
        "${_rec:-проверка записи не исполнилась}" >&2
    exit 3
fi

# Ключ несёт ХОД (H1 скептика D1104): ключ по одному тексту совпадал в следующем ходе, дедуп `rc_log_outcome` молча
# отбрасывал повтор, а команда печатала «исход записан». Ход — у якоря стража ТЕКУЩЕГО хода (D1109, M3): ход отказа
# прошлого хода давал тот же ключ, и повтор во втором ходе снова терялся.
TURN=$(grep '^outfrom|' "$SEEN" 2>/dev/null | tail -1 | cut -d'|' -f2)
# И поводы (D1116): тот же пункт, дописанный проявлением второй находки, принимается уже для двух — это новая запись,
# а не повтор.
KEY="manual-$(printf '%s|%s|%s' "$WHY" "$TURN" "$TOKS" | cksum | awk '{print $1}')"

OUTF="$STATE/outcome-${SID}.jsonl"
_n0=$(grep -c '' "$OUTF" 2>/dev/null || true)
rc_log_outcome "$STATE" "$SID" "$KEY" "$SIG" "$OUT" "$WHY" "" "$TOKS"
_n1=$(grep -c '' "$OUTF" 2>/dev/null || true)
[ -n "$_skip" ] && printf 'для этих находок исход не принят:\n%s' "$_skip" >&2
# Дедуп пары называется, а не выдаётся за запись: «исход записан» при неизменном журнале — ложное утверждение.
if [ "${_n1:-0}" -gt "${_n0:-0}" ] 2>/dev/null; then
    echo "исход записан: $SIG → $OUT${TOKS:+ (поводы: ${TOKS//|/, })} ($OUTF)"
    # ПОДСКАЗКА «ЭТО РАЗВОРОТ» (D1303, 16 ноября 2026; решение владельца — подсказка, а не отказ). Эталонная выборка ProjectA
    # 16 ноября: «показалось» по переработке ошибочно у 8 из 15, у всех восьми между заходами был КРАСНЫЙ прогон. Живая
    # выборка 22 ноября (40 случаев с красным прогоном, слепое чтение хода): разворот в 22, шаг плана в 13, шаг протокола
    # в 3; из 32 снятых «показалось» разворотами были 18. Признак — повод разобрать, а не вердикт: отказом он ошибался бы
    # почти в половине случаев. Исход принят. Журнала случаев нет (D1303, 22 ноября 2026: прежний
    # `rework-red-hint.jsonl` не читал никто, а записанное выводится повтором помощника по журналу исходов и расшифровке на
    # время исхода, пока расшифровка жива — повтор к тому же берёт нынешнюю улику, а запись хранила ложную). Расшифровка — по сессии в каталоге
    # расшифровок (`CLAUDE_PROJECTS_DIR`, как у `project-conformance.sh`): команде её не передают. Нет расшифровки или
    # помощника — молчит.
    if [ "$OUT" = disproved ] && [ "$SIG" = rework ] && [ -n "$TOKS" ]; then
        _rr_py="$(dirname "$RC_LIB")/lib/rework_red_run.py"
        _rr_tr=""
        for _rr_f in "${CLAUDE_PROJECTS_DIR:-$HOME/.claude/projects}"/*/"$SID".jsonl; do [ -f "$_rr_f" ] && { _rr_tr="$_rr_f"; break; }; done
        if [ -f "$_rr_py" ] && [ -n "$_rr_tr" ]; then
            while IFS= read -r _rr_t; do
                case "$_rr_t" in rework:*) ;; *) continue ;; esac
                _rr_p="${_rr_t#rework:}"; _rr_p="${_rr_p%:*}"
                _rr=$(python3 -I "$_rr_py" "$_rr_tr" "$_rr_p" 600 2>/dev/null)
                case "$_rr" in
                    red*)
                        printf '⚠️ Между двумя последними правками %s был КРАСНЫЙ прогон (%s) — часто это разворот, а не «показалось» (чтение 40 таких случаев 22 ноября 2026: 18 из 32 снятых «показалось» были разворотами). Исход принят; если прогон опроверг первую попытку — разбери, почему она не сошлась (что в ней взято не из мира).\n' \
                            "${_rr_p##*/}" "${_rr#red	}"
                        ;;
                esac
            done <<EOF
$(printf '%s' "$TOKS" | tr '|' '\n')
EOF
        fi
    fi
else
    echo "исход уже записан в этом ходе тем же текстом — повтор не пишется ($OUTF)"
fi
