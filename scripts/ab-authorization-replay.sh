#!/usr/bin/env bash
# ab-authorization-replay.sh — ADR-010 Ф3: A/B нового классификатора авторизации
# Результат: расхождения нового и старого классификатора авторизации названы числом, а не предположением
# Проверка результата: bash scripts/ab-authorization-replay.sh — сверка прогнана, доля несогласий напечатана
#
# на накопленных транскриптах ДО включения гейта Ф2.
#
# A — семантика v1.22.0 (авторизация как состояние задачи);
# B — одношаговая проверка (ручка AUTH_ONESHOT_ONLY=1). Семантикой до v1.22.0 она не является с D1150: границу хода
# оба плеча берут правилом владельца реплики, и одношаговая судит ту же реплику, что пишет состояние, тем же
# классификатором — плечи расходятся лишь там, где реплика состояния не записала (D1205: на 30 расшифровках 11 из 11
# совпали по типу, 8 из них плечо A приняло по состоянию задачи).
# Оба прогона идут через hooks/lib/backfill-replay-one.sh в песочницах —
# живое состояние не трогается, события читаются из stdout воркера.
#
# Выборка: свежайшие основные транскрипты сессий (~/.claude/projects/*/*.jsonl,
# без subagents/workflows), размером 50КБ..6МБ, N штук (default 8). Границы
# выборки печатаются в отчёте: молчаливое усечение читается как «всё покрыто».
#
# Ожидание ADR-010: proactive(A) < proactive(B) — часть «самовольных» правок
# на деле шла под действовавшим поручением, которого одношаговая проверка не видела.
# Писалось, пока одношаговая видела уведомление задачи репликой; с D1150 (подпись плеча B выше) по типу ожидание
# проверяемо лишь на репликах без записи состояния, а различие плеч видно по ПУТИ решения — отчёт печатает, сколько
# решений плечо A приняло по состоянию задачи (маркер `auth:`).

set -uo pipefail

N="${1:-8}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORKER="$ROOT/hooks/lib/backfill-replay-one.sh"
[ -f "$WORKER" ] || { echo "нет воркера $WORKER" >&2; exit 2; }
command -v jq >/dev/null 2>&1 || { echo "нужен jq" >&2; exit 2; }

REAL_HOME="$HOME"
# Верхняя граница 6МБ, не 1.5МБ: длинные АВТОРИЗОВАННЫЕ сессии — именно та страта,
# где живут спорные proactive-классификации; кап 1.5МБ отбирал болтовню без правок
# (первый честный прогон: 3 деструктивных хода на 8 транскриптов — предмет замера
# был не тот, о котором утверждение).
SAMPLE=$(find "$REAL_HOME/.claude/projects" -maxdepth 2 -name "*.jsonl" -type f \
    ! -path "*subagents*" ! -path "*workflows*" -size +50k -size -6000k 2>/dev/null \
    | while IFS= read -r f; do
        # GNU-форма первой: на Linux `stat -f` возвращает 0 со справкой о ФС, и фоллбек
        # не наступает (см. hooks/portable-lib.sh, file_mtime).
        printf '%s %s\n' "$(stat -c %Y "$f" 2>/dev/null || stat -f %m "$f" 2>/dev/null)" "$f"
      done | sort -rn | head -"$N" | sed 's/^[0-9]* //')

# Без завершающего перевода строки: `printf '%s\n' ""` даёт одну пустую строку, и пустая выборка
# считалась ОДНИМ транскриптом — ветка «выборка пуста» была недостижима, а прогон уходил в
# «Не измеряли» с кодом 0 (поймано свидетелем test_ab_authorization_replay.sh, 12 сентября 2026).
TOTAL_FOUND=$(printf '%s' "$SAMPLE" | grep -c '' || true)
[ "$TOTAL_FOUND" -gt 0 ] || { echo "выборка пуста — транскриптов 50КБ..6МБ не нашлось"; exit 1; }

# Отрицательный контроль ДО замера: фикстура с заведомо деструктивным ходом.
# Ноль событий на ней = реплей неисправен, и нули корпуса — поломка, не данные.
# Урок этого же дня: два прогона подряд публиковали нули как «нет ходов», пока
# причиной была расщеплённая песочница (прибор не отличал «нет» от «не измерил»).
_selfcheck() {
    local fxd fx out
    # Свой каталог, а не файл по шаблону с суффиксом: BSD mktemp не подставляет X перед
    # суффиксом и создаёт файл под именем самого шаблона в ОБЩЕМ TMPDIR — остаток прерванного
    # прогона или вторая копия давали «File exists», и здоровый инструмент отвечал «реплей
    # неисправен» кодом 2 (прожарка 13 сентября 2026, атака 1).
    fxd=$(mktemp -d "${TMPDIR:-/tmp}/ab-selfcheck.XXXXXX") || return 1
    fx="$fxd/fixture.jsonl"
    # Контроль ПАРОЙ (D1205, круг скептика, H1): вопрос → правка самовольная; содержательная реплика → правка под
    # поручением, принятая плечом A по состоянию задачи. Прежний контроль с одной «обсуждаем дизайн» ждал самовольной
    # только потому, что в песочнице было мертво правило «содержательная реплика авторизует» (D207): живой
    # классификатор считает эту реплику поручением. Половина «под поручением» ловит эту поломку, маркер `auth:` —
    # плечо A, не видящее состояния прошлого хода.
    {
        jq -cn '{type:"user",timestamp:"2026-01-01T10:00:00Z",message:{role:"user",content:[{type:"text",text:"как лучше устроить дизайн?"}]}}'
        jq -cn '{type:"assistant",timestamp:"2026-01-01T10:00:05Z",message:{role:"assistant",content:[{type:"text",text:"Поправил."},{type:"tool_use",name:"Edit",id:"x",input:{}}]}}'
        jq -cn '{type:"user",timestamp:"2026-01-01T10:00:30Z",message:{role:"user",content:[{type:"text",text:"сегодня разбираемся с отчётами по продажам"}]}}'
        jq -cn '{type:"assistant",timestamp:"2026-01-01T10:00:35Z",message:{role:"assistant",content:[{type:"text",text:"Поправил отчёт."},{type:"tool_use",name:"Edit",id:"y",input:{}}]}}'
        jq -cn '{type:"user",timestamp:"2026-01-01T10:01:00Z",message:{role:"user",content:[{type:"text",text:"спасибо, посмотрю позже обязательно"}]}}'
    } > "$fx"
    out=$(AUTH_ONESHOT_ONLY=0 bash "$WORKER" "$fx" 2>/dev/null)
    rm -rf "$fxd"
    grep -q '"type":"proactive"' <<< "$out" && grep -q "solicited:'auth:task:content:Edit'" <<< "$out"
}
_selfcheck || { echo "реплей неисправен: контроль не дал пары «вопрос → самовольная, поручение → под поручением по состоянию» — числа корпуса были бы поломкой, не данными" >&2; exit 2; }

run_replay() { # $1 transcript, $2 oneshot(0|1) → события в stdout
    # Воркер САМ создаёт песочницу (export HOME=$WORK_DIR) и сам задаёт её каталог
    # состояния (STATE_DIR, ITR_STATE_DIR снят — D1154), живое состояние не трогает.
    # Прежде унаследованный STATE_DIR/ITR_STATE_DIR расщеплял песочницу — детектор
    # писал события в один каталог, воркер читал из другого, и реплей молча выдавал
    # ноль; здесь это держалось соглашением «не передавать», теперь держит воркер.
    AUTH_ONESHOT_ONLY="$2" bash "$WORKER" "$1" 2>/dev/null || true
}

count_type() { grep -c "\"type\":\"$2\"" <<< "$1" 2>/dev/null || true; }

PA=0; SA=0; PB=0; SB=0; GA=0; AA=0; ROWS=""
while IFS= read -r t; do
    [ -n "$t" ] || continue
    A=$(run_replay "$t" 0)
    B=$(run_replay "$t" 1)
    pa=$(count_type "$A" proactive); sa=$(count_type "$A" solicited)
    pb=$(count_type "$B" proactive); sb=$(count_type "$B" solicited)
    ga=$(count_type "$A" gentle)
    aa=$(grep -c "solicited:'auth:" <<< "$A" 2>/dev/null || true)
    PA=$((PA + pa)); SA=$((SA + sa)); PB=$((PB + pb)); SB=$((SB + sb)); GA=$((GA + ga)); AA=$((AA + aa))
    ROWS="${ROWS}| $(basename "$t" .jsonl | cut -c1-8)… | ${pa} | ${sa} | ${pb} | ${sb} |\n"
done <<< "$SAMPLE"

DA=$((PA + SA)); DB=$((PB + SB))
echo "# A/B авторизации (ADR-010 Ф3) — $(date -u +%Y-%m-%d)"
echo ""
echo "Выборка: ${TOTAL_FOUND} транскриптов (свежайшие, 50КБ..6МБ, без subagents/workflows)."
echo "A = состояние задачи (v1.22.0), B = одношаговая проверка по той же реплике владельца."
echo ""
echo "| Транскрипт | proactive A | solicited A | proactive B | solicited B |"
echo "|------------|-------------|-------------|-------------|-------------|"
printf '%b' "$ROWS"
echo "| **итого** | **${PA}** | **${SA}** | **${PB}** | **${SB}** |"
echo ""
if [ "$DA" -gt 0 ] && [ "$DB" -gt 0 ]; then
    echo "Деструктивных ходов классифицировано: A=${DA}, B=${DB}; gentle (для контроля неизменности): ${GA}."
    echo "Доля самовольных (proactive) среди деструктивных: A = $((PA * 100 / DA))%, B = $((PB * 100 / DB))%."
    echo "Плечо A приняло по состоянию задачи (поручение прошлого хода, маркер auth:) ${AA} из ${DA} решений."
    if [ "$PA" -lt "$PB" ]; then
        echo ""
        echo "Вывод: состояние задачи перевело $((PB - PA)) ходов из «самовольных» в «под поручением» — ожидание ADR-010 подтверждается на корпусе."
    elif [ "$PA" -eq "$PB" ]; then
        echo ""
        echo "Вывод: по типу разницы нет. С D1150 плечи судят одну реплику одним классификатором, и тип расходится лишь на реплике, не записавшей состояния, — расширение выборки этого не меняет; различие плеч — в пути решения (строка выше)."
    else
        echo ""
        echo "Вывод: proactive выросло — ПРОТИВОРЕЧИТ ожиданию ADR-010, гейт НЕ включать, разбираться."
    fi
else
    # Код 2, не 0: «не измеряли» с нулевым кодом читается планировщиком как успех — тот же
    # класс, что «пропущен» у measure-linux-parity.sh.
    echo "Не измеряли: деструктивных ходов в выборке не нашлось — расширь выборку (N=${N})."
    exit 2
fi
