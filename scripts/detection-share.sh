#!/usr/bin/env bash
# detection-share.sh — доля «страж сказал» против «промолчал по троттлу» (D205).
#
# Результат: у каждого стража названо число совпадений признака и доля тех, где он
#            заговорил — «сработал» и «помог» перестают быть одним утверждением
# Проверка результата: bash scripts/detection-share.sh печатает строку по каждому стражу
#            и даёт 0; при доле молчания выше половины — 1 (находка)
#
# Зачем (D205). Журналы `*-fired-<SID>.jsonl` пишутся ПОСЛЕ решения сказать: по ним видно
# только то, что страж заговорил, и невидимо то, сколько раз признак совпал, а страж
# промолчал по троттлу. Знаменатель отсутствовал по построению — тот же корень, что чинили
# у гейта разбора (D112): предмет учёта задан работой стража, а не событием мира.
#
# ЧТО РЕШАЕТ ЭТО ЧИСЛО. Доля молчания выше половины означает, что троттл съедает больше,
# чем пропускает: либо окно троттла слишком широко, либо признак совпадает слишком часто и
# его надо сужать. Решение принимает владелец; скрипт даёт число и называет, чего оно требует.
#
# ОКНО В СЕССИЯХ, А НЕ В ДНЯХ: ритм работы неравномерный.
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${DETECTION_SHARE_SESSIONS:-20}"
MIN_N="${DETECTION_SHARE_MIN_N:-20}"
command -v jq >/dev/null 2>&1 || { echo "нет jq"; exit 0; }

FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/detection-*.jsonl 2>/dev/null | head -n "$SESSIONS")
EOF
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "журналов совпадений нет: контур ещё не наработал данных (STATE=$STATE)"
    exit 0
fi

echo "Доля «сказал» по стражам (последние ${#FILES[@]} сессий, порог знаменателя $MIN_N):"
# СОБЫТИЕ — РАЗНАЯ ПОДПИСЬ, А НЕ КАЖДЫЙ ВЫЗОВ. Первый прогон (30 августа 2026) дал «сказал
# 14% и 16%» у двух стражей, и оба раза «промолчал» был повтором той же подписи: одна реплика
# собеседника на каждом вызове инструмента, тот же файл в той же сессии. Знаменатель считал
# объём работы — контрпример, названный в самой rc_note_detection. Теперь записи с полем `sig`
# сводятся по (страж, подпись): подпись «сказала», если прозвучала хоть раз; «промолчала»,
# если не прозвучала ни разу. Записи без подписи (старые журналы) считаются по-старому.
JQ_SIGS='def events: group_by(.guard) | map(.[0].guard as $g
    | (map(select(.sig != null)) | group_by(.sig) | map({said: (map(select(.act == "said")) | length > 0)})) as $bysig
    | (map(select(.sig == null))) as $raw
    | {guard: $g,
       n: (($bysig | length) + ($raw | length)),
       said: (($bysig | map(select(.said)) | length) + ($raw | map(select(.act == "said")) | length)),
       calls: length});'
jq -rs --argjson minn "$MIN_N" "$JQ_SIGS"'
    events
    | map(. + {share: (if .n > 0 then (.said * 100 / .n | floor) else 0 end)})
    | sort_by(-.n) | .[]
    | "  \(.guard): подписей \(.n) (совпадений \(.calls)), сказал \(.share)%"
      + (if .n < $minn then "  — мало данных, решения не принимаются"
         elif .share < 50 then "  — троттл съедает больше половины: сузить признак либо окно"
         else "  — соотношение здоровое" end)
' "${FILES[@]}" 2>/dev/null
FINDINGS=$(jq -rs --argjson minn "$MIN_N" "$JQ_SIGS"'
    events | map(select(.n >= $minn and (.said * 100 / .n) < 50)) | length
' "${FILES[@]}" 2>/dev/null)
case "${FINDINGS:-}" in ''|*[!0-9]*) FINDINGS=0 ;; esac
if [ "$FINDINGS" -gt 0 ]; then
    echo "[замер: находки, не сбой] стражей, где троттл съедает больше половины: $FINDINGS"
    exit 1
fi
exit 0
