#!/usr/bin/env bash
# adversary-replay.sh — ретро-прогон признака «крупный коммит без адверсариального прогона»
#                       по корпусу расшифровок: точность признака ДО подъёма уровня.
#
# Результат: названы два числа — доля крупных кодовых коммитов, ушедших без прогона, и
#            перечень случаев с адресами, по которому точность классифицируется вручную
# Проверка результата: bash scripts/adversary-replay.sh --self-test даёт 0 (оба плеча живы)
#
# Зачем (D372). ADR-015 разрешает поднимать уровень принуждения только по числам: ≥20
# срабатываний, доля без исхода выше половины, доля ложных ниже десятой части. Живой замер
# `adversary-before-commit` даёт первые два, но копит их с 9 сентября 2026 — а история
# коммитов уже есть. Ретро-прогон достаёт число из прошлого вместо ожидания.
#
# ПОЧЕМУ ЭТО НЕ ПРИБЛИЖЕНИЕ. Детект прогона — чистая функция от расшифровки, и берётся он
# из того же файла, что у стража (`hooks/lib/adversary-run-lib.sh`). Прогон по префиксу
# расшифровки воспроизводит ровно то, что страж видел в тот момент.
#
# ЛОЖНЫЕ СЧИТАЮТСЯ РУКАМИ. Скрипт печатает случаи с адресами (расшифровка, время, коммит);
# настоящее это срабатывание или ложное — решает человек. Тот же порядок у
# `scripts/signal-precision-corpus.py`: «инструмент не решает, настоящее совпадение или
# ложное». Прибор, который сам себе ставит точность, меряет своё мнение.
#
# НАЗВАННЫЕ ПРЕДЕЛЫ.
#  1. Порог считается по `git show <sha> --numstat`, а страж видел `git diff --cached`.
#     Совпадает, когда коммит взял ровно индекс; расходится при `git commit -a` и `--amend`.
#     Доля таких коммитов печатается ОТДЕЛЬНОЙ строкой, а не прячется в общем числе.
#  2. Сцепка «вызов в расшифровке → коммит» идёт по ВРЕМЕНИ (окно ниже). Коммит, сделанный
#     не через инструмент Bash этой сессии, в выборку не попадает — это видно по числу
#     несцепленных вызовов, оно тоже печатается.
#  3. Прогон из ДРУГОЙ сессии виден с 13 сентября 2026 (D373) в окне от времени РОДИТЕЛЯ
#     коммита до времени вызова — тем же правилом, что у стража (`adversary_run_elsewhere`,
#     у стража нижняя граница — HEAD, здесь HEAD в момент вызова и есть родитель). До этого
#     дня чужой прогон был невидим, и доля «без прогона» была верхней границей: 58 из 212
#     срабатываний приходились на дни с прогоном в соседней сессии. Предел детекта
#     наследуется: правка старше родителя, не вошедшая в него, вне окна.
#  5. Класс ложности «прогон не требовался» считается по ТИПУ коммита (chore/docs/test/perf
#     в заголовке) — тем же правилом, каким его классифицировали руками 9 сентября 2026
#     (11 из 212). Иных классов ложности осмотр того дня не нашёл; появится — добавляется
#     здесь, а не в прозе пункта.
#  4. Расшифровки живут ограниченное время; корпус — то, что уцелело, а не вся история.
set -uo pipefail

REPO="${CLAUDSOUL_REPO:-$(cd "$(dirname "$0")/.." && pwd)}"
# Корпус сужен до расшифровок ЭТОГО проекта, а не всех подряд. Сцепка идёт по ВРЕМЕНИ, и
# чужая сессия, коммитившая в свой репозиторий в ту же минуту, дала бы ложную сцепку с
# коммитом ClaudSoul — событие постороннего проекта попало бы в знаменатель. Поймано
# самопроверкой 9 сентября 2026: третье плечо насчитало 224 расшифровки при 55 своих.
# Имя каталога — путь репозитория, где `/` и пробел заменены дефисом (соглашение клиента).
_ARP_SLUG=$(printf '%s' "$REPO" | tr '/ ' '--')
CORPUS="${ADVERSARY_REPLAY_CORPUS:-$HOME/.claude/projects/$_ARP_SLUG}"
LINES_THRESHOLD="${LINES_THRESHOLD:-80}"
FILES_THRESHOLD="${FILES_THRESHOLD:-4}"
CODE_EXT="${CODE_REVIEW_EXT:-ts|tsx|js|jsx|mjs|cjs|py|sh|bash|go|rs|rb|java|kt|php|c|cc|cpp|h|hpp|sql}"
# Окно сцепки: коммит рождается через доли секунды после вызова, но вызов бывает длинным
# (`git add` + тесты + commit в одной команде). Верхняя граница щедрая, нижняя узкая.
WIN_BEFORE="${ADVERSARY_REPLAY_WIN_BEFORE:-5}"
WIN_AFTER="${ADVERSARY_REPLAY_WIN_AFTER:-300}"
MODE="${1:-run}"

command -v jq >/dev/null 2>&1 || { echo "нет jq"; exit 2; }
command -v git >/dev/null 2>&1 || { echo "нет git"; exit 2; }

AR_LIB="$REPO/hooks/lib/adversary-run-lib.sh"
[ -f "$AR_LIB" ] || { echo "нет $AR_LIB — детект недоступен, мерить нечем"; exit 2; }
# shellcheck source=/dev/null
. "$AR_LIB"

PORT_LIB="$REPO/hooks/portable-lib.sh"
if [ -f "$PORT_LIB" ]; then
    # shellcheck source=/dev/null
    . "$PORT_LIB"
else
    echo "нет $PORT_LIB — разбор времени непереносим, мерить нечем"; exit 2
fi

# Детект коммита берётся У СТРАЖА, а не пишется заново. `is_git_commit` смотрит на
# ИСПОЛНЯЕМУЮ часть команды: `git commit` в кавычках, в теле heredoc или внутри `grep`
# — это текст, а не коммит. Наивный `test("git commit")` давал 182 несцепленных вызова из
# 457 (40%): прибор считал собственные поисковые команды событиями мира.
SCOPE_LIB="$REPO/hooks/command-scope-lib.sh"
[ -f "$SCOPE_LIB" ] || { echo "нет $SCOPE_LIB — признак коммита разошёлся бы со стражем"; exit 2; }
# shellcheck source=/dev/null
. "$SCOPE_LIB"
command -v is_git_commit >/dev/null 2>&1 || { echo "is_git_commit недоступна — мерить нечем"; exit 2; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
# Память выборки вызовов по расшифровке: соседей одной расшифровки спрашивают на каждом
# случае «без прогона», а разбор большой расшифровки стоит секунды (см. библиотеку).
mkdir -p "$TMP/select-cache"; export ADVERSARY_SELECT_CACHE="$TMP/select-cache"
NOTNEEDED_RE="${ADVERSARY_NOTNEEDED_RE:-^(chore|docs|test|perf)(\\(|:|!)}"

# --- самопроверка прибора -----------------------------------------------------------
#
# Без обоих плеч ноль корпуса неотличим от поломки. Повод — ab-authorization-replay.sh:
# «два прогона подряд публиковали нули как "нет ходов", пока причиной была расщеплённая
# песочница (прибор не отличал "нет" от "не измерил")».
self_test() {
    local rc=0 probe="$TMP/probe.jsonl"
    jq -cn '{message:{content:[{type:"tool_use",name:"Skill",input:{skill:"adversary"}}]}}' > "$probe"

    # Положительное плечо: заведомый вызов обязан найтись.
    local pos; pos=$(adversary_run_count "$probe")
    if [ "${pos:-0}" -gt 0 ]; then echo "  положительное плечо: $pos (ожидалось >0) — ok"
    else echo "  положительное плечо: $pos — ПРИБОР СЛЕП"; rc=1; fi

    # Отрицательное плечо: невозможный маркер обязан дать ноль на том же входе.
    local neg; neg=$(ADVERSARY_SKILL_NAME='__нет_такого_скилла__' \
                     ADVERSARY_PROMPT_MARKER='__нет_такого_маркера__' \
                     adversary_run_count "$probe")
    if [ "${neg:-1}" -eq 0 ]; then echo "  отрицательное плечо: $neg (ожидался 0) — ok"
    else echo "  отрицательное плечо: $neg — ПРИБОР ВИДИТ ЧЕГО НЕТ"; rc=1; fi

    # Третье плечо: корпус на месте и непуст, иначе «0 коммитов» значит «нет каталога».
    local n; n=$(ls "$CORPUS"/*.jsonl 2>/dev/null | wc -l | tr -d ' ')
    if [ "${n:-0}" -gt 0 ]; then echo "  корпус: $n расшифровок — ok"
    else echo "  корпус: пусто ($CORPUS) — мерить не на чем"; rc=1; fi
    return $rc
}

if [ "$MODE" = "--self-test" ]; then
    echo "Самопроверка adversary-replay:"
    self_test && { echo "прибор исправен"; exit 0; } || { echo "прибор НЕИСПРАВЕН — числа не публиковать"; exit 2; }
fi
if [ "$MODE" != "run" ] && [ "$MODE" != "--run" ]; then
    echo "применение: adversary-replay.sh [run|--self-test]" >&2; exit 2
fi

echo "Самопроверка прибора:"
self_test || { echo "прибор НЕИСПРАВЕН — числа не публиковать"; exit 2; }
echo ""

# --- коммиты репозитория: sha и время СРАЗУ в эпохе ----------------------------------
#
# `%ct` вместо `%cI`: сцепка сравнивает числа, и приводить время каждого из тысячи коммитов
# к эпохе на каждом вызове значило бы звать `date` сотни тысяч раз. Разбор времени остаётся
# ровно там, где иначе нельзя, — на отметке расшифровки (она приходит строкой ISO).
COMMITS="$TMP/commits.tsv"
git -C "$REPO" log --format='%H%x09%ct' > "$COMMITS" 2>/dev/null || { echo "git log не дал ничего"; exit 2; }
[ -s "$COMMITS" ] || { echo "история пуста"; exit 2; }

# --- обход корпуса -------------------------------------------------------------------
BIG=0; NORUN=0; RUN=0; ELSEWHERE=0; NOTNEEDED=0; UNJOINED=0; SCANNED=0
# Полный перечень случаев кладётся туда, куда попросили: классификация ложных — ручная,
# и работать с ней надо в файле, а не в хвосте вывода. Умолчание — во временном каталоге.
CASES="${ADVERSARY_REPLAY_CASES:-$TMP/cases.txt}"; : > "$CASES"
CALLS="$TMP/calls.tsv"
PAIRS="$TMP/pairs.tsv"
ALLPAIRS="$TMP/allpairs.tsv"; : > "$ALLPAIRS"

for TR in "$CORPUS"/*.jsonl; do
    [ -f "$TR" ] || continue
    grep -qF 'git commit' "$TR" 2>/dev/null || continue
    SCANNED=$(( SCANNED + 1 ))

    # Если во ВСЕЙ расшифровке прогонов нет, то и ни в одном её префиксе их нет — префиксы
    # для такой сессии не считаем. Это не срезка выборки, а тождество: счёт по префиксу
    # монотонен по длине префикса.
    WHOLE=$(adversary_run_count "$TR")
    case "${WHOLE:-}" in ''|*[!0-9]*) WHOLE=0 ;; esac

    # ШАГ 1 — собрать ВСЕ вызовы коммита этой расшифровки: время и номер строки.
    # Номера строк добываются дешёвым грепом, точность — разбором и `is_git_commit`.
    : > "$CALLS"
    while IFS= read -r LN; do
        [ -n "$LN" ] || continue
        REC=$(sed -n "${LN}p" "$TR" 2>/dev/null | jq -c '
            select(.message.content? != null) | .timestamp as $t
            | .message.content | if type=="array" then .[] else empty end
            | select(type=="object" and .type=="tool_use" and .name=="Bash")
            | select((.input.command // "") | test("git commit"))
            | {t: $t, c: (.input.command // "")}' 2>/dev/null | head -1)
        [ -n "$REC" ] || continue         # строка не была вызовом инструмента — это текст
        TS=$(printf '%s' "$REC" | jq -r '.t // ""' 2>/dev/null)
        CMD=$(printf '%s' "$REC" | jq -r '.c // ""' 2>/dev/null)
        [ -n "$TS" ] || continue
        is_git_commit "$CMD" || continue
        T=$(iso_epoch "$TS")
        case "${T:-}" in ''|*[!0-9]*) T=0 ;; esac
        [ "$T" -gt 0 ] || continue
        printf '%s\t%s\t%s\n' "$T" "$LN" "$TS" >> "$CALLS"
    done <<EOF
$(grep -n 'git commit' "$TR" 2>/dev/null | cut -d: -f1)
EOF
    [ -s "$CALLS" ] || continue

    # ШАГ 2 — сцепка идёт ОТ КОММИТА К ВЫЗОВУ, а не наоборот.
    #
    # Прежде цикл шёл по вызовам, и коммит доставался тому вызову, который дотянулся до
    # него ПЕРВЫМ; вдобавок `awk` брал не ближайший коммит в окне, а самый ранний
    # (`d=$2-lo` — расстояние от НАЧАЛА окна). Два следствия, оба поймал противник
    # 9 сентября 2026:
    #   · атака 4 — успешный путь стража (напомнил → прогнали → закоммитили) читался как
    #     провал: вердикт снимался с ПЕРВОГО вызова, где прогона ещё не было. На живом
    #     корпусе 96 вердиктов из 741 (13%) снимались не с того вызова;
    #   · атака 5 — мелкий коммит, случившийся за 3 секунды ДО вызова, перехватывал сцепку,
    #     крупный выпадал, и прибор объявлял «мерить нечего» там, где предмет был.
    #
    # Верное правило: коммит породил ПОСЛЕДНИЙ вызов, случившийся до него. Поэтому для
    # каждого коммита берётся вызов с наименьшим НЕОТРИЦАТЕЛЬНЫМ зазором; небольшое окно
    # «до» оставлено на расхождение часов. Один коммит — один вызов по построению, и
    # отдельный дедуп больше не нужен: единица счёта есть коммит.
    awk -F'\t' -v wb="$WIN_BEFORE" -v wa="$WIN_AFTER" -v tr="$TR" '
        NR==FNR { csha[FNR]=$1; cts[FNR]=$2; cn=FNR; next }
        { ct[FNR]=$1; cl[FNR]=$2; cs[FNR]=$3; kn=FNR }
        END {
            for (i=1; i<=cn; i++) {
                # ДВА КАНДИДАТА, А НЕ ОДИН, и признак «выбрано» отдельным флагом.
                # Прежде `bestgap=-1` служил и сентинелом «не выбрано», и законным зазором:
                # окно пускает вызовы до -wb секунд ПОСЛЕ коммита (расхождение часов), и
                # условие `bestgap < 0` оставалось истинным навсегда — побеждал последний
                # отрицательный кандидат, то есть вызов ПОЗЖЕ коммита. Вердикт снимался с
                # более длинного префикса, и нарушение пряталось. На живом корпусе такой
                # выбор сделан в 4 сцепках из 769. Поймано вторым раундом противника.
                best=""; bestts=""; bestgap=0; hasbest=0      # ближайший вызов ДО коммита
                skew=""; skewts=""; skewgap=0; hasskew=0      # запасной: после, в пределах wb
                for (j=1; j<=kn; j++) {
                    gap = cts[i] - ct[j]
                    if (gap >= 0 && gap <= wa) {
                        if (!hasbest || gap < bestgap) { bestgap=gap; best=cl[j]; bestts=cs[j]; hasbest=1 }
                    } else if (gap < 0 && gap >= -wb) {
                        if (!hasskew || gap > skewgap) { skewgap=gap; skew=cl[j]; skewts=cs[j]; hasskew=1 }
                    }
                }
                if (hasbest)      print csha[i] "\t" best "\t" bestts "\t" bestgap "\t" tr
                else if (hasskew) print csha[i] "\t" skew "\t" skewts "\t" (-skewgap) "\t" tr
            }
        }' "$COMMITS" "$CALLS" > "$PAIRS"

    # Вызовы, которым не досталось ни одного коммита, — предел 2 шапки, печатается числом.
    _paired=$(cut -f2 "$PAIRS" 2>/dev/null | sort -u | grep -c . ) || _paired=0
    _calls=$(cut -f2 "$CALLS" 2>/dev/null | sort -u | grep -c . ) || _calls=0
    case "${_paired:-}" in ''|*[!0-9]*) _paired=0 ;; esac
    case "${_calls:-}" in ''|*[!0-9]*) _calls=0 ;; esac
    UNJOINED=$(( UNJOINED + _calls - _paired ))

    # ШАГ 3 — пары этой расшифровки уходят в ОБЩИЙ список. Оценка идёт после всего обхода:
    # один коммит достижим из НЕСКОЛЬКИХ параллельных сессий (реестр сессий той же машины
    # показывал 7 одновременных), а `BIG/RUN/NORUN` внутри цикла по расшифровкам об этом не
    # знают — одно событие мира ложилось и в числитель, и в знаменатель. На живом корпусе
    # 2 коммита из 767 сцеплены с двумя расшифровками. Это моя регрессия: снимая дедуп при
    # перестройке сцепки, я записал «один коммит — один вызов ПО ПОСТРОЕНИЮ» — верно внутри
    # расшифровки и неверно между ними; неиспользуемая переменная SEEN осталась уликой.
    # Поймано вторым раундом противника 9 сентября 2026.
    cat "$PAIRS" >> "$ALLPAIRS"
done

# Разрешение между сессиями: у коммита остаётся ОДИН вызов — с наименьшим зазором.
# При равных зазорах побеждает лексикографически первая расшифровка: исход не должен
# зависеть от порядка обхода каталога.
BEST="$TMP/best.tsv"
sort -t"$(printf '\t')" -k1,1 -k4,4n -k5,5 "$ALLPAIRS" 2>/dev/null \
  | awk -F'\t' '!seen[$1]++' > "$BEST"

while IFS="$(printf '\t')" read -r SHA LN TS GAP TR; do
    [ -n "$SHA" ] && [ -n "$LN" ] && [ -f "$TR" ] || continue

    # Порог — по кодовой части коммита. Слияния дифа не несут и в выборку не попадают:
    # `git show` для них пуст, и это правильный исход, а не потеря.
    NS=$(git -C "$REPO" show --numstat --format='' "$SHA" 2>/dev/null \
         | grep -E "	.*\.($CODE_EXT)\"?$" || true)
    [ -n "$NS" ] || continue
    FC=$(printf '%s\n' "$NS" | grep -c .) || FC=0
    LC=$(printf '%s\n' "$NS" | awk '{a+=$1; d+=$2} END{print a+d+0}')
    if [ "$LC" -le "$LINES_THRESHOLD" ] && [ "$FC" -le "$FILES_THRESHOLD" ]; then continue; fi

    BIG=$(( BIG + 1 ))
    head -n "$LN" "$TR" > "$TMP/prefix.jsonl" 2>/dev/null
    PRE=$(adversary_run_count "$TMP/prefix.jsonl")
    case "${PRE:-}" in ''|*[!0-9]*) PRE=0 ;; esac

    if [ "$PRE" -gt 0 ]; then
        RUN=$(( RUN + 1 ))
        continue
    fi
    # Прогон в ДРУГОЙ сессии (D373): окно от времени родителя коммита до времени вызова.
    SINCE=$(git -C "$REPO" log -1 --format=%ct "${SHA}^" 2>/dev/null); case "${SINCE:-}" in ''|*[!0-9]*) SINCE=0 ;; esac
    UNTIL=$(iso_epoch "$TS"); case "${UNTIL:-}" in ''|*[!0-9]*) UNTIL=0 ;; esac
    [ "$UNTIL" -gt 0 ] || UNTIL=$(( SINCE + 86400 ))
    ELSE=$(adversary_run_elsewhere "$TR" "$SINCE" "$UNTIL"); case "${ELSE:-}" in ''|*[!0-9]*) ELSE=0 ;; esac
    if [ "$ELSE" -gt 0 ]; then
        ELSEWHERE=$(( ELSEWHERE + 1 ))
        continue
    fi
    NORUN=$(( NORUN + 1 ))
    SUBJ=$(git -C "$REPO" log -1 --format=%s "$SHA" 2>/dev/null)
    MARK=""
    if grep -qE "$NOTNEEDED_RE" <<< "$SUBJ"; then NOTNEEDED=$(( NOTNEEDED + 1 )); MARK="	не требовался (тип коммита)"; fi
    printf '%s\t%s\t%s\t%s строк / %s файлов%s\n' \
        "$(basename "$TR" .jsonl | cut -c1-8)" "$TS" "$(printf '%s' "$SHA" | cut -c1-8)" "$LC" "$FC" "$MARK" >> "$CASES"
done < "$BEST"

echo "Ретро-прогон по корпусу расшифровок ($SCANNED с вызовами коммита):"
if [ "$BIG" -eq 0 ]; then
    echo "  крупных кодовых коммитов не сцеплено — мерить нечего (несцепленных вызовов: $UNJOINED)"
    exit 2
fi
SHARE=$(( NORUN * 100 / BIG ))
echo "  крупных кодовых коммитов: $BIG"
echo "  без адверсариального прогона: $NORUN ($SHARE%)"
echo "  с прогоном: $RUN"
echo "  с прогоном в другой сессии после родителя коммита (D373, в «с прогоном» не входит): $ELSEWHERE"
if [ "$NORUN" -gt 0 ]; then
    echo "  из «без прогона» — прогон не требовался по типу коммита (chore/docs/test/perf): $NOTNEEDED ($(( NOTNEEDED * 100 / NORUN ))%) — доля ложных, ТОЧКА"
fi
echo "  вызовов, не сцепленных с коммитом: $UNJOINED (предел 2 шапки)"
echo ""
echo "Случаи «без прогона» — для ручной классификации на настоящие и ложные:"
echo "  расшифровка  время  коммит  размер"
head -40 "$CASES" | sed 's/^/  /'
# `grep -c` при НУЛЕ совпадений печатает 0 И возвращает 1, поэтому `|| echo 0` дописывает
