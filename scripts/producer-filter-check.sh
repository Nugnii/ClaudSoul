#!/usr/bin/env bash
# producer-filter-check.sh — продюсер событий, читающий РЕЧЬ СОБЕСЕДНИКА лексическим
# Результат: продюсеров, применяющих словарь к речи собеседника без отсева чужой речи, — ноль
# Проверка результата: bash scripts/producer-filter-check.sh даёт 0
#
# словарём, обязан отсеивать чужую речь. Кто не отсеивает — называется по имени.
#
# Это ответ на D88 вместо параметра `propagation_risk`, который предлагала внешняя рецензия.
# Решение владельца 28 августа 2026: поля не вводить. Основание измеримое — за одни сутки
# нашлись ТРИ поля, живущие только в прозе (множитель у `fragile`, `effective_contradicted`,
# `contradiction_log`); четвёртое добавило бы ту же видимость точности. Шкала риска
# описывает элементы; проверка их трогает.
#
# Почему признак именно такой. Реестр продюсеров (`docs/event-producers-registry.md`)
# показал: наблюдаемое делится надвое. Кто смотрит на СВОЙ вывод — чужой речи там нет по
# построению. Кто смотрит на речь собеседника — там работает и цитирование, и пересылка
# чужого документа, и лексический словарь ловит их как объектный сигнал. Общая функция
# отсева живёт в `hook-input-lib.sh` (режет markdown-цитаты, типографские кавычки,
# вставленные документы). Вопрос один: подключена ли она там, где нужна.
#
# Замер, с которого всё началось (2026-08-27): `user-correction-guard.sh` читает речь
# собеседника словарём поправок и `hook-input-lib.sh` НЕ подключает. По корпусу D88 он дал
# 96 срабатываний вне цитат.
#
# Признаки наблюдаемые, суждения не требуют:
#   речь собеседника — упоминание last_user / role=="user" в извлечении текста;
#   лексический словарь — массив PATTERNS-подобных строк либо grep -qiE по перечню слов;
#   отсев — подключение hook-input-lib.sh.
#
# Использование: scripts/producer-filter-check.sh
# Exit: 0 — все подключили; 1 — есть продюсеры без отсева (находка, не сбой).
set -uo pipefail

REPO=$(git rev-parse --show-toplevel 2>/dev/null) || REPO="$(cd "$(dirname "$0")/.." && pwd)"
H="$REPO/hooks"
[ -d "$H" ] || { echo "producer-filter-check: нет $H" >&2; exit 2; }

MISSING=""; OK_LIST=""
# Признак строится в ДВА шага, и второй важнее первого.
#
# Шаг 1 — файл достаёт речь собеседника (переменная с USER в имени).
# Шаг 2 — СЛОВАРЬ ПРИМЕНЯЕТСЯ ИМЕННО К НЕЙ: в той же строке, где вызывается grep, стоит
#         эта переменная. Без шага 2 в улов попадают хуки, которым речь нужна для другого:
#         `five-whys-gate` берёт её как границу хода, `timestamp-canary-check` — как ключ
#         троттла. Обе читают речь и обе имеют альтернативы в регулярках, но ни одна не
#         прикладывает словарь к чужому тексту, и требовать от них отсева нечего.
#
# Первая версия проверки искала `PATTERNS=(` и встроенный в grep перечень — и пропустила
# `user-correction-guard.sh`, чей словарь лежит в `CORRECTION_REGEX='а|б|в…'`, то есть
# ровно тот хук, ради которого проверка писалась. Перечень форм неполон по построению
# (`pattern-subject-checked-by-enumeration`, confidence 4).
for f in "$H"/*.sh; do
    b=$(basename "$f")
    case "$b" in hook-input-lib.sh) continue ;; esac

    # Шаг 1: речь собеседника вообще извлекается.
    grep -qE '[A-Z_]*USER[A-Z_]*=\$\(|LAST_USER' "$f" 2>/dev/null || continue
    # Шаг 2: grep применяется К ЭТОЙ переменной — словарь работает по чужому тексту.
    grep -E 'grep' "$f" 2>/dev/null | grep -qE '\$\{?[A-Z_]*USER[A-Z_]*' || continue

    if grep -q 'hook-input-lib' "$f" 2>/dev/null; then
        OK_LIST="$OK_LIST $b"
    else
        MISSING="$MISSING $b"
    fi
done

echo "ПРОДЮСЕРЫ, ЧИТАЮЩИЕ РЕЧЬ СОБЕСЕДНИКА СЛОВАРЁМ"
[ -n "${OK_LIST# }" ] && echo "  ✅ отсев чужой речи подключён:$OK_LIST"
if [ -n "${MISSING# }" ]; then
    echo "  ⚠️  БЕЗ ОТСЕВА:$MISSING"
    echo "     Цитата, пересылка и вставленный документ попадут в словарь как объектный"
    echo "     сигнал. Подключается так: . \"\$HOOKS_DIR/hook-input-lib.sh\" и разбор текста"
    echo "     через её функции. Если для конкретного хука отсев не нужен — сказать почему"
    echo "     комментарием в шапке со словом hook-input-lib, тогда он засчитается."
    echo "[замер: находки, не сбой] — продюсеры без отсева перечислены выше"
    exit 1
fi
echo "  Все продюсеры со словарём по речи собеседника отсев подключают."
exit 0
