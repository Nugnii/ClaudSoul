#!/usr/bin/env bash
# backlog-stale-reads.sh — сколько раз за окно сессий показание бэклога прочитано устаревшим.
#
# Результат: число чтений BACKLOG.md, при которых показание в файле расходилось с выводом
#            своей команды, названо за окно последних сессий, и по нему принимается решение
# Проверка результата: bash scripts/backlog-stale-reads.sh даёт 0, когда за окно ни одно
#            чтение не застало показание устаревшим
#
# Зачем (D210). Утверждение «показание не может прожить устаревшим дольше одного хода»
# держится пересчётом на Stop, но внутри хода мир меняется тоже (сигналы пишут журнал
# исходов до конца хода), и чтение агентом может застать старое число. Эта величина не
# наблюдалась вовсе — она и есть предмет пункта. Пишет её `hooks/backlog-reading-refresh.sh`
# на PostToolUse[Read]: строка `{ts,item,file,world,path}` в `state/backlog-stale-read-<SID>.jsonl`.
#
# ЧТО РЕШАЕТ ЭТО ЧИСЛО. Ноль — пересчёта на границе хода достаточно. Больше нуля — показание
# устаревает ВНУТРИ хода, и пересчёт нужен ещё и при чтении (не только сверка); решение
# принимает владелец, скрипт называет число и адреса пунктов.
#
# ОКНО СЧИТАЕТСЯ В СЕССИЯХ, А НЕ В ДНЯХ — как у outcome-share.sh: ритм работы неравномерный.
# КОНТРПРИМЕР: чтение через Bash (`cat BACKLOG.md`) хук не видит, и сюда оно не попадает —
# число есть нижняя оценка, а не полный счёт; предел назван в шапке хука.
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${STALE_READS_SESSIONS:-20}"
command -v jq >/dev/null 2>&1 || { echo "нет jq"; exit 0; }

# Список — массивом: каталог состояния задаётся извне и может лежать по пути с пробелом.
FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/backlog-stale-read-*.jsonl 2>/dev/null | head -n "$SESSIONS")
EOF
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "устаревших чтений: 0 (журналов нет — за окно ни одно чтение не застало показание устаревшим, STATE=$STATE)"
    exit 0
fi

N=$(jq -rs 'length' "${FILES[@]}" 2>/dev/null)
case "${N:-}" in ''|*[!0-9]*) N=0 ;; esac
echo "устаревших чтений: $N (последние ${#FILES[@]} сессий)"
if [ "$N" -gt 0 ]; then
    jq -rs 'group_by(.item) | map("  · \(.[0].item): \(length) раз, последнее \(.[-1].ts): в файле «\(.[-1].file)», в мире «\(.[-1].world)»") | .[]' "${FILES[@]}" 2>/dev/null
    # [замер: находки, не сбой] — ненулевой код здесь не провал, а решение к принятию.
    echo "[замер: находки, не сбой] показание устаревает внутри хода — пересчёт нужен и при чтении, не только на Stop"
    exit 1
fi
exit 0
