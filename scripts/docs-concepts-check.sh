#!/usr/bin/env bash
# docs-concepts-check.sh — понятие ранга этапа названо в документах состояния, а не только в коде.
#
# Результат: ни одно понятие реестра не пропало из документов, где оно объявлено обязательным.
# Проверка результата: bash scripts/docs-concepts-check.sh даёт 0
#
# Повод, 10 сентября 2026. Карта корней («лес») построена 9 сентября и к следующему утру не
# упоминалась НИ В ОДНОМ документе состояния — нашёл это собеседник чтением. Числа документов
# держит реестр `doc-claims.tsv` (173 проверки), у понятий сверщика не было вовсе.
# Почему не поймали существующие: `doc-impact-check` требует решения, когда описание УЖЕ живо
# в документе, а у новой сущности связи в индексе нет; `docs-inventory.sh` ищет ИМЕНА
# механизмов, тогда как документ-экспорт по замыслу пишется без имён файлов — предмет сверки
# не тот (`pattern-subject-of-measurement-mismatch`).
#
# У прибора ТРИ состояния: реестра нет → сказать и выйти 2 (это поломка, а не «чисто»);
# понятие пропало → назвать поимённо и выйти 1; всё на месте → одна строка и 0.
set -uo pipefail

ROOT="${CLAUDSOUL_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")/.." 2>/dev/null && pwd -P)}"
REG="$ROOT/scripts/doc-concepts.tsv"
if [ ! -f "$REG" ]; then
    echo "docs-concepts-check: нет реестра $REG — это отказ прибора, а не «понятия на месте»" >&2
    exit 2
fi

MISS=0; SEEN=0
while IFS=$'\t' read -r name pat files why; do
    case "${name:-}" in ''|'#'*) continue ;; esac
    # Строка, которую НЕ УДАЛОСЬ разобрать, называется, а не выбрасывается (10 сентября 2026,
    # находка противника). Прежде `continue` без слова уносил строку с пробелами вместо
    # табуляции — опечатка в разделителе визуально неотличима, — и понятие исчезало
    # из-под надзора навсегда при зелёном «всё на месте».
    if [ -z "${pat:-}" ] || [ -z "${files:-}" ]; then
        echo "  ✗ строка реестра не разобрана (нет шаблона либо файлов): ${name}"
        echo "      колонки разделяются ТАБУЛЯЦИЕЙ; проверь: sed -n 's/\t/<TAB>/gp' \"$REG\""
        MISS=$((MISS+1))
        continue
    fi
    IFS=',' read -r -a _fs <<< "$files"
    for f in "${_fs[@]}"; do
        [ -f "$ROOT/$f" ] || { echo "  ✗ $f — файла нет, а понятие «${name}» в нём объявлено"; MISS=$((MISS+1)); continue; }
        SEEN=$((SEEN+1))
        # `grep -i` складывает регистр кириллицы только в UTF-8-локали, а `[а-яё]` в GNU grep
        # читается по-разному в C и C.UTF-8: в контейнере 12 сентября 2026 «пропали» 1 из 18
        # понятий без локали и 9 из 18 с C.UTF-8 при 0 на macOS. perl -CSDA сверяет символы.
        perl -CSDA -ne 'BEGIN{$p=shift} if(/$p/i){$f=1;last} END{exit($f?0:1)}' "$pat" "$ROOT/$f" 2>/dev/null && continue
        echo "  ✗ «${name}» пропало из $f"
        echo "      зачем оно там: $why"
        MISS=$((MISS+1))
    done
done < <(cat "$REG"; echo)

# --- вторая часть: КОРНИ КАРТЫ выводятся из неё самой, а не перечисляются -------------
# Реестр выше пополняется рукой, и в этом его предел: сущность, о которой не вспомнили,
# в него не попадёт. Здесь предел частично снят для того класса, который и случился:
# наличие корня в карте — факт дерева, и требовать его упоминания можно, ничего не
# объявляя. Новый корень подхватывается сам.
# Требуется УПОМИНАНИЕ ХОТЯ БЫ В ОДНОМ документе состояния, а не в каждом: подробность
# описания у документов разная по замыслу (пересказ, архитектура, таблица статуса).
ROOTS="$ROOT/ROOTS.md"
if [ -f "$ROOTS" ]; then
    _state_docs="CLAUDE.md docs/architecture.md docs/mechanism-errors-and-backlog.ru.md"
    while IFS= read -r _rid; do
        [ -n "$_rid" ] || continue
        SEEN=$((SEEN+1))
        _found=0
        for _d in $_state_docs; do
            [ -f "$ROOT/$_d" ] || continue
            # Целиком, а не префиксом: `grep -qF R1` находил его внутри «R10», и корень без
            # описания числился названным. Сегодня корней три, дефект наступал бы на десятом —
            # ровно там, где вторая половина прибора и должна работать (находка противника).
            grep -qE "(^|[^A-Za-z0-9])${_rid}([^0-9A-Za-z]|$)" "$ROOT/$_d" 2>/dev/null && { _found=1; break; }
        done
        [ "$_found" -eq 1 ] && continue
        echo "  ✗ корень ${_rid} есть в карте, но не назван ни в одном документе состояния"
        echo "      зачем: корень без описания снаружи — это лес, о котором знает только код"
        MISS=$((MISS+1))
    done <<< "$(grep -oE '^## R[0-9]+' "$ROOTS" 2>/dev/null | sed 's/^## //')"
fi

if [ "$SEEN" -eq 0 ]; then
    echo "docs-concepts-check: реестр пуст — сравнивать нечего, это отказ прибора" >&2
    exit 2
fi
if [ "$MISS" -gt 0 ]; then
    echo "[замер: находки, не сбой] понятий пропало: $MISS из $SEEN проверенных"
    exit 1
fi
echo "понятия контура на месте: проверено $SEEN"
exit 0
