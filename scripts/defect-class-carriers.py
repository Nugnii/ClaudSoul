# строкой. Условие снятия: у журнала появляется тождество (писатель → путь записи), и
# группировка идёт по паре (журнал, поле), а не по имени.
#
# НАЗВАННЫЙ ПРЕДЕЛ 2 — заведена одна форма рода из трёх, и это ИЗМЕРЕНО, а не решено.
# · Форма «величина объявлена в коде и не названа документом, который её определяет» (D293):
#   проба 4 сентября — «имя ручки (`os.environ.get`, `${ИМЯ:-}`) не упоминается в дереве
#   больше нигде» — дала 214 совпадений при десятках ложных (под неё подпадает всякий
