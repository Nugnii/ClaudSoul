# РОД I — граница поля отдана ПРОБЕЛЬНОМУ разделителю
#
# Признак НЕ ЗАВЕДЁН. Это вердикт, а не пропуск, и он с доказательством.
#
# Что пробовали (повод — D303, 3-4 сентября 2026, половина «реестр читается не как TSV»):
# «файл объявляет запись разделённой ТАБОМ (`IFS=$'\t'`) и разбирает её `read`-ом, для
# которого таб — ПРОБЕЛЬНЫЙ разделитель IFS: подряд идущие разделители сливаются в один,
# ведущие снимаются, и пустая НЕ-последняя колонка исчезает вместе со своей границей».
# Заявленное последствие: тихое — переменная держит значение соседа, вердикт вынесен.
#
# Устройство описано верно, и прогон его показывает:
#   printf 'a\t\tc\n' | while IFS=$'\t' read -r x y z  →  x=[a] y=[c] z=[]    ← съезд
#   printf 'a||c\n'   | while IFS='|'   read -r x y z  →  x=[a] y=[]  z=[c]   ← верно
# Но НАЛИЧИЕ схлопывания — это сам признак; мерить им себя тавтологично (по такой мерке
# было бы 7 из 7). Мерка «настоящий» взята жёстче: съезд ДОСТИЖИМ производителем потока
# И последствие тихое, как объявлено.
#
# ЗАМЕР 4 сентября 2026, осмотр ВСЕХ совпадений (единица — АДРЕС, не файл): 7 адресов в 4
# файлах, настоящих 0 (0%). По более мягкой мерке, одной достижимости без последствия — 1
# из 7 (14%). Оба числа ниже порога ~50%, за которым признак ловит ЖАНР, а не отношение.
# Разбор поадресно, у каждого назван производитель:
#   · `hooks/backfill-compliance.sh:85`, `:119`, `:131` (7, 4 и 4 поля) — производитель
#     ЕСТЬ и он один: `hooks/lib/backfill-compliance-one.py` (вызов
#     `backfill-compliance.sh:217` `xargs python3 "$WORKER"` → `:219` `> "$OUT_FILE"`).
#     Значения `arm`/`exposure` там — строковые литералы замкнутого перечня (`:211`
#     FRESH|STALE, `:284-294` never|d1|d2|d3_5|d6_10|d10p, `:298` и `:333-334`
#     treated|control, warned|unwarned, `:190-205` treated|treated_unknown|placebo),
