# подпадают три файла — сам прибор и два потребителя замка, — и у каждого потребителя ровно
# один адрес, то есть скрытых мест сегодня нет (проверено 5 сентября 2026 выводом самого
# прибора: `completion-gate.sh fired_log:311`, `knowledge-link-symmetry.sh parent:80`).
# Файл, написавший в комментарии «замка тут нет», выпадет молча.
#
# ПОТРЕБИТЕЛИ ЗАМКА ДОБАВЛЕНЫ 5 сентября 2026, и это починка промаха прибора, а не расширение
# охвата. Прежний признак искал РЕАЛИЗАЦИЮ замка (`mkdir … .lock`), которая есть ровно в
# одном файле — `hooks/state-lock-lib.sh`. Потребители зовут `with_lock`/`lock_acquire`/
# `atomic_filter`, и признак их не узнавал: `completion-gate.sh:131` и
# `knowledge-link-symmetry.sh:65` оборачивают свои блоки замком с 4 сентября, а прибор
# держал их в очереди как носителей. То есть очередь не убывала от той самой починки,
# ради которой род и заведён: 2 из 15 «носителей» были уже закрыты.
# Корень — не в перечне имён, а в том, что признак опознавал механизм по его реализации и
# опирался на факт о мире («во всём дереве нет ни одного замка» — так сказано в шапке рода
# выше), у которого нет сторожа. Факт отменила собственная починка проекта; тот же класс,
# что `case-2026-09-04-measurement-premise-ages-with-the-world`.
# Условие снятия предела: `H_LOCK` станет решать ПОАДРЕСНО — какой именно путь накрыт
# замком, — а не снимать файл целиком; для этого нужен разбор аргумента `with_lock`.
H_LOCK = re.compile(
    r"\bflock\b|\blockf\s*\(|O_EXCL|mkdir[^\n]*\.lock|noclobber"
    r"|\bwith_lock\b|\block_acquire\b|\batomic_filter\b|\bwrite_if_changed\b|\bdrain_file\b")
H_SQ = re.compile(r"'[^'\n]*'")
H_PY_READ = re.compile(r"""(?x)
      ([A-Za-z_]\w*)\s*\.\s*read_(?:text|bytes)\s*\(
    | \bopen\s*\(\s*(?:str\(\s*)?([A-Za-z_]\w*)\s*[,)]
    | json\.load\s*\(\s*open\s*\(\s*([A-Za-z_]\w*)
""")
H_PY_KILL = re.compile(r"""(?x)
      \bopen\s*\(\s*(?:str\(\s*)?([A-Za-z_]\w*)[^\n)]*,\s*["']w
    | ([A-Za-z_]\w*)\s*\.\s*write_(?:text|bytes)\s*\(
    | os\.replace\s*\([^,\n]+,\s*(?:str\(\s*)?([A-Za-z_]\w*)\s*\)
    | shutil\.move\s*\([^,\n]+,\s*([A-Za-z_]\w*)
    | ([A-Za-z_]\w*)\s*\.\s*unlink\s*\(
    | os\.(?:remove|unlink)\s*\(\s*(?:str\(\s*)?([A-Za-z_]\w*)
    | \w+\s*\.\s*replace\s*\(\s*([A-Za-z_]\w*)\s*\)
""")
H_SH_FILTER = re.compile(r"\b(?:cat|jq|grep|egrep|awk|sed|tail|head|sort|uniq|python3|perl)\b")
H_SH_VAR = re.compile(r'"\$\{?([A-Za-z_]\w*)\}?"')
# Одиночная `|` разделителем НЕ считается: в двойных кавычках она данные, а не синтаксис
# (`sed -e "s@активн(ый|ых)@…" "$MD" > "$tmp"` — так терялось настоящее окно count-stats.sh:108).
H_SH_CMDSEP = re.compile(r"&&|\|\||[;&]")
# Команда-условие: `[`, `[[`, `test`, в том числе после `if`/`elif`/`while`/`until`/`!` (D1227).
H_SH_TESTCMD = re.compile(r"\s*(?:(?:if|elif|while|until|!)\s+)*(?:\[\[?|test)\s")
# `< "$F"` — чтение. `<<` (heredoc) чтением файла НЕ является: `cat > "$F" <<EOF` пишет.
# Переменная обязана ЗАКРЫВАТЬ слово: `< "$idx.tmp.$$"` читает временный файл, а не `$idx`,
# и без этого требования fsrs-lib.sh:91 числился окном (замер 4 сентября 2026).
H_SH_INFILE = re.compile(r'(?<!<)<(?!<)\s*"\$\{?([A-Za-z_]\w*)\}?"')
# `mv`/`cp` считаются только в КОМАНДНОЙ позиции: те же три буквы внутри регекспа — текст.
# Цель — ПОСЛЕДНИЙ аргумент (потому `*` жадная), и за ней разрешён хвост перенаправления:
# `mv "$tmp" "$F" 2>/dev/null` — самая частая форма замены в этом дереве, и якорь конца
# команды её терял (замер 4 сентября 2026: 12 пропущенных мест, среди них root-cause-lib.sh).
H_SH_PUT = re.compile(r"""(?x)
      (?:^|[;&|(]|&&|\|\|)\s*(?:mv|cp)\b[^\n;|&]*\s"?\$\{?([A-Za-z_]\w*)\}?"?
        (?=\s*(?:$|;|&|\)|\||[0-9]?[<>]))
    | (?<![>&0-9])>\s*"\$\{?([A-Za-z_]\w*)\}?"
""")
# Переменная обязана быть ДОКАЗАННО путём: строка команды путём не является. `<<<` — не `<`.
H_SH_ISPATH = re.compile(r"""(?x)
      \[\s*-[fserwd]\s+"\$\{?(\w+)
    | (?<!<)<(?!<)\s*"\$\{?(\w+)
    | >>?\s*"\$\{?(\w+)
    | (?:^|[;&|(]|&&|\|\|)\s*(?:touch|rm|mv|cp|mkdir)\b[^\n;]*"\$\{?(\w+)
""")
# `tmp_path`/`tmpdir`/`tmp_path_factory` — фикстуры pytest: личный каталог теста, как `mkdtemp` (D1227,
# `mcp-server/tests/test_discovery.py:323`).
H_PRIVATE = re.compile(r"mktemp|mkdtemp|tempfile\.|TemporaryDirectory|NamedTemporary|TMPDIR|\$\$"
                       r"|\btmp_path(?:_factory)?\b|\btmpdir\b")
H_STAGING = re.compile(r"""\.(?:tmp|new|bak|part)["']?\s*$|["']\.(?:tmp|new)["']""")
H_ASSIGN_SH = re.compile(r"^\s*(?:local\s+|export\s+|declare\s+\S+\s+)?([A-Za-z_]\w*)=(.*)$")
H_ASSIGN_PY = re.compile(r"^\s*([A-Za-z_]\w*)\s*=\s*(.*)$")
# ТРИ ФОРМЫ ПРИСВАИВАНИЯ, КОТОРЫХ РАЗБОР НЕ ЗНАЛ (D306/D308/D310/D370, 9 сентября 2026).
# `_h_kind` сливал два разных предмета в один исход «общий»: «происхождения в файле НЕТ»
# (законно общее — имя пришло из окружения) и «происхождение ЕСТЬ, разбор его не узнал».
# Это род B на самом приборе: неудача разбора выдана вердиктом. Четыре носителя рода H,
# все ложные, держались ровно на этом:
#   · `for f in "$T/hooks/…"` — переменная ЦИКЛА присваивания не имеет
#     (`test_adv5_scan_false_alarm.sh:121`, `test_open_findings.sh:69`; у обоих `$T`/`$S`
#     ведут в `mktemp -d`);
#   · `p, first = sys.argv[1], int(sys.argv[2])` — РАСПАКОВКА кортежа: `H_ASSIGN_PY` требует
#     имя вплотную к `=` (`test_adv_dep_index_data_region_deletion.sh:78`);
#   · `path=$(_itr_state_path "$1")` — значение ВЫЗОВА функции: разбор за неё не заходит
#     (`test_budget_gate.sh:54`; тест экспортирует `ITR_STATE_DIR="$TMP/state"`).
# Первые две формы разбираются, третья честно объявляется НЕИЗВЕСТНОЙ: «не смог проследить»
# ≠ «общий», и носителем неизвестное не числится.
H_FOR_SH = re.compile(r"^\s*for\s+([A-Za-z_]\w*)\s+in\s+(.*?)(?:;|\s+do\b|$)")
H_FOR_PY = re.compile(r"^\s*for\s+([A-Za-z_]\w*)\s+in\s+(.*?):\s*$")
H_UNPACK_PY = re.compile(r"^\s*([A-Za-z_]\w*(?:\s*,\s*[A-Za-z_]\w*)+)\s*=\s*(.*)$")
# Вызов функции проекта: `$(fname …)` целиком в правой части. Таблица имён собирается по
# ВСЕМУ дереву, а не по одному файлу: функция приходит из библиотеки через `source "$VAR"`,
# и следовать за переменной подключения хрупче, чем знать имена (`test_budget_gate.sh:31`
# подключает `intrusiveness-state-lib.sh`, где и лежит `_itr_state_path`).
H_FUNCALL_SH = re.compile(r'^"?\$\(\s*([A-Za-z_][\w-]*)\b')
H_FUNCDEF_SH = re.compile(r"^\s*(?:function\s+)?([A-Za-z_][\w-]*)\s*\(\s*\)\s*\{", re.M)


@functools.lru_cache(maxsize=1)
def _h_project_funcs() -> frozenset:
    """Имена функций оболочки, определённых где угодно в дереве."""
    names: set = set()
    for f in tracked("*.sh"):
        names |= set(H_FUNCDEF_SH.findall(f.read_text(errors="replace")))
    return frozenset(names)


def _h_bare(line: str) -> str:
    """Строка без одинарных кавычек: `mv` внутри регекспа — текст, а не команда."""
    return H_SQ.sub(" ", line)


def _h_func_return(text: str, fname: str) -> str | None:
    """Имя переменной, которую функция ПЕЧАТАЕТ последней строкой вывода."""
    m = re.search(r"^\s*(?:function\s+)?" + re.escape(fname) + r"\s*\(\s*\)\s*\{(.*?)^\}",
                  text, re.S | re.M)
    if not m:
        return None
    outs = re.findall(r"(?:printf[^\n]*|echo)\s+\"?\$\{?([A-Za-z_]\w*)", m.group(1))
    return outs[-1] if outs else None


def _h_split_top(rhs: str) -> list[str]:
    """Правая часть кортежа по запятым ВЕРХНЕГО уровня: `Path(a[1]), Path(a[2]), a[3]`."""
    parts, depth, cur = [], 0, ""
    for ch in rhs:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip()); cur = ""
            continue
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


@functools.lru_cache(maxsize=1)
def _h_sh_texts() -> tuple:
    """Тексты всех .sh дерева — один раз на прогон.

    Обход мест вызова читал дерево заново на каждое имя функции: 12 имён × ~1400 файлов дали
    ~17 тыс. из 21,5 тыс. чтений прогона (замер 18 октября 2026, D1000).
    """
    return tuple((f, f.read_text(errors="replace")) for f in tracked("*.sh"))


@functools.lru_cache(maxsize=256)
def _h_func_call_args(fname: str) -> tuple:
    """Места вызова функции по ВСЕМУ дереву: кортеж (текст файла, список аргументов).

    Дерево, а не файл: библиотека определяет функцию у себя, а зовут её из установщика
    (`lib/claude-md-merge.sh` определяет `sync_claude_md`, `install.sh:139` зовёт).
    Определение функции местом вызова не считается — иначе `sync_claude_md() {` дало бы
    аргументом `{`.
    """
    out = []
    call = re.compile(r"(?:^|[\s;&|(])" + re.escape(fname) + r"\s+([^\n;&|)]+)")
    for _f, txt in _h_sh_texts():
        if fname not in txt:
            continue
        for line in txt.splitlines():
            s = line.strip()
            if s.startswith("#") or H_FUNCDEF_SH.match(line):
                continue
            m = call.search(line)
            if m:
                args = re.findall(r'"[^"]*"|\'[^\']*\'|\S+', m.group(1))
                if args:
                    out.append((txt, tuple(args)))
    return tuple(out)


def _h_func_arg_kind(fname: str, positional: str):
    """Происхождение N-го параметра функции, выведенное из её мест вызова.

    None — мест вызова нет либо номер не разобран: это «не смог», и наверху оно станет
    `unknown`, а не вердиктом. ЛЮБОЙ вызов с общим путём делает параметр общим: библиотека
    не может обещать, что её позовут только с личным.
    """
    m = re.search(r"[0-9]+", positional)
    if not m:
        return None
    n = int(m.group(0))
    if n < 1:
        return None
    calls = _h_func_call_args(fname)
    if not calls:
        return None
    verdicts = []
    for txt, args in calls:
        if n > len(args):
            continue
        # Аргумент судит классификатор ВЫЗЫВАЮЩЕГО файла: имя живёт там, а не здесь.
        caller_kind = _h_sh_kind(txt)
        for ref in re.findall(r"\$\{?([A-Za-z_]\w*)", args[n - 1]):
            verdicts.append(caller_kind(ref))
    if not verdicts:
        return None
    if "shared" in verdicts:
        return "shared"
    if all(v in ("private", "staging") for v in verdicts):
        return "private"
    return None


def _h_kind(text: str, is_py: bool, outer=None):
    """имя → private | staging | unknown | shared. Происхождение имени, не счёт писателей.

    `outer` — классификатор ОБЪЕМЛЮЩЕГО языка: у питона в heredoc правая часть после
    подстановки argv содержит оболочечные имена (`"$R2/install.sh"`), и судить их может
    только оболочечный разбор того же файла.
    """
    src: dict[str, list[str]] = {}
    # Имя ФУНКЦИИ, внутри тела которой стоит присваивание. Нужно, чтобы отличить
    # позиционный параметр функции от argv скрипта: у первого место вызова известно.
    in_func: dict[str, str] = {}
    rx = H_ASSIGN_PY if is_py else H_ASSIGN_SH
    funcs = set() if is_py else (set(H_FUNCDEF_SH.findall(text)) | _h_project_funcs())
    _cur_func, _depth_br = None, 0
    for line in text.splitlines():
        if not is_py:
            _fd = H_FUNCDEF_SH.match(line)
            if _fd and _cur_func is None:
                _cur_func, _depth_br = _fd.group(1), line.count("{") - line.count("}")
            elif _cur_func is not None:
                _depth_br += line.count("{") - line.count("}")
                if _depth_br <= 0:
                    _cur_func = None
        # `a=$(mktemp) && b=$(mktemp)`: присваиваний на строке бывает несколько, и правая
        # часть одного не должна утечь в другое — режем по разделителям команд.
        for piece in ([line] if is_py else re.split(r"&&|\|\||;", line)):
            m = rx.match(piece if is_py else " " + piece.strip())
            if m:
                src.setdefault(m.group(1), []).append(m.group(2))
                if _cur_func:
                    in_func.setdefault(m.group(1), _cur_func)
                continue
            # Переменная цикла: её происхождение — перечень, по которому идут.
            fm = (H_FOR_PY if is_py else H_FOR_SH).match(piece)
            if fm:
                src.setdefault(fm.group(1), []).append(fm.group(2))
                continue
            # Распаковка кортежа: происхождение раздаётся ПОЭЛЕМЕНТНО, когда числа
            # совпадают. Присваивать всю правую часть каждому имени нельзя: у
            # `backlog, archive, mode, masked = …, …, …, mktemp-путь` один личный элемент
            # красил бы личным ВСЕ имена, и настоящий носитель уходил из вида (замер
            # 9 сентября 2026 на дереве 5 сентября: `scripts/backlog-archive.sh`).
            if is_py:
                um = H_UNPACK_PY.match(piece)
                if um:
                    names = [n.strip() for n in um.group(1).split(",")]
                    parts = _h_split_top(um.group(2))
                    for k, name in enumerate(names):
                        src.setdefault(name, []).append(
                            parts[k] if len(parts) == len(names) else um.group(2))
    # Путь, пришедший из argv СКРИПТА, происхождения в файле не имеет: судить его нельзя.
    # ОБЛАСТЬ ПРАВИЛА СУЖЕНА 9 сентября 2026 (противник, атака 1). Обоснование верно для
    # argv скрипта — его подаёт оператор снаружи. Позиционный параметр ФУНКЦИИ — другое
    # дело: место вызова лежит в том же дереве, и его можно прочитать. Пока правило
    # действовало и на функции, прибор пропускал НАСТОЯЩИЙ носитель: `sync_claude_md`
    # (`lib/claude-md-merge.sh:29` — `local target="$1"`, чтения `:48,:51`, запись `:53`
    # `mv "$tmp" "$target"`, замка нет) зовётся из `install.sh:139,142,145,149` с
    # `$GLOBAL_CLAUDE_MD` = `$HOME/.claude/CLAUDE.md` — файлом, который правит и собеседник.
    # Прибор при этом печатал «носителей 0»: показание было верным по букве и ложным по делу.
    argv = re.compile(r"sys\.argv") if is_py else re.compile(r'^"?\$\{?[0-9@*]')

    def kind(v: str, depth: int = 0) -> str:
        pieces = [x.strip() for x in src.get(v, []) if x.strip()]
        rhs = " ".join(pieces)
        if not rhs:
            return "shared"
        if all(argv.search(x) for x in pieces):
            # Позиционный параметр функции: идём к местам её вызова по всему дереву.
            fn = in_func.get(v)
            if not is_py and fn:
                k = _h_func_arg_kind(fn, pieces[0])
                if k is not None:
                    return k
            return "unknown"
        # Значение пришло из функции. Сперва пробуем ДОЙТИ до того, что она печатает:
        # `sandbox() { _s="$TMP/$1"; …; printf '%s' "$_s"; }` — возвращаемое имя есть в той
        # же таблице происхождений, и «неизвестно» тут было бы отказом от разбора, который
        # выполним. Не вышло — объявляем «неизвестно» отдельным исходом, а не «общим».
        if not is_py and all(
            (fc := H_FUNCALL_SH.match(x)) and fc.group(1) in funcs for x in pieces
        ):
            for x in pieces:
                fname = H_FUNCALL_SH.match(x).group(1)
                ret = _h_func_return(text, fname)
                if ret and ret != v and depth < 4:
                    k = kind(ret, depth + 1)
                    if k != "shared":
                        return k
            return "unknown"
        if H_STAGING.search(rhs):
            return "staging"
        if H_PRIVATE.search(rhs):
            return "private"
        if outer is not None:
            for r in re.findall(r"\$\{?([A-Za-z_]\w*)", rhs):
                k = outer(r)
                # «неизвестно» переносится наружу вместе с остальными: не-вердикт,
                # провалившийся в «общее», и есть та слитность двух предметов, ради
                # которой правится этот классификатор.
                if k in ("private", "staging", "unknown"):
                    return k
        refs = set(re.findall(r"\$\{?([A-Za-z_]\w*)", rhs))
        if is_py:
            refs |= set(re.findall(r"\b([A-Za-z_]\w*)\b", rhs))
        pending = [r for r in refs if r != v and r in src]
        if depth < 8:
            for r in pending:
                if kind(r, depth + 1) == "private":
                    return "private"
        elif pending:
            # СПУСК ОБОРВАН ПРЕДЕЛОМ — это «не смог проследить», а не «общий» (противник,
            # атака 4). Прежде предел 4 молча ронял вердикт: шесть звеньев от `mktemp -d`
            # (`A=$(mktemp -d); B="$A/run"; …; G="$C/counters.json"`) объявлялись общим
            # файлом. Тот же слитый исход, ради разделения которого заведён `unknown`.
            # Предел поднят до 8 и стал НАЗЫВАЕМЫМ: глубже — честное «не знаю».
            return "unknown"
        return "shared"
    return kind


# Аргументы вызова питона в heredoc: `python3 - "$BACKLOG" "$ARCHIVE" … <<'PY'`.
# argv[N] у такого питона приходит НЕ извне, а из этой же строки этого же файла.
H_PY_CALL_ARGS = re.compile(r"python3?\s+-\s+(.*?)<<-?\s*['\"]?\w+['\"]?")


def _h_quote_walk(code: str, upto: int, carry: str = ""):
    """Контекст оболочки в позиции `upto`: «sq», «dq» (текст литерала) либо «code»; `carry` — литерал, открытый на прошлой
    строке («sq»/«dq»), — его закрывает первая кавычка этой строки (скептик opus по 2ae73909, M1). Подстановка `$(…)`
    внутри двойных кавычек — снова код (M2: `printf "python3 - <<'PY'"` — текст, `X="$(python3 - <<'PY'` — код)."""
    stack = [carry] if carry else ["code"]
    i = 0
    while i < upto and i < len(code):
        c, top = code[i], stack[-1]
        if top == "sq":
            if c == "'":
                stack.pop()
                if not stack:
                    stack = ["code"]
        elif top == "dq":
            if c == "\\":
                i += 2
                continue
            if c == '"':
                stack.pop()
                if not stack:
                    stack = ["code"]
            elif code.startswith("$(", i):
                stack.append("sub")
                i += 2
                continue
        else:
            if c == "\\":
                i += 2
                continue
            if c == "'":
                stack.append("sq")
            elif c == '"':
                stack.append("dq")
            elif code.startswith("$(", i):
                stack.append("sub")
                i += 2
                continue
            elif c == ")" and top == "sub":
                stack.pop()
            elif c == "#" and top == "code" and (i == 0 or code[i - 1].isspace()):
                break      # комментарий: дальше текст, кавычки в нём не считаются («payload'а»)
        i += 1
    return stack[-1] if stack[-1] in ("sq", "dq") else "code"


def _h_in_squote(code: str, pos: int, carry: str = "") -> bool:
    """Стоит ли позиция в ТЕКСТЕ литерала (одинарные кавычки; двойные — вне `$(…)`)."""
    return _h_quote_walk(code, pos, carry) != "code"


def _h_line_carry(line: str, carry: str = "") -> str:
    """Литерал, оставшийся открытым к концу строки («sq»/«dq»), либо «»; строка-комментарий вне литерала его не меняет."""
    if not carry and line.lstrip().startswith("#"):
        return ""
    st = _h_quote_walk(line, len(line), carry)
    return st if st in ("sq", "dq") else ""


def _h_heredoc_open(line: str, carry: str = ""):
    """Маркер heredoc, ОТКРЫВАЕМОГО этой строкой, либо None.

    Признак снимается с КОДА, а не с сырого текста (противник, 9 сентября 2026):
    · `# повод: кейс записан `cat > … <<EOF`` — упоминание в комментарии ставило маркер,
      который никогда не закрывается, и ВЕСЬ хвост файла обнулялся. В дереве 42 такие
      строки, в 31 файле хвост терялся целиком (`detection-signals-lib.sh:256` — 311 строк
      ниже слепы, `knowledge-frontmatter-check.sh:32` — 237, `undefined-function-check.sh:22` — 224);
    · `MASK=$(( 1 << 3 ))` — арифметический сдвиг принимался за открытие с маркером «3».
    Оба гасились молча: слепота хвоста неотличима от «носителей там нет».
    """
    code = line.split("#", 1)[0] if line.lstrip().startswith("#") and not carry else line
    if "<<<" in code:
        return None
    # `<<` внутри ОДИНАРНЫХ кавычек — текст, а не открытие: `printf 'python3 - "$D/x" <<PYY\n'` печатает чужую
    # программу, и её строки — данные этого файла (D1227, `hooks/tests/test_mutant_gate_probe.sh:54`). Двойные кавычки
    # не в счёт: `X="$(python3 - <<'PY'` открывает настоящий heredoc внутри подстановки.
    m = next((x for x in re.finditer(r"<<-?\s*(['\"]?)(\w+)\1(?!<)", code) if not _h_in_squote(code, x.start(), carry)), None)
    if not m:
        return None
    mark = m.group(2)
    # Маркер из одних цифр heredoc не открывает: это операнд сдвига. Настоящих маркеров
    # такого вида в дереве нет (проверено: все из букв, `PY`/`EOF`/`SQL`-подобные).
    if mark.isdigit():
        return None
    return mark


def _h_py_lines(text: str, is_py: bool) -> list[tuple[int, str]]:
    """Строки питона: весь файл (.py) либо heredoc `python3 - <<'PY'` внутри .sh.

    `sys.argv[N]` подставляется аргументами СВОЕГО места вызова: для питона в heredoc это
    единственный способ узнать, ЧТО ему подали. Без подстановки
    `backlog, archive, mode = pathlib.Path(sys.argv[1]), …` судится как «пришло извне,
    судить нельзя», и настоящий носитель (`scripts/backlog-archive.sh`) выпадает из вида.

    Аргументы собираются У КАЖДОЙ вставки отдельно. Первая редакция (9 сентября 2026)
    брала их у ПЕРВОЙ и подставляла во ВСЕ: второй heredoc судился по аргументам первого,
    и общий файл объявлялся личным. Область значения была шире его предмета — тот же род L,
    против которого правился прибор. Двадцать файлов дерева несут 2+ вставки, у пятнадцати
    хотя бы одна с аргументами (`scripts/backlog-recheck.sh:101` и `:165` — ближайшая пара).
    """
    lines = text.splitlines()
    if is_py:
        return list(enumerate(lines))
    out: list[tuple[int, str]] = []
    mark = skip = None
    carry = ""
    argv: list = []
    for i, l in enumerate(lines):
        # ТЕЛО ЧУЖОГО heredoc — ДАННЫЕ, а не код этого файла. Оболочечная ветвь это
        # различает с самого начала (`_h_sh_code`), питоновская — не различала, и питон,
        # напечатанный внутри `cat > файл <<'EOF'`, считался кодом. Поймано на себе: мой же
        # `test_defect_registry_origin_forms.sh` стал носителем рода H на своих заготовках.
        if skip is not None:
            if l.strip() == skip:
                skip = None
            continue
        if mark is not None:
            if l.strip() == mark:
                mark = None
                argv = []
            else:
                out.append((i, _h_argv_sub(l, argv)))
            continue
        opened = _h_heredoc_open(l, carry)
        carry = _h_line_carry(l, carry)
        if opened is None:
            continue
        if re.search(r"python3?[^\n]*<<", l):
            mark = opened
            argv = ["-"]
            am = H_PY_CALL_ARGS.search(l)
            if am:
                argv.extend(re.findall(r'"[^"]*"|\'[^\']*\'|\S+', am.group(1)))
        else:
            skip = opened
    return out


def _h_argv_sub(line: str, argv: list) -> str:
    """`sys.argv[N]` → N-й аргумент СВОЕЙ вставки; чего нет — оставляем как было."""
    if not argv:
        return line

    def rep(m):
        i = int(m.group(1))
        return '"' + argv[i].strip('"\'') + '"' if i < len(argv) else m.group(0)
    return re.sub(r"sys\.argv\[(\d+)\]", rep, line)


def _h_sh_reads(win: str) -> dict[str, int]:
    """var → смещение ПЕРВОГО чтения в окне.

    Чтение — это РОЛЬ переменной (ввод фильтра либо `< "$V"`), а не присутствие слова
    фильтра на строке: `cat > "$F" <<EOF` фильтр называет, а файла не читает — он его
    создаёт. Признак, снятый с формы, числил такое окном (замер 4 сентября 2026: 10
    адресов из 45 без единого чтения). Фильтр ищется только в СВОЁМ сегменте команды,
    иначе `cat "$A" ; mv "$t" "$B"` сделал бы чтением и `$B`.
    """
    out: dict[str, int] = {}
    for m in H_SH_VAR.finditer(win):
        pre = win[:m.start()]
        cut = max((c.end() for c in H_SH_CMDSEP.finditer(pre)), default=0)
        # Чтение в УСЛОВИИ (`[ "$(cat "$F")" = "$RUN" ] && exit 0`) — сравнение, а не данные записи: прочитанное в файл не
        # возвращается, и потерянной записи у такой пары «чтение → перезапись» не бывает (D1227, отметка СВОЕЙ сессии
        # `playwright-cli-guard.sh:142`). Чтение в теле той же команды за пределами условия по-прежнему чтение.
        if H_SH_TESTCMD.match(pre[cut:]):
            continue
        fm = [x for x in H_SH_FILTER.finditer(pre) if x.start() >= cut]
        if not fm or ">" in pre[fm[-1].end():]:
            continue
        out.setdefault(m.group(1), m.start())
    for m in H_SH_INFILE.finditer(win):
        v = m.group(1)
        if m.start() < out.get(v, len(win)):
            out[v] = m.start()
    return out


@functools.lru_cache(maxsize=None)
def _h_sh_kind(text: str):
    """Оболочечный классификатор файла — один на прогон.

    Его просят роды F и H и обход мест вызова функции, по три-четыре раза на файл; таблицы
    происхождений после построения только читаются, поэтому общий экземпляр равносилен
    свежему. Без него `_h_kind` строился 4260 раз на ~1400 файлов (замер 18 октября 2026, D1000).
    """
    return _h_kind(_h_sh_code(text), False)


@functools.lru_cache(maxsize=None)
def _h_sh_code(text: str) -> str:
    """Текст .sh без тел heredoc: там СТРОКА, а не код этого файла.

    `} > "$F.new" && mv "$F.new" "$F"` внутри `<<'GEN'` — программа, которую файл только
    ПЕЧАТАЕТ; окна в нём нет, потому что нет и исполнения. Это третья форма кавычек после
    одинарных (`_h_bare`): тот же корень — роль текста, а не его вид. Питон в heredoc
    разбирает питоновская ветвь (`_h_py_lines`), и здесь он тоже гасится.
    """
    out, mark, carry = [], None, ""
    for l in text.splitlines():
        if mark is not None:
            out.append("")
            if l.strip() == mark:
                mark = None
            continue
        out.append(l)
        # Признак открытия — общий с питоновской ветвью (`_h_heredoc_open`): он снят с
        # КОДА, а не с сырой строки. Своя копия регулярки стояла здесь до 9 сентября 2026 и
        # расходилась с соседней (род K), а заодно принимала за открытие упоминание `<<EOF`
        # в комментарии и операнд сдвига `$(( 1 << 3 ))`.
        mk = _h_heredoc_open(l, carry)
        carry = _h_line_carry(l, carry)
        if mk:
            mark = mk
    return "\n".join(out)


def _h_logical(lines: list[str]) -> list[tuple[int, str]]:
    """Склейка продолжений: `jq … \\` и `"$F" > "$t" && mv …` — одна команда, не две."""
    out: list[tuple[int, str]] = []
    buf, start = "", 0
    for i, l in enumerate(lines):
        if not buf:
            start = i
        if l.rstrip().endswith("\\"):
            buf += l.rstrip()[:-1] + " "
            continue
        out.append((start, buf + l))
        buf = ""
    if buf:
        out.append((start, buf))
    return out


def carriers_h() -> list[tuple[Path, list[tuple[str, int]]]]:
    out = []
    for f in tracked("*.sh", "*.py"):
        t = f.read_text(errors="replace")
        if H_LOCK.search(t):
            continue
        found: list[tuple[str, int]] = []
        pyl = _h_py_lines(t, f.suffix == ".py")
        pykind = _h_kind(t if f.suffix == ".py" else "\n".join(l for _, l in pyl), True,
                         outer=None if f.suffix == ".py" else _h_sh_kind(t))
        reads: dict[str, int] = {}
        reads_all: dict[str, list[int]] = {}
        kills: dict[str, int] = {}
        for i, l in pyl:
            if l.lstrip().startswith("#"):
                continue
            for m in H_PY_KILL.finditer(l):
                for g in m.groups():
                    if g:
                        kills[g] = i            # ПОСЛЕДНЕЕ разрушение
            for m in H_PY_READ.finditer(l):
                for g in m.groups():
                    if g:
                        reads.setdefault(g, i)  # ПЕРВОЕ чтение
                        reads_all.setdefault(g, []).append(i)
        for v, ri in reads.items():
            if v in kills and kills[v] > ri and pykind(v) == "shared":
                # Адрес — чтение, ОТ КОТОРОГО идёт разрушение, то есть ближайшее к нему
                # сверху. Первое чтение по файлу им быть не обязано: в brain.py оно на 103
                # (выгрузка), а окно — на 235-243 (загрузка), и адрес указывал мимо окна.
                found.append((v, max(x for x in reads_all[v] if x < kills[v]) + 1))
        if f.suffix != ".py":
            code = _h_sh_code(t)
            kind = _h_sh_kind(t)
            log = [(i, _h_bare(l)) for i, l in _h_logical(code.splitlines())]
            paths = {g for _, l in log for m in H_SH_ISPATH.finditer(l)
                     for g in m.groups() if g}
            for n, (i, l) in enumerate(log):
                if l.lstrip().startswith("#"):
                    continue
                # Окно склеивается ВМЕСТЕ со смещениями строк: без них порядок «чтение
                # раньше разрушения» непроверяем, а он — половина правила рода.
                win, offs = "", []
                for ln, txt in log[n:n + 4]:
                    offs.append((len(win), ln))
                    win += txt + " ; "
                reads = _h_sh_reads(win)
                if not reads:
                    continue
                for m in H_SH_PUT.finditer(win):
                    v = next(g for g in m.groups() if g)
                    if v not in reads or reads[v] >= m.start():
                        continue
                    if v in paths and kind(v) == "shared":
                        # Адрес — строка ЧТЕНИЯ, то есть начало окна, а не начало склейки:
                        # иначе соседние окна дали бы разные адреса одному и тому же окну.
                        found.append((v, max(l0 for o, l0 in offs if o <= reads[v]) + 1))
        if found:
            out.append((f, sorted(set(found))))
    return out


