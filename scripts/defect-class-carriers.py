#   · test_docs_family_check.sh: перечисляет DEFAULT_FAMILY из пяти документов состояния
#     (docs-family-check.sh:65) — это ОБЪЯВЛЕННОЕ решение, расширяемое через
#     DOCS_FAMILY_LIST, а не множество, выводимое из дерева. Предмет стража и есть перечень.
# Условие пересмотра: установщик начнёт класть в новый подкаталог hooks/ — тогда зеркало
# обязано покраснеть первым; если не покраснеет, цена появилась и у него.

# Глоб-ИСТОЧНИК копирования в СВЕЖЕСОЗДАННЫЙ каталог универсума не объявляет (D370).
# `cp "$REPO"/hooks/*.sh "$TMP/hooks/"` — тест копирует дерево в свою песочницу, и универсум
# там как раз ВЫВЕДЕН оболочкой: что нашлось, то и приехало, за спиной ничего не осталось.
# Одного «это аргумент cp» НЕ хватает: `install.sh` копирует тем же глобом в живую систему,
# и там непопавшее остаётся стоять — это настоящий носитель. Разделитель — ЦЕЛЬ копии:
# каталог, происхождение которого личное (mktemp и производные), начинается пустым.
# `uninstall.sh` под правило не подпадает по построению: у него глоб стоит в `for … in`,
# он решает, ЧТО СНИМАТЬ, и невидимое остаётся в системе.
F_COPY = re.compile(r"\b(?:cp|rsync|install)\b")
F_LAST_ARG = re.compile(r'(?:"([^"]*)"|\'([^\']*)\'|(\S+))\s*(?:2>[^\s]*\s*)*$')


def _f_copy_into_private(line: str, kind) -> bool:
    """Строка копирует глоб в каталог, созданный этим же прогоном."""
    if not F_COPY.search(line):
        return False
    # Хвостовое перенаправление отрезается ДО поиска цели (противник, атака 5).
    # `cp "$REPO"/hooks/*.sh "$HOME/.claude/hooks/" >> "$LOGDIR/install.log"` — цель копии
    # живая система, а последним токеном стоит личный журнал, и признак снимал с учёта всю
    # строку. Позиция вместо роли: `F_LAST_ARG` привязана к КОНЦУ СТРОКИ, а нужен последний
    # аргумент КОМАНДЫ.
    _cmd = re.split(r'(?<!\\)(?:[12]?>>?|<)(?![<>])', line, maxsplit=1)[0]
    m = F_LAST_ARG.search(_cmd.rstrip().rstrip(";&"))
    if not m:
        return False
    dest = next((g for g in m.groups() if g), "")
    for v in re.findall(r"\$\{?([A-Za-z_]\w*)", dest):
        if kind(v) in ("private", "staging"):
            return True
    return False


def carriers_f() -> list[tuple[Path, list[tuple[str, int, int]]]]:
    all_paths = [str(p.relative_to(ROOT)) for p in tracked()]
    by_dir: dict[tuple[str, str], list[str]] = {}
    for p in all_paths:
        d, _, n = p.rpartition("/")
        by_dir.setdefault((d, n.rpartition(".")[2]), []).append(p)
    known = set(all_paths)

    out = []
    for f in tracked("*.sh", "*.py"):
        t = f.read_text(errors="replace")
        rep: dict[tuple[str, str], set[str]] = {}
        lits: dict[tuple[str, str], set[str]] = {}
        fkind = _h_sh_kind(t) if f.suffix != ".py" else (lambda v: "shared")
        fwd = set(F_FORWARD_FN.findall(t)) if f.suffix != ".py" else set()
        fwd_re = (re.compile(r"(?:^|[;{&|(]\s*)(?:" + "|".join(map(re.escape, sorted(fwd))) + r")\s")
                  if fwd else None)
        for line in _f_code(t, f.suffix == ".py"):
            if _f_copy_into_private(line, fkind):
                continue
            # ФОРМА 1 — мелкий шаблон: `каталог/*.ext` не спускается, и подкаталог невидим.
            if not F_DERIVED.search(line) and not (fwd_re and fwd_re.search(line)):
                for m in F_GLOB.finditer(line):
                    if _f_in_message(line, m.start()):
                        continue
                    d = m.group(1).strip('"').lstrip("./")
                    ext = m.group(2)
                    if not by_dir.get((d, ext)):
                        continue
                    deep = [p for (dd, ee), v in by_dir.items() if ee == ext
                            and dd.startswith(d + "/") for p in v]
                    # Названный в тексте подкаталог механизм ВИДИТ — исключил ли, обошёл ли
                    # отдельно. Слепота — это неназванность, а не отсутствие в шаблоне.
                    # Поиск — по подкаталогу, а не по пути: путей под шаблоном тысячи, разных
                    # подкаталогов единицы (11 407 поисков по тексту → десятки, D1000).
                    named = {s: bool(re.search(r"\b" + re.escape(s) + r"\b", t))
                             for s in {p[len(d) + 1:].split("/")[0] for p in deep}}
                    blind = [p for p in deep if not named[p[len(d) + 1:].split("/")[0]]]
                    if blind:
                        rep.setdefault((d, ext), set()).update(blind)
            # ФОРМА 2 — литеральный список путей.
            for m in F_LIT.finditer(line):
                p = m.group(1)
                if p in known:
                    d, _, n = p.rpartition("/")
                    lits.setdefault((d, n.rpartition(".")[2]), set()).add(p)
        items = [(f"{d}/*.{ext}", len(by_dir[(d, ext)]), len(v))
                 for (d, ext), v in rep.items()]
        if not F_DERIVED.search(t):
            for (d, ext), got in lits.items():
                uni = by_dir.get((d, ext), [])
                # Три и больше — это уже множество, а не пара названных предметов; два пути
                # рядом встречаются у любого теста, называющего свой предмет и его соседа.
                if len(got) >= 3 and len(uni) > len(got):
                    items.append((f"перечень {d}/*.{ext}", len(got), len(uni) - len(got)))
        if items:
            out.append((f, sorted(items, key=lambda x: -x[2])))
    return out


# --- РОД G: объявление без исполнителя (форма «поле записи, которого никто не читает») ---
#
# Повод (3-4 сентября 2026: D286, D291, D293, D296, D299). Родительское знание —
# `pattern-declaration-family-without-a-registry`: документ, схема или правило объявляют
# механизм, а исполнителя у объявления нет — числа никто не сверяет, правило никто не
# проверяет, второе значение поля никто не пишет. Снаружи это неотличимо от работающего:
# поле стоит в каждой записи, порог назван в двух документах, правило записано в контракте.
#
# Правило рода: ОБЪЯВЛЕНО имя, которое обещает различение или свидетельство, и в дереве нет
# ни одного места, где по нему различают или его проверяют.
#
# Признак заведён на ОДНУ форму рода — поле машинной записи. Поле пишется в
# ПЕРСИСТЕНТНУЮ запись (перенаправление в файл либо компактный `jq -c`, то есть запись,
# предназначенную машине, а не глазу) и НЕ ЧИТАЕТСЯ ни одним механизмом дерева: ни
# структурно (`.поле`, `["поле"]`, `.get("поле")`), ни текстом (`grep '"поле":"…"'`), ни
# именем-аргументом (`analyze(rows, "поле")`), ни разметкой панели (`data.поле`).
#
# КОНТРПРИМЕР (признак обязан НЕ поймать) — `hash` в `hooks/bulk-copy-guard.sh:172`. Он
# пишется ТОЙ ЖЕ строкой `printf`, что и пойманные `signature` и `dest`, и в ту же
# `bulk-copy-fired-*.jsonl`; читается он четырьмя строками выше, на :168, текстом:
# `grep -Fq "\"hash\":\"$THROTTLE_KEY\""`. Контрпример выбран так нарочно: он отличается от
# носителей НЕ жанром, не файлом и не строкой, а ровно наличием читателя. Признак, который
# делит по жанру, снял бы всю строку целиком либо оставил бы всю. Прогон делит её: `hash`
# вне списка, `signature` и `dest` в списке.
# Второй контрпример — `outcome` в журналах вмешательства: читается
# `hooks/metrics-collector.sh:587,615` (`grep -h '"outcome":"outdated_knowledge"'`), в
# списке отсутствует. Третий — `queued`/`pairs_done` из `scripts/ablation/phase.sh:38`:
# пишутся `jq -s` в человекочитаемый отчёт на stdout, и читателя у них нет по замыслу —
# читатель тут глаз. Их снимает требование МАШИННОЙ записи, а не отдельная оговорка.
#
# ТОЧНОСТЬ, измеренная осмотром ВСЕХ совпадений 4 сентября 2026: 12 полей в 8 файлах
# (13 пар «поле-писатель»: `stage` пишут двое), настоящих 12 из 12, ложных 0.
# Метод осмотра: у каждого поля прочитано место записи и проверено командой
# `git grep -nE '"поле"|.поле\b' -- scripts hooks mcp-server | grep -v /tests/` за вычетом
# файла-писателя — у всех двенадцати ноль совпадений, то есть имя поля не встречается в
# дереве нигде, кроме места, где его пишут. Слабейшие из двенадцати названы: `signature` и
# `dest` в дросселе bulk-copy — крошка для человека, читающего файл состояния глазами;
