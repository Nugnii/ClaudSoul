# РОД A — структурный формат читается построчным шаблоном, а не разбором формата
#
# Правило: файл ИЗВЛЕКАЕТ ПОЛЕ из структурного формата (YAML-шапка, JSON, JSONL) текстовым
# шаблоном, привязанным к началу строки (`^ключ:`), и НЕ отдаёт этот же текст разбору.
# Форма поля тогда становится вопросом, и каждая новая форма — новая находка.
#
# КОНТРПРИМЕР (признак обязан НЕ поймать): файл, который извлекает область текстом, а
# значения берёт разбором (`jq`, `json.loads`, `yaml.safe_load`) — там форма не решает.
# Пример в дереве: hooks/detection-signals-lib.sh — 35 вызовов разбора при одном текстовом
# извлечении; носителем не является.
#
# ТОЧНОСТЬ, измеренная осмотром ВСЕХ совпадений 29 августа 2026: 8 из 8 читают поле
# структурного документа построчно — ложных нет. Но последствие разное, и вывод делит
# носителей на механизмы и тесты: у механизма это тихое неверное значение, у теста —
# хрупкое утверждение, падающее громко.
A_FIELD = re.compile(r"""(?x)
      awk\s[^\n]*\^(?:[a-z_]+):            # awk '/^ключ:/ ...'
    | sed\s+-n\s+[^\n]*\^(?:[a-z_]+):      # sed -n 's/^ключ: ...'
    | grep\s+-[a-zA-Z]*E?[^\n]*'\^[a-z_]+:  # grep -E '^ключ:'
    | re\.(?:search|match|findall)\(\s*rf?["'][^"']*\^\{?[a-z_]+\}?:   # питон по ^ключ:
    | /\^[a-z_]+:/\s*\{                    # правило awk/sed отдельной строкой: /^ключ:/ { ... }
""")
# Пятая альтернатива добавлена 4 сентября 2026, и добавлена ПО ПРОМАХУ. Прежние четыре
# требовали имя команды и `^ключ:` в ОДНОЙ строке — многострочная программа awk под них не
# подпадала. Из-за этого признак не увидел единственный настоящий дефект своего рода:
# `co-cognition-lib.sh:58` (`/^origin:/ { org = $2 }`) занижал co_cognition_ratio на 8
# записей из 441. Точность 8/8, измеренная 29 августа, была измерена только на том, что
# признак ловит, — она ничего не говорила о том, что он пропускает.
A_PARSE = re.compile(r"yaml\.safe_load|json\.loads|\bjq\b|json\.load\(")
# КОНТРПРИМЕР к пятой альтернативе: читатель, СНИМАЮЩИЙ форму со всей записи до разбора
# полей (`gsub(/"/, "")` без третьего аргумента работает по $0), формой не связан и
# носителем не является. Без этой оговорки признак считал бы носителем файл, ПОЧИНЕННЫЙ
# в тот же час, — та же ошибка, что уже описана у рода B: очередь не убывала бы от работы.
A_NORMALIZED = re.compile(r'gsub\(/"/,\s*""\)')
# ЦЕНА РОДА ИЗМЕРЕНА ПОИМЁННО (7 сентября 2026). Все восемь механизмов-носителей прогнаны
# против честного разбора их СОБСТВЕННЫХ источников на реальных данных: 26 расхождений, и
# все они у ДВУХ носителей.
#   · knowledge-audit-digest.sh — 21: читатель прошлого итога стоял на якоре `^**Total:**`,
#     писатель печатал `- **Total:** N`; в 21 дайджесте с W17 по W37 строк `Trend:` ноль.
#     Починено сведением формата к одному объявлению.
#   · regen-readme-skills.sh — 2: кавычки снимались только с краёв, и `\"update X\"`
#     попадало в опубликованную витрину. Починено разворотом у double-quoted скаляра.
#   · Остальные шесть — цена НОЛЬ на сегодняшних данных, у каждого назван предел:
#     у escalation-age.sh она держится на плоских шапках (первая вложенная её сломает),
#     у knowledge-independence.py настоящая цена была и уже оплачена 6 сентября 2026
#     (построчный `^\s+-\s+date:` давал 143 записи повода при 125 настоящих).
# ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ ОЧЕРЕДИ: список рода A — очередь на ПРОВЕРКУ, а не на
# переписывание. У трёх четвертей носителей построчное чтение на нынешних данных
# бесплатно, и переписывать их без цены значило бы менять работающий код ради формы —
# ровно та ошибка, которую этот реестр и должен предотвращать.
#
# Носитель читает поле ИЗ СТРУКТУРНОГО ДОКУМЕНТА. Правило, а не перечень имён полей:
# перечень имён был бы тем самым дефектом, который здесь и ищется. Документ опознаётся по
# обращению к шапке `.md`, к `.json`/`.jsonl` либо к каталогу знаний.
#
# КОНТРПРИМЕР: тест, который грепает `^ключ:` в собственной строке-фикстуре, документа не
# читает и носителем не является.
# Адрес из этой строки УБРАН 5 сентября 2026: `hooks/tests/test_knowledge_fields.sh` был
# назван здесь как «фикстурный», а на :35 и :38 он грепает `"$REPO/$f"` и
# `templates/knowledge.md.tmpl` — то есть настоящие документы. Признак его ловит ПРАВИЛЬНО,
# и он носитель тестового вида (см. деление «механизмы и тесты» выше). Контрпример
# устарел вместе с миром: файл сменил устройство, а текст рядом с регекспом — нет.
# Отсюда правило ведения: у контрпримера адрес живой, и держится он машинно
# (`hooks/tests/test_defect_registry_counterexamples.sh`), а не глазом автора.
A_DOC = re.compile(r"\.jsonl?\b|global-lessons|LESSONS_DIR|knowledge/|frontmatter|шапк")


def carriers_a() -> list[tuple[Path, int, int]]:
    out = []
    for f in tracked("*.sh", "*.py"):
        t = f.read_text(errors="replace")
        # ПРИЗНАК ДЕФЕКТА судится по строкам, которые ИСПОЛНЯЮТСЯ (`_f_code`, тот же
        # отбор, что у рода F): построчный шаблон в комментарии — рассказ о чужом коде,
        # а не чтение поля. Замер 6 сентября 2026: носителей 19, из них 2 держались
        # ровно на комментарии, и прибор при этом печатал собственную точность.
        # ДОКУМЕНТАЛЬНАЯ ПРИМЕТА (A_DOC) остаётся по ПОЛНОМУ тексту: у неё другая роль —
        # она говорит, О ЧЁМ файл, а тема законно живёт в прозе. Слепое сужение обоих
        # теряет живого носителя scripts/regen-readme-skills.sh (awk по `^name:` в коде,
        # слово «frontmatter» только в шапке) — ложное отрицание вместо ложного
        # срабатывания. Контрсвидетельства (разбор, снятая форма) считаются по коду:
        # упоминание `json.loads` в комментарии оправданием быть не может.
        code = "\n".join(_f_code(t, f.suffix == ".py"))
        hits = len(A_FIELD.findall(code))
        if not hits or not A_DOC.search(t):
            continue
        parses = len(A_PARSE.findall(code))
        # Контрпример в действии: разбора существенно больше, чем текстовых извлечений —
        # текст служит поиском области, а не чтением значения.
        if parses > hits:
            continue
        # Контрпример в действии: форма снята со всей записи до разбора полей.
        if A_NORMALIZED.search(code):
            continue
        out.append((f, hits, parses))
    return out


