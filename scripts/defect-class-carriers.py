    # `root-map.py --count` (корни) и по той же причине: число стояло прозой и разошлось.
    # Считает ПЕРЕЧЕНЬ, а не носителей: род без носителей существует, и «не заведён» тоже.
    if "--count" in sys.argv:
        print(len(GENERA))
        return 0
    # Путь носителя с суррогатом (имя не в UTF-8, D1170 M3) печатается экранированным, а не роняет вывод.
    try:
        sys.stdout.reconfigure(errors="backslashreplace")
    except (AttributeError, ValueError):
        pass
    only = None
    for _i, _arg in enumerate(sys.argv):
        if _arg == "--genus" and _i + 1 < len(sys.argv):
            only = sys.argv[_i + 1].upper()
    if only and only not in GENERA:
        print(f"неизвестный род: {only} (есть {', '.join(GENERA)})")
        return 2
    # Отказ git проверяется ДО кэша (D1168): ключ кэша собирается по перечню, и при пустом перечне он совпадал бы с
    # прошлым прогоном без git — «0 носителей» отдавался бы из кэша. Первая строка вывода — её читают показания.
    tracked()
    if _GIT_FAILED:
        print(f"НЕ ИЗМЕРЕНО: перечень файлов корня не получен ({_GIT_FAILED[0]}) — носители не считались")
        return 2
    _out = sys.stdout
    # Кэш проверяется ДО счёта: вход тот же — считать нечего.
    _key = _input_key()
    # `_input_key()` зовёт `tracked()` второй раз — его отказ проверяется до чтения кэша (второй круг D1168, M2).
    if _GIT_FAILED:
        print(f"НЕ ИЗМЕРЕНО: перечень файлов корня не получен ({_GIT_FAILED[0]}) — носители не считались")
        return 2
    _hit = _cache_read(_key)
    if _hit is not None and not os.environ.get("DCC_NO_CACHE"):
        return _emit(_hit["text"], _hit["counts"], only, _out)
    # Буфер собирается ВСЕГДА, а не только под `--genus`: текст нужен целиком, чтобы лечь в
    # кэш, из которого потом вырежут любой род.
    _buf = io.StringIO()
    sys.stdout = _buf

    print("НОСИТЕЛИ РОДОВ ДЕФЕКТА (D109)\n")

    a = carriers_a()
    # Делим по ПОСЛЕДСТВИЮ: у механизма построчное чтение даёт тихое неверное значение,
    # у теста — хрупкое утверждение, которое падает громко. Одно число на оба ввело бы в
    # заблуждение, хотя признак верен для обоих.
    a_mech = [x for x in a if not is_fixture(x[0])]
    a_test = [x for x in a if is_fixture(x[0])]
    # ОЧЕРЕДЬ РОДА — механизмы, и это следствие деления по последствию, а не удобство.
    # Шапка рода говорит про тесты «не дефект», и пока они входили в счёт, «у рода ноль
    # носителей» было недостижимо ПО ПОСТРОЕНИЮ: доктрина сама зовёт эти носители чистыми.
    # Замер 6 сентября 2026, сплошная сверка 18 адресов чтением: ложных 0, тестов 10,
    # механизмов 8, из них действующий дефект 1 (knowledge-independence.py — 143 записи
    # повода при 125 настоящих). Тесты остаются в выводе поимённо: они не исчезают из
