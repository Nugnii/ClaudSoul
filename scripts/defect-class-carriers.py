def _input_key() -> str:
    h = hashlib.md5()
    try:
        me = Path(__file__).resolve()
        st = me.stat()
        h.update(f"self:{st.st_mtime_ns}".encode())
    except OSError as e:
        # Отказ говорит, а не молчит (род B — «чтение не различает прочитал и не смог»).
        # Пустой ключ выключает кэш целиком, и без этой строки выключение было бы
        # неотличимо от «кэша ещё нет»: прибор поймал этот код носителем в день, когда он
        # был написан. В stdout не пишем — его читают `head -1` и `sed` показаний.
        print(f"defect-class-carriers: ключ кэша не собран ({e}) — считаю без кэша",
              file=sys.stderr)
        return ""
    _skipped = 0
    for f in tracked():
        try:
            st = f.stat()
        except OSError:
            # Пропуск отдельного файла кэш не отменяет, но и молчать о нём нельзя: ключ,
            # собранный по неполному множеству, совпадёт там, где вход на деле изменился.
            _skipped += 1
            continue
        # Размер в ключ НЕ входит, и это выведено замером, а не вкусом. Механизмы границы
        # хода правят файлы, СОХРАНЯЯ mtime намеренно (контракт `backlog-refresh-readings.sh`:
        # «MTIME СОХРАНЯЕТСЯ… сверщик исхода хода судит по mtime»). Замер 8 сентября 2026: за
        # один прогон `session-collector` меняется ровно один отслеживаемый файл — BACKLOG.md,
        # size 170117→170112 при том же mtime. С размером в ключе кэш промахивался на КАЖДОЙ
        # границе хода, то есть не работал вовсе. При этом на вывод реестра BACKLOG.md не
        # влияет — проверено вставкой строки: хеш вывода тот же.
        # ПРЕДЕЛ: правка, сохранившая mtime и изменившая содержимое, кэшем не замечается.
        # Условие снятия: появится механизм, который так же сохраняет mtime, но правит файл,
        # ВЛИЯЮЩИЙ на роды, — тогда ключ обязан стать хешем содержимого, и его цену надо
        # мерить заново (сейчас ключ стоит 0,03 с против 7 с прогона).
        # Путь — байтами файловой системы (скептик D1170, M3): имя не в UTF-8 несёт суррогат, и `.encode()` его ронял.
        h.update(os.fsencode(str(f)) + f":{st.st_mtime_ns}".encode())
    if _skipped:
        print(f"defect-class-carriers: при сборке ключа пропущено файлов: {_skipped}"
              " — кэш может не заметить их правку", file=sys.stderr)
        h.update(f"skipped:{_skipped}".encode())
    return h.hexdigest()


def _cache_read(key: str):
    if not key:
        return None
    try:
        data = json.loads(_cache_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(data, dict) or data.get("key") != key:
        return None
    if not isinstance(data.get("text"), str) or not isinstance(data.get("counts"), dict):
        return None
    return data


def _cache_write(key: str, text: str, counts: dict) -> None:
    if not key:
        return
    try:
        _cache_path().write_text(
            json.dumps({"key": key, "text": text, "counts": counts}, ensure_ascii=False),
            encoding="utf-8")
    except (OSError, UnicodeError):
        # Текст с суррогатом (путь не в UTF-8, D1170 M3) в UTF-8 не пишется — счёт верен, кэш просто не ложится.
        pass


def _emit(text: str, counts: dict, only, out) -> int:
    """Печать и код возврата из готового текста — общий путь для счёта и для кэша."""
    if only:
        for chunk in text.split("\nРОД "):
            if chunk.startswith(only + " "):
                print("РОД " + chunk.rstrip().split("\n\nПрожарено")[0], file=out)
                break
        if only in GENERA_NOT_ENTERED:
            return 2
        return 1 if counts.get(only, 0) else 0
    print(text, end="", file=out)
    return 1 if any(counts.get(x, 0) for x in ("A", "B", "D", "E", "F", "G", "H", "J", "K", "L", "M")) else 0


