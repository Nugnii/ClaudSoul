#   отсутствует у неё ОПРЕДЕЛЯЮЩИЙ ДОКУМЕНТ. Это отношение к документу, а не к дереву.
# · Форма «правило в прозе без проверяющего» (D291, D296) — предел самого родительского
#   паттерна: «граница семьи — суждение», глобальная дробь НЕ ИЗМЕРЕНА. Признак на неё
#   повторил бы исход рода C: ловил бы жанр повелительной фразы, а не отношение.
# Условие снятия: величины плеч замера публикуются одним источником, который читают и
# протокол, и код, — тогда расхождение сверяется, а не вычитывается.
G_WRITE = re.compile(r"""(?<![A-Za-z0-9_])["']?([a-z][a-z0-9_]{2,})["']?\s*:\s*(?:["'$\{]|[0-9])""")
# В питоне ключ словаря всегда в кавычках. Без этого требования полем считался формат
# f-строки (`f"b{block_index:03d}"` в mcp-server/ingest/normalize.py:39).
G_WRITE_PY = re.compile(r"""(?<![A-Za-z0-9_])["]([a-z][a-z0-9_]{2,})["]\s*:\s*(?:["'$\{]|[0-9])""")
# `(?<!\$)` перед скобкой: `${ИМЯ:-0}` — разбор параметра оболочки, а не сборка объекта.
G_OBJ = re.compile(r"""jq\s|json\.dump|printf\s+'?\{|(?<!\$)\{\s*["']?[a-z][a-z0-9_]*["']?\s*:"""
                   r"""|--argjson|--arg\s""")
# Запись МАШИНЕ: уходит в файл. `2>/dev/null` и `>&2` персистентностью не являются.
G_PERSIST = re.compile(r"""(?<![0-9&])>>?\s*["']?[$A-Za-z_.][^&\s]|json\.dump\s*\(|write_text\s*\(""")
G_COMPACT = re.compile(r"\bjq\s+-[a-zA-Z]*c")
G_TEXTMATCH = re.compile(r"\bgrep\b|\bawk\b|\bsed\b|\bmatch\(|\bcontains\(|\btest\(|\bre\.")
G_TRUNC = re.compile(r"""(?<![>0-9&])>\s*["']?[$A-Za-z_.]""")


def _g_reads(name: str, text: str, skip: set[int]) -> bool:
    """Читает ли файл поле `name` — структурно, текстом или именем-аргументом."""
    # Каждое из трёх выражений ниже содержит имя БУКВАЛЬНО, поэтому строка без имени
    # совпасть не может — отсев по подстроке равносилен, а не приближение. Без него род
    # перебирал «поля × файлы × строки» регулярными выражениями: 5,6 с из 9,5 с прогона
    # (замер 18 октября 2026, D1000 — хук Stop carrier-growth-check ждал этого на границе).
    if name not in text:
        return False
    e = re.escape(name)
    struct = re.compile(r"""\.{n}(?![A-Za-z0-9_])|\[["']{n}["']\]|get\(\s*["']{n}["']"""
                        r"""|["']{n}["']\s*\)|\b{n}\b\s*==|\$\{{?{n}\b""".format(n=e))
    txt = re.compile(r"""\\?["']{n}\\?["']\s*:?""".format(n=e))
    arg = re.compile(r"""[(,]\s*["']{n}["']\s*[,)]""".format(n=e))
    for i, line in enumerate(text.splitlines()):
        if name not in line or i in skip or line.lstrip().startswith("#"):
            continue
        if struct.search(line) or arg.search(line):
            return True
        if G_TEXTMATCH.search(line) and txt.search(line):
            return True
    return False


def carriers_g() -> list[tuple[Path, list[tuple[str, str]]]]:
    code = [f for f in tracked("*.sh", "*.py") if not is_fixture(f)]
    text = {f: f.read_text(errors="replace") for f in tracked("*.sh", "*.py")}
    # Читатель бывает и вне кода: панель `mcp-server/visualization/dashboard.html:523`
    # берёт `data.confidence_dist`, и без этого корпуса поле числилось бы мёртвым.
    outside = "\n".join(p.read_text(errors="replace")
                        for p in tracked("*.html", "*.js", "*.md"))

    writes: dict[str, set[Path]] = {}
    wlines: dict[tuple[str, Path], set[int]] = {}
    kind: dict[str, str] = {}
    for f in code:
        lines = text[f].splitlines()
        rx = G_WRITE_PY if f.suffix == ".py" else G_WRITE
        for i, line in enumerate(lines):
            if line.lstrip().startswith("#") or not G_OBJ.search(line):
                continue
            near = lines[max(0, i - 3):i + 4]
            persisted = [x for x in near if G_PERSIST.search(x)]
            if not persisted and not any(G_COMPACT.search(x) for x in near):
                continue
            # Манифест (перезапись `>`) против журнала (дозапись `>>` или поток): у журнала
            # непрочитанное поле — мёртвая нагрузка, у манифеста оно ЯКОРЬ утверждения о
            # воспроизводимости, и непроверенный якорь делает утверждение необналичиваемым.
            kk = "манифест" if persisted and any(G_TRUNC.search(x) for x in persisted) \
                 else "журнал"
            for m in rx.finditer(line):
                writes.setdefault(m.group(1), set()).add(f)
                wlines.setdefault((m.group(1), f), set()).add(i)
                kind.setdefault(m.group(1), kk)

    out: dict[Path, list[tuple[str, str]]] = {}
    for name, ws in writes.items():
        if any(_g_reads(name, text[f], set()) for f in code if f not in ws):
            continue
        if any(_g_reads(name, text[f], wlines[(name, f)]) for f in ws):
            continue
        if re.search(r"[.\[]" + re.escape(name) + r"\b", outside):
            continue
        for f in ws:
            out.setdefault(f, []).append((name, kind[name]))
    return sorted(((f, sorted(v)) for f, v in out.items()), key=lambda x: str(x[0]))


