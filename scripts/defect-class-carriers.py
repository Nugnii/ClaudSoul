# РОД K — правило вынесено в модуль, а копия у потребителя осталась
#
# Правило: в дереве есть МОДУЛЬ-ВЛАДЕЛЕЦ правила — файл, внесённый в чужое пространство
# имён (`source`/`.` для оболочки, `import` для питона), — и есть файл, который определяет
# СВОЮ функцию с тем же именем, не называя владельца в исполняемом коде. Последствие одно:
# копии расходятся молча, и правка владельца до потребителя не доходит.
#
# Владелец ВЫВОДИТСЯ, а не перечислен: библиотека — тот, кого кто-то источает или
# импортирует. Питоновский файл со своей точкой входа (`if __name__ == "__main__"`)
# библиотекой не считается, даже если его импортирует тест: это программа. Без оговорки
# владельцем становился `mcp-server/visualization/serve.py` (его импортирует
# `mcp-server/tests/test_serve_security.py:23`), и его `main` делал носителями 22 файла —
# ровно жанр вместо отношения, из-за которого не заведены роды C и I.
#
# КОНТРПРИМЕР (признак обязан НЕ поймать): определение в ветке `else` стража источения —
# запасной путь на случай, когда библиотека не задеплоена рядом. Владелец там НАЗВАН, и
# молча разойтись копия не может. Пример в дереве: `hooks/bulk-copy-guard.sh:41` —
# `to_lower` при названном `portable-lib.sh`; носителем не является, хотя ТОТ ЖЕ файл
# носитель за `hash_value` на :183. Единица рода — пара «файл + имя», а не файл.
# ВТОРОЙ КОНТРПРИМЕР: `hooks/lib/state_lock.py` — сам библиотека (его импортируют трое),
# узаконенный питоновский близнец `hooks/state-lock-lib.sh`. Один протокол на двух языках
# копией у потребителя не является: у оболочки нет способа вызвать питоновскую функцию.
# ТРЕТИЙ КОНТРПРИМЕР, стерегущий оговорку про точку входа: `scripts/regen-seed.py` — его
# `main` есть вход программы, а не правило модуля. Все три держатся машинно
# (`hooks/tests/test_defect_registry_counterexamples.sh`) и проверены мутацией: снятие
# клаузы «владелец назван» краснит первый, снятие оговорки про точку входа — третий.
#
# ТОЧНОСТЬ, измеренная осмотром ВСЕХ совпадений 6 сентября 2026: 7 из 7, ложных нет.
#   · `hash_value` × 3 — `bulk-copy-guard.sh:183`, `internal-doc-leak-guard.sh:153`,
#     `user-correction-guard.sh:283`: байт-в-байт копии при живом `hooks/hash-lib.sh`,
#     который в собственной шапке пишет, что заведён ради снятия ровно этих копий
#     («скопирована байт-в-байт в 5 хуков… фикс переносимости пришлось бы повторять в 7
#     местах»). Упоминаний `hash-lib` в трёх файлах — ноль.
#   · `lock_acquire`, `lock_release` — `hooks/lib/injection-log-rotate.py:49,72` при живом
#     `hooks/lib/state_lock.py`.
#   · `unread_note` — `scripts/dep-index.py:145` и `scripts/meta-contamination.py:58` при
#     живой `hooks/lib/unread-lib.sh`; обе называют её в КОММЕНТАРИИ (`:119` и `:36`), а
#     комментарий источением не является — потому признак судит по `_f_code`.
#
# ОТРИЦАТЕЛЬНЫЙ КЛАСС промерен и больше положительного. Определений в не-библиотеках 1303;
# имя, принадлежащее владельцу, несут 36; клауза «владелец не назван в коде» отвергла 29:
# `to_lower` × 11, `is_git_commit` × 9, `file_mtime` × 2, `iso_epoch` × 2,
# `executable_part` × 2, по одному `to_tokens`, `token_in`, `reverse_lines` — все до одного
# запасные пути под стражем источения. Отбор работает и отбирает то самое отношение.
#
# НАЗВАННЫЙ ПРЕДЕЛ: признак видит копию, СОХРАНИВШУЮ ИМЯ. Копия, переписанная примитивом
# без имени, ему не видна — `hooks/shared-language-lib.sh:60,66` сворачивает регистр через
# `tr 'A-Z' 'a-z'` при объявленном единственным способом `to_lower` из `portable-lib.sh`,
# и признак молчит. Дробь рода из D328 (четыре вынесенные библиотеки — `state-lock`,
# `unread`, `backlog-lib`, `portable-lib`, — и у всех четырёх копии остались) считана
# ГЛАЗОМ и охватывает обе формы; прибор считает первую.
# Условие снятия предела: у библиотеки появляется машинно читаемое объявление примитива,
# который она заменяет (строка шапки вида `# Заменяет: tr '[:upper:]' '[:lower:]'`) —
# тогда вторая форма ищется тем же перебором, а не отдельным правилом на каждую библиотеку.
#
# Повод: D328.
K_DEF_SH = re.compile(r"^\s*(?:function\s+)?([a-z_][a-z0-9_]*)\s*\(\)\s*\{")
K_DEF_PY = re.compile(r"^def\s+([a-z_][a-z0-9_]*)\s*\(")
K_SOURCE = re.compile(r"(?:^|[;&|(]|\bthen\b|\belse\b|\bdo\b|\|\|)\s*(?:\.|source)\s+(\S+)")
K_ASSIGN = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)=.*?([a-z0-9_.-]+\.sh)")
K_IMPORT = re.compile(r"^\s*(?:from\s+([a-z0-9_]+)\s+import|import\s+([a-z0-9_]+))")
K_PROGRAM = re.compile(r"^if\s+__name__\s*==")


# ЗАКОННЫЕ ЗЕРКАЛА (D1285): правило владельца на другом языке, которое потребитель не может подключить, и копия сверяется
# с владельцем ИСПОЛНЕНИЕМ — функцией в том же файле (значение записи). Запись без такой функции исключением не служит.
K_MIRRORS: dict[tuple[str, str], str] = {
    ("scripts/signal-precision-corpus.py", "pad_words"): "pad_owner_mismatch",
}


def _k_numbered(path: Path) -> list[tuple[int, str]]:
    """Исполняемые строки С НОМЕРОМ. `_f_code` отдаёт подпоследовательность строк файла в
    их порядке, поэтому номер восстанавливается указателем, а не вторым разбором: второй
    разбор был бы копией правила `_f_code` — тем самым родом K в самом приборе."""
    text = path.read_text(errors="replace")
    kept = iter(_f_code(text, path.suffix == ".py"))
    cur = next(kept, None)
    out: list[tuple[int, str]] = []
    for i, line in enumerate(text.splitlines(), 1):
        if cur is not None and line == cur:
            out.append((i, line))
            cur = next(kept, None)
    return out


def carriers_k() -> list[tuple[Path, list[tuple[str, str]]]]:
    files = tracked("*.sh", "*.py")
    code: dict[Path, list[tuple[int, str]]] = {}
    defs: dict[Path, dict[str, int]] = {}
    by_base: dict[str, list[Path]] = {}
    for f in files:
        cl = _k_numbered(f)
        code[f] = cl
        d: dict[str, int] = {}
        for i, line in cl:
            mo = (K_DEF_PY if f.suffix == ".py" else K_DEF_SH).match(line)
            # Имя с подчёркиванием — внутреннее по соглашению обоих языков: его не
            # источают и не импортируют, совпадение имён там ничего не обещает.
            if mo and not mo.group(1).startswith("_"):
                d.setdefault(mo.group(1), i)
        defs[f] = d
        by_base.setdefault(f.name, []).append(f)

    # Библиотека — та, кого ВНЕСЛИ в чужое пространство имён. Имя приходит и переменной
    # (`PORTABLE_LIB=…/portable-lib.sh; source "$PORTABLE_LIB"`) — это ходовая форма в
    # дереве, и без разбора присваивания владельцами оказались бы 19 файлов вместо 38.
    libs: set[Path] = set()
    brought: dict[Path, set[Path]] = {}   # кого файл ВНОСИТ в своё пространство имён (D1285): исключение — только им
    for f, cl in code.items():
        if f.suffix == ".sh":
            var: dict[str, set[str]] = {}
            for _, line in cl:
                a = K_ASSIGN.match(line)
                if a:
                    var.setdefault(a.group(1), set()).add(a.group(2))
            for _, line in cl:
                s = K_SOURCE.search(line)
                if not s:
                    continue
                bases = set(re.findall(r"[a-z0-9_.-]+\.sh", s.group(1)))
                for v in re.findall(r"\$\{?([A-Za-z_][A-Za-z0-9_]*)", s.group(1)):
                    bases |= var.get(v, set())
                for b in bases:
                    libs.update(c for c in by_base.get(b, []) if c != f)
                    brought.setdefault(f, set()).update(c for c in by_base.get(b, []) if c != f)
        else:
            for _, line in cl:
                mo = K_IMPORT.match(line)
                if mo:
                    nm = (mo.group(1) or mo.group(2)) + ".py"
                    libs.update(c for c in by_base.get(nm, []) if c != f)
                    brought.setdefault(f, set()).update(c for c in by_base.get(nm, []) if c != f)
    libs = {l for l in libs
            if not (l.suffix == ".py" and any(K_PROGRAM.match(x) for _, x in code[l]))}

    owner_of: dict[str, set[Path]] = {}
    for l in libs:
        for n in defs[l]:
            owner_of.setdefault(n, set()).add(l)

    rows: list[tuple[Path, list[tuple[str, str]]]] = []
    for f in files:
        if f in libs:
            continue
        body = "\n".join(l for _, l in code[f])
        found: list[tuple[str, str]] = []
        for n, ln in sorted(defs[f].items()):
            owners = owner_of.get(n)
            if not owners:
                continue
            # Контрпример в действии: владелец ПОДКЛЮЧЁН (`source`/`.`, `import`) либо, у шелл-файла, НАЗВАН в исполняемом
            # коде — определение есть запасной путь под стражем источения, а не молчаливая копия. Копию на питоне имя
            # файла не освобождает (D1285, скептик opus, Н4): строка с именем шелл-владельца делала копию невидимой, хотя
            # копия оставалась. Строгое «только подключение» и для шелла замерено 10 ноября 2026 и отвергнуто: вскрыло
            # ложный носитель — обёртку библиотеки в heredoc фикстуры (`test_guarantee_map_guard.sh:241`).
            if any(o in brought.get(f, ()) for o in owners) or (f.suffix == ".sh" and any(o.name in body for o in owners)):
                continue
            # Законный двойник на другом языке — запись реестра ниже, и функция сверки с владельцем определена в том же
            # файле: копия судится исполнением, а не объявлением.
            chk = K_MIRRORS.get((str(f.relative_to(ROOT)), n))
            if chk and chk in defs[f] and any(o.name in body for o in owners):
                continue
            found.append((f"{n}:{ln}",
                          ", ".join(sorted(str(o.relative_to(ROOT)) for o in owners))))
        if found:
            rows.append((f, found))
    return sorted(rows)


