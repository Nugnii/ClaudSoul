# РОД M — песочница проверки построена там, где судимый механизм её ОТБРАСЫВАЕТ
#
# Правило: механизм объявляет путь неинтересным по признаку временности (`*/tmp/*`), а его
# свидетель строит песочницу голым `$(mktemp -d)` — на Linux это ровно `/tmp`. Механизм
# получает НЕВЕРНЫЙ вход и исправно молчит; свидетель читает молчание как утверждение о
# поведении. Последствие одно и оно названо: проверка зелена на одной машине и красна на
# другой, а её вердикт не о том, что она объявляет.
#
# НА macOS ПРИЗНАК НЕВИДИМ: `mktemp -d` там даёт `/var/folders/…`, и совпадения нет. Поэтому
# класс не ловится локальным прогоном по построению — он ловится раннером, то есть поздно.
#
# ДОСТИЖИМОСТЬ, А НЕ УПОМИНАНИЕ. Свидетель связан с механизмом двумя путями: судит его прямо
# либо судит диспетчер, который зовёт его по объявленному списку (`bash-write-dispatch.sh:57`).
# Первая редакция признака искала имя механизма в тексте теста — и выронила ЕДИНСТВЕННОГО
# настоящего носителя (`test_bash_write_dispatch.sh`, связь непрямая), зато поймала
# `test_five_whys_gate.sh`, который поминает `rework-detector` в КОММЕНТАРИИ на :489.
# Оттого имя ищется в КОДЕ, а множество механизмов замыкается по вызову.
#
# ТОЧНОСТЬ, измеренная 14 сентября 2026 на двух срезах дерева: 0 из 4 сейчас, 1 из 4 на
# срезе `b9beec9^` — носитель `test_bash_write_dispatch.sh`, тот самый, что покраснел в
# прогоне CI 34886464295. Разделитель назван и проверяем ОТДЕЛЬНО от дефекта: у здоровых
# рядом с голым `mktemp -d` стоит песочница с корнем `${HOME}`.
#
# КОНТРПРИМЕР (признак обязан НЕ поймать): тест с голым `$(mktemp -d)`, чей механизм
# исключения временных путей не несёт. Таких в дереве 482 — например
# `hooks/tests/test_absent_tool_guard.sh`. Их песочница в `/tmp` законна: вход верен.
#
# НАЗВАННЫЙ ПРЕДЕЛ: судится ОДНА форма исключения — `*/tmp/*` в case-шаблоне. Механизм,
# отбрасывающий временное иначе (`$TMPDIR`, `-ot`, проверка префикса в питоне), признаком не
# виден. Условие снятия: замер назовёт вторую форму числом — она добавляется сюда же.
# Отброс БЕЗУСЛОВНЫЙ: ветка шаблона сразу уходит (`continue`, `exit 0`, `return`). Ветка, которая затем сверяет путь с
# корнем сессии или бэклога (D1224, D1268), песочницу внутри корня судит — её свидетели с голым `mktemp -d` носителями
# не являются (7 ноября 2026: после двух починок признак называл их двенадцать, все ложные).
M_TEMP_EXCLUDE = re.compile(r"\*/tmp/\*[^)\n]*\)\s*(?:continue|exit 0|return)\b")
M_BARE_MKTEMP = re.compile(r"\$\(\s*mktemp -d\s*\)")
M_HOME_MKTEMP = re.compile(r"mktemp -d\s+[\"\']?\$\{?HOME\}?")


def _m_code(text: str) -> str:
    """строки кода: строка-комментарий исключается целиком — имя механизма в прозе связью не является"""
    return "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("#"))


def carriers_m() -> list[tuple[Path, list[str]]]:
    hooks = {p.name: _m_code(p.read_text(errors="replace"))
             for p in tracked("hooks/*.sh") if not is_fixture(p)}
    bearers = {n for n, c in hooks.items() if M_TEMP_EXCLUDE.search(c)}
    # Замыкание по ВЫЗОВУ: диспетчер, называющий стража в своём коде, доставляет ему вход.
    reachable = set(bearers) | {n for n, c in hooks.items()
                                if n not in bearers and any(g in c for g in bearers)}
    rows: list[tuple[Path, list[str]]] = []
    for path in sorted(tracked("hooks/tests/*.sh")):
        c = _m_code(path.read_text(errors="replace"))
        subj = sorted(n for n in reachable if n in c)
        if not subj:
            continue
        bare, homed = bool(M_BARE_MKTEMP.search(c)), bool(M_HOME_MKTEMP.search(c))
        # Песочницы нет вовсе — в области рода такой свидетель не состоит.
        if not (bare or homed):
            continue
        if bare and not homed:
            rows.append((path, subj))
    return rows


def _under_temp(p: Path) -> bool:
    """временный ли путь — спрашивает владельца перечня корней `rc_path_is_private` (`hooks/root-cause-lib.sh`,
    D1013), а не держит свою копию. Владельца не достать ни в судимом дереве, ни в установке (либо нет bash) —
    путь частный: настоящее дерево библиотеку несёт всегда, пробное (копия реестра в `mktemp -d`) — нет."""
    lib = ROOT / "hooks" / "root-cause-lib.sh"
    if not lib.is_file():
        lib = Path.home() / ".claude" / "hooks" / "root-cause-lib.sh"
    try:
        return subprocess.run(
            ["bash", "-c", '. "$1" 2>/dev/null; command -v rc_path_is_private >/dev/null 2>&1 || exit 0; '
             'rc_path_is_private "$2"', "_", str(lib), str(p)],
            stdin=subprocess.DEVNULL, capture_output=True).returncode == 0
    except OSError:
        return True


