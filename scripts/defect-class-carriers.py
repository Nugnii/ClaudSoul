# РОД J — предмет объявлен СОБЫТИЕМ, а регистрация снята с ИМЕНИ ИНСТРУМЕНТА
#
# Правило: хук объявляет в шапке предметом ИЗМЕНЕНИЕ ФАЙЛА («при правке», «записанного
# знания», «изменённый файл»), а в `install.sh` зарегистрирован на PostToolUse со списком
# имён инструментов, которыми это изменение ОБЫЧНО производят, без `Bash`. Оболочка правит
# те же файлы (heredoc, `sed`, короткий скрипт) — событие происходит, хук не зовётся, и
# молчание неотличимо от «проверять было нечего».
#
# Почему это дефект, а не предел платформы: отбор по имени инструмента — единственное, что
# платформа умеет, и в этом никто не виноват. Дефект в том, что ДОСТУПНЫЙ ОТБОР ПРИНЯТ ЗА
# ПРЕДМЕТ: у механизма, чей предмет — файл, имя инструмента есть форма вызова, а не роль.
#
# КОНТРПРИМЕР (признак обязан НЕ поймать): хук на PreToolUse. Там предмет наблюдаем ТОЛЬКО
# через `file_path` — файл ещё не изменён, а у команды оболочки будущая цель до выполнения
# не определима вовсе. Пример в дереве: hooks/module-context-inject.sh — подаёт док модуля
# ДО правки; носителем не является. Второй контрпример — PostToolUse с `Bash` в matcher:
# hooks/knowledge-link-symmetry.sh (починен 5 сентября 2026).
#
# ТОЧНОСТЬ, измеренная осмотром ВСЕХ совпадений 5 сентября 2026: сырой признак (без
# различения события) дал 3 файла, из них 1 ложный — `module-context-inject.sh`, то есть
# 2 из 3. С различением PreToolUse/PostToolUse — 2 из 2, ложных нет. Универсум мал (4
# регистрации PostToolUse с предметом-файлом), и это назван, а не скрыт: род заведён ради
# того, чтобы следующая находка увеличивала счётчик носителей, а не заводила пункт по месту.
#
# Повод: D311. Замер того же дня — `case-2026-09-05-fix-carries-the-genus-it-repairs`
# записан `cat > … <<EOF`, и на нём молчали ДВА хука сразу.
# Знание рода лежит в базе с 27 августа 2026:
# `case-2026-08-27-tool-name-detection-blind-to-work-mode` (confirmed_count 4).
J_SUBJECT = re.compile(r"изменённый файл|изменение файла|записанного знания"
                       r"|по правке|при правке")
J_EVENTS = ("PreToolUse", "PostToolUse", "Stop", "SessionStart", "UserPromptSubmit",
            "PreCompact", "SessionEnd", "Notification", "SubagentStop")


def _registrations() -> list[tuple[str, str, str]]:
    """(событие, имя хука, matcher) из install.sh — универсум ВЫВОДИТСЯ, а не перечислен.

    Разрез сначала по событию, потом по matcher: без первого шага matcher соседнего
    события приписывается чужому хуку, и род ловил бы `doc-impact-check` (PreToolUse[Bash])
    как носителя PostToolUse.
    """
    ins = (ROOT / "install.sh").read_text(errors="replace")
    parts = re.split(r'"(' + "|".join(J_EVENTS) + r')"\s*:', ins)
    out: list[tuple[str, str, str]] = []
    event = None
    for chunk in parts:
        if chunk in J_EVENTS:
            event = chunk
            continue
        if event is None:
            continue
        for matcher, tail in re.findall(r'"matcher":\s*"([^"]*)"(.*?)(?="matcher"|\Z)',
                                        chunk, re.S):
            for hook in re.findall(r"hooks/([a-z0-9._-]+\.sh)", tail):
                out.append((event, hook, matcher))
    return out


def carriers_j() -> list[tuple[Path, list[str]]]:
    rows: dict[Path, list[str]] = {}
    for event, hook, matcher in _registrations():
        if event != "PostToolUse":
            continue
        path = ROOT / "hooks" / hook
        if not path.exists():
            continue
        head = "\n".join(path.read_text(errors="replace").splitlines()[:40])
        if not J_SUBJECT.search(head):
            continue
        if "Bash" in matcher:
            continue
        rows.setdefault(path, []).append(matcher)
    return sorted(rows.items())


