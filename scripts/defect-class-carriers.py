# положенным в тот подкаталог.
#
# НАЗВАННЫЙ ПРЕДЕЛ 1: признак не знает РОДА невидимого остатка и потому не отличает
# «подкаталог с файлами того же рода» от «подкаталог другого рода». Отсюда все три ложных.
# Различить механически можно было бы только перечнем имён вроде `tests|fixtures` — то есть тем
# самым устройством, которое здесь и ищется.
# НАЗВАННЫЙ ПРЕДЕЛ 2: признак смотрит на перечни ПУТЕЙ. Перечень ИМЁН — D280, где изоляция
# прогонов держится списком известных имён хранилищ (`LESSONS_DIR`, `STATE_DIR`), а хуки заводят
# свои (`ABLATION_DIR`, `ITR_STATE_DIR`, `COMPILE_STATE_FILE` и ещё девять) — тем же признаком
# не ловится. Проба 4 сентября 2026 показала, почему: под «файл присваивает два и более имени
# вида `*_DIR`/`*_FILE`» подпадают 105 файлов `.sh` из 476, и 77 из них — тесты
# (`grep -cE '^[[:space:]]*(export )?[A-Z][A-Z0-9_]*(_DIR|_FILE)=' `). То есть признак ловил бы
# ЖАНР «файл держит состояние», а не отношение «перечень против источника» — ровно исход
# рода C. Условие снятия: имена хранилищ публикуются одним источником (`paths-lib`), и
# тогда перечень сверяется с ним, а не с жанром.
F_GLOB = re.compile(r"""(?:\$\{?\w+\}?"?/)?((?:[\w][\w.-]*/)*[\w][\w.-]*)/\*\.([a-z]{1,5})\b""")
F_LIT = re.compile(r"""["']((?:[\w][\w.-]*/)+[\w][\w.-]*\.[a-z]{1,5})["']""")
# Выводом множества считается обращение к источнику истины: индекс git, обход дерева, `**`.
# `tracked(` — имя, под которым индекс git вызывается в этом репозитории.
# `\*\*` берётся ТОЛЬКО в позиции рекурсивного шаблона (`**/`, `/**`): голая пара звёзд —
# это жирный markdown в фикстуре, и первая редакция признака сняла на ней целый файл
# случайно, а не по правилу (`hooks/tests/test_docs_family_check.sh:345`).
# Две формы того же вывода, которых признак не знал (12 сентября 2026, D306): `git -C <корень>
# ls-files` (ключ между словом и подкомандой) и argv-список интерпретатора —
# `["git","ls-files","scripts/*.sh"]` в `scripts/probes/R3.sh:22`. Обе выводят множество
# индексом git, а числились носителями по букве регулярки. Осмотрены обе, ложных среди них
# две из двух; настоящие носители (`for f in scripts/*.sh`) под расширение не подпадают —
# положительный контроль в test_defect_registry_counterexamples.
F_DERIVED = re.compile(r"git(?:\s+-C\s+\S+)?(?:\s+|[\"']\s*,\s*[\"'])(?:ls-files|diff|grep)|\*\*/|/\*\*|rglob|os\.walk"
                       r"|\btracked\(|\bfind\s+\S")
# Глоб, переданный АРГУМЕНТОМ функции, которая пробрасывает "$@" в `git ls-files`, выведен той
# же функцией: `universe_instruments() { _universe 'scripts/*.sh'; }` — сама библиотека вывода
# универсума (hooks/lib/universe-lib.sh) числилась носителем рода, который закрывает. Имя такой
# функции ВЫВОДИТСЯ из файла по устройству тела, а не берётся из перечня имён.
F_FORWARD_FN = re.compile(r'^\s*(\w+)\s*\(\)\s*\{[^}]*?\bls-files\b[^}]*?"\$@"', re.M | re.S)
# Литерал-СООБЩЕНИЕ против литерала-АРГУМЕНТА (D310). Шаблон внутри кавычек, в которых
# есть ПРОБЕЛ, множества не задаёт: это текст, адресованный человеку
# (`assert_empty "$OUT" "T11b: … frozen docs/*.md игнорируются"`), и в поле зрения он ничего
# не держит. Ложный носитель зовёт чинить место, где чинить нечего, и очередь не убывает от
# работы. Снимать ВСЕ строковые литералы нельзя: у механизма перечень как раз в литерале и
# живёт (`install.sh` — "$CLAUDSOUL_DIR"/hooks/*.sh, настоящий носитель), поэтому разделитель
# именно пробел, а не факт кавычек.
# ЗАМЕР 6 сентября 2026, все 62 совпадения F_GLOB в дереве: кандидатов в сообщения 3
# (test_docs_family_check.sh, test_quality_gate.sh, test_adv_dep_index_plist_dependents.sh),
# настоящих сообщений 3, ложных 0; настоящих носителей задето 0 из 59 — у них пробела в
# литерале нет по построению (путь с пробелом в шаблоне оболочки не живёт).
F_QUOTED = re.compile(r'"([^"]*)"|\'([^\']*)\'')


def _f_in_message(line: str, start: int) -> bool:
    """Шаблон на позиции start лежит внутри строкового литерала С ПРОБЕЛОМ."""
    for q in F_QUOTED.finditer(line):
        body = q.group(1) if q.group(1) is not None else q.group(2)
        if q.start() < start < q.end():
            return " " in body
    return False


F_HEREDOC = re.compile(r"<<-?\s*[\"']?(\w+)[\"']?")
F_REDIR = re.compile(r">\s*[\"']?\$?\{?\w")


def _py_string_rows(text: str):
    """Номера строк, занятых многострочными литералами питона (от строки открытия до строки закрытия), по `tokenize`;
    None — разбор не удался."""
    import tokenize
    rows = set()
    try:
        for tok in tokenize.generate_tokens(io.StringIO(text).readline):
            if tok.type == tokenize.STRING and tok.start[0] != tok.end[0]:
                rows.update(range(tok.start[0], tok.end[0] + 1))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return None
    return rows


def _f_code(text: str, py: bool):
    """Строки, которые ИСПОЛНЯЮТСЯ: без комментариев, docstring и heredoc, пишущегося в файл.

    Осмотр 4 сентября 2026 до этой оговорки: 11 совпадений, из них 8 — упоминание шаблона в
    КОММЕНТАРИИ либо литерал внутри фикстуры. Комментарий про универсум универсумом не является.
    """
    in_doc = False
    mark = None
    # Строки многострочных литералов питона называет РАЗБОРЩИК (`tokenize`), а не счёт кавычек в строке (D1267): `"""`
    # в комментарии, в обычной строке или в регулярном выражении открывал «строку» до следующего такого же, и точка
    # входа `dep-index.py` выпадала из кода. Не разобрался (обрывок, синтаксис новее интерпретатора) — прежний счёт.
    # Номера `tokenize` — по `\n`, а строки здесь — по `splitlines()`, который режет и на `\u2028`, `\f` (в дереве такой
    # файл есть — `mcp-server/tests/test_discovery.py`): номер `\n`-строки куска — число `\n` до него плюс один.
    doc_rows = _py_string_rows(text) if py else None
    row = 1
    for piece in text.splitlines(keepends=True):
        line, n = piece.rstrip("\r\n\x0b\x0c\x1c\x1d\x1e\x85\u2028\u2029"), row
        row += piece.count("\n")
        if mark is not None:
            if line.strip() == mark:
                mark = None
            continue
        if py and doc_rows is not None:
            if n in doc_rows:
                continue
        elif py:
            q = line.count('"""') + line.count("'''")
            if in_doc:
                in_doc = not q % 2
                continue
            if q % 2:
                in_doc = True
                continue
        if line.lstrip().startswith("#"):
            continue
        # Heredoc — конструкция оболочки: в питоне `<<'EOF'` бывает только внутри строки, и метка ждала бы строку `EOF`,
        # которой нет, — хвост файла выпадал из кода (`signal-precision-corpus.py:218`, D1267).
        m = None if py else F_HEREDOC.search(line)
        if m and F_REDIR.search(line[:m.start()]):
            mark = m.group(1)
            continue
        yield line


# ЦЕНА ОБОИХ НОСИТЕЛЕЙ ИЗМЕРЕНА (7 сентября 2026) — ноль, с названными основаниями.
#   · uninstall.sh: установщик кладёт ровно три вещи (hooks/*.sh, hooks/lib/*,
