def tracked(*globs: str) -> list[Path]:
    # ОТКАЗ GIT — «НЕ ИЗМЕРЕНО», А НЕ ПУСТОЙ ПЕРЕЧЕНЬ (D1168, 28 октября 2026, корень R6). Код возврата не читался:
    # в дереве без git (снимок `git archive`, копия прибора) перечень был пуст, и ответ «носителей: 0» кодом 0 был
    # неотличим от «чисто» — «Проверки» D307 и D310 зеленели при дефекте на месте. Причина копится здесь, вердикт
    # «не измерено» (код 2) выносит `main()`.
    # `-z` (второй круг D1168, скептик M1): без него имя с кириллицей или кавычкой приходит в кавычках с escape и как
    # путь не существует — файл выпадал из перечня молча.
    # КОРЕНЬ ВЫБРАЛ ПРИБОР — ОН И НАЗЫВАЕТ ЕГО git (D1170, корень R6; pattern-tree-chooser-names-tree-to-callee):
    # унаследованные `GIT_DIR`, `GIT_INDEX_FILE`, `GIT_WORK_TREE` вызывающего подменяли индекс, и путь, общий у чужого
    # индекса и снимка (README.md), давал «носителей 0» кодом 0. Снимаются ВСЕ `GIT_*`, а не перечень (скептик D1170,
    # M1): `GIT_LITERAL_PATHSPECS` и родственные — git ставит их потомкам сам (`git --literal-pathspecs`, magit) —
    # опустошали `tracked("*.sh")`, а ключ кэша (вызов без шаблонов) не менялся, и «0» ложился в кэш для чистых прогонов.
    # Вывод `-z` читается байтами и разбирается `os.fsdecode`: путь не в UTF-8 в индексе ронял `text=True`.
    _env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z", *globs],
                             capture_output=True, env=_env)
    except OSError as e:
        if not _GIT_FAILED:
            _GIT_FAILED.append(f"git не запускается: {e}")
        return []
    if out.returncode != 0:
        if not _GIT_FAILED:
            _err = (out.stderr or b"").decode(errors="replace").strip().splitlines()
            _GIT_FAILED.append(f"код {out.returncode}: {_err[0][:160] if _err else 'без вывода'}")
        return []
    # ФАЙЛ, ЖИВОЙ В `git ls-files`, НО СНЯТЫЙ С ДИСКА (удалён без `git rm`/`git add -u`),
    # доходил отсюда до первого же `f.read_text()` и ронял Traceback — при коде возврата 1,
    # неотличимом от законного «носителей 0» (D447). Форма ответа взята у соседа в этом же
    # файле: `_input_key()` на том же состоянии называет пропуск в stderr и продолжает.
    # Имя пропущенного называется ОДИН раз за прогон, а не на каждый вызов: `tracked()`
    # зовут все одиннадцать родов, и первая редакция печатала одну и ту же строку 21 раз.
    # КОД ВОЗВРАТА НЕ ТРОГАЕТСЯ, и это решение, а не умолчание. Вторая редакция починки
    # отвечала на неполный вход своим кодом 3 — и сломала троих: `measurement-due.sh:254`
    # держит 3 под «находки второго рода» и ЗАСЧИТЫВАЛ бы замер выполненным, обнуляя срок;
    # `test_contract_line_anchor.sh:97` читает не-0 у `--genus E` как «носители есть»;
    # а сама подмена накрывала и код 2 («признак не заведён» у родов C, I, N, O) — то есть
    # заводила НОВОЕ смешение вместо снятого. Вдобавок законные состояния дерева
    # (sparse-checkout, отслеживаемая битая ссылка) давали бы 3 на здоровом прогоне.
    # Неполнота называется СЛОВАМИ в stderr — тем же каналом, что у соседа `_input_key()`.
    paths = [ROOT / os.fsdecode(p) for p in out.stdout.split(b"\0") if p]
    live = []
    for _p in paths:
        if _p.exists():
            live.append(_p)
        elif str(_p) not in _MISSING_TRACKED:
            _MISSING_TRACKED.add(str(_p))
            print(f"defect-class-carriers: файл есть в `git ls-files`, но не на диске — "
                  f"пропущен: {_p}", file=sys.stderr)
        else:
            _MISSING_TRACKED.add(str(_p))
    # ПУСТОЙ ПЕРЕЧЕНЬ КОРНЯ ПРИ КОДЕ 0 — ТОЖЕ «НЕ ИЗМЕРЕНО» (второй круг D1168, скептик M1). git отвечает успехом и
    # пусто, когда корень прибора — неотслеживаемая папка чужого репозитория (снимок `git archive` внутри него), и
    # путями чужого индекса (`GIT_DIR`, `GIT_INDEX_FILE`), которых на диске нет. Правило — только для вызова без шаблонов:
    # с шаблоном пусто законно (в проекте нет `hooks/`). Тот же ответ «пусто — отказ» — у `hooks/lib/universe-lib.sh`.
    if not globs and not live and not _GIT_FAILED:
        _GIT_FAILED.append("git ответил, но живых файлов в перечне корня нет — корень вне своего репозитория"
                           " или индекс чужой")
    return live


