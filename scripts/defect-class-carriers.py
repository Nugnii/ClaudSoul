#!/usr/bin/env python3
# Результат: в дереве не осталось носителей известных родов дефекта
# Проверка результата: python3 scripts/defect-class-carriers.py даёт 0
#
# Пока даёт 1: носители есть, их число печатает сам прогон, и это очередь на разбор, а не
# достигнутое состояние. Объявленный результат — состояние МИРА, а не работа прибора: «носителей
# нет», а не «назвал носителей». Инструмент, объявляющий результатом собственную работу,
# всегда успешен и потому бесполезен (поймано стражем контракта на этом самом файле).
"""defect-class-carriers.py — сколько в дереве носителей каждого известного рода дефекта.

Зачем (D109). Замер 29 августа 2026 свёл 68 находок трёх раундов прожарки к ТРЁМ родам.
Роды закрыты у трёх механизмов из 154 (индекс на 29 августа 2026; нынешнее число печатает
`python3 scripts/dep-index.py --check`) — то есть у тех, по которым шла прожарка. Найти
остальных носителей было нечем: род известен, признака носителя нет. Прожарить все
механизмы подряд — это перечень мест, а не работа с родом.

Признак каждого рода объявляется здесь ВМЕСТЕ с контрпримером: случаем, который признак
обязан НЕ поймать. Без объявленного контрпримера признак снимается с того, что видно, и
промахивается по отрицательному классу — это стоило проекту отдельного пункта долга
(D107: признак «снимок» дал 6 ложных из 12).

Точность каждого признака измерена на дереве и записана в шапке рода ниже. Признак с
непроверенной точностью здесь не заводится.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def tracked(*globs: str) -> list[Path]:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", *globs],
                         capture_output=True, text=True)
    return [ROOT / p for p in out.stdout.split("\n") if p]


# --------------------------------------------------------------------------------------
# РОД A — структурный формат читается построчным шаблоном, а не разбором формата
#
# Правило: файл ИЗВЛЕКАЕТ ПОЛЕ из структурного формата (YAML-шапка, JSON, JSONL) текстовым
# шаблоном, привязанным к началу строки (`^ключ:`), и НЕ отдаёт этот же текст разбору.
# Форма поля тогда становится вопросом, и каждая новая форма — новая находка.
#
# КОНТРПРИМЕР (признак обязан НЕ поймать): файл, который извлекает область текстом, а
# значения берёт разбором (`jq`, `json.loads`, `yaml.safe_load`) — там форма не решает.
# Пример в дереве: hooks/detection-signals-lib.sh — 35 вызовов разбора при одном текстовом
# извлечении; носителем не является.
#
# ТОЧНОСТЬ, измеренная осмотром ВСЕХ совпадений 29 августа 2026: 8 из 8 читают поле
# структурного документа построчно — ложных нет. Но последствие разное, и вывод делит
# носителей на механизмы и тесты: у механизма это тихое неверное значение, у теста —
# хрупкое утверждение, падающее громко.
A_FIELD = re.compile(r"""(?x)
      awk\s[^\n]*\^(?:[a-z_]+):            # awk '/^ключ:/ ...'
    | sed\s+-n\s+[^\n]*\^(?:[a-z_]+):      # sed -n 's/^ключ: ...'
    | grep\s+-[a-zA-Z]*E?[^\n]*'\^[a-z_]+:  # grep -E '^ключ:'
    | re\.(?:search|match|findall)\(\s*rf?["'][^"']*\^\{?[a-z_]+\}?:   # питон по ^ключ:
""")
A_PARSE = re.compile(r"yaml\.safe_load|json\.loads|\bjq\b|json\.load\(")
# Носитель читает поле ИЗ СТРУКТУРНОГО ДОКУМЕНТА. Правило, а не перечень имён полей:
# перечень имён был бы тем самым дефектом, который здесь и ищется. Документ опознаётся по
# обращению к шапке `.md`, к `.json`/`.jsonl` либо к каталогу знаний.
#
# КОНТРПРИМЕР: тест, который грепает `^ключ:` в собственной строке-фикстуре, документа не
# читает и носителем не является (`hooks/tests/test_knowledge_fields.sh`).
A_DOC = re.compile(r"\.jsonl?\b|global-lessons|LESSONS_DIR|knowledge/|frontmatter|шапк")


def carriers_a() -> list[tuple[Path, int, int]]:
    out = []
    for f in tracked("*.sh", "*.py"):
        t = f.read_text(errors="replace")
        hits = len(A_FIELD.findall(t))
        if not hits or not A_DOC.search(t):
            continue
        parses = len(A_PARSE.findall(t))
        # Контрпример в действии: разбора существенно больше, чем текстовых извлечений —
        # текст служит поиском области, а не чтением значения.
        if parses > hits:
            continue
        out.append((f, hits, parses))
    return out


# --------------------------------------------------------------------------------------
# РОД B — чтение не различает «прочитал» и «не смог»
#
# Правило: на отказе чтения подставляется ВЫДУМАННОЕ значение вместо признания
# нечитаемости. Незнание тогда выражается значением — и выбирается благоприятное:
# ноль подтверждений, ноль дней, пустой список.
#
# КОНТРПРИМЕР (признак обязан НЕ поймать): подстановка ПУСТОГО значения (`${v:-}`) и
# возврат `None`/`"bad"`/отдельного маркера — это и есть различение, а не его отсутствие.
# Пример в дереве: queue_age() в knowledge-instrument-audit возвращает None при
# неразбираемой дате, и вызывающий трактует None как «неизвестно» → просрочен.
# Носитель — подстановка выдуманного значения ТАМ, ГДЕ БЫЛО ЧТЕНИЕ. Просто `${v:-0}` не
# признак: у счётчика это законная инициализация. Признак — переменная, получившая значение
# из чтения (подстановка команды `grep`/`awk`/`sed`/`cat`/`jq`/`python3`), и затем гашение
# отказа числом. В питоне — `except`, подставляющий литерал вместо возврата маркера.
#
# КОНТРПРИМЕР: `COUNT=0` в начале цикла и `${COUNT:-0}` при выводе — это инициализация
# счётчика, а не гашение отказа чтения; признак обязан её НЕ поймать.
#
# ТОЧНОСТЬ, измеренная осмотром выборки 29 августа 2026: 4 настоящих из 5 (80%).
# Ложный — `hooks/five-whys-gate.sh`: там `${_rw_key:-0}` стоит поверх контрольной суммы,
# то есть значение служит КЛЮЧОМ, а не замером, и ноль означает «файла нет», а не
# «не смог прочитать». Отличить ключ от замера механически при нынешних средствах нечем;
# 80% достаточно для ОЧЕРЕДИ на разбор и недостаточно для вердикта о файле.
B_PY = re.compile(r"""except[^\n:]*:\s*\n\s+(?:return|[a-z_]+\s*=)\s*"""
                  r"""(?:0|\[\]|\{\}|""|\'\'|"[^"]*"|\'[^\']*\')\s*\n""")
B_READ_ASSIGN = re.compile(
    r"^\s*([A-Za-z_][A-Za-z_0-9]*)=(\$\([^\n]*\b(?:grep|awk|sed|cat|jq|python3|ls|wc)\b[^\n]*)",
    re.M)
B_DEFAULT_NUM = re.compile(r"\$\{([A-Za-z_][A-Za-z_0-9]*):-[0-9]+\}")
# Правило, добытое РАЗБОРОМ 39 носителей 29 августа 2026: ноль правдив там, где читается
# СЧЁТ — пустой вход честно равен нулю (`grep -c`, `wc -l/-c/-m`, `find | grep -c`). Ноль
# лжив там, где читается ЗНАЧЕНИЕ ПОЛЯ или ЗАМЕР: отсутствие значения не есть значение.
# Без этой оговорки признак ловил 39 мест при трёх настоящих дефектах — то есть мерил
# «есть ли подстановка», а утверждал «есть ли дефект»: предмет замера не совпадал с
# предметом утверждения. Ровно род C, допущенный в приборе для рода B.
B_COUNT = re.compile(r"\bgrep\s+-[a-zA-Z]*c|\bwc\s+-[lcmw]|\bcksum\b")


def carriers_b() -> list[tuple[Path, int]]:
    out = []
    for f in tracked("*.sh", "*.py"):
        t = f.read_text(errors="replace")
        # Читатель, который САМ нормализует исход (`jq '// значение'`, `awk '{print $1+0}'`,
        # `|| echo`), значения не теряет — подстановка поверх него не гашение отказа.
        # Замер осмотром 29 августа 2026 до этой оговорки: из четырёх проверенных файлов
        # настоящих носителей был один, ложных два. Оговорка их снимает.
        # Читатель, который САМ подставляет значение (`jq '// 0'`, `awk '{print $1+0}'`,
        # `|| echo 0`), отказа не теряет — подстановка поверх него не гашение.
        # `|| true` сюда НЕ входит: он глушит только код возврата, значение остаётся
        # пустым. Первая редакция оговорки этого не различала и выбросила единственный
        # подтверждённый носитель (`metrics-collector`), оставив подтверждённый ложный
        # (`five-whys-gate`) первым в списке — поймано осмотром вершины списка.
        read_vars = {v for v, line in B_READ_ASSIGN.findall(t)
                     if not re.search(r"//\s*\S|\+\s*0\b|\|\|\s*echo\s+\S", line)
                     and not B_COUNT.search(line)}
        # Число подставлено переменной, которая пришла ИЗ ЧТЕНИЯ, — вот носитель.
        # Переменная, у которой рядом стоит проверка на пустоту (`[ -z "$V" ]`), уже
        # различает «прочитал» и «не смог»: подстановка после признания — нормализация,
        # а не гашение. Без этой оговорки признак продолжал считать носителями места,
        # ПОЧИНЕННЫЕ в тот же час, и очередь не убывала бы от работы.
        acknowledged = set(re.findall(r'\[\s*-z\s+"\$\{?([A-Za-z_][A-Za-z_0-9]*)', t))
        hits = sum(1 for v in B_DEFAULT_NUM.findall(t)
                   if v in read_vars and v not in acknowledged)
        hits += len(B_PY.findall(t))
        if hits:
            out.append((f, hits))
    return out


# --------------------------------------------------------------------------------------
# РОД C — глобальный вердикт вынесен из локальной улики
#
# Признак НЕ ЗАВЕДЁН. Это вердикт, а не пропуск, и он с доказательством.
#
# Что пробовали: «сообщение содержит утверждение о системе (`не выполнялась`, `нет`,
# `совпадают`, `находок нет`), а ветка, из которой оно печатается, смотрит на один объект».
# Замер на дереве 29 августа 2026: 112 файлов содержат такие сообщения, а подтверждённых
# носителей рода среди них 3 — точность 3%. Признак ловит ЖАНР сообщения, а не отношение
# предмета к улике; отношение видно только из того, ЧТО утверждается и ЧЕМ подтверждается,
# то есть требует чтения смысла, а не текста.
#
# Отсюда честный исход: род C ищется не признаком носителя, а проверкой утверждения — у
# каждого вердикта объявлен предмет, и улика сверяется с ним. Такая проверка строится
# ПОШТУЧНО в месте вердикта (как `_absent_or_drift` в drift-check) и общего признака не
# имеет при нынешних средствах.
C_VERDICT = "не заведён: точность 3% (112 совпадений, 3 носителя) — ловит жанр, не отношение"


# --------------------------------------------------------------------------------------
# РАЗБОР НОСИТЕЛЕЙ, 29 августа 2026 (D109, часть 2). Вердикт по каждому, а не счёт.
#
# РОД A — разобрано 8, дефектов ДЕЙСТВУЮЩИХ 0.
#   · 3 механизма (`knowledge-independence.py`, `escalation-age.sh`,
#     `knowledge-audit-digest.sh`) читают поле шапки построчно — носители по форме.
#     Достижимость промаха измерена: записей знания с ломающей формой (комментарий после
#     значения, значение в кавычках) — 0 из 395. Единственный файл с такими формами —
#     `META.md`, спецификация формата; два механизма исключают её по имени, третий — по
#     шаблону `pattern-*.md`/`principle-*.md`. Переписывать три работающих механизма ради
#     недостижимого промаха значило бы работу без результата.
#   · 5 тестов утверждают о знании через `^ключ:`. Последствие иное: хрупкое утверждение
#     падает громко, а не читает молча неверно. Не дефект.
#
# РОД B — разобрано 39, дефектов 3, все починены в тот же ход:
#   · `metrics-collector.sh` — нечитаемый `confirmed_count` складывался нулём в итог,
#     и итог печатался как измеренный. Теперь считается отдельно и называется.
#   · `knowledge-activator.sh` — нечитаемая `confidence` становилась единицей и
#     участвовала в отборе как измеренная. Теперь запись исключается из ранжирования.
#   · `state-size.sh` — отказ `du` печатался как «0 МБ». Теперь отказ кодом 2.
#   Остальные 36 верны по построению: там читается СЧЁТ, и ноль есть его истинное
#   значение при пустом входе.
#
# НАЗВАННЫЙ ПРЕДЕЛ признака B. Он не отличает поле-счётчик событий (`confirmed_count`:
# отсутствие честно равно нулю) от поля-свойства (`confidence`: отсутствие не есть ноль).
# Различие семантическое; выразить его можно только перечнем имён полей, а перечень — тот
# самый дефект, который здесь ищется. Отсюда остаточные совпадения на `INTENSITY`,
# `CONFIRMED_COUNT` — они в очереди и не дефекты.
#
# Условие снятия: предел держится, пока смысл поля берётся из его ИМЕНИ. Появится он в
# схеме знания (`knowledge/META.md` объявляет, счётчик поле или свойство) — признак
# читает схему, и различие перестаёт быть семантическим.

def main() -> int:
    print("НОСИТЕЛИ РОДОВ ДЕФЕКТА (D109)\n")

    a = carriers_a()
    # Делим по ПОСЛЕДСТВИЮ: у механизма построчное чтение даёт тихое неверное значение,
    # у теста — хрупкое утверждение, которое падает громко. Одно число на оба ввело бы в
    # заблуждение, хотя признак верен для обоих.
    a_mech = [x for x in a if "/tests/" not in str(x[0])]
    a_test = [x for x in a if "/tests/" in str(x[0])]
    print(f"РОД A · построчное чтение структурного формата — носителей: {len(a)}"
          f" (механизмов {len(a_mech)}, тестов {len(a_test)})")
    for f, hits, parses in sorted(a, key=lambda x: -x[1]):
        kind = "тест     " if "/tests/" in str(f) else "механизм "
        print(f"  · {kind}{f.relative_to(ROOT)}  извлечений={hits} разборов={parses}")

    b = carriers_b()
    print(f"\nРОД B · чтение не различает «прочитал» и «не смог» — носителей: {len(b)}")
    for f, hits in sorted(b, key=lambda x: -x[1])[:20]:
        print(f"  · {f.relative_to(ROOT)}  подстановок={hits}")
    if len(b) > 20:
        print(f"  … и ещё {len(b) - 20}")

    print(f"\nРОД C · глобальный вердикт из локальной улики — признак {C_VERDICT}")

    print(f"\nПрожарено механизмов: 3. Носителей A: {len(a)}, B: {len(b)}.")
    print("Число носителя — не приговор файлу: это очередь на разбор, а не список дефектов.")
    return 1 if (a or b) else 0


if __name__ == "__main__":
    sys.exit(main())
