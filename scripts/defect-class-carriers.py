# РОД B — чтение не различает «прочитал» и «не смог»
#
# Правило: на отказе чтения подставляется ВЫДУМАННОЕ значение вместо признания
# нечитаемости. Незнание тогда выражается значением — и выбирается благоприятное:
# ноль подтверждений, ноль дней, пустой список.
#
# КОНТРПРИМЕР (признак обязан НЕ поймать): подстановка ПУСТОГО значения (`${v:-}`) и
# возврат `None`/`"bad"`/отдельного маркера — это и есть различение, а не его отсутствие.
# Пример в дереве: queue_age() в knowledge-instrument-audit возвращает None при
# неразбираемой дате, и вызывающий трактует None как «неизвестно» → просрочен.
# Носитель — подстановка выдуманного значения ТАМ, ГДЕ БЫЛО ЧТЕНИЕ. Просто `${v:-0}` не
# признак: у счётчика это законная инициализация. Признак — переменная, получившая значение
# из чтения (подстановка команды `grep`/`awk`/`sed`/`cat`/`jq`/`python3`), и затем гашение
# отказа числом. В питоне — `except`, подставляющий литерал вместо возврата маркера.
#
# КОНТРПРИМЕР: `COUNT=0` в начале цикла и `${COUNT:-0}` при выводе — это инициализация
# счётчика, а не гашение отказа чтения; признак обязан её НЕ поймать.
#
# ТОЧНОСТЬ, измеренная осмотром выборки 29 августа 2026: 4 настоящих из 5 (80%).
# Ложный — `hooks/five-whys-gate.sh`: там `${_rw_key:-0}` стоит поверх контрольной суммы,
# то есть значение служит КЛЮЧОМ, а не замером, и ноль означает «файла нет», а не
# «не смог прочитать». Отличить ключ от замера механически при нынешних средствах нечем;
# 80% достаточно для ОЧЕРЕДИ на разбор и недостаточно для вердикта о файле.
# НЕПУСТОЙ строковый литерал из перечня ВЫБРОШЕН 5 сентября 2026. Он противоречил
# контрпримеру этого же рода, стоящему двенадцатью строками выше: «возврат `None`/`"bad"`/
# отдельного маркера — это и есть различение, а не его отсутствие». Регексп ловил ровно то,
# что доктрина объявляет правильным поведением, и звал чинить уже правильные места: очередь
# не убывала бы от работы. Замер: совпадений во всём дереве пять, из них ТРИ — возврат
# маркера (`"bad"` в scripts/knowledge-instrument-audit.sh:224, `"?"` в
# scripts/usage-outcome-audit.py:107, `"unknown"` в
# mcp-server/ingest/readers/markitdown_reader.py:37). Номера строк — на 5 сентября 2026;
# держит родство ИМЯ, а не число, и проверяет его тест контрпримеров.
# Выдуманное значение — число и ПУСТОЙ контейнер: у них нет канала «я не смог». Непустая
# строка такой канал несёт по построению, потому что вызывающий может её сверить.
# НАЗВАННЫЙ ПРЕДЕЛ: правило берёт смысл из ФОРМЫ литерала, а не из того, сверяет ли его
# вызывающий. `except: return "0"` — выдуманное значение в одежде маркера, и признак его
# не увидит. Условие снятия: появится проверка вызывающих (сверяет ли кто-нибудь
# возвращённое со строкой-маркером) — форма станет не нужна. Держится машинно тестом
# hooks/tests/test_defect_registry_counterexamples.sh.
B_PY = re.compile(r"""except[^\n:]*:\s*\n\s+(?:return|[a-z_]+\s*=)\s*"""
                  r"""(?:0|\[\]|\{\}|""|\'\')\s*\n""")
B_READ_ASSIGN = re.compile(
    r"^\s*([A-Za-z_][A-Za-z_0-9]*)=(\$\([^\n]*\b(?:grep|awk|sed|cat|jq|python3|ls|wc)\b[^\n]*)",
    re.M)
B_DEFAULT_NUM = re.compile(r"\$\{([A-Za-z_][A-Za-z_0-9]*):-[0-9]+\}")
# Правило, добытое РАЗБОРОМ 39 носителей 29 августа 2026: ноль правдив там, где читается
# СЧЁТ — пустой вход честно равен нулю (`grep -c`, `wc -l/-c/-m`, `find | grep -c`). Ноль
# лжив там, где читается ЗНАЧЕНИЕ ПОЛЯ или ЗАМЕР: отсутствие значения не есть значение.
# Без этой оговорки признак ловил 39 мест при трёх настоящих дефектах — то есть мерил
# «есть ли подстановка», а утверждал «есть ли дефект»: предмет замера не совпадал с
# предметом утверждения. Ровно род C, допущенный в приборе для рода B.
B_COUNT = re.compile(r"\bgrep\s+-[a-zA-Z]*c|\bwc\s+-[lcmw]|\bcksum\b")


# СУЖЕНИЕ 6 сентября 2026: четыре класса ложности названы разбором и внесены в признак.
# Носителей 10 → 2, и оба оставшихся признаны ложными ГЛАЗОМ, но механически неотличимы:
#   · hooks/adaptive-stats-lib.sh:73 — `jq` складывает три счётчика, файл гарантирован
#     `_ensure_adaptive_stats`, а у самой функции ноль вызывающих (замер D90 держится);
#   · scripts/doc-figures.sh:166 — рядом стоит ВТОРОЙ независимый канал (`[ "$_rc" -ne 0 ]`),
#     и «со-проверяемый канал» механически выразить нечем. НЕ ИЗМЕРЕНО, честный остаток.
# Класс 1 («счёт») расширять НЕЛЬЗЯ, и это главная находка разбора: настоящий носитель,
# починенный в тот же день, читался `jq -r 'length'`, а ложный — `jq -rs '… | length'`.
# Они различаются синтаксисом, а не смыслом; расширение убило бы положительный контроль.
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ сужения (прогон по копии исторического дерева, 2 из 2):
# `test_cyrillic_tokens.sh` версии fa59b1c^ и `test_session_liveness_survives_stop.sh`
# версии c0bdc3a^ — оба ЛОВЯТСЯ и после сужения. Каждый класс стережёт свой контрпример в
# hooks/tests/test_defect_registry_counterexamples.sh; снятие любого роняет ровно его.
def carriers_b() -> list[tuple[Path, int]]:
    out = []
    for f in tracked("*.sh", "*.py"):
        t_raw = f.read_text(errors="replace")
        # ПРОДОЛЖЕНИЯ СТРОКИ СКЛЕИВАЮТСЯ (5 сентября 2026). `B_READ_ASSIGN` ограничен одной
        # строкой (`[^\n]*`), а чтение в оболочке сплошь и рядом переносится обратным
        # слэшем — и тогда `grep -c` в ХВОСТЕ конвейера признаку не виден: счётчик выдаётся
        # за замер. Так в списке держались `metrics-collector` (LANG_RECENT кончается на
        # `grep -c ''`), `ablation-phase-guard` и `test_assert_no_sigpipe`. Замер правки:
        # носителей 13 → 11, ушли трое ложных, пришёл один настоящий
        # (`session-collector.sh:350` — отказ архиватора неотличим от «перенесено 0»).
        # Тот же промах уже случился у рода A на многострочной программе awk (4 сентября).
        # КОНТРПРИМЕР к склейке: `B_PY` считается по ИСХОДНОМУ тексту, не по склеенному —
        # питоновский `except` значим построчно, и склейка продолжений там ничего не
        # добавляет, а рискует слить `except`-строку со следующей.
        t = re.sub(r"\\\n\s*", " ", t_raw)
        # Читатель, который САМ нормализует исход (`jq '// значение'`, `awk '{print $1+0}'`,
        # `|| echo`), значения не теряет — подстановка поверх него не гашение отказа.
        # Замер осмотром 29 августа 2026 до этой оговорки: из четырёх проверенных файлов
        # настоящих носителей был один, ложных два. Оговорка их снимает.
        # Читатель, который САМ подставляет значение (`jq '// 0'`, `awk '{print $1+0}'`,
        # `|| echo 0`), отказа не теряет — подстановка поверх него не гашение.
        # `|| true` сюда НЕ входит: он глушит только код возврата, значение остаётся
        # пустым. Первая редакция оговорки этого не различала и выбросила единственный
        # подтверждённый носитель (`metrics-collector`), оставив подтверждённый ложный
        # (`five-whys-gate`) первым в списке — поймано осмотром вершины списка.
        # `// empty` ИСКЛЮЧЕНО из оговорки 5 сентября 2026. Оговорка снимает читателей,
        # которые САМИ нормализуют исход, — но `// empty` нормализацией не является: он даёт
        # ПУСТОТУ, то есть ровно ту потерю, ради которой род и заведён. Отличать надо
        # `// 0` (значение подставлено, отказ не потерян) от `// empty` (значения нет).
        # Замер: чтений, отсеиваемых по `//`, было 361, из них 91 — по `// empty`; носителей
        # 10 → 11, и единственный новый настоящий: `hooks/tests/test_cyrillic_tokens.sh`
        # читал БАЛЛ из журнала и на отказе `jq` падал с «совпадений не дало» — красный тест
        # по причине, которой нет в мире. Точность расширения 1 из 1.
        # КЛАСС 2б (6 сентября 2026): самонормализация может стоять НЕ в первой строке
        # подстановки. Многострочная программа `awk`/`jq` прячет её от построчного взгляда:
        # `awk '… END { print n + 0 }'` нормализует исход, но `+ 0` лежит в третьей строке.
        # Тело подстановки берём целиком — от `$(` до парной скобки.
        def _subst_body(text, start):
            i = text.find('$(', start)
            if i < 0:
                return ''
            depth, j = 0, i + 1
            while j < len(text):
                if text[j] == '(':
                    depth += 1
                elif text[j] == ')':
                    depth -= 1
                    if depth == 0:
                        return text[i:j + 1]
                j += 1
            return text[i:]

        _norm = re.compile(r"//\s*(?!empty\b)\S|\+\s*0\b|\|\|\s*echo\s+\S")
        read_vars = set()
        for m in B_READ_ASSIGN.finditer(t):
            v, line = m.group(1), m.group(2)
            body = _subst_body(t, m.start()) or line
            if _norm.search(line) or _norm.search(body) or B_COUNT.search(line):
                continue
            read_vars.add(v)
        # КЛАСС 2а (6 сентября 2026): ветка отказа стоит на ИСТОЧНИКЕ, а не на производной.
        # `stats=$(cat …); [ -z "$stats" ] && stats_unread=1; total=$(jq … <<< "$stats")` —
        # отказ уже признан на `stats`, и подстановка в `total` есть нормализация после
        # признания, а не гашение. Прежний признак искал `[ -z ]` только по имени самой
        # производной и потому считал такие места носителями (hooks/activity-flush-lib.sh:91,
        # :212 — обе подстановки этого устройства).
        src_acknowledged = set()
        for v, line in B_READ_ASSIGN.findall(t):
            for x in re.findall(r'\$\{?([A-Za-z_][A-Za-z_0-9]*)', line):
                if re.search(r'\[\s*-[zn]\s+"\$\{?%s\}?"?\s*\]' % re.escape(x), t) or \
                   re.search(r'case\s+"\$\{?%s\}?"\s+in\s*\n?\s*\x27\x27' % re.escape(x), t):
                    src_acknowledged.add(v)
                    break
        # Число подставлено переменной, которая пришла ИЗ ЧТЕНИЯ, — вот носитель.
        # Переменная, у которой рядом стоит проверка на пустоту (`[ -z "$V" ]`), уже
        # различает «прочитал» и «не смог»: подстановка после признания — нормализация,
        # а не гашение. Без этой оговорки признак продолжал считать носителями места,
        # ПОЧИНЕННЫЕ в тот же час, и очередь не убывала бы от работы.
        acknowledged = set(re.findall(r'\[\s*-z\s+"\$\{?([A-Za-z_][A-Za-z_0-9]*)', t))
        # `case "$V" in ''|*[!0-9]*) V=0` — то же признание отказа, что `[ -z "$V" ]`, лишь
        # записанное иначе: пустое и мусорное значение разобраны ЯВНО, а не подставлены
        # молча. Признак различает роль, а не форму записи (hooks/code-review-reminder.sh:139).
        _case_ack = ('case\\s+"\\$\\{?([A-Za-z_][A-Za-z_0-9]*)[:}]?[^"]*"'
                     '\\s+in\\s*\\n?\\s*' + chr(39) * 2)
        acknowledged |= set(re.findall(_case_ack, t))
        # КЛАСС 4 (6 сентября 2026): отказ ОСТАЁТСЯ ВИДИМ. Условие красное, а диагностика
        # печатает переменную СЫРОЙ — без `:-`, — и читатель красного видит пустоту, а не
        # подставленный ноль. «Я не смог посмотреть» при этом различимо, то есть последствие
        # рода не наступает. Именно этот класс, а не «счёт», отделял ложных от настоящего в
        # разборе трёх тестов (test_meta_contamination_unreadable, test_metrics_channel,
        # test_research_slot: 4 подстановки на троих).
        visible_on_failure = {
            v for v in B_DEFAULT_NUM.findall(t)
            if re.search(r'(?:echo|printf|bad|ok|warn|FAIL|>&2)[^\n]*\$\{?%s\}?(?![A-Za-z_0-9:])'
                         % re.escape(v), t)
        }
        # КЛАСС 5 (7 сентября 2026): подстановка ведёт в ветку ОТКАЗА, а не успеха.
        # `if [ "${N:-0}" -ge 1 ] && …; then ok; else bad "…"; fi` — при непрочитанном N
        # подставляется НЕблагоприятное значение, условие становится ложным, и проверка
        # КРАСНЕЕТ. Последствие обратное роду: отказ чтения не выдаётся за «нарушений нет»,
        # он кричит. Повод: страж прироста назвал носителями два теста, починенных этим же
        # днём, — и оба оказались этого класса (test_adv3_dep_merge_conflict.sh:83,
        # test_adv_dep_index_plist_dependents.sh:85), ветка отказа стоит через 3-4 строки.
        # Класс ложности пятый: до него были «отказ видим в диагностике», «ветка отказа на
        # источнике», «самонормализация в теле подстановки», «честное отсутствие файла».
        leads_to_failure = set()
        _lines = t.splitlines()
        for i, line in enumerate(_lines):
            for v in re.findall(r'\$\{([A-Za-z_][A-Za-z_0-9]*):-', line):
                if not re.search(r'^\s*(if|elif|while)\b|\[\[?', line):
                    continue
                # Ветка отказа рядом: `bad`, `fail`, `FAIL` в ближайших строках после условия.
                # РАСШИРЕНИЕ НА ФОРМУ «else bad» / «then fail» ПРОМЕРЕНО И ОТВЕРГНУТО
                # (7 сентября 2026). Оно снимало 1 ложного носителя
                # (`test_metrics_field_shift.sh`), но положительный контроль показал цену:
                # синтетический носитель с НАСТОЯЩИМ гашением (`${N:-0}` поверх пустого
                # `jq`), рядом с которым `else bad` стоит от ДРУГОЙ ноги, старый признак
                # видит, а расширенный пропускает. Корень не в списке форм: подстановка
                # связывается с отказом по БЛИЗОСТИ (окно ниже), а не по принадлежности к
                # одной ветке `if…fi`. Пока связь по близости, всякое расширение списка
                # форм увеличивает радиус этой ошибки. Условие снятия: связь станет
                # структурной — блок от `if` до парного `fi`, отказ ищется внутри него.
                window = "\n".join(_lines[i:i + 6])
                # Ветка отказа опознаётся ПО РОЛИ, а не по виду слова. Первая редакция
                # искала `\bFAIL\b` и сняла scripts/doc-figures.sh ложно: там `FAIL:` стоит
                # внутри ОБРАЗЦА для поиска (`grep -oE 'FAIL: *([0-9]+)'`), то есть слово
                # является данными, а не вызовом. Годятся только формы вызова: `bad …` либо
                # `fail …` в начале строки и инкремент счётчика провалов.
                if re.search(r'(?m)^\s*(bad|fail)\s|^\s*FAIL=\$\(\(', window):
                    leads_to_failure.add(v)

        hits = sum(1 for v in B_DEFAULT_NUM.findall(t)
                   if v in read_vars and v not in acknowledged
                   and v not in visible_on_failure and v not in src_acknowledged
                   and v not in leads_to_failure)
        # КЛАСС 3 (6 сентября 2026): честное отсутствие файла. `except FileNotFoundError:
        # x = {}` — не гашение отказа, а разбор ОЖИДАЕМОГО состояния мира: файла ещё нет,
        # и пустой словарь тут верное значение, а не подмена непрочитанного. Признак снимает
        # такое место, только если в том же `try` есть ДРУГОЙ обработчик, называющий отказ
        # (`sys.exit`, `raise`, вывод в stderr) — то есть неожиданная беда всё-таки громкая.
        # Носитель, ради которого условие заведено: scripts/knowledge-instrument-audit.sh:445,
        # где соседний `except Exception` выходит кодом 2 с сообщением.
        py_hits = 0
        for m in B_PY.finditer(t_raw):
            around = t_raw[max(0, m.start() - 600):m.start() + 400]
            honest_missing = "FileNotFoundError" in t_raw[max(0, m.start() - 200):m.end() + 60]
            loud_sibling = re.search(r"except\s+\w+[^\n]*:\n(?:[^\n]*\n){0,6}?[^\n]*"
                                     r"(sys\.exit|raise\b|stderr)", around)
            if honest_missing and loud_sibling:
                continue
            py_hits += 1
        hits += py_hits
        if hits:
            out.append((f, hits))
    return out


