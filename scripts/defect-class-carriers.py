    fcar = carriers_f()
    # Делим по ПОСЛЕДСТВИЮ, и оно обратно роду A. У теста и стража неполный универсум даёт
    # ЗЕЛЁНЫЙ вердикт о непросмотренном — тихая ложь, читаемая как проверка. У механизма,
    # который просто обходит места, невидимый файл остаётся необработанным, и это видно при
