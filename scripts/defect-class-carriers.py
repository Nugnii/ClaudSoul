#     пустую колонку (прогон). Съезд недостижим. ТРИ ЛОЖНЫХ.
#   · `hooks/disagreement-lib.sh:215` и `:303` (3 поля) — механизм воспроизводится
#     целиком (запись с `file:""` даёт `i_file=[4]`, страж `[ -n "$i_file" ]` пропускает,
#     ключ несогласия становится «4»), но ДОСТИЖИМОСТЬ закрыта: оба читателя берут поток
#     из `select(.session_id == $sid and .injected == true)` (`:200`, `:278`), а писатель
