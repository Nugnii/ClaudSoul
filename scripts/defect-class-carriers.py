#     ПОСЛЕДНЕЕ поле `cmd`. ЛОЖНЫЙ.
#   · `scripts/measurement-due.sh:73` (4 поля, реестр `scripts/measurements.tsv`) —
#     единственный, где съезд ДОСТИЖИМ: реестр правится руками, писателя-кода у него нет
#     (`git grep measurements.tsv` отдаёт только читателей, упоминания и тестовые
#     фикстуры), читатель проверяет `id` и `period` и НЕ проверяет `cmd`. Но последствие
#     здесь ОБРАТНО объявленному, и это показала дифференциальная проба — сравнение
#     разбора механизмом с верным разбором TSV на всех формах строки:
#       `probe\t1\ttrue\tчто`  СОВПАЛО    — съезда нет
#       `probe\t1\t\tчто`      РАЗОШЛОСЬ  — read=[probe][1][что][]  верно=[probe][1][][что]
#       `probe\t1\t\t`         СОВПАЛО    — съезда НЕТ
#       `\t1\ttrue\tчто`       РАЗОШЛОСЬ  — но обе ветви отсеиваются стражами `id`/`period`
#       `probe\t\ttrue\tчто`   РАЗОШЛОСЬ  — то же, обе отсеиваются
#       `probe\t1\ttrue\t`     СОВПАЛО    — пустое ПОСЛЕДНЕЕ поле съезда не даёт
#     Наблюдаемое расхождение остаётся ровно одно — пустая `cmd` при непустом описании, —
#     и там механизм кричит: `eval "описание замера"` → код 127, «→ НЕ ВЫПОЛНЕН (код
#     127)», итоговый rc=1, отметка НЕ ставится. Верный же разбор дал бы `eval ""` → тихий
#     зелёный «выполнен, находок нет» с отметкой. То есть съезд делает прибор ГРОМЧЕ, а не
#     тише. ЛОЖНЫЙ по объявленному последствию.
#     Отдельно: тихий зелёный, который я сперва принял за улику рода I (фикстура
#     `probe\t1\t\t`), даёт СОВПАДЕНИЕ в дифференциальной пробе — он порождён пустой `cmd`
#     самой по себе, а не съездом. Это род B («пустой предмет засчитан зелёным
#     вердиктом»), и искать его надо там. Прогон живого реестра: 51 строка, во всех 4 поля,
#     пустых НЕ-последних полей ноль
#     (`awk -F'\t' '!/^#/{for(i=1;i<NF;i++) if($i=="") e++} END{print e+0}'`).
#
# Отсюда честный исход. Признак делит дерево по ФОРМЕ объявления (`IFS=` с табом плюс три
# и больше переменных) и на ней останавливается, а решает всё ДРУГОЕ отношение — замкнут
# ли производитель не-последних полей. Замкнутость производителя из вида чтения не
# выводится: у шести адресов из семи её задают перечень литералов, `length`, страж
# непустоты или конъюнкт `select(... == true)` в ЧУЖОМ файле, и увидеть их можно только
# прочитав производителя. Признак, ловящий форму объявления, ловит жанр «строка режется по
# табу» — исход рода C.
#
# ОТРИЦАТЕЛЬНЫЙ КЛАСС промерен и больше положительного: адресов `IFS=… read` в дереве 91,
# форма брала 7. Отвергала она 84: 10 с непробельным разделителем и 3-11 переменными, 1 с
# табом и двумя (`fix-level-check.sh:162`), 2 с пробелом и двумя, 71 с пустым `IFS=` и
# одной переменной. Отбор работал — но отбирал не то отношение.
#
# ДВА КОНТРПРИМЕРА, которые форма ловила верно и которые стоит сохранить, потому что они
# отделяют устройство от жанра:
#   · `hooks/disagreement-lib.sh:153` — `while IFS='|' read -r sid key dt _ _`: ТОТ ЖЕ
#     файл, соседняя функция, тот же вид строки, ПЯТЬ переменных; отличается ровно тем,
#     что `|` не пробельный, и пустое поле сохраняется (прогон выше). Контрпример по
#     разделителю, а не по жанру.
#   · `hooks/fix-level-check.sh:162` — `IFS=$'\t' read -r os_name os_phrase`, две
#     переменные. ВНИМАНИЕ: ходовое объяснение «при двух переменных съезжать нечему»
#     ЛОЖНО, и прогон это показывает — `printf '\tb\n' | while IFS=$'\t' read -r p q`
#     даёт `p=[b] q=[]`, то есть ведущая пустая колонка съезжает и при двух. Настоящее
#     основание другое и лежит опять у производителя: `:154` `printf "%s\t%s\n", name,
#     line` кладёт в первое поле `basename`, который пуст не бывает, и отбивает пустую
#     `line` условием `if (line != "")`.
#
# УСЛОВИЕ СНЯТИЯ вердикта: у потока появляется объявленный формат — заголовок TSV, схема,
# либо страж числа колонок на входе. Тогда сверяется ЧИСЛО КОЛОНОК прочитанного против
# объявленного, и это проверка отношения, а не вида вызова; она мехнизируема и не требует
# читать производителя глазами.
