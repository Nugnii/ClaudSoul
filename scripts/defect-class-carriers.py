# шести известных, и род сможет претендовать на уровень выше очереди.
def carriers_l() -> list[tuple[Path, list[str]]]:
    def _fields(rel: str) -> set[str]:
        f = ROOT / rel
        if not f.exists():
            return set()
        t = f.read_text(errors="replace")
        if t.startswith("---"):
            end = t.find("\n---", 3)
            t = t[3:end] if end > 0 else t
        return set(re.findall(r"(?m)^([a-z_]+):", t))

    op = _fields("templates/knowledge.md.tmpl")
    enc = (_fields("templates/entity.md.tmpl") | _fields("templates/fact.md.tmpl")
           | _fields("templates/relation.md.tmpl"))
    only_op = op - enc
    # Шаблонов нет — прибор ОТКАЗЫВАЕТ, а не отдаёт пустую очередь: пустой список полей
    # дал бы ноль носителей, неотличимый от «дерево чисто» (род B, закрытый 6 сентября).
    if not op or not enc:
        return []

    whole = re.compile(
        r'(LESSONS_DIR|GLOBAL_LESSONS|global-lessons|LESSONS)[^\n]{0,40}\*\.md'
        r'|\.glob\(\s*["\']\*\.md["\']\s*\)'
        r'|FROM\s+knowledge\b')
    # Формы различения перечислены ПО ИСХОДУ, а не по вкусу: каждая означает «механизм
    # спросил, есть ли поле, прежде чем считать». Три последние добавлены 7 сентября 2026
    # после починки brain.py и indexer.py: без них очередь НЕ УБЫВАЛА БЫ ОТ РАБОТЫ —
    # починенный файл оставался бы носителем, и «ноль» стал бы недостижим по построению
    # (тот же дефект, от которого страхуется род B).
    distinguishes = re.compile(
        r'case-\*|pattern-\*|principle-\*'
        r'|startswith\(\s*\(?["\'](case|pattern|principle)'
        r'|is not None|IS NOT NULL|!= *None'
        r'|not in \w*meta\b|in \w*meta\b'
        r'|\.get\(["\'](confirmed_count|contradicted_count|impact|outcome)["\']\)(?!\s*[,)]\s*0)'
        r'|type\s*(==|in)\s*["\']?(case|pattern|principle)')

    out: list[tuple[Path, list[str]]] = []
    for f in tracked("*.sh", "*.py"):
        # ФИКСТУРЫ ЗДЕСЬ НЕ ОТСЕИВАЮТСЯ, И ЭТО РЕШЕНИЕ (D468, 19 сентября 2026). У рода L
        # тест — носитель с ИНЫМ последствием, а не «не носитель»: по правилу счёта родов
        # такие печатаются поимённо и в очередь не входят, иначе «ноль в очереди» берётся
        # вычёркиванием. Деление стоит в ВЫВОДЕ (`l` против `l_test`), и оно одно.
        # Прежде здесь стоял отсев по литералу `"hooks/tests/"`, а вывод делил по
        # `"/tests/"`: два разных ответа на один вопрос в одном роде — `hooks/tests/*`
        # исчезали молча, `mcp-server/tests/*` печатались. Перевод на владельца сделал
        # расхождение видимым (замер: «плюс 2 тестов» превратилось в «плюс 0» и две строки
        # пропали), и чинится оно снятием отсева, а не расширением его.
        t = f.read_text(errors="replace")
        if not whole.search(t):
            continue
        used = sorted({fl for fl in only_op
                       if re.search(r'["\'^]%s\b|\.%s\b|\[%s\]|%s:' % (fl, fl, fl, fl), t)})
        if used and not distinguishes.search(t):
            out.append((f, used[:5]))
    return out


