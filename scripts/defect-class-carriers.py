#     (`knowledge-activator.sh:781`) по списку, из которого пустые строки уже вычищены
#     (`map(select(length > 0))`). Прогон: `["a","b"] | index("")` → null, то есть
#     `injected == true` ВЛЕЧЁТ непустой `.file` по построению. Живая сверка: 16260 строк
#     `injection-log.jsonl` + 7513 строк архива = 23773, записей с `injected==true` и
#     пустым `.file` — НОЛЬ. ДВА ЛОЖНЫХ.
