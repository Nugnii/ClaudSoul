#!/usr/bin/env bash
# doc-state-decisions.sh — доля правок поведения, прошедших без решения по документу состояния.
#
# Результат: названо число — сколько раз поведение механизма менялось при живом описании в
#            документе состояния, и в скольких случаях решение (обновить либо «не задето»)
#            осталось не принятым
# Проверка результата: bash scripts/doc-state-decisions.sh печатает обе величины и даёт 1,
#            когда доля без решения выше половины при достаточном знаменателе
#
# Зачем (D209). Требование обновить документ состояния было привязано к бампу версии либо к
# появлению нового модуля; изменение ПОВЕДЕНИЯ существующего механизма не требовало ничего.
# Следствие измерено 29 августа 2026: `docs/architecture.md` говорил «поводов семь» при
# восьми, а правило эскалации жило в трёх местах без ADR — и нашёл это владелец вопросом.
#
# ЧТО СЧИТАЕТСЯ РЕШЕНИЕМ. Наблюдаемый след: документ состояния в том же коммите ЛИБО
# отметка `doc-state:` в сообщении коммита. «Не задето» — законный исход, но без следа он
# неотличим от «забыл», и именно эта неотличимость и была дефектом.
#
# ОКНО В СЕССИЯХ, А НЕ В ДНЯХ: ритм работы неравномерный.
set -uo pipefail

STATE="${STATE_DIR:-$HOME/.claude/hooks/state}"
SESSIONS="${DOC_STATE_SESSIONS:-20}"
MIN_N="${DOC_STATE_MIN_N:-20}"
command -v jq >/dev/null 2>&1 || { echo "нет jq"; exit 0; }

FILES=()
while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
done <<EOF
$(ls -t "$STATE"/doc-state-*.jsonl 2>/dev/null | head -n "$SESSIONS")
EOF
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "журналов решений нет: правок поведения с живым описанием ещё не было (STATE=$STATE)"
    exit 0
fi

TOTAL=$(jq -rs 'length' "${FILES[@]}" 2>/dev/null); case "${TOTAL:-}" in ''|*[!0-9]*) TOTAL=0 ;; esac
UND=$(jq -rs 'map(select(.status == "undecided")) | length' "${FILES[@]}" 2>/dev/null)
case "${UND:-}" in ''|*[!0-9]*) UND=0 ;; esac
[ "$TOTAL" -gt 0 ] || { echo "записей нет"; exit 0; }
SHARE=$(( UND * 100 / TOTAL ))

echo "Правки поведения при живом описании (последние ${#FILES[@]} сессий):"
echo "  всего: $TOTAL, без принятого решения: $UND ($SHARE%)"
if [ "$TOTAL" -lt "$MIN_N" ]; then
    echo "  — мало данных, решения не принимаются (порог $MIN_N)"
    exit 0
fi
if [ "$SHARE" -gt 50 ]; then
    echo "[замер: находки, не сбой] больше половины правок поведения проходит без решения —"
    echo "по ADR-015 это повод поднять уровень: инжект читается и не меняет действий"
    exit 1
fi
echo "  — уровень соответствует: решение принимается в большинстве случаев"
exit 0
